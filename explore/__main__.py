"""CLI: ``python -m explore "<goal>" <root>`` -- print ranked approaches + winner.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  main(argv=None) -> int
DEPENDS-ON: explore, introspect.project_extract
SIDE-EFFECTS: prints to stdout
RUN/TEST: python -m pytest tests/explore/
"""
from __future__ import annotations

import argparse

from introspect.project_extract import extractProject

from explore import generateApproaches, scoreApproaches, selectOrSynthesize


def main(argv: list[str] | None = None) -> int:
    """Explore the solution space for <goal> against <root>, brain-free."""
    parser = argparse.ArgumentParser(
        prog="python -m explore",
        description="Rank deterministic approach candidates for a goal.",
    )
    parser.add_argument("goal", help="the change/goal to explore approaches for")
    parser.add_argument("root", help="project root directory to analyze")
    parser.add_argument("-n", type=int, default=3, help="number of approaches (default 3)")
    args = parser.parse_args(argv)

    model = extractProject(args.root, use_cache=False)
    candidates = generateApproaches(args.goal, model, n=args.n)
    scores = scoreApproaches(candidates, model)
    result = selectOrSynthesize(candidates, scores)
    by_id = {c.approach_id: c for c in candidates}

    header = (
        f"{'id':<4} {'total':>6} {'risk':>6} {'effort':>6} {'testab':>6} {'fit':>6}"
        "  archetype"
    )
    print(header)
    print("-" * (len(header) + 12))
    for s in result.scores:
        mark = "  <- winner" if s.approach_id == result.winner.approach_id else ""
        print(
            f"{s.approach_id:<4} {s.total:>6.4f} {s.risk:>6.4f} {s.effort:>6.4f} "
            f"{s.testability:>6.4f} {s.fit:>6.4f}  {by_id[s.approach_id].archetype}{mark}"
        )
    print()
    print(f"Winner: {result.winner.approach_id} {result.winner.title}")
    print(f"Rationale: {result.rationale}")
    if result.adopted_mitigations:
        print("Adopted mitigations:")
        for step in result.adopted_mitigations:
            print(f"  - {step}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
