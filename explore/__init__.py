def exploreSolutionSpace(
    goal: str, root_or_model, *, brain=None, n: int = 3
) -> SynthesisResult:
    """One-call facade: generate -> score -> synthesize for a model or a root path."""
    if isinstance(root_or_model, ProjectModel):
        model = root_or_model
    else:
        from introspect import extractProject

        model = extractProject(root_or_model, use_cache=False)
    candidates = generateApproaches(goal, model, brain=brain, n=n)
    scores = scoreApproaches(candidates, model)
    return selectOrSynthesize(candidates, scores, brain=brain)
