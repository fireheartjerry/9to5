"""Trade-off scoring: deterministic risk/effort/testability/fit composite per candidate.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  W_RISK, W_EFFORT, W_TESTABILITY, W_FIT -- composite weights (sum 1.0)
  RISK_NORMALIZER, EFFORT_NORMALIZER -- component saturation denominators
  TESTABILITY_TEST_FIRST, TESTABILITY_WITH_TESTS, TESTABILITY_NO_TESTS -- testability tiers
  TradeoffScore(approach_id, risk, effort, testability, fit, total)
  scoreApproaches(candidates, model) -> list[TradeoffScore]  # sorted total desc
DEPENDS-ON: explore.approach_gen, introspect.project_model
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/explore/test_approach_tradeoffs.py
"""
from __future__ import annotations

from dataclasses import dataclass

from introspect.project_model import ProjectModel

from explore.approach_gen import ApproachCandidate

W_RISK = 0.35
W_EFFORT = 0.20
W_TESTABILITY = 0.25
W_FIT = 0.20

# blast radius (files touched x mean fan-in) that saturates risk to its worst score
RISK_NORMALIZER = 10.0
# steps + files-touched budget that saturates effort to its worst score
EFFORT_NORMALIZER = 20.0
TESTABILITY_TEST_FIRST = 1.0
TESTABILITY_WITH_TESTS = 0.7
TESTABILITY_NO_TESTS = 0.2

_SERVER_MARKERS = ("dockerfile", "docker-compose", "gunicorn", "uwsgi", "procfile")

# archetype fit per project kind (library / cli / service), each in [0, 1]
_FIT_TABLE = {
    "library": {
        "minimal-patch": 0.9,
        "refactor-first": 0.8,
        "test-first": 0.9,
        "new-module": 0.7,
        "bold-redesign": 0.3,
    },
    "cli": {
        "minimal-patch": 0.9,
        "refactor-first": 0.6,
        "test-first": 0.7,
        "new-module": 0.8,
        "bold-redesign": 0.4,
    },
    "service": {
        "minimal-patch": 0.8,
        "refactor-first": 0.7,
        "test-first": 0.9,
        "new-module": 0.6,
        "bold-redesign": 0.2,
    },
}


@dataclass(frozen=True)
class TradeoffScore:
    """Component + composite scores for one candidate; higher is better everywhere."""

    approach_id: str
    risk: float          # in [0,1]; 1 = low blast radius
    effort: float        # in [0,1]; 1 = cheap
    testability: float   # in [0,1]
    fit: float           # in [0,1]; archetype-vs-project-kind
    total: float         # weighted composite, rounded to 4dp


def scoreApproaches(
    candidates: list[ApproachCandidate], model: ProjectModel
) -> list[TradeoffScore]:
    """Score every candidate against the project model; sorted total desc."""
    kind = _projectKind(model)
    has_test_cmd = any(c.kind == "test" for c in model.commands)
    module_count = max(1, len(model.modules))
    mean_fan_in = len(model.import_edges) / module_count
    scores = [_scoreOne(c, kind, has_test_cmd, mean_fan_in) for c in candidates]
    return sorted(scores, key=lambda s: (-s.total, s.approach_id))


def _scoreOne(
    cand: ApproachCandidate,
    kind: str,
    has_test_cmd: bool,
    mean_fan_in: float,
) -> TradeoffScore:
    """Compute the four components + weighted total for one candidate."""
    # blast radius = files touched x mean fan-in; bigger radius on a more-coupled
    # project => lower risk score (mean_fan_in is already normalized per module,
    # so no second division by module count)
    blast_radius = cand.files_touched_estimate * mean_fan_in
    risk = 1.0 - min(1.0, blast_radius / RISK_NORMALIZER)
    effort = 1.0 - min(
        1.0, (len(cand.steps) + cand.files_touched_estimate) / EFFORT_NORMALIZER
    )
    if has_test_cmd and cand.archetype == "test-first":
        testability = TESTABILITY_TEST_FIRST
    elif has_test_cmd:
        testability = TESTABILITY_WITH_TESTS
    else:
        testability = TESTABILITY_NO_TESTS
    fit = _FIT_TABLE[kind].get(cand.archetype, _FIT_TABLE[kind]["minimal-patch"])
    risk, effort, testability, fit = (
        round(risk, 4), round(effort, 4), round(testability, 4), round(fit, 4)
    )
    total = round(
        W_RISK * risk + W_EFFORT * effort + W_TESTABILITY * testability + W_FIT * fit,
        4,
    )
    return TradeoffScore(
        approach_id=cand.approach_id,
        risk=risk,
        effort=effort,
        testability=testability,
        fit=fit,
        total=total,
    )


def _projectKind(model: ProjectModel) -> str:
    """Infer library / cli / service from boundaries (deterministic)."""
    if model.boundaries.entrypoints:
        return "cli"
    config_names = " ".join(model.boundaries.config_files).lower()
    if any(marker in config_names for marker in _SERVER_MARKERS):
        return "service"
    return "library"
