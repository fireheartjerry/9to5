LOG = config.getLogger("sie.orchestrator")

# Heavy passes run at most once per this window (seconds). "Daily" without a scheduler.
DEFAULT_THROTTLE_SECONDS = 12 * 3600
# Prompt/policy promotion is a slower tier -- it needs many field uses to accumulate.
WEEKLY_THROTTLE_SECONDS = 7 * 24 * 3600


def _state_path() -> Path:
    return Path(config.CONTROL_DIR) / "sie_state.json"


def _lock_path() -> Path:
    return Path(config.CONTROL_DIR) / "sie_maintenance.lock"


def _read_state() -> dict[str, Any]:
    data = fsio.loadJson(_state_path(), default=None)   # corrupt -> warned, not silent
    return data if isinstance(data, dict) else {}


def _write_state(data: dict[str, Any]) -> None:
    try:
        fsio.atomicWriteJson(_state_path(), data, indent=2)
    except Exception as e:  # noqa: BLE001
        LOG.warning("sie state write failed (ignored): %s", e)


def _lock_owner_alive(lp: Path) -> bool:
    """True if the PID written in the lock file is still running. Maintenance runs on a DAEMON
    thread, so a process that exits (or is killed) while a pass is mid-flight leaves the lock with
    a dead owner -- which otherwise blocks ALL maintenance until the 1h staleness reclaim. If the
    owner can't be determined, assume alive (never steal a lock we can't prove is dead)."""
    try:
        pid = int((lp.read_text(encoding="utf-8") or "").strip())
    except Exception:  # noqa: BLE001 -- unreadable/garbage owner -> conservative
        return True
    if pid == os.getpid():
        return True
    try:
        import psutil
        return psutil.pid_exists(pid)
    except Exception:  # noqa: BLE001 -- psutil missing/errored -> conservative
        return True


def _acquire_lock() -> Optional[Path]:
    """O_EXCL lock so two concurrent runs never run maintenance at once. A stale lock is reclaimed
    when it is older than 1h (a wedged pass) OR its owning PID is dead (an orphaned lock from a
    process that exited mid-maintenance). Returns the lock path, or None if held by a live owner.
    The kernel's re-stat-before-unlink closes the old remove-fresh-lock race."""
    lp = _lock_path()
    got = fsio.tryAcquireLock(lp, stale_after=3600,
                              owner_alive=lambda _pid: _lock_owner_alive(lp))
    return lp if got else None


def _due(state: dict[str, Any], throttle_seconds: float) -> bool:
    last = state.get("last_full_at")
    if not last:
        return True
    try:
        elapsed = (datetime.now().astimezone() - datetime.fromisoformat(last)).total_seconds()
    except Exception:  # noqa: BLE001
        return True
    return elapsed >= throttle_seconds


def run_maintenance(*, reason: str = "post-run", force: bool = False,
                    throttle_seconds: float = DEFAULT_THROTTLE_SECONDS,
                    db_path: Optional[Path] = None) -> dict[str, Any]:
    """Run the throttled learning passes once (idempotent, best-effort, locked).

    Returns a summary dict. ``skipped`` reasons: ``kill_switch`` (SIE off), ``not_due``
    (throttled), ``locked`` (another run is mid-maintenance). Never raises.
    """
    if config.SIE_KILL_SWITCH:
        return {"skipped": "kill_switch"}
    state = _read_state()
    if not force and not _due(state, throttle_seconds):
        return {"skipped": "not_due", "last_full_at": state.get("last_full_at")}

    lock = _acquire_lock()
    if lock is None:
        return {"skipped": "locked"}
    summary: dict[str, Any] = {"reason": reason, "ran_at": datetime.now().astimezone().isoformat(timespec="seconds")}
    try:
        experience.init(db_path)
        # Zero-touch setup so the user only ever presses start: provision the training
        # stack + Ollama models once (best-effort, gated, no-op when already present).
        if config.SIE_BOOTSTRAP:
            try:
                from learning import bootstrap
                summary["bootstrap"] = bootstrap.ensure_all()
            except Exception as e:  # noqa: BLE001
                LOG.debug("bootstrap failed (ignored): %s", e)
        summary["steps"] = {}
        steps = list(_maintenance_steps(db_path))
        # The weekly tier (prompt/policy promotion) rides on the same pass but only when
        # its slower window is due -- so promotion is automatic yet never premature.
        weekly_due = force or _weekly_due(state)
        if weekly_due:
            steps += list(_weekly_steps(db_path))
        # Each step is independent + best-effort: one failing never blocks the others.
        for name, fn in steps:
            try:
                summary["steps"][name] = fn()
            except Exception as e:  # noqa: BLE001
                LOG.warning("sie step %s failed (ignored): %s", name, e)
                summary["steps"][name] = {"error": str(e)}
        state["last_full_at"] = summary["ran_at"]
        if weekly_due:
            state["last_weekly_at"] = summary["ran_at"]
        state["runs"] = int(state.get("runs", 0)) + 1
        _write_state(state)
        LOG.info("sie maintenance done (%s): %s", reason, summary["steps"])
        return summary
    finally:
        try:
            Path(lock).unlink(missing_ok=True)
        except Exception:  # noqa: BLE001
            pass


