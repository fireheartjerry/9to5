"""Self-improvement made visible -- the wisdom trail + growth summary.

Surfaces the system's accumulated SIE experience to the operator:
  * ``wisdomTrail(state, reflections=None)`` -- reflections relevant to THIS run's goal
    (keyword-matched against ``state.meta['goal_raw']``), with run ids + confidence.
  * ``growthSummary(domain=None, reflections=None, runs=None)`` -- a short "what the last runs
    taught me" learning summary, optionally narrowed to one domain keyword.

Pure: all ledger data is injectable so the suite never hits the DB; the real path defaults to
``memory.experience.fetch_reflections()`` / ``fetch_runs()``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  wisdomTrail(state, *, reflections=None, limit=8) -> str
  growthSummary(*, domain=None, reflections=None, runs=None, limit=5) -> str
DEPENDS-ON: config, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_wisdom.py
"""
from __future__ import annotations

import re
from typing import Optional

import config

LOG = config.getLogger("wisdom")

_STOP = {"the", "and", "for", "with", "that", "this", "from", "into", "your", "have", "make",
         "fix", "add", "use", "run", "code", "file", "files", "test", "tests"}


def _keywords(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9]{4,}", (text or "").lower()) if w not in _STOP}


def _reflectionText(r: dict) -> str:
    return (r.get("approach") or r.get("reusable_recipe") or r.get("verify_critique") or "").strip()


def _relevant(reflections: list, keywords: set[str]) -> list[dict]:
    out = []
    for r in reflections or []:
        text = _reflectionText(r)
        if text and (_keywords(text) & keywords):
            out.append(r)
    return out


def wisdomTrail(state, *, reflections: Optional[list] = None, limit: int = 8) -> str:
    """Reflections tagged relevant to this run's domain (keyword-matched on the goal)."""
    if reflections is None:
        reflections = _fetchReflections()
    keywords = _keywords(state.meta.get("goal_raw", "")) | _keywords(
        state.meta.get("goal_elaborated", "") if isinstance(state.meta, dict) else "")
    rel = _relevant(reflections, keywords)[-limit:]
    if not rel:
        return "No relevant past reflections yet — this run is breaking fresh ground."
    lines = ["**Wisdom trail** — relevant lessons from past runs"]
    for r in rel:
        conf = r.get("confidence")
        conf_txt = f" ({float(conf):.0%})" if isinstance(conf, (int, float)) else ""
        lines.append(f"- [{r.get('run_id','?')}]{conf_txt} {_reflectionText(r)[:200]}")
    return "\n".join(lines)


def growthSummary(*, domain: Optional[str] = None, reflections: Optional[list] = None,
                  runs: Optional[list] = None, limit: int = 5) -> str:
    """A short learning summary: what the most recent runs taught the system."""
    if reflections is None:
        reflections = _fetchReflections()
    if domain:
        dk = _keywords(domain) or {domain.lower()}
        reflections = [r for r in reflections if _keywords(_reflectionText(r)) & dk]
    recent = [r for r in (reflections or []) if _reflectionText(r)][-limit:]
    if not recent:
        scope = f" in `{domain}`" if domain else ""
        return f"No new lessons recorded{scope} yet — still gathering experience."
    head = f"**Growth**{' · ' + domain if domain else ''} — recent lessons:"
    lines = [head]
    for r in recent:
        lines.append(f"- [{r.get('run_id','?')}] {_reflectionText(r)[:180]}")
    return "\n".join(lines)


def _fetchReflections() -> list:  # pragma: no cover -- reads the live experience ledger
    try:
        from memory import experience
        return experience.fetch_reflections()
    except Exception as e:  # noqa: BLE001
        LOG.warning("wisdom fetch_reflections failed (ignored): %s", e)
        return []
