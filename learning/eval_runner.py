"""Live eval runner -- closes the keystone gap so fitness is measured AUTOMATICALLY.

The eval harness needs a ``runner(goal) -> result`` to produce a real fitness number. This
module provides a built-in **deterministic verify runner** (executes each golden goal's
held-out verify command -- zero-API, runs anywhere) and a registry so a richer brain-in-
the-loop runner (and a per-adapter fitness function for adapter A/B) can be registered by
the orchestrator when a live brain is available.

See the spec (the eval-harness spine) + learning/adapter_promotion.py.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  register(*, goal_runner: Optional[Callable[[dict], dict]]=None, fitness_under_tag: Optional[Callable[[str], float]]=None) -> None  -- Register richer runners (called by the orchestrator when a live brain exists).
  clear() -> None
  fitness_under_tag() -> Optional[Callable[[str], float]]
  verify_runner(goal: dict[str, Any]) -> dict[str, Any]  -- Deterministic, zero-API runner: run the goal's held-out verify command and score it.
  active_runner() -> Callable[[dict], dict]  -- The runner the harness should use now: a registered brain runner if present, else
DEPENDS-ON: agents.verifier, config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_eval_runner.py
"""
from __future__ import annotations

from typing import Any, Callable, Optional

import config

LOG = config.getLogger("sie.eval_runner")

_GOAL_RUNNER: Optional[Callable[[dict], dict]] = None
_FITNESS_UNDER_TAG: Optional[Callable[[str], float]] = None


def register(*, goal_runner: Optional[Callable[[dict], dict]] = None,
             fitness_under_tag: Optional[Callable[[str], float]] = None) -> None:
    """Register richer runners (called by the orchestrator when a live brain exists)."""
    global _GOAL_RUNNER, _FITNESS_UNDER_TAG
    if goal_runner is not None:
        _GOAL_RUNNER = goal_runner
    if fitness_under_tag is not None:
        _FITNESS_UNDER_TAG = fitness_under_tag


def clear() -> None:
    global _GOAL_RUNNER, _FITNESS_UNDER_TAG
    _GOAL_RUNNER = _FITNESS_UNDER_TAG = None


def fitness_under_tag() -> Optional[Callable[[str], float]]:
    return _FITNESS_UNDER_TAG


def verify_runner(goal: dict[str, Any]) -> dict[str, Any]:
    """Deterministic, zero-API runner: run the goal's held-out verify command and score it.

    Reflects whether the repo satisfies the golden checks -- a real, automatic fitness
    signal that runs in any environment (no GPU/brain required)."""
    from agents import verifier
    verify = goal.get("verify") or {}
    if not verify.get("cmd"):
        return {"passed": False, "attempts": 1, "challenged": True}
    try:
        res = verifier.runVerification(verify, str(config.PROJECT_ROOT), {})
        return {"passed": bool(res.get("passed")), "attempts": 1,
                "challenged": not bool(res.get("passed")), "cost": 0.0}
    except Exception as e:  # noqa: BLE001 -- a broken golden verify scores as a fail
        LOG.debug("verify_runner failed on %s: %s", goal.get("id"), e)
        return {"passed": False, "attempts": 1, "challenged": True}


def active_runner() -> Callable[[dict], dict]:
    """The runner the harness should use now: a registered brain runner if present, else
    the built-in deterministic verify runner (so fitness is ALWAYS real, never a marker)."""
    return _GOAL_RUNNER or verify_runner
