"""SIE curriculum-and-report step -- extracted from sie.py to hold the size budget.

Owns the adaptive curriculum auto-queue trigger (_curriculum_and_report): when >=5 new
human_feedback rows have accrued since the last consolidation, this MAY spawn generated
curriculum goals directly as detached orchestrator runs -- bypassing the human approval
gate. Because that is a real safety-relevant bypass, it is opt-in only
(config.CURRICULUM_AUTO_QUEUE_ENABLED, default OFF) and mirrors learning/selfplay.py's
guardrails: a busy-check (never compete with a live run), a per-day cap
(config.CURRICULUM_AUTO_QUEUE_MAX_PER_DAY), and cross-pass de-dup by family/goal-text so
the same weak-family goal is never re-spawned on a later maintenance pass.

State (the per-day counter + de-dup set) is persisted into the SAME sie_state.json the
caller (sie.py) already reads/writes, via injected ``read_state``/``write_state``
callables -- this module never imports its ``sie`` facade (no circular import), matching
sie_steps.py's contract. ``sie`` re-exports ``_curriculum_and_report`` so callers keep
resolving it there.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  (no public exports)
DEPENDS-ON: config, learning.curriculum, learning.release, notifications.work_launcher
SIDE-EFFECTS: may spawn a detached orchestrator run via notifications.work_launcher.spawn
RUN/TEST: python -m pytest tests/evolution/test_curriculum.py tests/evolution/test_sie.py
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any, Callable, Optional

import config

LOG = config.getLogger("sie.orchestrator")

ReadStateFn = Callable[[], dict[str, Any]]
WriteStateFn = Callable[[dict[str, Any]], None]
CountFeedbackFn = Callable[..., int]


def _curriculum_today() -> str:
    return datetime.now().astimezone().strftime("%Y-%m-%d")


def _curriculum_auto_queue_count_today(state: dict[str, Any]) -> int:
    counts = state.get("curriculum_auto_queue_counts")
    return int(counts.get(_curriculum_today(), 0)) if isinstance(counts, dict) else 0


def _curriculum_auto_queue_record(
    state: dict[str, Any], queued_goal_keys: list[str], write_state: WriteStateFn
) -> None:
    """Persist the day's bump + the de-dup set of already-queued goal keys into sie_state.json
    (mirrors selfplay_state.json's per-day counter, but co-located with SIE state since this is
    an SIE-owned adaptive trigger, not a selfplay concern)."""
    today = _curriculum_today()
    counts = state.get("curriculum_auto_queue_counts")
    counts = dict(counts) if isinstance(counts, dict) else {}
    counts[today] = int(counts.get(today, 0)) + len(queued_goal_keys)
    state["curriculum_auto_queue_counts"] = counts

    queued = state.get("curriculum_auto_queued_keys")
    queued = set(queued) if isinstance(queued, list) else set()
    queued.update(queued_goal_keys)
    state["curriculum_auto_queued_keys"] = sorted(queued)
    write_state(state)


def _curriculum_and_report(
    db_path: Optional[Path],
    *,
    read_state: ReadStateFn,
    write_state: WriteStateFn,
    count_new_feedback: CountFeedbackFn,
) -> dict[str, Any]:
    # Author practice goals for the weakest families + write the "what did I learn"
    # report. Both best-effort and human-facing -- the system narrates its own progress.
    # ADAPTIVE TRIGGER: if >=5 new feedback records appeared since last consolidation, MAY
    # auto-queue generated curriculum goals directly into the work queue -- bypassing human
    # approval, so this is opt-in only (CURRICULUM_AUTO_QUEUE_ENABLED, default OFF) and
    # mirrors selfplay's guardrails: busy-check, per-day cap, cross-pass dedup.
    from learning import curriculum, release

    goals = curriculum.generate_goals(db_path=db_path)
    curriculum.write_suggestions(goals)
    release.write_report(db_path=db_path)
    result: dict[str, Any] = {"curriculum_goals": len(goals), "auto_queued": 0}

    if not config.CURRICULUM_AUTO_QUEUE_ENABLED:
        result["auto_queue_skipped"] = "disabled"
        return result

    # Check adaptive trigger: >=5 new feedback since last consolidation?
    state = read_state()
    new_feedback_count = count_new_feedback(state, db_path=db_path)
    if new_feedback_count < 5 or not goals:
        return result

    try:
        from notifications import work_launcher

        if work_launcher.activeRun() is not None:
            result["auto_queue_skipped"] = "busy"  # never compete with a live run
            return result

        already_queued = set(state.get("curriculum_auto_queued_keys") or [])
        cap = config.CURRICULUM_AUTO_QUEUE_MAX_PER_DAY
        queued_today = _curriculum_auto_queue_count_today(state)
        newly_queued_keys: list[str] = []
        for goal_dict in goals:
            if queued_today + len(newly_queued_keys) >= cap:
                break
            key = f"{goal_dict.get('family', '')}:{goal_dict['goal']}"
            if key in already_queued:
                continue  # de-dup: don't re-spawn the same goal
            req = work_launcher.WorkRequest(goal=goal_dict["goal"], hours=1.0)
            work_launcher.spawn(req)
            newly_queued_keys.append(key)
            result["auto_queued"] += 1

        if newly_queued_keys:
            _curriculum_auto_queue_record(state, newly_queued_keys, write_state)
        if result["auto_queued"] == 0:
            result["auto_queue_skipped"] = "daily_cap_or_dedup"
        LOG.info(
            "curriculum: auto-queued %d goals (%d new feedback)", result["auto_queued"], new_feedback_count
        )
    except Exception as e:  # noqa: BLE001
        LOG.debug("curriculum auto-queue failed (ignored): %s", e)

    return result
