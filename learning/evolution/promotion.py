"""Champion/challenger promotion gate -- Layer 3 of the Self-Improvement Engine.

Decides, automatically and conservatively, whether a challenger prompt should replace the
champion. A challenger is promoted ONLY when its field first-pass rate beats the champion
by a statistically significant margin over enough uses (one-sided two-proportion z-test).
This runs in the auto-runner's weekly tier -- the human never triggers it; in ``gated``
mode the actual flip still waits on ``!approve`` (wired where promotions are applied).

Invariant I2 (no self-promotion): the brain can only *propose* challengers; promotion is
decided here by an independent statistical gate, never by the brain.

See the spec (Layer 3 + governance).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  proportion_z(succ_a: int, n_a: int, succ_b: int, n_b: int) -> float  -- One-sided pooled two-proportion z for (A better than B)
  decide(champ: dict[str, int], chall: dict[str, int], *, min_uses: Optional[int]=None, z_thresh: Optional[float]=None) -> dict  -- Gate decision from {n, first_pass} field stats
  pick_challenger(role: str, *, rng: Optional[random.Random]=None, db_path: Optional[Path]=None) -> Optional[int]  -- Thompson-pick which challenger to evaluate next (favors promising + under-tried).
  run_promotions(*, rng: Optional[random.Random]=None, db_path: Optional[Path]=None) -> dict  -- Auto-evaluate one challenger per role and promote it if the gate passes
DEPENDS-ON: config, learning.prompts, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/evolution/test_promotion.py
"""
from __future__ import annotations

import math
import random
from pathlib import Path
from typing import Optional

import config
from learning import prompts
from memory import experience

LOG = config.getLogger("sie.promotion")


def proportion_z(succ_a: int, n_a: int, succ_b: int, n_b: int) -> float:
    """One-sided pooled two-proportion z for (A better than B). 0.0 if undefined.

    Positive z means A's success rate exceeds B's; compare against a threshold (1.64 ~ 95%).
    """
    if n_a <= 0 or n_b <= 0:
        return 0.0
    pa, pb = succ_a / n_a, succ_b / n_b
    pool = (succ_a + succ_b) / (n_a + n_b)
    denom = math.sqrt(pool * (1 - pool) * (1 / n_a + 1 / n_b))
    if denom == 0.0:
        return 0.0
    return (pa - pb) / denom


def decide(champ: dict[str, int], chall: dict[str, int], *,
           min_uses: Optional[int] = None, z_thresh: Optional[float] = None) -> dict:
    """Gate decision from {n, first_pass} field stats. Returns
    {decision: promote|reject|insufficient, z, reason}."""
    min_uses = config.PROMPT_PROMOTE_MIN_USES if min_uses is None else min_uses
    z_thresh = config.PROMPT_PROMOTE_Z if z_thresh is None else z_thresh
    if chall["n"] < min_uses:
        return {"decision": "insufficient", "z": 0.0,
                "reason": f"challenger has {chall['n']}/{min_uses} uses"}
    z = proportion_z(chall["first_pass"], chall["n"], champ["first_pass"], champ["n"])
    ca = chall["first_pass"] / chall["n"]
    cb = (champ["first_pass"] / champ["n"]) if champ["n"] else 0.0
    if ca >= cb and z >= z_thresh:
        return {"decision": "promote", "z": z,
                "reason": f"challenger {ca:.0%} vs champion {cb:.0%}, z={z:.2f}"}
    return {"decision": "reject", "z": z,
            "reason": f"challenger {ca:.0%} vs champion {cb:.0%}, z={z:.2f} < {z_thresh}"}


def _sample(stats: dict[str, int], rng: random.Random) -> float:
    """Thompson sample of a variant's success rate (Beta posterior, uniform prior)."""
    a = stats["first_pass"] + 1
    b = (stats["n"] - stats["first_pass"]) + 1
    return rng.betavariate(a, b)


def pick_challenger(role: str, *, rng: Optional[random.Random] = None,
                    db_path: Optional[Path] = None) -> Optional[int]:
    """Thompson-pick which challenger to evaluate next (favors promising + under-tried)."""
    rng = rng or random
    chs = prompts.challengers(role, db_path=db_path)
    if not chs:
        return None
    best_id, best = None, -1.0
    for c in chs:
        s = experience.prompt_field_stats(str(c["id"]), db_path=db_path)
        draw = _sample(s, rng)
        if draw > best:
            best_id, best = int(c["id"]), draw
    return best_id


def run_promotions(*, rng: Optional[random.Random] = None,
                   db_path: Optional[Path] = None) -> dict:
    """Auto-evaluate one challenger per role and promote it if the gate passes. Best-effort;
    returns a per-role summary. Called automatically by the weekly maintenance tier."""
    summary: dict[str, dict] = {}
    for role in prompts.ROLES:
        try:
            champ = experience.get_champion(role, db_path=db_path)
            if not champ:
                continue
            cid = pick_challenger(role, rng=rng, db_path=db_path)
            if cid is None:
                continue
            champ_stats = experience.prompt_field_stats(str(champ["id"]), db_path=db_path)
            chall_stats = experience.prompt_field_stats(str(cid), db_path=db_path)
            d = decide(champ_stats, chall_stats)
            if d["decision"] == "promote":
                prompts.promote(role, cid, db_path=db_path)
                LOG.info("PROMOTED %s challenger %s: %s", role, cid, d["reason"])
            summary[role] = {"challenger": cid, **d}
        except Exception as e:  # noqa: BLE001 -- one role's failure never blocks others
            LOG.warning("run_promotions failed for %s (ignored): %s", role, e)
    return summary


if __name__ == "__main__":  # pragma: no cover
    experience.init()
    print(run_promotions())
