"""Implicit human feedback (RLHF-lite) -- subsystem J of the Self-Improvement Engine.

The control layer already emits the highest-quality signal in the system -- a human's
approve/reject/skip/edit. This captures each as a label and derives correction pairs
(edit before -> after) that feed the DPO preference set. Nearly free; reuses the existing
ControlBus surface. Best-effort + offline-testable.

See the spec (subsystem J).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  record(kind: str, *, run_id: Optional[str]=None, subtask_id: Optional[str]=None, target: Optional[str]=None, before: Any=None, after: Any=None, db_path: Optional[Path]=None) -> bool  -- Capture one human control decision as a label
  correction_pairs(*, db_path: Optional[Path]=None) -> list[dict[str, Any]]  -- Derive DPO chosen/rejected pairs from human EDITs (the before is rejected, the
  stats(*, db_path: Optional[Path]=None) -> dict[str, int]
DEPENDS-ON: config, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/evolution/test_nextwave_batch1.py tests/notifications/test_feedback_view.py
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Optional

import config
from memory import experience

LOG = config.getLogger("sie.human_feedback")

# Control decisions worth learning from, and their polarity hint.
POSITIVE = {"approve", "retry"}
NEGATIVE = {"reject", "skip", "abort"}
CORRECTION = {"edit", "add"}


def record(kind: str, *, run_id: Optional[str] = None, subtask_id: Optional[str] = None,
           target: Optional[str] = None, before: Any = None, after: Any = None,
           db_path: Optional[Path] = None) -> bool:
    """Capture one human control decision as a label. Call this from the control path."""
    return experience.record_feedback(kind=kind, run_id=run_id, subtask_id=subtask_id,
                                      target=target, before=before, after=after, db_path=db_path)


def correction_pairs(*, db_path: Optional[Path] = None) -> list[dict[str, Any]]:
    """Derive DPO chosen/rejected pairs from human EDITs (the before is rejected, the
    human-preferred after is chosen)."""
    import json
    pairs: list[dict[str, Any]] = []
    for fb in experience.fetch_feedback(db_path=db_path):
        if fb["kind"] not in CORRECTION or not fb.get("before_json") or not fb.get("after_json"):
            continue
        try:
            before = json.loads(fb["before_json"])
            after = json.loads(fb["after_json"])
        except Exception:  # noqa: BLE001
            before, after = fb["before_json"], fb["after_json"]
        bs, as_ = (before if isinstance(before, str) else json.dumps(before)), \
                  (after if isinstance(after, str) else json.dumps(after))
        if bs and as_ and bs != as_:
            pairs.append({"prompt": f"Improve the {fb.get('target') or 'plan'} per human review.",
                          "rejected": bs, "chosen": as_, "goal": fb.get("target") or ""})
    return pairs


def stats(*, db_path: Optional[Path] = None) -> dict[str, int]:
    fb = experience.fetch_feedback(db_path=db_path)
    out = {"total": len(fb), "positive": 0, "negative": 0, "corrections": 0}
    for f in fb:
        if f["kind"] in POSITIVE:
            out["positive"] += 1
        elif f["kind"] in NEGATIVE:
            out["negative"] += 1
        elif f["kind"] in CORRECTION:
            out["corrections"] += 1
    return out
