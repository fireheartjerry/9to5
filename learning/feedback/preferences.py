"""DPO preference-pair builder -- Layer F of the Self-Improvement Engine.

The biggest quality jump over plain imitation: teach the brain what *not* to do. For a
given task family, a spec that PASSED (chosen) paired with one that FAILED (rejected) is a
free, naturally-occurring preference pair. These feed DPO/ORPO LoRA training.

Everything passes the same data-quality gate (scrub + decontaminate) as SFT. Pure-stdlib,
offline-testable. See the spec (subsystem B) + learning/finetune.py.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  build_pairs(*, db_path: Optional[Path]=None, suite: Optional[list[dict[str, Any]]]=None) -> list[dict[str, Any]]  -- Build cleaned chosen/rejected preference pairs from passing-vs-failing specs,
  write_jsonl(pairs: list[dict[str, Any]], path: Path) -> None
  build(*, db_path: Optional[Path]=None, out_path: Optional[Path]=None, suite: Optional[list[dict[str, Any]]]=None) -> dict[str, Any]  -- Build + (optionally) write the DPO preference dataset
DEPENDS-ON: config, learning.dataset, learning.lessons, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/evolution/test_preferences.py
"""
from __future__ import annotations

import hashlib
import json
from collections import defaultdict
from pathlib import Path
from typing import Any, Optional

import config
from learning import dataset
from learning.lessons import family_of
from memory import experience

LOG = config.getLogger("sie.preferences")

# Cap pairs per family so one busy family can't dominate the dataset (collapse guard).
MAX_PAIRS_PER_FAMILY = 8


def _prompt_for(row: dict[str, Any]) -> str:
    title = (row.get("title") or "").strip()
    return (f"Subtask: {title}\n"
            f"Acceptance verify: {row.get('verify_cmd')} (expect: {row.get('verify_expect')})\n"
            f"Author the JSON invocation spec for this subtask.")


def build_pairs(*, db_path: Optional[Path] = None,
                suite: Optional[list[dict[str, Any]]] = None) -> list[dict[str, Any]]:
    """Build cleaned chosen/rejected preference pairs from passing-vs-failing specs,
    matched within task family."""
    passing: dict[str, list[dict]] = defaultdict(list)
    failing: dict[str, list[dict]] = defaultdict(list)
    for r in experience.fetch_subtasks(db_path=db_path):
        spec = r.get("invocation_spec_json")
        if not spec:
            continue
        fam = family_of(r.get("title") or "", r.get("signature_tags"))
        (passing if r.get("verify_passed") == 1 else failing)[fam].append(r)

    sigs = dataset.suite_signatures(suite)
    seen: set[str] = set()
    pairs: list[dict[str, Any]] = []
    for fam, wins in passing.items():
        losses = failing.get(fam)
        if not losses:
            continue
        made = 0
        for c in wins:
            for r in losses:
                if made >= MAX_PAIRS_PER_FAMILY:
                    break
                chosen, rejected = c["invocation_spec_json"], r["invocation_spec_json"]
                if chosen == rejected:
                    continue
                ex = {"prompt": _prompt_for(c), "goal": c.get("title") or "",
                      "chosen": dataset.scrub(chosen), "rejected": dataset.scrub(rejected)}
                if dataset.is_contaminated(ex, sigs):
                    continue
                h = hashlib.sha256((ex["prompt"] + ex["chosen"] + ex["rejected"])
                                   .encode("utf-8")).hexdigest()
                if h in seen:
                    continue
                seen.add(h)
                pairs.append(ex)
                made += 1
            if made >= MAX_PAIRS_PER_FAMILY:
                break
    return pairs


def write_jsonl(pairs: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for ex in pairs:
            f.write(json.dumps(ex, ensure_ascii=False) + "\n")


def build(*, db_path: Optional[Path] = None, out_path: Optional[Path] = None,
          suite: Optional[list[dict[str, Any]]] = None) -> dict[str, Any]:
    """Build + (optionally) write the DPO preference dataset. Returns count + path."""
    pairs = build_pairs(db_path=db_path, suite=suite)
    written = None
    if out_path is not None and pairs:
        write_jsonl(pairs, Path(out_path))
        written = str(out_path)
    LOG.info("preference pairs: %d", len(pairs))
    return {"pairs": len(pairs), "path": written}
