"""Compute router -- decides whether to use the GPU for SIE training.

The deep layers (LoRA/DPO) want a GPU; the rest of the engine runs anywhere. This module
detects a CUDA GPU (via torch if present, else ``nvidia-smi``), honors the operator's
policy (``SIE_COMPUTE`` = auto|gpu|cpu|off), and tells the trainers which device to use --
so the same code trains on the user's strong local GPU and degrades cleanly elsewhere.

Detection is best-effort and cached; importing this module never requires torch/CUDA.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  detect_gpu() -> dict  -- Best-effort GPU probe -> {available, name, source}
  policy() -> str
  training_enabled() -> bool  -- False only when the operator turned training off entirely.
  should_use_gpu() -> bool  -- Resolve policy + detection into a yes/no for GPU training.
  device() -> str
  summary() -> dict  -- Human-facing compute status for dashboards/reports.
  reset_cache() -> None  -- Clear the detection cache (tests / after a driver change).
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_compute.py
"""
from __future__ import annotations

import shutil
import subprocess
from typing import Optional

import config

LOG = config.getLogger("sie.compute")

_gpu_cache: Optional[dict] = None


def detect_gpu() -> dict:
    """Best-effort GPU probe -> {available, name, source}. Cached for the process."""
    global _gpu_cache
    if _gpu_cache is not None:
        return _gpu_cache
    info = {"available": False, "name": None, "source": None}
    # Prefer torch (authoritative + what the trainer will use).
    try:
        import torch  # type: ignore
        if torch.cuda.is_available():
            info = {"available": True, "name": torch.cuda.get_device_name(0), "source": "torch"}
            _gpu_cache = info
            return info
    except Exception as e:  # noqa: BLE001 -- torch absent/broken -> fall back to nvidia-smi
        LOG.debug("torch CUDA probe failed: %s", e)
    # Fallback: nvidia-smi (works even without torch installed).
    if shutil.which("nvidia-smi"):
        try:
            out = subprocess.run(["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
                                 capture_output=True, text=True, timeout=8)
            name = (out.stdout or "").strip().splitlines()
            if out.returncode == 0 and name:
                info = {"available": True, "name": name[0].strip(), "source": "nvidia-smi"}
        except Exception as e:  # noqa: BLE001
            LOG.debug("nvidia-smi probe failed: %s", e)
    _gpu_cache = info
    return info


def policy() -> str:
    return (config.SIE_COMPUTE or "auto").strip().lower()


def training_enabled() -> bool:
    """False only when the operator turned training off entirely."""
    return policy() != "off"


def should_use_gpu() -> bool:
    """Resolve policy + detection into a yes/no for GPU training."""
    p = policy()
    if p in ("off", "cpu"):
        return False
    avail = detect_gpu()["available"]
    if p == "gpu" and not avail:
        LOG.warning("SIE_COMPUTE=gpu but no GPU detected — training will be skipped")
    return avail  # 'auto' and 'gpu' both require an actual GPU


def device() -> str:
    return "cuda" if should_use_gpu() else "cpu"


def summary() -> dict:
    """Human-facing compute status for dashboards/reports."""
    gpu = detect_gpu()
    return {"policy": policy(), "gpu_available": gpu["available"], "gpu_name": gpu["name"],
            "will_train_on": device() if training_enabled() else "disabled"}


def reset_cache() -> None:
    """Clear the detection cache (tests / after a driver change)."""
    global _gpu_cache
    _gpu_cache = None
