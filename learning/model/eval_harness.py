"""Evaluation Harness -- the spine of the Self-Improvement Engine.

A fixed golden suite + a single ``fitness`` scalar. EVERY prompt variant and EVERY LoRA
adapter must beat the incumbent here before it is promoted, and the persisted score
series is the visible, months-long proof that the system is actually getting better.

This module is split so the math is fully testable offline:
  * ``compute_fitness`` / ``aggregate`` are pure functions over result dicts.
  * ``run_suite`` drives a pluggable ``runner(goal) -> result`` callable -- a real run
    wires Claude/Ollama in later phases; tests inject a deterministic runner; the CLI
    entrypoint, with no live brain in this container, records a "no_runner" marker row.

See docs/superpowers/specs/2026-06-22-self-improvement-engine-design.md (the spine).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  aggregate(results: list[dict[str, Any]], *, cost_cap: float=DEFAULT_COST_CAP) -> dict[str, float]  -- Reduce per-goal results into the normalized 0..1 metric dict ``compute_fitness`` wants.
  compute_fitness(metrics: dict[str, Any], weights: Optional[dict[str, float]]=None) -> float  -- The single scalar gate
  load_suite(suite_dir: Optional[Path]=None) -> list[dict[str, Any]]  -- Load every golden goal (``*.json``) from the suite directory, sorted by filename
  score(results: list[dict[str, Any]], *, weights: Optional[dict[str, float]]=None, cost_cap: float=DEFAULT_COST_CAP) -> dict[str, Any]  -- Full score payload: the aggregate metrics plus the fitness scalar.
  run_suite(runner: Optional[Callable[[dict[str, Any]], dict[str, Any]]]=None, *, suite_dir: Optional[Path]=None, prompt_set_id: Optional[str]=None, adapter_id: Optional[str]=None, record: bool=True, db_path: Optional[Path]=None) -> dict[str, Any]  -- Run every goal through ``runner`` (goal -> result), score, and (optionally) persist
  fitness_panel(limit: int=30, db_path: Optional[Path]=None) -> str  -- Render the recent fitness series as a compact sparkline + delta for a dashboard
DEPENDS-ON: config, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/evolution/test_eval_harness.py
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Callable, Optional

import config
from memory import experience

LOG = config.getLogger("sie.eval")

SUITE_VERSION = "v1"
# Cost (USD) at/above which norm_cost saturates to 1.0 when scoring. Conservative default;
# overridable so the curve can be recalibrated as real telemetry accrues.
DEFAULT_COST_CAP = 1.0


def _clip01(x: float) -> float:
    return 0.0 if x < 0 else 1.0 if x > 1 else x


def aggregate(results: list[dict[str, Any]], *, cost_cap: float = DEFAULT_COST_CAP) -> dict[str, float]:
    """Reduce per-goal results into the normalized 0..1 metric dict ``compute_fitness`` wants.

    Each result may carry: ``passed`` (bool), ``attempts`` (int>=1), ``cost`` (USD),
    ``challenged`` (bool), ``plan_changes`` (int). Missing keys use safe neutral defaults.
    """
    n = len(results)
    if n == 0:
        return {"first_pass_rate": 0.0, "norm_attempts": 0.0, "norm_cost": 0.0,
                "plan_stability": 1.0, "challenge_rate": 0.0, "n": 0}

    max_attempts = max(2, int(getattr(config, "MAX_SUBTASK_ATTEMPTS", 3)))
    first_pass = sum(1 for r in results if r.get("passed") and int(r.get("attempts", 1)) <= 1)
    mean_attempts = sum(int(r.get("attempts", 1)) for r in results) / n
    mean_cost = sum(float(r.get("cost", 0.0)) for r in results) / n
    challenged = sum(1 for r in results if r.get("challenged"))
    mean_plan_changes = sum(int(r.get("plan_changes", 0)) for r in results) / n

    return {
        "first_pass_rate": first_pass / n,
        # 1 attempt -> 0 (best); max_attempts -> 1 (worst).
        "norm_attempts": _clip01((mean_attempts - 1.0) / (max_attempts - 1.0)),
        "norm_cost": _clip01(mean_cost / cost_cap) if cost_cap > 0 else 0.0,
        # No plan churn -> 1.0 stability; capped so a single change can't zero it out.
        "plan_stability": _clip01(1.0 - mean_plan_changes / max_attempts),
        "challenge_rate": challenged / n,
        "n": n,
    }


def compute_fitness(metrics: dict[str, Any], weights: Optional[dict[str, float]] = None) -> float:
    """The single scalar gate. Higher is better; bounded to [0, 1].

    fitness = w_fp·first_pass_rate + w_att·(1−norm_attempts) + w_cost·(1−norm_cost)
            + w_ps·plan_stability + w_cr·(1−challenge_rate)
    """
    w = weights or config.EVAL_FITNESS_WEIGHTS
    f = (
        w["first_pass_rate"] * _clip01(float(metrics.get("first_pass_rate", 0.0)))
        + w["attempts"] * (1.0 - _clip01(float(metrics.get("norm_attempts", 0.0))))
        + w["cost"] * (1.0 - _clip01(float(metrics.get("norm_cost", 0.0))))
        + w["plan_stability"] * _clip01(float(metrics.get("plan_stability", 1.0)))
        + w["challenge_rate"] * (1.0 - _clip01(float(metrics.get("challenge_rate", 0.0))))
    )
    return round(_clip01(f), 6)


def load_suite(suite_dir: Optional[Path] = None) -> list[dict[str, Any]]:
    """Load every golden goal (``*.json``) from the suite directory, sorted by filename
    so the suite is deterministic. Held-out verifies live in each goal file by design."""
    d = Path(suite_dir or config.EVAL_SUITE_DIR)
    goals: list[dict[str, Any]] = []
    if not d.exists():
        return goals
    for f in sorted(d.glob("*.json")):
        try:
            goal = json.loads(f.read_text(encoding="utf-8"))
            goal.setdefault("id", f.stem)
            goals.append(goal)
        except Exception as e:  # noqa: BLE001 -- a malformed fixture must not crash scoring
            LOG.warning("skipping malformed suite goal %s: %s", f.name, e)
    return goals


def score(results: list[dict[str, Any]], *, weights: Optional[dict[str, float]] = None,
          cost_cap: float = DEFAULT_COST_CAP) -> dict[str, Any]:
    """Full score payload: the aggregate metrics plus the fitness scalar."""
    metrics = aggregate(results, cost_cap=cost_cap)
    return {**metrics, "fitness": compute_fitness(metrics, weights)}


def run_suite(runner: Optional[Callable[[dict[str, Any]], dict[str, Any]]] = None,
              *, suite_dir: Optional[Path] = None, prompt_set_id: Optional[str] = None,
              adapter_id: Optional[str] = None, record: bool = True,
              db_path: Optional[Path] = None) -> dict[str, Any]:
    """Run every goal through ``runner`` (goal -> result), score, and (optionally) persist
    an ``eval_runs`` row. With ``runner=None`` (no live brain available, e.g. this
    container) it records a transparent ``no_runner`` marker so the absence is observable
    rather than silently producing a fake fitness."""
    goals = load_suite(suite_dir)
    # No runner OR no goals -> record a TRANSPARENT marker, never score([]). score([]) fabricates a
    # neutral 'scored' fitness (~0.5) from zero signal, which then pollutes the SIE fitness series and
    # can drive adapter promotion/rollback on noise. An empty/missing suite must be observably empty.
    if runner is None or not goals:
        status = "no_runner" if runner is None else "empty_suite"
        payload = {"status": status, "suite_version": SUITE_VERSION, "suite_size": len(goals)}
        if record:
            experience.record_eval(payload, suite_version=SUITE_VERSION,
                                   prompt_set_id=prompt_set_id, adapter_id=adapter_id,
                                   passed_gate=None, db_path=db_path)
        return payload

    results = []
    for goal in goals:
        try:
            results.append(runner(goal))
        except Exception as e:  # noqa: BLE001 -- a runner blow-up scores as a hard fail
            LOG.warning("runner failed on goal %s: %s", goal.get("id"), e)
            results.append({"passed": False, "attempts": config.MAX_SUBTASK_ATTEMPTS,
                            "challenged": True})
    payload = score(results)
    payload["status"] = "scored"
    payload["suite_version"] = SUITE_VERSION
    if record:
        experience.record_eval(payload, suite_version=SUITE_VERSION,
                               prompt_set_id=prompt_set_id, adapter_id=adapter_id,
                               db_path=db_path)
    return payload


_SPARK = "▁▂▃▄▅▆▇█"


def fitness_panel(limit: int = 30, db_path: Optional[Path] = None) -> str:
    """Render the recent fitness series as a compact sparkline + delta for a dashboard
    (Layer-C visibility). Pure-text so Discord/web can drop it straight into an embed."""
    series = [p for p in experience.fitness_series(limit, db_path=db_path)
              if isinstance(p.get("score"), dict) and "fitness" in p["score"]]
    if not series:
        return "Fitness: no eval points yet."
    vals = [float(p["score"]["fitness"]) for p in series]
    lo, hi = min(vals), max(vals)
    spread = (hi - lo) or 1.0
    spark = "".join(_SPARK[min(len(_SPARK) - 1, int((v - lo) / spread * (len(_SPARK) - 1)))]
                    for v in vals)
    delta = vals[-1] - vals[0]
    arrow = "▲" if delta > 0 else "▼" if delta < 0 else "▬"
    return (f"Fitness {spark}  now={vals[-1]:.3f} {arrow}{abs(delta):.3f} "
            f"over {len(vals)} evals (min={lo:.3f}, max={hi:.3f})")


if __name__ == "__main__":  # pragma: no cover -- CLI: load suite + record a marker row
    experience.init()
    out = run_suite(runner=None)
    print(json.dumps(out, indent=2))
