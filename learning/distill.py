"""Gold dataset builder -- Layer 5 (SFT) of the Self-Improvement Engine.

Distills the brain's *successful* spec-authoring into training pairs: for every GOLD
subtask (first-pass verify-pass + adversary-approved, via ``experience.gold_examples``),
the input is the subtask's authoring context and the target is the invocation spec the
brain actually produced. Everything passes the data-quality gate (subsystem G) before it
is written. Pure-stdlib, offline-testable.

See the spec (Layer 5) + learning/dataset.py + learning/finetune.py.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  format_pair(row: dict[str, Any]) -> Optional[dict[str, Any]]  -- Turn one gold subtask row into an SFT (prompt, completion) pair, or None if it
  write_jsonl(examples: list[dict[str, Any]], path: Path) -> None
  build(*, db_path: Optional[Path]=None, out_path: Optional[Path]=None, suite: Optional[list[dict[str, Any]]]=None) -> dict[str, Any]  -- Build, clean, and (optionally) write the gold SFT dataset
DEPENDS-ON: config, learning.dataset, learning.eval_harness, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Optional

import config
from learning import dataset, eval_harness
from memory import experience

LOG = config.getLogger("sie.distill")


def format_pair(row: dict[str, Any]) -> Optional[dict[str, Any]]:
    """Turn one gold subtask row into an SFT (prompt, completion) pair, or None if it
    lacks the brain's recorded output."""
    spec = row.get("invocation_spec_json")
    if not spec:
        return None
    title = (row.get("title") or "").strip()
    prompt = (f"Subtask: {title}\n"
              f"Acceptance verify: {row.get('verify_cmd')} (expect: {row.get('verify_expect')})\n"
              f"Author the JSON invocation spec for this subtask.")
    return {"prompt": prompt, "completion": spec, "goal": title}


def write_jsonl(examples: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for ex in examples:
            f.write(json.dumps(ex, ensure_ascii=False) + "\n")


def build(*, db_path: Optional[Path] = None, out_path: Optional[Path] = None,
          suite: Optional[list[dict[str, Any]]] = None) -> dict[str, Any]:
    """Build, clean, and (optionally) write the gold SFT dataset. Returns stats + path."""
    raw = [p for p in (format_pair(r) for r in experience.gold_examples(db_path=db_path))
           if p is not None]
    cleaned = dataset.clean(raw, suite=suite)
    examples = cleaned["examples"]
    written = None
    if out_path is not None and examples:
        write_jsonl(examples, Path(out_path))
        written = str(out_path)
    return {"examples": len(examples), "path": written, "stats": cleaned["stats"]}


if __name__ == "__main__":  # pragma: no cover
    experience.init()
    print(build(out_path=config.LORA_OUTPUT_DIR / "dataset.jsonl"))
