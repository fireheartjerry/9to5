"""Meta-optimization -- subsystem Q of the SIE.

Tunes the learner's OWN knobs against the fitness series. Conservative + analysis-first:
it proposes knob changes with reasons; a slow, gated apply path adopts them. Pure-stdlib
+ ledger; offline-testable.

See the spec (subsystem Q).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  suggest(*, db_path: Optional[Path]=None) -> list[dict[str, Any]]  -- Heuristic knob suggestions from observed outcomes
  apply(*, db_path: Optional[Path]=None) -> dict[str, Any]  -- Auto-apply suggestions within safe bounds (hands-off)
DEPENDS-ON: config, learning.curriculum, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/evolution/test_nextwave_batch2.py tests/slow/test_full_autonomy.py
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Optional

import config
from learning import curriculum
from memory import experience

LOG = config.getLogger("sie.meta_opt")


def suggest(*, db_path: Optional[Path] = None) -> list[dict[str, Any]]:
    """Heuristic knob suggestions from observed outcomes. Returns a list of
    {knob, current, suggested, reason}."""
    suggestions: list[dict[str, Any]] = []
    fams = curriculum.family_stats(min_support=3, db_path=db_path)
    if fams:
        mean_fp = sum(f["first_pass_rate"] for f in fams) / len(fams)
        # If first-pass is chronically low, the bandit/effort floor is too timid.
        if mean_fp < 0.5:
            suggestions.append(
                {
                    "knob": "MAX_SUBTASK_ATTEMPTS",
                    "current": config.MAX_SUBTASK_ATTEMPTS,
                    "suggested": config.MAX_SUBTASK_ATTEMPTS + 1,
                    "reason": f"mean first-pass {mean_fp:.0%} < 50% — allow one more retry",
                }
            )
    # If almost nothing is being retrieved, widen K.
    n_emb = len(experience.embedded_subtasks(only_passed=True, db_path=db_path))
    if n_emb > 50 and config.RETRIEVAL_K < 8:
        suggestions.append(
            {
                "knob": "RETRIEVAL_K",
                "current": config.RETRIEVAL_K,
                "suggested": config.RETRIEVAL_K + 2,
                "reason": f"{n_emb} embedded successes available — retrieve more context",
            }
        )
    return suggestions


# Safe bounds so auto-apply can never push a knob somewhere harmful.
_BOUNDS = {
    "MAX_SUBTASK_ATTEMPTS": (1, 5),
    "RETRIEVAL_K": (1, 12),
    "ADVERSARY_HEARTBEAT_EVERY": (1, 10),
    "PROMPT_PROMOTE_MIN_USES": (5, 100),
    "CONFIDENCE_DEFER_THRESHOLD": (0.1, 0.8),
}


def apply(*, db_path: Optional[Path] = None) -> dict[str, Any]:
    """Auto-apply suggestions within safe bounds (hands-off). Persisted across restarts."""
    if not config.SIE_META_AUTOAPPLY:
        return {"skipped": "disabled"}
    applied = []
    for s in suggest(db_path=db_path):
        knob, val = s["knob"], s["suggested"]
        lo, hi = _BOUNDS.get(knob, (None, None))
        if lo is not None and not (lo <= val <= hi):
            continue
        knob_applied, persisted = config.set_override_detailed(knob, val)
        if knob_applied:
            applied.append({"knob": knob, "value": val, "reason": s["reason"]})
            if persisted:
                LOG.info("meta-opt auto-applied %s=%s (%s)", knob, val, s["reason"])
            else:
                LOG.warning(
                    "meta-opt applied %s=%s live but failed to persist to disk (%s)", knob, val, s["reason"]
                )
    return {"applied": applied}
