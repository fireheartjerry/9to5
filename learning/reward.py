"""Reward modeling -- Layer F of the Self-Improvement Engine.

Binary verify-pass is a weak signal. This builds a richer composite reward from outcomes
9to5 already records (pass, attempts, adversary verdict, cost) and a small, locally-fit
logistic **calibrator** that keeps the reward honest by mapping signals -> probability of
eventual success. Pure-stdlib (no numpy), deterministic, offline-testable.

Consumers: reward-weighted SFT and the DPO preference builder (learning/preferences.py).
See the spec (subsystem B).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  signals(row: dict[str, Any]) -> list[float]  -- Feature vector in [0,1] derived from a subtask outcome row.
  composite_reward(row: dict[str, Any]) -> float  -- A single [0,1] reward used to weight gold examples (heavier = cleaner win).
  Calibrator  -- A tiny logistic-regression head: signals(row) -> P(eventual success).
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_reward.py
"""
from __future__ import annotations

import math
from typing import Any, Optional

import config

LOG = config.getLogger("sie.reward")

_APPROVED = {"approved", "approve"}


def signals(row: dict[str, Any]) -> list[float]:
    """Feature vector in [0,1] derived from a subtask outcome row.

    Order: [passed, first_pass, low_attempts, adversary_ok, cheap]. Stable so the
    calibrator's learned weights stay interpretable.
    """
    passed = 1.0 if row.get("verify_passed") == 1 else 0.0
    attempts = row.get("attempt_count") or 1
    try:
        attempts = max(1, int(attempts))
    except (TypeError, ValueError):
        attempts = 1
    first_pass = 1.0 if (passed and attempts <= 1) else 0.0
    low_attempts = 1.0 / attempts
    verdict = (row.get("adversary_verdict") or "").lower()
    adversary_ok = 1.0 if verdict in _APPROVED else (0.5 if not verdict else 0.0)
    cost = float(row.get("cost_usd") or 0.0)
    cheap = 1.0 - min(1.0, cost / 1.0)
    return [passed, first_pass, low_attempts, adversary_ok, cheap]


def composite_reward(row: dict[str, Any]) -> float:
    """A single [0,1] reward used to weight gold examples (heavier = cleaner win)."""
    s = signals(row)
    weights = [0.4, 0.3, 0.1, 0.1, 0.1]   # success dominates; the rest are tie-breakers
    return round(sum(w * x for w, x in zip(weights, s)), 6)


def _sigmoid(z: float) -> float:
    if z < -60:
        return 0.0
    if z > 60:
        return 1.0
    return 1.0 / (1.0 + math.exp(-z))


class Calibrator:
    """A tiny logistic-regression head: signals(row) -> P(eventual success).

    Fit locally by gradient descent (deterministic), so the composite reward can be
    sanity-checked against what actually predicts success -- the anchor against reward
    hacking. No external ML deps.
    """

    def __init__(self, n_features: int = 5):
        self.w = [0.0] * n_features
        self.b = 0.0

    def predict(self, row: dict[str, Any]) -> float:
        x = signals(row)
        z = sum(wi * xi for wi, xi in zip(self.w, x)) + self.b
        return _sigmoid(z)

    def fit(self, rows: list[dict[str, Any]], *, label_key: str = "verify_passed",
            epochs: int = 300, lr: float = 0.3) -> "Calibrator":
        data = [(signals(r), 1.0 if r.get(label_key) == 1 else 0.0) for r in rows]
        if not data:
            return self
        n = len(self.w)
        for _ in range(epochs):
            gw = [0.0] * n
            gb = 0.0
            for x, y in data:
                pred = _sigmoid(sum(wi * xi for wi, xi in zip(self.w, x)) + self.b)
                err = pred - y
                for i in range(n):
                    gw[i] += err * x[i]
                gb += err
            m = len(data)
            self.w = [wi - lr * gw[i] / m for i, wi in enumerate(self.w)]
            self.b -= lr * gb / m
        return self
