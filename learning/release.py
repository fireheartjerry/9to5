"""Brain releases, model cards & attribution -- subsystem H of the Self-Improvement Engine.

Every promotion produces an auditable **model card**, and a periodic **attribution report**
summarizes what the system has learned (lessons, policy arms, champion prompts, adapters)
and how its fitness is trending -- the human-facing "what did I get better at" surface.
Pure-stdlib + ledger; offline-testable.

See the spec (subsystem H).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  model_card(kind: str, entity: dict[str, Any]) -> str  -- Render a markdown model card for a promoted prompt variant or adapter.
  attribution(*, db_path: Optional[Path]=None) -> dict[str, Any]  -- Summarize the SIE's learned state + fitness trend (the attribution signal).
  render_report(attr: dict[str, Any]) -> str
  write_report(path: Optional[Path]=None, *, db_path: Optional[Path]=None) -> Optional[Path]  -- Write the attribution report (best-effort)
DEPENDS-ON: config, learning.compute, learning.prompts, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Optional

import config
from learning import prompts
from memory import experience

LOG = config.getLogger("sie.release")


def model_card(kind: str, entity: dict[str, Any]) -> str:
    """Render a markdown model card for a promoted prompt variant or adapter."""
    if kind == "adapter":
        return (f"# Model Card — adapter `{entity.get('tag')}`\n\n"
                f"- Base model: `{entity.get('base_model')}` (frozen — invariant I1)\n"
                f"- Role: {entity.get('role', 'all')}\n"
                f"- Training examples: {entity.get('n_train_examples')}\n"
                f"- Trained at: {entity.get('trained_at')}\n"
                f"- State: {entity.get('state')}\n"
                f"- LoRA path: `{entity.get('lora_path')}`\n")
    return (f"# Model Card — prompt `{entity.get('role')}` v{entity.get('version')}\n\n"
            f"- Variant id: {entity.get('id')}  (parent: {entity.get('parent_id')})\n"
            f"- Body hash: `{entity.get('body_hash', '')[:12]}`\n"
            f"- Created at: {entity.get('created_at')}\n"
            f"- State: {entity.get('state')}\n")


def attribution(*, db_path: Optional[Path] = None) -> dict[str, Any]:
    """Summarize the SIE's learned state + fitness trend (the attribution signal)."""
    series = [p for p in experience.fitness_series(60, db_path=db_path)
              if isinstance(p.get("score"), dict) and "fitness" in p["score"]]
    vals = [float(p["score"]["fitness"]) for p in series]
    champ_prompts = {}
    for role in prompts.ROLES:
        c = experience.get_champion(role, db_path=db_path)
        if c:
            champ_prompts[role] = c["version"]
    try:
        from learning import compute
        compute_summary = compute.summary()
    except Exception:  # noqa: BLE001
        compute_summary = {}
    return {
        "lessons": len(experience.fetch_lessons(db_path=db_path)),
        "policy_arms": len(experience.fetch_arms(db_path=db_path)),
        "prompt_champions": champ_prompts,
        "adapters_total": len(experience.fetch_adapters(db_path=db_path)),
        "adapters_champion": len(experience.fetch_adapters("champion", db_path=db_path)),
        "compute": compute_summary,
        "fitness": {"first": vals[0] if vals else None,
                    "last": vals[-1] if vals else None,
                    "delta": (vals[-1] - vals[0]) if len(vals) >= 2 else 0.0,
                    "points": len(vals)},
    }


def render_report(attr: dict[str, Any]) -> str:
    f = attr["fitness"]
    trend = (f"{f['first']:.3f} → {f['last']:.3f} (Δ{f['delta']:+.3f}) over {f['points']} evals"
             if f["first"] is not None else "no eval points yet")
    champs = ", ".join(f"{r}=v{v}" for r, v in attr["prompt_champions"].items()) or "none"
    c = attr.get("compute", {})
    compute_line = (f"{c.get('policy')} · GPU={'yes (' + str(c.get('gpu_name')) + ')' if c.get('gpu_available') else 'no'}"
                    f" · trains on {c.get('will_train_on')}") if c else "n/a"
    return ("# 9TO5 Self-Improvement Report\n\n"
            f"- **Compute:** {compute_line}\n"
            f"- **Fitness:** {trend}\n"
            f"- **Lessons:** {attr['lessons']}\n"
            f"- **Policy arms:** {attr['policy_arms']}\n"
            f"- **Champion prompts:** {champs}\n"
            f"- **Adapters:** {attr['adapters_total']} total, "
            f"{attr['adapters_champion']} champion\n")


def write_report(path: Optional[Path] = None, *, db_path: Optional[Path] = None) -> Optional[Path]:
    """Write the attribution report (best-effort). Returns the path or None."""
    p = Path(path) if path is not None \
        else Path(config.VAULT_DISK_ROOT) / config.SESSIONS_DIR_REL / "sie-report.md"
    try:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(render_report(attribution(db_path=db_path)), encoding="utf-8")
        return p
    except Exception as e:  # noqa: BLE001
        LOG.warning("report write failed (ignored): %s", e)
        return None
