"""Solution memoization / warm-start -- subsystem O of the SIE.

Lessons are advice; this reuses *work*. On a near-duplicate subtask signature, return the
prior PASSING spec to warm-start or short-circuit instead of re-deriving it. Gated by
"did it still verify". Pure-stdlib + ledger; offline-testable.

See the spec (subsystem O).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  signature_of(title: str) -> str  -- A coarse, normalized signature for matching near-duplicate subtasks.
  build_from_ledger(*, db_path: Optional[Path]=None) -> dict[str, int]  -- Populate the cache from gold (first-pass, approved) subtasks that carry a spec.
  warm_start(title: str, *, db_path: Optional[Path]=None) -> Optional[str]  -- Return a cached PASSING spec for a near-duplicate subtask, or None.
DEPENDS-ON: config, memory.experience, provenance.Verdict, provenance.assertIngestible, provenance.coerce
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_solution_cache_provenance.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Optional

import config
from memory import experience
from provenance import Verdict, assertIngestible, coerce

LOG = config.getLogger("sie.solution_cache")


def signature_of(title: str) -> str:
    """A coarse, normalized signature for matching near-duplicate subtasks."""
    return re.sub(r"\s+", " ", (title or "").strip().lower())


_GOLD_PROVENANCE = '{"origin":"brain","attested_by":"sie:gold"}'


def build_from_ledger(*, db_path: Optional[Path] = None) -> dict[str, int]:
    """Populate the cache from gold (first-pass, approved) subtasks that carry a spec.

    Gold rows are real-adversary-approved (non-stub) -> stamp them TRUSTED so
    warm_start's provenance gate still serves them.
    """
    cached = 0
    for r in experience.gold_examples(db_path=db_path):
        spec = r.get("invocation_spec_json")
        if not spec:
            continue
        if experience.upsert_solution(signature_of(r.get("title") or ""), spec,
                                      verify_passed=True,
                                      provenance=_GOLD_PROVENANCE,
                                      db_path=db_path):
            cached += 1
    return {"cached": cached}


def warm_start(title: str, *, db_path: Optional[Path] = None) -> Optional[str]:
    """Return a cached PASSING spec for a near-duplicate subtask, or None.

    Fails CLOSED: a row is served only when its provenance passes the
    assertIngestible 'believe' gate (i.e. attested or trusted origin).
    Missing / executor / brain-unattested provenance all block warm-start.
    Forgery residual (Spec 3): an attacker who can write to the DB can forge
    attested_by; that risk is accepted at this phase -- a signing/MAC layer
    would be required to close it fully.
    """
    try:
        sig = signature_of(title)
        sol = experience.get_solution(sig, db_path=db_path)
        if sol is None:
            return None
        # Parse provenance -- missing/NULL degrades to EXECUTOR (least trusted).
        raw_prov = sol.get("provenance")
        try:
            prov_dict = json.loads(raw_prov) if raw_prov else {}
        except Exception:  # noqa: BLE001
            prov_dict = {}
        prov = coerce(prov_dict)
        decision = assertIngestible(f"solution_cache:{sig}", "believe", prov)
        if decision.verdict is not Verdict.ALLOW:
            LOG.debug("warm_start blocked for %r: %s", sig, decision.reason)
            return None
        return sol["spec_json"]
    except Exception as e:  # noqa: BLE001
        LOG.debug("warm_start failed (ignored): %s", e)
        return None
