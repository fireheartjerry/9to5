"""Import-cycle detection + pre-flight cycle prediction (iterative Tarjan SCC).

Semantics deliberately match ``introspect.project_extract._cycleCount``: a cycle
is an SCC of size >1 OR a self-loop. Output is fully deterministic -- each
cycle's members are sorted ascending (NOT rotated edge order) and the cycle
list itself is sorted.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  buildImportGraph(model: ProjectModel) -> dict[str, set[str]]  -- Adjacency dict over module relpaths from the model's load-time import edges.
  findCycles(graph: dict[str, set[str]]) -> list[list[str]]  -- All import cycles in ``graph``: SCCs of size >1 plus self-loops.
  wouldCreateCycle(graph: dict[str, set[str]], added_edges: list[tuple[str, str]], removed_edges: list[tuple[str, str]] | tuple[tuple[str, str], ...]=()) -> list[list[str]]  -- Cycles that would exist AFTER the edge changes but do not exist now.
DEPENDS-ON: introspect.project_model
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/refactor/test_cycle_detect.py
"""
from __future__ import annotations

from introspect.project_model import ProjectModel


def buildImportGraph(model: ProjectModel) -> dict[str, set[str]]:
    """Adjacency dict over module relpaths from the model's load-time import edges."""
    graph: dict[str, set[str]] = {m.path: set() for m in model.modules}
    for src, dst in model.import_edges:
        if src in graph and dst in graph:
            graph[src].add(dst)
    return graph


def findCycles(graph: dict[str, set[str]]) -> list[list[str]]:
    """All import cycles in ``graph``: SCCs of size >1 plus self-loops.

    Iterative Tarjan (explicit work stack -- no recursion-limit risk). Each cycle
    is returned with members sorted ascending (not in traversal/rotation order)
    and the resulting list is itself sorted, so output is deterministic.
    """
    adjacency = _normalizedAdjacency(graph)
    cycles = [
        sorted(scc)
        for scc in _tarjanSccs(adjacency)
        if len(scc) > 1 or scc[0] in adjacency[scc[0]]
    ]
    cycles.sort()
    return cycles


def wouldCreateCycle(
    graph: dict[str, set[str]],
    added_edges: list[tuple[str, str]],
    removed_edges: list[tuple[str, str]] | tuple[tuple[str, str], ...] = (),
) -> list[list[str]]:
    """Cycles that would exist AFTER the edge changes but do not exist now.

    Pre-existing cycles are subtracted, so an unrelated safe edge in an already
    cyclic graph reports []. Runs ``findCycles`` over the whole graph twice --
    O(V+E) each, fine at project scale (documented trade-off vs a reachable-
    subgraph restriction). The input graph is never mutated.
    """
    before = {tuple(cycle) for cycle in findCycles(graph)}
    modified = {node: set(targets) for node, targets in graph.items()}
    for src, dst in removed_edges:
        modified.get(src, set()).discard(dst)
    for src, dst in added_edges:
        modified.setdefault(src, set()).add(dst)
        modified.setdefault(dst, set())
    return [cycle for cycle in findCycles(modified) if tuple(cycle) not in before]


def _normalizedAdjacency(graph: dict[str, set[str]]) -> dict[str, list[str]]:
    """Sorted adjacency lists covering every referenced node (dangling targets too)."""
    nodes = set(graph)
    for targets in graph.values():
        nodes.update(targets)
    return {node: sorted(graph.get(node, ())) for node in sorted(nodes)}


def _tarjanSccs(adjacency: dict[str, list[str]]) -> list[list[str]]:
    """Strongly connected components via iterative Tarjan over sorted adjacency."""
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    on_stack: set[str] = set()
    stack: list[str] = []
    next_index = 0
    sccs: list[list[str]] = []
    for start in adjacency:
        if start in index:
            continue
        work: list[tuple[str, int]] = [(start, 0)]
        while work:
            node, i = work.pop()
            if i == 0:
                index[node] = low[node] = next_index
                next_index += 1
                stack.append(node)
                on_stack.add(node)
            descended = False
            for j in range(i, len(adjacency[node])):
                nxt = adjacency[node][j]
                if nxt not in index:
                    work.append((node, j + 1))
                    work.append((nxt, 0))
                    descended = True
                    break
                if nxt in on_stack:
                    low[node] = min(low[node], index[nxt])
            if descended:
                continue
            if low[node] == index[node]:
                scc: list[str] = []
                while True:
                    member = stack.pop()
                    on_stack.discard(member)
                    scc.append(member)
                    if member == node:
                        break
                sccs.append(scc)
            if work:
                parent = work[-1][0]
                low[parent] = min(low[parent], low[node])
    return sccs
