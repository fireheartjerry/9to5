"""Cross-root symbol usage scan: every AST Name/Attribute/ImportFrom reference.

Generalizes ``tools/codemod.py::cmd_usages`` to ANY root directory: walks .py
files (skipping the same vendored/build/cache dirs as introspect's scanner) and
records each reference to ``symbol`` with its file, line, and reference kind.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Usage -- frozen (file, line, kind) record; kind in {"name","attr","import"}
  findUsages(root, symbol) -> list[Usage]  -- sorted (file, line, kind), python files only
DEPENDS-ON: introspect.project_scanner
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/refactor/test_symbol_usages.py
"""
from __future__ import annotations

import ast
import os
from dataclasses import dataclass
from pathlib import Path

from introspect.project_scanner import EXCLUDE_DIRS


@dataclass(frozen=True)
class Usage:
    """One reference to a symbol: POSIX relpath, 1-based line, reference kind."""

    file: str
    line: int
    kind: str  # "name" | "attr" | "import"


def findUsages(root: str | Path, symbol: str) -> list[Usage]:
    """Every reference to ``symbol`` in .py files under ``root``, sorted.

    ``ast.Name`` => "name", ``ast.Attribute`` (matching ``.attr``) => "attr",
    ``ast.ImportFrom`` imported names => "import". Unreadable or syntactically
    invalid files are skipped, never a crash.
    """
    root_path = Path(root).resolve()
    usages: list[Usage] = []
    for rel in _pyFiles(root_path):
        tree = _parseOrNone(root_path / rel)
        if tree is None:
            continue
        usages.extend(_usagesInTree(tree, rel, symbol))
    usages.sort(key=lambda u: (u.file, u.line, u.kind))
    return usages


def _usagesInTree(tree: ast.Module, rel: str, symbol: str) -> list[Usage]:
    """All Usage records for ``symbol`` in one parsed module."""
    hits: list[Usage] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            hits.extend(
                Usage(file=rel, line=getattr(alias, "lineno", node.lineno), kind="import")
                for alias in node.names
                if alias.name == symbol
            )
        elif isinstance(node, ast.Name) and node.id == symbol:
            hits.append(Usage(file=rel, line=node.lineno, kind="name"))
        elif isinstance(node, ast.Attribute) and node.attr == symbol:
            hits.append(Usage(file=rel, line=node.lineno, kind="attr"))
    return hits


def _pyFiles(root_path: Path) -> list[str]:
    """Sorted POSIX relpaths of every .py file under root, excluding EXCLUDE_DIRS."""
    found: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root_path):
        dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDE_DIRS)
        found.extend(
            (Path(dirpath) / name).relative_to(root_path).as_posix()
            for name in filenames
            if name.endswith(".py")
        )
    return sorted(found)


def _parseOrNone(path: Path) -> ast.Module | None:
    """Parsed AST for ``path``, or None when unreadable / not valid Python."""
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    try:
        return ast.parse(src)
    except SyntaxError:
        return None
