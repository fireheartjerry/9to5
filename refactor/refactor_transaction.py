"""Atomic multi-file refactor transaction: snapshot -> write -> gate -> rollback.

All-or-nothing: every touched path is byte-snapshotted (MISSING sentinel for
not-yet-existing files) before any write; any validation or gate failure
restores every snapshot byte-for-byte (MISSING => unlink) and reports an
explicit RefactorResult. Gates: py_compile on every touched .py, only-NEW-
import-cycles check (pre-existing cycles never block unrelated edits), and an
optional caller command run WITHOUT a shell. Unrelated dirty files are never
touched. Restore errors are reported loudly in ``reason``, never swallowed.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  MISSING -- snapshot sentinel for files that did not exist pre-apply
  RefactorResult -- frozen apply outcome (applied, reason, gate_output, files_touched)
  RefactorTransaction -- add(edit) -> preview() -> apply(gate_cmd=..., check_cycles=...)
DEPENDS-ON: introspect, refactor.change_impact, refactor.cycle_detect, refactor.refactor_edits
SIDE-EFFECTS: writes/renames/deletes files under the transaction root during apply;
  runs the optional gate command as a subprocess; compiles touched .py files
RUN/TEST: python -m pytest tests/refactor/test_refactor_transaction.py
"""
from __future__ import annotations

import py_compile
import shlex
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

from refactor.change_impact import ImpactReport, predictImpact
from refactor.cycle_detect import buildImportGraph, findCycles
from refactor.refactor_edits import (
    DeleteFile,
    RenameFile,
    ReplaceInFile,
    WriteFile,
    editPaths,
    validateEdit,
)

MISSING = object()  # snapshot sentinel: path did not exist before apply


@dataclass(frozen=True)
class RefactorResult:
    """Outcome of one apply(): all-applied or nothing-applied, with the why."""

    applied: bool
    reason: str = ""
    gate_output: str = ""
    files_touched: tuple[str, ...] = ()


class RefactorTransaction:
    """Collect edits against one root, preview their impact, apply atomically."""

    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()
        self.edits: list = []

    def add(self, edit) -> None:
        """Queue one edit; raises ValueError when validation rejects it."""
        reason = validateEdit(self.root, edit)
        if reason is not None:
            raise ValueError(reason)
        self.edits.append(edit)

    def preview(self, model=None) -> ImpactReport:
        """Pure impact prediction for the queued edits (no writes)."""
        if model is None:
            from introspect import extractProject

            model = extractProject(self.root, use_cache=False)
        return predictImpact(model, self.edits)

    def apply(
        self, *, gate_cmd: str | None = None, check_cycles: bool = True, timeout_s: int = 300
    ) -> RefactorResult:
        """Validate -> snapshot -> write all -> gate -> commit or full rollback."""
        reason = self._validateAll()
        if reason is not None:
            return RefactorResult(applied=False, reason=reason)
        pre_cycles = self._cycleSet() if check_cycles else set()
        touched = sorted({_norm(p) for e in self.edits for p in editPaths(e)})
        snapshots = self._snapshot(touched)
        try:
            self._writeAll()
        except Exception as exc:  # noqa: BLE001 -- any write failure => rollback
            return self._rollback(snapshots, f"write failed: {exc}", "")
        failure, gate_output = self._gate(touched, pre_cycles, check_cycles, gate_cmd, timeout_s)
        if failure is not None:
            return self._rollback(snapshots, failure, gate_output)
        return RefactorResult(applied=True, gate_output=gate_output, files_touched=tuple(touched))

    # -- apply phases ----------------------------------------------------------

    def _validateAll(self) -> str | None:
        """Re-validate every edit + must-match-once, simulated sequentially in memory."""
        if not self.edits:
            return "no edits added"
        contents: dict[str, bytes | None] = {}
        for edit in self.edits:
            reason = validateEdit(self.root, edit)
            if reason is None:
                reason = self._simulateEdit(edit, contents)
            if reason is not None:
                return reason
        return None

    def _simulateEdit(self, edit, contents: dict[str, bytes | None]) -> str | None:
        """Apply one edit to the in-memory byte map; reason string on any problem."""
        current = self._currentReader(contents)
        if isinstance(edit, WriteFile):
            contents[_norm(edit.path)] = edit.content.encode("utf-8")
            return None
        if isinstance(edit, ReplaceInFile):
            rel = _norm(edit.path)
            data = current(rel)
            if data is None:
                return f"ReplaceInFile target missing: {rel}"
            count = data.count(edit.old.encode("utf-8"))
            if count != 1:
                return f"ReplaceInFile {rel}: old text must match exactly once, found {count}"
            contents[rel] = data.replace(edit.old.encode("utf-8"), edit.new.encode("utf-8"))
            return None
        if isinstance(edit, DeleteFile):
            rel = _norm(edit.path)
            if current(rel) is None:
                return f"DeleteFile target missing: {rel}"
            contents[rel] = None
            return None
        src, dst = _norm(edit.path), _norm(edit.new_path)   # RenameFile
        data = current(src)
        if data is None:
            return f"RenameFile source missing: {src}"
        contents[dst] = data
        contents[src] = None
        return None

    def _currentReader(self, contents: dict[str, bytes | None]):
        """Reader over the in-memory map, falling back to on-disk bytes."""

        def current(rel: str) -> bytes | None:
            if rel in contents:
                return contents[rel]
            path = self.root / rel
            return path.read_bytes() if path.is_file() else None

        return current

    def _snapshot(self, touched: list[str]) -> dict[str, object]:
        """Exact current bytes per touched path; MISSING when it does not exist."""
        snapshots: dict[str, object] = {}
        for rel in touched:
            path = self.root / rel
            snapshots[rel] = path.read_bytes() if path.is_file() else MISSING
        return snapshots

    def _writeAll(self) -> None:
        """Perform every edit on disk, in order (parents created as needed)."""
        for edit in self.edits:
            if isinstance(edit, WriteFile):
                target = self.root / _norm(edit.path)
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(edit.content.encode("utf-8"))
            elif isinstance(edit, ReplaceInFile):
                target = self.root / _norm(edit.path)
                data = target.read_bytes()
                target.write_bytes(
                    data.replace(edit.old.encode("utf-8"), edit.new.encode("utf-8"))
                )
            elif isinstance(edit, DeleteFile):
                (self.root / _norm(edit.path)).unlink()
            else:                                            # RenameFile: read+write+delete
                src = self.root / _norm(edit.path)
                dst = self.root / _norm(edit.new_path)
                data = src.read_bytes()
                dst.parent.mkdir(parents=True, exist_ok=True)
                dst.write_bytes(data)
                src.unlink()

    def _gate(
        self,
        touched: list[str],
        pre_cycles: set[tuple[str, ...]],
        check_cycles: bool,
        gate_cmd: str | None,
        timeout_s: int,
    ) -> tuple[str | None, str]:
        """(failure reason | None, gate command output). Order: compile, cycles, cmd."""
        reason = self._compileGate(touched)
        if reason is not None:
            return reason, ""
        if check_cycles:
            new_cycles = sorted(self._cycleSet() - pre_cycles)
            if new_cycles:
                rendered = "; ".join(" -> ".join(c) for c in new_cycles)
                return f"new import cycle(s) introduced: {rendered}", ""
        if gate_cmd is not None:
            return self._commandGate(gate_cmd, timeout_s)
        return None, ""

    def _compileGate(self, touched: list[str]) -> str | None:
        """py_compile every touched .py that still exists; scratch cfile, no pollution."""
        with tempfile.TemporaryDirectory(prefix="9to5-gate-") as scratch:
            cfile = str(Path(scratch) / "gate.pyc")
            for rel in touched:
                path = self.root / rel
                if not rel.endswith(".py") or not path.is_file():
                    continue
                try:
                    py_compile.compile(str(path), cfile=cfile, doraise=True)
                except py_compile.PyCompileError as exc:
                    return f"py_compile failed: {exc}"
                except Exception as exc:  # noqa: BLE001 -- unreadable file etc.
                    return f"py_compile failed for {rel}: {exc}"
        return None

    def _commandGate(self, gate_cmd: str, timeout_s: int) -> tuple[str | None, str]:
        """Run the caller's gate command WITHOUT a shell; rc 0 required."""
        try:
            proc = subprocess.run(
                shlex.split(gate_cmd),
                cwd=self.root,
                timeout=timeout_s,
                capture_output=True,
            )
        except subprocess.TimeoutExpired:
            return f"gate command timed out after {timeout_s}s: {gate_cmd}", ""
        except Exception as exc:  # noqa: BLE001 -- e.g. executable not found
            return f"gate command failed to start: {exc}", ""
        output = (proc.stdout + proc.stderr).decode("utf-8", errors="replace")
        if proc.returncode != 0:
            return f"gate command exited {proc.returncode}: {gate_cmd}", output
        return None, output

    def _cycleSet(self) -> set[tuple[str, ...]]:
        """Current import cycles of the root as canonical tuples."""
        from introspect import extractProject

        model = extractProject(self.root, use_cache=False)
        return {tuple(c) for c in findCycles(buildImportGraph(model))}

    def _rollback(
        self, snapshots: dict[str, object], reason: str, gate_output: str
    ) -> RefactorResult:
        """Restore every snapshot byte-for-byte; restore errors reported loudly."""
        errors: list[str] = []
        for rel, data in snapshots.items():
            path = self.root / rel
            try:
                if data is MISSING:
                    if path.is_file():
                        path.unlink()
                else:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(data)  # type: ignore[arg-type]
            except Exception as exc:  # noqa: BLE001 -- collected, reported below
                errors.append(f"{rel}: {exc}")
        if errors:
            reason += " | ROLLBACK ERRORS (tree may be inconsistent): " + "; ".join(errors)
        return RefactorResult(applied=False, reason=reason, gate_output=gate_output)


def _norm(path: str) -> str:
    """Canonical POSIX relpath key for an edit path."""
    return path.replace("\\", "/")
