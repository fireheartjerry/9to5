"""Crash journal for RefactorTransaction: spill snapshots to disk pre-write.

apply() writes every snapshot into a ``refactor-tx-*`` temp dir (one file per
snapshot plus a ``manifest.json`` mapping relpath -> snapshot-file-or-MISSING
and recording the target root) BEFORE touching any target file. A hard process
crash mid-apply therefore leaves a durable journal behind;
``refactor.refactor_transaction.recoverJournal`` restores it. The journal is
deleted after a successful apply and after a clean rollback; it is KEPT when
restore itself errors, so the bytes are never lost while the tree is broken.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  MISSING -- snapshot sentinel for files that did not exist pre-apply
  writeJournal(root, snapshots) -> Path -- spill snapshots + manifest to a new temp dir
  loadJournal(journal_dir) -> tuple[Path, dict[str, object]] -- read a journal back
  restoreSnapshots(root, snapshots) -> list[str] -- byte-for-byte restore; error strings
  deleteJournal(journal_dir) -- best-effort removal of a journal dir
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: creates/deletes a temp journal dir; restoreSnapshots writes/unlinks
  files under the given root
RUN/TEST: python -m pytest tests/refactor/test_refactor_hardening.py
"""
from __future__ import annotations

import json
import shutil
import tempfile
from pathlib import Path

MISSING = object()  # snapshot sentinel: path did not exist before apply

_MANIFEST = "manifest.json"
_MISSING_MARK = "MISSING"


def writeJournal(root: Path, snapshots: dict[str, object]) -> Path:
    """Spill ``snapshots`` to a new ``refactor-tx-*`` temp dir; returns the dir."""
    journal = Path(tempfile.mkdtemp(prefix="refactor-tx-"))
    manifest: dict[str, str] = {}
    for i, rel in enumerate(sorted(snapshots)):
        data = snapshots[rel]
        if data is MISSING:
            manifest[rel] = _MISSING_MARK
            continue
        name = f"snap-{i:04d}.bin"
        (journal / name).write_bytes(data)  # type: ignore[arg-type]
        manifest[rel] = name
    payload = {"root": str(root), "snapshots": manifest}
    (journal / _MANIFEST).write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return journal


def loadJournal(journal_dir: str | Path) -> tuple[Path, dict[str, object]]:
    """(root, snapshots) parsed back from a journal dir's manifest."""
    journal = Path(journal_dir)
    payload = json.loads((journal / _MANIFEST).read_text(encoding="utf-8"))
    snapshots: dict[str, object] = {}
    for rel, marker in payload["snapshots"].items():
        snapshots[rel] = MISSING if marker == _MISSING_MARK else (journal / marker).read_bytes()
    return Path(payload["root"]), snapshots


def restoreSnapshots(root: Path, snapshots: dict[str, object]) -> list[str]:
    """Restore every snapshot byte-for-byte (MISSING => unlink); error strings back."""
    errors: list[str] = []
    for rel, data in snapshots.items():
        path = root / rel
        try:
            if data is MISSING:
                if path.is_file():
                    path.unlink()
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)  # type: ignore[arg-type]
        except Exception as exc:  # noqa: BLE001 -- collected, reported by caller
            errors.append(f"{rel}: {exc}")
    return errors


def deleteJournal(journal_dir: Path) -> None:
    """Best-effort removal of a journal dir (no error when already gone)."""
    shutil.rmtree(journal_dir, ignore_errors=True)
