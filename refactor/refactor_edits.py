"""Edit primitives (frozen dataclasses) + fail-closed path validation.

Every edit targets a path INSIDE the transaction root: absolute paths outside
the root, ``../`` escapes, and any FORBIDDEN_SEGMENTS component are rejected
with an explicit reason string (never silently skipped).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  WriteFile(path, content) -- create-or-overwrite one file
  ReplaceInFile(path, old, new) -- exact replacement; old must occur EXACTLY once
  DeleteFile(path) -- remove one file
  RenameFile(path, new_path) -- move one file
  FORBIDDEN_SEGMENTS -- path components no edit may ever touch
  EDIT_TYPES -- tuple of the four edit classes (isinstance checks)
  Edit -- union type alias over the four edit primitives
  editPaths(edit) -> tuple[str, ...] -- every path an edit touches
  validateEdit(root, edit) -> str | None  -- None = ok, else rejection reason
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/refactor/test_refactor_edits.py
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

FORBIDDEN_SEGMENTS = (".git", ".env", "venv", ".venv", "node_modules", "__pycache__")


@dataclass(frozen=True)
class WriteFile:
    """Create or overwrite ``path`` with ``content`` (UTF-8)."""

    path: str
    content: str


@dataclass(frozen=True)
class ReplaceInFile:
    """Replace ``old`` with ``new`` in ``path``; ``old`` must occur exactly once."""

    path: str
    old: str
    new: str


@dataclass(frozen=True)
class DeleteFile:
    """Delete ``path``."""

    path: str


@dataclass(frozen=True)
class RenameFile:
    """Move ``path`` to ``new_path`` (content preserved byte-for-byte)."""

    path: str
    new_path: str


EDIT_TYPES = (WriteFile, ReplaceInFile, DeleteFile, RenameFile)

Edit = WriteFile | ReplaceInFile | DeleteFile | RenameFile  # type alias over all primitives


def editPaths(edit) -> tuple[str, ...]:
    """Every path the edit touches (both endpoints for RenameFile)."""
    if isinstance(edit, RenameFile):
        return (edit.path, edit.new_path)
    return (edit.path,)


def validateEdit(root: Path, edit) -> str | None:
    """None when the edit is safe to consider, else a human-readable rejection.

    Rejections: unknown edit type; empty path; path resolving outside ``root``
    (absolute or via ``..``); any FORBIDDEN_SEGMENTS component in the relpath.
    """
    if not isinstance(edit, EDIT_TYPES):
        return f"unsupported edit type: {type(edit).__name__}"
    root_resolved = Path(root).resolve()
    for raw in editPaths(edit):
        reason = _validatePath(root_resolved, raw)
        if reason is not None:
            return reason
    return None


def _validatePath(root_resolved: Path, raw: str) -> str | None:
    """Rejection reason for one path, or None when it stays inside the root."""
    if not raw or not str(raw).strip():
        return "empty path"
    candidate = Path(raw)
    target = candidate if candidate.is_absolute() else root_resolved / candidate
    try:
        rel = target.resolve().relative_to(root_resolved)
    except (ValueError, OSError):
        return f"path escapes root: {raw}"
    for part in rel.parts:
        if part in FORBIDDEN_SEGMENTS:
            return f"forbidden path segment '{part}': {raw}"
    return None
