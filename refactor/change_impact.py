"""Pure breaking-change prediction for a planned edit set -- no disk writes.

Applies edits in memory, re-analyzes the changed Python files (via a scratch
temp dir so ``introspect.python_import_graph.analyzePython`` sees post-edit
content), then derives: deleted/renamed exports -> orphaned usage sites,
import-edge diff -> NEW cycles only (pre-existing cycles never re-reported),
touched files -> convention-mapped tests.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ImpactReport -- frozen prediction summary; ok = no orphans and no new cycles
  predictImpact(model, edits) -> ImpactReport
DEPENDS-ON: introspect.python_import_graph, introspect.project_test_map,
  refactor.cycle_detect, refactor.refactor_edits, refactor.symbol_usages
SIDE-EFFECTS: creates and removes a scratch temp dir during analysis
RUN/TEST: python -m pytest tests/refactor/test_change_impact.py
"""
from __future__ import annotations

import posixpath
import tempfile
from dataclasses import dataclass
from pathlib import Path

from introspect.project_model import ModuleInfo, ProjectModel
from introspect.project_test_map import mapFileToTests
from introspect.python_import_graph import analyzePython

from refactor.cycle_detect import buildImportGraph, wouldCreateCycle
from refactor.refactor_edits import DeleteFile, RenameFile, ReplaceInFile, WriteFile
from refactor.symbol_usages import Usage, findUsages


@dataclass(frozen=True)
class ImpactReport:
    """Prediction of what a planned edit set breaks (pure, computed pre-apply)."""

    files_touched: tuple[str, ...]
    orphaned_usages: tuple[Usage, ...]
    new_cycles: tuple[tuple[str, ...], ...]
    affected_tests: tuple[str, ...]
    ok: bool


def predictImpact(model: ProjectModel, edits: list) -> ImpactReport:
    """Predict orphaned usages, new import cycles, and affected tests for ``edits``."""
    root = Path(model.root)
    contents = _postEditContents(root, edits)          # relpath -> str | None(=deleted)
    old_by_path = {m.path: m for m in model.modules}
    new_infos = _reanalyzePython(old_by_path, contents)
    orphans = _orphanedUsages(root, old_by_path, contents, new_infos)
    new_cycles = _newCycles(model, old_by_path, contents, new_infos)
    tests = _affectedTests(model, contents)
    return ImpactReport(
        files_touched=tuple(sorted(contents)),
        orphaned_usages=tuple(orphans),
        new_cycles=tuple(tuple(c) for c in new_cycles),
        affected_tests=tuple(tests),
        ok=not orphans and not new_cycles,
    )


def _postEditContents(root: Path, edits: list) -> dict[str, str | None]:
    """Post-edit text per touched relpath (None = deleted), applied in order."""
    contents: dict[str, str | None] = {}

    def current(rel: str) -> str | None:
        if rel in contents:
            return contents[rel]
        try:
            return (root / rel).read_text(encoding="utf-8", errors="replace")
        except OSError:
            return None

    for edit in edits:
        if isinstance(edit, WriteFile):
            contents[_norm(edit.path)] = edit.content
        elif isinstance(edit, ReplaceInFile):
            rel = _norm(edit.path)
            text = current(rel)
            contents[rel] = text.replace(edit.old, edit.new) if text is not None else None
        elif isinstance(edit, DeleteFile):
            contents[_norm(edit.path)] = None
        elif isinstance(edit, RenameFile):
            src, dst = _norm(edit.path), _norm(edit.new_path)
            contents[dst] = current(src)
            contents[src] = None
    return contents


def _norm(path: str) -> str:
    """Canonical POSIX relpath key for an edit path."""
    return path.replace("\\", "/")


def _reanalyzePython(
    old_by_path: dict[str, ModuleInfo], contents: dict[str, str | None]
) -> dict[str, ModuleInfo]:
    """New ModuleInfo per changed/new .py file, analyzed against the post-edit set.

    Post-edit files are written to a scratch temp dir so analyzePython parses the
    NEW text; the full survivor relpath list keeps first-party import resolution
    correct (unchanged files degrade to skeletons there, which we never consume).
    """
    changed = {rel for rel, text in contents.items() if rel.endswith(".py") and text is not None}
    survivors = {p for p in old_by_path if p.endswith(".py")}
    survivors -= {rel for rel, text in contents.items() if text is None}
    survivors |= changed
    if not changed:
        return {}
    with tempfile.TemporaryDirectory(prefix="9to5-impact-") as scratch:
        scratch_root = Path(scratch)
        for rel in changed:
            target = scratch_root / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(contents[rel] or "", encoding="utf-8")
        analyzed = analyzePython(scratch_root, sorted(survivors))
    return {rel: analyzed[rel] for rel in changed if rel in analyzed}


def _orphanedUsages(
    root: Path,
    old_by_path: dict[str, ModuleInfo],
    contents: dict[str, str | None],
    new_infos: dict[str, ModuleInfo],
) -> list[Usage]:
    """Usage sites referencing exports that a planned edit deletes or renames."""
    removed_by_symbol: dict[str, set[str]] = {}
    for rel, old_info in old_by_path.items():
        if rel not in contents or not rel.endswith(".py"):
            continue
        new_exports = (
            set(new_infos[rel].exports) if rel in new_infos else set()
        )
        for symbol in set(old_info.exports) - new_exports:
            removed_by_symbol.setdefault(symbol, set()).add(rel)
    orphans: dict[Usage, None] = {}
    for symbol in sorted(removed_by_symbol):
        sources = removed_by_symbol[symbol]
        for usage in findUsages(root, symbol):
            if _isOrphan(usage, symbol, sources, contents):
                orphans[usage] = None
    return sorted(orphans, key=lambda u: (u.file, u.line, u.kind))


def _isOrphan(
    usage: Usage, symbol: str, sources: set[str], contents: dict[str, str | None]
) -> bool:
    """True unless the usage lives in the defining file or an edit already fixes it."""
    if usage.file in sources:
        return False                     # the edited file's own references/definitions
    if usage.file in contents:
        text = contents[usage.file]
        return text is not None and symbol in text
    return True


def _newCycles(
    model: ProjectModel,
    old_by_path: dict[str, ModuleInfo],
    contents: dict[str, str | None],
    new_infos: dict[str, ModuleInfo],
) -> list[list[str]]:
    """Cycles introduced by the import-edge diff (pre-existing cycles excluded)."""
    added: list[tuple[str, str]] = []
    removed: list[tuple[str, str]] = []
    for rel, text in contents.items():
        if not rel.endswith(".py"):
            continue
        old_targets = set(old_by_path[rel].imports) if rel in old_by_path else set()
        new_targets = set(new_infos[rel].imports) if text is not None else set()
        added.extend((rel, t) for t in sorted(new_targets - old_targets))
        removed.extend((rel, t) for t in sorted(old_targets - new_targets))
        if text is None:                 # deleted file: incoming edges vanish too
            removed.extend((s, t) for s, t in model.import_edges if t == rel)
    return wouldCreateCycle(buildImportGraph(model), added, removed)


def _affectedTests(model: ProjectModel, contents: dict[str, str | None]) -> list[str]:
    """Convention-mapped tests for every touched file, deduped and sorted."""
    test_files = [m.path for m in model.modules if _isTestFile(m.path)]
    hits: set[str] = set()
    for rel in contents:
        hits.update(mapFileToTests(model.root, rel, test_files))
    return sorted(hits)


def _isTestFile(path: str) -> bool:
    """Conventional test file: test_*.py, or JS/TS *.test.* / *.spec.*."""
    base = posixpath.basename(path)
    if base.startswith("test_") and base.endswith(".py"):
        return True
    return ".test." in base or ".spec." in base
