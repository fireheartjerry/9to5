#!/usr/bin/env python3
"""VERIFY Phase 2 end-to-end: enter the 9to5 PROJECT, send a multiline adversary prompt,
confirm the message stayed IN the project, and parse the JSON verdict.
Please DON'T close the browser window until it prints a final verdict line.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  (no public exports)
DEPENDS-ON: agents.chatgpt_driver, config
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
import json
import sys

from agents.chatgpt_driver import ChatGPTSession
import config

PROMPT = """Review this subtask output for a self-improvement run:

**Subtask:** Improve Discord dashboard embed rendering

**What was done:**
- Added a live metrics bar (cpu, token usage, subtask progress)
- Implemented field clamping for large outputs
- Added relative timestamps via Discord <t:unix:R>

**Verification:** none (UI change, manual browser check only)
**Flagged risk:** embed size limits if metrics get verbose

Reply with JSON only."""

print(f"[*] project url: {config.CHATGPT_PROJECT_URL}")
sess = ChatGPTSession()
ok = True
try:
    sess.open()
    print("[*] start_run_conversation -> entering 9to5 project...")
    sess.start_run_conversation(goal="Discord integration improvements", task_id="verify-001")

    url_before = sess.page.url
    in_project_before = "/g/g-p-" in url_before
    print(f"[{'✓' if in_project_before else '✗'}] in project before send: {in_project_before}  ({url_before[:80]})")
    ok = ok and in_project_before

    print("[*] sending multiline adversary prompt (Shift+Enter newlines)...")
    reply = sess.ask(PROMPT, expect_json=True)

    url_after = sess.page.url
    in_project_after = "/g/g-p-" in url_after
    print(f"[{'✓' if in_project_after else '✗'}] still in project after send: {in_project_after}  ({url_after[:80]})")
    ok = ok and in_project_after

    if not reply:
        print("[✗] no reply")
        ok = False
    else:
        print(f"[✓] reply received ({len(reply)} chars)")
        try:
            v = json.loads(reply)
            print(f"[✓] valid JSON  verdict={v.get('verdict')}  confidence={v.get('confidence')}")
            for f in (v.get("findings") or [])[:3]:
                print(f"      - {f}")
        except json.JSONDecodeError as e:
            print(f"[!] reply not strict JSON ({e}); first 200 chars: {reply[:200]}")

    print()
    print(f"{'[✓✓✓] PHASE 2 PROJECT FLOW VERIFIED' if ok else '[✗] VERIFICATION FAILED — see flags above'}")
except Exception as e:
    print(f"[✗] {type(e).__name__}: {e}")
    import traceback
    traceback.print_exc()
    ok = False
finally:
    try:
        sess.close()
    except Exception:
        pass
sys.exit(0 if ok else 1)
