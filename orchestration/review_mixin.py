from notifications import discord_bot as discord
import orchestrator_github
from state.task import TaskState

LOG = config.getLogger("orchestrator")


class OrchestratorReviewMixin:
    """Handles adversary review routing, Gemini session lifecycle, git helpers, and the PR gate."""

    # ===================================================================
    # Dual-brain second opinion -- dispatcher, cost guard, session lifecycle
    # ===================================================================
    def _adversaryReview(self, subtask_title: str, trigger_reason: str, executor_output: str, *,
                         ollama_chat=None, goal: str = "", review_type: str = "subtask",
                         worth=None) -> dict:
        """Default reviewer: route through second_brain (Gemini -> Ollama -> stub), apply the cost
        guard, disable a dead Gemini session for the rest of the run, and record trust telemetry.
        Signature matches the legacy ``adversary.review`` so every existing call site is unchanged."""
        if worth is None:
            worth = self._worthGptReview(executor_output) if review_type == "subtask" else True
        rv = second_brain.consult(
            review_type, title=subtask_title, trigger_reason=trigger_reason,
            content=executor_output, goal=goal,
            ollama_chat=ollama_chat or self._ollamaChat,
            browser_ask=self._gemini_ask, session_ok=self._gemini_session_ok, worth=worth)
        if rv.get("session_dead") and self._gemini_session_ok:
            self._gemini_session_ok = False
            try:
                discord.sendEmbed(discord.noticeEmbed(
                    "Gemini second brain unreachable (auth / safety block / rate-limit) — "
                    "using the Ollama brain for the rest of this run."))
            except Exception:  # noqa: BLE001
                pass
        elif self._gemini_session_ok and worth and rv.get("tier") != "gpt":
            # SOFT-fail: Gemini was attempted (worth + session live) but the verdict came from
            # Ollama/stub with no hard session_dead -- a silent degradation. After a few consecutive
            # soft-fails, stop re-paying the Gemini round-trip for the run (mirrors session_dead).
            self._gpt_soft_fails = getattr(self, "_gpt_soft_fails", 0) + 1
            if self._gpt_soft_fails >= 3:
                self._gemini_session_ok = False
                LOG.warning("Gemini second brain soft-failed %d consecutive reviews; disabling for run",
                            self._gpt_soft_fails)
                try:
                    discord.sendEmbed(discord.noticeEmbed(
                        "Gemini second brain repeatedly unusable — Ollama for the rest of this run."))
                except Exception:  # noqa: BLE001
                    pass
        elif rv.get("tier") == "gpt":
            self._gpt_soft_fails = 0   # a real Gemini verdict resets the soft-fail streak
        try:
            adversary_trust.record(review_type, rv, tier=rv.get("tier"))
        except Exception:  # noqa: BLE001 -- telemetry never affects the run
            pass
        return rv

    def _openGeminiSession(self, state: TaskState, dashboard=None) -> None:
        """Run-start: health-probe Gemini and start ONE run conversation. On any failure, Gemini
        stays disabled and the run uses the Ollama brain -- announced once, never fatal."""
        if not config.GEMINI_ENABLED:
            return
        try:
            from agents import browser_executor
            # The Gemini transport is stateless thread-safe HTTPS, so it can be consulted directly
            # from the parallel pool workers later -- no dedicated session thread is needed.
            if not browser_executor.probe():
                discord.sendEmbed(discord.noticeEmbed(
                    "Gemini second brain unavailable (health probe failed) — Ollama for this run."))
                return
            self._gemini_session = browser_executor
            browser_executor.startConversation(self._goalText(state), state.task_id)
            self._gemini_ask = lambda message: browser_executor.sessionAsk(message, expect_json=True)
            self._gemini_session_ok = True
            LOG.info("Gemini second brain online for task %s", state.task_id)
            discord.sendEmbed(discord.noticeEmbed(
                f"🧠 Gemini second brain online ({config.GEMINI_MODEL})."))
        except Exception as e:  # noqa: BLE001 -- never block a run on the second brain
            LOG.warning("could not start Gemini session (%s); Ollama only", e)
            self._gemini_session_ok = False
            try:
                from agents import browser_executor as _be
                _be.closeSession()
            except Exception:  # noqa: BLE001
                pass
            self._gemini_session = None
            self._gemini_ask = None

    def _closeGeminiSession(self) -> None:
        try:
            if self._gemini_session is not None:
                self._gemini_session.closeSession()
        except Exception:  # noqa: BLE001
            pass
        self._gemini_session = None
        self._gemini_session_ok = False
        self._gemini_ask = None

    # ===================================================================
    # Adversary teeth -- shared tree guard, git helpers, pre-PR hold
    # ===================================================================
    def _remediationTreeShared(self, exec_cwd: str = "") -> bool:
        """True when >1 subtask runs concurrently against the SHARED real edit tree -- the case where
        the remediation snapshot + whole-tree `git checkout <sha> -- .` would revert a peer worker's
        edits (silent data loss). The real edit tree is ALWAYS work_dir: non-self-ref subtasks run
        directly in it, and self-ref subtasks edit it (== PROJECT_ROOT) via --add-dir even though their
        cwd is an isolated .sc-ctx scratch. So ANY parallel run (self-ref OR not) shares the real tree;
        only a sequential run (parallelism<=1) has no peers and can safely snapshot/revert it."""
        return getattr(self, "_parallelism", 1) > 1

    @staticmethod
    def _gitSnapshot(cwd: str) -> "str | None":
        return orchestrator_github._gitSnapshot(cwd)

    @staticmethod
    def _gitRestore(cwd: str, sha: "str | None") -> None:
        return orchestrator_github._gitRestore(cwd, sha)

    def _gitDiffForReview(self, work_dir: "str | None") -> str:
        return orchestrator_github._gitDiffForReview(work_dir)

    def _prePrAdversary(self, state: TaskState, work_dir: "str | None" = None) -> dict:
        """Pre-PR safety review: the second brain judges the whole change before a PR is opened --
        from the REAL git diff when available, else a subtask-status summary. Best-effort: any
        failure approves (the reviewer must never block a run by erroring). Returns the verdict dict."""
        try:
            _t, reason = adversary.shouldTrigger("", 0, pre_pr=True)
            diff = self._gitDiffForReview(work_dir)
            if diff:
                review_type, content = "pre_pr_diff", diff
            else:
                review_type = "pre_pr_diff"
                content = "\n".join(
                    f"- {s['subtask_id']} [{s['status']}] {s['title']}"
                    + (" (verify PASS)" if (s.get('verify_result') or {}).get('passed') else "")
                    for s in state.subtasks if s["status"] != "removed") or "(no subtasks)"
            rv = self._consult(state, review_type, "Pre-PR safety review", reason, content)
            with self._state_lock:
                state.addAdversaryReview("pre_pr", reason, rv["verdict"], None, stub=rv.get("stub", False))
            discord.sendEmbed(discord.adversaryTriggeredEmbed("Pre-PR review", reason, rv.get("verdict")))
            cast.speak("adversary", f"⚔️ Pre-PR review → **{discord.formatVerdict(rv.get('verdict'))}**. "
                       f"Trigger: {reason}")
            cast.duel("Pre-PR review", rv.get("verdict"))   # VS-card on a CHALLENGE (T8)
            return rv
        except Exception as e:  # noqa: BLE001 -- never block a run on the reviewer itself
            LOG.warning("pre-PR adversary review failed (%s); approving", e)
            return {"verdict": "approved", "concerns": [], "stub": True}

    def _runIsDegraded(self, state: TaskState) -> bool:
        return orchestrator_github._runIsDegraded(state)

    def _prGate(self, review: dict, auto_pr: bool, state: TaskState) -> "tuple[bool, str]":
        """Decide whether to create the PR. Returns (create, skip_reason)."""
        if not auto_pr:
            return False, "--no-pr"
        # FX-18: a DEGRADED run (most subtasks failed, or core changes reverted) must NEVER open a PR,
        # INDEPENDENT of the adversary verdict. The brain frequently auto-approves/stubs (empty
        # completions), so gating the degraded check behind a 'challenged' verdict made it dead code.
        if self._runIsDegraded(state):
            return False, "degraded run (majority failed / core reverted) — PR held for review"
        if config.ADVERSARY_PR_HOLD_ENABLED and second_brain.is_blocking(review):
            # Night mode normally suppresses an advisory challenge hold (hands-off); the degraded
            # check above already covers the must-never-ship cases regardless of night mode.
            if not config.NIGHT_MODE:
                concerns = "; ".join(review.get("must_fix") or review.get("concerns") or ["challenged"])
                return False, f"adversary HOLD: {concerns}"[:300]
        return True, ""

    def _prePrSuiteGate(self, state: TaskState, work_dir: str) -> "tuple[bool, str]":
        return orchestrator_github._prePrSuiteGate(state, work_dir)

    # ===================================================================
    # Phase 4 -- PR creation (best effort; skips gracefully)
    # ===================================================================
    def createPullRequest(self, state: TaskState, work_dir: str) -> dict:
        return orchestrator_github.createPullRequest(state, work_dir)
