"""Compact, dependency-aware navigation projection and context packets for LLM agents.

The full .repo-map.json remains the compatibility manifest. This module derives a
small projection and retrieves only the direct symbols plus a bounded dependency neighborhood.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  build_projection(repo_map: dict) -> dict  -- Return the stable compact subset required for navigation and context selection.
  build_context_packet(projection: dict, query: str, *, budget_chars: int=12000) -> dict  -- Retrieve direct matches then bounded graph neighbors without dropping direct hits.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/platform/test_llm_navigation.py
"""
from __future__ import annotations

from collections import deque


def build_projection(repo_map: dict) -> dict:
    """Return the stable compact subset required for navigation and context selection."""
    modules = {}
    for dotted, rec in (repo_map.get("modules") or {}).items():
        modules[dotted] = {
            "path": rec.get("path", ""), "purpose": rec.get("purpose", ""),
            "exports": [e.get("name", "") for e in rec.get("exports", ())],
            "depends_on": list(rec.get("depends_on", ())), "callers": list(rec.get("callers", ())),
            "test": list(rec.get("test", ())),
        }
    return {"schema": 1, "generated_from": ".repo-map.json", "modules": modules}


def _score(dotted: str, rec: dict, terms: set[str]) -> int:
    haystack = " ".join([dotted, rec.get("path", ""), rec.get("purpose", ""), *rec.get("exports", ())]).lower()
    return sum(1 for term in terms if term and term in haystack)


def build_context_packet(projection: dict, query: str, *, budget_chars: int = 12000) -> dict:
    """Retrieve direct matches then bounded graph neighbors without dropping direct hits."""
    modules = projection.get("modules") or {}
    terms = {part.lower() for part in query.replace("/", " ").replace(".", " ").split() if len(part) > 2}
    direct = sorted((name for name, rec in modules.items() if _score(name, rec, terms)),
                    key=lambda name: (-_score(name, modules[name], terms), name))
    selected = list(direct)
    queue = deque(direct)
    while queue and len(selected) < 12:
        current = queue.popleft()
        for neighbor in [*modules[current].get("depends_on", ()), *modules[current].get("callers", ())]:
            if neighbor in modules and neighbor not in selected:
                selected.append(neighbor)
                queue.append(neighbor)
                if len(selected) >= 12:
                    break
    records = []
    used = 0
    truncated = False
    for name in selected:
        rec = {"module": name, **modules[name]}
        cost = len(str(rec))
        if name not in direct and used + cost > budget_chars:
            truncated = True
            continue
        records.append(rec)
        used += cost
    return {"schema": 1, "query": query, "modules": records, "direct_modules": direct,
            "context_chars": used, "budget_chars": budget_chars,
            "truncated": truncated or used > budget_chars,
            "over_budget_direct_context": used > budget_chars}
