"""dev -- the one-command developer/agent task runner for 9to5 (cross-platform, no `make`).

Canonical agent commands. Main loop: ``python tools/dev.py check <file>`` runs
ruff -> typecheck(changed) -> mapped tests -> repo-map drift, failing fast.

Subcommands:
  map [args]            regenerate the AI-navigation layer
  check [files] [--json] ruff + typecheck + affected tests + repo-map drift
  test [pytest-args]    run tests (default: full suite)
  fast                  run the fast lane: pytest -m "not slow"
  ci-local              local CI gate: repo-map, workflows, affected tests, fast fallback
  slow-report           run slow lane with heartbeat + durations; write logs/slow-test-report.md
  heartbeat-test        prove pytest heartbeat output with an explicit slow fixture
  context-check         validate Claude-facing context budgets
  iteration-health      summarize recent iteration metrics and next validation hints
  bench-iteration       run/list the iteration benchmark suite
  size-audit            bucket tracked Python files and functions by line count
  affected              print pytest targets for `git diff` (delegates to affected_tests.py)
  watch [files]         re-run affected tests on .py changes
  outline <file>        signatures + docstring-first-lines + anchors only
  where <symbol>        definition file:line + module-level callers (from .repo-map.json)
  run [args]            python main.py [args]
  dryrun                python main.py --dry-run (offline pipeline smoke)
  e2e                   python main.py --e2e

Check/lint/type/test/watch implementations live in dev_checks.py.
Reporting/navigation implementations live in dev_reports.py.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  cmd_bench_iteration(args: list[str]) -> int
  cmd_size_audit(args: list[str]) -> int
  cmd_affected(args: list[str]) -> int
  cmd_map(args: list[str]) -> int
  cmd_run(args: list[str]) -> int
  cmd_dryrun(args: list[str]) -> int
  cmd_e2e(args: list[str]) -> int
  cmd_codemod(args: list[str]) -> int
  main(argv: list[str]) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_dev_commands.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import affected_tests  # noqa: E402
import iteration_bench  # noqa: E402
import repo_map  # noqa: E402
import size_audit  # noqa: E402

from dev_checks import (  # noqa: E402
    REPO_ROOT, PY, _run,
    _progress_env,  # re-exported for backward compat (test_dev_commands.py)
    cmd_lint, cmd_typecheck, cmd_check, cmd_test, cmd_fast, cmd_ci_local,
)
from dev_reports import (  # noqa: E402
    _run_tee,  # re-exported for backward compat (test_dev_commands.py)
    cmd_slow_report, cmd_heartbeat_test, cmd_context_check,
    cmd_iteration_health, cmd_outline, cmd_where, cmd_watch,
)


# ==== PASSTHROUGHS ====
def cmd_bench_iteration(args: list[str]) -> int:
    return iteration_bench.main(args)


def cmd_size_audit(args: list[str]) -> int:
    return size_audit.main(args)


def cmd_affected(args: list[str]) -> int:
    return affected_tests.main(args)


def cmd_map(args: list[str]) -> int:
    return repo_map.main(args)


def cmd_run(args: list[str]) -> int:
    return _run([PY, str(REPO_ROOT / "main.py"), *args]).returncode


def cmd_dryrun(args: list[str]) -> int:
    return _run([PY, str(REPO_ROOT / "main.py"), "--dry-run", "--goal",
                 "dev smoke build a thing", "--hours", "1", "--no-web", *args]).returncode


def cmd_e2e(args: list[str]) -> int:
    return _run([PY, str(REPO_ROOT / "main.py"), "--e2e", *args]).returncode


def cmd_codemod(args: list[str]) -> int:
    return _run([PY, str(REPO_ROOT / "tools" / "codemod.py"), *args]).returncode


# ==== CLI ====
COMMANDS = {
    "map": cmd_map, "check": cmd_check, "test": cmd_test, "fast": cmd_fast,
    "ci-local": cmd_ci_local, "slow-report": cmd_slow_report,
    "heartbeat-test": cmd_heartbeat_test, "context-check": cmd_context_check,
    "iteration-health": cmd_iteration_health, "bench-iteration": cmd_bench_iteration,
    "size-audit": cmd_size_audit,
    "affected": cmd_affected, "watch": cmd_watch,
    "outline": cmd_outline, "where": cmd_where, "lint": cmd_lint, "typecheck": cmd_typecheck,
    "run": cmd_run, "dryrun": cmd_dryrun, "e2e": cmd_e2e, "codemod": cmd_codemod,
}


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help", "help"):
        print(__doc__)
        return 0
    cmd, rest = argv[0], argv[1:]
    fn = COMMANDS.get(cmd)
    if fn is None:
        print(f"[dev] unknown command '{cmd}'. Try: {', '.join(COMMANDS)}", file=sys.stderr)
        return 2
    return fn(rest)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
