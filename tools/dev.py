"""dev -- the one-command developer/agent task runner for 9to5 (cross-platform, no `make`).

Canonical invocations so an agent never re-derives a command. The headline is the fast inner
loop: ``python tools/dev.py check <file>`` runs gates cheapest->slowest and FAILS FAST --
ruff -> typecheck(changed) -> only the mapped tests -> repo-map drift -- usually in seconds.

Subcommands:
  map [args]            regenerate the AI-navigation layer (delegates to tools/repo_map.py)
  check [files] [--json] ruff + typecheck + affected tests + repo-map drift, fail-fast
  test [pytest-args]    run tests (default: full suite)
  fast                  run the fast lane: pytest -m "not slow"
  affected              print pytest targets for `git diff` (delegates to affected_tests.py)
  watch [files]         re-run affected tests whenever a .py file changes (Ctrl-C to stop)
  outline <file>        signatures + docstring-first-lines + anchors only (grok a big file cheap)
  where <symbol>        definition file:line + module-level callers (from .repo-map.json)
  lint [files]          ruff check
  typecheck [files]     mypy (lenient, ignore-missing-imports)
  run [args]            python main.py [args]
  dryrun                python main.py --dry-run (offline pipeline smoke)
  e2e                   python main.py --e2e
  codemod [args]        delegate to tools/codemod.py

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  cmd_lint(args: list[str]) -> int
  cmd_typecheck(args: list[str]) -> int
  cmd_check(args: list[str]) -> int  -- Fail-fast gate chain: ruff -> typecheck(changed) -> affected tests -> repo-map drift.
  cmd_test(args: list[str]) -> int
  cmd_fast(args: list[str]) -> int
  cmd_affected(args: list[str]) -> int
  cmd_watch(args: list[str]) -> int  -- Poll .py mtimes; on any change, run the affected tests
  cmd_outline(args: list[str]) -> int
  cmd_where(args: list[str]) -> int
  cmd_map(args: list[str]) -> int
  cmd_run(args: list[str]) -> int
  cmd_dryrun(args: list[str]) -> int
  cmd_e2e(args: list[str]) -> int
  cmd_codemod(args: list[str]) -> int
  main(argv: list[str]) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

# ==== IMPORTS ====
import ast
import json
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import affected_tests  # noqa: E402
import repo_map  # noqa: E402

# ==== CONSTANTS ====
REPO_ROOT = repo_map.REPO_ROOT
PY = sys.executable
HEADER_SENTINEL = repo_map.HEADER_SENTINEL
# follow-imports=skip scopes mypy to the NAMED files only -> the gate answers "did my edit break
# THIS file", not "is the whole 37k-LOC repo mypy-clean" (it isn't yet -- baseline is advisory).
MYPY_FLAGS = ["--ignore-missing-imports", "--follow-imports=skip", "--no-error-summary"]


# ==== TOOL RESOLUTION ====
def _ruff() -> list[str]:
    exe = Path(PY).with_name("ruff.exe")
    if not exe.exists():
        exe = Path(PY).with_name("ruff")
    return [str(exe)] if exe.exists() else [PY, "-m", "ruff"]


def _run(cmd: list[str], capture: bool = False) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=REPO_ROOT, text=True,
                          capture_output=capture)


# ==== GATES ====
def _py_files(args: list[str]) -> list[str]:
    files = [a for a in args if not a.startswith("-") and a.endswith(".py")]
    return files or affected_tests._git_changed()


def cmd_lint(args: list[str]) -> int:
    files = [a for a in args if a.endswith(".py")] or ["."]
    return _run([*_ruff(), "check", *files]).returncode


def cmd_typecheck(args: list[str]) -> int:
    files = _py_files(args)
    if not files:
        print("[dev] typecheck: no changed .py files")
        return 0
    return _run([PY, "-m", "mypy", *MYPY_FLAGS, *files]).returncode


def cmd_check(args: list[str]) -> int:
    """Fail-fast gate chain: ruff -> typecheck(changed) -> affected tests -> repo-map drift."""
    as_json = "--json" in args
    files = _py_files([a for a in args if a != "--json"])
    results: list[dict] = []

    def gate(name: str, cmd: list[str], fix: str) -> bool:
        cp = _run(cmd, capture=as_json)
        ok = cp.returncode == 0
        if as_json:
            out = ((cp.stdout or "") + (cp.stderr or "")).strip().splitlines()
            results.append({"gate": name, "ok": ok, "returncode": cp.returncode,
                            "head": out[:25], "fix_hint": fix if not ok else ""})
        else:
            print(f"[dev] {name}: {'ok' if ok else 'FAIL'}")
        return ok

    chain_ok = True
    if files:
        chain_ok = gate("ruff", [*_ruff(), "check", *[f for f in files]], "fix lint, or adjust ruff config")
        if chain_ok:
            chain_ok = gate("typecheck", [PY, "-m", "mypy", *MYPY_FLAGS, *files],
                            "fix type errors on changed files")
    if chain_ok:
        targets = affected_tests.targets_for(files) if files else []
        if targets:
            chain_ok = gate("tests", [PY, "-m", "pytest", "-q", *targets], "fix failing affected tests")
        elif not as_json:
            print("[dev] tests: (no mapped tests for changed files)")
    if chain_ok:
        chain_ok = gate("repo-map", [PY, str(REPO_ROOT / "tools" / "repo_map.py"), "--check"],
                        "run: python tools/repo_map.py")

    if as_json:
        print(json.dumps({"ok": chain_ok, "files": files, "gates": results}, indent=2))
    else:
        print(f"[dev] check: {'PASS' if chain_ok else 'FAIL'} ({len(files)} file(s))")
    return 0 if chain_ok else 1


def _xdist(args: list[str]) -> list[str]:
    """Add `-n auto` (parallel across cores) unless the caller already chose a worker count."""
    return args if any(a == "-n" or a.startswith("-n") for a in args) else ["-n", "auto", *args]


def cmd_test(args: list[str]) -> int:
    return _run([PY, "-m", "pytest", *_xdist(args or ["-q"])]).returncode


def cmd_fast(args: list[str]) -> int:
    return _run([PY, "-m", "pytest", *_xdist(["-m", "not slow", "-q", *args])]).returncode


def cmd_affected(args: list[str]) -> int:
    return affected_tests.main(args)


def cmd_watch(args: list[str]) -> int:
    """Poll .py mtimes; on any change, run the affected tests. Ctrl-C to stop."""
    watch = [a for a in args if a.endswith(".py")]
    print(f"[dev] watching {'given files' if watch else 'the repo'} -- Ctrl-C to stop")

    def snapshot() -> dict[str, float]:
        files = [REPO_ROOT / w for w in watch] if watch else repo_map.iter_py_files()
        snap = {}
        for f in files:
            try:
                snap[str(f)] = Path(f).stat().st_mtime
            except OSError:
                pass
        return snap

    last = snapshot()
    try:
        while True:
            time.sleep(1.0)
            cur = snapshot()
            changed = [f for f, mt in cur.items() if last.get(f) != mt]
            if changed:
                rel = [str(Path(f).relative_to(REPO_ROOT)) for f in changed]
                print(f"\n[dev] changed: {', '.join(rel)}")
                targets = affected_tests.targets_for(rel)
                if targets:
                    _run([PY, "-m", "pytest", "-q", *targets])
                else:
                    print("[dev] (no mapped tests)")
                last = cur
    except KeyboardInterrupt:
        print("\n[dev] watch stopped")
        return 0


# ==== NAVIGATION ====
def cmd_outline(args: list[str]) -> int:
    if not args:
        print("usage: dev.py outline <file>", file=sys.stderr)
        return 2
    path = Path(args[0])
    if not path.is_absolute():
        path = REPO_ROOT / args[0]
    src = repo_map._read_source(path)
    tree = ast.parse(src)
    doc = (ast.get_docstring(tree) or "").split(HEADER_SENTINEL, 1)[0].strip().split("\n", 1)[0]
    print(f"# {path.relative_to(REPO_ROOT) if str(path).startswith(str(REPO_ROOT)) else path}")
    if doc:
        print(f'"""{doc}"""')
    for i, line in enumerate(src.splitlines(), 1):
        if line.startswith("# ===="):
            print(f"\n{line.strip()}")
    print()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            print(f"{node.lineno}: def {node.name}{repo_map._signature(node)}")
        elif isinstance(node, ast.ClassDef):
            print(f"{node.lineno}: class {node.name}")
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    print(f"  {sub.lineno}:   def {sub.name}{repo_map._signature(sub)}")
    return 0


def cmd_where(args: list[str]) -> int:
    if not args:
        print("usage: dev.py where <symbol>", file=sys.stderr)
        return 2
    sym = args[0]
    jpath = REPO_ROOT / ".repo-map.json"
    if not jpath.exists():
        print("[dev] .repo-map.json missing -- run: python tools/dev.py map", file=sys.stderr)
        return 1
    m = json.loads(jpath.read_text(encoding="utf-8"))
    hits = []
    for dotted, rec in m["modules"].items():
        for e in rec["exports"]:
            if e["name"] == sym:
                hits.append((dotted, rec, e))
    if not hits:
        print(f"[dev] no exported symbol named '{sym}' in the map "
              f"(it may be a private/_-prefixed name).")
        return 1
    for dotted, rec, e in hits:
        print(f"{rec['path']}:{e['lineno']}  {e['kind']} {e['name']}{e['signature']}")
        if e["summary"]:
            print(f"    {e['summary']}")
        callers = rec.get("callers", [])
        print(f"    callers ({len(callers)}): {', '.join(callers) or '(none)'}")
    return 0


# ==== PASSTHROUGHS ====
def cmd_map(args: list[str]) -> int:
    return repo_map.main(args)


def cmd_run(args: list[str]) -> int:
    return _run([PY, str(REPO_ROOT / "main.py"), *args]).returncode


def cmd_dryrun(args: list[str]) -> int:
    return _run([PY, str(REPO_ROOT / "main.py"), "--dry-run", "--goal",
                 "dev smoke build a thing", "--hours", "1", "--no-web", *args]).returncode


def cmd_e2e(args: list[str]) -> int:
    return _run([PY, str(REPO_ROOT / "main.py"), "--e2e", *args]).returncode


def cmd_codemod(args: list[str]) -> int:
    return _run([PY, str(REPO_ROOT / "tools" / "codemod.py"), *args]).returncode


# ==== CLI ====
COMMANDS = {
    "map": cmd_map, "check": cmd_check, "test": cmd_test, "fast": cmd_fast,
    "affected": cmd_affected, "watch": cmd_watch, "outline": cmd_outline, "where": cmd_where,
    "lint": cmd_lint, "typecheck": cmd_typecheck, "run": cmd_run, "dryrun": cmd_dryrun,
    "e2e": cmd_e2e, "codemod": cmd_codemod,
}


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help", "help"):
        print(__doc__)
        return 0
    cmd, rest = argv[0], argv[1:]
    fn = COMMANDS.get(cmd)
    if fn is None:
        print(f"[dev] unknown command '{cmd}'. Try: {', '.join(COMMANDS)}", file=sys.stderr)
        return 2
    return fn(rest)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
