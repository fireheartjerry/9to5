"""codemod -- AST/libcst-based mechanical edits across the repo (formatting-preserving).

For reliable structural changes an agent would otherwise do by hand across many files (rename a
symbol, find every usage). DRY-RUN by default: prints what would change; pass --apply to write.
Powers the Phase-3 splits and the Phase-2 scale.

Usage:
  python tools/codemod.py usages <symbol>              # every Name/Attribute usage (file:line)
  python tools/codemod.py rename <old> <new> [--apply] # rename a symbol repo-wide

CAVEAT: `rename` is name-based, NOT scope-aware -- it renames every `<old>` identifier (and
`.<old>` attribute) it sees. Review the dry-run before --apply; avoid for very common names.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  cmd_usages(symbol: str, only: str | None=None) -> int  -- Print file:line for every Name/Attribute reference to ``symbol``.
  cmd_rename(old: str, new: str, apply: bool, only: str | None=None) -> int  -- Rename ``old`` -> ``new`` (Name + .attr) across files
  main(argv: list[str]) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import repo_map  # noqa: E402

REPO_ROOT = repo_map.REPO_ROOT

try:
    import libcst as cst
except Exception:  # noqa: BLE001
    cst = None


def _iter_files(only: str | None) -> list[Path]:
    return repo_map.iter_py_files(only)


def cmd_usages(symbol: str, only: str | None = None) -> int:
    """Print file:line for every Name/Attribute reference to ``symbol``."""
    import ast
    n = 0
    for path in _iter_files(only):
        try:
            tree = ast.parse(repo_map._read_source(path))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            hit = (isinstance(node, ast.Name) and node.id == symbol) or \
                  (isinstance(node, ast.Attribute) and node.attr == symbol)
            if hit:
                print(f"{path.relative_to(REPO_ROOT).as_posix()}:{getattr(node, 'lineno', '?')}")
                n += 1
    print(f"[codemod] {n} usage(s) of '{symbol}'", file=sys.stderr)
    return 0


def cmd_rename(old: str, new: str, apply: bool, only: str | None = None) -> int:
    """Rename ``old`` -> ``new`` (Name + .attr) across files. Dry-run unless ``apply``."""
    if cst is None:
        print("[codemod] libcst not installed: pip install libcst", file=sys.stderr)
        return 1

    class _Rename(cst.CSTTransformer):
        def __init__(self) -> None:
            self.count = 0

        def leave_Name(self, on, un):  # noqa: N802 (libcst API)
            if un.value == old:
                self.count += 1
                return un.with_changes(value=new)
            return un

        def leave_Attribute(self, on, un):  # noqa: N802
            if isinstance(un.attr, cst.Name) and un.attr.value == old:
                self.count += 1
                return un.with_changes(attr=un.attr.with_changes(value=new))
            return un

    changed = 0
    for path in _iter_files(only):
        src = repo_map._read_source(path)
        if old not in src:
            continue
        try:
            mod = cst.parse_module(src)
        except Exception:  # noqa: BLE001
            continue
        tr = _Rename()
        new_mod = mod.visit(tr)
        if tr.count:
            changed += 1
            rel = path.relative_to(REPO_ROOT).as_posix()
            print(f"{'apply' if apply else 'would change'}: {rel} ({tr.count} occurrence(s))")
            if apply:
                path.write_text(new_mod.code, encoding="utf-8", newline="\n")
    print(f"[codemod] rename '{old}'->'{new}': {changed} file(s) "
          f"{'changed' if apply else '(dry-run; pass --apply to write)'}", file=sys.stderr)
    return 0


def main(argv: list[str]) -> int:
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    only = None
    if "--only" in argv:
        i = argv.index("--only")
        only = argv[i + 1]
        argv = argv[:i] + argv[i + 2:]
    cmd = argv[0]
    if cmd == "usages" and len(argv) >= 2:
        return cmd_usages(argv[1], only)
    if cmd == "rename" and len(argv) >= 3:
        return cmd_rename(argv[1], argv[2], apply="--apply" in argv, only=only)
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
