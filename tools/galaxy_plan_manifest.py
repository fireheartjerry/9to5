"""Emit deterministic file manifests from approved implementation-plan tasks.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  PlanManifestError  -- The plan cannot produce an exact file selection.
  FileRow
  parse_plan(text: str, *, through: int | None=None) -> dict[int, tuple[FileRow, ...]]  -- Parse exact ``**Files**`` blocks from task headings.
  select_paths(tasks: dict[int, tuple[FileRow, ...]], requested: Sequence[int], kind: str) -> tuple[str, ...]
  main(argv: Iterable[str] | None=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/platform/test_galaxy_plan_manifest.py
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
import re
import sys
from typing import Iterable, Sequence


_TASK_HEADING = re.compile(r"^##\s+(?:\d+\.\s+)?Task\s+(\d+)\b(?:\s+[-—].*)?\s*$")
_FILE_ROW = re.compile(
    r"^-\s+(Add|Create|Modify|Test):\s+`([^`]+)`(?:\s+[^`]+)?\s*$"
)
_ACTIONS = frozenset({"Add", "Create", "Modify", "Test"})
_KINDS = (
    "all",
    "required-changes",
    "red-tests",
    "tests",
    "python",
    "production-python",
)


class PlanManifestError(ValueError):
    """The plan cannot produce an exact file selection."""


@dataclass(frozen=True)
class FileRow:
    action: str
    path: str


def _normalize_path(raw: str) -> str:
    if not raw or raw.strip() != raw or "\\" in raw or "\x00" in raw:
        raise PlanManifestError(f"malformed repository path: {raw!r}")
    path = PurePosixPath(raw)
    if path.is_absolute() or len(path.parts) == 0:
        raise PlanManifestError(f"absolute or empty path refused: {raw!r}")
    if any(part in {"", ".", ".."} for part in path.parts):
        raise PlanManifestError(f"path traversal or alias refused: {raw!r}")
    if ":" in path.parts[0] or raw.startswith("//"):
        raise PlanManifestError(f"absolute path refused: {raw!r}")
    normalized = path.as_posix()
    if normalized != raw:
        raise PlanManifestError(f"non-canonical repository path: {raw!r}")
    return normalized


def parse_plan(text: str, *, through: int | None = None) -> dict[int, tuple[FileRow, ...]]:
    """Parse exact ``**Files**`` blocks from task headings."""
    lines = text.splitlines()
    tasks: dict[int, tuple[FileRow, ...]] = {}
    index = 0
    while index < len(lines):
        match = _TASK_HEADING.fullmatch(lines[index])
        if match is None:
            index += 1
            continue
        task = int(match.group(1))
        if through is not None and task > through:
            index += 1
            continue
        if task in tasks:
            raise PlanManifestError(f"duplicate Task {task} heading")
        cursor = index + 1
        while cursor < len(lines) and not lines[cursor].strip():
            cursor += 1
        if cursor >= len(lines) or lines[cursor].strip() != "**Files**":
            raise PlanManifestError(f"Task {task} has no immediate **Files** block")
        cursor += 1
        rows: list[FileRow] = []
        seen: dict[str, str] = {}
        while cursor < len(lines):
            line = lines[cursor]
            if line.startswith("## ") or (line.startswith("**") and line.strip() != "**Files**"):
                break
            if not line.strip():
                cursor += 1
                continue
            row = _FILE_ROW.fullmatch(line)
            if row is None:
                # A new prose paragraph ends a non-empty list.  A bullet or
                # action-like row inside the list is always a hard error.
                if rows and not line.startswith("-"):
                    break
                raise PlanManifestError(f"Task {task} malformed file row: {line!r}")
            action, raw_path = row.groups()
            if action not in _ACTIONS:
                raise PlanManifestError(f"Task {task} unknown action: {action}")
            path = _normalize_path(raw_path)
            if path in seen:
                prior = seen[path]
                detail = "duplicate" if prior == action else "conflicting"
                raise PlanManifestError(
                    f"Task {task} {detail} rows for {path}: {prior}/{action}"
                )
            seen[path] = action
            rows.append(FileRow(action=action, path=path))
            cursor += 1
        if not rows:
            raise PlanManifestError(f"Task {task} **Files** block is empty")
        tasks[task] = tuple(rows)
        index = max(cursor, index + 1)
    if not tasks:
        raise PlanManifestError("plan contains no task **Files** blocks")
    return tasks


def _validate_action_history(tasks: dict[int, tuple[FileRow, ...]], through: int) -> None:
    known: dict[str, str] = {}
    for task in sorted(number for number in tasks if number <= through):
        for row in tasks[task]:
            prior = known.get(row.path)
            if row.action in {"Add", "Create"}:
                if prior is not None:
                    raise PlanManifestError(
                        f"Task {task} creates already-known path {row.path} ({prior})"
                    )
                known[row.path] = f"created by Task {task}"
            elif prior is None:
                known[row.path] = "documentation baseline"


def _matches(row: FileRow, kind: str) -> bool:
    is_test = row.path == "tests" or row.path.startswith("tests/")
    is_python = row.path.endswith(".py")
    if kind == "all":
        return True
    if kind == "required-changes":
        return row.action in {"Add", "Create", "Modify"}
    if kind == "red-tests":
        return is_test and row.action in {"Add", "Create"}
    if kind == "tests":
        return is_test
    if kind == "python":
        return is_python
    if kind == "production-python":
        return is_python and not is_test
    raise PlanManifestError(f"unsupported selection kind: {kind}")


def select_paths(
    tasks: dict[int, tuple[FileRow, ...]], requested: Sequence[int], kind: str
) -> tuple[str, ...]:
    if not requested:
        raise PlanManifestError("at least one exact task number is required")
    if any(number not in {1, 2, 3, 4} for number in requested):
        raise PlanManifestError("only implementation Tasks 1-4 may be selected")
    if len(set(requested)) != len(requested):
        raise PlanManifestError("duplicate requested task number")
    missing = [number for number in requested if number not in tasks]
    if missing:
        raise PlanManifestError(f"unknown task selection: {missing}")
    _validate_action_history(tasks, max(requested))
    emitted: list[str] = []
    seen: set[str] = set()
    for task in requested:
        for row in tasks[task]:
            if _matches(row, kind) and row.path not in seen:
                emitted.append(row.path)
                seen.add(row.path)
    if not emitted:
        raise PlanManifestError(f"empty selection for kind {kind}")
    return tuple(emitted)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan", type=Path, required=True)
    parser.add_argument("--task", type=int, action="append", required=True)
    parser.add_argument("--kind", choices=_KINDS, required=True)
    return parser


def main(argv: Iterable[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        raw = args.plan.read_bytes()
        if raw.startswith((b"\xff\xfe", b"\xfe\xff", b"\xef\xbb\xbf")):
            raise PlanManifestError("plan BOM is not canonical UTF-8")
        text = raw.decode("utf-8")
        if any(number not in {1, 2, 3, 4} for number in args.task):
            raise PlanManifestError("only implementation Tasks 1-4 may be selected")
        tasks = parse_plan(text, through=max(args.task))
        selected = select_paths(tasks, args.task, args.kind)
    except (OSError, UnicodeDecodeError, PlanManifestError) as exc:
        print(f"galaxy plan manifest refused: {exc}", file=sys.stderr)
        return 2
    for path in selected:
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
