"""Competitive-programming strategy selection for measured engineering bottlenecks.

"3000+" throughout this module means the Codeforces *rating* threshold: techniques
expected in Grandmaster-level competitive programming, not a count of algorithms.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  StrategyCard  -- One Codeforces 3000+ rating technique with an engineering applicability rule.
  recommend_strategies(query: dict, limit: int=3) -> list[StrategyCard]  -- Return deterministic cards matching a structured bottleneck query.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/platform/test_strategy_catalog.py
"""
from __future__ import annotations

from dataclasses import asdict, dataclass


@dataclass(frozen=True)
class StrategyCard:
    """One Codeforces 3000+ rating technique with an engineering applicability rule."""

    key: str
    family: str
    applies_to: tuple[str, ...]
    complexity: str
    invariant: str
    reject_when: str
    benchmark: str

    def to_dict(self) -> dict:
        return asdict(self)


CARDS = (
    StrategyCard("weighted-coverage", "optimization", ("test-selection", "coverage"),
                 "exact branch-and-bound O(2^n), deterministic greedy fallback", "mandatory tests remain selected",
                 "the direct mapped set already exceeds budget", "selected coverage and runtime"),
    StrategyCard("lpt-scheduling", "scheduling", ("ci-scheduling", "makespan"),
                 "O(n log n)", "each lane appears exactly once", "resource measurements are absent", "predicted versus actual makespan"),
    StrategyCard("scc-condensation", "graph", ("dependency-impact", "context-retrieval"),
                 "O(V + E)", "all nodes in an SCC share reachability", "the graph is incomplete or stale", "affected closure size"),
    StrategyCard("bm25-graph-expansion", "indexing", ("context-retrieval", "llm-navigation"),
                 "sparse scoring plus bounded BFS", "direct symbol/path hits are never dropped", "query has no stable target", "context size and task completion"),
    StrategyCard("aho-corasick", "strings", ("multi-pattern-scan", "log-analysis"),
                 "O(text + matches + patterns)", "all patterns are compiled before scan", "pattern count is tiny", "scan wall-clock time"),
)


def recommend_strategies(query: dict, limit: int = 3) -> list[StrategyCard]:
    """Return deterministic cards matching a structured bottleneck query.

    ``query[\"kind\"]`` is the primary signal; optional ``constraints`` terms add
    secondary matches. The function stays dependency-free so CI and manual agents share it.
    """
    terms = {str(query.get("kind", "")).strip().lower()}
    terms.update(str(x).strip().lower() for x in query.get("constraints", ()) if str(x).strip())
    ranked = [card for card in CARDS if terms.intersection(card.applies_to)]
    return sorted(ranked, key=lambda card: (card.family, card.key))[:max(0, limit)]
