"""Benchmark harness for validated Claude/agent iteration speed.

The default mode is intentionally dry-run/listing friendly. Real benchmark runs
record command runtime and return code without invoking Claude directly.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  main(argv: list[str] | None=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REPORT_DIR = REPO_ROOT / "logs" / "iteration_bench"

TASKS = [
    {
        "id": "test-selector",
        "description": "Map changed files to the cheapest useful pytest targets.",
        "command": [sys.executable, "tools/affected_tests.py", "tools/dev.py"],
    },
    {
        "id": "context-budget",
        "description": "Check Claude-facing context surfaces for budget drift.",
        "command": [sys.executable, "tools/context_budget.py"],
    },
    {
        "id": "workflow-validation",
        "description": "Validate GitHub workflow syntax and registry expectations.",
        "command": [sys.executable, "validate_workflows.py"],
    },
    {
        "id": "repo-map",
        "description": "Detect AI navigation index drift.",
        "command": [sys.executable, "tools/repo_map.py", "--check"],
    },
]


def _run_task(task: dict) -> dict:
    started = time.perf_counter()
    cp = subprocess.run(task["command"], cwd=REPO_ROOT, text=True,
                        capture_output=True)
    elapsed = time.perf_counter() - started
    return {
        "id": task["id"],
        "description": task["description"],
        "command": task["command"],
        "returncode": cp.returncode,
        "elapsed_seconds": round(elapsed, 3),
        "ok": cp.returncode == 0,
        "stdout_tail": (cp.stdout or "").splitlines()[-20:],
        "stderr_tail": (cp.stderr or "").splitlines()[-20:],
    }


def _write_reports(results: list[dict]) -> None:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y%m%d-%H%M%S")
    json_path = REPORT_DIR / f"{stamp}.json"
    md_path = REPORT_DIR / f"{stamp}.md"
    payload = {"generated": stamp, "ok": all(r["ok"] for r in results), "results": results}
    json_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    lines = ["# Iteration Benchmark", "", f"- Generated: `{stamp}`", ""]
    for row in results:
        state = "PASS" if row["ok"] else "FAIL"
        lines.append(f"- {state} `{row['id']}`: {row['elapsed_seconds']}s")
    md_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[bench] wrote {json_path.relative_to(REPO_ROOT)}")
    print(f"[bench] wrote {md_path.relative_to(REPO_ROOT)}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    if args.dry_run:
        payload = {"tasks": TASKS}
        if args.json:
            print(json.dumps(payload, indent=2))
        else:
            for task in TASKS:
                print(f"[bench] {task['id']}: {' '.join(task['command'])}")
        return 0
    results = [_run_task(task) for task in TASKS]
    _write_reports(results)
    return 0 if all(row["ok"] for row in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
