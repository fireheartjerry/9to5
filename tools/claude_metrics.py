"""Small JSONL telemetry helpers for Claude/agent iteration speed.

The helpers are intentionally dependency-free and best-effort. Hook callers must
never block Claude Code just because logging failed.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  git_state() -> dict[str, Any]
  append_jsonl(path: Path, entry: dict[str, Any]) -> None
  compact_payload(data: dict[str, Any]) -> dict[str, Any]
  record_hook_event(hook_name: str, data: dict[str, Any]) -> None
  record_executor_event(entry: dict[str, Any]) -> None
  read_recent(path: Path, limit: int=20) -> list[dict[str, Any]]
DEPENDS-ON: platform_core.execution
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/platform/test_iteration_telemetry.py
"""
from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path
from typing import Any

# This module is also imported by ``tools/claude_statusline.py`` when the
# process working directory is unrelated to the checkout.  Anchor the trusted
# local import universe to this file before importing platform boundaries.
REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from platform_core.execution.pre_execution import (
    mutateLegacyPath,
    openLegacyFile,
    readLegacyText,
)
from platform_core.execution.sandbox_broker import runLegacyProcess

METRICS_DIR = REPO_ROOT / "logs" / "claude_metrics"
TURN_LOG = METRICS_DIR / "turns.jsonl"
EXECUTOR_LOG = METRICS_DIR / "executor.jsonl"


def _git(args: list[str]) -> str:
    try:
        cp = runLegacyProcess(["git", *args], cwd=REPO_ROOT, text=True,
                              capture_output=True, timeout=2)
        return (cp.stdout or "").strip() if cp.returncode == 0 else ""
    except Exception:
        return ""


def git_state() -> dict[str, Any]:
    status = _git(["status", "--short"])
    return {
        "branch": _git(["branch", "--show-current"]) or "unknown",
        "dirty": bool(status),
        "changed_files": len([ln for ln in status.splitlines() if ln.strip()]),
    }


def append_jsonl(path: Path, entry: dict[str, Any]) -> None:
    mutateLegacyPath(path.parent.mkdir,parents=True, exist_ok=True)
    with openLegacyFile(path, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(entry, sort_keys=True, default=str) + "\n")


def compact_payload(data: dict[str, Any]) -> dict[str, Any]:
    tool_input = data.get("tool_input") if isinstance(data.get("tool_input"), dict) else {}
    prompt = data.get("prompt") or data.get("message") or ""
    if not isinstance(prompt, str):
        prompt = str(prompt)
    return {
        "hook_event": data.get("hook_event_name") or data.get("event") or data.get("type"),
        "session_id": data.get("session_id"),
        "transcript_path": data.get("transcript_path"),
        "cwd": data.get("cwd") or os.getcwd(),
        "model": data.get("model"),
        "tool_name": data.get("tool_name"),
        "tool_command_len": len(tool_input.get("command") or "") if tool_input else 0,
        "prompt_chars": len(prompt),
        "exit_status": data.get("exit_status"),
        "duration_ms": data.get("duration_ms") or data.get("elapsed_ms"),
    }


def record_hook_event(hook_name: str, data: dict[str, Any]) -> None:
    entry = {
        "time": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "source": "claude_hook",
        "hook": hook_name,
        **git_state(),
        **compact_payload(data),
    }
    append_jsonl(TURN_LOG, entry)


def record_executor_event(entry: dict[str, Any]) -> None:
    payload = {
        "time": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "source": "executor",
        **git_state(),
        **entry,
    }
    append_jsonl(EXECUTOR_LOG, payload)


def read_recent(path: Path, limit: int = 20) -> list[dict[str, Any]]:
    try:
        lines = readLegacyText(path, encoding="utf-8").splitlines()[-limit:]
    except OSError:
        return []
    out: list[dict[str, Any]] = []
    for line in lines:
        try:
            obj = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(obj, dict):
            out.append(obj)
    return out
