"""test_brain_reports -- markdown/JSON report rendering for tools/test_brain.py.

Given the data test_brain_selection.py computes (Selection, mapping audit, history
stats, shard plans), render the JSON/Markdown artifacts CI step summaries and cached
reports consume. No selection logic lives here -- pure "data in, report out."

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  write_quarantine(stats: dict[str, TestStat], path: Path | None=None) -> Path
  stat_record(stat: TestStat) -> dict
  history_report(stats: dict[str, TestStat], limit: int=20) -> dict
  history_markdown(data: dict) -> str
  write_history_report(stats: dict[str, TestStat], out_dir: Path, limit: int=20) -> tuple[Path, Path]
  mapping_markdown(data: dict) -> str
  write_mapping_report(data: dict, out_dir: Path) -> tuple[Path, Path]
  selection_report(selection: Selection) -> dict  -- Stable machine-readable report for CI summaries and cached artifacts.
  shard_report(shards: list[dict]) -> dict
  matrix_report(shards: list[dict]) -> dict  -- GitHub Actions matrix payload for duration-balanced shards.
  write_reports(selection: Selection, out_dir: Path, shards: list[dict] | None=None) -> tuple[Path, Path]
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: write_* functions write JSON/Markdown report files under the given out_dir
RUN/TEST: python -m pytest tests/platform/test_test_brain.py
"""

from __future__ import annotations

import json
from pathlib import Path
from time import time

from test_brain_selection import (
    MAX_QUARANTINE_FAILURE_RATE,
    MIN_FLAKE_RUNS,
    QUARANTINE_FILE,
    Selection,
    TestStat,
    flake_candidates,
    mapping_debt_priority_label,
    slowest_tests,
)


def write_quarantine(stats: dict[str, TestStat], path: Path | None = None) -> Path:
    qpath = path or QUARANTINE_FILE
    targets = [s.target for s in flake_candidates(stats)]
    qpath.parent.mkdir(parents=True, exist_ok=True)
    qpath.write_text(
        json.dumps(
            {
                "schema": 1,
                "generated_at": int(time()),
                "policy": {
                    "min_runs": MIN_FLAKE_RUNS,
                    "max_failure_rate": MAX_QUARANTINE_FAILURE_RATE,
                },
                "targets": targets,
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    return qpath


def stat_record(stat: TestStat) -> dict:
    return {
        "target": stat.target,
        "runs": stat.runs,
        "passes": stat.passes,
        "failures": stat.failures,
        "skips": stat.skips,
        "avg_duration": round(stat.avg_duration, 3),
        "max_duration": round(stat.max_duration, 3),
        "failure_rate": round(stat.failure_rate, 3),
    }


def history_report(stats: dict[str, TestStat], limit: int = 20) -> dict:
    slowest = slowest_tests(stats, limit)
    flakes = flake_candidates(stats)
    return {
        "schema": 1,
        "target_count": len(stats),
        "total_runs": sum(s.runs for s in stats.values()),
        "total_failures": sum(s.failures for s in stats.values()),
        "slowest": [stat_record(s) for s in slowest],
        "flake_candidates": [stat_record(s) for s in flakes[:limit]],
    }


def _bullet_list(items: list[str]) -> str:
    if not items:
        return "- none\n"
    return "".join(f"- `{item}`\n" for item in items)


def history_markdown(data: dict) -> str:
    lines = [
        "# Test Brain History",
        "",
        f"- Targets: `{data['target_count']}`",
        f"- Runs: `{data['total_runs']}`",
        f"- Failures: `{data['total_failures']}`",
        "",
        "## Slowest Targets",
        "",
    ]
    if not data["slowest"]:
        lines.append("- none")
    for row in data["slowest"]:
        lines.append(
            f"- `{row['target']}` avg `{row['avg_duration']}`s max `{row['max_duration']}`s "
            f"runs `{row['runs']}` failures `{row['failures']}`"
        )
    lines.extend(["", "## Flake Candidates", ""])
    if not data["flake_candidates"]:
        lines.append("- none")
    for row in data["flake_candidates"]:
        lines.append(
            f"- `{row['target']}` failure_rate `{row['failure_rate']}` "
            f"runs `{row['runs']}` failures `{row['failures']}`"
        )
    return "\n".join(lines) + "\n"


def write_history_report(stats: dict[str, TestStat], out_dir: Path, limit: int = 20) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    data = history_report(stats, limit)
    json_path = out_dir / "history.json"
    md_path = out_dir / "history.md"
    json_path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    md_path.write_text(history_markdown(data), encoding="utf-8")
    return json_path, md_path


def mapping_markdown(data: dict) -> str:
    lines = [
        "# Test Brain Mapping Audit",
        "",
        f"- Source files: `{data['total_files']}`",
        f"- Mapped files: `{data['mapped_files']}`",
        f"- Unmapped files: `{data['unmapped_files']}`",
        f"- Coverage: `{data['coverage']:.1%}`",
        "",
        "## Unmapped Files",
        "",
    ]
    if not data["unmapped"]:
        lines.append("- none")
    for priority in (0, 1, 2):
        rows = [row for row in data["unmapped"] if int(row.get("priority", 2)) == priority]
        if not rows:
            continue
        lines.extend(["", f"### {mapping_debt_priority_label(priority).title()}"])
        for row in rows[:100]:
            lines.append(f"- `{row['file']}`")
    if len(data["unmapped"]) > 100:
        lines.append(f"- ... {len(data['unmapped']) - 100} more")
    return "\n".join(lines) + "\n"


def write_mapping_report(data: dict, out_dir: Path) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "mapping.json"
    md_path = out_dir / "mapping.md"
    json_path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    md_path.write_text(mapping_markdown(data), encoding="utf-8")
    return json_path, md_path


def selection_report(selection: Selection) -> dict:
    """Stable machine-readable report for CI summaries and cached artifacts."""
    return {
        "schema": 1,
        "ok": selection.ok,
        "reason": selection.reason,
        "estimated_seconds": round(selection.estimated_seconds, 3),
        "changed_files": selection.changed_files,
        "targets": selection.targets,
        "direct_targets": selection.direct_targets,
        "sentinel_targets": selection.sentinel_targets,
        "recent_failure_targets": selection.recent_failure_targets,
        "quarantined_targets": selection.quarantined_targets,
        "explanations": selection.explanations,
    }


def shard_report(shards: list[dict]) -> dict:
    return {
        "schema": 1,
        "shard_count": len(shards),
        "total_targets": sum(len(s["targets"]) for s in shards),
        "max_estimated_seconds": max((float(s["estimated_seconds"]) for s in shards), default=0.0),
        "shards": shards,
    }


def matrix_report(shards: list[dict]) -> dict:
    """GitHub Actions matrix payload for duration-balanced shards."""
    include = []
    for shard in shards:
        targets = [str(t) for t in shard.get("targets", []) if str(t).strip()]
        include.append(
            {
                "shard": int(shard["index"]),
                "estimated_seconds": float(shard["estimated_seconds"]),
                "targets": " ".join(targets),
                "has_targets": bool(targets),
            }
        )
    return {"include": include}


def _shards_markdown(data: dict) -> str:
    lines = [
        "## Shard Plan",
        "",
        f"- Shards: `{data['shard_count']}`",
        f"- Targets: `{data['total_targets']}`",
        f"- Max estimated seconds: `{data['max_estimated_seconds']}`",
        "",
    ]
    for shard in data["shards"]:
        targets = " ".join(shard["targets"]) if shard["targets"] else "(empty)"
        lines.append(f"### Shard {shard['index']} (~{shard['estimated_seconds']}s)")
        lines.append("")
        lines.append(f"`python -m pytest {targets}`")
        lines.append("")
    return "\n".join(lines)


def _markdown_report(data: dict) -> str:
    text = (
        "# Test Brain Selection\n\n"
        f"- Status: `{'ok' if data['ok'] else 'fallback'}`\n"
        f"- Reason: `{data['reason']}`\n"
        f"- Estimated seconds: `{data['estimated_seconds']}`\n"
        f"- Targets: `{len(data['targets'])}`\n\n"
        "## Explanation\n\n"
        + _bullet_list([str(x) for x in data["explanations"]])
        + "\n## Changed Files\n\n"
        + _bullet_list([str(x) for x in data["changed_files"]])
        + "\n## Selected Targets\n\n"
        + _bullet_list([str(x) for x in data["targets"]])
        + "\n## Domain Sentinels\n\n"
        + _bullet_list([str(x) for x in data["sentinel_targets"]])
        + "\n## Recent Failures\n\n"
        + _bullet_list([str(x) for x in data["recent_failure_targets"]])
        + "\n## Quarantined Recent Failures\n\n"
        + _bullet_list([str(x) for x in data["quarantined_targets"]])
    )
    if "shard_plan" in data:
        text += "\n" + _shards_markdown(data["shard_plan"])
    return text


def write_reports(selection: Selection, out_dir: Path, shards: list[dict] | None = None) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    data = selection_report(selection)
    if shards is not None:
        data["shard_plan"] = shard_report(shards)
    json_path = out_dir / "selection.json"
    md_path = out_dir / "selection.md"
    json_path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    md_path.write_text(_markdown_report(data), encoding="utf-8")
    if shards is not None:
        (out_dir / "shards.json").write_text(
            json.dumps(shard_report(shards), indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        (out_dir / "shards.md").write_text(_shards_markdown(shard_report(shards)), encoding="utf-8")
    return json_path, md_path
