"""Exact and greedy budget optimization for optional Test Brain targets.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  optimize_optional_targets(required: list[str], optional: list[str], stats: dict, budget_seconds: float) -> list[str]
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/platform/test_test_brain.py
"""
from __future__ import annotations


def _duration(stats: dict, target: str) -> float:
    stat = stats.get(target)
    return float(getattr(stat, "avg_duration", 5.0))


def _value(stats: dict, target: str) -> float:
    stat = stats.get(target)
    return 1.0 + float(getattr(stat, "failure_rate", 0.0)) + (1.0 if getattr(stat, "recent_failure", False) else 0.0)


def optimize_optional_targets(required: list[str], optional: list[str], stats: dict,
                              budget_seconds: float) -> list[str]:
    """Select optional targets under budget with exact search, then greedy fallback.

    Required direct mappings and sentinels are intentionally outside the optimization: they
    remain mandatory even if the optional recommendation set must be empty.
    """
    required = sorted(set(required))
    left = budget_seconds - sum(_duration(stats, target) for target in required)
    if left < 0:
        return []
    weighted = [(target, _duration(stats, target), _value(stats, target))
                for target in sorted(set(optional) - set(required))]
    if len(weighted) <= 18:
        best: tuple[float, float, tuple[str, ...]] = (0.0, 0.0, ())
        for mask in range(1 << len(weighted)):
            cost = benefit = 0.0
            picked: list[str] = []
            for i, (target, duration, value) in enumerate(weighted):
                if mask & (1 << i):
                    cost += duration
                    if cost > left:
                        break
                    benefit += value
                    picked.append(target)
            else:
                if (benefit, -cost, tuple(picked)) > (best[0], -best[1], best[2]):
                    best = (benefit, cost, tuple(picked))
        return list(best[2])
    selected: list[str] = []
    used = 0.0
    for target, duration, value in sorted(weighted, key=lambda x: (-x[2] / max(x[1], 0.01), x[0])):
        if used + duration <= left:
            selected.append(target)
            used += duration
    return selected
