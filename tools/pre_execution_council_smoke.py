"""CLI smoke for the pre-execution council.

RUN/TEST: ENABLE_PRE_EXECUTION_COUNCIL=1 python tools/pre_execution_council_smoke.py --task "..."

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  main(argv: list[str] | None=None) -> int
DEPENDS-ON: agents.planning.pre_execution_council
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/planning/test_pre_execution_council.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from agents.planning.pre_execution_council import CouncilConfig, run_pre_execution_council


def _parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run the pre-execution council smoke.")
    parser.add_argument("--task", required=True, help="Task for the council to deliberate.")
    parser.add_argument("--messages-per-seat", type=int, default=12)
    parser.add_argument("--show-transcript", action="store_true")
    parser.add_argument("--output-dir", default="state/council_runs")
    parser.add_argument(
        "--selector-mode",
        action="store_true",
        help="Use explicit selector council conversation policy instead of round-robin.",
    )
    parser.add_argument("--selector-debate-rounds", type=int, default=1)
    parser.add_argument("--live-gpt-browser", action="store_true", help="Replace only the GPT seat with the live ChatGPT browser driver.")
    parser.add_argument("--gpt-project-url", default="", help="Project URL for --live-gpt-browser.")
    parser.add_argument("--gpt-model", default="", help="Model label for --live-gpt-browser.")
    parser.add_argument("--gpt-reasoning", default="", help="Reasoning label for --live-gpt-browser.")
    parser.add_argument("--live-gemini", action="store_true", help="Replace only the Gemini seat with live Gemini.")
    parser.add_argument("--live-local", action="store_true", help="Replace only the Local LLM seat with local Ollama-compatible HTTP.")
    parser.add_argument("--local-model", default="", help="Model name for --live-local; defaults to council/local brain config.")
    parser.add_argument("--live-groq", action="store_true", help="Replace only the Groq seat with live Groq API.")
    parser.add_argument("--groq-model", default="", help="Model name for --live-groq; defaults to qwen/qwen3-32b.")
    parser.add_argument(
        "--groq-fallback-models",
        default="",
        help="Comma-separated fallback models for --live-groq.",
    )
    parser.add_argument("--live-cloudflare", action="store_true", help="Add live Cloudflare Workers AI as an optional extra seat.")
    parser.add_argument(
        "--cloudflare-model",
        default="",
        help="Model name for --live-cloudflare; defaults to PRE_EXECUTION_COUNCIL_CLOUDFLARE_MODEL.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv or sys.argv[1:])
    env_cfg = CouncilConfig.from_config()
    live_groq = bool(args.live_groq or env_cfg.live_groq_enabled)
    live_cloudflare = bool(args.live_cloudflare or env_cfg.live_cloudflare_enabled)
    seat_count = 4 + int(live_groq) + int(live_cloudflare)
    cfg = CouncilConfig(
        enabled=True,
        prompt_version=env_cfg.prompt_version,
        messages_per_seat=max(1, args.messages_per_seat),
        total_target_messages=max(1, args.messages_per_seat) * seat_count,
        transcript_mode=env_cfg.transcript_mode,
        compact_protocol=env_cfg.compact_protocol,
        anti_filler=env_cfg.anti_filler,
        conversation_policy="selector" if args.selector_mode else env_cfg.conversation_policy,
        selector_debate_rounds=max(1, args.selector_debate_rounds),
        output_dir=args.output_dir,
        logging_enabled=True,
        mock_seats_enabled=True,
        live_gpt_enabled=bool(args.live_gpt_browser or env_cfg.live_gpt_enabled),
        gpt_project_url=args.gpt_project_url or env_cfg.gpt_project_url,
        gpt_model=args.gpt_model or env_cfg.gpt_model,
        gpt_reasoning=args.gpt_reasoning or env_cfg.gpt_reasoning,
        live_gemini_enabled=bool(args.live_gemini or env_cfg.live_gemini_enabled),
        live_claude_enabled=False,
        live_local_enabled=bool(args.live_local or env_cfg.live_local_enabled),
        local_model=args.local_model or env_cfg.local_model,
        live_groq_enabled=live_groq,
        groq_model=args.groq_model or env_cfg.groq_model,
        groq_fallback_models=args.groq_fallback_models or env_cfg.groq_fallback_models,
        live_cloudflare_enabled=live_cloudflare,
        cloudflare_model=args.cloudflare_model or env_cfg.cloudflare_model,
    )
    result = run_pre_execution_council(
        args.task,
        work_dir=Path.cwd(),
        council_config=cfg,
    )
    if result.brief is None:
        print(f"Council skipped: {result.skipped_reason}")
        return 2
    print(f"run_id: {result.run_id}")
    print(f"messages: {len(result.messages)}")
    print(f"log_dir: {result.log_dir}")
    print(f"transcript: {result.transcript_path}")
    print(f"brief: {result.brief_path}")
    print(f"synthesis: {result.brief.final_synthesis}")
    print(f"recommended_first_slice: {result.brief.recommended_first_execution_slice}")
    if args.show_transcript and result.transcript_path:
        print("\n===== TRANSCRIPT =====")
        print(Path(result.transcript_path).read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
