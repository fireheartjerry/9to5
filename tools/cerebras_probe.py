from __future__ import annotations

import argparse
import os
import sys
import urllib.error
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import config  # noqa: E402
from agents.planning.pre_execution_council import (  # noqa: E402
    CEREBRAS_DEFAULT_MODEL,
    _cerebras_chat_completion,
    _cerebras_error_category,
)


def _parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Probe Cerebras without printing secrets.")
    parser.add_argument("--model", default="")
    parser.add_argument("--timeout", type=float, default=20.0)
    return parser.parse_args(argv)


def _safe_status(exc: BaseException) -> str:
    if isinstance(exc, urllib.error.HTTPError):
        return f"http_{getattr(exc, 'code', 'unknown')}"
    category = _cerebras_error_category(exc)
    if category == "auth":
        return "missing_or_invalid_key"
    if category == "rate_limit":
        return "rate_limited"
    if category == "model_not_found":
        return "model_not_found"
    if category == "malformed_response":
        return "malformed_response"
    if category == "empty_response":
        return "empty_response"
    return "transport_unavailable"


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv or sys.argv[1:])
    _ = config.ENABLE_PRE_EXECUTION_COUNCIL
    model = args.model or getattr(config, "PRE_EXECUTION_COUNCIL_CEREBRAS_MODEL", "") or CEREBRAS_DEFAULT_MODEL
    print("model\tstatus\terror_category\tactual_live")
    if not os.getenv("CEREBRAS_API_KEY", "").strip():
        print(f"{model}\tmissing_api_key\tauth\tfalse")
        return 2
    try:
        reply = _cerebras_chat_completion(
            model=model,
            messages=[
                {
                    "role": "user",
                    "content": "Reply with exactly: cerebras_probe_ok",
                }
            ],
            temperature=0.0,
            timeout=args.timeout,
        )
    except Exception as exc:  # noqa: BLE001 -- probe reports safe categories only
        print(f"{model}\t{_safe_status(exc)}\t{_cerebras_error_category(exc)}\tfalse")
        return 1
    if not reply:
        print(f"{model}\tempty_response\tempty_response\tfalse")
        return 1
    print(f"{model}\tok\tok\ttrue")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
