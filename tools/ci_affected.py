"""Decide whether a change set is safe for affected-only CI test selection (fail closed).

Compatibility facade for the CI PR lane. The implementation delegates to ``test_brain`` so the
GitHub workflow can keep consuming the original affected_* outputs while the selector becomes
history-aware and budgeted.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Decision
  targets_for_safe(files: list[str]) -> list[str]
  decide(files: list[str], repo_root: Path) -> Decision
  main(argv: list[str]) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/platform/test_ci_affected.py
"""
from __future__ import annotations

import sys
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import affected_tests  # noqa: E402
import test_brain  # noqa: E402


@dataclass
class Decision:
    ok: bool
    reason: str = ""
    targets: list[str] = field(default_factory=list)
    estimated_seconds: float = 0.0
    explanations: list[str] = field(default_factory=list)


def targets_for_safe(files: list[str]) -> list[str]:
    return test_brain.select_tests(files, repo_root=affected_tests.REPO_ROOT).targets


def decide(files: list[str], repo_root: Path) -> Decision:
    sel = test_brain.select_tests(files, repo_root=repo_root)
    return Decision(sel.ok, sel.reason, sel.targets, sel.estimated_seconds, sel.explanations)


def main(argv: list[str]) -> int:
    files = argv or [ln.strip() for ln in sys.stdin.read().splitlines()]
    d = decide(files, repo_root=affected_tests.REPO_ROOT)
    print(f"affected_ok={'true' if d.ok else 'false'}")
    print(f"affected_reason={d.reason}")
    print(f"affected_targets={' '.join(d.targets)}")
    print(f"testbrain_estimated_seconds={int(d.estimated_seconds + 0.999)}")
    print("testbrain_explain<<EOF")
    for line in d.explanations:
        print(line)
    print("EOF")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
