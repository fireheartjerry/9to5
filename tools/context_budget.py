"""Context-budget checks for Claude-facing repo surfaces.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Budget
  measure() -> list[dict]
  main(argv: list[str] | None=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_context_budget.py
"""
from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


@dataclass(frozen=True)
class Budget:
    label: str
    path: Path
    max_lines: int
    max_chars: int
    glob: str | None = None


BUDGETS = (
    Budget("CLAUDE.md", REPO_ROOT / "CLAUDE.md", 200, 16000),
    Budget(".claude/rules", REPO_ROOT / ".claude" / "rules", 900, 60000, "*.md"),
    Budget(".claude/skills", REPO_ROOT / ".claude" / "skills", 8000, 500000, "SKILL.md"),
)


def _files_for(budget: Budget) -> list[Path]:
    if budget.glob:
        if not budget.path.exists():
            return []
        return sorted(p for p in budget.path.rglob(budget.glob)
                      if "logs" not in p.parts and "__pycache__" not in p.parts)
    return [budget.path] if budget.path.exists() else []


def measure() -> list[dict]:
    rows: list[dict] = []
    for budget in BUDGETS:
        files = _files_for(budget)
        lines = 0
        chars = 0
        for path in files:
            try:
                text = path.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                text = path.read_text(errors="ignore")
            lines += len(text.splitlines())
            chars += len(text)
        rows.append({
            "label": budget.label,
            "files": len(files),
            "lines": lines,
            "chars": chars,
            "max_lines": budget.max_lines,
            "max_chars": budget.max_chars,
            "ok": lines <= budget.max_lines and chars <= budget.max_chars,
        })
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--strict", action="store_true",
                        help="return non-zero when any budget is exceeded")
    args = parser.parse_args(argv)
    rows = measure()
    ok = all(row["ok"] for row in rows)
    if args.json:
        print(json.dumps({"ok": ok, "budgets": rows}, indent=2))
    else:
        for row in rows:
            state = "ok" if row["ok"] else "WARN"
            print(
                f"[context-budget] {state} {row['label']}: "
                f"{row['lines']}/{row['max_lines']} lines, "
                f"{row['chars']}/{row['max_chars']} chars ({row['files']} files)"
            )
    return 0 if ok or not args.strict else 1


if __name__ == "__main__":
    raise SystemExit(main())
