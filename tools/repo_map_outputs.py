"""write_outputs and its sub-functions for the 9to5 AI-navigation layer.

Imported lazily from repo_map.py's write_outputs wrapper to avoid circular-import issues
when repo_map.py is run as __main__ (see that module's write_outputs docstring).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  write_outputs(*, check: bool, only: Optional[str], no_headers: bool, headers_only: bool=False) -> int  -- Write (or --check) all artifacts
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/platform/test_repo_map.py
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Optional

# repo_map.py re-exports write_outputs via a lazy wrapper; these top-level imports are safe
# because by the time repo_map_outputs is first imported, repo_map is already fully loaded.
from repo_map import (  # noqa: E402
    build_map, is_test_path, iter_py_files, module_dotted, render_header, splice_header,
    _read_source, HEADER_SENTINEL, REPO_ROOT, REMEDIATION, first_party_roots,
    iter_header_files, parse_module, validate_header_prefix,
)
from repo_map_render import (
    render_root_agents_md, render_package_agents_md, _packages_with_init, _dump_json,
)

_JSON_PATH = REPO_ROOT / ".repo-map.json"
_ROOT_AGENTS = REPO_ROOT / "AGENTS.md"
_LLM_MAP = REPO_ROOT / ".llm-map.json"


# ==== SUB-FUNCTIONS ====

def _spliceHeaders(
    m: dict, drift: list, no_doc: list, *, check: bool, only: Optional[str]
) -> None:
    """Splice (or drift-check) @AI-MAP headers into source files. Test trees are excluded
    OUTRIGHT (belt to build_map's braces): a header in tests/ is pure noise and a bad
    splice there corrupts the suite, so the splice path must never touch them."""
    for path in iter_py_files(None if check else only):
        if is_test_path(path):  # never splice test code, even if it somehow got mapped
            continue
        rec = m["modules"].get(module_dotted(path))
        if rec is None:  # unparseable (skipped in build_map) -> don't touch
            continue
        src = _read_source(path)
        has_header = HEADER_SENTINEL in src
        spliced = splice_header(src, render_header(rec))
        if spliced is None:
            if not check:
                no_doc.append(str(path.relative_to(REPO_ROOT)))
            continue
        if check:
            if has_header and spliced != src:   # only adopted headers must stay current
                drift.append(str(path.relative_to(REPO_ROOT)))
        elif spliced != src:
            path.write_text(spliced, encoding="utf-8", newline="\n")


def _writeJsonMap(json_text: str, *, check: bool, drift: list) -> None:
    """Write or drift-check .repo-map.json."""
    if check:
        have = _JSON_PATH.read_text(encoding="utf-8") if _JSON_PATH.exists() else None
        if have != json_text:
            drift.append(str(_JSON_PATH.relative_to(REPO_ROOT)))
    else:
        _JSON_PATH.write_text(json_text, encoding="utf-8", newline="\n")


def _writeLlmProjection(m: dict, *, check: bool, drift: list) -> None:
    """Write/check the compact LLM projection while preserving the canonical full map."""
    from llm_navigation import build_projection
    text = _dump_json(build_projection(m))
    if check:
        # Like AGENTS.md, this derived convenience artifact is optional on a fresh clone.
        # Once generated and adopted it participates in drift protection.
        have = _LLM_MAP.read_text(encoding="utf-8") if _LLM_MAP.exists() else None
        if have is not None and have != text:
            drift.append(str(_LLM_MAP.relative_to(REPO_ROOT)))
    else:
        _LLM_MAP.write_text(text, encoding="utf-8", newline="\n")


def _writeAgentsMd(*, check: bool, root_md: str, pkg_mds: dict, drift: list) -> None:
    """Write or drift-check root AGENTS.md and per-package AGENTS.md files.

    AGENTS.md files are gitignored derived artifacts: on a clean checkout they simply do
    not exist, so in check mode a MISSING file is not drift -- only a present-but-stale
    one is. (Same adoption rule as headers; keeps `--check` green in CI clean clones.)"""
    def _cmp(path: Path, want: str) -> None:
        if not path.exists():
            return
        if path.read_text(encoding="utf-8") != want:
            drift.append(str(path.relative_to(REPO_ROOT)))

    if check:
        _cmp(_ROOT_AGENTS, root_md)
        for pkg, text in pkg_mds.items():
            _cmp(REPO_ROOT / pkg / "AGENTS.md", text)
    else:
        _ROOT_AGENTS.write_text(root_md, encoding="utf-8", newline="\n")
        for pkg, text in pkg_mds.items():
            (REPO_ROOT / pkg / "AGENTS.md").write_text(text, encoding="utf-8", newline="\n")


def _reportResults(
    drift: list, no_doc: list, *, check: bool, only: Optional[str], n_modules: int, n_pkgs: int,
) -> None:
    """Print the final summary line or drift report."""
    if no_doc:
        print(f"[repo_map] {len(no_doc)} file(s) have no module docstring (skipped header): "
              + ", ".join(no_doc[:8]) + ("..." if len(no_doc) > 8 else ""), file=sys.stderr)
    if check and drift:
        print(f"[repo_map] STALE: {len(drift)} artifact(s)/header(s) out of date:", file=sys.stderr)
        for d in drift[:20]:
            print(f"  - {d}", file=sys.stderr)
        print(REMEDIATION, file=sys.stderr)
    elif check:
        print("[repo_map] up to date.")
    else:
        print(f"[repo_map] wrote .repo-map.json ({n_modules} modules), "
              f"AGENTS.md (+{n_pkgs} package), spliced headers"
              + (f" under {only}/" if only else " (all modules)") + ".")


def _writeHeadersOnly(*, check: bool, only: Optional[str]) -> int:
    """Splice/check one source prefix without deriving or touching global artifacts."""
    try:
        prefix = validate_header_prefix(only)
        paths = iter_header_files(prefix)
    except ValueError as exc:
        print(f"[repo_map] headers-only refused: {exc}", file=sys.stderr)
        return 2
    if not paths:
        print("[repo_map] headers-only refused: prefix has no Python leaves", file=sys.stderr)
        return 2
    discovered = [path for path in iter_py_files() if not is_test_path(path)]
    inventory_paths = sorted(set(discovered).union(paths))
    roots = first_party_roots(inventory_paths)
    known_modules = {module_dotted(path) for path in inventory_paths}
    drift: list[str] = []
    errors: list[str] = []
    for path in paths:
        rel = path.relative_to(REPO_ROOT).as_posix()
        try:
            source = _read_source(path)
            record = parse_module(path, roots, known_modules)
            spliced = splice_header(source, render_header(record))
        except (OSError, SyntaxError, UnicodeError) as exc:
            errors.append(f"{rel}: {exc}")
            continue
        if spliced is None:
            errors.append(f"{rel}: module docstring required")
            continue
        if spliced != source:
            if check:
                drift.append(rel)
            else:
                path.write_text(spliced, encoding="utf-8", newline="\n")
    if errors:
        print("[repo_map] headers-only source errors:", file=sys.stderr)
        for item in errors:
            print(f"  - {item}", file=sys.stderr)
    if check and drift:
        print("[repo_map] headers-only STALE:", file=sys.stderr)
        for item in drift:
            print(f"  - {item}", file=sys.stderr)
    if not errors and not drift:
        verb = "verified" if check else "spliced"
        print(f"[repo_map] headers-only {verb} {len(paths)} file(s) under {prefix}/.")
    return 1 if errors or (check and drift) else 0


# ==== THIN DISPATCHER ====

def write_outputs(
    *, check: bool, only: Optional[str], no_headers: bool, headers_only: bool = False
) -> int:
    """Write (or --check) all artifacts. Returns process exit code (0 ok, 1 drift/problem).

    Order matters: in write mode we splice headers FIRST, then rebuild the index from the
    post-splice source, so a single run is a fixpoint (the committed .repo-map.json reflects the
    headers it just wrote). Adoption is INCREMENTAL: write mode splices the files matched by
    ``only``; check mode scans ALL files but verifies only those that have ALREADY adopted a
    header (contain the sentinel) -- so un-adopted files never count as drift."""
    if headers_only:
        if no_headers:
            print("[repo_map] headers-only cannot skip headers", file=sys.stderr)
            return 2
        return _writeHeadersOnly(check=check, only=only)
    m = build_map()
    drift: list[str] = []
    no_doc: list[str] = []
    if not no_headers:
        _spliceHeaders(m, drift, no_doc, check=check, only=only)
    if not check and not no_headers:
        m = build_map()
    json_text = _dump_json(m)
    root_md = render_root_agents_md(m)
    pkg_mds = {pkg: render_package_agents_md(m, pkg) for pkg in _packages_with_init(m)}
    _writeJsonMap(json_text, check=check, drift=drift)
    _writeLlmProjection(m, check=check, drift=drift)
    _writeAgentsMd(check=check, root_md=root_md, pkg_mds=pkg_mds, drift=drift)
    _reportResults(drift, no_doc, check=check, only=only,
                   n_modules=len(m["modules"]), n_pkgs=len(pkg_mds))
    return 1 if (check and drift) else 0
