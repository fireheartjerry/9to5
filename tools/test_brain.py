@dataclass
class TestStat:
    target: str
    runs: int = 0
    passes: int = 0
    failures: int = 0
    skips: int = 0
    total_duration: float = 0.0
    max_duration: float = 0.0
    last_seen: float = 0.0
    last_failed: float = 0.0

    @property
    def avg_duration(self) -> float:
        if self.runs <= 0:
            return UNKNOWN_TARGET_SECONDS
        return max(0.01, self.total_duration / self.runs)

    @property
    def recent_failure(self) -> bool:
        return self.last_failed > 0 and (time() - self.last_failed) <= RECENT_FAILURE_WINDOW_SECONDS

    @property
    def failure_rate(self) -> float:
        if self.runs <= 0:
            return 0.0
        return self.failures / self.runs

    @property
    def flaky(self) -> bool:
        return self.runs >= MIN_FLAKE_RUNS and self.failures > 0 and self.passes > 0

    @property
    def quarantine_candidate(self) -> bool:
        return self.flaky and self.failure_rate <= MAX_QUARANTINE_FAILURE_RATE


@dataclass
class Selection:
    ok: bool
    reason: str
    targets: list[str] = field(default_factory=list)
    estimated_seconds: float = 0.0
    direct_targets: list[str] = field(default_factory=list)
    recent_failure_targets: list[str] = field(default_factory=list)
    sentinel_targets: list[str] = field(default_factory=list)
    quarantined_targets: list[str] = field(default_factory=list)
    explanations: list[str] = field(default_factory=list)
    changed_files: list[str] = field(default_factory=list)


def _clean_files(files: list[str]) -> list[str]:
    return [Path(f.strip().strip(chr(0xFEFF)).strip()).as_posix() for f in files if f and f.strip()]


def _git_changed() -> list[str]:
    try:
        out = subprocess.run(["git", "diff", "--name-only", "HEAD"], cwd=REPO_ROOT,
                             capture_output=True, text=True, timeout=30)
        return [ln.strip() for ln in out.stdout.splitlines() if ln.strip()]
    except Exception:  # noqa: BLE001
        return []


def _target_from_nodeid(nodeid: str) -> str:
    return nodeid.split("::", 1)[0].replace("\\", "/")


def _iter_history_files(history_dir: Path) -> list[Path]:
    if not history_dir.exists():
        return []
    return sorted(history_dir.glob("*.jsonl"), key=lambda p: p.stat().st_mtime, reverse=True)[:200]


def load_stats(history_dir: Path | None = None) -> dict[str, TestStat]:
    """Load aggregate file-level test stats from pytest history JSONL."""
    stats: dict[str, TestStat] = {}
    seen_nodes: set[tuple[str, str]] = set()
    for path in _iter_history_files(history_dir or RUNS_DIR):
        try:
            lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            continue
        for line in lines:
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            nodeid = str(rec.get("nodeid") or "")
            if not nodeid:
                continue
            run_key = str(rec.get("run_id") or path.name)
            seen_key = (run_key, nodeid)
            if seen_key in seen_nodes:
                continue
            seen_nodes.add(seen_key)
            target = _target_from_nodeid(nodeid)
            stat = stats.setdefault(target, TestStat(target=target))
            duration = float(rec.get("duration_seconds") or 0.0)
            ts = float(rec.get("timestamp") or path.stat().st_mtime)
            outcome = str(rec.get("outcome") or "")
            stat.runs += 1
            stat.total_duration += max(0.0, duration)
            stat.max_duration = max(stat.max_duration, duration)
            stat.last_seen = max(stat.last_seen, ts)
            if outcome in {"failed", "error"}:
                stat.failures += 1
                stat.last_failed = max(stat.last_failed, ts)
            elif outcome == "skipped":
                stat.skips += 1
            else:
                stat.passes += 1
    return stats


def flake_candidates(stats: dict[str, TestStat]) -> list[TestStat]:
    """Return tests with mixed pass/fail history that are safe quarantine candidates."""
    return sorted(
        (stat for stat in stats.values() if stat.quarantine_candidate),
        key=lambda s: (-s.failure_rate, -s.failures, s.target),
    )


def slowest_tests(stats: dict[str, TestStat], limit: int = 20) -> list[TestStat]:
    """Return targets with the highest average runtime."""
    return sorted(stats.values(), key=lambda s: (-s.avg_duration, -s.max_duration, s.target))[:limit]


def _audit_source_files(repo_root: Path = REPO_ROOT) -> list[str]:
    files: list[str] = []
    for prefix in AUDIT_SOURCE_PREFIXES:
        root = repo_root / prefix
        if not root.exists():
            continue
        for path in root.rglob("*.py"):
            if "__pycache__" in path.parts:
                continue
            rel = path.relative_to(repo_root).as_posix()
            if rel in AUDIT_EXCLUDED_FILES or rel.endswith("/__init__.py"):
                continue
            files.append(rel)
    return sorted(files)


def audit_mapping(repo_root: Path = REPO_ROOT) -> dict:
    """Report source files that do not currently resolve to any affected-test target."""
    mapped = []
    unmapped = []
    for rel in _audit_source_files(repo_root):
        targets = affected_tests.targets_for([rel])
        row = {
            "file": rel,
            "targets": targets,
            "priority": mapping_debt_priority(rel),
            "priority_label": mapping_debt_priority_label(mapping_debt_priority(rel)),
        }
        if targets:
            mapped.append(row)
        else:
            unmapped.append(row)
    total = len(mapped) + len(unmapped)
    return {
        "schema": 1,
        "total_files": total,
        "mapped_files": len(mapped),
        "unmapped_files": len(unmapped),
        "coverage": round((len(mapped) / total) if total else 1.0, 4),
        "mapped": mapped,
        "unmapped": sorted(unmapped, key=lambda row: (row["priority"], row["file"])),
    }


def mapping_debt_priority(path: str) -> int:
    for priority, prefixes in MAPPING_DEBT_PRIORITY:
        if any(path.startswith(prefix) for prefix in prefixes):
            return priority
    return 2


def mapping_debt_priority_label(priority: int) -> str:
    return {0: "critical", 1: "domain", 2: "leaf"}.get(priority, "leaf")


def history_report(stats: dict[str, TestStat], limit: int = 20) -> dict:
    slowest = slowest_tests(stats, limit)
    flakes = flake_candidates(stats)
    return {
        "schema": 1,
        "target_count": len(stats),
        "total_runs": sum(s.runs for s in stats.values()),
        "total_failures": sum(s.failures for s in stats.values()),
        "slowest": [stat_record(s) for s in slowest],
        "flake_candidates": [stat_record(s) for s in flakes[:limit]],
    }


def stat_record(stat: TestStat) -> dict:
    return {
        "target": stat.target,
        "runs": stat.runs,
        "passes": stat.passes,
        "failures": stat.failures,
        "skips": stat.skips,
        "avg_duration": round(stat.avg_duration, 3),
        "max_duration": round(stat.max_duration, 3),
        "failure_rate": round(stat.failure_rate, 3),
    }


def load_quarantine(path: Path | None = None) -> set[str]:
    qpath = path or QUARANTINE_FILE
    try:
        data = json.loads(qpath.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return set()
    if isinstance(data, dict):
        raw = data.get("targets", [])
    else:
        raw = data
    return {str(t).replace("\\", "/") for t in raw if str(t).strip()}


def write_quarantine(stats: dict[str, TestStat], path: Path | None = None) -> Path:
    qpath = path or QUARANTINE_FILE
    targets = [s.target for s in flake_candidates(stats)]
    qpath.parent.mkdir(parents=True, exist_ok=True)
    qpath.write_text(json.dumps({
        "schema": 1,
        "generated_at": int(time()),
        "policy": {
            "min_runs": MIN_FLAKE_RUNS,
            "max_failure_rate": MAX_QUARANTINE_FAILURE_RATE,
        },
        "targets": targets,
    }, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return qpath


def sentinel_targets_for(files: list[str]) -> list[str]:
    """Cheap domain sentinels for adjacent-contract coverage beyond direct mappings."""
    targets: list[str] = []
    seen: set[str] = set()
    for rel in _clean_files(files):
        if rel.startswith("tests/"):
            continue
        for prefix, sentinels in DOMAIN_SENTINELS.items():
            if not rel.startswith(prefix):
                continue
            for target in sentinels:
                if target in seen or not (REPO_ROOT / target).exists():
                    continue
                seen.add(target)
                targets.append(target)
    return targets


def _safety_reason(rels: list[str], repo_root: Path) -> str:
    if not rels:
        return "empty change set"
    if len(rels) > MAX_CHANGED_FILES:
        return f"too many files ({len(rels)} > {MAX_CHANGED_FILES})"
    for rel in rels:
        if rel in SENSITIVE_EXACT or rel.endswith("/conftest.py") \
                or any(rel.startswith(p) for p in SENSITIVE_PREFIXES):
            return f"sensitive file: {rel}"
        if not rel.endswith(".py"):
            return f"non-python change: {rel}"
        if not (repo_root / rel).exists():
            return f"missing (deleted/renamed): {rel}"
    return ""


def _estimate(targets: list[str], stats: dict[str, TestStat]) -> float:
    return sum(stats.get(t, TestStat(t)).avg_duration for t in targets)


def plan_shards(targets: list[str], stats: dict[str, TestStat], shard_count: int) -> list[dict]:
    """Greedy duration-balanced pytest target shards.

    Longest-known targets are assigned first to the currently lightest shard. Unknown targets use
    the same conservative default duration as selection so a never-seen file is not treated as free.
    """
    count = max(1, shard_count)
    shards = [{"index": i + 1, "estimated_seconds": 0.0, "targets": []} for i in range(count)]
    unique_targets = sorted(set(t.replace("\\", "/") for t in targets if str(t).strip()))
    weighted = sorted(
        ((target, stats.get(target, TestStat(target)).avg_duration) for target in unique_targets),
        key=lambda item: (-item[1], item[0]),
    )
    for target, duration in weighted:
        shard = min(shards, key=lambda s: (float(s["estimated_seconds"]), int(s["index"])))
        shard["targets"].append(target)
        shard["estimated_seconds"] = round(float(shard["estimated_seconds"]) + duration, 3)
    return shards


def _recent_failures(stats: dict[str, TestStat]) -> list[str]:
    return sorted(t for t, stat in stats.items() if stat.recent_failure and Path(REPO_ROOT / t).exists())


def select_tests(files: list[str], repo_root: Path = REPO_ROOT, budget_seconds: float = 480.0,
                 history_dir: Path | None = None, quarantine_file: Path | None = None) -> Selection:
    rels = _clean_files(files)
    safety = _safety_reason(rels, repo_root)
    if safety:
        return Selection(False, safety, changed_files=rels)

    direct = affected_tests.targets_for(rels)
    if not direct:
        return Selection(False, "no mapped tests for change set", changed_files=rels)
    for rel in rels:
        if rel.startswith("tests/"):
            continue
        if not affected_tests.targets_for([rel]):
            return Selection(False, f"unmapped module: {rel}", changed_files=rels)

    stats = load_stats(history_dir)
    quarantined = load_quarantine(quarantine_file)
    quarantined_recent = sorted(t for t in _recent_failures(stats) if t in quarantined and t not in direct)
    sentinels = [t for t in sentinel_targets_for(rels) if t not in direct]
    recent = [t for t in _recent_failures(stats)
              if t not in direct and t not in sentinels and t not in quarantined]
    targets = sorted(set(direct + sentinels + recent))
    estimated = _estimate(targets, stats)
    explanations = [
        f"direct affected targets: {len(direct)}",
        f"domain sentinel targets added: {len(sentinels)}",
        f"recent failing targets added: {len(recent)}",
        f"quarantined recent failures skipped: {len(quarantined_recent)}",
        f"estimated runtime: {estimated:.2f}s / budget {budget_seconds:.2f}s",
    ]
    if estimated > budget_seconds:
        return Selection(False, f"selection exceeds budget ({estimated:.1f}s > {budget_seconds:.1f}s)",
                         targets=targets, estimated_seconds=estimated, direct_targets=direct,
                         recent_failure_targets=recent, sentinel_targets=sentinels,
                         quarantined_targets=quarantined_recent, explanations=explanations,
                         changed_files=rels)
    return Selection(True, "smart selection ok", targets=targets, estimated_seconds=estimated,
                     direct_targets=direct, recent_failure_targets=recent, sentinel_targets=sentinels,
                     quarantined_targets=quarantined_recent, explanations=explanations,
                     changed_files=rels)


def selection_report(selection: Selection) -> dict:
    """Stable machine-readable report for CI summaries and cached artifacts."""
    return {
        "schema": 1,
        "ok": selection.ok,
        "reason": selection.reason,
        "estimated_seconds": round(selection.estimated_seconds, 3),
        "changed_files": selection.changed_files,
        "targets": selection.targets,
        "direct_targets": selection.direct_targets,
        "sentinel_targets": selection.sentinel_targets,
        "recent_failure_targets": selection.recent_failure_targets,
        "quarantined_targets": selection.quarantined_targets,
        "explanations": selection.explanations,
    }


def shard_report(shards: list[dict]) -> dict:
    return {
        "schema": 1,
        "shard_count": len(shards),
        "total_targets": sum(len(s["targets"]) for s in shards),
        "max_estimated_seconds": max((float(s["estimated_seconds"]) for s in shards), default=0.0),
        "shards": shards,
    }


def matrix_report(shards: list[dict]) -> dict:
    """GitHub Actions matrix payload for duration-balanced shards."""
    include = []
    for shard in shards:
        targets = [str(t) for t in shard.get("targets", []) if str(t).strip()]
        include.append({
            "shard": int(shard["index"]),
            "estimated_seconds": float(shard["estimated_seconds"]),
            "targets": " ".join(targets),
            "has_targets": bool(targets),
        })
    return {"include": include}


def write_reports(selection: Selection, out_dir: Path, shards: list[dict] | None = None) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    data = selection_report(selection)
    if shards is not None:
        data["shard_plan"] = shard_report(shards)
    json_path = out_dir / "selection.json"
    md_path = out_dir / "selection.md"
    json_path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    md_path.write_text(_markdown_report(data), encoding="utf-8")
    if shards is not None:
        (out_dir / "shards.json").write_text(
            json.dumps(shard_report(shards), indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        (out_dir / "shards.md").write_text(_shards_markdown(shard_report(shards)), encoding="utf-8")
    return json_path, md_path


def _bullet_list(items: list[str]) -> str:
    if not items:
        return "- none\n"
    return "".join(f"- `{item}`\n" for item in items)


def _markdown_report(data: dict) -> str:
    text = (
        "# Test Brain Selection\n\n"
        f"- Status: `{'ok' if data['ok'] else 'fallback'}`\n"
        f"- Reason: `{data['reason']}`\n"
        f"- Estimated seconds: `{data['estimated_seconds']}`\n"
        f"- Targets: `{len(data['targets'])}`\n\n"
        "## Explanation\n\n"
        + _bullet_list([str(x) for x in data["explanations"]])
        + "\n## Changed Files\n\n"
        + _bullet_list([str(x) for x in data["changed_files"]])
        + "\n## Selected Targets\n\n"
        + _bullet_list([str(x) for x in data["targets"]])
        + "\n## Domain Sentinels\n\n"
        + _bullet_list([str(x) for x in data["sentinel_targets"]])
        + "\n## Recent Failures\n\n"
        + _bullet_list([str(x) for x in data["recent_failure_targets"]])
        + "\n## Quarantined Recent Failures\n\n"
        + _bullet_list([str(x) for x in data["quarantined_targets"]])
    )
    if "shard_plan" in data:
        text += "\n" + _shards_markdown(data["shard_plan"])
    return text


def _shards_markdown(data: dict) -> str:
    lines = [
        "## Shard Plan",
        "",
        f"- Shards: `{data['shard_count']}`",
        f"- Targets: `{data['total_targets']}`",
        f"- Max estimated seconds: `{data['max_estimated_seconds']}`",
        "",
    ]
    for shard in data["shards"]:
        targets = " ".join(shard["targets"]) if shard["targets"] else "(empty)"
        lines.append(f"### Shard {shard['index']} (~{shard['estimated_seconds']}s)")
        lines.append("")
        lines.append(f"`python -m pytest {targets}`")
        lines.append("")
    return "\n".join(lines)


def history_markdown(data: dict) -> str:
    lines = [
        "# Test Brain History",
        "",
        f"- Targets: `{data['target_count']}`",
        f"- Runs: `{data['total_runs']}`",
        f"- Failures: `{data['total_failures']}`",
        "",
        "## Slowest Targets",
        "",
    ]
    if not data["slowest"]:
        lines.append("- none")
    for row in data["slowest"]:
        lines.append(
            f"- `{row['target']}` avg `{row['avg_duration']}`s max `{row['max_duration']}`s "
            f"runs `{row['runs']}` failures `{row['failures']}`"
        )
    lines.extend(["", "## Flake Candidates", ""])
    if not data["flake_candidates"]:
        lines.append("- none")
    for row in data["flake_candidates"]:
        lines.append(
            f"- `{row['target']}` failure_rate `{row['failure_rate']}` "
            f"runs `{row['runs']}` failures `{row['failures']}`"
        )
    return "\n".join(lines) + "\n"


def mapping_markdown(data: dict) -> str:
    lines = [
        "# Test Brain Mapping Audit",
        "",
        f"- Source files: `{data['total_files']}`",
        f"- Mapped files: `{data['mapped_files']}`",
        f"- Unmapped files: `{data['unmapped_files']}`",
        f"- Coverage: `{data['coverage']:.1%}`",
        "",
        "## Unmapped Files",
        "",
    ]
    if not data["unmapped"]:
        lines.append("- none")
    for priority in (0, 1, 2):
        rows = [row for row in data["unmapped"] if int(row.get("priority", 2)) == priority]
        if not rows:
            continue
        lines.extend(["", f"### {mapping_debt_priority_label(priority).title()}"])
        for row in rows[:100]:
            lines.append(f"- `{row['file']}`")
    if len(data["unmapped"]) > 100:
        lines.append(f"- ... {len(data['unmapped']) - 100} more")
    return "\n".join(lines) + "\n"


def write_history_report(stats: dict[str, TestStat], out_dir: Path, limit: int = 20) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
