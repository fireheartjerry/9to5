"""Deterministic evaluation harness for the elaborator excellence tier.

Proves the tier's LLM-INDEPENDENT contributions with a scripted brain (no Ollama,
no network -- reproducible byte-for-byte):
  (a) more real repo grounding reaches the prompt (prompt_signal), and
  (b) best-of-N SELECTS the more-grounded candidate (groundedness).

The scripted brain (``scriptedChat``) dispatches on the structured ``act`` tag and
on stance markers in the SYSTEM prompt -- never on prompt wording -- so results are
exact. When a "thorough"/"exhaustive" stance is present it returns a spec naming a
REAL file under work_dir (high groundedness); otherwise it names a clearly-fake path
(low groundedness). Best-of-N then measurably prefers the grounded candidate.

The core comparison is kept to grounding + selection: SOCIETY/LOOKAHEAD/DEFER are OFF,
the portfolio optimizer is OFF (plain max-weight sort), and precedent is ON with an
INJECTED seam (fixed fake hits) so the ON prompt reliably carries the PRECEDENT marker.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  scoreSpec(spec: str, work_dir: str) -> dict  -- Deterministic quality signals for a produced spec.
  promptSignal(user_prompt: str) -> int  -- How many real-context grounding markers reached the model (0-3).
  scriptedChat(work_dir: str)  -- Return ``(chat, holder)``
  runOne(goal: str, is_vague: bool, work_dir: str) -> dict  -- Elaborate ``goal`` twice (flags OFF vs excellence-ON) against the same repo.
  runBattery() -> list[dict]  -- Run the whole battery, each item in a fresh temp repo.
  historicalCases(records=None, *, limit: int=100) -> list[dict]  -- Read-only audit of completed task history for elaboration outcome evidence.
  report(results: list[dict]) -> str  -- Readable per-goal + aggregate table with the on-vs-off delta.
  main() -> None
DEPENDS-ON: agents.planning.elaborator, agents.planning.elaborator.core, agents.planning.elaborator.precedent, config, state.task
SIDE-EFFECTS: creates a throwaway temp repo per battery item (auto-cleaned)
RUN/TEST: python -m pytest tests/orchestration/test_elaborator.py
"""
from __future__ import annotations

import os
import sys
import tempfile
from unittest import mock

# Repo ROOT on sys.path so `python tools/elaborator_eval.py` finds top-level `config` etc.
# (a no-op under pytest / `from tools import elaborator_eval`, where root is already present).
_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

import config
from agents.planning import elaborator
from agents.planning.elaborator import precedent
from agents.planning.elaborator.core import _groundedness

REAL_MODULE = "real_module.py"          # created under each temp repo -> grounded
FAKE_PATH = "does/not/exist.py"         # never created -> ungrounded
SECTIONS = ("Objective", "Deliverables", "Acceptance Criteria", "Constraints", "Assumptions")
MARKERS = ("ACTUAL REPOSITORY SNAPSHOT", "STATE OF THE REPO", "PRECEDENT")

# Reviewable fixtures cover several repository shapes instead of a single synthetic
# file. The suite remains offline and deterministic, but its path expectations now
# mirror the modules a real elaborator must reason about.
FIXTURE_CASES = (
    {"goal": "add a helper to agents/planning/elaborator/core.py", "vague": False,
     "files": ("agents/planning/elaborator/core.py", "tests/orchestration/test_elaborator.py")},
    {"goal": "improve everything", "vague": True,
     "files": ("platform_core/orchestration/plan_mixin.py", "tests/orchestration/test_elaborator.py")},
    {"goal": "fix the failing tests", "vague": True,
     "files": ("tests/orchestration/test_elaborator.py", "agents/planning/elaborator/schema.py")},
)


def _spec(path: str) -> str:
    """A 5-section spec naming ``path`` -- completeness is identical across candidates so the
    ONLY thing that varies is groundedness (which path is real)."""
    return (
        f"# Objective\nWork on {path}.\n\n"
        f"# Deliverables\n- Edit `{path}` to satisfy the goal.\n\n"
        "# Acceptance Criteria\n- Tests pass and the change is verified.\n\n"
        "# Constraints\n- Keep the change surgical and on-scope.\n\n"
        "# Assumptions\n- The goal is achievable within this module.\n"
    )


def scoreSpec(spec: str, work_dir: str) -> dict:
    """Deterministic quality signals for a produced spec."""
    low = spec.lower()
    completeness = sum(1 for s in SECTIONS if s.lower() in low) / len(SECTIONS)
    has_assumptions = 1.0 if ("inferred" in low or "assumptions" in low) else 0.0
    return {
        "groundedness": _groundedness(spec, work_dir),
        "completeness": completeness,
        "has_assumptions": has_assumptions,
        "length": len(spec),
    }


def promptSignal(user_prompt: str) -> int:
    """How many real-context grounding markers reached the model (0-3)."""
    if not user_prompt:
        return 0
    return sum(1 for m in MARKERS if m in user_prompt)


def scriptedChat(work_dir: str):
    """Return ``(chat, holder)``. ``chat(system, user, *, act, want_json=False)`` is the
    deterministic brain; ``holder['user']`` captures the last ``act=="elaborate"`` prompt so
    ``promptSignal`` can read exactly what the model saw. Grounding VARIES by stance so
    best-of-N has a real choice to make."""
    holder: dict = {"user": ""}

    def chat(system, user, *, act, want_json=False):
        if act == "elaborate":
            holder["user"] = user
            thorough = ("thorough" in system) or ("exhaustive" in system)
            return {"message": {"content": _spec(REAL_MODULE if thorough else FAKE_PATH)}}
        if act == "elaborate_defer":
            return {"message": {"content": _spec(REAL_MODULE)}}
        if act == "self_review":
            return {"message": {"content": "Inferred: scope is this module — because the goal names it\n"
                                           "Inferred: existing tests cover it — because they exist"}}
        if act == "predict":
            return {"message": {"content": '{"predicted_success": 0.7}'}}
        return {"message": {"content": ""}}

    return chat, holder


_PRECEDENT_BLOCK = ("PRECEDENT (how similar goals resolved before):\n"
                    "- past success: added a helper cleanly (score 0.80)\n"
                    "- avoid (past failure): over-broad refactor")


def _flags(on: bool) -> dict:
    """Flag values for a run. ON = excellence tier's measurable core (grounding + best-of-N +
    precedent); society/lookahead/defer/optimizer stay OFF so the comparison isolates
    grounding + selection."""
    return {
        "ELABORATOR_EXCELLENCE_ENABLED": on,
        "ELABORATOR_BESTOFN_ENABLED": on,
        "ELABORATOR_PRECEDENT_ENABLED": on,
        "ELABORATOR_LOOKAHEAD_ENABLED": False,
        "ELABORATOR_DEFER_ENABLED": False,
        "SOCIETY_ENABLED": False,
        "PORTFOLIO_OPTIMIZER_ENABLED": False,
        "ELABORATOR_CANDIDATES_MAX": 3,
    }


def _runWithFlags(goal: str, work_dir: str, on: bool) -> dict:
    chat, holder = scriptedChat(work_dir)
    patches = [mock.patch.object(config, k, v) for k, v in _flags(on).items()]
    # Precedent is injected (fixed fake hits) so the ON prompt reliably carries the marker
    # without touching the real embedding index -- keeps the harness offline & deterministic.
    patches.append(mock.patch.object(precedent, "precedentEvidence", return_value={
        "block": _PRECEDENT_BLOCK, "success_hits": 1, "failure_hits": 1}))
    for p in patches:
        p.start()
    try:
        spec = elaborator.elaborate(goal, work_dir, chat=chat)
    finally:
        for p in reversed(patches):
            p.stop()
    scores = scoreSpec(spec, work_dir)
    scores["prompt_signal"] = promptSignal(holder["user"])
    return scores


def _makeRepo(root: str, files: tuple[str, ...] = (REAL_MODULE,)) -> None:
    """Create the minimal REAL grounding a run needs: the target module + an AGENTS.md so
    ``repoContext`` fires and the snapshot marker appears."""
    files = tuple(dict.fromkeys((REAL_MODULE, *files)))
    for rel in files:
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("def helper():\n    return 1\n")
    with open(os.path.join(root, "AGENTS.md"), "w", encoding="utf-8") as fh:
        fh.write("# Repo map\n\n- real_module.py — the module under evaluation\n")


def runOne(goal: str, is_vague: bool, work_dir: str) -> dict:
    """Elaborate ``goal`` twice (flags OFF vs excellence-ON) against the same repo."""
    return {
        "goal": goal,
        "is_vague": is_vague,
        "off": _runWithFlags(goal, work_dir, on=False),
        "on": _runWithFlags(goal, work_dir, on=True),
    }


BATTERY = [(case["goal"], case["vague"]) for case in FIXTURE_CASES]


def runBattery() -> list[dict]:
    """Run the whole battery, each item in a fresh temp repo."""
    results: list[dict] = []
    for case in FIXTURE_CASES:
        with tempfile.TemporaryDirectory() as root:
            _makeRepo(root, case["files"])
            results.append(runOne(case["goal"], case["vague"], root))
    return results


def historicalCases(records=None, *, limit: int = 100) -> list[dict]:
    """Read-only audit of completed task history for elaboration outcome evidence."""
    if records is None:
        from state.task import TaskState
        records = (data for _path, data in TaskState.iterStored())
    out = []
    for data in records:
        meta = (data or {}).get("meta") or {}
        if meta.get("status") not in ("done", "complete", "partial"):
            continue
        raw, spec = meta.get("goal_raw"), meta.get("goal_elaborated")
        universe = meta.get("universe") or {}
        if not raw or not spec:
            continue
        evidence = meta.get("elaboration") or {}
        out.append({"task_id": (data or {}).get("task_id", ""),
                    "has_approved_spec": bool(str(spec).strip()),
                    "has_universe": bool(universe.get("hard_boundaries")),
                    "has_selection_evidence": bool(evidence.get("candidates") or evidence.get("schema")),
                    "human_edited": bool(evidence.get("human_edited"))})
        if len(out) >= max(1, int(limit)):
            break
    return out


def _mean(results: list[dict], side: str, key: str) -> float:
    return sum(r[side][key] for r in results) / len(results)


def report(results: list[dict]) -> str:
    """Readable per-goal + aggregate table with the on-vs-off delta."""
    lines = ["Elaborator excellence tier -- flag-OFF vs flag-ON (deterministic scripted brain)", ""]
    head = f"{'goal':44} {'vague':5} | {'grounded off/on':16} {'signal off/on':13} {'complete off/on':15}"
    lines.append(head)
    lines.append("-" * len(head))
    for r in results:
        g = r["goal"][:42]
        lines.append(
            f"{g:44} {str(r['is_vague']):5} | "
            f"{r['off']['groundedness']:.2f} -> {r['on']['groundedness']:.2f}   "
            f"{r['off']['prompt_signal']:d} -> {r['on']['prompt_signal']:d}         "
            f"{r['off']['completeness']:.2f} -> {r['on']['completeness']:.2f}"
        )
    lines.append("-" * len(head))
    og, ng = _mean(results, "off", "groundedness"), _mean(results, "on", "groundedness")
    osig, nsig = _mean(results, "off", "prompt_signal"), _mean(results, "on", "prompt_signal")
    oc, nc = _mean(results, "off", "completeness"), _mean(results, "on", "completeness")
    lines.append(f"{'AGGREGATE MEAN':44} {'':5} | {og:.2f} -> {ng:.2f}   {osig:.2f} -> {nsig:.2f}      {oc:.2f} -> {nc:.2f}")
    lines.append(f"{'DELTA (on - off)':44} {'':5} | {ng - og:+.2f}          {nsig - osig:+.2f}           {nc - oc:+.2f}")
    lines.append("")
    lines.append(f"VERDICT: flag-on groundedness {ng - og:+.2f}, prompt-signal {nsig - osig:+.2f} vs flag-off")
    return "\n".join(lines)


def main() -> None:
    results = runBattery()
    print(report(results))


if __name__ == "__main__":
    main()
