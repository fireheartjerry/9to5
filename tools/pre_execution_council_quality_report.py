"""Generate a quality report from pre-execution council comparison artifacts.

RUN/TEST: python tools/pre_execution_council_quality_report.py --comparison name:round_dir,selector_dir

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  RunArtifact
  ComparisonArtifact
  load_run(label: str, raw_path: str | Path) -> RunArtifact
  build_report(comparisons: list[ComparisonArtifact], smoke_runs: list[RunArtifact]) -> str
  main(argv: list[str] | None=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/planning/test_pre_execution_council.py
"""
from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


@dataclass(frozen=True)
class RunArtifact:
    label: str
    path: Path
    metadata: dict[str, Any]
    brief: dict[str, Any]
    messages: list[dict[str, Any]]

    @property
    def policy(self) -> str:
        return str(self.metadata.get("conversation_policy") or "")

    @property
    def prompt_chars(self) -> int:
        return sum(len(str(msg.get("prompt_excerpt") or "")) for msg in self.messages)

    @property
    def warning_count(self) -> int:
        return len(self.metadata.get("warnings") or [])

    @property
    def disagreement_count(self) -> int:
        return len(self.brief.get("disagreements_between_agents") or [])

    @property
    def brief_chars(self) -> int:
        brief_md = self.path / "brief.md"
        return len(brief_md.read_text(encoding="utf-8")) if brief_md.exists() else len(json.dumps(self.brief))

    @property
    def first_slice(self) -> str:
        return str(self.brief.get("recommended_first_execution_slice") or "")

    @property
    def implementation_prompt(self) -> str:
        return str(self.brief.get("implementation_prompt_export") or "")

    @property
    def provider_summaries(self) -> list[dict[str, Any]]:
        raw = self.brief.get("provider_run_summaries") or []
        return [item for item in raw if isinstance(item, dict)]


@dataclass(frozen=True)
class ComparisonArtifact:
    label: str
    round_robin: RunArtifact
    selector: RunArtifact


def _parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Report on pre-execution council quality artifacts.")
    parser.add_argument(
        "--comparison",
        action="append",
        default=[],
        metavar="LABEL:ROUND_DIR,SELECTOR_DIR",
        help="Comparison pair emitted by tools/pre_execution_council_compare.py. May be repeated.",
    )
    parser.add_argument(
        "--smoke-log",
        action="append",
        default=[],
        metavar="LABEL:DIR",
        help="Single smoke run artifact directory to include. May be repeated.",
    )
    parser.add_argument("--output", default="", help="Optional markdown output path.")
    return parser.parse_args(argv)


def _load_json(path: Path) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"{path} did not contain a JSON object")
    return data


def _load_messages(path: Path) -> list[dict[str, Any]]:
    transcript = path / "transcript.jsonl"
    messages: list[dict[str, Any]] = []
    if not transcript.exists():
        return messages
    for line in transcript.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        item = json.loads(line)
        if isinstance(item, dict):
            messages.append(item)
    return messages


def load_run(label: str, raw_path: str | Path) -> RunArtifact:
    path = Path(raw_path)
    if not path.exists():
        raise FileNotFoundError(path)
    return RunArtifact(
        label=label,
        path=path,
        metadata=_load_json(path / "metadata.json"),
        brief=_load_json(path / "brief.json"),
        messages=_load_messages(path),
    )


def _parse_comparison(raw: str) -> ComparisonArtifact:
    try:
        label, paths = raw.split(":", 1)
        round_path, selector_path = paths.split(",", 1)
    except ValueError as exc:
        raise ValueError(f"Invalid --comparison {raw!r}; expected LABEL:ROUND_DIR,SELECTOR_DIR") from exc
    return ComparisonArtifact(
        label=label.strip() or "comparison",
        round_robin=load_run(f"{label}:round_robin", round_path.strip()),
        selector=load_run(f"{label}:selector", selector_path.strip()),
    )


def _parse_smoke(raw: str) -> RunArtifact:
    try:
        label, path = raw.split(":", 1)
    except ValueError as exc:
        raise ValueError(f"Invalid --smoke-log {raw!r}; expected LABEL:DIR") from exc
    return load_run(label.strip() or "smoke", path.strip())


def _provider_line(run: RunArtifact) -> str:
    parts = []
    for state in run.provider_summaries:
        name = str(state.get("seat_name") or "")
        if not name:
            continue
        status = str(state.get("last_provider_state") or "")
        live = int(state.get("actual_live_turn_count") or 0)
        fallback = int(state.get("fallback_turn_count") or 0)
        models = ", ".join(str(m) for m in (state.get("models_used") or []) if m)
        detail = f"{name}: {status}; live={live}; fallback={fallback}"
        if models:
            detail += f"; models={models}"
        parts.append(detail)
    return " | ".join(parts) if parts else "(no provider summary)"


def _fallback_line(run: RunArtifact) -> str:
    fallbacks = []
    for state in run.provider_summaries:
        if int(state.get("fallback_turn_count") or 0) <= 0:
            continue
        reasons = "; ".join(str(r) for r in (state.get("fallback_reasons") or []) if r)
        fallbacks.append(f"{state.get('seat_name')}: {reasons or 'fallback observed'}")
    return " | ".join(fallbacks) if fallbacks else "No fallbacks observed."


def _cloudflare_note(run: RunArtifact) -> str:
    state = next((s for s in run.provider_summaries if s.get("seat_name") == "Cloudflare"), None)
    if not state:
        return "Cloudflare did not participate."
    live = bool(state.get("actual_live_any"))
    excerpts = [
        str(msg.get("content") or "").replace("\n", " ").strip()
        for msg in run.messages
        if msg.get("speaker") == "Cloudflare"
    ]
    excerpt = excerpts[0][:220].rstrip() if excerpts else ""
    status = "live" if live else "not live"
    return f"Cloudflare participated {status}; first contribution: {excerpt or '(none)'}"


def _quality_delta(comp: ComparisonArtifact) -> list[str]:
    rr = comp.round_robin
    selector = comp.selector
    prompt_delta = selector.prompt_chars - rr.prompt_chars
    warning_delta = selector.warning_count - rr.warning_count
    disagreement_delta = selector.disagreement_count - rr.disagreement_count
    first_slice_changed = selector.first_slice != rr.first_slice
    return [
        f"prompt_chars: round_robin={rr.prompt_chars}, selector={selector.prompt_chars}, delta={prompt_delta}",
        f"warnings: round_robin={rr.warning_count}, selector={selector.warning_count}, delta={warning_delta}",
        f"disagreements: round_robin={rr.disagreement_count}, selector={selector.disagreement_count}, delta={disagreement_delta}",
        f"brief_chars: round_robin={rr.brief_chars}, selector={selector.brief_chars}",
        f"first_slice_changed={str(first_slice_changed).lower()}",
    ]


def _live_diversity_helped(comparisons: list[ComparisonArtifact], smoke_runs: list[RunArtifact]) -> tuple[str, str]:
    baseline = next((c.selector for c in comparisons if "mock" in c.label.lower()), None)
    live_runs = [c.selector for c in comparisons if c.selector is not baseline]
    live_runs.extend(smoke_runs)
    live_actual = [
        run
        for run in live_runs
        if any(bool(state.get("actual_live_any")) for state in run.provider_summaries)
    ]
    if not live_actual:
        return ("no", "No live provider run was available in the supplied artifacts.")
    changed_slice = bool(baseline and any(run.first_slice != baseline.first_slice for run in live_actual))
    fallback_seen = any(any(int(s.get("fallback_turn_count") or 0) for s in run.provider_summaries) for run in live_actual)
    warnings_seen = any(run.warning_count for run in live_actual)
    prompt_mentions_quality = any("synthesis" in run.first_slice.lower() or "quality" in run.first_slice.lower() for run in live_actual)
    if changed_slice and not warnings_seen:
        return ("yes", "Live diversity changed the recommended slice without adding quality warnings.")
    if changed_slice:
        return ("partial", "Live diversity changed the recommended slice, but warnings or formatting issues need prompt refinement.")
    if fallback_seen or prompt_mentions_quality:
        return ("diagnostic", "Live diversity mostly exposed provider health/fallback behavior rather than a clearly better implementation prompt.")
    return ("unclear", "The supplied live runs did not materially change the recommended implementation prompt.")


def _recommended_next_slice(helped: str) -> str:
    if helped == "yes":
        return "Council-to-execution seam planning, still as a design/reporting slice with no production wiring."
    if helped in {"partial", "diagnostic"}:
        return "Prompt/role/routing refinement before council-to-execution seam planning."
    return "Prompt/role/routing refinement and another quality audit before adding providers or wiring execution."


def build_report(comparisons: list[ComparisonArtifact], smoke_runs: list[RunArtifact]) -> str:
    helped, helped_reason = _live_diversity_helped(comparisons, smoke_runs)
    lines = [
        "# Council Quality Evaluation Report v1",
        "",
        "## Summary",
        f"- live_diversity_helped: {helped}",
        f"- rationale: {helped_reason}",
        f"- recommended_next_slice: {_recommended_next_slice(helped)}",
        "- boundary: pre-execution only; no production orchestration wiring.",
        "",
        "## Round-Robin vs Selector",
    ]
    if not comparisons:
        lines.append("- No comparison pairs supplied.")
    for comp in comparisons:
        lines.append(f"### {comp.label}")
        lines.extend(f"- {item}" for item in _quality_delta(comp))
        lines.append(f"- round_robin_first_slice: {comp.round_robin.first_slice}")
        lines.append(f"- selector_first_slice: {comp.selector.first_slice}")
        lines.append(f"- selector_provider_health: {_provider_line(comp.selector)}")
        lines.append(f"- selector_fallback_story: {_fallback_line(comp.selector)}")
        lines.append(f"- cloudflare: {_cloudflare_note(comp.selector)}")
        lines.append("")

    lines.append("## Smoke Runs")
    if not smoke_runs:
        lines.append("- No smoke runs supplied.")
    for run in smoke_runs:
        lines.append(f"### {run.label}")
        lines.append(f"- path: {run.path}")
        lines.append(f"- policy: {run.policy}")
        lines.append(f"- messages: {len(run.messages)}")
        lines.append(f"- prompt_chars: {run.prompt_chars}")
        lines.append(f"- warnings: {run.warning_count}")
        lines.append(f"- disagreements: {run.disagreement_count}")
        lines.append(f"- first_slice: {run.first_slice}")
        lines.append(f"- provider_health: {_provider_line(run)}")
        lines.append(f"- fallback_story: {_fallback_line(run)}")
        lines.append(f"- cloudflare: {_cloudflare_note(run)}")
        lines.append("")

    lines.append("## Brief Quality Notes")
    notes = []
    all_runs = [run for comp in comparisons for run in (comp.round_robin, comp.selector)] + smoke_runs
    if any(run.warning_count for run in all_runs):
        notes.append("At least one run produced quality warnings; inspect formatting/tag compliance before seam planning.")
    if any("Tighten CouncilBrief synthesis" in run.first_slice for run in all_runs):
        notes.append("Live runs are still converging on brief/provider-health synthesis work, not execution wiring.")
    if any("mock-only" in run.implementation_prompt.lower() and any(s.get("actual_live_any") for s in run.provider_summaries) for run in all_runs):
        notes.append("Some live-seat prompts still collide with mock-only context language; route/prompt context needs refinement.")
    if not notes:
        notes.append("No deterministic quality blockers were detected in the supplied artifacts.")
    lines.extend(f"- {note}" for note in notes)
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv or sys.argv[1:])
    comparisons = [_parse_comparison(raw) for raw in args.comparison]
    smoke_runs = [_parse_smoke(raw) for raw in args.smoke_log]
    report = build_report(comparisons, smoke_runs)
    if args.output:
        out = Path(args.output)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(report, encoding="utf-8")
        print(str(out))
    else:
        print(report, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
