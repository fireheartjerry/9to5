def _canonical(value: object) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _digest(value: object, label: str) -> str:
    if not isinstance(value, str) or _DIGEST_RE.fullmatch(value) is None:
        raise Sha1dcBuildRefused(f"{label} digest is malformed")
    return value


def _positive(value: object, label: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value < 1:
        raise Sha1dcBuildRefused(f"{label} must be a positive integer")
    return value


def readSha1dcSourceLock(path: str | Path) -> Sha1dcSourceLock:
    """Read the canonical exact-source admission lock."""

    location = Path(path)
    try:
        raw = location.read_bytes()
        value = json.loads(raw.decode("utf-8", errors="strict"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise Sha1dcBuildRefused("source lock is not strict JSON") from exc
    canonical_raw = raw[:-1] if raw.endswith(b"\n") else raw
    if (
        raw not in {canonical_raw, canonical_raw + b"\n"}
        or not isinstance(value, dict)
        or _canonical(value) != canonical_raw
        or set(value) != {
        "schema",
        "repository",
        "revision",
        "tree_oid",
        "tree_sha256",
        "license",
        "archive",
        "files",
        }
    ):
        raise Sha1dcBuildRefused("source lock is not canonical and closed")
    if value["schema"] != "galaxy.sha1dc-source-lock/v1" or value["license"] != "MIT":
        raise Sha1dcBuildRefused("source lock schema or license differs")
    revision = value["revision"]
    tree_oid = value["tree_oid"]
    repository = value["repository"]
    if (
        not isinstance(revision, str)
        or _REVISION_RE.fullmatch(revision) is None
        or not isinstance(tree_oid, str)
        or _REVISION_RE.fullmatch(tree_oid) is None
        or repository != "https://github.com/cr-marcstevens/sha1collisiondetection"
    ):
        raise Sha1dcBuildRefused("source repository identity is malformed")
    archive = value["archive"]
    if not isinstance(archive, dict) or set(archive) != {"url", "size", "sha256"}:
        raise Sha1dcBuildRefused("source archive binding is malformed")
    expected_url = f"https://codeload.github.com/cr-marcstevens/sha1collisiondetection/tar.gz/{revision}"
    if archive["url"] != expected_url:
        raise Sha1dcBuildRefused("source archive URL is not revision-exact")
    raw_files = value["files"]
    if not isinstance(raw_files, list):
        raise Sha1dcBuildRefused("source file inventory is malformed")
    files: list[Sha1dcSourceFile] = []
    for item in raw_files:
        if not isinstance(item, dict) or set(item) != {"path", "size", "sha256"}:
            raise Sha1dcBuildRefused("source file record is not closed")
        file_path = item["path"]
        if not isinstance(file_path, str) or file_path not in _SOURCE_PATHS:
            raise Sha1dcBuildRefused("source file path is outside the copied inventory")
        files.append(
            Sha1dcSourceFile(
                path=file_path,
                size=_positive(item["size"], f"source file {file_path} size"),
                sha256=_digest(item["sha256"], f"source file {file_path}"),
            )
        )
    if tuple(item.path for item in files) != _SOURCE_PATHS:
        raise Sha1dcBuildRefused("source file inventory is incomplete or unordered")
    return Sha1dcSourceLock(
        repository=repository,
        revision=revision,
        tree_oid=tree_oid,
        tree_sha256=_digest(value["tree_sha256"], "source tree"),
        archive_url=expected_url,
        archive_size=_positive(archive["size"], "source archive size"),
        archive_sha256=_digest(archive["sha256"], "source archive"),
        files=tuple(files),
        license_sha256=files[0].sha256,
    )


def _passport_time(value: object, label: str) -> datetime:
    if not isinstance(value, str):
        raise Sha1dcBuildRefused(f"source passport {label} is malformed")
    try:
        parsed = datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=UTC)
    except ValueError as exc:
        raise Sha1dcBuildRefused(f"source passport {label} is malformed") from exc
    return parsed


def readSha1dcSourcePassport(
    path: str | Path,
    *,
    source: Sha1dcSourceLock,
    at_time: datetime | None = None,
) -> Sha1dcSourcePassport:
    """Admit one canonical passport bound to the exact source lock and live expiry."""

    location = Path(path)
    try:
        raw = location.read_bytes()
        value = json.loads(raw.decode("utf-8", errors="strict"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise Sha1dcBuildRefused("source passport is not strict JSON") from exc
    canonical_raw = raw[:-1] if raw.endswith(b"\n") else raw
    required_fields = {
        "authority",
        "closed_input_contract",
        "consumer",
        "copied_files",
        "copied_symbols",
        "default_branch",
        "dependency_review",
        "end_to_end_benchmark",
        "expiry",
        "failure_behavior",
        "fetch_time",
        "fetched_tree",
        "independent_oracle",
        "invariant",
        "kill_switch_owner",
        "license_file",
        "repository",
        "revision",
        "rollback",
        "schema",
        "upstream_drift_review",
    }
    if (
        raw not in {canonical_raw, canonical_raw + b"\n"}
        or not isinstance(value, dict)
        or _canonical(value) != canonical_raw
        or set(value) != required_fields
    ):
        raise Sha1dcBuildRefused("source passport is not canonical and closed")
    if (
        value["schema"] != "galaxy.source-passport/v1"
        or value["authority"] != "qualification_only"
    ):
        raise Sha1dcBuildRefused("source passport schema or authority differs")
    if value["repository"] != source.repository or value["revision"] != source.revision:
        raise Sha1dcBuildRefused("source passport does not match the source lock")

    fetched_tree = value["fetched_tree"]
    if (
        not isinstance(fetched_tree, dict)
        or set(fetched_tree) != {"archive_sha256", "git_tree_oid", "tree_listing_sha256"}
        or fetched_tree["archive_sha256"] != source.archive_sha256
        or fetched_tree["git_tree_oid"] != source.tree_oid
        or fetched_tree["tree_listing_sha256"] != source.tree_sha256
    ):
        raise Sha1dcBuildRefused("source passport tree does not match the source lock")
    license_file = value["license_file"]
    if (
        not isinstance(license_file, dict)
        or set(license_file) != {"path", "sha256"}
        or license_file["path"] != "LICENSE.txt"
        or license_file["sha256"] != source.license_sha256
    ):
        raise Sha1dcBuildRefused("source passport license does not match the source lock")

    copied_files = value["copied_files"]
    if copied_files != list(_SOURCE_PATHS[1:]):
        raise Sha1dcBuildRefused("source passport copied-file inventory differs")
    copied_symbols = value["copied_symbols"]
    if copied_symbols != list(_SOURCE_SYMBOLS):
        raise Sha1dcBuildRefused("source passport symbol inventory differs")
    owner = value["kill_switch_owner"]
    if owner != _SOURCE_OWNER:
        raise Sha1dcBuildRefused("source passport owner differs")

    input_contract = value["closed_input_contract"]
    if input_contract != {
        "maximum_payload_bytes": 536870912,
        "object_types": ["blob", "tree", "commit", "tag"],
        "protocol": "galaxy.sha1dc-object-oracle/v1",
        "repository_access": False,
    }:
        raise Sha1dcBuildRefused("source passport input contract differs")
    oracle = value["independent_oracle"]
    if (
        not isinstance(oracle, dict)
        or set(oracle) != {"adversarial_fixture_provenance", "negative_inputs", "normal_inputs"}
        or any(not isinstance(item, str) or not item.strip() for item in oracle.values())
    ):
        raise Sha1dcBuildRefused("source passport independent oracle is incomplete")

    fetched_at = _passport_time(value["fetch_time"], "fetch time")
    expiry = _passport_time(value["expiry"], "expiry")
    observed_at = datetime.now(UTC) if at_time is None else at_time
    if observed_at.tzinfo is None or observed_at.utcoffset() is None:
        raise Sha1dcBuildRefused("source passport verification time must be timezone-aware")
    if fetched_at >= expiry:
        raise Sha1dcBuildRefused("source passport validity interval is malformed")
    if observed_at.astimezone(UTC) >= expiry:
        raise Sha1dcBuildRefused("source passport is expired")
    return Sha1dcSourcePassport(
        repository=source.repository,
        revision=source.revision,
        tree_oid=source.tree_oid,
        tree_sha256=source.tree_sha256,
        archive_sha256=source.archive_sha256,
        license_sha256=source.license_sha256,
        copied_files=tuple(copied_files),
        copied_symbols=tuple(copied_symbols),
        owner=owner,
        fetched_at=fetched_at,
        expiry=expiry,
    )


def acquireSha1dcSource(*, source_lock_path: str | Path, destination: str | Path) -> Path:
    """Perform the one authorized HTTPS acquisition and verify it before publish."""

    source = readSha1dcSourceLock(source_lock_path)
    target = Path(destination)
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name(target.name + ".download")
    if temporary.exists():
        temporary.unlink()
    try:
        with urllib.request.urlopen(source.archive_url, timeout=60) as response:
            if response.geturl() != source.archive_url:
                raise Sha1dcBuildRefused("source acquisition redirected")
            with temporary.open("xb") as stream:
                shutil.copyfileobj(response, stream, length=1024 * 1024)
                stream.flush()
                os.fsync(stream.fileno())
        if (
            temporary.stat().st_size != source.archive_size
            or _sha256_file(temporary) != source.archive_sha256
        ):
            raise Sha1dcBuildRefused("downloaded source archive differs from its lock")
        if target.exists():
            if target.stat().st_size != source.archive_size or _sha256_file(target) != source.archive_sha256:
                raise Sha1dcBuildRefused("source cache contains a conflicting archive")
            temporary.unlink()
        else:
            os.replace(temporary, target)
        return target.resolve(strict=True)
    finally:
        if temporary.exists():
            temporary.unlink()


def _verify_archive(source: Sha1dcSourceLock, archive: Path) -> None:
    try:
        size = archive.stat().st_size
    except OSError as exc:
        raise Sha1dcBuildRefused("source archive is unavailable") from exc
    if size != source.archive_size or _sha256_file(archive) != source.archive_sha256:
        raise Sha1dcBuildRefused("source archive digest or size differs")


def _extract_source(source: Sha1dcSourceLock, archive: Path, destination: Path) -> None:
    prefix = f"sha1collisiondetection-{source.revision}/"
    expected = {item.path: item for item in source.files}
    observed: set[str] = set()
    destination.mkdir(parents=True, exist_ok=False)
    try:
        with tarfile.open(archive, mode="r:gz") as bundle:
            for member in bundle:
                if member.name == prefix[:-1] and member.isdir():
                    continue
                if not member.name.startswith(prefix):
                    raise Sha1dcBuildRefused("source archive has an unexpected root")
                relative = member.name[len(prefix) :]
                if relative not in expected:
                    continue
                path = PurePosixPath(relative)
                if (
                    relative in observed
                    or not member.isfile()
                    or path.is_absolute()
                    or any(part in {"", ".", ".."} for part in path.parts)
                ):
                    raise Sha1dcBuildRefused("source archive contains an unsafe copied leaf")
                record = expected[relative]
                stream = bundle.extractfile(member)
                if stream is None:
                    raise Sha1dcBuildRefused("source archive leaf is unreadable")
                raw = stream.read(record.size + 1)
                if len(raw) != record.size or hashlib.sha256(raw).hexdigest() != record.sha256:
                    raise Sha1dcBuildRefused("source archive leaf differs from its lock")
                target = destination.joinpath(*path.parts)
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(raw)
                observed.add(relative)
    except (OSError, tarfile.TarError) as exc:
        raise Sha1dcBuildRefused("source archive cannot be parsed safely") from exc
    if observed != set(expected):
        raise Sha1dcBuildRefused("source archive omitted a copied leaf")


def _run(
    command: Sequence[str],
    *,
    timeout: float = 300,
    input_bytes: bytes | None = None,
) -> subprocess.CompletedProcess[bytes]:
    if not command or command[0] != "docker":
        raise Sha1dcBuildRefused("offline SHA1DC runner accepts only pinned Docker commands")
    tools = resolvePinnedDockerTools()
    with tempfile.TemporaryDirectory(prefix="galaxy-docker-config-") as config_root:
        result = subprocess.run(
            [str(tools.executable), *command[1:]],
            env=closedDockerEnvironment(Path(config_root)),
            input=input_bytes,
            stdin=subprocess.DEVNULL if input_bytes is None else None,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=timeout,
            check=False,
            shell=False,
        )
    if result.returncode != 0:
        raise Sha1dcBuildRefused(
            "offline SHA1DC command failed: "
            + result.stderr.decode("utf-8", errors="replace")[-2000:]
        )
    return result


def _mount(path: Path, target: str, *, readonly: bool) -> str:
    text = str(path.resolve(strict=True))
    if "," in text:
        raise Sha1dcBuildRefused("builder mount path is not losslessly representable")
    return f"type=bind,source={text},target={target}" + (",readonly" if readonly else "")


def _compile(source_root: Path, output_root: Path) -> Path:
    output_root.mkdir(parents=True, exist_ok=False)
    command = [
        "docker",
        "run",
        "--rm",
        "--network=none",
        "--read-only",
        "--cap-drop=ALL",
        "--security-opt=no-new-privileges:true",
        "--pids-limit=64",
        "--memory=536870912",
        "--cpus=1.0",
        "--tmpfs=/tmp:rw,nosuid,nodev,size=67108864",
        "--mount",
        _mount(source_root, "/src", readonly=True),
        "--mount",
        _mount(output_root, "/out", readonly=False),
        _FULL_BASE,
        "/usr/bin/env",
        "-i",
        "PATH=/usr/bin:/bin",
        "LC_ALL=C",
        "SOURCE_DATE_EPOCH=0",
        "/usr/bin/gcc",
        "-std=c99",
        "-O2",
        "-Wall",
        "-Wextra",
        "-Werror",
        "-pedantic",
        "-fno-ident",
        "-fno-asynchronous-unwind-tables",
        "-ffile-prefix-map=/src=.",
        "-Wl,--build-id=none",
        "-I/src/lib",
        "/src/galaxy_sha1dc.c",
        "/src/lib/sha1.c",
        "/src/lib/ubc_check.c",
        "-o",
        "/out/galaxy-sha1dc",
    ]
    _run(command)
    executable = output_root / "galaxy-sha1dc"
    if not executable.is_file() or executable.stat().st_size < 1024:
        raise Sha1dcBuildRefused("builder did not produce the bounded oracle executable")
    return executable


def _run_oracle(executable: Path, arguments: Sequence[str], payload: bytes = b"") -> bytes:
    command = [
        "docker",
        "run",
        "--rm",
        "--interactive",
        "--network=none",
        "--read-only",
        "--cap-drop=ALL",
        "--security-opt=no-new-privileges:true",
        "--pids-limit=16",
        "--memory=67108864",
        "--cpus=0.5",
        "--mount",
        _mount(executable.parent, "/oracle", readonly=True),
        "--entrypoint",
        "/oracle/galaxy-sha1dc",
        _SLIM_BASE,
        *arguments,
    ]
    result = _run(command, input_bytes=payload, timeout=30)
    if result.returncode != 0 or result.stderr:
        detail = result.stderr.decode("utf-8", errors="replace").strip()
        raise Sha1dcBuildRefused(
            f"built SHA1DC oracle failed its runtime protocol ({result.returncode}): {detail}"
        )
    return result.stdout


def buildSha1dcOracle(
    *,
    source_lock_path: str | Path,
    source_archive: str | Path,
    output_root: str | Path,
) -> Sha1dcBuildEvidence:
    """Compile twice offline, compare bytes, and execute collision/parity canaries."""

    lock_path = Path(source_lock_path).resolve(strict=True)
    archive = Path(source_archive).resolve(strict=True)
    root = Path(output_root).resolve(strict=False)
    if root.exists():
        if not root.is_dir() or root.is_symlink() or any(root.iterdir()):
            raise Sha1dcBuildRefused("oracle output root must be new and empty")
    else:
        root.mkdir(parents=True)
    source = readSha1dcSourceLock(lock_path)
    readSha1dcSourcePassport(_PASSPORT, source=source)
    _verify_archive(source, archive)
    source_root = root / ".source"
    _extract_source(source, archive, source_root)
    shutil.copyfile(_WRAPPER, source_root / "galaxy_sha1dc.c")
    first_root = root / ".build-one"
    second_root = root / ".build-two"
    first = _compile(source_root, first_root)
    second = _compile(source_root, second_root)
    first_raw = first.read_bytes()
    second_raw = second.read_bytes()
    if first_raw != second_raw:
        raise Sha1dcBuildRefused("two offline SHA1DC builds were not reproducible")
    self_test = _run_oracle(first, ["--self-test"])
    if self_test != b"GALAXY_SHA1DC_SELF_TEST/v1 collision-detected normal-sha1-exact\n":
        raise Sha1dcBuildRefused("SHA1DC collision self-test output differs")
    corpus = (
        ("blob", b""),
        ("blob", b"hello\n"),
        ("tree", b"100644 a.txt\0" + bytes.fromhex("0" * 40)),
        ("commit", b"tree " + b"0" * 40 + b"\n\nmessage\n"),
    )
    for object_type, payload in corpus:
        frame = (
            object_type.encode("ascii")
            + b" "
            + str(len(payload)).encode("ascii")
            + b"\0"
            + payload
        )
        expected = hashlib.sha1(frame, usedforsecurity=False).hexdigest().encode("ascii") + b"\n"
        if _run_oracle(first, ["hash-object", object_type, str(len(payload))], payload) != expected:
            raise Sha1dcBuildRefused("SHA1DC normal-object differential corpus differs")
    executable = root / "galaxy-sha1dc"
    shutil.copyfile(first, executable)
    evidence = Sha1dcBuildEvidence(
        executable_path=str(executable.resolve(strict=True)),
        executable_sha256=hashlib.sha256(first_raw).hexdigest(),
        executable_size=len(first_raw),
        source_lock_sha256=_sha256_file(lock_path),
        source_archive_sha256=source.archive_sha256,
        source_passport_sha256=_sha256_file(_PASSPORT),
        wrapper_sha256=_sha256_file(_WRAPPER),
        builder_base_digest=_FULL_BASE.removeprefix("python@sha256:"),
        runtime_base_digest=_SLIM_BASE.removeprefix("python@sha256:"),
        reproducibility_runs=2,
        self_test="collision-detected",
        normal_object_corpus_count=len(corpus),
        network_allowed=False,
    )
    (root / "sha1dc-build-evidence.json").write_bytes(_canonical(evidence.toDict()))
    for staging in (source_root, first_root, second_root):
        shutil.rmtree(staging)
    return evidence


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="build_sha1dc_oracle")
    parser.add_argument("--source-lock", type=Path, required=True)
    actions = parser.add_mutually_exclusive_group(required=True)
    actions.add_argument("--acquire", action="store_true")
    actions.add_argument("--build", action="store_true")
    parser.add_argument("--source-archive", type=Path, required=True)
    parser.add_argument("--output-root", type=Path)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    if args.acquire:
        if args.output_root is not None:
            raise Sha1dcBuildRefused("source acquisition does not accept an output root")
        print(acquireSha1dcSource(source_lock_path=args.source_lock, destination=args.source_archive))
        return 0
    if args.output_root is None:
        raise Sha1dcBuildRefused("offline build requires --output-root")
    evidence = buildSha1dcOracle(
        source_lock_path=args.source_lock,
        source_archive=args.source_archive,
        output_root=args.output_root,
    )
    print(json.dumps(evidence.toDict(), indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
