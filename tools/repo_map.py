"""repo_map -- generate the 9to5 AI-navigation layer from the source AST.

Writes three DETERMINISTIC artifacts: @AI-MAP header blocks (spliced into each module's
docstring), .repo-map.json (machine index), and AGENTS.md files (human+LLM index).
The only source mutation is inside module docstring literals -- runtime behaviour unchanged.
Rendering helpers are in repo_map_render.py; write/check logic is in repo_map_outputs.py.

Usage:
  python tools/repo_map.py [--only agents] [--check] [--no-headers]

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  is_test_path(path: Path) -> bool  -- True for files under the test trees (see TEST_TOP_DIRS): never mapped, never spliced.
  iter_py_files(only: Optional[str]=None) -> list[Path]  -- All first-party .py files (sorted, deterministic), skipping EXCLUDE_DIRS
  validate_header_prefix(value: Optional[str]) -> str  -- Return one canonical, narrow, repository-relative directory prefix.
  iter_header_files(prefix: str) -> list[Path]  -- Python leaves under one validated prefix, including reviewed untracked leaves.
  module_dotted(path: Path) -> str  -- agents/adversary.py -> 'agents.adversary'
  first_party_roots() -> set[str]  -- Top-level importable names: every top-level .py stem + every dir holding an __init__.py.
  parse_module(path: Path, roots: set[str]) -> dict  -- Extract the per-module record (sans callers, which are computed globally).
  find_tests(dotted: str, name: str) -> list[str]  -- Resolve a module's covering tests: MANUAL_TEST_MAP -> exact -> prefix exact -> glob -> …
  build_map(only: Optional[str]=None) -> dict  -- Full-repo machine index
  toplevel_import_graph() -> dict[str, list[str]]  -- {dotted-module: [first-party modules imported at LOAD time]}
  render_header(rec: dict) -> str  -- Render the @AI-MAP block (text only, no surrounding quotes).
  splice_header(src: str, header: str) -> Optional[str]  -- Return ``src`` with ``header`` placed inside the module docstring (below the prose,
  write_outputs(*, check: bool, only: Optional[str], no_headers: bool, headers_only: bool=False) -> int  -- Write (or --check) all artifacts
  main(argv: Optional[list[str]]=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/platform/test_repo_map.py
"""

from __future__ import annotations

# ==== IMPORTS ====
import argparse
import ast
import subprocess
import sys
from pathlib import Path, PurePosixPath
from typing import Optional

# Header-only closure generation promises not to mutate anything outside the
# requested source prefix.  Import caches would violate that promise.
sys.dont_write_bytecode = True

# Rendering helpers live in repo_map_render (no import of repo_map there -> no circular).
# Re-exported here so callers can do `from repo_map import render_root_agents_md`.
from repo_map_render import render_root_agents_md, render_package_agents_md  # noqa: F401

# MANUAL_TEST_MAP is pure data (dotted-module -> covering tests); lives in its own module
# so this facade stays under the size-audit line budget. Re-exported here so callers can do
# `from repo_map import MANUAL_TEST_MAP` unchanged.
from repo_map_test_map import MANUAL_TEST_MAP  # noqa: F401

# ==== CONSTANTS ====
REPO_ROOT = Path(__file__).resolve().parent.parent
TESTS_DIR = REPO_ROOT / "tests"
JSON_PATH = REPO_ROOT / ".repo-map.json"
ROOT_AGENTS = REPO_ROOT / "AGENTS.md"
SCHEMA = "ai-map/1"

HEADER_SENTINEL = "@AI-MAP v1"
HEADER_TITLE = (
    f"{HEADER_SENTINEL}  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)"
)
SIDE_EFFECTS_PLACEHOLDER = "unannotated"
REMEDIATION = "Run:  python tools/repo_map.py"

# Directories never scanned (runtime data, vendored, build caches, docs). Must cover every
# gitignored dir that can hold stray .py files on a dev box, else a local regeneration bakes
# them into .repo-map.json and the CI drift check fails on a fresh checkout.
EXCLUDE_DIRS = {
    "venv",
    ".venv",
    ".git",
    "__pycache__",
    ".claude",
    ".pytest_cache",
    ".sc-ctx",
    "test-run",
    "test-run2",
    "test-run3",
    "vault",
    "logs",
    "docs",
    "node_modules",
    ".github",
    "references",
    ".superpowers",
}

# Top-level dirs holding test code: indexed NEVER, header-spliced NEVER. Test files carry
# no AI-MAP value and a bad splice there corrupted the suite (2026-07 incident); both
# build_map and the write/splice path in repo_map_outputs honor this via is_test_path().
TEST_TOP_DIRS = ("tests", "testing")


# ==== FILE DISCOVERY ====
def _git_tracked_py_files() -> Optional[list[Path]]:
    """Git-tracked ``*.py`` paths under REPO_ROOT, or None when git is unavailable / not a repo.

    Tracked-only discovery keeps untracked scratch files and nested worktree clones (a second
    orchestrator.py/config.py + its own tests/, e.g. fable-rewrite/) out of the map -- a filesystem
    walk pulls those in and produces phantom modules / drift. EXCLUDE_DIRS filtering still applies."""
    try:
        proc = subprocess.run(
            ["git", "-C", str(REPO_ROOT), "ls-files", "-z", "--", "*.py"],
            capture_output=True,
            text=True,
            timeout=30,
        )
    except Exception:  # noqa: BLE001 -- git missing / not installed
        return None
    if proc.returncode != 0:
        return None
    return [REPO_ROOT / rel for rel in proc.stdout.split("\0") if rel]


def is_test_path(path: Path) -> bool:
    """True for files under the test trees (see TEST_TOP_DIRS): never mapped, never spliced."""
    return path.relative_to(REPO_ROOT).parts[0] in TEST_TOP_DIRS


def iter_py_files(only: Optional[str] = None) -> list[Path]:
    """All first-party .py files (sorted, deterministic), skipping EXCLUDE_DIRS. ``only`` limits
    to one or more comma-separated top-level path prefixes (e.g. 'agents' or 'agents,tools').

    Discovery uses the git-tracked set so untracked scratch/worktree clones never enter the map;
    falls back to a filesystem walk when git is unavailable (old/partial checkout)."""
    prefixes = [s.strip().rstrip("/") for s in only.split(",")] if only else []
    tracked = _git_tracked_py_files()
    candidates = tracked if tracked is not None else list(REPO_ROOT.rglob("*.py"))
    out: list[Path] = []
    for p in candidates:
        try:
            rel = p.relative_to(REPO_ROOT)
        except ValueError:
            continue
        if any(part in EXCLUDE_DIRS for part in rel.parts):
            continue
            continue
        if prefixes and rel.parts[0] not in prefixes:
            continue
        if not p.exists():  # a tracked-but-locally-deleted file must not break parsing
            continue
        out.append(p)
    return sorted(out)


def validate_header_prefix(value: Optional[str]) -> str:
    """Return one canonical, narrow, repository-relative directory prefix."""
    if not value or value.strip() != value or "\\" in value or "," in value:
        raise ValueError("--headers-only requires one canonical repository-relative prefix")
    prefix = PurePosixPath(value)
    if (prefix.is_absolute() or value in {".", ".."} or value.startswith("//")
            or ":" in prefix.parts[0]
            or any(part in {"", ".", ".."} for part in prefix.parts)
            or prefix.as_posix() != value.rstrip("/")):
        raise ValueError("--headers-only prefix is absolute, broad, or contains traversal")
    target = REPO_ROOT.joinpath(*prefix.parts)
    try:
        resolved = target.resolve(strict=True)
        resolved.relative_to(REPO_ROOT.resolve(strict=True))
    except (OSError, ValueError) as exc:
        raise ValueError("--headers-only prefix must name a repository directory") from exc
    if not resolved.is_dir() or resolved == REPO_ROOT.resolve(strict=True):
        raise ValueError("--headers-only prefix must be a narrow repository directory")
    for component in (target, *target.parents):
        if component == REPO_ROOT.parent:
            break
        if component.exists() and component.is_symlink():
            raise ValueError("--headers-only prefix may not traverse a symlink")
    return prefix.as_posix()


def iter_header_files(prefix: str) -> list[Path]:
    """Python leaves under one validated prefix, including reviewed untracked leaves."""
    normalized = validate_header_prefix(prefix)
    target = REPO_ROOT.joinpath(*PurePosixPath(normalized).parts)
    result: list[Path] = []
    for path in target.rglob("*.py"):
        rel = path.relative_to(REPO_ROOT)
        if any(part in EXCLUDE_DIRS for part in rel.parts) or is_test_path(path):
            continue
        if path.is_symlink() or not path.is_file():
            raise ValueError(f"header source leaf is not a regular no-follow file: {rel.as_posix()}")
        result.append(path)
    return sorted(result)


def module_dotted(path: Path) -> str:
    """agents/adversary.py -> 'agents.adversary'; pkg/__init__.py -> 'pkg'."""
    rel = path.relative_to(REPO_ROOT).with_suffix("")
    parts = [p for p in rel.parts if p != "__init__"]
    return ".".join(parts) if parts else rel.parts[0]


def first_party_roots() -> set[str]:
    """Top-level importable names: every top-level .py stem + every dir holding an __init__.py."""
    roots: set[str] = set()
    for child in REPO_ROOT.iterdir():
        if child.is_file() and child.suffix == ".py":
            roots.add(child.stem)
        elif child.is_dir() and child.name not in EXCLUDE_DIRS and (child / "__init__.py").exists():
            roots.add(child.name)
    return roots


# ==== AST PARSING ====
def _first_sentence(doc: Optional[str], limit: int = 88) -> str:
    """First sentence/line of a docstring, collapsed + truncated. '' if none."""
    if not doc:
        return ""
    line = doc.strip().split("\n", 1)[0].strip()
    for sep in (". ", " -- ", "; "):
        if sep in line:
            line = line.split(sep, 1)[0]
            break
    return (line[: limit - 1] + "…") if len(line) > limit else line


def _module_purpose(tree: ast.Module) -> str:
    """First line of the module docstring, taken from BEFORE the @AI-MAP sentinel."""
    doc = ast.get_docstring(tree, clean=False) or ""
    before = doc.split(HEADER_SENTINEL, 1)[0]
    return before.strip().split("\n", 1)[0].strip()


def _existing_side_effects(tree: ast.Module) -> Optional[str]:
    """Preserve a human-authored SIDE-EFFECTS line from an existing header, if present."""
    doc = ast.get_docstring(tree, clean=False) or ""
    for line in doc.splitlines():
        s = line.strip()
        if s.startswith("SIDE-EFFECTS:"):
            return s[len("SIDE-EFFECTS:") :].strip()
    return None


def _public_names(tree: ast.Module) -> Optional[set[str]]:
    """Members of __all__ if the module defines it, else None (=> default '_'-prefix rule)."""
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == "__all__":
                    try:
                        val = ast.literal_eval(node.value)
                        return {str(x) for x in val}
                    except Exception:  # noqa: BLE001
                        return None
    return None


def _signature(node: ast.AST) -> str:
    """Condensed signature for a function (args + return), '' for a class."""
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        try:
            args = ast.unparse(node.args)
        except Exception:  # noqa: BLE001
            args = "..."
        ret = ""
        if node.returns is not None:
            try:
                ret = " -> " + ast.unparse(node.returns)
            except Exception:  # noqa: BLE001
                ret = ""
        return f"({args}){ret}"
    return ""


def _exports(tree: ast.Module) -> list[dict]:
    """Public top-level functions/classes (honoring __all__), in source order."""
    allowed = _public_names(tree)
    out: list[dict] = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            name = node.name
            public = (name in allowed) if allowed is not None else not name.startswith("_")
            if not public:
                continue
            out.append(
                {
                    "name": name,
                    "kind": "class" if isinstance(node, ast.ClassDef) else "function",
                    "signature": _signature(node),
                    "summary": _first_sentence(ast.get_docstring(node)),
                    "lineno": node.lineno,
                }
            )
    return out


def _depends_on(tree: ast.Module, roots: set[str], *, toplevel_only: bool = False) -> list[str]:
    """First-party modules imported, sorted+deduped. ``toplevel_only`` = load-time graph only."""
    deps: set[str] = set()
    nodes = tree.body if toplevel_only else list(ast.walk(tree))
    for node in nodes:
        if isinstance(node, ast.Import):
            for alias in node.names:
                top = alias.name.split(".")[0]
                if top in roots:
                    deps.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            if node.level:  # relative import
                continue
            mod = node.module or ""
            top = mod.split(".")[0]
            if top in roots:
                # `from agents import executor` -> agents.executor; `from config import X` -> config
                if mod in roots:
                    for alias in node.names:
                        deps.add(f"{mod}.{alias.name}")
                else:
                    deps.add(mod)
    return sorted(deps)


def _read_source(path: Path) -> str:
    """Read source normalised: strip UTF-8 BOM + fold CRLF->LF for byte-stable drift checks."""
    return path.read_text(encoding="utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")


def parse_module(path: Path, roots: set[str]) -> dict:
    """Extract the per-module record (sans callers, which are computed globally)."""
    src = _read_source(path)
    tree = ast.parse(src)
    dotted = module_dotted(path)
    se = _existing_side_effects(tree)
    return {
        "path": str(path.relative_to(REPO_ROOT)).replace("\\", "/"),
        "purpose": _module_purpose(tree),
        "exports": _exports(tree),
        "depends_on": _depends_on(tree, roots),
        "side_effects": [s.strip() for s in se.split(";")] if se else [SIDE_EFFECTS_PLACEHOLDER],
        "test": find_tests(dotted, path.stem),
        "callers": [],  # filled by build_map
    }


# ==== TEST MAPPING ====
def find_tests(dotted: str, name: str) -> list[str]:
    """Resolve a module's covering tests: MANUAL_TEST_MAP -> exact -> prefix exact -> glob -> []."""
    if dotted in MANUAL_TEST_MAP:
        return sorted(MANUAL_TEST_MAP[dotted])
    if not TESTS_DIR.exists():
        return []
    exact = sorted(TESTS_DIR.rglob(f"test_{name}.py"))
    if exact:
        return [f"tests/{p.relative_to(TESTS_DIR).as_posix()}" for p in exact]
    parts = name.split("_")
    for size in range(len(parts) - 1, 0, -1):
        prefix = "_".join(parts[:size])
        if len(prefix) < 4:
            continue
        prefix_exact = sorted(TESTS_DIR.rglob(f"test_{prefix}.py"))
        if prefix_exact:
            return [f"tests/{p.relative_to(TESTS_DIR).as_posix()}" for p in prefix_exact]
    hits = sorted(TESTS_DIR.rglob(f"test_*{name}*.py"))
    return [f"tests/{p.relative_to(TESTS_DIR).as_posix()}" for p in hits]


# ==== MAP ASSEMBLY ====
def build_map(only: Optional[str] = None) -> dict:
    """Full-repo machine index. ``only`` is ignored for the map (always full) -- it only scopes
    header splicing in write_outputs."""
    roots = first_party_roots()
    modules: dict[str, dict] = {}
    skipped: list[str] = []
    for path in iter_py_files():
        # Tests excluded: reached via RUN/TEST lines; excluding keeps callers = production consumers.
        if is_test_path(path):
            continue
        try:
            modules[module_dotted(path)] = parse_module(path, roots)
        except SyntaxError as e:  # a single unparseable file must not break the whole map
            skipped.append(f"{path.relative_to(REPO_ROOT)} ({e.msg})")
    if skipped:
        print(
            f"[repo_map] skipped {len(skipped)} unparseable file(s): "
            + ", ".join(skipped[:6])
            + ("..." if len(skipped) > 6 else ""),
            file=sys.stderr,
        )
    for dotted, rec in modules.items():
        callers = sorted(m for m, r in modules.items() if dotted in r["depends_on"])
        rec["callers"] = callers
    return {
        "schema": SCHEMA,
        "generated_by": "tools/repo_map.py",
        "root": "9to5",  # stable id; NOT REPO_ROOT.name (varies across worktrees/CI clones)
        "first_party_roots": sorted(roots),
        "modules": {k: modules[k] for k in sorted(modules)},
    }


def toplevel_import_graph() -> dict[str, list[str]]:
    """{dotted-module: [first-party modules imported at LOAD time]} -- the load-time dependency
    graph used by the layering/cycle guard test. Excludes lazy in-function imports by design."""
    roots = first_party_roots()
    graph: dict[str, list[str]] = {}
    for path in iter_py_files():
        try:
            tree = ast.parse(_read_source(path))
        except SyntaxError:
            continue
        graph[module_dotted(path)] = _depends_on(tree, roots, toplevel_only=True)
    return graph


# ==== HEADER RENDER + SPLICE (the only source mutation) ====
def render_header(rec: dict) -> str:
    """Render the @AI-MAP block (text only, no surrounding quotes)."""
    lines = [HEADER_TITLE, "EXPORTS:"]
    if rec["exports"]:
        for e in rec["exports"]:
            sig = e["signature"] or ""
            summ = f"  -- {e['summary']}" if e["summary"] else ""
            lines.append(f"  {e['name']}{sig}{summ}")
    else:
        lines.append("  (no public exports)")
    lines.append("DEPENDS-ON: " + (", ".join(rec["depends_on"]) or "(stdlib only)"))
    lines.append("SIDE-EFFECTS: " + "; ".join(rec["side_effects"]))
    lines.append(
        "RUN/TEST: " + ("python -m pytest " + " ".join(rec["test"]) if rec["test"] else "(no mapped test)")
    )
    return "\n".join(lines)


def _char_offset(lines: list[str], lineno: int, col_bytes: int) -> int:
    """Char offset into the joined source for an AST (lineno, col_offset) position.
    AST col offsets are UTF-8 BYTE offsets, not char offsets -- treating them as chars
    overshoots on any line holding non-ASCII (em-dash docstrings) and ate the first
    chars after the docstring ('\"\"\"mport'), corrupting 5 committed test files."""
    prefix = sum(len(lines[i]) for i in range(lineno - 1))
    line = lines[lineno - 1]
    return prefix + len(line.encode("utf-8")[:col_bytes].decode("utf-8"))


def splice_header(src: str, header: str) -> Optional[str]:
    """Return ``src`` with ``header`` placed inside the module docstring (below the prose,
    replacing any prior @AI-MAP block). None if the module has no docstring (caller flags it).
    Mutates ONLY the docstring literal -- nothing executable changes; the result is re-parsed
    so a bad splice can never produce an uncompilable file."""
    tree = ast.parse(src)
    if not (
        tree.body
        and isinstance(tree.body[0], ast.Expr)
        and isinstance(tree.body[0].value, ast.Constant)
        and isinstance(tree.body[0].value.value, str)
    ):
        return None
    node = tree.body[0].value
    assert isinstance(node, ast.Constant)
    assert isinstance(node.value, str)
    assert node.end_lineno is not None
    assert node.end_col_offset is not None
    content = node.value  # the docstring's string value (unescaped)
    prose = content.split(HEADER_SENTINEL, 1)[0].rstrip()
    new_content = f"{prose}\n\n{header}\n"
    # Compute char offsets of the docstring literal in the raw source via line/col.
    lines = src.splitlines(keepends=True)
    start = _char_offset(lines, node.lineno, node.col_offset)
    end = _char_offset(lines, node.end_lineno, node.end_col_offset)
    # Escape backslashes so Windows paths in prose/RUN-TEST lines (e.g. venv\Scripts, C:\9to5)
    # do not become invalid escape sequences (W605) in the emitted non-raw docstring. This is
    # value-preserving: ast.get_docstring unescapes them back to single backslashes on re-read,
    # so header extraction and the drift check stay byte-stable across regenerations.
    literal_body = new_content.replace("\\", "\\\\")
    new_literal = '"""' + literal_body + '"""'
    out = src[:start] + new_literal + src[end:]
    ast.parse(out)  # hard guarantee: raise loudly instead of writing a corrupt file
    return out


# ==== WRITE / CHECK (implementation: tools/repo_map_outputs.py) ====
def write_outputs(
    *, check: bool, only: Optional[str], no_headers: bool, headers_only: bool = False
) -> int:
    """Write (or --check) all artifacts. Thin wrapper; implementation in repo_map_outputs.

    The wrapper exists to break the circular import: repo_map_outputs imports build_map,
    iter_py_files, etc. from repo_map at module level. If repo_map also imported
    repo_map_outputs at module level, loading repo_map as __main__ would deadlock (Python
    would return a partially-initialised repo_map_outputs to repo_map before write_outputs
    is defined). Lazy import here avoids that."""
    import repo_map_outputs as _ro  # noqa: PLC0415 (lazy: breaks circular when __main__)

    return _ro.write_outputs(
        check=check, only=only, no_headers=no_headers, headers_only=headers_only
    )


# ==== CLI ====
def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the 9to5 AI-navigation layer.")
    ap.add_argument("--check", action="store_true", help="dry-run; exit 1 on drift")
    ap.add_argument("--only", default=None, help="splice headers only under this path prefix (e.g. agents)")
    ap.add_argument("--no-headers", action="store_true", help="write index only, skip header splicing")
    ap.add_argument(
        "--headers-only", action="store_true",
        help="splice/check only one narrow --only prefix; never touch maps or AGENTS files",
    )
    args = ap.parse_args(argv)
    if args.headers_only:
        if args.no_headers:
            ap.error("--headers-only cannot be combined with --no-headers")
        try:
            args.only = validate_header_prefix(args.only)
        except ValueError as exc:
            ap.error(str(exc))
    return write_outputs(
        check=args.check,
        only=args.only,
        no_headers=args.no_headers,
        headers_only=args.headers_only,
    )


if __name__ == "__main__":
    raise SystemExit(main())
