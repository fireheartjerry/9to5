"""repo_map -- generate the 9to5 AI-navigation layer from the source AST.

Single source of truth for three artifacts, all DETERMINISTIC (byte-stable) so a drift test
(tests/test_repo_map.py) can assert the committed copies are current:

  * `@AI-MAP` header block spliced into each module's docstring (EXPORTS/DEPENDS-ON/SIDE-EFFECTS/
    RUN-TEST) -- everything is AST-derived EXCEPT SIDE-EFFECTS, which is human-authored and
    PRESERVED across regeneration (heuristics give too many false pos/neg).
  * `.repo-map.json` (root) -- the machine index: per-module purpose, exports (name/kind/
    signature/summary/lineno), depends_on, side_effects, test, callers (reverse import edges).
  * `AGENTS.md` (root) + per-package `AGENTS.md` -- the human+LLM readable index.

The ONLY mutation to source files happens inside the module docstring literal (splice_header),
so module runtime behaviour is provably unchanged. Pure stdlib (ast) -- no third-party deps.

Usage:
  python tools/repo_map.py                # write all artifacts; splice headers into all modules
  python tools/repo_map.py --only agents  # ...but splice headers only under agents/ (pilot)
  python tools/repo_map.py --check        # dry-run; exit 1 on drift, print remediation

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  iter_py_files(only: Optional[str]=None) -> list[Path]  -- All first-party .py files (sorted, deterministic), skipping EXCLUDE_DIRS
  module_dotted(path: Path) -> str  -- agents/adversary.py -> 'agents.adversary'
  first_party_roots() -> set[str]  -- Top-level importable names: every top-level .py stem + every dir holding an __init__.py.
  parse_module(path: Path, roots: set[str]) -> dict  -- Extract the per-module record (sans callers, which are computed globally).
  find_tests(dotted: str, name: str) -> list[str]  -- Resolve a module's covering tests: MANUAL_TEST_MAP -> exact -> glob -> [].
  build_map(only: Optional[str]=None) -> dict  -- Full-repo machine index
  toplevel_import_graph() -> dict[str, list[str]]  -- {dotted-module: [first-party modules imported at LOAD time]}
  render_header(rec: dict) -> str  -- Render the @AI-MAP block (text only, no surrounding quotes).
  splice_header(src: str, header: str) -> Optional[str]  -- Return ``src`` with ``header`` placed inside the module docstring (below the prose,
  render_root_agents_md(m: dict) -> str
  render_package_agents_md(m: dict, pkg: str) -> str
  write_outputs(*, check: bool, only: Optional[str], no_headers: bool) -> int  -- Write (or --check) all artifacts
  main(argv: Optional[list[str]]=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_repo_map.py
"""
from __future__ import annotations

# ==== IMPORTS ====
import argparse
import ast
import json
import sys
from pathlib import Path
from typing import Optional

# ==== CONSTANTS ====
REPO_ROOT = Path(__file__).resolve().parent.parent
TESTS_DIR = REPO_ROOT / "tests"
JSON_PATH = REPO_ROOT / ".repo-map.json"
ROOT_AGENTS = REPO_ROOT / "AGENTS.md"
SCHEMA = "ai-map/1"

HEADER_SENTINEL = "@AI-MAP v1"
HEADER_TITLE = f"{HEADER_SENTINEL}  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)"
SIDE_EFFECTS_PLACEHOLDER = "unannotated"
REMEDIATION = "Run:  python tools/repo_map.py"

# Directories never scanned (runtime data, vendored, build caches, docs).
EXCLUDE_DIRS = {
    "venv", ".git", "__pycache__", ".claude", ".pytest_cache", ".sc-ctx",
    "test-run", "test-run2", "vault", "logs", "docs", "node_modules", ".github",
}

# Modules whose covering test is not tests/test_<name>.py. dotted-module -> [test paths].
MANUAL_TEST_MAP: dict[str, list[str]] = {
    "agents.second_brain": ["tests/test_phase2_second_brain.py"],
    "agents.architect": ["tests/test_phase_3_architecture.py"],
    "agents.chatgpt_driver": ["tests/test_chatgpt_driver.py", "tests/test_chatgpt_e2e_offline.py"],
    "agents.browser_executor": ["tests/test_browser_executor.py", "tests/test_phase2_cdp_adversary.py"],
}


# ==== FILE DISCOVERY ====
def iter_py_files(only: Optional[str] = None) -> list[Path]:
    """All first-party .py files (sorted, deterministic), skipping EXCLUDE_DIRS. ``only`` limits
    to one or more comma-separated top-level path prefixes (e.g. 'agents' or 'agents,tools')."""
    prefixes = [s.strip().rstrip("/") for s in only.split(",")] if only else []
    out: list[Path] = []
    for p in sorted(REPO_ROOT.rglob("*.py")):
        rel = p.relative_to(REPO_ROOT)
        if any(part in EXCLUDE_DIRS for part in rel.parts):
            continue
        if prefixes and rel.parts[0] not in prefixes:
            continue
        out.append(p)
    return out


def module_dotted(path: Path) -> str:
    """agents/adversary.py -> 'agents.adversary'; pkg/__init__.py -> 'pkg'."""
    rel = path.relative_to(REPO_ROOT).with_suffix("")
    parts = [p for p in rel.parts if p != "__init__"]
    return ".".join(parts) if parts else rel.parts[0]


def first_party_roots() -> set[str]:
    """Top-level importable names: every top-level .py stem + every dir holding an __init__.py."""
    roots: set[str] = set()
    for child in REPO_ROOT.iterdir():
        if child.is_file() and child.suffix == ".py":
            roots.add(child.stem)
        elif child.is_dir() and child.name not in EXCLUDE_DIRS and (child / "__init__.py").exists():
            roots.add(child.name)
    return roots


# ==== AST PARSING ====
def _first_sentence(doc: Optional[str], limit: int = 88) -> str:
    """First sentence/line of a docstring, collapsed + truncated. '' if none."""
    if not doc:
        return ""
    line = doc.strip().split("\n", 1)[0].strip()
    for sep in (". ", " -- ", "; "):
        if sep in line:
            line = line.split(sep, 1)[0]
            break
    return (line[: limit - 1] + "…") if len(line) > limit else line


def _module_purpose(tree: ast.Module) -> str:
    """First line of the module docstring, taken from BEFORE the @AI-MAP sentinel."""
    doc = ast.get_docstring(tree, clean=False) or ""
    before = doc.split(HEADER_SENTINEL, 1)[0]
    return before.strip().split("\n", 1)[0].strip()


def _existing_side_effects(tree: ast.Module) -> Optional[str]:
    """Preserve a human-authored SIDE-EFFECTS line from an existing header, if present."""
    doc = ast.get_docstring(tree, clean=False) or ""
    for line in doc.splitlines():
        s = line.strip()
        if s.startswith("SIDE-EFFECTS:"):
            return s[len("SIDE-EFFECTS:"):].strip()
    return None


def _public_names(tree: ast.Module) -> Optional[set[str]]:
    """Members of __all__ if the module defines it, else None (=> default '_'-prefix rule)."""
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == "__all__":
                    try:
                        val = ast.literal_eval(node.value)
                        return {str(x) for x in val}
                    except Exception:  # noqa: BLE001
                        return None
    return None


def _signature(node: ast.AST) -> str:
    """Condensed signature for a function (args + return), '' for a class."""
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        try:
            args = ast.unparse(node.args)
        except Exception:  # noqa: BLE001
            args = "..."
        ret = ""
        if node.returns is not None:
            try:
                ret = " -> " + ast.unparse(node.returns)
            except Exception:  # noqa: BLE001
                ret = ""
        return f"({args}){ret}"
    return ""


def _exports(tree: ast.Module) -> list[dict]:
    """Public top-level functions/classes (honoring __all__), in source order."""
    allowed = _public_names(tree)
    out: list[dict] = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            name = node.name
            public = (name in allowed) if allowed is not None else not name.startswith("_")
            if not public:
                continue
            out.append({
                "name": name,
                "kind": "class" if isinstance(node, ast.ClassDef) else "function",
                "signature": _signature(node),
                "summary": _first_sentence(ast.get_docstring(node)),
                "lineno": node.lineno,
            })
    return out


def _depends_on(tree: ast.Module, roots: set[str], *, toplevel_only: bool = False) -> list[str]:
    """First-party modules imported, sorted+deduped. By default includes in-function (lazy)
    imports; ``toplevel_only`` restricts to module-level imports = the LOAD-TIME graph (lazy
    imports are the deliberate cycle-break escape hatch, so the layering guard uses this)."""
    deps: set[str] = set()
    nodes = tree.body if toplevel_only else list(ast.walk(tree))
    for node in nodes:
        if isinstance(node, ast.Import):
            for alias in node.names:
                top = alias.name.split(".")[0]
                if top in roots:
                    deps.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            if node.level:  # relative import
                continue
            mod = node.module or ""
            top = mod.split(".")[0]
            if top in roots:
                # `from agents import executor` -> agents.executor; `from config import X` -> config
                if mod in roots:
                    for alias in node.names:
                        deps.add(f"{mod}.{alias.name}")
                else:
                    deps.add(mod)
    return sorted(deps)


def _read_source(path: Path) -> str:
    """Read source, normalized for stable comparison: strip a leading UTF-8 BOM (some files carry
    one; ast.parse rejects it) and fold CRLF/CR -> LF so the drift test never trips on a Windows
    autocrlf checkout (the generator always writes LF)."""
    return path.read_text(encoding="utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")


def parse_module(path: Path, roots: set[str]) -> dict:
    """Extract the per-module record (sans callers, which are computed globally)."""
    src = _read_source(path)
    tree = ast.parse(src)
    dotted = module_dotted(path)
    se = _existing_side_effects(tree)
    return {
        "path": str(path.relative_to(REPO_ROOT)).replace("\\", "/"),
        "purpose": _module_purpose(tree),
        "exports": _exports(tree),
        "depends_on": _depends_on(tree, roots),
        "side_effects": [s.strip() for s in se.split(";")] if se else [SIDE_EFFECTS_PLACEHOLDER],
        "test": find_tests(dotted, path.stem),
        "callers": [],  # filled by build_map
    }


# ==== TEST MAPPING ====
def find_tests(dotted: str, name: str) -> list[str]:
    """Resolve a module's covering tests: MANUAL_TEST_MAP -> exact -> glob -> []."""
    if dotted in MANUAL_TEST_MAP:
        return sorted(MANUAL_TEST_MAP[dotted])
    exact = TESTS_DIR / f"test_{name}.py"
    if exact.exists():
        return [f"tests/test_{name}.py"]
    hits = sorted(p for p in TESTS_DIR.glob(f"test_*{name}*.py")) if TESTS_DIR.exists() else []
    return [f"tests/{p.name}" for p in hits]


# ==== MAP ASSEMBLY ====
def build_map(only: Optional[str] = None) -> dict:
    """Full-repo machine index. ``only`` is ignored for the map (always full) -- it only scopes
    header splicing in write_outputs."""
    roots = first_party_roots()
    modules: dict[str, dict] = {}
    skipped: list[str] = []
    for path in iter_py_files():
        # The map indexes PRODUCTION code (what agents navigate + edit for features). Tests are
        # excluded -- they're reached via each module's RUN/TEST line, and excluding them keeps
        # `callers` = real production consumers AND avoids a map regen on every test edit (TDD
        # churns tests constantly; that friction would defeat the iteration-speed goal).
        if path.relative_to(REPO_ROOT).parts[0] in ("tests", "testing"):
            continue
        try:
            modules[module_dotted(path)] = parse_module(path, roots)
        except SyntaxError as e:  # a single unparseable file must not break the whole map
            skipped.append(f"{path.relative_to(REPO_ROOT)} ({e.msg})")
    if skipped:
        print(f"[repo_map] skipped {len(skipped)} unparseable file(s): "
              + ", ".join(skipped[:6]) + ("..." if len(skipped) > 6 else ""), file=sys.stderr)
    # callers = reverse of depends_on, at module granularity (reliable blast-radius).
    for dotted, rec in modules.items():
        callers = sorted(m for m, r in modules.items() if dotted in r["depends_on"])
        rec["callers"] = callers
    return {
        "schema": SCHEMA,
        "generated_by": "tools/repo_map.py",
        # Stable project identifier -- NOT REPO_ROOT.name, which is the checkout *directory*
        # basename and varies across worktrees/clones/CI (e.g. "9to5-final"), making the
        # byte-compared drift test fail anywhere the folder isn't literally "9to5".
        "root": "9to5",
        "first_party_roots": sorted(roots),
        "modules": {k: modules[k] for k in sorted(modules)},
    }


def toplevel_import_graph() -> dict[str, list[str]]:
    """{dotted-module: [first-party modules imported at LOAD time]} -- the load-time dependency
    graph used by the layering/cycle guard test. Excludes lazy in-function imports by design."""
    roots = first_party_roots()
    graph: dict[str, list[str]] = {}
    for path in iter_py_files():
        try:
            tree = ast.parse(_read_source(path))
        except SyntaxError:
            continue
        graph[module_dotted(path)] = _depends_on(tree, roots, toplevel_only=True)
    return graph


# ==== HEADER RENDER + SPLICE (the only source mutation) ====
def render_header(rec: dict) -> str:
    """Render the @AI-MAP block (text only, no surrounding quotes)."""
    lines = [HEADER_TITLE, "EXPORTS:"]
    if rec["exports"]:
        for e in rec["exports"]:
            sig = e["signature"] or ""
            summ = f"  -- {e['summary']}" if e["summary"] else ""
            lines.append(f"  {e['name']}{sig}{summ}")
    else:
        lines.append("  (no public exports)")
    lines.append("DEPENDS-ON: " + (", ".join(rec["depends_on"]) or "(stdlib only)"))
    lines.append("SIDE-EFFECTS: " + "; ".join(rec["side_effects"]))
    lines.append("RUN/TEST: " + ("python -m pytest " + " ".join(rec["test"]) if rec["test"]
                                  else "(no mapped test)"))
    return "\n".join(lines)


def splice_header(src: str, header: str) -> Optional[str]:
    """Return ``src`` with ``header`` placed inside the module docstring (below the prose,
    replacing any prior @AI-MAP block). None if the module has no docstring (caller flags it).
    Mutates ONLY the docstring literal -- nothing executable changes."""
    tree = ast.parse(src)
    if not (tree.body and isinstance(tree.body[0], ast.Expr)
            and isinstance(tree.body[0].value, ast.Constant)
            and isinstance(tree.body[0].value.value, str)):
        return None
    node = tree.body[0].value
    content = node.value  # the docstring's string value (unescaped)
    prose = content.split(HEADER_SENTINEL, 1)[0].rstrip()
    new_content = f"{prose}\n\n{header}\n"
    # Compute char offsets of the docstring literal in the raw source via line/col.
    lines = src.splitlines(keepends=True)
    start = sum(len(lines[i]) for i in range(node.lineno - 1)) + node.col_offset
    end = sum(len(lines[i]) for i in range(node.end_lineno - 1)) + node.end_col_offset
    new_literal = '"""' + new_content + '"""'
    return src[:start] + new_literal + src[end:]


# ==== AGENTS.md RENDER ====
def _read_first_party_dirs() -> list[str]:
    return sorted(d for d in first_party_roots() if (REPO_ROOT / d).is_dir())


def render_root_agents_md(m: dict) -> str:
    out: list[str] = []
    out.append("# 9to5 -- AI navigation index (AGENTS.md)\n")
    out.append("> Generated by `tools/repo_map.py`. Do not hand-edit module rows below; "
               "regenerate with `python tools/repo_map.py`. Machine index: `.repo-map.json`.\n")
    out.append("## Mental model (4 layers)\n")
    out.append("1. **Browser** -- CDP driving claude.ai / chatgpt.com (Phase 2).\n"
               "2. **Native** -- UIA/pywinauto driving desktop apps (Phase 3).\n"
               "3. **Terminal/CLI** -- PRIMARY: Claude Code CLI, gh, git.\n"
               "4. **Local model** -- Ollama as the orchestrator brain.\n")
    out.append("## Commands\n")
    out.append("| Task | Command |\n|---|---|")
    for task, cmd in (
        ("Regenerate this index", "`python tools/repo_map.py`"),
        ("Fast check one file (lint+type+tests)", "`python tools/dev.py check <file>`"),
        ("Watch + auto-run affected tests", "`python tools/dev.py watch <files>`"),
        ("Tests for changed files", "`python tools/affected_tests.py $(git diff --name-only)`"),
        ("Outline a big file (signatures only)", "`python tools/dev.py outline <file>`"),
        ("Find a symbol's def + callers", "`python tools/dev.py where <symbol>`"),
        ("Full suite", "`python -m unittest discover -s tests -v`"),
        ("Fast lane", "`python -m pytest -m \"not slow\" -q`"),
        ("Dry-run pipeline", "`python main.py --dry-run --goal ... --hours 1 --no-web`"),
    ):
        out.append(f"| {task} | {cmd} |")
    out.append("")
    out.append("## How to do X (runbook)\n")
    out.append("- **Add an agent role:** create `agents/<role>.py` (module docstring + "
               "`LOG = config.getLogger('<role>')`), wire it from `orchestrator.py`, add "
               "`tests/test_<role>.py`, then `python tools/repo_map.py`.\n"
               "- **Add a config flag:** add an `ALL_CAPS` constant in `config.py` sourced from "
               "`.env` via `os.getenv`/`_envBool`/`_envPath`; reference as `config.NAME`.\n"
               "- **Add a Discord embed:** add a builder in `notifications/discord_bot.py` "
               "(see existing `*Embed` builders) + send via `discord.sendEmbed`.\n"
               "- **Add + run one test:** use `tests/factories.py` builders; run "
               "`python tools/dev.py check tests/test_<x>.py`.\n")
    out.append("## Packages\n")
    out.append("| Package | Modules | Index |\n|---|---|---|")
    dirs = _read_first_party_dirs()
    for d in dirs:
        count = sum(1 for k, r in m["modules"].items() if r["path"].startswith(d + "/"))
        idx = f"`{d}/AGENTS.md`" if (REPO_ROOT / d / "__init__.py").exists() or count else "-"
        if count:
            out.append(f"| `{d}/` | {count} | {idx} |")
    top = sum(1 for r in m["modules"].values() if "/" not in r["path"])
    out.append(f"| (top-level) | {top} | this file |")
    out.append("")
    return "\n".join(out) + "\n"


def render_package_agents_md(m: dict, pkg: str) -> str:
    out = [f"# `{pkg}/` -- module index\n",
           "> Generated by `tools/repo_map.py` (`python tools/repo_map.py`). "
           "Source of truth: `.repo-map.json`.\n"]
    for dotted in sorted(m["modules"]):
        rec = m["modules"][dotted]
        if not rec["path"].startswith(pkg + "/"):
            continue
        exports = ", ".join(e["name"] for e in rec["exports"]) or "(none)"
        out.append(f"## {rec['path']}")
        out.append(rec["purpose"] or "(no docstring)")
        out.append(f"- Exports: {exports}")
        out.append(f"- Depends on: {', '.join(rec['depends_on']) or '(stdlib only)'}")
        out.append(f"- Side effects: {'; '.join(rec['side_effects'])}")
        out.append(f"- Test: {('pytest ' + ' '.join(rec['test'])) if rec['test'] else '(none)'}")
        out.append("")
    return "\n".join(out) + "\n"


def _packages_with_init(m: dict) -> list[str]:
    return sorted({rec["path"].split("/")[0] for rec in m["modules"].values()
                   if "/" in rec["path"] and (REPO_ROOT / rec["path"].split("/")[0] / "__init__.py").exists()})


# ==== WRITE / CHECK ====
def _dump_json(m: dict) -> str:
    return json.dumps(m, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def write_outputs(*, check: bool, only: Optional[str], no_headers: bool) -> int:
    """Write (or --check) all artifacts. Returns process exit code (0 ok, 1 drift/problem).

    Order matters: in write mode we splice headers FIRST, then rebuild the index from the
    post-splice source, so a single run is a fixpoint (the committed .repo-map.json reflects the
    headers it just wrote). Adoption is INCREMENTAL: write mode splices the files matched by
    ``only``; check mode scans ALL files but verifies only those that have ALREADY adopted a
    header (contain the sentinel) -- so un-adopted files never count as drift."""
    m = build_map()
    drift: list[str] = []
    no_doc: list[str] = []

    # 1. Headers (the only source mutation).
    if not no_headers:
        for path in iter_py_files(None if check else only):
            rec = m["modules"].get(module_dotted(path))
            if rec is None:  # unparseable (skipped in build_map) -> don't touch
                continue
            src = _read_source(path)
            has_header = HEADER_SENTINEL in src
            spliced = splice_header(src, render_header(rec))
            if spliced is None:
                if not check:
                    no_doc.append(str(path.relative_to(REPO_ROOT)))
                continue
            if check:
                if has_header and spliced != src:   # only adopted headers must stay current
                    drift.append(str(path.relative_to(REPO_ROOT)))
            elif spliced != src:
                path.write_text(spliced, encoding="utf-8", newline="\n")

    # 2. Rebuild the index AFTER splicing so it reflects the just-written headers.
    if not check and not no_headers:
        m = build_map()
    json_text = _dump_json(m)
    root_md = render_root_agents_md(m)
    pkg_mds = {pkg: render_package_agents_md(m, pkg) for pkg in _packages_with_init(m)}

    def _cmp(path: Path, want: str) -> None:
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have != want:
            drift.append(str(path.relative_to(REPO_ROOT)))

    if check:
        _cmp(JSON_PATH, json_text)
        _cmp(ROOT_AGENTS, root_md)
        for pkg, text in pkg_mds.items():
            _cmp(REPO_ROOT / pkg / "AGENTS.md", text)
    else:
        JSON_PATH.write_text(json_text, encoding="utf-8", newline="\n")
        ROOT_AGENTS.write_text(root_md, encoding="utf-8", newline="\n")
        for pkg, text in pkg_mds.items():
            (REPO_ROOT / pkg / "AGENTS.md").write_text(text, encoding="utf-8", newline="\n")

    if no_doc:
        print(f"[repo_map] {len(no_doc)} file(s) have no module docstring (skipped header): "
              + ", ".join(no_doc[:8]) + ("..." if len(no_doc) > 8 else ""), file=sys.stderr)

    if check and drift:
        print(f"[repo_map] STALE: {len(drift)} artifact(s)/header(s) out of date:", file=sys.stderr)
        for d in drift[:20]:
            print(f"  - {d}", file=sys.stderr)
        print(REMEDIATION, file=sys.stderr)
        return 1
    if check:
        print("[repo_map] up to date.")
    else:
        print(f"[repo_map] wrote .repo-map.json ({len(m['modules'])} modules), "
              f"AGENTS.md (+{len(pkg_mds)} package), spliced headers"
              + (f" under {only}/" if only else " (all modules)") + ".")
    return 0


# ==== CLI ====
def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the 9to5 AI-navigation layer.")
    ap.add_argument("--check", action="store_true", help="dry-run; exit 1 on drift")
    ap.add_argument("--only", default=None, help="splice headers only under this path prefix (e.g. agents)")
    ap.add_argument("--no-headers", action="store_true", help="write index only, skip header splicing")
    args = ap.parse_args(argv)
    return write_outputs(check=args.check, only=args.only, no_headers=args.no_headers)


if __name__ == "__main__":
    raise SystemExit(main())
