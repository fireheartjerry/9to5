"""Capacity-aware CI lane scheduling using longest-processing-time placement.

The scheduler is deliberately small: it prevents a single self-hosted workstation
from running every expensive lane at once while exposing predicted makespan for review.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  plan_lanes(lanes: list[dict], workers: int=1) -> list[list[dict]]  -- Schedule lanes with LPT
  makespan(schedule: list[list[dict]]) -> float
  main(argv: list[str] | None=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/platform/test_ci_schedule.py
"""
from __future__ import annotations

import argparse
import json


def plan_lanes(lanes: list[dict], workers: int = 1) -> list[list[dict]]:
    """Schedule lanes with LPT; resource-heavy lanes are serialized for safety."""
    slots = [[] for _ in range(max(1, int(workers)))]
    loads = [0.0] * len(slots)
    for lane in sorted(lanes, key=lambda x: (-float(x.get("seconds", 0)), str(x.get("name", "")))):
        if lane.get("heavy"):
            index = 0
        else:
            index = min(range(len(slots)), key=lambda i: (loads[i], i))
        slots[index].append(dict(lane))
        loads[index] += float(lane.get("seconds", 0))
    return slots


def makespan(schedule: list[list[dict]]) -> float:
    return max((sum(float(lane.get("seconds", 0)) for lane in slot) for slot in schedule), default=0.0)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Plan self-hosted CI lanes with LPT scheduling.")
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--lanes-json", default="[]")
    args = parser.parse_args(argv)
    schedule = plan_lanes(json.loads(args.lanes_json), args.workers)
    print(json.dumps({"schedule": schedule, "makespan_seconds": makespan(schedule)}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
