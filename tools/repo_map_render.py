"""AGENTS.md and JSON rendering helpers for the 9to5 AI-navigation layer.

Pure rendering functions: no source mutation, no file I/O (except REPO_ROOT path checks).
Imported by repo_map.py (re-export) and repo_map_outputs.py (write_outputs pipeline).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  render_root_agents_md(m: dict) -> str
  render_package_agents_md(m: dict, pkg: str) -> str
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import json
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent


# ==== JSON SERIALIZATION ====

def _dump_json(m: dict) -> str:
    return json.dumps(m, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


# ==== PACKAGE DISCOVERY (from map, no filesystem scan needed) ====

def _packages_with_init(m: dict) -> list[str]:
    return sorted({rec["path"].split("/")[0] for rec in m["modules"].values()
                   if "/" in rec["path"]
                   and (_REPO_ROOT / rec["path"].split("/")[0] / "__init__.py").exists()})


# ==== MODULE ROW RENDERING ====

def _formatExports(exports: list[dict]) -> str:
    """Format a module's exports list as a comma-separated string."""
    return ", ".join(e["name"] for e in exports) or "(none)"


def _renderModuleRow(rec: dict) -> list[str]:
    """Return the lines for one module section in a package AGENTS.md."""
    lines = [f"## {rec['path']}", rec["purpose"] or "(no docstring)"]
    lines.append(f"- Exports: {_formatExports(rec['exports'])}")
    lines.append(f"- Depends on: {', '.join(rec['depends_on']) or '(stdlib only)'}")
    lines.append(f"- Side effects: {'; '.join(rec['side_effects'])}")
    lines.append(f"- Test: {('pytest ' + ' '.join(rec['test'])) if rec['test'] else '(none)'}")
    lines.append("")
    return lines


# ==== AGENTS.md RENDER ====

def render_root_agents_md(m: dict) -> str:
    out: list[str] = []
    out.append("# 9to5 -- AI navigation index (AGENTS.md)\n")
    out.append("> Generated by `tools/repo_map.py`. Do not hand-edit module rows below; "
               "regenerate with `python tools/repo_map.py`. Machine index: `.repo-map.json`.\n")
    out.append("## Mental model (4 layers)\n")
    out.append("1. **Browser** -- CDP driving claude.ai / chatgpt.com (Phase 2).\n"
               "2. **Native** -- UIA/pywinauto driving desktop apps (Phase 3).\n"
               "3. **Terminal/CLI** -- PRIMARY: Claude Code CLI, gh, git.\n"
               "4. **Local model** -- Ollama as the orchestrator brain.\n")
    out.append("## Commands\n")
    out.append("| Task | Command |\n|---|---|")
    for task, cmd in (
        ("Regenerate this index", "`python tools/repo_map.py`"),
        ("Fast check one file (lint+type+tests)", "`python tools/dev.py check <file>`"),
        ("Watch + auto-run affected tests", "`python tools/dev.py watch <files>`"),
        ("Tests for changed files", "`python tools/affected_tests.py $(git diff --name-only)`"),
        ("Outline a big file (signatures only)", "`python tools/dev.py outline <file>`"),
        ("Find a symbol's def + callers", "`python tools/dev.py where <symbol>`"),
        ("Full suite", "`python tools/dev.py fast`"),
        ("Fast lane", "`python -m pytest -m \"not slow\" -q`"),
        ("Dry-run pipeline", "`python main.py --dry-run --goal ... --hours 1 --no-web`"),
    ):
        out.append(f"| {task} | {cmd} |")
    out.append("")
    out.append("## How to do X (runbook)\n")
    out.append("- **Add an agent role:** create `agents/<role>.py` (module docstring + "
               "`LOG = config.getLogger('<role>')`), wire it from `orchestrator.py`, add "
               "`tests/test_<role>.py`, then `python tools/repo_map.py`.\n"
               "- **Add a config flag:** add an `ALL_CAPS` constant in `config.py` sourced from "
               "`.env` via `os.getenv`/`_envBool`/`_envPath`; reference as `config.NAME`.\n"
               "- **Add a Discord embed:** add a builder in `notifications/discord_bot.py` "
               "(see existing `*Embed` builders) + send via `discord.sendEmbed`.\n"
               "- **Add + run one test:** use `tests/factories.py` builders; run "
               "`python tools/dev.py check tests/test_<x>.py`.\n")
    out.append("## Tree Guide\n")
    out.append("- Root files are public facades or entrypoints: `main.py`, `config.py`, "
               "`orchestrator.py`, `knowledge.py`, `validate_workflows.py`.\n"
               "- Internal platform plumbing lives under `platform_core/`: orchestration, "
               "runtime/control, config internals, knowledge-base mechanics, ops, and simulation.\n"
               "- Product domains stay at root: `agents/`, `notifications/`, `memory/`, "
               "`learning/`, `workflows/`, `state/`, `tools/`, and `tests/`.\n"
               "- Prefer editing the narrow implementation module, while preserving root "
               "facades and compatibility imports when callers already use them.\n")
    out.append("## Packages\n")
    out.append("| Package | Modules | Index |\n|---|---|---|")
    dirs = _packages_with_init(m)
    for d in dirs:
        count = sum(1 for r in m["modules"].values() if r["path"].startswith(d + "/"))
        idx = f"`{d}/AGENTS.md`" if (_REPO_ROOT / d / "__init__.py").exists() or count else "-"
        if count:
            out.append(f"| `{d}/` | {count} | {idx} |")
    top = sum(1 for r in m["modules"].values() if "/" not in r["path"])
    out.append(f"| (top-level) | {top} | this file |")
    out.append("")
    return "\n".join(out) + "\n"


def render_package_agents_md(m: dict, pkg: str) -> str:
    out = [f"# `{pkg}/` -- module index\n",
           "> Generated by `tools/repo_map.py` (`python tools/repo_map.py`). "
           "Source of truth: `.repo-map.json`.\n"]
    for dotted in sorted(m["modules"]):
        rec = m["modules"][dotted]
        if not rec["path"].startswith(pkg + "/"):
            continue
        out.extend(_renderModuleRow(rec))
    return "\n".join(out) + "\n"
