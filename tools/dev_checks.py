"""Check, lint, type, and test commands for the 9to5 dev runner.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  cmd_lint(args: list[str]) -> int
  cmd_typecheck(args: list[str]) -> int
  cmd_check(args: list[str]) -> int  -- Fail-fast gate chain: ruff -> typecheck(changed) -> affected tests -> repo-map drift.
  cmd_test(args: list[str]) -> int
  cmd_fast(args: list[str]) -> int
  count_swallow_sites() -> dict[str, int]  -- Per-file count of bare 'except Exception: pass/continue' swallow sites.
  cmd_swallow_ratchet(args: list[str]) -> int  -- Ratchet gate: bare swallow count may only go DOWN vs the recorded baseline.
  cmd_ci_local(args: list[str]) -> int  -- Run the local CI gates in cheapest useful order.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: --update rewrites tools/swallow_baseline.json
RUN/TEST: python -m pytest tests/evolution/test_selfmod_runner.py tests/orchestration/test_best_effort.py tests/platform/test_dev_commands.py
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import affected_tests  # noqa: E402
import repo_map  # noqa: E402

# ==== CONSTANTS ====
REPO_ROOT = repo_map.REPO_ROOT
PY = sys.executable
HEADER_SENTINEL = repo_map.HEADER_SENTINEL
# follow-imports=skip scopes mypy to the NAMED files only -> the gate answers "did my edit break
# THIS file", not "is the whole 37k-LOC repo mypy-clean" (it isn't yet -- baseline is advisory).
MYPY_FLAGS = ["--ignore-missing-imports", "--follow-imports=skip", "--no-error-summary"]


# ==== TOOL RESOLUTION ====
def _ruff() -> list[str]:
    exe = Path(PY).with_name("ruff.exe")
    if not exe.exists():
        exe = Path(PY).with_name("ruff")
    return [str(exe)] if exe.exists() else [PY, "-m", "ruff"]


def _run(cmd: list[str], capture: bool = False) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=REPO_ROOT, text=True, capture_output=capture)


def _progress_env(interval: str = "30") -> dict[str, str]:
    env = dict(os.environ)
    env.setdefault("NINE_TO_FIVE_TEST_PROGRESS", "1")
    env.setdefault("NINE_TO_FIVE_TEST_HEARTBEAT_SECONDS", interval)
    return env


def _run_env(cmd: list[str], *, env: dict[str, str] | None = None,
             capture: bool = False) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=REPO_ROOT, text=True, env=env, capture_output=capture)


# ==== GATES ====
def _exists(path: str) -> bool:
    """True if the path resolves to a real file (absolute, or relative to REPO_ROOT)."""
    p = Path(path)
    return p.exists() or (REPO_ROOT / path).exists()


def _py_files(args: list[str]) -> list[str]:
    files = [a for a in args if not a.startswith("-") and a.endswith(".py")]
    files = files or affected_tests._git_changed()
    # Drop deleted/renamed-away paths: feeding them to ruff/mypy makes the gate fail after any
    # deletion for a file that no longer exists on disk.
    return [f for f in files if _exists(f)]


def cmd_lint(args: list[str]) -> int:
    files = [a for a in args if a.endswith(".py")] or ["."]
    return _run([*_ruff(), "check", *files]).returncode


def cmd_typecheck(args: list[str]) -> int:
    files = _py_files(args)
    if not files:
        print("[dev] typecheck: no changed .py files")
        return 0
    return _run([PY, "-m", "mypy", *MYPY_FLAGS, *files]).returncode


def cmd_check(args: list[str]) -> int:
    """Fail-fast gate chain: ruff -> typecheck(changed) -> affected tests -> repo-map drift."""
    as_json = "--json" in args
    files = _py_files([a for a in args if a != "--json"])
    results: list[dict] = []

    def gate(name: str, cmd: list[str], fix: str) -> bool:
        cp = _run(cmd, capture=as_json)
        ok = cp.returncode == 0
        if as_json:
            out = ((cp.stdout or "") + (cp.stderr or "")).strip().splitlines()
            results.append({"gate": name, "ok": ok, "returncode": cp.returncode,
                            "head": out[:25], "fix_hint": fix if not ok else ""})
        else:
            print(f"[dev] {name}: {'ok' if ok else 'FAIL'}")
        return ok

    chain_ok = True
    if files:
        chain_ok = gate("ruff", [*_ruff(), "check", *[f for f in files]], "fix lint, or adjust ruff config")
        if chain_ok:
            chain_ok = gate("typecheck", [PY, "-m", "mypy", *MYPY_FLAGS, *files],
                            "fix type errors on changed files")
    if chain_ok:
        targets = affected_tests.targets_for(files) if files else []
        if targets:
            chain_ok = gate("tests", [PY, "-m", "pytest", "-q", *targets], "fix failing affected tests")
        elif not as_json:
            print("[dev] tests: (no mapped tests for changed files)")
    if chain_ok:
        chain_ok = gate("repo-map", [PY, str(REPO_ROOT / "tools" / "repo_map.py"), "--check"],
                        "run: python tools/repo_map.py")

    if as_json:
        print(json.dumps({"ok": chain_ok, "files": files, "gates": results}, indent=2))
    else:
        print(f"[dev] check: {'PASS' if chain_ok else 'FAIL'} ({len(files)} file(s))")
    return 0 if chain_ok else 1


def _has_xdist() -> bool:
    try:
        import xdist  # noqa: F401
        return True
    except ImportError:
        return False


def _xdist(args: list[str]) -> list[str]:
    """Prepend `-n auto --dist loadscope` when pytest-xdist is installed and the caller hasn't
    chosen a worker count. If xdist is absent, run serially (never breaks with unrecognized -n)."""
    if any(a == "-n" or a.startswith("-n") for a in args) or not _has_xdist():
        return args
    return ["-n", "auto", "--dist", "loadscope", *args]


def cmd_test(args: list[str]) -> int:
    return _run([PY, "-m", "pytest", *_xdist(args or ["-q"])]).returncode


def cmd_fast(args: list[str]) -> int:
    rc = cmd_swallow_ratchet([])   # cheap static gate first: swallow count only goes down
    if rc != 0:
        return rc
    return _run([PY, "-m", "pytest", *_xdist(["-m", "not slow", "-q", *args])]).returncode


# Test files must never carry a unittest runner block: `python tests/test_x.py` (and
# `unittest discover`) bypass the pytest-only conftest sandbox and can fire REAL
# Discord/Ollama side effects with the live creds in .env. pytest is the only runner.
UNITTEST_MAIN_TOKEN = "unittest.main("


def _bare_runner_offenders() -> list[str]:
    """Test files containing a forbidden bare-runner block (see UNITTEST_MAIN_TOKEN).
    Private: kept out of the AI-nav index so no generated artifact advertises the token."""
    out: list[str] = []
    for p in sorted((REPO_ROOT / "tests").rglob("*.py")):
        if "__pycache__" in p.parts:
            continue
        if UNITTEST_MAIN_TOKEN in p.read_text(encoding="utf-8", errors="ignore"):
            out.append(str(p.relative_to(REPO_ROOT)).replace("\\", "/"))
    return out


def _no_unittest_main_gate() -> int:
    offenders = _bare_runner_offenders()
    if offenders:
        print(f"[dev] no-unittest-main: FAIL -- {len(offenders)} test file(s) carry a "
              f"unittest.main() runner block (pytest is the only allowed runner):", file=sys.stderr)
        for f in offenders[:10]:
            print(f"  - {f}", file=sys.stderr)
        return 1
    print("[dev] no-unittest-main: ok")
    return 0


# ==== SWALLOW RATCHET ====
# A bare swallow is `except Exception:` (with/without `as e` / trailing comment) whose body
# is ONLY `pass`/`continue`. New code must route through platform_core.core.best_effort
# instead; this ratchet lets the count only go DOWN against the recorded baseline.
SWALLOW_BASELINE_FILE = REPO_ROOT / "tools" / "swallow_baseline.json"
_SWALLOW_RE = re.compile(
    r"^[ \t]*except Exception[^\n]*:[ \t]*(?:#[^\n]*)?\n"
    r"[ \t]*(?:pass|continue)[ \t]*(?:#[^\n]*)?$", re.MULTILINE)
_SWALLOW_SKIP_DIRS = {".git", ".venv", "venv", "__pycache__", ".mypy_cache",
                      ".pytest_cache", "node_modules", "logs", "references"}


def count_swallow_sites() -> dict[str, int]:
    """Per-file count of bare 'except Exception: pass/continue' swallow sites."""
    out: dict[str, int] = {}
    for p in sorted(REPO_ROOT.rglob("*.py")):
        if _SWALLOW_SKIP_DIRS.intersection(p.relative_to(REPO_ROOT).parts):
            continue
        try:
            n = len(_SWALLOW_RE.findall(p.read_text(encoding="utf-8", errors="ignore")))
        except OSError:
            continue
        if n:
            out[str(p.relative_to(REPO_ROOT)).replace("\\", "/")] = n
    return out


def cmd_swallow_ratchet(args: list[str]) -> int:
    """Ratchet gate: bare swallow count may only go DOWN vs the recorded baseline.
    `--update` records the current (lower) count; refuses to RAISE the baseline."""
    sites = count_swallow_sites()
    count = sum(sites.values())
    try:
        baseline = int(json.loads(SWALLOW_BASELINE_FILE.read_text(encoding="utf-8"))["count"])
    except (OSError, ValueError, KeyError, TypeError):
        baseline = None
    if "--update" in args:
        if baseline is not None and count > baseline:
            print(f"[dev] swallow-ratchet: REFUSING to raise baseline {baseline} -> {count}; "
                  "convert the new bare swallows to best_effort() instead", file=sys.stderr)
            return 1
        SWALLOW_BASELINE_FILE.write_text(json.dumps(
            {"count": count,
             "note": "bare 'except Exception: pass/continue' sites; may only go down "
                     "(see platform_core/core/best_effort.py)"}, indent=1) + "\n", encoding="utf-8")
        print(f"[dev] swallow-ratchet: baseline updated {baseline} -> {count}")
        return 0
    if baseline is None:
        print(f"[dev] swallow-ratchet: no baseline at {SWALLOW_BASELINE_FILE}; "
              f"current count = {count}. Record it with: python tools/dev.py swallow-ratchet --update",
              file=sys.stderr)
        return 1
    if count > baseline:
        print(f"[dev] swallow-ratchet: FAIL -- {count} bare swallow site(s) > baseline {baseline}. "
              "Route new swallows through platform_core.core.best_effort.best_effort().",
              file=sys.stderr)
        for f, n in sorted(sites.items(), key=lambda kv: -kv[1])[:10]:
            print(f"  - {f}: {n}", file=sys.stderr)
        return 1
    hint = "" if count == baseline else \
        " (improved; lock it in: python tools/dev.py swallow-ratchet --update)"
    print(f"[dev] swallow-ratchet: ok ({count} <= baseline {baseline}){hint}")
    return 0


def cmd_ci_local(args: list[str]) -> int:  # noqa: ARG001
    """Run the local CI gates in cheapest useful order."""
    # Step zero: corrupt/uncompilable test files must fail in seconds, never at collection.
    print("[dev] compile-tests")
    rc = _run([PY, "-m", "compileall", "-q", str(REPO_ROOT / "tests")]).returncode
    if rc != 0:
        return rc
    rc = _no_unittest_main_gate()
    if rc != 0:
        return rc
    rc = cmd_swallow_ratchet([])
    if rc != 0:
        return rc
    gates = [
        ("repo-map", [PY, str(REPO_ROOT / "tools" / "repo_map.py"), "--check"]),
        ("workflows", [PY, str(REPO_ROOT / "validate_workflows.py")]),
    ]
    for name, cmd in gates:
        print(f"[dev] {name}")
        rc = _run(cmd).returncode
        if rc != 0:
            return rc
    files = affected_tests._git_changed()
    targets = affected_tests.targets_for(files)
    if targets:
        print(f"[dev] affected tests: {len(targets)} target(s)")
        rc = _run([PY, "-m", "pytest", "-q", *targets]).returncode
        if rc != 0:
            return rc
    else:
        print("[dev] affected tests: none")
    if not targets or any(Path(f).suffix in {".yml", ".yaml", ".toml", ".txt", ".md"}
                         for f in subprocess.run(["git", "diff", "--name-only", "HEAD"],
                                                 cwd=REPO_ROOT, capture_output=True,
                                                 text=True).stdout.splitlines()):
        print("[dev] fast lane")
        return cmd_fast([])
    return 0
