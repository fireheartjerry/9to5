def _canonical_json(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")


def _sha256_bytes(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _strict_json_file(path: Path, label: str) -> dict[str, object]:
    try:
        raw = path.read_bytes()
        value = json.loads(raw.decode("utf-8", errors="strict"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ImageBuildRefused(f"{label} is not strict JSON") from exc
    if not isinstance(value, dict) or _canonical_json(value) != raw:
        raise ImageBuildRefused(f"{label} is not canonical JSON")
    return value


def _duplicate_free_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    value: dict[str, object] = {}
    for key, item in pairs:
        if key in value:
            raise ImageBuildRefused("JSON input contains a duplicate key")
        value[key] = item
    return value


def _input_json_file(path: Path, label: str) -> dict[str, object]:
    """Read strict duplicate-free builder JSON before canonical rewriting."""
    try:
        raw = path.read_bytes()
        if raw.startswith(b"\xef\xbb\xbf"):
            raise ImageBuildRefused(f"{label} has a forbidden UTF-8 BOM")
        value = json.loads(
            raw.decode("utf-8", errors="strict"),
            object_pairs_hook=_duplicate_free_object,
        )
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ImageBuildRefused(f"{label} is not strict JSON") from exc
    if not isinstance(value, dict):
        raise ImageBuildRefused(f"{label} is not a JSON object")
    return value


def _descriptor_digest(value: object, label: str) -> str:
    if not isinstance(value, str) or not value.startswith("sha256:"):
        raise ImageBuildRefused(f"{label} descriptor is not sha256")
    digest = value[7:]
    if _SHA256.fullmatch(digest) is None:
        raise ImageBuildRefused(f"{label} descriptor is malformed")
    return digest


def _read_verified_blob(root: Path, digest: str, size: object, label: str) -> bytes:
    path = root / "blobs" / "sha256" / digest
    try:
        raw = path.read_bytes()
    except OSError as exc:
        raise ImageBuildRefused(f"{label} blob is unavailable") from exc
    if _sha256_bytes(raw) != digest:
        raise ImageBuildRefused(f"{label} blob digest mismatch")
    if not isinstance(size, int) or isinstance(size, bool) or size != len(raw):
        raise ImageBuildRefused(f"{label} blob size mismatch")
    return raw


def seal_oci_layout(layout: Path, closure_documents: Mapping[str, bytes]) -> SealedOciFacts:
    """Attach six canonical closure documents to one minimal OCI layout."""
    if set(closure_documents) != set(_CLOSURE_LEAVES):
        raise ImageBuildRefused("exact six-document closure is required")
    closure_digests: dict[str, str] = {}
    for label in _CLOSURE_LEAVES:
        raw = closure_documents[label]
        try:
            value = json.loads(raw.decode("utf-8", errors="strict"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise ImageBuildRefused(f"{label} closure is not strict JSON") from exc
        if not isinstance(value, dict) or _canonical_json(value) != raw:
            raise ImageBuildRefused(f"{label} closure is not canonical JSON")
        closure_digests[label] = _sha256_bytes(raw)
    if len(set(closure_digests.values())) != len(_CLOSURE_LEAVES):
        raise ImageBuildRefused("the six closure documents must be byte-distinct")

    root = layout.resolve(strict=True)
    index_path = root / "index.json"
    index = _input_json_file(index_path, "OCI index")
    manifests = index.get("manifests")
    if index.get("schemaVersion") != 2 or not isinstance(manifests, list) or len(manifests) != 1:
        raise ImageBuildRefused("OCI index must contain exactly one manifest")
    descriptor = manifests[0]
    if not isinstance(descriptor, dict):
        raise ImageBuildRefused("OCI manifest descriptor is malformed")
    old_manifest_digest = _descriptor_digest(descriptor.get("digest"), "manifest")
    manifest_raw = _read_verified_blob(root, old_manifest_digest, descriptor.get("size"), "manifest")
    try:
        manifest = json.loads(manifest_raw.decode("utf-8", errors="strict"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ImageBuildRefused("OCI manifest is invalid JSON") from exc
    if not isinstance(manifest, dict) or manifest.get("schemaVersion") != 2:
        raise ImageBuildRefused("OCI manifest schema is unsupported")
    config_descriptor = manifest.get("config")
    layers = manifest.get("layers")
    if not isinstance(config_descriptor, dict) or not isinstance(layers, list) or not layers:
        raise ImageBuildRefused("OCI config or layer closure is malformed")
    config_digest = _descriptor_digest(config_descriptor.get("digest"), "config")
    _read_verified_blob(root, config_digest, config_descriptor.get("size"), "config")
    layer_digests: list[str] = []
    for layer in layers:
        if not isinstance(layer, dict):
            raise ImageBuildRefused("OCI layer descriptor is malformed")
        digest = _descriptor_digest(layer.get("digest"), "layer")
        _read_verified_blob(root, digest, layer.get("size"), "layer")
        layer_digests.append(digest)

    blobs = root / "blobs" / "sha256"
    reachable_before = {old_manifest_digest, config_digest, *layer_digests}
    present_before = {path.name for path in blobs.iterdir() if path.is_file()}
    allowed_existing_closure = set(closure_digests.values())
    if not present_before <= reachable_before | allowed_existing_closure:
        raise ImageBuildRefused("OCI layout contains an unreferenced blob")
    for label, raw in closure_documents.items():
        destination = blobs / closure_digests[label]
        if destination.exists():
            if not destination.is_file() or destination.read_bytes() != raw:
                raise ImageBuildRefused(f"{label} closure blob collision")
        else:
            destination.write_bytes(raw)

    annotations = manifest.get("annotations")
    if annotations is None:
        annotations = {}
    if not isinstance(annotations, dict):
        raise ImageBuildRefused("OCI manifest annotations are malformed")
    annotations = dict(annotations)
    for label, digest in closure_digests.items():
        annotations[f"org.galaxy.{label}.digest"] = f"sha256:{digest}"
    manifest["annotations"] = annotations
    new_manifest_raw = _canonical_json(manifest)
    new_manifest_digest = _sha256_bytes(new_manifest_raw)
    new_manifest_path = blobs / new_manifest_digest
    if new_manifest_path.exists() and new_manifest_path.read_bytes() != new_manifest_raw:
        raise ImageBuildRefused("sealed manifest digest collision")
    new_manifest_path.write_bytes(new_manifest_raw)

    new_descriptor = dict(descriptor)
    new_descriptor["digest"] = f"sha256:{new_manifest_digest}"
    new_descriptor["size"] = len(new_manifest_raw)
    index["manifests"] = [new_descriptor]
    index_path.write_bytes(_canonical_json(index))
    if old_manifest_digest != new_manifest_digest:
        (blobs / old_manifest_digest).unlink()

    try:
        inspected = inspect_oci_layout(root)
    except OfflineActivationArtifactsUnavailable as exc:
        raise ImageBuildRefused("sealed OCI layout failed independent inspection") from exc
    return SealedOciFacts(
        manifest_digest=inspected.manifest_digest,
        config_digest=inspected.config_digest,
        layer_digests=inspected.layer_digests,
        closure_digests=dict(inspected.closure_digests),
    )


def _is_reparse(path: Path) -> bool:
    if path.is_symlink():
        return True
    attributes = getattr(path.lstat(), "st_file_attributes", 0)
    return bool(attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT) if os.name == "nt" else False


def write_deterministic_oci_archive(layout: Path, destination: Path) -> None:
    """Write a stable uncompressed tar while refusing links and special files."""
    root = layout.resolve(strict=True)
    paths = sorted(root.rglob("*"), key=lambda path: path.relative_to(root).as_posix())
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(destination.name + ".tmp")
    if temporary.exists():
        temporary.unlink()
    try:
        with tarfile.open(temporary, mode="w", format=tarfile.USTAR_FORMAT) as bundle:
            for path in paths:
                relative = path.relative_to(root).as_posix()
                metadata = path.lstat()
                if _is_reparse(path):
                    raise ImageBuildRefused(f"OCI archive input link refused: {relative}")
                info = tarfile.TarInfo(relative + ("/" if path.is_dir() else ""))
                info.mtime = 0
                info.uid = 0
                info.gid = 0
                info.uname = ""
                info.gname = ""
                if stat.S_ISDIR(metadata.st_mode):
                    info.type = tarfile.DIRTYPE
                    info.mode = 0o755
                    info.size = 0
                    bundle.addfile(info)
                elif stat.S_ISREG(metadata.st_mode):
                    if metadata.st_nlink != 1:
                        raise ImageBuildRefused(f"OCI archive hard-linked input refused: {relative}")
                    info.type = tarfile.REGTYPE
                    info.mode = 0o444
                    info.size = metadata.st_size
                    with path.open("rb") as stream:
                        bundle.addfile(info, stream)
                else:
                    raise ImageBuildRefused(f"OCI archive special input refused: {relative}")
        os.replace(temporary, destination)
    finally:
        if temporary.exists():
            temporary.unlink()


def audit_dockerfile(
    path: Path,
    *,
    expected_base_digest: str,
    expected_roles: Sequence[str] | None = None,
) -> DockerfileAudit:
    """Require a one-stage, download-free, digest-pinned generic image source."""
    if _SHA256.fullmatch(expected_base_digest) is None:
        raise ImageBuildRefused("expected base digest is malformed")
    try:
        raw = path.read_bytes()
        text = raw.decode("utf-8", errors="strict")
    except (OSError, UnicodeDecodeError) as exc:
        raise ImageBuildRefused("Dockerfile is unavailable or not UTF-8") from exc
    if raw.startswith(b"\xef\xbb\xbf") or "\r" in text.replace("\r\n", ""):
        raise ImageBuildRefused("Dockerfile encoding or continuations are refused")
    text = text.replace("\r\n", "\n")
    if "\\\n" in text:
        raise ImageBuildRefused("Dockerfile encoding or continuations are refused")
    instructions: list[tuple[str, str]] = []
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 1)
        if len(parts) != 2:
            raise ImageBuildRefused("Dockerfile instruction is malformed")
        instructions.append((parts[0].upper(), parts[1].strip()))
    allowed = {"FROM", "COPY", "LABEL", "USER", "WORKDIR", "ENTRYPOINT", "CMD"}
    if any(instruction not in allowed for instruction, _ in instructions):
        raise ImageBuildRefused("Dockerfile contains a build-capable or unknown instruction")
    from_values = [value for instruction, value in instructions if instruction == "FROM"]
    expected_from = f"python@sha256:{expected_base_digest}"
    if from_values != [expected_from]:
        raise ImageBuildRefused("Dockerfile base is not the exact approved digest")
    copy_values = [value for instruction, value in instructions if instruction == "COPY"]
    if copy_values != [
        "bootstrap/galaxy_launcher/activation_image_entrypoint.py /opt/galaxy/activation_image_entrypoint.py"
    ]:
        raise ImageBuildRefused("Dockerfile COPY closure is not exact")
    if [value for instruction, value in instructions if instruction == "USER"] != ["65532:65532"]:
        raise ImageBuildRefused("Dockerfile must select the exact nonroot identity")
    if [value for instruction, value in instructions if instruction == "WORKDIR"] not in (
        [],
        ["/empty"],
    ):
        raise ImageBuildRefused("Dockerfile working directory is not the empty root")
    entries = [value for instruction, value in instructions if instruction == "ENTRYPOINT"]
    try:
        parsed_entry = json.loads(entries[0]) if len(entries) == 1 else None
    except json.JSONDecodeError as exc:
        raise ImageBuildRefused("Dockerfile entrypoint is not JSON exec form") from exc
    if parsed_entry != _ENTRYPOINT:
        raise ImageBuildRefused("Dockerfile entrypoint does not clear ambient environment")
    labels = [value for instruction, value in instructions if instruction == "LABEL"]
    label_values: dict[str, str] = {}
    for value in labels:
        match = re.fullmatch(r'([^=\s]+)="([^"]*)"', value)
        if match is None or match.group(1) in label_values:
            raise ImageBuildRefused("Dockerfile label closure is malformed")
        label_values[match.group(1)] = match.group(2)
    if set(label_values) not in (
        set(),
        {"org.galaxy.image.authority", "org.galaxy.image.roles"},
    ):
        raise ImageBuildRefused("Dockerfile labels are not closed")
    supported_roles = tuple(
        value for value in label_values.get("org.galaxy.image.roles", "").split(",") if value
    )
    if labels and label_values.get("org.galaxy.image.authority") != "inactive":
        raise ImageBuildRefused("Dockerfile authority label must remain inactive")
    if expected_roles is not None and supported_roles != tuple(expected_roles):
        raise ImageBuildRefused("Dockerfile role label differs from the reviewed role set")
    commands = [value for instruction, value in instructions if instruction == "CMD"]
    if commands:
        try:
            command = json.loads(commands[0]) if len(commands) == 1 else None
        except json.JSONDecodeError as exc:
            raise ImageBuildRefused("Dockerfile command is not JSON exec form") from exc
        if command != ["image-canary"]:
            raise ImageBuildRefused("Dockerfile default command must be the inactive canary")
    return DockerfileAudit(
        path=path.resolve(strict=True),
        sha256=_sha256_bytes(raw),
        base_digest=expected_base_digest,
        supported_roles=supported_roles,
    )


def _run(
    command: Sequence[str],
    *,
    timeout: float = 1800,
    cwd: Path | None = None,
    check: bool = True,
) -> subprocess.CompletedProcess[str]:
    completed = subprocess.run(
        list(command),
        cwd=cwd,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        timeout=timeout,
        check=False,
    )
    if check and completed.returncode != 0:
        rendered = " ".join(command)
        raise ImageBuildRefused(
            f"offline command failed ({completed.returncode}): {rendered}\n"
            f"stdout={completed.stdout[-4000:]}\nstderr={completed.stderr[-4000:]}"
        )
    return completed


def require_docker_desktop_network_closed() -> dict[str, object]:
    """Prove the Docker Desktop VM has no default route during final work."""
    if os.name != "nt":
        raise ImageBuildRefused("this reviewed closure requires the pinned Windows lane")
    routes = _run(
        [
            "wsl.exe",
            "-d",
            "docker-desktop",
            "-u",
            "root",
            "--",
            "sh",
            "-lc",
            "ip route",
        ],
        timeout=30,
    ).stdout.splitlines()
    if any(line.strip().startswith("default ") for line in routes):
        raise ImageBuildRefused("Docker Desktop still has an external default route; final build refused")
    context = _run(["docker", "context", "show"], timeout=30).stdout.strip()
    if context != "desktop-linux":
        raise ImageBuildRefused("the reviewed desktop-linux Docker context is required")
    server = _run(["docker", "version", "--format", "{{json .Server}}"], timeout=30).stdout.strip()
    buildx = _run(["docker", "buildx", "version"], timeout=30).stdout.strip()
    try:
        server_value = json.loads(server)
    except json.JSONDecodeError as exc:
        raise ImageBuildRefused("Docker server identity is unavailable") from exc
    return {
        "schema": "galaxy.offline-docker-boundary/v1",
        "context": context,
        "docker_server": server_value,
        "buildx": buildx,
        "routes": sorted(line.strip() for line in routes if line.strip()),
        "default_route_absent": True,
    }


def _collect_base(base: BaseSpec) -> dict[str, object]:
    inspect_raw = _run(["docker", "image", "inspect", base.reference], timeout=60).stdout
    try:
        values = json.loads(inspect_raw)
    except json.JSONDecodeError as exc:
        raise ImageBuildRefused(f"{base.name}: Docker inspect returned invalid JSON") from exc
    if not isinstance(values, list) or len(values) != 1 or not isinstance(values[0], dict):
        raise ImageBuildRefused(f"{base.name}: exact local base image is unavailable")
    image = values[0]
    exact_reference = f"python@sha256:{base.digest}"
    repo_digests = image.get("RepoDigests")
    rootfs = image.get("RootFS")
    if (
        not isinstance(repo_digests, list)
        or exact_reference not in repo_digests
        or image.get("Id") != f"sha256:{base.digest}"
        or image.get("Architecture") != "amd64"
        or image.get("Os") != "linux"
        or not isinstance(rootfs, dict)
        or rootfs.get("Type") != "layers"
        or not isinstance(rootfs.get("Layers"), list)
        or not rootfs["Layers"]
    ):
        raise ImageBuildRefused(f"{base.name}: local base identity or platform mismatch")
    diff_ids = rootfs["Layers"]
    if any(
        not isinstance(value, str) or not value.startswith("sha256:") or _SHA256.fullmatch(value[7:]) is None
        for value in diff_ids
    ):
        raise ImageBuildRefused(f"{base.name}: rootfs diff-id closure is malformed")
    inventory_completed = _run(
        [
            "docker",
            "run",
            "--rm",
            "--network",
            "none",
            "--read-only",
            "--cap-drop",
            "ALL",
            "--security-opt",
            "no-new-privileges",
            base.reference,
            "/usr/bin/env",
            "-i",
            "/usr/local/bin/python3",
            "-I",
            "-S",
            "-c",
            _INVENTORY_PROGRAM,
        ],
        timeout=180,
    )
    try:
        inventory = json.loads(inventory_completed.stdout)
    except json.JSONDecodeError as exc:
        raise ImageBuildRefused(f"{base.name}: offline inventory is invalid") from exc
    if not isinstance(inventory, dict) or set(inventory) != {"packages", "runtime", "tools"}:
        raise ImageBuildRefused(f"{base.name}: offline inventory fields are malformed")
    packages = inventory["packages"]
    if not isinstance(packages, list) or not packages:
        raise ImageBuildRefused(f"{base.name}: package inventory is empty")
    for package in packages:
        if (
            not isinstance(package, dict)
            or set(package) != {"architecture", "license_evidence", "name", "version"}
            or not isinstance(package["license_evidence"], dict)
        ):
            raise ImageBuildRefused(f"{base.name}: package license closure is incomplete")
    return {
        "name": base.name,
        "reference": exact_reference,
        "manifest_digest": base.digest,
        "image_id": image["Id"],
        "architecture": "amd64",
        "os": "linux",
        "rootfs_diff_ids": diff_ids,
        "base_config": image.get("Config"),
        "inventory": inventory,
    }


def _unsealed_layout_details(layout: Path) -> tuple[dict[str, object], str, tuple[str, ...]]:
    root = layout.resolve(strict=True)
    index = _input_json_file(root / "index.json", "OCI index")
    manifests = index.get("manifests")
    if not isinstance(manifests, list) or len(manifests) != 1 or not isinstance(manifests[0], dict):
        raise ImageBuildRefused("built OCI index is not a single-image layout")
    manifest_descriptor = manifests[0]
    manifest_digest = _descriptor_digest(manifest_descriptor.get("digest"), "manifest")
    manifest_raw = _read_verified_blob(root, manifest_digest, manifest_descriptor.get("size"), "manifest")
    try:
        manifest = json.loads(manifest_raw.decode("utf-8", errors="strict"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ImageBuildRefused("built OCI manifest is invalid") from exc
    if not isinstance(manifest, dict):
        raise ImageBuildRefused("built OCI manifest is not an object")
    config_descriptor = manifest.get("config")
    layers = manifest.get("layers")
    if not isinstance(config_descriptor, dict) or not isinstance(layers, list) or not layers:
        raise ImageBuildRefused("built OCI config or layers are absent")
    config_digest = _descriptor_digest(config_descriptor.get("digest"), "config")
    config_raw = _read_verified_blob(root, config_digest, config_descriptor.get("size"), "config")
    try:
        config = json.loads(config_raw.decode("utf-8", errors="strict"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ImageBuildRefused("built OCI config is invalid") from exc
    if not isinstance(config, dict):
        raise ImageBuildRefused("built OCI config is not an object")
    layer_digests: list[str] = []
    for descriptor in layers:
        if not isinstance(descriptor, dict):
            raise ImageBuildRefused("built OCI layer descriptor is malformed")
        digest = _descriptor_digest(descriptor.get("digest"), "layer")
        _read_verified_blob(root, digest, descriptor.get("size"), "layer")
        layer_digests.append(digest)
    return config, config_digest, tuple(layer_digests)


def _validate_built_config(config: Mapping[str, object], spec: ImageSpec, base: Mapping[str, object]) -> None:
    runtime = config.get("config")
    rootfs = config.get("rootfs")
    if not isinstance(runtime, dict) or not isinstance(rootfs, dict):
        raise ImageBuildRefused(f"{spec.name}: OCI runtime config is incomplete")
    labels = runtime.get("Labels")
    expected_labels = {
        "org.galaxy.image.authority": "inactive",
        "org.galaxy.image.roles": ",".join(spec.roles),
    }
    if (
        runtime.get("User") != "65532:65532"
        or runtime.get("WorkingDir") != "/empty"
        or runtime.get("Entrypoint") != _ENTRYPOINT
        or runtime.get("Cmd") != ["image-canary"]
        or not isinstance(labels, dict)
        or any(labels.get(key) != value for key, value in expected_labels.items())
    ):
        raise ImageBuildRefused(f"{spec.name}: OCI runtime boundary differs from source")
    diff_ids = rootfs.get("diff_ids")
    base_diff_ids = base["rootfs_diff_ids"]
    if (
        rootfs.get("type") != "layers"
        or not isinstance(diff_ids, list)
        or not isinstance(base_diff_ids, list)
        or diff_ids[: len(base_diff_ids)] != base_diff_ids
        or len(diff_ids) <= len(base_diff_ids)
    ):
        raise ImageBuildRefused(f"{spec.name}: built rootfs is not based on the pinned closure")


