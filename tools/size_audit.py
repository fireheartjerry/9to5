"""Line-count audit for agent-friendly files and functions.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  collect() -> tuple[list[dict], list[dict]]
  main(args: list[str]) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import ast
import json
import subprocess
from pathlib import Path

import repo_map

REPO_ROOT = repo_map.REPO_ROOT
FILE_BUCKETS = ("must_split", "acceptable", "ideal")
FUNCTION_BUCKETS = ("must_split", "preferred_over")


def _run_git_ls() -> list[str]:
    cp = subprocess.run(
        ["git", "ls-files", "*.py"],
        cwd=REPO_ROOT,
        text=True,
        capture_output=True,
        check=False,
    )
    return (cp.stdout or "").splitlines()


def _tracked_py_files() -> list[Path]:
    paths: list[Path] = []
    for line in _run_git_ls():
        p = REPO_ROOT / line
        parts = set(p.relative_to(REPO_ROOT).parts)
        if parts & {"logs", "venv", "__pycache__", ".pytest_cache", "tests"}:
            continue
        paths.append(p)
    return paths


def _rel(path: Path) -> str:
    return str(path.relative_to(REPO_ROOT)).replace("\\", "/")


def _function_rows(path: Path) -> list[dict]:
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
        tree = ast.parse(src)
    except (OSError, SyntaxError):
        return []
    rows = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            end = getattr(node, "end_lineno", node.lineno)
            loc = end - node.lineno + 1
            if loc > 25:
                rows.append({
                    "path": _rel(path), "name": node.name, "line": node.lineno,
                    "lines": loc, "bucket": "must_split" if loc > 70 else "preferred_over",
                })
    return rows


def collect() -> tuple[list[dict], list[dict]]:
    files = []
    functions = []
    for path in _tracked_py_files():
        try:
            lines = len(path.read_text(encoding="utf-8", errors="replace").splitlines())
        except OSError:
            continue
        bucket = "must_split" if lines > 450 else ("acceptable" if lines > 300 else "ideal")
        files.append({"path": _rel(path), "lines": lines, "bucket": bucket})
        functions.extend(_function_rows(path))
    files.sort(key=lambda r: (-r["lines"], r["path"]))
    functions.sort(key=lambda r: (-r["lines"], r["path"], r["line"]))
    return files, functions


def _print_file_buckets(files: list[dict]) -> None:
    print("[size-audit] file thresholds: ideal <=300, acceptable <=450, must_split >450")
    for label in FILE_BUCKETS:
        subset = [r for r in files if r["bucket"] == label]
        print(f"[size-audit] {label}: {len(subset)} file(s)")
        for row in subset[:40]:
            print(f"  {row['lines']:4d}  {row['path']}")


def _print_function_buckets(functions: list[dict]) -> None:
    print("[size-audit] function thresholds: preferred <=25, max <=70")
    for label in FUNCTION_BUCKETS:
        subset = [r for r in functions if r["bucket"] == label]
        print(f"[size-audit] functions {label}: {len(subset)}")
        for row in subset[:40]:
            print(f"  {row['lines']:4d}  {row['path']}:{row['line']} {row['name']}")


def main(args: list[str]) -> int:
    files, functions = collect()
    violations = [r for r in files if r["bucket"] == "must_split"]
    violations += [r for r in functions if r["bucket"] == "must_split"]
    if "--json" in args:
        print(json.dumps({"files": files, "functions": functions}, indent=2))
        return 1 if violations else 0
    _print_file_buckets(files)
    _print_function_buckets(functions)
    return 1 if violations else 0


if __name__ == "__main__":
    import sys
    sys.exit(main(sys.argv[1:]))
