EXPECTED = {
    ("ast_serialize", "0.6.0", "ast_serialize-0.6.0-cp39-abi3-win_amd64.whl"),
    ("librt", "0.13.0", "librt-0.13.0-cp312-cp312-win_amd64.whl"),
    ("mypy_extensions", "1.1.0", "mypy_extensions-1.1.0-py3-none-any.whl"),
    ("mypy", "2.3.0", "mypy-2.3.0-py3-none-any.whl"),
    ("pathspec", "1.1.1", "pathspec-1.1.1-py3-none-any.whl"),
    ("typing_extensions", "4.16.0", "typing_extensions-4.16.0-py3-none-any.whl"),
}
_SHA256 = re.compile(r"^[0-9a-f]{64}$")
_POISON = {
    "PIP_CONFIG_FILE", "PIP_INDEX_URL", "PIP_EXTRA_INDEX_URL", "PIP_TRUSTED_HOST",
    "HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY", "NO_PROXY",
    "PYTHONPATH", "PYTHONHOME", "VIRTUAL_ENV",
}


class DevToolBootstrapRefused(RuntimeError):
    """The offline developer-tool closure or destination is not exact."""


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _read_lock(path: Path) -> tuple[dict[str, Any], bytes]:
    raw = path.read_bytes()
    if raw.startswith((b"\xef\xbb\xbf", b"\xff\xfe", b"\xfe\xff")):
        raise DevToolBootstrapRefused("lock BOM is forbidden")
    try:
        lock = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise DevToolBootstrapRefused("lock is not strict UTF-8 JSON") from exc
    if not isinstance(lock, dict):
        raise DevToolBootstrapRefused("lock root must be an object")
    return lock, raw


def _artifact_root(lock: dict[str, Any]) -> Path:
    artifact_set = lock.get("artifact_set")
    if not isinstance(artifact_set, str) or not artifact_set:
        raise DevToolBootstrapRefused("artifact_set is missing")
    return _user_profile() / ".galaxy-r3" / "artifacts" / "dev-tools" / artifact_set


def _user_profile() -> Path:
    """Resolve the Windows profile without trusting caller environment text."""
    if os.name != "nt":
        try:
            return Path.home()
        except RuntimeError as exc:
            raise DevToolBootstrapRefused("user profile is unavailable") from exc
    import ctypes

    buffer = ctypes.create_unicode_buffer(32768)
    # CSIDL_PROFILE is stable on PowerShell 5.1-era Windows and does not consult
    # the potentially hostile USERPROFILE/HOME variables in the request env.
    result = ctypes.windll.shell32.SHGetFolderPathW(None, 0x28, None, 0, buffer)
    if result != 0 or not buffer.value:
        raise DevToolBootstrapRefused("Windows user profile is unavailable")
    return Path(buffer.value)


def _wheel_metadata(path: Path) -> tuple[str, str, set[str], set[str]]:
    try:
        with zipfile.ZipFile(path) as archive:
            metadata_files = [name for name in archive.namelist()
                              if name.endswith(".dist-info/METADATA")]
            wheel_files = [name for name in archive.namelist()
                           if name.endswith(".dist-info/WHEEL")]
            if len(metadata_files) != 1 or len(wheel_files) != 1:
                raise DevToolBootstrapRefused(f"wheel metadata closure malformed: {path.name}")
            metadata = archive.read(metadata_files[0]).decode("utf-8")
            wheel = archive.read(wheel_files[0]).decode("utf-8")
    except (OSError, UnicodeDecodeError, zipfile.BadZipFile) as exc:
        raise DevToolBootstrapRefused(f"invalid wheel archive: {path.name}") from exc
    fields: dict[str, str] = {}
    classifiers: set[str] = set()
    for line in metadata.splitlines():
        if ": " in line:
            key, value = line.split(": ", 1)
            if key in {"Name", "Version", "License-Expression"} and key not in fields:
                fields[key] = value
            if key == "Classifier" and "License ::" in value:
                classifiers.add(value)
    tags = {line[5:] for line in wheel.splitlines() if line.startswith("Tag: ")}
    return fields.get("Name", ""), fields.get("Version", ""), tags, classifiers | {
        fields.get("License-Expression", "")
    }


def _validate_lock(lock: dict[str, Any], artifact_root: Path) -> list[tuple[dict[str, Any], Path]]:
    if lock.get("schema_version") != 1 or lock.get("mypy_version") != "2.3.0":
        raise DevToolBootstrapRefused("exact mypy 2.3.0 lock required")
    if (lock.get("python_version"), lock.get("implementation"), lock.get("platform")) != (
        "3.12.13", "cpython", "win_amd64"
    ):
        raise DevToolBootstrapRefused("exact CPython 3.12.13 win_amd64 target required")
    wheels = lock.get("wheels")
    if not isinstance(wheels, list) or len(wheels) != len(EXPECTED):
        raise DevToolBootstrapRefused("wheel closure is incomplete")
    observed: set[tuple[str, str, str]] = set()
    result: list[tuple[dict[str, Any], Path]] = []
    for item in wheels:
        if not isinstance(item, dict):
            raise DevToolBootstrapRefused("wheel record must be an object")
        identity = (item.get("name"), item.get("version"), item.get("filename"))
        if identity not in EXPECTED or identity in observed:
            raise DevToolBootstrapRefused(f"unexpected or duplicate wheel: {identity}")
        observed.add(identity)
        filename = item["filename"]
        if not filename.endswith(".whl") or filename.endswith((".tar.gz", ".zip")):
            raise DevToolBootstrapRefused("sdists and non-wheel artifacts are forbidden")
        digest = item.get("sha256")
        size = item.get("size")
        license_id = item.get("license")
        compatibility = item.get("compatibility")
        source_url = item.get("source_url")
        if (not isinstance(digest, str) or _SHA256.fullmatch(digest) is None
                or not isinstance(size, int) or size <= 0
                or not isinstance(license_id, str) or not license_id
                or not isinstance(compatibility, list) or not compatibility
                or not isinstance(source_url, str) or not source_url.startswith("https://")):
            raise DevToolBootstrapRefused(f"wheel metadata incomplete: {filename}")
        path = artifact_root / filename
        if not path.is_file() or path.is_symlink():
            raise DevToolBootstrapRefused(f"preseeded wheel unavailable: {filename}")
        if path.stat().st_size != size or _sha256(path) != digest:
            raise DevToolBootstrapRefused(f"wheel size/hash mismatch: {filename}")
        name, version, tags, licenses = _wheel_metadata(path)
        normalized_name = name.lower().replace("-", "_")
        if normalized_name != item["name"] or version != item["version"]:
            raise DevToolBootstrapRefused(f"wheel identity mismatch: {filename}")
        if set(compatibility) != tags:
            raise DevToolBootstrapRefused(f"wheel compatibility mismatch: {filename}")
        if license_id == "MPL-2.0":
            license_ok = any("Mozilla Public License 2.0" in value for value in licenses)
        else:
            license_ok = license_id in licenses
        if not license_ok:
            raise DevToolBootstrapRefused(f"wheel license mismatch: {filename}")
        result.append((item, path))
    if observed != EXPECTED:
        raise DevToolBootstrapRefused("wheel closure identity mismatch")
    extras = {path.name for path in artifact_root.glob("*.whl")} - {
        item["filename"] for item, _ in result
    }
    if extras:
        raise DevToolBootstrapRefused(f"undeclared wheel artifacts present: {sorted(extras)}")
    return result


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def _external_destination(root: Path) -> Path:
    candidate = root.resolve(strict=False)
    repository = _repo_root().resolve(strict=True)
    if candidate == repository or repository in candidate.parents:
        raise DevToolBootstrapRefused("developer tool root must be outside the repository")
    if candidate == candidate.anchor:
        raise DevToolBootstrapRefused("filesystem root is not a valid destination")
    for parent in (candidate, *candidate.parents):
        if parent.exists() and parent.is_symlink():
            raise DevToolBootstrapRefused("destination reparse/symlink component refused")
    return candidate


def _pinned_python() -> Path:
    candidate = (_user_profile() / "AppData" / "Roaming" / "uv" / "python" /
                 "cpython-3.12.13-windows-x86_64-none" / "python.exe")
    if not candidate.is_file() or candidate.is_symlink():
        raise DevToolBootstrapRefused("pinned CPython 3.12.13 runtime is unavailable")
    cp = subprocess.run([str(candidate), "-I", "-S", "--version"], stdin=subprocess.DEVNULL,
                        capture_output=True, text=True, env={}, timeout=15, check=False)
    if cp.returncode != 0 or cp.stdout.strip() != "Python 3.12.13":
        raise DevToolBootstrapRefused("pinned CPython identity mismatch")
    return candidate


def _safe_extract(wheel: Path, destination: Path, claimed: set[Path]) -> None:
    with zipfile.ZipFile(wheel) as archive:
        for info in archive.infolist():
            raw = info.filename
            path = PurePosixPath(raw)
            if (not raw or "\\" in raw or path.is_absolute()
                    or any(part in {"", ".", ".."} for part in path.parts)):
                raise DevToolBootstrapRefused(f"unsafe wheel member: {wheel.name}:{raw}")
            mode = info.external_attr >> 16
            if stat.S_IFMT(mode) == stat.S_IFLNK:
                raise DevToolBootstrapRefused(f"wheel symlink refused: {wheel.name}:{raw}")
            target = destination.joinpath(*path.parts)
            if info.is_dir():
                target.mkdir(parents=True, exist_ok=True)
                continue
            if target in claimed:
                raise DevToolBootstrapRefused(f"wheel member collision: {raw}")
            claimed.add(target)
            target.parent.mkdir(parents=True, exist_ok=True)
            with archive.open(info, "r") as source, target.open("xb") as sink:
                shutil.copyfileobj(source, sink)


def _verify_install(root: Path, lock_digest: str) -> Path:
    python = root / "Scripts" / "python.exe"
    marker = root / ".galaxy-dev-tools.json"
    if not python.is_file() or not marker.is_file():
        raise DevToolBootstrapRefused("existing developer-tool root is incomplete")
    try:
        state = json.loads(marker.read_text("utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DevToolBootstrapRefused("developer-tool marker is invalid") from exc
    if state != {"lock_sha256": lock_digest, "mypy_version": "2.3.0"}:
        raise DevToolBootstrapRefused("developer-tool root is bound to another lock")
    cp = subprocess.run([str(python), "-I", "-m", "mypy", "--version"],
                        stdin=subprocess.DEVNULL, capture_output=True, text=True,
                        env={}, timeout=30, check=False)
    if cp.returncode != 0 or not cp.stdout.startswith("mypy 2.3.0"):
        raise DevToolBootstrapRefused("installed mypy identity mismatch")
    return python


def _install(root: Path, wheels: list[tuple[dict[str, Any], Path]], lock_digest: str) -> Path:
    if root.exists():
        return _verify_install(root, lock_digest)
    runtime = _pinned_python()
    root.parent.mkdir(parents=True, exist_ok=True)
    build = root.parent / f".{root.name}.building-{os.getpid()}"
    if build.exists():
        raise DevToolBootstrapRefused("developer-tool build path collision")
    try:
        cp = subprocess.run([str(runtime), "-I", "-S", "-m", "venv", "--without-pip", str(build)],
                            stdin=subprocess.DEVNULL, capture_output=True, text=True,
                            env={}, timeout=120, check=False)
        if cp.returncode != 0:
            raise DevToolBootstrapRefused(f"offline venv creation failed: {cp.stderr.strip()}")
        site_packages = build / "Lib" / "site-packages"
        site_packages.mkdir(parents=True, exist_ok=True)
        claimed: set[Path] = set()
        for _, wheel in wheels:
            _safe_extract(wheel, site_packages, claimed)
        marker = {"lock_sha256": lock_digest, "mypy_version": "2.3.0"}
        (build / ".galaxy-dev-tools.json").write_text(
            json.dumps(marker, sort_keys=True, separators=(",", ":")), encoding="utf-8"
        )
        _verify_install(build, lock_digest)
        os.replace(build, root)
    finally:
        if build.exists():
            # ``build`` was constructed as a direct child of the already
            # attested external destination parent.
            shutil.rmtree(build)
    return _verify_install(root, lock_digest)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lock", type=Path, required=True)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--validate-lock-only", action="store_true")
    parser.add_argument("--offline", action="store_true")
    parser.add_argument("--only-binary", action="store_true")
    parser.add_argument("--require-hashes", action="store_true")
    parser.add_argument("--print-python-only", action="store_true")
    return parser


def main(argv: Iterable[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        root = _external_destination(args.root)
        lock, raw = _read_lock(args.lock)
        if not args.validate_lock_only:
            poisoned = sorted(name for name in _POISON if os.environ.get(name))
            if poisoned:
                raise DevToolBootstrapRefused(
                    f"ambient pip configuration/index/proxy refused: {poisoned}"
                )
        artifacts = _artifact_root(lock)
        wheels = _validate_lock(lock, artifacts)
        report = {
            "mypy_version": lock["mypy_version"],
            "closure_complete": len(wheels) == len(EXPECTED),
            "all_artifacts_are_wheels": all(path.suffix == ".whl" for _, path in wheels),
            "hashes_sizes_licenses_compatibility_complete": True,
        }
        if args.validate_lock_only:
            print(json.dumps(report, sort_keys=True, separators=(",", ":")))
            return 0
        if not (args.offline and args.only_binary and args.require_hashes):
            raise DevToolBootstrapRefused(
                "--offline, --only-binary, and --require-hashes are mandatory"
            )
        python = _install(root, wheels, hashlib.sha256(raw).hexdigest())
        if args.print_python_only:
            print(python)
        else:
            print(json.dumps({**report, "python": str(python)}, sort_keys=True,
                             separators=(",", ":")))
        return 0
    except (OSError, DevToolBootstrapRefused) as exc:
        print(f"GALAXY developer-tool bootstrap refused: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
