from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from agents.planning.pre_execution_council import CouncilConfig, CouncilRunResult, run_pre_execution_council


def _parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Compare round-robin vs selector council artifacts.")
    parser.add_argument("--task", required=True)
    parser.add_argument("--messages-per-seat", type=int, default=2)
    parser.add_argument("--selector-debate-rounds", type=int, default=1)
    parser.add_argument("--output-dir", default="state/council_runs")
    parser.add_argument("--mock-only", action="store_true", help="Force all comparison seats to mock. This is the default.")
    parser.add_argument("--live-gpt-browser", action="store_true", help="Explicitly allow live GPT browser in comparison.")
    parser.add_argument("--live-gemini", action="store_true", help="Explicitly allow live Gemini in comparison.")
    parser.add_argument("--live-groq", action="store_true", help="Explicitly allow live Groq in comparison.")
    parser.add_argument("--live-cloudflare", action="store_true", help="Explicitly allow live Cloudflare Workers AI in comparison.")
    parser.add_argument("--live-local", action="store_true", help="Explicitly allow live Local LLM in comparison.")
    parser.add_argument("--gpt-project-url", default="")
    parser.add_argument("--gpt-model", default="")
    parser.add_argument("--gpt-reasoning", default="")
    parser.add_argument("--local-model", default="")
    parser.add_argument("--groq-model", default="")
    parser.add_argument("--groq-fallback-models", default="")
    parser.add_argument("--cloudflare-model", default="")
    return parser.parse_args(argv)


def _config(args: argparse.Namespace, *, policy: str) -> CouncilConfig:
    env_cfg = CouncilConfig.from_config()
    live_gpt = bool(args.live_gpt_browser and not args.mock_only)
    live_gemini = bool(args.live_gemini and not args.mock_only)
    live_groq = bool(args.live_groq and not args.mock_only)
    live_cloudflare = bool(args.live_cloudflare and not args.mock_only)
    live_local = bool(args.live_local and not args.mock_only)
    seat_count = 4 + int(live_groq) + int(live_cloudflare)
    return CouncilConfig(
        enabled=True,
        prompt_version=env_cfg.prompt_version,
        messages_per_seat=max(1, args.messages_per_seat),
        total_target_messages=max(1, args.messages_per_seat) * seat_count,
        transcript_mode=env_cfg.transcript_mode,
        compact_protocol=env_cfg.compact_protocol,
        anti_filler=env_cfg.anti_filler,
        conversation_policy=policy,
        selector_debate_rounds=max(1, args.selector_debate_rounds),
        output_dir=args.output_dir,
        logging_enabled=True,
        mock_seats_enabled=True,
        live_gpt_enabled=live_gpt,
        gpt_project_url=args.gpt_project_url,
        gpt_model=args.gpt_model,
        gpt_reasoning=args.gpt_reasoning,
        live_gemini_enabled=live_gemini,
        live_groq_enabled=live_groq,
        live_local_enabled=live_local,
        local_model=args.local_model,
        groq_model=args.groq_model or env_cfg.groq_model,
        groq_fallback_models=args.groq_fallback_models or env_cfg.groq_fallback_models,
        live_cloudflare_enabled=live_cloudflare,
        cloudflare_model=args.cloudflare_model or env_cfg.cloudflare_model,
    )


def _requested_live_text(args: argparse.Namespace) -> str:
    if args.mock_only:
        return "(none)"
    providers = []
    if args.live_gpt_browser:
        providers.append("gpt-browser")
    if args.live_gemini:
        providers.append("gemini")
    if args.live_groq:
        providers.append("groq")
    if args.live_cloudflare:
        providers.append("cloudflare")
    if args.live_local:
        providers.append("local")
    return ",".join(providers) if providers else "(none)"


def _count_prompt_chars(result: CouncilRunResult) -> int:
    return sum(len(m.prompt_excerpt or "") for m in result.messages)


def _metric_line(label: str, result: CouncilRunResult) -> str:
    brief = result.brief
    disagreements = len(result.compact_state.get("disagreements") or [])
    warnings = len(result.warnings)
    prompt_chars = _count_prompt_chars(result)
    live = ",".join(
        sorted({m.speaker for m in result.messages if m.provider_metadata.get("actual_live")})
    ) or "(none)"
    fallbacks = ",".join(
        sorted({m.speaker for m in result.messages if m.provider_metadata.get("fallback")})
    ) or "(none)"
    brief_chars = len(brief.to_markdown()) if brief else 0
    first_slice = brief.recommended_first_execution_slice if brief else "(missing)"
    return (
        f"{label}\tmessages={len(result.messages)}\twarnings={warnings}\t"
        f"disagreements={disagreements}\tprompt_chars={prompt_chars}\tbrief_chars={brief_chars}\t"
        f"live={live}\tfallbacks={fallbacks}\tfirst_slice={first_slice[:160]}"
    )


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv or sys.argv[1:])
    round_result = run_pre_execution_council(
        args.task,
        work_dir=Path.cwd(),
        council_config=_config(args, policy="round_robin"),
    )
    selector_result = run_pre_execution_council(
        args.task,
        work_dir=Path.cwd(),
        council_config=_config(args, policy="selector"),
    )
    print("policy\tmetrics")
    print(f"requested_live_providers\t{_requested_live_text(args)}")
    print(_metric_line("round_robin", round_result))
    print(_metric_line("selector", selector_result))
    print(f"round_robin_log\t{round_result.log_dir}")
    print(f"selector_log\t{selector_result.log_dir}")
    return 0 if round_result.brief and selector_result.brief else 1


if __name__ == "__main__":
    raise SystemExit(main())
