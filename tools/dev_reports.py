"""Reporting, navigation, health-check, and watch commands for the 9to5 dev runner.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  cmd_slow_report(args: list[str]) -> int
  cmd_heartbeat_test(args: list[str]) -> int
  cmd_context_check(args: list[str]) -> int
  cmd_iteration_health(args: list[str]) -> int
  cmd_outline(args: list[str]) -> int
  cmd_where(args: list[str]) -> int
  cmd_watch(args: list[str]) -> int  -- Poll .py mtimes; on any change, run the affected tests
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/evolution/test_selfmod_runner.py tests/platform/test_dev_commands.py
"""
from __future__ import annotations

import ast, json, subprocess, sys, time  # noqa: E401
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import affected_tests  # noqa: E402
import claude_metrics  # noqa: E402
import context_budget  # noqa: E402
import repo_map  # noqa: E402

from dev_checks import (  # noqa: E402
    REPO_ROOT, PY, HEADER_SENTINEL,
    _run, _run_env, _progress_env, _xdist,
)


def _run_tee(cmd: list[str], out_path: Path, *, env: dict[str, str] | None = None,
             pass_no_tests: bool = False) -> int:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = []
    # encoding/errors: on Windows text pipes default to cp1252, so Unicode in pytest output
    # (checkmarks, box-drawing, non-ASCII test names) would raise UnicodeDecodeError mid-stream.
    proc = subprocess.Popen(cmd, cwd=REPO_ROOT, text=True, env=env,
                            encoding="utf-8", errors="replace",
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    assert proc.stdout is not None
    for line in proc.stdout:
        print(line, end="")
        lines.append(line)
    rc = proc.wait()
    raw = "".join(lines)
    tail = "\n".join(raw.strip().splitlines()[-80:])
    out_path.write_text(
        "# Slow Test Report\n\n"
        f"- Command: `{' '.join(cmd)}`\n"
        f"- Exit code: `{rc}`\n"
        f"- Generated: `{time.strftime('%Y-%m-%d %H:%M:%S')}`\n\n"
        "## Tail\n\n"
        "```text\n"
        f"{tail}\n"
        "```\n",
        encoding="utf-8",
    )
    try:
        display = out_path.relative_to(REPO_ROOT)
    except ValueError:
        display = out_path
    print(f"[dev] wrote {display}")
    if pass_no_tests and rc != 0 and "no tests ran" in raw.lower():
        return 0
    return rc


def cmd_slow_report(args: list[str]) -> int:
    cmd = [PY, "-m", "pytest", "-m", "slow", *_xdist(["--durations=30", "-vv", *args])]
    return _run_tee(cmd, REPO_ROOT / "logs" / "slow-test-report.md",
                    env=_progress_env(), pass_no_tests=True)


def cmd_heartbeat_test(args: list[str]) -> int:
    target = REPO_ROOT / "tests" / "fixtures" / "heartbeat_progress_test.py"
    cmd = [PY, "-m", "pytest", str(target), "-q", *args]
    env = _progress_env("1")
    env["NINE_TO_FIVE_REAL_SLEEP"] = "1"
    return _run_env(cmd, env=env).returncode


def cmd_context_check(args: list[str]) -> int:
    return context_budget.main(args)


def cmd_iteration_health(args: list[str]) -> int:  # noqa: ARG001
    git = claude_metrics.git_state()
    print(f"[iteration-health] branch={git['branch']} dirty={git['dirty']} changed={git['changed_files']}")
    rows = context_budget.measure()
    for row in rows:
        state = "ok" if row["ok"] else "WARN"
        print(f"[iteration-health] context {state}: {row['label']} {row['lines']}/{row['max_lines']} lines")
    hooks = claude_metrics.read_recent(claude_metrics.TURN_LOG, limit=5)
    execs = claude_metrics.read_recent(claude_metrics.EXECUTOR_LOG, limit=5)
    print(f"[iteration-health] recent hook events={len(hooks)} executor runs={len(execs)}")
    if execs:
        latest = execs[-1]
        print("[iteration-health] latest executor: "
              f"ok={latest.get('ok')} rc={latest.get('returncode')} "
              f"duration={latest.get('duration_seconds')}s prompt={latest.get('prompt_chars')}ch")
    files = affected_tests._git_changed()
    targets = affected_tests.targets_for(files)
    if targets:
        print("[iteration-health] next: python -m pytest -q " + " ".join(targets[:8]))
    else:
        print("[iteration-health] next: python tools/dev.py fast")
    return 0


def cmd_outline(args: list[str]) -> int:
    if not args:
        print("usage: dev.py outline <file>", file=sys.stderr)
        return 2
    path = Path(args[0])
    if not path.is_absolute():
        path = REPO_ROOT / args[0]
    src = repo_map._read_source(path)
    tree = ast.parse(src)
    doc = (ast.get_docstring(tree) or "").split(HEADER_SENTINEL, 1)[0].strip().split("\n", 1)[0]
    print(f"# {path.relative_to(REPO_ROOT) if str(path).startswith(str(REPO_ROOT)) else path}")
    if doc:
        print(f'"""{doc}"""')
    for i, line in enumerate(src.splitlines(), 1):
        if line.startswith("# ===="):
            print(f"\n{line.strip()}")
    print()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            print(f"{node.lineno}: def {node.name}{repo_map._signature(node)}")
        elif isinstance(node, ast.ClassDef):
            print(f"{node.lineno}: class {node.name}")
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    print(f"  {sub.lineno}:   def {sub.name}{repo_map._signature(sub)}")
    return 0


def cmd_where(args: list[str]) -> int:
    if not args:
        print("usage: dev.py where <symbol>", file=sys.stderr)
        return 2
    sym = args[0]
    jpath = REPO_ROOT / ".repo-map.json"
    if not jpath.exists():
        print("[dev] .repo-map.json missing -- run: python tools/dev.py map", file=sys.stderr)
        return 1
    m = json.loads(jpath.read_text(encoding="utf-8"))
    hits = []
    for dotted, rec in m["modules"].items():
        for e in rec["exports"]:
            if e["name"] == sym:
                hits.append((dotted, rec, e))
    if not hits:
        print(f"[dev] no exported symbol named '{sym}' in the map "
              f"(it may be a private/_-prefixed name).")
        return 1
    for dotted, rec, e in hits:
        print(f"{rec['path']}:{e['lineno']}  {e['kind']} {e['name']}{e['signature']}")
        if e["summary"]:
            print(f"    {e['summary']}")
        callers = rec.get("callers", [])
        print(f"    callers ({len(callers)}): {', '.join(callers) or '(none)'}")
    return 0


def cmd_watch(args: list[str]) -> int:
    """Poll .py mtimes; on any change, run the affected tests. Ctrl-C to stop."""
    watch = [a for a in args if a.endswith(".py")]
    print(f"[dev] watching {'given files' if watch else 'the repo'} -- Ctrl-C to stop")

    def snapshot() -> dict[str, float]:
        files = [REPO_ROOT / w for w in watch] if watch else repo_map.iter_py_files()
        snap = {}
        for f in files:
            try:
                snap[str(f)] = Path(f).stat().st_mtime
            except OSError:
                pass
        return snap

    last = snapshot()
    try:
        while True:
            time.sleep(1.0)
            cur = snapshot()
            changed = [f for f, mt in cur.items() if last.get(f) != mt]
            if changed:
                rel = [str(Path(f).relative_to(REPO_ROOT)) for f in changed]
                print(f"\n[dev] changed: {', '.join(rel)}")
                targets = affected_tests.targets_for(rel)
                if targets:
                    _run([PY, "-m", "pytest", "-q", *targets])
                else:
                    print("[dev] (no mapped tests)")
                last = cur
    except KeyboardInterrupt:
        print("\n[dev] watch stopped")
        return 0
