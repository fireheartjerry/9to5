from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import config
from agents.planning.pre_execution_council import (
    GROQ_DEFAULT_FALLBACK_MODELS,
    GROQ_HTTP_HEADERS,
    _groq_chat_completion,
    _groq_error_category,
    _groq_error_message,
    _split_csv_models,
)


DEFAULT_MODELS = (
    "qwen/qwen3-32b",
    "llama-3.1-8b-instant",
    "llama-3.3-70b-versatile",
    "openai/gpt-oss-20b",
)

GROQ_BASE_URL = "https://api.groq.com/openai/v1"


def _parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Probe Groq model access without printing secrets.")
    parser.add_argument(
        "--models",
        default=",".join(DEFAULT_MODELS),
        help="Comma-separated Groq models to probe.",
    )
    parser.add_argument("--timeout", type=float, default=20.0)
    return parser.parse_args(argv)


def _models_from_config_or_args(raw: str) -> list[str]:
    models = _split_csv_models(raw)
    if models:
        return models
    primary = str(getattr(config, "PRE_EXECUTION_COUNCIL_GROQ_MODEL", "") or "qwen/qwen3-32b")
    fallbacks = _split_csv_models(getattr(config, "PRE_EXECUTION_COUNCIL_GROQ_FALLBACK_MODELS", ""))
    return [primary, *(fallbacks or list(GROQ_DEFAULT_FALLBACK_MODELS))]


def _dedupe(models: list[str]) -> list[str]:
    seen = set()
    out = []
    for model in models:
        if model and model not in seen:
            seen.add(model)
            out.append(model)
    return out


def _probe_model(model: str, timeout: float) -> tuple[str, str, bool]:
    try:
        reply = _groq_chat_completion(
            model=model,
            messages=[
                {
                    "role": "user",
                    "content": "Reply with exactly: groq_probe_ok",
                }
            ],
            temperature=0.0,
            timeout=timeout,
        )
        if not reply:
            return ("empty_response", "empty_response", False)
        return ("ok", "ok", True)
    except Exception as exc:  # noqa: BLE001 -- probe reports safe categories only
        root = exc.__cause__ if exc.__cause__ is not None else exc
        category = _groq_error_category(root)
        message = _groq_error_message(root)
        if isinstance(root, urllib.error.HTTPError):
            message = f"http_{getattr(root, 'code', 'unknown')}"
        return (category, message, False)


def _probe_models_endpoint(timeout: float) -> tuple[str, str, bool, list[str]]:
    api_key = os.getenv("GROQ_API_KEY", "")
    if not api_key:
        return ("auth", "missing_key", False, [])
    req = urllib.request.Request(
        f"{GROQ_BASE_URL}/models",
        headers={
            **GROQ_HTTP_HEADERS,
            "Authorization": f"Bearer {api_key}",
        },
        method="GET",
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8", errors="replace"))
    except Exception as exc:  # noqa: BLE001 -- report safe category only
        root = exc.__cause__ if exc.__cause__ is not None else exc
        category = _groq_error_category(root)
        if isinstance(root, urllib.error.HTTPError):
            return (category, f"http_{getattr(root, 'code', 'unknown')}", False, [])
        return (category, _groq_error_message(root), False, [])
    raw_models = data.get("data") if isinstance(data, dict) else []
    model_ids = []
    if isinstance(raw_models, list):
        for item in raw_models:
            if isinstance(item, dict) and item.get("id"):
                model_ids.append(str(item["id"]))
    return ("ok", "ok", True, model_ids)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv or sys.argv[1:])
    models = _dedupe(_models_from_config_or_args(args.models))
    print("check\ttarget\tstatus\terror_category\tactual_live")
    if not models:
        print("chat\t(none)\tmissing_model\tconfiguration\tfalse")
        return 2
    if not getattr(config, "PRE_EXECUTION_COUNCIL_GROQ_MODEL", "") and not models:
        print("chat\t(none)\tmissing_model\tconfiguration\tfalse")
        return 2
    if not os.getenv("GROQ_API_KEY", ""):
        for model in models:
            print(f"chat\t{model}\tmissing_key\tauth\tfalse")
        return 2
    models_category, models_status, models_live, model_ids = _probe_models_endpoint(args.timeout)
    visible = ",".join(model_ids[:8]) if model_ids else "(none)"
    print(f"models\t{visible}\t{models_status}\t{models_category}\t{str(models_live).lower()}")
    any_live = False
    for model in models:
        category, status, live = _probe_model(model, args.timeout)
        any_live = any_live or live
        print(f"chat\t{model}\t{status}\t{category}\t{str(live).lower()}")
    return 0 if any_live else 1


if __name__ == "__main__":
    raise SystemExit(main())
