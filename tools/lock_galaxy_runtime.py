def _canonical(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")


def _sha_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _sha_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _powershell_signature_record(path: Path) -> dict[str, object]:
    """Verify the pinned Windows PowerShell Authenticode identity without modules."""
    resolved = path.resolve(strict=True)
    encoded_path = base64.b64encode(str(resolved).encode("utf-8")).decode("ascii")
    script = rf"""
$ErrorActionPreference='Stop'
$path=[System.Text.Encoding]::UTF8.GetString(
    [System.Convert]::FromBase64String('{encoded_path}'))
$signature=Microsoft.PowerShell.Security\Get-AuthenticodeSignature `
    -LiteralPath $path -ErrorAction Stop
if ($null -eq $signature -or $null -eq $signature.SignerCertificate) {{
    throw 'host signer is unavailable'
}}
$record=[ordered]@{{
    is_os_binary=[bool]$signature.IsOSBinary
    signature_type=[string]$signature.SignatureType
    signer_subject=[string]$signature.SignerCertificate.Subject
    signer_thumbprint=([string]$signature.SignerCertificate.Thumbprint).ToLowerInvariant()
    status=[string]$signature.Status
}}
[System.Console]::Out.Write(($record | ConvertTo-Json -Compress))
"""
    with tempfile.TemporaryDirectory(prefix="galaxy-host-signature-") as empty_cwd:
        completed = subprocess.run(
            [
                str(resolved),
                "-NoLogo",
                "-NoProfile",
                "-NonInteractive",
                "-Command",
                script,
            ],
            cwd=empty_cwd,
            env={
                "SystemRoot": os.environ["SystemRoot"],
                "WINDIR": os.environ["SystemRoot"],
                "PSModulePath": str(
                    Path(os.environ["SystemRoot"])
                    / "System32/WindowsPowerShell/v1.0/Modules"
                ),
            },
            stdin=subprocess.DEVNULL,
            text=True,
            capture_output=True,
            timeout=30,
            check=False,
        )
    if completed.returncode != 0:
        raise RuntimeLockRefused(
            f"PowerShell Authenticode verification failed: {completed.stderr.strip()}"
        )
    try:
        value = json.loads(completed.stdout)
    except json.JSONDecodeError as exc:
        raise RuntimeLockRefused("PowerShell signature record is not JSON") from exc
    expected = {
        "is_os_binary",
        "signature_type",
        "signer_subject",
        "signer_thumbprint",
        "status",
    }
    if (
        not isinstance(value, dict)
        or set(value) != expected
        or value["status"] != "Valid"
        or value["is_os_binary"] is not True
        or value["signature_type"] not in {"Catalog", "Authenticode"}
        or not isinstance(value["signer_subject"], str)
        or not value["signer_subject"].startswith("CN=Microsoft Windows,")
        or not isinstance(value["signer_thumbprint"], str)
        or re.fullmatch(r"[0-9a-f]{40}", value["signer_thumbprint"]) is None
    ):
        raise RuntimeLockRefused("PowerShell host is not the valid OS-owned signer")
    return value


