def _compile_windows_sha1dc(
    *,
    source_archive: Path,
    output: Path,
    evidence_path: Path,
    probe: Callable[[Path, tuple[str, ...], bytes], tuple[int, bytes, bytes]] = _probeSha1dc,
) -> dict[str, Any]:
    """Double-build and exercise the separate native Windows SHA1DC oracle."""

    if os.name != "nt":
        raise RuntimeLockRefused("the SHA1DC Windows host build requires Windows")
    source_lock_path = REPOSITORY_ROOT / "bootstrap/galaxy_launcher/sha1dc_source.lock.json"
    source_passport_path = (
        REPOSITORY_ROOT / "bootstrap/galaxy_launcher/sha1dc_source_passport.json"
    )
    wrapper_path = REPOSITORY_ROOT / "containers/galaxy/sha1dc_object_oracle.c"
    from tools.build_sha1dc_oracle import (
        Sha1dcBuildRefused,
        _extract_source,
        _verify_archive,
        readSha1dcSourceLock,
        readSha1dcSourcePassport,
    )

    try:
        archive = _ordinary_file(source_archive, "retained SHA1DC source archive")
        source_lock = readSha1dcSourceLock(source_lock_path)
        readSha1dcSourcePassport(source_passport_path, source=source_lock)
        _verify_archive(source_lock, archive)
    except (OSError, Sha1dcBuildRefused) as exc:
        raise RuntimeLockRefused("retained SHA1DC source closure differs") from exc
    wrapper = _ordinary_file(wrapper_path, "SHA1DC oracle wrapper")
    compiler = _ordinary_file(
        PINNED_GCC,
        "pinned native compiler",
        require_single_link=False,
    )
    if _sha_file(compiler) != PINNED_GCC_SHA256:
        raise RuntimeLockRefused("pinned native compiler digest drift")
    if output.exists() or evidence_path.exists():
        raise RuntimeLockRefused("SHA1DC Windows build output collision")
    output.parent.mkdir(parents=True, exist_ok=True)
    evidence_path.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(
        prefix="galaxy-sha1dc-windows-build-",
        dir=output.parent,
    ) as temporary:
        build_root = Path(temporary)
        environment = _compiler_environment(build_root)
        version_result = subprocess.run(
            [str(compiler), "--version"],
            cwd=build_root,
            env=environment,
            text=True,
            capture_output=True,
            timeout=20,
            check=False,
            shell=False,
        )
        version = version_result.stdout.splitlines()[0] if version_result.stdout else ""
        if version_result.returncode != 0 or version != PINNED_GCC_VERSION:
            raise RuntimeLockRefused("pinned native compiler version drift")

        source_root = build_root / "source"
        try:
            _extract_source(source_lock, archive, source_root)
        except Sha1dcBuildRefused as exc:
            raise RuntimeLockRefused("SHA1DC source extraction was refused") from exc
        shutil.copyfile(wrapper, source_root / "galaxy_sha1dc.c")
        first = build_root / "build-one" / "galaxy-sha1dc.exe"
        second = build_root / "build-two" / "galaxy-sha1dc.exe"
        for candidate in (first, second):
            candidate.parent.mkdir()
            actual_flags = [
                *(_SHA1DC_WINDOWS_FLAGS[:8]),
                f"-ffile-prefix-map={source_root}=.",
                *(_SHA1DC_WINDOWS_FLAGS[9:]),
            ]
            command = [
                str(compiler),
                *actual_flags,
                f"-I{source_root / 'lib'}",
                str(source_root / "galaxy_sha1dc.c"),
                str(source_root / "lib/sha1.c"),
                str(source_root / "lib/ubc_check.c"),
                "-o",
                str(candidate),
            ]
            completed = subprocess.run(
                command,
                cwd=build_root,
                env=environment,
                text=True,
                capture_output=True,
                timeout=120,
                check=False,
                shell=False,
            )
            if completed.returncode != 0:
                raise RuntimeLockRefused(
                    "SHA1DC Windows compilation failed: " + completed.stderr.strip()
                )
            if not candidate.is_file() or candidate.is_symlink():
                raise RuntimeLockRefused("SHA1DC Windows compiler produced no ordinary file")
            _assert_windows_pe(candidate)

        first_raw = first.read_bytes()
        second_raw = second.read_bytes()
        first_digest = _sha_bytes(first_raw)
        second_digest = _sha_bytes(second_raw)
        if first_raw != second_raw or first_digest != second_digest:
            raise RuntimeLockRefused("SHA1DC Windows double-build was not reproducible")

        for arguments, expected in (
            (("--version",), _SHA1DC_VERSION),
            (("--self-test",), _SHA1DC_SELF_TEST),
        ):
            returncode, stdout, stderr = probe(first, arguments, b"")
            if returncode != 0 or stderr or stdout != expected:
                raise RuntimeLockRefused(
                    "SHA1DC Windows runtime self-test differs: "
                    f"arguments={arguments!r} returncode={returncode} "
                    f"stdout={stdout!r} stderr={stderr!r}"
                )
        corpus = (
            ("blob", b""),
            ("blob", b"hello\n"),
            ("tree", b"100644 a.txt\0" + bytes.fromhex("0" * 40)),
            ("commit", b"tree " + b"0" * 40 + b"\n\nmessage\n"),
        )
        for object_type, payload in corpus:
            frame = (
                object_type.encode("ascii")
                + b" "
                + str(len(payload)).encode("ascii")
                + b"\0"
                + payload
            )
            expected = (
                hashlib.sha1(frame, usedforsecurity=False).hexdigest().encode("ascii")
                + b"\n"
            )
            returncode, stdout, stderr = probe(
                first,
                ("hash-object", object_type, str(len(payload))),
                payload,
            )
            if returncode != 0 or stderr or stdout != expected:
                raise RuntimeLockRefused("SHA1DC Windows normal-object corpus differs")
        _copy_file(first, output)

    _assert_windows_pe(output)
    output_digest = _sha_file(output)
    if output_digest != first_digest:
        raise RuntimeLockRefused("SHA1DC Windows final output digest differs")
    evidence: dict[str, Any] = {
        "schema": "galaxy.sha1dc-windows-build-evidence/v1",
        "authority": "inactive",
        "platform": "windows",
        "architecture": "amd64",
        "compiler": {
            "path": str(compiler),
            "sha256": PINNED_GCC_SHA256,
            "version": PINNED_GCC_VERSION,
        },
        "environment": {
            "LC_ALL": "C",
            "SOURCE_DATE_EPOCH": "0",
            "inherited_environment": False,
        },
        "flags": list(_SHA1DC_WINDOWS_FLAGS),
        "source_archive_sha256": source_lock.archive_sha256,
        "source_archive_size": source_lock.archive_size,
        "source_lock_sha256": _sha_file(source_lock_path),
        "source_passport_sha256": _sha_file(source_passport_path),
        "source_revision": source_lock.revision,
        "source_tree_oid": source_lock.tree_oid,
        "source_files": [
            {"path": item.path, "sha256": item.sha256, "size": item.size}
            for item in source_lock.files
        ],
        "wrapper_sha256": _sha_file(wrapper),
        "first_output_sha256": first_digest,
        "second_output_sha256": second_digest,
        "output_sha256": output_digest,
        "output_size": output.stat().st_size,
        "reproducibility_runs": 2,
        "self_test": "collision-detected-and-normal-sha1-exact",
        "normal_object_corpus_count": len(corpus),
        "network_allowed": False,
    }
    _write_canonical(evidence_path, evidence)
    return evidence


def _compile_powershell_launcher(
    *,
    source: Path,
    output: Path,
    evidence_path: Path,
) -> dict[str, Any]:
    """Double-build the empty-environment PowerShell wrapper byte-for-byte."""
    source = source.resolve(strict=True)
    if source.is_symlink() or not source.is_file():
        raise RuntimeLockRefused("PowerShell wrapper source is not an ordinary file")
    if not PINNED_GCC.is_file() or PINNED_GCC.is_symlink():
        raise RuntimeLockRefused("pinned native wrapper compiler is unavailable")
    if _sha_file(PINNED_GCC) != PINNED_GCC_SHA256:
        raise RuntimeLockRefused("pinned native wrapper compiler digest drift")
    output.parent.mkdir(parents=True, exist_ok=True)
    environment = _compiler_environment(output.parent)
    version_result = subprocess.run(
        [str(PINNED_GCC), "--version"],
        cwd=output.parent,
        env=environment,
        text=True,
        capture_output=True,
        timeout=20,
        check=False,
    )
    version = version_result.stdout.splitlines()[0] if version_result.stdout else ""
    if version_result.returncode != 0 or version != PINNED_GCC_VERSION:
        raise RuntimeLockRefused("pinned native wrapper compiler version drift")
    candidates = (
        output.with_name(f".{output.name}.first"),
        output.with_name(f".{output.name}.second"),
    )
    for candidate in candidates:
        if candidate.exists():
            raise RuntimeLockRefused("native wrapper build output collision")
        command = [
            str(PINNED_GCC),
            *POWERSHELL_WRAPPER_FLAGS,
            str(source),
            "-o",
            str(candidate),
        ]
        completed = subprocess.run(
            command,
            cwd=output.parent,
            env=environment,
            text=True,
            capture_output=True,
            timeout=60,
            check=False,
        )
        if completed.returncode != 0:
            raise RuntimeLockRefused(
                "native wrapper compilation failed: " + completed.stderr.strip()
            )
        if not candidate.is_file() or candidate.is_symlink():
            raise RuntimeLockRefused("native wrapper compiler produced no ordinary file")
    first_digest = _sha_file(candidates[0])
    second_digest = _sha_file(candidates[1])
    if first_digest != second_digest or candidates[0].read_bytes() != candidates[1].read_bytes():
        raise RuntimeLockRefused("native wrapper double-build was not reproducible")
    if output.exists():
        raise RuntimeLockRefused("native wrapper final output collision")
    shutil.copyfile(candidates[0], output)
    for candidate in candidates:
        candidate.unlink()
    evidence: dict[str, Any] = {
        "schema": "galaxy.native-wrapper-build/v1",
        "authority": "inactive",
        "compiler": {
            "path": str(PINNED_GCC.resolve()),
            "sha256": PINNED_GCC_SHA256,
            "version": version,
        },
        "environment": {
            "LC_ALL": "C",
            "SOURCE_DATE_EPOCH": "0",
            "inherited_environment": False,
        },
        "flags": list(POWERSHELL_WRAPPER_FLAGS),
        "source_logical_path": "bootstrap/galaxy_launcher/powershell_env_launcher.c",
        "source_sha256": _sha_file(source),
        "first_output_sha256": first_digest,
        "second_output_sha256": second_digest,
        "output_sha256": _sha_file(output),
        "reproducible": True,
    }
    _write_canonical(evidence_path, evidence)
    return evidence


def _current_sid(powershell: Path) -> str:
    windows_environment = {
        "SystemRoot": os.environ["SystemRoot"],
        "WINDIR": os.environ["SystemRoot"],
    }
    completed = subprocess.run(
        [
            str(powershell),
            "-NoLogo",
            "-NoProfile",
            "-NonInteractive",
            "-Command",
            "[System.Security.Principal.WindowsIdentity]::GetCurrent().User.Value",
        ],
        env=windows_environment,
        text=True,
        capture_output=True,
        timeout=20,
        check=False,
    )
    sid = completed.stdout.strip()
    if completed.returncode != 0 or re.fullmatch(r"S-1(?:-[0-9]+)+", sid) is None:
        raise RuntimeLockRefused("operator SID could not be resolved")
    return sid


def _service_sid() -> str:
    windows_environment = {
        "SystemRoot": os.environ["SystemRoot"],
        "WINDIR": os.environ["SystemRoot"],
    }
    completed = subprocess.run(
        [str(Path(os.environ["SystemRoot"]) / "System32" / "sc.exe"), "showsid", SERVICE_NAME],
        env=windows_environment,
        text=True,
        capture_output=True,
        timeout=20,
        check=False,
    )
    match = re.search(r"SERVICE SID:\s*(S-1(?:-[0-9]+)+)", completed.stdout)
    if completed.returncode != 0 or match is None:
        raise RuntimeLockRefused("service SID could not be derived")
    return match.group(1)


def _leaf(logical: str, staging: Path | None, installed: Path) -> dict[str, Any]:
    source = staging if staging is not None else installed
    return {
        "logical_path": logical,
        "staging_path": str(staging.resolve()) if staging is not None else None,
        "installed_path": str(installed.absolute()),
        "size": source.stat().st_size,
        "sha256": _sha_file(source),
    }


def _leaf_root(domain: str, leaves: Iterable[Mapping[str, Any]]) -> str:
    hashes = []
    for leaf in leaves:
        record = {
            "logical_path": leaf["logical_path"],
            "sha256": leaf["sha256"],
            "size": leaf["size"],
        }
        hashes.append(hashlib.sha256(_canonical(record)).digest())
    return hashlib.sha256(domain.encode("ascii") + b"\0" + b"".join(sorted(hashes))).hexdigest()


def _profile_digest(record: Mapping[str, Any]) -> str:
    return _sha_bytes(_canonical(record))


