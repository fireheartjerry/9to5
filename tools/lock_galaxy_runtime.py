class RuntimeLockRefused(RuntimeError):
    """The proposed runtime closure was incomplete, ambiguous, or drifted."""


def _probeSha1dc(
    executable: Path,
    arguments: tuple[str, ...],
    payload: bytes = b"",
) -> tuple[int, bytes, bytes]:
    try:
        with tempfile.TemporaryDirectory(prefix="galaxy-sha1dc-admission-") as work:
            completed = subprocess.run(
                [str(executable), *arguments],
                cwd=work,
                env={},
                input=payload,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                timeout=15,
                check=False,
                shell=False,
                creationflags=(
                    getattr(subprocess, "CREATE_NO_WINDOW", 0) if os.name == "nt" else 0
                ),
            )
    except (OSError, subprocess.SubprocessError) as exc:
        raise RuntimeLockRefused("SHA1DC runtime probe could not execute") from exc
    return completed.returncode, completed.stdout, completed.stderr


def _assert_windows_pe(executable: Path) -> None:
    """Refuse ELF or malformed output at the Windows host-executable boundary."""

    try:
        raw = executable.read_bytes()
    except OSError as exc:
        raise RuntimeLockRefused("SHA1DC Windows PE is unavailable") from exc
    if len(raw) < 0x88 or raw[:2] != b"MZ":
        raise RuntimeLockRefused("SHA1DC host executable is not a Windows PE")
    pe_offset = int.from_bytes(raw[0x3C:0x40], "little")
    if (
        pe_offset < 0x40
        or pe_offset + 6 > len(raw)
        or raw[pe_offset : pe_offset + 4] != b"PE\0\0"
        or int.from_bytes(raw[pe_offset + 4 : pe_offset + 6], "little") != 0x8664
    ):
        raise RuntimeLockRefused("SHA1DC host executable is not an amd64 Windows PE")


