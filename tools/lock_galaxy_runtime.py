def _ordinary_file(
    path: Path, label: str, *, require_single_link: bool = True
) -> Path:
    _assert_no_reparse(path, label)
    try:
        resolved = path.resolve(strict=True)
        metadata = resolved.stat()
    except OSError as exc:
        raise RuntimeLockRefused(f"{label} is unavailable") from exc
    if not resolved.is_file() or (require_single_link and metadata.st_nlink != 1):
        qualifier = "single-link " if require_single_link else ""
        raise RuntimeLockRefused(f"{label} must be a {qualifier}ordinary file")
    return resolved


def _source_leaf(logical: str, path: Path) -> dict[str, object]:
    ordinary = _ordinary_file(path, f"source leaf {logical}")
    return {
        "path": logical,
        "sha256": _sha_file(ordinary),
        "size": ordinary.stat().st_size,
    }


def _artifact_record(path: Path, label: str) -> dict[str, object]:
    ordinary = _ordinary_file(path, label, require_single_link=False)
    return {
        "path": str(ordinary),
        "sha256": _sha_file(ordinary),
        "size": ordinary.stat().st_size,
    }


def _python_source_leaves(root: Path) -> list[dict[str, object]]:
    _assert_no_reparse(root, "Python runtime root")
    try:
        resolved = root.resolve(strict=True)
    except OSError as exc:
        raise RuntimeLockRefused("Python runtime root is unavailable") from exc
    if not resolved.is_dir():
        raise RuntimeLockRefused("Python runtime root is not a directory")
    leaves: list[dict[str, object]] = []
    for path in sorted(resolved.rglob("*"), key=lambda value: value.as_posix().casefold()):
        relative = path.relative_to(resolved)
        if "__pycache__" in relative.parts or path.suffix.casefold() == ".pyc":
            continue
        if path.is_dir():
            continue
        ordinary = _ordinary_file(
            path,
            f"Python runtime leaf {relative.as_posix()}",
            require_single_link=False,
        )
        leaves.append(
            {
                "path": relative.as_posix(),
                "sha256": _sha_file(ordinary),
                "size": ordinary.stat().st_size,
            }
        )
    if not leaves or not any(leaf["path"] == "python.exe" for leaf in leaves):
        raise RuntimeLockRefused("Python runtime closure has no interpreter")
    return leaves


def _reviewed_leaf_root(domain: str, leaves: Sequence[Mapping[str, object]]) -> str:
    canonical = [
        {
            "path": leaf["path"],
            "sha256": leaf["sha256"],
            "size": leaf["size"],
        }
        for leaf in sorted(leaves, key=lambda value: str(value["path"]))
    ]
    return _sha_bytes(domain.encode("ascii") + b"\0" + _canonical(canonical))


def write_reviewed_source_lock(
    *,
    manifest_path: Path,
    lock_path: Path,
    python_root: Path,
    powershell: Path,
    json_assembly: Path,
    image_lock: Path,
    source_paths: Mapping[str, Path] | None = None,
) -> tuple[dict[str, object], dict[str, object]]:
    """Write the inert reviewed source manifest and platform content lock."""
    selected = dict(_reviewed_source_paths() if source_paths is None else source_paths)
    if not selected or any(
        not logical or "\\" in logical or Path(logical).is_absolute() or ".." in Path(logical).parts
        for logical in selected
    ):
        raise RuntimeLockRefused("reviewed source path set is empty or non-canonical")
    source_leaves = [_source_leaf(logical, selected[logical]) for logical in sorted(selected)]
    manifest: dict[str, object] = {
        "authority": "inactive",
        "canonicalization_policy": "strict-utf8-parent-bom-preserving-crlf-to-lf-or-exact",
        "generated_companions": [
            "bootstrap/galaxy_launcher/manifest.json",
            "bootstrap/galaxy_launcher/runtime.lock.json",
        ],
        "schema": "galaxy.bootstrap-source-manifest/v1",
        "source_leaves": source_leaves,
        "source_root": _reviewed_leaf_root("galaxy-bootstrap-source-v1", source_leaves),
    }
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    _write_canonical(manifest_path, manifest)

    python_leaves = _python_source_leaves(python_root)
    host = _ordinary_file(powershell, "PowerShell host", require_single_link=False)
    parser = _ordinary_file(
        json_assembly, "JSON parser assembly", require_single_link=False
    )
    images = _ordinary_file(image_lock, "activation image lock")
    lock: dict[str, object] = {
        "ambient_site_packages_allowed": False,
        "architecture": "amd64" if sys.maxsize > 2**32 else "x86",
        "authority": "inactive",
        "image_lock": {
            "path": str(images),
            "sha256": _sha_file(images),
            "size": images.stat().st_size,
        },
        "isolated_flags": ["-I", "-S"],
        "json_parser": _artifact_record(parser, "JSON parser assembly"),
        "network_allowed": False,
        "platform": "windows",
        "powershell": _artifact_record(host, "PowerShell host"),
        "python_leaves": python_leaves,
        "python_root": str(Path(python_root).resolve(strict=True)),
        "python_tree_root": _reviewed_leaf_root("galaxy-python-runtime-v1", python_leaves),
        "schema": "galaxy.controller-runtime-source-lock/v1",
        "source_manifest_sha256": _sha_file(manifest_path),
        "status": "reviewed_inactive",
    }
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    _write_canonical(lock_path, lock)
    return manifest, lock


def _read_canonical_object(path: Path, label: str) -> dict[str, Any]:
    ordinary = _ordinary_file(path, label)
    try:
        raw = ordinary.read_bytes()
        value = json.loads(raw.decode("utf-8", errors="strict"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise RuntimeLockRefused(f"{label} is not strict JSON") from exc
    if not isinstance(value, dict) or raw != _canonical(value):
        raise RuntimeLockRefused(f"{label} is not canonical JSON")
    return value


