def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="lock-galaxy-runtime")
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--prepare", action="store_true")
    modes.add_argument("--verify-proposal")
    modes.add_argument("--write-reviewed-locks", action="store_true")
    parser.add_argument("--output-root")
    parser.add_argument("--final-root")
    parser.add_argument("--python-root")
    parser.add_argument("--image-root")
    parser.add_argument("--checkout-root")
    parser.add_argument("--generation", type=int, default=1)
    parser.add_argument("--manifest-output")
    parser.add_argument("--lock-output")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.write_reviewed_locks:
            if not args.python_root or not args.manifest_output or not args.lock_output:
                raise RuntimeLockRefused(
                    "reviewed-lock generation requires Python root and both outputs"
                )
            if any(
                value is not None
                for value in (
                    args.output_root,
                    args.final_root,
                    args.image_root,
                    args.checkout_root,
                )
            ):
                raise RuntimeLockRefused("reviewed-lock generation accepts no staging roots")
            system_root = Path(os.environ["SystemRoot"])
            framework = "Framework64" if sys.maxsize > 2**32 else "Framework"
            write_reviewed_source_lock(
                manifest_path=Path(args.manifest_output),
                lock_path=Path(args.lock_output),
                python_root=Path(args.python_root),
                powershell=(
                    system_root
                    / "System32/WindowsPowerShell/v1.0/powershell.exe"
                ),
                json_assembly=(
                    system_root
                    / "Microsoft.NET"
                    / framework
                    / "v4.0.30319/System.Web.Extensions.dll"
                ),
                image_lock=(
                    REPOSITORY_ROOT
                    / "bootstrap/galaxy_launcher/activation_images.lock.json"
                ),
            )
            sys.stdout.write("reviewed inactive source/runtime locks written\n")
            return 0
        if args.prepare:
            required = (
                args.output_root,
                args.final_root,
                args.python_root,
                args.image_root,
                args.checkout_root,
            )
            if any(value is None for value in required):
                raise RuntimeLockRefused("prepare requires every closure root")
            proposal = prepare_runtime(
                output_root=Path(args.output_root),
                final_root=Path(args.final_root),
                python_root=Path(args.python_root),
                image_root=Path(args.image_root),
                checkout_root=Path(args.checkout_root),
                generation=args.generation,
            )
            sys.stdout.write(str(proposal.resolve()) + "\n")
            return 0
        if any(
            value is not None
            for value in (
                args.output_root,
                args.final_root,
                args.python_root,
                args.image_root,
                args.checkout_root,
                args.manifest_output,
                args.lock_output,
            )
        ):
            raise RuntimeLockRefused("verify mode accepts only the proposal path")
        verify_proposal(Path(args.verify_proposal))
        sys.stdout.write("TOFU proposal closure verified; no authority granted\n")
        return 0
    except (OSError, ValueError, KeyError, RuntimeLockRefused) as exc:
        sys.stderr.write(f"{type(exc).__name__}: {exc}\n")
        return 78


if __name__ == "__main__":
    raise SystemExit(main())
