def _copy_python_tree(source: Path, staging: Path, installed: Path) -> list[dict[str, Any]]:
    leaves = []
    for path in sorted(source.rglob("*"), key=lambda item: item.as_posix().casefold()):
        if path.is_dir():
            continue
        relative = path.relative_to(source)
        if "__pycache__" in relative.parts or path.suffix.casefold() in {".pyc", ".pyo"}:
            continue
        if path.is_symlink() or not path.is_file():
            raise RuntimeLockRefused(f"Python runtime contains a non-file: {path}")
        destination = staging / relative
        _copy_file(path, destination)
        leaves.append(
            _leaf(
                f"python/{relative.as_posix()}",
                destination,
                installed / relative,
            )
        )
    return leaves


