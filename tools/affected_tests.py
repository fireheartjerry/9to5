"""affected_tests -- map changed source files to the pytest targets that cover them.

Reuses ``repo_map.find_tests`` (same module->test resolution as the @AI-MAP RUN/TEST line) so the
verify loop runs only the 2-3 relevant tests instead of the whole 137-file suite. A changed file
that IS a test maps to itself.

Usage:
  python tools/affected_tests.py path/a.py path/b.py        # explicit files
  python tools/affected_tests.py $(git diff --name-only)    # everything changed
  (no args) -> reads `git diff --name-only HEAD` itself
Prints space-joined pytest targets on stdout (empty if nothing maps).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  targets_for(files: list[str]) -> list[str]  -- Union of covering tests for ``files`` (repo-relative or absolute), deterministic + dedu…
  main(argv: list[str]) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import repo_map  # noqa: E402

REPO_ROOT = repo_map.REPO_ROOT


def _git_changed() -> list[str]:
    try:
        out = subprocess.run(["git", "diff", "--name-only", "HEAD"], cwd=REPO_ROOT,
                             capture_output=True, text=True, timeout=30)
        return [ln.strip() for ln in out.stdout.splitlines() if ln.strip().endswith(".py")]
    except Exception:  # noqa: BLE001
        return []


def targets_for(files: list[str]) -> list[str]:
    """Union of covering tests for ``files`` (repo-relative or absolute), deterministic + deduped."""
    tests: set[str] = set()
    for f in files:
        p = Path(f)
        if not p.is_absolute():
            p = REPO_ROOT / f
        if not p.exists() or p.suffix != ".py":
            continue
        rel = p.relative_to(REPO_ROOT).as_posix() if str(p).startswith(str(REPO_ROOT)) else f
        if rel.startswith("tests/") and p.name.startswith("test_"):
            tests.add(rel)                       # a changed test covers itself
            continue
        dotted = repo_map.module_dotted(p)
        for t in repo_map.find_tests(dotted, p.stem):
            tests.add(t)
    return sorted(tests)


def main(argv: list[str]) -> int:
    files = argv or _git_changed()
    print(" ".join(targets_for(files)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
