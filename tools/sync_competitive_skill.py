"""Install the versioned competitive-systems skill into a Codex skills directory.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  sync(destination: Path) -> Path
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: copies .claude/skills/competitive-systems into the selected destination
RUN/TEST: python -m pytest tests/platform/test_sync_competitive_skill.py
"""
from __future__ import annotations

import argparse
import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / ".claude" / "skills" / "competitive-systems"


def sync(destination: Path) -> Path:
    """Copy the canonical project skill to ``destination/competitive-systems``."""
    if not (SOURCE / "SKILL.md").exists():
        raise FileNotFoundError(SOURCE / "SKILL.md")
    target = destination / SOURCE.name
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(SOURCE, target)
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Sync the 9to5 competitive-systems skill into Codex.")
    parser.add_argument("--destination", type=Path, default=Path.home() / ".codex" / "skills")
    args = parser.parse_args(argv)
    print(sync(args.destination))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
