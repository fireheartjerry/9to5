"""Claude Code status line for 9TO5.

Reads Claude's optional JSON payload from stdin and prints one compact line. It
is safe to run outside Claude Code for smoke tests.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  main() -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/platform/test_claude_statusline.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import claude_metrics  # noqa: E402


def _read_payload() -> dict:
    try:
        raw = sys.stdin.read()
        obj = json.loads(raw) if raw.strip() else {}
        return obj if isinstance(obj, dict) else {}
    except Exception:
        return {}


def main() -> int:
    payload = _read_payload()
    git = claude_metrics.git_state()
    model = payload.get("model") or payload.get("model_name") or "claude"
    cost = payload.get("cost_usd") or payload.get("total_cost_usd")
    cost_part = f" ${float(cost):.3f}" if isinstance(cost, (int, float)) else ""
    dirty = f"+{git['changed_files']}" if git["dirty"] else "clean"
    print(f"9TO5 {model}{cost_part} | {git['branch']} {dirty}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
