from __future__ import annotations

import sys
from typing import Any

# Force UTF-8 stdio so emoji/arrows in prints, logs, and dashboards never crash
# under Windows' cp1252 default (e.g. when stdout is redirected to a file).
for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
    except Exception:  # noqa: BLE001 -- not a real TextIOWrapper; ignore
        pass

from platform_core.app_config import settings as _settings  # noqa: E402
# Never-crash env readers: tests exercise them as ``config._envInt`` / ``config._envFloat``.
from platform_core.app_config._env import _envBool, _envFloat, _envInt  # noqa: E402,F401
from platform_core.app_config.paths import ensureDirs  # noqa: E402,F401
from platform_core.app_config.settings import getLogger  # noqa: E402,F401

_SELF = sys.modules[__name__]

# Explicit export surface: every registry constant + the facade helpers. (Computed from
# the registry so the single source of truth stays the typed dataclasses; the accidental
# star-import exports of the old facade -- config.os, config.Path -- are gone.)
__all__ = tuple(_settings.allNames()) + (
    "set_override", "validateEnv", "getLogger", "ensureDirs", "reload",
)


def __getattr__(name: str) -> Any:
    """PEP 562 delegation to the live registry (only reached when ``name`` is not a
    real attribute of this module -- so monkeypatched shadows always win)."""
    if name == "_SIE_BOUNDS":   # legacy private alias (pre-registry name)
        return _settings.settings().sie.SIE_BOUNDS
    try:
        return _settings.lookup(name)
    except AttributeError:
        raise AttributeError(f"module 'config' has no attribute {name!r}") from None


def __dir__() -> list[str]:
    return sorted(set(list(globals()) + list(__all__)))


def reload() -> None:
    """Rebuild the registry from the current env + overrides file (tests)."""
    _settings.reload()


# ---------------------------------------------------------------------------
# Meta-optimizer override facade
# ---------------------------------------------------------------------------

def set_override(knob: str, value) -> bool:
    """Persist + live-apply a meta-optimizer knob change (whitelisted knobs only).

    Writes the typed registry (so ``config.KNOB`` AND ``settings().sie.KNOB`` move
    together -- the pre-R12 divergence bug) and persists atomically via fsio. If a
    test/e2e shadow for the knob exists on this module it is refreshed too, so a
    prior ``setattr(config, knob, ...)`` can never mask a live-tune."""
    applied, persisted = _settings.setOverride(knob, value)
    if applied and knob in vars(_SELF):
        setattr(_SELF, knob, value)
    return applied and persisted


# ---------------------------------------------------------------------------
# Environment validation
# ---------------------------------------------------------------------------

def validateEnv() -> list[str]:
    """Return the names of required-but-missing environment values."""
    missing: list[str] = []
    # getattr on THIS module (not the registry) so test shadows are respected.
    if not getattr(_SELF, "OBSIDIAN_API_KEY"):
        missing.append("OBSIDIAN_API_KEY")
    if not getattr(_SELF, "DISCORD_BOT_TOKEN"):
        missing.append("DISCORD_BOT_TOKEN")
    if not getattr(_SELF, "DISCORD_CHANNEL_ID"):
        missing.append("DISCORD_CHANNEL_ID")
    return missing
