# Logging
# ---------------------------------------------------------------------------

_LOGGER_CONFIGURED = False


def _configureLogging() -> None:
    global _LOGGER_CONFIGURED
    if _LOGGER_CONFIGURED:
        return
    LOG_PATH.mkdir(parents=True, exist_ok=True)  # type: ignore[name-defined]  # from config_paths
    fmt = logging.Formatter("%(asctime)s [%(levelname)s] %(name)s: %(message)s")
    base = logging.getLogger("9to5")
    base.setLevel(logging.INFO)
    fh = logging.FileHandler(LOG_PATH / "9to5.log", encoding="utf-8")  # type: ignore[name-defined]
    fh.setFormatter(fmt)
    ch = logging.StreamHandler()
    ch.setFormatter(fmt)
    base.addHandler(fh)
    base.addHandler(ch)
    base.propagate = False
    _LOGGER_CONFIGURED = True


def getLogger(name: str = "9to5") -> logging.Logger:
    """Return a child of the configured ``9to5`` logger."""
    _configureLogging()
    full = name if name.startswith("9to5") else f"9to5.{name}"
    return logging.getLogger(full)
