from __future__ import annotations

from typing import Any, Optional

import config
from memory.memory_sanitizer import sanitizeInjectedField


def approx_tokens(text: str) -> int:
    """Cheap token estimate (~4 chars/token), sufficient for retrieval budget caps."""
    return max(1, len(text) // 4)


def sanitize_field(text: Any, limit: int = 400) -> str:
    """Collapse retrieved text to one prompt-safe inline line."""
    if not text:
        return ""
    s = "".join(ch for ch in str(text) if ch >= " " or ch in "\t\n")
    s = " ".join(s.split())
    s = s.lstrip("#").lstrip()
    s = s.replace("```", "'''")
    return s[:limit]


def render_lessons(neighbors: list[dict[str, Any]],
                   max_tokens: Optional[int] = None) -> str:
    """Render compact metadata lessons from similar passing subtasks."""
    budget = max_tokens or config.RETRIEVAL_MAX_TOKENS
    if not neighbors:
        return ""
    header = "## RELEVANT PAST LESSONS (from similar subtasks that PASSED)\n"
    lines: list[str] = []
    for n in neighbors:
        title = sanitizeInjectedField((n.get("title") or "untitled"), max_chars=120)
        bits = [f"- \"{title}\": effort={n.get('effort') or 'default'}"]
        if n.get("model"):
            bits.append(f"model={n['model']}")
        try:
            attempts_int = int(float(n.get("attempt_count"))) if n.get("attempt_count") is not None else 0
        except (TypeError, ValueError):
            attempts_int = 0
        if attempts_int > 1:
            bits.append(f"needed {attempts_int} tries -- be careful")
        line = ", ".join(bits)
        if approx_tokens(header + "\n".join(lines + [line])) > budget:
            break
        lines.append(line)
    return header + "\n".join(lines) + "\n" if lines else ""


def render_solutions(neighbors: list[dict[str, Any]],
                     max_tokens: Optional[int] = None) -> str:
    """Render sanitized solution content from similar passing subtasks."""
    budget = max_tokens or config.RETRIEVAL_CONTENT_MAX_TOKENS
    if not neighbors:
        return ""
    header = "## RELEVANT PAST SOLUTIONS (content from similar PASSED subtasks)\n"
    lines: list[str] = []
    for n in neighbors:
        content = sanitize_field(n.get("solution_content"))
        if not content:
            continue
        title = sanitize_field(n.get("title") or "untitled", 80)
        line = f'- "{title}": {content}'
        lesson = sanitize_field(n.get("post_mortem"), 200)
        if lesson:
            line += f" [lesson: {lesson}]"
        if approx_tokens(header + "\n".join(lines + [line])) > budget:
            break
        lines.append(line)
    return header + "\n".join(lines) + "\n" if lines else ""


def render_failures(neighbors: list[dict[str, Any]],
                    max_tokens: Optional[int] = None) -> str:
    """Render distinctly tagged warnings from similar failed subtasks."""
    budget = max_tokens or config.RETRIEVAL_MAX_TOKENS
    if not neighbors:
        return ""
    header = "## SIMILAR PAST FAILURES (these subtasks FAILED verification -- avoid repeating)\n"
    lines: list[str] = []
    for n in neighbors:
        title = sanitizeInjectedField((n.get("title") or "untitled"), max_chars=120)
        bits = [f"- FAILURE \"{title}\": effort={n.get('effort') or 'default'}"]
        lesson = sanitize_field(n.get("post_mortem"), 200)
        if lesson:
            bits.append(f"why: {lesson}")
        line = ", ".join(bits)
        if approx_tokens(header + "\n".join(lines + [line])) > budget:
            break
        lines.append(line)
    return header + "\n".join(lines) + "\n" if lines else ""
