"""Backing store for the novelty index: named vector collections, fail-open.

Two interchangeable backends behind one tiny API (``add`` / ``query`` / ``count``):

* ``ChromaNoveltyStore`` -- compatibility name for persistent logical state-worker
  collections (findings/approaches/corpus/qd), with exact cosine scoring.
* ``MemoryNoveltyStore`` -- a process-local dict of {collection: {uid: (vec, payload)}}
  with an exact O(n) cosine scan. Always available (no chromadb, no disk), so tests and
  chroma-less installs still get REAL novelty scoring rather than an empty NullIndex.

``get_store()`` returns the persistent backend when NOVELTY_INDEX_ENABLED and chromadb
import both succeed, else the in-memory backend. Never raises.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  MemoryNoveltyStore  -- Process-local exact-cosine vector store (the always-available fallback).
  ChromaNoveltyStore  -- Persistent exact-cosine novelty collections in the isolated worker.
  get_store() -> object  -- Cached novelty-store singleton (chroma when available, else memory).
  set_store(store: object) -> None  -- Install an explicit store (tests / custom backends).
  reset_store() -> None  -- Drop the cached singleton (tests, or after a config change).
DEPENDS-ON: config, memory.retrieval, platform_core.app_config.paths, platform_core.runtime
SIDE-EFFECTS: ChromaNoveltyStore writes under config.ANN_INDEX_DIR/novelty
RUN/TEST: python -m pytest tests/control/test_control_store.py tests/human_nature/test_psyche_store.py
"""
from __future__ import annotations

import hashlib
import heapq
import re
from os import PathLike
from pathlib import Path
from typing import Optional

import config
from memory import retrieval
from platform_core.runtime.state_store_worker import (
    executeStateOperation,
    legacyDiagnosticStateWorkerAccess,
)

LOG = config.getLogger("sie.novelty_store")

NOVELTY_COLLECTIONS: tuple[str, ...] = ("findings", "approaches", "corpus", "qd")


class MemoryNoveltyStore:
    """Process-local exact-cosine vector store (the always-available fallback)."""

    def __init__(self) -> None:
        self._c: dict[str, dict[str, tuple[list[float], dict]]] = {}

    def add(self, collection: str, uid: str, vec: list[float], payload: dict | None = None) -> None:
        if not vec:
            return
        self._c.setdefault(collection, {})[uid] = (list(vec), dict(payload or {}))

    def query(self, collection: str, vec: list[float], k: int, threshold: float) -> list[dict]:
        rows = self._c.get(collection) or {}
        if not vec or not rows:
            return []
        scored = ((retrieval.cosine(vec, v), uid, meta) for uid, (v, meta) in rows.items())
        top = heapq.nlargest(max(1, int(k)), scored, key=lambda t: t[0])
        return [{"uid": uid, "score": float(s), "payload": dict(meta)}
                for s, uid, meta in top if s >= threshold]

    def count(self, collection: str) -> int:
        return len(self._c.get(collection) or {})


def _collection_name(kind: str) -> str:
    """Embedder-pinned chroma collection name (a model/dim swap starts a fresh space)."""
    raw = f"nov_{kind}_{config.EMBED_MODEL}_{int(config.ANN_EMBED_DIM)}"
    return re.sub(r"[^A-Za-z0-9_.-]", "-", raw)[:60]


class ChromaNoveltyStore:
    """Persistent exact-cosine novelty collections in the isolated worker."""

    def __init__(
        self,
        persist_dir: str | PathLike[str] | None,
        *,
        state_authority: object = None,
    ) -> None:
        if state_authority is None:
            with legacyDiagnosticStateWorkerAccess():
                self._persist_dir = persist_dir
        else:
            self._persist_dir = None
        self._state_authority = state_authority

    def _legacyPath(self) -> Path:
        raw = (
            Path(config.ANN_INDEX_DIR) / "novelty"
            if self._persist_dir is None
            else Path(self._persist_dir)
        )
        if not raw.is_absolute():
            raw = (Path(config.PROJECT_ROOT) / raw).resolve(strict=False)
        return raw

    @staticmethod
    def _key(uid: str) -> str:
        return f"vector_{hashlib.sha256(str(uid).encode('utf-8')).hexdigest()}"

    def _execute(
        self,
        collection: str,
        operation: str,
        *,
        key: str = "",
        value: object = None,
    ) -> object:
        if self._state_authority is not None:
            return executeStateOperation(
                database_id="novelty_index",
                namespace=_collection_name(collection),
                operation=operation,
                key=key,
                value=value,
                authority=self._state_authority,
            )
        with legacyDiagnosticStateWorkerAccess():
            return executeStateOperation(
                database_id="novelty_index",
                namespace=_collection_name(collection),
                operation=operation,
                key=key,
                value=value,
                legacy_path=self._legacyPath(),
            )

    def add(self, collection: str, uid: str, vec: list[float], payload: dict | None = None) -> None:
        if not vec:
            return
        try:
            meta = {k: v for k, v in (payload or {}).items()
                    if isinstance(v, (str, int, float, bool)) and v is not None}
            self._execute(
                collection,
                "kv_put",
                key=self._key(uid),
                value={"payload": meta, "uid": str(uid), "vector": list(vec)},
            )
        except Exception as e:  # noqa: BLE001 -- best-effort; a miss just lowers recall
            LOG.debug("ChromaNoveltyStore.add failed (ignored): %s", e)

    def query(self, collection: str, vec: list[float], k: int, threshold: float) -> list[dict]:
        if not vec:
            return []
        try:
            values = self._execute(collection, "kv_list")
        except Exception as e:  # noqa: BLE001
            LOG.debug("ChromaNoveltyStore.query failed (ignored): %s", e)
            return []
        out = []
        for item in values if isinstance(values, list) else []:
            row = item.get("value") if isinstance(item, dict) else None
            if not isinstance(row, dict) or not isinstance(row.get("vector"), list):
                continue
            score = retrieval.cosine(vec, row["vector"])
            if score >= threshold:
                out.append(
                    {
                        "uid": str(row.get("uid") or ""),
                        "score": score,
                        "payload": dict(row.get("payload") or {}),
                    }
                )
        out.sort(key=lambda item: (-item["score"], item["uid"]))
        return out[: max(1, int(k))]

    def count(self, collection: str) -> int:
        try:
            values = self._execute(collection, "kv_list")
            return len(values) if isinstance(values, list) else 0
        except Exception as e:  # noqa: BLE001
            LOG.debug("ChromaNoveltyStore.count failed (ignored): %s", e)
            return 0


_STORE_SINGLETON: Optional[object] = None


def _build_store() -> object:
    """Persistent chroma when enabled + importable, else the in-memory fallback."""
    if not getattr(config, "NOVELTY_INDEX_ENABLED", True):
        return MemoryNoveltyStore()
    try:
        return ChromaNoveltyStore(None)
    except Exception as e:  # noqa: BLE001 -- chromadb absent/broken -> memory fallback
        LOG.info("novelty store: chroma unavailable, using in-memory store: %s", e)
        return MemoryNoveltyStore()


def get_store() -> object:
    """Cached novelty-store singleton (chroma when available, else memory)."""
    global _STORE_SINGLETON
    if _STORE_SINGLETON is None:
        _STORE_SINGLETON = _build_store()
    return _STORE_SINGLETON


def set_store(store: object) -> None:
    """Install an explicit store (tests / custom backends)."""
    global _STORE_SINGLETON
    _STORE_SINGLETON = store


def reset_store() -> None:
    """Drop the cached singleton (tests, or after a config change)."""
    global _STORE_SINGLETON
    _STORE_SINGLETON = None
