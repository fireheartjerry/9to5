"""Novelty index: measure how NEW a candidate is vs the history of prior ideas.

The finders' self-reported ``innovation`` score is gameable, so this module measures
novelty from vector distance instead: ``history_distance = 1 - max_cosine(candidate,
prior findings/approaches)``, optionally blended with archive-cell rarity, corpus-transfer
distance, and implementation distinctiveness. Everything is best-effort and FAIL-OPEN: if
embedding is unavailable the score degrades to a permissive 1.0 (never zeroes a candidate,
never crashes a run). Backed by ``novelty_store`` (chroma or in-memory) and reusing
``retrieval.embed`` (nomic-embed-text) so the space matches the rest of 9to5.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  NoveltyResult  -- Measured-novelty verdict for one candidate text.
  signature_text(obj: Any) -> str  -- Build the text we embed from a FindingCandidate / Finding / dict / str.
  nearest_history(text: str, k: int=5, *, collection: str='findings', embed_fn: Optional[Callable]=None, store: Any=None) -> list[dict]  -- The k most-similar prior items to ``text`` in ``collection`` (empty on any miss).
  compose_novelty(history_distance: float, **components: Optional[float]) -> float  -- Weight-renormalized composite over the supplied components (history always in).
  novelty_score(text: str, *, collection: str='findings', embed_fn: Optional[Callable]=None, store: Any=None, **components: Optional[float]) -> NoveltyResult  -- Measure novelty of ``text`` vs history
  record_finding(candidate: Any, *, run_id: str='', embed_fn: Optional[Callable]=None, store: Any=None) -> bool  -- Persist a finding into the ``findings`` history space (best-effort).
  record_approach(candidate: Any, *, run_id: str='', embed_fn: Optional[Callable]=None, store: Any=None) -> bool  -- Persist an approach into the ``approaches`` history space (best-effort).
  appraisal_event(text: str, *, outcome: str='', agency: float=0.5, collection: str='findings', embed_fn: Optional[Callable]=None, store: Any=None, **components: Optional[float]) -> dict[str, Any]  -- Build a human_nature appraisal event whose ``novelty`` is MEASURED from vector
  semantic_dedup(items: list, *, threshold: Optional[float]=None, key_fn: Optional[Callable[[Any], str]]=None, embed_fn: Optional[Callable]=None) -> list  -- Greedy in-batch dedup: drop an item whose cosine to a kept item >= threshold.
DEPENDS-ON: config, memory.novelty_store, memory.retrieval
SIDE-EFFECTS: record_* upsert into the novelty store
RUN/TEST: python -m pytest tests/evolution/test_exp_index.py tests/evolution/test_novelty_index.py
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from typing import Any, Callable, Optional

import config
from memory import novelty_store, retrieval

LOG = config.getLogger("sie.novelty")

# Composite-novelty component weights (renormalized over whichever are supplied).
_W = {"history_distance": 0.45, "archive_cell_rarity": 0.20,
      "corpus_transform_distance": 0.20, "implementation_distinctiveness": 0.15}


@dataclass
class NoveltyResult:
    """Measured-novelty verdict for one candidate text."""

    measured_novelty: float = 1.0
    history_similarity_max: float = 0.0
    nearest_id: str = ""
    components: dict[str, float] = field(default_factory=dict)
    degraded: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {"measured_novelty": round(self.measured_novelty, 4),
                "history_similarity_max": round(self.history_similarity_max, 4),
                "nearest_id": self.nearest_id, "components": self.components,
                "degraded": self.degraded}


def signature_text(obj: Any) -> str:
    """Build the text we embed from a FindingCandidate / Finding / dict / str."""
    if isinstance(obj, str):
        return obj.strip()
    get = obj.get if isinstance(obj, dict) else (lambda k, d="": getattr(obj, k, d))
    parts = [str(get("title", "") or ""), str(get("summary", "") or ""),
             str(get("design_sketch", "") or get("rationale", "") or "")]
    subs = get("target_subsystems", None) or get("affected_files", None) or []
    if subs:
        parts.append(" ".join(str(s) for s in subs))
    return "\n".join(p for p in parts if p).strip()


def _embed(text: str, embed_fn: Optional[Callable[[str], Any]]) -> Optional[list[float]]:
    """Embed via the injected fn (default retrieval.embed); None on empty/failure."""
    if not text or not text.strip():
        return None
    try:
        vec = (embed_fn or retrieval.embed)(text)
        return list(vec) if vec else None
    except Exception as e:  # noqa: BLE001 -- fail-open: caller treats None as degraded
        LOG.debug("novelty embed failed (ignored): %s", e)
        return None


def _uid_for(obj: Any, text: str) -> str:
    """Stable id: the object's own id if present, else a content hash of the text."""
    cid = getattr(obj, "id", None) if not isinstance(obj, (str, dict)) else \
        (obj.get("id") if isinstance(obj, dict) else None)
    if cid:
        return str(cid)
    return "h" + hashlib.sha1(text.encode("utf-8", "ignore")).hexdigest()[:16]


def nearest_history(text: str, k: int = 5, *, collection: str = "findings",
                    embed_fn: Optional[Callable] = None, store: Any = None) -> list[dict]:
    """The k most-similar prior items to ``text`` in ``collection`` (empty on any miss)."""
    vec = _embed(text, embed_fn)
    if vec is None:
        return []
    st = store or novelty_store.get_store()
    try:
        return st.query(collection, vec, k, threshold=0.0)
    except Exception as e:  # noqa: BLE001
        LOG.debug("nearest_history failed (ignored): %s", e)
        return []


def compose_novelty(history_distance: float, **components: Optional[float]) -> float:
    """Weight-renormalized composite over the supplied components (history always in)."""
    present: dict[str, float] = {"history_distance": max(0.0, min(1.0, float(history_distance)))}
    for name, val in components.items():
        if val is not None and name in _W:
            present[name] = max(0.0, min(1.0, float(val)))
    wsum = sum(_W[n] for n in present)
    if wsum <= 0:
        return present["history_distance"]
    return round(sum(_W[n] * v for n, v in present.items()) / wsum, 6)


def novelty_score(text: str, *, collection: str = "findings", embed_fn: Optional[Callable] = None,
                  store: Any = None, **components: Optional[float]) -> NoveltyResult:
    """Measure novelty of ``text`` vs history. Fail-open: degraded -> permissive 1.0."""
    vec = _embed(text, embed_fn)
    if vec is None:
        return NoveltyResult(measured_novelty=1.0, degraded=True)
    st = store or novelty_store.get_store()
    try:
        hits = st.query(collection, vec, 1, threshold=0.0)
    except Exception as e:  # noqa: BLE001
        LOG.debug("novelty_score query failed (ignored): %s", e)
        return NoveltyResult(measured_novelty=1.0, degraded=True)
    sim = float(hits[0]["score"]) if hits else 0.0
    nearest = str(hits[0]["uid"]) if hits else ""
    hist_dist = max(0.0, 1.0 - sim)
    measured = compose_novelty(hist_dist, **components)
    comp = {"history_distance": round(hist_dist, 4),
            **{k: round(float(v), 4) for k, v in components.items() if v is not None}}
    return NoveltyResult(measured_novelty=measured, history_similarity_max=round(sim, 4),
                         nearest_id=nearest, components=comp)


def _record(candidate: Any, collection: str, run_id: str,
            embed_fn: Optional[Callable], store: Any) -> bool:
    """Embed + upsert a candidate into ``collection`` (best-effort, returns success)."""
    text = signature_text(candidate)
    vec = _embed(text, embed_fn)
    if vec is None:
        return False
    st = store or novelty_store.get_store()
    payload = {"run_id": str(run_id or ""),
               "kind": str(getattr(candidate, "kind", "") or
                           (candidate.get("kind") if isinstance(candidate, dict) else "")),
               "title": signature_text(candidate)[:120]}
    try:
        st.add(collection, _uid_for(candidate, text), vec, payload)
        return True
    except Exception as e:  # noqa: BLE001
        LOG.debug("novelty record failed (ignored): %s", e)
        return False


def record_finding(candidate: Any, *, run_id: str = "", embed_fn: Optional[Callable] = None,
                   store: Any = None) -> bool:
    """Persist a finding into the ``findings`` history space (best-effort)."""
    return _record(candidate, "findings", run_id, embed_fn, store)


def record_approach(candidate: Any, *, run_id: str = "", embed_fn: Optional[Callable] = None,
                    store: Any = None) -> bool:
    """Persist an approach into the ``approaches`` history space (best-effort)."""
    return _record(candidate, "approaches", run_id, embed_fn, store)


def appraisal_event(text: str, *, outcome: str = "", agency: float = 0.5,
                    collection: str = "findings", embed_fn: Optional[Callable] = None,
                    store: Any = None, **components: Optional[float]) -> dict[str, Any]:
    """Build a human_nature appraisal event whose ``novelty`` is MEASURED from vector
    distance (feeds appraisal.appraise(), which stays pure). Unlike finder-scoring,
    a degraded read yields novelty 0.0 here -- affect must not fake curiosity when the
    measurement is unavailable."""
    r = novelty_score(text, collection=collection, embed_fn=embed_fn, store=store, **components)
    ev: dict[str, Any] = {"novelty": 0.0 if r.degraded else round(float(r.measured_novelty), 4),
                          "agency": float(agency)}
    if outcome:
        ev["outcome"] = outcome
    return ev


def semantic_dedup(items: list, *, threshold: Optional[float] = None,
                   key_fn: Optional[Callable[[Any], str]] = None,
                   embed_fn: Optional[Callable] = None) -> list:
    """Greedy in-batch dedup: drop an item whose cosine to a kept item >= threshold.

    Fail-open: an un-embeddable item is always kept (never silently dropped)."""
    thr = float(threshold if threshold is not None else getattr(config, "NOVELTY_DEDUP_THRESHOLD", 0.88))
    kf = key_fn or (lambda x: signature_text(x))
    kept: list = []
    kept_vecs: list[list[float]] = []
    for it in items:
        vec = _embed(kf(it), embed_fn)
        if vec is None:
            kept.append(it)
            continue
        if any(retrieval.cosine(vec, kv) >= thr for kv in kept_vecs):
            continue
        kept.append(it)
        kept_vecs.append(vec)
    return kept
