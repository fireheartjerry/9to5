LOG = config.getLogger("sie.retrieval")

# Negative cache: once the local embedder looks down, stop hammering it on every brain
# call (it's invoked many times per run). Retry at most once per cooldown window.
# Sentinel is -inf, NOT 0.0: time.monotonic()'s origin is arbitrary (system boot on Linux),
# so on a freshly-booted host monotonic() can be < the cooldown, and `monotonic() - 0.0 <
# cooldown` would wrongly suppress the very first embedding. -inf makes the gap always huge.
_FAIL_COOLDOWN_SECONDS = 60.0
_last_embed_fail_at: float = float("-inf")


# --------------------------------------------------------------------- embeddings

def _embed_call(text: str) -> Optional[list[float]]:
    """Raw local-Ollama embedding call. Isolated so tests patch exactly this seam.

    Returns the vector, or None if the model/server is unavailable (the common case in
    a container with no Ollama running -- callers treat None as "no retrieval today")."""
    try:
        import ollama  # imported lazily: absent/slow import must not taint module load
        client = ollama.Client(host=config.OLLAMA_HOST)
        resp = client.embeddings(model=config.EMBED_MODEL, prompt=text)
        vec = resp.get("embedding") if isinstance(resp, dict) else getattr(resp, "embedding", None)
        return list(vec) if vec else None
    except Exception as e:  # noqa: BLE001 -- no server / model / package -> degrade
        LOG.debug("embedding unavailable (ignored): %s", e)
        return None


def embed(text: str) -> Optional[list[float]]:
    """Best-effort embedding of ``text`` (returns None when unavailable).

    Honors a negative cache: after a failure we skip the call for ``_FAIL_COOLDOWN_SECONDS``
    so a dead embedder doesn't add latency to every subsequent brain call."""
    global _last_embed_fail_at
    if not text or not text.strip():
        return None
    if time.monotonic() - _last_embed_fail_at < _FAIL_COOLDOWN_SECONDS:
        return None
    vec = _embed_call(text.strip())
    if vec is None:
        _last_embed_fail_at = time.monotonic()
    else:
        _last_embed_fail_at = float("-inf")  # reset so next call is never wrongly suppressed
    return vec


def reset_embed_cache() -> None:
    """Clear the negative cache (used by tests, and after a known embedder restart)."""
    global _last_embed_fail_at
    _last_embed_fail_at = float("-inf")


def pack(vec: list[float]) -> bytes:
    """Pack a float vector into compact float32 bytes for the BLOB column."""
    if not vec:
        return b""
    return array.array("f", [float(x) for x in vec]).tobytes()


def unpack(blob: bytes) -> list[float]:
    """Inverse of ``pack``. Returns [] for None/empty/misaligned blobs."""
    if not blob or not isinstance(blob, (bytes, bytearray)):
        return []
    if len(blob) % 4:  # float32 requires 4-byte alignment
        LOG.debug("unpack: blob length %d is not a multiple of 4, skipping", len(blob))
        return []
    a = array.array("f")
    a.frombytes(blob)
    return list(a)


def cosine(a: list[float], b: list[float]) -> float:
    """Cosine similarity in [-1, 1]; 0.0 for a degenerate/zero vector."""
    if not a or not b or len(a) != len(b):
        return 0.0
    dot = sum(x * y for x, y in zip(a, b))
    na = math.sqrt(sum(x * x for x in a))
    nb = math.sqrt(sum(y * y for y in b))
    if na == 0.0 or nb == 0.0:
        return 0.0
    return dot / (na * nb)


# ------------------------------------------------------------------- signatures

def signature_text(goal: str, title: str = "") -> str:
    """The text we embed for a subtask/goal -- goal gives domain, title gives the act."""
    return f"{(goal or '').strip()}\n{(title or '').strip()}".strip()


def _uid(run_id: str, st_id: str) -> str:
    """Stable index id for a subtask (collision-free across runs)."""
    return f"{run_id}::{st_id}"


def _embedText(goal: str, title: str = "") -> Optional[list[float]]:
    """The single embedding-composition seam: BOTH the live write path (embed_and_store) and the
    nightly backfill compose their vector here, so a backfilled row lands in the SAME vector space
    as a live-embedded row and the query. Embedding two different texts (title-only vs goal+title)
    would silently split the space and starve retrieval of matches."""
    return embed(signature_text(goal, title))


def embed_and_store(run_id: str, st_id: str, goal: str, title: str = "",
                    db_path: Optional[Path] = None, verify_passed: bool = True) -> bool:
    """Compute + persist a subtask's embedding AND seed the ANN index (derived cache; the
    BLOB column stays source of truth). Best-effort."""
    vec = _embedText(goal, title)
    if not vec:
        return False
    ok = experience.set_subtask_embedding(run_id, st_id, pack(vec), db_path=db_path)
    try:
        idx = exp_index.getIndex()
        payload = {"run_id": run_id, "st_id": st_id, "title": title,
                   "verify_passed": 1 if verify_passed else 0}
        if verify_passed:
            idx.addPair(_uid(run_id, st_id), vec, payload)
        elif hasattr(idx, "addFailurePair"):
            idx.addFailurePair(_uid(run_id, st_id), vec, payload)
    except Exception as e:  # noqa: BLE001
        LOG.debug("index seed skipped (ignored): %s", e)
    return ok


# --------------------------------------------------------------------- top-K

def _tie(row: dict[str, Any]) -> tuple[str, str, str]:
    return (str(row.get("created_at") or ""), str(row.get("run_id") or ""),
            str(row.get("st_id") or ""))


def _heapTopK(scored_rows, k: int) -> list[dict[str, Any]]:
    """Exact top-k using a fixed min-heap: O(n log k), deterministic ties."""
    if k <= 0:
        return []
    heap: list[tuple[tuple[float, str, str, str], int, dict[str, Any]]] = []
    seq = 0
    for row in scored_rows:
        score = float(row.get("score") or 0.0)
        key = (score, *_tie(row))
        item = (key, seq, row)
        seq += 1
        if len(heap) < k:
            heapq.heappush(heap, item)
        elif key > heap[0][0]:
            heapq.heapreplace(heap, item)
    out = [item[2] for item in heap]
    out.sort(key=lambda r: (float(r.get("score") or 0.0), *_tie(r)), reverse=True)
    return out


def _scoredEmbeddedRows(query_vec: list[float], *, only_passed: bool,
                        db_path: Optional[Path] = None):
    floor = float(getattr(config, "RETRIEVAL_MIN_SCORE", 0.0) or 0.0)
    for row in experience.embedded_subtasks(only_passed=only_passed, db_path=db_path):
        blob = row.get("embedding")
        if not blob:
            continue
        try:
            score = cosine(query_vec, unpack(blob))
        except Exception:  # noqa: BLE001 -- a corrupt blob just doesn't compete
            continue
        if score < floor:
            continue
        yield {**row, "score": score}


def _annCandidateK(k: int) -> int:
    mult = max(1, int(getattr(config, "ANN_INDEX_CANDIDATE_MULTIPLIER", 10) or 1))
    return max(k, k * mult, 50 if k > 0 else 0)

def top_k_similar(query_vec: list[float], k: int = 5, *, only_passed: bool = True,
                  db_path: Optional[Path] = None) -> list[dict[str, Any]]:
    """The ``k`` most-similar embedded subtasks to ``query_vec``, each annotated with a
    ``score``. Pulls only verify-passing rows by default (we learn from wins)."""
    return _heapTopK(
        _scoredEmbeddedRows(query_vec, only_passed=only_passed, db_path=db_path),
        k,
    )


def top_k_failures(query_vec: list[float], k: int = 2, *,
                   db_path: Optional[Path] = None) -> list[dict[str, Any]]:
    """The ``k`` most-similar embedded subtasks that FAILED verification (``verify_passed==0``).

    Mirrors ``top_k_similar`` but over the FAILED pool. The fallback is an exact heap top-k
    scan, so it avoids sorting every embedded row when ANN is unavailable."""
    return _heapTopK(
        (r for r in _scoredEmbeddedRows(query_vec, only_passed=False, db_path=db_path)
         if r.get("verify_passed") == 0),
        k,
    )


def retrieve(goal: str, title: str = "", *, k: Optional[int] = None,
             db_path: Optional[Path] = None) -> list[dict[str, Any]]:
    """Embed the (goal, title) query and return the top-K similar past successes."""
    qvec = embed(signature_text(goal, title))
    if not qvec:
        return []
    return top_k_similar(qvec, k or config.RETRIEVAL_K, db_path=db_path)


def retrieve_failures(goal: str, title: str = "", *, k: Optional[int] = None,
                      db_path: Optional[Path] = None) -> list[dict[str, Any]]:
    """Embed the (goal, title) query and return up to ``k`` similar past FAILED subtasks.

    Best-effort mate of ``retrieve`` for the failure lane: shares the SAME embedding seam and
    cosine scan, so surfacing failures costs one extra scan over an already-loaded pool, not a
    new store. ``k`` defaults to ``config.RETRIEVAL_FAILURES_K``; ``k<=0`` short-circuits."""
    k = k if k is not None else int(getattr(config, "RETRIEVAL_FAILURES_K", 2) or 0)
    t0 = time.perf_counter()
    if k <= 0:
        return []
    qvec = embed(signature_text(goal, title))
    if not qvec:
        return []
    floor = float(getattr(config, "RETRIEVAL_MIN_SCORE", 0.0) or 0.0)
    try:
        idx = exp_index.getIndex()
        hits = idx.queryFailures(qvec, _annCandidateK(k), floor) if hasattr(idx, "queryFailures") else []
    except Exception:  # noqa: BLE001
        hits = []
    if hits:
        rows = []
        for h in hits:
            payload = dict(h.get("payload") or {})
            payload["score"] = h.get("score")
            payload.setdefault("uid", h.get("uid"))
            rows.append(payload)
        out = retrieval_rank.rerank(rows)[:k]
        perf.record("retrieval_failures", time.perf_counter() - t0, ann_hit=True, k=k)
        return out
    out = top_k_failures(qvec, k, db_path=db_path)
    perf.record("retrieval_failures", time.perf_counter() - t0, ann_hit=False, k=k)
    return out


def retrieve_content(goal: str, title: str = "", *, k: Optional[int] = None,
                     db_path: Optional[Path] = None) -> list[dict[str, Any]]:
    """Embed the query, look up the ANN index (fallback: O(n) scan), and JOIN each hit to
    its exp_content row. Best-effort: empty list on any failure."""
    t0 = time.perf_counter()
    qvec = embed(signature_text(goal, title))
    if not qvec:
        return []
    k = k or config.RETRIEVAL_K
    floor = float(getattr(config, "RETRIEVAL_MIN_SCORE", 0.0) or 0.0)
    neighbors: list[dict[str, Any]] = []
    try:
        hits = exp_index.getIndex().query(qvec, _annCandidateK(k), floor)
    except Exception:  # noqa: BLE001 -- a broken index never blocks retrieval
        hits = []
    joined = 0
    if hits:
        for h in hits:
            payload = dict(h.get("payload") or {})
            payload["score"] = h.get("score")
            payload.setdefault("uid", h.get("uid"))
            neighbors.append(payload)
    else:
        neighbors = top_k_similar(qvec, k, db_path=db_path)
    for n in neighbors:
        row = experience_content.fetchSolutionContent(
            n.get("run_id"), n.get("st_id"), db_path=db_path)
        if row:
            joined += 1
            n["solution_content"] = row.get("solution_content")
            n["post_mortem"] = row.get("post_mortem")
            n["created_at"] = row.get("created_at")
            if row.get("importance") is not None:
                n["importance"] = row.get("importance")
    if hits and joined == 0:
        neighbors = top_k_similar(qvec, k, db_path=db_path)
    neighbors = retrieval_rank.rerank(neighbors)
    out = neighbors[:k]
    perf.record("retrieval_content", time.perf_counter() - t0, ann_hit=bool(hits), k=k)
    return out


def backfill_embeddings(db_path: Optional[Path] = None) -> dict[str, int]:
    """Embed every verify-passing subtask that lacks an embedding (run off the hot path,
    e.g. by the nightly SIE job). Returns {embedded, skipped}. Stops early if the embedder
    is unavailable so it doesn't spin on a dead server."""
    embedded = skipped = 0
    for row in experience.fetch_subtasks(db_path=db_path):
        if row.get("embedding") or row.get("verify_passed") not in (0, 1):
            skipped += 1
            continue
        # The goal text isn't on the subtask row; title is the strongest available signal. Route
        # through the SAME _embedText seam as the live path so both share one vector space.
        vec = _embedText("", row.get("title") or "")
        if not vec:
            skipped += 1
            if embedded == 0:          # embedder dead on first try -> bail, don't spin
                break
            continue
        experience.set_subtask_embedding(row["run_id"], row["st_id"], pack(vec), db_path=db_path)
        try:
            idx = exp_index.getIndex()
            payload = {"run_id": row["run_id"], "st_id": row["st_id"],
                       "title": row.get("title") or "",
                       "verify_passed": int(row.get("verify_passed") or 0),
                       "importance": row.get("importance") or 0.0,
                       "created_at": row.get("ended_at") or row.get("started_at") or ""}
            if row.get("verify_passed") == 1:
                idx.addPair(_uid(row["run_id"], row["st_id"]), vec, payload)
            elif hasattr(idx, "addFailurePair"):
                idx.addFailurePair(_uid(row["run_id"], row["st_id"]), vec, payload)
        except Exception as e:  # noqa: BLE001
            LOG.debug("backfill index seed skipped (ignored): %s", e)
        embedded += 1
    LOG.info("embedding backfill: %d embedded, %d skipped", embedded, skipped)
    return {"embedded": embedded, "skipped": skipped}


def rebuild_retrieval_index(db_path: Optional[Path] = None,
                            include_failures: bool = True) -> dict[str, int]:
    """Rebuild the derived ANN index from SQLite embeddings. Best-effort and safe to run
    offline; SQLite remains the source of truth."""
    indexed = skipped = failures = 0
    try:
        idx = exp_index.getIndex()
        for row in experience.embedded_subtasks(only_passed=False, db_path=db_path):
            passed = row.get("verify_passed")
            if passed not in (0, 1) or (passed == 0 and not include_failures):
                skipped += 1
                continue
            vec = unpack(row.get("embedding"))
            if not vec:
                skipped += 1
                continue
            payload = {
                "run_id": row.get("run_id") or "",
                "st_id": row.get("st_id") or "",
                "title": row.get("title") or "",
                "verify_passed": int(passed),
                "importance": row.get("importance") or 0.0,
                "created_at": row.get("ended_at") or row.get("started_at") or "",
            }
            uid = _uid(payload["run_id"], payload["st_id"])
            if passed == 1:
                idx.addPair(uid, vec, payload)
            elif hasattr(idx, "addFailurePair"):
                idx.addFailurePair(uid, vec, payload)
                failures += 1
            else:
                skipped += 1
                continue
            indexed += 1
        try:
            idx.persist()
        except Exception:  # noqa: BLE001
            pass
    except Exception as e:  # noqa: BLE001
        LOG.debug("rebuild_retrieval_index failed (ignored): %s", e)
    return {"indexed": indexed, "failures": failures, "skipped": skipped}


def lessons_block(goal: str, title: str = "", *, db_path: Optional[Path] = None) -> str:
    """Orchestrator-facing one-call helper: retrieve + render, fully best-effort.

    Prefers REAL solution content (retrieve_content + render_solutions); degrades to the
    metadata block (render_lessons) when no neighbor carries content. Returns "" when
    retrieval is unavailable, so a caller can unconditionally prepend the result."""
    try:
        neighbors = retrieve_content(goal, title, db_path=db_path)
        block = render_solutions(neighbors)
        if not block:
            block = render_lessons(neighbors)
        # Failure-aware lane (opt-out via RETRIEVAL_FAILURES_ENABLED). With the flag OFF this
        # branch is skipped entirely, so the returned block stays byte-identical to before.
        if getattr(config, "RETRIEVAL_FAILURES_ENABLED", True):
            failure_block = render_failures(
                retrieve_failures(goal, title, db_path=db_path))
            if failure_block:
                block = (block + "\n" + failure_block) if block else failure_block
        return (block + "\n") if block else ""
    except Exception as e:  # noqa: BLE001 -- learning must never break authoring
        LOG.debug("lessons_block failed (ignored): %s", e)
        return ""
