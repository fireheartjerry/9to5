"""Swappable vector index for Layer-1 retrieval (fail-open to the O(n) cosine scan).

``AnnIndex`` is a tiny Protocol; ``NullIndex`` is the always-available fallback whose
``query`` returns ``[]`` (so retrieval falls back to ``top_k_similar``). The historical
``ChromaIndex`` compatibility name now fronts an exact-cosine logical state-worker
collection. No host path-only vector engine remains. ``getIndex()`` is cached.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  AnnIndex
  NullIndex  -- The fail-open fallback: never stores, always returns no hits.
  ChromaIndex  -- Persistent exact-cosine index backed by a logical worker namespace.
  getIndex() -> 'AnnIndex'  -- Cached singleton
  resetIndex() -> None  -- Drop the cached singleton (tests, or after a known backfill rebuild).
DEPENDS-ON: config, platform_core.app_config.paths, platform_core.runtime
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/evolution/test_exp_index.py tests/evolution/test_novelty_index.py
"""
from __future__ import annotations

import hashlib
import math
import re
from os import PathLike
from pathlib import Path
from typing import Optional, Protocol, runtime_checkable

import config
from platform_core.runtime.state_store_worker import (
    executeStateOperation,
    legacyDiagnosticStateWorkerAccess,
)

LOG = config.getLogger("sie.exp_index")


@runtime_checkable
class AnnIndex(Protocol):
    def addPair(self, uid: str, vec: list[float], payload: dict) -> None: ...
    def query(self, vec: list[float], k: int, threshold: float) -> list[dict]: ...
    def persist(self) -> None: ...


class NullIndex:
    """The fail-open fallback: never stores, always returns no hits."""

    def addPair(self, uid: str, vec: list[float], payload: dict) -> None:
        return None

    def query(self, vec: list[float], k: int, threshold: float) -> list[dict]:
        return []

    def addFailurePair(self, uid: str, vec: list[float], payload: dict) -> None:
        return None

    def queryFailures(self, vec: list[float], k: int, threshold: float) -> list[dict]:
        return []

    def persist(self) -> None:
        return None


class ChromaIndex:
    """Persistent exact-cosine index backed by a logical worker namespace.

    The class name is retained for import compatibility. Persistent segment/ANN
    accelerators remain dark until their crossover and qualification gates pass.
    """

    def __init__(
        self,
        persist_dir: str | PathLike[str] | None,
        *,
        state_authority: object = None,
    ) -> None:
        if state_authority is None:
            with legacyDiagnosticStateWorkerAccess():
                self._persist_dir = persist_dir
        else:
            self._persist_dir = None
        self._state_authority = state_authority

    def _legacyPath(self) -> Path:
        raw = (
            Path(config.ANN_INDEX_DIR)
            if self._persist_dir is None
            else Path(self._persist_dir)
        )
        if not raw.is_absolute():
            raw = (Path(config.PROJECT_ROOT) / raw).resolve(strict=False)
        return raw

    @staticmethod
    def _key(uid: str) -> str:
        return f"vector_{hashlib.sha256(str(uid).encode('utf-8')).hexdigest()}"

    def _execute(
        self,
        kind: str,
        operation: str,
        *,
        key: str = "",
        value: object = None,
    ) -> object:
        if self._state_authority is not None:
            return executeStateOperation(
                database_id="ann_index",
                namespace=_collectionName(kind),
                operation=operation,
                key=key,
                value=value,
                authority=self._state_authority,
            )
        with legacyDiagnosticStateWorkerAccess():
            return executeStateOperation(
                database_id="ann_index",
                namespace=_collectionName(kind),
                operation=operation,
                key=key,
                value=value,
                legacy_path=self._legacyPath(),
            )

    def _add(self, kind: str, uid: str, vec: list[float], payload: dict) -> None:
        try:
            meta = {k: v for k, v in (payload or {}).items()
                    if isinstance(v, (str, int, float, bool)) and v is not None}
            self._execute(
                kind,
                "kv_put",
                key=self._key(uid),
                value={"payload": meta, "uid": str(uid), "vector": list(vec)},
            )
        except Exception as e:  # noqa: BLE001
            LOG.debug("ChromaIndex.addPair failed (ignored): %s", e)

    def addPair(self, uid: str, vec: list[float], payload: dict) -> None:
        self._add("passed", uid, vec, payload)

    def addFailurePair(self, uid: str, vec: list[float], payload: dict) -> None:
        self._add("failed", uid, vec, payload)

    @staticmethod
    def _cosine(left: list[float], right: list[float]) -> float:
        if len(left) != len(right) or not left:
            return 0.0
        dot = sum(a * b for a, b in zip(left, right))
        left_norm = math.sqrt(sum(value * value for value in left))
        right_norm = math.sqrt(sum(value * value for value in right))
        return dot / (left_norm * right_norm) if left_norm and right_norm else 0.0

    def _query(self, kind: str, vec: list[float], k: int, threshold: float) -> list[dict]:
        try:
            values = self._execute(kind, "kv_list")
        except Exception as e:  # noqa: BLE001
            LOG.debug("ChromaIndex.query failed (ignored): %s", e)
            return []
        out: list[dict] = []
        for item in values if isinstance(values, list) else []:
            row = item.get("value") if isinstance(item, dict) else None
            if not isinstance(row, dict) or not isinstance(row.get("vector"), list):
                continue
            score = self._cosine(list(vec), row["vector"])
            if score < threshold:
                continue
            out.append(
                {
                    "uid": str(row.get("uid") or ""),
                    "score": score,
                    "payload": dict(row.get("payload") or {}),
                }
            )
        out.sort(key=lambda item: (-item["score"], item["uid"]))
        return out[: max(1, int(k))]

    def query(self, vec: list[float], k: int, threshold: float) -> list[dict]:
        return self._query("passed", vec, k, threshold)

    def queryFailures(self, vec: list[float], k: int, threshold: float) -> list[dict]:
        return self._query("failed", vec, k, threshold)

    def persist(self) -> None:
        return None


def _collectionName(kind: str = "passed") -> str:
    """Embedder-pinned collection name so a model/dim swap starts a fresh space."""
    raw = f"exp_{kind}_{config.EMBED_MODEL}_{int(config.ANN_EMBED_DIM)}"
    return re.sub(r"[^A-Za-z0-9_.-]", "-", raw)[:60]


def _buildBackend() -> "AnnIndex":
    """Construct the configured primary backend. Raises if its dependency is absent (the
    caller catches and falls open to NullIndex)."""
    backend = getattr(config, "ANN_INDEX_BACKEND", "chroma")
    if backend == "chroma":
        return ChromaIndex(None)
    raise ValueError(f"unknown ANN_INDEX_BACKEND: {backend!r}")


_INDEX_SINGLETON: Optional["AnnIndex"] = None


def getIndex() -> "AnnIndex":
    """Cached singleton. Returns NullIndex when ANN_INDEX_ENABLED is false or the backend
    import fails -- keeping chromadb strictly optional and retrieval always working."""
    global _INDEX_SINGLETON
    if _INDEX_SINGLETON is not None:
        return _INDEX_SINGLETON
    if not getattr(config, "ANN_INDEX_ENABLED", False):
        _INDEX_SINGLETON = NullIndex()
        return _INDEX_SINGLETON
    try:
        _INDEX_SINGLETON = _buildBackend()
    except Exception as e:  # noqa: BLE001 -- absent/broken dep -> fail open to the scan
        LOG.info("ANN backend unavailable, using O(n) scan fallback: %s", e)
        _INDEX_SINGLETON = NullIndex()
    return _INDEX_SINGLETON


def resetIndex() -> None:
    """Drop the cached singleton (tests, or after a known backfill rebuild)."""
    global _INDEX_SINGLETON
    _INDEX_SINGLETON = None
