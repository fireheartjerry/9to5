import config
from memory.experience_schema import LOG, _connect, _j, _nowIso, _writeConnect


def record_pr_outcome(
    run_id: str,
    pr_url: str,
    result: dict[str, Any],
    *,
    subtask_id: Optional[str] = None,
    db_path: Optional[Path] = None,
) -> bool:
    """Upsert one PR outcome row keyed by ``(run_id, pr_url)``. Best-effort.

    ``result`` is the dict returned by ``capturePRFeedback``; missing keys are
    stored as NULL so partial results are still recorded.
    Provenance is stored as JSON alongside the row so retrieval can attribute
    each outcome to its originating commit / subtask.
    """
    if not config.EXPERIENCE_LEDGER_ENABLED:
        return False
    if not (run_id or "").strip():
        LOG.warning("record_pr_outcome: missing run_id, skipping")
        return False
    if not (pr_url or "").strip():
        LOG.warning("record_pr_outcome: missing pr_url, skipping")
        return False
    try:
        prov = result.get("provenance") or {}
        if subtask_id and not prov.get("subtask_id"):
            prov = dict(prov, subtask_id=subtask_id)
        promote_safe = result.get("promote_safe")
        with _writeConnect(db_path) as conn:
            conn.execute(
                """INSERT INTO pr_outcomes
                   (run_id, subtask_id, pr_url, ci_status, ci_summary,
                    review_state, review_feedback_json, promote_safe,
                    provenance_json, recorded_at)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                   ON CONFLICT(run_id, pr_url) DO UPDATE SET
                     subtask_id=COALESCE(excluded.subtask_id, pr_outcomes.subtask_id),
                     ci_status=excluded.ci_status,
                     ci_summary=excluded.ci_summary,
                     review_state=excluded.review_state,
                     review_feedback_json=excluded.review_feedback_json,
                     promote_safe=excluded.promote_safe,
                     provenance_json=excluded.provenance_json,
                     recorded_at=excluded.recorded_at""",
                (
                    run_id,
                    subtask_id,
                    pr_url,
                    result.get("ci_status"),
                    result.get("ci_summary"),
                    result.get("review_state"),
                    _j(result.get("review_feedback")),
                    None if promote_safe is None else int(bool(promote_safe)),
                    _j(prov),
                    _nowIso(),
                ),
            )
        return True
    except Exception as e:  # noqa: BLE001
        LOG.warning("record_pr_outcome failed (ignored): %s", e)
        return False


def fetch_pr_outcomes(
    run_id: Optional[str] = None,
    *,
    promote_safe: Optional[bool] = None,
    limit: Optional[int] = None,
    db_path: Optional[Path] = None,
) -> list[dict[str, Any]]:
    """Query stored PR outcomes, optionally filtered by run or promotion safety."""
    try:
        with _connect(db_path) as conn:
            clauses: list[str] = []
            params: list[Any] = []
            if run_id is not None:
                clauses.append("run_id=?")
                params.append(run_id)
            if promote_safe is not None:
                clauses.append("promote_safe=?")
                params.append(1 if promote_safe else 0)
            sql = "SELECT * FROM pr_outcomes"
            if clauses:
                sql += " WHERE " + " AND ".join(clauses)
            sql += " ORDER BY id DESC"
            if limit is not None:
                sql += f" LIMIT {int(limit)}"
            return [dict(r) for r in conn.execute(sql, params)]
    except Exception as e:  # noqa: BLE001
        LOG.warning("fetch_pr_outcomes failed (ignored): %s", e)
        return []


if __name__ == "__main__":  # pragma: no cover -- self-test entrypoint
    import sys
    import tempfile

    if "--test" not in sys.argv:
        print("usage: python memory/experience_pr.py --test")
        sys.exit(1)

    from memory.experience_schema import _reset_schema_cache

    failed: list[str] = []

    def _check(label: str, condition: bool) -> None:
        if condition:
            print(f"  PASS  {label}")
        else:
            print(f"  FAIL  {label}")
            failed.append(label)

    with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as tmp:
        db = Path(tmp.name)

    try:
        _reset_schema_cache()

        # --- 1. disabled ledger skips silently
        _orig = config.EXPERIENCE_LEDGER_ENABLED
        config.EXPERIENCE_LEDGER_ENABLED = False
        ok = record_pr_outcome("r1", "https://github.com/x/x/pull/1", {}, db_path=db)
        _check("disabled ledger returns False", ok is False)
        config.EXPERIENCE_LEDGER_ENABLED = _orig

        # --- 2. missing run_id / pr_url guard
        ok = record_pr_outcome("", "https://github.com/x/x/pull/1", {}, db_path=db)
        _check("empty run_id returns False", ok is False)
        ok = record_pr_outcome("r1", "", {}, db_path=db)
        _check("empty pr_url returns False", ok is False)

        # --- 3. round-trip: write then read back
        result = {
            "ci_status": "success",
            "ci_summary": "All checks passed",
            "review_state": "approved",
            "review_feedback": {"comments": []},
            "promote_safe": True,
            "provenance": {"commit": "abc123", "subtask_id": "st-001"},
        }
        ok = record_pr_outcome("run-test", "https://github.com/x/x/pull/42", result, subtask_id="st-001", db_path=db)
        _check("record returns True", ok is True)

        rows = fetch_pr_outcomes(run_id="run-test", db_path=db)
        _check("fetch returns one row", len(rows) == 1)
        row = rows[0]
        _check("ci_status stored", row["ci_status"] == "success")
        _check("review_state stored", row["review_state"] == "approved")
        _check("promote_safe stored as 1", row["promote_safe"] == 1)
        _check("subtask_id stored", row["subtask_id"] == "st-001")

        # --- 4. upsert: update ci_status on same (run_id, pr_url)
        update = {"ci_status": "failure", "promote_safe": False}
        record_pr_outcome("run-test", "https://github.com/x/x/pull/42", update, db_path=db)
        rows2 = fetch_pr_outcomes(run_id="run-test", db_path=db)
        _check("upsert keeps one row", len(rows2) == 1)
        _check("upsert updated ci_status", rows2[0]["ci_status"] == "failure")
        _check("upsert updated promote_safe to 0", rows2[0]["promote_safe"] == 0)

        # --- 5. promote_safe filter
        record_pr_outcome("run-test", "https://github.com/x/x/pull/99", {"promote_safe": True}, db_path=db)
        safe_rows = fetch_pr_outcomes(run_id="run-test", promote_safe=True, db_path=db)
        _check("promote_safe=True filter returns 1", len(safe_rows) == 1)
        _check("filtered row is the safe one", safe_rows[0]["pr_url"] == "https://github.com/x/x/pull/99")

        # --- 6. limit
        all_rows = fetch_pr_outcomes(db_path=db, limit=1)
        _check("limit=1 returns 1 row", len(all_rows) == 1)

        # --- 7. unknown run_id returns empty
        empty = fetch_pr_outcomes(run_id="no-such-run", db_path=db)
        _check("unknown run_id returns empty list", empty == [])

    finally:
        _reset_schema_cache()
        try:
            db.unlink()
        except OSError:
            pass

    if failed:
        print(f"\n{len(failed)} check(s) failed: {failed}")
        sys.exit(1)

    print("\nAll checks passed.")
    sys.exit(0)
