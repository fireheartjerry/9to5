"""Experience Ledger -- solution-content store (owns the ``exp_content`` table).

Stores the REAL diff/answer/post-mortem per passed subtask plus a write-time
``importance`` salience, sibling to ``experience_subtasks`` (which owns ``subtasks``).
Same best-effort ``_WRITE_LOCK`` + ``_connect`` convention as ``experience_solutions``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  computeImportance(*, attempt_count: Any=None, adversary_verdict: Any=None, cost_usd: Any=None) -> float  -- Write-time salience: a noisy first-pass subtask that EVENTUALLY passed, or a
  recordSolutionContent(run_id: str, st_id: str, *, solution_content: str, post_mortem: str, importance: float, model_id: Optional[str], db_path: Optional[Path]=None) -> bool  -- Upsert one ``exp_content`` row keyed by ``(run_id, st_id)``
  recordFromSubtask(run_id: str, st: dict[str, Any], db_path: Optional[Path]=None) -> bool  -- Convenience: extract content + compute importance from ``st`` then store
  fetchSolutionContent(run_id: str, st_id: str, db_path: Optional[Path]=None) -> Optional[dict[str, Any]]  -- The stored content row for ``(run_id, st_id)``, or None
  fetchSolutionContents(keys: list[tuple[str, str]], db_path: Optional[Path]=None) -> dict[tuple[str, str], dict]
  lexicalSearch(query: str, limit: int=50, db_path: Optional[Path]=None) -> list[dict]  -- Derived FTS5 lane
DEPENDS-ON: memory.experience_schema, platform_core.core.best_effort
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/evolution/test_experience_content.py
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Optional

from memory.experience_schema import LOG, _connect, _nowIso, _writeConnect
from platform_core.core.best_effort import best_effort

_CONTESTED = {"challenged", "fail", "failed", "blocked", "reject", "rejected"}


def _ensure_fts(conn) -> bool:
    try:
        conn.execute("CREATE VIRTUAL TABLE IF NOT EXISTS exp_content_fts USING fts5(run_id UNINDEXED, st_id UNINDEXED, text)")
        return True
    except Exception:
        return False


def computeImportance(*, attempt_count: Any = None, adversary_verdict: Any = None,
                      cost_usd: Any = None) -> float:
    """Write-time salience: a noisy first-pass subtask that EVENTUALLY passed, or a
    contested/expensive one, is a higher-stakes lesson. Tolerant of nulls/garbage."""
    score = 1.0
    try:
        attempts = int(float(attempt_count)) if attempt_count is not None else 1
    except (TypeError, ValueError):
        attempts = 1
    if attempts > 1:
        score += min(attempts - 1, 3) * 0.5
    if isinstance(adversary_verdict, str) and adversary_verdict.strip().lower() in _CONTESTED:
        score += 1.0
    try:
        cost = float(cost_usd) if cost_usd is not None else 0.0
    except (TypeError, ValueError):
        cost = 0.0
    if cost > 0:
        score += min(cost, 5.0) * 0.2
    return round(score, 4)


def _extractFields(st: dict[str, Any]) -> tuple[str, str, Optional[str]]:
    """Pull (solution_content, post_mortem, model_id) from a synced subtask dict.
    Best-effort across known result shapes; degrades to title/description."""
    session = st.get("session") or {}
    solution = (session.get("result_text") or session.get("output") or session.get("summary")
                or st.get("_solution_content") or st.get("description") or "")
    post_mortem = (session.get("learning_summary") or st.get("_reflection")
                   or st.get("_post_mortem") or "")
    return str(solution), str(post_mortem), session.get("model")


def recordSolutionContent(run_id: str, st_id: str, *, solution_content: str,
                          post_mortem: str, importance: float, model_id: Optional[str],
                          db_path: Optional[Path] = None) -> bool:
    """Upsert one ``exp_content`` row keyed by ``(run_id, st_id)``. Best-effort."""
    if not (run_id or "").strip() or not (st_id or "").strip():
        return False
    with best_effort("ledger.exp_content", log=LOG):   # learning never blocks a run
        with _writeConnect(db_path) as conn:
            conn.execute(
                """INSERT INTO exp_content
                   (run_id, st_id, solution_content, post_mortem, importance, model_id, created_at)
                   VALUES (?, ?, ?, ?, ?, ?, ?)
                   ON CONFLICT(run_id, st_id) DO UPDATE SET
                     solution_content=excluded.solution_content,
                     post_mortem=excluded.post_mortem,
                     importance=excluded.importance,
                     model_id=excluded.model_id""",
                (run_id, st_id, solution_content, post_mortem, float(importance),
                 model_id, _nowIso()))
            if _ensure_fts(conn):
                conn.execute("DELETE FROM exp_content_fts WHERE run_id=? AND st_id=?", (run_id, st_id))
                conn.execute("INSERT INTO exp_content_fts(run_id, st_id, text) VALUES (?, ?, ?)",
                             (run_id, st_id, f"{solution_content}\n{post_mortem}"))
        return True
    return False


def recordFromSubtask(run_id: str, st: dict[str, Any], db_path: Optional[Path] = None) -> bool:
    """Convenience: extract content + compute importance from ``st`` then store. Best-effort."""
    if not isinstance(st, dict) or not (st.get("subtask_id") or "").strip():
        return False
    solution, post_mortem, model_id = _extractFields(st)
    if not solution.strip():
        return False
    session = st.get("session") or {}
    vres = st.get("verify_result") or {}
    importance = computeImportance(
        attempt_count=session.get("attempts") or vres.get("attempt_count"),
        adversary_verdict=st.get("_adversary_verdict"),
        cost_usd=session.get("cost_usd"))
    return recordSolutionContent(run_id, st["subtask_id"], solution_content=solution,
                                 post_mortem=post_mortem, importance=importance,
                                 model_id=model_id, db_path=db_path)


def fetchSolutionContent(run_id: str, st_id: str,
                         db_path: Optional[Path] = None) -> Optional[dict[str, Any]]:
    """The stored content row for ``(run_id, st_id)``, or None. Best-effort (None on error)."""
    with best_effort("ledger.exp_content_read", log=LOG):
        with _connect(db_path) as conn:
            row = conn.execute(
                "SELECT * FROM exp_content WHERE run_id=? AND st_id=?",
                (run_id, st_id)).fetchone()
            return dict(row) if row else None
    return None


def fetchSolutionContents(keys: list[tuple[str, str]], db_path: Optional[Path] = None) -> dict[tuple[str, str], dict]:
    if not keys:
        return {}
    with best_effort("ledger.exp_content_batch_read", log=LOG):
        with _connect(db_path) as conn:
            query = " OR ".join("(run_id=? AND st_id=?)" for _ in keys)
            params = [v for key in keys for v in key]
            rows = conn.execute(f"SELECT * FROM exp_content WHERE {query}", params).fetchall()
            return {(str(row["run_id"]), str(row["st_id"])): dict(row) for row in rows}
    return {}


def lexicalSearch(query: str, limit: int = 50, db_path: Optional[Path] = None) -> list[dict]:
    """Derived FTS5 lane; callers fall back to semantic retrieval when it is unavailable."""
    terms = " ".join(str(query or "").replace("\n", " ").split())
    if not terms:
        return []
    # FTS5 treats punctuation such as a hyphen as query syntax. Search
    # user-authored goals as literal tokens so they cannot name fake columns.
    tokens = re.findall(r"\w+", terms, flags=re.UNICODE)
    if not tokens:
        return []
    match_query = " ".join(f'"{token}"' for token in tokens)
    with best_effort("ledger.exp_content_fts", log=LOG):
        with _connect(db_path) as conn:
            if not _ensure_fts(conn):
                return []
            rows = conn.execute("SELECT run_id, st_id, bm25(exp_content_fts) AS rank FROM exp_content_fts WHERE exp_content_fts MATCH ? ORDER BY rank LIMIT ?", (match_query, max(1, int(limit)))).fetchall()
            return [{"run_id": row["run_id"], "st_id": row["st_id"], "lexical_rank": float(row["rank"])} for row in rows]
    return []
