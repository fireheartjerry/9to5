"""Conviction calibration ledger over the isolated logical state worker.

Judgments remain advisory evidence.  No row or aggregate can issue authority.

RUN/TEST: python -m pytest tests/evolution/test_conviction_ledger.py

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  record_judgment(*, judgment_type: str, domain: str, conviction: float, db_path: Optional[Path]=None, state_authority: object=None) -> str
  score_judgment(judgment_id: str, correct: bool, db_path: Optional[Path]=None, *, state_authority: object=None) -> bool
  track_record(judgment_type: str, domain: str, db_path: Optional[Path]=None, *, state_authority: object=None) -> dict[str, Any]
DEPENDS-ON: config, platform_core.app_config.paths, platform_core.runtime
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/evolution/test_conviction_ledger.py
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

import config
from platform_core.runtime.state_store_worker import (
    executeStateOperation,
    legacyDiagnosticStateWorkerAccess,
)


def _legacyPath(db_path: Optional[Path], authority: object) -> Path | None:
    if authority is not None:
        return None
    return Path(db_path) if db_path is not None else Path(config.CONVICTION_DB_PATH)


def _execute(
    operation: str,
    *,
    db_path: Optional[Path],
    state_authority: object,
    key: str = "",
    value: object = None,
) -> object:
    if state_authority is not None:
        return executeStateOperation(
            database_id="conviction",
            namespace="judgments",
            operation=operation,
            key=key,
            value=value,
            authority=state_authority,
        )
    with legacyDiagnosticStateWorkerAccess():
        return executeStateOperation(
            database_id="conviction",
            namespace="judgments",
            operation=operation,
            key=key,
            value=value,
            legacy_path=_legacyPath(db_path, state_authority),
        )


def record_judgment(
    *,
    judgment_type: str,
    domain: str,
    conviction: float,
    db_path: Optional[Path] = None,
    state_authority: object = None,
) -> str:
    judgment_id = str(uuid.uuid4())
    _execute(
        "kv_put",
        db_path=db_path,
        state_authority=state_authority,
        key=f"judgment_{judgment_id}",
        value={
            "conviction": float(conviction),
            "correct": None,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "domain": str(domain),
            "id": judgment_id,
            "judgment_type": str(judgment_type),
        },
    )
    return judgment_id


def score_judgment(
    judgment_id: str,
    correct: bool,
    db_path: Optional[Path] = None,
    *,
    state_authority: object = None,
) -> bool:
    key = f"judgment_{judgment_id}"
    value = _execute(
        "kv_get",
        db_path=db_path,
        state_authority=state_authority,
        key=key,
    )
    if not isinstance(value, dict) or value.get("id") != judgment_id:
        return False
    updated = dict(value)
    updated["correct"] = bool(correct)
    _execute(
        "kv_put",
        db_path=db_path,
        state_authority=state_authority,
        key=key,
        value=updated,
    )
    return True


def track_record(
    judgment_type: str,
    domain: str,
    db_path: Optional[Path] = None,
    *,
    state_authority: object = None,
) -> dict[str, Any]:
    values = _execute(
        "kv_list",
        db_path=db_path,
        state_authority=state_authority,
    )
    rows: list[dict[str, Any]] = []
    for item in values if isinstance(values, list) else []:
        row = item.get("value") if isinstance(item, dict) else None
        if isinstance(row, dict):
            rows.append(row)
    scored = [
        row
        for row in rows
        if row.get("judgment_type") == judgment_type
        and row.get("domain") == domain
        and isinstance(row.get("correct"), bool)
    ]
    hits = sum(1 for row in scored if row["correct"] is True)
    total = len(scored)
    return {"hits": hits, "total": total, "rate": hits / total if total else 0.0}


__all__ = ["record_judgment", "score_judgment", "track_record"]
