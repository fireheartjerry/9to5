def _buildRunOrchestrator(args):
    """The Orchestrator for a live run. --sim-run swaps in the zero-API simulation doubles
    (brain/executor/replan/review) while every surface (Discord dashboard, web, control gates)
    stays live, so the bot is exercised end-to-end for free. Otherwise the real Orchestrator."""
    if getattr(args, "sim_run", False):
        import platform_core.simulator.simulation as simulation
        LOG.info("SIM-RUN: full lifecycle over live surfaces with simulation doubles (zero API cost)")
        return simulation.buildOrchestrator(offline=False)
    return Orchestrator()


_CTL_HELP = ("[terminal control] commands: abort | pause | resume | skip <st-00N> | "
             "add <text> | approve | reject | status | help")


def _startTerminalControl(task_id: str) -> threading.Thread:
    """Daemon thread: read stdin and mirror Discord control commands to the ControlBus."""
    bus = ControlBus(task_id)

    def loop() -> None:
        print(_CTL_HELP, flush=True)
        for line in sys.stdin:
            cmd = line.strip()
            if not cmd:
                continue
            low = cmd.lower().lstrip("!")
            try:
                if low in ("abort", "stop", "quit"):
                    bus.requestAbort()
                    print("[ctl] abort requested", flush=True)
                elif low == "pause":
                    bus.requestPause()
                    print("[ctl] paused", flush=True)
                elif low == "resume":
                    bus.clearPause()
                    print("[ctl] resumed", flush=True)
                elif low in ("approve", "reject"):
                    gate = bus.getPendingGate()
                    if gate:
                        bus.decide(gate, "approve" if low == "approve" else "reject")
                        print(f"[ctl] gate {gate} -> {low}", flush=True)
                    else:
                        print("[ctl] no pending gate", flush=True)
                elif low.startswith("skip "):
                    bus.pushOp({"op": "skip", "subtask_id": cmd.split(None, 1)[1].strip()})
                    print("[ctl] skip queued", flush=True)
                elif low.startswith("add "):
                    text = cmd.split(None, 1)[1].strip()
                    bus.pushOp({"op": "add", "title": text, "description": text})
                    print("[ctl] add queued", flush=True)
                elif low == "status":
                    st = TaskState.load(task_id)
                    d, t = st.progress()
                    print(f"[ctl] {st.meta['status']} · {d}/{t} subtasks", flush=True)
                else:
                    print(_CTL_HELP, flush=True)
            except Exception as e:  # noqa: BLE001
                print(f"[ctl] error: {e}", flush=True)

    thread = threading.Thread(target=loop, name="terminal-control", daemon=True)
    thread.start()
    return thread


def _collectEditedSpec() -> str:
    print("Enter the replacement specification. End with a single '.' on its own line:")
    buf: list[str] = []
    for line in sys.stdin:
        if line.rstrip("\n") == ".":
            break
        buf.append(line.rstrip("\n"))
    return "\n".join(buf).strip()


def _runDryRun(args) -> int:
    """Simulate a FULL run (architect -> plan -> execute -> verify -> complete) with no
    Ollama / Claude CLI / Discord / Obsidian. Proves the orchestration end-to-end."""
    import platform_core.simulator.simulation as simulation
    import tempfile
    flags = app_settings.runFlags()   # run-scoped flags; config module globals stay untouched
    flags.WEB_DASHBOARD = False
    flags.CLAUDE_DOC_FETCH = False    # offline knowledge build only -- no web fetch in a dry-run
    config.ensureDirs()
    goal = (args.goal or "Simulated dry-run goal").strip()
    state = TaskState.create(goal, args.hours)
    _applyWorkProfile(args, state)
    state.setElaboratedGoal(goal)
    state.setUniverse({"description": "dry-run", "allowed_paths": [],
                       "allowed_to_expand_to": [], "hard_boundaries": []})
    state.save()
    # isolated temp work_dir: keeps the dry-run from tripping self-referential detection
    # (which would create a git branch) or writing into the real project tree.
    work_dir = tempfile.mkdtemp(prefix="9to5-dryrun-")
    chaos_seed = getattr(args, "chaos", None)
    if chaos_seed is not None:
        import platform_core.simulator.chaos as chaos
        print(f"[DRY-RUN · CHAOS seed={chaos_seed}] simulating a full run for {goal!r} under "
              f"seeded fault injection — no Ollama/Claude/Discord/Obsidian touched.")
        orch = chaos.buildChaosOrchestrator(work_dir, chaos_seed)
    else:
        print(f"[DRY-RUN] simulating a full run for {goal!r} — no Ollama/Claude/Discord/Obsidian touched.")
        orch = simulation.buildOrchestrator(offline=True)
    # A dry-run is a non-interactive offline proof of the whole lifecycle.  It
    # must never inherit the CLI's default ``gated`` mode and wait indefinitely
    # for an approval that no live surface can deliver.
    summary = orch.runFull(state, work_dir=work_dir, auto_pr=False,
                           control_mode="watch", parallelism=max(1, args.parallel))
    print("\n===== DRY-RUN SUMMARY =====")
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0



def _applyConfigOverrides(args) -> None:
    """Apply CLI args to the run-scoped flag object (NOT config module globals -- the
    facade routes NIGHT_MODE/WEB_DASHBOARD/WEB_DASHBOARD_PORT/CLAUDE_DOC_FETCH reads
    to this object) and call ensureDirs."""
    flags = app_settings.runFlags()
    flags.WEB_DASHBOARD_PORT = args.web_port
    if args.no_web:
        flags.WEB_DASHBOARD = False
    if args.night_mode:
        flags.NIGHT_MODE = True
        args.mode = "watch"          # night mode is always watch — no human gates
        args.auto_approve = True     # suppress elaboration approval prompt
    config.ensureDirs()


def _applyWorkProfile(args, state: TaskState) -> None:
    """Resolve CLI profile once and persist both raw axes and compiled policy."""
    prof = work_profile.resolve(getattr(args, "work_profile", None))
    state.meta["work_profile"] = prof.to_meta()
    state.meta["run_intent_policy"] = work_profile.policy(prof).to_meta()
    state.save()


def _resolveOrphan(args) -> None:
    """Auto-resume orphan when no --goal/--resume given.
    Only resumes when the run is provably dead (heartbeat.isRunAlive: no fresh heartbeat AND
    the recorded pid is gone; unverifiable -> assumed ALIVE, never double-spawn)."""
    if args.resume or args.goal:
        return
    import platform_core.runtime.resilience as _res
    orphan = _res.pick_resume_task()
    if not orphan:
        return
    try:
        from platform_core.runtime.heartbeat import isRunAlive
        if not isRunAlive(orphan):
            LOG.info("auto-resuming orphaned run %s (recorded process is dead)", orphan)
            print(f"Resuming orphaned run {orphan[:8]} (previous process died)…")
            args.resume = orphan
    except Exception:  # noqa: BLE001 -- orphan resume is opportunistic, but never silent
        LOG.warning("orphan liveness check failed for %s; skipping auto-resume", orphan,
                    exc_info=True)


def _announceLaunch(args, state: TaskState) -> None:
    """Launch handshake: report this run's task_id to the launcher via state/launch/<id>.json
    (replaces the launcher's newest-state-file polling). Best-effort, never blocks the run."""
    launch_id = getattr(args, "launch_id", None)
    if not launch_id:
        return
    try:
        from platform_core.core import fsio
        fsio.atomicWriteJson(config.LAUNCH_DIR / f"{launch_id}.json",
                             {"task_id": state.task_id, "pid": os.getpid(),
                              "at": datetime.now().astimezone().isoformat(timespec="seconds")})
    except Exception:  # noqa: BLE001
        LOG.warning("launch handshake write failed (launcher will time out politely)",
                    exc_info=True)


def _resumeRun(args) -> int:
    """Load a task and resume it under the resilience supervisor."""
    try:
        state = TaskState.load(args.resume)
    except Exception as e:  # noqa: BLE001
        print(f"Cannot resume {args.resume}: {e}")
        return 2
    main_cli.extendResumeDeadline(state, getattr(args, "resume_extend_hours", None))
    if getattr(args, "retry_failed", False):
        main_cli.retryFailedSubtasks(state)
    # Re-stamp the liveness beacon immediately so a concurrent activeRun() never mis-aborts this run.
    state.meta["run_pid"] = os.getpid()
    state.save()
    from platform_core.runtime import heartbeat as _hb
    _hb.writeHeartbeat(state.task_id)
    _announceLaunch(args, state)
    resume_work_dir = args.work_dir or state.meta.get("work_dir") or str(config.PROJECT_ROOT)
    LOG.info("Resuming task %s in %s", state.task_id, resume_work_dir)
    if sys.stdin.isatty():   # only on a real TTY — a detached resume gets EOF -> useless spin
        _startTerminalControl(state.task_id)
    import platform_core.runtime.resilience as resilience

    def _run_resume(st):
        st.meta["run_pid"] = os.getpid()   # liveness beacon so the launcher never double-spawns a live run
        st.save()
        return _buildRunOrchestrator(args).runFull(st, work_dir=resume_work_dir, auto_pr=not args.no_pr,
                                                    control_mode=args.mode, resume=True,
                                                    parallelism=max(1, args.parallel))

    summary = resilience.run_with_recovery(_run_resume, state)
    print("\n===== RUN SUMMARY =====")
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0


def _handleApproval(args, state, work_dir: str) -> bool:
    """Prompt for approval; returns True to proceed, False when human aborts (marks state aborted)."""
    if args.auto_approve:
        return True
    try:
        ans = input("Approve elaboration? [Y / edit / n] ").strip().lower()
    except EOFError:   # non-interactive without --auto-approve -> proceed (don't crash the run)
        return True
    if ans in {"n", "no"}:
        print("Aborted by human.")
        state.setStatus("aborted")
        return False
    if ans == "edit":
        edited = _collectEditedSpec()
        if edited:
            state.setElaboratedGoal(edited)
            # Scope is derived from the specification, not merely the original raw
            # goal. Recompute it after a human changes the approved contract so the
            # architect, executor, and hard-boundary hooks never inherit stale hints.
            universe = elaborator.extractUniverse(state.meta.get("goal_raw", ""), edited, work_dir)
            state.setUniverse(universe)
            state.meta["elaboration_human_edited"] = True
            # The nested record is the one retained with the eventual run outcome
            # for elaborator learning. Keep it authoritative as well as the legacy
            # top-level marker so human revisions are never mislabeled as model-only.
            state.meta.setdefault("elaboration", {})["human_edited"] = True
            state.save()
            print("Elaboration replaced.")
    return True


def _elaborateGoal(args, work_dir: str):
    """Validate env/goal, create TaskState, elaborate and approve.
    Returns the TaskState on success, or an int exit-code to abort early."""
    missing = config.validateEnv()
    if missing:
        LOG.warning("Missing env values: %s (degraded mode)", ", ".join(missing))
    obs_health = ObsidianClient().health()
    LOG.info("Obsidian REST: reachable=%s authed=%s (disk fallback always available)",
             obs_health["rest_ok"], obs_health["authed"])
    try:
        goal = (args.goal or input("9TO5 goal> ")).strip()
    except EOFError:   # non-interactive stdin with no --goal -> abort cleanly
        goal = (args.goal or "").strip()
    if not goal:
        print("No goal given; aborting.")
        return 2
    state = TaskState.create(goal, args.hours)
    _applyWorkProfile(args, state)
    # Stamp run_pid BEFORE first save so no concurrent activeRun() mis-declares this run stale.
    state.meta["run_pid"] = os.getpid()
    state.save()
    from platform_core.runtime import heartbeat as _hb
    _hb.writeHeartbeat(state.task_id)   # liveness beacon covering the slow elaboration window
    _announceLaunch(args, state)        # launch handshake for the Discord launcher (--launch-id)
    LOG.info("Created task %s (horizon %sh, mode %s, parallel %s)",
             state.task_id, args.hours, args.mode, args.parallel)
    if getattr(args, "sim_run", False):
        # Token-light: skip the Ollama elaborator/universe extraction entirely. The goal is used
        # verbatim and the run edits nothing (simulation executor), so a wide-open universe is safe.
        state.setElaboratedGoal(goal)
        state.setUniverse({"description": "sim-run", "allowed_paths": [],
                           "allowed_to_expand_to": [], "hard_boundaries": []})
        return state
    with best_effort("doctor.preflight", log=LOG):
        import platform_core.ops.doctor as doctor
        _pf = doctor.run()
        if not _pf["ready"]:
            print(doctor.render(_pf))
            print("(continuing in degraded mode — run `python main.py --doctor` for details)\n")
    _elab_meta: dict = {}
    elaborated = elaborator.elaborate(goal, work_dir, out_meta=_elab_meta)
    state.setElaboratedGoal(elaborated)
    state.meta["elaboration_stance"] = _elab_meta.get("stance", "single-shot")
    state.meta["elaboration"] = {"schema": _elab_meta.get("schema", {}),
                                  "candidates": _elab_meta.get("candidates", {}),
                                  "precedent": _elab_meta.get("precedent", {}),
                                  "uncertainty": _elab_meta.get("uncertainty", {}),
                                  "human_edited": False}
    state.save()
    print("\n===== ELABORATED GOAL =====\n" + elaborated + "\n===========================\n")
    universe = elaborator.extractUniverse(goal, elaborated, work_dir)
    state.setUniverse(universe)
    LOG.info("Universe: %d allowed_paths, hard_boundaries=%s",
             len(universe.get("allowed_paths", [])), universe.get("hard_boundaries"))
    if not _handleApproval(args, state, work_dir):
        return 1
    return state


def _setupAndRun(args, state, work_dir: str) -> int:
    """Start terminal control thread then run under the resilience supervisor."""
    # Start stdin control thread AFTER all prompts (earlier = two threads on stdin, lost keystrokes).
    if sys.stdin.isatty():
        _startTerminalControl(state.task_id)
    import platform_core.runtime.resilience as resilience

    def _run(st):
        st.meta["run_pid"] = os.getpid()   # liveness beacon so the launcher never double-spawns a live run
        st.save()
        return _buildRunOrchestrator(args).runFull(st, work_dir=work_dir, auto_pr=not args.no_pr,
                                                    control_mode=args.mode, parallelism=max(1, args.parallel))

    summary = resilience.run_with_recovery(_run, state)
    print("\n===== RUN SUMMARY =====")
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0


def _freshRun(args, work_dir: str) -> int:
    """Validate env, prompt for goal, elaborate, then run under the resilience supervisor."""
    result = _elaborateGoal(args, work_dir)
    if isinstance(result, int):
        return result
    return _setupAndRun(args, result, work_dir)


def _resolveWorkDir(args) -> "str | int":
    """Resolve the run's work_dir (clone repo / validate --work-dir / fence a sim-run).
    Returns the work_dir path, or an int exit code on a resolution error."""
    if args.repo_ref and not args.repo_url:
        print("--repo-ref requires --repo-url")
        return 2
    if args.repo_url and args.work_dir:
        print("--repo-url and --work-dir are mutually exclusive")
        return 2
    if args.repo_url:
        try:
            from platform_core.ops.external_project import cloneRepo
            args.work_dir = str(cloneRepo(args.repo_url, args.repo_ref))
            print(f"Cloned repo -> {args.work_dir}")
        except Exception as e:  # noqa: BLE001
            print(f"--repo-url clone failed: {e}")
            return 2
    # A user-chosen --work-dir must exist (9to5 operates on YOUR project tree, not its own root).
    if args.work_dir and not Path(args.work_dir).is_dir():
        print(f"--work-dir does not exist or is not a directory: {args.work_dir}")
        return 2
    if getattr(args, "sim_run", False) and not args.work_dir:
        # A sim-run edits nothing (simulation executor), so keep it OUT of the repo root: an
        # isolated temp work_dir prevents self-referential detection from creating/committing a
        # branch. The live surfaces (Discord/web/control) still run — only the work_dir is fenced.
        import tempfile
        work_dir = tempfile.mkdtemp(prefix="9to5-simrun-")
        LOG.info("SIM-RUN work_dir fenced to %s (no self-ref git branch)", work_dir)
        return work_dir
    return args.work_dir or str(config.PROJECT_ROOT)


def main() -> int:
    # `@9to5 <goal>` chat-style shorthand -> rewrite to `--goal "..." --auto-approve`.
    argv = _applyMentionShorthand(sys.argv[1:])

    # Intercept before argparse (which would reject bare "/refresh" / "--doctor" tokens).
    refresh_code = _interceptRefreshCommand(argv)
    if refresh_code is not None:
        return refresh_code
    doctor_code = _interceptDoctorCommand(argv)
    if doctor_code is not None:
        return doctor_code

    args = _parseArgs(argv)

    if args.health:
        import platform_core.ops.health as health
        return 0 if health.runHealthChecks() else 1
    if args.e2e:
        from platform_core.simulator.testing.e2e import main as e2eMain
        return e2eMain()
    if args.dry_run:
        return _runDryRun(args)

    if not getattr(args, "sim_run", False):
        requireTransactionalKernelActive()

    if args.task_id and not args.resume:   # --task-id is an alias for --resume
        args.resume = args.task_id

    _applyConfigOverrides(args)

    # Living knowledge refresh: happens before any Ollama call so the brain reasons from the
    # current Claude Code feature set. Idempotent per process; never blocks the run.
    # Skipped for --sim-run (no real brain -> nothing to inform; keeps it fully offline/free).
    if not getattr(args, "sim_run", False):
        try:
            refreshClaudeKnowledge()
        except Exception as e:  # noqa: BLE001
            LOG.warning("startup knowledge refresh failed (non-fatal): %s", e)

    work_dir = _resolveWorkDir(args)
    if isinstance(work_dir, int):        # a resolution error surfaced as an exit code
        return work_dir
    if config.WEB_DASHBOARD:
        print(f"Live web dashboard -> http://127.0.0.1:{config.WEB_DASHBOARD_PORT}/  "
              f"(control: terminal / Discord !abort / web buttons)")

    _resolveOrphan(args)

    if args.resume:
        return _resumeRun(args)
    return _freshRun(args, work_dir)


if __name__ == "__main__":
    sys.exit(main())
