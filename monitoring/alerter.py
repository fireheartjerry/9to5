from __future__ import annotations

import threading
import time
from typing import Optional

import config
import monitoring
from monitoring.tracker import CRITICAL_DETECTION_WINDOW_SECS, MAX_RETRIES, SUCCESS_RATE_MIN

LOG = config.getLogger("monitoring.alerter")

# How long (seconds) a notified alert key is suppressed before re-firing.
DEDUP_TTL_SECONDS: float = 300.0

_lock = threading.Lock()
# Maps dedup key -> monotonic timestamp when it was last notified.
_notified: dict[str, float] = {}

_stop_event = threading.Event()
_thread: Optional[threading.Thread] = None


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def startAlertLoop(interval_seconds: float = 10.0) -> None:
    """Start a background daemon thread that calls ``checkAndNotify`` on an
    interval.  Idempotent -- a second call while the thread is alive is a no-op."""
    global _thread
    with _lock:
        if _thread is not None and _thread.is_alive():
            return
        _stop_event.clear()
        _thread = threading.Thread(
            target=_alertLoop,
            args=(interval_seconds,),
            daemon=True,
            name="monitoring-alerter",
        )
        _thread.start()
    LOG.info("Alert loop started (interval=%.0fs)", interval_seconds)


def stopAlertLoop() -> None:
    """Signal the background loop to exit.  Returns immediately; join if you
    need to wait."""
    _stop_event.set()
    LOG.info("Alert loop stop requested")


def checkAndNotify() -> list[str]:
    """Single synchronous poll: read current alerts from tracker, fire Discord
    notifications for any that are new (not in dedup window), return list of
    keys that fired this round."""
    fired: list[str] = []
    now = time.monotonic()

    alerts = monitoring.get_alerts()
    critical_events = monitoring.get_critical_events()

    for alert in alerts:
        # Late-detection critical alerts are surfaced BOTH here (via
        # tracker.get_alerts()) and in the dedicated critical-events loop below.
        # Handling them in both places fired two Discord notifications under two
        # dedup keys for a single event. The critical-events loop owns them, so
        # skip them here and let that loop fire exactly once.
        if alert.get("type") == "critical_event_late_detection":
            continue
        key = _alertKey(alert)
        if _shouldFire(key, now):
            _markFired(key, now)
            _notifyAlert(alert)
            fired.append(key)

    # Also check for any critical events detected with lag > threshold
    for ev in critical_events:
        if ev.get("lag_seconds", 0) > CRITICAL_DETECTION_WINDOW_SECS:
            key = f"critical_late:{ev['event_id']}"
            if _shouldFire(key, now):
                _markFired(key, now)
                _notifyCriticalEvent(ev)
                fired.append(key)

    return fired


def getNotifiedKeys() -> dict[str, float]:
    """Return a snapshot of the dedup map (test helper)."""
    with _lock:
        return dict(_notified)


def resetState() -> None:
    """Clear dedup state and stop the loop.  For tests."""
    global _thread
    stopAlertLoop()
    with _lock:
        _notified.clear()
        _thread = None


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _alertLoop(interval_seconds: float) -> None:
    while not _stop_event.is_set():
        try:
            checkAndNotify()
        except Exception as exc:  # noqa: BLE001
            LOG.warning("Alert loop error: %s", exc)
        _stop_event.wait(interval_seconds)


def _alertKey(alert: dict) -> str:
    """Stable dedup key for an alert dict."""
    a_type = alert.get("type", "unknown")
    if a_type == "max_retries_exceeded":
        return f"{a_type}:{alert.get('workflow_id', '')}"
    if a_type == "critical_event_late_detection":
        return f"{a_type}:{alert.get('event_id', '')}"
    return a_type


def _shouldFire(key: str, now: float) -> bool:
    with _lock:
        last = _notified.get(key)
    if last is None:
        return True
    return (now - last) >= DEDUP_TTL_SECONDS


def _markFired(key: str, now: float) -> None:
    with _lock:
        _notified[key] = now


def _notifyAlert(alert: dict) -> None:
    """Send a Discord embed for a threshold-breach alert."""
    try:
        from notifications import discord_bot
    except Exception:  # noqa: BLE001
        return

    a_type = alert.get("type", "unknown")
    msg = alert.get("message", a_type)

    embed = _buildAlertEmbed(a_type, msg, alert)
    content = discord_bot.humanPing() or None
    discord_bot.sendEmbed(embed, content=content)
    LOG.warning("Alert notified: %s", msg)


def _notifyCriticalEvent(ev: dict) -> None:
    """Send a Discord embed for a late-detected critical event."""
    try:
        from notifications import discord_bot
    except Exception:  # noqa: BLE001
        return

    lag = ev.get("lag_seconds", 0.0)
    event_id = ev.get("event_id", "?")
    event_type = ev.get("event_type", "?")
    msg = (
        f"Critical event `{event_id}` ({event_type}) detected "
        f"{lag:.1f}s after occurrence (threshold: {CRITICAL_DETECTION_WINDOW_SECS:.0f}s)"
    )
    embed = _buildAlertEmbed("critical_event_late_detection", msg, ev)
    content = discord_bot.humanPing() or None
    discord_bot.sendEmbed(embed, content=content)
    LOG.warning("Critical event alert notified: %s", msg)


def _buildAlertEmbed(a_type: str, message: str, data: dict) -> dict:
    from datetime import datetime, timezone

    _COLORS = {
        "low_success_rate": 0xE74C3C,           # red
        "high_avg_delay": 0xE67E22,             # orange
        "max_retries_exceeded": 0xF39C12,        # amber
        "critical_event_late_detection": 0x9B59B6,  # purple
    }
    color = _COLORS.get(a_type, 0x95A5A6)

    _TITLES = {
        "low_success_rate": "Alert — Low Success Rate",
        "high_avg_delay": "Alert — High Average Delay",
        "max_retries_exceeded": "Alert — Max Retries Exceeded",
        "critical_event_late_detection": "Alert — Critical Event Late Detection",
    }
    title = _TITLES.get(a_type, f"Alert — {a_type}")

    fields = [{"name": "Detail", "value": message[:1024], "inline": False}]

    if a_type == "low_success_rate":
        val = data.get("value")
        thr = data.get("threshold", SUCCESS_RATE_MIN)
        if val is not None:
            fields.append({"name": "Rate", "value": f"{val:.1%}", "inline": True})
        fields.append({"name": "Threshold", "value": f"{thr:.0%}", "inline": True})

    elif a_type == "high_avg_delay":
        val = data.get("value")
        thr = data.get("threshold", 300.0)
        if val is not None:
            fields.append({"name": "Avg delay", "value": f"{val:.1f}s", "inline": True})
        fields.append({"name": "Threshold", "value": f"{thr:.0f}s", "inline": True})

    elif a_type == "max_retries_exceeded":
        wf_id = data.get("workflow_id", "?")
        retries = data.get("retries", MAX_RETRIES)
        fields.append({"name": "Workflow", "value": f"`{wf_id}`", "inline": True})
        fields.append({"name": "Retries", "value": str(retries), "inline": True})

    elif a_type == "critical_event_late_detection":
        lag = data.get("lag_seconds", 0.0)
        fields.append({"name": "Lag", "value": f"{lag:.1f}s", "inline": True})
        fields.append({"name": "Window", "value": f"{CRITICAL_DETECTION_WINDOW_SECS:.0f}s", "inline": True})

    return {
        "title": title,
        "color": color,
        "description": message[:2048],
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "fields": fields,
        "footer": {"text": "9to5 active alerting"},
    }
