"""monitoring.tracker -- in-memory execution tracking and threshold alerting.

All state lives in a module-level list so callers (and tests) can share it without
passing objects around.  Call ``reset()`` between tests.

Thresholds (acceptance criteria):
  SUCCESS_RATE_MIN               = 0.90  (flag when rate drops below 90%)
  MAX_DELAY_SECONDS              = 300.0 (flag when avg delay exceeds 5 minutes)
  MAX_RETRIES                    = 3     (flag when retries at or above this value)
  CRITICAL_DETECTION_WINDOW_SECS = 120.0 (flag when detection lag exceeds 2 minutes)

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  record_execution(workflow_id: str, success: bool, delay_seconds: float, retries: int=0) -> None  -- Record one workflow execution and refresh alerts.
  get_success_rate(workflow_id: Optional[str]=None) -> Optional[float]  -- Return fraction of successful executions, or None if no records.
  get_avg_delay(workflow_id: Optional[str]=None) -> Optional[float]  -- Return mean delay in seconds, or None if no records.
  record_critical_event(event_id: str, event_type: str, occurred_at: Optional[float]=None) -> None  -- Record a critical event and fire a late-detection alert if lag > 2 min.
  get_alerts() -> list[dict]  -- Return a snapshot of current active alerts.
  get_critical_events() -> list[dict]  -- Return a snapshot of all recorded critical events.
  reset() -> None  -- Clear all state
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import threading
import time
from typing import Optional

SUCCESS_RATE_MIN: float = 0.90
MAX_DELAY_SECONDS: float = 300.0
MAX_RETRIES: int = 3
CRITICAL_DETECTION_WINDOW_SECS: float = 120.0

_lock = threading.Lock()
_records: list[dict] = []
_alerts: list[dict] = []
_critical_events: list[dict] = []


def record_execution(
    workflow_id: str,
    success: bool,
    delay_seconds: float,
    retries: int = 0,
) -> None:
    """Record one workflow execution and refresh alerts."""
    with _lock:
        _records.append({
            "workflow_id": workflow_id,
            "success": success,
            "delay_seconds": delay_seconds,
            "retries": retries,
        })
        _refreshAlerts()


def get_success_rate(workflow_id: Optional[str] = None) -> Optional[float]:
    """Return fraction of successful executions, or None if no records."""
    with _lock:
        recs = _filterRecords(workflow_id)
    if not recs:
        return None
    return sum(1 for r in recs if r["success"]) / len(recs)


def get_avg_delay(workflow_id: Optional[str] = None) -> Optional[float]:
    """Return mean delay in seconds, or None if no records."""
    with _lock:
        recs = _filterRecords(workflow_id)
    if not recs:
        return None
    return sum(r["delay_seconds"] for r in recs) / len(recs)


def record_critical_event(
    event_id: str,
    event_type: str,
    occurred_at: Optional[float] = None,
) -> None:
    """Record a critical event and fire a late-detection alert if lag > 2 min."""
    detected_at = time.time()
    if occurred_at is None:
        occurred_at = detected_at
    lag = detected_at - occurred_at
    entry: dict = {
        "event_id": event_id,
        "event_type": event_type,
        "occurred_at": occurred_at,
        "detected_at": detected_at,
        "lag_seconds": lag,
    }
    with _lock:
        _critical_events.append(entry)
        if lag > CRITICAL_DETECTION_WINDOW_SECS:
            _alerts.append({
                "type": "critical_event_late_detection",
                "event_id": event_id,
                "event_type": event_type,
                "lag_seconds": lag,
                "threshold": CRITICAL_DETECTION_WINDOW_SECS,
                "message": (
                    f"Critical event '{event_id}' ({event_type}) detected "
                    f"{lag:.1f}s after occurrence "
                    f"(threshold: {CRITICAL_DETECTION_WINDOW_SECS:.0f}s)"
                ),
            })


def get_alerts() -> list[dict]:
    """Return a snapshot of current active alerts."""
    with _lock:
        return list(_alerts)


def get_critical_events() -> list[dict]:
    """Return a snapshot of all recorded critical events."""
    with _lock:
        return list(_critical_events)


def reset() -> None:
    """Clear all state. Intended for tests."""
    with _lock:
        _records.clear()
        _alerts.clear()
        _critical_events.clear()


# ---------------------------------------------------------------------------
# Internal helpers (called under _lock)
# ---------------------------------------------------------------------------

def _filterRecords(workflow_id: Optional[str]) -> list[dict]:
    if workflow_id is None:
        return list(_records)
    return [r for r in _records if r["workflow_id"] == workflow_id]


def _refreshAlerts() -> None:
    """Recompute alert list from current _records. Called under _lock.

    Critical-event late-detection alerts are produced by ``record_critical_event``
    and are NOT derivable from ``_records``; preserve them so a subsequent
    ``record_execution`` refresh does not wipe them.
    """
    preserved = [
        a for a in _alerts
        if a.get("type") == "critical_event_late_detection"
    ]
    _alerts.clear()
    _alerts.extend(preserved)

    if not _records:
        return

    rate = sum(1 for r in _records if r["success"]) / len(_records)
    if rate < SUCCESS_RATE_MIN:
        _alerts.append({
            "type": "low_success_rate",
            "value": rate,
            "threshold": SUCCESS_RATE_MIN,
            "message": (
                f"Success rate {rate:.1%} is below the "
                f"{SUCCESS_RATE_MIN:.0%} threshold"
            ),
        })

    avg_delay = sum(r["delay_seconds"] for r in _records) / len(_records)
    if avg_delay > MAX_DELAY_SECONDS:
        _alerts.append({
            "type": "high_avg_delay",
            "value": avg_delay,
            "threshold": MAX_DELAY_SECONDS,
            "message": (
                f"Average delay {avg_delay:.1f}s exceeds the "
                f"{MAX_DELAY_SECONDS:.0f}s threshold"
            ),
        })

    # Per-record retry alerts
    seen_ids: set[str] = set()
    for r in _records:
        wf_id = r["workflow_id"]
        if r["retries"] >= MAX_RETRIES and wf_id not in seen_ids:
            seen_ids.add(wf_id)
            _alerts.append({
                "type": "max_retries_exceeded",
                "workflow_id": wf_id,
                "retries": r["retries"],
                "threshold": MAX_RETRIES,
                "message": (
                    f"Workflow '{wf_id}' hit {r['retries']} retries "
                    f"(threshold: {MAX_RETRIES})"
                ),
            })
