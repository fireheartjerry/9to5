class CleanupReceipt(ImmutableReceipt):
    receipt_type: ClassVar[str] = "cleanup"
    transaction_id: str
    finalization_receipt_id: str
    previous_cleanup_receipt_id: str
    removed_artifact_ids: tuple[str, ...]
    retained_artifact_ids: tuple[str, ...]
    failed_artifact_ids: tuple[str, ...]
    warnings: tuple[str, ...]
    complete: bool
    completed_at: str

    def __post_init__(self) -> None:
        _require_identifier(self.transaction_id, "transaction_id")
        _require_digest(self.finalization_receipt_id, "finalization_receipt_id")
        _require_digest(
            self.previous_cleanup_receipt_id,
            "previous_cleanup_receipt_id",
            optional=True,
        )
        if not all(isinstance(value, tuple) for value in (
            self.removed_artifact_ids,
            self.retained_artifact_ids,
            self.failed_artifact_ids,
            self.warnings,
        )):
            raise TypeError("cleanup collections must be immutable tuples")
        if type(self.complete) is not bool:
            raise TypeError("cleanup complete must be bool")
        dispositions = (
            self.removed_artifact_ids,
            self.retained_artifact_ids,
            self.failed_artifact_ids,
        )
        for values in dispositions:
            if values != tuple(sorted(values)) or len(values) != len(set(values)):
                raise ValueError("cleanup artifact IDs must be unique canonical tuples")
            for artifact_id in values:
                _require_identifier(artifact_id, "cleanup artifact ID")
        all_artifacts = tuple(item for values in dispositions for item in values)
        if len(all_artifacts) != len(set(all_artifacts)):
            raise ValueError("every cleanup artifact must have one terminal disposition")
        for warning in self.warnings:
            _require_text(warning, "cleanup warning")
            if len(warning.encode("utf-8")) > 2048:
                raise ValueError("cleanup warning exceeds quota")
        if self.complete and self.failed_artifact_ids:
            raise ValueError("cleanup with failed artifacts cannot be complete")
        _require_iso8601(self.completed_at, "completed_at")


