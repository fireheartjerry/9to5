@dataclass(frozen=True)
class ValidatedPromotionEvidence:
    """Re-read receipt evidence only; this object is deliberately not landing authority."""

    journal_record: AttemptRecord
    staging: StagingReceipt
    verification: RevisionVerificationReceipt
    review: ReviewReceipt
    selection: SelectionReceipt | None


def validatePromotionAuthorization(
    authorization: object,
    *,
    store: ReceiptStore,
    journal: AttemptJournal,
    recovery: bool = False,
) -> ValidatedPromotionEvidence:
    """Re-read and cross-link the complete journal-selected promotion evidence.

    This function takes no lock and mints no live authority.  The promotion boundary
    must call it before lock acquisition and again while its landing fences are held.
    """

    from platform_core.runtime.attempt_journal import AttemptPhase

    auth = PromotionAuthorization.from_value(authorization)
    record = journal.load(auth.transaction_id)
    canonical = _absolute(record.canonical_root)
    clone = _absolute(record.clone_path)
    if (
        _is_within(store.root, canonical)
        or _is_within(canonical, store.root)
        or _is_within(store.root, clone)
        or _is_within(clone, store.root)
    ):
        raise ValueError("receipt store must remain outside canonical and candidate roots")
    allowed_phases = {
        AttemptPhase.REF_MOVED,
        AttemptPhase.MATERIALIZED,
        AttemptPhase.PROMOTED,
    } if recovery else {
        AttemptPhase.PROMOTION_PREPARED,
        AttemptPhase.INDEX_FENCED,
    }
    if record.phase not in allowed_phases:
        raise ValueError("attempt journal must be promotion_prepared before authorization")
    if (record.task_id, record.subtask_id) != (auth.task_id, auth.subtask_id):
        raise ValueError("authorization task identity does not match attempt journal")
    if record.spec_digest != auth.spec_digest:
        raise ValueError("authorization spec digest does not match attempt journal")
    if record.policy_digest != auth.policy_digest:
        raise ValueError("authorization policy digest does not match attempt journal")
    journal_links = (
        ("staging", record.staging_receipt_id, auth.staging_receipt_id),
        ("verification", record.verification_receipt_id, auth.verification_receipt_id),
        ("review", record.review_receipt_id, auth.review_receipt_id),
    )
    for label, journal_id, authorization_id in journal_links:
        if not journal_id or journal_id != authorization_id:
            raise ValueError(f"authorization {label} receipt is not journal-bound")
    if (
        record.proposed_revision != auth.proposed_revision
        or record.proposed_tree != auth.proposed_tree
        or record.proposed_diff_digest != auth.proposed_diff_digest
    ):
        raise ValueError("authorization target does not match staged journal target")

    staging = store.read(auth.staging_receipt_id, expected_type=StagingReceipt)
    if staging.transaction_id != auth.transaction_id:
        raise ValueError("staging transaction does not match authorization")
    if (
        staging.proposed_commit != auth.proposed_revision
        or staging.proposed_tree != auth.proposed_tree
        or staging.proposed_diff_digest != auth.proposed_diff_digest
        or staging.policy_manifest_digest != auth.policy_digest
    ):
        raise ValueError("staging receipt target does not match authorization")

    verification = store.read(
        auth.verification_receipt_id,
        expected_type=RevisionVerificationReceipt,
    )
    if verification.transaction_id != auth.transaction_id:
        raise ValueError("verification transaction does not match authorization")
    if verification.staging_receipt_id != auth.staging_receipt_id:
        raise ValueError("verification is not linked to the authorized staging receipt")
    if not verification.passed or verification.verified_revision != auth.proposed_revision:
        raise ValueError("verification does not pass the authorized revision")

    review = store.read(auth.review_receipt_id, expected_type=ReviewReceipt)
    if review.transaction_id != auth.transaction_id:
        raise ValueError("review transaction does not match authorization")
    if review.staging_receipt_id != auth.staging_receipt_id:
        raise ValueError("review is not linked to the authorized staging receipt")
    if review.proposed_revision != auth.proposed_revision or not review.permits_promotion:
        raise ValueError("review does not permit the authorized revision")

    selection: SelectionReceipt | None = None
    if record.tournament_batch_id:
        if not auth.selection_receipt_id:
            raise ValueError("tournament attempt requires a selection receipt")
        if record.selection_receipt_id != auth.selection_receipt_id:
            raise ValueError("selection receipt is not journal-bound")
        selection = store.read(
            auth.selection_receipt_id,
            expected_type=SelectionReceipt,
        )
        if selection.batch_id != record.tournament_batch_id:
            raise ValueError("selection batch does not match attempt journal")
        if selection.selected_transaction_id != auth.transaction_id:
            raise ValueError("selection does not name this transaction as winner")
        try:
            index = selection.candidate_transaction_ids.index(auth.transaction_id)
        except ValueError as exc:
            raise ValueError("selection candidate set omits authorized transaction") from exc
        if (
            selection.candidate_verification_receipt_ids[index]
            != auth.verification_receipt_id
            or selection.candidate_review_receipt_ids[index] != auth.review_receipt_id
        ):
            raise ValueError("selection evidence does not link the authorized candidate")
        for candidate_index, transaction_id in enumerate(
            selection.candidate_transaction_ids
        ):
            try:
                candidate_verification = store.read(
                    selection.candidate_verification_receipt_ids[candidate_index],
                    expected_type=RevisionVerificationReceipt,
                )
                candidate_review = store.read(
                    selection.candidate_review_receipt_ids[candidate_index],
                    expected_type=ReviewReceipt,
                )
                candidate_staging = store.read(
                    candidate_verification.staging_receipt_id,
                    expected_type=StagingReceipt,
                )
            except (
                OSError,
                MissingReceipt,
                ReceiptCorruption,
                ReceiptTypeMismatch,
            ) as exc:
                raise ValueError(
                    f"selection candidate {transaction_id!r} receipt chain is unavailable"
                ) from exc
            if (
                candidate_staging.transaction_id != transaction_id
                or candidate_verification.transaction_id != transaction_id
                or candidate_review.transaction_id != transaction_id
                or candidate_review.staging_receipt_id
                != candidate_verification.staging_receipt_id
                or candidate_staging.proposed_commit
                != candidate_verification.proposed_revision
                or candidate_staging.proposed_commit
                != candidate_review.proposed_revision
            ):
                raise ValueError(
                    f"selection candidate {transaction_id!r} receipt chain is not cross-linked"
                )
            if transaction_id in selection.eligible_transaction_ids and (
                not candidate_verification.passed
                or not candidate_review.permits_promotion
            ):
                raise ValueError(
                    f"selection candidate {transaction_id!r} is not evidenced as eligible"
                )
    elif auth.selection_receipt_id or record.selection_receipt_id:
        raise ValueError("ordinary attempt cannot accept tournament selection evidence")

    return ValidatedPromotionEvidence(
        journal_record=record,
        staging=staging,
        verification=verification,
        review=review,
        selection=selection,
    )


Receipt = (
    FinalizationReceipt
    | ExecutionReceipt
    | StagingReceipt
    | RevisionVerificationReceipt
    | ReviewReceipt
    | SelectionReceipt
    | PromotionReceipt
    | ReconciliationReceipt
    | CleanupReceipt
)
ReceiptType = type[Receipt]
_RECEIPT_TYPES: dict[str, ReceiptType] = {
    receipt_type.receipt_type: receipt_type
    for receipt_type in (
        FinalizationReceipt,
        ExecutionReceipt,
        StagingReceipt,
        RevisionVerificationReceipt,
        ReviewReceipt,
        SelectionReceipt,
        PromotionReceipt,
        ReconciliationReceipt,
        CleanupReceipt,
    )
}
_T = TypeVar("_T", bound=Receipt)


@dataclass(frozen=True)
class StoredReceipt:
    receipt_id: str
    receipt_type: str
    path: Path


def _absolute(path: str | Path) -> Path:
    return Path(os.path.abspath(os.fspath(path)))


def _is_within(path: Path, root: Path) -> bool:
    try:
        common = os.path.commonpath((str(path), str(root)))
        return os.path.normcase(common) == os.path.normcase(str(root))
    except ValueError:
        return False


def _assert_no_reparse_components(path: Path) -> None:
    try:
        assertNoReparsePath(path)
    except OSError as exc:
        raise ReceiptPathViolation(str(exc)) from exc


def _read_no_follow(path: Path, *, max_bytes: int = _MAX_RECEIPT_BYTES) -> bytes:
    try:
        return readNoFollowBytes(path, max_bytes=max_bytes)
    except FileNotFoundError as exc:
        raise MissingReceipt(f"missing receipt node: {path.name}") from exc
    except ValueError as exc:
        raise ReceiptCorruption(str(exc)) from exc
    except OSError as exc:
        raise ReceiptPathViolation(str(exc)) from exc


def _receipt_bytes(receipt: ImmutableReceipt) -> bytes:
    return canonical_json_bytes(receipt.envelope())


def _decode_receipt(raw: bytes) -> Receipt:
    try:
        decoded = raw.decode("utf-8")
        value = json.loads(decoded)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ReceiptCorruption("receipt is not strict UTF-8 JSON") from exc
    if not isinstance(value, dict) or set(value) != {"schema", "receipt_type", "payload"}:
        raise ReceiptCorruption("receipt envelope is not the closed v1 schema")
    if value["schema"] != _SCHEMA:
        raise ReceiptCorruption("receipt schema is unavailable")
    receipt_type = value["receipt_type"]
    cls = _RECEIPT_TYPES.get(receipt_type)
    if cls is None or not isinstance(value["payload"], dict):
        raise ReceiptCorruption("receipt type is unavailable")
    payload = dict(value["payload"])
    if cls is ReviewReceipt and "decision" in payload:
        payload["decision"] = ReviewDecision(payload["decision"])
    for field_ in fields(cls):
        if field_.name in payload and isinstance(payload[field_.name], list):
            payload[field_.name] = tuple(payload[field_.name])
    try:
        receipt = cls(**payload)
    except (TypeError, ValueError) as exc:
        raise ReceiptCorruption("receipt payload violates its closed contract") from exc
    if _receipt_bytes(receipt) != raw:
        raise ReceiptCorruption("receipt JSON is not in canonical byte form")
    return receipt


class ReceiptStore:
    """External, content-addressed, create-only storage for immutable receipts."""

    def __init__(
        self,
        root: str | Path,
        *,
        forbidden_roots: tuple[str | Path, ...] = (),
    ) -> None:
        self.root = _absolute(root)
        for forbidden in forbidden_roots:
            boundary = _absolute(forbidden)
            if _is_within(self.root, boundary) or _is_within(boundary, self.root):
                raise ReceiptPathViolation("receipt store must remain outside forbidden roots")
        _assert_no_reparse_components(self.root)
        self.root.mkdir(parents=True, exist_ok=True)
        _assert_no_reparse_components(self.root)
        (self.root / "nodes").mkdir(exist_ok=True)
        (self.root / "quarantine").mkdir(exist_ok=True)
        _assert_no_reparse_components(self.root / "nodes")
        _assert_no_reparse_components(self.root / "quarantine")

    def path_for(self, receipt_id: str) -> Path:
        _require_digest(receipt_id, "receipt_id")
        return self.root / "nodes" / receipt_id[:2] / f"{receipt_id}.json"

    def _quarantine(self, receipt_id: str, raw: bytes) -> None:
        actual = hashlib.sha256(raw).hexdigest()
        target = self.root / "quarantine" / f"{receipt_id}.{actual}.corrupt"
        try:
            exclusiveCreateBytes(target, raw)
        except FileExistsError:
            existing = _read_no_follow(target)
            if existing != raw:
                raise ReceiptCollision("quarantine content-address collision")

    def put(self, receipt: Receipt) -> StoredReceipt:
        if not isinstance(receipt, tuple(_RECEIPT_TYPES.values())):
            raise TypeError("ReceiptStore accepts only closed transactional receipt types")
        receipt_id = receipt.receipt_id
        payload = _receipt_bytes(receipt)
        path = self.path_for(receipt_id)
        path.parent.mkdir(parents=True, exist_ok=True)
        _assert_no_reparse_components(path.parent)
        try:
            exclusiveCreateBytes(path, payload)
        except FileExistsError:
            existing = _read_no_follow(path)
            if existing != payload:
                self._quarantine(receipt_id, existing)
                raise ReceiptCollision(f"receipt path collision for {receipt_id}")
        persisted = self.read(receipt_id, expected_type=type(receipt))
        if persisted != receipt:
            raise ReceiptCorruption("persisted receipt changed during create/re-read")
        return StoredReceipt(receipt_id, receipt.receipt_type, path)

    def read(self, receipt_id: str, *, expected_type: type[_T]) -> _T:
        path = self.path_for(receipt_id)
        raw = _read_no_follow(path)
        try:
            actual_id = hashlib.sha256(raw).hexdigest()
            if actual_id != receipt_id:
                raise ReceiptCorruption("receipt content address does not match its path")
            receipt = _decode_receipt(raw)
            if type(receipt) is not expected_type:
                raise ReceiptTypeMismatch(
                    f"expected {expected_type.receipt_type}, found {receipt.receipt_type}"
                )
            if receipt.receipt_id != receipt_id:
                raise ReceiptCorruption("decoded receipt id does not match its path")
            return cast(_T, receipt)
        except ReceiptCorruption:
            self._quarantine(receipt_id, raw)
            raise

    def find_cleanup_receipts(
        self,
        *,
        transaction_id: str,
        finalization_receipt_id: str,
        previous_cleanup_receipt_id: str,
        max_receipts: int = 100_000,
    ) -> tuple[CleanupReceipt, ...]:
        """Find an unjournaled cleanup node after a crash at the receipt boundary."""

        _require_identifier(transaction_id, "transaction_id")
        _require_digest(finalization_receipt_id, "finalization_receipt_id")
        _require_digest(
            previous_cleanup_receipt_id,
            "previous_cleanup_receipt_id",
            optional=True,
        )
        if type(max_receipts) is not int or max_receipts < 1:
            raise ValueError("max_receipts must be a positive integer")
        nodes = self.root / "nodes"
        try:
            nodes_handle = openNativeDirectory(nodes)
        except OSError as exc:
            raise ReceiptPathViolation("receipt nodes cannot be enumerated") from exc
        matches: list[CleanupReceipt] = []
        observed = 0
        with nodes_handle:
            nodes_identity = nodes_handle.identity
            try:
                buckets = nodes_handle.listEntries()
            except (OSError, UnicodeError) as exc:
                raise ReceiptPathViolation(
                    "receipt nodes cannot be enumerated"
                ) from exc
            for bucket_entry in buckets:
                if (
                    bucket_entry.identity.is_reparse
                    or not bucket_entry.identity.is_directory
                    or re.fullmatch(r"[0-9a-f]{2}", bucket_entry.name) is None
                ):
                    raise ReceiptCorruption("receipt store has an unknown bucket")
                try:
                    bucket = nodes_handle.openDirectory(
                        bucket_entry.name,
                        expected=bucket_entry.identity,
                    )
                except OSError as exc:
                    raise ReceiptPathViolation(
                        "receipt bucket cannot be opened exactly"
                    ) from exc
                with bucket:
                    bucket_identity = bucket.identity
                    try:
                        paths = bucket.listEntries()
                    except (OSError, UnicodeError) as exc:
                        raise ReceiptPathViolation(
                            "receipt bucket cannot be enumerated"
                        ) from exc
                    for entry in paths:
                        observed += 1
                        if observed > max_receipts:
                            raise ReceiptCorruption(
                                "cleanup receipt discovery exceeds quota"
                            )
                        match = re.fullmatch(r"([0-9a-f]{64})\.json", entry.name)
                        if (
                            match is None
                            or entry.identity.is_reparse
                            or entry.identity.is_directory
                            or entry.identity.link_count != 1
                        ):
                            raise ReceiptCorruption(
                                "receipt bucket has an unknown artifact"
                            )
                        receipt_id = match.group(1)
                        if receipt_id[:2] != bucket_entry.name:
                            raise ReceiptCorruption(
                                "receipt node is stored in the wrong bucket"
                            )
                        try:
                            raw = bucket.readFile(
                                entry.name,
                                max_bytes=_MAX_RECEIPT_BYTES,
                                expected=entry.identity,
                            )
                        except (OSError, ValueError) as exc:
                            raise ReceiptPathViolation(
                                "receipt node raced retained read"
                            ) from exc
                        if hashlib.sha256(raw).hexdigest() != receipt_id:
                            self._quarantine(receipt_id, raw)
                            raise ReceiptCorruption(
                                "receipt content address does not match discovery path"
                            )
                        receipt = _decode_receipt(raw)
                        if not isinstance(receipt, CleanupReceipt):
                            continue
                        if (
                            receipt.transaction_id == transaction_id
                            and receipt.finalization_receipt_id
                            == finalization_receipt_id
                            and receipt.previous_cleanup_receipt_id
                            == previous_cleanup_receipt_id
                        ):
                            matches.append(receipt)
                    if bucket.identity != bucket_identity:
                        raise ReceiptPathViolation(
                            "receipt bucket raced discovery"
                        )
            if nodes_handle.identity != nodes_identity:
                raise ReceiptPathViolation("receipt nodes raced discovery")
        return tuple(sorted(matches, key=lambda receipt: receipt.receipt_id))


class CleanupDisposition(str, Enum):
    REMOVE = "remove"
    RETAIN = "retain"


@dataclass(frozen=True, slots=True, kw_only=True)
class CleanupArtifact:
    """One explicitly owned artifact and its policy-selected terminal state."""

    artifact_id: str
    disposition: CleanupDisposition
    ownership_digest: str
    runtime_token: object = field(repr=False, compare=False)

    def __post_init__(self) -> None:
        _require_identifier(self.artifact_id, "artifact_id")
        if not isinstance(self.disposition, CleanupDisposition):
            raise TypeError("cleanup disposition must be CleanupDisposition")
        _require_digest(self.ownership_digest, "ownership_digest")
        if self.runtime_token is None:
            raise ValueError("cleanup artifact requires a live ownership token")


@dataclass(frozen=True, slots=True, kw_only=True)
class ArtifactCleanupResult:
    artifact_id: str
    ownership_digest: str
    removed: bool
    warning: str = ""

    def __post_init__(self) -> None:
        _require_identifier(self.artifact_id, "artifact_id")
        _require_digest(self.ownership_digest, "ownership_digest")
        if type(self.removed) is not bool:
            raise TypeError("artifact cleanup removed must be bool")
        if self.warning:
            _require_text(self.warning, "artifact cleanup warning")
        if not self.removed and not self.warning:
            raise ValueError("failed artifact cleanup requires a warning")


def _cleanup_warning(artifact_id: str, exc: BaseException) -> str:
    message = " ".join(str(exc).split()) or type(exc).__name__
    value = f"{artifact_id}: {type(exc).__name__}: {message}"
    encoded = value.encode("utf-8")[:2048]
    while True:
        try:
            return encoded.decode("utf-8")
        except UnicodeDecodeError:
            encoded = encoded[:-1]


class CleanupCoordinator:
    """Persist finalization first, then append retryable cleanup observations."""

    def __init__(
        self,
        *,
        receipt_store: ReceiptStore,
        journal: AttemptJournal,
        process_capability: object,
        remove_artifact: Callable[[CleanupArtifact], ArtifactCleanupResult],
        cleanup_lock_root: str | Path | None = None,
        clock: Callable[[], str] | None = None,
    ) -> None:
        from platform_core.runtime.attempt_journal import AttemptJournal

        if not isinstance(receipt_store, ReceiptStore):
            raise TypeError("receipt_store must be ReceiptStore")
        if not isinstance(journal, AttemptJournal):
            raise TypeError("journal must be AttemptJournal")
        if process_capability is None:
            raise ValueError("cleanup requires a process-local capability")
        if not callable(remove_artifact):
            raise TypeError("remove_artifact must be callable")
        root = _absolute(cleanup_lock_root or (receipt_store.root / "cleanup-locks"))
        for forbidden in (journal.root,):
            if _is_within(root, forbidden) or _is_within(forbidden, root):
                raise ReceiptPathViolation("cleanup locks must not overlap the journal")
        try:
            root.mkdir(parents=True, exist_ok=True)
            _assert_no_reparse_components(root)
        except OSError as exc:
            raise ReceiptPathViolation("cleanup lock root is unsafe") from exc
        self.receipt_store = receipt_store
        self.journal = journal
        self.cleanup_lock_root = root
        self._process_capability = process_capability
        self._remove_artifact = remove_artifact
        self._clock = clock or (
            lambda: datetime.now(timezone.utc).isoformat(timespec="microseconds")
        )

    @staticmethod
    def _validate_artifacts(
        artifacts: tuple[CleanupArtifact, ...],
    ) -> dict[str, CleanupArtifact]:
        if not isinstance(artifacts, tuple) or not artifacts:
            raise ValueError("cleanup requires a non-empty immutable artifact set")
        if any(not isinstance(artifact, CleanupArtifact) for artifact in artifacts):
            raise TypeError("cleanup artifacts must use the frozen contract")
        identifiers = tuple(artifact.artifact_id for artifact in artifacts)
        if identifiers != tuple(sorted(identifiers)) or len(identifiers) != len(
            set(identifiers)
        ):
            raise ValueError("cleanup artifacts must be unique and canonically ordered")
        return {artifact.artifact_id: artifact for artifact in artifacts}

    @staticmethod
    def _validate_finalization(
        transaction_id: str,
        finalization: FinalizationReceipt,
        record: AttemptRecord,
    ) -> None:
        from platform_core.runtime.attempt_journal import AttemptPhase

        if not isinstance(finalization, FinalizationReceipt):
            raise TypeError("finalization must be FinalizationReceipt")
        if finalization.promotion_transaction_id not in {"", transaction_id}:
            raise ValueError("finalization belongs to another transaction")
        if (
            finalization.staging_receipt_id
            and finalization.staging_receipt_id != record.staging_receipt_id
        ):
            raise ValueError("finalization staging evidence differs from the journal")
        if record.phase is AttemptPhase.PROMOTED:
            if not finalization.succeeded:
                raise ValueError("promoted attempt requires successful finalization")
            if (
                finalization.promotion_transaction_id != transaction_id
                or finalization.promotion_receipt_id != record.promotion_receipt_id
                or finalization.resulting_revision != record.resulting_revision
            ):
                raise ValueError("finalization promotion truth differs from the journal")
        elif finalization.succeeded:
            raise ValueError("non-promoted attempt cannot have successful finalization")

    @staticmethod
    def _validate_cleanup_receipt(
        receipt: CleanupReceipt,
        *,
        transaction_id: str,
        finalization_receipt_id: str,
        previous_receipt_id: str,
        artifacts: Mapping[str, CleanupArtifact],
    ) -> None:
        if (
            receipt.transaction_id != transaction_id
            or receipt.finalization_receipt_id != finalization_receipt_id
            or receipt.previous_cleanup_receipt_id != previous_receipt_id
        ):
            raise ReceiptCorruption("cleanup receipt chain binding differs")
        removed = set(receipt.removed_artifact_ids)
        retained = set(receipt.retained_artifact_ids)
        failed = set(receipt.failed_artifact_ids)
        if removed | retained | failed != set(artifacts):
            raise ReceiptCorruption("cleanup receipt does not cover every artifact")
        expected_retained = {
            artifact_id
            for artifact_id, artifact in artifacts.items()
            if artifact.disposition is CleanupDisposition.RETAIN
        }
        expected_removed = set(artifacts) - expected_retained
        if retained != expected_retained or removed | failed != expected_removed:
            raise ReceiptCorruption("cleanup receipt violates artifact disposition policy")
        if receipt.complete != (not failed):
            raise ReceiptCorruption("cleanup receipt completion is not evidence-derived")

    def _load_chain(
        self,
        *,
        transaction_id: str,
        finalization_receipt_id: str,
        artifacts: Mapping[str, CleanupArtifact],
    ) -> CleanupReceipt | None:
        record = self.journal.load(transaction_id)
        previous = ""
        latest: CleanupReceipt | None = None
        prior_removed: set[str] = set()
        for index, receipt_id in enumerate(record.cleanup_receipt_ids):
            receipt = self.receipt_store.read(
                receipt_id,
                expected_type=CleanupReceipt,
            )
            self._validate_cleanup_receipt(
                receipt,
                transaction_id=transaction_id,
                finalization_receipt_id=finalization_receipt_id,
                previous_receipt_id=previous,
                artifacts=artifacts,
            )
            removed = set(receipt.removed_artifact_ids)
            if not prior_removed.issubset(removed):
                raise ReceiptCorruption("cleanup receipt moved an artifact backward")
            if record.cleanup_receipt_completions[index] is not receipt.complete:
                raise ReceiptCorruption("journal cleanup completion differs from receipt")
            prior_removed = removed
            previous = receipt_id
            latest = receipt
        return latest

    def cleanup(
        self,
        *,
        transaction_id: str,
        finalization: FinalizationReceipt,
        artifacts: tuple[CleanupArtifact, ...],
        process_capability: object,
        failpoint: Callable[[str], None] | None = None,
    ) -> CleanupReceipt:
        from platform_core.runtime.attempt_journal import AttemptRecord

        _require_identifier(transaction_id, "transaction_id")
        if process_capability is not self._process_capability:
            raise PermissionError("cleanup capability is not live")
        artifact_map = self._validate_artifacts(artifacts)
        lock_name = hashlib.sha256(transaction_id.encode("utf-8")).hexdigest()
        with fileLock(self.cleanup_lock_root / f"{lock_name}.lock", timeout=30):
            record = self.journal.load(transaction_id)
            if not isinstance(record, AttemptRecord):
                raise TypeError("journal returned an invalid attempt record")
            self._validate_finalization(transaction_id, finalization, record)
            stored_finalization = self.receipt_store.put(finalization)
            if self.receipt_store.read(
                stored_finalization.receipt_id,
                expected_type=FinalizationReceipt,
            ) != finalization:
                raise ReceiptCorruption("persisted finalization receipt differs")
            self.journal.append_finalization_receipt(
                transaction_id,
                stored_finalization.receipt_id,
            )
            latest = self._load_chain(
                transaction_id=transaction_id,
                finalization_receipt_id=stored_finalization.receipt_id,
                artifacts=artifact_map,
            )
            if latest is not None and latest.complete:
                return latest
            previous_id = latest.receipt_id if latest is not None else ""
            orphaned = self.receipt_store.find_cleanup_receipts(
                transaction_id=transaction_id,
                finalization_receipt_id=stored_finalization.receipt_id,
                previous_cleanup_receipt_id=previous_id,
            )
            if len(orphaned) > 1:
                raise ReceiptCollision("cleanup receipt chain forked before journaling")
            if orphaned:
                recovered = orphaned[0]
                self._validate_cleanup_receipt(
                    recovered,
                    transaction_id=transaction_id,
                    finalization_receipt_id=stored_finalization.receipt_id,
                    previous_receipt_id=previous_id,
                    artifacts=artifact_map,
                )
                self.journal.append_cleanup_receipt(
                    transaction_id,
                    recovered.receipt_id,
                    finalization_receipt_id=stored_finalization.receipt_id,
                    previous_cleanup_receipt_id=previous_id,
                    complete=recovered.complete,
                )
                return recovered

            retained = {
                artifact_id
                for artifact_id, artifact in artifact_map.items()
                if artifact.disposition is CleanupDisposition.RETAIN
            }
            removed = set(latest.removed_artifact_ids) if latest is not None else set()
            remove_ids = set(artifact_map) - retained
            failed: set[str] = set()
            warnings: list[str] = []
            for artifact_id in sorted(remove_ids - removed):
                artifact = artifact_map[artifact_id]
                try:
                    result = self._remove_artifact(artifact)
                    if not isinstance(result, ArtifactCleanupResult):
                        raise TypeError("cleanup adapter returned an untyped result")
                    if (
                        result.artifact_id != artifact.artifact_id
                        or result.ownership_digest != artifact.ownership_digest
                    ):
                        raise ValueError("cleanup adapter ownership result differs")
                    if result.removed:
                        removed.add(artifact_id)
                    else:
                        failed.add(artifact_id)
                        warnings.append(result.warning)
                except Exception as exc:
                    failed.add(artifact_id)
                    warnings.append(_cleanup_warning(artifact_id, exc))
            observed_at = self._clock()
            _require_iso8601(observed_at, "cleanup clock")
            receipt = CleanupReceipt(
                transaction_id=transaction_id,
                finalization_receipt_id=stored_finalization.receipt_id,
                previous_cleanup_receipt_id=previous_id,
                removed_artifact_ids=tuple(sorted(removed)),
                retained_artifact_ids=tuple(sorted(retained)),
                failed_artifact_ids=tuple(sorted(failed)),
                warnings=tuple(warnings),
                complete=not failed,
                completed_at=observed_at,
            )
            stored = self.receipt_store.put(receipt)
            persisted = self.receipt_store.read(
                stored.receipt_id,
                expected_type=CleanupReceipt,
            )
            if persisted != receipt:
                raise ReceiptCorruption("persisted cleanup receipt differs")
            if failpoint is not None:
                failpoint("after_cleanup_receipt_persisted")
            self.journal.append_cleanup_receipt(
                transaction_id,
                stored.receipt_id,
                finalization_receipt_id=stored_finalization.receipt_id,
                previous_cleanup_receipt_id=previous_id,
                complete=receipt.complete,
            )
            if failpoint is not None:
                failpoint("after_cleanup_receipt_journaled")
            return receipt
