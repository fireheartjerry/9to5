def _require_text(value: str, name: str) -> None:
    if not isinstance(value, str) or not value.strip() or any(ord(ch) < 32 for ch in value):
        raise ValueError(f"{name} must be non-empty text without control characters")


def _require_identifier(value: str, name: str) -> None:
    if not isinstance(value, str) or _IDENTIFIER_RE.fullmatch(value) is None:
        raise ValueError(f"{name} must be a closed portable identifier")


def _require_digest(value: str, name: str, *, optional: bool = False) -> None:
    if optional and value == "":
        return
    if not isinstance(value, str) or _DIGEST_RE.fullmatch(value) is None:
        raise ValueError(f"{name} must be a lowercase SHA-256 digest")


def _require_oid(value: str, name: str, *, optional: bool = False) -> None:
    if optional and value == "":
        return
    if not isinstance(value, str) or _OID_RE.fullmatch(value) is None:
        raise ValueError(f"{name} must be a full lowercase Git object id")


def _require_iso8601(value: str, name: str) -> None:
    _require_text(value, name)
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError(f"{name} must be an ISO-8601 timestamp") from exc
    if parsed.tzinfo is None:
        raise ValueError(f"{name} must include a timezone")


class ImmutableReceipt:
    receipt_type: ClassVar[str]

    def to_dict(self) -> dict[str, Any]:
        return {
            field.name: getattr(self, field.name)
            for field in fields(cast(Any, self))
        }

    def envelope(self) -> dict[str, Any]:
        return {
            "schema": _SCHEMA,
            "receipt_type": self.receipt_type,
            "payload": self.to_dict(),
        }

    @property
    def receipt_id(self) -> str:
        return hashlib.sha256(canonical_json_bytes(self.envelope())).hexdigest()


