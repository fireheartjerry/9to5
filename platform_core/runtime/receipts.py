@dataclass(frozen=True, kw_only=True)
class SelectionReceipt(ImmutableReceipt):
    receipt_type: ClassVar[str] = "selection"
    batch_id: str
    candidate_transaction_ids: tuple[str, ...]
    candidate_verification_receipt_ids: tuple[str, ...]
    candidate_review_receipt_ids: tuple[str, ...]
    eligible_transaction_ids: tuple[str, ...]
    judge_evidence_digest: str
    policy_digest: str
    selected_transaction_id: str
    loser_transaction_ids: tuple[str, ...]

    def __post_init__(self) -> None:
        _require_identifier(self.batch_id, "batch_id")
        candidates = self.candidate_transaction_ids
        if not candidates or len(candidates) != len(set(candidates)):
            raise ValueError("candidate_transaction_ids must be non-empty and unique")
        for transaction_id in candidates:
            _require_identifier(transaction_id, "candidate transaction id")
        if not all(isinstance(value, tuple) for value in (
            candidates,
            self.candidate_verification_receipt_ids,
            self.candidate_review_receipt_ids,
            self.eligible_transaction_ids,
            self.loser_transaction_ids,
        )):
            raise TypeError("selection collections must be immutable tuples")
        if len(self.candidate_verification_receipt_ids) != len(candidates):
            raise ValueError("every candidate needs a verification receipt")
        if len(self.candidate_review_receipt_ids) != len(candidates):
            raise ValueError("every candidate needs a review receipt")
        if len(set(self.candidate_verification_receipt_ids)) != len(candidates):
            raise ValueError("candidate verification receipt IDs must be unique")
        if len(set(self.candidate_review_receipt_ids)) != len(candidates):
            raise ValueError("candidate review receipt IDs must be unique")
        for receipt_id in self.candidate_verification_receipt_ids + self.candidate_review_receipt_ids:
            _require_digest(receipt_id, "candidate receipt id")
        eligible = self.eligible_transaction_ids
        if len(eligible) != len(set(eligible)):
            raise ValueError("eligible_transaction_ids must be unique")
        if not set(eligible).issubset(set(candidates)):
            raise ValueError("eligible_transaction_ids must be a candidate subset")
        if eligible != tuple(item for item in candidates if item in set(eligible)):
            raise ValueError("eligible_transaction_ids must preserve candidate order")
        if self.selected_transaction_id not in self.eligible_transaction_ids:
            raise ValueError("selected transaction must be eligible")
        expected_losers = set(candidates) - {self.selected_transaction_id}
        losers = self.loser_transaction_ids
        if len(losers) != len(set(losers)):
            raise ValueError("loser transaction dispositions must be unique")
        if set(losers) != expected_losers:
            raise ValueError("loser dispositions must cover every non-selected candidate")
        if losers != tuple(item for item in candidates if item in expected_losers):
            raise ValueError("loser dispositions must preserve candidate order")
        _require_digest(self.judge_evidence_digest, "judge_evidence_digest")
        _require_digest(self.policy_digest, "policy_digest")


