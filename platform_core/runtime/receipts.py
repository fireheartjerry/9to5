def _freeze_json(value: Any) -> Any:
    if isinstance(value, Mapping):
        return MappingProxyType(
            {str(key): _freeze_json(item) for key, item in value.items()}
        )
    if isinstance(value, (list, tuple)):
        return tuple(_freeze_json(item) for item in value)
    if value is None or isinstance(value, (str, int, bool)):
        return value
    raise TypeError(f"finalization summary is not canonical JSON: {type(value).__name__}")


def _thaw_json(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {str(key): _thaw_json(item) for key, item in value.items()}
    if isinstance(value, tuple):
        return [_thaw_json(item) for item in value]
    return value


@dataclass(frozen=True, kw_only=True)
class FinalizationReceipt(ImmutableReceipt):
    """Canonical immutable outcome returned by every environment completion."""

    receipt_type: ClassVar[str] = "finalization"
    backend: str = ""
    accepted: bool = False
    requires_canonical_landing: bool = False
    collected: bool = False
    merged: bool = False
    removed: bool = False
    expected_revision: str = ""
    observed_revision: str = ""
    resulting_revision: str = ""
    checkpoint_revision: str = ""
    checkpoint_ref: str = ""
    verification_revision: str = ""
    promotion_transaction_id: str = ""
    execution_receipt_id: str = ""
    staging_receipt_id: str = ""
    verification_receipt_id: str = ""
    review_receipt_id: str = ""
    selection_receipt_id: str = ""
    promotion_receipt_id: str = ""
    materialized: bool = False
    journal_phase: str = ""
    error: str = ""
    cleanup_error: str = ""
    summary: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not isinstance(self.summary, Mapping):
            raise TypeError("finalization summary must be a mapping")
        object.__setattr__(self, "summary", _freeze_json(self.summary))
        for name in (
            "expected_revision",
            "observed_revision",
            "resulting_revision",
            "checkpoint_revision",
            "verification_revision",
        ):
            _require_oid(getattr(self, name), name, optional=True)
        for name in (
            "execution_receipt_id",
            "staging_receipt_id",
            "verification_receipt_id",
            "review_receipt_id",
            "selection_receipt_id",
            "promotion_receipt_id",
        ):
            _require_digest(getattr(self, name), name, optional=True)
        if self.promotion_transaction_id:
            _require_identifier(
                self.promotion_transaction_id,
                "promotion_transaction_id",
            )

    @property
    def succeeded(self) -> bool:
        if not self.accepted or self.error:
            return False
        if not self.requires_canonical_landing:
            return self.collected
        return bool(
            self.collected
            and self.merged
            and self.materialized
            and self.resulting_revision
            and self.verification_revision == self.resulting_revision
            and self.promotion_receipt_id
            and self.journal_phase == "promoted"
        )

    @property
    def outcome(self) -> FinalizationOutcome:
        lowered = self.error.lower()
        if "staged preparation required" in lowered:
            return FinalizationOutcome.STAGED_PREPARATION_REQUIRED
        if "recovery unavailable" in lowered:
            return FinalizationOutcome.RECOVERY_UNAVAILABLE
        if "authorization required" in lowered:
            return FinalizationOutcome.AUTHORIZATION_REQUIRED
        if self.succeeded:
            return FinalizationOutcome.SUCCEEDED
        if not self.accepted:
            return FinalizationOutcome.REJECTED
        return FinalizationOutcome.COMPLETION_FAILED

    def to_dict(self) -> dict[str, Any]:
        return {
            field_.name: _thaw_json(getattr(self, field_.name))
            for field_ in fields(self)
        }

    def toDict(self) -> dict[str, Any]:
        return self.to_dict()


