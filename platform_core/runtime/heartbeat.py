"""One cross-process liveness primitive: heartbeat files under ``state/heartbeats/``.

The run loop atomically re-writes ``state/heartbeats/<task_id>.json`` (~every 10s) and the
gateway bot writes ``gateway-bot.json`` from its presence loop. Every consumer that needs
"is that process alive?" (work_launcher stale detection, orphan resume, poller gating) asks
``isRunAlive`` / ``isBotAlive`` instead of inventing mtime heuristics: a run is alive when
its heartbeat is FRESH **or** its recorded pid is still running. When pid liveness cannot
be determined (psutil missing) a recorded pid is assumed ALIVE -- we never false-abort a
run we cannot prove dead; with no heartbeat and no pid at all, the run is dead.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  heartbeatPath(name: str) -> Path
  writeHeartbeat(name: str, pid: Optional[int]=None, seq: Optional[int]=None) -> None  -- Atomic-replace ``state/heartbeats/<name>.json``
  beat(name: str, *, interval_s: float=HEARTBEAT_INTERVAL_SECONDS) -> bool  -- Throttled ``writeHeartbeat`` for hot loops (the run loop calls this every iteration).
  readHeartbeat(name: str) -> Optional[dict]
  clearHeartbeat(name: str) -> None  -- Best-effort unlink (clean run teardown)
  isRunAlive(task_id: str, *, grace_s: float=RUN_GRACE_SECONDS) -> bool  -- True while the orchestrator process behind ``task_id`` may still be running.
  writeBotHeartbeat() -> None  -- Gateway-bot heartbeat
  isBotAlive(*, grace_s: float=BOT_GRACE_SECONDS) -> bool  -- True while the gateway bot process may still be running (heartbeat fresh or pid alive).
DEPENDS-ON: config, platform_core.core, platform_core.core.clock
SIDE-EFFECTS: writes/removes state/heartbeats/<name>.json
RUN/TEST: python -m pytest tests/control/test_heartbeat.py
"""
from __future__ import annotations

import os
import threading
import time
from pathlib import Path
from typing import Optional

import config
from platform_core.core import fsio
from platform_core.core.clock import nowIsoLocal

LOG = config.getLogger("heartbeat")

HEARTBEAT_INTERVAL_SECONDS: float = 10.0
RUN_GRACE_SECONDS: float = 45.0
# Presence loop ticks every config.PRESENCE_INTERVAL (30s) -> 3 missed ticks = dead.
BOT_GRACE_SECONDS: float = 90.0
BOT_NAME: str = "gateway-bot"

# In-process throttle/seq bookkeeping for ``beat`` (per heartbeat name).
_BEAT_LOCK = threading.Lock()
_LAST_BEAT: dict[str, float] = {}
_SEQ: dict[str, int] = {}


def heartbeatPath(name: str) -> Path:
    return Path(config.HEARTBEAT_DIR) / f"{name}.json"


def writeHeartbeat(name: str, pid: Optional[int] = None, seq: Optional[int] = None) -> None:
    """Atomic-replace ``state/heartbeats/<name>.json``. Never raises -- a liveness stamp
    must not break its caller (a failed write only makes the run LOOK stale, and the
    pid fallback in ``isRunAlive`` still vouches for it)."""
    try:
        with _BEAT_LOCK:
            s = (_SEQ.get(name, 0) + 1) if seq is None else int(seq)
            _SEQ[name] = s
            _LAST_BEAT[name] = time.monotonic()
        fsio.atomicWriteJson(heartbeatPath(name), {
            "name": name,
            "pid": int(pid if pid is not None else os.getpid()),
            "seq": s,
            "ts": time.time(),
            "at": nowIsoLocal(),
        })
    except Exception:  # noqa: BLE001
        LOG.warning("writeHeartbeat(%s) failed (run may look stale)", name, exc_info=True)


def beat(name: str, *, interval_s: float = HEARTBEAT_INTERVAL_SECONDS) -> bool:
    """Throttled ``writeHeartbeat`` for hot loops (the run loop calls this every iteration).
    Writes at most once per ``interval_s``; returns True when a write happened. A falsy
    name (e.g. a test fake without a task_id) is a no-op, never an error."""
    if not name or not isinstance(name, str):
        return False
    with _BEAT_LOCK:
        last = _LAST_BEAT.get(name)
        due = last is None or (time.monotonic() - last) >= interval_s
    if due:
        writeHeartbeat(name)
    return due


def readHeartbeat(name: str) -> Optional[dict]:
    data = fsio.loadJson(heartbeatPath(name), default=None)
    return data if isinstance(data, dict) else None


def clearHeartbeat(name: str) -> None:
    """Best-effort unlink (clean run teardown). Never raises."""
    try:
        heartbeatPath(name).unlink(missing_ok=True)
    except OSError:
        pass


def _pidAlive(pid) -> Optional[bool]:
    """Tri-state pid liveness: True/False when provable, None when unknowable
    (no/garbage pid, or psutil unavailable)."""
    if not isinstance(pid, int) or pid <= 0:
        return None
    try:
        import psutil
        return bool(psutil.pid_exists(pid))
    except Exception:  # noqa: BLE001 -- psutil missing/errored -> unknown
        return None


def _heartbeatFresh(hb: Optional[dict], grace_s: float) -> bool:
    if not hb:
        return False
    try:
        age = time.time() - float(hb.get("ts"))
    except (TypeError, ValueError):
        return False
    return age <= grace_s   # a future ts (clock skew) counts as fresh, never as dead


def _alive(name: str, grace_s: float, fallback_pid: Optional[int] = None) -> bool:
    """Alive = heartbeat fresh OR recorded pid alive. Unknown pid liveness with a pid on
    record -> assume ALIVE (never false-abort the unprovable); no heartbeat + no pid -> dead."""
    hb = readHeartbeat(name)
    if _heartbeatFresh(hb, grace_s):
        return True
    pid = (hb or {}).get("pid") or fallback_pid
    verdict = _pidAlive(pid)
    if verdict is not None:
        return verdict
    return isinstance(pid, int) and pid > 0


def isRunAlive(task_id: str, *, grace_s: float = RUN_GRACE_SECONDS) -> bool:
    """True while the orchestrator process behind ``task_id`` may still be running.
    Falls back to the task JSON's ``meta.run_pid`` for runs that have not written a
    heartbeat yet (e.g. still in the elaboration window)."""
    fallback = None
    data = fsio.loadJson(Path(config.STATE_DIR) / f"{task_id}.json", default=None)
    if isinstance(data, dict):
        fallback = (data.get("meta") or {}).get("run_pid")
    return _alive(task_id, grace_s, fallback_pid=fallback)


def writeBotHeartbeat() -> None:
    """Gateway-bot heartbeat -- called from the bot's presence loop."""
    writeHeartbeat(BOT_NAME)


def isBotAlive(*, grace_s: float = BOT_GRACE_SECONDS) -> bool:
    """True while the gateway bot process may still be running (heartbeat fresh or pid alive)."""
    return _alive(BOT_NAME, grace_s)
