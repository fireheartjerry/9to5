"""One cross-process liveness primitive: heartbeat files under ``state/heartbeats/``.

The run loop atomically re-writes ``state/heartbeats/<task_id>.json`` (~every 10s) and the
gateway bot writes ``gateway-bot.json`` from its presence loop. Every consumer that needs
"is that process alive?" (work_launcher stale detection, orphan resume, poller gating) asks
``isRunAlive`` / ``isBotAlive`` instead of inventing mtime heuristics: a run is alive when
its heartbeat is FRESH **or** its recorded pid is still running. When pid liveness cannot
be determined (psutil missing) a recorded pid is assumed ALIVE -- we never false-abort a
run we cannot prove dead; with no heartbeat and no pid at all, the run is dead.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  HeartbeatStoreUnavailable  -- No exact external heartbeat-state binding is available in capsule mode.
  HeartbeatStoreBinding
  installHeartbeatStore(*, store: ControllerStateStore, authority: ControllerStateAuthority) -> HeartbeatStoreBinding  -- Install an inactive-path diagnostic binding
  heartbeatPath(name: str) -> Path
  writeHeartbeat(name: str, pid: Optional[int]=None, seq: Optional[int]=None) -> None  -- Atomic-replace ``state/heartbeats/<name>.json``
  beat(name: str, *, interval_s: float=HEARTBEAT_INTERVAL_SECONDS) -> bool  -- Throttled ``writeHeartbeat`` for hot loops (the run loop calls this every iteration).
  readHeartbeat(name: str) -> Optional[dict]
  clearHeartbeat(name: str) -> None  -- Best-effort unlink (clean run teardown)
  isRunAlive(task_id: str, *, grace_s: float=RUN_GRACE_SECONDS) -> bool  -- True while the orchestrator process behind ``task_id`` may still be running.
  writeBotHeartbeat() -> None  -- Gateway-bot heartbeat
  isBotAlive(*, grace_s: float=BOT_GRACE_SECONDS) -> bool  -- True while the gateway bot process may still be running (heartbeat fresh or pid alive).
DEPENDS-ON: config, platform_core.app_config.paths, platform_core.core.clock, platform_core.core.fsio, platform_core.execution, platform_core.runtime, state.task_io
SIDE-EFFECTS: writes/removes state/heartbeats/<name>.json
RUN/TEST: python -m pytest tests/control/test_heartbeat.py
"""
from __future__ import annotations

import os
import re
import threading
import time
from contextlib import ExitStack, contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import config
from platform_core.core import fsio
from platform_core.core.clock import nowIsoLocal
from platform_core.execution.pre_execution import mutateLegacyPath
from platform_core.runtime.controller_state import (
    ControllerStateAuthority,
    ControllerStateRefused,
    ControllerStateStore,
    isDiagnosticControllerStateAuthority,
)

LOG = config.getLogger("heartbeat")

HEARTBEAT_INTERVAL_SECONDS: float = 10.0
RUN_GRACE_SECONDS: float = 45.0
# Presence loop ticks every config.PRESENCE_INTERVAL (30s) -> 3 missed ticks = dead.
BOT_GRACE_SECONDS: float = 90.0
BOT_NAME: str = "gateway-bot"
_HEARTBEAT_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$")

# In-process throttle/seq bookkeeping for ``beat`` (per heartbeat name).
_BEAT_LOCK = threading.Lock()
_LAST_BEAT: dict[str, float] = {}
_SEQ: dict[str, int] = {}
_BINDING_LOCK = threading.RLock()


class HeartbeatStoreUnavailable(RuntimeError):
    """No exact external heartbeat-state binding is available in capsule mode."""


@dataclass(frozen=True, slots=True)
class HeartbeatStoreBinding:
    store: ControllerStateStore
    authority: ControllerStateAuthority


_INSTALLED_BINDING: HeartbeatStoreBinding | None = None


def installHeartbeatStore(
    *,
    store: ControllerStateStore,
    authority: ControllerStateAuthority,
) -> HeartbeatStoreBinding:
    """Install an inactive-path diagnostic binding; production resolves centrally."""

    if type(store) is not ControllerStateStore or type(authority) is not ControllerStateAuthority:
        raise HeartbeatStoreUnavailable(
            "exact open diagnostic controller-state store and authority are required"
        )
    from platform_core.app_config.paths import controllerPathsActivationFence
    from platform_core.runtime.controller_state import (
        controllerRuntimeStateAbsentPermit,
    )

    try:
        store._validateInstallableAuthority(authority)
    except ControllerStateRefused as exc:
        raise HeartbeatStoreUnavailable(
            "an open diagnostic controller-state store and authority are required"
        ) from exc
    if not isDiagnosticControllerStateAuthority(authority):
        raise HeartbeatStoreUnavailable(
            "diagnostic controller-state authority is required"
        )

    try:
        with controllerRuntimeStateAbsentPermit():
            with controllerPathsActivationFence() as paths_active:
                if paths_active or _controllerPathsActive():
                    raise HeartbeatStoreUnavailable(
                        "diagnostic heartbeat binding is unavailable after activation"
                    )
                try:
                    store._validateInstallableAuthority(authority)
                except ControllerStateRefused as exc:
                    raise HeartbeatStoreUnavailable(
                        "an open diagnostic controller-state store and authority are required"
                    ) from exc
                binding = HeartbeatStoreBinding(store=store, authority=authority)
                global _INSTALLED_BINDING
                with _BINDING_LOCK:
                    if _INSTALLED_BINDING is not None:
                        if (
                            _INSTALLED_BINDING.store is store
                            and _INSTALLED_BINDING.authority is authority
                        ):
                            installed = _INSTALLED_BINDING
                        else:
                            raise HeartbeatStoreUnavailable(
                                "diagnostic heartbeat binding is already installed"
                            )
                    else:
                        _INSTALLED_BINDING = binding
                        installed = binding
    except HeartbeatStoreUnavailable:
        raise
    except ControllerStateRefused as exc:
        raise HeartbeatStoreUnavailable(
            "controller runtime installation is not exactly absent"
        ) from exc
    return installed


def _controllerPathsActive() -> bool:
    try:
        from platform_core.app_config.paths import controllerPathsActive

        return bool(controllerPathsActive())
    except Exception:
        return True


def _centralBinding() -> HeartbeatStoreBinding:
    from platform_core.runtime import controller_state

    try:
        runtime = controller_state.currentControllerRuntimeStateBinding()
        store = runtime.store
        authority = runtime.authority
        if (
            type(store) is not ControllerStateStore
            or type(authority) is not ControllerStateAuthority
        ):
            raise ControllerStateRefused(
                "central controller runtime binding has invalid exact types"
            )
        store._validateInstallableAuthority(authority)
    except (AttributeError, ControllerStateRefused) as exc:
        raise HeartbeatStoreUnavailable(
            "external heartbeat controller binding is unavailable"
        ) from exc
    return HeartbeatStoreBinding(store=store, authority=authority)


@contextmanager
def _bindingOperation():
    try:
        central = _centralBinding()
    except HeartbeatStoreUnavailable:
        pass
    else:
        yield central
        return

    from platform_core.app_config.paths import controllerPathsActivationFence
    from platform_core.runtime.controller_state import (
        controllerRuntimeStateAbsentPermit,
    )

    diagnostic: HeartbeatStoreBinding | None = None
    active = False
    permit = ExitStack()
    try:
        permit.enter_context(controllerRuntimeStateAbsentPermit())
    except ControllerStateRefused as exc:
        permit.close()
        raise HeartbeatStoreUnavailable(
            "controller runtime installation is not exactly absent"
        ) from exc
    with permit:
        with controllerPathsActivationFence() as paths_active:
            active = paths_active or _controllerPathsActive()
            if not active:
                with _BINDING_LOCK:
                    diagnostic = _INSTALLED_BINDING
                yield diagnostic
                return

    if active:
        yield _centralBinding()
        return
    raise HeartbeatStoreUnavailable(
        "external heartbeat controller binding is unavailable"
    )


def _binding() -> HeartbeatStoreBinding | None:
    with _bindingOperation() as binding:
        return binding


def _logicalHeartbeat(name: str) -> str:
    return f"heartbeats/{_validateHeartbeatName(name)}"


def _validateHeartbeatName(name: str) -> str:
    """Return a safe heartbeat filename stem, or raise for path-like names."""
    if not isinstance(name, str) or not _HEARTBEAT_NAME_RE.fullmatch(name) or ".." in name:
        raise ValueError(f"invalid heartbeat name: {name!r}")
    return name


def heartbeatPath(name: str) -> Path:
    safe_name = _validateHeartbeatName(name)
    return Path(config.HEARTBEAT_DIR) / f"{safe_name}.json"


def writeHeartbeat(name: str, pid: Optional[int] = None, seq: Optional[int] = None) -> None:
    """Atomic-replace ``state/heartbeats/<name>.json``. Never raises -- a liveness stamp
    must not break its caller (a failed write only makes the run LOOK stale, and the
    pid fallback in ``isRunAlive`` still vouches for it)."""
    try:
        safe_name = _validateHeartbeatName(name)
        with _BEAT_LOCK:
            s = (_SEQ.get(safe_name, 0) + 1) if seq is None else int(seq)
            _SEQ[safe_name] = s
            _LAST_BEAT[safe_name] = time.monotonic()
        payload = {
            "name": safe_name,
            "pid": int(pid if pid is not None else os.getpid()),
            "seq": s,
            "ts": time.time(),
            "at": nowIsoLocal(),
        }
        with _bindingOperation() as binding:
            if binding is not None:
                binding.store.writeJson(
                    _logicalHeartbeat(safe_name),
                    payload,
                    authority=binding.authority,
                )
            else:
                fsio.atomicWriteJson(heartbeatPath(safe_name), payload)
    except Exception:  # noqa: BLE001
        LOG.warning("writeHeartbeat(%s) failed (run may look stale)", name, exc_info=True)


def beat(name: str, *, interval_s: float = HEARTBEAT_INTERVAL_SECONDS) -> bool:
    """Throttled ``writeHeartbeat`` for hot loops (the run loop calls this every iteration).
    Writes at most once per ``interval_s``; returns True when a write happened. A falsy
    name (e.g. a test fake without a task_id) is a no-op, never an error."""
    if not name or not isinstance(name, str):
        return False
    with _BEAT_LOCK:
        last = _LAST_BEAT.get(name)
        due = last is None or (time.monotonic() - last) >= interval_s
    if due:
        writeHeartbeat(name)
    return due


def readHeartbeat(name: str) -> Optional[dict]:
    try:
        safe_name = _validateHeartbeatName(name)
        with _bindingOperation() as binding:
            if binding is not None:
                data = binding.store.readJson(
                    _logicalHeartbeat(safe_name), authority=binding.authority
                )
            else:
                data = fsio.loadJson(heartbeatPath(safe_name), default=None)
    except (FileNotFoundError, ControllerStateRefused, HeartbeatStoreUnavailable, ValueError):
        return None
    return data if isinstance(data, dict) else None


def clearHeartbeat(name: str) -> None:
    """Best-effort unlink (clean run teardown). Never raises."""
    try:
        safe_name = _validateHeartbeatName(name)
        with _bindingOperation() as binding:
            if binding is not None:
                binding.store.deleteJson(
                    _logicalHeartbeat(safe_name), authority=binding.authority
                )
            else:
                mutateLegacyPath(heartbeatPath(safe_name).unlink, missing_ok=True)
    except (
        ControllerStateRefused,
        HeartbeatStoreUnavailable,
        OSError,
        ValueError,
    ):
        pass


def _pidAlive(pid) -> Optional[bool]:
    """Tri-state pid liveness: True/False when provable, None when unknowable
    (no/garbage pid, or psutil unavailable)."""
    if not isinstance(pid, int) or pid <= 0:
        return None
    try:
        import psutil
        return bool(psutil.pid_exists(pid))
    except Exception:  # noqa: BLE001 -- psutil missing/errored -> unknown
        return None


def _heartbeatFresh(hb: Optional[dict], grace_s: float) -> bool:
    if not hb:
        return False
    try:
        age = time.time() - float(hb.get("ts"))
    except (TypeError, ValueError):
        return False
    return age <= grace_s   # a future ts (clock skew) counts as fresh, never as dead


def _alive(name: str, grace_s: float, fallback_pid: Optional[int] = None) -> bool:
    """Alive = heartbeat fresh OR recorded pid alive. Unknown pid liveness with a pid on
    record -> assume ALIVE (never false-abort the unprovable); no heartbeat + no pid -> dead."""
    hb = readHeartbeat(name)
    if _heartbeatFresh(hb, grace_s):
        return True
    pid = (hb or {}).get("pid") or fallback_pid
    verdict = _pidAlive(pid)
    if verdict is not None:
        return verdict
    return isinstance(pid, int) and pid > 0


def isRunAlive(task_id: str, *, grace_s: float = RUN_GRACE_SECONDS) -> bool:
    """True while the orchestrator process behind ``task_id`` may still be running.
    Falls back to the task JSON's ``meta.run_pid`` for runs that have not written a
    heartbeat yet (e.g. still in the elaboration window)."""
    try:
        _validateHeartbeatName(task_id)
    except ValueError:
        return False
    fallback = None
    try:
        from state import task_io

        try:
            task_io.validateTaskId(task_id)
        except ValueError:
            # Historical heartbeat names are not always TaskState UUIDs. Keep
            # their legacy diagnostic fallback, but perform the read through
            # task_io's runtime-absence + path-fence operation boundary.
            with task_io._bindingOperation() as binding:
                if binding is None:
                    task_state_path = Path(config.STATE_DIR) / f"{task_id}.json"
                    data = fsio.loadJson(task_state_path, default=None)
                    if isinstance(data, dict):
                        fallback = (data.get("meta") or {}).get("run_pid")
        else:
            task = task_io.loadSafe(task_id)
            if task is not None:
                fallback = task.meta.get("run_pid")
    except Exception:
        fallback = None
    return _alive(task_id, grace_s, fallback_pid=fallback)


def writeBotHeartbeat() -> None:
    """Gateway-bot heartbeat -- called from the bot's presence loop."""
    writeHeartbeat(BOT_NAME)


def isBotAlive(*, grace_s: float = BOT_GRACE_SECONDS) -> bool:
    """True while the gateway bot process may still be running (heartbeat fresh or pid alive)."""
    return _alive(BOT_NAME, grace_s)
