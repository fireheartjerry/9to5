"""Strict memory-safe DIRC-v2 parser and deterministic proposed-index encoder.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  GitIndexRefused
  GitIndexEntry
  GitIndex
DEPENDS-ON: platform_core.runtime.object_manifest
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_git_index.py
"""
from __future__ import annotations

import hashlib
import re
import struct
from dataclasses import dataclass
from typing import Any, Mapping

from platform_core.runtime.object_manifest import ObjectManifest

_HEADER = struct.Struct("!4sII")
_ENTRY_FIXED = struct.Struct("!10I20sH")
_OID_RE = re.compile(r"^[0-9a-f]{40}$")
_SUPPORTED_MODES = frozenset({0o100644, 0o100755})
_MAX_ENTRIES = 1_000_000
_MAX_INDEX_BYTES = 512 * 1024 * 1024


class GitIndexRefused(ValueError):
    pass


@dataclass(frozen=True, kw_only=True)
class GitIndexEntry:
    path: str
    mode: int
    oid: str
    size: int
    flags: int
    stat_words: tuple[int, ...]

    def toDict(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "mode": self.mode,
            "oid": self.oid,
            "size": self.size,
            "flags": self.flags,
            "stat_words": list(self.stat_words),
        }


def _sha1(payload: bytes) -> bytes:
    return hashlib.sha1(payload, usedforsecurity=False).digest()


@dataclass(frozen=True)
class _CacheTreeNode:
    path: str
    entry_count: int
    subtree_count: int
    oid: str


def _validate_cache_tree(
    data: bytes,
    entries: tuple[GitIndexEntry, ...] | list[GitIndexEntry],
    expected_tree_oids: Mapping[str, str] | None,
) -> None:
    offset = 0
    nodes = 0
    observed: dict[str, _CacheTreeNode] = {}

    def read_node(parent: str | None) -> _CacheTreeNode:
        nonlocal offset, nodes
        if offset >= len(data):
            raise GitIndexRefused("TREE extension is missing a declared subtree")
        nul = data.find(b"\0", offset)
        if nul < 0:
            raise GitIndexRefused("TREE extension has a truncated path")
        component_raw = data[offset:nul]
        if (
            b"/" in component_raw
            or b"\\" in component_raw
            or b"\0" in component_raw
            or any(byte < 32 for byte in component_raw)
        ):
            raise GitIndexRefused("TREE extension has an unsafe path")
        try:
            component = component_raw.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise GitIndexRefused("TREE extension path is not strict UTF-8") from exc
        if parent is None:
            if component:
                raise GitIndexRefused("TREE extension root path must be empty")
            path = ""
        else:
            if component in {"", ".", ".."}:
                raise GitIndexRefused("TREE extension child path is not canonical")
            path = f"{parent}/{component}" if parent else component
        space = data.find(b" ", nul + 1)
        newline = data.find(b"\n", space + 1 if space >= 0 else nul + 1)
        if space < 0 or newline < 0:
            raise GitIndexRefused("TREE extension has a truncated count record")
        try:
            entry_count = int(data[nul + 1 : space].decode("ascii"))
            subtree_count = int(data[space + 1 : newline].decode("ascii"))
        except (UnicodeDecodeError, ValueError) as exc:
            raise GitIndexRefused("TREE extension has invalid counts") from exc
        if entry_count < 0 or subtree_count < 0:
            raise GitIndexRefused("TREE extension has invalid counts")
        offset = newline + 1
        if offset + 20 > len(data):
            raise GitIndexRefused("TREE extension has a truncated object id")
        oid = data[offset : offset + 20].hex()
        offset += 20
        if _OID_RE.fullmatch(oid) is None or oid == "0" * 40:
            raise GitIndexRefused("TREE extension has an invalid object id")
        nodes += 1
        if nodes > _MAX_ENTRIES:
            raise GitIndexRefused("TREE extension exceeds node quota")
        if path in observed:
            raise GitIndexRefused("TREE extension contains a duplicate subtree")
        node = _CacheTreeNode(
            path=path,
            entry_count=entry_count,
            subtree_count=subtree_count,
            oid=oid,
        )
        observed[path] = node
        child_names: list[bytes] = []
        for _ in range(subtree_count):
            child_start = offset
            child = read_node(path)
            child_component = child.path.rsplit("/", 1)[-1].encode("utf-8")
            if child_names and child_component <= child_names[-1]:
                raise GitIndexRefused(
                    "TREE extension child paths are duplicate or unsorted"
                )
            child_names.append(child_component)
            if offset <= child_start:
                raise GitIndexRefused("TREE extension parser made no progress")
        return node

    read_node(None)
    if offset != len(data):
        raise GitIndexRefused("TREE extension has trailing undeclared nodes")

    expected_directories: set[str] = {""}
    paths = tuple(entry.path for entry in entries)
    for path in paths:
        parts = path.split("/")
        expected_directories.update(
            "/".join(parts[:index]) for index in range(1, len(parts))
        )
    if set(observed) != expected_directories:
        raise GitIndexRefused("TREE extension hierarchy differs from index entries")
    for path, node in observed.items():
        prefix = f"{path}/" if path else ""
        expected_count = sum(
            1 for entry_path in paths if not path or entry_path.startswith(prefix)
        )
        expected_children = {
            candidate
            for candidate in expected_directories
            if candidate
            and (
                candidate.rpartition("/")[0]
                if "/" in candidate
                else ""
            )
            == path
        }
        if (
            node.entry_count != expected_count
            or node.subtree_count != len(expected_children)
        ):
            raise GitIndexRefused(
                "TREE extension count differs from index hierarchy"
            )
    if expected_tree_oids is not None:
        if not isinstance(expected_tree_oids, Mapping):
            raise TypeError("expected_tree_oids must be a mapping")
        if set(expected_tree_oids) != expected_directories:
            raise GitIndexRefused(
                "TREE expected object map differs from index hierarchy"
            )
        for path, expected_oid in expected_tree_oids.items():
            if not isinstance(expected_oid, str) or _OID_RE.fullmatch(expected_oid) is None:
                raise GitIndexRefused("TREE expected object id is malformed")
            if observed[path].oid != expected_oid:
                raise GitIndexRefused("TREE object OID differs from independent evidence")


@dataclass(frozen=True, kw_only=True)
class GitIndex:
    version: int
    entries: tuple[GitIndexEntry, ...]
    extensions: tuple[str, ...]
    index_digest: str
    tree_extension_digest: str

    @classmethod
    def build(cls, manifest: ObjectManifest) -> bytes:
        body = bytearray(_HEADER.pack(b"DIRC", 2, len(manifest.entries)))
        for item in manifest.entries:
            path = item.path.encode("utf-8")
            flags = min(len(path), 0xFFF)
            stat_words = (
                0,
                0,
                0,
                0,
                0,
                0,
                item.mode,
                0,
                0,
                item.size,
            )
            entry = bytearray(
                _ENTRY_FIXED.pack(
                    *stat_words,
                    bytes.fromhex(item.blob_oid),
                    flags,
                )
            )
            entry.extend(path)
            entry.append(0)
            entry.extend(b"\0" * ((-len(entry)) % 8))
            body.extend(entry)
        body.extend(_sha1(bytes(body)))
        return bytes(body)

    @classmethod
    def parse(
        cls,
        raw: bytes,
        *,
        expected_manifest: ObjectManifest | None = None,
        expected_tree_oids: Mapping[str, str] | None = None,
    ) -> GitIndex:
        if not isinstance(raw, bytes):
            raise TypeError("Git index input must be immutable bytes")
        if len(raw) > _MAX_INDEX_BYTES:
            raise GitIndexRefused("Git index exceeds byte quota")
        if len(raw) < _HEADER.size + 20:
            raise GitIndexRefused("Git index is truncated")
        payload, observed_checksum = raw[:-20], raw[-20:]
        if _sha1(payload) != observed_checksum:
            raise GitIndexRefused("Git index checksum mismatch")
        signature, version, count = _HEADER.unpack_from(payload, 0)
        if signature != b"DIRC" or version != 2:
            raise GitIndexRefused("only canonical DIRC v2 is supported")
        if count > _MAX_ENTRIES:
            raise GitIndexRefused("Git index exceeds entry quota")
        entries: list[GitIndexEntry] = []
        offset = _HEADER.size
        previous_path = b""
        for _ in range(count):
            entry_start = offset
            if offset + _ENTRY_FIXED.size > len(payload):
                raise GitIndexRefused("Git index entry is truncated")
            unpacked = _ENTRY_FIXED.unpack_from(payload, offset)
            stat_words = tuple(int(value) for value in unpacked[:10])
            oid_raw = unpacked[10]
            flags = int(unpacked[11])
            if oid_raw == b"\0" * 20:
                raise GitIndexRefused("Git index intent-to-add entries are unsupported")
            offset += _ENTRY_FIXED.size
            nul = payload.find(b"\0", offset)
            if nul < 0:
                raise GitIndexRefused("Git index path is truncated")
            path_raw = payload[offset:nul]
            if not path_raw:
                raise GitIndexRefused("Git index path is empty")
            try:
                path = path_raw.decode("utf-8")
            except UnicodeDecodeError as exc:
                raise GitIndexRefused("Git index path is not strict UTF-8") from exc
            if b"\\" in path_raw or path_raw.startswith(b"/") or b"\0" in path_raw:
                raise GitIndexRefused("Git index path is unsafe")
            if any(part in {"", ".", ".."} for part in path.split("/")):
                raise GitIndexRefused("Git index path is not canonical")
            name_length = flags & 0x0FFF
            if name_length != min(len(path_raw), 0x0FFF):
                raise GitIndexRefused("Git index path-length flags disagree")
            if flags & 0x8000:
                raise GitIndexRefused("Git index assume-valid entries are unsupported")
            if flags & 0x4000:
                raise GitIndexRefused("Git index extended/skip-worktree entries are unsupported")
            if flags & 0x3000:
                raise GitIndexRefused("Git index unmerged stages are unsupported")
            mode = stat_words[6]
            if mode not in _SUPPORTED_MODES:
                raise GitIndexRefused("Git index contains unsupported entry mode")
            if previous_path and path_raw <= previous_path:
                raise GitIndexRefused("Git index paths are duplicate or unsorted")
            previous_path = path_raw
            entry_length = _ENTRY_FIXED.size + len(path_raw) + 1
            padded_length = entry_length + ((-entry_length) % 8)
            offset = entry_start + padded_length
            if offset > len(payload):
                raise GitIndexRefused("Git index entry padding is truncated")
            padding = payload[nul + 1 : offset]
            if any(padding):
                raise GitIndexRefused("Git index entry padding is nonzero")
            entries.append(
                GitIndexEntry(
                    path=path,
                    mode=mode,
                    oid=oid_raw.hex(),
                    size=stat_words[9],
                    flags=flags,
                    stat_words=stat_words,
                )
            )

        extensions: list[str] = []
        tree_digest = ""
        while offset < len(payload):
            if offset + 8 > len(payload):
                raise GitIndexRefused("Git index extension header is truncated")
            signature_raw = payload[offset : offset + 4]
            size = int.from_bytes(payload[offset + 4 : offset + 8], "big")
            offset += 8
            if offset + size > len(payload):
                raise GitIndexRefused("Git index extension body is truncated")
            data = payload[offset : offset + size]
            offset += size
            try:
                signature_text = signature_raw.decode("ascii")
            except UnicodeDecodeError as exc:
                raise GitIndexRefused("Git index extension signature is invalid") from exc
            if signature_text != "TREE" or signature_text in extensions:
                raise GitIndexRefused(
                    f"unsupported or duplicate Git index extension: {signature_text!r}"
                )
            if expected_manifest is not None and expected_tree_oids is None:
                raise GitIndexRefused(
                    "TREE extension requires independent tree OID evidence"
                )
            _validate_cache_tree(data, entries, expected_tree_oids)
            tree_digest = hashlib.sha256(data).hexdigest()
            extensions.append(signature_text)

        result = cls(
            version=version,
            entries=tuple(entries),
            extensions=tuple(extensions),
            index_digest=hashlib.sha256(raw).hexdigest(),
            tree_extension_digest=tree_digest,
        )
        if expected_manifest is not None:
            expected = [
                (entry.path, entry.mode, entry.blob_oid, entry.size)
                for entry in expected_manifest.entries
            ]
            observed = [
                (entry.path, entry.mode, entry.oid, entry.size)
                for entry in result.entries
            ]
            if observed != expected:
                raise GitIndexRefused("Git index does not match the canonical manifest")
        return result


