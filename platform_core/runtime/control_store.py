"""Transactional SQLite backing store for the run control plane (``state/control.db``).

Replaces the JSON-file-per-task ControlBus mailbox (``state/control/<task_id>.json``)
whose hand-rolled sidecar locking could still interleave two bypassing processes and
whose corrupt-rebuild path could zero the autonomy spend ledger. Every mutation here is
ONE ``BEGIN IMMEDIATE`` transaction on a per-call connection (WAL, busy_timeout=30s), so
the orchestrator run, the gateway bot, and the web dashboard serialize inside SQLite
itself -- Windows-safe, no lock files, no retry ladders.

DB location: ``Path(config.STATE_DIR).parent / "control.db"`` -- i.e. ``state/control.db``,
one level above the task store (``config.STATE_DIR`` is ``state/tasks``). The path is
derived at CALL time (never cached) so tests that monkeypatch ``config.STATE_DIR`` get a
per-test database; ``_DB_OVERRIDE`` pins an explicit path (tests/conftest.py sets it per
test; cross-process test workers set it before first use).

One-shot migration: the first time a control.db is CREATED, any legacy
``state/control/*.json`` mailboxes are imported and renamed to ``*.json.migrated``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  setFlag(task_id: str, key: str, value: Any) -> None
  getFlag(task_id: str, key: str, default: Any=None) -> Any
  setDecision(task_id: str, gate: str, verdict: str) -> None
  getDecision(task_id: str, gate: str) -> Optional[str]
  clearDecision(task_id: str, gate: str) -> None
  pushOp(task_id: str, op: dict, source_msg_id: Optional[str]=None) -> bool  -- Queue one plan op
  drainOps(task_id: str) -> list[dict]  -- Atomically remove and return all queued ops in push order (DELETE ..
  meterSpend(task_id: str, attempt_id: Optional[str], usd: float) -> None  -- Append one committed spend
  spentTotal(task_id: str) -> float
  snapshot(task_id: str) -> dict  -- One-connection read of everything ControlBus.load() surfaces (ops are PEEKED,
  clearTask(task_id: str) -> None  -- Full transactional reset of one task's control state (including its ledger).
  clearRunStart(task_id: str) -> None  -- Reset ONLY the run-execution cursor (queued ops, Discord poll cursor, pending gate)
DEPENDS-ON: config, platform_core.core.clock
SIDE-EFFECTS: creates/writes state/control.db; renames legacy state/control/*.json once
RUN/TEST: python -m pytest tests/test_control_store.py
"""
from __future__ import annotations

import contextlib
import json
import sqlite3
import threading
from pathlib import Path
from typing import Any, Optional

import config
from platform_core.core.clock import nowIsoLocal

LOG = config.getLogger("control")

# Explicit db-path pin (Path | None). Tests set this per test; spawn-based cross-process
# test workers set it before their first store call. None -> derive from config.STATE_DIR.
_DB_OVERRIDE: Optional[Path] = None

_BUSY_TIMEOUT_MS = 30000

_SCHEMA: tuple[str, ...] = (
    """CREATE TABLE IF NOT EXISTS flags(
        task_id     TEXT NOT NULL,
        key         TEXT NOT NULL,
        value       TEXT,
        updated_at  TEXT NOT NULL,
        PRIMARY KEY(task_id, key))""",
    """CREATE TABLE IF NOT EXISTS decisions(
        task_id     TEXT NOT NULL,
        gate        TEXT NOT NULL,
        verdict     TEXT NOT NULL,
        decided_at  TEXT NOT NULL,
        PRIMARY KEY(task_id, gate))""",
    # UNIQUE(task_id, source_msg_id): one Discord message ingested twice (gateway bot AND
    # the degraded REST poller) collapses to ONE op; rows with a NULL source_msg_id (web
    # dashboard, terminal, launcher) are all distinct per SQLite NULL-unique semantics --
    # two real user messages are two ops.
    """CREATE TABLE IF NOT EXISTS ops(
        id            INTEGER PRIMARY KEY AUTOINCREMENT,
        task_id       TEXT NOT NULL,
        op_json       TEXT NOT NULL,
        source_msg_id TEXT,
        created_at    TEXT NOT NULL,
        UNIQUE(task_id, source_msg_id))""",
    # attempt_id UNIQUE makes per-attempt idempotency STRUCTURAL (INSERT OR IGNORE), and
    # spent = SUM(usd) means no code path can ever zero the money ledger by rebuilding.
    """CREATE TABLE IF NOT EXISTS ledger(
        task_id     TEXT NOT NULL,
        attempt_id  TEXT UNIQUE,
        usd         REAL NOT NULL,
        at          TEXT NOT NULL)""",
)

# Per-path schema-init memo so the DDL runs once per process per database.
_SCHEMA_READY: set[str] = set()
_SCHEMA_LOCK = threading.Lock()


def _dbPath() -> Path:
    """state/control.db, derived from config at call time (monkeypatch-friendly)."""
    if _DB_OVERRIDE is not None:
        return Path(_DB_OVERRIDE)
    return Path(config.STATE_DIR).parent / "control.db"


def _connect() -> sqlite3.Connection:
    path = _dbPath()
    path.parent.mkdir(parents=True, exist_ok=True)
    fresh = not path.exists()
    conn = sqlite3.connect(str(path), timeout=_BUSY_TIMEOUT_MS / 1000.0, isolation_level=None)
    conn.execute(f"PRAGMA busy_timeout={_BUSY_TIMEOUT_MS}")
    key = str(path)
    if key not in _SCHEMA_READY:
        with _SCHEMA_LOCK:
            if key not in _SCHEMA_READY:
                conn.execute("PRAGMA journal_mode=WAL")
                for ddl in _SCHEMA:
                    conn.execute(ddl)
                _SCHEMA_READY.add(key)
                if fresh:
                    _migrateLegacyJson(conn)
    return conn


@contextlib.contextmanager
def _tx():
    """One BEGIN IMMEDIATE transaction on a per-call connection (the whole locking story)."""
    conn = _connect()
    try:
        conn.execute("BEGIN IMMEDIATE")
        yield conn
        conn.execute("COMMIT")
    except Exception:
        with contextlib.suppress(sqlite3.Error):
            conn.execute("ROLLBACK")
        raise
    finally:
        conn.close()


@contextlib.contextmanager
def _ro():
    """Read path: WAL readers never block on writers; no explicit transaction needed."""
    conn = _connect()
    try:
        yield conn
    finally:
        conn.close()


# ---- legacy JSON migration (one-shot, on db creation) ----------------------
def _importLegacyTask(conn: sqlite3.Connection, task_id: str, data: dict) -> None:
    now = nowIsoLocal()
    for key in ("abort", "pause", "kill_subprocess", "force_replan",
                "pending_gate", "seen_discord_id"):
        if data.get(key) not in (None, False):
            conn.execute("INSERT OR IGNORE INTO flags VALUES (?,?,?,?)",
                         (task_id, key, json.dumps(data[key]), now))
    for gate, verdict in (data.get("decisions") or {}).items():
        if verdict:
            conn.execute("INSERT OR IGNORE INTO decisions VALUES (?,?,?,?)",
                         (task_id, gate, str(verdict), now))
    for op in (data.get("plan_ops") or []):
        conn.execute("INSERT INTO ops(task_id, op_json, source_msg_id, created_at) "
                     "VALUES (?,?,NULL,?)", (task_id, json.dumps(op, ensure_ascii=False), now))
    # The old schema kept one running float + a list of metered attempt ids. Preserve the
    # TOTAL as a single keyed row (idempotent re-import) and mark the old attempt ids as
    # already-metered 0-usd rows so a post-migration retry can never double-charge them.
    total = float(data.get("autonomy_spent_usd") or 0.0)
    if total > 0:
        conn.execute("INSERT OR IGNORE INTO ledger VALUES (?,?,?,?)",
                     (task_id, f"migrated:{task_id}", total, now))
    for aid in (data.get("autonomy_metered_attempts") or []):
        conn.execute("INSERT OR IGNORE INTO ledger VALUES (?,?,?,?)",
                     (task_id, str(aid), 0.0, now))


def _migrateLegacyJson(conn: sqlite3.Connection) -> None:
    """Import every state/control/*.json into the just-created db, then rename each file to
    ``*.json.migrated`` so it can never re-import. Best-effort per file, never raises."""
    try:
        files = sorted(Path(config.CONTROL_DIR).glob("*.json"))
    except Exception:  # noqa: BLE001 -- config not fully wired (e.g. minimal test harness)
        return
    for f in files:
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
            conn.execute("BEGIN IMMEDIATE")
            if isinstance(data, dict):
                _importLegacyTask(conn, f.stem, data)
            conn.execute("COMMIT")
            f.rename(f.with_name(f.name + ".migrated"))
            LOG.info("control-store: migrated legacy %s into %s", f.name, _dbPath().name)
        except Exception:  # noqa: BLE001 -- a bad legacy file must not block the new store
            with contextlib.suppress(sqlite3.Error):
                conn.execute("ROLLBACK")
            LOG.warning("control-store: could not migrate %s", f.name, exc_info=True)


# ---- flags -----------------------------------------------------------------
def setFlag(task_id: str, key: str, value: Any) -> None:
    with _tx() as conn:
        conn.execute("INSERT OR REPLACE INTO flags VALUES (?,?,?,?)",
                     (task_id, key, json.dumps(value), nowIsoLocal()))


def getFlag(task_id: str, key: str, default: Any = None) -> Any:
    with _ro() as conn:
        row = conn.execute("SELECT value FROM flags WHERE task_id=? AND key=?",
                           (task_id, key)).fetchone()
    if row is None:
        return default
    try:
        return json.loads(row[0])
    except (TypeError, ValueError):
        return default


# ---- decisions (approval gates) ---------------------------------------------
def setDecision(task_id: str, gate: str, verdict: str) -> None:
    with _tx() as conn:
        conn.execute("INSERT OR REPLACE INTO decisions VALUES (?,?,?,?)",
                     (task_id, gate, str(verdict), nowIsoLocal()))


def getDecision(task_id: str, gate: str) -> Optional[str]:
    with _ro() as conn:
        row = conn.execute("SELECT verdict FROM decisions WHERE task_id=? AND gate=?",
                           (task_id, gate)).fetchone()
    return row[0] if row else None


def clearDecision(task_id: str, gate: str) -> None:
    with _tx() as conn:
        conn.execute("DELETE FROM decisions WHERE task_id=? AND gate=?", (task_id, gate))


# ---- queued plan ops ---------------------------------------------------------
def pushOp(task_id: str, op: dict, source_msg_id: Optional[str] = None) -> bool:
    """Queue one plan op. Returns False when ``source_msg_id`` was already ingested for
    this task (the SAME Discord message seen by two ingesters) -- one message, one op."""
    with _tx() as conn:
        cur = conn.execute(
            "INSERT OR IGNORE INTO ops(task_id, op_json, source_msg_id, created_at) "
            "VALUES (?,?,?,?)",
            (task_id, json.dumps(op, ensure_ascii=False),
             str(source_msg_id) if source_msg_id is not None else None, nowIsoLocal()))
        return cur.rowcount > 0


def drainOps(task_id: str) -> list[dict]:
    """Atomically remove and return all queued ops in push order (DELETE ... RETURNING;
    sqlite >= 3.35, which CPython 3.11 bundles). A garbage row is dropped, never fatal."""
    with _tx() as conn:
        rows = conn.execute("DELETE FROM ops WHERE task_id=? RETURNING id, op_json",
                            (task_id,)).fetchall()
    ops: list[dict] = []
    for _id, raw in sorted(rows, key=lambda r: r[0]):
        try:
            op = json.loads(raw)
            if isinstance(op, dict):
                ops.append(op)
        except (TypeError, ValueError):
            LOG.warning("control-store: dropping unparseable op row for %s", task_id)
    return ops


# ---- autonomy spend ledger ----------------------------------------------------
def meterSpend(task_id: str, attempt_id: Optional[str], usd: float) -> None:
    """Append one committed spend. Same ``attempt_id`` twice = one charge (UNIQUE +
    INSERT OR IGNORE); rows are never updated or deleted, so the total is monotonic."""
    usd = max(0.0, float(usd or 0.0))
    if attempt_id is None and usd <= 0.0:
        return   # nothing to record and nothing to mark idempotent
    with _tx() as conn:
        conn.execute("INSERT OR IGNORE INTO ledger VALUES (?,?,?,?)",
                     (task_id, attempt_id, usd, nowIsoLocal()))


def spentTotal(task_id: str) -> float:
    with _ro() as conn:
        row = conn.execute("SELECT COALESCE(SUM(usd), 0) FROM ledger WHERE task_id=?",
                           (task_id,)).fetchone()
    return float(row[0] or 0.0)


# ---- whole-bus reads / lifecycle ----------------------------------------------
def snapshot(task_id: str) -> dict:
    """One-connection read of everything ControlBus.load() surfaces (ops are PEEKED,
    not drained)."""
    with _ro() as conn:
        flags: dict[str, Any] = {}
        for key, raw in conn.execute("SELECT key, value FROM flags WHERE task_id=?", (task_id,)):
            try:
                flags[key] = json.loads(raw)
            except (TypeError, ValueError):
                flags[key] = None
        decisions = dict(conn.execute(
            "SELECT gate, verdict FROM decisions WHERE task_id=?", (task_id,)))
        plan_ops = []
        for (raw,) in conn.execute(
                "SELECT op_json FROM ops WHERE task_id=? ORDER BY id", (task_id,)):
            with contextlib.suppress(TypeError, ValueError):
                op = json.loads(raw)
                if isinstance(op, dict):
                    plan_ops.append(op)
        spent = conn.execute("SELECT COALESCE(SUM(usd), 0) FROM ledger WHERE task_id=?",
                             (task_id,)).fetchone()[0]
    return {"flags": flags, "decisions": decisions, "plan_ops": plan_ops,
            "autonomy_spent_usd": float(spent or 0.0)}


def clearTask(task_id: str) -> None:
    """Full transactional reset of one task's control state (including its ledger)."""
    with _tx() as conn:
        for table in ("flags", "decisions", "ops", "ledger"):
            conn.execute(f"DELETE FROM {table} WHERE task_id=?", (task_id,))


def clearRunStart(task_id: str) -> None:
    """Reset ONLY the run-execution cursor (queued ops, Discord poll cursor, pending gate)
    in one transaction, PRESERVING abort/pause/decisions/ledger the user already issued."""
    with _tx() as conn:
        conn.execute("DELETE FROM ops WHERE task_id=?", (task_id,))
        conn.execute("DELETE FROM flags WHERE task_id=? AND key IN "
                     "('seen_discord_id', 'pending_gate')", (task_id,))
