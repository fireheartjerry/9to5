"""Authority-bound native control-plane store.

The installed controller owns one :class:`ControllerStateStore` rooted outside the
target repository.  Control state is a canonical JSON document per task, updated by
one retained-handle, cross-process transaction.  No SQLite/path-only engine, target
``state/`` directory, environment override, or serialized row can create authority.

``_DB_OVERRIDE`` remains a diagnostic compatibility seam for the existing hermetic
test harness and spawn-concurrency tests.  It selects an isolated retained-handle
store only while explicitly patched; production refuses before consulting any target
path unless the boot capsule has installed an exact store and authority.

Legacy target ``state/control/*.json`` files are inert.  Import is owned exclusively
by :mod:`platform_core.runtime.legacy_state_migration` under its one-use authority.

RUN/TEST: python -m pytest tests/control/test_control_store.py tests/control/test_control_concurrency.py tests/execution/test_external_state_writers.py

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ControlStoreUnavailable  -- No exact external controller-state binding is installed.
  ControlStoreCorrupt  -- A durable control document does not satisfy the closed schema.
  ControlStoreBinding
  installControlStore(*, store: ControllerStateStore, authority: ControllerStateAuthority) -> ControlStoreBinding  -- Install an inactive-path diagnostic binding
  setFlag(task_id: str, key: str, value: Any) -> None
  getFlag(task_id: str, key: str, default: Any=None) -> Any
  setDecision(task_id: str, gate: str, verdict: str) -> None
  getDecision(task_id: str, gate: str) -> Optional[str]
  clearDecision(task_id: str, gate: str) -> None
  pushOp(task_id: str, op: dict, source_msg_id: Optional[str]=None) -> bool  -- Queue one bounded operation with durable source-message idempotency.
  drainOps(task_id: str) -> list[dict]  -- Compatibility drain for pre-Stage-3 callers.
  meterSpend(task_id: str, attempt_id: Optional[str], usd: float) -> None  -- Append one finite non-negative charge
  spentTotal(task_id: str) -> float
  snapshot(task_id: str) -> dict
  clearTask(task_id: str) -> None
  clearRunStart(task_id: str) -> None  -- Reset execution cursors while preserving operator control and spend truth.
DEPENDS-ON: config, platform_core.app_config.paths, platform_core.core.clock, platform_core.execution, platform_core.runtime
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/control/test_control_store.py
"""

from __future__ import annotations

import copy
import hashlib
import json
import math
import secrets
import threading
from contextlib import ExitStack, contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable, Optional, TypeVar

import config
from platform_core.core.clock import nowIsoLocal
from platform_core.execution.pre_execution import (
    mutateLegacyPath,
)
from platform_core.runtime.controller_state import (
    ControllerStateAuthority,
    ControllerStateRefused,
    ControllerStateStore,
    isDiagnosticControllerStateAuthority,
    issueDiagnosticControllerStateAuthority,
)

LOG = config.getLogger("control")


class ControlStoreUnavailable(RuntimeError):
    """No exact external controller-state binding is installed."""


class ControlStoreCorrupt(RuntimeError):
    """A durable control document does not satisfy the closed schema."""


@dataclass(frozen=True, slots=True)
class ControlStoreBinding:
    store: ControllerStateStore
    authority: ControllerStateAuthority


# Historical name retained only because tests/conftest.py and the spawn worker set it.
# It is not read by production when no diagnostic override was explicitly installed.
_DB_OVERRIDE: Optional[Path] = None
_INSTALLED_BINDING: ControlStoreBinding | None = None
_DIAGNOSTIC_BINDINGS: dict[str, ControlStoreBinding] = {}
_BINDING_LOCK = threading.RLock()
_T = TypeVar("_T")

_CONTROL_FLAG_KEYS = frozenset(
    {
        "abort",
        "pause",
        "kill_subprocess",
        "force_replan",
        "pending_gate",
        "seen_discord_id",
    }
)
_BOOL_FLAG_KEYS = frozenset(
    {"abort", "pause", "kill_subprocess", "force_replan"}
)
_PENDING_GATE_VALUES = frozenset(
    {"plan", "pre_pr", "action_risk", "council_risk"}
)
_AUTHORITY_NAME_MARKERS = frozenset(
    {
        "activation",
        "authority",
        "capability",
        "grant",
        "operator",
        "receipt",
        "trust",
        "warrant",
    }
)
_SCHEMA = "galaxy.control-task/v2"


def _isAuthorityShapedName(value: object) -> bool:
    if not isinstance(value, str):
        return True
    normalized = value.strip().casefold()
    return not normalized or any(marker in normalized for marker in _AUTHORITY_NAME_MARKERS)


def _isValidFlagValue(key: str, value: object) -> bool:
    """Validate the closed durable schema for each public control flag."""

    if key in _BOOL_FLAG_KEYS:
        return type(value) is bool
    if key == "pending_gate":
        return value is None or value in _PENDING_GATE_VALUES
    if key == "seen_discord_id":
        return value is None or (
            type(value) is str
            and 0 < len(value) <= 191
            and "\x00" not in value
        )
    return False


def _dbPath() -> Path:
    """Compatibility diagnostic locator; never the production state authority."""

    if _DB_OVERRIDE is not None:
        return Path(_DB_OVERRIDE)
    return Path(config.STATE_DIR).parent / "control.db"


def installControlStore(
    *,
    store: ControllerStateStore,
    authority: ControllerStateAuthority,
) -> ControlStoreBinding:
    """Install an inactive-path diagnostic binding; production resolves centrally."""

    if type(store) is not ControllerStateStore or type(authority) is not ControllerStateAuthority:
        raise ControlStoreUnavailable(
            "exact open diagnostic controller-state store and authority are required"
        )
    from platform_core.app_config.paths import controllerPathsActivationFence
    from platform_core.runtime.controller_state import (
        controllerRuntimeStateAbsentPermit,
    )

    try:
        store._validateInstallableAuthority(authority)
    except ControllerStateRefused as exc:
        raise ControlStoreUnavailable(
            "an open diagnostic controller-state store and authority are required"
        ) from exc
    if not isDiagnosticControllerStateAuthority(authority):
        raise ControlStoreUnavailable(
            "diagnostic controller-state authority is required"
        )

    try:
        with controllerRuntimeStateAbsentPermit():
            with controllerPathsActivationFence() as paths_active:
                if paths_active or _controllerPathsActive():
                    raise ControlStoreUnavailable(
                        "diagnostic control-store binding is unavailable after activation"
                    )
                try:
                    store._validateInstallableAuthority(authority)
                except ControllerStateRefused as exc:
                    raise ControlStoreUnavailable(
                        "an open diagnostic controller-state store and authority are required"
                    ) from exc
                binding = ControlStoreBinding(store=store, authority=authority)
                global _INSTALLED_BINDING
                with _BINDING_LOCK:
                    if _INSTALLED_BINDING is not None:
                        if (
                            _INSTALLED_BINDING.store is store
                            and _INSTALLED_BINDING.authority is authority
                        ):
                            installed = _INSTALLED_BINDING
                        else:
                            raise ControlStoreUnavailable(
                                "diagnostic control-store binding is already installed"
                            )
                    else:
                        _INSTALLED_BINDING = binding
                        installed = binding
    except ControlStoreUnavailable:
        raise
    except ControllerStateRefused as exc:
        raise ControlStoreUnavailable(
            "controller runtime installation is not exactly absent"
        ) from exc
    return installed


def _controllerPathsActive() -> bool:
    try:
        from platform_core.app_config.paths import controllerPathsActive

        return bool(controllerPathsActive())
    except Exception:
        return True


def _centralBinding() -> ControlStoreBinding:
    from platform_core.runtime import controller_state

    try:
        runtime = controller_state.currentControllerRuntimeStateBinding()
        store = runtime.store
        authority = runtime.authority
        if (
            type(store) is not ControllerStateStore
            or type(authority) is not ControllerStateAuthority
        ):
            raise ControllerStateRefused(
                "central controller runtime binding has invalid exact types"
            )
        store._validateInstallableAuthority(authority)
    except (AttributeError, ControllerStateRefused) as exc:
        raise ControlStoreUnavailable(
            "external controller-state binding is unavailable"
        ) from exc
    return ControlStoreBinding(store=store, authority=authority)


def _diagnosticBinding(path: Path) -> ControlStoreBinding:
    """Create the explicit test-only retained-handle backend selected by `_DB_OVERRIDE`."""

    marker = path.resolve(strict=False)
    root = marker.parent / f"{marker.name}.native"
    key = str(root)
    with _BINDING_LOCK:
        existing = _DIAGNOSTIC_BINDINGS.get(key)
        if existing is not None:
            return existing
        # `_DB_OVERRIDE` is an explicit diagnostic path selected by the test
        # harness. Production never reaches this branch and never creates a
        # directory without a capsule-issued authority.
        mutateLegacyPath(root.parent.mkdir,parents=True, exist_ok=True)
        capability = object()
        authority = issueDiagnosticControllerStateAuthority(
            root=root,
            repository_id="repo_control_test",
            controller_generation=1,
            process_capability=capability,
            expires_at="2099-01-01T00:00:00+00:00",
        )
        binding = ControlStoreBinding(
            store=ControllerStateStore(root=root, authority=authority),
            authority=authority,
        )
        _DIAGNOSTIC_BINDINGS[key] = binding
        return binding


@contextmanager
def _bindingOperation():
    try:
        central = _centralBinding()
    except ControlStoreUnavailable:
        pass
    else:
        yield central
        return

    from platform_core.app_config.paths import controllerPathsActivationFence
    from platform_core.runtime.controller_state import (
        controllerRuntimeStateAbsentPermit,
    )

    selected: ControlStoreBinding | None = None
    active = False
    permit = ExitStack()
    try:
        permit.enter_context(controllerRuntimeStateAbsentPermit())
    except ControllerStateRefused as exc:
        permit.close()
        raise ControlStoreUnavailable(
            "controller runtime installation is not exactly absent"
        ) from exc
    with permit:
        with controllerPathsActivationFence() as paths_active:
            active = paths_active or _controllerPathsActive()
            if not active:
                with _BINDING_LOCK:
                    selected = _INSTALLED_BINDING
                    override = _DB_OVERRIDE
                if selected is None and override is not None:
                    selected = _diagnosticBinding(Path(override))
                if selected is None:
                    raise ControlStoreUnavailable(
                        "external controller-state binding is unavailable"
                    )
                yield selected
                return

    if active:
        # Runtime installation owns runtime-lock -> path-lock order. Retry only
        # after releasing both the absent permit and the path fence.
        yield _centralBinding()
        return
    raise ControlStoreUnavailable("external controller-state binding is unavailable")


def _binding() -> ControlStoreBinding:
    with _bindingOperation() as binding:
        return binding


def _logical(task_id: str) -> str:
    if (
        not isinstance(task_id, str)
        or not task_id
        or len(task_id) > 191
        or any(char not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_.:-" for char in task_id)
    ):
        raise ValueError("invalid control task ID")
    return f"control/tasks/{task_id}"


def _blankDocument() -> dict[str, Any]:
    return {
        "decisions": {},
        "flags": {},
        "ingested": {},
        "ledger": [],
        "next_sequence": 0,
        "ops": [],
        "schema": _SCHEMA,
    }


def _document(value: object) -> dict[str, Any]:
    if not isinstance(value, dict) or value.get("schema") != _SCHEMA:
        raise ControlStoreCorrupt("control document schema differs")
    required = {
        "decisions": dict,
        "flags": dict,
        "ingested": dict,
        "ledger": list,
        "next_sequence": int,
        "ops": list,
    }
    for key, expected in required.items():
        item = value.get(key)
        if type(item) is not expected:
            raise ControlStoreCorrupt(f"control document {key} is malformed")
    if value["next_sequence"] < 0:
        raise ControlStoreCorrupt("control document sequence is negative")
    return copy.deepcopy(value)


def _read(task_id: str) -> dict[str, Any]:
    with _bindingOperation() as binding:
        try:
            value = binding.store.readJson(
                _logical(task_id), authority=binding.authority
            )
        except FileNotFoundError:
            return _blankDocument()
        except ControllerStateRefused as exc:
            raise ControlStoreCorrupt(
                "control document cannot be read safely"
            ) from exc
    return _document(value)


def _mutate(task_id: str, operation: Callable[[dict[str, Any]], _T]) -> _T:
    result: list[_T] = []

    def transform(value: object) -> dict[str, Any]:
        document = _document(value)
        result.append(operation(document))
        return document

    with _bindingOperation() as binding:
        binding.store.updateJson(
            _logical(task_id),
            default=_blankDocument(),
            mutate=transform,
            authority=binding.authority,
        )
    return result[0]


def setFlag(task_id: str, key: str, value: Any) -> None:
    if key not in _CONTROL_FLAG_KEYS:
        raise ValueError(f"unknown control flag: {key!r}")
    if not _isValidFlagValue(key, value):
        raise ValueError(f"invalid value for control flag {key!r}")

    def apply(document: dict[str, Any]) -> None:
        document["flags"][key] = value

    _mutate(task_id, apply)


def getFlag(task_id: str, key: str, default: Any = None) -> Any:
    if key not in _CONTROL_FLAG_KEYS:
        return default
    value = _read(task_id)["flags"].get(key, default)
    return copy.deepcopy(value) if _isValidFlagValue(key, value) else default


def setDecision(task_id: str, gate: str, verdict: str) -> None:
    if _isAuthorityShapedName(gate):
        raise ValueError(f"authority-shaped control decision gate is forbidden: {gate!r}")

    def apply(document: dict[str, Any]) -> None:
        document["decisions"][gate] = str(verdict)

    _mutate(task_id, apply)


def getDecision(task_id: str, gate: str) -> Optional[str]:
    if _isAuthorityShapedName(gate):
        return None
    value = _read(task_id)["decisions"].get(gate)
    return value if isinstance(value, str) else None


def clearDecision(task_id: str, gate: str) -> None:
    if _isAuthorityShapedName(gate):
        raise ValueError(f"authority-shaped control decision gate is forbidden: {gate!r}")

    def apply(document: dict[str, Any]) -> None:
        document["decisions"].pop(gate, None)

    _mutate(task_id, apply)


def _canonicalOp(op: dict[str, Any]) -> tuple[dict[str, Any], str]:
    if not isinstance(op, dict):
        raise ValueError("control op must be an object")
    try:
        raw = json.dumps(
            op,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=False,
            allow_nan=False,
        ).encode("utf-8")
    except (TypeError, ValueError, UnicodeEncodeError) as exc:
        raise ValueError("control op is not canonicalizable") from exc
    if len(raw) > 256 * 1024:
        raise ValueError("control op exceeds its quota")
    return copy.deepcopy(op), hashlib.sha256(raw).hexdigest()


def pushOp(task_id: str, op: dict, source_msg_id: Optional[str] = None) -> bool:
    """Queue one bounded operation with durable source-message idempotency."""

    payload, digest = _canonicalOp(op)
    dedup = None if source_msg_id is None else f"{source_msg_id}:{digest[:24]}"

    def apply(document: dict[str, Any]) -> bool:
        if dedup is not None and dedup in document["ingested"]:
            return False
        sequence = document["next_sequence"] + 1
        document["next_sequence"] = sequence
        command_id = hashlib.sha256(
            f"{task_id}\0{sequence}\0{dedup or secrets.token_hex(16)}".encode("utf-8")
        ).hexdigest()
        document["ops"].append(
            {
                "command_id": command_id,
                "created_at": nowIsoLocal(),
                "op": payload,
                "sequence": sequence,
            }
        )
        if dedup is not None:
            document["ingested"][dedup] = command_id
        return True

    return _mutate(task_id, apply)


def drainOps(task_id: str) -> list[dict]:
    """Compatibility drain for pre-Stage-3 callers.

    Stage 3 replaces this diagnostic convenience with leased command transitions;
    the native store already removes atomically and never rebuilds on corruption.
    """

    def apply(document: dict[str, Any]) -> list[dict]:
        rows = list(document["ops"])
        document["ops"] = []
        result: list[dict] = []
        for row in sorted(
            (item for item in rows if isinstance(item, dict)),
            key=lambda item: item.get("sequence", -1),
        ):
            payload = row.get("op")
            if isinstance(payload, dict):
                result.append(copy.deepcopy(payload))
            else:
                LOG.warning("control-store: dropping malformed op evidence for %s", task_id)
        return result

    return _mutate(task_id, apply)


def meterSpend(task_id: str, attempt_id: Optional[str], usd: float) -> None:
    """Append one finite non-negative charge; an attempt ID is idempotent forever."""

    amount = float(usd or 0.0)
    if not math.isfinite(amount):
        raise ValueError("control spend must be finite")
    amount = max(0.0, amount)
    if attempt_id is None and amount <= 0.0:
        return

    def apply(document: dict[str, Any]) -> None:
        if attempt_id is not None and any(
            isinstance(row, dict) and row.get("attempt_id") == attempt_id
            for row in document["ledger"]
        ):
            return
        document["ledger"].append(
            {
                "at": nowIsoLocal(),
                "attempt_id": attempt_id,
                "entry_id": secrets.token_hex(16),
                "usd": amount,
            }
        )

    _mutate(task_id, apply)


def spentTotal(task_id: str) -> float:
    total = 0.0
    for row in _read(task_id)["ledger"]:
        if not isinstance(row, dict):
            raise ControlStoreCorrupt("control ledger row is malformed")
        amount = row.get("usd")
        if isinstance(amount, bool) or not isinstance(amount, (int, float)):
            raise ControlStoreCorrupt("control ledger amount is malformed")
        numeric = float(amount)
        if not math.isfinite(numeric) or numeric < 0:
            raise ControlStoreCorrupt("control ledger amount is unsafe")
        total += numeric
    return total


def snapshot(task_id: str) -> dict:
    document = _read(task_id)
    flags = {
        key: copy.deepcopy(value)
        for key, value in document["flags"].items()
        if key in _CONTROL_FLAG_KEYS and _isValidFlagValue(key, value)
    }
    decisions = {
        gate: str(verdict)
        for gate, verdict in document["decisions"].items()
        if not _isAuthorityShapedName(gate) and isinstance(verdict, str)
    }
    plan_ops = [
        copy.deepcopy(row["op"])
        for row in sorted(
            (item for item in document["ops"] if isinstance(item, dict)),
            key=lambda item: item.get("sequence", -1),
        )
        if isinstance(row.get("op"), dict)
    ]
    return {
        "autonomy_spent_usd": spentTotal(task_id),
        "decisions": decisions,
        "flags": flags,
        "plan_ops": plan_ops,
    }


def clearTask(task_id: str) -> None:
    with _bindingOperation() as binding:
        binding.store.deleteJson(_logical(task_id), authority=binding.authority)


def clearRunStart(task_id: str) -> None:
    """Reset execution cursors while preserving operator control and spend truth."""

    def apply(document: dict[str, Any]) -> None:
        document["ops"] = []
        document["flags"].pop("seen_discord_id", None)
        document["flags"].pop("pending_gate", None)

    _mutate(task_id, apply)


