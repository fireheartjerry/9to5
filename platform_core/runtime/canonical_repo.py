def _native_entries(
    directory: NativeDirectoryHandle,
    *,
    label: str,
) -> tuple[NativeDirectoryEntry, ...]:
    try:
        entries = directory.listEntries()
    except (OSError, UnicodeError) as exc:
        raise CanonicalRepositoryRefused(f"cannot enumerate {label}") from exc
    aliases: dict[str, tuple[str, int]] = {}
    for entry in entries:
        if entry.identity.is_reparse:
            raise CanonicalRepositoryRefused(f"{label} contains a reparse point")
        for alias in (entry.name, entry.short_name):
            if not alias:
                continue
            key = alias.casefold().rstrip(" .")
            identity = (entry.name, entry.identity.file_id)
            prior = aliases.get(key)
            if not key or (prior is not None and prior != identity):
                raise CanonicalRepositoryRefused(
                    f"{label} contains a filesystem alias collision"
                )
            aliases[key] = identity
    return entries


def _native_entry(
    directory: NativeDirectoryHandle,
    name: str,
    *,
    label: str,
    required: bool = True,
) -> NativeDirectoryEntry | None:
    entries = _native_entries(directory, label=label)
    exact = [entry for entry in entries if entry.name == name]
    if len(exact) == 1:
        return exact[0]
    requested = name.casefold().rstrip(" .")
    if any(
        requested
        in {
            entry.name.casefold().rstrip(" ."),
            entry.short_name.casefold().rstrip(" ."),
        }
        for entry in entries
        if entry.short_name
    ):
        raise CanonicalRepositoryRefused(f"{label} resolves through an alias")
    if required:
        raise CanonicalRepositoryRefused(f"{label} is missing")
    return None


@contextmanager
def _native_parent(
    root: NativeDirectoryHandle,
    parts: tuple[str, ...],
    *,
    label: str,
) -> Iterator[tuple[NativeDirectoryHandle, str]]:
    if not parts:
        raise ValueError("native relative path cannot be empty")
    opened: list[NativeDirectoryHandle] = []
    current = root
    try:
        for part in parts[:-1]:
            entry = _native_entry(current, part, label=label)
            if entry is None:
                raise CanonicalRepositoryRefused(f"{label} ancestor is missing")
            if not entry.identity.is_directory:
                raise CanonicalRepositoryRefused(f"{label} ancestor is not a directory")
            try:
                child = current.openDirectory(part, expected=entry.identity)
            except OSError as exc:
                raise CanonicalRepositoryRefused(f"{label} ancestor raced") from exc
            opened.append(child)
            current = child
        yield current, parts[-1]
    finally:
        for child in reversed(opened):
            child.close()


def _read_native(
    directory: NativeDirectoryHandle,
    name: str,
    *,
    limit: int = _METADATA_FILE_LIMIT,
    label: str,
) -> bytes:
    entry = _native_entry(directory, name, label=label)
    if entry is None:
        raise CanonicalRepositoryRefused(f"{label} is missing")
    if entry.identity.is_directory or entry.identity.link_count != 1:
        raise CanonicalRepositoryRefused(f"unsafe {label}")
    try:
        return directory.readFile(name, max_bytes=limit, expected=entry.identity)
    except (OSError, ValueError) as exc:
        raise CanonicalRepositoryRefused(f"unsafe {label}") from exc


def _read_native_text(
    directory: NativeDirectoryHandle,
    name: str,
    *,
    limit: int = _METADATA_FILE_LIMIT,
    encoding: str = "utf-8",
    label: str,
) -> str:
    try:
        return _read_native(directory, name, limit=limit, label=label).decode(encoding)
    except UnicodeDecodeError as exc:
        raise CanonicalRepositoryRefused(f"{label} has invalid {encoding} bytes") from exc


def _identity_evidence(identity: NativeFileIdentity) -> dict[str, int | bool]:
    return {
        "volume_id": identity.volume_id,
        "file_id": identity.file_id,
        "link_count": identity.link_count,
        "size": identity.size,
        "attributes": identity.attributes,
        "mode": identity.mode,
        "write_time": identity.write_time,
        "change_time": identity.change_time,
        "is_directory": identity.is_directory,
        "is_reparse": identity.is_reparse,
        "mount_id": identity.mount_id,
        "reparse_tag": identity.reparse_tag,
    }


def _read_evidence_file(
    directory: NativeDirectoryHandle,
    entry: NativeDirectoryEntry,
    *,
    relative: str,
    label: str,
    limit: int = _OPAQUE_FILE_LIMIT,
) -> tuple[bytes, dict[str, Any]]:
    identity = entry.identity
    if (
        identity.is_directory
        or identity.is_reparse
        or not stat.S_ISREG(identity.mode)
        or identity.link_count != 1
        or identity.size > limit
    ):
        raise CanonicalRepositoryRefused(f"unsafe {label}")
    try:
        raw = directory.readFile(
            entry.name,
            max_bytes=limit,
            expected=identity,
        )
    except (OSError, ValueError) as exc:
        raise CanonicalRepositoryRefused(f"unsafe {label}") from exc
    if len(raw) != identity.size:
        raise CanonicalRepositoryRefused(f"{label} raced its retained identity")
    return raw, {
        "path": relative,
        "kind": "file",
        "identity": _identity_evidence(identity),
        "sha256": hashlib.sha256(raw).hexdigest(),
        "size": len(raw),
    }


def _digest_opaque_tree(
    root: NativeDirectoryHandle,
    *,
    prefix: str,
    label: str,
    max_files: int = _OPAQUE_TREE_FILE_LIMIT,
    max_bytes: int = _OPAQUE_TREE_BYTE_LIMIT,
    max_depth: int = 16,
) -> str:
    records: list[dict[str, Any]] = []
    total = 0
    files = 0
    root_identity = root.identity

    def walk(directory: NativeDirectoryHandle, relative: str, depth: int) -> None:
        nonlocal total, files
        if depth > max_depth:
            raise CanonicalRepositoryRefused(f"{label} exceeds its depth quota")
        before = directory.identity
        children = _native_entries(directory, label=label)
        for child in children:
            child_relative = f"{relative}/{child.name}" if relative else child.name
            if (
                child.identity.volume_id != root_identity.volume_id
                or child.identity.mount_id != root_identity.mount_id
            ):
                raise CanonicalRepositoryRefused(f"{label} crosses a mount boundary")
            if child.identity.is_directory:
                records.append(
                    {
                        "path": f"{prefix}/{child_relative}",
                        "kind": "directory",
                        "identity": _identity_evidence(child.identity),
                    }
                )
                try:
                    with directory.openDirectory(
                        child.name,
                        expected=child.identity,
                    ) as nested:
                        walk(nested, child_relative, depth + 1)
                except CanonicalRepositoryRefused:
                    raise
                except OSError as exc:
                    raise CanonicalRepositoryRefused(f"{label} directory raced") from exc
                continue
            files += 1
            if files > max_files:
                raise CanonicalRepositoryRefused(f"{label} exceeds its file quota")
            raw, record = _read_evidence_file(
                directory,
                child,
                relative=f"{prefix}/{child_relative}",
                label=label,
            )
            total += len(raw)
            if total > max_bytes:
                raise CanonicalRepositoryRefused(f"{label} exceeds its byte quota")
            records.append(record)
        if directory.identity != before or _native_entries(directory, label=label) != children:
            raise CanonicalRepositoryRefused(f"{label} raced attestation")

    walk(root, "", 0)
    if root.identity != root_identity:
        raise CanonicalRepositoryRefused(f"{label} root identity drifted")
    return canonical_digest(records)


def _validate_magic(raw: bytes, magic: bytes, label: str) -> None:
    if len(raw) < 12 or raw[:4] != magic:
        raise CanonicalRepositoryRefused(f"{label} has an invalid accelerator header")


def _validate_info_packs(raw: bytes, paired_pack_ids: set[str]) -> None:
    try:
        lines = raw.decode("ascii").splitlines()
    except UnicodeDecodeError as exc:
        raise CanonicalRepositoryRefused("objects/info/packs is not strict ASCII") from exc
    observed: set[str] = set()
    for line in lines:
        if not line:
            continue
        match = re.fullmatch(r"P pack-([0-9a-f]{40})\.pack", line)
        if match is None or match.group(1) not in paired_pack_ids:
            raise CanonicalRepositoryRefused(
                "objects/info/packs names an unavailable paired pack"
            )
        if match.group(1) in observed:
            raise CanonicalRepositoryRefused("objects/info/packs contains a duplicate pack")
        observed.add(match.group(1))


def _validate_owned_fence(raw: bytes, *, schema: str, label: str) -> None:
    try:
        value = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise CanonicalRepositoryRefused(f"{label} is not an owned fence") from exc
    if (
        not isinstance(value, dict)
        or canonical_json_bytes(value) != raw
        or set(value) != {"schema", "transaction_id", "fence_nonce"}
        or value.get("schema") != schema
        or not isinstance(value.get("transaction_id"), str)
        or _ID_RE.fullmatch(value["transaction_id"]) is None
        or not isinstance(value.get("fence_nonce"), str)
        or re.fullmatch(r"[0-9a-f]{64}", value["fence_nonce"]) is None
    ):
        raise CanonicalRepositoryRefused(f"{label} is not an owned fence")


def _native_exists(
    root: NativeDirectoryHandle,
    parts: tuple[str, ...],
    *,
    label: str,
) -> bool:
    opened: list[NativeDirectoryHandle] = []
    current = root
    try:
        for index, part in enumerate(parts):
            entry = _native_entry(
                current,
                part,
                label=label,
                required=False,
            )
            if entry is None:
                return False
            if index == len(parts) - 1:
                return True
            if not entry.identity.is_directory:
                raise CanonicalRepositoryRefused(f"{label} ancestor is not a directory")
            try:
                child = current.openDirectory(part, expected=entry.identity)
            except OSError as exc:
                raise CanonicalRepositoryRefused(f"{label} ancestor raced") from exc
            opened.append(child)
            current = child
        return False
    finally:
        for child in reversed(opened):
            child.close()


def _attest_native_handle_tree(
    root: NativeDirectoryHandle,
    *,
    label: str,
    max_entries: int,
    max_bytes: int,
) -> None:
    root_identity = root.identity
    entries_seen = 0
    total_bytes = 0

    def walk(directory: NativeDirectoryHandle) -> None:
        nonlocal entries_seen, total_bytes
        before = directory.identity
        children = _native_entries(directory, label=label)
        for child in children:
            entries_seen += 1
            if entries_seen > max_entries:
                raise CanonicalRepositoryRefused(f"{label} exceeds its entry quota")
            identity = child.identity
            if (
                identity.volume_id != root_identity.volume_id
                or identity.mount_id != root_identity.mount_id
            ):
                raise CanonicalRepositoryRefused(f"{label} crosses a mount boundary")
            if identity.is_directory:
                try:
                    with directory.openDirectory(
                        child.name,
                        expected=identity,
                    ) as nested:
                        walk(nested)
                except CanonicalRepositoryRefused:
                    raise
                except OSError as exc:
                    raise CanonicalRepositoryRefused(
                        f"{label} directory raced"
                    ) from exc
                continue
            if not stat.S_ISREG(identity.mode) or identity.link_count != 1:
                raise CanonicalRepositoryRefused(
                    f"{label} contains an unsupported or multi-link file"
                )
            total_bytes += identity.size
            if total_bytes > max_bytes:
                raise CanonicalRepositoryRefused(f"{label} exceeds its byte quota")
        if directory.identity != before or _native_entries(directory, label=label) != children:
            raise CanonicalRepositoryRefused(f"{label} raced attestation")

    walk(root)
    if root.identity != root_identity:
        raise CanonicalRepositoryRefused(f"{label} root identity drifted")


def _digest_object_metadata_handle(git: NativeDirectoryHandle) -> str:
    """Bind derived object metadata while leaving new loose objects admissible."""

    objects_entry = _native_entry(
        git,
        "objects",
        label="canonical object store",
    )
    if objects_entry is None:
        raise CanonicalRepositoryRefused("canonical object store is missing")
    if not objects_entry.identity.is_directory:
        raise CanonicalRepositoryRefused("canonical object store is not a directory")
    records: list[dict[str, Any]] = []
    with git.openDirectory("objects", expected=objects_entry.identity) as objects:
        root_identity = objects.identity
        root_entries = _native_entries(objects, label="canonical object store")
        by_name = {entry.name: entry for entry in root_entries}
        pack_ids: dict[str, set[str]] = {}
        paired_pack_ids: set[str] = set()

        pack_entry = by_name.get("pack")
        if pack_entry is not None:
            if not pack_entry.identity.is_directory:
                raise CanonicalRepositoryRefused("canonical pack store is not a directory")
            with objects.openDirectory("pack", expected=pack_entry.identity) as pack:
                pack_identity = pack.identity
                pack_entries = _native_entries(pack, label="canonical pack store")
                deferred: list[NativeDirectoryEntry] = []
                for entry in sorted(pack_entries, key=lambda item: item.name.encode("utf-8")):
                    match = _PACK_RE.fullmatch(entry.name)
                    if match is not None:
                        identity = entry.identity
                        if (
                            identity.is_directory
                            or identity.is_reparse
                            or not stat.S_ISREG(identity.mode)
                            or identity.link_count != 1
                            or identity.size < 1
                        ):
                            raise CanonicalRepositoryRefused(
                                "canonical pack authority file is unsafe"
                            )
                        pack_ids.setdefault(match.group(1), set()).add(match.group(2))
                        records.append(
                            {
                                "path": f"objects/pack/{entry.name}",
                                "kind": "object-authority-file",
                                "identity": _identity_evidence(identity),
                            }
                        )
                        continue
                    deferred.append(entry)
                if any(members != {"pack", "idx"} for members in pack_ids.values()):
                    raise CanonicalRepositoryRefused(
                        "canonical pack and index authority files must be paired"
                    )
                paired_pack_ids = set(pack_ids)
                for entry in deferred:
                    sidecar = _PACK_SIDECAR_RE.fullmatch(entry.name)
                    if sidecar is not None:
                        if sidecar.group(1) not in paired_pack_ids:
                            raise CanonicalRepositoryRefused(
                                "derived object sidecar lacks its paired pack and index"
                            )
                        raw, record = _read_evidence_file(
                            pack,
                            entry,
                            relative=f"objects/pack/{entry.name}",
                            label="derived object sidecar",
                        )
                        magic = {
                            "bitmap": b"BITM",
                            "rev": b"RIDX",
                            "mtimes": b"MTME",
                        }[sidecar.group(2)]
                        _validate_magic(raw, magic, "derived object sidecar")
                        records.append(record)
                        continue
                    if entry.name == "multi-pack-index":
                        raw, record = _read_evidence_file(
                            pack,
                            entry,
                            relative="objects/pack/multi-pack-index",
                            label="multi-pack index",
                        )
                        _validate_magic(raw, b"MIDX", "multi-pack index")
                        records.append(record)
                        continue
                    raise CanonicalRepositoryRefused(
                        "canonical pack store contains unknown authority metadata"
                    )
                if (
                    pack.identity != pack_identity
                    or _native_entries(pack, label="canonical pack store") != pack_entries
                ):
                    raise CanonicalRepositoryRefused(
                        "canonical pack store raced attestation"
                    )

        for entry in sorted(root_entries, key=lambda item: item.name.encode("utf-8")):
            if (
                entry.identity.volume_id != root_identity.volume_id
                or entry.identity.mount_id != root_identity.mount_id
            ):
                raise CanonicalRepositoryRefused(
                    "canonical object store crosses a mount boundary"
                )
            if re.fullmatch(r"[0-9a-f]{2}", entry.name):
                if not entry.identity.is_directory:
                    raise CanonicalRepositoryRefused(
                        "loose-object fanout is not a directory"
                    )
                with objects.openDirectory(entry.name, expected=entry.identity) as fanout:
                    fanout_identity = fanout.identity
                    leaves = _native_entries(fanout, label="loose-object fanout")
                    for leaf in sorted(leaves, key=lambda item: item.name.encode("utf-8")):
                        if re.fullmatch(r"[0-9a-f]{38}", leaf.name):
                            identity = leaf.identity
                            if (
                                identity.is_directory
                                or identity.is_reparse
                                or not stat.S_ISREG(identity.mode)
                                or identity.link_count != 1
                                or identity.size < 1
                            ):
                                raise CanonicalRepositoryRefused(
                                    "canonical loose-object authority file is unsafe"
                                )
                            continue
                        if re.fullmatch(r"tmp_obj_[A-Za-z0-9._-]+", leaf.name):
                            raw, record = _read_evidence_file(
                                fanout,
                                leaf,
                                relative=f"objects/{entry.name}/{leaf.name}",
                                label="unreachable temporary object",
                            )
                            del raw
                            records.append(record)
                            continue
                        raise CanonicalRepositoryRefused(
                            "canonical loose-object fanout contains unknown data"
                        )
                    if (
                        fanout.identity != fanout_identity
                        or _native_entries(fanout, label="loose-object fanout") != leaves
                    ):
                        raise CanonicalRepositoryRefused(
                            "loose-object fanout raced attestation"
                        )
                continue
            if entry.name in {"pack", "info"}:
                if not entry.identity.is_directory:
                    raise CanonicalRepositoryRefused(
                        "canonical object metadata root is not a directory"
                    )
                continue
            raise CanonicalRepositoryRefused(
                "canonical object store contains unknown top-level data"
            )

        info_entry = by_name.get("info")
        if info_entry is not None:
            with objects.openDirectory("info", expected=info_entry.identity) as info:
                info_identity = info.identity
                info_entries = _native_entries(info, label="canonical object info store")
                for entry in sorted(info_entries, key=lambda item: item.name.encode("utf-8")):
                    if entry.name == "commit-graphs":
                        if not entry.identity.is_directory:
                            raise CanonicalRepositoryRefused(
                                "commit-graph chain root is not a directory"
                            )
                        with info.openDirectory(
                            entry.name,
                            expected=entry.identity,
                        ) as graphs:
                            graph_identity = graphs.identity
                            graph_entries = _native_entries(
                                graphs,
                                label="commit-graph chain",
                            )
                            graph_ids: set[str] = set()
                            chain_ids: list[str] | None = None
                            for graph_entry in sorted(
                                graph_entries,
                                key=lambda item: item.name.encode("utf-8"),
                            ):
                                if graph_entry.name == "commit-graph-chain":
                                    raw, record = _read_evidence_file(
                                        graphs,
                                        graph_entry,
                                        relative="objects/info/commit-graphs/commit-graph-chain",
                                        label="commit-graph chain",
                                    )
                                    try:
                                        chain_ids = raw.decode("ascii").splitlines()
                                    except UnicodeDecodeError as exc:
                                        raise CanonicalRepositoryRefused(
                                            "commit-graph chain is not strict ASCII"
                                        ) from exc
                                    if (
                                        not chain_ids
                                        or len(set(chain_ids)) != len(chain_ids)
                                        or any(_OID_RE.fullmatch(item) is None for item in chain_ids)
                                    ):
                                        raise CanonicalRepositoryRefused(
                                            "commit-graph chain is malformed"
                                        )
                                    records.append(record)
                                    continue
                                match = _GRAPH_RE.fullmatch(graph_entry.name)
                                if match is None:
                                    raise CanonicalRepositoryRefused(
                                        "commit-graph chain contains unknown metadata"
                                    )
                                raw, record = _read_evidence_file(
                                    graphs,
                                    graph_entry,
                                    relative=f"objects/info/commit-graphs/{graph_entry.name}",
                                    label="commit-graph accelerator",
                                )
                                _validate_magic(raw, b"CGPH", "commit-graph accelerator")
                                graph_ids.add(match.group(1))
                                records.append(record)
                            if chain_ids is None or set(chain_ids) != graph_ids:
                                raise CanonicalRepositoryRefused(
                                    "commit-graph chain and graph files disagree"
                                )
                            if (
                                graphs.identity != graph_identity
                                or _native_entries(
                                    graphs,
                                    label="commit-graph chain",
                                )
                                != graph_entries
                            ):
                                raise CanonicalRepositoryRefused(
                                    "commit-graph chain raced attestation"
                                )
                        continue
                    if entry.identity.is_directory:
                        raise CanonicalRepositoryRefused(
                            "canonical object info store contains an unknown directory"
                        )
                    raw, record = _read_evidence_file(
                        info,
                        entry,
                        relative=f"objects/info/{entry.name}",
                        label="derived object accelerator",
                    )
                    if entry.name == "packs":
                        _validate_info_packs(raw, paired_pack_ids)
                    elif entry.name == "commit-graph":
                        _validate_magic(raw, b"CGPH", "commit-graph accelerator")
                    elif entry.name == "multi-pack-index":
                        _validate_magic(raw, b"MIDX", "multi-pack index")
                    else:
                        raise CanonicalRepositoryRefused(
                            "canonical object info store contains unknown metadata"
                        )
                    records.append(record)
                if (
                    info.identity != info_identity
                    or _native_entries(info, label="canonical object info store")
                    != info_entries
                ):
                    raise CanonicalRepositoryRefused(
                        "canonical object info store raced attestation"
                    )
        if (
            objects.identity != root_identity
            or _native_entries(objects, label="canonical object store") != root_entries
        ):
            raise CanonicalRepositoryRefused(
                "canonical object store raced metadata attestation"
            )
    return canonical_digest(sorted(records, key=lambda record: str(record["path"])))


def _digest_inert_metadata_handle(
    git: NativeDirectoryHandle,
    git_entries: tuple[NativeDirectoryEntry, ...],
) -> str:
    records: list[dict[str, Any]] = []
    for entry in sorted(git_entries, key=lambda item: item.name.encode("utf-8")):
        name = entry.name
        if entry.identity.is_directory:
            if name in _STANDARD_GIT_DIRECTORIES:
                if name in {"logs", "branches"}:
                    with git.openDirectory(name, expected=entry.identity) as subtree:
                        _attest_native_handle_tree(
                            subtree,
                            label=f"canonical {name} store",
                            max_entries=200_000,
                            max_bytes=1 << 34,
                        )
                continue
            if name == "cursor":
                with git.openDirectory(name, expected=entry.identity) as cursor:
                    records.append(
                        {
                            "path": "cursor",
                            "kind": "opaque-tree",
                            "digest": _digest_opaque_tree(
                                cursor,
                                prefix="cursor",
                                label="cursor metadata",
                            ),
                        }
                    )
                continue
            if name == "gk":
                with git.openDirectory(name, expected=entry.identity) as gk:
                    children = _native_entries(gk, label="gk metadata")
                    if len(children) != 1 or children[0].name != "config":
                        raise CanonicalRepositoryRefused(
                            "gk metadata contains an unknown surface"
                        )
                    raw, record = _read_evidence_file(
                        gk,
                        children[0],
                        relative="gk/config",
                        label="gk config",
                    )
                    del raw
                    records.append(record)
                continue
            if name == "9to5-tombstones":
                with git.openDirectory(name, expected=entry.identity) as tombstones:
                    _attest_native_handle_tree(
                        tombstones,
                        label="journal-owned materialization tombstones",
                        max_entries=200_000,
                        max_bytes=1 << 40,
                    )
                continue
            raise CanonicalRepositoryRefused(
                f"canonical Git metadata contains an unknown directory surface: {name}"
            )

        if name in _STANDARD_GIT_FILES:
            if name in {"COMMIT_EDITMSG", "FETCH_HEAD", "ORIG_HEAD", "description"}:
                raw, record = _read_evidence_file(
                    git,
                    entry,
                    relative=name,
                    label=f"inert Git metadata {name}",
                )
                del raw
                records.append(record)
            continue
        if name == "sg-reviewed-shas" or re.fullmatch(
            r"sg-hook-once-[A-Za-z0-9._-]+",
            name,
        ):
            raw, record = _read_evidence_file(
                git,
                entry,
                relative=name,
                label="opaque review metadata",
            )
            del raw
            records.append(record)
            continue
        if name == "index.lock":
            raw, _ = _read_evidence_file(
                git,
                entry,
                relative=name,
                label="canonical index lock",
                limit=64 * 1024,
            )
            _validate_owned_fence(
                raw,
                schema="galaxy.index-fence/v1",
                label="canonical index lock",
            )
            continue
        if name == "ORIG_HEAD.lock":
            raw, _ = _read_evidence_file(
                git,
                entry,
                relative=name,
                label="canonical ORIG_HEAD lock",
                limit=64 * 1024,
            )
            _validate_owned_fence(
                raw,
                schema="galaxy.orig-head-fence/v1",
                label="canonical ORIG_HEAD lock",
            )
            continue
        if _INDEX_SIBLING_RE.fullmatch(name):
            _read_evidence_file(
                git,
                entry,
                relative=name,
                label="journal-owned canonical index sibling",
                limit=512 * 1024 * 1024,
            )
            continue
        if re.fullmatch(r"sharedindex\.[0-9a-f]{40}", name):
            raise CanonicalRepositoryRefused(
                "canonical index uses unsupported split-index metadata"
            )
        raise CanonicalRepositoryRefused(
            f"canonical Git metadata contains an unknown file surface: {name}"
        )

    info_entry = next((entry for entry in git_entries if entry.name == "info"), None)
    if info_entry is not None:
        with git.openDirectory("info", expected=info_entry.identity) as info:
            info_entries = _native_entries(info, label="canonical info store")
            for entry in sorted(info_entries, key=lambda item: item.name.encode("utf-8")):
                if entry.name == "attributes":
                    continue
                if entry.name not in {"exclude", "refs"}:
                    raise CanonicalRepositoryRefused(
                        "canonical info store contains unknown metadata"
                    )
                raw, record = _read_evidence_file(
                    info,
                    entry,
                    relative=f"info/{entry.name}",
                    label=f"inert info/{entry.name}",
                )
                del raw
                records.append(record)
    return canonical_digest(sorted(records, key=lambda record: str(record["path"])))


def _digest_inert_registry_handle(
    git: NativeDirectoryHandle,
    *,
    target_ref: str,
) -> str:
    entry = _native_entry(
        git,
        "worktrees",
        label="linked-worktree registry",
        required=False,
    )
    if entry is None:
        return canonical_digest([])
    if not entry.identity.is_directory:
        raise CanonicalRepositoryRefused("linked-worktree registry is not a directory")
    records: list[dict[str, Any]] = []
    total = 0
    file_count = 0
    allowed_files = {
        "COMMIT_EDITMSG",
        "HEAD",
        "ORIG_HEAD",
        "commondir",
        "gitdir",
        "index",
        "locked",
    }
    required_files = {"HEAD", "commondir", "gitdir", "index"}
    with git.openDirectory("worktrees", expected=entry.identity) as registry:
        root_identity = registry.identity
        registrations = _native_entries(registry, label="linked-worktree registry")
        for registration_entry in sorted(
            registrations,
            key=lambda item: item.name.encode("utf-8"),
        ):
            if not registration_entry.identity.is_directory:
                raise CanonicalRepositoryRefused(
                    "linked-worktree registry contains non-directory metadata"
                )
            registration_name = registration_entry.name
            records.append(
                {
                    "path": registration_name,
                    "kind": "directory",
                    "identity": _identity_evidence(registration_entry.identity),
                }
            )
            with registry.openDirectory(
                registration_name,
                expected=registration_entry.identity,
            ) as registration:
                registration_identity = registration.identity
                children = _native_entries(
                    registration,
                    label="linked-worktree registration",
                )
                names = {child.name for child in children}
                if not required_files.issubset(names):
                    raise CanonicalRepositoryRefused(
                        "linked-worktree registry metadata is incomplete"
                    )
                for child in sorted(children, key=lambda item: item.name.encode("utf-8")):
                    relative = f"{registration_name}/{child.name}"
                    if child.identity.is_directory:
                        if child.name not in {"logs", "refs"}:
                            raise CanonicalRepositoryRefused(
                                "linked-worktree registry metadata has an unknown directory"
                            )
                        records.append(
                            {
                                "path": relative,
                                "kind": "directory",
                                "identity": _identity_evidence(child.identity),
                            }
                        )
                        with registration.openDirectory(
                            child.name,
                            expected=child.identity,
                        ) as nested:
                            nested_identity = nested.identity
                            nested_children = _native_entries(
                                nested,
                                label="linked-worktree registry metadata",
                            )
                            if child.name == "refs" and nested_children:
                                raise CanonicalRepositoryRefused(
                                    "linked-worktree registry metadata has nonempty refs"
                                )
                            if child.name == "logs" and any(
                                item.identity.is_directory or item.name != "HEAD"
                                for item in nested_children
                            ):
                                raise CanonicalRepositoryRefused(
                                    "linked-worktree registry metadata has unknown logs"
                                )
                            for nested_child in nested_children:
                                file_count += 1
                                if file_count > _REGISTRY_FILE_LIMIT:
                                    raise CanonicalRepositoryRefused(
                                        "linked-worktree registry exceeds quota"
                                    )
                                raw, record = _read_evidence_file(
                                    nested,
                                    nested_child,
                                    relative=f"{relative}/{nested_child.name}",
                                    label="linked-worktree registry metadata",
                                )
                                total += len(raw)
                                if total > _REGISTRY_BYTE_LIMIT:
                                    raise CanonicalRepositoryRefused(
                                        "linked-worktree registry exceeds quota"
                                    )
                                records.append(record)
                            if (
                                nested.identity != nested_identity
                                or _native_entries(
                                    nested,
                                    label="linked-worktree registry metadata",
                                )
                                != nested_children
                            ):
                                raise CanonicalRepositoryRefused(
                                    "linked-worktree registry metadata raced"
                                )
                        continue
                    if child.name not in allowed_files:
                        raise CanonicalRepositoryRefused(
                            "linked-worktree registry metadata has an unknown file"
                        )
                    file_count += 1
                    if file_count > _REGISTRY_FILE_LIMIT:
                        raise CanonicalRepositoryRefused(
                            "linked-worktree registry exceeds quota"
                        )
                    raw, record = _read_evidence_file(
                        registration,
                        child,
                        relative=relative,
                        label="linked-worktree registry metadata",
                    )
                    total += len(raw)
                    if total > _REGISTRY_BYTE_LIMIT:
                        raise CanonicalRepositoryRefused(
                            "linked-worktree registry exceeds quota"
                        )
                    if child.name == "HEAD":
                        try:
                            text = raw.decode("ascii", errors="strict").strip()
                        except UnicodeDecodeError as exc:
                            raise CanonicalRepositoryRefused(
                                "linked-worktree HEAD is not ASCII"
                            ) from exc
                        if text.startswith("ref: "):
                            ref = text[5:]
                            if (
                                _REF_RE.fullmatch(ref) is None
                                or ".." in ref
                                or "//" in ref
                            ):
                                raise CanonicalRepositoryRefused(
                                    "linked-worktree HEAD is malformed"
                                )
                            if ref == target_ref:
                                raise CanonicalRepositoryRefused(
                                    "another worktree names the canonical target branch"
                                )
                        elif _OID_RE.fullmatch(text) is None:
                            raise CanonicalRepositoryRefused(
                                "linked-worktree HEAD is malformed"
                            )
                    elif child.name == "ORIG_HEAD":
                        try:
                            original = raw.decode("ascii", errors="strict").strip()
                        except UnicodeDecodeError as exc:
                            raise CanonicalRepositoryRefused(
                                "linked-worktree ORIG_HEAD is malformed"
                            ) from exc
                        if _OID_RE.fullmatch(original) is None:
                            raise CanonicalRepositoryRefused(
                                "linked-worktree ORIG_HEAD is malformed"
                            )
                    elif child.name in {"gitdir", "commondir"} and (
                        not raw.strip() or b"\0" in raw
                    ):
                        raise CanonicalRepositoryRefused(
                            "linked-worktree path metadata is malformed"
                        )
                    records.append(record)
                if (
                    registration.identity != registration_identity
                    or _native_entries(
                        registration,
                        label="linked-worktree registration",
                    )
                    != children
                ):
                    raise CanonicalRepositoryRefused(
                        "linked-worktree registry metadata raced"
                    )
        if _native_entries(registry, label="linked-worktree registry") != registrations:
            raise CanonicalRepositoryRefused(
                "linked-worktree registry raced attestation"
            )
        if registry.identity != root_identity:
            raise CanonicalRepositoryRefused(
                "linked-worktree registry root identity drifted"
            )
    return canonical_digest(sorted(records, key=lambda record: str(record["path"])))


def _parse_config(raw: bytes, *, git_common: Path) -> dict[str, str]:
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise CanonicalRepositoryRefused("Git config is not strict UTF-8") from exc
    section = ""
    values: dict[str, str] = {}
    for number, original in enumerate(text.splitlines(), 1):
        line = original.strip()
        if not line or line.startswith(("#", ";")):
            continue
        if line.endswith("\\"):
            raise CanonicalRepositoryRefused("Git config continuations are unsupported")
        if line.startswith("[") and line.endswith("]"):
            section = line[1:-1].strip().lower()
            if not section:
                raise CanonicalRepositoryRefused("Git config has an empty section")
            if section == "include" or section.startswith("includeif "):
                raise CanonicalRepositoryRefused("Git config include directives are forbidden")
            if section == "alias" or section.startswith(
                (
                    "filter ",
                    "diff ",
                    "merge ",
                    "url ",
                    "credential ",
                    "gpg ",
                    "protocol ",
                )
            ) or section in {"credential", "gpg", "protocol"}:
                raise CanonicalRepositoryRefused("Git config executable helper section is forbidden")
            continue
        if not section or "=" not in line:
            raise CanonicalRepositoryRefused(f"unsupported Git config syntax at line {number}")
        key, value = (part.strip() for part in line.split("=", 1))
        full_key = f"{section}.{key.lower()}"
        inert_multivar = (
            section.startswith('branch "')
            and section.endswith('"')
            and key.lower() == "vscode-merge-base"
        )
        if inert_multivar and (
            not value
            or len(value.encode("utf-8")) > 1024
            or any(ord(character) < 0x20 for character in value)
        ):
            raise CanonicalRepositoryRefused(
                "Git config has malformed inert VS Code merge-base metadata"
            )
        if full_key in values and values[full_key] != value:
            if inert_multivar:
                continue
            raise CanonicalRepositoryRefused("Git config has conflicting duplicate keys")
        values[full_key] = value

    hooks_path = values.get("core.hookspath")
    if hooks_path is not None:
        decoded: list[str] = []
        index = 0
        while index < len(hooks_path):
            character = hooks_path[index]
            if character != "\\":
                decoded.append(character)
                index += 1
                continue
            if index + 1 >= len(hooks_path) or hooks_path[index + 1] != "\\":
                raise CanonicalRepositoryRefused(
                    "core.hooksPath uses unsupported Git config escaping"
                )
            decoded.append("\\")
            index += 2
        observed_hooks = os.path.normcase(os.path.abspath("".join(decoded)))
        expected_hooks = os.path.normcase(os.path.abspath(git_common / "hooks"))
        if observed_hooks != expected_hooks:
            raise CanonicalRepositoryRefused(
                "core.hooksPath must be the attested internal default hooks directory"
            )

    forbidden_exact = {
        "core.fsmonitor",
        "core.sparsecheckout",
        "core.sparsecheckoutcone",
        "core.sshcommand",
        "core.gitproxy",
        "core.attributesfile",
        "core.excludesfile",
        "core.worktree",
        "credential.helper",
        "extensions.partialclone",
        "extensions.refstorage",
        "extensions.objectformat",
    }
    for key in values:
        key_tail = key.split(".")[-1]
        if key in forbidden_exact or key_tail in {
            "promisor",
            "partialclonefilter",
            "uploadpack",
            "receivepack",
            "helper",
        }:
            raise CanonicalRepositoryRefused(f"unsafe Git config key is forbidden: {key}")
    version = values.get("core.repositoryformatversion", "0")
    if version != "0":
        raise CanonicalRepositoryRefused("only Git repository format version 0 is supported")
    return values


def _parse_packed_refs(raw: bytes) -> dict[str, str]:
    try:
        text = raw.decode("ascii")
    except UnicodeDecodeError as exc:
        raise CanonicalRepositoryRefused("packed-refs is not strict ASCII") from exc
    result: dict[str, str] = {}
    for line in text.splitlines():
        if not line or line.startswith("#") or line.startswith("^"):
            continue
        parts = line.split(" ")
        if len(parts) != 2 or _OID_RE.fullmatch(parts[0]) is None:
            raise CanonicalRepositoryRefused("packed-refs has unsupported syntax")
        ref = parts[1]
        if _REF_RE.fullmatch(ref) is None or ".." in ref or "//" in ref:
            raise CanonicalRepositoryRefused("packed-refs contains an unsafe ref")
        if ref in result:
            raise CanonicalRepositoryRefused("packed-refs contains a duplicate ref")
        result[ref] = parts[0]
    return result


@dataclass(frozen=True, kw_only=True)
class CanonicalRepositoryAttestation:
    canonical_root: str
    git_common_dir: str
    canonical_root_identity_digest: str
    git_common_identity_digest: str
    repository_id: str
    head_ref: str
    head_oid: str
    object_format: str
    oid_length: int
    ref_backend: str
    config_digest: str
    index_digest: str
    packed_refs_digest: str
    object_metadata_digest: str
    inert_metadata_digest: str
    worktree_registry_digest: str
    metadata_digest: str

    def toDict(self) -> dict[str, Any]:
        return {field.name: getattr(self, field.name) for field in fields(self)}

    @property
    def attestation_digest(self) -> str:
        return canonical_digest(self.toDict())


def attestCanonicalRepository(root: str | Path) -> CanonicalRepositoryAttestation:
    canonical_path = _absolute(root)
    git_dir = canonical_path / ".git"
    canonical_root = str(canonical_path)
    git_common = str(git_dir)
    try:
        root_handle = openNativeDirectory(canonical_path)
    except OSError as exc:
        raise CanonicalRepositoryRefused("cannot open canonical root exactly") from exc
    with root_handle:
        root_native_identity = root_handle.identity
        if root_native_identity.is_reparse or not root_native_identity.is_directory:
            raise CanonicalRepositoryRefused("canonical root is not a native directory")
        root_identity = _native_identity_digest(canonical_path, root_native_identity)
        root_entries = _native_entries(root_handle, label="canonical root")
        git_entry = _native_entry(
            root_handle,
            ".git",
            label="canonical Git common directory",
        )
        if git_entry is None:
            raise CanonicalRepositoryRefused(
                "canonical Git common directory is missing"
            )
        if not git_entry.identity.is_directory:
            raise CanonicalRepositoryRefused(
                "canonical repository requires a normal .git directory"
            )
        try:
            git_handle = root_handle.openDirectory(
                ".git",
                expected=git_entry.identity,
            )
        except OSError as exc:
            raise CanonicalRepositoryRefused(
                "canonical Git common directory raced open"
            ) from exc
        with git_handle:
            git_native_identity = git_handle.identity
            git_identity = _native_identity_digest(git_dir, git_native_identity)
            git_entries = _native_entries(
                git_handle,
                label="canonical Git common directory",
            )
            if _native_entry(
                git_handle,
                "commondir",
                label="linked canonical checkout marker",
                required=False,
            ) is not None:
                raise CanonicalRepositoryRefused(
                    "linked canonical checkouts are unsupported"
                )

            for relative, label, entry_limit, byte_limit in (
                ("objects", "canonical object store", 2_000_000, 1 << 40),
                ("refs", "canonical ref store", 200_000, 1 << 30),
                ("hooks", "canonical hook store", 10_000, 1 << 30),
                ("info", "canonical info store", 10_000, 1 << 30),
                ("worktrees", "linked-worktree registry", 10_000, 1 << 34),
            ):
                entry = _native_entry(
                    git_handle,
                    relative,
                    label=label,
                    required=False,
                )
                if entry is None:
                    continue
                if not entry.identity.is_directory:
                    raise CanonicalRepositoryRefused(f"{label} is not a directory")
                with git_handle.openDirectory(
                    relative,
                    expected=entry.identity,
                ) as subtree:
                    _attest_native_handle_tree(
                        subtree,
                        label=label,
                        max_entries=entry_limit,
                        max_bytes=byte_limit,
                    )

            config_raw = _read_native(
                git_handle,
                "config",
                limit=_CONFIG_LIMIT,
                label="Git config",
            )
            _parse_config(config_raw, git_common=Path(git_common))
            config_digest = hashlib.sha256(config_raw).hexdigest()

            head_text = _read_native_text(
                git_handle,
                "HEAD",
                encoding="ascii",
                label="symbolic HEAD",
            ).strip()
            if not head_text.startswith("ref: "):
                raise CanonicalRepositoryRefused("canonical HEAD must be symbolic")
            head_ref = head_text[5:]
            if (
                _REF_RE.fullmatch(head_ref) is None
                or not head_ref.startswith("refs/heads/")
                or ".." in head_ref
                or "//" in head_ref
            ):
                raise CanonicalRepositoryRefused("canonical HEAD names an unsafe ref")
            with _native_parent(
                git_handle,
                tuple(head_ref.split("/")),
                label="loose target ref",
            ) as (ref_parent, ref_name):
                try:
                    head_oid = _read_native_text(
                        ref_parent,
                        ref_name,
                        encoding="ascii",
                        label="loose target ref",
                    ).strip()
                except CanonicalRepositoryRefused as exc:
                    raise CanonicalRepositoryRefused(
                        "canonical target must have an authoritative loose target ref"
                    ) from exc
            if _OID_RE.fullmatch(head_oid) is None:
                raise CanonicalRepositoryRefused(
                    "loose target ref does not contain a full SHA-1 OID"
                )

            packed_digest = ""
            if _native_entry(
                git_handle,
                "packed-refs",
                label="packed-refs",
                required=False,
            ) is not None:
                packed_raw = _read_native(
                    git_handle,
                    "packed-refs",
                    label="packed-refs",
                )
                packed_digest = hashlib.sha256(packed_raw).hexdigest()
                shadow = _parse_packed_refs(packed_raw).get(head_ref)
                if shadow is not None and shadow != head_oid:
                    raise CanonicalRepositoryRefused(
                        "packed target ref disagrees with authoritative loose ref"
                    )

            unsupported = (
                "objects/info/alternates",
                "objects/info/http-alternates",
                "shallow",
                "info/grafts",
            )
            for relative in unsupported:
                if _native_exists(
                    git_handle,
                    tuple(relative.split("/")),
                    label=relative,
                ):
                    raise CanonicalRepositoryRefused(
                        f"unsupported Git metadata is present: {relative}"
                    )
            if _native_exists(
                git_handle,
                ("refs", "replace"),
                label="refs/replace",
            ):
                with _native_parent(
                    git_handle,
                    ("refs", "replace"),
                    label="refs/replace",
                ) as (refs_parent, replace_name):
                    replace_entry = _native_entry(
                        refs_parent,
                        replace_name,
                        label="refs/replace",
                    )
                    if replace_entry is None:
                        raise CanonicalRepositoryRefused(
                            "refs/replace disappeared during attestation"
                        )
                    if not replace_entry.identity.is_directory:
                        raise CanonicalRepositoryRefused(
                            "unsupported Git metadata is present: refs/replace"
                        )
                    with refs_parent.openDirectory(
                        replace_name,
                        expected=replace_entry.identity,
                    ) as replace:
                        if _native_entries(replace, label="refs/replace"):
                            raise CanonicalRepositoryRefused(
                                "unsupported Git metadata is present: refs/replace"
                            )
            if _native_exists(
                git_handle,
                ("info", "attributes"),
                label="repository-private info/attributes",
            ):
                raise CanonicalRepositoryRefused(
                    "repository-private info/attributes is forbidden"
                )
            hooks_entry = _native_entry(
                git_handle,
                "hooks",
                label="canonical hook store",
                required=False,
            )
            if hooks_entry is not None:
                with git_handle.openDirectory(
                    "hooks",
                    expected=hooks_entry.identity,
                ) as hooks:
                    for hook in _native_entries(hooks, label="canonical hook store"):
                        if hook.identity.is_directory or not hook.name.endswith(".sample"):
                            raise CanonicalRepositoryRefused(
                                "active repository hook is forbidden"
                            )

            object_metadata_digest = _digest_object_metadata_handle(git_handle)
            inert_metadata_digest = _digest_inert_metadata_handle(
                git_handle,
                git_entries,
            )

            index_raw = _read_native(
                git_handle,
                "index",
                label="canonical index",
            )
            try:
                GitIndex.parse(index_raw)
            except GitIndexRefused as exc:
                raise CanonicalRepositoryRefused(
                    f"canonical index violates the ordinary DIRC-v2 profile: {exc}"
                ) from exc
            index_digest = hashlib.sha256(index_raw).hexdigest()
            registry_digest = _digest_inert_registry_handle(
                git_handle,
                target_ref=head_ref,
            )
            if (
                git_handle.identity != git_native_identity
                or _native_entries(
                    git_handle,
                    label="canonical Git common directory",
                )
                != git_entries
            ):
                raise CanonicalRepositoryRefused(
                    "canonical Git common directory drifted during attestation"
                )
        if (
            root_handle.identity != root_native_identity
            or _native_entries(root_handle, label="canonical root") != root_entries
        ):
            raise CanonicalRepositoryRefused(
                "canonical root drifted during attestation"
            )
        try:
            with openNativeDirectory(canonical_path) as visible_root:
                visible_identity = visible_root.identity
        except OSError as exc:
            raise CanonicalRepositoryRefused(
                "canonical root identity drifted during attestation"
            ) from exc
        if not _same_native_object(visible_identity, root_native_identity):
            raise CanonicalRepositoryRefused(
                "canonical root identity drifted during attestation"
            )
    repository_id = canonical_digest(
        {
            "canonical_root": os.path.normcase(canonical_root),
            "root_identity": root_identity,
            "git_common": os.path.normcase(git_common),
            "git_identity": git_identity,
        }
    )
    metadata = {
        "repository_id": repository_id,
        "head_ref": head_ref,
        "head_oid": head_oid,
        "config_digest": config_digest,
        "index_digest": index_digest,
        "packed_refs_digest": packed_digest,
        "object_metadata_digest": object_metadata_digest,
        "inert_metadata_digest": inert_metadata_digest,
        "worktree_registry_digest": registry_digest,
        "object_format": "sha1",
        "oid_length": 40,
        "ref_backend": "files",
    }
    return CanonicalRepositoryAttestation(
        canonical_root=canonical_root,
        git_common_dir=git_common,
        canonical_root_identity_digest=root_identity,
        git_common_identity_digest=git_identity,
        repository_id=repository_id,
        head_ref=head_ref,
        head_oid=head_oid,
        object_format="sha1",
        oid_length=40,
        ref_backend="files",
        config_digest=config_digest,
        index_digest=index_digest,
        packed_refs_digest=packed_digest,
        object_metadata_digest=object_metadata_digest,
        inert_metadata_digest=inert_metadata_digest,
        worktree_registry_digest=registry_digest,
        metadata_digest=canonical_digest(metadata),
    )


@dataclass(frozen=True, kw_only=True)
class ExternalStateAuthority:
    domain_root: str
    controller_generation: int
    repository_id: str
    canonical_attestation_digest: str
    request_id: str
    issuer_instance_id: str
    _authority_token: object
    _process_capability: object

    def toDict(self) -> dict[str, Any]:
        return {
            "domain_root": self.domain_root,
            "controller_generation": self.controller_generation,
            "repository_id": self.repository_id,
            "canonical_attestation_digest": self.canonical_attestation_digest,
            "request_id": self.request_id,
            "issuer_instance_id": self.issuer_instance_id,
            "activation_authority": False,
        }


class ExternalStateAuthorityIssuer:
    def __init__(
        self,
        *,
        domain_root: str | Path,
        controller_generation: int,
        process_capability: object,
    ) -> None:
        if controller_generation < 1:
            raise ValueError("controller_generation must be positive")
        if process_capability is None:
            raise ValueError("process_capability is required")
        self.domain_root = str(_absolute(domain_root))
        self.controller_generation = controller_generation
        self._process_capability = process_capability
        self._instance_id = secrets.token_hex(32)
        self._live: dict[str, ExternalStateAuthority] = {}

    def issue(
        self,
        *,
        attestation: CanonicalRepositoryAttestation,
        request_id: str,
        process_capability: object,
    ) -> ExternalStateAuthority:
        _require_id(request_id, "request_id")
        if process_capability is not self._process_capability:
            raise ExternalRootAuthorityRefused("process capability does not match issuer")
        existing = self._live.get(request_id)
        if existing is not None:
            if (
                existing.repository_id == attestation.repository_id
                and existing.canonical_attestation_digest
                == attestation.attestation_digest
            ):
                return existing
            raise ExternalRootAuthorityRefused("request_id is already bound to another repository")
        authority = ExternalStateAuthority(
            domain_root=self.domain_root,
            controller_generation=self.controller_generation,
            repository_id=attestation.repository_id,
            canonical_attestation_digest=attestation.attestation_digest,
            request_id=request_id,
            issuer_instance_id=self._instance_id,
            _authority_token=object(),
            _process_capability=self._process_capability,
        )
        self._live[request_id] = authority
        return authority

    def validate(
        self,
        authority: object,
        attestation: CanonicalRepositoryAttestation,
    ) -> ExternalStateAuthority:
        if type(authority) is not ExternalStateAuthority:
            raise ExternalRootAuthorityRefused("external root requires a live issuer authority")
        live = self._live.get(authority.request_id)
        if (
            live is not authority
            or authority._process_capability is not self._process_capability
            or authority.issuer_instance_id != self._instance_id
            or authority.domain_root != self.domain_root
            or authority.controller_generation != self.controller_generation
            or authority.repository_id != attestation.repository_id
            or authority.canonical_attestation_digest != attestation.attestation_digest
        ):
            raise ExternalRootAuthorityRefused("external root authority is not live issuer evidence")
        return authority


@dataclass(frozen=True, kw_only=True)
class ExternalRepositoryRoots:
    repository_root: str
    controller_root: str
    checkout_root: str
    candidate_checkout_root: str
    verification_checkout_root: str
    artifact_root: str
    journal_root: str
    receipts_root: str
    locks_root: str
    manifest_path: str


def _root_values(repository_root: Path) -> ExternalRepositoryRoots:
    controller = repository_root / "controller"
    checkouts = repository_root / "checkouts"
    return ExternalRepositoryRoots(
        repository_root=str(repository_root),
        controller_root=str(controller),
        checkout_root=str(checkouts),
        candidate_checkout_root=str(checkouts / "candidate"),
        verification_checkout_root=str(checkouts / "verification"),
        artifact_root=str(repository_root / "artifacts"),
        journal_root=str(controller / "journal"),
        receipts_root=str(controller / "receipts"),
        locks_root=str(controller / "locks"),
        manifest_path=str(repository_root / "root-manifest.json"),
    )


def _manifest(
    *,
    attestation: CanonicalRepositoryAttestation,
    authority: ExternalStateAuthority,
    roots: ExternalRepositoryRoots,
) -> dict[str, Any]:
    return {
        "schema": "galaxy.external-repository-roots/v1",
        "repository_id": attestation.repository_id,
        "canonical_attestation_digest": attestation.attestation_digest,
        "canonical_root_identity_digest": attestation.canonical_root_identity_digest,
        "git_common_identity_digest": attestation.git_common_identity_digest,
        "controller_generation": authority.controller_generation,
        "request_id": authority.request_id,
        "roots": {
            field.name: getattr(roots, field.name)
            for field in fields(roots)
            if field.name != "manifest_path"
        },
        "activation_authority": False,
    }


def _verify_existing_manifest(path: Path, expected: bytes) -> None:
    try:
        observed = readNoFollowBytes(path, max_bytes=_CONFIG_LIMIT)
    except (OSError, ValueError) as exc:
        raise ExternalRootCollision("external root manifest is unsafe") from exc
    if observed != expected:
        raise ExternalRootCollision("existing external root manifest is foreign or corrupt")


def registerExternalRepositoryRoots(
    *,
    attestation: CanonicalRepositoryAttestation,
    authority: object,
    issuer: ExternalStateAuthorityIssuer,
) -> ExternalRepositoryRoots:
    live = issuer.validate(authority, attestation)
    domain = _absolute(live.domain_root)
    canonical = _absolute(attestation.canonical_root)
    git_common = _absolute(attestation.git_common_dir)
    if _overlaps(domain, canonical) or _overlaps(domain, git_common):
        raise ExternalRootAuthorityRefused(
            "installed controller state root must remain outside canonical and Git common"
        )
    try:
        assertNoReparsePath(domain)
        domain.mkdir(parents=True, exist_ok=True)
        assertNoReparsePath(domain)
    except OSError as exc:
        raise ExternalRootAuthorityRefused("controller state root traverses reparse point") from exc

    repositories = domain / "repositories"
    repositories.mkdir(exist_ok=True)
    try:
        assertNoReparsePath(repositories)
    except OSError as exc:
        raise ExternalRootAuthorityRefused("repository registry traverses reparse point") from exc
    final_root = repositories / attestation.repository_id
    roots = _root_values(final_root)
    expected = canonical_json_bytes(
        _manifest(attestation=attestation, authority=live, roots=roots)
    )
    final_manifest = Path(roots.manifest_path)
    if final_root.exists():
        _verify_existing_manifest(final_manifest, expected)
    else:
        staging = repositories / (
            f".{attestation.repository_id}.{live.request_id}.creating"
        )
        staging_manifest = staging / "root-manifest.json"
        if staging.exists():
            _verify_existing_manifest(staging_manifest, expected)
        else:
            try:
                os.mkdir(staging)
                exclusiveCreateBytes(staging_manifest, expected)
            except (OSError, FileExistsError) as exc:
                raise ExternalRootCollision("could not create owned external root staging") from exc
        staging_roots = _root_values(staging)
        for value in (
            staging_roots.controller_root,
            staging_roots.candidate_checkout_root,
            staging_roots.verification_checkout_root,
            staging_roots.artifact_root,
            staging_roots.journal_root,
            staging_roots.receipts_root,
            staging_roots.locks_root,
        ):
            Path(value).mkdir(parents=True, exist_ok=True)
        try:
            os.rename(staging, final_root)
        except FileExistsError:
            _verify_existing_manifest(final_manifest, expected)
        except OSError as exc:
            if not final_root.exists():
                raise ExternalRootCollision("external root publication failed") from exc
            _verify_existing_manifest(final_manifest, expected)

    _verify_existing_manifest(final_manifest, expected)
    for value in (
        roots.controller_root,
        roots.candidate_checkout_root,
        roots.verification_checkout_root,
        roots.artifact_root,
        roots.journal_root,
        roots.receipts_root,
        roots.locks_root,
    ):
        path = Path(value)
        if not path.is_dir():
            raise ExternalRootCollision("external root is incomplete")
        try:
            assertNoReparsePath(path)
        except OSError as exc:
            raise ExternalRootCollision("external root contains a reparse point") from exc
    return roots


