def _canonical_json(value: object) -> str:
    return json.dumps(
        value,
        ensure_ascii=False,
        allow_nan=False,
        separators=(",", ":"),
        sort_keys=True,
    )


def _now() -> datetime:
    return datetime.now(timezone.utc)


class OperatorTrustAuthority:
    """Issue and resolve grants that cannot survive process replacement.

    SQLite stores immutable evidence and revocation state.  Liveness comes
    solely from object identity in ``_live_grants`` plus the caller-provided
    process capability; durable rows can never recreate that identity.
    """

    def __init__(
        self,
        *,
        issuer_id: str,
        revocation_generation: int,
        process_capability: object,
        evidence_store: str | Path,
    ) -> None:
        if not issuer_id:
            raise ValueError("issuer_id is required")
        if type(revocation_generation) is not int or revocation_generation < 0:
            raise ValueError("revocation_generation must be a non-negative integer")
        if process_capability is None:
            raise ValueError("process_capability is required")
        self.issuer_id = issuer_id
        self.revocation_generation = revocation_generation
        self._process_capability = process_capability
        self._instance_id = secrets.token_hex(32)
        self._live_grants: dict[str, WorkloadTrustGrant] = {}
        self._revoked: set[str] = set()
        self.evidence_store = Path(evidence_store)
        self.evidence_store.parent.mkdir(parents=True, exist_ok=True)
        self._initialize_store()

    def _connect(self) -> sqlite3.Connection:
        database = sqlite3.connect(self.evidence_store, timeout=5)
        database.execute("PRAGMA journal_mode=WAL")
        database.execute("PRAGMA synchronous=FULL")
        return database

    def _initialize_store(self) -> None:
        with self._connect() as database:
            database.execute(
                "CREATE TABLE IF NOT EXISTS trust_metadata ("
                "key TEXT PRIMARY KEY, value TEXT NOT NULL) WITHOUT ROWID"
            )
            database.execute(
                "CREATE TABLE IF NOT EXISTS trust_receipts ("
                "receipt_id TEXT PRIMARY KEY, receipt_json TEXT NOT NULL, "
                "receipt_digest TEXT NOT NULL, revoked INTEGER NOT NULL DEFAULT 0, "
                "issuer_id TEXT NOT NULL, revocation_generation INTEGER NOT NULL"
                ") WITHOUT ROWID"
            )
            row = database.execute(
                "SELECT value FROM trust_metadata WHERE key='revocation_generation'"
            ).fetchone()
            if row is None:
                database.execute(
                    "INSERT INTO trust_metadata VALUES ('revocation_generation', ?)",
                    (str(self.revocation_generation),),
                )
                self._store_generation_valid = True
            else:
                self._store_generation_valid = row[0] == str(
                    self.revocation_generation
                )

    def issueWorkloadGrant(
        self,
        *,
        repository_attestation_digest: str,
        expected_base_sha: str,
        task_id: str,
        acceptance_spec_digest: str,
        capability_profile: str,
        expires_at: datetime | None = None,
    ) -> WorkloadTrustGrant:
        if not self._store_generation_valid:
            raise RuntimeError("trust evidence generation was rolled back or replaced")
        observed_now = _now()
        expiry = expires_at or (observed_now + timedelta(minutes=5))
        issued_at = (
            expiry - timedelta(seconds=1) if expiry <= observed_now else observed_now
        )
        receipt = WorkloadTrustReceipt(
            issuer_id=self.issuer_id,
            repository_attestation_digest=repository_attestation_digest,
            expected_base_sha=expected_base_sha,
            task_id=task_id,
            acceptance_spec_digest=acceptance_spec_digest,
            capability_profile=capability_profile,
            issued_at=issued_at,
            expires_at=expiry,
            nonce=secrets.token_hex(32),
            revocation_generation=self.revocation_generation,
        )
        grant = WorkloadTrustGrant(
            receipt=receipt,
            capability_profile=capability_profile,
            _process_capability=self._process_capability,
            _authority_instance_id=self._instance_id,
        )
        payload = _canonical_json(receipt.toDict())
        digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()
        with self._connect() as database:
            metadata = database.execute(
                "SELECT value FROM trust_metadata WHERE key='revocation_generation'"
            ).fetchone()
            if metadata != (str(self.revocation_generation),):
                self._store_generation_valid = False
                raise RuntimeError("trust evidence generation changed during issuance")
            database.execute(
                "INSERT INTO trust_receipts "
                "(receipt_id, receipt_json, receipt_digest, revoked, issuer_id, "
                "revocation_generation) VALUES (?, ?, ?, 0, ?, ?)",
                (
                    receipt.id,
                    payload,
                    digest,
                    receipt.issuer_id,
                    receipt.revocation_generation,
                ),
            )
        self._live_grants[receipt.id] = grant
        return grant

    def _durable_receipt_is_intact(self, receipt: WorkloadTrustReceipt) -> bool:
        if not self._store_generation_valid:
            return False
        try:
            with self._connect() as database:
                metadata = database.execute(
                    "SELECT value FROM trust_metadata "
                    "WHERE key='revocation_generation'"
                ).fetchone()
                row = database.execute(
                    "SELECT receipt_json, receipt_digest, revoked, issuer_id, "
                    "revocation_generation FROM trust_receipts WHERE receipt_id=?",
                    (receipt.id,),
                ).fetchone()
        except sqlite3.Error:
            return False
        if metadata != (str(self.revocation_generation),) or row is None:
            return False
        payload, digest, revoked, issuer_id, generation = row
        expected_payload = _canonical_json(receipt.toDict())
        return (
            payload == expected_payload
            and digest == hashlib.sha256(payload.encode("utf-8")).hexdigest()
            and digest == hashlib.sha256(expected_payload.encode("utf-8")).hexdigest()
            and revoked == 0
            and issuer_id == self.issuer_id
            and generation == self.revocation_generation
        )

    def resolve(
        self,
        *,
        grant: object,
        repository_attestation_digest: str,
        expected_base_sha: str,
        task_id: str,
        acceptance_spec_digest: str,
        capability_profile: str,
        on_local_eligible: Callable[[], object] | None = None,
    ) -> ResolvedWorkloadTrust:
        if type(grant) is not WorkloadTrustGrant:
            return unknownTrust("grant is not a live process-local capability")
        receipt = grant.receipt
        checks = (
            self._live_grants.get(receipt.id) is grant,
            grant._process_capability is self._process_capability,
            grant._authority_instance_id == self._instance_id,
            grant.capability_profile == capability_profile,
            receipt.issuer_id == self.issuer_id,
            receipt.revocation_generation == self.revocation_generation,
            receipt.repository_attestation_digest == repository_attestation_digest,
            receipt.expected_base_sha == expected_base_sha,
            receipt.task_id == task_id,
            receipt.acceptance_spec_digest == acceptance_spec_digest,
            receipt.capability_profile == capability_profile,
            receipt.id not in self._revoked,
            receipt.issued_at <= _now() < receipt.expires_at,
            self._durable_receipt_is_intact(receipt),
        )
        if not all(checks):
            return unknownTrust("grant is stale, revoked, forged, or scope-mismatched")
        local_eligible = capability_profile == TRUSTED_LOCAL_PROFILE
        if not local_eligible:
            return unknownTrust("capability profile is not trusted Local")
        resolved = ResolvedWorkloadTrust(
            tier="trusted_local",
            local_eligible=True,
            receipt_id=receipt.id,
            refusal_reason=None,
        )
        if on_local_eligible is not None:
            on_local_eligible()
        return resolved

    def revoke(self, grant: WorkloadTrustGrant) -> None:
        receipt_id = grant.receipt.id
        self._revoked.add(receipt_id)
        self._live_grants.pop(receipt_id, None)
        with self._connect() as database:
            database.execute(
                "UPDATE trust_receipts SET revoked=1 WHERE receipt_id=?",
                (receipt_id,),
            )


