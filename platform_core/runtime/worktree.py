"""Git-worktree-per-subtask isolation backend (Epic 1, unit c; hermes/guild pattern port).

Each parallel worker runs in its own git worktree off HEAD under
``state/.sc-worktrees/<task8>/<sid>``; a successful subtask merges its branch back, a failed
one is left for inspection. Modeled on hermes' BaseEnvironment interface so a container backend
can be added later (Epic 6). Fail-open: ANY git error degrades to the shared work_dir (today's
behavior). gc/remove refuse any path outside state/.sc-worktrees/ (path-scoped safe-remove).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  enterWorktree(state, sid: str) -> str  -- `git worktree add` a branch off HEAD into state/.sc-worktrees/<task8>/<sid>.
  collectChanges(path: str, sid: str) -> None  -- Stage+commit the worktree's working tree so a merge brings the executor's edits back.
  exitWorktree(path: str, *, merge: bool) -> None  -- On success commit + merge the worktree branch back into the run branch, then remove the
  removeWorktree(path: str) -> None  -- Path-scoped safe-remove: refuse any path outside state/.sc-worktrees/
  gcOrphans(state) -> None  -- Remove leftover worktrees for THIS task (TTL/whitelist cleanup)
  isIsolated(path: str) -> bool  -- True only when ``path`` lives under state/.sc-worktrees/ (an isolated worktree).
DEPENDS-ON: config, platform_core.core
SIDE-EFFECTS: creates/removes git worktrees under state/.sc-worktrees/
RUN/TEST: python -m pytest tests/test_worktree.py
"""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import config
from platform_core.core import git_io

LOG = config.getLogger("runtime.worktree")


def _worktreesRoot() -> Path:
    return Path(config.STATE_DIR) / ".sc-worktrees"


def _git(args: list[str], cwd: Path) -> subprocess.CompletedProcess:
    # Kernel wrapper: GIT_TERMINAL_PROMPT=0 + stdin=DEVNULL + a hard timeout, so a
    # credential prompt or wedged git can never hang the run (this wrapper had NO timeout).
    return git_io.runGit(*args, cwd=cwd, check=True, timeout=config.GIT_TIMEOUT_SECONDS)


def _branchFor(task8: str, sid: str) -> str:
    return f"wt/{task8}/{sid}"


def _sharedDir(state) -> str:
    return state.meta.get("work_dir") or str(config.PROJECT_ROOT)


def enterWorktree(state, sid: str) -> str:
    """`git worktree add` a branch off HEAD into state/.sc-worktrees/<task8>/<sid>.
    Returns the worktree path, or the shared work_dir on any git error (fail-open)."""
    try:
        task8 = str(state.task_id)[:8]
        dest = _worktreesRoot() / task8 / sid
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.exists():   # stale leftover from a prior crash -> reuse path, recreate clean
            removeWorktree(str(dest))
        branch = _branchFor(task8, sid)
        repo = Path(config.PROJECT_ROOT)
        # -B (force-reset) not -b: on a re-run/resume the branch wt/<task8>/<sid> already exists
        # (worktree remove keeps the branch), and -b would fail -> silent loss of isolation.
        _git(["worktree", "add", "-B", branch, str(dest), "HEAD"], repo)
        LOG.info("worktree: %s -> %s", sid, dest)
        return str(dest)
    except Exception as e:  # noqa: BLE001 -- degrade to the shared tree (today's behavior)
        LOG.warning("enterWorktree(%s) failed (%s); using shared tree", sid, e)
        return _sharedDir(state)


def collectChanges(path: str, sid: str) -> None:
    """Stage+commit the worktree's working tree so a merge brings the executor's edits back.
    The executor leaves UNCOMMITTED edits -- without this the worktree branch has zero commits and
    a merge is a no-op, then `worktree remove --force` deletes the work. No-op on a clean tree
    (nothing to commit)."""
    p = Path(path)
    _git(["add", "-A"], p)
    status = git_io.runGit("status", "--porcelain", cwd=p,
                           timeout=config.GIT_TIMEOUT_SECONDS)
    if status.stdout.strip():
        _git(["commit", "-m", f"9TO5 {sid}"], p)


def exitWorktree(path: str, *, merge: bool) -> None:
    """On success commit + merge the worktree branch back into the run branch, then remove the
    worktree. On a merge conflict abort the merge (never leave the shared repo MERGING) and leave
    the worktree for inspection. Fail-open; never raises."""
    if not isIsolated(path):
        return
    repo = Path(config.PROJECT_ROOT)
    p = Path(path)
    try:
        if merge:
            # Branch name == wt/<task8>/<sid> derived from the worktree dir layout.
            sid = p.name
            task8 = p.parent.name
            branch = _branchFor(task8, sid)
            collectChanges(str(p), sid)   # commit the executor's edits before merging
            try:
                _git(["merge", "--no-edit", branch], repo)
            except Exception:
                # A conflicting merge leaves the SHARED repo mid-merge -> abort so it is never
                # stranded in MERGING state, then leave the worktree for inspection (re-raise).
                try:
                    _git(["merge", "--abort"], repo)
                except Exception:  # noqa: BLE001 -- nothing to abort / best-effort
                    pass
                raise
        _git(["worktree", "remove", "--force", str(p)], repo)
    except Exception as e:  # noqa: BLE001
        LOG.warning("exitWorktree(%s, merge=%s) failed (%s); leaving for inspection", path, merge, e)


def removeWorktree(path: str) -> None:
    """Path-scoped safe-remove: refuse any path outside state/.sc-worktrees/. Never raises."""
    if not isIsolated(path):
        LOG.warning("removeWorktree refused non-worktree path: %s", path)
        return
    try:
        repo = Path(config.PROJECT_ROOT)
        try:
            _git(["worktree", "remove", "--force", path], repo)
        except Exception:  # noqa: BLE001 -- not a registered worktree -> just rmtree the dir
            shutil.rmtree(path, ignore_errors=True)
    except Exception as e:  # noqa: BLE001
        LOG.warning("removeWorktree(%s) failed (ignored): %s", path, e)


def gcOrphans(state) -> None:
    """Remove leftover worktrees for THIS task (TTL/whitelist cleanup). Never raises."""
    try:
        task8 = str(state.task_id)[:8]
        base = _worktreesRoot() / task8
        if base.exists():
            for child in base.iterdir():
                removeWorktree(str(child))
    except Exception as e:  # noqa: BLE001
        LOG.warning("gcOrphans failed (ignored): %s", e)


def isIsolated(path: str) -> bool:
    """True only when ``path`` lives under state/.sc-worktrees/ (an isolated worktree)."""
    try:
        Path(path).resolve().relative_to(_worktreesRoot().resolve())
        return True
    except Exception:  # noqa: BLE001 -- ValueError (not a subpath) or a resolve error
        return False
