_RESOURCE_RECOVERY_ROLE_ORDER = (
    ResourceRole.STATE_STORE_WORKER,
    ResourceRole.SOURCE_PARSER,
    ResourceRole.SOURCE_FETCHER,
    ResourceRole.VERIFIER,
    ResourceRole.CANDIDATE_PARSER,
    ResourceRole.COMMAND_SANDBOX,
    ResourceRole.BROKER,
    ResourceRole.MODEL_DRIVER,
    ResourceRole.AUTHORITY_WATCHDOG,
    ResourceRole.CREDENTIAL_LEASE,
)
_RESOURCE_RECOVERY_ROLE_INDEX = {
    role: index for index, role in enumerate(_RESOURCE_RECOVERY_ROLE_ORDER)
}


def _resourceIdentity(resource: RuntimeResourceLease) -> str:
    return f"{resource.role.value}:{resource.resource_id}"


def _dependencySafeResourceTeardownOrder(
    resources: tuple[RuntimeResourceLease, ...],
) -> tuple[RuntimeResourceLease, ...]:
    """Return a deterministic dependent-before-dependency recovery order."""

    if not isinstance(resources, tuple) or not all(
        isinstance(resource, RuntimeResourceLease) for resource in resources
    ):
        raise CloneRecoveryRefused(
            "runtime resource dependency closure is not an immutable exact tuple"
        )
    by_identity = {_resourceIdentity(resource): resource for resource in resources}
    if len(by_identity) != len(resources):
        raise CloneRecoveryRefused("runtime resource dependency closure is duplicated")
    identities = set(by_identity)
    dependencies: dict[str, set[str]] = {}
    dependents: dict[str, set[str]] = {identity: set() for identity in identities}
    for identity, resource in by_identity.items():
        if resource.role is ResourceRole.CREDENTIAL_LEASE and resource.depends_on:
            raise CloneRecoveryRefused(
                "credential resource cannot depend on a runtime child"
            )
        required = set(resource.depends_on)
        if not required <= identities:
            raise CloneRecoveryRefused(
                "runtime resource dependency closure is incomplete"
            )
        dependencies[identity] = required
        for dependency in required:
            dependents[dependency].add(identity)

    def startup_key(identity: str) -> tuple[int, bytes]:
        resource = by_identity[identity]
        # Reverse the legacy role priority for independent roots so reversing
        # the completed startup order preserves the established teardown order.
        return (
            -_RESOURCE_RECOVERY_ROLE_INDEX[resource.role],
            identity.encode("utf-8"),
        )

    ready = {identity for identity, required in dependencies.items() if not required}
    startup: list[str] = []
    while ready:
        identity = min(ready, key=startup_key)
        ready.remove(identity)
        startup.append(identity)
        for dependent in dependents[identity]:
            dependencies[dependent].remove(identity)
            if not dependencies[dependent]:
                ready.add(dependent)
    if len(startup) != len(resources):
        raise CloneRecoveryRefused(
            "runtime resource dependency closure contains a cycle"
        )
    return tuple(by_identity[identity] for identity in reversed(startup))


@dataclass(frozen=True, slots=True, kw_only=True)
class LegacyWorktreeInspection:
    legacy_id: str
    snapshot_digest: str
    dirty: bool

    def __post_init__(self) -> None:
        parts = self.legacy_id.split("/")
        if (
            len(parts) != 2
            or any(not part or part in {".", ".."} for part in parts)
            or any("\\" in part for part in parts)
        ):
            raise ValueError("legacy_id must be one task/entry identity")
        if re.fullmatch(r"[0-9a-f]{64}", self.snapshot_digest) is None:
            raise ValueError("legacy snapshot digest must be SHA-256")
        if type(self.dirty) is not bool:
            raise TypeError("legacy dirty state must be a bool")


@dataclass(frozen=True, slots=True, kw_only=True)
class LegacyWorktreeRetirement:
    legacy_id: str
    snapshot_digest: str
    disposition: str
    archive_name: str
    checkpoint_ref: str = ""
    checkpoint_revision: str = ""

    def __post_init__(self) -> None:
        LegacyWorktreeInspection(
            legacy_id=self.legacy_id,
            snapshot_digest=self.snapshot_digest,
            dirty=self.disposition == "dirty_checkpointed",
        )
        if self.disposition not in {"clean_retired", "dirty_checkpointed"}:
            raise ValueError("legacy retirement disposition is invalid")
        if re.fullmatch(r"legacy-[0-9a-f]{64}", self.archive_name) is None:
            raise ValueError("legacy archive name is invalid")
        if self.disposition == "dirty_checkpointed":
            if not self.checkpoint_ref.startswith("refs/9to5/legacy-recovery/"):
                raise ValueError("dirty legacy retirement requires a recovery ref")
            if re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", self.checkpoint_revision) is None:
                raise ValueError("dirty legacy retirement requires a checkpoint revision")
        elif self.checkpoint_ref or self.checkpoint_revision:
            raise ValueError("clean legacy retirement cannot claim a checkpoint")


LegacyInspector = Callable[
    [NativeDirectoryHandle, str],
    LegacyWorktreeInspection,
]
LegacyCheckpointer = Callable[
    [LegacyWorktreeInspection],
    tuple[str, str],
]


class LegacyWorktreeRetirer:
    """One-use, no-follow migration out of repository-local linked-worktree roots."""

    def __init__(
        self,
        *,
        legacy_roots: tuple[str | Path, ...],
        archive_root: str | Path,
        inspect: LegacyInspector,
        checkpoint: LegacyCheckpointer,
    ) -> None:
        if not legacy_roots:
            raise ValueError("at least one legacy root is required")
        if not callable(inspect) or not callable(checkpoint):
            raise TypeError("legacy inspection and checkpoint adapters are required")
        roots = tuple(Path(os.path.abspath(path)) for path in legacy_roots)
        archive = Path(os.path.abspath(archive_root))
        if not archive.is_absolute():
            raise ValueError("legacy archive root must be absolute")
        if any(_overlaps(root, archive) for root in roots):
            raise ValueError("legacy archive must be outside every legacy root")
        self.legacy_roots = roots
        self.archive_root = archive
        self.inspect = inspect
        self.checkpoint = checkpoint

    @staticmethod
    def _directoryEntries(
        directory: NativeDirectoryHandle,
        *,
        label: str,
    ):
        try:
            entries = directory.listEntries()
        except (OSError, UnicodeError) as exc:
            raise LegacyWorktreeRefused(f"{label} cannot be inventoried") from exc
        if any(entry.identity.is_reparse for entry in entries):
            raise LegacyWorktreeRefused(f"{label} contains a reparse entry")
        return entries

    def retire(self) -> tuple[LegacyWorktreeRetirement, ...]:
        try:
            archive = openNativeDirectory(self.archive_root)
        except OSError as exc:
            raise LegacyWorktreeRefused("legacy archive root is unavailable") from exc
        results: list[LegacyWorktreeRetirement] = []
        with archive:
            for legacy_root in self.legacy_roots:
                if not legacy_root.exists():
                    continue
                try:
                    root = openNativeDirectory(legacy_root)
                except OSError as exc:
                    raise LegacyWorktreeRefused("legacy root is unsafe") from exc
                with root:
                    tasks = self._directoryEntries(root, label="legacy root")
                    for task in tasks:
                        if not task.identity.is_directory:
                            raise LegacyWorktreeRefused(
                                "legacy root contains a non-directory task entry"
                            )
                        try:
                            task_directory = root.openDirectory(
                                task.name,
                                expected=task.identity,
                            )
                        except OSError as exc:
                            raise LegacyWorktreeRefused(
                                "legacy task directory identity raced"
                            ) from exc
                        with task_directory:
                            entries = self._directoryEntries(
                                task_directory,
                                label="legacy task directory",
                            )
                            for entry in entries:
                                if not entry.identity.is_directory:
                                    raise LegacyWorktreeRefused(
                                        "legacy task contains a non-directory checkout"
                                    )
                                legacy_id = f"{task.name}/{entry.name}"
                                try:
                                    checkout = task_directory.openDirectory(
                                        entry.name,
                                        expected=entry.identity,
                                    )
                                except OSError as exc:
                                    raise LegacyWorktreeRefused(
                                        f"legacy checkout identity raced: {legacy_id}"
                                    ) from exc
                                with checkout:
                                    before = checkout.identity
                                    try:
                                        inspection = self.inspect(checkout, legacy_id)
                                    except Exception as exc:
                                        raise LegacyWorktreeRefused(
                                            f"legacy inspection failed: {legacy_id}"
                                        ) from exc
                                    if (
                                        not isinstance(inspection, LegacyWorktreeInspection)
                                        or inspection.legacy_id != legacy_id
                                        or checkout.identity != before
                                    ):
                                        raise LegacyWorktreeRefused(
                                            f"legacy inspection identity differs: {legacy_id}"
                                        )
                                checkpoint_ref = ""
                                checkpoint_revision = ""
                                if inspection.dirty:
                                    try:
                                        checkpoint_ref, checkpoint_revision = self.checkpoint(
                                            inspection
                                        )
                                        if not checkpoint_ref.startswith(
                                            "refs/9to5/legacy-recovery/"
                                        ) or re.fullmatch(
                                            r"[0-9a-f]{40}|[0-9a-f]{64}",
                                            checkpoint_revision,
                                        ) is None:
                                            raise ValueError("checkpoint result is malformed")
                                    except Exception as exc:
                                        raise LegacyWorktreeRefused(
                                            f"legacy checkpoint failed: {legacy_id}"
                                        ) from exc
                                archive_name = "legacy-" + canonical_digest(
                                    {
                                        "legacy_id": legacy_id,
                                        "snapshot_digest": inspection.snapshot_digest,
                                    }
                                )
                                if any(
                                    child.name == archive_name
                                    for child in self._directoryEntries(
                                        archive,
                                        label="legacy archive",
                                    )
                                ):
                                    raise LegacyWorktreeRefused(
                                        f"legacy archive collision: {legacy_id}"
                                    )
                                try:
                                    task_directory.moveChild(
                                        entry.name,
                                        archive,
                                        archive_name,
                                        expected=entry.identity,
                                    )
                                except (OSError, ValueError) as exc:
                                    raise LegacyWorktreeRefused(
                                        f"legacy checkout retirement failed: {legacy_id}"
                                    ) from exc
                                results.append(
                                    LegacyWorktreeRetirement(
                                        legacy_id=legacy_id,
                                        snapshot_digest=inspection.snapshot_digest,
                                        disposition=(
                                            "dirty_checkpointed"
                                            if inspection.dirty
                                            else "clean_retired"
                                        ),
                                        archive_name=archive_name,
                                        checkpoint_ref=checkpoint_ref,
                                        checkpoint_revision=checkpoint_revision,
                                    )
                                )
        return tuple(results)


