def _isReparse(info: os.stat_result) -> bool:
    flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
    return stat.S_ISLNK(info.st_mode) or bool(
        getattr(info, "st_file_attributes", 0) & flag
    )


def validateCloneLease(lease: CloneLease) -> CloneLease:
    """Re-prove that a lease has no linked-worktree, remote, alternate, or hardlink."""

    if not isinstance(lease, CloneLease):
        raise TypeError("lease must be CloneLease")
    try:
        checkout = assertNoReparsePath(lease.checkout_path)
        git_dir = assertNoReparsePath(lease.git_dir)
        common = assertNoReparsePath(lease.git_common_dir)
    except OSError as exc:
        raise PrivateCloneRefused("private clone path traverses a reparse point") from exc
    if not checkout.is_dir() or not git_dir.is_dir() or git_dir != common:
        raise PrivateCloneRefused("private clone requires one ordinary embedded .git directory")
    if git_dir != checkout / ".git" or (git_dir / "commondir").exists():
        raise PrivateCloneRefused("linked-worktree Git metadata is forbidden")
    try:
        config_raw = readNoFollowBytes(git_dir / "config", max_bytes=1024 * 1024)
        config_text = config_raw.decode("utf-8", errors="strict").casefold()
        head = readNoFollowBytes(git_dir / "HEAD", max_bytes=512).decode(
            "ascii", errors="strict"
        )
        shallow = readNoFollowBytes(git_dir / "shallow", max_bytes=512).decode(
            "ascii", errors="strict"
        )
    except (OSError, ValueError, UnicodeDecodeError) as exc:
        raise PrivateCloneRefused("private clone control files are unsafe") from exc
    forbidden_config = (
        "[remote ",
        "\nremote.",
        "\n\turl =",
        "\nurl =",
        "alternates",
        "promisor",
        "partialclone",
        "hookspath",
    )
    if any(marker in config_text for marker in forbidden_config):
        raise PrivateCloneRefused("private clone configuration contains an external provider")
    if head != f"ref: {lease.candidate_branch}\n":
        raise PrivateCloneRefused("private clone HEAD differs from its candidate branch")
    ref_path = git_dir.joinpath(*lease.candidate_branch.split("/"))
    try:
        ref_oid = readNoFollowBytes(ref_path, max_bytes=128).decode("ascii").strip()
    except (OSError, ValueError, UnicodeDecodeError) as exc:
        raise PrivateCloneRefused("private clone branch ref is unsafe") from exc
    if ref_oid != lease.expected_base_revision:
        raise PrivateCloneRefused("private clone branch is not the exact expected base")
    if shallow != lease.shallow_root_revision + "\n":
        raise PrivateCloneRefused("private clone shallow boundary differs")
    if (git_dir / "objects" / "info" / "alternates").exists():
        raise PrivateCloneRefused("private clone object alternates are forbidden")
    objects = git_dir / "objects"
    try:
        for path in objects.rglob("*"):
            info = os.lstat(path)
            if _isReparse(info):
                raise PrivateCloneRefused("private clone object store contains reparse data")
            if stat.S_ISDIR(info.st_mode):
                continue
            if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                raise PrivateCloneRefused("private clone object is linked or unsupported")
    except OSError as exc:
        raise PrivateCloneRefused("private clone object store could not be attested") from exc
    return lease


def _overlaps(left: Path, right: Path) -> bool:
    left_text = os.path.normcase(os.path.abspath(left))
    right_text = os.path.normcase(os.path.abspath(right))
    try:
        common = os.path.commonpath((left_text, right_text))
    except ValueError:
        return False
    return common in {left_text, right_text}


class CloneLeaseProvisioner:
    """Build and durably register one executable private clone before launch."""

    def __init__(
        self,
        *,
        attestation: CanonicalRepositoryAttestation,
        journal: AttemptJournal,
        writer: Any,
        candidate_checkout_root: str | Path,
        process_capability: object,
        clock: Callable[[], datetime] | None = None,
    ) -> None:
        if not isinstance(attestation, CanonicalRepositoryAttestation):
            raise TypeError("attestation must be CanonicalRepositoryAttestation")
        if not isinstance(journal, AttemptJournal):
            raise TypeError("journal must be AttemptJournal")
        if not callable(getattr(writer, "createCandidateRepository", None)):
            raise TypeError("writer must expose createCandidateRepository")
        root = Path(candidate_checkout_root)
        if not root.is_absolute():
            raise ValueError("candidate checkout root must be absolute")
        root = Path(os.path.abspath(root))
        canonical = Path(attestation.canonical_root)
        common = Path(attestation.git_common_dir)
        if (
            _overlaps(root, canonical)
            or _overlaps(root, common)
            or _overlaps(root, journal.root)
        ):
            raise PrivateCloneRefused(
                "candidate checkout root overlaps canonical or journal state"
            )
        if process_capability is None:
            raise ValueError("process_capability is required")
        self.attestation = attestation
        self.journal = journal
        self.writer = writer
        self.candidate_checkout_root = root
        self._process_capability = process_capability
        self._clock = clock or (lambda: datetime.now(timezone.utc))
        self._live: dict[str, CloneLease] = {}
        self._fingerprints: dict[str, str] = {}
        self._lock = threading.RLock()

    @staticmethod
    def _fingerprint(
        *,
        transaction_id: str,
        task_id: str,
        subtask_id: str,
        attempt_id: str,
        clone_lease_id: str,
        runner_kind: RunnerKind,
        source_manifest: ObjectManifest,
        source_closure: SourceObjectClosure,
        ownership_nonce: str,
        spec_digest: str,
        checkpoint_message_digest: str,
        proposal_message_digest: str,
        commit_timestamp_seed: str,
        runtime_resource_manifest_json: str,
        runtime_resource_manifest_digest: str,
    ) -> str:
        return canonical_digest(
            {
                "transaction_id": transaction_id,
                "task_id": task_id,
                "subtask_id": subtask_id,
                "attempt_id": attempt_id,
                "clone_lease_id": clone_lease_id,
                "runner_kind": runner_kind.value,
                "source_manifest": source_manifest.toDict(),
                "source_closure": {
                    "repository_id": source_closure.repository_id,
                    "revision": source_closure.revision,
                    "tree_oid": source_closure.tree_oid,
                    "manifest_digest": source_closure.manifest_digest,
                    "object_closure_digest": source_closure.object_closure_digest,
                    "source_snapshot_digest": source_closure.source_snapshot_digest,
                    "parser_receipt_id": source_closure.parser_receipt_id,
                    "parser_image_digest": source_closure.parser_image_digest,
                    "parser_runtime_digest": source_closure.parser_runtime_digest,
                    "parser_security_profile_digest": (
                        source_closure.parser_security_profile_digest
                    ),
                    "objects": [record.toDict() for record in source_closure.objects],
                    "intentional_shallow": source_closure.intentional_shallow,
                    "parser_network_allowed": source_closure.parser_network_allowed,
                },
                "ownership_nonce": ownership_nonce,
                "spec_digest": spec_digest,
                "checkpoint_message_digest": checkpoint_message_digest,
                "proposal_message_digest": proposal_message_digest,
                "commit_timestamp_seed": commit_timestamp_seed,
                "runtime_resource_manifest_json": runtime_resource_manifest_json,
                "runtime_resource_manifest_digest": runtime_resource_manifest_digest,
            }
        )

    @staticmethod
    def _sameRegisteredIntent(
        persisted: AttemptRecord,
        requested: AttemptRecord,
    ) -> bool:
        """Compare immutable lease intent while ignoring registration wall time."""

        if (
            persisted.phase is not AttemptPhase.LEASE_REGISTERED
            or persisted.sequence != 0
            or persisted.previous_event_digest
            or persisted.resource_lease_ids
        ):
            return False
        persisted_value = persisted.to_dict()
        requested_value = requested.to_dict()
        for name in ("created_at", "updated_at"):
            persisted_value.pop(name)
            requested_value.pop(name)
        return persisted_value == requested_value

    def provision(
        self,
        *,
        transaction_id: str,
        task_id: str,
        subtask_id: str,
        attempt_id: str,
        clone_lease_id: str,
        runner_kind: RunnerKind,
        source_manifest: ObjectManifest,
        source_closure: SourceObjectClosure,
        ownership_nonce: str,
        spec_digest: str,
        checkpoint_message_digest: str,
        proposal_message_digest: str,
        commit_timestamp_seed: str,
        runtime_resource_manifest_json: str,
        runtime_resource_manifest_digest: str,
        process_capability: object,
    ) -> CloneLease:
        if process_capability is not self._process_capability:
            raise PrivateCloneRefused("clone provisioning capability is not live")
        if not isinstance(runner_kind, RunnerKind):
            raise TypeError("runner_kind must be RunnerKind")
        if not isinstance(source_manifest, ObjectManifest) or not isinstance(
            source_closure,
            SourceObjectClosure,
        ):
            raise TypeError("source manifest and closure must be typed")
        try:
            validateRuntimeResourceManifest(
                runtime_resource_manifest_json,
                runtime_resource_manifest_digest,
                runner_kind=runner_kind.value,
            )
        except (TypeError, ValueError) as exc:
            raise PrivateCloneRefused(
                "runtime resource manifest is invalid"
            ) from exc
        live_attestation = attestCanonicalRepository(self.attestation.canonical_root)
        if live_attestation != self.attestation:
            raise PrivateCloneRefused("canonical repository drifted before clone registration")
        if (
            source_closure.repository_id != self.attestation.repository_id
            or source_closure.revision != self.attestation.head_oid
            or source_manifest.expected_revision != self.attestation.head_oid
            or source_closure.manifest_digest != source_manifest.manifest_digest
        ):
            raise PrivateCloneRefused(
                "source closure is not the exact attested canonical revision"
            )
        fingerprint = self._fingerprint(
            transaction_id=transaction_id,
            task_id=task_id,
            subtask_id=subtask_id,
            attempt_id=attempt_id,
            clone_lease_id=clone_lease_id,
            runner_kind=runner_kind,
            source_manifest=source_manifest,
            source_closure=source_closure,
            ownership_nonce=ownership_nonce,
            spec_digest=spec_digest,
            checkpoint_message_digest=checkpoint_message_digest,
            proposal_message_digest=proposal_message_digest,
            commit_timestamp_seed=commit_timestamp_seed,
            runtime_resource_manifest_json=runtime_resource_manifest_json,
            runtime_resource_manifest_digest=runtime_resource_manifest_digest,
        )
        with self._lock:
            prior = self._live.get(transaction_id)
            if prior is not None:
                if self._fingerprints.get(transaction_id) != fingerprint:
                    raise PrivateCloneRefused(
                        "live transaction cannot be replayed with different inputs"
                    )
                return validateCloneLease(prior)
            checkout = self.candidate_checkout_root / transaction_id
            branch = f"refs/heads/9to5/candidates/{transaction_id}"
            observed = self._clock()
            if not isinstance(observed, datetime) or observed.tzinfo is None:
                raise PrivateCloneRefused("clone registration clock must be timezone-aware")
            registered_at = observed.astimezone(timezone.utc).isoformat(
                timespec="microseconds"
            )
            policy_digest = canonical_digest(
                {
                    "attribute_rules": [
                        rule.toDict() for rule in source_manifest.attribute_rules
                    ],
                    "policy": source_manifest.policy.toDict(),
                }
            )
            record = AttemptRecord(
                transaction_id=transaction_id,
                task_id=task_id,
                subtask_id=subtask_id,
                attempt_id=attempt_id,
                repository_id=self.attestation.repository_id,
                canonical_root=self.attestation.canonical_root,
                canonical_ref=self.attestation.head_ref,
                base_revision=self.attestation.head_oid,
                candidate_kind="clone",
                clone_lease_id=clone_lease_id,
                clone_path=str(checkout),
                ownership_nonce=ownership_nonce,
                spec_digest=spec_digest,
                policy_digest=policy_digest,
                canonical_metadata_attestation_digest=(
                    self.attestation.attestation_digest
                ),
                object_format=self.attestation.object_format,
                oid_length=self.attestation.oid_length,
                ref_backend=self.attestation.ref_backend,
                candidate_branch=branch,
                checkpoint_message_digest=checkpoint_message_digest,
                proposal_message_digest=proposal_message_digest,
                commit_timestamp_seed=commit_timestamp_seed,
                runner_kind=runner_kind.value,
                candidate_git_dir=str(checkout / ".git"),
                canonical_git_common_dir=self.attestation.git_common_dir,
                source_manifest_digest=source_manifest.manifest_digest,
                source_object_closure_digest=source_closure.object_closure_digest,
                source_snapshot_digest=source_closure.source_snapshot_digest,
                source_parser_receipt_id=source_closure.parser_receipt_id,
                source_payload_root=source_closure.payload_root,
                runtime_resource_manifest_json=runtime_resource_manifest_json,
                runtime_resource_manifest_digest=runtime_resource_manifest_digest,
                created_at=registered_at,
                updated_at=registered_at,
            )
            try:
                record = self.journal.create(record, require_new=True)
            except AttemptCollision as exc:
                try:
                    persisted = self.journal.load(transaction_id)
                except (JournalError, OSError, TypeError, ValueError) as load_exc:
                    raise PrivateCloneRefused(
                        "durable clone registration cannot be replayed exactly"
                    ) from load_exc
                try:
                    self.journal.load_resources(transaction_id)
                except MissingResourceSet:
                    resource_set_missing = True
                except (IncompleteResourceSet, JournalCorruption) as load_exc:
                    raise PrivateCloneRefused(
                        "durable clone resource closure requires recovery"
                    ) from load_exc
                except (JournalError, OSError, TypeError, ValueError) as load_exc:
                    raise PrivateCloneRefused(
                        "durable clone registration cannot be replayed exactly"
                    ) from load_exc
                else:
                    resource_set_missing = False
                if (
                    not self._sameRegisteredIntent(persisted, record)
                    or not resource_set_missing
                ):
                    raise PrivateCloneRefused(
                        "durable transaction already exists and requires recovery ownership"
                    ) from exc
                record = persisted
                registered_at = persisted.created_at
            repository: CandidateRepositoryLease = (
                self.writer.createCandidateRepository(
                    transaction_id=transaction_id,
                    checkout_root=checkout,
                    candidate_branch=branch,
                    manifest=source_manifest,
                    closure=source_closure,
                    forbidden_roots=(
                        self.attestation.canonical_root,
                        self.attestation.git_common_dir,
                        self.journal.root,
                    ),
                )
            )
            if (
                not isinstance(repository, CandidateRepositoryLease)
                or repository.transaction_id != transaction_id
                or repository.checkout_path != str(checkout)
                or repository.base_revision != self.attestation.head_oid
                or repository.repository_id != self.attestation.repository_id
                or repository.manifest_digest != source_manifest.manifest_digest
                or repository.object_closure_digest
                != source_closure.object_closure_digest
            ):
                raise PrivateCloneRefused(
                    "candidate repository builder returned a different closure"
                )
            lease = CloneLease(
                transaction_id=transaction_id,
                task_id=task_id,
                subtask_id=subtask_id,
                attempt_id=attempt_id,
                checkout_path=repository.checkout_path,
                expected_base_revision=repository.base_revision,
                runner_kind=runner_kind,
                candidate_branch=repository.candidate_branch,
                repository_id=repository.repository_id,
                ownership_nonce=ownership_nonce,
                git_dir=repository.git_dir,
                git_common_dir=repository.git_dir,
                canonical_git_common_dir=self.attestation.git_common_dir,
                closure_manifest_digest=repository.object_closure_digest,
                shallow_root_revision=repository.shallow_root_revision,
                hardlink_count_verified=True,
                alternates_absent=True,
                remote_absent=True,
                linked_worktree_pointer_absent=True,
                registered_at=registered_at,
                runtime_token=object(),
            )
            validateCloneLease(lease)
            self._live[transaction_id] = lease
            self._fingerprints[transaction_id] = fingerprint
            return lease

    def registerRuntimeResources(
        self,
        lease: CloneLease,
        *,
        resources: tuple[RuntimeResourceLease, ...],
    ) -> AttemptRecord:
        if not isinstance(lease, CloneLease):
            raise TypeError("lease must be CloneLease")
        transaction_id = cast(str, cast(Any, lease).transaction_id)
        if not isinstance(resources, tuple) or not resources:
            raise ValueError("runtime resources must be a non-empty immutable tuple")
        lease_ownership_nonce = cast(str, cast(Any, lease).ownership_nonce)
        with self._lock:
            if self._live.get(transaction_id) is not lease:
                raise PrivateCloneRefused("runtime registration requires the live clone lease")
            requested_identities: list[str] = []
            for resource in resources:
                if not isinstance(resource, RuntimeResourceLease):
                    raise TypeError("runtime resource must be RuntimeResourceLease")
                if resource.transaction_id != transaction_id:
                    raise PrivateCloneRefused("runtime resource belongs to another attempt")
                if resource.ownership_nonce != lease_ownership_nonce:
                    raise PrivateCloneRefused("runtime resource ownership differs from clone")
                if resource.state not in {
                    ProcessResourceState.REGISTERED,
                    CredentialResourceState.REGISTERED,
                }:
                    raise PrivateCloneRefused(
                        "runtime resources must be registered before they start"
                    )
                requested_identities.append(
                    f"{resource.role.value}:{resource.resource_id}"
                )
            if len(requested_identities) != len(set(requested_identities)):
                raise PrivateCloneRefused("runtime resource identities are not unique")
            canonical_resources = tuple(
                sorted(
                    resources,
                    key=lambda resource: (
                        f"{resource.role.value}:{resource.resource_id}"
                    ),
                )
            )
            registered = self.journal.register_resources(transaction_id, resources)
            if registered != canonical_resources:
                raise PrivateCloneRefused("durable runtime resource registry differs")
            identities = tuple(
                f"{resource.role.value}:{resource.resource_id}"
                for resource in registered
            )
            return self.journal.transition(
                transaction_id,
                AttemptPhase.RUNNING,
                resource_lease_ids=identities,
            )


@dataclass(frozen=True, kw_only=True)
class CloneRecoveryCheckpoint:
    checkpoint_revision: str
    checkpoint_ref: str
    candidate_snapshot_digest: str
    parser_manifest_digest: str
    blob_set_digest: str

    def __post_init__(self) -> None:
        if not re.fullmatch(r"[0-9a-f]{40}", self.checkpoint_revision):
            raise ValueError("checkpoint_revision must be a full SHA-1 OID")
        if (
            not self.checkpoint_ref.startswith("refs/9to5/checkpoints/")
            or ".." in self.checkpoint_ref
        ):
            raise ValueError("checkpoint_ref is outside the recovery namespace")
        for name in (
            "candidate_snapshot_digest",
            "parser_manifest_digest",
            "blob_set_digest",
        ):
            value = getattr(self, name)
            if not isinstance(value, str) or not re.fullmatch(r"[0-9a-f]{64}", value):
                raise ValueError(f"{name} must be a lowercase SHA-256 digest")


@dataclass(frozen=True, kw_only=True)
class CloneRecoveryResult:
    record: AttemptRecord
    checkpoint: CloneRecoveryCheckpoint
    recovered_resource_ids: tuple[str, ...]


class CloneLeaseRecovery:
    """Recovery-own, quiesce, and checkpoint one stale executable clone."""

    def __init__(
        self,
        *,
        journal: AttemptJournal,
        recovery_lock_root: str | Path,
        process_capability: object,
        quiesce_resource: Callable[[RuntimeResourceLease], bool],
        checkpoint_clone: Callable[
            [CloneLease, CloneQuiescenceProof, AttemptRecord],
            CloneRecoveryCheckpoint,
        ],
        container_absence_probe: Callable[[RuntimeResourceLease], bool] | None = None,
        credential_channel_destroyer: CredentialChannelDestroyer | None = None,
        credential_absence_verifier: CredentialChannelAbsenceVerifier | None = None,
        clock: Callable[[], datetime] | None = None,
    ) -> None:
        if not isinstance(journal, AttemptJournal):
            raise TypeError("journal must be AttemptJournal")
        if process_capability is None:
            raise ValueError("recovery requires a process-local capability")
        if not callable(quiesce_resource) or not callable(checkpoint_clone):
            raise TypeError("recovery adapters must be callable")
        if container_absence_probe is not None and not callable(container_absence_probe):
            raise TypeError("container_absence_probe must be callable")
        if credential_channel_destroyer is not None and type(
            credential_channel_destroyer
        ) is not CredentialChannelDestroyer:
            raise TypeError(
                "credential channel destroyer must be the exact sealed typed adapter"
            )
        if credential_absence_verifier is not None and type(
            credential_absence_verifier
        ) is not CredentialChannelAbsenceVerifier:
            raise TypeError(
                "credential absence verifier must be the exact sealed typed adapter"
            )
        if (credential_channel_destroyer is None) != (
            credential_absence_verifier is None
        ):
            raise TypeError(
                "credential recovery requires both exact typed channel adapters"
            )
        try:
            root = assertNoReparsePath(recovery_lock_root)
            root.mkdir(parents=True, exist_ok=True)
            root = assertNoReparsePath(root)
        except OSError as exc:
            raise CloneRecoveryRefused("recovery lock root is unsafe") from exc
        self.journal = journal
        self.recovery_lock_root = root
        self._process_capability = process_capability
        self._quiesce_resource = quiesce_resource
        self._checkpoint_clone = checkpoint_clone
        self._container_absence_probe = container_absence_probe
        self._credential_channel_destroyer = credential_channel_destroyer
        self._credential_absence_verifier = credential_absence_verifier
        self._clock = clock or (lambda: datetime.now(timezone.utc))
        self._results: dict[str, CloneRecoveryResult] = {}
        self._lock = threading.RLock()

    @staticmethod
    def _checkpoint_from_record(record: AttemptRecord) -> CloneRecoveryCheckpoint:
        return CloneRecoveryCheckpoint(
            checkpoint_revision=record.checkpoint_revision,
            checkpoint_ref=record.checkpoint_ref,
            candidate_snapshot_digest=record.candidate_snapshot_digest,
            parser_manifest_digest=record.parser_manifest_digest,
            blob_set_digest=record.blob_set_digest,
        )

    @staticmethod
    def _lease_from_record(record: AttemptRecord, runtime_token: object) -> CloneLease:
        try:
            runner_kind = RunnerKind(record.runner_kind)
        except ValueError as exc:
            raise CloneRecoveryRefused("recorded clone runner kind is unavailable") from exc
        lease = CloneLease(
            transaction_id=record.transaction_id,
            task_id=record.task_id,
            subtask_id=record.subtask_id,
            attempt_id=record.attempt_id,
            checkout_path=record.clone_path,
            expected_base_revision=record.base_revision,
            runner_kind=runner_kind,
            candidate_branch=record.candidate_branch,
            repository_id=record.repository_id,
            ownership_nonce=record.ownership_nonce,
            git_dir=record.candidate_git_dir,
            git_common_dir=record.candidate_git_dir,
            canonical_git_common_dir=record.canonical_git_common_dir,
            closure_manifest_digest=record.source_object_closure_digest,
            shallow_root_revision=record.base_revision,
            hardlink_count_verified=True,
            alternates_absent=True,
            remote_absent=True,
            linked_worktree_pointer_absent=True,
            registered_at=record.created_at,
            runtime_token=runtime_token,
        )
        try:
            return validateCloneLease(lease)
        except PrivateCloneRefused as exc:
            raise CloneRecoveryRefused("stale clone is no longer self-contained") from exc

    def _validate_lock_boundary(self, record: AttemptRecord) -> None:
        root = os.path.normcase(str(self.recovery_lock_root))
        for forbidden in (
            record.canonical_root,
            record.canonical_git_common_dir,
            record.clone_path,
            str(self.journal.root),
        ):
            if _overlaps(Path(root), Path(forbidden)):
                raise CloneRecoveryRefused(
                    "recovery lock storage overlaps controlled repository data"
                )

    def _revokeCredential(
        self,
        record: AttemptRecord,
        resource: RuntimeResourceLease,
    ) -> RuntimeResourceLease:
        state = cast(CredentialResourceState, resource.state)
        if state not in {
            CredentialResourceState.ISSUED,
            CredentialResourceState.INJECTED,
        }:
            return resource
        destroyer = self._credential_channel_destroyer
        if type(destroyer) is not CredentialChannelDestroyer:
            raise CloneRecoveryRefused(
                "credential revocation has no sealed typed broker adapter"
            )
        try:
            revoked = destroyer.revoke(resource)
        except CredentialChannelEvidenceRefused as exc:
            raise CloneRecoveryRefused(
                f"credential resource did not revoke: {resource.resource_id}"
            ) from exc
        if type(revoked) is not RuntimeResourceLease:
            raise CloneRecoveryRefused(
                f"credential revocation returned no exact resource: {resource.resource_id}"
            )
        return revoked

    def _proveCredentialAbsent(
        self,
        resource: RuntimeResourceLease,
    ) -> None:
        verifier = self._credential_absence_verifier
        if type(verifier) is not CredentialChannelAbsenceVerifier:
            raise CloneRecoveryRefused(
                "credential absence has no sealed typed verifier"
            )
        assert isinstance(verifier, CredentialChannelAbsenceVerifier)
        try:
            terminal = runtimeResourceIsQuiescent(
                resource,
                credential_absence_verifier=verifier,
            )
        except RuntimeResourceProbeRefused as exc:
            raise CloneRecoveryRefused(
                "credential channel destruction is unproven: "
                f"{resource.resource_id}"
            ) from exc
        if not terminal:
            raise CloneRecoveryRefused(
                "credential channel destruction is unproven: "
                f"{resource.resource_id}"
            )

    def _destroyCredential(
        self,
        record: AttemptRecord,
        resource: RuntimeResourceLease,
    ) -> RuntimeResourceLease:
        resource = self._revokeCredential(record, resource)
        state = cast(CredentialResourceState, resource.state)
        if state is CredentialResourceState.DESTROYED:
            self._proveCredentialAbsent(resource)
            return resource
        if state not in {
            CredentialResourceState.REGISTERED,
            CredentialResourceState.REVOKED_OR_EXPIRED,
        }:
            raise CloneRecoveryRefused(
                f"credential resource state is not recoverable: {resource.resource_id}"
            )
        destroyer = self._credential_channel_destroyer
        if type(destroyer) is not CredentialChannelDestroyer:
            raise CloneRecoveryRefused(
                "credential destruction has no sealed typed broker adapter"
            )
        if state is CredentialResourceState.REGISTERED:
            try:
                revoked = destroyer.revoke(resource)
            except CredentialChannelEvidenceRefused as exc:
                raise CloneRecoveryRefused(
                    f"credential resource did not revoke: {resource.resource_id}"
                ) from exc
            if type(revoked) is not RuntimeResourceLease:
                raise CloneRecoveryRefused(
                    "credential revocation returned no exact resource"
                )
            resource = revoked

        try:
            destroyer.destroy(resource)
        except CredentialChannelEvidenceRefused as exc:
            raise CloneRecoveryRefused(
                "credential channel destruction is unproven: "
                f"{resource.resource_id}"
            ) from exc
        destroyed = next(
            (
                observed
                for observed in self.journal.load_resources(record.transaction_id)
                if observed.resource_id == resource.resource_id
            ),
            None,
        )
        if type(destroyed) is not RuntimeResourceLease:
            raise CloneRecoveryRefused(
                "credential terminal journal result is unavailable"
            )
        self._proveCredentialAbsent(destroyed)
        return destroyed

    def _quiesce(
        self,
        record: AttemptRecord,
        resources: tuple[RuntimeResourceLease, ...],
    ) -> tuple[RuntimeResourceLease, ...]:
        identities = tuple(
            f"{resource.role.value}:{resource.resource_id}" for resource in resources
        )
        if identities != tuple(record.resource_lease_ids):
            raise CloneRecoveryRefused(
                "durable runtime resources differ from the attempt record"
            )
        recovered = {
            (resource.role, resource.resource_id): resource for resource in resources
        }
        for identity, resource in tuple(recovered.items()):
            if resource.role is ResourceRole.CREDENTIAL_LEASE:
                recovered[identity] = self._revokeCredential(record, resource)
        ordered = _dependencySafeResourceTeardownOrder(
            tuple(recovered.values()),
        )
        for resource in ordered:
            if resource.role is ResourceRole.CREDENTIAL_LEASE:
                resource = self._destroyCredential(record, resource)
                self._proveCredentialAbsent(resource)
            else:
                process_state = cast(ProcessResourceState, resource.state)
                if process_state is ProcessResourceState.REGISTERED:
                    if not self._quiesce_resource(resource):
                        raise CloneRecoveryRefused(
                            "process cleanup locator did not quiesce: "
                            f"{resource.resource_id}"
                        )
                elif process_state in {
                    ProcessResourceState.CREATED,
                    ProcessResourceState.STARTED,
                } and not self._quiesce_resource(resource):
                    raise CloneRecoveryRefused(
                        f"process resource did not quiesce: {resource.resource_id}"
                    )
                try:
                    writers_absent = runtimeResourceWritersAbsent(
                        resource,
                        container_absence_probe=self._container_absence_probe,
                    )
                except RuntimeResourceProbeRefused as exc:
                    raise CloneRecoveryRefused(
                        f"process resource absence is unproven: {resource.resource_id}"
                    ) from exc
                if not writers_absent:
                    raise CloneRecoveryRefused(
                        f"process resource remains live: {resource.resource_id}"
                    )
                if process_state not in {
                    ProcessResourceState.QUIESCED,
                    ProcessResourceState.COLLECTED,
                }:
                    resource = self.journal.transition_resource(
                        record.transaction_id,
                        resource.resource_id,
                        ProcessResourceState.QUIESCED,
                    )
                if not runtimeResourceIsQuiescent(
                    resource,
                    container_absence_probe=self._container_absence_probe,
                ):
                    raise CloneRecoveryRefused(
                        f"process resource is not terminal: {resource.resource_id}"
                    )
            recovered[(resource.role, resource.resource_id)] = resource
        return tuple(
            recovered[(resource.role, resource.resource_id)]
            for resource in resources
        )

    def _loadRecoveryResources(
        self,
        transaction_id: str,
    ) -> tuple[RuntimeResourceLease, ...]:
        try:
            resources = self.journal.load_resources(transaction_id)
        except MissingResourceSet as exc:
            raise CloneRecoveryRefused(
                "attempt runtime resource closure is missing"
            ) from exc
        except IncompleteResourceSet as exc:
            raise CloneRecoveryRefused(
                "attempt runtime resource closure is incomplete"
            ) from exc
        except JournalCorruption as exc:
            raise CloneRecoveryRefused(
                "attempt runtime resource closure is corrupt"
            ) from exc
        except (JournalError, OSError, TypeError, ValueError) as exc:
            raise CloneRecoveryRefused(
                "attempt runtime resource closure is unavailable"
            ) from exc
        if not isinstance(resources, tuple):
            raise CloneRecoveryRefused(
                "attempt runtime resource closure is not immutable"
            )
        return resources

    def _collect(
        self,
        record: AttemptRecord,
        resources: tuple[RuntimeResourceLease, ...] | None = None,
    ) -> None:
        observed = (
            self._loadRecoveryResources(record.transaction_id)
            if resources is None
            else resources
        )
        ordered = _dependencySafeResourceTeardownOrder(observed)
        process_resources = tuple(
            resource
            for resource in ordered
            if resource.role is not ResourceRole.CREDENTIAL_LEASE
        )
        for resource in process_resources:
            try:
                terminal = runtimeResourceIsQuiescent(
                    resource,
                    container_absence_probe=self._container_absence_probe,
                )
            except RuntimeResourceProbeRefused as exc:
                raise CloneRecoveryRefused(
                    f"process resource absence is unproven: {resource.resource_id}"
                ) from exc
            if not terminal:
                raise CloneRecoveryRefused(
                    f"process resource is not terminal: {resource.resource_id}"
                )
        for resource in ordered:
            if resource.role is ResourceRole.CREDENTIAL_LEASE:
                self._destroyCredential(record, resource)
        for resource in process_resources:
            if resource.state is not ProcessResourceState.COLLECTED:
                self.journal.transition_resource(
                    record.transaction_id,
                    resource.resource_id,
                    ProcessResourceState.COLLECTED,
                )

    def recover(
        self,
        transaction_id: str,
        *,
        process_capability: object,
    ) -> CloneRecoveryResult:
        if process_capability is not self._process_capability:
            raise CloneRecoveryRefused("recovery capability is not live")
        with self._lock:
            cached = self._results.get(transaction_id)
            if cached is not None:
                self._collect(
                    cached.record,
                    self._loadRecoveryResources(transaction_id),
                )
                return cached
            try:
                record = self.journal.load(transaction_id)
            except MissingAttempt as exc:
                raise CloneRecoveryRefused(
                    f"attempt {transaction_id!r} does not exist"
                ) from exc
            self._validate_lock_boundary(record)
            lock_name = hashlib.sha256(transaction_id.encode("utf-8")).hexdigest()
            with fileLock(self.recovery_lock_root / f"{lock_name}.lock", timeout=30):
                record = self.journal.load(transaction_id)
                if record.phase is AttemptPhase.CANDIDATE_CHECKPOINTED:
                    resources = self._loadRecoveryResources(transaction_id)
                    self._collect(record, resources)
                    checkpoint = self._checkpoint_from_record(record)
                    result = CloneRecoveryResult(
                        record=record,
                        checkpoint=checkpoint,
                        recovered_resource_ids=record.resource_lease_ids,
                    )
                    self._results[transaction_id] = result
                    return result
                if record.phase is not AttemptPhase.RUNNING:
                    raise CloneRecoveryRefused(
                        f"attempt phase {record.phase.value} is not recoverable as a dirty clone"
                    )
                resources = self._loadRecoveryResources(transaction_id)
                if not resources:
                    raise CloneRecoveryRefused("running attempt has no durable resources")
                try:
                    quiesced = self._quiesce(record, resources)
                    runtime_token = object()
                    lease = self._lease_from_record(record, runtime_token)
                    observed = self._clock()
                    if not isinstance(observed, datetime) or observed.tzinfo is None:
                        raise CloneRecoveryRefused(
                            "recovery clock must be timezone-aware"
                        )
                    proof = CloneQuiescenceProof(
                        transaction_id=record.transaction_id,
                        attempt_id=record.attempt_id,
                        resource_ids=record.resource_lease_ids,
                        resource_state_digest=runtimeResourceStateDigest(quiesced),
                        all_quiesced=True,
                        observed_at=observed.astimezone(timezone.utc).isoformat(
                            timespec="microseconds"
                        ),
                        runtime_token=runtime_token,
                    )
                    checkpoint = self._checkpoint_clone(lease, proof, record)
                    if not isinstance(checkpoint, CloneRecoveryCheckpoint):
                        raise CloneRecoveryRefused(
                            "checkpoint adapter returned an untyped result"
                        )
                    updated = self.journal.transition(
                        transaction_id,
                        AttemptPhase.CANDIDATE_CHECKPOINTED,
                        checkpoint_revision=checkpoint.checkpoint_revision,
                        checkpoint_ref=checkpoint.checkpoint_ref,
                        candidate_snapshot_digest=(
                            checkpoint.candidate_snapshot_digest
                        ),
                        parser_manifest_digest=checkpoint.parser_manifest_digest,
                        blob_set_digest=checkpoint.blob_set_digest,
                    )
                    self._collect(updated)
                except CloneRecoveryRefused as exc:
                    latest = self.journal.load(transaction_id)
                    if latest.phase is AttemptPhase.RUNNING:
                        self.journal.transition(
                            transaction_id,
                            AttemptPhase.RECOVERY_CONFLICT,
                            error=str(exc),
                        )
                    raise
                except Exception as exc:
                    latest = self.journal.load(transaction_id)
                    message = f"recovery adapter failed: {type(exc).__name__}: {exc}"
                    if latest.phase is AttemptPhase.RUNNING:
                        self.journal.transition(
                            transaction_id,
                            AttemptPhase.RECOVERY_CONFLICT,
                            error=message,
                        )
                    raise CloneRecoveryRefused(message) from exc
                result = CloneRecoveryResult(
                    record=updated,
                    checkpoint=checkpoint,
                    recovered_resource_ids=tuple(
                        f"{resource.role.value}:{resource.resource_id}"
                        for resource in quiesced
                    ),
                )
