class GitSha1dcOracle:
    def __init__(self, evidence: Sha1dcEvidence) -> None:
        self.evidence = evidence
        self._executable = Path(evidence.executable_path)
        self._sterile_root = Path(evidence._sterile_root)

    def withExpectedEvidence(self, evidence: Sha1dcEvidence) -> GitSha1dcOracle:
        return GitSha1dcOracle(evidence)

    def _revalidate(self) -> None:
        executable = _actual_git_executable(self._executable)
        if str(executable) != self.evidence.executable_path:
            raise Sha1dcRefused("SHA1_DC executable identity changed")
        if _digest_file(executable) != self.evidence.executable_sha256:
            raise Sha1dcRefused("SHA1_DC binary digest changed")
        if os.lstat(executable).st_nlink != self.evidence.executable_link_count:
            raise Sha1dcRefused("SHA1_DC binary link identity changed")
        result = _run(
            executable,
            ["version", "--build-options"],
            sterile_root=self._sterile_root,
            input_bytes=None,
            timeout=10,
        )
        if result.returncode != 0 or result.stderr:
            raise Sha1dcRefused("SHA1_DC build attestation failed")
        if result.stdout != self.evidence._build_options:
            raise Sha1dcRefused("SHA1_DC build options changed")
        if hashlib.sha256(result.stdout).hexdigest() != self.evidence.build_options_digest:
            raise Sha1dcRefused("SHA1_DC build-options digest changed")
        if b"SHA-1: SHA1_DC" not in result.stdout:
            raise Sha1dcRefused("Git runtime is not collision-detecting SHA1_DC")

    def revalidate(self) -> Sha1dcEvidence:
        """Re-attest the exact runtime and return its immutable evidence."""

        self._revalidate()
        return self.evidence

    def hashObject(self, object_type: str, payload: bytes) -> str:
        if object_type not in _OBJECT_TYPES:
            raise ValueError("object type must be blob, tree, or commit")
        if not isinstance(payload, bytes):
            raise TypeError("object payload must be immutable bytes")
        if len(payload) > _MAX_OBJECT_BYTES:
            raise Sha1dcRefused("object payload exceeds SHA1_DC quota")
        self._revalidate()
        result = _run(
            self._executable,
            ["hash-object", "--stdin", "--no-filters", "-t", object_type],
            sterile_root=self._sterile_root,
            input_bytes=payload,
            timeout=30,
        )
        if result.returncode != 0 or result.stderr:
            detail = result.stderr.decode("utf-8", errors="replace").strip()
            raise Sha1dcRefused(f"SHA1_DC object hash refused: {detail}")
        try:
            oid = result.stdout.decode("ascii").strip()
        except UnicodeDecodeError as exc:
            raise Sha1dcRefused("SHA1_DC returned non-ASCII output") from exc
        if _OID_RE.fullmatch(oid) is None or result.stdout != (oid + "\n").encode("ascii"):
            raise Sha1dcRefused("SHA1_DC returned a noncanonical object id")
        return oid


def _attest_standalone_runtime(executable: Path, sterile_root: Path) -> bytes:
    observed: list[bytes] = []
    for arguments, expected in (
        (["--version"], _STANDALONE_VERSION),
        (["--self-test"], _STANDALONE_SELF_TEST),
    ):
        result = _run_standalone(
            executable,
            arguments,
            sterile_root=sterile_root,
            input_bytes=None,
            timeout=10,
        )
        if result.returncode != 0 or result.stderr or result.stdout != expected:
            raise Sha1dcRefused("standalone SHA1_DC runtime attestation failed")
        observed.append(result.stdout)
    return b"".join(observed)


class StandaloneSha1dcOracle(GitSha1dcOracle):
    """Closed-protocol SHA1DC oracle; never delegates object hashing to Git."""

    def __init__(self, evidence: StandaloneSha1dcEvidence) -> None:
        super().__init__(evidence)
        self.evidence: StandaloneSha1dcEvidence = evidence
        self._build_evidence_path = Path(evidence.build_evidence_path)

    def withExpectedEvidence(
        self, evidence: Sha1dcEvidence
    ) -> StandaloneSha1dcOracle:
        if not isinstance(evidence, StandaloneSha1dcEvidence):
            raise TypeError("standalone oracle requires standalone evidence")
        return StandaloneSha1dcOracle(evidence)

    def _revalidate(self) -> None:
        executable = _actual_standalone_executable(self._executable)
        if str(executable) != self.evidence.executable_path:
            raise Sha1dcRefused("standalone SHA1_DC executable identity changed")
        if _digest_file(executable) != self.evidence.executable_sha256:
            raise Sha1dcRefused("standalone SHA1_DC binary digest changed")
        if os.lstat(executable).st_nlink != self.evidence.executable_link_count:
            raise Sha1dcRefused("standalone SHA1_DC binary link identity changed")
        evidence_path, raw, _ = _standalone_build_evidence(
            executable, self._build_evidence_path
        )
        if (
            str(evidence_path) != self.evidence.build_evidence_path
            or raw != self.evidence._build_evidence
            or hashlib.sha256(raw).hexdigest()
            != self.evidence.build_evidence_sha256
        ):
            raise Sha1dcRefused("standalone SHA1_DC build evidence changed")
        attestation = _attest_standalone_runtime(executable, self._sterile_root)
        if (
            attestation != self.evidence._build_options
            or hashlib.sha256(attestation).hexdigest()
            != self.evidence.build_options_digest
        ):
            raise Sha1dcRefused("standalone SHA1_DC runtime attestation changed")

    def hashObject(self, object_type: str, payload: bytes) -> str:
        if object_type not in _OBJECT_TYPES:
            raise ValueError("object type must be blob, tree, or commit")
        if not isinstance(payload, bytes):
            raise TypeError("object payload must be immutable bytes")
        if len(payload) > _MAX_OBJECT_BYTES:
            raise Sha1dcRefused("object payload exceeds SHA1_DC quota")
        self._revalidate()
        result = _run_standalone(
            self._executable,
            ["hash-object", object_type, str(len(payload))],
            sterile_root=self._sterile_root,
            input_bytes=payload,
            timeout=30,
        )
        if result.returncode != 0 or result.stderr:
            detail = result.stderr.decode("utf-8", errors="replace").strip()
            raise Sha1dcRefused(f"standalone SHA1_DC object hash refused: {detail}")
        try:
            oid = result.stdout.decode("ascii").strip()
        except UnicodeDecodeError as exc:
            raise Sha1dcRefused("standalone SHA1_DC returned non-ASCII output") from exc
        if _OID_RE.fullmatch(oid) is None or result.stdout != (oid + "\n").encode("ascii"):
            raise Sha1dcRefused("standalone SHA1_DC returned a noncanonical object id")
        return oid


def _prepare_sterile_root(value: str | Path) -> Path:
    root = Path(os.path.abspath(os.fspath(value)))
    try:
        assertNoReparsePath(root)
        root.mkdir(parents=True, exist_ok=True)
        assertNoReparsePath(root)
    except OSError as exc:
        raise Sha1dcRefused("sterile SHA1_DC root traverses a reparse point") from exc
    if any(root.iterdir()):
        raise Sha1dcRefused("sterile SHA1_DC root must be empty")
    return root


def qualifyStandaloneSha1dc(
    *,
    executable: str | Path,
    build_evidence: str | Path,
    sterile_root: str | Path,
) -> tuple[StandaloneSha1dcEvidence, StandaloneSha1dcOracle]:
    """Qualify the exact reviewed standalone SHA1DC runtime closure."""

    actual = _actual_standalone_executable(Path(executable))
    root = _prepare_sterile_root(sterile_root)
    evidence_path, evidence_raw, _ = _standalone_build_evidence(
        actual, Path(build_evidence)
    )
    attestation = _attest_standalone_runtime(actual, root)
    evidence = StandaloneSha1dcEvidence(
        executable_path=str(actual),
        executable_sha256=_digest_file(actual),
        executable_link_count=os.lstat(actual).st_nlink,
        build_options_digest=hashlib.sha256(attestation).hexdigest(),
        collision_detection="SHA1_DC",
        network_allowed=False,
        _build_options=attestation,
        _sterile_root=str(root),
        build_evidence_path=str(evidence_path),
        build_evidence_sha256=hashlib.sha256(evidence_raw).hexdigest(),
        source_revision=_STANDALONE_SOURCE_REVISION,
        protocol="galaxy.sha1dc-object-oracle/v1",
        _build_evidence=evidence_raw,
    )
    return evidence, StandaloneSha1dcOracle(evidence)


def qualifyGitSha1dc(
    *,
    executable: str | Path,
    sterile_root: str | Path,
) -> tuple[Sha1dcEvidence, GitSha1dcOracle]:
    actual = _actual_git_executable(Path(executable))
    root = _prepare_sterile_root(sterile_root)
    result = _run(
        actual,
        ["version", "--build-options"],
        sterile_root=root,
        input_bytes=None,
        timeout=10,
    )
    if result.returncode != 0 or result.stderr:
        raise Sha1dcRefused("could not attest Git SHA1_DC build options")
    if b"SHA-1: SHA1_DC" not in result.stdout:
        raise Sha1dcRefused("Git runtime does not report SHA1_DC")
    evidence = Sha1dcEvidence(
        executable_path=str(actual),
        executable_sha256=_digest_file(actual),
        executable_link_count=os.lstat(actual).st_nlink,
        build_options_digest=hashlib.sha256(result.stdout).hexdigest(),
        collision_detection="SHA1_DC",
        network_allowed=False,
        _build_options=result.stdout,
        _sterile_root=str(root),
    )
    return evidence, GitSha1dcOracle(evidence)


