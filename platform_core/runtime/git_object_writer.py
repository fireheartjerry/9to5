_DIGEST_RE = re.compile(r"^[0-9a-f]{64}$")
_OID_RE = re.compile(r"^[0-9a-f]{40}$")
_TIMEZONE_RE = re.compile(r"^[+-][0-9]{4}$")
_TRANSACTION_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")
_OBJECT_TYPES = frozenset({"blob", "tree", "commit"})
_MAX_OBJECT_BYTES = 64 * 1024 * 1024
_MAX_CLOSURE_BYTES = 128 * 1024 * 1024
_MAX_CLOSURE_OBJECTS = 100_000
_MAX_LOOSE_BYTES = _MAX_OBJECT_BYTES + (1024 * 1024)


class ObjectWriterRefused(RuntimeError):
    """The requested object closure was not safe and exact."""


def _requireDigest(value: str, name: str) -> None:
    if not isinstance(value, str) or _DIGEST_RE.fullmatch(value) is None:
        raise ValueError(f"{name} must be a lowercase SHA-256 digest")


def _requireOid(value: str, name: str) -> None:
    if not isinstance(value, str) or _OID_RE.fullmatch(value) is None:
        raise ObjectWriterRefused(f"{name} must be a 40-character lowercase object id")


def _frame(object_type: str, payload: bytes) -> bytes:
    return object_type.encode("ascii") + b" " + str(len(payload)).encode("ascii") + b"\0" + payload


def _preflightManifestClosure(manifest: ObjectManifest) -> None:
    total = sum(entry.size for entry in manifest.entries)
    if total > _MAX_CLOSURE_BYTES:
        raise ObjectWriterRefused("manifest exceeds aggregate object-byte quota")
    directories: set[tuple[str, ...]] = {()}
    for entry in manifest.entries:
        parts = PurePosixPath(entry.path).parts
        directories.update(parts[:index] for index in range(1, len(parts)))
    object_count = len(manifest.entries) + len(directories) + 1
    if object_count > _MAX_CLOSURE_OBJECTS:
        raise ObjectWriterRefused("manifest exceeds object-count quota")


def _pathOverlaps(left: Path, right: Path) -> bool:
    left_text = os.path.normcase(str(left))
    right_text = os.path.normcase(str(right))
    try:
        common = os.path.commonpath((left_text, right_text))
    except ValueError:
        return False
    return common in {left_text, right_text}


def _isReparseStat(info: os.stat_result) -> bool:
    reparse_flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
    return stat.S_ISLNK(info.st_mode) or bool(
        getattr(info, "st_file_attributes", 0) & reparse_flag
    )


def _sameNativeObject(left: NativeFileIdentity, right: NativeFileIdentity) -> bool:
    return (
        left.volume_id,
        left.file_id,
        left.is_directory,
        left.is_reparse,
        left.mount_id,
        left.reparse_tag,
    ) == (
        right.volume_id,
        right.file_id,
        right.is_directory,
        right.is_reparse,
        right.mount_id,
        right.reparse_tag,
    )


def _nativeEntry(
    directory: NativeDirectoryHandle,
    name: str,
    *,
    required: bool = True,
) -> NativeDirectoryEntry | None:
    try:
        entries = directory.listEntries()
    except (OSError, UnicodeError) as exc:
        raise ObjectWriterRefused("object directory cannot be enumerated exactly") from exc
    requested = name.casefold().rstrip(" .")
    exact: list[NativeDirectoryEntry] = []
    for entry in entries:
        if entry.identity.is_reparse:
            raise ObjectWriterRefused("object directory contains a reparse entry")
        if entry.name == name:
            exact.append(entry)
            continue
        aliases = {entry.name.casefold().rstrip(" .")}
        if entry.short_name:
            aliases.add(entry.short_name.casefold().rstrip(" ."))
        if requested in aliases:
            raise ObjectWriterRefused("object path resolves through a filesystem alias")
    if len(exact) == 1:
        return exact[0]
    if len(exact) > 1:
        raise ObjectWriterRefused("object directory contains duplicate exact names")
    if required:
        raise ObjectWriterRefused(f"object path is missing: {name}")
    return None


def _safeDirectory(path: Path) -> Path:
    try:
        safe = assertNoReparsePath(path)
        safe.mkdir(parents=True, exist_ok=True)
        safe = assertNoReparsePath(safe)
        info = os.lstat(safe)
    except OSError as exc:
        raise ObjectWriterRefused("verification directory is unsafe") from exc
    if _isReparseStat(info) or not stat.S_ISDIR(info.st_mode):
        raise ObjectWriterRefused("verification directory is unsafe")
    return safe


def _createOrVerifyFile(path: Path, payload: bytes, *, label: str) -> None:
    try:
        exclusiveCreateBytes(path, payload)
        return
    except FileExistsError:
        pass
    except OSError as exc:
        raise ObjectWriterRefused(f"could not create exact {label}") from exc
    try:
        observed = readNoFollowBytes(path, max_bytes=max(1, len(payload)))
    except (OSError, ValueError) as exc:
        raise ObjectWriterRefused(f"existing {label} is not exact") from exc
    if observed != payload:
        raise ObjectWriterRefused(f"existing {label} collision")


def _verifyClosedFiles(root: Path, expected: dict[str, bytes]) -> None:
    expected_directories = {""}
    for relative in expected:
        parent = PurePosixPath(relative).parent
        while parent.as_posix() not in {"", "."}:
            expected_directories.add(parent.as_posix())
            parent = parent.parent
    actual_files: set[str] = set()
    actual_directories: set[str] = {""}
    stack = [root]
    root_device = os.lstat(root).st_dev
    while stack:
        directory = stack.pop()
        try:
            with os.scandir(directory) as stream:
                children = list(stream)
        except OSError as exc:
            raise ObjectWriterRefused("verification repository cannot be inspected") from exc
        for child in children:
            location = directory / child.name
            try:
                info = os.lstat(location)
            except OSError as exc:
                raise ObjectWriterRefused("verification repository entry raced") from exc
            if _isReparseStat(info) or info.st_dev != root_device:
                raise ObjectWriterRefused("verification repository contains an unsafe link")
            relative = location.relative_to(root).as_posix()
            if stat.S_ISDIR(info.st_mode):
                actual_directories.add(relative)
                stack.append(location)
                continue
            if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                raise ObjectWriterRefused(
                    "verification repository contains an unsupported or linked file"
                )
            payload = expected.get(relative)
            if payload is None:
                raise ObjectWriterRefused("verification repository contains unknown files")
            try:
                observed = readNoFollowBytes(location, max_bytes=max(1, len(payload)))
            except (OSError, ValueError) as exc:
                raise ObjectWriterRefused("verification repository file is not exact") from exc
            if observed != payload:
                raise ObjectWriterRefused("verification repository file collision")
            actual_files.add(relative)
    if actual_files != set(expected) or actual_directories != expected_directories:
        raise ObjectWriterRefused("verification repository closure is not exact")


def _safeAttributes(manifest: ObjectManifest) -> bytes:
    lines = ["* -filter -diff -merge -ident -working-tree-encoding"]
    for rule in manifest.attribute_rules:
        if (
            any(character.isspace() for character in rule.pattern)
            or "\\" in rule.pattern
            or rule.pattern.startswith(("!", "#"))
        ):
            raise ObjectWriterRefused("attribute pattern is not safely representable")
        lines.append(f"{rule.pattern} text eol=lf")
    return ("\n".join(lines) + "\n").encode("utf-8")


def _boundedDecompress(raw: bytes, *, max_output: int) -> bytes:
    if len(raw) > _MAX_LOOSE_BYTES:
        raise ObjectWriterRefused("loose object exceeds compressed-byte quota")
    decoder = zlib.decompressobj()
    try:
        output = decoder.decompress(raw, max_output + 1)
    except zlib.error as exc:
        raise ObjectWriterRefused("loose object has invalid zlib framing") from exc
    if len(output) > max_output or decoder.unconsumed_tail:
        raise ObjectWriterRefused("loose object exceeds decompressed-byte quota")
    if not decoder.eof or decoder.unused_data:
        raise ObjectWriterRefused("loose object has truncated or trailing compressed data")
    return output


def _identity(value: str, name: str) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{name} must be non-empty")
    if "<" in value or ">" in value or any(ord(character) < 32 for character in value):
        raise ValueError(f"{name} contains unsafe identity characters")
    return value


def _email(value: str, name: str) -> str:
    value = _identity(value, name)
    if "@" not in value or any(character.isspace() for character in value):
        raise ValueError(f"{name} must be a canonical email address")
    return value


@dataclass(frozen=True, kw_only=True)
class CommitMetadata:
    author_name: str
    author_email: str
    committer_name: str
    committer_email: str
    timestamp: int
    timezone: str
    message: str

    def __post_init__(self) -> None:
        _identity(self.author_name, "author_name")
        _email(self.author_email, "author_email")
        _identity(self.committer_name, "committer_name")
        _email(self.committer_email, "committer_email")
        if type(self.timestamp) is not int or self.timestamp < 0:
            raise ValueError("timestamp must be a non-negative integer")
        if not isinstance(self.timezone, str) or _TIMEZONE_RE.fullmatch(self.timezone) is None:
            raise ValueError("timezone must use signed HHMM form")
        hours = int(self.timezone[1:3])
        minutes = int(self.timezone[3:5])
        if hours > 14 or minutes > 59 or (hours == 14 and minutes != 0):
            raise ValueError("timezone is outside the closed UTC offset range")
        if not isinstance(self.message, str) or "\0" in self.message:
            raise ValueError("commit message must be NUL-free text")
        normalized = self.message.replace("\r\n", "\n").replace("\r", "\n")
        if not normalized.endswith("\n"):
            normalized += "\n"
        object.__setattr__(self, "message", normalized)


@dataclass(frozen=True, kw_only=True)
class ObjectRecord:
    object_type: str
    oid: str
    payload_sha256: str
    framed_object_sha256: str
    size: int

    def __post_init__(self) -> None:
        if self.object_type not in _OBJECT_TYPES:
            raise ValueError("object_type is outside the closed vocabulary")
        _requireOid(self.oid, "oid")
        _requireDigest(self.payload_sha256, "payload_sha256")
        _requireDigest(self.framed_object_sha256, "framed_object_sha256")
        if type(self.size) is not int or self.size < 0:
            raise ValueError("object size must be a non-negative integer")

    def toDict(self) -> dict[str, Any]:
        return {
            "object_type": self.object_type,
            "oid": self.oid,
            "payload_sha256": self.payload_sha256,
            "framed_object_sha256": self.framed_object_sha256,
            "size": self.size,
        }


