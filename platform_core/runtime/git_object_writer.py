@dataclass(frozen=True)
class _PreparedObject:
    record: ObjectRecord
    frame: bytes


class _TreeNode:
    def __init__(self) -> None:
        self.files: dict[str, ManifestEntry] = {}
        self.directories: dict[str, _TreeNode] = {}


class GitObjectWriter:
    """Build and install one deterministic external loose-object closure."""

    def __init__(
        self,
        *,
        object_root: str | Path,
        blob_root: str | Path,
        sha1dc_oracle: GitSha1dcOracle,
        sha1dc_evidence: Sha1dcEvidence,
        writer_version_digest: str,
        forbidden_roots: tuple[str | Path, ...] = (),
        canonical_object_verifier: Callable[[bytes, ObjectRecord], str] | None = None,
    ) -> None:
        _requireDigest(writer_version_digest, "writer_version_digest")
        try:
            self.object_root = assertNoReparsePath(object_root)
            self.blob_root = assertNoReparsePath(blob_root)
            forbidden = tuple(assertNoReparsePath(path) for path in forbidden_roots)
        except OSError as exc:
            raise ObjectWriterRefused("writer path traverses a reparse point") from exc
        if _pathOverlaps(self.object_root, self.blob_root):
            raise ObjectWriterRefused("object and blob roots must not overlap")
        for root in forbidden:
            if _pathOverlaps(self.object_root, root) or _pathOverlaps(self.blob_root, root):
                raise ObjectWriterRefused("writer roots overlap a forbidden repository root")
        if not isinstance(sha1dc_oracle, GitSha1dcOracle) or not isinstance(
            sha1dc_evidence, Sha1dcEvidence
        ):
            raise TypeError("writer requires the typed SHA1_DC oracle and evidence")
        if sha1dc_oracle.evidence != sha1dc_evidence:
            raise ObjectWriterRefused("SHA1_DC oracle and evidence do not match")
        if canonical_object_verifier is not None and not callable(
            canonical_object_verifier
        ):
            raise TypeError("canonical_object_verifier must be callable")
        self._oracle = sha1dc_oracle
        self._evidence = sha1dc_evidence
        self._writer_version_digest = writer_version_digest
        self._canonical_object_verifier = canonical_object_verifier

    @property
    def writer_version_digest(self) -> str:
        return self._writer_version_digest

    @property
    def sha1dcEvidence(self) -> Sha1dcEvidence:
        """Expose the immutable oracle evidence for external artifact binding."""

        return self._evidence

    def _prepareObject(
        self,
        object_type: str,
        payload: bytes,
        prepared: dict[str, _PreparedObject],
        *,
        expected_oid: str | None = None,
        expected_frame_digest: str | None = None,
    ) -> str:
        if len(payload) > _MAX_OBJECT_BYTES:
            raise ObjectWriterRefused("object payload exceeds byte quota")
        frame = _frame(object_type, payload)
        frame_digest = hashlib.sha256(frame).hexdigest()
        if expected_frame_digest is not None and frame_digest != expected_frame_digest:
            raise ObjectWriterRefused("blob framed-object digest does not match manifest")
        oid = self._oracle.hashObject(object_type, payload)
        if expected_oid is not None and oid != expected_oid:
            raise ObjectWriterRefused("blob object id does not match manifest")
        record = ObjectRecord(
            object_type=object_type,
            oid=oid,
            payload_sha256=hashlib.sha256(payload).hexdigest(),
            framed_object_sha256=frame_digest,
            size=len(payload),
        )
        existing = prepared.get(oid)
        if existing is not None and existing.frame != frame:
            raise ObjectWriterRefused("object-id collision maps to different framed bytes")
        prepared.setdefault(oid, _PreparedObject(record=record, frame=frame))
        return oid

    def _readBlobs(
        self,
        manifest: ObjectManifest,
        prepared: dict[str, _PreparedObject],
    ) -> _TreeNode:
        for entry in manifest.entries:
            if len(entry.blob_oid) != 40:
                raise ObjectWriterRefused("SHA-256 object manifests are not qualified")
            location = self.blob_root / entry.blob_sha256[:2] / entry.blob_sha256
            try:
                payload = readNoFollowBytes(location, max_bytes=entry.size)
            except (OSError, ValueError) as exc:
                raise ObjectWriterRefused("blob digest could not be proven from immutable storage") from exc
            if len(payload) != entry.size or hashlib.sha256(payload).hexdigest() != entry.blob_sha256:
                raise ObjectWriterRefused("blob digest does not match manifest")
            self._prepareObject(
                "blob",
                payload,
                prepared,
                expected_oid=entry.blob_oid,
                expected_frame_digest=entry.framed_object_sha256,
            )
        return self._treeFromManifest(manifest)

    @staticmethod
    def _treeFromManifest(manifest: ObjectManifest) -> _TreeNode:
        root = _TreeNode()
        for entry in manifest.entries:
            node = root
            parts = PurePosixPath(entry.path).parts
            for component in parts[:-1]:
                node = node.directories.setdefault(component, _TreeNode())
            node.files[parts[-1]] = entry
        return root

    def _prepareTree(
        self,
        node: _TreeNode,
        prepared: dict[str, _PreparedObject],
        *,
        path: str = "",
        tree_oids: dict[str, str] | None = None,
    ) -> str:
        children: list[tuple[bytes, bytes]] = []
        for name, entry in node.files.items():
            name_bytes = name.encode("utf-8")
            body = f"{entry.mode:o} ".encode("ascii") + name_bytes + b"\0" + bytes.fromhex(
                entry.blob_oid
            )
            children.append((name_bytes + b"\0", body))
        for name, child in node.directories.items():
            child_path = f"{path}/{name}" if path else name
            child_oid = self._prepareTree(
                child,
                prepared,
                path=child_path,
                tree_oids=tree_oids,
            )
            name_bytes = name.encode("utf-8")
            body = b"40000 " + name_bytes + b"\0" + bytes.fromhex(child_oid)
            children.append((name_bytes + b"/", body))
        payload = b"".join(body for _, body in sorted(children, key=lambda item: item[0]))
        oid = self._prepareObject("tree", payload, prepared)
        if tree_oids is not None:
            tree_oids[path] = oid
        return oid

    def planTreeOids(self, manifest: ObjectManifest) -> dict[str, str]:
        """Derive every manifest tree OID through the pinned SHA1_DC oracle."""

        if not isinstance(manifest, ObjectManifest):
            raise TypeError("tree planning requires a typed manifest")
        _preflightManifestClosure(manifest)
        prepared: dict[str, _PreparedObject] = {}
        tree_oids: dict[str, str] = {}
        self._prepareTree(
            self._treeFromManifest(manifest),
            prepared,
            tree_oids=tree_oids,
        )
        return dict(sorted(tree_oids.items()))

    def _prepareCommit(
        self,
        *,
        tree_oid: str,
        parent_oid: str,
        metadata: CommitMetadata,
        prepared: dict[str, _PreparedObject],
    ) -> str:
        author = (
            f"{metadata.author_name} <{metadata.author_email}> "
            f"{metadata.timestamp} {metadata.timezone}"
        )
        committer = (
            f"{metadata.committer_name} <{metadata.committer_email}> "
            f"{metadata.timestamp} {metadata.timezone}"
        )
        payload = (
            f"tree {tree_oid}\nparent {parent_oid}\nauthor {author}\n"
            f"committer {committer}\n\n{metadata.message}"
        ).encode("utf-8")
        return self._prepareObject("commit", payload, prepared)

    def _existingMatches(self, path: Path, prepared: _PreparedObject) -> bool:
        compressed = zlib.compress(prepared.frame, level=9)
        try:
            raw = readNoFollowBytes(path, max_bytes=max(1, len(compressed)))
            observed = _boundedDecompress(raw, max_output=len(prepared.frame))
        except (OSError, ValueError, ObjectWriterRefused) as exc:
            raise ObjectWriterRefused("existing loose object is not exact immutable evidence") from exc
        if observed != prepared.frame:
            raise ObjectWriterRefused("existing loose object differs from proposed object")
        return True

    def _installAt(
        self,
        root: Path,
        prepared: tuple[_PreparedObject, ...],
        *,
        collision_label: str,
    ) -> tuple[tuple[str, ...], tuple[str, ...]]:
        collision_text = (
            "existing loose object in external store"
            if collision_label == "external"
            else f"existing {collision_label} loose object"
        )
        missing: list[tuple[Path, bytes, _PreparedObject]] = []
        reused: list[str] = []
        for item in prepared:
            path = root / item.record.oid[:2] / item.record.oid[2:]
            compressed = zlib.compress(item.frame, level=9)
            if path.exists():
                try:
                    self._existingMatches(path, item)
                except ObjectWriterRefused as exc:
                    raise ObjectWriterRefused(f"{collision_text} is not exact") from exc
                reused.append(item.record.oid)
            else:
                missing.append((path, compressed, item))
        installed: list[str] = []
        for path, compressed, item in missing:
            try:
                assertNoReparsePath(path)
                exclusiveCreateBytes(path, compressed)
                installed.append(item.record.oid)
            except FileExistsError:
                try:
                    self._existingMatches(path, item)
                except ObjectWriterRefused as exc:
                    raise ObjectWriterRefused(f"{collision_text} is not exact") from exc
                reused.append(item.record.oid)
            except OSError as exc:
                raise ObjectWriterRefused("could not create immutable loose object") from exc
        return tuple(sorted(installed)), tuple(sorted(reused))

    def _existingMatchesAt(
        self,
        directory: NativeDirectoryHandle,
        name: str,
        prepared: _PreparedObject,
        identity: NativeFileIdentity,
    ) -> str:
        verifier = self._canonical_object_verifier
        if verifier is None:
            raise ObjectWriterRefused(
                "existing canonical loose object requires contained proof"
            )
        try:
            raw = directory.readFile(
                name,
                max_bytes=_MAX_LOOSE_BYTES,
                expected=identity,
            )
            receipt_id = verifier(raw, prepared.record)
            _requireDigest(receipt_id, "canonical loose-object proof receipt")
        except Exception as exc:
            raise ObjectWriterRefused(
                "existing canonical loose object is not exact"
            ) from exc
        return receipt_id

    def _installAtHandle(
        self,
        root: NativeDirectoryHandle,
        prepared: tuple[_PreparedObject, ...],
    ) -> tuple[
        tuple[str, ...],
        tuple[str, ...],
        tuple[tuple[str, str], ...],
    ]:
        installed: list[str] = []
        reused: list[str] = []
        reuse_proofs: list[tuple[str, str]] = []
        root_identity = root.identity
        for item in prepared:
            prefix = item.record.oid[:2]
            leaf = item.record.oid[2:]
            prefix_entry = _nativeEntry(root, prefix, required=False)
            try:
                fanout = (
                    root.createDirectory(prefix)
                    if prefix_entry is None
                    else root.openDirectory(prefix, expected=prefix_entry.identity)
                )
            except OSError as exc:
                raise ObjectWriterRefused(
                    "canonical object fanout is not an exact directory"
                ) from exc
            with fanout:
                if (
                    fanout.identity.volume_id != root_identity.volume_id
                    or fanout.identity.mount_id != root_identity.mount_id
                ):
                    raise ObjectWriterRefused(
                        "canonical object fanout crosses the object-root volume"
                    )
                target = _nativeEntry(fanout, leaf, required=False)
                if target is not None:
                    if (
                        target.identity.volume_id != root_identity.volume_id
                        or target.identity.mount_id != root_identity.mount_id
                    ):
                        raise ObjectWriterRefused(
                            "canonical loose object crosses the object-root volume"
                        )
                    proof_id = self._existingMatchesAt(
                        fanout,
                        leaf,
                        item,
                        target.identity,
                    )
                    reused.append(item.record.oid)
                    reuse_proofs.append((item.record.oid, proof_id))
                    continue
                compressed = zlib.compress(item.frame, level=9)
                try:
                    installed_identity = fanout.createFile(leaf, compressed)
                    if (
                        installed_identity.volume_id != root_identity.volume_id
                        or installed_identity.mount_id != root_identity.mount_id
                    ):
                        raise ObjectWriterRefused(
                            "canonical loose object crosses the object-root volume"
                        )
                    installed.append(item.record.oid)
                except FileExistsError:
                    raced = _nativeEntry(fanout, leaf)
                    if raced is None:
                        raise ObjectWriterRefused(
                            "canonical loose-object publication raced disappearance"
                        )
                    proof_id = self._existingMatchesAt(
                        fanout,
                        leaf,
                        item,
                        raced.identity,
                    )
                    reused.append(item.record.oid)
                    reuse_proofs.append((item.record.oid, proof_id))
                except OSError as exc:
                    raise ObjectWriterRefused(
                        "could not create immutable canonical loose object"
                    ) from exc
        if not _sameNativeObject(root.identity, root_identity):
            raise ObjectWriterRefused(
                "canonical object-root identity drifted during installation"
            )
        return (
            tuple(sorted(installed)),
            tuple(sorted(reused)),
            tuple(sorted(reuse_proofs)),
        )

    def _install(self, prepared: tuple[_PreparedObject, ...]) -> None:
        self._installAt(self.object_root, prepared, collision_label="external")

    def _planRevision(
        self,
        *,
        manifest: ObjectManifest,
        metadata: CommitMetadata,
    ) -> tuple[ObjectWriteReceipt, tuple[_PreparedObject, ...]]:
        if not isinstance(manifest, ObjectManifest) or not isinstance(metadata, CommitMetadata):
            raise TypeError("writer requires typed manifest and commit metadata")
        _requireOid(manifest.expected_revision, "expected_revision")
        _preflightManifestClosure(manifest)
        prepared: dict[str, _PreparedObject] = {}
        tree = self._readBlobs(manifest, prepared)
        tree_oid = self._prepareTree(tree, prepared)
        commit_oid = self._prepareCommit(
            tree_oid=tree_oid,
            parent_oid=manifest.expected_revision,
            metadata=metadata,
            prepared=prepared,
        )
        ordered = tuple(prepared[oid] for oid in sorted(prepared))
        if len(ordered) > _MAX_CLOSURE_OBJECTS:
            raise ObjectWriterRefused("object closure exceeds object-count quota")
        if sum(len(item.frame) for item in ordered) > _MAX_CLOSURE_BYTES:
            raise ObjectWriterRefused("object closure exceeds aggregate object-byte quota")
        closure_digest = canonical_digest([item.record.toDict() for item in ordered])
        proposed_index_digest = hashlib.sha256(GitIndex.build(manifest)).hexdigest()
        receipt = ObjectWriteReceipt(
            parent_oid=manifest.expected_revision,
            tree_oid=tree_oid,
            commit_oid=commit_oid,
            objects=tuple(item.record for item in ordered),
            object_closure_digest=closure_digest,
            proposed_index_digest=proposed_index_digest,
            manifest_digest=manifest.manifest_digest,
            writer_version_digest=self._writer_version_digest,
            sha1dc_evidence_digest=canonical_digest(self._evidence.toDict()),
        )
        return receipt, ordered

    def planRevision(
        self,
        *,
        manifest: ObjectManifest,
        metadata: CommitMetadata,
    ) -> ObjectWriteReceipt:
        """Derive exact object truth without creating or repairing any artifact."""

        receipt, _ = self._planRevision(manifest=manifest, metadata=metadata)
        return receipt

    def writeRevision(
        self,
        *,
        manifest: ObjectManifest,
        metadata: CommitMetadata,
    ) -> ObjectWriteReceipt:
        receipt, ordered = self._planRevision(manifest=manifest, metadata=metadata)
        self._install(ordered)
        # Keep opaque controller-generated payloads content-addressed alongside
        # ordinary blobs.  A source-clone builder can reconstruct loose objects
        # from typed parser records without interpreting compressed Git bytes.
        for item in ordered:
            payload = item.frame[item.frame.index(b"\0") + 1 :]
            location = (
                self.blob_root
                / item.record.payload_sha256[:2]
                / item.record.payload_sha256
            )
            _safeDirectory(location.parent)
            _createOrVerifyFile(location, payload, label="object payload")
        return receipt

    def _validatedReceiptObjects(
        self,
        receipt: ObjectWriteReceipt,
    ) -> tuple[_PreparedObject, ...]:
        if not isinstance(receipt, ObjectWriteReceipt):
            raise TypeError("receipt must be ObjectWriteReceipt")
        if len(receipt.objects) > _MAX_CLOSURE_OBJECTS:
            raise ObjectWriterRefused("receipt exceeds object-count quota")
        if sum(record.size for record in receipt.objects) > _MAX_CLOSURE_BYTES:
            raise ObjectWriterRefused("receipt exceeds aggregate object-byte quota")
        evidence_digest = canonical_digest(self._evidence.toDict())
        if (
            receipt.writer_version_digest != self._writer_version_digest
            or receipt.sha1dc_evidence_digest != evidence_digest
            or tuple(sorted(record.oid for record in receipt.objects))
            != tuple(record.oid for record in receipt.objects)
            or len({record.oid for record in receipt.objects}) != len(receipt.objects)
            or canonical_digest([record.toDict() for record in receipt.objects])
            != receipt.object_closure_digest
        ):
            raise ObjectWriterRefused("object-write receipt is not bound to this writer closure")
        prepared: list[_PreparedObject] = []
        for record in receipt.objects:
            try:
                object_type, payload = readLooseObject(
                    self.object_root,
                    record.oid,
                    sha1dc_oracle=self._oracle,
                )
            except ObjectWriterRefused as exc:
                raise ObjectWriterRefused(
                    "external loose-object closure is incomplete"
                ) from exc
            frame = _frame(object_type, payload)
            if (
                object_type != record.object_type
                or len(payload) != record.size
                or hashlib.sha256(payload).hexdigest() != record.payload_sha256
                or hashlib.sha256(frame).hexdigest() != record.framed_object_sha256
                or self._oracle.hashObject(object_type, payload) != record.oid
            ):
                raise ObjectWriterRefused("external loose-object closure drifted")
            prepared.append(_PreparedObject(record=record, frame=frame))
        if (
            not any(
                item.record.oid == receipt.tree_oid
                and item.record.object_type == "tree"
                for item in prepared
            )
            or not any(
                item.record.oid == receipt.commit_oid
                and item.record.object_type == "commit"
                for item in prepared
            )
        ):
            raise ObjectWriterRefused("receipt does not contain its proposed tree and commit")
        return tuple(prepared)

    def _validatedSourceObjects(
        self,
        closure: SourceObjectClosure,
        manifest: ObjectManifest,
    ) -> tuple[_PreparedObject, ...]:
        if not isinstance(closure, SourceObjectClosure) or not isinstance(
            manifest,
            ObjectManifest,
        ):
            raise TypeError("candidate source requires typed closure and manifest")
        if (
            closure.revision != manifest.expected_revision
            or closure.manifest_digest != manifest.manifest_digest
        ):
            raise ObjectWriterRefused("source closure differs from its inert manifest")
        _preflightManifestClosure(manifest)
        if len(closure.objects) > _MAX_CLOSURE_OBJECTS:
            raise ObjectWriterRefused("source closure exceeds object-count quota")
        if sum(record.size for record in closure.objects) > _MAX_CLOSURE_BYTES:
            raise ObjectWriterRefused(
                "source closure exceeds aggregate object-byte quota"
            )
        by_oid = {record.oid: record for record in closure.objects}
        for entry in manifest.entries:
            record = by_oid.get(entry.blob_oid)
            if (
                record is None
                or record.object_type != "blob"
                or record.payload_sha256 != entry.blob_sha256
                or record.framed_object_sha256 != entry.framed_object_sha256
                or record.size != entry.size
            ):
                raise ObjectWriterRefused(
                    "source closure does not contain every exact manifest blob"
                )
        prepared: list[_PreparedObject] = []
        payload_root = Path(closure.payload_root)
        expected_payloads: dict[str, bytes] = {}
        for record in closure.objects:
            location = payload_root / record.payload_sha256[:2] / record.payload_sha256
            try:
                payload = readNoFollowBytes(location, max_bytes=max(1, record.size))
            except (OSError, ValueError) as exc:
                raise ObjectWriterRefused(
                    "source parser payload is unavailable or unsafe"
                ) from exc
            frame = _frame(record.object_type, payload)
            if (
                len(payload) != record.size
                or hashlib.sha256(payload).hexdigest() != record.payload_sha256
                or hashlib.sha256(frame).hexdigest() != record.framed_object_sha256
                or self._oracle.hashObject(record.object_type, payload) != record.oid
            ):
                raise ObjectWriterRefused("source object closure drifted")
            prepared.append(_PreparedObject(record=record, frame=frame))
            expected_payloads[
                f"{record.payload_sha256[:2]}/{record.payload_sha256}"
            ] = payload
        _verifyClosedFiles(payload_root, expected_payloads)
        return tuple(prepared)

    def createCandidateRepository(
        self,
        *,
        transaction_id: str,
        checkout_root: str | Path,
        candidate_branch: str,
        manifest: ObjectManifest,
        closure: SourceObjectClosure,
        forbidden_roots: tuple[str | Path, ...] = (),
    ) -> CandidateRepositoryLease:
        """Materialize one exact private candidate without Git clone/checkout."""

        if (
            not isinstance(transaction_id, str)
            or _TRANSACTION_RE.fullmatch(transaction_id) is None
        ):
            raise ValueError("transaction_id is not filesystem-safe")
        expected_branch = f"refs/heads/9to5/candidates/{transaction_id}"
        if candidate_branch != expected_branch:
            raise ObjectWriterRefused("candidate branch is outside its transaction namespace")
        checkout_input = Path(checkout_root)
        if not checkout_input.is_absolute():
            raise ObjectWriterRefused("candidate checkout root must be absolute")
        try:
            checkout = assertNoReparsePath(checkout_input)
            forbidden = tuple(assertNoReparsePath(path) for path in forbidden_roots)
        except OSError as exc:
            raise ObjectWriterRefused("candidate repository path is unsafe") from exc
        for source in (
            self.object_root,
            self.blob_root,
            Path(closure.payload_root),
            *forbidden,
        ):
            if _pathOverlaps(checkout, source):
                raise ObjectWriterRefused(
                    "candidate repository overlaps source or forbidden storage"
                )
        prepared = self._validatedSourceObjects(closure, manifest)
        index = GitIndex.build(manifest)
        index_digest = hashlib.sha256(index).hexdigest()
        files: dict[str, bytes] = {
            ".git/config": (
                b"[core]\n"
                b"\trepositoryformatversion = 0\n"
                b"\tbare = false\n"
                b"\tfilemode = false\n"
                b"\tsymlinks = false\n"
                b"\tautocrlf = false\n"
                b"\tsafecrlf = true\n"
                b"\tlogallrefupdates = false\n"
            ),
            ".git/HEAD": f"ref: {candidate_branch}\n".encode("ascii"),
            f".git/{candidate_branch}": f"{closure.revision}\n".encode("ascii"),
            ".git/shallow": f"{closure.revision}\n".encode("ascii"),
            ".git/index": index,
            ".git/info/attributes": _safeAttributes(manifest),
        }
        for item in prepared:
            files[f".git/objects/{item.record.oid[:2]}/{item.record.oid[2:]}"] = (
                zlib.compress(item.frame, level=9)
            )
        worktree_modes: dict[str, int] = {}
        for entry in manifest.entries:
            location = (
                Path(closure.payload_root)
                / entry.blob_sha256[:2]
                / entry.blob_sha256
            )
            try:
                payload = readNoFollowBytes(location, max_bytes=entry.size)
            except (OSError, ValueError) as exc:
                raise ObjectWriterRefused(
                    "source manifest blob cannot seed the candidate worktree"
                ) from exc
            if (
                len(payload) != entry.size
                or hashlib.sha256(payload).hexdigest() != entry.blob_sha256
            ):
                raise ObjectWriterRefused("source manifest blob drifted")
            files[entry.path] = payload
            worktree_modes[entry.path] = entry.mode
        _safeDirectory(checkout)
        for relative in sorted(files, key=lambda value: value.encode("utf-8")):
            target = checkout.joinpath(*PurePosixPath(relative).parts)
            _safeDirectory(target.parent)
            _createOrVerifyFile(
                target,
                files[relative],
                label="candidate repository file",
            )
            mode = worktree_modes.get(relative)
            if mode is not None:
                try:
                    os.chmod(target, 0o755 if mode == 0o100755 else 0o644)
                except OSError as exc:
                    raise ObjectWriterRefused(
                        "candidate worktree mode could not be applied"
                    ) from exc
        _verifyClosedFiles(checkout, files)
        return CandidateRepositoryLease(
            transaction_id=transaction_id,
            checkout_path=str(checkout),
            git_dir=str(checkout / ".git"),
            base_revision=closure.revision,
            base_tree=closure.tree_oid,
            candidate_branch=candidate_branch,
            repository_id=closure.repository_id,
            manifest_digest=manifest.manifest_digest,
            object_closure_digest=closure.object_closure_digest,
            index_digest=index_digest,
            shallow_root_revision=closure.revision,
        )

    def createVerificationRepository(
        self,
        *,
        transaction_id: str,
        checkout_root: str | Path,
        manifest: ObjectManifest,
        receipt: ObjectWriteReceipt,
        forbidden_roots: tuple[str | Path, ...] = (),
    ) -> VerificationRepositoryLease:
        """Create one no-checkout repository from the sealed controller closure."""

        if (
            not isinstance(transaction_id, str)
            or _TRANSACTION_RE.fullmatch(transaction_id) is None
        ):
            raise ValueError("transaction_id is not filesystem-safe")
        if not isinstance(manifest, ObjectManifest):
            raise TypeError("manifest must be ObjectManifest")
        checkout_input = Path(checkout_root)
        if not checkout_input.is_absolute():
            raise ObjectWriterRefused("verification checkout root must be absolute")
        try:
            checkout = assertNoReparsePath(checkout_input)
            forbidden = tuple(assertNoReparsePath(path) for path in forbidden_roots)
        except OSError as exc:
            raise ObjectWriterRefused("verification repository path is unsafe") from exc
        for source in (self.object_root, self.blob_root, *forbidden):
            if _pathOverlaps(checkout, source):
                raise ObjectWriterRefused(
                    "verification repository overlaps source or forbidden storage"
                )
        prepared = self._validatedReceiptObjects(receipt)
        index = GitIndex.build(manifest)
        index_digest = hashlib.sha256(index).hexdigest()
        if (
            receipt.parent_oid != manifest.expected_revision
            or receipt.manifest_digest != manifest.manifest_digest
            or receipt.proposed_index_digest != index_digest
        ):
            raise ObjectWriterRefused(
                "verification manifest differs from the object-write receipt"
            )
        branch = f"refs/heads/9to5/verification/{transaction_id}"
        files: dict[str, bytes] = {
            ".git/config": (
                b"[core]\n"
                b"\trepositoryformatversion = 0\n"
                b"\tbare = false\n"
                b"\tfilemode = true\n"
                b"\tsymlinks = false\n"
                b"\tlogallrefupdates = false\n"
            ),
            ".git/HEAD": f"ref: {branch}\n".encode("ascii"),
            f".git/{branch}": f"{receipt.commit_oid}\n".encode("ascii"),
            ".git/shallow": f"{receipt.commit_oid}\n".encode("ascii"),
            ".git/index": index,
        }
        for item in prepared:
            files[f".git/objects/{item.record.oid[:2]}/{item.record.oid[2:]}"] = (
                zlib.compress(item.frame, level=9)
            )
        _safeDirectory(checkout)
        for relative in sorted(files, key=lambda value: value.encode("utf-8")):
            target = checkout.joinpath(*PurePosixPath(relative).parts)
            _safeDirectory(target.parent)
            _createOrVerifyFile(
                target,
                files[relative],
                label="verification repository file",
            )
        _verifyClosedFiles(checkout, files)
        return VerificationRepositoryLease(
            transaction_id=transaction_id,
            checkout_path=str(checkout),
            git_dir=str(checkout / ".git"),
            proposed_revision=receipt.commit_oid,
            proposed_tree=receipt.tree_oid,
            manifest_digest=manifest.manifest_digest,
            object_closure_digest=receipt.object_closure_digest,
            proposed_index_digest=index_digest,
            shallow_root_revision=receipt.commit_oid,
            verification_branch=branch,
            runtime_token=object(),
        )

    def installClosureIntoCanonical(
        self,
        *,
        receipt: ObjectWriteReceipt,
        attestation: CanonicalRepositoryAttestation,
        failpoint: Callable[[str], None] | None = None,
    ) -> ObjectInstallationReceipt:
        """Create-only install an already-validated closure before any ref names it."""

        if not isinstance(receipt, ObjectWriteReceipt) or not isinstance(
            attestation, CanonicalRepositoryAttestation
        ):
            raise TypeError("canonical installation requires typed receipt and attestation")
        live = attestCanonicalRepository(attestation.canonical_root)
        if live != attestation:
            raise ObjectWriterRefused("canonical repository attestation drifted")
        if live.object_format != "sha1" or live.oid_length != 40:
            raise ObjectWriterRefused("canonical object format is unsupported")
        prepared = self._validatedReceiptObjects(receipt)
        target = Path(live.git_common_dir) / "objects"
        try:
            target = assertNoReparsePath(target)
        except OSError as exc:
            raise ObjectWriterRefused("canonical object root traverses a reparse point") from exc
        if _pathOverlaps(target, self.object_root) or _pathOverlaps(target, self.blob_root):
            raise ObjectWriterRefused("canonical and external object roots must not overlap")
        try:
            with openNativeDirectory(live.git_common_dir) as common:
                common_identity = common.identity
                common_digest = canonical_digest(
                    {
                        "path": os.path.normcase(str(Path(live.git_common_dir))),
                        "device": common_identity.volume_id,
                        "mount_id": common_identity.mount_id,
                        "inode": common_identity.file_id,
                        "reparse_tag": common_identity.reparse_tag,
                    }
                )
                if common_digest != live.git_common_identity_digest:
                    raise ObjectWriterRefused(
                        "canonical Git common identity differs from attestation"
                    )
                objects_entry = _nativeEntry(common, "objects")
                if objects_entry is None:
                    raise ObjectWriterRefused("canonical object root is missing")
                with common.openDirectory(
                    "objects",
                    expected=objects_entry.identity,
                ) as objects:
                    object_identity = objects.identity
                    if failpoint is not None:
                        failpoint("after_object_root_open")

                    def assert_visible() -> None:
                        try:
                            with openNativeDirectory(target) as visible:
                                visible_identity = visible.identity
                        except OSError as exc:
                            raise ObjectWriterRefused(
                                "canonical object-root identity drifted"
                            ) from exc
                        if not _sameNativeObject(visible_identity, object_identity):
                            raise ObjectWriterRefused(
                                "canonical object-root identity drifted"
                            )

                    assert_visible()
                    installed, reused, reuse_proofs = self._installAtHandle(
                        objects,
                        prepared,
                    )
                    assert_visible()
                    if not _sameNativeObject(common.identity, common_identity):
                        raise ObjectWriterRefused(
                            "canonical Git common identity drifted"
                        )
        except ObjectWriterRefused:
            raise
        except OSError as exc:
            raise ObjectWriterRefused(
                "canonical object store could not be opened exactly"
            ) from exc
        return ObjectInstallationReceipt(
            canonical_attestation_digest=live.attestation_digest,
            object_closure_digest=receipt.object_closure_digest,
            target_root_digest=canonical_digest(
                {
                    "repository_id": live.repository_id,
                    "object_root": str(target),
                }
            ),
            installed_oids=installed,
            reused_oids=reused,
            reuse_proof_receipts=reuse_proofs,
        )

    def proveClosureInCanonical(
        self,
        *,
        receipt: ObjectWriteReceipt,
        attestation: CanonicalRepositoryAttestation,
    ) -> ObjectInstallationReceipt:
        """Read-only proof that every validated object remains canonical."""

        if not isinstance(receipt, ObjectWriteReceipt) or not isinstance(
            attestation, CanonicalRepositoryAttestation
        ):
            raise TypeError("canonical proof requires typed receipt and attestation")
        live = attestCanonicalRepository(attestation.canonical_root)
        if live != attestation:
            raise ObjectWriterRefused("canonical repository attestation drifted")
        if live.object_format != "sha1" or live.oid_length != 40:
            raise ObjectWriterRefused("canonical object format is unsupported")
        prepared = self._validatedReceiptObjects(receipt)
        target = Path(live.git_common_dir) / "objects"
        try:
            target = assertNoReparsePath(target)
        except OSError as exc:
            raise ObjectWriterRefused(
                "canonical object root traverses a reparse point"
            ) from exc
        if _pathOverlaps(target, self.object_root) or _pathOverlaps(
            target, self.blob_root
        ):
            raise ObjectWriterRefused(
                "canonical and external object roots must not overlap"
            )
        proofs: list[tuple[str, str]] = []
        try:
            with openNativeDirectory(live.git_common_dir) as common:
                common_identity = common.identity
                common_digest = canonical_digest(
                    {
                        "path": os.path.normcase(str(Path(live.git_common_dir))),
                        "device": common_identity.volume_id,
                        "mount_id": common_identity.mount_id,
                        "inode": common_identity.file_id,
                        "reparse_tag": common_identity.reparse_tag,
                    }
                )
                if common_digest != live.git_common_identity_digest:
                    raise ObjectWriterRefused(
                        "canonical Git common identity differs from attestation"
                    )
                objects_entry = _nativeEntry(common, "objects")
                if objects_entry is None:
                    raise ObjectWriterRefused("canonical object root is missing")
                with common.openDirectory(
                    "objects",
                    expected=objects_entry.identity,
                ) as objects:
                    object_identity = objects.identity

                    def assert_visible() -> None:
                        try:
                            with openNativeDirectory(target) as visible:
                                visible_identity = visible.identity
                        except OSError as exc:
                            raise ObjectWriterRefused(
                                "canonical object-root identity drifted"
                            ) from exc
                        if not _sameNativeObject(visible_identity, object_identity):
                            raise ObjectWriterRefused(
                                "canonical object-root identity drifted"
                            )

                    assert_visible()
                    for item in prepared:
                        prefix = item.record.oid[:2]
                        leaf = item.record.oid[2:]
                        prefix_entry = _nativeEntry(objects, prefix, required=False)
                        if prefix_entry is None:
                            raise ObjectWriterRefused(
                                "canonical loose-object fanout is missing"
                            )
                        try:
                            fanout = objects.openDirectory(
                                prefix,
                                expected=prefix_entry.identity,
                            )
                        except OSError as exc:
                            raise ObjectWriterRefused(
                                "canonical object fanout is not an exact directory"
                            ) from exc
                        with fanout:
                            existing = _nativeEntry(fanout, leaf, required=False)
                            if existing is None:
                                raise ObjectWriterRefused(
                                    "canonical loose object is missing"
                                )
                            proof_id = self._existingMatchesAt(
                                fanout,
                                leaf,
                                item,
                                existing.identity,
                            )
                            proofs.append((item.record.oid, proof_id))
                    assert_visible()
                    if not _sameNativeObject(objects.identity, object_identity):
                        raise ObjectWriterRefused(
                            "canonical object-root identity drifted during proof"
                        )
                    if not _sameNativeObject(common.identity, common_identity):
                        raise ObjectWriterRefused(
                            "canonical Git common identity drifted"
                        )
        except ObjectWriterRefused:
            raise
        except OSError as exc:
            raise ObjectWriterRefused(
                "canonical object store could not be opened exactly"
            ) from exc
        reused = tuple(sorted(item.record.oid for item in prepared))
        return ObjectInstallationReceipt(
            canonical_attestation_digest=live.attestation_digest,
            object_closure_digest=receipt.object_closure_digest,
            target_root_digest=canonical_digest(
                {
                    "repository_id": live.repository_id,
                    "object_root": str(target),
                }
            ),
            installed_oids=(),
            reused_oids=reused,
            reuse_proof_receipts=tuple(sorted(proofs)),
        )


def readLooseObject(
    object_root: str | Path,
    oid: str,
    *,
    sha1dc_oracle: GitSha1dcOracle,
) -> tuple[str, bytes]:
    """Read and structurally validate one bounded loose object (never authority)."""

    _requireOid(oid, "oid")
    if not isinstance(sha1dc_oracle, GitSha1dcOracle):
        raise TypeError("loose-object validation requires the typed SHA1DC oracle")
    try:
        root = assertNoReparsePath(object_root)
        raw = readNoFollowBytes(root / oid[:2] / oid[2:], max_bytes=_MAX_LOOSE_BYTES)
    except (OSError, ValueError) as exc:
        raise ObjectWriterRefused("loose object is not a bounded no-follow file") from exc
    frame = _boundedDecompress(raw, max_output=_MAX_OBJECT_BYTES + 64)
    nul = frame.find(b"\0")
    if nul < 0:
        raise ObjectWriterRefused("loose object header is truncated")
    header = frame[:nul]
    try:
        object_type_raw, size_raw = header.split(b" ", 1)
        object_type = object_type_raw.decode("ascii")
        size_text = size_raw.decode("ascii")
        size = int(size_text)
    except (ValueError, UnicodeDecodeError) as exc:
        raise ObjectWriterRefused("loose object header is noncanonical") from exc
    if object_type not in _OBJECT_TYPES or str(size) != size_text or size < 0:
        raise ObjectWriterRefused("loose object header is outside the closed format")
    payload = frame[nul + 1 :]
    if len(payload) != size:
        raise ObjectWriterRefused("loose object payload size does not match header")
    observed_oid = sha1dc_oracle.hashObject(object_type, payload)
    if observed_oid != oid:
        raise ObjectWriterRefused("loose object does not match its requested id")
    return object_type, payload


