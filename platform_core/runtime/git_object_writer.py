"""Deterministic, memory-safe construction of an inert loose-object closure.

The writer accepts only a validated :class:`ObjectManifest`, reads immutable blobs
from the external controller domain, and asks a pinned repo-less SHA1_DC oracle for
object identifiers.  It never reads repository configuration, invokes a Git write
command, or updates a ref.  Its sole target-repository mutation is a retained-handle,
create-only install of already validated loose objects; it never changes canonical
refs, the index, or working-tree paths.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ObjectWriterRefused  -- The requested object closure was not safe and exact.
  CommitMetadata
  ObjectRecord
  ObjectWriteReceipt
  ObjectInstallationReceipt
  VerificationRepositoryLease
  SourceObjectClosure  -- Contained-parser proof for one exact, intentionally shallow source root.
  CandidateRepositoryLease
  GitObjectWriter  -- Build and install one deterministic external loose-object closure.
  readLooseObject(object_root: str | Path, oid: str, *, sha1dc_oracle: GitSha1dcOracle) -> tuple[str, bytes]  -- Read and structurally validate one bounded loose object (never authority).
DEPENDS-ON: platform_core.core.fsio, platform_core.core.galaxy_evidence, platform_core.runtime.canonical_repo, platform_core.runtime.git_index, platform_core.runtime.object_manifest, platform_core.runtime.sha1dc
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_git_object_writer.py
"""
