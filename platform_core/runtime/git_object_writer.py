@dataclass(frozen=True, kw_only=True)
class ObjectInstallationReceipt:
    canonical_attestation_digest: str
    object_closure_digest: str
    target_root_digest: str
    installed_oids: tuple[str, ...]
    reused_oids: tuple[str, ...]
    reuse_proof_receipts: tuple[tuple[str, str], ...]

    def __post_init__(self) -> None:
        for name in (
            "canonical_attestation_digest",
            "object_closure_digest",
            "target_root_digest",
        ):
            _requireDigest(getattr(self, name), name)
        if (
            not isinstance(self.installed_oids, tuple)
            or not isinstance(self.reused_oids, tuple)
            or not isinstance(self.reuse_proof_receipts, tuple)
        ):
            raise TypeError("installation OID sets must be immutable tuples")
        all_oids = self.installed_oids + self.reused_oids
        if len(all_oids) != len(set(all_oids)):
            raise ValueError("an object cannot be both installed and reused")
        for oid in all_oids:
            _requireOid(oid, "installed object id")
        proof_oids: list[str] = []
        for pair in self.reuse_proof_receipts:
            if not isinstance(pair, tuple) or len(pair) != 2:
                raise TypeError("reuse proof records must be immutable pairs")
            oid, receipt_id = pair
            _requireOid(oid, "reused object id")
            _requireDigest(receipt_id, "reuse proof receipt id")
            proof_oids.append(oid)
        if tuple(proof_oids) != self.reused_oids:
            raise ValueError("every reused object requires one ordered contained proof")


@dataclass(frozen=True, kw_only=True)
class VerificationRepositoryLease:
    transaction_id: str
    checkout_path: str
    git_dir: str
    proposed_revision: str
    proposed_tree: str
    manifest_digest: str
    object_closure_digest: str
    proposed_index_digest: str
    shallow_root_revision: str
    verification_branch: str
    runtime_token: object = field(repr=False, compare=False)

    def __post_init__(self) -> None:
        if (
            not isinstance(self.transaction_id, str)
            or _TRANSACTION_RE.fullmatch(self.transaction_id) is None
        ):
            raise ValueError("transaction_id is not filesystem-safe")
        checkout = Path(self.checkout_path)
        git_dir = Path(self.git_dir)
        if not checkout.is_absolute() or not git_dir.is_absolute():
            raise ValueError("verification repository paths must be absolute")
        if git_dir != checkout / ".git":
            raise ValueError("verification Git directory must be embedded")
        for name in ("proposed_revision", "proposed_tree", "shallow_root_revision"):
            _requireOid(getattr(self, name), name)
        if self.shallow_root_revision != self.proposed_revision:
            raise ValueError("verification shallow root must equal proposed revision")
        for name in (
            "manifest_digest",
            "object_closure_digest",
            "proposed_index_digest",
        ):
            _requireDigest(getattr(self, name), name)
        expected = f"refs/heads/9to5/verification/{self.transaction_id}"
        if self.verification_branch != expected:
            raise ValueError(f"verification_branch must be {expected}")
        if self.runtime_token is None:
            raise ValueError("verification repository requires a process-local token")


@dataclass(frozen=True, kw_only=True)
class SourceObjectClosure:
    """Contained-parser proof for one exact, intentionally shallow source root."""

    repository_id: str
    revision: str
    tree_oid: str
    manifest_digest: str
    object_closure_digest: str
    source_snapshot_digest: str
    parser_receipt_id: str
    parser_image_digest: str
    parser_runtime_digest: str
    parser_security_profile_digest: str
    payload_root: str
    objects: tuple[ObjectRecord, ...]
    intentional_shallow: bool
    parser_network_allowed: bool

    def __post_init__(self) -> None:
        for name in (
            "repository_id",
            "manifest_digest",
            "object_closure_digest",
            "source_snapshot_digest",
            "parser_receipt_id",
            "parser_image_digest",
            "parser_runtime_digest",
            "parser_security_profile_digest",
        ):
            _requireDigest(getattr(self, name), name)
        _requireOid(self.revision, "revision")
        _requireOid(self.tree_oid, "tree_oid")
        payload_root = Path(self.payload_root)
        if not payload_root.is_absolute():
            raise ValueError("source payload root must be absolute")
        try:
            safe_payload_root = assertNoReparsePath(payload_root)
        except OSError as exc:
            raise ValueError("source payload root traverses a reparse point") from exc
        if not safe_payload_root.is_dir():
            raise ValueError("source payload root must exist")
        object.__setattr__(self, "payload_root", str(safe_payload_root))
        if not isinstance(self.objects, tuple):
            raise TypeError("source closure objects must be an immutable tuple")
        if tuple(sorted(record.oid for record in self.objects)) != tuple(
            record.oid for record in self.objects
        ) or len({record.oid for record in self.objects}) != len(self.objects):
            raise ValueError("source closure objects must be sorted and unique")
        if canonical_digest([record.toDict() for record in self.objects]) != (
            self.object_closure_digest
        ):
            raise ValueError("source closure digest differs from its object records")
        if not any(
            record.oid == self.revision and record.object_type == "commit"
            for record in self.objects
        ) or not any(
            record.oid == self.tree_oid and record.object_type == "tree"
            for record in self.objects
        ):
            raise ValueError("source closure lacks its exact commit or tree")
        if self.intentional_shallow is not True:
            raise ValueError("source closure must declare its intentional shallow boundary")
        if self.parser_network_allowed is not False:
            raise ValueError("source parser networking must remain disabled")


