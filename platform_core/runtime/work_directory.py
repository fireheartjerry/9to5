"""Resolve run work directories and own temporary simulation lifetimes.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  LaunchError  -- A user-facing launch failure with an explicit process exit code.
  ResolvedWorkDir  -- A resolved run directory plus optional ownership of its temporary lifetime.
  resolveWorkDir(args: Any) -> ResolvedWorkDir  -- Resolve and own the run directory, including any temporary simulation fence.
DEPENDS-ON: config, platform_core.ops.external_project
SIDE-EFFECTS: may clone a managed repository or create/delete a simulation temp directory
RUN/TEST: python -m pytest tests/platform/test_work_directory.py
"""
from __future__ import annotations

import tempfile
from dataclasses import dataclass
from pathlib import Path
from types import TracebackType
from typing import Any

import config

LOG = config.getLogger("work_directory")


class LaunchError(RuntimeError):
    """A user-facing launch failure with an explicit process exit code."""

    def __init__(self, message: str, *, exit_code: int) -> None:
        super().__init__(message)
        self.exit_code = exit_code


@dataclass
class ResolvedWorkDir:
    """A resolved run directory plus optional ownership of its temporary lifetime."""

    path: Path
    _temporary: tempfile.TemporaryDirectory[str] | None = None

    def close(self) -> None:
        if self._temporary is not None:
            self._temporary.cleanup()
            self._temporary = None

    def __enter__(self) -> "ResolvedWorkDir":
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        traceback: TracebackType | None,
    ) -> None:
        self.close()


def resolveWorkDir(args: Any) -> ResolvedWorkDir:
    """Resolve and own the run directory, including any temporary simulation fence."""
    if args.repo_ref and not args.repo_url:
        raise LaunchError("--repo-ref requires --repo-url", exit_code=2)
    if args.repo_url and args.work_dir:
        raise LaunchError("--repo-url and --work-dir are mutually exclusive", exit_code=2)
    if args.repo_url:
        try:
            from platform_core.ops.external_project import cloneRepo

            args.work_dir = str(cloneRepo(args.repo_url, args.repo_ref))
            print(f"Cloned repo -> {args.work_dir}")
        except Exception as exc:  # noqa: BLE001 -- normalize adapter failures for the CLI
            raise LaunchError(f"--repo-url clone failed: {exc}", exit_code=2) from exc
    if args.work_dir and not Path(args.work_dir).is_dir():
        raise LaunchError(
            f"--work-dir does not exist or is not a directory: {args.work_dir}",
            exit_code=2,
        )
    if getattr(args, "sim_run", False) and not args.work_dir:
        temporary = tempfile.TemporaryDirectory(prefix="9to5-simrun-")
        path = Path(temporary.name).resolve()
        args.work_dir = str(path)
        LOG.info("SIM-RUN work_dir fenced to %s (no self-ref git branch)", path)
        return ResolvedWorkDir(path, temporary)
    path = Path(args.work_dir).resolve() if args.work_dir else Path(config.PROJECT_ROOT).resolve()
    if args.work_dir:
        args.work_dir = str(path)
    return ResolvedWorkDir(path)
