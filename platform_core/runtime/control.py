"""ControlBus -- transactional, cross-process run control over SQLite.

Three processes share one control plane per task (``state/control.db``): the orchestrator
run, the Discord gateway command bot, and the web dashboard. Each command (abort / pause /
approve / reject / skip / add / retry) is written to the bus; the orchestrator drains it
between steps. Every mutation is one BEGIN IMMEDIATE transaction in
:mod:`platform_core.runtime.control_store`, so writers can never interleave or clobber
each other -- no sidecar locks, no atomic-replace retry ladders, no corrupt-rebuild path.

The public API is unchanged from the JSON-file era; only the backing store moved.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  AbortRun  -- Raised inside the orchestrator when an abort has been requested.
  ControlBus
DEPENDS-ON: config, platform_core.runtime
SIDE-EFFECTS: reads/writes state/control.db via control_store
RUN/TEST: python -m pytest tests/control/test_control_concurrency.py tests/control/test_control_store.py tests/control/test_granular_controls.py tests/control/test_webdash_control.py tests/slow/test_fuzz_control.py tests/test_bot_control_auth.py
"""
from __future__ import annotations

import time
from typing import Any, Callable, Optional

import config
from platform_core.runtime import control_store

LOG = config.getLogger("control")


class AbortRun(Exception):
    """Raised inside the orchestrator when an abort has been requested."""


# Approval gates the orchestrator may wait on (gated mode).
GATES = ("plan", "pre_pr", "action_risk")

_BOOL_FLAGS = ("abort", "pause", "kill_subprocess", "force_replan")


def _blank() -> dict[str, Any]:
    """Canonical shape of ``ControlBus.load()`` (kept for callers and tests)."""
    return {
        "abort": False,
        "pause": False,
        "kill_subprocess": False,  # Spec B: kill the current Claude attempt (not the run)
        "force_replan": False,     # Spec B: operator-requested replanning pass
        "decisions": {g: None for g in GATES},
        "plan_ops": [],            # queued: {"op": "skip"|"add"|"retry"|"intent"|..., ...}
        "seen_discord_id": None,   # last Discord message id processed by an ingester
        "pending_gate": None,      # gate the run is currently waiting on (gated mode)
        "autonomy_spent_usd": 0.0,  # Epic 4: monotonic ledger (SUM over control_store.ledger)
    }


class ControlBus:
    def __init__(self, task_id: str):
        self.task_id = task_id

    # ---- whole-bus read --------------------------------------------------
    def load(self) -> dict[str, Any]:
        """Tolerant snapshot of the whole control plane (a missed poll is re-checked next
        tick, so a transient read failure degrades to blank instead of raising)."""
        base = _blank()
        try:
            snap = control_store.snapshot(self.task_id)
        except Exception:  # noqa: BLE001
            LOG.warning("control bus load failed for %s; returning blank", self.task_id,
                        exc_info=True)
            return base
        for key in _BOOL_FLAGS:
            base[key] = bool(snap["flags"].get(key, False))
        base["pending_gate"] = snap["flags"].get("pending_gate")
        base["seen_discord_id"] = snap["flags"].get("seen_discord_id")
        base["decisions"].update(snap["decisions"])
        base["plan_ops"] = snap["plan_ops"]
        base["autonomy_spent_usd"] = snap["autonomy_spent_usd"]
        return base

    def _flag(self, key: str, default: Any = None) -> Any:
        """Tolerant single-flag read (poll loops re-check next tick; mutations still raise)."""
        try:
            return control_store.getFlag(self.task_id, key, default)
        except Exception:  # noqa: BLE001
            LOG.warning("control flag read %s/%s failed", self.task_id, key, exc_info=True)
            return default

    # ---- abort / pause ----------------------------------------------------
    def requestAbort(self) -> None:
        control_store.setFlag(self.task_id, "abort", True)

    def isAbort(self) -> bool:
        return bool(self._flag("abort"))

    def requestPause(self) -> None:
        control_store.setFlag(self.task_id, "pause", True)

    def clearPause(self) -> None:
        control_store.setFlag(self.task_id, "pause", False)

    def isPaused(self) -> bool:
        return bool(self._flag("pause"))

    # ---- Spec B: granular mid-run control signals ---------------------------
    def requestKillSubprocess(self) -> None:
        control_store.setFlag(self.task_id, "kill_subprocess", True)

    def isKillSubprocess(self) -> bool:
        return bool(self._flag("kill_subprocess"))

    def clearKillSubprocess(self) -> None:
        control_store.setFlag(self.task_id, "kill_subprocess", False)

    def requestForceReplan(self) -> None:
        control_store.setFlag(self.task_id, "force_replan", True)

    def isForceReplan(self) -> bool:
        return bool(self._flag("force_replan"))

    def clearForceReplan(self) -> None:
        control_store.setFlag(self.task_id, "force_replan", False)

    # ---- approval decisions (gated mode) ------------------------------------
    def decide(self, gate: str, verdict: str) -> None:
        control_store.setDecision(self.task_id, gate, verdict)

    def getDecision(self, gate: str) -> Optional[str]:
        try:
            return control_store.getDecision(self.task_id, gate)
        except Exception:  # noqa: BLE001
            LOG.warning("control decision read %s/%s failed", self.task_id, gate, exc_info=True)
            return None

    def clearDecision(self, gate: str) -> None:
        control_store.clearDecision(self.task_id, gate)

    def setPendingGate(self, gate: Optional[str]) -> None:
        control_store.setFlag(self.task_id, "pending_gate", gate)

    def getPendingGate(self) -> Optional[str]:
        return self._flag("pending_gate")

    def waitDecision(self, gate: str, timeout: "float | None" = None, *, poll: float = 1.0,
                     on_tick: "Callable[[], object] | None" = None,
                     escape: "Callable[[], bool] | None" = None) -> Optional[str]:
        """Block until ``gate`` is decided -- the ONE shared wait that replaced the
        per-caller sleep-poll gate loops. Returns the verdict (``approve``/``reject``),
        ``"abort"`` when an abort lands mid-wait, or ``None`` when the wait ends
        undecided: ``timeout`` elapsed, ``escape()`` turned true (e.g. the run deadline),
        or night mode capped an unattended wait at ``config.NIGHT_MODE_PAUSE_TIMEOUT``.
        ``on_tick()`` runs every poll (callers hook Discord ingestion + op drain there)."""
        start = time.time()
        while True:
            if on_tick is not None:
                on_tick()
            if self.isAbort():
                return "abort"
            verdict = self.getDecision(gate)
            if verdict:
                return verdict
            elapsed = time.time() - start
            if timeout is not None and elapsed >= timeout:
                return None
            if config.NIGHT_MODE and elapsed >= config.NIGHT_MODE_PAUSE_TIMEOUT:
                return None
            if escape is not None and escape():
                return None
            time.sleep(poll)

    # ---- queued plan operations ----------------------------------------------
    def pushOp(self, op: dict[str, Any], source_msg_id: Optional[str] = None) -> None:
        """Queue one plan op. ``source_msg_id`` (the Discord message id) makes ingestion
        idempotent: the SAME message pushed by two ingesters lands ONCE; two identical
        user messages (two ids) land twice. Ops without an id never dedup."""
        control_store.pushOp(self.task_id, op, source_msg_id)

    def drainOps(self) -> list[dict[str, Any]]:
        return control_store.drainOps(self.task_id)

    # ---- Discord poll cursor ----------------------------------------------------
    def setSeen(self, message_id: Optional[str]) -> None:
        control_store.setFlag(self.task_id, "seen_discord_id", message_id)

    def getSeen(self) -> Optional[str]:
        return self._flag("seen_discord_id")

    # ---- lifecycle ------------------------------------------------------------
    def clear(self) -> None:
        control_store.clearTask(self.task_id)

    def clearForRunStart(self) -> None:
        """Reset only the run-execution cursor for a fresh run (queued plan_ops, Discord
        poll cursor, pending_gate), PRESERVING any control the user already issued
        (abort / pause / gate decisions) during the pre-run elaboration window -- the
        gateway bot and the terminal-control thread are live before runFull."""
        control_store.clearRunStart(self.task_id)
