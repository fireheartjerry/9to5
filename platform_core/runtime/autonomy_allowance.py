"""Run-scoped monotonic autonomy-allowance ledger over the SQLite control store (Epic 4 unit b).

A thin facade -- NOT a parallel store. Spend rows live in ``control_store.ledger``
(``task_id, attempt_id UNIQUE, usd, at``): ``meterSpend`` is one INSERT OR IGNORE (same
attempt twice = one charge) and ``spent`` is ``SELECT COALESCE(SUM(usd), 0)``, so
idempotency and monotonicity are STRUCTURAL -- no mailbox corruption or rebuild path can
ever zero the money (the cap-bypass guard the old JSON schema only promised).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  spent(bus) -> float  -- Current run-scoped autonomy spend (0.0 on a fresh/unreadable ledger).
  meterSpend(bus, amount_usd: 'float | None', *, attempt_id: Optional[str]=None) -> float  -- Add a committed (post-runClaude) cost to the running total, monotonically and idempoten…
DEPENDS-ON: platform_core.runtime.control_store
SIDE-EFFECTS: writes the control_store ledger table
RUN/TEST: python -m pytest tests/orchestration/test_autonomy_allowance.py
"""
from __future__ import annotations

from typing import Optional

from platform_core.runtime import control_store

SPEND_KEY: str = "autonomy_spent_usd"   # field name in ControlBus.load() snapshots


def spent(bus) -> float:
    """Current run-scoped autonomy spend (0.0 on a fresh/unreadable ledger)."""
    try:
        return control_store.spentTotal(bus.task_id)
    except Exception:  # noqa: BLE001 -- a metering read must never break a run
        return 0.0


def meterSpend(bus, amount_usd: "float | None", *, attempt_id: Optional[str] = None) -> float:
    """Add a committed (post-runClaude) cost to the running total, monotonically and idempotently.

    Negative/None amounts clamp to 0. When ``attempt_id`` was already metered this run, the add is
    a no-op (retry double-charge guard, enforced by the ledger's UNIQUE constraint). Returns the
    new total."""
    try:
        amount = max(0.0, float(amount_usd or 0.0))
        control_store.meterSpend(bus.task_id, attempt_id, amount)
    except Exception:  # noqa: BLE001 -- metering must never break a run
        pass
    return spent(bus)
