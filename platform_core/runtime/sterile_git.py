"""Closed host-Git runner for controller-generated shadow object stores.

This is intentionally not a general Git wrapper.  It exposes a tiny read-only
object-inspection vocabulary, pins the qualified SHA1_DC executable, constructs an
ambient-free environment, bounds output/time, and refuses target-repository roots.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  SterileGitRefused  -- The requested Git operation was outside the sterile closed surface.
  initializeSterileGitDirectory(git_dir: str | Path) -> Path  -- Create or exactly replay the minimal controller-owned bare Git directory.
  SterileGitResult
  SterileGit  -- Execute the exact read-only allowlist against one owned shadow Git directory.
DEPENDS-ON: platform_core.core.fsio, platform_core.runtime.sha1dc
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_sterile_git.py
"""
from __future__ import annotations

import os
import re
import subprocess
import threading
from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO

from platform_core.core.fsio import assertNoReparsePath, exclusiveCreateBytes, readNoFollowBytes
from platform_core.runtime.sha1dc import GitSha1dcOracle, Sha1dcEvidence, Sha1dcRefused

_OID_RE = re.compile(r"^[0-9a-f]{40}$")
_LOCAL_CONFIG = b"[core]\n\trepositoryformatversion = 0\n\tbare = true\n"
_HEAD = b"ref: refs/heads/unused\n"
_MAX_METADATA_BYTES = 64 * 1024
_CAT_FILE_FLAGS = frozenset({"-e", "-p", "-s", "-t"})


class SterileGitRefused(RuntimeError):
    """The requested Git operation was outside the sterile closed surface."""


def _pathContains(parent: Path, child: Path) -> bool:
    parent_text = os.path.normcase(str(parent))
    child_text = os.path.normcase(str(child))
    try:
        return os.path.commonpath((parent_text, child_text)) == parent_text
    except ValueError:
        return False


def _pathOverlaps(left: Path, right: Path) -> bool:
    return _pathContains(left, right) or _pathContains(right, left)


def _ensureExactFile(path: Path, payload: bytes) -> None:
    try:
        exclusiveCreateBytes(path, payload)
    except FileExistsError:
        try:
            observed = readNoFollowBytes(path, max_bytes=max(1, len(payload)))
        except (OSError, ValueError) as exc:
            raise SterileGitRefused(f"sterile metadata is unsafe: {path.name}") from exc
        if observed != payload:
            raise SterileGitRefused(f"sterile metadata collision: {path.name}")


def initializeSterileGitDirectory(git_dir: str | Path) -> Path:
    """Create or exactly replay the minimal controller-owned bare Git directory."""

    try:
        root = assertNoReparsePath(git_dir)
        root.mkdir(parents=True, exist_ok=True)
        for relative in (
            "objects/info",
            "objects/pack",
            "refs/heads",
            "refs/tags",
            "runtime/home",
            "runtime/hooks-disabled",
        ):
            directory = root / relative
            directory.mkdir(parents=True, exist_ok=True)
            assertNoReparsePath(directory)
        _ensureExactFile(root / "config", _LOCAL_CONFIG)
        _ensureExactFile(root / "HEAD", _HEAD)
        _ensureExactFile(root / "runtime" / "global.config", b"")
        _ensureExactFile(root / "runtime" / "attributes", b"")
        return root
    except SterileGitRefused:
        raise
    except OSError as exc:
        raise SterileGitRefused("could not initialize sterile Git directory") from exc


@dataclass(frozen=True, kw_only=True)
class SterileGitResult:
    argv: tuple[str, ...]
    returncode: int
    stdout: bytes
    stderr: bytes
    network_allowed: bool = False

    def __post_init__(self) -> None:
        if self.network_allowed is not False:
            raise ValueError("sterile Git networking must remain disabled")


class SterileGit:
    """Execute the exact read-only allowlist against one owned shadow Git directory."""

    def __init__(
        self,
        *,
        git_dir: str | Path,
        controller_root: str | Path,
        sha1dc_oracle: GitSha1dcOracle,
        sha1dc_evidence: Sha1dcEvidence,
        forbidden_roots: tuple[str | Path, ...] = (),
        timeout_seconds: float = 30.0,
        max_output_bytes: int = 16 * 1024 * 1024,
    ) -> None:
        try:
            self.git_dir = assertNoReparsePath(git_dir)
            self.controller_root = assertNoReparsePath(controller_root)
            forbidden = tuple(assertNoReparsePath(path) for path in forbidden_roots)
        except OSError as exc:
            raise SterileGitRefused("sterile Git path traverses a reparse point") from exc
        if not _pathContains(self.controller_root, self.git_dir) or self.git_dir == self.controller_root:
            raise SterileGitRefused("sterile Git directory must be below its controller root")
        if any(_pathOverlaps(self.git_dir, root) for root in forbidden):
            raise SterileGitRefused("sterile Git directory overlaps a forbidden root")
        if not isinstance(sha1dc_oracle, GitSha1dcOracle) or not isinstance(
            sha1dc_evidence, Sha1dcEvidence
        ):
            raise TypeError("sterile Git requires typed SHA1_DC evidence")
        if sha1dc_oracle.evidence != sha1dc_evidence:
            raise SterileGitRefused("SHA1_DC oracle and evidence do not match")
        if not isinstance(timeout_seconds, (int, float)) or isinstance(timeout_seconds, bool):
            raise TypeError("timeout_seconds must be numeric")
        if timeout_seconds <= 0:
            raise ValueError("timeout_seconds must be positive")
        if type(max_output_bytes) is not int or max_output_bytes < 1:
            raise ValueError("max_output_bytes must be a positive integer")
        self._oracle = sha1dc_oracle
        self._evidence = sha1dc_evidence
        self._timeout_seconds = float(timeout_seconds)
        self._max_output_bytes = max_output_bytes
        self._validateShadow()

    def _validateShadow(self) -> None:
        try:
            for path in (
                self.git_dir,
                self.git_dir / "objects",
                self.git_dir / "refs",
                self.git_dir / "runtime",
                self.git_dir / "runtime" / "home",
                self.git_dir / "runtime" / "hooks-disabled",
            ):
                checked = assertNoReparsePath(path)
                if not checked.is_dir():
                    raise OSError(f"not a directory: {checked}")
            config = readNoFollowBytes(
                self.git_dir / "config", max_bytes=_MAX_METADATA_BYTES
            )
            head = readNoFollowBytes(self.git_dir / "HEAD", max_bytes=_MAX_METADATA_BYTES)
            global_config = readNoFollowBytes(
                self.git_dir / "runtime" / "global.config",
                max_bytes=_MAX_METADATA_BYTES,
            )
            attributes = readNoFollowBytes(
                self.git_dir / "runtime" / "attributes",
                max_bytes=_MAX_METADATA_BYTES,
            )
        except (OSError, ValueError) as exc:
            raise SterileGitRefused("sterile local configuration cannot be proven") from exc
        if config != _LOCAL_CONFIG or head != _HEAD or global_config or attributes:
            raise SterileGitRefused("sterile local configuration is not exact")
        for relative in (
            "objects/info/alternates",
            "objects/info/http-alternates",
            "info/attributes",
            "shallow",
        ):
            if (self.git_dir / relative).exists():
                raise SterileGitRefused("sterile local configuration contains forbidden metadata")

    @staticmethod
    def _validateArgv(argv: tuple[str, ...]) -> None:
        if not isinstance(argv, tuple) or any(not isinstance(value, str) for value in argv):
            raise TypeError("sterile Git argv must be an immutable string tuple")
        if any(not value or "\0" in value or "\r" in value or "\n" in value for value in argv):
            raise SterileGitRefused("Git argv is outside the allowlist")
        if (
            len(argv) != 3
            or argv[0] != "cat-file"
            or argv[1] not in _CAT_FILE_FLAGS
            or _OID_RE.fullmatch(argv[2]) is None
        ):
            raise SterileGitRefused("Git command, flag, or revision is outside the allowlist")

    def _environment(self) -> dict[str, str]:
        runtime = self.git_dir / "runtime"
        env = {
            "GIT_DIR": str(self.git_dir),
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_CONFIG_SYSTEM": os.devnull,
            "GIT_CONFIG_GLOBAL": str(runtime / "global.config"),
            "GIT_ATTR_NOSYSTEM": "1",
            "GIT_NO_REPLACE_OBJECTS": "1",
            "GIT_NO_LAZY_FETCH": "1",
            "GIT_TERMINAL_PROMPT": "0",
            "GIT_ASKPASS": "",
            "SSH_ASKPASS": "",
            "GCM_INTERACTIVE": "Never",
            "GIT_PROTOCOL_FROM_USER": "0",
            "GIT_ALLOW_PROTOCOL": "",
            "HOME": str(runtime / "home"),
            "USERPROFILE": str(runtime / "home"),
            "PATH": str(Path(self._evidence.executable_path).parent),
            "LC_ALL": "C",
            "LANG": "C",
        }
        system_root = os.environ.get("SystemRoot")
        if system_root:
            env["SystemRoot"] = system_root
        return env

    def _readPipe(
        self,
        pipe: BinaryIO,
        destination: list[bytes],
        state: dict[str, int | bool],
        lock: threading.Lock,
        process: subprocess.Popen[bytes],
    ) -> None:
        try:
            while True:
                chunk = pipe.read(65536)
                if not chunk:
                    return
                with lock:
                    state["total"] = int(state["total"]) + len(chunk)
                    if int(state["total"]) > self._max_output_bytes:
                        state["exceeded"] = True
                    else:
                        destination.append(chunk)
                if bool(state["exceeded"]):
                    process.kill()
                    return
        finally:
            pipe.close()

    def run(self, argv: tuple[str, ...]) -> SterileGitResult:
        self._validateArgv(argv)
        self._validateShadow()
        try:
            self._oracle.revalidate()
        except Sha1dcRefused as exc:
            raise SterileGitRefused("pinned SHA1_DC runtime is no longer valid") from exc
        hooks = self.git_dir / "runtime" / "hooks-disabled"
        command = (
            self._evidence.executable_path,
            "-c",
            f"core.hooksPath={hooks}",
            "-c",
            "core.fsmonitor=false",
            "-c",
            "core.pager=cat",
            "-c",
            "pager.cat-file=false",
            "-c",
            "diff.external=",
            "-c",
            "commit.gpgSign=false",
            "-c",
            "tag.gpgSign=false",
            *argv,
        )
        try:
            process = subprocess.Popen(
                command,
                cwd=self.git_dir / "runtime" / "home",
                env=self._environment(),
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                shell=False,
                creationflags=(
                    getattr(subprocess, "CREATE_NO_WINDOW", 0) if os.name == "nt" else 0
                ),
            )
        except OSError as exc:
            raise SterileGitRefused("could not start pinned sterile Git") from exc
        if process.stdout is None or process.stderr is None:
            process.kill()
            raise SterileGitRefused("sterile Git pipes are unavailable")
        stdout: list[bytes] = []
        stderr: list[bytes] = []
        state: dict[str, int | bool] = {"total": 0, "exceeded": False}
        lock = threading.Lock()
        readers = (
            threading.Thread(
                target=self._readPipe,
                args=(process.stdout, stdout, state, lock, process),
                daemon=True,
            ),
            threading.Thread(
                target=self._readPipe,
                args=(process.stderr, stderr, state, lock, process),
                daemon=True,
            ),
        )
        for reader in readers:
            reader.start()
        try:
            returncode = process.wait(timeout=self._timeout_seconds)
        except subprocess.TimeoutExpired as exc:
            process.kill()
            process.wait()
            for reader in readers:
                reader.join(timeout=1)
            raise SterileGitRefused("sterile Git exceeded its wall-time quota") from exc
        for reader in readers:
            reader.join(timeout=1)
        if any(reader.is_alive() for reader in readers):
            process.kill()
            raise SterileGitRefused("sterile Git output reader did not quiesce")
        if bool(state["exceeded"]):
            raise SterileGitRefused("sterile Git exceeded its combined output quota")
        return SterileGitResult(
            argv=command,
            returncode=returncode,
            stdout=b"".join(stdout),
            stderr=b"".join(stderr),
        )


