"""Closed inert tree manifests for memory-safe Git object construction.

The manifest is already the output of a contained parser.  Host code accepts only
regular blobs, canonical POSIX paths, strong digests, and the single pre-normalized
``text eol=lf`` attribute subset.  No repository attribute/config file is consulted.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ObjectManifestRefused
  ManifestEntry
  AttributeRule
  ManifestPolicy
  ObjectManifest
DEPENDS-ON: platform_core.core.galaxy_evidence
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_object_manifest.py
"""
from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass
from pathlib import PurePosixPath
from typing import Any

from platform_core.core.galaxy_evidence import canonical_digest

_OID_RE = re.compile(r"^[0-9a-f]{40}(?:[0-9a-f]{24})?$")
_DIGEST_RE = re.compile(r"^[0-9a-f]{64}$")
_SHORT_ALIAS_RE = re.compile(
    r"^[^~]{1,6}~[1-9][0-9]*(?:\.[^.]{0,3})?$",
    re.IGNORECASE,
)
_WINDOWS_INVALID_CHARACTERS = frozenset('<>"|?*')
_PORTABLE_PATH_BYTES = 240
_WINDOWS_COMPONENT_UTF16_UNITS = 255
_RESERVED_DEVICES = {
    "CON",
    "PRN",
    "AUX",
    "NUL",
    "CLOCK$",
    "CONIN$",
    "CONOUT$",
    *(f"COM{number}" for number in range(1, 10)),
    *(f"LPT{number}" for number in range(1, 10)),
}
_REGULAR_MODES = frozenset({0o100644, 0o100755})


class ObjectManifestRefused(ValueError):
    pass


def _require_digest(value: str, name: str) -> None:
    if not isinstance(value, str) or _DIGEST_RE.fullmatch(value) is None:
        raise ValueError(f"{name} must be a lowercase SHA-256 digest")


def _require_oid(value: str, name: str) -> None:
    if not isinstance(value, str) or _OID_RE.fullmatch(value) is None:
        raise ValueError(f"{name} must be a full lowercase Git object id")


def _validate_path(value: str) -> tuple[str, ...]:
    if not isinstance(value, str) or not value or "\\" in value:
        raise ValueError("path must be a non-empty canonical POSIX path")
    path = PurePosixPath(value)
    if path.is_absolute() or path.as_posix() != value:
        raise ValueError("path must be a canonical repository-relative POSIX path")
    parts = path.parts
    if not parts or any(part in {"", ".", ".."} for part in parts):
        raise ValueError("path cannot contain empty, dot, or parent components")
    for part in parts:
        if any(ord(character) < 32 or ord(character) == 127 for character in part):
            raise ValueError("path cannot contain control characters")
        if ":" in part:
            raise ValueError("path cannot contain alternate-data-stream separators")
        if any(character in _WINDOWS_INVALID_CHARACTERS for character in part):
            raise ValueError("path contains a Windows-invalid character")
        if part.endswith((".", " ")):
            raise ValueError("path cannot contain trailing dot or space aliases")
        if unicodedata.normalize("NFC", part) != part:
            raise ValueError("path components must use canonical NFC spelling")
        try:
            utf16_units = len(part.encode("utf-16-le", errors="strict")) // 2
        except UnicodeEncodeError as exc:
            raise ValueError("path contains an unrepresentable Unicode component") from exc
        if utf16_units > _WINDOWS_COMPONENT_UTF16_UNITS:
            raise ValueError("path component exceeds the Windows native limit")
        if part.casefold() == ".git":
            raise ValueError("path cannot enter Git metadata")
        base = part.rstrip(" .").split(".", 1)[0].rstrip(" ").upper()
        if base in _RESERVED_DEVICES:
            raise ValueError("path contains a reserved Windows device name")
        if _SHORT_ALIAS_RE.fullmatch(part):
            raise ValueError("path contains an ambiguous Windows short-name alias")
    return parts


def _filesystem_key(path: str) -> tuple[str, ...]:
    return tuple(
        unicodedata.normalize("NFC", component).casefold()
        for component in PurePosixPath(path).parts
    )


@dataclass(frozen=True, kw_only=True)
class ManifestEntry:
    path: str
    mode: int
    blob_oid: str
    blob_sha256: str
    framed_object_sha256: str
    size: int

    def __post_init__(self) -> None:
        _validate_path(self.path)
        if type(self.mode) is not int or self.mode not in _REGULAR_MODES:
            raise ValueError("manifest mode must be regular 100644 or 100755")
        _require_oid(self.blob_oid, "blob_oid")
        _require_digest(self.blob_sha256, "blob_sha256")
        _require_digest(self.framed_object_sha256, "framed_object_sha256")
        if type(self.size) is not int or self.size < 0:
            raise ValueError("manifest size must be a non-negative integer")

    def toDict(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "mode": self.mode,
            "blob_oid": self.blob_oid,
            "blob_sha256": self.blob_sha256,
            "framed_object_sha256": self.framed_object_sha256,
            "size": self.size,
        }

    @classmethod
    def fromDict(cls, value: object) -> ManifestEntry:
        if not isinstance(value, dict) or set(value) != {
            "path",
            "mode",
            "blob_oid",
            "blob_sha256",
            "framed_object_sha256",
            "size",
        }:
            raise ObjectManifestRefused("manifest entry fields are not closed")
        try:
            return cls(**value)
        except (TypeError, ValueError) as exc:
            raise ObjectManifestRefused("manifest entry violates its contract") from exc


@dataclass(frozen=True, kw_only=True)
class AttributeRule:
    pattern: str
    attributes: tuple[str, ...]

    def __post_init__(self) -> None:
        if not isinstance(self.pattern, str) or not self.pattern.strip():
            raise ValueError("attribute pattern must be non-empty")
        if (
            any(ord(character) < 32 for character in self.pattern)
            or self.pattern.startswith(("!", "[attr]"))
            or "\\" in self.pattern
            or any(character.isspace() for character in self.pattern)
            or any(character in self.pattern for character in "?[]")
            or self.pattern.startswith("/")
            or self.pattern.endswith("/")
            or ".." in PurePosixPath(self.pattern).parts
        ):
            raise ValueError("attribute pattern is outside the safe subset")
        if not isinstance(self.attributes, tuple):
            raise TypeError("attributes must be an immutable tuple")
        if self.attributes != ("text", "eol=lf"):
            raise ValueError("only exact pre-canonicalized text eol=lf is supported")

    def toDict(self) -> dict[str, Any]:
        return {"pattern": self.pattern, "attributes": list(self.attributes)}

    @classmethod
    def fromDict(cls, value: object) -> AttributeRule:
        if not isinstance(value, dict) or set(value) != {"pattern", "attributes"}:
            raise ObjectManifestRefused("attribute rule fields are not closed")
        attributes = value.get("attributes")
        if not isinstance(attributes, list):
            raise ObjectManifestRefused("attribute rule attributes must be a list")
        try:
            return cls(pattern=value["pattern"], attributes=tuple(attributes))
        except (TypeError, ValueError) as exc:
            raise ObjectManifestRefused("attribute rule violates its contract") from exc


@dataclass(frozen=True, kw_only=True)
class ManifestPolicy:
    reserved_roots: tuple[str, ...]
    max_files: int
    max_total_bytes: int
    max_file_bytes: int
    max_depth: int
    max_path_bytes: int

    def __post_init__(self) -> None:
        if not isinstance(self.reserved_roots, tuple):
            raise TypeError("reserved_roots must be an immutable tuple")
        normalized: list[str] = []
        for root in self.reserved_roots:
            _validate_path(root)
            normalized.append(root.rstrip("/"))
        if len(normalized) != len(set(_filesystem_key(root) for root in normalized)):
            raise ValueError("reserved_roots contain aliases")
        object.__setattr__(self, "reserved_roots", tuple(sorted(normalized)))
        for name in (
            "max_files",
            "max_total_bytes",
            "max_file_bytes",
            "max_depth",
            "max_path_bytes",
        ):
            value = getattr(self, name)
            if type(value) is not int or value < 1:
                raise ValueError(f"{name} must be a positive integer")
        if self.max_file_bytes > self.max_total_bytes:
            raise ValueError("max_file_bytes cannot exceed max_total_bytes")
        if self.max_path_bytes > _PORTABLE_PATH_BYTES:
            raise ValueError(
                f"max_path_bytes exceeds the {_PORTABLE_PATH_BYTES}-byte "
                "portable path ceiling"
            )

    def toDict(self) -> dict[str, Any]:
        return {
            "reserved_roots": list(self.reserved_roots),
            "max_files": self.max_files,
            "max_total_bytes": self.max_total_bytes,
            "max_file_bytes": self.max_file_bytes,
            "max_depth": self.max_depth,
            "max_path_bytes": self.max_path_bytes,
        }

    @classmethod
    def fromDict(cls, value: object) -> ManifestPolicy:
        if not isinstance(value, dict) or set(value) != {
            "reserved_roots",
            "max_files",
            "max_total_bytes",
            "max_file_bytes",
            "max_depth",
            "max_path_bytes",
        }:
            raise ObjectManifestRefused("manifest policy fields are not closed")
        roots = value.get("reserved_roots")
        if not isinstance(roots, list):
            raise ObjectManifestRefused("reserved_roots must be a list")
        payload = dict(value)
        payload["reserved_roots"] = tuple(roots)
        try:
            return cls(**payload)
        except (TypeError, ValueError) as exc:
            raise ObjectManifestRefused("manifest policy violates its contract") from exc


@dataclass(frozen=True, kw_only=True)
class ObjectManifest:
    expected_revision: str
    entries: tuple[ManifestEntry, ...]
    attribute_rules: tuple[AttributeRule, ...]
    policy: ManifestPolicy

    def __post_init__(self) -> None:
        _require_oid(self.expected_revision, "expected_revision")
        if not isinstance(self.entries, tuple) or not isinstance(
            self.attribute_rules, tuple
        ):
            raise TypeError("manifest collections must be immutable tuples")
        if len(self.entries) > self.policy.max_files:
            raise ObjectManifestRefused("manifest exceeds file-count quota")
        ordered = tuple(sorted(self.entries, key=lambda entry: entry.path.encode("utf-8")))
        exact_paths = [entry.path for entry in ordered]
        if len(exact_paths) != len(set(exact_paths)):
            raise ObjectManifestRefused("manifest contains duplicate paths")
        aliases: dict[tuple[str, ...], str] = {}
        path_set = set(exact_paths)
        total = 0
        reserved_keys = tuple(_filesystem_key(root) for root in self.policy.reserved_roots)
        for entry in ordered:
            parts = _validate_path(entry.path)
            path_bytes = len(entry.path.encode("utf-8"))
            if path_bytes > self.policy.max_path_bytes:
                raise ObjectManifestRefused("manifest path exceeds byte quota")
            if len(parts) > self.policy.max_depth:
                raise ObjectManifestRefused("manifest path exceeds depth quota")
            if entry.size > self.policy.max_file_bytes:
                raise ObjectManifestRefused("manifest file exceeds per-file byte quota")
            total += entry.size
            key = _filesystem_key(entry.path)
            prior = aliases.setdefault(key, entry.path)
            if prior != entry.path:
                raise ObjectManifestRefused(
                    f"filesystem alias collision: {prior!r} and {entry.path!r}"
                )
            if any(key[: len(root_key)] == root_key for root_key in reserved_keys):
                raise ObjectManifestRefused(
                    f"reserved runtime path is not proposable: {entry.path}"
                )
            for index in range(1, len(parts)):
                ancestor = "/".join(parts[:index])
                if ancestor in path_set:
                    raise ObjectManifestRefused(
                        f"manifest file is an ancestor of another path: {ancestor}"
                    )
        if total > self.policy.max_total_bytes:
            raise ObjectManifestRefused("manifest exceeds aggregate byte quota")
        rules = tuple(sorted(self.attribute_rules, key=lambda rule: rule.pattern))
        if len({rule.pattern for rule in rules}) != len(rules):
            raise ObjectManifestRefused("attribute rules contain duplicate patterns")
        object.__setattr__(self, "entries", ordered)
        object.__setattr__(self, "attribute_rules", rules)

    def toDict(self) -> dict[str, Any]:
        return {
            "expected_revision": self.expected_revision,
            "entries": [entry.toDict() for entry in self.entries],
            "attribute_rules": [rule.toDict() for rule in self.attribute_rules],
            "policy": self.policy.toDict(),
        }

    @classmethod
    def fromDict(cls, value: object) -> ObjectManifest:
        if not isinstance(value, dict) or set(value) != {
            "expected_revision",
            "entries",
            "attribute_rules",
            "policy",
        }:
            raise ObjectManifestRefused("object manifest fields are not closed")
        entries = value.get("entries")
        rules = value.get("attribute_rules")
        if not isinstance(entries, list) or not isinstance(rules, list):
            raise ObjectManifestRefused("manifest entries and rules must be lists")
        try:
            return cls(
                expected_revision=value["expected_revision"],
                entries=tuple(ManifestEntry.fromDict(item) for item in entries),
                attribute_rules=tuple(AttributeRule.fromDict(item) for item in rules),
                policy=ManifestPolicy.fromDict(value["policy"]),
            )
        except (TypeError, ValueError, KeyError) as exc:
            if isinstance(exc, ObjectManifestRefused):
                raise
            raise ObjectManifestRefused("object manifest violates its contract") from exc

    @property
    def manifest_digest(self) -> str:
        return canonical_digest(self.toDict())

    @property
    def object_closure_digest(self) -> str:
        return canonical_digest(
            [
                {
                    "path": entry.path,
                    "mode": entry.mode,
                    "oid": entry.blob_oid,
                    "raw_sha256": entry.blob_sha256,
                    "framed_sha256": entry.framed_object_sha256,
                    "size": entry.size,
                }
                for entry in self.entries
            ]
        )


