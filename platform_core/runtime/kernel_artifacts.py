"""External, signed qualification for the transactional-kernel artifact set.

The repository cannot mint this authority.  A caller can construct the public
dataclass for diagnostics, but only a receipt verified through the protected,
installed Singularity generation receives the unforgeable in-process marker.
The qualification ceiling is deliberately staging-only; it never grants ref
promotion, task completion, or activation authority.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  KernelArtifactsUnavailable  -- The installed staging-only kernel artifact qualification is unavailable.
  VerifiedKernelArtifacts  -- Freshly cross-resolved, externally signed staging artifact identities.
  loadInstalledKernelArtifacts() -> VerifiedKernelArtifacts  -- Load the one protected, signed, non-revoked staging qualification.
DEPENDS-ON: bootstrap.galaxy_launcher.activation_crypto, bootstrap.galaxy_launcher.activation_harness, bootstrap.galaxy_launcher.runtime_manifest, platform_core.core.fsio, platform_core.runtime.sha1dc
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_kernel_artifacts.py
"""
