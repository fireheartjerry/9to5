def _now() -> datetime:
    return datetime.now(timezone.utc)


def _dockerServerIdentityDigest(executable: Path, context: str) -> str:
    if context != "desktop-linux":
        raise KernelArtifactsUnavailable("Docker context is not the reviewed desktop-linux context")
    try:
        with tempfile.TemporaryDirectory(prefix="galaxy-docker-config-") as config_root:
            environment = {
                "DOCKER_CONFIG": config_root,
                "DOCKER_HOST": "npipe:////./pipe/dockerDesktopLinuxEngine",
                "DOCKER_CLI_HINTS": "false",
                "DOCKER_SCAN_SUGGEST": "false",
            }
            system_root = os.environ.get("SystemRoot")
            if system_root:
                environment["SystemRoot"] = system_root
            completed = subprocess.run(
                [str(executable), "version", "--format", "{{json .Server}}"],
                cwd=executable.parent,
                env=environment,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                timeout=15,
                check=False,
                shell=False,
                creationflags=(
                    getattr(subprocess, "CREATE_NO_WINDOW", 0) if os.name == "nt" else 0
                ),
            )
    except (OSError, subprocess.SubprocessError) as exc:
        raise KernelArtifactsUnavailable("Docker server identity cannot be observed") from exc
    if (
        completed.returncode != 0
        or completed.stderr
        or not completed.stdout
        or len(completed.stdout) > 1024 * 1024
    ):
        raise KernelArtifactsUnavailable("Docker server identity cannot be observed")
    try:
        value = json.loads(
            completed.stdout.decode("utf-8", errors="strict"),
            object_pairs_hook=_duplicates,
            parse_constant=_constant,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise KernelArtifactsUnavailable("Docker server identity is malformed") from exc
    if not isinstance(value, dict) or not value:
        raise KernelArtifactsUnavailable("Docker server identity is malformed")
    return hashlib.sha256(_canonical(value)).hexdigest()


def _attestHostSha1dc(value: Mapping[str, object]) -> Mapping[str, object]:
    executable = _text(value.get("executable_path"), "host SHA1_DC executable path", maximum=32768)
    build_evidence = _text(
        value.get("build_evidence_path"),
        "host SHA1_DC build evidence path",
        maximum=32768,
    )
    try:
        with tempfile.TemporaryDirectory(prefix="galaxy-sha1dc-attest-") as temporary:
            evidence, oracle = qualifyStandaloneSha1dc(
                executable=executable,
                build_evidence=build_evidence,
                sterile_root=Path(temporary) / "sterile",
            )
            oracle.revalidate()
    except (OSError, RuntimeError, ValueError) as exc:
        raise KernelArtifactsUnavailable("host SHA1_DC attestation failed") from exc
    return dict(evidence.toDict())


def _signature(value: object) -> bytes:
    encoded = _text(value, "qualification signature", maximum=128)
    if _SIGNATURE_RE.fullmatch(encoded) is None:
        raise KernelArtifactsUnavailable("qualification signature is malformed")
    try:
        raw = base64.urlsafe_b64decode(encoded + "==")
    except (ValueError, binascii.Error) as exc:
        raise KernelArtifactsUnavailable("qualification signature is malformed") from exc
    if (
        len(raw) != 64
        or base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=") != encoded
    ):
        raise KernelArtifactsUnavailable("qualification signature is noncanonical")
    return raw


def _generationRoot(runtime: object) -> Path:
    generation = _integer(getattr(runtime, "generation", None), "installed generation", minimum=1)
    try:
        external_root = assertNoReparsePath(getattr(runtime, "external_root")).resolve(strict=True)
    except (OSError, TypeError) as exc:
        raise KernelArtifactsUnavailable("installed controller root is unavailable") from exc
    root = _beneath(
        external_root / "generations" / f"{generation:08d}",
        external_root,
        "installed generation",
    )
    expected_lock = root / "controller" / "runtime.lock.json"
    try:
        observed_lock = Path(getattr(runtime, "runtime_lock_path")).resolve(strict=True)
    except (OSError, TypeError) as exc:
        raise KernelArtifactsUnavailable("installed runtime lock is unavailable") from exc
    if observed_lock != expected_lock:
        raise KernelArtifactsUnavailable("installed runtime lock path differs")
    return root


def loadInstalledKernelArtifacts() -> VerifiedKernelArtifacts:
    """Load the one protected, signed, non-revoked staging qualification."""

    try:
        runtime = _resolveInstalledRuntime()
    except KernelArtifactsUnavailable:
        raise
    except Exception as exc:
        raise KernelArtifactsUnavailable(
            "installed sealed runtime pointer is unavailable"
        ) from exc

    generation_root = _generationRoot(runtime)
    generation = _integer(getattr(runtime, "generation", None), "installed generation", minimum=1)
    pointer_path = Path(getattr(runtime, "external_root")) / "kernel-artifacts.current.json"
    pointer_raw, _ = _readNoFollow(
        pointer_path,
        label="kernel artifact pointer",
        max_bytes=_MAX_POINTER_BYTES,
        capture=True,
    )
    assert pointer_raw is not None
    pointer = _strictObject(pointer_raw, "kernel artifact pointer")
    _exactKeys(
        pointer,
        {
            "schema",
            "status",
            "generation",
            "revocation_generation",
            "qualification_path",
            "qualification_sha256",
            "runtime_lock_sha256",
        },
        "kernel artifact pointer",
    )
    if (
        pointer["schema"] != "galaxy.kernel-artifacts-pointer/v1"
        or pointer["status"] != "qualified_staging_only"
    ):
        raise KernelArtifactsUnavailable("kernel artifact pointer is not staging-only qualified")
    if _integer(pointer["generation"], "pointer generation", minimum=1) != generation:
        raise KernelArtifactsUnavailable("kernel artifact pointer generation differs")
    revocation_generation = _integer(
        pointer["revocation_generation"],
        "pointer revocation generation",
    )

    runtime_lock = _beneath(Path(getattr(runtime, "runtime_lock_path")), generation_root, "runtime lock")
    _, runtime_lock_attestation = _readNoFollow(
        runtime_lock,
        label="runtime lock",
        max_bytes=_MAX_RUNTIME_LOCK_BYTES,
        capture=False,
    )
    runtime_lock_sha256 = _expectDigest(
        runtime_lock_attestation,
        pointer["runtime_lock_sha256"],
        "runtime lock",
    )

    qualification_path = _installedPath(
        pointer["qualification_path"], generation_root, "qualification"
    )
    receipt_raw, receipt_attestation = _readNoFollow(
        qualification_path,
        label="kernel artifact qualification",
        max_bytes=_MAX_RECEIPT_BYTES,
        capture=True,
    )
    _expectDigest(
        receipt_attestation,
        pointer["qualification_sha256"],
        "kernel artifact qualification",
    )
    assert receipt_raw is not None
    receipt = _strictObject(receipt_raw, "kernel artifact qualification")
    _exactKeys(receipt, {"signed_payload", "signature_base64url"}, "qualification wrapper")
    payload = receipt["signed_payload"]
    if not isinstance(payload, dict):
        raise KernelArtifactsUnavailable("qualification signed payload is not an object")
    signature = _signature(receipt["signature_base64url"])
    key_path = _beneath(
        Path(getattr(runtime, "receipt_public_key_path")),
        generation_root,
        "qualification public key",
    )
    public_key, _ = _readNoFollow(
        key_path,
        label="qualification public key",
        max_bytes=32,
        capture=True,
    )
    if public_key is None or len(public_key) != 32 or not verify(public_key, _canonical(payload), signature):
        raise KernelArtifactsUnavailable("qualification signature is invalid")

    _exactKeys(
        payload,
        {
            "schema",
            "status",
            "authority_ceiling",
            "qualification_id",
            "generation",
            "controller_source_revision",
            "runtime_digest",
            "runtime_lock_sha256",
            "issued_at",
            "expires_at",
            "revocation_generation",
            "docker",
            "object_parser",
            "writer",
        },
        "qualification payload",
    )
    if (
        payload["schema"] != "galaxy.kernel-artifact-qualification/v1"
        or payload["status"] != "qualified_staging_only"
        or payload["authority_ceiling"] != "staging_only"
    ):
        raise KernelArtifactsUnavailable("qualification is not staging-only")
    payload_generation = _integer(payload["generation"], "qualification generation", minimum=1)
    payload_revocation = _integer(
        payload["revocation_generation"], "qualification revocation generation"
    )
    if payload_generation != generation or payload_revocation != revocation_generation:
        raise KernelArtifactsUnavailable("qualification generation or revocation binding differs")

    qualification_id = _digestValue(payload["qualification_id"], "qualification id")
    identity_payload = dict(payload)
    identity_payload.pop("qualification_id")
    if hashlib.sha256(_canonical(identity_payload)).hexdigest() != qualification_id:
        raise KernelArtifactsUnavailable("qualification id does not bind the signed payload")
    revision = _text(payload["controller_source_revision"], "controller source revision", maximum=40)
    if _REVISION_RE.fullmatch(revision) is None:
        raise KernelArtifactsUnavailable("controller source revision is not a full revision")
    runtime_digest = _digestValue(payload["runtime_digest"], "qualification runtime digest")
    if runtime_digest != _digestValue(getattr(runtime, "runtime_digest", None), "installed runtime digest"):
        raise KernelArtifactsUnavailable("qualification runtime digest differs")
    if _digestValue(payload["runtime_lock_sha256"], "qualification runtime lock") != runtime_lock_sha256:
        raise KernelArtifactsUnavailable("qualification runtime lock differs")

    issued_text, issued = _timestamp(payload["issued_at"], "qualification issued_at")
    expires_text, expires = _timestamp(payload["expires_at"], "qualification expires_at")
    now = _now()
    if now.tzinfo is None or now.utcoffset() != timedelta(0):
        raise KernelArtifactsUnavailable("qualification verifier clock is not UTC")
    if issued > now:
        raise KernelArtifactsUnavailable("qualification is not yet valid")
    if now >= expires:
        raise KernelArtifactsUnavailable("qualification is expired")
    if expires <= issued or expires - issued > _MAX_QUALIFICATION_LIFETIME:
        raise KernelArtifactsUnavailable("qualification lifetime is not bounded")

    docker = payload["docker"]
    parser = payload["object_parser"]
    writer = payload["writer"]
    if not isinstance(docker, dict) or not isinstance(parser, dict) or not isinstance(writer, dict):
        raise KernelArtifactsUnavailable("qualification artifact records are malformed")
    _exactKeys(
        docker,
        {"executable_path", "executable_sha256", "context", "server_identity_digest"},
        "Docker qualification",
    )
    _exactKeys(
        parser,
        {
            "repository",
            "manifest_digest",
            "archive_path",
            "archive_sha256",
            "config_digest",
            "toolchain_digest",
            "runtime_digest",
            "security_profile_digest",
            "sha1dc_binding_digest",
            "runtime_entrypoint_path",
            "runtime_entrypoint_sha256",
        },
        "object-parser qualification",
    )
    _exactKeys(
        writer,
        {"source_path", "source_sha256", "version_digest", "host_sha1dc"},
        "writer qualification",
    )

    docker_path = _installedPath(docker["executable_path"], generation_root, "Docker executable")
    runtime_docker = _beneath(Path(getattr(runtime, "docker_path")), generation_root, "sealed Docker executable")
    if docker_path != runtime_docker:
        raise KernelArtifactsUnavailable("qualified Docker executable differs from sealed runtime")
    _, docker_before = _readNoFollow(
        docker_path,
        label="Docker executable",
        max_bytes=_MAX_EXECUTABLE_BYTES,
        capture=False,
    )
    docker_sha256 = _expectDigest(docker_before, docker["executable_sha256"], "Docker executable")
    if docker_sha256 != _digestValue(getattr(runtime, "docker_digest", None), "sealed Docker digest"):
        raise KernelArtifactsUnavailable("qualified Docker digest differs from sealed runtime")
    docker_context = _text(docker["context"], "Docker context", maximum=64)
    server_identity = _dockerServerIdentityDigest(docker_path, docker_context)
    if server_identity != _digestValue(docker["server_identity_digest"], "Docker server identity"):
        raise KernelArtifactsUnavailable("Docker server identity differs")
    _, docker_after = _readNoFollow(
        docker_path,
        label="Docker executable",
        max_bytes=_MAX_EXECUTABLE_BYTES,
        capture=False,
    )
    if not _sameIdentity(docker_before, docker_after):
        raise KernelArtifactsUnavailable("Docker executable changed during attestation")

    repository = _text(parser["repository"], "object-parser repository", maximum=255)
    if (
        _REPOSITORY_RE.fullmatch(repository) is None
        or ".." in repository.split("/")
        or repository != "galaxy-r3/object-parser"
    ):
        raise KernelArtifactsUnavailable("object-parser repository is not the reviewed repository")
    archive_path = _installedPath(parser["archive_path"], generation_root, "object-parser archive")
    _, archive_before = _readNoFollow(
        archive_path,
        label="object-parser archive",
        max_bytes=_MAX_OCI_ARCHIVE_BYTES,
        capture=False,
    )
    archive_sha256 = _expectDigest(
        archive_before, parser["archive_sha256"], "object-parser archive"
    )
    try:
        inspection = _inspectObjectParserArchive(archive_path)
    except Exception as exc:
        raise KernelArtifactsUnavailable("object-parser OCI archive inspection failed") from exc
    _, archive_after = _readNoFollow(
        archive_path,
        label="object-parser archive",
        max_bytes=_MAX_OCI_ARCHIVE_BYTES,
        capture=False,
    )
    if not _sameIdentity(archive_before, archive_after):
        raise KernelArtifactsUnavailable("object-parser archive changed during inspection")

    manifest_digest = _digestValue(parser["manifest_digest"], "object-parser manifest")
    config_digest = _digestValue(parser["config_digest"], "object-parser config")
    toolchain_digest = _digestValue(parser["toolchain_digest"], "object-parser toolchain")
    parser_runtime_digest = _digestValue(parser["runtime_digest"], "object-parser runtime")
    security_digest = _digestValue(
        parser["security_profile_digest"], "object-parser security profile"
    )
    if (
        inspection.manifest_digest != manifest_digest
        or inspection.config_digest != config_digest
        or inspection.closure_digests.get("toolchain") != toolchain_digest
        or inspection.closure_digests.get("runtime") != parser_runtime_digest
        or inspection.closure_digests.get("security_profile") != security_digest
    ):
        raise KernelArtifactsUnavailable("object-parser OCI closure differs")
    runtime_document = inspection.closure_documents.get("runtime")
    sha1dc_binding = runtime_document.get("sha1dc_oracle") if isinstance(runtime_document, Mapping) else None
    if not isinstance(sha1dc_binding, dict):
        raise KernelArtifactsUnavailable("object-parser SHA1_DC runtime binding is absent")
    sha1dc_binding_digest = hashlib.sha256(_canonical(sha1dc_binding)).hexdigest()
    if sha1dc_binding_digest != _digestValue(
        parser["sha1dc_binding_digest"], "object-parser SHA1_DC binding"
    ):
        raise KernelArtifactsUnavailable("object-parser SHA1_DC runtime binding differs")

    parser_entrypoint = _installedPath(
        parser["runtime_entrypoint_path"], generation_root, "object-parser entrypoint"
    )
    _, parser_entrypoint_attestation = _readNoFollow(
        parser_entrypoint,
        label="object-parser entrypoint",
        max_bytes=_MAX_RUNTIME_SOURCE_BYTES,
        capture=False,
    )
    parser_entrypoint_sha256 = _expectDigest(
        parser_entrypoint_attestation,
        parser["runtime_entrypoint_sha256"],
        "object-parser entrypoint",
    )
    runtime_parser_entrypoint = _beneath(
        Path(getattr(runtime, "object_parser_entrypoint_path")),
        generation_root,
        "sealed object-parser entrypoint",
    )
    if (
        parser_entrypoint != runtime_parser_entrypoint
        or parser_entrypoint_sha256
        != _digestValue(
            getattr(runtime, "object_parser_entrypoint_digest", None),
            "sealed object-parser entrypoint",
        )
    ):
        raise KernelArtifactsUnavailable(
            "qualified object-parser entrypoint differs from sealed runtime"
        )

    writer_source = _installedPath(writer["source_path"], generation_root, "object writer source")
    _, writer_attestation = _readNoFollow(
        writer_source,
        label="object writer source",
        max_bytes=_MAX_RUNTIME_SOURCE_BYTES,
        capture=False,
    )
    writer_source_sha256 = _expectDigest(
        writer_attestation, writer["source_sha256"], "object writer source"
    )
    runtime_writer_source = _beneath(
        Path(getattr(runtime, "git_object_writer_source_path")),
        generation_root,
        "sealed object writer source",
    )
    if (
        writer_source != runtime_writer_source
        or writer_source_sha256
        != _digestValue(
            getattr(runtime, "git_object_writer_source_digest", None),
            "sealed object writer source",
        )
    ):
        raise KernelArtifactsUnavailable(
            "qualified object writer source differs from sealed runtime"
        )
    writer_version_digest = _digestValue(writer["version_digest"], "object writer version")
    signed_host_sha1dc = writer["host_sha1dc"]
    if not isinstance(signed_host_sha1dc, dict):
        raise KernelArtifactsUnavailable("host SHA1_DC evidence is malformed")
    _exactKeys(
        signed_host_sha1dc,
        {
            "schema",
            "executable_path",
            "executable_sha256",
            "executable_link_count",
            "runtime_attestation_digest",
            "build_evidence_path",
            "build_evidence_sha256",
            "source_revision",
            "protocol",
            "collision_detection",
            "network_allowed",
        },
        "host SHA1_DC evidence",
    )
    host_sha1dc_executable = _installedPath(
        signed_host_sha1dc["executable_path"],
        generation_root,
        "host SHA1_DC executable",
    )
    host_sha1dc_build_evidence = _installedPath(
        signed_host_sha1dc["build_evidence_path"],
        generation_root,
        "host SHA1_DC build evidence",
    )
    host_sha1dc_digest = _digestValue(
        signed_host_sha1dc["executable_sha256"], "host SHA1_DC executable"
    )
    host_sha1dc_build_digest = _digestValue(
        signed_host_sha1dc["build_evidence_sha256"],
        "host SHA1_DC build evidence",
    )
    _integer(signed_host_sha1dc["executable_link_count"], "host SHA1_DC link count", minimum=1)
    _digestValue(
        signed_host_sha1dc["runtime_attestation_digest"],
        "host SHA1_DC runtime attestation",
    )
    source_revision = _text(
        signed_host_sha1dc["source_revision"],
        "host SHA1_DC source revision",
        maximum=40,
    )
    if (
        signed_host_sha1dc["schema"]
        != "galaxy.sha1dc-standalone-evidence/v1"
        or source_revision != "855827c583bc30645ba427885caa40c5b81764d2"
        or signed_host_sha1dc["protocol"]
        != "galaxy.sha1dc-object-oracle/v1"
        or signed_host_sha1dc["collision_detection"] != "SHA1_DC"
        or signed_host_sha1dc["network_allowed"] is not False
    ):
        raise KernelArtifactsUnavailable("host SHA1_DC policy is not closed")
    runtime_sha1dc_executable = _beneath(
        Path(getattr(runtime, "sha1dc_oracle_path")),
        generation_root,
        "sealed SHA1_DC executable",
    )
    runtime_sha1dc_build_evidence = _beneath(
        Path(getattr(runtime, "sha1dc_build_evidence_path")),
        generation_root,
        "sealed SHA1_DC build evidence",
    )
    runtime_sha1dc_source = _beneath(
        Path(getattr(runtime, "sha1dc_runtime_source_path")),
        generation_root,
        "sealed SHA1_DC attestor source",
    )
    _, runtime_sha1dc_source_attestation = _readNoFollow(
        runtime_sha1dc_source,
        label="sealed SHA1_DC attestor source",
        max_bytes=_MAX_RUNTIME_SOURCE_BYTES,
        capture=False,
    )
    runtime_sha1dc_source_digest = _expectDigest(
        runtime_sha1dc_source_attestation,
        getattr(runtime, "sha1dc_runtime_source_digest", None),
        "sealed SHA1_DC attestor source",
    )
    try:
        repository_sha1dc_source = Path(_sha1dc_module.__file__).resolve(strict=True)
    except (OSError, TypeError) as exc:
        raise KernelArtifactsUnavailable(
            "repository SHA1_DC attestor source is unavailable"
        ) from exc
    _, repository_sha1dc_attestation = _readNoFollow(
        repository_sha1dc_source,
        label="repository SHA1_DC attestor source",
        max_bytes=_MAX_RUNTIME_SOURCE_BYTES,
        capture=False,
    )
    if repository_sha1dc_attestation.sha256 != runtime_sha1dc_source_digest:
        raise KernelArtifactsUnavailable(
            "repository SHA1_DC attestor source differs from sealed runtime"
        )
    if (
        host_sha1dc_executable != runtime_sha1dc_executable
        or host_sha1dc_build_evidence != runtime_sha1dc_build_evidence
        or host_sha1dc_digest
        != _digestValue(
            getattr(runtime, "sha1dc_oracle_digest", None),
            "sealed SHA1_DC executable",
        )
        or host_sha1dc_build_digest
        != _digestValue(
            getattr(runtime, "sha1dc_build_evidence_digest", None),
            "sealed SHA1_DC build evidence",
        )
    ):
        raise KernelArtifactsUnavailable(
            "qualified SHA1_DC closure differs from sealed runtime"
        )
    observed_host_sha1dc = dict(_attestHostSha1dc(signed_host_sha1dc))
    if _canonical(observed_host_sha1dc) != _canonical(signed_host_sha1dc):
        raise KernelArtifactsUnavailable("host SHA1_DC evidence differs")

    return VerifiedKernelArtifacts(
        qualification_id=qualification_id,
        authority_ceiling="staging_only",
        generation=generation,
        revocation_generation=revocation_generation,
        controller_source_revision=revision,
        issued_at=issued_text,
        expires_at=expires_text,
        runtime_digest=runtime_digest,
        runtime_lock_sha256=runtime_lock_sha256,
        generation_root=generation_root,
        docker_executable=docker_path,
        docker_executable_sha256=docker_sha256,
        docker_context=docker_context,
        docker_server_identity_digest=server_identity,
        object_parser_repository=repository,
        object_parser_manifest_digest=manifest_digest,
        object_parser_archive=archive_path,
        object_parser_archive_sha256=archive_sha256,
        object_parser_config_digest=config_digest,
        object_parser_toolchain_digest=toolchain_digest,
        object_parser_runtime_digest=parser_runtime_digest,
        object_parser_security_profile_digest=security_digest,
        object_parser_sha1dc_binding_digest=sha1dc_binding_digest,
        object_parser_entrypoint=parser_entrypoint,
        object_parser_entrypoint_sha256=parser_entrypoint_sha256,
        writer_source=writer_source,
        writer_source_sha256=writer_source_sha256,
        writer_version_digest=writer_version_digest,
        host_sha1dc_evidence=MappingProxyType(observed_host_sha1dc),
        _authority_token=_INSTALLED_AUTHORITY_TOKEN,
    )


