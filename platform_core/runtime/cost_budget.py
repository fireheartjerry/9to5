# platform_core/runtime/cost_budget.py
"""Swarmclaw-style per-run cost budget (Epic 1, unit d bolt-on).

Rolling sum over the trajectory cost series; emits an 80%-warn and a hard-ceiling
Event on the live bus. Config-gated (COST_BUDGET_ENABLED, OFF by default) and fail-open:
a budget alert is advisory and NEVER aborts a run.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  CostBudget  -- Accumulate per-run USD; emit one warn + one ceiling event
DEPENDS-ON: config, notifications.event_bus
SIDE-EFFECTS: emits Events on the live bus
RUN/TEST: python -m pytest tests/test_cost_budget.py
"""
from __future__ import annotations

import threading
from typing import Any, Optional

import config

LOG = config.getLogger("runtime.cost_budget")

WARN_FRACTION = 0.80


class CostBudget:
    """Accumulate per-run USD; emit one warn + one ceiling event. Fail-open."""

    def __init__(self, run_id: str, bus: Any = None) -> None:
        self.run_id = run_id
        self._bus = bus
        self._lock = threading.Lock()   # concurrent pool workers call add() for their attempt cost
        self._total = 0.0
        self._warned = False
        self._ceiling_hit = False

    def add(self, cost_usd: Optional[float]) -> None:
        if not getattr(config, "COST_BUDGET_ENABLED", False):
            return
        try:
            if cost_usd is None:
                return
            # Guard the running total + one-shot flags so concurrent adds neither lose total nor
            # double-fire the warn/ceiling events. The bus emit runs OUTSIDE the lock.
            pending: "tuple[str, str] | None" = None
            with self._lock:
                self._total += float(cost_usd)
                ceiling = float(getattr(config, "COST_BUDGET_CEILING_USD", 0.0) or 0.0)
                if ceiling <= 0:
                    return
                if not self._ceiling_hit and self._total >= ceiling:
                    self._ceiling_hit = True
                    pending = ("ceiling", f"run cost ${self._total:.2f} hit ceiling ${ceiling:.2f}")
                elif not self._warned and self._total >= ceiling * WARN_FRACTION:
                    self._warned = True
                    pending = ("warn", f"run cost ${self._total:.2f} >= 80% of ${ceiling:.2f}")
            if pending is not None:
                self._emit(*pending)
        except Exception as e:  # noqa: BLE001 -- budgeting is advisory, never crashes a run
            LOG.warning("cost_budget.add failed (ignored): %s", e)

    def _emit(self, level: str, text: str) -> None:
        try:
            bus = self._bus
            if bus is None:
                from notifications.event_bus import get_bus
                bus = get_bus()
            from notifications.event_bus import Event
            bus.emit(Event(kind="cost_budget", sid=self.run_id, text=text,
                           data={"level": level, "total_usd": round(self._total, 4)}))
        except Exception as e:  # noqa: BLE001
            LOG.warning("cost_budget emit failed (ignored): %s", e)
