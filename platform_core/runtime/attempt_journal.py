def _validate_phase(record: AttemptRecord) -> None:
    phase = record.phase
    missing: list[str] = []

    def require(name: str) -> None:
        if not getattr(record, name):
            missing.append(name)

    if phase is AttemptPhase.RUNNING:
        require("resource_lease_ids")
    elif phase is AttemptPhase.CANDIDATE_CHECKPOINTED:
        for name in ("checkpoint_revision", "checkpoint_ref", "candidate_snapshot_digest", "parser_manifest_digest", "blob_set_digest"):
            require(name)
    elif phase is AttemptPhase.STAGED_PREPARED:
        for name in (
            "staging_receipt_id",
            "proposed_revision",
            "proposed_tree",
            "proposed_diff_digest",
            "staged_ref",
            "staging_manifest_bundle_digest",
            "expected_manifest_digest",
            "proposed_manifest_digest",
        ):
            require(name)
    elif phase is AttemptPhase.VERIFIED:
        for name in ("verification_receipt_id", "verified_revision"):
            require(name)
        if record.verified_revision and record.verified_revision != record.proposed_revision:
            raise InvalidAttemptTransition("verified_revision must equal proposed_revision")
    elif phase is AttemptPhase.PROMOTION_PREPARED:
        require("review_receipt_id")
        if record.tournament_batch_id:
            require("selection_receipt_id")
    elif phase is AttemptPhase.INDEX_FENCED:
        for name in (
            "intent_ref",
            "promotion_plan_digest",
            "proposed_index_digest",
            "proposed_index_path",
            "canonical_index_path",
            "index_fence_path",
            "orig_head_fence_path",
            "index_fence_nonce",
            "index_fence_owner_digest",
            "index_fence_identity_digest",
            "orig_head_fence_owner_digest",
            "orig_head_fence_identity_digest",
            "custom_lock_path",
            "custom_lock_owner_digest",
            "custom_lock_identity_digest",
            "canonical_ref_lock_path",
            "canonical_ref_lock_owner_digest",
            "canonical_ref_lock_identity_digest",
            "materialization_manifest_digest",
            "index_install_sibling",
        ):
            require(name)
    elif phase is AttemptPhase.REF_MOVED:
        for name in ("observed_revision", "resulting_revision"):
            require(name)
        if record.observed_revision and record.observed_revision != record.base_revision:
            raise InvalidAttemptTransition("observed_revision must equal the expected base")
        if record.resulting_revision and record.resulting_revision != record.proposed_revision:
            raise InvalidAttemptTransition("resulting_revision must equal proposed_revision")
    elif phase is AttemptPhase.MATERIALIZED:
        for name in ("canonical_index_digest", "canonical_tree_digest"):
            require(name)
        if record.canonical_index_digest != record.canonical_tree_digest:
            raise InvalidAttemptTransition("canonical index and tree digests must agree")
    elif phase is AttemptPhase.PROMOTED:
        require("promotion_receipt_id")
        if record.resulting_revision != record.proposed_revision:
            raise InvalidAttemptTransition("promoted resulting revision must equal proposed")
    elif phase in _FAILURE_PHASES and not (record.error or record.reconciliation_outcome):
        missing.append("error")
    if missing:
        raise InvalidAttemptTransition(
            f"{phase.value} requires: {', '.join(missing)}"
        )


