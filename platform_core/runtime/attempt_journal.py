def _require_id(value: str, name: str) -> None:
    if not isinstance(value, str) or _ID_RE.fullmatch(value) is None:
        raise ValueError(f"{name} must be a closed portable identifier")


def _require_digest(value: str, name: str, *, optional: bool = False) -> None:
    if optional and value == "":
        return
    if not isinstance(value, str) or _DIGEST_RE.fullmatch(value) is None:
        raise ValueError(f"{name} must be a lowercase SHA-256 digest")


def _require_oid(value: str, name: str, *, optional: bool = False) -> None:
    if optional and value == "":
        return
    if not isinstance(value, str) or _OID_RE.fullmatch(value) is None:
        raise ValueError(f"{name} must be a full lowercase Git object id")


def _require_ref(value: str, name: str, *, optional: bool = False) -> None:
    if optional and value == "":
        return
    if (
        not isinstance(value, str)
        or _REF_RE.fullmatch(value) is None
        or ".." in value
        or "//" in value
        or value.endswith("/")
    ):
        raise ValueError(f"{name} must be a normalized full ref")


def _require_time(value: str, name: str) -> None:
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except (AttributeError, ValueError) as exc:
        raise ValueError(f"{name} must be an ISO-8601 timestamp") from exc
    if parsed.tzinfo is None:
        raise ValueError(f"{name} must include a timezone")


def _reject_json_constant(value: str) -> object:
    raise ValueError(f"non-finite JSON constant is forbidden: {value}")


def _strict_json_bytes(raw: bytes, *, label: str) -> object:
    try:
        return json.loads(
            raw.decode("utf-8"),
            parse_constant=_reject_json_constant,
        )
    except (UnicodeDecodeError, json.JSONDecodeError, ValueError) as exc:
        raise JournalCorruption(f"{label} is not strict JSON") from exc


def _strict_json_text(value: str) -> object:
    return json.loads(value, parse_constant=_reject_json_constant)


@dataclass(frozen=True, slots=True)
class _RuntimeResourceManifestEntry:
    resource_identity: str
    backend: str
    depends_on: tuple[str, ...]


def _manifest_identity(value: object) -> tuple[str, str]:
    if type(value) is not str:
        raise ValueError("resource identity must be a role-tagged string")
    role, separator, resource_id = value.partition(":")
    if not separator or role not in _RUNTIME_RESOURCE_ROLES:
        raise ValueError("resource identity uses an unknown role")
    _require_id(resource_id, "runtime resource manifest identity")
    return role, resource_id


def _runtime_resource_manifest_entries(
    value: str,
    digest: str,
    *,
    runner_kind: str,
) -> tuple[_RuntimeResourceManifestEntry, ...]:
    """Validate the immutable admission manifest without touching storage."""

    if not value and not digest:
        return ()
    if not value or not digest:
        raise ValueError("runtime resource manifest payload and digest must be bound")
    try:
        encoded = value.encode("utf-8", errors="strict")
        if len(encoded) > _MAX_RUNTIME_RESOURCE_MANIFEST_BYTES:
            raise ValueError("manifest exceeds its byte quota")
        payload = _strict_json_text(value)
        if canonical_json_bytes(payload) != encoded:
            raise ValueError("manifest JSON is not canonical")
        if hashlib.sha256(encoded).hexdigest() != digest:
            raise ValueError("manifest digest differs")
        if not isinstance(payload, dict) or set(payload) != {
            "schema",
            "runner_kind",
            "resources",
        }:
            raise ValueError("manifest root schema is not closed")
        if payload["schema"] != _RUNTIME_RESOURCE_MANIFEST_SCHEMA:
            raise ValueError("manifest schema differs")
        if payload["runner_kind"] != runner_kind:
            raise ValueError("manifest runner kind differs")
        resources = payload["resources"]
        if not isinstance(resources, list) or not resources:
            raise ValueError("manifest resources must be a non-empty array")
        if len(resources) > _MAX_RUNTIME_RESOURCE_COUNT:
            raise ValueError("manifest resource count exceeds quota")
        entries: list[_RuntimeResourceManifestEntry] = []
        raw_ids: list[str] = []
        for item in resources:
            if not isinstance(item, dict) or set(item) != {
                "resource_identity",
                "backend",
                "depends_on",
            }:
                raise ValueError("manifest resource entry schema is not closed")
            role, resource_id = _manifest_identity(item["resource_identity"])
            backend = item["backend"]
            if type(backend) is not str or backend not in _RUNTIME_RESOURCE_BACKENDS:
                raise ValueError("manifest resource backend is unknown")
            if role == "credential_lease":
                if backend != "credential-broker":
                    raise ValueError("credential manifest backend differs")
            elif backend == "credential-broker":
                raise ValueError("process manifest cannot use credential backend")
            dependencies = item["depends_on"]
            if not isinstance(dependencies, list) or any(
                type(dependency) is not str for dependency in dependencies
            ):
                raise ValueError("manifest dependencies must be strings")
            dependency_tuple = tuple(dependencies)
            if (
                len(set(dependency_tuple)) != len(dependency_tuple)
                or dependency_tuple != tuple(sorted(dependency_tuple))
            ):
                raise ValueError("manifest dependencies are not canonical")
            if role == "credential_lease" and dependency_tuple:
                raise ValueError(
                    "credential manifest cannot declare dependencies"
                )
            for dependency in dependency_tuple:
                _manifest_identity(dependency)
            if item["resource_identity"] in dependency_tuple:
                raise ValueError("manifest resource cannot depend on itself")
            entries.append(
                _RuntimeResourceManifestEntry(
                    resource_identity=item["resource_identity"],
                    backend=backend,
                    depends_on=dependency_tuple,
                )
            )
            raw_ids.append(resource_id)
        identities = tuple(entry.resource_identity for entry in entries)
        if identities != tuple(sorted(identities)):
            raise ValueError("manifest resources are not canonically ordered")
        if len(set(identities)) != len(identities) or len(set(raw_ids)) != len(raw_ids):
            raise ValueError("manifest resource identities are duplicated")
        identity_set = set(identities)
        if any(
            dependency not in identity_set
            for entry in entries
            for dependency in entry.depends_on
        ):
            raise ValueError("manifest dependency closure is incomplete")

        dependencies_by_identity = {
            entry.resource_identity: entry.depends_on for entry in entries
        }
        visiting: set[str] = set()
        visited: set[str] = set()

        def visit(identity: str) -> None:
            if identity in visiting:
                raise ValueError("manifest dependency graph contains a cycle")
            if identity in visited:
                return
            visiting.add(identity)
            for dependency in dependencies_by_identity[identity]:
                visit(dependency)
            visiting.remove(identity)
            visited.add(identity)

        for identity in identities:
            visit(identity)

        role_entries: dict[str, list[_RuntimeResourceManifestEntry]] = {}
        for entry in entries:
            role_entries.setdefault(
                entry.resource_identity.split(":", 1)[0],
                [],
            ).append(entry)
        if any(len(role_resources) != 1 for role_resources in role_entries.values()):
            raise ValueError("manifest v1 permits only one resource per role")

        if runner_kind == "local":
            required_backends = {
                "authority_watchdog": "local",
                "model_driver": "local",
                "candidate_parser": "docker",
                "verifier": "docker",
            }
            watchdogs = tuple(
                entry
                for entry in entries
                if entry.resource_identity.startswith("authority_watchdog:")
            )
            drivers = tuple(
                entry
                for entry in entries
                if entry.resource_identity.startswith("model_driver:")
            )
            if set(role_entries) != set(required_backends):
                raise ValueError(
                    "local runtime resource manifest differs from its closed required roles"
                )
            if any(
                role_entries[role][0].backend != backend
                for role, backend in required_backends.items()
            ):
                raise ValueError(
                    "local runtime resource manifest role backend differs"
                )
            if len(watchdogs) != 1 or len(drivers) != 1:
                raise ValueError(
                    "local runtime resource manifest requires one authority watchdog "
                    "and one model driver"
                )
            if watchdogs[0].resource_identity not in drivers[0].depends_on:
                raise ValueError(
                    "local runtime resource manifest model driver must depend on "
                    "the authority watchdog"
                )
        elif runner_kind == "docker":
            required_backends = {
                "credential_lease": "credential-broker",
                "authority_watchdog": "docker",
                "model_driver": "docker",
                "broker": "docker",
                "command_sandbox": "docker",
                "candidate_parser": "docker",
                "verifier": "docker",
            }
            if set(role_entries) != set(required_backends):
                raise ValueError(
                    "docker runtime resource manifest differs from its closed required roles"
                )
            if any(
                role_entries[role][0].backend != backend
                for role, backend in required_backends.items()
            ):
                raise ValueError(
                    "docker runtime resource manifest role backend differs"
                )
            watchdogs = tuple(
                entry
                for entry in entries
                if entry.resource_identity.startswith("authority_watchdog:")
            )
            drivers = tuple(
                entry
                for entry in entries
                if entry.resource_identity.startswith("model_driver:")
            )
            if len(watchdogs) != 1 or len(drivers) != 1:
                raise ValueError(
                    "docker runtime resource manifest requires one authority watchdog "
                    "and one model driver"
                )
            if watchdogs[0].resource_identity not in drivers[0].depends_on:
                raise ValueError(
                    "docker runtime resource manifest model driver must depend on "
                    "the authority watchdog"
                )
        return tuple(entries)
    except (TypeError, ValueError, json.JSONDecodeError, UnicodeEncodeError) as exc:
        if isinstance(exc, ValueError) and str(exc).startswith(
            "runtime resource manifest"
        ):
            raise
        raise ValueError(f"runtime resource manifest is invalid: {exc}") from exc


def validateRuntimeResourceManifest(
    value: str,
    digest: str,
    *,
    runner_kind: str,
) -> None:
    """Validate one required admission manifest through the canonical parser."""

    if not _runtime_resource_manifest_entries(
        value,
        digest,
        runner_kind=runner_kind,
    ):
        raise ValueError("runtime resource manifest is required")


def _absolute(value: str, name: str) -> str:
    if not isinstance(value, str) or not os.path.isabs(value):
        raise ValueError(f"{name} must be absolute")
    return os.path.normcase(os.path.abspath(value))


def _is_within(path: str, root: str) -> bool:
    try:
        common = os.path.commonpath((path, root))
    except ValueError:
        return False
    return os.path.normcase(common) == os.path.normcase(root)


def _attempt_lock_owner_alive(pid: int) -> bool:
    """Treat only a positively observed absent lock owner as dead."""

    if not isinstance(pid, int) or pid <= 0:
        return True
    try:
        from platform_core.runtime.candidate import processStartToken

        return processStartToken(pid) is not None
    except Exception:
        return True


def _root_identity(value: str | Path) -> tuple[str, int, int]:
    try:
        path = assertNoReparsePath(value)
        observed = os.stat(path, follow_symlinks=False)
    except OSError as exc:
        raise AttemptPersistenceAuthorityRefused(
            "attempt journal root identity is unavailable"
        ) from exc
    if not stat.S_ISDIR(observed.st_mode):
        raise AttemptPersistenceAuthorityRefused(
            "attempt journal root is not a directory"
        )
    return (
        os.path.normcase(os.path.abspath(path)),
        int(observed.st_dev),
        int(observed.st_ino),
    )


