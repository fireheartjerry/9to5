def _partition_resource_publications(
    directory: NativeDirectoryHandle,
    *,
    label: str,
    max_sequence: int,
    max_bytes: int,
    sequence_max_bytes: tuple[int, ...] | None = None,
) -> _ResourcePublicationInventory:
    """Separate committed events from one recoverable dead publication prefix."""

    entries = _native_entries(directory, label=label)
    finals_by_sequence: dict[int, NativeDirectoryEntry] = {}
    debris_by_sequence: dict[int, list[NativeCreateOnlyDebris]] = {}
    for entry in entries:
        match = _EVENT_RE.fullmatch(entry.name)
        if match is not None:
            if entry.identity.is_directory or entry.identity.link_count != 1:
                raise JournalCorruption(f"{label} contains a non-file artifact")
            sequence = int(match.group("sequence"))
            if sequence in finals_by_sequence:
                raise JournalCorruption(f"{label} sequence is forked")
            if (
                sequence_max_bytes is not None
                and sequence <= max_sequence
                and entry.identity.size > sequence_max_bytes[sequence]
            ):
                raise JournalCorruption(f"{label} event exceeds sequence quota")
            finals_by_sequence[sequence] = entry
            continue
        if not entry.name.startswith(".galaxy-publish-"):
            raise JournalCorruption(f"unknown {label} artifact: {entry.name}")
        try:
            debris = directory.inspectCreateOnlyDebris(
                entry,
                max_bytes=max_bytes,
            )
        except (OSError, ValueError) as exc:
            raise JournalCorruption(f"{label} publication debris is unsafe") from exc
        if debris is None:
            raise JournalCorruption(f"{label} publication debris is malformed")
        if debris.owner_alive:
            raise JournalCorruption(f"{label} publication owner is still live")
        possible_sequences = tuple(
            sequence
            for sequence in range(max_sequence + 1)
            if hashlib.sha256(
                f"{sequence:08d}-{debris.payload_digest}.json".encode("utf-8")
            ).hexdigest()[:32]
            == debris.destination_key
        )
        if len(possible_sequences) != 1:
            raise JournalCorruption(
                f"{label} publication destination is not an allowed event"
            )
        sequence = possible_sequences[0]
        if (
            sequence_max_bytes is not None
            and debris.payload_size > sequence_max_bytes[sequence]
        ):
            raise JournalCorruption(f"{label} publication exceeds sequence quota")
        if (
            len(debris.observed) == debris.payload_size
            and hashlib.sha256(debris.observed).hexdigest()
            != debris.payload_digest
        ):
            raise JournalCorruption(f"{label} complete publication payload differs")
        debris_by_sequence.setdefault(sequence, []).append(debris)

    if len(finals_by_sequence) > max_sequence + 1:
        raise JournalCorruption(f"{label} exceeds event-count quota")
    if any(sequence > max_sequence for sequence in finals_by_sequence):
        raise JournalCorruption(f"{label} sequence is out of range")
    final_sequences = set(finals_by_sequence)
    if final_sequences != set(range(len(final_sequences))):
        raise JournalCorruption(f"{label} sequence is non-contiguous")

    pending: NativeCreateOnlyDebris | None = None
    for sequence, candidates in debris_by_sequence.items():
        final = finals_by_sequence.get(sequence)
        if final is not None:
            expected_name = (
                f"{sequence:08d}-{candidates[0].payload_digest}.json"
            )
            if any(
                candidate.payload_digest != candidates[0].payload_digest
                or candidate.payload_size != candidates[0].payload_size
                for candidate in candidates
            ) or final.name != expected_name:
                raise JournalCorruption(f"{label} publication conflicts with final")
            try:
                final_raw = directory.readFile(
                    final.name,
                    max_bytes=(
                        sequence_max_bytes[sequence]
                        if sequence_max_bytes is not None
                        else max_bytes
                    ),
                    expected=final.identity,
                )
            except (OSError, ValueError) as exc:
                raise JournalCorruption(
                    f"{label} final raced publication inspection"
                ) from exc
            if (
                len(final_raw) != candidates[0].payload_size
                or hashlib.sha256(final_raw).hexdigest()
                != candidates[0].payload_digest
                or any(not final_raw.startswith(candidate.observed) for candidate in candidates)
            ):
                raise JournalCorruption(f"{label} publication differs from final")
            continue
        if pending is not None or len(candidates) != 1:
            raise JournalCorruption(f"{label} pending publication is ambiguous")
        if sequence != len(finals_by_sequence):
            raise JournalCorruption(f"{label} pending publication is non-contiguous")
        pending = candidates[0]

    return _ResourcePublicationInventory(
        finals=tuple(
            finals_by_sequence[sequence]
            for sequence in range(len(finals_by_sequence))
        ),
        pending=pending,
    )


