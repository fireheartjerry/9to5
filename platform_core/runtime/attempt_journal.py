@contextmanager
def _diagnosticPersistenceAccess(label: str) -> Iterator[None]:
    from platform_core.runtime.state_store_worker import (
        StateStoreWorkerRefused,
        _requireDiagnosticAccessLive,
        legacyDiagnosticStateWorkerAccess,
    )

    try:
        with legacyDiagnosticStateWorkerAccess():
            yield
            _requireDiagnosticAccessLive()
    except StateStoreWorkerRefused as exc:
        if "runtime" in str(exc):
            message = f"{label} requires an absent runtime"
        else:
            message = f"{label} is unavailable after controller activation"
        raise AttemptPersistenceAuthorityRefused(message) from exc


def _revalidateDiagnosticPersistenceAccess(label: str) -> None:
    """Recheck held diagnostic truth without entering a second outer fence."""

    from platform_core.runtime.state_store_worker import (
        StateStoreWorkerRefused,
        _requireDiagnosticAccessLive,
    )

    try:
        _requireDiagnosticAccessLive()
    except StateStoreWorkerRefused as exc:
        if "runtime" in str(exc):
            message = f"{label} requires an absent runtime"
        else:
            message = f"{label} is unavailable after controller activation"
        raise AttemptPersistenceAuthorityRefused(message) from exc


@contextmanager
def _installedPersistenceAccess(
    bootstrap_authorities: object,
    label: str,
) -> Iterator[object]:
    from platform_core.runtime.controller_state import (
        _controllerRuntimeConsumerPermit,
    )

    try:
        with _controllerRuntimeConsumerPermit(
            expected_bundle=bootstrap_authorities,
        ) as runtime_binding:
            yield runtime_binding
    except ControllerStateRefused as exc:
        raise AttemptPersistenceAuthorityRefused(
            f"{label} requires the exact live installed runtime bundle"
        ) from exc


_FencedMethod = TypeVar("_FencedMethod", bound=Callable[..., Any])


def _diagnosticPersistenceOperation(method: _FencedMethod) -> _FencedMethod:
    @wraps(method)
    def fenced(self: object, *args: object, **kwargs: object) -> object:
        diagnostic = bool(
            getattr(self, "_diagnostic", False)
            or getattr(self, "_diagnostic_parent", False)
        )
        label = (
            "diagnostic journal"
            if getattr(self, "_diagnostic", False)
            else "diagnostic persistence authority"
        )
        bootstrap_authorities = getattr(self, "_bootstrap_authorities", None)
        access: AbstractContextManager[object | None]
        if diagnostic:
            access = _diagnosticPersistenceAccess(label)
        elif bootstrap_authorities is not None:
            access = _installedPersistenceAccess(
                bootstrap_authorities,
                "installed attempt persistence",
            )
        else:
            raise AttemptPersistenceAuthorityRefused(
                "attempt persistence is not bound to diagnostic or installed authority"
            )
        with access:
            return method(self, *args, **kwargs)

    return cast(_FencedMethod, fenced)


