    @staticmethod
    def _resource_transition_error(
        previous: RuntimeResourceLease,
        current: RuntimeResourceLease,
    ) -> str | None:
        from platform_core.runtime.candidate import (
            CredentialResourceState,
            ProcessResourceState,
            ResourceRole,
        )

        mutable = {
            "state",
            "pid",
            "process_group_id",
            "process_start_token",
            "container_id",
            "secret_fingerprint",
            "error",
            "expires_at",
            "revocation_generation",
            "credential_destruction_receipt_digest",
            "credential_destroyed_at",
            "updated_at",
        }
        for field in fields(previous):
            if field.name not in mutable and getattr(previous, field.name) != getattr(
                current,
                field.name,
            ):
                return f"protected field changed: {field.name}"
        if previous.role is ResourceRole.CREDENTIAL_LEASE:
            if not isinstance(previous.state, CredentialResourceState) or not isinstance(
                current.state,
                CredentialResourceState,
            ):
                return "credential resource carries a process state"
            credential_edges = {
                CredentialResourceState.REGISTERED: {
                    CredentialResourceState.ISSUED,
                    CredentialResourceState.REVOKED_OR_EXPIRED,
                },
                CredentialResourceState.ISSUED: {
                    CredentialResourceState.INJECTED,
                    CredentialResourceState.REVOKED_OR_EXPIRED,
                },
                CredentialResourceState.INJECTED: {
                    CredentialResourceState.REVOKED_OR_EXPIRED,
                },
                CredentialResourceState.REVOKED_OR_EXPIRED: {
                    CredentialResourceState.DESTROYED,
                },
                CredentialResourceState.DESTROYED: set(),
            }
            if current.state not in credential_edges[previous.state]:
                return "state edge is not adjacent or recovery-safe"
        else:
            if not isinstance(previous.state, ProcessResourceState) or not isinstance(
                current.state,
                ProcessResourceState,
            ):
                return "process resource carries a credential state"
            process_edges = {
                ProcessResourceState.REGISTERED: {
                    ProcessResourceState.CREATED,
                    ProcessResourceState.QUIESCED,
                },
                ProcessResourceState.CREATED: {
                    ProcessResourceState.STARTED,
                    ProcessResourceState.QUIESCED,
                },
                ProcessResourceState.STARTED: {
                    ProcessResourceState.QUIESCED,
                },
                ProcessResourceState.QUIESCED: {
                    ProcessResourceState.COLLECTED,
                },
                ProcessResourceState.COLLECTED: set(),
            }
            if current.state not in process_edges[previous.state]:
                return "state edge is not adjacent or recovery-safe"
        if previous.role is ResourceRole.CREDENTIAL_LEASE:
            if not current.expires_at:
                return "credential expiry cannot be removed"
            previous_expiry = datetime.fromisoformat(
                previous.expires_at.replace("Z", "+00:00")
            )
            current_expiry = datetime.fromisoformat(
                current.expires_at.replace("Z", "+00:00")
            )
            if current_expiry > previous_expiry:
                return "credential expiry cannot be extended"
            if current.revocation_generation < previous.revocation_generation:
                return "credential revocation generation cannot move backward"
            if previous.secret_fingerprint:
                if current.secret_fingerprint != previous.secret_fingerprint:
                    return "credential fingerprint is write-once"
            elif current.secret_fingerprint and not (
                previous.state is CredentialResourceState.REGISTERED
                and current.state is CredentialResourceState.ISSUED
            ):
                return "credential fingerprint may be set only on issued transition"
            if (
                current.state is CredentialResourceState.ISSUED
                and not current.secret_fingerprint
            ):
                return "issued credential requires a secret fingerprint"
            if current.state is CredentialResourceState.DESTROYED:
                if (
                    not current.credential_destruction_receipt_digest
                    or not current.credential_destroyed_at
                ):
                    return "destroyed credential requires exact destruction evidence"
            elif (
                current.credential_destruction_receipt_digest
                or current.credential_destroyed_at
            ):
                return "credential destruction evidence is terminal-only"
        if (
            current.role is not ResourceRole.CREDENTIAL_LEASE
            and current.state is ProcessResourceState.CREATED
        ):
            if current.backend == "local":
                if (
                    current.pid <= 0
                    or not current.process_start_token
                    or bool(current.container_id)
                ):
                    return (
                        "created local process must carry exactly one durable "
                        "process identity"
                    )
            elif current.backend == "docker":
                if (
                    not current.container_id
                    or current.pid
                    or current.process_group_id
                    or current.process_start_token
                ):
                    return (
                        "created docker process must carry exactly one durable "
                        "process identity"
                    )
            else:
                return "created process backend kind is unsupported"
        for name in (
            "pid",
            "process_group_id",
            "process_start_token",
            "container_id",
        ):
            old_value = getattr(previous, name)
            if old_value and getattr(current, name) != old_value:
                return f"write-once field changed: {name}"
        return None

