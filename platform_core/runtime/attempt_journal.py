    def _validate_storage_boundaries(self, record: AttemptRecord) -> None:
        root = os.path.normcase(str(self.root))
        canonical = _absolute(record.canonical_root, "canonical_root")
        clone = _absolute(record.clone_path, "clone_path")
        source_payload = _absolute(record.source_payload_root, "source_payload_root")
        if _is_within(root, canonical) or _is_within(canonical, root):
            raise InvalidAttemptTransition("journal root must remain outside canonical")
        if _is_within(root, clone) or _is_within(clone, root):
            raise InvalidAttemptTransition("journal root must remain outside candidate checkout")
        if _is_within(root, source_payload) or _is_within(source_payload, root):
            raise InvalidAttemptTransition("journal root must remain outside source payloads")

