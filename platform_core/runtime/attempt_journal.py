    @classmethod
    def from_dict(cls, value: object) -> AttemptRecord:
        if not isinstance(value, dict):
            raise JournalCorruption("attempt record must be an object")
        expected = {field.name for field in fields(cls)}
        if set(value) != expected:
            raise JournalCorruption("attempt record fields do not match the closed schema")
        payload = dict(value)
        try:
            payload["phase"] = AttemptPhase(payload["phase"])
            payload["resource_lease_ids"] = tuple(payload["resource_lease_ids"])
            payload["reconciliation_receipt_ids"] = tuple(payload["reconciliation_receipt_ids"])
            payload["reconciliation_receipt_outcomes"] = tuple(
                payload["reconciliation_receipt_outcomes"]
            )
            payload["cleanup_receipt_ids"] = tuple(payload["cleanup_receipt_ids"])
            payload["cleanup_receipt_completions"] = tuple(
                payload["cleanup_receipt_completions"]
            )
            return cls(**payload)
        except (TypeError, ValueError, KeyError) as exc:
            raise JournalCorruption("attempt record violates its contract") from exc


