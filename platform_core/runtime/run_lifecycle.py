"""Shared run-liveness transitions used by fresh and resumed launches.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  markRunActive(state: Any, *, pid: int | None=None) -> int  -- Persist the active PID before publishing its heartbeat and return that PID.
DEPENDS-ON: platform_core.runtime.heartbeat
SIDE-EFFECTS: persists task metadata and writes the task heartbeat
RUN/TEST: python -m pytest tests/control/test_run_lifecycle.py
"""
from __future__ import annotations

import os
from typing import Any

from platform_core.runtime import heartbeat


def markRunActive(state: Any, *, pid: int | None = None) -> int:
    """Persist the active PID before publishing its heartbeat and return that PID."""
    active_pid = os.getpid() if pid is None else int(pid)
    state.meta["run_pid"] = active_pid
    state.save()
    heartbeat.writeHeartbeat(state.task_id, pid=active_pid)
    return active_pid
