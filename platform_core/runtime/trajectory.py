# platform_core/runtime/trajectory.py
"""Eliza-style APPEND-ONLY JSONL span recorder (Epic 1, unit d).

One event per line at ``state/trajectories/<run_id>.jsonl``: an ``open`` line when a span
starts and a ``close`` line when it ends -- O(1) IO per event (the old writer rewrote the
ENTIRE span list per event through a FIXED temp name, the exact torn-file race the
unique-temp discipline exists to prevent). ``loadSpans`` replays the log back into the
span tree and still accepts the legacy whole-tree ``.json`` for one release. EVERY
Recorder method swallows its own errors -- the recorder must never crash a run.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Recorder  -- Append-only JSONL span recorder for one run
  loadSpans(run_id: str, root: Optional[Path]=None) -> dict  -- Replay a run's event log into ``{"run_id": ..., "spans": [...]}``.
DEPENDS-ON: config, platform_core.core
SIDE-EFFECTS: writes state/trajectories/<run_id>.jsonl
RUN/TEST: python -m pytest tests/test_trajectory.py
"""
from __future__ import annotations

import json
import threading
import uuid
from pathlib import Path
from typing import Any, Optional

import config
from platform_core.core import clock, jsonl_io

LOG = config.getLogger("runtime.trajectory")

SPAN_KINDS = ("architect", "planner", "executor", "tool", "verify",
              "adversary", "replan", "remediation", "brain")


class Recorder:
    """Append-only JSONL span recorder for one run. Thread-safe; every method is fail-open."""

    def __init__(self, run_id: str, root: Optional[Path] = None) -> None:
        self.run_id = run_id
        self._root = Path(root) if root is not None else (config.STATE_DIR / "trajectories")
        self._lock = threading.Lock()
        self._spans: dict[str, dict[str, Any]] = {}
        self._order: list[str] = []

    def _path(self) -> Path:
        return self._root / f"{self.run_id}.jsonl"

    def openSpan(self, kind: str, parent_id: Optional[str], attrs: Optional[dict] = None,
                 act: Optional[str] = None) -> str:
        """Open a span; returns its step_id (a child of parent_id, or a root span).
        ``act`` is the structured brain-act tag (R5) -- free telemetry on every brain span."""
        step_id = uuid.uuid4().hex
        try:
            span = {
                "step_id": step_id, "parent_id": parent_id,
                "kind": kind if kind in SPAN_KINDS else "tool",
                "attrs": dict(attrs or {}), "act": act, "opened_at": clock.nowIsoLocal(),
                "closed_at": None, "usage": None, "cost_usd": None,
            }
            with self._lock:
                self._spans[step_id] = span
                self._order.append(step_id)
                jsonl_io.appendRecord(self._path(), {
                    "ev": "open", "step_id": step_id, "parent_id": parent_id,
                    "kind": span["kind"], "attrs": span["attrs"], "act": act,
                    "at": span["opened_at"],
                })
        except Exception as e:  # noqa: BLE001 -- recorder must never crash a run
            LOG.warning("trajectory.openSpan failed (ignored): %s", e)
        return step_id

    def closeSpan(self, step_id: str, usage: Optional[dict] = None,
                  cost_usd: Optional[float] = None) -> None:
        """Close a span, attaching its token usage + USD cost (real 0 for local Ollama)."""
        try:
            with self._lock:
                span = self._spans.get(step_id)
                if span is None:
                    return
                span["closed_at"] = clock.nowIsoLocal()
                span["usage"] = usage
                span["cost_usd"] = cost_usd
                jsonl_io.appendRecord(self._path(), {
                    "ev": "close", "step_id": step_id, "at": span["closed_at"],
                    "usage": usage, "cost_usd": cost_usd,
                })
        except Exception as e:  # noqa: BLE001
            LOG.warning("trajectory.closeSpan failed (ignored): %s", e)


def loadSpans(run_id: str, root: Optional[Path] = None) -> dict:
    """Replay a run's event log into ``{"run_id": ..., "spans": [...]}``.

    Prefers the JSONL event log (torn tail lines are skipped, never fatal); falls back to
    the legacy whole-tree ``<run_id>.json`` for one release. Missing/unreadable files
    degrade to an empty span list."""
    base = Path(root) if root is not None else (config.STATE_DIR / "trajectories")
    jsonl_path = base / f"{run_id}.jsonl"
    if jsonl_path.exists():
        events, skipped = jsonl_io.iterRecords(jsonl_path)
        if skipped:
            LOG.warning("trajectory %s: skipped %d unreadable event line(s)", run_id, skipped)
        return {"run_id": run_id, "spans": _replayEvents(events)}
    legacy = base / f"{run_id}.json"   # pre-JSONL format (one-release compat)
    if legacy.exists():
        try:
            data = json.loads(legacy.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                return {"run_id": data.get("run_id", run_id), "spans": data.get("spans", [])}
        except Exception as e:  # noqa: BLE001
            LOG.warning("trajectory %s: legacy .json unreadable (%s)", run_id, e)
    return {"run_id": run_id, "spans": []}


def _replayEvents(events: list) -> list:
    """Fold open/close event lines back into the ordered span list the old writer produced."""
    spans: dict[str, dict[str, Any]] = {}
    order: list[str] = []
    for ev in events:
        if not isinstance(ev, dict):
            continue
        sid = ev.get("step_id")
        if not sid:
            continue
        if ev.get("ev") == "open":
            spans[sid] = {
                "step_id": sid, "parent_id": ev.get("parent_id"), "kind": ev.get("kind"),
                "attrs": ev.get("attrs") or {}, "act": ev.get("act"), "opened_at": ev.get("at"),
                "closed_at": None, "usage": None, "cost_usd": None,
            }
            order.append(sid)
        elif ev.get("ev") == "close" and sid in spans:
            spans[sid]["closed_at"] = ev.get("at")
            spans[sid]["usage"] = ev.get("usage")
            spans[sid]["cost_usd"] = ev.get("cost_usd")
    return [spans[s] for s in order]
