# platform_core/runtime/trajectory.py
"""Eliza-style file-based JSON span-tree trajectory recorder (Epic 1, unit d).

One append-only span tree per run at ``state/trajectories/<run_id>.json``, written with
an atomic tmp+rename so a crash mid-write never corrupts the file. Records a per-step
token/USD cost series with orchestrator->executor spawn linking. EVERY method swallows
its own errors -- the recorder must never crash a run.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Recorder(run_id: str, root=None)  -- Open/close spans; atomic-write the span tree.
DEPENDS-ON: config
SIDE-EFFECTS: writes state/trajectories/<run_id>.json
RUN/TEST: python -m pytest tests/test_trajectory.py
"""
from __future__ import annotations

import json
import os
import threading
import uuid
from datetime import datetime
from pathlib import Path
from typing import Any, Optional

import config

LOG = config.getLogger("runtime.trajectory")

SPAN_KINDS = ("architect", "planner", "executor", "tool", "verify",
              "adversary", "replan", "remediation")


def _nowIso() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


class Recorder:
    """Append-only JSON span tree for one run. Thread-safe; every method is fail-open."""

    def __init__(self, run_id: str, root: Optional[Path] = None) -> None:
        self.run_id = run_id
        self._root = Path(root) if root is not None else (config.STATE_DIR / "trajectories")
        self._lock = threading.Lock()
        self._spans: dict[str, dict[str, Any]] = {}
        self._order: list[str] = []

    def _path(self) -> Path:
        return self._root / f"{self.run_id}.json"

    def openSpan(self, kind: str, parent_id: Optional[str], attrs: Optional[dict] = None) -> str:
        """Open a span; returns its step_id (a child of parent_id, or a root span)."""
        step_id = uuid.uuid4().hex
        try:
            span = {
                "step_id": step_id, "parent_id": parent_id,
                "kind": kind if kind in SPAN_KINDS else "tool",
                "attrs": dict(attrs or {}), "opened_at": _nowIso(),
                "closed_at": None, "usage": None, "cost_usd": None,
            }
            with self._lock:
                self._spans[step_id] = span
                self._order.append(step_id)
                self._flush()
        except Exception as e:  # noqa: BLE001 -- recorder must never crash a run
            LOG.warning("trajectory.openSpan failed (ignored): %s", e)
        return step_id

    def closeSpan(self, step_id: str, usage: Optional[dict] = None,
                  cost_usd: Optional[float] = None) -> None:
        """Close a span, attaching its token usage + USD cost (real 0 for local Ollama)."""
        try:
            with self._lock:
                span = self._spans.get(step_id)
                if span is None:
                    return
                span["closed_at"] = _nowIso()
                span["usage"] = usage
                span["cost_usd"] = cost_usd
                self._flush()
        except Exception as e:  # noqa: BLE001
            LOG.warning("trajectory.closeSpan failed (ignored): %s", e)

    def _flush(self) -> None:
        """Atomic tmp+rename whole-file write (caller holds the lock)."""
        self._root.mkdir(parents=True, exist_ok=True)
        payload = {"run_id": self.run_id,
                   "spans": [self._spans[s] for s in self._order]}
        path = self._path()
        tmp = path.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(payload, ensure_ascii=False, default=str), encoding="utf-8")
        os.replace(tmp, path)
