def processStartToken(pid: int) -> str | None:
    """Return a PID-reuse-safe birth token, or ``None`` when the PID is absent.

    The token is deliberately OS-derived rather than caller-authored.  Windows uses
    the kernel process creation FILETIME.  Linux combines ``/proc`` start ticks with
    the boot identity so a reboot cannot make an old observation look current.
    """

    if type(pid) is not int or pid <= 0:
        raise ValueError("pid must be a positive integer")
    if os.name == "nt":
        import ctypes
        from ctypes import wintypes

        process_query_limited_information = 0x1000
        synchronize = 0x00100000
        error_invalid_parameter = 87
        kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
        kernel32.OpenProcess.argtypes = (
            wintypes.DWORD,
            wintypes.BOOL,
            wintypes.DWORD,
        )
        kernel32.OpenProcess.restype = wintypes.HANDLE
        kernel32.GetProcessTimes.argtypes = (
            wintypes.HANDLE,
            ctypes.POINTER(wintypes.FILETIME),
            ctypes.POINTER(wintypes.FILETIME),
            ctypes.POINTER(wintypes.FILETIME),
            ctypes.POINTER(wintypes.FILETIME),
        )
        kernel32.GetProcessTimes.restype = wintypes.BOOL
        kernel32.CloseHandle.argtypes = (wintypes.HANDLE,)
        kernel32.CloseHandle.restype = wintypes.BOOL
        kernel32.WaitForSingleObject.argtypes = (wintypes.HANDLE, wintypes.DWORD)
        kernel32.WaitForSingleObject.restype = wintypes.DWORD
        handle = kernel32.OpenProcess(
            process_query_limited_information | synchronize,
            False,
            pid,
        )
        if not handle:
            error = ctypes.get_last_error()
            if error == error_invalid_parameter:
                return None
            raise RuntimeResourceProbeRefused(
                f"process {pid} creation time is not observable (winerror={error})"
            )
        creation = wintypes.FILETIME()
        exit_time = wintypes.FILETIME()
        kernel = wintypes.FILETIME()
        user = wintypes.FILETIME()
        running = False
        try:
            if not kernel32.GetProcessTimes(
                handle,
                ctypes.byref(creation),
                ctypes.byref(exit_time),
                ctypes.byref(kernel),
                ctypes.byref(user),
            ):
                error = ctypes.get_last_error()
                raise RuntimeResourceProbeRefused(
                    f"process {pid} creation time changed during observation "
                    f"(winerror={error})"
                )
            wait_result = kernel32.WaitForSingleObject(handle, 0)
            if wait_result == 0:
                return None
            if wait_result != 0x102:
                error = ctypes.get_last_error()
                raise RuntimeResourceProbeRefused(
                    f"process {pid} liveness is not observable "
                    f"(wait={wait_result}, winerror={error})"
                )
            running = True
        finally:
            kernel32.CloseHandle(handle)
        if not running:
            return None
        creation_ticks = (creation.dwHighDateTime << 32) | creation.dwLowDateTime
        return canonical_digest(
            {
                "schema": "galaxy.process-start-token/v1",
                "platform": "windows",
                "pid": pid,
                "creation_filetime": creation_ticks,
            }
        )
    if os.name == "posix" and Path("/proc").is_dir():
        try:
            stat_text = Path(f"/proc/{pid}/stat").read_text(
                encoding="ascii",
                errors="strict",
            )
        except FileNotFoundError:
            return None
        except (OSError, UnicodeError) as exc:
            raise RuntimeResourceProbeRefused(
                f"process {pid} start ticks are not observable"
            ) from exc
        closing = stat_text.rfind(")")
        fields = stat_text[closing + 1 :].split() if closing > 0 else []
        if len(fields) <= 19 or not fields[19].isdigit():
            raise RuntimeResourceProbeRefused("Linux process stat is malformed")
        if fields[0] in {"Z", "X", "x"}:
            return None
        try:
            boot_id = Path("/proc/sys/kernel/random/boot_id").read_text(
                encoding="ascii",
                errors="strict",
            ).strip()
        except (OSError, UnicodeError) as exc:
            raise RuntimeResourceProbeRefused("Linux boot identity is unavailable") from exc
        if re.fullmatch(r"[0-9a-fA-F-]{36}", boot_id) is None:
            raise RuntimeResourceProbeRefused("Linux boot identity is malformed")
        return canonical_digest(
            {
                "schema": "galaxy.process-start-token/v1",
                "platform": "linux",
                "pid": pid,
                "boot_id": boot_id.lower(),
                "start_ticks": int(fields[19]),
            }
        )
    raise RuntimeResourceProbeRefused(
        "this platform has no qualified process-birth observation"
    )


@dataclass(frozen=True, slots=True, kw_only=True)
class CloneQuiescenceProof:
    """Process-local proof that every writer of one private clone has stopped."""

    transaction_id: str
    attempt_id: str
    resource_ids: tuple[str, ...]
    resource_state_digest: str
    all_quiesced: bool
    observed_at: str
    runtime_token: object

    def __post_init__(self) -> None:
        _require_id(self.transaction_id, "transaction_id")
        _require_id(self.attempt_id, "attempt_id")
        if not isinstance(self.resource_ids, tuple) or not self.resource_ids:
            raise ValueError("resource_ids must be a non-empty immutable tuple")
        if len(set(self.resource_ids)) != len(self.resource_ids):
            raise ValueError("quiescence resource identities must be unique")
        valid_roles = {role.value for role in ResourceRole}
        for resource in self.resource_ids:
            if not isinstance(resource, str):
                raise TypeError("quiescence resource identities must be strings")
            role, separator, identity = resource.partition(":")
            if not separator or role not in valid_roles:
                raise ValueError("quiescence resource identity must be role-tagged")
            _require_id(identity, "quiescence resource identity")
        _require_digest(self.resource_state_digest, "resource_state_digest")
        if type(self.all_quiesced) is not bool:
            raise TypeError("all_quiesced must be a bool")
        _require_time(self.observed_at, "observed_at")
        if self.runtime_token is None:
            raise ValueError("quiescence proof requires its process-local runtime token")

    def toDict(self) -> dict[str, Any]:
        return {
            "transaction_id": self.transaction_id,
            "attempt_id": self.attempt_id,
            "resource_ids": list(self.resource_ids),
            "resource_state_digest": self.resource_state_digest,
            "all_quiesced": self.all_quiesced,
            "observed_at": self.observed_at,
        }


class _CloneSnapshotAdmission:
    """One-use, process-local authority for one exact lease/proof pair."""

    __slots__ = (
        "_consumed",
        "_issuer_identity",
        "_issuer",
        "_lease",
        "_lock",
        "_quiescence",
        "_seal",
    )

    def __init__(
        self,
        *,
        lease: CloneLease,
        quiescence: CloneQuiescenceProof,
        issuer: _CloneSnapshotAdmissionIssuer,
        _factory: object,
    ) -> None:
        if _factory is not _SNAPSHOT_ADMISSION_FACTORY:
            raise StagedRevisionRefused(
                "clone snapshot admission requires its sealed issuer"
            )
        if type(issuer) is not _CloneSnapshotAdmissionIssuer:
            raise StagedRevisionRefused(
                "clone snapshot admission requires its exact originating issuer"
            )
        self._lease = lease
        self._quiescence = quiescence
        self._issuer = issuer
        self._issuer_identity = issuer._identity
        self._seal = issuer._seal
        self._consumed = False
        self._lock = threading.Lock()

    def _consume(
        self,
        lease: CloneLease,
        quiescence: CloneQuiescenceProof,
    ) -> None:
        issuer = self._issuer
        if (
            type(issuer) is not _CloneSnapshotAdmissionIssuer
            or self._issuer_identity != issuer._identity
            or self._seal is not issuer._seal
        ):
            raise StagedRevisionRefused(
                "clone snapshot admission originating issuer seal differs"
            )
        issuer._consume(self, lease, quiescence)


class _CloneSnapshotAdmissionIssuer:
    """Kernel-owned issuer for exact one-use snapshot admission."""

    __slots__ = (
        "_admissions",
        "_identity",
        "_lock",
        "_owner",
        "_process_capability",
        "_seal",
    )

    def __init__(
        self,
        *,
        owner: object,
        process_capability: object,
        _factory: object,
    ) -> None:
        with _SNAPSHOT_ISSUER_REGISTRY_LOCK:
            grant = _SNAPSHOT_ISSUER_CONSTRUCTION_GRANTS.pop(id(_factory), None)
        if (
            grant is None
            or grant[0] is not _factory
            or grant[1] is not owner
            or grant[2] is not process_capability
        ):
            raise StagedRevisionRefused(
                "snapshot admission issuer requires trusted kernel composition"
            )
        if process_capability is None:
            raise ValueError("snapshot admission requires a process capability")
        self._owner = owner
        self._process_capability = process_capability
        self._identity = id(self)
        self._seal = object()
        self._admissions: dict[
            int,
            tuple[_CloneSnapshotAdmission, CloneLease, CloneQuiescenceProof],
        ] = {}
        self._lock = threading.Lock()
        with _SNAPSHOT_ISSUER_REGISTRY_LOCK:
            _SNAPSHOT_ISSUERS[id(self)] = (
                self,
                owner,
                process_capability,
                self._seal,
            )

    def _requireRegistered(self) -> None:
        with _SNAPSHOT_ISSUER_REGISTRY_LOCK:
            registered = _SNAPSHOT_ISSUERS.get(id(self))
        if (
            registered is None
            or registered[0] is not self
            or registered[1] is not self._owner
            or registered[2] is not self._process_capability
            or registered[3] is not self._seal
        ):
            raise StagedRevisionRefused(
                "snapshot admission issuer composition is not initialized"
            )

    def issue(
        self,
        lease: CloneLease,
        quiescence: CloneQuiescenceProof,
        *,
        owner: object,
        process_capability: object,
        journal_validation: object = None,
    ) -> _CloneSnapshotAdmission:
        self._requireRegistered()
        if owner is not self._owner or process_capability is not self._process_capability:
            raise StagedRevisionRefused(
                "snapshot admission kernel composition differs"
            )
        try:
            validated = owner._consumeSnapshotJournalValidation(  # type: ignore[attr-defined]
                journal_validation,
                lease,
                quiescence,
            )
        except StagedRevisionRefused:
            raise
        except (AttributeError, TypeError) as exc:
            raise StagedRevisionRefused(
                "snapshot admission requires exact fresh journal validation"
            ) from exc
        if validated is not True:
            raise StagedRevisionRefused(
                "snapshot admission requires exact fresh journal validation"
            )
        if type(lease) is not CloneLease or type(quiescence) is not CloneQuiescenceProof:
            raise StagedRevisionRefused(
                "snapshot admission requires exact lease and quiescence contracts"
            )
        if (
            quiescence.transaction_id != lease.transaction_id
            or quiescence.attempt_id != lease.attempt_id
            or quiescence.runtime_token is not lease.runtime_token
            or not quiescence.all_quiesced
        ):
            raise StagedRevisionRefused(
                "snapshot admission requires exact process-local quiescence"
            )
        admission = _CloneSnapshotAdmission(
            lease=lease,
            quiescence=quiescence,
            issuer=self,
            _factory=_SNAPSHOT_ADMISSION_FACTORY,
        )
        with self._lock:
            self._admissions[id(admission)] = (admission, lease, quiescence)
        return admission

    def _consume(
        self,
        admission: _CloneSnapshotAdmission,
        lease: CloneLease,
        quiescence: CloneQuiescenceProof,
    ) -> None:
        self._requireRegistered()
        with self._lock:
            if admission._consumed:
                raise StagedRevisionRefused(
                    "clone snapshot admission was already consumed"
                )
            registered = self._admissions.pop(id(admission), None)
            if (
                registered is None
                or registered[0] is not admission
                or registered[1] is not lease
                or registered[2] is not quiescence
                or admission._lease is not lease
                or admission._quiescence is not quiescence
            ):
                raise StagedRevisionRefused(
                    "one-use clone snapshot admission binding differs"
                )
            admission._consumed = True


def _createCloneSnapshotAdmissionIssuer(
    *,
    owner: object,
    process_capability: object,
) -> _CloneSnapshotAdmissionIssuer:
    from platform_core.execution.backends.clone import TransactionalCloneKernel

    try:
        composition_live = owner._snapshotAdmissionCompositionLive(  # type: ignore[attr-defined]
            process_capability
        )
    except (AttributeError, TypeError):
        composition_live = False
    if type(owner) is not TransactionalCloneKernel or composition_live is not True:
        raise StagedRevisionRefused(
            "snapshot admission issuer requires an exact live kernel composition"
        )
    grant = object()
    with _SNAPSHOT_ISSUER_REGISTRY_LOCK:
        _SNAPSHOT_ISSUER_CONSTRUCTION_GRANTS[id(grant)] = (
            grant,
            owner,
            process_capability,
        )
    try:
        return _CloneSnapshotAdmissionIssuer(
            owner=owner,
            process_capability=process_capability,
            _factory=grant,
        )
    finally:
        with _SNAPSHOT_ISSUER_REGISTRY_LOCK:
            _SNAPSHOT_ISSUER_CONSTRUCTION_GRANTS.pop(id(grant), None)


def _createNoReparseDirectory(path: Path) -> Path:
    try:
        absolute = assertNoReparsePath(path)
        absolute.mkdir(parents=True, exist_ok=True)
        absolute = assertNoReparsePath(absolute)
        info = os.lstat(absolute)
    except OSError as exc:
        raise StagedRevisionRefused("snapshot directory is not a safe native directory") from exc
    if _isReparse(info) or not stat.S_ISDIR(info.st_mode):
        raise StagedRevisionRefused("snapshot directory is not a safe native directory")
    return absolute


def _createOrVerifyImmutable(path: Path, payload: bytes, *, label: str) -> None:
    try:
        exclusiveCreateBytes(path, payload)
        return
    except FileExistsError:
        pass
    except OSError as exc:
        raise StagedRevisionRefused(f"{label} could not be persisted") from exc
    try:
        observed = readNoFollowBytes(path, max_bytes=max(1, len(payload)))
    except (OSError, ValueError) as exc:
        raise StagedRevisionRefused(f"existing {label} is not immutable evidence") from exc
    if observed != payload:
        raise StagedRevisionRefused(f"{label} immutable-file collision")


def _snapshotMode(info: os.stat_result, expected_mode: int | None) -> int:
    if expected_mode is not None:
        return expected_mode
    return 0o100755 if info.st_mode & 0o111 else 0o100644


def _scanCloneTree(
    checkout: Path,
    *,
    policy: ManifestPolicy,
    expected: ObjectManifest | None,
    wall_timeout_seconds: float,
    idle_timeout_seconds: float,
) -> tuple[tuple[SnapshotEntry, bytes], ...]:
    started = time.monotonic()
    last_progress = started
    expected_modes = (
        {entry.path: entry.mode for entry in expected.entries} if expected is not None else {}
    )
    records: list[tuple[SnapshotEntry, bytes]] = []
    total_bytes = 0

    def snapshot_entries(directory) -> tuple[NativeDirectoryEntry, ...]:
        try:
            return _validatedNativeEntries(directory)
        except PromotionRefused as exc:
            detail = str(exc)
            if "alias" in detail:
                raise StagedRevisionRefused(
                    "candidate snapshot refuses a filesystem alias collision"
                ) from exc
            if "reparse" in detail:
                raise StagedRevisionRefused(
                    "candidate snapshot refuses reparse entries"
                ) from exc
            raise StagedRevisionRefused(
                "candidate directory could not be inventoried exactly"
            ) from exc

    def check_budget() -> None:
        now = time.monotonic()
        if now - started > wall_timeout_seconds:
            raise StagedRevisionRefused("candidate snapshot exceeded its wall-time quota")
        if now - last_progress > idle_timeout_seconds:
            raise StagedRevisionRefused("candidate snapshot exceeded its idle-time quota")

    def walk(
        directory,
        relative_parent: str,
        depth: int,
        root_volume: int,
        root_mount: int,
    ) -> None:
        nonlocal last_progress, total_bytes
        try:
            before = directory.identity
            children = snapshot_entries(directory)
        except (OSError, UnicodeError) as exc:
            raise StagedRevisionRefused("candidate directory could not be walked exactly") from exc
        for child in children:
            check_budget()
            name = child.name
            relative = f"{relative_parent}/{name}" if relative_parent else name
            info = child.identity
            if info.is_reparse:
                raise StagedRevisionRefused("candidate snapshot refuses reparse entries")
            if relative == ".git":
                if not info.is_directory:
                    raise StagedRevisionRefused("private clone Git metadata is not a directory")
                continue
            if info.volume_id != root_volume or info.mount_id != root_mount:
                raise StagedRevisionRefused("candidate snapshot refuses mount boundaries")
            if info.is_directory:
                if depth + 1 > policy.max_depth:
                    raise StagedRevisionRefused("candidate snapshot exceeds depth quota")
                try:
                    with directory.openDirectory(name, expected=info) as child_directory:
                        walk(
                            child_directory,
                            relative,
                            depth + 1,
                            root_volume,
                            root_mount,
                        )
                except StagedRevisionRefused:
                    raise
                except OSError as exc:
                    raise StagedRevisionRefused(
                        "candidate directory identity raced"
                    ) from exc
                continue
            if not stat.S_ISREG(info.mode):
                raise StagedRevisionRefused("candidate snapshot refuses unsupported entries")
            if info.link_count != 1:
                raise StagedRevisionRefused("candidate snapshot refuses multi-link files")
            if info.size > policy.max_file_bytes:
                raise StagedRevisionRefused("candidate snapshot exceeds per-file byte quota")
            if len(records) >= policy.max_files:
                raise StagedRevisionRefused("candidate snapshot exceeds file-count quota")
            if total_bytes + info.size > policy.max_total_bytes:
                raise StagedRevisionRefused("candidate snapshot exceeds aggregate byte quota")
            try:
                payload = directory.readFile(
                    name,
                    max_bytes=policy.max_file_bytes,
                    expected=info,
                )
            except (OSError, ValueError) as exc:
                raise StagedRevisionRefused("candidate file could not be read through one identity") from exc
            if len(payload) != info.size:
                raise StagedRevisionRefused("candidate file identity raced during snapshot")
            digest = hashlib.sha256(payload).hexdigest()
            try:
                canonical_path = relative.replace(os.sep, "/")
                if os.name == "nt":
                    observed_mode = expected_modes.get(canonical_path, 0o100644)
                else:
                    observed_mode = (
                        0o100755 if info.mode & 0o111 else 0o100644
                    )
                entry = SnapshotEntry(
                    path=canonical_path,
                    mode=observed_mode,
                    blob_sha256=digest,
                    size=len(payload),
                )
            except (TypeError, ValueError) as exc:
                raise StagedRevisionRefused("candidate path or mode violates snapshot policy") from exc
            records.append((entry, payload))
            total_bytes += len(payload)
            last_progress = time.monotonic()
        try:
            after = directory.identity
            after_children = snapshot_entries(directory)
        except OSError as exc:
            raise StagedRevisionRefused("candidate directory disappeared during snapshot") from exc
        if after != before or after_children != children:
            raise StagedRevisionRefused("candidate directory identity raced during snapshot")

    try:
        with openNativeDirectory(checkout) as root:
            root_identity = root.identity
            if root_identity.is_reparse or not root_identity.is_directory:
                raise StagedRevisionRefused("candidate checkout is not a native directory")
            walk(
                root,
                "",
                0,
                root_identity.volume_id,
                root_identity.mount_id,
            )
            if root.identity != root_identity:
                raise StagedRevisionRefused("candidate checkout identity raced during snapshot")
    except StagedRevisionRefused:
        raise
    except OSError as exc:
        raise StagedRevisionRefused("candidate checkout is unavailable") from exc
    return tuple(sorted(records, key=lambda item: item[0].path.encode("utf-8")))


def snapshotCloneTree(
    lease: CloneLease,
    *,
    quiescence: CloneQuiescenceProof,
    admission: object = None,
    policy: ManifestPolicy,
    snapshot_root: str | Path,
    expected: ObjectManifest | None = None,
    wall_timeout_seconds: float = 30.0,
    idle_timeout_seconds: float = 5.0,
) -> CandidateSnapshot:
    """Export one quiesced clone into immutable external content-addressed bytes.

    Git metadata and Git-authored syntax are never inputs.  The native walk includes
    every regular worktree file; therefore deletions are represented by omission and
    untracked files cannot disappear behind repository configuration.
    """

    if not isinstance(lease, CloneLease):
        raise TypeError("lease must be CloneLease")
    if not isinstance(quiescence, CloneQuiescenceProof):
        raise TypeError("quiescence must be CloneQuiescenceProof")
    if type(admission) is not _CloneSnapshotAdmission:
        raise StagedRevisionRefused(
            "snapshot requires an exact one-use process-local admission"
        )
    if not isinstance(policy, ManifestPolicy):
        raise TypeError("policy must be ManifestPolicy")
    if expected is not None and not isinstance(expected, ObjectManifest):
        raise TypeError("expected must be an ObjectManifest")
    if expected is not None and expected.policy != policy:
        raise StagedRevisionRefused("snapshot policy differs from expected-tree policy")
    if (
        expected is not None
        and expected.expected_revision != lease.expected_base_revision
    ):
        raise StagedRevisionRefused("expected tree differs from the clone base revision")
    for name, value in (
        ("wall_timeout_seconds", wall_timeout_seconds),
        ("idle_timeout_seconds", idle_timeout_seconds),
    ):
        if not isinstance(value, (int, float)) or isinstance(value, bool) or value <= 0:
            raise ValueError(f"{name} must be positive")
    if (
        quiescence.transaction_id != lease.transaction_id
        or quiescence.attempt_id != lease.attempt_id
        or quiescence.runtime_token is not lease.runtime_token
        or not quiescence.all_quiesced
    ):
        raise StagedRevisionRefused("clone is not exactly and process-locally quiesced")
    registered = datetime.fromisoformat(lease.registered_at.replace("Z", "+00:00"))
    quiesced_at = datetime.fromisoformat(
        quiescence.observed_at.replace("Z", "+00:00")
    )
    if quiesced_at < registered:
        raise StagedRevisionRefused("quiescence predates the executable clone lease")
    if _FILESYSTEM_ID_RE.fullmatch(lease.transaction_id) is None:
        raise StagedRevisionRefused("transaction identity is unsafe for snapshot storage")

    checkout = Path(_absolute(lease.checkout_path, "checkout_path"))
    canonical_git = Path(
        _absolute(lease.canonical_git_common_dir, "canonical_git_common_dir")
    )
    canonical_root = canonical_git.parent
    root = Path(_absolute(os.fspath(snapshot_root), "snapshot_root"))
    checkout_text = os.fspath(checkout)
    canonical_text = os.fspath(canonical_git)
    root_text = os.fspath(root)
    if _is_within(root_text, checkout_text) or _is_within(checkout_text, root_text):
        raise StagedRevisionRefused("snapshot storage must be outside the candidate clone")
    if _is_within(root_text, canonical_text) or _is_within(canonical_text, root_text):
        raise StagedRevisionRefused("snapshot storage must be outside canonical Git")
    canonical_root_text = os.fspath(canonical_root)
    if _is_within(root_text, canonical_root_text) or _is_within(
        canonical_root_text,
        root_text,
    ):
        raise StagedRevisionRefused("snapshot storage must be outside canonical worktree")
    try:
        assertNoReparsePath(root)
    except OSError as exc:
        raise StagedRevisionRefused("snapshot root traverses a reparse point") from exc

    assert isinstance(admission, _CloneSnapshotAdmission)
    admission._consume(lease, quiescence)
    records = _scanCloneTree(
        checkout,
        policy=policy,
        expected=expected,
        wall_timeout_seconds=float(wall_timeout_seconds),
        idle_timeout_seconds=float(idle_timeout_seconds),
    )
    transaction_root = _createNoReparseDirectory(root / lease.transaction_id)
    blob_root = _createNoReparseDirectory(transaction_root / "blobs")
    try:
        snapshot = CandidateSnapshot(
            transaction_id=lease.transaction_id,
            blob_root=blob_root,
            entries=tuple(entry for entry, _payload in records),
            policy=policy,
        )
    except (TypeError, ValueError) as exc:
        raise StagedRevisionRefused(
            f"candidate snapshot violates reserved/path/quota policy: {exc}"
        ) from exc
    manifest_payload = canonical_json_bytes(
        {
            "schema": _CANDIDATE_SNAPSHOT_SCHEMA,
            "transaction_id": lease.transaction_id,
            "attempt_id": lease.attempt_id,
            "repository_id": lease.repository_id,
            "ownership_nonce": lease.ownership_nonce,
            "expected_base_revision": lease.expected_base_revision,
            "quiescence": quiescence.toDict(),
            "policy": policy.toDict(),
            "blob_root": "blobs",
            "snapshot": snapshot.toDict(),
        }
    )
    manifest_path = transaction_root / "snapshot.json"
    if manifest_path.exists():
        try:
            observed_manifest = readNoFollowBytes(
                manifest_path,
                max_bytes=_MAX_SNAPSHOT_MANIFEST_BYTES,
            )
        except (OSError, ValueError) as exc:
            raise StagedRevisionRefused("existing snapshot manifest is unsafe") from exc
        if observed_manifest != manifest_payload:
            raise StagedRevisionRefused("snapshot manifest immutable-file collision")
    for entry, payload in records:
        prefix = _createNoReparseDirectory(blob_root / entry.blob_sha256[:2])
        _createOrVerifyImmutable(
            prefix / entry.blob_sha256,
            payload,
            label="snapshot blob",
        )
    _createOrVerifyImmutable(
        manifest_path,
        manifest_payload,
        label="snapshot manifest",
    )
    fsyncDirectory(transaction_root)
    return snapshot


@dataclass(frozen=True, kw_only=True)
class RuntimeResourceLease:
    resource_id: str
    run_id: str
    transaction_id: str
    controller_scope_id: str
    role: ResourceRole
    backend: str
    ownership_nonce: str
    state: ProcessResourceState | CredentialResourceState
    cleanup_locator_digest: str
    pid: int
    process_group_id: int
    container_id: str
    image_digest: str
    entrypoint_digest: str
    mount_digest: str
    environment_digest: str
    security_profile_digest: str
    created_at: str
    updated_at: str
    provider: str = ""
    auth_mode: str = ""
    secret_channel_id: str = ""
    secret_fingerprint: str = ""
    expires_at: str = ""
    issuer_id: str = ""
    revocation_generation: int = 0
    credential_destruction_receipt_digest: str = ""
    credential_destroyed_at: str = ""
    error: str = ""
    process_start_token: str = ""
    depends_on: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        text_fields = (
            "resource_id",
            "run_id",
            "transaction_id",
            "controller_scope_id",
            "backend",
            "ownership_nonce",
            "cleanup_locator_digest",
            "container_id",
            "image_digest",
            "entrypoint_digest",
            "mount_digest",
            "environment_digest",
            "security_profile_digest",
            "created_at",
            "updated_at",
            "provider",
            "auth_mode",
            "secret_channel_id",
            "secret_fingerprint",
            "expires_at",
            "issuer_id",
            "credential_destruction_receipt_digest",
            "credential_destroyed_at",
            "error",
            "process_start_token",
        )
        for name in text_fields:
            if type(getattr(self, name)) is not str:
                raise TypeError(f"{name} must be str")
        for name in ("pid", "process_group_id", "revocation_generation"):
            if type(getattr(self, name)) is not int:
                raise TypeError(f"{name} must be int")
        if not isinstance(self.depends_on, tuple):
            raise TypeError("depends_on must be an immutable tuple")
        if len(set(self.depends_on)) != len(self.depends_on):
            raise ValueError("depends_on cannot contain duplicates")
        if self.depends_on != tuple(sorted(self.depends_on)):
            raise ValueError("depends_on must use canonical sorted order")
        valid_roles = {role.value for role in ResourceRole}
        for dependency in self.depends_on:
            if type(dependency) is not str:
                raise TypeError("depends_on identities must be strings")
            dependency_role, separator, dependency_id = dependency.partition(":")
            if not separator or dependency_role not in valid_roles:
                raise ValueError("depends_on identities must be role-tagged")
            _require_id(dependency_id, "depends_on resource identity")
        if not self.backend:
            raise ValueError("backend must be nonempty")
        for name in ("resource_id", "run_id", "transaction_id", "controller_scope_id"):
            _require_id(getattr(self, name), name)
        if not isinstance(self.role, ResourceRole):
            raise TypeError("role must be ResourceRole")
        _require_digest(self.ownership_nonce, "ownership_nonce")
        _require_digest(self.cleanup_locator_digest, "cleanup_locator_digest")
        for name in (
            "image_digest",
            "entrypoint_digest",
            "mount_digest",
            "environment_digest",
            "security_profile_digest",
            "secret_fingerprint",
            "process_start_token",
            "credential_destruction_receipt_digest",
        ):
            _require_digest(getattr(self, name), name, optional=True)
        _require_digest(self.container_id, "container_id", optional=True)
        if self.role is ResourceRole.CREDENTIAL_LEASE:
            if not isinstance(self.state, CredentialResourceState):
                raise ValueError("credential lease requires a credential state")
            if self.pid or self.process_group_id or self.container_id or self.process_start_token:
                raise ValueError("credential lease cannot carry process identities")
            if self.state is CredentialResourceState.DESTROYED:
                if not self.credential_destruction_receipt_digest:
                    raise ValueError(
                        "destroyed credential requires a destruction receipt digest"
                    )
                if not self.credential_destroyed_at:
                    raise ValueError(
                        "destroyed credential requires its destruction timestamp"
                    )
                _require_time(
                    self.credential_destroyed_at,
                    "credential_destroyed_at",
                )
            elif (
                self.credential_destruction_receipt_digest
                or self.credential_destroyed_at
            ):
                raise ValueError(
                    "credential destruction evidence is terminal-only"
                )
        elif not isinstance(self.state, ProcessResourceState):
            raise ValueError("process resource requires a process state")
        elif (
            self.credential_destruction_receipt_digest
            or self.credential_destroyed_at
        ):
            raise ValueError(
                "process resource cannot carry credential destruction evidence"
            )
        if self.pid < 0 or self.process_group_id < 0:
            raise ValueError("process identities cannot be negative")
        if self.pid > 0 and not self.process_start_token:
            raise ValueError("positive pid requires process_start_token")
        if self.pid == 0 and self.process_start_token:
            raise ValueError("process_start_token requires a positive pid")
        if (
            self.role is not ResourceRole.CREDENTIAL_LEASE
            and self.state is ProcessResourceState.STARTED
            and not self.pid
            and not self.container_id
        ):
            raise ValueError("started process resource requires a durable identity")
        if self.revocation_generation < 0:
            raise ValueError("revocation_generation cannot be negative")
        _require_time(self.created_at, "created_at")
        _require_time(self.updated_at, "updated_at")
        if self.expires_at:
            _require_time(self.expires_at, "expires_at")

    def toDict(self) -> dict[str, Any]:
        return {field.name: _json_value(getattr(self, field.name)) for field in fields(self)}


def validateRuntimeResourceRegistration(
    resource: RuntimeResourceLease,
) -> RuntimeResourceLease:
    """Validate one pristine role/backend-specific registration contract.

    This is the sole registration-shape validator used before a resource-set
    reservation is created.  Later events retain these plan fields immutably.
    """

    if not isinstance(resource, RuntimeResourceLease):
        raise TypeError("resource must be a RuntimeResourceLease")
    if resource.backend not in {"local", "docker", "credential-broker"}:
        raise ValueError("runtime resource backend kind is unsupported")
    identity = f"{resource.role.value}:{resource.resource_id}"
    if identity in resource.depends_on:
        raise ValueError("runtime resource cannot depend on itself")

    if resource.role is ResourceRole.CREDENTIAL_LEASE:
        if resource.backend != "credential-broker":
            raise ValueError("credential lease requires the credential-broker backend")
        if resource.state is not CredentialResourceState.REGISTERED:
            raise ValueError("credential registration state must be REGISTERED")
        for name in ("provider", "auth_mode", "secret_channel_id", "issuer_id"):
            try:
                _require_id(getattr(resource, name), name)
            except (TypeError, ValueError) as exc:
                label = "secret channel" if name == "secret_channel_id" else name
                raise ValueError(f"credential registration requires {label}") from exc
        if not resource.expires_at:
            raise ValueError("credential registration requires expires_at")
        registered = datetime.fromisoformat(
            resource.created_at.replace("Z", "+00:00")
        )
        expires = datetime.fromisoformat(resource.expires_at.replace("Z", "+00:00"))
        if expires <= registered:
            raise ValueError("credential expires_at must be strictly after registration")
        if resource.revocation_generation < 1:
            raise ValueError("credential revocation_generation must be at least one")
        if not resource.cleanup_locator_digest:
            raise ValueError("credential registration requires cleanup metadata")
        if not resource.security_profile_digest:
            raise ValueError("credential registration requires security metadata")
        if resource.secret_fingerprint:
            raise ValueError("credential registration cannot carry a secret fingerprint")
        if any(
            (
                resource.pid,
                resource.process_group_id,
                bool(resource.container_id),
                bool(resource.process_start_token),
            )
        ):
            raise ValueError("credential registration cannot carry process identity")
        if any(
            (
                resource.image_digest,
                resource.entrypoint_digest,
                resource.mount_digest,
                resource.environment_digest,
            )
        ):
            raise ValueError("credential registration cannot carry a process plan")
        return resource

    if resource.backend == "credential-broker":
        raise ValueError("process resources cannot use the credential-broker backend")
    if resource.state is not ProcessResourceState.REGISTERED:
        raise ValueError("process registration state must be REGISTERED")
    if any(
        (
            resource.pid,
            resource.process_group_id,
            bool(resource.container_id),
            bool(resource.process_start_token),
        )
    ):
        raise ValueError("registered process cannot carry materialized process identity")
    for name in (
        "cleanup_locator_digest",
        "entrypoint_digest",
        "mount_digest",
        "environment_digest",
        "security_profile_digest",
    ):
        if not getattr(resource, name):
            raise ValueError(f"process registration requires {name}")
    if resource.backend == "local" and resource.image_digest:
        raise ValueError("local process registration cannot carry an image digest")
    if resource.backend == "docker" and not resource.image_digest:
        raise ValueError("docker process registration requires image_digest")
    if any(
        (
            resource.provider,
            resource.auth_mode,
            resource.secret_channel_id,
            resource.secret_fingerprint,
            resource.expires_at,
                resource.issuer_id,
                resource.revocation_generation,
                resource.credential_destruction_receipt_digest,
                resource.credential_destroyed_at,
            )
    ):
        raise ValueError("process registration cannot carry credential metadata")
    return resource


def runtimeResourceStateDigest(
    resources: tuple[RuntimeResourceLease, ...],
) -> str:
    """Bind one proof to the exact sorted terminal resource observations."""

    if not isinstance(resources, tuple) or not resources:
        raise ValueError("resources must be a non-empty immutable tuple")
    if not all(isinstance(resource, RuntimeResourceLease) for resource in resources):
        raise TypeError("resources must contain RuntimeResourceLease values")
    identities = tuple((item.role.value, item.resource_id) for item in resources)
    if len(set(identities)) != len(identities):
        raise ValueError("runtime resource identities must be unique")
    ordered = sorted(resources, key=lambda item: (item.role.value, item.resource_id))
    return canonical_digest([resource.toDict() for resource in ordered])


def runtimeResourceWritersAbsent(
    resource: RuntimeResourceLease,
    *,
    container_absence_probe: Callable[[RuntimeResourceLease], bool] | None = None,
) -> bool:
    """Independently re-probe whether the recorded process/container is absent."""

    if not isinstance(resource, RuntimeResourceLease):
        raise TypeError("resource must be RuntimeResourceLease")
    if resource.role is ResourceRole.CREDENTIAL_LEASE:
        raise RuntimeResourceProbeRefused(
            "credential revocation requires its typed authority adapter"
        )
    process_quiesced = True
    if resource.pid > 0:
        observed = processStartToken(resource.pid)
        process_quiesced = observed is None or observed != resource.process_start_token
    elif resource.state in {
        ProcessResourceState.CREATED,
        ProcessResourceState.STARTED,
    } and not resource.container_id:
        raise RuntimeResourceProbeRefused(
            "created process resource has no durable process identity"
        )
    if not process_quiesced:
        return False
    if resource.container_id:
        if container_absence_probe is None:
            raise RuntimeResourceProbeRefused(
                "container absence requires a sealed independent probe"
            )
        absent = container_absence_probe(resource)
        if type(absent) is not bool:
            raise RuntimeResourceProbeRefused(
                "container absence probe returned an untyped observation"
            )
        return absent
    return True


def runtimeResourceIsQuiescent(
    resource: RuntimeResourceLease,
    *,
    container_absence_probe: Callable[[RuntimeResourceLease], bool] | None = None,
    credential_absence_verifier: object | None = None,
) -> bool:
    """Require both a terminal journal state and independent writer absence."""

    if not isinstance(resource, RuntimeResourceLease):
        raise TypeError("resource must be RuntimeResourceLease")
    if resource.role is ResourceRole.CREDENTIAL_LEASE:
        if resource.state is not CredentialResourceState.DESTROYED:
            return False
        if credential_absence_verifier is None:
            return False
        from platform_core.runtime.credential_channel import (
            CredentialChannelAbsenceObservation,
            CredentialChannelAbsenceVerifier,
            CredentialChannelEvidenceRefused,
        )

        if type(credential_absence_verifier) is not CredentialChannelAbsenceVerifier:
            raise RuntimeResourceProbeRefused(
                "credential absence requires the exact sealed typed verifier"
            )
        exact_verifier = cast(Any, credential_absence_verifier)
        try:
            observation = exact_verifier.verify(resource)
        except CredentialChannelEvidenceRefused as exc:
            raise RuntimeResourceProbeRefused(
                "credential channel absence could not be proven freshly"
            ) from exc
        if type(observation) is not CredentialChannelAbsenceObservation:
            raise RuntimeResourceProbeRefused(
                "credential absence verifier returned an untyped observation"
            )
        return True
    if resource.state not in {
        ProcessResourceState.QUIESCED,
        ProcessResourceState.COLLECTED,
    }:
        return False
    return runtimeResourceWritersAbsent(
        resource,
        container_absence_probe=container_absence_probe,
    )


