def _operationManifestDigest(
    transaction_id: str,
    expected: ObjectManifest,
    proposed: ObjectManifest,
) -> str:
    expected_by_path = {entry.path: entry for entry in expected.entries}
    proposed_by_path = {entry.path: entry for entry in proposed.entries}
    operations: list[dict[str, object]] = []
    for path in sorted(set(expected_by_path) | set(proposed_by_path)):
        before = expected_by_path.get(path)
        after = proposed_by_path.get(path)
        if before == after:
            continue
        operations.append(
            {
                "path": path,
                "before": None if before is None else before.toDict(),
                "after": None if after is None else after.toDict(),
            }
        )
    return canonical_digest(
        {
            "schema": "galaxy.materialization-operations/v1",
            "transaction_id": transaction_id,
            "expected_manifest_digest": expected.manifest_digest,
            "proposed_manifest_digest": proposed.manifest_digest,
            "operations": operations,
        }
    )


