@dataclass(frozen=True)
class _OwnedFile:
    path: Path
    payload: bytes
    identity: NativeFileIdentity

    @property
    def identity_digest(self) -> str:
        return canonical_digest(
            {
                "path": os.path.normcase(str(self.path.resolve(strict=False))),
                "volume_id": self.identity.volume_id,
                "mount_id": self.identity.mount_id,
                "file_id": self.identity.file_id,
                "is_directory": self.identity.is_directory,
                "is_reparse": self.identity.is_reparse,
                "reparse_tag": self.identity.reparse_tag,
                "payload_sha256": hashlib.sha256(self.payload).hexdigest(),
            }
        )


def _acquireOwnedFile(path: Path, payload: bytes) -> _OwnedFile:
    try:
        assertNoReparsePath(path.parent)
        with openNativeDirectory(path.parent) as parent:
            identity = parent.createFile(path.name, payload)
            observed = parent.readFile(
                path.name,
                max_bytes=len(payload),
                expected=identity,
            )
    except FileExistsError as exc:
        raise PromotionRefused(f"landing fence is already owned: {path}") from exc
    except (OSError, ValueError) as exc:
        raise PromotionRefused(f"landing fence path is unsafe: {path}") from exc
    if (
        identity.is_reparse
        or identity.is_directory
        or identity.link_count != 1
        or observed != payload
    ):
        raise PromotionRefused(f"landing fence ownership is unverifiable: {path}")
    return _OwnedFile(
        path=path,
        payload=payload,
        identity=identity,
    )


def _releaseOwnedFile(owned: _OwnedFile) -> None:
    try:
        with openNativeDirectory(owned.path.parent) as parent:
            if parent.readFile(
                owned.path.name,
                max_bytes=len(owned.payload),
                expected=owned.identity,
            ) != owned.payload:
                raise PromotionRefused(
                    "refusing to remove a landing fence with changed ownership: "
                    f"{owned.path}"
                )
            parent.removeFile(owned.path.name, expected=owned.identity)
    except FileNotFoundError:
        return
    except (OSError, ValueError) as exc:
        raise PromotionRefused(
            f"refusing to remove a landing fence with changed ownership: {owned.path}"
        ) from exc


def _recoverOwnedFile(
    path: Path,
    payload: bytes,
    expected_identity_digest: str,
) -> _OwnedFile:
    owned = _inspectOwnedFile(path, payload)
    if owned.identity_digest != expected_identity_digest:
        raise PromotionRecoveryRequired(
            f"durable landing fence identity differs: {path}"
        )
    return owned


def _inspectOwnedFile(path: Path, payload: bytes) -> _OwnedFile:
    """Recover exact retained-handle identity without yet claiming ownership."""

    try:
        with openNativeDirectory(path.parent) as parent:
            matches = [entry for entry in parent.listEntries() if entry.name == path.name]
            if len(matches) != 1:
                raise OSError("owned file is absent or ambiguous")
            identity = matches[0].identity
            if (
                identity.is_reparse
                or identity.is_directory
                or identity.link_count != 1
                or parent.readFile(
                    path.name,
                    max_bytes=len(payload),
                    expected=identity,
                )
                != payload
            ):
                raise OSError("owned file contract differs")
    except (OSError, ValueError) as exc:
        raise PromotionRecoveryRequired(
            f"durable landing fence is missing or changed: {path}"
        ) from exc
    owned = _OwnedFile(
        path=path,
        payload=payload,
        identity=identity,
    )
    return owned


def _recoverOptionalOwnedFile(
    path: Path,
    payload: bytes,
    expected_identity_digest: str,
    *,
    allow_planned_adoption: bool = False,
) -> _OwnedFile | None:
    try:
        with openNativeDirectory(path.parent) as parent:
            present = any(entry.name == path.name for entry in parent.listEntries())
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise PromotionRecoveryRequired(
            f"durable landing fence cannot be enumerated: {path}"
        ) from exc
    if not present:
        return None
    if not expected_identity_digest:
        if allow_planned_adoption:
            return _inspectOwnedFile(path, payload)
        raise PromotionRecoveryRequired(
            f"durable landing fence exists without a journaled identity: {path}"
        )
    return _recoverOwnedFile(path, payload, expected_identity_digest)


@contextmanager
def _promotionProcessLease(path: Path):
    """Hold an OS byte-range lock for the whole promotion/recovery transaction."""

    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        assertNoReparsePath(path.parent)
        flags = os.O_RDWR | os.O_CREAT
        if hasattr(os, "O_BINARY"):
            flags |= os.O_BINARY
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        fd = os.open(path, flags, 0o600)
    except OSError as exc:
        raise _PromotionProcessLeaseBusy(
            "promotion process lease is unavailable"
        ) from exc
    handle = os.fdopen(fd, "r+b", buffering=0)
    locked = False
    try:
        info = os.fstat(handle.fileno())
        visible = os.lstat(path)
        if (
            not stat.S_ISREG(info.st_mode)
            or _isReparse(visible)
            or not stat.S_ISREG(visible.st_mode)
            or (info.st_dev, info.st_ino) != (visible.st_dev, visible.st_ino)
        ):
            raise _PromotionProcessLeaseBusy(
                "promotion process lease identity is unsafe"
            )
        if info.st_size == 0:
            handle.write(b"\0")
            handle.flush()
            os.fsync(handle.fileno())
        handle.seek(0)
        try:
            if os.name == "nt":
                import msvcrt

                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl

                flock = getattr(fcntl, "flock")
                flock(
                    handle.fileno(),
                    int(getattr(fcntl, "LOCK_EX")) | int(getattr(fcntl, "LOCK_NB")),
                )
        except OSError as exc:
            raise _PromotionProcessLeaseBusy(
                "promotion process is still active"
            ) from exc
        locked = True
        yield
    finally:
        if locked:
            handle.seek(0)
            try:
                if os.name == "nt":
                    import msvcrt

                    msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
                else:
                    import fcntl

                    getattr(fcntl, "flock")(
                        handle.fileno(),
                        int(getattr(fcntl, "LOCK_UN")),
                    )
            except OSError:
                pass
        handle.close()


