def _entryPayload(writer: GitObjectWriter, entry: Any) -> bytes:
    path = writer.blob_root / entry.blob_sha256[:2] / entry.blob_sha256
    try:
        raw = readNoFollowBytes(path, max_bytes=entry.size)
    except (OSError, ValueError) as exc:
        raise PromotionRefused(f"sealed blob is unavailable: {entry.path}") from exc
    if len(raw) != entry.size or hashlib.sha256(raw).hexdigest() != entry.blob_sha256:
        raise PromotionRefused(f"sealed blob content drifted: {entry.path}")
    return raw


def _filesystemAliasKey(name: str) -> str:
    return unicodedata.normalize("NFC", name).casefold().rstrip(" .")


_DOS_8DOT3_SAFE_COMPONENT_RE = re.compile(
    r"^[A-Za-z0-9_$%'-]{1,8}(?:\.[A-Za-z0-9_$%'-]{1,3})?$"
)


def _windowsShortNamesMayBeGenerated(root: Path) -> bool:
    """Conservatively resolve whether this target volume may mint 8.3 aliases."""

    if os.name != "nt":
        return False
    try:
        import winreg

        with winreg.OpenKey(
            winreg.HKEY_LOCAL_MACHINE,
            r"SYSTEM\CurrentControlSet\Control\FileSystem",
        ) as key:
            value, _kind = winreg.QueryValueEx(
                key,
                "NtfsDisable8dot3NameCreation",
            )
    except (OSError, TypeError, ValueError):
        return True
    if type(value) is not int:
        return True
    if value == 1:
        return False
    if value == 3:
        system_root = Path(os.environ.get("SystemRoot", r"C:\Windows"))
        return root.drive.casefold() == system_root.drive.casefold()
    # State 0 enables aliases.  State 2 is per-volume and has no stable
    # standard-library query, so it remains conservatively enabled.
    return True


def _windowsLongPathsEnabled() -> bool:
    if os.name != "nt":
        return True
    try:
        import winreg

        with winreg.OpenKey(
            winreg.HKEY_LOCAL_MACHINE,
            r"SYSTEM\CurrentControlSet\Control\FileSystem",
        ) as key:
            value, _kind = winreg.QueryValueEx(key, "LongPathsEnabled")
    except (OSError, TypeError, ValueError):
        return False
    return type(value) is int and value == 1


def _manifestNodeKinds(manifest: ObjectManifest) -> dict[tuple[str, ...], str]:
    nodes: dict[tuple[str, ...], str] = {(): "directory"}
    for entry in manifest.entries:
        parts = tuple(entry.path.split("/"))
        for index in range(1, len(parts)):
            nodes[parts[:index]] = "directory"
        nodes[parts] = "file"
    return nodes


def _filesystemRepresentationPlanDigest(
    canonical_root: Path,
    expected: ObjectManifest,
    proposed: ObjectManifest,
) -> str:
    root = Path(os.path.abspath(canonical_root))
    expected_nodes = _manifestNodeKinds(expected)
    proposed_nodes = _manifestNodeKinds(proposed)
    changed_nodes = tuple(
        sorted(
            (
                ("/".join(parts), kind)
                for parts, kind in proposed_nodes.items()
                if parts and expected_nodes.get(parts) != kind
            ),
            key=lambda item: item[0].encode("utf-8"),
        )
    )
    short_names_may_generate = _windowsShortNamesMayBeGenerated(root)
    long_paths_enabled = _windowsLongPathsEnabled()
    if os.name == "nt":
        maximum_units = 32_767 if long_paths_enabled else 259
        for parts, _kind in sorted(
            ((parts, kind) for parts, kind in proposed_nodes.items() if parts),
            key=lambda item: "/".join(item[0]).encode("utf-8"),
        ):
            absolute = os.fspath(root.joinpath(*parts))
            units = len(absolute.encode("utf-16-le", errors="strict")) // 2
            if units > maximum_units:
                raise PromotionRefused(
                    "proposed path is not representable on the canonical Windows volume"
                )
        if short_names_may_generate:
            for path, _kind in changed_nodes:
                component = path.rsplit("/", 1)[-1]
                if _DOS_8DOT3_SAFE_COMPONENT_RE.fullmatch(component) is None:
                    raise PromotionRefused(
                        "proposed component requires an unproven generated short-name alias"
                    )
    return canonical_digest(
        {
            "schema": "galaxy.filesystem-representation-plan/v1",
            "canonical_root": os.fspath(root),
            "platform": os.name,
            "short_names_may_generate": short_names_may_generate,
            "long_paths_enabled": long_paths_enabled,
            "changed_nodes": [
                {"path": path, "kind": kind} for path, kind in changed_nodes
            ],
        }
    )


def _validateProspectiveFilesystemRepresentation(
    canonical_root: Path,
    expected: ObjectManifest,
    proposed: ObjectManifest,
) -> str:
    """Prove every proposed name before CAS against actual retained aliases."""

    digest = _filesystemRepresentationPlanDigest(
        canonical_root,
        expected,
        proposed,
    )
    if os.name != "nt":
        return digest
    expected_nodes = _manifestNodeKinds(expected)
    proposed_nodes = _manifestNodeKinds(proposed)
    changed = [
        parts
        for parts, kind in proposed_nodes.items()
        if parts and expected_nodes.get(parts) != kind
    ]
    try:
        with openNativeDirectory(canonical_root) as root:
            for parts in sorted(changed, key=lambda value: (len(value), value)):
                parent = parts[:-1]
                if parent and expected_nodes.get(parent) != "directory":
                    continue
                with _nativeDirectoryPath(root, parent, create=False) as directory:
                    entries = _validatedNativeEntries(directory)
                    requested = _filesystemAliasKey(parts[-1])
                    for entry in entries:
                        aliases = {
                            _filesystemAliasKey(entry.name),
                            *(
                                {_filesystemAliasKey(entry.short_name)}
                                if entry.short_name
                                else set()
                            ),
                        }
                        if requested not in aliases:
                            continue
                        existing_parts = parent + (entry.name,)
                        if existing_parts == parts and parts in expected_nodes:
                            break
                        raise PromotionRefused(
                            "proposed path collides with an actual long/short-name alias"
                        )
    except PromotionRefused:
        raise
    except OSError as exc:
        raise PromotionRefused(
            "prospective filesystem representation could not be proven"
        ) from exc
    return digest


def _sameNativeObject(left: Any, right: Any) -> bool:
    return (
        left.volume_id,
        left.file_id,
        left.is_directory,
        left.is_reparse,
        left.mount_id,
        left.reparse_tag,
    ) == (
        right.volume_id,
        right.file_id,
        right.is_directory,
        right.is_reparse,
        right.mount_id,
        right.reparse_tag,
    )


def _validatedNativeEntries(
    directory: NativeDirectoryHandle,
) -> tuple[NativeDirectoryEntry, ...]:
    try:
        entries = directory.listEntries()
    except (OSError, UnicodeError) as exc:
        raise PromotionRefused("native directory enumeration failed") from exc
    aliases: dict[str, tuple[str, int]] = {}
    for entry in entries:
        if entry.identity.is_reparse:
            raise PromotionRefused(f"native tree contains a reparse entry: {entry.name}")
        for value in (entry.name, entry.short_name):
            if not value:
                continue
            key = _filesystemAliasKey(value)
            if not key:
                raise PromotionRefused("native tree contains an empty filesystem alias")
            prior = aliases.get(key)
            identity = (entry.name, entry.identity.file_id)
            if prior is not None and prior != identity:
                raise PromotionRefused(
                    f"native tree contains a long/short-name alias collision: {entry.name}"
                )
            aliases[key] = identity
    return entries


def _nativeEntry(
    directory: NativeDirectoryHandle,
    name: str,
    *,
    required: bool = True,
) -> NativeDirectoryEntry | None:
    entries = _validatedNativeEntries(directory)
    exact = [entry for entry in entries if entry.name == name]
    if len(exact) == 1:
        return exact[0]
    requested = _filesystemAliasKey(name)
    if any(
        requested in {_filesystemAliasKey(entry.name), _filesystemAliasKey(entry.short_name)}
        for entry in entries
        if entry.short_name
    ) or any(requested == _filesystemAliasKey(entry.name) for entry in entries):
        raise PromotionRefused(f"canonical path resolves only through an alias: {name}")
    if required:
        raise PromotionRefused(f"canonical path is missing: {name}")
    return None


@contextmanager
def _nativeDirectoryPath(
    root: NativeDirectoryHandle,
    parts: tuple[str, ...],
    *,
    create: bool,
):
    opened: list[NativeDirectoryHandle] = []
    current = root
    root_identity = root.identity
    try:
        for part in parts:
            entry = _nativeEntry(current, part, required=False)
            try:
                child = (
                    current.createDirectory(part)
                    if entry is None and create
                    else current.openDirectory(
                        part,
                        expected=None if entry is None else entry.identity,
                    )
                )
            except (FileExistsError, FileNotFoundError, OSError, ValueError) as exc:
                raise PromotionRefused(
                    f"canonical path ancestor is not a stable directory: {part}"
                ) from exc
            if (
                child.identity.volume_id != root_identity.volume_id
                or child.identity.mount_id != root_identity.mount_id
            ):
                child.close()
                raise PromotionRefused(
                    f"canonical path ancestor crosses a volume boundary: {part}"
                )
            opened.append(child)
            current = child
        yield current
    finally:
        for child in reversed(opened):
            child.close()


def _verifyCanonicalHandle(
    root: NativeDirectoryHandle,
    manifest: ObjectManifest,
) -> str:
    expected = {entry.path: entry for entry in manifest.entries}
    expected_directories = _expectedDirectories(manifest)
    observed: dict[str, dict[str, object]] = {}
    root_identity = root.identity
    identities: list[dict[str, object]] = [
        {"path": "", "short_name": "", **_nativeIdentityEvidence(root_identity)}
    ]

    def walk(directory: NativeDirectoryHandle, prefix: str) -> None:
        before = directory.identity
        children = _validatedNativeEntries(directory)
        for child in children:
            if not prefix and child.name == ".git":
                if not child.identity.is_directory:
                    raise PromotionRefused("canonical Git metadata is not a directory")
                continue
            relative = f"{prefix}/{child.name}" if prefix else child.name
            identities.append(
                {
                    "path": relative,
                    "short_name": child.short_name,
                    **_nativeIdentityEvidence(child.identity),
                }
            )
            if (
                child.identity.volume_id != root_identity.volume_id
                or child.identity.mount_id != root_identity.mount_id
            ):
                raise PromotionRefused(
                    f"canonical worktree contains a mount escape: {relative}"
                )
            if child.identity.is_directory:
                if relative not in expected_directories:
                    raise PromotionRefused(
                        f"canonical worktree contains untracked directory: {relative}"
                    )
                try:
                    with directory.openDirectory(
                        child.name,
                        expected=child.identity,
                    ) as nested:
                        walk(nested, relative)
                except PromotionRefused:
                    raise
                except OSError as exc:
                    raise PromotionRefused(
                        f"canonical worktree directory raced: {relative}"
                    ) from exc
                continue
            if not stat.S_ISREG(child.identity.mode) or child.identity.link_count != 1:
                raise PromotionRefused(
                    f"canonical worktree contains unsupported entry: {relative}"
                )
            item = expected.get(relative)
            if item is None:
                raise PromotionRefused(
                    f"canonical worktree contains untracked file: {relative}"
                )
            try:
                raw = directory.readFile(
                    child.name,
                    max_bytes=item.size,
                    expected=child.identity,
                )
            except (OSError, ValueError) as exc:
                raise PromotionRefused(
                    f"canonical worktree file is unsafe or over quota: {relative}"
                ) from exc
            if len(raw) != item.size or hashlib.sha256(raw).hexdigest() != item.blob_sha256:
                raise PromotionRefused(
                    f"canonical worktree bytes differ from manifest: {relative}"
                )
            if os.name != "nt":
                executable = bool(child.identity.mode & 0o111)
                if executable != (item.mode == 0o100755):
                    raise PromotionRefused(
                        f"canonical worktree mode differs from manifest: {relative}"
                    )
            observed[relative] = {
                "path": relative,
                "mode": item.mode,
                "blob_sha256": item.blob_sha256,
                "size": item.size,
            }
        if directory.identity != before or _validatedNativeEntries(directory) != children:
            raise PromotionRefused("canonical worktree directory raced enumeration")

    walk(root, "")
    if set(observed) != set(expected):
        missing = sorted(set(expected) - set(observed))
        raise PromotionRefused(f"canonical worktree omits tracked paths: {missing[:3]}")
    if root.identity != root_identity:
        raise PromotionRefused("canonical worktree root identity changed")
    return canonical_digest(
        {
            "manifest_digest": manifest.manifest_digest,
            "entries": [observed[path] for path in sorted(observed)],
            "native_identity_map": sorted(
                identities,
                key=lambda record: str(record["path"]).encode("utf-8"),
            ),
        }
    )


def _ensureOwnedDirectory(root: Path, relative: str) -> Path:
    current = root
    for part in relative.split("/") if relative else ():
        current /= part
        try:
            info = os.lstat(current)
        except FileNotFoundError:
            try:
                os.mkdir(current)
            except OSError as exc:
                raise PromotionRefused(
                    f"could not create canonical directory: {relative}"
                ) from exc
            info = os.lstat(current)
            fsyncDirectory(current.parent)
        if _isReparse(info) or not stat.S_ISDIR(info.st_mode):
            raise PromotionRefused(
                f"canonical path ancestor is not a normal directory: {relative}"
            )
    return current


def _materializationTempPath(
    canonical_root: Path,
    *,
    transaction_id: str,
    fence_nonce: str,
    path: str,
) -> Path:
    target = canonical_root.joinpath(*path.split("/"))
    temp_digest = hashlib.sha256(
        f"{transaction_id}\0{fence_nonce}\0{path}".encode("utf-8")
    ).hexdigest()[:24]
    return target.with_name(f".{target.name}.galaxy-{temp_digest}.new")


def _assertRecoverablePartialWorktree(
    *,
    canonical_root: Path,
    transaction_id: str,
    fence_nonce: str,
    expected: ObjectManifest,
    proposed: ObjectManifest,
) -> None:
    """Accept only exact expected/proposed bytes and deterministic owned temps."""

    root = assertNoReparsePath(canonical_root)
    root_info = os.lstat(root)
    expected_by_path = {entry.path: entry for entry in expected.entries}
    proposed_by_path = {entry.path: entry for entry in proposed.entries}
    changed = {
        path
        for path in set(expected_by_path) | set(proposed_by_path)
        if expected_by_path.get(path) != proposed_by_path.get(path)
    }
    temp_entries: dict[str, Any] = {}
    for path in changed:
        after = proposed_by_path.get(path)
        if after is None:
            continue
        temporary = _materializationTempPath(
            root,
            transaction_id=transaction_id,
            fence_nonce=fence_nonce,
            path=path,
        )
        temp_entries[temporary.relative_to(root).as_posix()] = after
    allowed_files = set(expected_by_path) | set(proposed_by_path) | set(temp_entries)
    allowed_directories: set[str] = set()
    for path in allowed_files:
        parts = path.split("/")
        for index in range(1, len(parts)):
            allowed_directories.add("/".join(parts[:index]))
    observed: set[str] = set()
    stack: list[tuple[Path, str]] = [(root, "")]
    while stack:
        directory, prefix = stack.pop()
        before_directory = os.lstat(directory)
        if (
            _isReparse(before_directory)
            or not stat.S_ISDIR(before_directory.st_mode)
            or before_directory.st_dev != root_info.st_dev
        ):
            raise PromotionRecoveryRequired("partial worktree directory is unsafe")
        with os.scandir(directory) as iterator:
            children = sorted(iterator, key=lambda item: item.name)
        for child in children:
            if not prefix and child.name == ".git":
                continue
            relative = f"{prefix}/{child.name}" if prefix else child.name
            info = os.lstat(child.path)
            if _isReparse(info) or info.st_dev != root_info.st_dev:
                raise PromotionRecoveryRequired("partial worktree escaped its root")
            if stat.S_ISDIR(info.st_mode):
                if relative not in allowed_directories:
                    raise PromotionRecoveryRequired(
                        f"partial worktree contains unknown directory: {relative}"
                    )
                stack.append((Path(child.path), relative))
                continue
            if (
                relative not in allowed_files
                or not stat.S_ISREG(info.st_mode)
                or info.st_nlink != 1
            ):
                raise PromotionRecoveryRequired(
                    f"partial worktree contains unknown entry: {relative}"
                )
            candidates = []
            if relative in temp_entries:
                candidates.append(temp_entries[relative])
            else:
                before = expected_by_path.get(relative)
                after = proposed_by_path.get(relative)
                if before is not None:
                    candidates.append(before)
                if after is not None and after != before:
                    candidates.append(after)
            max_bytes = max(item.size for item in candidates)
            raw = readNoFollowBytes(child.path, max_bytes=max_bytes)
            if not any(
                len(raw) == item.size
                and hashlib.sha256(raw).hexdigest() == item.blob_sha256
                for item in candidates
            ):
                raise PromotionRecoveryRequired(
                    f"partial worktree bytes are not journal-owned: {relative}"
                )
            observed.add(relative)
        after_directory = os.lstat(directory)
        if (after_directory.st_dev, after_directory.st_ino) != (
            before_directory.st_dev,
            before_directory.st_ino,
        ):
            raise PromotionRecoveryRequired("partial worktree directory raced")
    unchanged = {
        path
        for path in set(expected_by_path) & set(proposed_by_path)
        if expected_by_path[path] == proposed_by_path[path]
    }
    if not unchanged.issubset(observed):
        raise PromotionRecoveryRequired("partial worktree lost an unchanged path")


def _materializationTempName(
    *,
    transaction_id: str,
    fence_nonce: str,
    path: str,
) -> str:
    name = path.rsplit("/", 1)[-1]
    temp_digest = hashlib.sha256(
        f"{transaction_id}\0{fence_nonce}\0{path}".encode("utf-8")
    ).hexdigest()[:24]
    return f".{name}.galaxy-{temp_digest}.new"


def _assertNativeRecoverablePartial(
    root: NativeDirectoryHandle,
    *,
    transaction_id: str,
    fence_nonce: str,
    expected: ObjectManifest,
    proposed: ObjectManifest,
) -> None:
    expected_by_path = {entry.path: entry for entry in expected.entries}
    proposed_by_path = {entry.path: entry for entry in proposed.entries}
    allowed_directories = _expectedDirectories(expected) | _expectedDirectories(proposed)
    temp_entries = {
        (
            f"{path.rsplit('/', 1)[0]}/" if "/" in path else ""
        )
        + _materializationTempName(
            transaction_id=transaction_id,
            fence_nonce=fence_nonce,
            path=path,
        ): entry
        for path, entry in proposed_by_path.items()
        if expected_by_path.get(path) != entry
    }
    unchanged = {
        path
        for path in set(expected_by_path) & set(proposed_by_path)
        if expected_by_path[path] == proposed_by_path[path]
    }
    observed: set[str] = set()
    root_identity = root.identity

    def walk(directory: NativeDirectoryHandle, prefix: str) -> None:
        before = directory.identity
        children = _validatedNativeEntries(directory)
        for child in children:
            if not prefix and child.name == ".git":
                continue
            relative = f"{prefix}/{child.name}" if prefix else child.name
            if (
                child.identity.volume_id != root_identity.volume_id
                or child.identity.mount_id != root_identity.mount_id
            ):
                raise PromotionRecoveryRequired("partial worktree crossed a mount boundary")
            if child.identity.is_directory:
                if relative not in allowed_directories:
                    raise PromotionRecoveryRequired(
                        f"partial worktree contains unknown directory: {relative}"
                    )
                try:
                    with directory.openDirectory(
                        child.name,
                        expected=child.identity,
                    ) as nested:
                        walk(nested, relative)
                except PromotionRecoveryRequired:
                    raise
                except OSError as exc:
                    raise PromotionRecoveryRequired(
                        "partial worktree directory raced"
                    ) from exc
                continue
            if not stat.S_ISREG(child.identity.mode) or child.identity.link_count != 1:
                raise PromotionRecoveryRequired(
                    f"partial worktree contains unsupported entry: {relative}"
                )
            candidates = []
            if relative in temp_entries:
                candidates.append(temp_entries[relative])
            else:
                before_entry = expected_by_path.get(relative)
                after_entry = proposed_by_path.get(relative)
                if before_entry is not None:
                    candidates.append(before_entry)
                if after_entry is not None and after_entry != before_entry:
                    candidates.append(after_entry)
            if not candidates:
                raise PromotionRecoveryRequired(
                    f"partial worktree contains unknown file: {relative}"
                )
            try:
                raw = directory.readFile(
                    child.name,
                    max_bytes=max(item.size for item in candidates),
                    expected=child.identity,
                )
            except (OSError, ValueError) as exc:
                raise PromotionRecoveryRequired(
                    f"partial worktree file raced: {relative}"
                ) from exc
            if not any(
                len(raw) == item.size
                and hashlib.sha256(raw).hexdigest() == item.blob_sha256
                for item in candidates
            ):
                raise PromotionRecoveryRequired(
                    f"partial worktree bytes are not journal-owned: {relative}"
                )
            observed.add(relative)
        if directory.identity != before or _validatedNativeEntries(directory) != children:
            raise PromotionRecoveryRequired("partial worktree directory raced")

    walk(root, "")
    if not unchanged.issubset(observed):
        raise PromotionRecoveryRequired("partial worktree lost an unchanged path")


def _readNativeManifestFile(
    directory: NativeDirectoryHandle,
    name: str,
    entry: Any,
) -> NativeFileIdentity:
    observed = _nativeEntry(directory, name)
    if observed is None or observed.identity.is_directory:
        raise PromotionRecoveryRequired(f"materialization file changed type: {entry.path}")
    try:
        raw = directory.readFile(
            name,
            max_bytes=entry.size,
            expected=observed.identity,
        )
    except (OSError, ValueError) as exc:
        raise PromotionRecoveryRequired(
            f"materialization file could not be read: {entry.path}"
        ) from exc
    if len(raw) != entry.size or hashlib.sha256(raw).hexdigest() != entry.blob_sha256:
        raise PromotionRecoveryRequired(
            f"materialization bytes differ: {entry.path}"
        )
    return observed.identity


def _materializeCanonicalWorktreeNative(
    *,
    canonical_root: Path,
    git_common: Path,
    transaction_id: str,
    fence_nonce: str,
    expected: ObjectManifest,
    proposed: ObjectManifest,
    writer: GitObjectWriter,
    failpoint: Callable[[str], None] | None,
    resume: bool,
) -> str:
    canonical_absolute = Path(os.path.abspath(canonical_root))
    git_absolute = Path(os.path.abspath(git_common))
    if os.path.normcase(os.fspath(git_absolute)) != os.path.normcase(
        os.fspath(canonical_absolute / ".git")
    ):
        raise PromotionRefused("native materializer requires the canonical .git directory")
    expected_by_path = {entry.path: entry for entry in expected.entries}
    proposed_by_path = {entry.path: entry for entry in proposed.entries}
    changed = {
        path
        for path in set(expected_by_path) | set(proposed_by_path)
        if expected_by_path.get(path) != proposed_by_path.get(path)
    }
    try:
        root = openNativeDirectory(canonical_absolute)
    except OSError as exc:
        raise PromotionRefused("canonical worktree root is unsafe") from exc
    with root:
        root_identity = root.identity
        git_entry = _nativeEntry(root, ".git")
        if git_entry is None or not git_entry.identity.is_directory:
            raise PromotionRefused("canonical Git metadata is unavailable")
        try:
            git = root.openDirectory(".git", expected=git_entry.identity)
        except OSError as exc:
            raise PromotionRefused("canonical Git metadata identity raced") from exc
        with git:
            if resume:
                try:
                    _verifyCanonicalHandle(root, proposed)
                    already_proposed = True
                except PromotionRefused:
                    already_proposed = False
                    try:
                        _verifyCanonicalHandle(root, expected)
                    except PromotionRefused:
                        _assertNativeRecoverablePartial(
                            root,
                            transaction_id=transaction_id,
                            fence_nonce=fence_nonce,
                            expected=expected,
                            proposed=proposed,
                        )
            else:
                _verifyCanonicalHandle(root, expected)
                already_proposed = False

            namespace_entry = _nativeEntry(git, "9to5-tombstones", required=False)
            try:
                namespace = (
                    git.createDirectory("9to5-tombstones")
                    if namespace_entry is None
                    else git.openDirectory(
                        "9to5-tombstones",
                        expected=namespace_entry.identity,
                    )
                )
            except (FileExistsError, OSError) as exc:
                raise PromotionRecoveryRequired(
                    "materialization tombstone namespace is unsafe"
                ) from exc
            with namespace:
                transaction_entry = _nativeEntry(
                    namespace,
                    transaction_id,
                    required=False,
                )
                if transaction_entry is not None and not resume:
                    raise PromotionRecoveryRequired(
                        "materialization tombstone already exists and requires reconciliation"
                    )
                try:
                    tombstone = (
                        namespace.createDirectory(transaction_id)
                        if transaction_entry is None
                        else namespace.openDirectory(
                            transaction_id,
                            expected=transaction_entry.identity,
                        )
                    )
                except (FileExistsError, OSError) as exc:
                    raise PromotionRecoveryRequired(
                        "materialization tombstone is unsafe"
                    ) from exc
                with tombstone:
                    if not already_proposed:
                        for path in sorted(changed):
                            before = expected_by_path.get(path)
                            if before is None:
                                continue
                            parts = tuple(path.split("/"))
                            with _nativeDirectoryPath(
                                tombstone,
                                parts[:-1],
                                create=True,
                            ) as destination_parent:
                                destination = _nativeEntry(
                                    destination_parent,
                                    parts[-1],
                                    required=False,
                                )
                                if destination is not None:
                                    _readNativeManifestFile(
                                        destination_parent,
                                        parts[-1],
                                        before,
                                    )
                                    if not resume:
                                        raise PromotionRecoveryRequired(
                                            f"unexpected materialization tombstone: {path}"
                                        )
                                    continue
                                try:
                                    with _nativeDirectoryPath(
                                        root,
                                        parts[:-1],
                                        create=False,
                                    ) as source_parent:
                                        source_identity = _readNativeManifestFile(
                                            source_parent,
                                            parts[-1],
                                            before,
                                        )
                                        source_parent.moveChild(
                                            parts[-1],
                                            destination_parent,
                                            parts[-1],
                                            expected=source_identity,
                                        )
                                except PromotionRecoveryRequired:
                                    raise
                                except (OSError, ValueError) as exc:
                                    raise PromotionRecoveryRequired(
                                        f"expected materialization source changed: {path}"
                                    ) from exc
                            if failpoint is not None:
                                failpoint(f"after_tombstone:{path}")

                        expected_dirs = _expectedDirectories(expected)
                        proposed_dirs = _expectedDirectories(proposed)
                        for directory_path in sorted(
                            expected_dirs - proposed_dirs,
                            key=lambda value: (value.count("/"), value),
                            reverse=True,
                        ):
                            parts = tuple(directory_path.split("/"))
                            try:
                                with _nativeDirectoryPath(
                                    root,
                                    parts[:-1],
                                    create=False,
                                ) as parent:
                                    entry = _nativeEntry(parent, parts[-1], required=False)
                                    if entry is None:
                                        continue
                                    if not entry.identity.is_directory:
                                        raise PromotionRecoveryRequired(
                                            f"deleted directory changed type: {directory_path}"
                                        )
                                    parent.removeDirectory(
                                        parts[-1],
                                        expected=entry.identity,
                                    )
                            except PromotionRecoveryRequired:
                                raise
                            except (OSError, ValueError) as exc:
                                raise PromotionRecoveryRequired(
                                    f"deleted directory contains an unknown descendant: {directory_path}"
                                ) from exc

                        for directory_path in sorted(
                            proposed_dirs,
                            key=lambda value: (value.count("/"), value),
                        ):
                            with _nativeDirectoryPath(
                                root,
                                tuple(directory_path.split("/")),
                                create=True,
                            ):
                                pass

                        for path in sorted(changed):
                            after = proposed_by_path.get(path)
                            if after is None:
                                continue
                            payload = _entryPayload(writer, after)
                            parts = tuple(path.split("/"))
                            with _nativeDirectoryPath(
                                root,
                                parts[:-1],
                                create=True,
                            ) as parent:
                                target = _nativeEntry(parent, parts[-1], required=False)
                                if target is not None:
                                    if target.identity.is_directory:
                                        raise PromotionRecoveryRequired(
                                            f"materialization target changed type: {path}"
                                        )
                                    _readNativeManifestFile(parent, parts[-1], after)
                                else:
                                    temporary_name = _materializationTempName(
                                        transaction_id=transaction_id,
                                        fence_nonce=fence_nonce,
                                        path=path,
                                    )
                                    temporary = _nativeEntry(
                                        parent,
                                        temporary_name,
                                        required=False,
                                    )
                                    try:
                                        if temporary is None:
                                            temporary_identity = parent.createFile(
                                                temporary_name,
                                                payload,
                                            )
                                        else:
                                            temporary_identity = _readNativeManifestFile(
                                                parent,
                                                temporary_name,
                                                after,
                                            )
                                        temporary_identity = parent.setFileMode(
                                            temporary_name,
                                            after.mode & 0o777,
                                            expected=temporary_identity,
                                        )
                                        parent.moveChild(
                                            temporary_name,
                                            parent,
                                            parts[-1],
                                            expected=temporary_identity,
                                        )
                                    except (FileExistsError, OSError, ValueError) as exc:
                                        raise PromotionRecoveryRequired(
                                            f"materialization write failed: {path}"
                                        ) from exc
                            if failpoint is not None:
                                failpoint(f"after_materialize:{path}")

                    result = _verifyCanonicalHandle(root, proposed)
                    if not _sameNativeObject(root.identity, root_identity):
                        raise PromotionRecoveryRequired(
                            "canonical root identity changed during materialization"
                        )

                    for path in sorted(changed):
                        before = expected_by_path.get(path)
                        if before is None:
                            continue
                        parts = tuple(path.split("/"))
                        try:
                            with _nativeDirectoryPath(
                                tombstone,
                                parts[:-1],
                                create=False,
                            ) as parent:
                                entry = _nativeEntry(parent, parts[-1], required=False)
                                if entry is None:
                                    continue
                                _readNativeManifestFile(parent, parts[-1], before)
                                parent.removeFile(parts[-1], expected=entry.identity)
                        except PromotionRefused:
                            raise
                        except (OSError, ValueError) as exc:
                            raise PromotionRecoveryRequired(
                                f"tombstone cleanup failed: {path}"
                            ) from exc

                    known_tombstone_directories: set[str] = set()
                    for path in changed:
                        if path not in expected_by_path:
                            continue
                        parent_parts = path.split("/")[:-1]
                        for index in range(1, len(parent_parts) + 1):
                            known_tombstone_directories.add(
                                "/".join(parent_parts[:index])
                            )
                    for directory_path in sorted(
                        known_tombstone_directories,
                        key=lambda value: (value.count("/"), value),
                        reverse=True,
                    ):
                        parts = tuple(directory_path.split("/"))
                        try:
                            with _nativeDirectoryPath(
                                tombstone,
                                parts[:-1],
                                create=False,
                            ) as parent:
                                entry = _nativeEntry(parent, parts[-1], required=False)
                                if entry is not None:
                                    parent.removeDirectory(
                                        parts[-1],
                                        expected=entry.identity,
                                    )
                        except PromotionRefused:
                            continue
                        except (OSError, ValueError) as exc:
                            raise PromotionRecoveryRequired(
                                "tombstone directory contains an unknown artifact"
                            ) from exc
                    if _validatedNativeEntries(tombstone):
                        raise PromotionRecoveryRequired(
                            "tombstone contains an unknown owned artifact"
                        )
                transaction_after = _nativeEntry(namespace, transaction_id)
                if transaction_after is None:
                    raise PromotionRecoveryRequired("tombstone transaction disappeared")
                try:
                    namespace.removeDirectory(
                        transaction_id,
                        expected=transaction_after.identity,
                    )
                except OSError as exc:
                    raise PromotionRecoveryRequired(
                        "tombstone transaction could not be retired"
                    ) from exc
            return result


def _materializeCanonicalWorktree(
    *,
    canonical_root: Path,
    git_common: Path,
    transaction_id: str,
    fence_nonce: str,
    expected: ObjectManifest,
    proposed: ObjectManifest,
    writer: GitObjectWriter,
    failpoint: Callable[[str], None] | None,
    resume: bool = False,
) -> str:
    """Apply one proven expected-to-proposed manifest without Git checkout code."""

    return _materializeCanonicalWorktreeNative(
        canonical_root=canonical_root,
        git_common=git_common,
        transaction_id=transaction_id,
        fence_nonce=fence_nonce,
        expected=expected,
        proposed=proposed,
        writer=writer,
        failpoint=failpoint,
        resume=resume,
    )

    # Retained for forensic comparison only; production never uses path reopens.
    if resume:
        _assertRecoverablePartialWorktree(
            canonical_root=canonical_root,
            transaction_id=transaction_id,
            fence_nonce=fence_nonce,
            expected=expected,
            proposed=proposed,
        )
    else:
        _verifyCanonicalWorktree(canonical_root, expected)
    expected_by_path = {entry.path: entry for entry in expected.entries}
    proposed_by_path = {entry.path: entry for entry in proposed.entries}
    changed = {
        path
        for path in set(expected_by_path) | set(proposed_by_path)
        if expected_by_path.get(path) != proposed_by_path.get(path)
    }
    tombstone_root = git_common / "9to5-tombstones" / transaction_id
    try:
        _ensureOwnedDirectory(git_common, "9to5-tombstones")
        assertNoReparsePath(tombstone_root.parent)
        try:
            os.mkdir(tombstone_root)
            fsyncDirectory(tombstone_root.parent)
        except FileExistsError:
            if not resume:
                raise
            info = os.lstat(tombstone_root)
            if _isReparse(info) or not stat.S_ISDIR(info.st_mode):
                raise PromotionRecoveryRequired("materialization tombstone changed type")
    except FileExistsError as exc:
        raise PromotionRecoveryRequired(
            "materialization tombstone already exists and requires reconciliation"
        ) from exc
    except OSError as exc:
        raise PromotionRecoveryRequired("materialization tombstone is unsafe") from exc

    tombstones: list[tuple[Path, Any]] = []
    try:
        for path in sorted(changed):
            before = expected_by_path.get(path)
            if before is None:
                continue
            source = canonical_root.joinpath(*path.split("/"))
            destination = tombstone_root.joinpath(*path.split("/"))
            _ensureOwnedDirectory(tombstone_root, str(Path(path).parent).replace("\\", "/") if "/" in path else "")
            destination_exists = destination.exists()
            if destination_exists:
                tombstone_raw = readNoFollowBytes(destination, max_bytes=before.size)
                if (
                    len(tombstone_raw) != before.size
                    or hashlib.sha256(tombstone_raw).hexdigest()
                    != before.blob_sha256
                ):
                    raise PromotionRecoveryRequired(
                        f"materialization tombstone bytes changed: {path}"
                    )
                tombstones.append((destination, before))
            try:
                source_info = os.lstat(source)
            except FileNotFoundError:
                source_info = None
            source_is_expected = False
            if source_info is not None and stat.S_ISREG(source_info.st_mode):
                source_raw = readNoFollowBytes(
                    source,
                    max_bytes=max(
                        before.size,
                        proposed_by_path[path].size
                        if path in proposed_by_path
                        else before.size,
                    ),
                )
                source_is_expected = (
                    len(source_raw) == before.size
                    and hashlib.sha256(source_raw).hexdigest() == before.blob_sha256
                )
                after = proposed_by_path.get(path)
                source_is_proposed = bool(
                    after is not None
                    and len(source_raw) == after.size
                    and hashlib.sha256(source_raw).hexdigest() == after.blob_sha256
                )
                if not source_is_expected and not source_is_proposed:
                    raise PromotionRecoveryRequired(
                        f"materialization source bytes are unknown: {path}"
                    )
            elif source_info is not None and not stat.S_ISDIR(source_info.st_mode):
                raise PromotionRecoveryRequired(
                    f"materialization source type changed: {path}"
                )
            if destination_exists:
                if source_is_expected:
                    raise PromotionRecoveryRequired(
                        f"materialization duplicated expected bytes: {path}"
                    )
            elif source_is_expected:
                os.replace(source, destination)
                fsyncDirectory(source.parent)
                fsyncDirectory(destination.parent)
                tombstones.append((destination, before))
                if failpoint is not None:
                    failpoint(f"after_tombstone:{path}")
            elif not resume:
                raise PromotionRecoveryRequired(
                    f"expected materialization source changed: {path}"
                )
            else:
                raise PromotionRecoveryRequired(
                    f"partial materialization lost its old-byte tombstone: {path}"
                )

        expected_dirs = _expectedDirectories(expected)
        proposed_dirs = _expectedDirectories(proposed)
        for directory in sorted(
            expected_dirs - proposed_dirs,
            key=lambda value: (value.count("/"), value),
            reverse=True,
        ):
            target = canonical_root.joinpath(*directory.split("/"))
            try:
                target.rmdir()
                fsyncDirectory(target.parent)
            except FileNotFoundError:
                continue
            except OSError as exc:
                raise PromotionRecoveryRequired(
                    f"deleted directory contains an unknown descendant: {directory}"
                ) from exc

        for directory in sorted(
            _expectedDirectories(proposed),
            key=lambda value: (value.count("/"), value),
        ):
            _ensureOwnedDirectory(canonical_root, directory)

        for path in sorted(changed):
            after = proposed_by_path.get(path)
            if after is None:
                continue
            target = canonical_root.joinpath(*path.split("/"))
            payload = _entryPayload(writer, after)
            temporary = _materializationTempPath(
                canonical_root,
                transaction_id=transaction_id,
                fence_nonce=fence_nonce,
                path=path,
            )
            if temporary.relative_to(canonical_root).as_posix() in proposed_by_path:
                raise PromotionRecoveryRequired("materialization temp aliases proposed path")
            try:
                target_payload = None
                try:
                    target_payload = readNoFollowBytes(target, max_bytes=after.size)
                except FileNotFoundError:
                    pass
                except (OSError, ValueError) as exc:
                    raise PromotionRecoveryRequired(
                        f"materialization target type changed: {path}"
                    ) from exc
                if target_payload is not None:
                    if target_payload != payload:
                        raise PromotionRecoveryRequired(
                            f"materialization target bytes changed: {path}"
                        )
                else:
                    try:
                        temporary_payload = readNoFollowBytes(
                            temporary,
                            max_bytes=after.size,
                        )
                    except FileNotFoundError:
                        exclusiveCreateBytes(temporary, payload)
                        temporary_payload = readNoFollowBytes(
                            temporary,
                            max_bytes=after.size,
                        )
                    if temporary_payload != payload:
                        raise PromotionRecoveryRequired(
                            f"materialization temp verification failed: {path}"
                        )
                    if os.name != "nt":
                        os.chmod(
                            temporary,
                            0o755 if after.mode == 0o100755 else 0o644,
                        )
                    os.replace(temporary, target)
                    fsyncDirectory(target.parent)
            except PromotionRecoveryRequired:
                raise
            except (FileExistsError, OSError, ValueError) as exc:
                raise PromotionRecoveryRequired(
                    f"materialization write failed: {path}"
                ) from exc
            if failpoint is not None:
                failpoint(f"after_materialize:{path}")

        result = _verifyCanonicalWorktree(canonical_root, proposed)
        for tombstone, before in tombstones:
            raw = readNoFollowBytes(tombstone, max_bytes=before.size)
            if len(raw) != before.size or hashlib.sha256(raw).hexdigest() != before.blob_sha256:
                raise PromotionRecoveryRequired("tombstone evidence changed before cleanup")
            tombstone.unlink()
            fsyncDirectory(tombstone.parent)
        known_directories: set[Path] = set()
        for tombstone, _ in tombstones:
            parent = tombstone.parent
            while parent != tombstone_root:
                known_directories.add(parent)
                parent = parent.parent
        for tombstone_directory in sorted(
            known_directories,
            key=lambda value: len(value.parts),
            reverse=True,
        ):
            try:
                tombstone_directory.rmdir()
            except FileNotFoundError:
                continue
            except OSError as exc:
                raise PromotionRecoveryRequired(
                    "tombstone directory contains an unknown artifact"
                ) from exc
        tombstone_root.rmdir()
        fsyncDirectory(tombstone_root.parent)
        return result
    except BaseException:
        # Every partial artifact stays addressable for exact reconciliation.
        raise


def _installCanonicalIndex(
    *,
    external_index: Path,
    canonical_index: Path,
    sibling: Path,
    expected_digest: str,
    proposed: ObjectManifest,
    failpoint: Callable[[str], None] | None,
) -> str:
    try:
        raw = readNoFollowBytes(external_index, max_bytes=512 * 1024 * 1024)
    except (OSError, ValueError) as exc:
        raise PromotionRecoveryRequired("external proposed index is unavailable") from exc
    if hashlib.sha256(raw).hexdigest() != expected_digest:
        raise PromotionRecoveryRequired("external proposed index digest drifted")
    GitIndex.parse(raw, expected_manifest=proposed)
    if os.name == "nt":
        canonical_parent = Path(os.path.abspath(canonical_index.parent))
        sibling_parent = Path(os.path.abspath(sibling.parent))
        if os.path.normcase(os.fspath(canonical_parent)) != os.path.normcase(
            os.fspath(sibling_parent)
        ):
            raise PromotionRecoveryRequired(
                "canonical index sibling is not in the index directory"
            )
        try:
            with openNativeDirectory(canonical_parent) as directory:
                sibling_entry = _nativeEntry(directory, sibling.name, required=False)
                if sibling_entry is None:
                    sibling_identity = directory.createFile(sibling.name, raw)
                else:
                    copied = directory.readFile(
                        sibling.name,
                        max_bytes=len(raw),
                        expected=sibling_entry.identity,
                    )
                    if copied != raw:
                        raise PromotionRecoveryRequired(
                            "canonical index sibling copy drifted"
                        )
                    GitIndex.parse(copied, expected_manifest=proposed)
                    sibling_identity = sibling_entry.identity
                canonical_entry = _nativeEntry(directory, canonical_index.name)
                if canonical_entry is None:
                    raise PromotionRecoveryRequired("canonical index disappeared")
                if failpoint is not None:
                    failpoint("before_index_replace")
                directory.replaceFile(
                    sibling.name,
                    canonical_index.name,
                    expected_source=sibling_identity,
                    expected_destination=canonical_entry.identity,
                )
                if failpoint is not None:
                    failpoint("after_index_replace")
                installed_entry = _nativeEntry(directory, canonical_index.name)
                if installed_entry is None:
                    raise PromotionRecoveryRequired("canonical index disappeared")
                installed = directory.readFile(
                    canonical_index.name,
                    max_bytes=len(raw),
                    expected=installed_entry.identity,
                )
        except PromotionRecoveryRequired:
            raise
        except (FileExistsError, OSError, ValueError) as exc:
            raise PromotionRecoveryRequired("canonical index installation failed") from exc
        if installed != raw:
            raise PromotionRecoveryRequired("canonical index postcondition drifted")
        GitIndex.parse(installed, expected_manifest=proposed)
        return hashlib.sha256(installed).hexdigest()
    try:
        try:
            exclusiveCreateBytes(sibling, raw)
        except FileExistsError:
            # A process death after the create-only sibling write is resumable
            # only when the exact journal-derived bytes already exist.
            existing = readNoFollowBytes(sibling, max_bytes=len(raw))
            if existing != raw:
                raise PromotionRecoveryRequired(
                    "canonical index sibling copy drifted"
                )
            GitIndex.parse(existing, expected_manifest=proposed)
        copied = readNoFollowBytes(sibling, max_bytes=len(raw))
        if copied != raw:
            raise PromotionRecoveryRequired("canonical index sibling copy drifted")
        GitIndex.parse(copied, expected_manifest=proposed)
        if failpoint is not None:
            failpoint("before_index_replace")
        os.replace(sibling, canonical_index)
        fsyncDirectory(canonical_index.parent)
        if failpoint is not None:
            failpoint("after_index_replace")
    except PromotionRecoveryRequired:
        raise
    except (FileExistsError, OSError, ValueError) as exc:
        raise PromotionRecoveryRequired("canonical index installation failed") from exc
    installed = readNoFollowBytes(canonical_index, max_bytes=len(raw))
    if installed != raw:
        raise PromotionRecoveryRequired("canonical index postcondition drifted")
    GitIndex.parse(installed, expected_manifest=proposed)
    return hashlib.sha256(installed).hexdigest()


class StagingCoordinator:
    """One durable object-only checkpoint/staging authority for Task 2."""

    def __init__(
        self,
        *,
        attestation: CanonicalRepositoryAttestation,
        journal: AttemptJournal,
        receipt_store: ReceiptStore,
        ref_store: LooseRefStore,
        writer: GitObjectWriter,
        parser_image_digest: str,
        parser_security_profile_digest: str,
        landing_authority_issuer: LandingAuthorityIssuer | None = None,
        run_admission: RunAdmissionAuthority | None = None,
    ) -> None:
        if not isinstance(attestation, CanonicalRepositoryAttestation):
            raise TypeError("attestation must be CanonicalRepositoryAttestation")
        if not isinstance(journal, AttemptJournal) or not isinstance(receipt_store, ReceiptStore):
            raise TypeError("staging requires typed journal and receipt store")
        if not isinstance(ref_store, LooseRefStore) or not isinstance(writer, GitObjectWriter):
            raise TypeError("staging requires typed ref store and object writer")
        if ref_store.attestation != attestation:
            raise ValueError("ref store attestation differs from staging attestation")
        _require_digest(parser_image_digest, "parser_image_digest")
        _require_digest(
            parser_security_profile_digest,
            "parser_security_profile_digest",
        )
        if (
            landing_authority_issuer is not None
            and type(landing_authority_issuer) is not LandingAuthorityIssuer
        ):
            raise TypeError(
                "landing_authority_issuer must be a LandingAuthorityIssuer"
            )
        if (landing_authority_issuer is None) != (run_admission is None):
            raise TypeError(
                "landing authority issuer and run_admission are an inseparable pair"
            )
        if run_admission is not None:
            assert landing_authority_issuer is not None
            try:
                live_admission = landing_authority_issuer._validateAdmission(
                    run_admission
                )
            except LandingAuthorityRefused as exc:
                raise ValueError("run_admission is not live for this coordinator") from exc
            if (
                live_admission.repository_attestation_digest
                != attestation.attestation_digest
                or live_admission.expected_base_sha != attestation.head_oid
            ):
                raise ValueError(
                    "run_admission repository or base differs from staging attestation"
                )
        self.attestation = attestation
        self.journal = journal
        self.receipt_store = receipt_store
        self.ref_store = ref_store
        self.writer = writer
        self.parser_image_digest = parser_image_digest
        self.parser_security_profile_digest = parser_security_profile_digest
        self._landing_authority_issuer = landing_authority_issuer
        self._run_admission = run_admission
        self.artifact_root = writer.object_root.parent / "staging-artifacts"
        canonical = os.path.normcase(os.path.abspath(attestation.canonical_root))
        artifacts = os.path.normcase(os.path.abspath(self.artifact_root))
        if _is_within(artifacts, canonical) or _is_within(canonical, artifacts):
            raise ValueError("staging artifacts must remain outside canonical")
        self._live_requests: dict[str, StagingRequest] = {}

    def _validateBoundRunAdmissionLocked(
        self,
        issuer: LandingAuthorityIssuer,
    ) -> RunAdmissionAuthority:
        """Revalidate the exact repository/base grant while issuer lock is held."""

        admission = self._run_admission
        if admission is None:
            raise LandingAuthorityRefused(
                "run admission is not bound to this coordinator"
            )
        live_admission = issuer._validateAdmissionLocked(admission)
        if (
            live_admission.repository_attestation_digest
            != self.attestation.attestation_digest
            or live_admission.expected_base_sha != self.attestation.head_oid
        ):
            raise LandingAuthorityRefused(
                "run admission repository or base differs from staging attestation"
            )
        return live_admission

    def _validateBoundLandingAuthority(
        self,
        authority: object,
        authorization: object,
    ) -> LandingAuthority:
        issuer = self._landing_authority_issuer
        if issuer is None:
            raise LandingAuthorityRefused(
                "landing authority issuer is not bound to this coordinator"
            )
        if type(authority) is not LandingAuthority or authority._issuer is not issuer:
            raise LandingAuthorityRefused(
                "landing authority issuer is not bound to this coordinator"
            )
        admission = self._run_admission
        if admission is None or authority.admission_id != admission.admission_id:
            raise LandingAuthorityRefused(
                "landing authority run admission is not bound to this coordinator"
            )
        return issuer.validateLandingAuthority(authority, authorization)

    @contextmanager
    def _boundLandingCommitPermit(
        self,
        authority: object,
        authorization: object,
    ):
        """Hold the bound issuer's exact liveness fence across canonical CAS."""

        issuer = self._landing_authority_issuer
        if issuer is None:
            raise LandingAuthorityRefused(
                "landing authority issuer is not bound to this coordinator"
            )
        if type(authority) is not LandingAuthority or authority._issuer is not issuer:
            raise LandingAuthorityRefused(
                "landing authority issuer is not bound to this coordinator"
            )
        admission = self._run_admission
        if admission is None or authority.admission_id != admission.admission_id:
            raise LandingAuthorityRefused(
                "landing authority run admission is not bound to this coordinator"
            )
        with issuer.landingCommitPermit(authority, authorization) as require_live:
            self._validateBoundRunAdmissionLocked(issuer)
            yield require_live

    def _validateBoundRecoveryAuthority(
        self,
        authority: object,
        *,
        transaction_id: str,
    ) -> PromotionRecoveryAuthority:
        issuer = self._landing_authority_issuer
        if issuer is None:
            raise LandingAuthorityRefused(
                "promotion recovery issuer is not bound to this coordinator"
            )
        if (
            type(authority) is not PromotionRecoveryAuthority
            or authority._issuer is not issuer
        ):
            raise LandingAuthorityRefused(
                "promotion recovery issuer is not bound to this coordinator"
            )
        admission = self._run_admission
        if admission is None or authority.admission_id != admission.admission_id:
            raise LandingAuthorityRefused(
                "promotion recovery run admission is not bound to this coordinator"
            )
        return issuer.validateRecoveryAuthority(
            authority,
            repository_id=self.attestation.repository_id,
            transaction_id=transaction_id,
        )

    def _promotionProcessLeasePath(self) -> Path:
        return (
            self.journal.root.parent
            / "locks"
            / f"{self.attestation.repository_id}.promotion-process.lock"
        )

    def _recoverOrAdoptOwnedPromotionArtifact(
        self,
        record: AttemptRecord,
        *,
        identity_field: str,
        path: Path,
        payload: bytes,
    ) -> _OwnedFile | None:
        """Adopt a power-loss artifact only from the prior durable exact plan."""

        fields = {
            "custom_lock_identity_digest": (
                "custom_lock_path",
                "custom_lock_owner_digest",
            ),
            "index_fence_identity_digest": (
                "index_fence_path",
                "index_fence_owner_digest",
            ),
            "orig_head_fence_identity_digest": (
                "orig_head_fence_path",
                "orig_head_fence_owner_digest",
            ),
        }
        try:
            path_field, owner_field = fields[identity_field]
        except KeyError as exc:
            raise PromotionRecoveryRequired(
                "unknown promotion artifact identity field"
            ) from exc
        if not record.promotion_plan_digest:
            raise PromotionRecoveryRequired(
                "promotion artifact cannot be adopted without a durable plan"
            )
        if (
            os.path.normcase(os.path.abspath(path))
            != os.path.normcase(os.path.abspath(getattr(record, path_field)))
            or hashlib.sha256(payload).hexdigest() != getattr(record, owner_field)
        ):
            raise PromotionRecoveryRequired(
                "promotion artifact differs from its durable plan"
            )
        expected_identity = getattr(record, identity_field)
        owned = _recoverOptionalOwnedFile(
            path,
            payload,
            expected_identity,
            allow_planned_adoption=True,
        )
        if owned is None or expected_identity:
            return owned
        if identity_field == "custom_lock_identity_digest":
            updated = self.journal.bind_promotion_artifact_identities(
                record.transaction_id,
                custom_lock_identity_digest=owned.identity_digest,
            )
        elif identity_field == "index_fence_identity_digest":
            updated = self.journal.bind_promotion_artifact_identities(
                record.transaction_id,
                index_fence_identity_digest=owned.identity_digest,
            )
        else:
            updated = self.journal.bind_promotion_artifact_identities(
                record.transaction_id,
                orig_head_fence_identity_digest=owned.identity_digest,
            )
        if getattr(updated, identity_field) != owned.identity_digest:
            raise PromotionRecoveryRequired(
                "adopted promotion artifact identity was not durable"
            )
        return owned

    def _recoverOrAdoptCanonicalRefLock(
        self,
        record: AttemptRecord,
    ) -> CanonicalRefLock | None:
        """Bind an exact planned ref-lock identity before cleanup after a crash."""

        try:
            os.lstat(record.canonical_ref_lock_path)
        except FileNotFoundError:
            return None
        except OSError as exc:
            raise PromotionRecoveryRequired(
                "canonical ref lock cannot be inspected during recovery"
            ) from exc
        try:
            if record.canonical_ref_lock_identity_digest:
                return self.ref_store.recoverCanonicalLock(
                    proposed_oid=record.proposed_revision,
                    expected_identity_digest=(
                        record.canonical_ref_lock_identity_digest
                    ),
                )
            if not record.promotion_plan_digest:
                raise PromotionRecoveryRequired(
                    "canonical ref lock has no durable promotion plan"
                )
            lease = self.ref_store.recoverPlannedCanonicalLock(
                proposed_oid=record.proposed_revision,
            )
            if (
                os.path.normcase(lease.path)
                != os.path.normcase(record.canonical_ref_lock_path)
                or lease.payload_digest != record.canonical_ref_lock_owner_digest
            ):
                raise PromotionRecoveryRequired(
                    "canonical ref lock differs from its durable plan"
                )
            updated = self.journal.bind_promotion_artifact_identities(
                record.transaction_id,
                canonical_ref_lock_identity_digest=lease.identity_digest,
            )
            if updated.canonical_ref_lock_identity_digest != lease.identity_digest:
                raise PromotionRecoveryRequired(
                    "adopted canonical ref lock identity was not durable"
                )
            return lease
        except RefError as exc:
            raise PromotionRecoveryRequired(
                "canonical ref lock ownership differs during recovery"
            ) from exc

    def _releaseDurablePromotionFences(self, record: AttemptRecord) -> None:
        """Retire only exact journal-owned fences; missing means prior cleanup won."""

        custom_payload = canonical_json_bytes(
            {
                "schema": "galaxy.promotion-lock/v1",
                "transaction_id": record.transaction_id,
                "ownership_nonce": record.ownership_nonce,
            }
        )
        index_payload = canonical_json_bytes(
            {
                "schema": "galaxy.index-fence/v1",
                "transaction_id": record.transaction_id,
                "fence_nonce": record.index_fence_nonce,
            }
        )
        orig_head_payload = canonical_json_bytes(
            {
                "schema": "galaxy.orig-head-fence/v1",
                "transaction_id": record.transaction_id,
                "fence_nonce": record.index_fence_nonce,
            }
        )
        canonical_index = Path(self.attestation.git_common_dir) / "index"
        expected_paths = {
            "canonical_index_path": str(canonical_index),
            "index_fence_path": str(canonical_index.with_name("index.lock")),
            "orig_head_fence_path": str(canonical_index.with_name("ORIG_HEAD.lock")),
        }
        for name, expected in expected_paths.items():
            if os.path.normcase(getattr(record, name)) != os.path.normcase(expected):
                raise PromotionRecoveryRequired(
                    f"durable promotion plan has an unexpected {name}"
                )
        ref_lock_path, ref_lock_digest = self.ref_store.canonicalLockPlan(
            proposed_oid=record.proposed_revision
        )
        if (
            os.path.normcase(record.canonical_ref_lock_path)
            != os.path.normcase(ref_lock_path)
            or record.canonical_ref_lock_owner_digest != ref_lock_digest
            or record.custom_lock_owner_digest
            != hashlib.sha256(custom_payload).hexdigest()
            or record.index_fence_owner_digest
            != hashlib.sha256(index_payload).hexdigest()
            or record.orig_head_fence_owner_digest
            != hashlib.sha256(orig_head_payload).hexdigest()
        ):
            raise PromotionRecoveryRequired("durable promotion fence plan differs")

        owned_files = (
            self._recoverOrAdoptOwnedPromotionArtifact(
                record,
                identity_field="orig_head_fence_identity_digest",
                path=Path(record.orig_head_fence_path),
                payload=orig_head_payload,
            ),
            self._recoverOrAdoptOwnedPromotionArtifact(
                record,
                identity_field="index_fence_identity_digest",
                path=Path(record.index_fence_path),
                payload=index_payload,
            ),
            self._recoverOrAdoptOwnedPromotionArtifact(
                record,
                identity_field="custom_lock_identity_digest",
                path=Path(record.custom_lock_path),
                payload=custom_payload,
            ),
        )
        ref_lock = self._recoverOrAdoptCanonicalRefLock(record)
        if ref_lock is not None:
            self.ref_store.releaseCanonicalLock(ref_lock)
        for owned in owned_files:
            if owned is not None:
                _releaseOwnedFile(owned)

    def _bundlePath(self, transaction_id: str) -> Path:
        _require_id(transaction_id, "transaction_id")
        return self.artifact_root / transaction_id / "manifest-bundle.json"

    def _bundleBytes(self, request: StagingRequest) -> bytes:
        payload = {
            "schema": _STAGING_BUNDLE_SCHEMA,
            "transaction_id": request.transaction_id,
            "expected_manifest_digest": request.expected_manifest.manifest_digest,
            "proposed_manifest_digest": request.parsed.manifest.manifest_digest,
            "expected_manifest": request.expected_manifest.toDict(),
            "proposed_manifest": request.parsed.manifest.toDict(),
        }
        return canonical_json_bytes(payload)

    def _persistManifestBundle(self, request: StagingRequest) -> _ManifestBundle:
        raw = self._bundleBytes(request)
        path = self._bundlePath(request.transaction_id)
        try:
            assertNoReparsePath(path.parent)
            exclusiveCreateBytes(path, raw)
        except FileExistsError:
            try:
                if readNoFollowBytes(path, max_bytes=_MAX_MANIFEST_BUNDLE_BYTES) != raw:
                    raise StagedRevisionRefused("staging manifest bundle collision")
            except (OSError, ValueError) as exc:
                raise StagedRevisionRefused("staging manifest bundle is unsafe") from exc
        except OSError as exc:
            raise StagedRevisionRefused("staging manifest bundle path is unsafe") from exc
        return _ManifestBundle(
            expected=request.expected_manifest,
            proposed=request.parsed.manifest,
            digest=hashlib.sha256(raw).hexdigest(),
        )

    def _loadManifestBundle(self, transaction_id: str) -> _ManifestBundle:
        path = self._bundlePath(transaction_id)
        try:
            raw = readNoFollowBytes(path, max_bytes=_MAX_MANIFEST_BUNDLE_BYTES)
            value = json.loads(raw.decode("utf-8"))
        except (OSError, ValueError, UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise PromotionRefused("staging manifest bundle is missing or corrupt") from exc
        if not isinstance(value, dict) or set(value) != {
            "schema",
            "transaction_id",
            "expected_manifest_digest",
            "proposed_manifest_digest",
            "expected_manifest",
            "proposed_manifest",
        }:
            raise PromotionRefused("staging manifest bundle schema is not closed")
        if canonical_json_bytes(value) != raw:
            raise PromotionRefused("staging manifest bundle is not canonical JSON")
        if value["schema"] != _STAGING_BUNDLE_SCHEMA or value["transaction_id"] != transaction_id:
            raise PromotionRefused("staging manifest bundle identity differs")
        try:
            expected = ObjectManifest.fromDict(value["expected_manifest"])
            proposed = ObjectManifest.fromDict(value["proposed_manifest"])
        except ObjectManifestRefused as exc:
            raise PromotionRefused("staging manifest bundle violates its contract") from exc
        if (
            value["expected_manifest_digest"] != expected.manifest_digest
            or value["proposed_manifest_digest"] != proposed.manifest_digest
        ):
            raise PromotionRefused("staging manifest bundle digest differs")
        bundle = _ManifestBundle(
            expected=expected,
            proposed=proposed,
            digest=hashlib.sha256(raw).hexdigest(),
        )
        record = self.journal.load(transaction_id)
        if (
            record.staging_manifest_bundle_digest != bundle.digest
            or record.expected_manifest_digest != expected.manifest_digest
            or record.proposed_manifest_digest != proposed.manifest_digest
            or record.source_manifest_digest != expected.manifest_digest
        ):
            raise PromotionRefused(
                "staging manifest bundle differs from durable attempt truth"
            )
        return bundle

    def _persistReconciliationReceipt(
        self,
        *,
        record: AttemptRecord,
        promotion_receipt_id: str,
        observed_ref_revision: str,
        observed_index_digest: str,
        observed_worktree_digest: str,
        recovery_action: str,
        classification: str,
        subsequent_canonical_revision: str = "",
    ) -> ReconciliationReceipt:
        receipt = ReconciliationReceipt(
            transaction_id=record.transaction_id,
            promotion_receipt_id=promotion_receipt_id,
            attempt_record_digest=canonical_digest(record.to_dict()),
            observed_ref_revision=observed_ref_revision,
            observed_index_digest=observed_index_digest,
            observed_worktree_digest=observed_worktree_digest,
            recovery_action=recovery_action,
            subsequent_canonical_revision=subsequent_canonical_revision,
            classification=classification,
            observed_at=record.updated_at,
        )
        stored = self.receipt_store.put(receipt)
        if self.receipt_store.read(
            stored.receipt_id,
            expected_type=ReconciliationReceipt,
        ) != receipt:
            raise PromotionRecoveryRequired("reconciliation receipt replay differs")
        return receipt

    def _validateRequestAndJournal(self, request: StagingRequest) -> None:
        if not isinstance(request, StagingRequest):
            raise TypeError("request must be StagingRequest")
        live = attestCanonicalRepository(self.attestation.canonical_root)
        if live != self.attestation:
            raise StagedRevisionRefused("canonical repository attestation drifted")
        if live.head_oid != request.expected_manifest.expected_revision:
            raise StagedRevisionRefused("expected target revision is stale")
        record = self.journal.load(request.transaction_id)
        if (
            record.task_id != request.task_id
            or record.subtask_id != request.subtask_id
            or record.attempt_id != request.attempt_id
            or record.repository_id != self.attestation.repository_id
            or record.canonical_metadata_attestation_digest
            != self.attestation.attestation_digest
            or record.base_revision != request.expected_manifest.expected_revision
        ):
            raise StagedRevisionRefused("attempt journal identity differs from staging request")
        if record.phase not in {
            AttemptPhase.RUNNING,
            AttemptPhase.CANDIDATE_CHECKPOINTED,
            AttemptPhase.STAGED_PREPARED,
        }:
            raise StagedRevisionRefused("attempt phase is not eligible for staging")
        if self.writer.blob_root != request.snapshot.blob_root:
            raise StagedRevisionRefused("writer blob root differs from immutable snapshot")
        if (
            request.parsed.manifest.expected_revision != record.base_revision
            or request.parsed.container_network_allowed is not False
        ):
            raise StagedRevisionRefused("parser result is not closed evidence")
        proposal_message_digest = hashlib.sha256(
            request.commit_metadata.message.encode("utf-8")
        ).hexdigest()
        commit_timestamp_seed = _commitTimestamp(request.commit_metadata)
        if (
            proposal_message_digest != record.proposal_message_digest
            or commit_timestamp_seed != record.commit_timestamp_seed
        ):
            raise StagedRevisionRefused(
                "commit metadata differs from the registered attempt plan"
            )
        metadata_raw = canonical_json_bytes(_commitMetadataDict(request.commit_metadata))
        try:
            bound = self.journal.bind_commit_metadata(
                request.transaction_id,
                metadata_json=metadata_raw.decode("utf-8"),
                metadata_digest=hashlib.sha256(metadata_raw).hexdigest(),
            )
        except InvalidAttemptTransition as exc:
            raise StagedRevisionRefused("commit metadata differs from journal truth") from exc
        if (
            bound.commit_metadata_json != metadata_raw.decode("utf-8")
            or bound.commit_metadata_digest != hashlib.sha256(metadata_raw).hexdigest()
        ):
            raise StagedRevisionRefused("commit metadata journal binding is unavailable")

    def _buildReceipt(
        self,
        request: StagingRequest,
        object_receipt: ObjectWriteReceipt,
    ) -> StagingReceipt:
        records = {record.oid: record for record in object_receipt.objects}
        try:
            commit_record = records[object_receipt.commit_oid]
            tree_record = records[object_receipt.tree_oid]
        except KeyError as exc:
            raise StagedRevisionRefused("object closure omits its commit or tree") from exc
        staged_ref = f"refs/9to5/staged/{request.transaction_id}"
        policy_digest = canonical_digest(
            {
                "attribute_rules": [
                    rule.toDict() for rule in request.parsed.manifest.attribute_rules
                ],
                "policy": request.parsed.manifest.policy.toDict(),
            }
        )
        return StagingReceipt(
            transaction_id=request.transaction_id,
            source_snapshot_digest=request.snapshot.snapshot_digest,
            parser_receipt_id=request.parsed.receipt_id,
            parser_manifest_digest=request.parsed.manifest.manifest_digest,
            blob_set_digest=request.snapshot.blob_set_digest,
            parser_image_digest=self.parser_image_digest,
            parser_runtime_digest=request.parsed.parser_version_digest,
            parser_security_profile_digest=self.parser_security_profile_digest,
            object_writer_version_digest=self.writer.writer_version_digest,
            expected_parent=request.expected_manifest.expected_revision,
            proposed_commit=object_receipt.commit_oid,
            proposed_tree=object_receipt.tree_oid,
            proposed_diff_digest=request.parsed.diff_digest,
            proposed_commit_content_digest=commit_record.payload_sha256,
            proposed_tree_content_digest=tree_record.payload_sha256,
            object_closure_digest=object_receipt.object_closure_digest,
            proposed_index_digest=object_receipt.proposed_index_digest,
            staged_ref=staged_ref,
            policy_manifest_digest=policy_digest,
            commit_metadata_digest=canonical_digest(
                _commitMetadataDict(request.commit_metadata)
            ),
            commit_timestamp=_commitTimestamp(request.commit_metadata),
        )

    def prepareStagedRevision(self, request: StagingRequest) -> StagedRevisionLease:
        self._validateRequestAndJournal(request)
        try:
            manifest_bundle = self._persistManifestBundle(request)
            object_receipt = self.writer.writeRevision(
                manifest=request.parsed.manifest,
                metadata=request.commit_metadata,
            )
            self.writer.installClosureIntoCanonical(
                receipt=object_receipt,
                attestation=self.attestation,
            )
            checkpoint_ref = f"refs/9to5/checkpoints/{request.transaction_id}"
            staged_ref = f"refs/9to5/staged/{request.transaction_id}"
            self.ref_store.createPrivateRef(checkpoint_ref, object_receipt.commit_oid)
            self.ref_store.createPrivateRef(staged_ref, object_receipt.commit_oid)
            current = self.journal.load(request.transaction_id)
            checkpoint_changes = {
                "checkpoint_revision": object_receipt.commit_oid,
                "checkpoint_ref": checkpoint_ref,
                "candidate_snapshot_digest": request.snapshot.snapshot_digest,
                "parser_manifest_digest": request.parsed.manifest.manifest_digest,
                "blob_set_digest": request.snapshot.blob_set_digest,
            }
            if current.phase is AttemptPhase.RUNNING:
                self.journal.transition(
                    request.transaction_id,
                    AttemptPhase.CANDIDATE_CHECKPOINTED,
                    **checkpoint_changes,
                )
            elif current.phase is AttemptPhase.CANDIDATE_CHECKPOINTED:
                self.journal.transition(
                    request.transaction_id,
                    AttemptPhase.CANDIDATE_CHECKPOINTED,
                    **checkpoint_changes,
                )
            receipt = self._buildReceipt(request, object_receipt)
            stored = self.receipt_store.put(receipt)
            current = self.journal.load(request.transaction_id)
            staging_changes = {
                "staging_receipt_id": stored.receipt_id,
                "proposed_revision": object_receipt.commit_oid,
                "proposed_tree": object_receipt.tree_oid,
                "proposed_diff_digest": request.parsed.diff_digest,
                "staged_ref": staged_ref,
                "staging_manifest_bundle_digest": manifest_bundle.digest,
                "expected_manifest_digest": request.expected_manifest.manifest_digest,
                "proposed_manifest_digest": request.parsed.manifest.manifest_digest,
            }
            if current.phase is AttemptPhase.CANDIDATE_CHECKPOINTED:
                self.journal.transition(
                    request.transaction_id,
                    AttemptPhase.STAGED_PREPARED,
                    **staging_changes,
                )
            elif current.phase is AttemptPhase.STAGED_PREPARED:
                self.journal.transition(
                    request.transaction_id,
                    AttemptPhase.STAGED_PREPARED,
                    **staging_changes,
                )
            else:
                raise StagedRevisionRefused("attempt journal did not reach staged preparation")
            lease = StagedRevisionLease(
                transaction_id=request.transaction_id,
                task_id=request.task_id,
                subtask_id=request.subtask_id,
                attempt_id=request.attempt_id,
                runner_kind=request.runner_kind,
                candidate_snapshot_digest=request.snapshot.snapshot_digest,
                parser_manifest_digest=request.parsed.manifest.manifest_digest,
                blob_set_digest=request.snapshot.blob_set_digest,
                checkpoint_ref=checkpoint_ref,
                checkpoint_revision=object_receipt.commit_oid,
                expected_target_revision=request.expected_manifest.expected_revision,
                staged_ref=staged_ref,
                proposed_revision=object_receipt.commit_oid,
                proposed_tree=object_receipt.tree_oid,
                proposed_diff_digest=request.parsed.diff_digest,
                staging_receipt_id=stored.receipt_id,
                object_closure_digest=object_receipt.object_closure_digest,
                cleanup_token=request.cleanup_token,
            )
            self._live_requests[request.transaction_id] = request
            return lease
        except StagedRevisionRefused:
            raise
        except (ObjectWriterRefused, RefError, ReceiptStoreError, OSError, ValueError) as exc:
            raise StagedRevisionRefused(f"staged revision refused: {exc}") from exc

    def _canonicalClosureMatches(self, object_receipt: ObjectWriteReceipt) -> bool:
        proof = self.writer.proveClosureInCanonical(
            receipt=object_receipt,
            attestation=self.attestation,
        )
        expected_oids = tuple(sorted(record.oid for record in object_receipt.objects))
        return (
            proof.canonical_attestation_digest == self.attestation.attestation_digest
            and proof.object_closure_digest == object_receipt.object_closure_digest
            and proof.installed_oids == ()
            and proof.reused_oids == expected_oids
            and tuple(oid for oid, _ in proof.reuse_proof_receipts)
            == expected_oids
        )

    def stagedRevisionIntact(
        self,
        request: StagingRequest,
        lease: StagedRevisionLease,
    ) -> bool:
        """Re-prove the sealed staged revision without repairing any artifact."""

        try:
            if not isinstance(request, StagingRequest) or not isinstance(
                lease, StagedRevisionLease
            ):
                return False
            if (
                request.transaction_id != lease.transaction_id
                or request.task_id != lease.task_id
                or request.subtask_id != lease.subtask_id
                or request.attempt_id != lease.attempt_id
                or self.ref_store.readRef(lease.checkpoint_ref)
                != lease.proposed_revision
                or self.ref_store.readRef(lease.staged_ref) != lease.proposed_revision
            ):
                return False
            live = attestCanonicalRepository(self.attestation.canonical_root)
            if live != self.attestation:
                return False
            record = self.journal.load(lease.transaction_id)
            if (
                record.phase
                not in {
                    AttemptPhase.STAGED_PREPARED,
                    AttemptPhase.VERIFIED,
                    AttemptPhase.PROMOTION_PREPARED,
                    AttemptPhase.INDEX_FENCED,
                }
                or record.staging_receipt_id != lease.staging_receipt_id
                or record.proposed_revision != lease.proposed_revision
                or record.proposed_tree != lease.proposed_tree
                or record.proposed_diff_digest != lease.proposed_diff_digest
            ):
                return False
            persisted = self.receipt_store.read(
                lease.staging_receipt_id,
                expected_type=StagingReceipt,
            )
            object_receipt = self.writer.planRevision(
                manifest=request.parsed.manifest,
                metadata=request.commit_metadata,
            )
            expected_receipt = self._buildReceipt(request, object_receipt)
            if (
                persisted != expected_receipt
                or object_receipt.commit_oid != lease.proposed_revision
                or object_receipt.tree_oid != lease.proposed_tree
                or object_receipt.object_closure_digest != lease.object_closure_digest
                or not self._canonicalClosureMatches(object_receipt)
            ):
                return False
            return True
        except (OSError, ValueError, RuntimeError):
            return False

    def _preflightCanonical(self, expected: ObjectManifest) -> tuple[str, str]:
        live = attestCanonicalRepository(self.attestation.canonical_root)
        if live != self.attestation:
            raise PromotionRefused("canonical repository metadata or revision drifted")
        if self.ref_store.classifyCanonical(
            expected_oid=expected.expected_revision,
            proposed_oid="0" * 40,
        ) is not CanonicalRefCas.NOT_MOVED:
            raise PromotionRefused("canonical ref is not the exact expected revision")
        index_path = Path(self.attestation.git_common_dir) / "index"
        try:
            raw_index = readNoFollowBytes(index_path, max_bytes=512 * 1024 * 1024)
            parsed = GitIndex.parse(
                raw_index,
                expected_manifest=expected,
                expected_tree_oids=self.writer.planTreeOids(expected),
            )
        except (OSError, ValueError, GitIndexRefused) as exc:
            raise PromotionRefused("canonical index does not match expected manifest") from exc
        if parsed.index_digest != self.attestation.index_digest:
            raise PromotionRefused("canonical index digest drifted from attestation")
        worktree_digest = _verifyCanonicalWorktree(
            Path(self.attestation.canonical_root),
            expected,
        )
        return parsed.index_digest, worktree_digest

    def _proposedIndexPlan(
        self,
        transaction_id: str,
        proposed: ObjectManifest,
    ) -> tuple[Path, str]:
        raw = GitIndex.build(proposed)
        GitIndex.parse(raw, expected_manifest=proposed)
        digest = hashlib.sha256(raw).hexdigest()
        path = self.artifact_root / transaction_id / "proposed.index"
        return path, digest

    def _persistProposedIndex(
        self,
        transaction_id: str,
        proposed: ObjectManifest,
        *,
        expected_path: Path,
        expected_digest: str,
    ) -> tuple[Path, bytes, str]:
        raw = GitIndex.build(proposed)
        GitIndex.parse(raw, expected_manifest=proposed)
        digest = hashlib.sha256(raw).hexdigest()
        path = self.artifact_root / transaction_id / "proposed.index"
        if path != expected_path or digest != expected_digest:
            raise PromotionRefused("external proposed index differs from durable plan")
        try:
            exclusiveCreateBytes(path, raw)
        except FileExistsError:
            try:
                existing = readNoFollowBytes(path, max_bytes=len(raw))
            except (OSError, ValueError) as exc:
                raise PromotionRefused("external proposed index is unsafe") from exc
            if existing != raw:
                raise PromotionRefused("external proposed index collision")
        except OSError as exc:
            raise PromotionRefused("external proposed index path is unsafe") from exc
        persisted = readNoFollowBytes(path, max_bytes=len(raw))
        if persisted != raw or hashlib.sha256(persisted).hexdigest() != digest:
            raise PromotionRefused("external proposed index did not persist exactly")
        return path, raw, digest

    def promoteStagedRevision(
        self,
        lease: StagedRevisionLease,
        authorization: object,
        landing_authority: object,
        *,
        failpoint: Callable[[str], None] | None = None,
    ) -> PromotionReceipt:
        try:
            with _promotionProcessLease(self._promotionProcessLeasePath()):
                return self._promoteStagedRevisionHeld(
                    lease,
                    authorization,
                    landing_authority,
                    failpoint=failpoint,
                )
        except _PromotionProcessLeaseBusy as exc:
            raise PromotionRefused("another promotion process is still active") from exc

    def _promoteStagedRevisionHeld(
        self,
        lease: StagedRevisionLease,
        authorization: object,
        landing_authority: object,
        *,
        failpoint: Callable[[str], None] | None = None,
    ) -> PromotionReceipt:
        """Land one exact staged revision under durable index and ref fences."""

        if not isinstance(lease, StagedRevisionLease):
            raise TypeError("lease must be StagedRevisionLease")
        auth = PromotionAuthorization.from_value(authorization)
        evidence = validatePromotionAuthorization(
            auth,
            store=self.receipt_store,
            journal=self.journal,
        )
        try:
            self._validateBoundLandingAuthority(landing_authority, auth)
        except LandingAuthorityRefused as exc:
            raise PromotionRefused(f"landing authority refused: {exc}") from exc
        if (
            lease.transaction_id != auth.transaction_id
            or lease.task_id != auth.task_id
            or lease.subtask_id != auth.subtask_id
            or lease.staging_receipt_id != auth.staging_receipt_id
            or lease.proposed_revision != auth.proposed_revision
            or lease.proposed_tree != auth.proposed_tree
            or lease.proposed_diff_digest != auth.proposed_diff_digest
            or evidence.staging.expected_parent != lease.expected_target_revision
        ):
            raise PromotionRefused("landing lease differs from authorized receipt chain")
        request = self._live_requests.get(lease.transaction_id)
        if request is None or not self.stagedRevisionIntact(request, lease):
            raise PromotionRefused("staged revision integrity is unavailable")
        bundle = self._loadManifestBundle(lease.transaction_id)
        if (
            bundle.expected != request.expected_manifest
            or bundle.proposed != request.parsed.manifest
            or bundle.expected.expected_revision != lease.expected_target_revision
            or bundle.proposed.manifest_digest != lease.parser_manifest_digest
        ):
            raise PromotionRefused("staging manifest bundle differs from the sealed lease")

        expected_preflight = self._preflightCanonical(bundle.expected)
        filesystem_representation_digest = (
            _validateProspectiveFilesystemRepresentation(
                Path(self.attestation.canonical_root),
                bundle.expected,
                bundle.proposed,
            )
        )
        proposed_index_path, proposed_index_digest = self._proposedIndexPlan(
            lease.transaction_id,
            bundle.proposed,
        )
        materialization_digest = _materializationPlanDigest(
            lease.transaction_id,
            bundle.expected,
            bundle.proposed,
            filesystem_representation_digest,
        )
        record = self.journal.load(lease.transaction_id)
        fence_nonce = record.index_fence_nonce or secrets.token_hex(32)
        _require_digest(fence_nonce, "index_fence_nonce")
        canonical_index = Path(self.attestation.git_common_dir) / "index"
        index_lock_path = canonical_index.with_name("index.lock")
        orig_head_lock_path = canonical_index.with_name("ORIG_HEAD.lock")
        sibling = canonical_index.with_name(
            f"index.galaxy-{lease.transaction_id}-{fence_nonce[:16]}.new"
        )
        intent_ref = f"refs/9to5/promotion-intent/{lease.transaction_id}"
        custom_lock_path = (
            self.journal.root.parent
            / "locks"
            / f"{self.attestation.repository_id}.promotion.lock"
        )
        custom_payload = canonical_json_bytes(
            {
                "schema": "galaxy.promotion-lock/v1",
                "transaction_id": lease.transaction_id,
                "ownership_nonce": record.ownership_nonce,
            }
        )
        index_payload = canonical_json_bytes(
            {
                "schema": "galaxy.index-fence/v1",
                "transaction_id": lease.transaction_id,
                "fence_nonce": fence_nonce,
            }
        )
        orig_head_payload = canonical_json_bytes(
            {
                "schema": "galaxy.orig-head-fence/v1",
                "transaction_id": lease.transaction_id,
                "fence_nonce": fence_nonce,
            }
        )
        custom_owner_digest = hashlib.sha256(custom_payload).hexdigest()
        index_owner_digest = hashlib.sha256(index_payload).hexdigest()
        orig_head_owner_digest = hashlib.sha256(orig_head_payload).hexdigest()
        canonical_ref_lock_path, canonical_ref_lock_owner_digest = (
            self.ref_store.canonicalLockPlan(proposed_oid=lease.proposed_revision)
        )
        custom_owned: _OwnedFile | None = None
        index_owned: _OwnedFile | None = None
        orig_head_owned: _OwnedFile | None = None
        canonical_ref_lock: CanonicalRefLock | None = None
        ref_moved = False
        promoted = False
        preserve_fences = False
        try:
            self.journal.bind_promotion_plan(
                lease.transaction_id,
                intent_ref=intent_ref,
                proposed_index_digest=proposed_index_digest,
                proposed_index_path=str(proposed_index_path),
                canonical_index_path=str(canonical_index),
                index_fence_path=str(index_lock_path),
                orig_head_fence_path=str(orig_head_lock_path),
                index_fence_nonce=fence_nonce,
                index_fence_owner_digest=index_owner_digest,
                orig_head_fence_owner_digest=orig_head_owner_digest,
                custom_lock_path=str(custom_lock_path),
                custom_lock_owner_digest=custom_owner_digest,
                canonical_ref_lock_path=canonical_ref_lock_path,
                canonical_ref_lock_owner_digest=canonical_ref_lock_owner_digest,
                materialization_manifest_digest=materialization_digest,
                index_install_sibling=str(sibling),
            )
            self._persistProposedIndex(
                lease.transaction_id,
                bundle.proposed,
                expected_path=proposed_index_path,
                expected_digest=proposed_index_digest,
            )
            custom_owned = _acquireOwnedFile(custom_lock_path, custom_payload)
            self.journal.bind_promotion_artifact_identities(
                lease.transaction_id,
                custom_lock_identity_digest=custom_owned.identity_digest,
            )
            if self._preflightCanonical(bundle.expected) != expected_preflight:
                raise PromotionRefused(
                    "canonical index or worktree identity drifted before fencing"
                )
            if (
                _validateProspectiveFilesystemRepresentation(
                    Path(self.attestation.canonical_root),
                    bundle.expected,
                    bundle.proposed,
                )
                != filesystem_representation_digest
            ):
                raise PromotionRefused(
                    "prospective filesystem representation drifted before fencing"
                )
            if failpoint is not None:
                failpoint("after_custom_lock")
            self.ref_store.createPrivateRef(intent_ref, lease.proposed_revision)
            if failpoint is not None:
                failpoint("after_promotion_intent")
            index_owned = _acquireOwnedFile(
                index_lock_path,
                index_payload,
            )
            orig_head_owned = _acquireOwnedFile(
                orig_head_lock_path,
                orig_head_payload,
            )
            self.journal.bind_promotion_artifact_identities(
                lease.transaction_id,
                index_fence_identity_digest=index_owned.identity_digest,
                orig_head_fence_identity_digest=orig_head_owned.identity_digest,
            )
            if failpoint is not None:
                failpoint("after_index_lock_create")
            canonical_ref_lock = self.ref_store.prepareCanonicalLock(
                proposed_oid=lease.proposed_revision
            )
            if (
                canonical_ref_lock.path != canonical_ref_lock_path
                or canonical_ref_lock.payload_digest
                != canonical_ref_lock_owner_digest
            ):
                raise PromotionRefused("canonical ref-lock plan drifted before CAS")
            self.journal.bind_promotion_artifact_identities(
                lease.transaction_id,
                canonical_ref_lock_identity_digest=(
                    canonical_ref_lock.identity_digest
                ),
            )
            self.journal.transition(
                lease.transaction_id,
                AttemptPhase.INDEX_FENCED,
            )
            if failpoint is not None:
                failpoint("after_index_fence")

            validatePromotionAuthorization(
                auth,
                store=self.receipt_store,
                journal=self.journal,
            )
            self._validateBoundLandingAuthority(landing_authority, auth)
            if not self.stagedRevisionIntact(request, lease):
                raise PromotionRefused("staged revision changed under index fence")
            if self._preflightCanonical(bundle.expected) != expected_preflight:
                raise PromotionRefused(
                    "canonical index or worktree identity drifted under fence"
                )
            if (
                _validateProspectiveFilesystemRepresentation(
                    Path(self.attestation.canonical_root),
                    bundle.expected,
                    bundle.proposed,
                )
                != filesystem_representation_digest
            ):
                raise PromotionRefused(
                    "prospective filesystem representation drifted under fence"
                )

            try:
                with self._boundLandingCommitPermit(
                    landing_authority,
                    auth,
                ) as require_landing_live:

                    def cas_failpoint(name: str) -> None:
                        if failpoint is not None:
                            failpoint(name)

                    result = self.ref_store.compareAndSwapCanonical(
                        expected_oid=lease.expected_target_revision,
                        proposed_oid=lease.proposed_revision,
                        ownership_nonce=fence_nonce,
                        prepared_lock=canonical_ref_lock,
                        commit_guard=require_landing_live,
                        failpoint=cas_failpoint,
                    )
            except PromotionCrashInjected:
                preserve_fences = True
                raise
            except BaseException as exc:
                classification = self.ref_store.classifyCanonical(
                    expected_oid=lease.expected_target_revision,
                    proposed_oid=lease.proposed_revision,
                )
                if classification is CanonicalRefCas.MOVED:
                    ref_moved = True
                    self.journal.transition(
                        lease.transaction_id,
                        AttemptPhase.REF_MOVED,
                        observed_revision=lease.expected_target_revision,
                        resulting_revision=lease.proposed_revision,
                    )
                    raise PromotionRecoveryRequired(
                        "canonical ref moved before promotion process interruption"
                    ) from exc
                if classification is CanonicalRefCas.DIVERGED:
                    preserve_fences = True
                    divergent_revision = self.ref_store.readRef(
                        self.attestation.head_ref
                    )
                    self.journal.transition(
                        lease.transaction_id,
                        AttemptPhase.POST_PROMOTION_DIVERGENCE,
                        observed_revision=divergent_revision,
                        error=(
                            "canonical ref diverged after or during the owned CAS: "
                            f"{exc}"
                        ),
                        reconciliation_outcome="post_promotion_divergence",
                    )
                    raise PromotionRecoveryRequired(
                        "canonical ref diverged outside the cooperative writer fence"
                    ) from exc
                self.journal.transition(
                    lease.transaction_id,
                    AttemptPhase.CAS_REFUSED,
                    error=f"canonical loose-ref CAS refused: {exc}",
                )
                raise PromotionRefused("canonical loose-ref CAS refused") from exc
            if result is not CanonicalRefCas.MOVED:
                raise PromotionRefused("canonical loose-ref CAS did not move")
            ref_moved = True
            self.journal.transition(
                lease.transaction_id,
                AttemptPhase.REF_MOVED,
                observed_revision=lease.expected_target_revision,
                resulting_revision=lease.proposed_revision,
            )
            if failpoint is not None:
                failpoint("after_ref_moved_journal")

            worktree_digest = _materializeCanonicalWorktree(
                canonical_root=Path(self.attestation.canonical_root),
                git_common=Path(self.attestation.git_common_dir),
                transaction_id=lease.transaction_id,
                fence_nonce=fence_nonce,
                expected=bundle.expected,
                proposed=bundle.proposed,
                writer=self.writer,
                failpoint=failpoint,
            )
            installed_index_digest = _installCanonicalIndex(
                external_index=proposed_index_path,
                canonical_index=canonical_index,
                sibling=sibling,
                expected_digest=proposed_index_digest,
                proposed=bundle.proposed,
                failpoint=failpoint,
            )
            if self.ref_store.readRef(self.attestation.head_ref) != lease.proposed_revision:
                raise PromotionRecoveryRequired("canonical ref diverged after materialization")
            confirmed_worktree_digest = _verifyCanonicalWorktree(
                Path(self.attestation.canonical_root),
                bundle.proposed,
            )
            if confirmed_worktree_digest != worktree_digest:
                raise PromotionRecoveryRequired(
                    "canonical native identity map drifted after materialization"
                )
            semantic_digest = bundle.proposed.manifest_digest
            self.journal.transition(
                lease.transaction_id,
                AttemptPhase.MATERIALIZED,
                canonical_index_digest=semantic_digest,
                canonical_tree_digest=semantic_digest,
            )
            postcondition_digest = canonical_digest(
                {
                    "transaction_id": lease.transaction_id,
                    "canonical_ref": self.attestation.head_ref,
                    "resulting_revision": lease.proposed_revision,
                    "proposed_tree": lease.proposed_tree,
                    "index_digest": installed_index_digest,
                    "worktree_digest": worktree_digest,
                    "manifest_digest": semantic_digest,
                }
            )
            receipt = PromotionReceipt(
                transaction_id=lease.transaction_id,
                staging_receipt_id=auth.staging_receipt_id,
                verification_receipt_id=auth.verification_receipt_id,
                review_receipt_id=auth.review_receipt_id,
                selection_receipt_id=auth.selection_receipt_id,
                expected_revision=lease.expected_target_revision,
                observed_revision=lease.expected_target_revision,
                proposed_revision=lease.proposed_revision,
                resulting_revision=lease.proposed_revision,
                canonical_index_revision=lease.proposed_tree,
                canonical_tree_revision=lease.proposed_tree,
                custom_lock_owner_digest=custom_owner_digest,
                index_fence_owner_digest=index_owner_digest,
                cas_result="moved",
                intent_ref=intent_ref,
                intent_oid=lease.proposed_revision,
                materialization_result="exact",
                postcondition_digest=postcondition_digest,
            )
            stored = self.receipt_store.put(receipt)
            reread = self.receipt_store.read(
                stored.receipt_id,
                expected_type=PromotionReceipt,
            )
            if reread != receipt:
                raise PromotionRecoveryRequired("promotion receipt replay differs")
            self.journal.transition(
                lease.transaction_id,
                AttemptPhase.PROMOTED,
                promotion_receipt_id=stored.receipt_id,
            )
            if failpoint is not None:
                failpoint("after_promoted_journal")
            promoted = True
            return receipt
        except PromotionCrashInjected as exc:
            preserve_fences = True
            raise PromotionRecoveryRequired(
                f"injected hard crash requires reconciliation: {exc}"
            ) from exc
        except PromotionRecoveryRequired:
            raise
        except BaseException as exc:
            if ref_moved:
                raise PromotionRecoveryRequired(
                    f"promotion requires durable consistency recovery: {exc}"
                ) from exc
            current = self.journal.load(lease.transaction_id)
            if current.phase is AttemptPhase.INDEX_FENCED:
                self.journal.transition(
                    lease.transaction_id,
                    AttemptPhase.CAS_REFUSED,
                    error=f"promotion refused before ref movement: {exc}",
                )
            if isinstance(exc, (PromotionRefused, TypeError)):
                raise
            raise PromotionRefused(f"promotion refused before ref movement: {exc}") from exc
        finally:
            if not preserve_fences and (promoted or not ref_moved):
                if orig_head_owned is not None:
                    _releaseOwnedFile(orig_head_owned)
                if index_owned is not None:
                    _releaseOwnedFile(index_owned)
                if custom_owned is not None:
                    _releaseOwnedFile(custom_owned)
                if canonical_ref_lock is not None:
                    self.ref_store.releaseCanonicalLock(canonical_ref_lock)

    def recoverPromotionConsistency(
        self,
        recovery_authority: object,
        transaction_id: str,
        *,
        failpoint: Callable[[str], None] | None = None,
    ) -> PromotionReceipt:
        _require_id(transaction_id, "transaction_id")
        try:
            with _promotionProcessLease(self._promotionProcessLeasePath()):
                return self._recoverPromotionConsistencyHeld(
                    recovery_authority,
                    transaction_id,
                    failpoint=failpoint,
                )
        except _PromotionProcessLeaseBusy as exc:
            raise PromotionRecoveryRequired(
                "original promotion process is still active"
            ) from exc

    def _recoverPromotionConsistencyHeld(
        self,
        recovery_authority: object,
        transaction_id: str,
        *,
        failpoint: Callable[[str], None] | None = None,
    ) -> PromotionReceipt:
        """Finish only an already-moved exact ref; never choose or CAS a revision."""

        _require_id(transaction_id, "transaction_id")
        try:
            self._validateBoundRecoveryAuthority(
                recovery_authority,
                transaction_id=transaction_id,
            )
        except LandingAuthorityRefused as exc:
            raise PromotionRecoveryRequired(
                f"promotion recovery authority refused: {exc}"
            ) from exc
        record = self.journal.load(transaction_id)
        if record.repository_id != self.attestation.repository_id:
            raise PromotionRecoveryRequired("recovery record names another repository")
        if record.phase is AttemptPhase.PROMOTED:
            receipt = self.receipt_store.read(
                record.promotion_receipt_id,
                expected_type=PromotionReceipt,
            )
            self._releaseDurablePromotionFences(record)
            current_revision = self.ref_store.readRef(self.attestation.head_ref)
            if current_revision != receipt.resulting_revision:
                for receipt_id in record.reconciliation_receipt_ids:
                    existing = self.receipt_store.read(
                        receipt_id,
                        expected_type=ReconciliationReceipt,
                    )
                    if (
                        existing.promotion_receipt_id == receipt.receipt_id
                        and existing.classification
                        == "historical_promotion_subsequent_revision"
                        and existing.subsequent_canonical_revision == current_revision
                    ):
                        return receipt
                try:
                    index_raw = readNoFollowBytes(
                        Path(self.attestation.git_common_dir) / "index",
                        max_bytes=512 * 1024 * 1024,
                    )
                    index_digest = hashlib.sha256(index_raw).hexdigest()
                except (OSError, ValueError):
                    index_digest = canonical_digest(
                        {
                            "classification": "subsequent_index_unavailable",
                            "revision": current_revision,
                        }
                    )
                worktree_observation_digest = canonical_digest(
                    {
                        "classification": "historical_promotion_not_replayed",
                        "canonical_root_identity_digest": (
                            self.attestation.canonical_root_identity_digest
                        ),
                        "subsequent_revision": current_revision,
                        "observed_index_digest": index_digest,
                    }
                )
                observation = self._persistReconciliationReceipt(
                    record=record,
                    promotion_receipt_id=receipt.receipt_id,
                    observed_ref_revision=current_revision,
                    observed_index_digest=index_digest,
                    observed_worktree_digest=worktree_observation_digest,
                    recovery_action=(
                        "preserve_historical_promotion_and_record_later_revision"
                    ),
                    classification="historical_promotion_subsequent_revision",
                    subsequent_canonical_revision=current_revision,
                )
                self.journal.append_reconciliation_receipt(
                    transaction_id,
                    observation.receipt_id,
                    outcome="historical_promotion_subsequent_revision",
                )
            return receipt
        if record.phase not in {AttemptPhase.REF_MOVED, AttemptPhase.MATERIALIZED}:
            raise PromotionRecoveryRequired(
                "consistency recovery requires a durably moved canonical ref"
            )
        authorization = PromotionAuthorization(
            transaction_id=record.transaction_id,
            task_id=record.task_id,
            subtask_id=record.subtask_id,
            staging_receipt_id=record.staging_receipt_id,
            verification_receipt_id=record.verification_receipt_id,
            review_receipt_id=record.review_receipt_id,
            selection_receipt_id=record.selection_receipt_id,
            proposed_revision=record.proposed_revision,
            proposed_tree=record.proposed_tree,
            proposed_diff_digest=record.proposed_diff_digest,
            spec_digest=record.spec_digest,
            policy_digest=record.policy_digest,
        )
        validatePromotionAuthorization(
            authorization,
            store=self.receipt_store,
            journal=self.journal,
            recovery=True,
        )
        if self.ref_store.classifyCanonical(
            expected_oid=record.base_revision,
            proposed_oid=record.proposed_revision,
        ) is not CanonicalRefCas.MOVED:
            self.journal.transition(
                transaction_id,
                AttemptPhase.POST_PROMOTION_DIVERGENCE,
                error="canonical ref is neither the durable exact proposed state",
            )
            raise PromotionRecoveryRequired("canonical ref diverged after durable movement")
        bundle = self._loadManifestBundle(transaction_id)
        filesystem_representation_digest = _filesystemRepresentationPlanDigest(
            Path(self.attestation.canonical_root),
            bundle.expected,
            bundle.proposed,
        )
        if (
            bundle.expected.expected_revision != record.base_revision
            or bundle.proposed.manifest_digest != record.parser_manifest_digest
            or _materializationPlanDigest(
                transaction_id,
                bundle.expected,
                bundle.proposed,
                filesystem_representation_digest,
            )
            != record.materialization_manifest_digest
        ):
            raise PromotionRecoveryRequired("recovery manifest artifacts differ")

        custom_payload = canonical_json_bytes(
            {
                "schema": "galaxy.promotion-lock/v1",
                "transaction_id": transaction_id,
                "ownership_nonce": record.ownership_nonce,
            }
        )
        index_payload = canonical_json_bytes(
            {
                "schema": "galaxy.index-fence/v1",
                "transaction_id": transaction_id,
                "fence_nonce": record.index_fence_nonce,
            }
        )
        orig_head_payload = canonical_json_bytes(
            {
                "schema": "galaxy.orig-head-fence/v1",
                "transaction_id": transaction_id,
                "fence_nonce": record.index_fence_nonce,
            }
        )
        if (
            hashlib.sha256(custom_payload).hexdigest()
            != record.custom_lock_owner_digest
            or hashlib.sha256(index_payload).hexdigest()
            != record.index_fence_owner_digest
            or hashlib.sha256(orig_head_payload).hexdigest()
            != record.orig_head_fence_owner_digest
        ):
            raise PromotionRecoveryRequired("recovery fence payload digest differs")
        _recoverOwnedFile(
            Path(record.custom_lock_path),
            custom_payload,
            record.custom_lock_identity_digest,
        )
        index_lock_path = Path(record.canonical_index_path).with_name("index.lock")
        _recoverOwnedFile(
            index_lock_path,
            index_payload,
            record.index_fence_identity_digest,
        )
        _recoverOwnedFile(
            index_lock_path.with_name("ORIG_HEAD.lock"),
            orig_head_payload,
            record.orig_head_fence_identity_digest,
        )
        canonical_index = Path(record.canonical_index_path)
        proposed_index = Path(record.proposed_index_path)
        sibling = Path(record.index_install_sibling)
        try:
            proposed_worktree_digest = ""
            expected_worktree = False
            proposed_worktree = False
            try:
                _verifyCanonicalWorktree(
                    Path(self.attestation.canonical_root),
                    bundle.expected,
                )
                expected_worktree = True
            except PromotionRefused:
                pass
            try:
                proposed_worktree_digest = _verifyCanonicalWorktree(
                    Path(self.attestation.canonical_root),
                    bundle.proposed,
                )
                proposed_worktree = True
            except PromotionRefused:
                pass

            raw_index = readNoFollowBytes(
                canonical_index,
                max_bytes=512 * 1024 * 1024,
            )
            expected_index = False
            proposed_index_installed = False
            try:
                GitIndex.parse(
                    raw_index,
                    expected_manifest=bundle.expected,
                    expected_tree_oids=self.writer.planTreeOids(bundle.expected),
                )
                expected_index = True
            except GitIndexRefused:
                pass
            try:
                GitIndex.parse(raw_index, expected_manifest=bundle.proposed)
                proposed_index_installed = True
            except GitIndexRefused:
                pass

            if record.phase is AttemptPhase.REF_MOVED:
                if expected_worktree and expected_index:
                    proposed_worktree_digest = _materializeCanonicalWorktree(
                        canonical_root=Path(self.attestation.canonical_root),
                        git_common=Path(self.attestation.git_common_dir),
                        transaction_id=transaction_id,
                        fence_nonce=record.index_fence_nonce,
                        expected=bundle.expected,
                        proposed=bundle.proposed,
                        writer=self.writer,
                        failpoint=failpoint,
                    )
                    proposed_worktree = True
                elif not proposed_worktree and expected_index:
                    proposed_worktree_digest = _materializeCanonicalWorktree(
                        canonical_root=Path(self.attestation.canonical_root),
                        git_common=Path(self.attestation.git_common_dir),
                        transaction_id=transaction_id,
                        fence_nonce=record.index_fence_nonce,
                        expected=bundle.expected,
                        proposed=bundle.proposed,
                        writer=self.writer,
                        failpoint=failpoint,
                        resume=True,
                    )
                    proposed_worktree = True
                if proposed_worktree and expected_index:
                    _installCanonicalIndex(
                        external_index=proposed_index,
                        canonical_index=canonical_index,
                        sibling=sibling,
                        expected_digest=record.proposed_index_digest,
                        proposed=bundle.proposed,
                        failpoint=failpoint,
                    )
                    proposed_index_installed = True
                if not (proposed_worktree and proposed_index_installed):
                    self.journal.transition(
                        transaction_id,
                        AttemptPhase.RECOVERY_CONFLICT,
                        error="partial materialization is not exactly recoverable",
                    )
                    raise PromotionRecoveryRequired(
                        "partial materialization requires preserved conflict evidence"
                    )
                semantic_digest = bundle.proposed.manifest_digest
                self.journal.transition(
                    transaction_id,
                    AttemptPhase.MATERIALIZED,
                    canonical_index_digest=semantic_digest,
                    canonical_tree_digest=semantic_digest,
                )
                record = self.journal.load(transaction_id)

            if not proposed_worktree_digest:
                proposed_worktree_digest = _verifyCanonicalWorktree(
                    Path(self.attestation.canonical_root),
                    bundle.proposed,
                )
            confirmed_worktree_digest = _verifyCanonicalWorktree(
                Path(self.attestation.canonical_root),
                bundle.proposed,
            )
            if confirmed_worktree_digest != proposed_worktree_digest:
                raise PromotionRecoveryRequired(
                    "canonical native identity map drifted during recovery"
                )
            installed_raw = readNoFollowBytes(
                canonical_index,
                max_bytes=512 * 1024 * 1024,
            )
            GitIndex.parse(installed_raw, expected_manifest=bundle.proposed)
            installed_index_digest = hashlib.sha256(installed_raw).hexdigest()
            if self.ref_store.readRef(self.attestation.head_ref) != record.proposed_revision:
                raise PromotionRecoveryRequired("canonical ref changed during recovery")
            postcondition_digest = canonical_digest(
                {
                    "transaction_id": transaction_id,
                    "canonical_ref": self.attestation.head_ref,
                    "resulting_revision": record.proposed_revision,
                    "proposed_tree": record.proposed_tree,
                    "index_digest": installed_index_digest,
                    "worktree_digest": proposed_worktree_digest,
                    "manifest_digest": bundle.proposed.manifest_digest,
                }
            )
            receipt = PromotionReceipt(
                transaction_id=transaction_id,
                staging_receipt_id=record.staging_receipt_id,
                verification_receipt_id=record.verification_receipt_id,
                review_receipt_id=record.review_receipt_id,
                selection_receipt_id=record.selection_receipt_id,
                expected_revision=record.base_revision,
                observed_revision=record.base_revision,
                proposed_revision=record.proposed_revision,
                resulting_revision=record.proposed_revision,
                canonical_index_revision=record.proposed_tree,
                canonical_tree_revision=record.proposed_tree,
                custom_lock_owner_digest=record.custom_lock_owner_digest,
                index_fence_owner_digest=record.index_fence_owner_digest,
                cas_result="moved",
                intent_ref=record.intent_ref,
                intent_oid=record.proposed_revision,
                materialization_result="exact",
                postcondition_digest=postcondition_digest,
            )
            stored = self.receipt_store.put(receipt)
            if self.receipt_store.read(
                stored.receipt_id,
                expected_type=PromotionReceipt,
            ) != receipt:
                raise PromotionRecoveryRequired("recovered promotion receipt differs")
            record = self.journal.load(transaction_id)
            reconciliation = self._persistReconciliationReceipt(
                record=record,
                promotion_receipt_id=stored.receipt_id,
                observed_ref_revision=record.proposed_revision,
                observed_index_digest=installed_index_digest,
                observed_worktree_digest=proposed_worktree_digest,
                recovery_action="finish_exact_moved_consistency_transaction",
                classification="promoted_recovered",
            )
            self.journal.transition(
                transaction_id,
                AttemptPhase.PROMOTED,
                promotion_receipt_id=stored.receipt_id,
                reconciliation_receipt_ids=(
                    *record.reconciliation_receipt_ids,
                    reconciliation.receipt_id,
                ),
                reconciliation_receipt_outcomes=(
                    *record.reconciliation_receipt_outcomes,
                    "promoted_recovered",
                ),
                reconciliation_outcome="promoted_recovered",
            )
            self._releaseDurablePromotionFences(self.journal.load(transaction_id))
            return receipt
        except PromotionRecoveryRequired:
            raise
        except (OSError, ValueError, RuntimeError) as exc:
            raise PromotionRecoveryRequired(
                f"promotion consistency recovery failed: {exc}"
            ) from exc

    def reconcileAttempt(
        self,
        recovery_authority: object,
        transaction_id: str,
    ) -> object:
        _require_id(transaction_id, "transaction_id")
        try:
            with _promotionProcessLease(self._promotionProcessLeasePath()):
                return self._reconcileAttemptHeld(
                    recovery_authority,
                    transaction_id,
                )
        except _PromotionProcessLeaseBusy as exc:
            raise PromotionRecoveryRequired(
                "original promotion process is still active"
            ) from exc

    def _reconcileAttemptHeld(
        self,
        recovery_authority: object,
        transaction_id: str,
    ) -> object:
        """Classify durable ref/index/worktree truth without implicit promotion."""

        _require_id(transaction_id, "transaction_id")
        try:
            self._validateBoundRecoveryAuthority(
                recovery_authority,
                transaction_id=transaction_id,
            )
        except LandingAuthorityRefused as exc:
            raise PromotionRecoveryRequired(
                f"promotion recovery authority refused: {exc}"
            ) from exc
        record = self.journal.load(transaction_id)
        if record.phase in {
            AttemptPhase.REF_MOVED,
            AttemptPhase.MATERIALIZED,
            AttemptPhase.PROMOTED,
        }:
            return self._recoverPromotionConsistencyHeld(
                recovery_authority,
                transaction_id,
            )
        if record.phase not in {
            AttemptPhase.PROMOTION_PREPARED,
            AttemptPhase.INDEX_FENCED,
        }:
            return record
        if not record.promotion_plan_digest or not record.custom_lock_path:
            raise PromotionRecoveryRequired(
                "prepared attempt has no durable promotion plan to reconcile"
            )
        bundle = self._loadManifestBundle(transaction_id)
        custom_payload = canonical_json_bytes(
            {
                "schema": "galaxy.promotion-lock/v1",
                "transaction_id": transaction_id,
                "ownership_nonce": record.ownership_nonce,
            }
        )
        if (
            hashlib.sha256(custom_payload).hexdigest()
            != record.custom_lock_owner_digest
        ):
            raise PromotionRecoveryRequired("custom recovery lock payload differs")
        self._recoverOrAdoptOwnedPromotionArtifact(
            record,
            identity_field="custom_lock_identity_digest",
            path=Path(record.custom_lock_path),
            payload=custom_payload,
        )
        index_payload = canonical_json_bytes(
            {
                "schema": "galaxy.index-fence/v1",
                "transaction_id": transaction_id,
                "fence_nonce": record.index_fence_nonce,
            }
        )
        orig_head_payload = canonical_json_bytes(
            {
                "schema": "galaxy.orig-head-fence/v1",
                "transaction_id": transaction_id,
                "fence_nonce": record.index_fence_nonce,
            }
        )
        if (
            hashlib.sha256(index_payload).hexdigest()
            != record.index_fence_owner_digest
            or hashlib.sha256(orig_head_payload).hexdigest()
            != record.orig_head_fence_owner_digest
        ):
            raise PromotionRecoveryRequired("index recovery fence payload differs")
        index_owned = self._recoverOrAdoptOwnedPromotionArtifact(
            record,
            identity_field="index_fence_identity_digest",
            path=Path(record.index_fence_path),
            payload=index_payload,
        )
        orig_head_owned = self._recoverOrAdoptOwnedPromotionArtifact(
            record,
            identity_field="orig_head_fence_identity_digest",
            path=Path(record.orig_head_fence_path),
            payload=orig_head_payload,
        )
        self._recoverOrAdoptCanonicalRefLock(record)
        record = self.journal.load(transaction_id)
        classification = self.ref_store.classifyCanonical(
            expected_oid=record.base_revision,
            proposed_oid=record.proposed_revision,
        )
        if (
            (index_owned is None) != (orig_head_owned is None)
            and classification is not CanonicalRefCas.NOT_MOVED
        ):
            raise PromotionRecoveryRequired(
                "only one standard Git promotion fence survived after ref movement"
            )
        if classification is CanonicalRefCas.MOVED:
            if record.phase is not AttemptPhase.INDEX_FENCED:
                raise PromotionRecoveryRequired(
                    "proposed ref without a durable index fence is a conflict"
                )
            self.journal.transition(
                transaction_id,
                AttemptPhase.REF_MOVED,
                observed_revision=record.base_revision,
                resulting_revision=record.proposed_revision,
            )
            return self._recoverPromotionConsistencyHeld(
                recovery_authority,
                transaction_id,
            )
        if classification is CanonicalRefCas.DIVERGED:
            self.journal.transition(
                transaction_id,
                AttemptPhase.RECOVERY_CONFLICT,
                error="canonical ref is neither expected nor proposed",
                reconciliation_outcome="recovery_conflict",
            )
            raise PromotionRecoveryRequired("canonical ref diverged during reconciliation")
        try:
            raw_index = readNoFollowBytes(
                Path(record.canonical_index_path),
                max_bytes=512 * 1024 * 1024,
            )
            GitIndex.parse(
                raw_index,
                expected_manifest=bundle.expected,
                expected_tree_oids=self.writer.planTreeOids(bundle.expected),
            )
            worktree_digest = _verifyCanonicalWorktree(
                Path(self.attestation.canonical_root),
                bundle.expected,
            )
        except (OSError, ValueError, PromotionRefused) as exc:
            self.journal.transition(
                transaction_id,
                AttemptPhase.RECOVERY_CONFLICT,
                error="expected ref has partial or divergent index/worktree state",
                reconciliation_outcome="recovery_conflict",
            )
            raise PromotionRecoveryRequired(
                "expected ref does not have exact expected materialization"
            ) from exc
        reconciliation = self._persistReconciliationReceipt(
            record=record,
            promotion_receipt_id="",
            observed_ref_revision=record.base_revision,
            observed_index_digest=hashlib.sha256(raw_index).hexdigest(),
            observed_worktree_digest=worktree_digest,
            recovery_action="retire_owned_pre_cas_fences",
            classification="not_promoted",
        )
        reconciled = self.journal.transition(
            transaction_id,
            AttemptPhase.NOT_PROMOTED,
            error="promotion intent did not move the canonical ref",
            reconciliation_outcome="not_promoted",
            reconciliation_receipt_ids=(
                *record.reconciliation_receipt_ids,
                reconciliation.receipt_id,
            ),
            reconciliation_receipt_outcomes=(
                *record.reconciliation_receipt_outcomes,
                "not_promoted",
            ),
        )
        self._releaseDurablePromotionFences(self.journal.load(transaction_id))
        return reconciled

    def reconcileAttempts(
        self,
        recovery_authority: object,
    ) -> tuple[object, ...]:
        """Reconcile every unresolved transaction for this canonical repository."""

        results: list[object] = []
        for record in self.journal.pending_recovery():
            if record.repository_id != self.attestation.repository_id:
                continue
            results.append(
                self.reconcileAttempt(
                    recovery_authority,
                    record.transaction_id,
                )
            )
        return tuple(results)

    def rejectStagedRevision(
        self,
        lease: StagedRevisionLease,
        *,
        reason: str,
    ) -> CandidateResult:
        """Quarantine exact staged evidence before independently retiring its ref."""

        if not isinstance(lease, StagedRevisionLease):
            raise TypeError("lease must be StagedRevisionLease")
        if (
            not isinstance(reason, str)
            or not reason.strip()
            or len(reason.encode("utf-8")) > 1024
            or any(ord(character) < 32 for character in reason)
        ):
            raise ValueError("rejection reason must be bounded printable text")
        quarantine_ref = f"refs/9to5/quarantine/{lease.transaction_id}"
        record = self.journal.load(lease.transaction_id)
        cleanup_error = ""
        if record.phase is AttemptPhase.REJECTED:
            if record.quarantine_ref != quarantine_ref or record.error != reason:
                raise StagedRevisionRefused("rejected attempt evidence differs on replay")
            if self.ref_store.readRef(quarantine_ref) != lease.proposed_revision:
                raise StagedRevisionRefused("quarantine ref differs on rejection replay")
            try:
                self.ref_store.retirePrivateRef(
                    lease.staged_ref,
                    lease.proposed_revision,
                )
            except RefError as exc:
                cleanup_error = str(exc)
            return CandidateResult(
                entered=True,
                staged=True,
                promoted=False,
                removed=not cleanup_error,
                expected_revision=lease.expected_target_revision,
                observed_revision=self.ref_store.readRef(self.attestation.head_ref),
                resulting_revision=self.ref_store.readRef(self.attestation.head_ref),
                checkpoint_revision=lease.checkpoint_revision,
                candidate_snapshot_digest=lease.candidate_snapshot_digest,
                parser_manifest_digest=lease.parser_manifest_digest,
                staged_tree_digest=lease.parser_manifest_digest,
                checkpoint_ref=lease.checkpoint_ref,
                staged_ref=lease.staged_ref,
                quarantine_ref=quarantine_ref,
                error=reason,
                cleanup_error=cleanup_error,
            )
        request = self._live_requests.get(lease.transaction_id)
        if request is None or not self.stagedRevisionIntact(request, lease):
            raise StagedRevisionRefused("cannot reject a non-intact staged revision")
        live_before = attestCanonicalRepository(self.attestation.canonical_root)
        if live_before != self.attestation:
            raise StagedRevisionRefused("canonical repository changed before rejection")
        self.ref_store.createPrivateRef(quarantine_ref, lease.proposed_revision)
        if self.ref_store.readRef(quarantine_ref) != lease.proposed_revision:
            raise StagedRevisionRefused("quarantine ref did not persist exactly")
        self.journal.transition(
            lease.transaction_id,
            AttemptPhase.REJECTED,
            quarantine_ref=quarantine_ref,
            error=reason,
        )
        try:
            self.ref_store.retirePrivateRef(
                lease.staged_ref,
                lease.proposed_revision,
            )
        except RefError as exc:
            cleanup_error = str(exc)
        live_after = attestCanonicalRepository(self.attestation.canonical_root)
        if live_after != self.attestation:
            raise StagedRevisionRefused("canonical repository changed during rejection")
        return CandidateResult(
            entered=True,
            staged=True,
            promoted=False,
            removed=not cleanup_error,
            expected_revision=lease.expected_target_revision,
            observed_revision=live_after.head_oid,
            resulting_revision=live_after.head_oid,
            checkpoint_revision=lease.checkpoint_revision,
            candidate_snapshot_digest=lease.candidate_snapshot_digest,
            parser_manifest_digest=lease.parser_manifest_digest,
            staged_tree_digest=lease.parser_manifest_digest,
            checkpoint_ref=lease.checkpoint_ref,
            staged_ref=lease.staged_ref,
            quarantine_ref=quarantine_ref,
            error=reason,
            cleanup_error=cleanup_error,
        )


@dataclass(frozen=True, kw_only=True)
class CloneLease:
    transaction_id: str
    task_id: str
    subtask_id: str
    attempt_id: str
    checkout_path: str
    expected_base_revision: str
    runner_kind: RunnerKind
    candidate_branch: str
    repository_id: str
    ownership_nonce: str
    git_dir: str
    git_common_dir: str
    canonical_git_common_dir: str
    closure_manifest_digest: str
    shallow_root_revision: str
    hardlink_count_verified: bool
    alternates_absent: bool
    remote_absent: bool
    linked_worktree_pointer_absent: bool
    registered_at: str
    runtime_token: object | None = None

    def __post_init__(self) -> None:
        for name in ("transaction_id", "task_id", "subtask_id", "attempt_id"):
            _require_id(getattr(self, name), name)
        if not isinstance(self.runner_kind, RunnerKind):
            raise TypeError("runner_kind must be RunnerKind")
        _require_oid(self.expected_base_revision, "expected_base_revision")
        _require_oid(self.shallow_root_revision, "shallow_root_revision")
        if self.shallow_root_revision != self.expected_base_revision:
            raise ValueError("shallow root must equal the exact expected base revision")
        _require_digest(self.repository_id, "repository_id")
        _require_digest(self.ownership_nonce, "ownership_nonce")
        _require_digest(self.closure_manifest_digest, "closure_manifest_digest")
        expected_branch = f"refs/heads/9to5/candidates/{self.transaction_id}"
        if self.candidate_branch != expected_branch:
            raise ValueError(f"candidate_branch must be {expected_branch}")
        checkout = _absolute(self.checkout_path, "checkout_path")
        git_dir = _absolute(self.git_dir, "git_dir")
        common = _absolute(self.git_common_dir, "git_common_dir")
        canonical_common = _absolute(
            self.canonical_git_common_dir, "canonical_git_common_dir"
        )
        if not _is_within(git_dir, checkout) or not _is_within(common, checkout):
            raise ValueError("Git metadata must remain inside the private clone")
        if _is_within(canonical_common, checkout) or _is_within(checkout, canonical_common):
            raise ValueError("private clone and canonical Git metadata must not overlap")
        if not self.hardlink_count_verified:
            raise ValueError("private clone hardlink absence must be verified")
        if not self.alternates_absent:
            raise ValueError("private clone alternates must be absent")
        if not self.remote_absent:
            raise ValueError("private clone remote must be absent")
        if not self.linked_worktree_pointer_absent:
            raise ValueError("private clone linked-worktree pointer must be absent")
        _require_time(self.registered_at, "registered_at")

    def toDict(self) -> dict[str, Any]:
        return {
            field.name: _json_value(getattr(self, field.name))
            for field in fields(self)
            if field.name != "runtime_token"
        }


