    def validateLandingAuthority(
        self,
        authority: object,
        authorization: object,
    ) -> LandingAuthority:
        with self._authorityPermit():
            return self._validateLandingAuthorityLocked(authority, authorization)

    def _validateLandingAuthorityLocked(
        self,
        authority: object,
        authorization: object,
    ) -> LandingAuthority:
        from platform_core.runtime.receipts import PromotionAuthorization

        auth = PromotionAuthorization.from_value(authorization)
        if type(authority) is not LandingAuthority:
            raise LandingAuthorityRefused("landing authority is not live")
        live = self._landings.get(authority.landing_id)
        if (
            live is None
            or not _processAuthorityRecordMatches(live, authority)
            or authority._process_capability is not self._process_capability
            or authority.issuer_instance_id != self._instance_id
            or authority.run_id != self.run_id
            or authority.controller_generation != self.controller_generation
            or authority.revocation_generation != self.revocation_generation
            or authority.outer_scope_digest != self.outer_scope_digest
        ):
            raise LandingAuthorityRefused("landing authority is not live")
        admission_record = self._admissions.get(authority.admission_id)
        admission = admission_record.authority if admission_record is not None else None
        self._validateAdmissionLocked(admission)
        if authority.watchdog_generation != self.watchdog_generation:
            raise LandingAuthorityRefused(
                "landing authority watchdog generation changed"
            )
        if self._now() >= authority.deadline:
            raise LandingAuthorityRefused("landing authority expired")
        scope = (
            authority.transaction_id,
            authority.task_id,
            authority.subtask_id,
            authority.proposed_revision,
            authority.proposed_tree,
            authority.staging_receipt_id,
            authority.verification_receipt_id,
            authority.review_receipt_id,
            authority.selection_receipt_id,
            authority.proposed_diff_digest,
            authority.spec_digest,
            authority.policy_digest,
        )
        expected = (
            auth.transaction_id,
            auth.task_id,
            auth.subtask_id,
            auth.proposed_revision,
            auth.proposed_tree,
            auth.staging_receipt_id,
            auth.verification_receipt_id,
            auth.review_receipt_id,
            auth.selection_receipt_id,
            auth.proposed_diff_digest,
            auth.spec_digest,
            auth.policy_digest,
        )
        if scope != expected:
            raise LandingAuthorityRefused("landing authority scope differs")
        return authority

    @contextmanager
    def landingCommitPermit(
        self,
        authority: object,
        authorization: object,
    ):
        """Hold landing liveness through the irreversible canonical CAS."""

        with self._authorityPermit():
            self._validateLandingAuthorityLocked(authority, authorization)

            def require_live() -> LandingAuthority:
                return self._validateLandingAuthorityLocked(
                    authority,
                    authorization,
                )

            yield require_live

    def revokeLandingAuthority(self, authority: LandingAuthority) -> None:
        with self._lock:
            if type(authority) is LandingAuthority:
                record = self._landings.get(authority.landing_id)
                if record is not None and record.authority is authority:
                    self._landings.pop(authority.landing_id, None)

    def revokeRunAdmission(self, admission: RunAdmissionAuthority) -> None:
        with self._lock:
            if type(admission) is RunAdmissionAuthority:
                record = self._admissions.get(admission.admission_id)
                if record is not None and record.authority is admission:
                    self._retireAdmissionLocked(admission.admission_id)

    def issueRecoveryAuthority(
        self,
        *,
        admission: object,
        repository_id: str,
        transaction_id: str,
    ) -> PromotionRecoveryAuthority:
        with self._authorityPermit():
            _require_digest(repository_id, "repository_id")
            _require_id(transaction_id, "transaction_id")
            live_admission = self._validateAdmissionLocked(admission)
            if (
                live_admission.canonical_repository_id
                and repository_id != live_admission.canonical_repository_id
            ):
                raise LandingAuthorityRefused(
                    "promotion recovery repository differs from run admission"
                )
            if self._recovery_quiescence_probe is None:
                raise LandingAuthorityRefused(
                    "promotion recovery requires a quiescence oracle"
                )
            try:
                quiescent = self._recovery_quiescence_probe(transaction_id)
            except Exception as exc:
                raise LandingAuthorityRefused(
                    "promotion recovery quiescence probe failed closed"
                ) from exc
            if quiescent is not True:
                raise LandingAuthorityRefused(
                    "original promoter is not proven quiescent"
                )
            authority = PromotionRecoveryAuthority(
                run_id=self.run_id,
                repository_id=repository_id,
                transaction_id=transaction_id,
                controller_generation=self.controller_generation,
                watchdog_generation=self.watchdog_generation,
                revocation_generation=self.revocation_generation,
                outer_scope_digest=self.outer_scope_digest,
                deadline=live_admission.deadline,
                issuer_instance_id=self._instance_id,
                admission_id=live_admission.admission_id,
                recovery_id=secrets.token_hex(32),
                _process_capability=self._process_capability,
                _authority_token=object(),
                _issuer=self,
            )
            self._validateAdmissionLocked(live_admission)
            self._recoveries[authority.recovery_id] = _processAuthorityRecord(
                authority,
                identity_fields=_RECOVERY_IDENTITY_FIELDS,
            )
            return authority

    def validateRecoveryAuthority(
        self,
        authority: object,
        *,
        repository_id: str,
        transaction_id: str,
    ) -> PromotionRecoveryAuthority:
        with self._authorityPermit():
            if type(authority) is not PromotionRecoveryAuthority:
                raise LandingAuthorityRefused(
                    "promotion recovery authority is not live"
                )
            live = self._recoveries.get(authority.recovery_id)
            if (
                live is None
                or not _processAuthorityRecordMatches(live, authority)
                or authority._process_capability is not self._process_capability
                or authority.issuer_instance_id != self._instance_id
                or authority.run_id != self.run_id
                or authority.repository_id != repository_id
                or authority.transaction_id != transaction_id
                or authority.controller_generation != self.controller_generation
                or authority.watchdog_generation != self.watchdog_generation
                or authority.revocation_generation != self.revocation_generation
                or authority.outer_scope_digest != self.outer_scope_digest
            ):
                raise LandingAuthorityRefused(
                    "promotion recovery authority scope differs"
                )
            admission_record = self._admissions.get(authority.admission_id)
            self._validateAdmissionLocked(
                admission_record.authority if admission_record is not None else None
            )
            if self._now() >= authority.deadline:
                raise LandingAuthorityRefused(
                    "promotion recovery authority expired"
                )
            return authority

    def advanceWatchdog(self, generation: int) -> None:
        with self._lock:
            self._requireIssuerScopeLocked()
            if not self._live:
                raise LandingAuthorityRefused("landing issuer is not live")
            if self._installed_authority:
                raise LandingAuthorityRefused(
                    "installed watchdog generation is owned by the bootstrap guard"
                )
            if type(generation) is not int or generation <= self.watchdog_generation:
                raise ValueError("watchdog generation must increase")
            self.watchdog_generation = generation
            self._captureIssuerScope()


