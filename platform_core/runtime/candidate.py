@dataclass(frozen=True, slots=True)
class _ProcessAuthorityRecord:
    """Issuer-owned authority snapshot detached from the returned capability."""

    authority: object
    value_scope: tuple[tuple[str, object], ...]
    identity_scope: tuple[tuple[str, object], ...]


def _processAuthorityRecord(
    authority: object,
    *,
    identity_fields: frozenset[str],
) -> _ProcessAuthorityRecord:
    value_scope: list[tuple[str, object]] = []
    identity_scope: list[tuple[str, object]] = []
    for field in fields(cast(Any, authority)):
        item = (field.name, getattr(authority, field.name))
        if field.name in identity_fields:
            identity_scope.append(item)
        else:
            value_scope.append(item)
    return _ProcessAuthorityRecord(
        authority=authority,
        value_scope=tuple(value_scope),
        identity_scope=tuple(identity_scope),
    )


def _processAuthorityRecordMatches(
    record: _ProcessAuthorityRecord,
    authority: object,
) -> bool:
    if record.authority is not authority:
        return False
    try:
        for name, expected in record.identity_scope:
            if getattr(authority, name) is not expected:
                return False
        for name, expected in record.value_scope:
            observed = getattr(authority, name)
            if type(observed) is not type(expected) or observed != expected:
                return False
    except AttributeError:
        return False
    return True


