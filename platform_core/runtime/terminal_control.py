"""Terminal adapter for the shared run-control command model.

The controller owns only terminal parsing and presentation. Mutations still flow through
``ControlBus``, the same transactional authority used by Discord and the web surface.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  TerminalController  -- Parse one terminal stream and dispatch normalized commands to a ControlBus.
  startTerminalControl(task_id: str) -> threading.Thread  -- Start the production terminal controller for ``task_id``.
DEPENDS-ON: platform_core.runtime.control, state.task
SIDE-EFFECTS: reads an injected terminal stream and writes ControlBus commands
RUN/TEST: python -m pytest tests/control/test_terminal_control.py
"""
from __future__ import annotations

import sys
import threading
from collections.abc import Callable
from typing import Any, TextIO

from platform_core.runtime.control import ControlBus
from state.task import TaskState


CONTROL_HELP = (
    "[terminal control] commands: abort | pause | resume | skip <st-00N> | "
    "add <text> | approve | reject | status | help"
)


class TerminalController:
    """Parse one terminal stream and dispatch normalized commands to a ControlBus."""

    def __init__(
        self,
        task_id: str,
        *,
        bus: Any | None = None,
        state_loader: Callable[[str], Any] = TaskState.load,
        input_stream: TextIO | None = None,
        output_stream: TextIO | None = None,
    ) -> None:
        self.task_id = task_id
        self.bus = bus if bus is not None else ControlBus(task_id)
        self.state_loader = state_loader
        self.input_stream = input_stream if input_stream is not None else sys.stdin
        self.output_stream = output_stream if output_stream is not None else sys.stdout

    def _write(self, message: str) -> None:
        print(message, file=self.output_stream, flush=True)

    @staticmethod
    def _parse(line: str) -> tuple[str, str]:
        normalized = line.strip()
        while normalized.startswith("!"):
            normalized = normalized[1:].lstrip()
        verb, _, payload = normalized.partition(" ")
        return verb.lower(), payload.strip()

    def handleLine(self, line: str) -> None:
        """Handle one line. Empty lines are inert; malformed commands show help."""
        verb, payload = self._parse(line)
        if not verb:
            return
        if verb in {"abort", "stop", "quit"} and not payload:
            self.bus.requestAbort()
            self._write("[ctl] abort requested")
        elif verb == "pause" and not payload:
            self.bus.requestPause()
            self._write("[ctl] paused")
        elif verb == "resume" and not payload:
            self.bus.clearPause()
            self._write("[ctl] resumed")
        elif verb in {"approve", "reject"} and not payload:
            gate = self.bus.getPendingGate()
            if gate:
                self.bus.decide(gate, verb)
                self._write(f"[ctl] gate {gate} -> {verb}")
            else:
                self._write("[ctl] no pending gate")
        elif verb == "skip" and payload:
            self.bus.pushOp({"op": "skip", "subtask_id": payload})
            self._write("[ctl] skip queued")
        elif verb == "add" and payload:
            self.bus.pushOp({"op": "add", "title": payload, "description": payload})
            self._write("[ctl] add queued")
        elif verb == "status" and not payload:
            state = self.state_loader(self.task_id)
            done, total = state.progress()
            status = (getattr(state, "meta", {}) or {}).get("status", "unknown")
            self._write(f"[ctl] {status} · {done}/{total} subtasks")
        else:
            self._write(CONTROL_HELP)

    def run(self) -> None:
        """Consume the configured stream until EOF, isolating individual command errors."""
        self._write(CONTROL_HELP)
        for line in self.input_stream:
            try:
                self.handleLine(line)
            except Exception as exc:  # noqa: BLE001 -- one bad command must not kill controls
                self._write(f"[ctl] error: {exc}")

    def startDaemon(self) -> threading.Thread:
        """Start the controller on a daemon thread and return the thread handle."""
        thread = threading.Thread(target=self.run, name="terminal-control", daemon=True)
        thread.start()
        return thread


def startTerminalControl(task_id: str) -> threading.Thread:
    """Start the production terminal controller for ``task_id``."""
    return TerminalController(task_id).startDaemon()
