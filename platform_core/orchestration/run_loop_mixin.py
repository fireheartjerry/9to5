    def runExecutionLoop(self, state: TaskState, architect_doc: str, work_dir: str,
                         bus: "ControlBus", dashboard: "DiscordDashboard",
                         parallelism: int = 1) -> None:
        # Record the run's concurrency + shared working tree so _remediationUnsafe can tell
        # whether a remediation snapshot/restore would clobber concurrent peer workers (see #1).
        self._parallelism = parallelism
        self._work_dir = work_dir
        self._last_instinct_ts = 0.0   # Spec B: throttle the periodic Nightclaw instinct call
        # Reclaim stale worktrees left by a PRIOR crash of this task before scheduling any work
        # (none are in use yet here) -- otherwise gcOrphans would be dead code and orphans pile up.
        if getattr(config, "WORKTREE_ISOLATION_ENABLED", False):
            from platform_core.runtime import worktree
            worktree.gcOrphans(state)
        position = iters = no_progress = 0
        prev_terminal = -1
        dry_backfills = 0     # consecutive empty horizon-fill attempts (self-improvement runs)
        while True:
            iters += 1
            _heartbeat.beat(getattr(state, "task_id", ""))   # liveness beacon (throttled ~10s)
            if self._deadlineBreak(state, dashboard):
                break
            # Guard on NO PROGRESS (not raw iteration count) to avoid false-aborting long runs.
            terminal = sum(1 for s in state.subtasks if s["status"] in ("done", "failed", "removed"))
            no_progress = no_progress + 1 if terminal == prev_terminal else 0
            prev_terminal = terminal
            self._livelockGuard(no_progress, iters)
            self._checkControl(state, bus, dashboard)
            if bus.isForceReplan():
                bus.clearForceReplan()
                self._forcedReplan(state, architect_doc, dashboard)
            try:
                self._maybeInstinct(state, bus)
            except Exception:  # noqa: BLE001 -- instinct is best-effort, never blocks the loop
                pass
            if parallelism <= 1:
                signal, position, dry_backfills = _sequentialIteration(
                    self, state, architect_doc, work_dir, bus, dashboard,
                    position, dry_backfills)
                if signal == "break":
                    break
                continue
            # parallel: run the ready set (deps satisfied) concurrently
            signal, position, dry_backfills = _parallelIteration(
                self, state, architect_doc, work_dir, bus, dashboard,
                position, parallelism, dry_backfills)
            if signal == "break":
                break
