def _clamp(v: Any) -> int:
    try:
        n = int(float(v))
    except (TypeError, ValueError):
        n = 0
    return max(0, min(100, n))


def _axis(name: str) -> str:
    key = str(name or "").strip().lower().replace("_", "-")
    key = ALIASES.get(key, key)
    if key not in AXES:
        raise ValueError(f"unknown work-profile axis: {name}")
    return key


@dataclass(frozen=True)
class WorkProfile:
    """Raw user-facing work profile."""
    preset: str
    axes: dict[str, int]
    source: str = "default"
    version: int = VERSION

    def to_meta(self) -> dict[str, Any]:
        return {"version": self.version, "preset": self.preset,
                "source": self.source, "axes": dict(self.axes)}

    def compact(self) -> str:
        return ", ".join(f"{AXIS_SHORT[k]}={self.axes[k]}" for k in AXES)

    def summary(self) -> str:
        return " | ".join(f"{AXIS_SHORT[k]} {self.axes[k]}" for k in AXES)

    def dominant_axis(self) -> str:
        return max(AXES, key=lambda k: self.axes.get(k, 0))


@dataclass(frozen=True)
class RunIntentPolicy:
    """Compiled operational policy consumed by Nightclaw subsystems."""
    discovery_depth: str
    planner_posture: str
    effort_floor_by_task_kind: dict[str, str]
    review_thresholds: dict[str, Any]
    verify_requirements: dict[str, Any]
    fork_strategy: dict[str, Any]
    society_strategy: dict[str, Any]
    execution_environment_preference: str
    safety_posture: dict[str, Any]
    horizon_fill_strategy: str
    learning_tags: dict[str, Any]

    def to_meta(self) -> dict[str, Any]:
        return {
            "version": VERSION,
            "discovery_depth": self.discovery_depth,
            "planner_posture": self.planner_posture,
            "effort_floor_by_task_kind": self.effort_floor_by_task_kind,
            "review_thresholds": self.review_thresholds,
            "verify_requirements": self.verify_requirements,
            "fork_strategy": self.fork_strategy,
            "society_strategy": self.society_strategy,
            "execution_environment_preference": self.execution_environment_preference,
            "safety_posture": self.safety_posture,
            "horizon_fill_strategy": self.horizon_fill_strategy,
            "learning_tags": self.learning_tags,
        }


def _parse_compact(raw: str) -> dict[str, int]:
    out: dict[str, int] = {}
    for part in str(raw or "").replace(";", ",").split(","):
        if not part.strip():
            continue
        if "=" not in part and ":" not in part:
            raise ValueError(f"invalid work-profile item: {part}")
        sep = "=" if "=" in part else ":"
        k, v = part.split(sep, 1)
        out[_axis(k)] = _clamp(v)
    return out


def resolve(raw: Any = None, *, preset: str | None = None) -> WorkProfile:
    """Resolve preset/JSON/compact profile into a complete WorkProfile."""
    selected = (preset or DEFAULT_PRESET).strip().lower()
    if selected not in PRESETS:
        raise ValueError(f"unknown work-profile preset: {preset}")
    axes = dict(PRESETS[selected])
    source = "preset" if preset else "default"
    if raw:
        if isinstance(raw, WorkProfile):
            return raw
        if isinstance(raw, dict):
            selected = str(raw.get("preset") or selected).strip().lower()
            if selected not in PRESETS:
                raise ValueError(f"unknown work-profile preset: {selected}")
            axes = dict(PRESETS[selected])
            values = raw.get("axes") if isinstance(raw.get("axes"), dict) else raw
            for k, v in values.items():
                if k in {"preset", "source", "version"}:
                    continue
                axes[_axis(k)] = _clamp(v)
            source = str(raw.get("source") or "dict")
        else:
            text = str(raw).strip()
            try:
                parsed = json.loads(text)
            except json.JSONDecodeError:
                parsed = None
            if isinstance(parsed, dict):
                return resolve(parsed, preset=selected)
            if text.lower() in PRESETS:
                selected = text.lower()
                axes = dict(PRESETS[selected])
                source = "preset"
            else:
                axes.update(_parse_compact(text))
                source = "compact"
    return WorkProfile(preset=selected, axes={k: _clamp(axes.get(k, 0)) for k in AXES}, source=source)


def policy(profile: WorkProfile) -> RunIntentPolicy:
    a = profile.axes
    dom = profile.dominant_axis()
    if a["discovery"] >= 85:
        discovery_depth = "transformative"
    elif a["discovery"] >= 60:
        discovery_depth = "lenses"
    elif a["momentum"] >= 80 and a["discovery"] < 40:
        discovery_depth = "none"
    else:
        discovery_depth = "digest"
    posture = {
        "stability": "audit",
        "evidence": "verify",
        "architecture": "design",
        "momentum": "delivery",
        "discovery": "explore",
    }[dom] if a[dom] >= 65 else "blended"
    effort_floor = {"default": "default", "strict_verify": "high"}
    if a["architecture"] >= 70:
        effort_floor["design"] = "xhigh"
    if a["discovery"] >= 75:
        effort_floor["explore"] = "xhigh"
    if a["momentum"] >= 80:
        effort_floor["simple"] = "default"
    review_floor = "medium" if max(a["stability"], a["evidence"]) >= 70 else "high"
    if a["momentum"] >= 80 and max(a["stability"], a["evidence"]) < 60:
        review_floor = "high"
    env_pref = "local"
    if a["discovery"] >= 75:
        env_pref = "worktree"
    if max(a["stability"], a["evidence"]) >= 75:
        env_pref = "isolated"
    return RunIntentPolicy(
        discovery_depth=discovery_depth,
        planner_posture=posture,
        effort_floor_by_task_kind=effort_floor,
        review_thresholds={
            "gemini_blocking_severity": review_floor,
            "review_short_outputs": max(a["stability"], a["evidence"]) >= 80,
            "skip_repeat_reviews": a["momentum"] >= 75,
            "architecture_review_weighted": a["architecture"] >= 65,
        },
        verify_requirements={
            "affected_tests": a["evidence"] >= 65,
            "evidence_receipt_strict": a["evidence"] >= 80,
            "regression_checks": a["stability"] >= 70,
            "keep_sufficient_not_sprawling": a["momentum"] >= 75,
        },
        fork_strategy={
            "prefer_forks": max(a["discovery"], a["architecture"]) >= 75,
            "conservative_forks": max(a["stability"], a["evidence"]) >= 75,
            "rare_forks": a["momentum"] >= 80,
        },
        society_strategy={
            "dominant_axis": dom,
            "debate_rounds": 1 if a["momentum"] >= 80 else (3 if a["architecture"] >= 70 or a["discovery"] >= 70 else 2),
            "preferred_roles": preferred_roles(profile),
        },
        execution_environment_preference=env_pref,
        safety_posture={
            "destructive_tolerance": "low" if a["stability"] >= 70 else "normal",
            "speculative_requires_isolation": a["discovery"] >= 70,
            "risky_actions_need_extra_justification": a["evidence"] >= 70,
        },
        horizon_fill_strategy=posture,
        learning_tags={"preset": profile.preset, "dominant_axis": dom, "axes": dict(a)},
    )


def surface_tags(profile: WorkProfile | dict | None) -> list[str]:
    p = resolve(profile) if not isinstance(profile, WorkProfile) else profile
    tags = [f"profile:{p.preset}", f"profile_axis:{p.dominant_axis()}"]
    tags.extend(f"profile_{axis}:{p.axes[axis]}" for axis in AXES)
    return tags


def preferred_roles(profile: WorkProfile | dict | None) -> list[str]:
    p = resolve(profile) if not isinstance(profile, WorkProfile) else profile
    a = p.axes
    roles = ["coder"]
    if a["stability"] >= 60:
        roles += ["reviewer", "tester"]
    if a["evidence"] >= 60:
        roles += ["tester", "reviewer"]
    if a["architecture"] >= 60:
        roles += ["planner", "researcher"]
    if a["discovery"] >= 60:
        roles += ["researcher", "planner"]
    seen = []
    for r in roles:
        if r not in seen:
            seen.append(r)
    return seen


def from_state(state) -> WorkProfile:
    try:
        return resolve((getattr(state, "meta", {}) or {}).get("work_profile"))
    except Exception:
        return resolve()


def policy_from_state(state) -> RunIntentPolicy:
    meta = getattr(state, "meta", {}) or {}
    stored = meta.get("run_intent_policy")
    if isinstance(stored, dict) and stored.get("version") == VERSION:
        try:
            return RunIntentPolicy(
                discovery_depth=stored.get("discovery_depth", "digest"),
                planner_posture=stored.get("planner_posture", "blended"),
                effort_floor_by_task_kind=dict(stored.get("effort_floor_by_task_kind") or {}),
                review_thresholds=dict(stored.get("review_thresholds") or {}),
                verify_requirements=dict(stored.get("verify_requirements") or {}),
                fork_strategy=dict(stored.get("fork_strategy") or {}),
                society_strategy=dict(stored.get("society_strategy") or {}),
                execution_environment_preference=stored.get("execution_environment_preference", "local"),
                safety_posture=dict(stored.get("safety_posture") or {}),
                horizon_fill_strategy=stored.get("horizon_fill_strategy", "blended"),
                learning_tags=dict(stored.get("learning_tags") or {}),
            )
        except Exception:
            pass
    return policy(from_state(state))


def guidance_block(profile: WorkProfile | dict | None, *, context: str = "run") -> str:
    p = resolve(profile) if not isinstance(profile, WorkProfile) else profile
    pol = policy(p)
    lines = [
        "## Nightclaw work profile",
        f"Preset/source: {p.preset} / {p.source}. Axes: {p.compact()}.",
        f"Dominant posture: {pol.planner_posture}. Discovery depth: {pol.discovery_depth}.",
        "Apply this as an operating policy, not decorative prose:",
        "- Hard boundaries: never override user scope, safety rules, feature flags, or available backends.",
    ]
    if p.axes["stability"] >= 60:
        lines.append("- Stability: prefer safe, narrow, compatible changes; call out regression risks.")
    if p.axes["evidence"] >= 60:
        lines.append("- Evidence: strengthen tests, verification, reproducible proof, and acceptance evidence.")
    if p.axes["architecture"] >= 60:
        lines.append("- Architecture: clarify boundaries, data flow, ownership, and maintainability tradeoffs.")
    if p.axes["momentum"] >= 60:
        lines.append("- Momentum: keep the path shippable; avoid avoidable analysis loops and sprawling scope.")
    if p.axes["discovery"] >= 60:
        lines.append("- Discovery: look for high-upside opportunities and transformative alternatives within scope.")
    if len(lines) == 4:
        lines.append("- Balanced: blend safety, evidence, design, delivery, and exploration pragmatically.")
    return "\n".join(lines) + f"\nContext: {context}.\n"


def profile_help_embed_fields() -> list[tuple[str, str]]:
    fields = [(axis.title(), AXIS_DESCRIPTIONS[axis]) for axis in AXES]
    presets = "\n".join(
        f"`{name}` - {PRESET_DESCRIPTIONS.get(name, '')} ({resolve(name).summary()})"
        for name in PRESETS
    )
    fields.append(("Presets", presets))
    return fields
