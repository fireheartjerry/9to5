"""Plan-time project-context injection (any-project capabilities, spec §3.4).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  projectContextBlock(work_dir: str) -> str  -- Budgeted introspection digest of work_dir for the plan prompt
DEPENDS-ON: config, introspect
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_plan_project_context.py
"""
from __future__ import annotations

import config

# Hard wall-clock budget for plan-time project introspection (fail-open to "" past it).
PROJECT_CONTEXT_TIMEOUT_S = 20.0


def projectContextBlock(work_dir: str) -> str:
    """Budgeted introspection digest of work_dir for the plan prompt. Fail-open:
    flag off, missing package, ANY scan error, or exceeding the hard time budget => "" --
    never blocks or degrades planning (a huge/slow tree costs at most the budget once)."""
    try:
        if not config.PROJECT_INTROSPECTION_ENABLED:
            return ""
        from concurrent.futures import ThreadPoolExecutor
        import introspect  # lazy: leaf package, paid only when the flag is on

        def _extract() -> str:
            model = introspect.project_extract.extractProject(
                work_dir, max_files=config.PROJECT_INTROSPECTION_MAX_FILES)
            return introspect.project_extract.contextForPrompt(model, budget_chars=3000)

        pool = ThreadPoolExecutor(max_workers=1)
        try:
            return pool.submit(_extract).result(timeout=PROJECT_CONTEXT_TIMEOUT_S)
        finally:
            pool.shutdown(wait=False, cancel_futures=True)
    except Exception:  # noqa: BLE001 -- fail-open: introspection never blocks planning
        return ""
