"""Fork policy: decide IF (shouldFork) and HOW (forkPlan) to fork a subtask (Epic 6).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  shouldFork(subtask: dict, *, enabled: bool, projected_cost: float, cost_ceiling: float, worktree_isolated: bool, goal_elaborated: str, is_self_referential: bool, work_profile=None) -> bool  -- CONSERVATIVE OPT-IN gate
  BranchSeed  -- One branch's diversity seed: effort (also picks the model) + an angle hint.
  ForkPlan
  forkPlan(subtask: dict, *, n: int, angles: tuple=DIVERSITY_ANGLES, work_profile=None, work_dir: str | None=None) -> ForkPlan  -- Build N diversity seeds spanning effort x angle
DEPENDS-ON: config, explore.generateApproaches, explore.scoreApproaches, introspect.extractProject, platform_core.orchestration, platform_core.orchestration.subtask
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_fork_policy.py
"""
from __future__ import annotations

from dataclasses import dataclass, field

import config
from platform_core.orchestration.subtask import _singleDeliverable

# Angle-hint bank: orthogonal approaches injected per branch (claude-code coordinator idea).
DIVERSITY_ANGLES: tuple[str, ...] = (
    "Approach A: the smallest safe change that satisfies the acceptance check.",
    "Approach B: refactor the touched code for clarity first, then satisfy the check.",
    "Approach C: test-first -- write/strengthen the check, then make it pass.",
)
# Effort spread; via config.MODEL_BY_EFFORT an effort spread is also a model spread for free.
EFFORT_CYCLE: tuple[str, ...] = ("high", "xhigh", "high")

_DOC_ONLY_MARKERS = ("doc-only", "documentation only", "typo", "readme")


def _isDocOnly(subtask: dict) -> bool:
    blob = f"{subtask.get('title', '')} {subtask.get('description', '')}".lower()
    return any(m in blob for m in _DOC_ONLY_MARKERS)


def shouldFork(subtask: dict, *, enabled: bool, projected_cost: float, cost_ceiling: float,
               worktree_isolated: bool, goal_elaborated: str, is_self_referential: bool,
               work_profile=None) -> bool:
    """CONSERVATIVE OPT-IN gate. Fork only when ALL hold (fork-as-retry is OFF)."""
    if not enabled:
        return False
    if not subtask.get("fork_eligible"):       # still the normal trigger
        try:
            from platform_core.orchestration import work_profile as _wp
            pol = _wp.policy(_wp.resolve(work_profile))
            if not pol.fork_strategy.get("prefer_forks"):
                return False
            blob = f"{subtask.get('title', '')} {subtask.get('description', '')}".lower()
            if not any(w in blob for w in ("design", "architect", "explore", "transform", "ambiguous")):
                return False
        except Exception:  # noqa: BLE001
            return False
    if not worktree_isolated:                  # forking REQUIRES isolation (else clobbers peers)
        return False
    if is_self_referential:                    # never fork a self-modification run
        return False
    if projected_cost > cost_ceiling:          # tight cost ceiling -> downgrade to single attempt
        return False
    if _isDocOnly(subtask):
        return False
    if _singleDeliverable(goal_elaborated):    # mechanical single-file edit: not fork-worthy
        return False
    return True


@dataclass
class BranchSeed:
    """One branch's diversity seed: effort (also picks the model) + an angle hint."""
    branch_id: str
    effort_level: str
    angle_hint: str
    model: str


@dataclass
class ForkPlan:
    branch_seeds: list = field(default_factory=list)
    n: int = 0


def _angleHintsFromExplore(goal_text: str, n: int, work_dir: str | None) -> list[str] | None:
    """Ranked explore approach summaries as angle hints; None on any failure (fail-open).

    Exploration root is ``work_dir`` when the caller supplies one (e.g. the
    worktree a fork actually runs in), else falls back to config.PROJECT_ROOT
    for callers that don't carry a work dir.
    """
    try:
        if not getattr(config, "EXPLORE_APPROACHES_ENABLED", False):
            return None
        from explore import generateApproaches, scoreApproaches
        from introspect import extractProject
        model = extractProject(work_dir or config.PROJECT_ROOT,
                               max_files=getattr(config, "PROJECT_INTROSPECTION_MAX_FILES", 4000))
        # Generate a wider pool (EXPLORE_APPROACHES_N) so ranking has real choice, seed the top n.
        pool = max(1, int(n), int(getattr(config, "EXPLORE_APPROACHES_N", 3)))
        candidates = generateApproaches(goal_text, model, n=pool)
        by_id = {c.approach_id: c for c in candidates}
        hints = [by_id[s.approach_id].summary
                 for s in scoreApproaches(candidates, model)
                 if s.approach_id in by_id and by_id[s.approach_id].summary][:max(1, int(n))]
        return hints or None
    except Exception:  # noqa: BLE001  -- fail-open: existing angle logic untouched
        return None


def forkPlan(subtask: dict, *, n: int, angles: tuple = DIVERSITY_ANGLES,
             work_profile=None, work_dir: str | None = None) -> ForkPlan:
    """Build N diversity seeds spanning effort x angle. Distinct by construction."""
    n = max(1, int(n))
    seeds: list = []
    profile_shaped = False
    try:
        from platform_core.orchestration import work_profile as _wp
        pol = _wp.policy(_wp.resolve(work_profile))
        if pol.fork_strategy.get("prefer_forks"):
            angles = DIVERSITY_ANGLES + (
                "Approach D: bold redesign -- maximize long-term upside while preserving acceptance.",
            )
            profile_shaped = True
        if pol.fork_strategy.get("conservative_forks"):
            angles = (
                "Approach A: conservative patch -- smallest safe change with regression awareness.",
                "Approach B: test-first patch -- prove the bug, then fix it.",
                "Approach C: safety review -- reduce risk before broadening the change.",
            )
            profile_shaped = True
        if pol.fork_strategy.get("rare_forks"):
            n = min(n, 2)
    except Exception:  # noqa: BLE001
        pass
    goal_text = f"{subtask.get('title', '')} {subtask.get('description', '')}".strip()
    explored = None if profile_shaped else _angleHintsFromExplore(goal_text, n, work_dir)
    if explored:
        angles = tuple(explored)
    for i in range(n):
        effort = EFFORT_CYCLE[i % len(EFFORT_CYCLE)]
        angle = angles[i % len(angles)]
        model = config.MODEL_BY_EFFORT.get(effort, config.PRIMARY_MODEL)
        seeds.append(BranchSeed(branch_id=f"b{i}", effort_level=effort,
                                angle_hint=angle, model=model))
    return ForkPlan(branch_seeds=seeds, n=len(seeds))
