"""Execute-mixin delegates – quality gate, evidence gate, adversary/SIE delegates, lazy caches.

Split out of execute_mixin.py to hold the size budget; OrchestratorExecuteMixin inherits
OrchestratorExecuteDelegatesMixin so the composed Orchestrator keeps the same public surface.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  OrchestratorExecuteDelegatesMixin  -- Thin delegates to self_ref_gate/evidence_gate/adversary_loop/dual_ledger_replan, plus l…
DEPENDS-ON: config, notifications.dashboard, platform_core.orchestration.adversary_loop, platform_core.orchestration.dual_ledger_replan, platform_core.orchestration.evidence_gate, platform_core.orchestration.self_ref_gate, platform_core.runtime.control, platform_core.runtime.cost_budget, platform_core.runtime.trajectory, state.task
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_evidence_gate.py tests/orchestration/test_execute_quality_gate.py tests/orchestration/test_trajectory.py
"""

from __future__ import annotations

from typing import TYPE_CHECKING

import config
from state.task import TaskState

if TYPE_CHECKING:
    from platform_core.runtime.control import ControlBus
    from notifications.dashboard import DiscordDashboard

LOG = config.getLogger("orchestrator")


class OrchestratorExecuteDelegatesMixin:
    """Thin delegates to self_ref_gate/evidence_gate/adversary_loop/dual_ledger_replan, plus lazy per-run caches."""

    def _selfRefQualityGate(self, work_dir: str, changed_files=None) -> "tuple[bool, str]":
        """Run cheap Windows repo gates after a self-ref subtask passes its own verify.
        ``changed_files`` scopes affected-test resolution to the subtask's own diff.
        Delegates to ``self_ref_gate`` (extracted for modularity)."""
        from platform_core.orchestration.self_ref_gate import run_self_ref_quality_gate

        return run_self_ref_quality_gate(work_dir, changed_files=changed_files)

    # ===================================================================
    # Adversary teeth -- bounded remediation LOOP
    # ===================================================================
    def _remediate(
        self,
        state: TaskState,
        subtask: dict,
        architect_doc: str,
        exec_cwd: str,
        concerns: list[str],
        cancel_check=None,
    ) -> dict:
        """Bounded adversary remediation LOOP on an already-passed subtask (delegates to
        adversary_loop to hold the size budget). Returns the last verify_result."""
        from platform_core.orchestration import adversary_loop

        return adversary_loop.remediate(self, state, subtask, architect_doc, exec_cwd, concerns, cancel_check)

    # ===================================================================
    # Phase 3 helpers: one attempt, attempt loop, enrichment sub-steps
    # ===================================================================
    def _runAttemptVerify(
        self,
        state: TaskState,
        subtask: dict,
        result: dict,
        exec_cwd: str,
        verify_spec: "dict | None",
        attempt_started: float,
        sid: str,
        combined: str,
        dashboard: "DiscordDashboard",
        resume_session: "str | None",
    ) -> tuple:
        """Run verify, repair if brittle, apply downgrades, record (delegates to evidence_gate).
        Returns (vresult, passed, resume_session, failure_feedback)."""
        from platform_core.orchestration import evidence_gate

        return evidence_gate.runAttemptVerify(
            self,
            state,
            subtask,
            result,
            exec_cwd,
            verify_spec,
            attempt_started,
            sid,
            combined,
            dashboard,
            resume_session,
        )

    # ===================================================================
    # Epic 2 (steal #3): execution-grounded evidence gate (thin delegates to evidence_gate)
    # ===================================================================
    def _gitDiffFacts(self, work_dir: str) -> dict:
        """Best-effort re-derivable git facts for the receipt (delegates to evidence_gate)."""
        from platform_core.orchestration import evidence_gate

        return evidence_gate.gitDiffFacts(work_dir)

    def _runEvidenceGate(
        self, state: TaskState, subtask: dict, result: dict, exec_cwd: str, vresult: dict, sid: str
    ) -> "tuple[dict, bool]":
        """Run the independent verifier + Evidence Receipt downgrade (delegates to evidence_gate)."""
        from platform_core.orchestration import evidence_gate

        return evidence_gate.runEvidenceGate(self, state, subtask, result, exec_cwd, vresult, sid)

    def _persistReceipt(self, state: TaskState, sid: str, receipt: dict) -> None:
        """Persist the Evidence Receipt as a per-subtask Obsidian note (delegates to evidence_gate)."""
        from platform_core.orchestration import evidence_gate

        evidence_gate.persistReceipt(self, state, sid, receipt)

    def _trajectoryRecorder(self, state: TaskState):
        """Lazily build ONE trajectory Recorder per run (cached on self; double-checked under
        _state_lock so concurrent pool workers can't race the same <run_id>.json). Off when disabled."""
        if not getattr(config, "TRAJECTORY_ENABLED", True):
            return None
        rec = getattr(self, "_trajectory", None)
        if rec is not None:
            return rec
        with self._state_lock:
            rec = getattr(self, "_trajectory", None)  # re-check inside the lock
            if rec is None:
                try:
                    from platform_core.runtime.trajectory import Recorder

                    rec = self._trajectory = Recorder(state.task_id)
                except Exception:  # noqa: BLE001
                    rec = None
        return rec

    def _costBudget(self, state: TaskState):
        """Lazily build ONE CostBudget per run (cached on self; double-checked under
        _state_lock so concurrent pool workers can't race and each construct their own
        CostBudget -- which would split the running cost total across separate instances)."""
        cb = getattr(self, "_cost_budget", None)
        if cb is not None:
            return cb
        with self._state_lock:
            cb = getattr(self, "_cost_budget", None)  # re-check inside the lock
            if cb is None:
                from platform_core.runtime.cost_budget import CostBudget

                cb = self._cost_budget = CostBudget(state.task_id)
        return cb

    def _runAdversaryReview(
        self,
        state: TaskState,
        subtask: dict,
        combined: str,
        final: str,
        exec_cwd: str,
        bus: "ControlBus",
        dashboard: "DiscordDashboard",
        heartbeat_ordinal: int,
        attempt: int,
        architect_doc: str,
    ) -> "tuple[str | None, bool]":
        """Trigger adversary review if warranted; run remediation if challenged (delegates to
        adversary_loop to hold the size budget). Returns (verdict, stub)."""
        from platform_core.orchestration import adversary_loop

        return adversary_loop.runReview(
            self,
            state,
            subtask,
            combined,
            final,
            exec_cwd,
            bus,
            dashboard,
            heartbeat_ordinal,
            attempt,
            architect_doc,
        )

    def _runSieAndReplan(
        self,
        state: TaskState,
        subtask: dict,
        spec: dict,
        combined: str,
        passed: bool,
        final: str,
        architect_doc: str,
        dashboard: "DiscordDashboard",
        adv_verdict: "str | None",
        adv_stub: bool,
        result: "dict | None" = None,
    ) -> None:
        """Capture SIE reflection, memoize passing spec, and trigger adaptive replan
        (delegates to dual_ledger_replan to hold the size budget)."""
        from platform_core.orchestration import dual_ledger_replan as _dlr

        _dlr.runSieAndReplan(
            self,
            state,
            subtask,
            spec,
            combined,
            passed,
            final,
            architect_doc,
            dashboard,
            adv_verdict,
            adv_stub,
            result=result,
        )

    def _progressLedgerReplan(
        self,
        state: TaskState,
        subtask: dict,
        combined: str,
        architect_doc: str,
        dashboard: "DiscordDashboard",
    ) -> None:
        """Dual-ledger replan driver: Progress Ledger + stall counter -> one root-cause replan at
        STALL_THRESHOLD (delegates to dual_ledger_replan). Best-effort."""
        from platform_core.orchestration import dual_ledger_replan as _dlr

        _dlr.progressLedgerReplan(self, state, subtask, combined, architect_doc, dashboard)
