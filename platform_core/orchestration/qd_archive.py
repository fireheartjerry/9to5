"""MAP-Elites quality-diversity archive: champion + capped Pareto frontier per cell.

Keeps a DIVERSE portfolio of high-quality inventions instead of one champion. Each verified
implementation is assigned to a product-first cell (capability_type, innovation_mechanism,
subsystem, novelty_bin, risk_bin); within a cell we keep the best-fitness champion PLUS a
capped set of non-dominated Pareto alternatives (so tradeoff solutions survive as stepping
stones). ``coverage`` (filled cells) and ``qd_score`` (sum of champion fitness) make "did we
get more DIVERSE wins" measurable. Hard gates: a failing-verify or factless elite can never
enter the archive. Pure + deterministic; optional best-effort persistence into the novelty
store's ``qd`` collection.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  novelty_bin(x: Any) -> str  -- Bin a 0..1 novelty score into low|medium|high (deterministic thirds).
  cell_for(obj: Any) -> QDCell  -- Derive a QD cell from a candidate/elite (dict or object).
  dominates(a: dict, b: dict) -> bool  -- True iff metrics ``a`` Pareto-dominates ``b`` (>= on all metrics, > on at least one).
  QDArchive  -- MAP-Elites archive: one champion + a capped non-dominated Pareto frontier per cell.
DEPENDS-ON: config, memory.novelty_index, memory.novelty_store, platform_core.orchestration.invention_types
SIDE-EFFECTS: persist_elite writes the novelty store 'qd' collection (best-effort)
RUN/TEST: python -m pytest tests/orchestration/test_qd_archive.py
"""
from __future__ import annotations

from typing import Any, Optional

import config
from platform_core.orchestration.invention_types import (
    PARETO_METRICS, QDCell, QDElite, clamp01, fitness_of, norm_risk,
)

LOG = config.getLogger("orchestrator.qd_archive")


def novelty_bin(x: Any) -> str:
    """Bin a 0..1 novelty score into low|medium|high (deterministic thirds)."""
    v = clamp01(x)
    return "low" if v < 0.34 else "medium" if v < 0.67 else "high"


def cell_for(obj: Any) -> QDCell:
    """Derive a QD cell from a candidate/elite (dict or object)."""
    get = obj.get if isinstance(obj, dict) else (lambda k, d=None: getattr(obj, k, d))
    subs = get("target_subsystems", None) or get("subsystem", None)
    subsystem = subs[0] if isinstance(subs, (list, tuple)) and subs else str(subs or "unknown")
    return QDCell(
        capability_type=str(get("capability_type", "") or "architecture_unlock"),
        innovation_mechanism=str(get("innovation_mechanism", "") or "prior_art_transfer"),
        subsystem=str(subsystem or "unknown"),
        novelty_bin=novelty_bin(get("measured_novelty", 0.0)),
        risk_bin=norm_risk(get("risk", "medium")))


def dominates(a: dict, b: dict) -> bool:
    """True iff metrics ``a`` Pareto-dominates ``b`` (>= on all metrics, > on at least one)."""
    a = a or {}
    b = b or {}
    ge_all = all(float(a.get(m, 0.0)) >= float(b.get(m, 0.0)) for m in PARETO_METRICS)
    gt_any = any(float(a.get(m, 0.0)) > float(b.get(m, 0.0)) for m in PARETO_METRICS)
    return ge_all and gt_any


class QDArchive:
    """MAP-Elites archive: one champion + a capped non-dominated Pareto frontier per cell."""

    def __init__(self, pareto_cap: Optional[int] = None) -> None:
        self.cells: dict[str, dict] = {}
        self.pareto_cap = int(pareto_cap if pareto_cap is not None
                              else getattr(config, "QD_PARETO_CAP", 4))

    def add(self, elite: QDElite) -> bool:
        """Insert an elite. HARD GATES: failing-verify or factless => rejected (returns False)."""
        m = elite.metrics or {}
        if (elite.unknown_metrics
                and getattr(config, "GALAXY_R3_POLICY_ENFORCEMENT_ENABLED", False)):
            return False                                   # unknown is not zero and cannot steer
        if float(m.get("verification_score", 0.0)) <= 0.0:
            return False                                   # a failing-verify elite can never win
        if not elite.evidence_refs:
            return False                                   # a factless claim can never win
        elite.fitness = fitness_of(m)
        key = elite.cell.key()
        cell = self.cells.setdefault(key, {"champion": None, "pareto": []})
        if cell["champion"] is None or elite.fitness > cell["champion"].fitness:
            cell["champion"] = elite
        self._update_pareto(cell, elite)
        return True

    def _update_pareto(self, cell: dict, elite: QDElite) -> None:
        m = elite.metrics or {}
        if any(dominates(e.metrics or {}, m) for e in cell["pareto"]):
            return                                          # dominated => not on the frontier
        cell["pareto"] = [e for e in cell["pareto"] if not dominates(m, e.metrics or {})]
        cell["pareto"].append(elite)
        if len(cell["pareto"]) > self.pareto_cap:
            cell["pareto"].sort(key=lambda e: e.fitness, reverse=True)
            cell["pareto"] = cell["pareto"][:self.pareto_cap]

    def champion(self, cell_key: str) -> Optional[QDElite]:
        c = self.cells.get(cell_key)
        return c["champion"] if c else None

    def pareto(self, cell_key: str) -> list[QDElite]:
        c = self.cells.get(cell_key)
        return list(c["pareto"]) if c else []

    def coverage(self) -> int:
        """Number of filled cells (diversity breadth). Deterministic."""
        return sum(1 for c in self.cells.values() if c["champion"] is not None)

    def qd_score(self) -> float:
        """Sum of champion fitness across filled cells (quality x diversity). Deterministic."""
        return round(sum(c["champion"].fitness for c in self.cells.values()
                         if c["champion"] is not None), 6)

    def champions(self) -> list[QDElite]:
        """All cell champions, highest fitness first (stable by cell key on ties)."""
        champs = [(k, c["champion"]) for k, c in self.cells.items() if c["champion"] is not None]
        champs.sort(key=lambda kc: (-kc[1].fitness, kc[0]))
        return [c for _, c in champs]

    def all_elites(self) -> list[QDElite]:
        """Every Pareto elite across all cells (the stepping-stone pool for recombination)."""
        return [e for c in self.cells.values() for e in c["pareto"]]

    def diverse_elites(self, k: int) -> list[QDElite]:
        """Up to k champions from DISTINCT cells (open-ended parent seeding). Deterministic."""
        return self.champions()[:max(0, int(k))]

    def persist_elite(self, elite: QDElite) -> None:
        """Best-effort: embed the elite into the novelty-store 'qd' collection for cross-run reuse."""
        if not getattr(config, "QD_ARCHIVE_ENABLED", False):
            return
        try:
            from memory import novelty_index, novelty_store
            text = f"{elite.cell.key()} {elite.candidate_id}"
            vec = novelty_index._embed(text, None)          # reuse the shared embedder
            if vec:
                novelty_store.get_store().add("qd", elite.id or elite.candidate_id, vec,
                                              {"cell": elite.cell.key(), "fitness": elite.fitness})
        except Exception as e:  # noqa: BLE001 -- persistence is optional
            LOG.debug("qd persist skipped (ignored): %s", e)
