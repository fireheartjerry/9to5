def _checkCodeDivergence(state) -> bool:
    """At each subtask boundary: has on-disk code drifted from the pinned epoch?  If so,
    record it on meta so the post-run gate can refuse to bless edited-but-never-executed
    modules.  Observe-only -- never blocks the edit."""
    ep_dict = (getattr(state, "meta", {}) or {}).get("epoch")
    if not ep_dict:
        return False
    diverged = epoch.diverged(epoch.Epoch.fromDict(ep_dict))
    if diverged and not state.meta.get("code_diverged"):
        state.meta["code_diverged"] = True
        state.save()
    return diverged


def _singleDeliverable(goal_elaborated: str) -> bool:
    """True when the goal targets at most one distinct file with no multi-deliverable phrasing.
    A goal that enumerates >=2 requirements (``(1).. (2).. (3)..``) is never single."""
    if len(verifier.extractRequirements(goal_elaborated)) >= 2:
        return False
    g = (goal_elaborated or "").lower()
    files = set(re.findall(
        r"([A-Za-z0-9_.-]+\.(?:py|md|txt|json|js|ts|tsx|jsx|html|css|csv|ya?ml|cfg|ini|sh|bat|"
        r"go|rs|java|c|cc|cpp|h|hpp|rb|php|swift|kt|sql|toml))\b", g))
    multi_phrase = any(w in g for w in ("multiple files", "several files", "multiple deliverables",
                                        "as well as", "separate "))
    return len(files) <= 1 and not multi_phrase


def _coversRequirement(req: str, hay: str) -> bool:
    """Cheap coverage check: the subtask text shares >=1 significant word with the requirement."""
    return any(w in hay for w in re.findall(r"[a-z0-9]{4,}", (req or "").lower()))


def _strengthenPlanVerifies(goal_elaborated: str, subtasks: list[dict]) -> list[dict]:
    """For an enumerated multi-deliverable goal with a single named target file, DECLARE that
    file as the diff-grounded target of any subtask covering >=2 requirements (R10): the
    receipt pipeline then FAILS the subtask unless git shows the target actually changed.
    Replaces the deleted token-scan content verify -- a goal word in a comment proves nothing.
    No-op for non-enumerated goals or when no single target file is named."""
    reqs = verifier.extractRequirements(goal_elaborated)
    if len(reqs) < 2:
        return subtasks
    target_rel = verifier.primaryTargetFile(goal_elaborated)
    if not target_rel:
        return subtasks
    target_abs = str((config.PROJECT_ROOT / target_rel).resolve())
    for st in subtasks:
        hay = f"{st.get('title', '')} {st.get('description', '')}".lower()
        covered = sum(1 for r in reqs if _coversRequirement(r, hay))
        if covered >= 2:
            v = dict(st.get("verify") or {})
            v.setdefault("targets", [target_abs])
            st["verify"] = v
            LOG.info("plan strengthen: subtask '%s' -> diff-grounded target %s "
                     "(%d requirements covered)", st.get("title"), target_abs, covered)
    return subtasks


def _repairVerify(subtask: dict, exec_cwd: str, t0: float = 0.0) -> "dict | None":
    """Synthesize a behavioral fallback verify from fresh artifacts this attempt produced.
    Only files the verify/description actually reference qualify (never arbitrary newest files).
    Returns None when no qualifying fresh artifact exists."""
    def _fresh(p: str) -> bool:
        try:
            return os.path.exists(p) and os.path.getmtime(p) >= t0 - 2.0
        except Exception:  # noqa: BLE001
            return False

    orig = subtask.get("verify") or {}
    orig_expect = orig.get("expect")
    keep_expect = orig_expect if (isinstance(orig_expect, str) and orig_expect.startswith(
        ("stdout_contains:", "stdout_regex:"))) else "exit_zero"
    text = (orig.get("cmd") or "") + "  " + (subtask.get("description") or "")
    for m in re.findall(r"([A-Za-z]:\\[^\s\"'`]+\.py|/[^\s\"'`]+\.py)", text):
        if _fresh(m):
            return {"cmd": f'python "{m}"', "expect": keep_expect}
    for cand in re.findall(r"([\w./\\-]+\.py)\b", text):
        if os.path.isabs(cand):
            continue
        p = os.path.normpath(os.path.join(exec_cwd, cand))
        if _fresh(p):
            return {"cmd": f'python "{p}"', "expect": keep_expect}
    for m in re.findall(r"([A-Za-z]:\\[^\s\"'`]+\.[A-Za-z0-9]{1,5}|/[^\s\"'`]+\.[A-Za-z0-9]{1,5})", text):
        if m.lower().endswith(".py") or not _fresh(m):
            continue
        return {"cmd": f"python -c \"import os,sys; sys.exit(0 if os.path.getsize(r'{m}')>0 else 1)\"",
                "expect": "exit_zero"}
    return None


def _asBlock(value) -> str:
    """Coerce a result/verify channel to a stripped string for a markdown code block.

    Executor results are best-effort dicts whose stdout/stderr can be non-strings
    (a malformed run — or the fuzz harness — yields ints/lists/None); calling
    ``.strip()`` on those raised AttributeError and crashed note enrichment."""
    if value is None:
        return ""
    return (value if isinstance(value, str) else str(value)).strip()


def _subtaskNote(state, subtask: dict, spec: dict, result: dict,
                 vresult: "dict | None") -> str:
    """Build the Obsidian markdown note for a completed subtask."""
    verify_block = ""
    if vresult:
        verify_block = (
            f"## Verification\n\n- **Passed:** {vresult.get('passed')}\n"
            f"- **Command:** `{vresult.get('cmd')}`  (expect: {vresult.get('expect')})\n"
            f"- **Return code:** {vresult.get('returncode')}\n\n"
            f"```\n{_asBlock(vresult.get('stdout'))}\n{_asBlock(vresult.get('stderr'))}\n```\n\n"
        )
    wf = spec.get("workflow_definition") if spec.get("use_workflow") else None
    spec_block = (
        f"## Invocation spec\n\n"
        f"- **Effort:** {spec.get('effort_level')}\n"
        f"- **Skills:** {spec.get('skills_to_invoke')}\n"
        f"- **Subagent:** {spec.get('subagent')}\n"
        f"- **Dynamic workflow:** {('yes — ' + str(wf.get('name'))) if wf else 'no'}\n"
        f"- **Pre hooks:** {spec.get('pre_tool_hooks')}  ·  **Post hooks:** {spec.get('post_tool_hooks')}\n\n"
        f"### CLAUDE.md inject\n\n```\n{(spec.get('claude_md_inject') or '')[:1500]}\n```\n\n"
        f"### Prompt\n\n```\n{spec.get('prompt')}\n```\n\n"
    )
    telem = ""
    if result.get("session_id") or result.get("cost_usd") is not None:
        telem = (f"- **Session:** `{result.get('session_id')}`  ·  **is_error:** {result.get('is_error')}"
                 f"  ·  **cost:** ${result.get('cost_usd')}  ·  **turns:** {result.get('num_turns')}\n")
    return (
        f"# {subtask['subtask_id']} -- {subtask['title']}\n\n"
        f"- **Status:** {subtask['status']}\n"
        f"- **Return code:** {result.get('returncode')}\n"
        f"{telem}\n"
        f"{verify_block}{spec_block}"
        f"## Executor (Claude Code CLI) output\n\n```\n{_asBlock(result.get('stdout'))}\n```\n\n"
        + (f"## stderr\n\n```\n{_asBlock(result.get('stderr'))}\n```\n" if result.get("stderr") else "")
    )


def _reviewNote(subtask: dict, reason: str, review: dict, output: str) -> str:
    """Build the Obsidian markdown note for an adversary review of a subtask."""
    concerns = review.get("concerns") or []
    concerns_md = "\n".join(f"- {c}" for c in concerns) if concerns else "_none_"
    return (
        f"# Adversary review -- {subtask['subtask_id']}\n\n"
        f"- **Trigger:** {reason}\n- **Verdict:** {review['verdict']}\n"
        f"- **Stub:** {review.get('stub', False)}\n\n"
        f"## Concerns\n{concerns_md}\n\n## Notes\n{review.get('notes', '')}\n\n"
        f"## Reviewed output (excerpt)\n\n```\n{(output or '')[:1500]}\n```\n"
    )


def _pendingCount(state) -> int:
    """Count subtasks still in the live queue (pending or in_progress)."""
    return sum(1 for s in state.subtasks if s["status"] in ("pending", "in_progress"))


def _readySet(state) -> list[dict]:
    """Return subtasks whose dependencies are all 'done' (ready to execute in parallel)."""
    out = []
    for s in state.subtasks:
        if s["status"] != "pending":
            continue
        deps = s.get("depends_on") or []
        if all((state.getSubtask(d) or {}).get("status") == "done" for d in deps):
            out.append(s)
    return out
