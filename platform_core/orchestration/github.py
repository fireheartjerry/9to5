"""Git and GitHub operations for the orchestrator (PR creation, repo helpers).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  createPullRequest(state, work_dir: str) -> dict  -- Create a PR for the completed run
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_github_pr_gate.py
"""
from __future__ import annotations

import os
import subprocess
import sys

import config

LOG = config.getLogger("orchestrator.github")


def createPullRequest(state, work_dir: str) -> dict:
    """Create a PR for the completed run.  Best-effort: any error degrades to a 'skipped'
    result so finalization always completes (never hangs or raises)."""
    env = os.environ.copy()
    env["GIT_TERMINAL_PROMPT"] = "0"   # git never blocks on a credential prompt

    def _runp(cmd: list[str]) -> subprocess.CompletedProcess:
        return subprocess.run(cmd, cwd=work_dir, capture_output=True, text=True,
                              stdin=subprocess.DEVNULL, env=env,
                              timeout=config.GIT_TIMEOUT_SECONDS)

    def git(*args: str) -> subprocess.CompletedProcess:
        return _runp(["git", *args])

    try:
        chk = git("rev-parse", "--is-inside-work-tree")
        if chk.returncode != 0 or "true" not in (chk.stdout or "").lower():
            LOG.info("PR skipped: %s is not a git repository", work_dir)
            return {"skipped": True, "reason": "not a git repository"}
        branch = state.meta.get("self_ref_branch") or f"9to5/{state.task_id[:8]}"
        git("checkout", "-B", branch)
        git("add", "-A", "--", ".", ":(exclude).sc-ctx", ":(exclude)**/__pycache__/**", ":(exclude)**/*.pyc")
        if not state.meta.get("is_self_referential"):
            tracked = git("ls-files", "--error-unmatch", "CLAUDE.md").returncode == 0
            if tracked:
                git("checkout", "HEAD", "--", "CLAUDE.md")
            else:
                git("rm", "--cached", "--ignore-unmatch", "CLAUDE.md")
        commit = git("commit", "-m", f"9TO5: {state.meta['goal_raw'][:60]}")
        if commit.returncode != 0 and "nothing to commit" in ((commit.stdout or "") + (commit.stderr or "")).lower():
            LOG.warning("PR skipped: no tracked changes to commit (work may have landed in .sc-ctx)")
            return {"skipped": True, "reason": "no tracked changes produced"}
        push = git("push", "-u", "origin", branch)
        if push.returncode != 0:
            return {"skipped": True, "reason": f"git push failed: {(push.stderr or '')[:200]}"}
        pr = _runp(["gh", "pr", "create", "--fill", "--head", branch])
        if pr.returncode != 0:
            return {"skipped": True, "reason": f"gh pr create failed: {(pr.stderr or '')[:200]}"}
        return {"ok": True, "url": (pr.stdout or "").strip()}
    except subprocess.TimeoutExpired as e:
        LOG.error("PR creation timed out (%ss) on %s -- finalizing without a PR",
                  config.GIT_TIMEOUT_SECONDS, e.cmd)
        return {"skipped": True, "reason": f"git/gh timed out after {config.GIT_TIMEOUT_SECONDS}s"}
    except Exception as e:  # noqa: BLE001
        LOG.warning("PR creation failed (%s) -- finalizing without a PR", e)
        return {"skipped": True, "reason": f"PR error: {e}"[:200]}


def _gitSnapshot(cwd: str) -> "str | None":
    """Capture the current (dirty) tree as a throwaway stash commit WITHOUT touching the tree;
    returns its SHA, or None if cwd isn't a git repo / nothing to snapshot."""
    try:
        r = subprocess.run(["git", "stash", "create"], cwd=cwd, capture_output=True,
                           text=True, timeout=30)
        return (r.stdout or "").strip() or None
    except Exception:  # noqa: BLE001
        return None


def _gitRestore(cwd: str, sha: "str | None") -> None:
    """Restore tracked files in cwd to a snapshot SHA from _gitSnapshot (revert edits since)."""
    if not sha:
        return
    try:
        subprocess.run(["git", "checkout", sha, "--", "."], cwd=cwd,
                       capture_output=True, text=True, timeout=30)
    except Exception as e:  # noqa: BLE001
        LOG.warning("remediation revert failed: %s", e)


def _gitDiffForReview(work_dir: "str | None") -> str:
    """Return a stat+patch diff for the pre-PR adversary review.  '' when no repo / no diff."""
    if not work_dir:
        return ""
    try:
        t = config.GIT_TIMEOUT_SECONDS
        stat = subprocess.run(["git", "diff", "HEAD", "--stat"], cwd=work_dir,
                              capture_output=True, text=True, timeout=t)
        patch = subprocess.run(["git", "diff", "HEAD"], cwd=work_dir,
                                capture_output=True, text=True, timeout=t)
        body = ((stat.stdout or "") + "\n\n" + (patch.stdout or "")).strip()
        return body[:config.ADVERSARY_PREPR_DIFF_MAX_CHARS]
    except Exception as e:  # noqa: BLE001
        LOG.warning("git diff for pre-PR review failed: %s", e)
        return ""


def _runIsDegraded(state) -> bool:
    """True when the run's self-mod gate reverted core changes, or fewer than half its subtasks
    passed.  A degraded run must never auto-ship a PR."""
    notes = state.data.get("notifications", []) if isinstance(state.data, dict) else []
    if any(isinstance(n, dict) and n.get("kind") == "selfmod_gate" and n.get("reverted")
           for n in notes):
        return True
    done, total = state.progress()
    return total > 0 and done * 2 < total


def _prePrSuiteGate(state, work_dir: str) -> "tuple[bool, str]":
    """Block self-improvement PRs unless the local Windows pre-PR gate is green."""
    if not state.meta.get("is_self_referential"):
        return True, ""
    commands = [
        [sys.executable, "tools\\repo_map.py"],
        [sys.executable, "tools\\repo_map.py", "--check"],
        [sys.executable, "validate_workflows.py"],
        [sys.executable, "-m", "pytest", "-m", "not slow", "-n", "auto", "--dist", "loadscope", "-q"],
    ]
    tail = ""
    for cmd in commands:
        try:
            proc = subprocess.run(
                cmd,
                cwd=work_dir,
                capture_output=True,
                text=True,
                stdin=subprocess.DEVNULL,
                timeout=config.GIT_TIMEOUT_SECONDS,
            )
        except subprocess.TimeoutExpired as e:
            detail = f"{' '.join(cmd)} timed out after {config.GIT_TIMEOUT_SECONDS}s"
            LOG.warning("pre-PR gate timed out: %s", e.cmd)
            return False, detail[-400:]
        except Exception as e:  # noqa: BLE001
            detail = f"{' '.join(cmd)} errored: {e}"
            LOG.warning("pre-PR gate errored: %s", e)
            return False, detail[-400:]
        tail = ((proc.stdout or "") + "\n" + (proc.stderr or "")).strip()
        if proc.returncode != 0:
            detail = f"{' '.join(cmd)} failed:\n{tail}"
            LOG.warning("pre-PR gate failed: %s", " ".join(cmd))
            return False, detail[-400:]
    return True, tail[-400:]


def _cleanupScaffolding(work_dir: str) -> None:
    """Remove 9to5's per-subtask scratch dir (.sc-ctx) from the project tree at the end of a
    run — never leave scaffolding behind.  Best-effort; never raises."""
    try:
        import shutil
        ctx = os.path.join(str(work_dir), ".sc-ctx")
        if os.path.isdir(ctx):
            shutil.rmtree(ctx, ignore_errors=True)
    except Exception:  # noqa: BLE001
        pass
