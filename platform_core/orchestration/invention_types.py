from __future__ import annotations

from dataclasses import asdict, dataclass, field, fields
from typing import Any

# --- controlled vocabularies (single source of truth for the whole pipeline) ---
FINDING_KINDS: tuple[str, ...] = ("feature", "improvement", "architecture", "workflow", "report")
RISK_LEVELS: tuple[str, ...] = ("low", "medium", "high")
BLAST_LEVELS: tuple[str, ...] = ("small", "medium", "large")
CAPABILITY_TYPES: tuple[str, ...] = (
    "new_user_facing_feature", "workflow_acceleration", "agent_capability_upgrade",
    "observability_or_explainability", "reliability_or_recovery", "developer_experience",
    "interface_or_reporting", "architecture_unlock",
)
INNOVATION_MECHANISMS: tuple[str, ...] = (
    "recombination", "prior_art_transfer", "automation_of_manual_step", "new_search_space",
    "new_feedback_loop", "new_memory_or_archive", "new_interface_surface",
)
EMITTERS: tuple[str, ...] = ("ollama", "claude", "recombination", "random")

# Fitness (scalar) composite weights -- sum to 1.0; verification dominates (spec B1).
FITNESS_WEIGHTS: dict[str, float] = {
    "verification_score": 0.35, "impact_score": 0.20, "maintainability_score": 0.15,
    "adoption_score": 0.15, "cost_efficiency_score": 0.10, "reversibility_score": 0.05,
}
# Pareto (vector) metrics -- dominance is computed over ALL of these (spec B2/D4).
PARETO_METRICS: tuple[str, ...] = (
    "verification_score", "impact_score", "measured_novelty", "maintainability_score",
    "cost_efficiency_score", "risk_inverse", "reversibility_score",
)


def clamp01(x: Any) -> float:
    """Coerce anything to a [0,1] float; unparseable -> 0.0 (never raises)."""
    try:
        v = float(x)
    except (TypeError, ValueError):
        return 0.0
    return 0.0 if v < 0.0 else 1.0 if v > 1.0 else v


def norm_risk(r: Any) -> str:
    """Normalize an arbitrary risk value to one of RISK_LEVELS (default 'medium')."""
    s = str(r or "").strip().lower()
    if s in ("med", "mid"):
        return "medium"
    return s if s in RISK_LEVELS else "medium"


def norm_blast(b: Any) -> str:
    """Normalize a blast-radius value to one of BLAST_LEVELS (default 'medium')."""
    s = str(b or "").strip().lower()
    return s if s in BLAST_LEVELS else "medium"


def fitness_of(metrics: dict[str, Any] | None) -> float:
    """Weighted QD fitness composite in [0,1] from a metrics dict (missing keys -> 0)."""
    m = metrics or {}
    return round(sum(w * clamp01(m.get(k, 0.0)) for k, w in FITNESS_WEIGHTS.items()), 6)


def _coerce(cls: type, d: dict[str, Any] | None) -> dict[str, Any]:
    """Filter a raw dict to ``cls``'s field names (drop unknown keys, fail-open)."""
    names = {f.name for f in fields(cls)}
    return {k: v for k, v in (d or {}).items() if k in names}


@dataclass
class FindingCandidate:
    """One candidate invention emitted by the finders (Track A)."""

    id: str = ""
    kind: str = "feature"          # feature|improvement|architecture|workflow|report
    title: str = ""
    summary: str = ""
    design_sketch: str = ""
    target_subsystems: list[str] = field(default_factory=list)
    prior_art_refs: list[str] = field(default_factory=list)
    measured_novelty: float = 0.0
    history_similarity_max: float = 0.0
    specificity: float = 0.0
    impact: float = 0.0
    feasibility: float = 0.0
    risk: str = "medium"
    confidence: float = 0.0
    provenance: dict[str, Any] = field(default_factory=dict)  # {lens, corpus_cards[], run_id}

    def __post_init__(self) -> None:
        self.kind = self.kind if self.kind in FINDING_KINDS else "feature"
        self.risk = norm_risk(self.risk)
        for k in ("measured_novelty", "history_similarity_max", "specificity",
                  "impact", "feasibility", "confidence"):
            setattr(self, k, clamp01(getattr(self, k)))

    def has_sketch(self) -> bool:
        """A routable invention needs a concrete sketch + a named target subsystem."""
        return bool(self.design_sketch.strip()) and bool(self.target_subsystems)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict[str, Any] | None) -> "FindingCandidate":
        return cls(**_coerce(cls, d))


@dataclass(frozen=True)
class QDCell:
    """Product-first quality-diversity cell coordinate (hashable + deterministic key)."""

    capability_type: str = "architecture_unlock"
    innovation_mechanism: str = "prior_art_transfer"
    subsystem: str = "unknown"
    novelty_bin: str = "low"
    risk_bin: str = "low"

    def key(self) -> str:
        """Stable string key for archive lookup / coverage counting."""
        return "|".join((self.capability_type, self.innovation_mechanism,
                          self.subsystem, self.novelty_bin, self.risk_bin))

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict[str, Any] | None) -> "QDCell":
        return cls(**_coerce(cls, d))


@dataclass
class QDElite:
    """One archived elite implementation occupying a QD cell (Track B / D4)."""

    id: str = ""
    candidate_id: str = ""
    cell: QDCell = field(default_factory=QDCell)
    fitness: float = 0.0
    metrics: dict[str, Any] = field(default_factory=dict)
    lineage: dict[str, Any] = field(default_factory=dict)  # {parents[], emitter, generation, mutation_prompt_hash}
    evidence_refs: list[str] = field(default_factory=list)
    created_at: str = ""

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["cell"] = self.cell.to_dict()
        return d

    @classmethod
    def from_dict(cls, d: dict[str, Any] | None) -> "QDElite":
        raw = _coerce(cls, d)
        if isinstance(raw.get("cell"), dict):
            raw["cell"] = QDCell.from_dict(raw["cell"])
        return cls(**raw)


