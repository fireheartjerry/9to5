"""Heterogeneous QD emitters: cheap Ollama, deep Claude, recombination, random.

Emitters produce candidate variants (branch seeds) for the generational fork loop, each with
a target cell, full lineage, and a mutation-prompt hash so reward-hacking is auditable. They
have DIFFERENT inductive biases (not redundant models): Ollama = cheap wide divergence, Claude
= deep implementation/verification-repair, recombination = graft two compatible elites (paired
by maximum-weight matching over a compatibility score), random = fill an underexplored cell.
Every emitter is fail-open: a brain error still yields a template candidate.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ollama_emitter(cell_key, parents, *, brain, generation) -> dict  -- Cheap divergent variant.
  claude_emitter(cell_key, parents, *, brain, generation) -> dict  -- Deep implement/verify variant.
  random_emitter(empty_cells, *, generation) -> dict | None  -- Fill an underexplored cell.
  compatibility(a, b) -> float  -- Recombination pairing score for two parents.
  match_parents(parents) -> list[tuple]  -- Max-weight (greedy) disjoint parent pairing.
  recombination_emitter(parents, *, generation) -> dict | None  -- Graft the best compatible pair.
DEPENDS-ON: config
SIDE-EFFECTS: emitters may call the injected brain (best-effort)
RUN/TEST: python -m pytest tests/orchestration/test_qd_emitters.py
"""
from __future__ import annotations

import hashlib
from typing import Any, Callable, Iterable, Optional

import config

LOG = config.getLogger("orchestrator.qd_emitters")


def _get(o: Any, k: str, d: Any = None) -> Any:
    return o.get(k, d) if isinstance(o, dict) else getattr(o, k, d)


def _files(p: Any) -> set:
    subs = _get(p, "target_subsystems", None) or _get(p, "affected_files", None) or []
    return {str(s) for s in subs}


def _pid(p: Any) -> str:
    return str(_get(p, "candidate_id", None) or _get(p, "id", None) or _get(p, "title", None) or id(p))


def _mk(cell_key: str, emitter: str, parents: Iterable[str], angle: str, generation: int,
        risk: str = "medium", verify: str = "run the affected tests + factsGate") -> dict:
    h = hashlib.sha1(f"{emitter}|{cell_key}|{angle}".encode("utf-8", "ignore")).hexdigest()[:16]
    return {"candidate_id": f"{emitter}-{h}", "target_cell": cell_key,
            "lineage": {"parents": list(parents), "emitter": emitter,
                        "generation": int(generation), "mutation_prompt_hash": h},
            "behavior_delta": angle, "risk": risk, "verify_plan": verify, "angle_hint": angle}


def _brain_angle(brain: Optional[Callable], prompt: str) -> Optional[str]:
    if brain is None:
        return None
    try:
        out = brain(prompt)
        text = out if isinstance(out, str) else str(_get(out, "message", {}) or {}).strip()
        return (text or "").strip()[:400] or None
    except Exception as e:  # noqa: BLE001 -- fail-open to the template angle
        LOG.debug("emitter brain call failed (ignored): %s", e)
        return None


def ollama_emitter(cell_key: str, parents: Iterable[str] = (), *,
                   brain: Optional[Callable] = None, generation: int = 0) -> dict:
    """Cheap, wide, divergent variant for a cell (Ollama's inductive bias)."""
    angle = _brain_angle(brain, f"Propose a bold divergent angle for {cell_key}") \
        or f"divergent angle for {cell_key}"
    return _mk(cell_key, "ollama", parents, angle, generation, risk="medium")


def claude_emitter(cell_key: str, parents: Iterable[str] = (), *,
                   brain: Optional[Callable] = None, generation: int = 0) -> dict:
    """Deep implementation + verification-repair variant (Claude's inductive bias)."""
    angle = _brain_angle(brain, f"Deeply implement and self-verify a solution for {cell_key}") \
        or f"deep implementation + verification for {cell_key}"
    return _mk(cell_key, "claude", parents, angle, generation, risk="medium")


def random_emitter(empty_cells: Iterable[str], *, generation: int = 0) -> Optional[dict]:
    """Emit an exploratory candidate targeting the first underexplored cell (deterministic)."""
    cells = sorted(str(c) for c in empty_cells)
    if not cells:
        return None
    return _mk(cells[0], "random", (), f"explore untested cell {cells[0]}", generation, risk="medium")


def compatibility(a: Any, b: Any) -> float:
    """Recombination pairing score: complementary + disjoint-files + novelty - overlap conflict."""
    fa, fb = _files(a), _files(b)
    disjoint_bonus = 1.0 if fa.isdisjoint(fb) else 0.0
    overlap_pen = 0.5 * len(fa & fb)
    complement = 1.0 if str(_get(a, "target_cell", _get(a, "cell", "a"))) != \
        str(_get(b, "target_cell", _get(b, "cell", "b"))) else 0.0
    novelty = 0.5 * (float(_get(a, "measured_novelty", 0.0) or 0.0)
                     + float(_get(b, "measured_novelty", 0.0) or 0.0))
    return round(complement + disjoint_bonus + novelty - overlap_pen, 6)


def match_parents(parents: list) -> list[tuple]:
    """Greedy maximum-weight matching over parent pairs (disjoint, highest compatibility first)."""
    pairs = []
    for i in range(len(parents)):
        for j in range(i + 1, len(parents)):
            pairs.append((compatibility(parents[i], parents[j]), i, j))
    pairs.sort(key=lambda t: (-t[0], t[1], t[2]))
    used: set[int] = set()
    out: list[tuple] = []
    for score, i, j in pairs:
        if score <= 0 or i in used or j in used:
            continue
        used.update((i, j))
        out.append((parents[i], parents[j], score))
    return out


def recombination_emitter(parents: list, *, generation: int = 0) -> Optional[dict]:
    """Graft the single best compatible parent pair into one candidate (None if < 2 parents)."""
    if not parents or len(parents) < 2:
        return None
    matches = match_parents(list(parents))
    if not matches:
        return None
    a, b, score = matches[0]
    cell_key = str(_get(a, "target_cell", _get(a, "cell", "unknown")))
    angle = f"graft {_pid(a)} + {_pid(b)} (compatibility {score:.2f})"
    cand = _mk(cell_key, "recombination", [_pid(a), _pid(b)], angle, generation, risk="medium")
    return cand
