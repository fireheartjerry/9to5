    def _surfaceSubtaskPass(self, state: TaskState, sid: str, attempt: int) -> None:
        """First-verify arc beat (once) + redemption moment after 2+ prior failures. Best-effort."""
        try:
            done_count = sum(1 for s in state.subtasks if s["status"] == "done")
            if done_count == 1:
                self._arcBeat(state, "Chapter 3 — First subtask closed clean.")
            if attempt >= 3:
                self._emitMoment(sid, "⚡ MOMENT — Redemption. It clawed back from "
                                 "two dead ends and closed clean.")
        except Exception:  # noqa: BLE001
            pass

    def _postSubtaskEnrich(self, state: TaskState, subtask: dict, spec: dict, result: dict,
                           vresult: "dict | None", combined: str, passed: bool, final: str,
                           exec_cwd: str, architect_doc: str, bus: "ControlBus",
                           dashboard: "DiscordDashboard", attempt: int) -> None:
        """Persist Obsidian note, run adversary review, capture SIE learning, and replan.

        Also posts a feedback embed (Subsystem C) to invite human approval/rejection/skip/retry.

        Best-effort: AbortRun re-raises; all other exceptions are swallowed so the committed
        subtask status is never rolled back by enrichment failures.
        """
        sid = subtask["subtask_id"]
        try:
            # POST FEEDBACK EMBED (Subsystem C): invite human feedback on the completed subtask.
            # Post for both done and failed; the FeedbackView will handle control actions.
            goal = subtask.get("title", f"subtask {sid}")
            discord.sendEmbed(discord.feedbackEmbed(sid, goal, final),
                             components=discord.feedbackComponents())
            with self._state_lock:
                note = self._subtaskNote(state, subtask, spec, result, vresult)
                written = self.obs.writeNote(state.subtaskNoteRel(sid), note)
                state.updateSubtask(sid, output_ref=written.get("rel_path"))
            # Snapshot under the lock: in parallel mode a peer worker may be appending via _applyReplan,
            # and iterating the live list unlocked risks 'list changed size during iteration'.
            with self._state_lock:
                heartbeat_ordinal = sum(
                    1 for s in state.subtasks if s["status"] in ("done", "failed", "removed"))
            adv_verdict, adv_stub = self._runAdversaryReview(
                state, subtask, combined, final, exec_cwd, bus, dashboard,
                heartbeat_ordinal, attempt, architect_doc)
            # SIE subsystem I: learning summary + memoize passing spec + adaptive replan.
            self._runSieAndReplan(state, subtask, spec, combined, passed, final,
                                  architect_doc, dashboard, adv_verdict, adv_stub)
            with self._state_lock:
                self.writeIndex(state)
        except AbortRun:
            raise
        except Exception as e:  # noqa: BLE001 -- enrichment is best-effort; committed status stands
            LOG.warning("post-completion enrichment for %s failed (status %s preserved): %s",
                        sid, final, e, exc_info=True)

    # ===================================================================
    # Phase 3 -- execution (per-subtask unit)
    # ===================================================================
    def _executeSubtask(self, state: TaskState, subtask: dict, architect_doc: str, work_dir: str,
                        bus: "ControlBus", dashboard: "DiscordDashboard", position: int,
                        exec_cwd: "str | None" = None) -> str:
        sid = subtask["subtask_id"]
        verify_spec = subtask.get("verify")
        exec_cwd = exec_cwd or self._execCwd(state, sid, work_dir)
        dashboard.update(state, "executing", f"-> {sid} {subtask['title']}")
        # Boundary divergence check (#12): observe-only, never blocks. Under _state_lock: it mutates
        # state.meta + saves, and EVERY other meta mutation in this parallel execution path is guarded
        # by _state_lock -- an unguarded save here races a peer worker's save (lost/torn meta update).
        with self._state_lock:
            try:
                from platform_core.orchestration.subtask import _checkCodeDivergence
                _checkCodeDivergence(state)
            except Exception:  # noqa: BLE001
                pass
        spec, result, vresult, combined, passed, attempt = self._runAttemptLoop(
            state, subtask, architect_doc, exec_cwd, bus, dashboard, sid, verify_spec)
        if spec is None:   # subtask removed mid-attempt-loop
            return "removed"
        if (state.getSubtask(sid) or {}).get("status") == "removed":
            return "removed"
        # COMMIT the verified outcome FIRST -- it is the source of truth. Everything below
        # (notes, adversary, replan, index) is best-effort enrichment that must never be able to
        # change a verified result.
        final = "done" if passed else "failed"
        with self._state_lock:
            state.updateSubtask(sid, status=final, completed_at=nowIso())
            if not passed:
                state.addNotification("subtask_failed",
                                      f"{sid} failed verification after {attempt} attempts")
        if passed:
            self._surfaceSubtaskPass(state, sid, attempt)
        if not passed:
            discord.sendEmbed(discord.subtaskFailedEmbed(sid, subtask["title"], vresult, attempt))
        dashboard.update(state, "executing", f"{sid} -> {final}")
        cast.speak("verifier" if not passed else "executor",
                   (f"❌ `{sid}` failed verification after {attempt} attempt(s)." if not passed
                    else f"⚙️ `{sid}` {subtask['title']} — done ✅"))
        self._postSubtaskEnrich(state, subtask, spec, result, vresult, combined,
                                passed, final, exec_cwd, architect_doc, bus, dashboard, attempt)
        return final
