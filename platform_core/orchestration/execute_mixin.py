    def _selfRefQualityGate(self, work_dir: str) -> "tuple[bool, str]":
        """Run cheap Windows repo gates after a self-ref subtask passes its own verify.
        Delegates to ``self_ref_gate`` (extracted for modularity)."""
        from platform_core.orchestration.self_ref_gate import run_self_ref_quality_gate
        return run_self_ref_quality_gate(work_dir)

    # ===================================================================
    # Adversary teeth -- bounded remediation LOOP
    # ===================================================================
    def _remediate(self, state: TaskState, subtask: dict, architect_doc: str, exec_cwd: str,
                   concerns: list[str], cancel_check=None) -> dict:
        """Bounded remediation LOOP (up to ADVERSARY_REMEDIATION_MAX_ATTEMPTS) on a subtask that
        ALREADY passed verification: feed the reviewer's concerns back to the executor, re-verify,
        then re-review with the second brain; stop when it approves (or attempts run out). Each
        attempt is snapshot-guarded -- an edit that breaks the artifact is reverted and the prior
        pass kept, so remediation can only keep or improve. Returns the last verify_result."""
        sid = subtask["subtask_id"]
        goal = self._goalText(state)
        vres: dict = {}
        attempts = max(1, config.ADVERSARY_REMEDIATION_MAX_ATTEMPTS)
        # The REAL git edit tree to snapshot/restore. For a self-referential run exec_cwd is the
        # gitignored .sc-ctx scratch, but the executor edits the project at work_dir via --add-dir --
        # so snapshotting/restoring exec_cwd was a NO-OP and a broken remediation was never reverted.
        # work_dir IS the real tree for both self-ref (== PROJECT_ROOT) and non-self-ref runs.
        repo_tree = getattr(self, "_work_dir", None) or exec_cwd
        for i in range(1, attempts + 1):
            feedback = ("The work PASSED its acceptance check, but an adversarial reviewer raised "
                        "concerns. Address these WITHOUT breaking the passing verification:\n- "
                        + "\n- ".join(concerns))
            snap = self._gitSnapshot(repo_tree)
            spec = self.authorInvocationSpec(state, subtask, architect_doc, feedback)
            result = self._run_claude(spec, work_dir=exec_cwd, task_state=state, subtask=subtask,
                                      cancel_check=cancel_check)
            vres = verifier.runVerification(subtask.get("verify"), exec_cwd, result)
            with self._state_lock:
                if vres.get("passed"):
                    state.recordVerify(sid, vres)   # adopt the still-passing post-remediation evidence
                else:
                    self._gitRestore(repo_tree, snap)   # revert broken edits so disk == kept pass
                state.addNotification(
                    "adversary_remediation",
                    f"{sid}: remediation {i}/{attempts} "
                    f"{'verified' if vres.get('passed') else 'did not verify (reverted, prior pass kept)'}")
            LOG.info("Adversary remediation %d/%d for %s -> %s", i, attempts, sid,
                     "verified" if vres.get("passed") else "reverted (kept prior pass)")
            if not vres.get("passed"):
                break   # a broken attempt was reverted; another try would re-break -- stop
            # Re-review the remediated output: if the second brain is now satisfied, we're done.
            combined = ((result or {}).get("stdout", "") + "\n" + (result or {}).get("stderr", "")) \
                if isinstance(result, dict) else ""
            rv = self._review(subtask["title"], f"remediation re-review {i}/{attempts}", combined,
                              ollama_chat=self._ollamaChat, goal=goal)
            if not second_brain.is_blocking(rv):
                break
            concerns = (rv.get("must_fix") or rv.get("concerns") or concerns)[:10]
        return vres

    # ===================================================================
    # Phase 3 helpers: one attempt, attempt loop, enrichment sub-steps
    # ===================================================================
    def _runAttemptVerify(self, state: TaskState, subtask: dict, result: dict,
                          exec_cwd: str, verify_spec: "dict | None", attempt_started: float,
                          sid: str, combined: str, dashboard: "DiscordDashboard",
                          resume_session: "str | None") -> tuple:
        """Run verify, repair if brittle, record. Returns (vresult, passed, resume_session, failure_feedback)."""
        # FX-1: synthesize a behavioral verify when none was authored.
        effective_verify = verify_spec
        if not (verify_spec or {}).get("cmd"):
            synth = self._repairVerify(subtask, exec_cwd, attempt_started)
            if synth:
                effective_verify = synth
                LOG.info("%s: no verify authored -> synthesized behavioral check %s", sid, synth["cmd"])
        vresult = verifier.runVerification(effective_verify, exec_cwd, result)
        passed = bool(vresult["passed"])
        if not (effective_verify or {}).get("cmd"):
            vresult["unverified"] = True   # exit-zero fallback only; no behavioral assertion ran
        # VERIFY REPAIR: rescue brittle single-fact verifies; strict compound verifies are never rescued.
        if not passed and not verifier.isStrictVerify(verify_spec):
            repaired = self._repairVerify(subtask, exec_cwd, attempt_started)
            same = bool(repaired) and (repaired.get("cmd"), repaired.get("expect")) == \
                ((verify_spec or {}).get("cmd"), (verify_spec or {}).get("expect"))
            if repaired and not same:
                rv = verifier.runVerification(repaired, exec_cwd, result)
                if rv.get("passed"):
                    LOG.info("%s: brittle verify repaired -> PASS via %s", sid, repaired["cmd"])
                    vresult, passed = rv, True
        if passed and state.meta.get("is_self_referential"):
            gate_ok, gate_detail = self._selfRefQualityGate(str(config.PROJECT_ROOT))
            if not gate_ok:
                passed = False
                vresult = dict(vresult)
                vresult.update({
                    "passed": False,
                    "returncode": 1,
                    "stderr": gate_detail,
                    "quality_gate": "self_ref",
                })
                LOG.warning("%s: self-ref quality gate failed after verify pass", sid)
        with self._state_lock:
            state.recordVerify(sid, vresult)
        dashboard.update(state, "verifying",
                         f"{sid} verify {'PASS' if passed else 'FAIL'} ({vresult.get('cmd') or 'exit'})")
        failure_feedback: "str | None" = None
        if not passed:
            failure_feedback = (
                f"cmd: {vresult.get('cmd')}\nexpect: {vresult.get('expect')}\n"
                f"rc: {vresult.get('returncode')}\nstdout:\n{vresult.get('stdout')}\n"
                f"stderr:\n{vresult.get('stderr')}"
            )
            # If the executor asked a human, the Ollama brain answers so the next attempt is autonomous.
            answer = self._resolveClarifications(state, subtask, combined, dashboard)
            if answer:
                failure_feedback += (
                    "\n\n[ORCHESTRATOR ANSWERS YOUR QUESTIONS -- proceed now, do NOT ask again]\n"
                    + answer
                )
                resume_session = None   # approach is changing -> start the next attempt fresh
        return vresult, passed, resume_session, failure_feedback

    def _trajectoryRecorder(self, state: TaskState):
        """Lazily build ONE trajectory Recorder per run (cached on self). Off when disabled."""
        if not getattr(config, "TRAJECTORY_ENABLED", True):
            return None
        rec = getattr(self, "_trajectory", None)
        if rec is None:
            try:
                from platform_core.runtime.trajectory import Recorder
                rec = self._trajectory = Recorder(state.task_id)
            except Exception:  # noqa: BLE001
                rec = None
        return rec

    def _costBudget(self, state: TaskState):
        """Lazily build ONE CostBudget per run (cached on self)."""
        cb = getattr(self, "_cost_budget", None)
        if cb is None:
            from platform_core.runtime.cost_budget import CostBudget
            cb = self._cost_budget = CostBudget(state.task_id)
        return cb

    def _runOneAttempt(self, state: TaskState, subtask: dict, architect_doc: str,
                       exec_cwd: str, bus: "ControlBus", dashboard: "DiscordDashboard",
                       sid: str, verify_spec: "dict | None", failure_feedback: "str | None",
                       resume_session: "str | None", attempt: int) -> tuple:
        """Plan spec, run executor, combine output, verify. Returns all loop-locals."""
        spec = self.authorInvocationSpec(state, subtask, architect_doc, failure_feedback)
        with self._state_lock:
            sess = dict(subtask.get("session") or {})
            # FX-20: record the model the executor will ACTUALLY route to by effort (low->haiku,
            # default/high->sonnet, xhigh/ultracode->opus) -- not a hardcoded opus.
            routed_model = config.MODEL_BY_EFFORT.get(
                (spec.get("effort_level") or "default").lower(), config.PRIMARY_MODEL)
            sess.update({"effort": spec.get("effort_level"), "model": routed_model,
                         "skills": spec.get("skills_to_invoke"), "subagent": spec.get("subagent"),
                         "surfaces": surfaces.surfaces_used(spec),   # SIE surface learning
                         "use_workflow": bool(spec.get("use_workflow")), "attempts": attempt})
            state.updateSubtask(sid, session=sess)
        LOG.info("Subtask %s attempt %d/%d effort=%s", sid, attempt, config.MAX_SUBTASK_ATTEMPTS,
                 spec.get("effort_level"))
        dashboard.update(state, "executing", f"{sid} attempt {attempt} · effort {spec.get('effort_level')}",
                         effort=spec.get("effort_level"))
        if attempt >= 2:
            self._narrate(f"`{sid}` attempt {attempt}. Still working on it.")
        attempt_started = time.time()
        hands = self._selectExecutor(spec)   # route to the right surface (terminal | browser)
        # Live surface feed: tap the Claude subprocess stdout in real time (terminal path only;
        # the browser hands layer doesn't take a feed). Best-effort -- never block a run.
        feed = None
        recorder = None
        if hands is self._run_claude:
            try:
                from notifications.event_bus import get_bus
                from notifications.subprocess_feed import SubprocessFeed
                from platform_core.orchestration.step_sink import makeSink
                # Plan signature gates resume; recorded on every journal row (Epic 1b consumer).
                try:
                    from platform_core.orchestration.step_resume import planSignature
                    plan_sig = planSignature(state)
                except Exception:  # noqa: BLE001 -- step_resume lands in Epic 1b; until then plan_sig=""
                    plan_sig = ""
                recorder = self._trajectoryRecorder(state)
                parent_span = None
                if recorder is not None:
                    parent_span = recorder.openSpan(
                        "executor", None, {"sid": sid, "attempt": attempt})
                    # eliza spawn-link: hand the parent step id to the subprocess so child
                    # tool spans stitch into this subtask span.
                    import os as _os
                    _os.environ["NINE_TO_FIVE_PARENT_TRAJECTORY_STEP_ID"] = str(parent_span)
                last = {"sid": resume_session}

                def _session_getter():
                    s = (state.getSubtask(sid) or {}).get("session") or {}
                    return s.get("resume_session_id") or last.get("sid")

                sink = makeSink(state.task_id, sid, attempt, plan_sig, _session_getter,
                                recorder=recorder, parent_span_id=parent_span)
                feed = SubprocessFeed(get_bus(), sid, time.monotonic(), on_step=sink)
                self._cur_exec_span = parent_span   # closed after the attempt (cost/usage)
            except Exception:  # noqa: BLE001 -- live feed + journal are best-effort
                feed, recorder = None, None
        # cancel_check lets a long in-hands wait break early on abort, deadline, or an operator
        # kill-subprocess signal (Spec B: terminate THIS attempt, not the whole run) (CB-9).
        hands_kw = dict(work_dir=exec_cwd, task_state=state, subtask=subtask,
                        resume_session=resume_session,
                        cancel_check=lambda: bus.isAbort() or bus.isKillSubprocess()
                        or self._deadlinePassed(state))
        if feed is not None:
            hands_kw["feed"] = feed
        result = None
        try:
            result = hands(spec, **hands_kw)
        finally:
            if feed is not None:
                feed.stop()
            span = getattr(self, "_cur_exec_span", None)
            if recorder is not None and span is not None:
                _res = result if isinstance(result, dict) else {}
                recorder.closeSpan(span, usage=_res.get("usage"), cost_usd=_res.get("cost_usd"))
                self._cur_exec_span = None
                if getattr(config, "COST_BUDGET_ENABLED", False):
                    try:
                        self._costBudget(state).add(_res.get("cost_usd"))
                    except Exception:  # noqa: BLE001
                        pass
        if bus.isKillSubprocess():
            bus.clearKillSubprocess()
            with self._state_lock:
                state.addNotification("kill_subprocess", f"{sid}: operator killed the attempt")
        if not isinstance(result, dict):   # a hands layer that returns junk must fail cleanly
            result = {"ok": False, "returncode": -1, "stdout": "",
                      "stderr": f"executor returned non-dict result: {type(result).__name__}"}
        # Carry a HEALTHY session forward; start fresh on error (is_error absent => no resume).
        resume_session = result.get("session_id") if (
            result.get("session_id") and not result.get("is_error")) else None
        combined = _resultText(result, "stdout")
        stderr_text = _resultText(result, "stderr")
        if stderr_text:
            combined += "\n[stderr]\n" + stderr_text
        vresult, passed, resume_session, failure_feedback = self._runAttemptVerify(
            state, subtask, result, exec_cwd, verify_spec, attempt_started,
            sid, combined, dashboard, resume_session)
        return spec, result, vresult, combined, passed, resume_session, failure_feedback

    def _runAttemptLoop(self, state: TaskState, subtask: dict, architect_doc: str,
                        exec_cwd: str, bus: "ControlBus", dashboard: "DiscordDashboard",
                        sid: str, verify_spec: "dict | None") -> tuple:
        """Run the verification-attempt loop for one subtask.

        Returns (spec, result, vresult, combined, passed, attempt).
        Returns (None, None, None, None, False, attempt) when the subtask is removed mid-loop.
        """
        attempt = 0
        passed = False
        failure_feedback: "str | None" = None
        spec: dict = {}
        result: dict = {"ok": False, "stdout": "", "stderr": "", "returncode": None}
        vresult: "dict | None" = None
        combined = ""
        resume_session: "str | None" = None   # continue the SAME Claude session across retries
        while attempt < config.MAX_SUBTASK_ATTEMPTS and not passed:
            attempt += 1
            with self._state_lock:
                state.updateSubtask(sid, status="in_progress",
                                    started_at=subtask.get("started_at") or nowIso())
            spec, result, vresult, combined, passed, resume_session, failure_feedback = \
                self._runOneAttempt(state, subtask, architect_doc, exec_cwd, bus, dashboard,
                                    sid, verify_spec, failure_feedback, resume_session, attempt)
            self._translateDiscord(bus, state)
            # honor !pause mid-subtask via the SHARED escapable wait (abort / night-mode timeout /
            # deadline) -- the inline loop here previously ignored all three and could wedge an
            # unattended night run forever (CB-1).
            self._waitWhilePaused(state, bus, dashboard, label=f"{sid} paused")
            if bus.isAbort():
                raise AbortRun("abort requested")
            if (state.getSubtask(sid) or {}).get("status") == "removed":
                return None, None, None, None, False, attempt
        return spec, result, vresult, combined, passed, attempt

    def _runAdversaryReview(self, state: TaskState, subtask: dict, combined: str,
                            final: str, exec_cwd: str, bus: "ControlBus",
                            dashboard: "DiscordDashboard", heartbeat_ordinal: int,
                            attempt: int, architect_doc: str) -> "tuple[str | None, bool]":
        """Trigger adversary review if warranted; run remediation if challenged. Returns (verdict, stub)."""
        sid = subtask["subtask_id"]
        triggered, reason = adversary.shouldTrigger(combined, heartbeat_ordinal, attempt)
        if not triggered:
            return None, False
        rv = self._review(subtask["title"], reason, combined,
                          ollama_chat=self._ollamaChat,
                          goal=state.meta.get("goal_elaborated") or state.meta.get("goal_raw", ""))
        _adv_verdict = rv.get("verdict")
        _adv_stub = rv.get("stub", False)
        discord.sendEmbed(discord.adversaryTriggeredEmbed(subtask["title"], reason, rv.get("verdict")))
        cast.speak("adversary", f"⚔️ Reviewing `{sid}` ({subtask['title']}) → "
                   f"**{discord.formatVerdict(rv.get('verdict'))}**.")
        cast.duel(subtask["title"], rv.get("verdict"))   # VS-card on a CHALLENGE (T8)
        # Proactive narration + a rare Moment when the adversary catches something critical.
        self._narrate(f"⚠️ Adversary flagged something in {sid}. Remediating.")
        if rv.get("verdict") == "rejected":
            self._emitMoment(sid, f"⚡ MOMENT — The adversary caught a critical issue in "
                             f"`{sid}` the plan never anticipated.")
        with self._state_lock:
            state.addNotification("adversary_triggered", f"{sid}: {reason} -> {rv['verdict']}")
            self.obs.writeNote(state.subtaskReviewNoteRel(sid),
                               self._reviewNote(subtask, reason, rv, combined))
            state.addAdversaryReview(sid, reason, rv["verdict"],
                                     state.subtaskReviewNoteRel(sid), stub=rv.get("stub", False))
        # TEETH: a challenged verdict on a PASSED subtask earns ONE bounded remediation attempt.
        if (config.ADVERSARY_REMEDIATION_ENABLED and final == "done"
                and rv.get("verdict") == "challenged" and rv.get("concerns")):
            if self._remediationTreeShared(exec_cwd):
                # Skip: snapshot + whole-tree checkout would clobber concurrent peer workers.
                LOG.warning("%s: skipping adversary remediation -- shared working tree under "
                            "parallelism>1 (a revert would clobber peer subtasks)", sid)
                with self._state_lock:
                    state.addNotification("adversary_remediation",
                                          f"{sid}: remediation skipped (shared tree, parallel run)")
            else:
                dashboard.update(state, "executing", f"{sid} adversary remediation (1 attempt)")
                self._remediate(state, subtask, architect_doc, exec_cwd, rv["concerns"],
                                cancel_check=lambda: bus.isAbort() or self._deadlinePassed(state))
        return _adv_verdict, _adv_stub

    def _runSieAndReplan(self, state: TaskState, subtask: dict, spec: dict, combined: str,
                         passed: bool, final: str, architect_doc: str,
                         dashboard: "DiscordDashboard", adv_verdict: "str | None",
                         adv_stub: bool) -> None:
        """Capture SIE reflection, memoize passing spec, and trigger adaptive replan."""
        sid = subtask["subtask_id"]
        try:
            reflection.capture(run_id=state.task_id, subtask_id=sid, executor_output=combined,
                               verify_passed=passed, adversary_verdict=adv_verdict,
                               adversary_stub=adv_stub)
            if passed and spec.get("prompt"):
                solution_cache_spec = json.dumps({k: spec.get(k) for k in
                    ("prompt", "effort_level", "skills_to_invoke", "subagent") if spec.get(k)})
                experience.upsert_solution(solution_cache.signature_of(subtask.get("title", "")),
                                           solution_cache_spec, verify_passed=True,
                                           provenance='{"origin":"executor"}')
        except Exception:  # noqa: BLE001 -- learning never affects the run
            pass
        # Replan after a PASSED subtask always; after a FAILED one ONLY on a self-improvement run.
        # Churn (fail -> re-add -> fail) is bounded by the no-progress livelock guard and pending cap.
        self_ref = bool(state.meta.get("is_self_referential"))
        replan_ok = final == "done" or (self_ref and final == "failed")
        if replan_ok and not self._singleDeliverable(state.meta.get("goal_elaborated", "")):
            with self._state_lock:                       # snapshot for parallel-safety
                subs_snapshot = list(state.subtasks)
            decision = self._replan(state.meta["goal_elaborated"], subs_snapshot, subtask, combined,
                                    self_referential=bool(state.meta.get("is_self_referential")),
                                    remaining_hours=self._remainingHours(state))
            if decision.get("action") == "mutate" and (decision.get("add") or decision.get("remove")):
                dashboard.update(state, "replanning", f"replanning after {sid}")
                with self._state_lock:
                    self._applyReplan(state, decision)
                from notifications import run_arc as _arc
                self._arcBeat(state, _arc.beat_replan(f"after {sid}"))
                self._narrate(f"🔁 Replanning after {sid}. Scope was wider than expected.")

    def _surfaceSubtaskPass(self, state: TaskState, sid: str, attempt: int) -> None:
        """First-verify arc beat (once) + redemption moment after 2+ prior failures. Best-effort."""
        try:
            done_count = sum(1 for s in state.subtasks if s["status"] == "done")
            if done_count == 1:
                self._arcBeat(state, "Chapter 3 — First subtask closed clean.")
            if attempt >= 3:
                self._emitMoment(sid, "⚡ MOMENT — Redemption. It clawed back from "
                                 "two dead ends and closed clean.")
        except Exception:  # noqa: BLE001
            pass

    def _postSubtaskEnrich(self, state: TaskState, subtask: dict, spec: dict, result: dict,
                           vresult: "dict | None", combined: str, passed: bool, final: str,
                           exec_cwd: str, architect_doc: str, bus: "ControlBus",
                           dashboard: "DiscordDashboard", attempt: int) -> None:
        """Persist Obsidian note, run adversary review, capture SIE learning, and replan.

        Also posts a feedback embed (Subsystem C) to invite human approval/rejection/skip/retry.

        Best-effort: AbortRun re-raises; all other exceptions are swallowed so the committed
        subtask status is never rolled back by enrichment failures.
        """
        sid = subtask["subtask_id"]
        try:
            # POST FEEDBACK EMBED (Subsystem C): invite human feedback on the completed subtask.
            # Post for both done and failed; the FeedbackView will handle control actions.
            goal = subtask.get("title", f"subtask {sid}")
            discord.sendEmbed(discord.feedbackEmbed(sid, goal, final),
                             components=discord.feedbackComponents())
            with self._state_lock:
                note = self._subtaskNote(state, subtask, spec, result, vresult)
                written = self.obs.writeNote(state.subtaskNoteRel(sid), note)
                state.updateSubtask(sid, output_ref=written.get("rel_path"))
            # Snapshot under the lock: in parallel mode a peer worker may be appending via _applyReplan,
            # and iterating the live list unlocked risks 'list changed size during iteration'.
            with self._state_lock:
                heartbeat_ordinal = sum(
                    1 for s in state.subtasks if s["status"] in ("done", "failed", "removed"))
            adv_verdict, adv_stub = self._runAdversaryReview(
                state, subtask, combined, final, exec_cwd, bus, dashboard,
                heartbeat_ordinal, attempt, architect_doc)
            # SIE subsystem I: learning summary + memoize passing spec + adaptive replan.
            self._runSieAndReplan(state, subtask, spec, combined, passed, final,
                                  architect_doc, dashboard, adv_verdict, adv_stub)
            with self._state_lock:
                self.writeIndex(state)
        except AbortRun:
            raise
        except Exception as e:  # noqa: BLE001 -- enrichment is best-effort; committed status stands
            LOG.warning("post-completion enrichment for %s failed (status %s preserved): %s",
                        sid, final, e, exc_info=True)

    # ===================================================================
    # Phase 3 -- execution (per-subtask unit)
    # ===================================================================
    def _executeSubtask(self, state: TaskState, subtask: dict, architect_doc: str, work_dir: str,
                        bus: "ControlBus", dashboard: "DiscordDashboard", position: int,
                        exec_cwd: "str | None" = None) -> str:
        sid = subtask["subtask_id"]
        verify_spec = subtask.get("verify")
        exec_cwd = exec_cwd or self._execCwd(state, sid, work_dir)
        dashboard.update(state, "executing", f"-> {sid} {subtask['title']}")
        # Boundary divergence check (#12): observe-only, never blocks. Under _state_lock: it mutates
        # state.meta + saves, and EVERY other meta mutation in this parallel execution path is guarded
        # by _state_lock -- an unguarded save here races a peer worker's save (lost/torn meta update).
        with self._state_lock:
            try:
                from platform_core.orchestration.subtask import _checkCodeDivergence
                _checkCodeDivergence(state)
            except Exception:  # noqa: BLE001
                pass
        spec, result, vresult, combined, passed, attempt = self._runAttemptLoop(
            state, subtask, architect_doc, exec_cwd, bus, dashboard, sid, verify_spec)
        if spec is None:   # subtask removed mid-attempt-loop
            return "removed"
        if (state.getSubtask(sid) or {}).get("status") == "removed":
            return "removed"
        # COMMIT the verified outcome FIRST -- it is the source of truth. Everything below
        # (notes, adversary, replan, index) is best-effort enrichment that must never be able to
        # change a verified result.
        final = "done" if passed else "failed"
        with self._state_lock:
            state.updateSubtask(sid, status=final, completed_at=nowIso())
            if not passed:
                state.addNotification("subtask_failed",
                                      f"{sid} failed verification after {attempt} attempts")
        if passed:
            self._surfaceSubtaskPass(state, sid, attempt)
        if not passed:
            discord.sendEmbed(discord.subtaskFailedEmbed(sid, subtask["title"], vresult, attempt))
        dashboard.update(state, "executing", f"{sid} -> {final}")
        cast.speak("verifier" if not passed else "executor",
                   (f"❌ `{sid}` failed verification after {attempt} attempt(s)." if not passed
                    else f"⚙️ `{sid}` {subtask['title']} — done ✅"))
        self._postSubtaskEnrich(state, subtask, spec, result, vresult, combined,
                                passed, final, exec_cwd, architect_doc, bus, dashboard, attempt)
        return final
