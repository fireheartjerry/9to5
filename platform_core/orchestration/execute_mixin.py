class OrchestratorExecuteMixin(OrchestratorExecuteAttemptMixin, OrchestratorExecuteDelegatesMixin):
    """Handles executor routing, the attempt loop, adversary remediation, and SIE enrichment.

    The single-attempt runner (_runOneAttempt + spec/feed/hands/verify helpers) lives in
    OrchestratorExecuteAttemptMixin; the quality-gate/evidence-gate/adversary/SIE delegates and
    lazy per-run caches live in OrchestratorExecuteDelegatesMixin. Both are inherited here."""

    def _prepareAttemptSpec(
        self,
        state: TaskState,
        subtask: dict,
        architect_doc: str,
        failure_feedback: "str | None",
        sid: str,
        attempt: int,
        dashboard: "DiscordDashboard",
    ) -> dict:
        """Author the invocation spec, record the routed session, surface the attempt."""
        if "attempt" in inspect.signature(self.authorInvocationSpec).parameters:
            spec = self.authorInvocationSpec(state, subtask, architect_doc, failure_feedback, attempt=attempt)
        else:
            spec = self.authorInvocationSpec(state, subtask, architect_doc, failure_feedback)
        spec.setdefault("work_profile", state.meta.get("work_profile"))
        spec.setdefault("run_intent_policy", state.meta.get("run_intent_policy"))
        with self._state_lock:
            sess = dict(subtask.get("session") or {})
            # FX-20: record the model the executor will ACTUALLY route to by effort.
            routed_model = config.MODEL_BY_EFFORT.get(
                (spec.get("effort_level") or "default").lower(), config.PRIMARY_MODEL
            )
            sess.update(
                {
                    "effort": spec.get("effort_level"),
                    "model": routed_model,
                    "skills": spec.get("skills_to_invoke"),
                    "subagent": spec.get("subagent"),
                    "surfaces": surfaces.surfaces_used(spec),  # SIE surface learning
                    "use_workflow": bool(spec.get("use_workflow")),
                    "attempts": attempt,
                    "work_profile": state.meta.get("work_profile"),
                    "run_intent_policy": state.meta.get("run_intent_policy"),
                }
            )
            state.updateSubtask(sid, session=sess)
        LOG.info(
            "Subtask %s attempt %d/%d effort=%s",
            sid,
            attempt,
            config.MAX_SUBTASK_ATTEMPTS,
            spec.get("effort_level"),
        )
        dashboard.update(
            state,
            "executing",
            f"{sid} attempt {attempt} · effort {spec.get('effort_level')}",
            effort=spec.get("effort_level"),
        )
        if attempt >= 2:
            self._narrate(f"`{sid}` attempt {attempt}. Still working on it.")
        return spec

    @staticmethod
    def _seedResumeContext(subtask: dict) -> "tuple[str | None, str | None]":
        """For a resumable subtask (Epic 1b), return (resume_block_as_feedback, resume_session_id)
        to seed attempt 1; ((None, None) when the flag is off or the subtask isn't resumable)."""
        if not getattr(config, "STEP_RESUME_ENABLED", False):
            return None, None
        sess = subtask.get("session") or {}
        if not sess.get("resumable"):
            return None, None
        return sess.get("resume_block"), sess.get("resume_session_id")

    def _runAttemptLoop(
        self,
        state: TaskState,
        subtask: dict,
        architect_doc: str,
        exec_cwd: str,
        bus: "ControlBus",
        dashboard: "DiscordDashboard",
        sid: str,
        verify_spec: "dict | None",
        env_ctx=None,
    ) -> tuple:
        """Run the verification-attempt loop for one subtask.

        Returns (spec, result, vresult, combined, passed, attempt).
        Returns (None, None, None, None, False, attempt) when the subtask is removed mid-loop.
        """
        attempt = 0
        passed = False
        seed_feedback, seed_resume = self._seedResumeContext(subtask)
        failure_feedback: "str | None" = seed_feedback
        spec: dict = {}
        result: dict = {"ok": False, "stdout": "", "stderr": "", "returncode": None}
        vresult: "dict | None" = None
        combined = ""
        resume_session: "str | None" = seed_resume  # continue the SAME Claude session across retries
        while attempt < config.MAX_SUBTASK_ATTEMPTS and not passed:
            attempt += 1
            with self._state_lock:
                state.updateSubtask(
                    sid, status="in_progress", started_at=subtask.get("started_at") or nowIso()
                )
            spec, result, vresult, combined, passed, resume_session, failure_feedback = self._runOneAttempt(
                state,
                subtask,
                architect_doc,
                exec_cwd,
                bus,
                dashboard,
                sid,
                verify_spec,
                failure_feedback,
                resume_session,
                attempt,
                env_ctx,
            )
            self._translateDiscord(bus, state)
            # honor !pause mid-subtask via the SHARED escapable wait (abort / night-mode
            # timeout / deadline), so a !pause can never wedge an unattended run (CB-1).
            self._waitWhilePaused(state, bus, dashboard, label=f"{sid} paused")
            if bus.isAbort():
                raise AbortRun("abort requested")
            if (state.getSubtask(sid) or {}).get("status") == "removed":
                return None, None, None, None, False, attempt
            if isinstance(result, dict) and result.get("subtype") == "blocked_clarification":
                break
            # R6: an operator kill never burns an attempt slot; a deadline-driven cancel must
            # stop respawning attempts the watcher would instantly re-kill.
            if isinstance(result, dict) and result.get("subtype") == "operator_killed":
                attempt -= 1
                if self._deadlinePassed(state):
                    break
        return spec, result, vresult, combined, passed, attempt

    def _surfaceSubtaskPass(self, state: TaskState, sid: str, attempt: int) -> None:
        """First-verify arc beat (once) + redemption moment after 2+ prior failures. Best-effort."""
        try:
            done_count = sum(1 for s in state.subtasks if s["status"] == "done")
            if done_count == 1:
                self._arcBeat(state, "Chapter 3 — First subtask closed clean.")
            if attempt >= 3:
                self._emitMoment(
                    sid, "⚡ MOMENT — Redemption. It clawed back from two dead ends and closed clean."
                )
        except Exception:  # noqa: BLE001
            pass

    def _postSubtaskEnrich(
        self,
        state: TaskState,
        subtask: dict,
        spec: dict,
        result: dict,
        vresult: "dict | None",
        combined: str,
        passed: bool,
        final: str,
        exec_cwd: str,
        architect_doc: str,
        bus: "ControlBus",
        dashboard: "DiscordDashboard",
        attempt: int,
    ) -> None:
        """Persist Obsidian note, run adversary review, capture SIE learning, and replan.

        Also posts a feedback embed (Subsystem C) to invite human approval/rejection/skip/retry.

        Best-effort: AbortRun re-raises; all other exceptions are swallowed so the committed
        subtask status is never rolled back by enrichment failures.
        """
        sid = subtask["subtask_id"]
        try:
            heartbeat_ordinal = self._recordSubtaskArtifacts(
                state, subtask, spec, result, vresult, sid, final
            )
            adv_verdict, adv_stub = self._runAdversaryReview(
                state,
                subtask,
                combined,
                final,
                exec_cwd,
                bus,
                dashboard,
                heartbeat_ordinal,
                attempt,
                architect_doc,
            )
            # SIE subsystem I: learning summary + memoize passing spec + adaptive replan.
            self._runSieAndReplan(
                state, subtask, spec, combined, passed, final, architect_doc, dashboard, adv_verdict, adv_stub,
                result=result,
            )
            with self._state_lock:
                self.writeIndex(state)
        except AbortRun:
            raise
        except Exception as e:  # noqa: BLE001 -- enrichment is best-effort; committed status stands
            from platform_core.core.best_effort import recordDegradation

            recordDegradation("enrichment.post_completion", e, log=LOG)
            LOG.warning(
                "post-completion enrichment for %s failed (status %s preserved): %s",
                sid,
                final,
                e,
                exc_info=True,
            )

    def _recordSubtaskArtifacts(
        self,
        state: TaskState,
        subtask: dict,
        spec: dict,
        result: dict,
        vresult: "dict | None",
        sid: str,
        final: str,
    ) -> int:
        """Post the feedback embed (Subsystem C) + write the per-subtask Obsidian note.
        Returns the heartbeat ordinal used by the adversary review call."""
        # POST FEEDBACK EMBED (Subsystem C): invite human feedback on the completed subtask.
        # Post for both done and failed; the FeedbackView will handle control actions.
        goal = subtask.get("title", f"subtask {sid}")
        discord.sendEmbed(discord.feedbackEmbed(sid, goal, final), components=discord.feedbackComponents())
        with self._state_lock:
            note = self._subtaskNote(state, subtask, spec, result, vresult)
            written = self.obs.writeNote(state.subtaskNoteRel(sid), note)
            state.updateSubtask(sid, output_ref=written.get("rel_path"))
        # Snapshot under the lock: in parallel mode a peer worker may be appending via _applyReplan,
        # and iterating the live list unlocked risks 'list changed size during iteration'.
        with self._state_lock:
            return sum(1 for s in state.subtasks if s["status"] in ("done", "failed", "removed"))

    def _runSubtaskAttempts(
        self,
        state: TaskState,
        subtask: dict,
        architect_doc: str,
        exec_cwd: str,
        bus: "ControlBus",
        dashboard: "DiscordDashboard",
        sid: str,
        verify_spec: "dict | None",
        env_ctx=None,
    ) -> tuple:
        """Fork seam: same 6-tuple as _runAttemptLoop. Flag-off => byte-identical (gate in solution_space).
        ``env_ctx`` (Epic 8) threads the provisioned env into the LINEAR path only."""
        from platform_core.orchestration import solution_space

        return solution_space.runSubtaskAttempts(
            self, state, subtask, architect_doc, exec_cwd, bus, dashboard, sid, verify_spec, env_ctx=env_ctx
        )

    # ===================================================================
    # Phase 3 -- execution (per-subtask unit)
    # ===================================================================
    def _executeSubtask(
        self,
        state: TaskState,
        subtask: dict,
        architect_doc: str,
        work_dir: str,
        bus: "ControlBus",
        dashboard: "DiscordDashboard",
        position: int,
        exec_cwd: "str | None" = None,
        defer_completion: bool = False,
    ) -> "str | AttemptOutcome":
        sid = subtask["subtask_id"]
        verify_spec = subtask.get("verify")
        exec_cwd = exec_cwd or self._execCwd(state, sid, work_dir)
        dashboard.update(state, "executing", f"-> {sid} {subtask['title']}")
        from platform_core.execution import wiring as _env_wiring

        exec_cwd, env, handle, env_ctx = self._prepareSubtaskEnv(state, subtask, exec_cwd)
        # finalizeQuietly (collect+teardown) must run on EVERY exit path, including an AbortRun
        # (or any other exception) raised out of _runSubtaskAttempts -- previously it only ran on
        # the two normal-return paths, so an abort mid-attempt leaked the provisioned env (a
        # Docker container that never self-exits despite --rm, or a remote host's /tmp tree).
        try:
            spec, result, vresult, combined, passed, attempt = self._runSubtaskAttempts(
                state, subtask, architect_doc, exec_cwd, bus, dashboard, sid, verify_spec, env_ctx=env_ctx
            )
            if spec is None or (state.getSubtask(sid) or {}).get("status") == "removed":
                return "removed"
            outcome = AttemptOutcome(sid, spec, result, vresult, combined, passed, attempt, exec_cwd)
            if defer_completion:
                return outcome
            return self._finalizeAttemptOutcome(state, subtask, architect_doc, bus, dashboard, outcome)

        finally:
            if env is not None and handle is not None:
                _env_wiring.finalizeQuietly(
                    env, handle, state, subtask, sid, LOG
                )  # Epic 8: collect+teardown

    def _finalizeAttemptOutcome(
        self, state: TaskState, subtask: dict, architect_doc: str, bus: "ControlBus",
        dashboard: "DiscordDashboard", outcome: AttemptOutcome,
    ) -> str:
        """Commit a completed attempt only after its execution environment is accepted."""
        sid = outcome.subtask_id
        final = self._commitSubtaskResult(state, sid, subtask, outcome.passed, outcome.attempt_count, outcome.verify_result)
        dashboard.update(state, "executing", f"{sid} -> {final}")
        self._postSubtaskEnrich(
            state, subtask, outcome.spec or {}, outcome.result or {}, outcome.verify_result, outcome.combined,
            outcome.passed, final, outcome.exec_cwd, architect_doc, bus, dashboard, outcome.attempt_count,
        )
        return final

    def _prepareSubtaskEnv(self, state: TaskState, subtask: dict, exec_cwd: str) -> tuple:
        """Boundary divergence check (#12, observe-only) + Epic 8 per-subtask env provisioning.
        Returns (exec_cwd, env, handle, env_ctx)."""
        # A fully injected credentialless harness has no environment adapter to
        # provision or finalize.  Its supplied executor writes only to the test
        # fixture and cannot reach the built-in backend registry/launcher.
        if getattr(self, "_fully_injected", False):
            return exec_cwd, None, None, None

        # Under _state_lock: it mutates state.meta + saves, and EVERY other meta mutation in this
        # parallel execution path is guarded by _state_lock -- an unguarded save here races a peer
        # worker's save (lost/torn meta update).
        with self._state_lock:
            try:
                from platform_core.orchestration.subtask import _checkCodeDivergence

                _checkCodeDivergence(state)
            except Exception:  # noqa: BLE001
                pass
        # Epic 8: provision a per-subtask env (default local; fabric OFF => identity => today).
        from platform_core.execution import wiring as _env_wiring

        env, handle, env_ctx, exec_cwd = _env_wiring.provisionForSubtask(state, subtask, exec_cwd)
        with self._state_lock:
            subtask["env_handle_meta"] = {"backend": handle.backend, "meta": handle.meta}
        return exec_cwd, env, handle, env_ctx

    def _commitSubtaskResult(
        self, state: TaskState, sid: str, subtask: dict, passed: bool, attempt: int, vresult: "dict | None"
    ) -> str:
        """Commit the verified outcome (source of truth) and speak/notify the result."""
        final = "done" if passed else "failed"
        with self._state_lock:
            state.updateSubtask(sid, status=final, completed_at=nowIso())
            if not passed:
                state.addNotification("subtask_failed", f"{sid} failed verification after {attempt} attempts")
        if passed:
            self._surfaceSubtaskPass(state, sid, attempt)
        if not passed:
            discord.sendEmbed(discord.subtaskFailedEmbed(sid, subtask["title"], vresult, attempt))
        cast.speak(
            "verifier" if not passed else "executor",
            (
                f"❌ `{sid}` failed verification after {attempt} attempt(s)."
                if not passed
                else f"⚙️ `{sid}` {subtask['title']} — done ✅"
            ),
        )
        return final
