"""File-disjointness parallel-safety + atomic CAS claim (Epic 1, unit c; guild port).

Two subtasks run concurrently only if their planner-authored file-sets are disjoint AND
neither depends on the other. LOCKED DECISION: file-sets are planner-authored via the
`files_touched` subtask field; an EMPTY/unknown set is treated as conflicting, so an
un-annotated plan conservatively SERIALIZES (never less safe than today). claim() is the
race-free pending->in_progress flip; the caller holds self._state_lock so the read-modify
-write is atomic. State-store ownership is preserved (mutation via state.updateSubtask).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ParallelBatch
  filesTouched(subtask: dict) -> set[str]  -- Planner-authored file-set
  disjoint(a: dict, b: dict) -> bool  -- True only if BOTH file-sets are known and share no file
  selectSafeBatch(ready: list[dict], *, budget: WorkerBudget) -> ParallelBatch  -- Return a planner-ordered, explicitly opted-in concurrent batch.
  safeParallelSet(state, ready: list[dict], limit: int) -> list[dict]  -- Greedily pick ready subtasks whose file-sets are pairwise disjoint + dependency-free.
  claim(state, sid: str) -> bool  -- Atomic CAS: flip pending->in_progress ONLY if still pending (else lost-race=False).
DEPENDS-ON: config, platform_core.core.concurrency
SIDE-EFFECTS: claim() flips subtask status via state.updateSubtask
RUN/TEST: python -m pytest tests/control/test_parallel_safety.py
"""
from __future__ import annotations

from dataclasses import dataclass

import config
from platform_core.core.concurrency import WorkerBudget

LOG = config.getLogger("orchestrator.parallel_safety")


@dataclass(frozen=True, slots=True)
class ParallelBatch:
    selected: tuple[dict, ...]
    serial_reason: str | None = None


def filesTouched(subtask: dict) -> set[str]:
    """Planner-authored file-set; empty/missing -> empty set (treated as conflicting)."""
    files = subtask.get("files_touched") or []
    if not isinstance(files, list):
        return set()
    return {str(f) for f in files if f}


def disjoint(a: dict, b: dict) -> bool:
    """True only if BOTH file-sets are known and share no file. Unknown set -> conflicting."""
    fa, fb = filesTouched(a), filesTouched(b)
    if not fa or not fb:
        return False
    return fa.isdisjoint(fb)


def selectSafeBatch(ready: list[dict], *, budget: WorkerBudget) -> ParallelBatch:
    """Return a planner-ordered, explicitly opted-in concurrent batch."""
    if not ready:
        return ParallelBatch(())
    first = ready[0]
    if not first.get("parallel_safe"):
        return ParallelBatch((first,), "first-ready-subtask-not-opted-in")
    picked = [first]
    for candidate in ready[1:]:
        if len(picked) >= max(1, budget.effective):
            break
        if not candidate.get("parallel_safe"):
            continue
        if all(disjoint(candidate, prior) and not _depConflict(candidate, prior) for prior in picked):
            picked.append(candidate)
    return ParallelBatch(tuple(picked), None if len(picked) > 1 else "no-disjoint-opted-in-peer")


def _depConflict(a: dict, b: dict) -> bool:
    """True if either subtask depends on the other (cannot co-run)."""
    return (a.get("subtask_id") in (b.get("depends_on") or [])
            or b.get("subtask_id") in (a.get("depends_on") or []))


def safeParallelSet(state, ready: list[dict], limit: int) -> list[dict]:
    """Greedily pick ready subtasks whose file-sets are pairwise disjoint + dependency-free.
    Always returns at least the first ready subtask (serialize on conflict). Fail-open."""
    if not ready:
        return []
    try:
        picked: list[dict] = [ready[0]]
        for cand in ready[1:]:
            if len(picked) >= max(1, limit):
                break
            if all(disjoint(cand, prior) and not _depConflict(cand, prior) for prior in picked):
                picked.append(cand)
        return picked
    except Exception as e:  # noqa: BLE001 -- on any error, serialize to today's safe single pick
        LOG.warning("safeParallelSet failed (%s); serializing", e)
        return [ready[0]]


def claim(state, sid: str) -> bool:
    """Atomic CAS: flip pending->in_progress ONLY if still pending (else lost-race=False).
    Caller MUST hold self._state_lock so the re-read + write is atomic (rowcount-0 analogue)."""
    st = state.getSubtask(sid)
    if st is None or st.get("status") != "pending":
        return False
    state.updateSubtask(sid, status="in_progress", claimed_by="worker")
    return True
