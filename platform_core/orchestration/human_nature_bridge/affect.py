from __future__ import annotations

from typing import Any

import config
from platform_core.core.best_effort import best_effort, recordDegradation

from ._common import LOG, _meta, appendUnique

# --- Emotion faculty: affect -> emotion label -> advisory behavior coupling ------
# Behavior intents this repo maps to a SAFE, BOUNDED run effect (a +1 retry-budget
# nudge). Only intents whose "do more" reading is bounded and non-destructive live
# here; every OTHER intent (explore/propose_refactor/None/unknown) is RECORD-ONLY
# (delta 0) -- it is still "used" (surfaced) but applies no run effect.
_SAFE_NUDGE_INTENTS: frozenset[str] = frozenset({"escalate_effort", "raise_verification"})


def _affectToLabel(affect: "dict | None") -> str:
    """Derive an emotion label from the self-model PAD affect (valence/arousal/control).

    SIMPLE, documented rule (never invents affect -- absent/zero affect => "neutral"):
      high valence (>= 0.3)                    -> satisfaction
      low valence (<= -0.3) + high arousal     -> frustration
      low valence (<= -0.3) + not-high arousal -> anxiety
      low arousal (<= -0.3), neutral valence   -> boredom
      else                                     -> neutral
    Best-effort: any malformed affect maps to "neutral"; never raises."""
    try:
        aff = affect or {}
        v = float(aff.get("valence", 0.0) or 0.0)
        a = float(aff.get("arousal", 0.0) or 0.0)
    except Exception:  # noqa: BLE001 -- garbage affect must never raise
        return "neutral"
    if v >= 0.3:
        return "satisfaction"
    if v <= -0.3:
        return "frustration" if a >= 0.3 else "anxiety"
    if a <= -0.3:
        return "boredom"
    return "neutral"


def _emotionLabel(self_state: dict) -> str:
    """Continuous-manifold emotion label when config.HN_MANIFOLD is on (project the 9-axis
    affect_manifold onto the nearest prototype), else the legacy PAD rule _affectToLabel(affect).
    Best-effort: falls back to _affectToLabel on any error."""
    if getattr(config, "HN_MANIFOLD", False):
        try:
            from human_nature import prototypes

            return prototypes.dominant(self_state.get("affect_manifold") or {})
        except Exception as exc:  # noqa: BLE001 -- garbage manifold must never raise
            recordDegradation("human_nature_bridge.affect_manifold", exc, log=LOG)
    return _affectToLabel(self_state.get("affect"))


def emotionNudge(behavior_intent: "str | None") -> int:
    """Pure helper: map a coupled behavior intent to a BOUNDED retry-budget delta in
    {0, +1}. Only the clearly-safe subset (escalate_effort, raise_verification) maps
    to +1 -- both read as "carefully try once more", a bounded, non-destructive act.
    Every other intent (explore/propose_refactor/None/unknown) maps to 0 (record-only).
    No side effects, never raises."""
    return 1 if behavior_intent in _SAFE_NUDGE_INTENTS else 0


def emotionAdvisory(state: Any, dashboard: Any = None) -> dict:
    """Wire the Human-Nature emotion faculty as an ADVISORY behavior coupling. Derive an
    emotion label from this run's self-model affect, call ``emotions.couple(label, meta)``,
    RECORD ``{"emotion", "behavior"}`` into ``state.meta["hn_behavior"]``, SURFACE a
    dashboard event, and RETURN the coupling dict. Complete no-op ({}) unless BOTH
    HUMAN_NATURE_ENABLED and HN_EMOTIONS_BEHAVIOR are True. Best-effort (never raises) and
    ADVISORY ONLY: it records + surfaces; it never blocks, aborts, skips/alters verification,
    rejects a plan, or changes control flow. The bounded run effect (a +1 retry nudge for a
    safe intent, via ``emotionNudge``) is applied ONLY at the opt-in call site, clamped there
    to the hard max. Returns the coupling ({"behavior", "comms"}) or {} when disabled/failed."""
    if not (config.HUMAN_NATURE_ENABLED and config.HN_EMOTIONS_BEHAVIOR):
        return {}
    try:
        from human_nature import emotions

        meta = _meta(state)
        self_state = meta.get("self_state") or {}
        label = _emotionLabel(self_state)
        coupling = emotions.couple(label, meta)
        intent = coupling.get("behavior")
        appendUnique(meta, "hn_behavior", {"emotion": label, "behavior": intent})
        LOG.info("human-nature emotion advisory: %s -> %s", label, intent)
        if dashboard is not None:
            with best_effort("human_nature.emotion_surface", log=LOG):
                dashboard.event(f"emotion — {label} (behavior: {intent})")
        return coupling
    except Exception:  # noqa: BLE001
        LOG.debug("emotionAdvisory failed (ignored)", exc_info=True)
        return {}
