"""Instinct hook: scan the run's event log for dangerous motifs and surface a signal.

Composes the pure ``human_nature`` streaming-instinct faculties (event log ->
type sequence -> Aho-Corasick exact scan + tail-prefix scan) into a single
best-effort, gated hook. On a strong match it builds a structured
``InstinctSignal``, resolves its earned-authority tier via the 5-cap gate for
an ADDITIVE action only ("deepen_verification"), records it into
``state.meta["hn_instinct"]``, and surfaces a dashboard receipt. It never
reads or alters a verifier verdict -- it only reads the event log.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  instinctCheck(state: Any, dashboard: Any=None) -> 'dict | None'  -- Hook: scan the run's event log for dangerous motif PREFIXES/exact matches
DEPENDS-ON: config, human_nature.instinct_signal, human_nature.instinct_stream, human_nature.run_events, platform_core.core.best_effort
SIDE-EFFECTS: mutates state.meta["hn_instinct"] when enabled and a motif matches
RUN/TEST: python -m pytest tests/notifications/test_instinct.py
"""
from __future__ import annotations

from typing import Any

import config
from platform_core.core.best_effort import best_effort

from ._common import LOG, _meta

# Known dangerous motifs (event-type sequences). Small default registry; hot path may
# extend it via state.meta["hn_scar_motifs"].
DEFAULT_SCAR_MOTIFS: list[tuple[str, list[str]]] = [
    ("scar.large-diff-hidden-regression", ["PATCH_LARGE", "TESTS_SKIPPED", "CONFIDENCE_HIGH"]),
    ("scar.overconfident-before-tests", ["PATCH_SIZE_SPIKE", "TESTS_NOT_YET_RUN", "CONFIDENCE_HIGH"]),
    ("scar.no-progress-loop", ["RETRY_SAME_STRATEGY", "NO_PROGRESS_LOOP"]),
]


def _motifsFor(meta: dict) -> list[tuple[str, list[str]]]:
    """Default motif registry plus any run-local extensions from state.meta."""
    return list(DEFAULT_SCAR_MOTIFS) + list(meta.get("hn_scar_motifs", []))


def _bestMatch(motifs: list[tuple[str, list[str]]], seq: list[str]) -> "dict | None":
    """Highest-score motif hit across exact (score 1.0) and tail-prefix matches."""
    from human_nature.instinct_stream import build_matcher, scan, scan_prefixes

    exact_hits = scan(build_matcher(motifs), seq)
    prefix_hits = scan_prefixes(motifs, seq, threshold=config.HN_SCAR_MATCH_THRESHOLD)
    candidates = list(exact_hits) + list(prefix_hits)
    if not candidates:
        return None
    return max(candidates, key=lambda hit: hit["score"])


def _buildSignal(best: dict, seq: list[str]) -> "Any":
    from human_nature.instinct_signal import InstinctSignal

    score = float(best["score"])
    return InstinctSignal(
        motif_id=best["motif_id"],
        match_type="exact" if best["match_type"] == "exact" else "prefix",
        confidence=score,
        severity=score,
        expected_loss_if_ignored=score,
        recommended_action="deepen_verification",
        authority_request="hold",
        evidence_events=seq[-5:],
        matched_history_refs=[best["motif_id"]],
    )


def _surface(dashboard: Any, motif_id: str, tier: str) -> None:
    if dashboard is None:
        return
    with best_effort("human_nature.instinct_surface", log=LOG):
        dashboard.event(f"instinct — {motif_id} ({tier})")


def instinctCheck(state: Any, dashboard: Any = None) -> "dict | None":
    """Hook: scan the run's event log for dangerous motif PREFIXES/exact matches; if a
    strong match is found, build a structured InstinctSignal, resolve its authority via
    the 5-cap gate (additive 'deepen_verification' action only), record it to
    state.meta["hn_instinct"], surface a dashboard receipt, and return the recorded
    dict. Best-effort + gated: no-op (None) unless config.HUMAN_NATURE_ENABLED and
    config.HN_INSTINCT; never raises; NEVER reads/alters a verifier verdict."""
    if not (config.HUMAN_NATURE_ENABLED and config.HN_INSTINCT):
        return None
    try:
        from human_nature.run_events import event_sequence
        from .authority_gate import resolveTier

        meta = _meta(state)
        seq = event_sequence(meta.get("hn_event_log", []))
        best = _bestMatch(_motifsFor(meta), seq)
        if best is None:
            return None
        sig = _buildSignal(best, seq)
        tier = resolveTier(
            "instinct", meta.get("domain", "unknown"), sig.confidence, {},
            action="deepen_verification",
        )
        record = {"signal": sig.to_dict(), "tier": tier}
        meta.setdefault("hn_instinct", []).append(record)
        LOG.info("human-nature instinct: %s (%s)", best["motif_id"], tier)
        _surface(dashboard, best["motif_id"], tier)
        return record
    except Exception:  # noqa: BLE001
        LOG.debug("instinctCheck failed (ignored)", exc_info=True)
        return None
