"""Plan-gate couplings: mid-run instinct + advisory-only opinion surfacing.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  midRunInstinct(state: Any, dashboard: Any=None) -> 'str | None'  -- Hook 4: once per run, fire the ledger-grounded instinct ("gut") check and SURFACE it
  opinionAdvisory(state: Any, dashboard: Any=None) -> 'list[dict]'  -- Advisory-only opinion coupling on the plan gate
  opinionVote(state: Any, dashboard: Any=None) -> 'list[dict]'  -- Earned-authority VOTE coupling on the plan gate (flag-only, never removes)
DEPENDS-ON: config, human_nature.authority, human_nature.conviction, human_nature.integration, human_nature.opinions, human_nature.operator_authority, memory.conviction_ledger, memory.experience_adapters, memory.experience_solutions, platform_core.core.best_effort
SIDE-EFFECTS: mutates state.meta["hn_opinions"] / state.meta["hn_votes"] when enabled
RUN/TEST: python -m pytest tests/orchestration/test_human_nature_bridge.py
"""
from __future__ import annotations

from typing import Any

import config
from platform_core.core.best_effort import best_effort

from ._common import LOG, _meta


def midRunInstinct(state: Any, dashboard: Any = None) -> "str | None":
    """Hook 4: once per run, fire the ledger-grounded instinct ("gut") check and SURFACE the
    advisory flag. Best-effort + gated: no-op when HUMAN_NATURE_ENABLED is off, never raises, and
    never blocks the run -- it only narrates a suspicion drawn from past reflections/failure modes."""
    if not config.HUMAN_NATURE_ENABLED:
        return None
    try:
        from human_nature import integration
        from memory.experience_adapters import fetch_failure_modes
        from memory.experience_solutions import fetch_reflections

        flag = integration.maybe_run_instinct(state, fetch_reflections() or [], fetch_failure_modes() or [])
        if flag:
            LOG.info("human-nature instinct: %s", flag)
            if dashboard is not None:
                with best_effort("human_nature.instinct_surface", log=LOG):
                    dashboard.event(f"instinct — {flag}")
        return flag
    except Exception:  # noqa: BLE001
        LOG.debug("midRunInstinct failed (ignored)", exc_info=True)
        return None


def _subtasks(state: Any) -> list:
    """Read planned subtasks from a TaskState or a plain state dict. Best-effort: []."""
    try:
        if hasattr(state, "subtasks"):
            return list(state.subtasks or [])
        return list(state.get("plan", {}).get("subtasks", []) or [])
    except Exception:  # noqa: BLE001
        return []


def _subtaskDomain(state: Any, subtask: dict) -> str:
    """Derive the opinion domain for a subtask: explicit type, else run domain, else 'unknown'."""
    dom = subtask.get("type") or _meta(state).get("domain") or "unknown"
    return str(dom)


# judgment_type recorded for opinion/flag calibration in the conviction ledger.
_OPINION_JUDGMENT_TYPE = "opinion"


def _convictionFor(state: Any, domain: str) -> float:
    """Best-effort conviction score in [0,1] for *domain*, sourced from the REAL
    conviction ledger's per-domain track record. ``track_record`` returns the HONEST
    hit-rate (fraction of times HN's past opinions in this domain proved correct);
    ``conviction.track_weight`` folds in the ledger's cold-start floor (below
    ``MIN_SAMPLES`` observations it yields 0.0, so a 1/1 record earns no teeth) and
    otherwise returns that hit-rate directly. 0.0 when the ledger is empty, the domain
    is unseen, or the accessor errors -- a 0.0 conviction maps to the "cosmetic" tier,
    i.e. a silent no-op. No fabricated conviction, no LLM calls. Never raises. The
    *state* arg is kept for signature stability (ledger scope is domain-wide, not per-run)."""
    try:
        from human_nature.conviction import track_weight
        from memory.conviction_ledger import track_record

        track = track_record(_OPINION_JUDGMENT_TYPE, str(domain))
        return max(0.0, min(1.0, float(track_weight(track))))
    except Exception:  # noqa: BLE001
        return 0.0


def opinionAdvisory(state: Any, dashboard: Any = None) -> "list[dict]":
    """Advisory-only opinion coupling on the plan gate. For each planned subtask, look
    up the HN conviction for its domain and grade it via ``opinions.tier``; when the
    tier is "hard" (a strong conviction), SURFACE it as an advisory concern -- append
    {"domain","tier","note"} to ``state.meta["hn_opinions"]``, emit a dashboard event,
    and LOG.info. It is a complete no-op unless BOTH HUMAN_NATURE_ENABLED and
    HN_OPINIONS_BEHAVIOR are True, is best-effort (never raises), and is ADVISORY ONLY:
    it never rejects/holds the plan, removes/skips subtasks, or alters control flow.
    Returns the list of surfaced advisories (empty when disabled or nothing surfaced)."""
    if not (config.HUMAN_NATURE_ENABLED and config.HN_OPINIONS_BEHAVIOR):
        return []
    surfaced: list[dict] = []
    try:
        from human_nature import opinions

        for subtask in _subtasks(state):
            domain = _subtaskDomain(state, subtask)
            conviction = _convictionFor(state, domain)
            tier = opinions.tier(conviction, domain)
            if tier != "hard":
                continue
            note = f"strong reservation on {domain} (conviction {conviction:.2f})"
            surfaced.append({"domain": domain, "tier": tier, "note": note})
        if surfaced:
            _meta(state).setdefault("hn_opinions", []).extend(surfaced)
            LOG.info("human-nature opinion advisory: %s", surfaced)
            if dashboard is not None:
                with best_effort("human_nature.opinion_surface", log=LOG):
                    for adv in surfaced:
                        dashboard.event(f"opinion -- strong reservation on {adv['domain']}")
    except Exception:  # noqa: BLE001
        LOG.debug("opinionAdvisory failed (ignored)", exc_info=True)
        return []
    return surfaced


def opinionVote(state: Any, dashboard: Any = None) -> "list[dict]":
    """Earned-authority VOTE coupling on the plan gate. For each planned subtask, resolve
    the psyche's earned authority tier for its domain via the shared 5-cap resolver
    (``authority_gate.resolveTier``); when the tier reaches "vote" or higher (vote/hold/
    veto), cast a weighted advisory VOTE -- append {"domain","tier","weight","flag":True}
    to ``state.meta["hn_votes"]`` and surface a dashboard receipt. It only FLAGS/down-ranks
    a subtask; it NEVER removes, skips, or reorders one, and NEVER alters control flow.
    Best-effort + gated: [] (no-op) unless BOTH HUMAN_NATURE_ENABLED and HN_PLAN_AUTHORITY
    are True. Never raises. Returns the list of cast votes (empty when disabled, nothing
    reached "vote", or an error occurred)."""
    if not (config.HUMAN_NATURE_ENABLED and config.HN_PLAN_AUTHORITY):
        return []
    votes: list[dict] = []
    try:
        from memory.conviction_ledger import track_record

        from .authority_gate import resolveTier

        for subtask in _subtasks(state):
            domain = _subtaskDomain(state, subtask)
            conviction = _convictionFor(state, domain)
            track = track_record(_OPINION_JUDGMENT_TYPE, str(domain)) or {}
            tier = resolveTier("opinion", domain, conviction, track, action="advise")
            if tier not in ("vote", "hold", "veto"):
                continue
            weight = conviction
            votes.append({"domain": domain, "tier": tier, "weight": weight, "flag": True})
        if votes:
            _meta(state).setdefault("hn_votes", []).extend(votes)
            LOG.info("human-nature opinion vote: %s", votes)
            if dashboard is not None:
                with best_effort("human_nature.vote_surface", log=LOG):
                    for v in votes:
                        dashboard.event(f"vote -- {v['tier']} on {v['domain']} (weight {v['weight']:.2f})")
    except Exception:  # noqa: BLE001
        LOG.debug("opinionVote failed (ignored)", exc_info=True)
        return []
    return votes
