"""Shared earned-authority resolver for later human_nature couplings.

Thin, no-op-safe wrapper over the pure ``human_nature.authority`` /
``operator_authority`` 5-cap min ladder. Later couplings call ``resolveTier`` to
learn how much authority a faculty has earned for an action before acting on it.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  resolveTier(faculty: str, domain: str, conviction: float, track: dict, action: str='advise', charter: dict | None=None) -> str  -- Resolve the effective earned-authority tier via the 5-cap min
DEPENDS-ON: human_nature
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/orchestration/test_authority_gate.py
"""
from __future__ import annotations

from human_nature import authority, operator_authority


def resolveTier(faculty: str, domain: str, conviction: float, track: dict, action: str = "advise",
                charter: dict | None = None) -> str:
    """Resolve the effective earned-authority tier via the 5-cap min. Best-effort: returns
    'cosmetic' on any error. No-op-safe."""
    try:
        return authority.resolve(
            conviction, track or {},
            operator_authority.domain_ceiling(domain),
            operator_authority.operator_ceiling(faculty, domain, charter),
            operator_authority.safety_ceiling(domain),
            operator_authority.verifier_invariance_ceiling(action),
        )
    except Exception:
        return "cosmetic"
