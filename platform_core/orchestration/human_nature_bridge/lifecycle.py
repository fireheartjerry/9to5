"""Run-boundary lifecycle hooks: preamble self-state init + teardown appraisal/AB.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  runPreambleHooks(state: Any) -> None  -- Hook 1: lazily initialise self_state at run start
  runTeardownHooks(orch: Any, state: Any) -> None  -- Hook 6 (A/B recording) always fires
DEPENDS-ON: config, human_nature.ab_harness, human_nature.continuity, human_nature.integration, human_nature.psyche_runtime, human_nature.psyche_store, memory.experience_solutions, platform_core.core.best_effort, platform_core.orchestration.time_utils
SIDE-EFFECTS: writes continuity letters + ab_runs.db rows; mutates state.meta when enabled
RUN/TEST: python -m pytest tests/platform/test_lifecycle.py
"""
from __future__ import annotations

from typing import Any

import config
from platform_core.core.best_effort import best_effort

from ._common import LOG, _meta


def _projectKey() -> str:
    """Stable per-project key for the cross-run psyche store."""
    root = getattr(config, "PROJECT_ROOT", None)
    try:
        import os

        return os.path.basename(str(root).rstrip("/\\")) or "project"
    except Exception:  # noqa: BLE001
        return "project"


def _loadPersistedPsyche(state: Any) -> None:
    """Load persisted mood/drives/personality/scars into meta['self_state'] (best-effort)."""
    if not config.HN_MOOD_PERSIST:
        return
    from human_nature import psyche_store, psyche_runtime

    store = psyche_store.open_store()
    try:
        saved = psyche_store.load_psyche(store, _projectKey())
    finally:
        psyche_store.close_store(store)
    meta = _meta(state)
    ss = meta.get("self_state") or {}
    for key in ("mood", "drives", "personality_ref", "affect_manifold", "scars_ref"):
        if saved.get(key) is not None:
            ss[key] = saved[key]
    psyche_runtime.ensure_psyche(ss)
    meta["self_state"] = ss
    meta.setdefault("hn_event_log", [])


def runPreambleHooks(state: Any) -> None:
    """Hook 1: lazily initialise self_state at run start. No-op when disabled."""
    if not config.HUMAN_NATURE_ENABLED:
        return
    with best_effort("human_nature.preamble", log=LOG):
        from human_nature import integration

        integration.ensure_self_state(state)
    with best_effort("human_nature.persist_load", log=LOG):
        _loadPersistedPsyche(state)


def _scoredJudgments(state: Any) -> list:
    """Build {"domain": str, "correct": bool} from this run's verified subtasks."""
    out = []
    for s in state.subtasks:
        vr = s.get("verify_result") or {}
        if vr:
            out.append({"domain": (s.get("title") or "")[:60], "correct": bool(vr.get("passed"))})
    return out


def _runEvents(state: Any) -> list:
    """Build appraisal events (outcome/agency/novelty) from this run's subtask outcomes."""
    events = []
    for s in state.subtasks:
        if s.get("status") not in ("done", "failed"):
            continue
        # agency is a float in [0,1] (appraisal coerces it via float()); these are the run's
        # OWN subtask outcomes, so self-agency is full (1.0). NOT the string "self" -- that
        # raised ValueError: could not convert string to float: 'self' in the appraisal path.
        events.append(
            {"outcome": "success" if s["status"] == "done" else "failure", "agency": 1.0, "novelty": 0.0}
        )
    return events


def _abMetrics(state: Any) -> dict:
    """test_pass (fraction of verified subtasks that passed) + time_to_green (run elapsed)."""
    from platform_core.orchestration.time_utils import _elapsedSince

    verified = [s.get("verify_result") for s in state.subtasks if s.get("verify_result")]
    test_pass = (sum(1 for v in verified if v.get("passed")) / len(verified)) if verified else 0.0
    meta = _meta(state)
    elapsed = _elapsedSince(meta.get("started_at")) if meta.get("started_at") else 0.0
    return {"test_pass": test_pass, "time_to_green": elapsed}


def runTeardownHooks(orch: Any, state: Any) -> None:
    """Hook 6 (A/B recording) always fires -- both arms need data for comparison.
    Hooks 3/5 (appraisal, consolidation, continuity letter) are gated behind
    HUMAN_NATURE_ENABLED and no-op otherwise. Every step is best-effort: a failure
    here must never fail run teardown."""
    arm = "on" if config.HUMAN_NATURE_ENABLED else "off"
    with best_effort("human_nature.ab_record", log=LOG):
        from human_nature.ab_harness import record_run

        record_run(run_id=state.task_id, arm=arm, metrics=_abMetrics(state))
    if not config.HUMAN_NATURE_ENABLED:
        return
    from human_nature import integration

    with best_effort("human_nature.observe", log=LOG):
        integration.observe_run_events(state, _runEvents(state))
    reflections: list = []
    with best_effort("human_nature.fetch_reflections", log=LOG):
        from memory.experience_solutions import fetch_reflections

        reflections = [
            r.get("text", "") for r in (fetch_reflections(trusted_only=False) or []) if r.get("text")
        ][:10]
    with best_effort("human_nature.consolidation", log=LOG):
        chat = getattr(orch, "_ollamaChat", None)
        integration.at_teardown(state, _scoredJudgments(state), reflections, chat=chat)
    with best_effort("human_nature.continuity", log=LOG):
        from human_nature.continuity import write_letter

        meta = _meta(state)
        self_state = meta.get("self_state") or {}
        write_letter(
            state.task_id,
            body_state={
                "competence": self_state.get("competence"),
                "affect": self_state.get("affect"),
            },
        )
    with best_effort("human_nature.persist_save", log=LOG):
        _integrateAndPersist(state)


def _integrateAndPersist(state: Any) -> None:
    """Teardown: fold run outcomes into mood/drives, then checkpoint the psyche (best-effort)."""
    if not config.HN_MOOD_PERSIST:
        return
    from human_nature import psyche_runtime, psyche_store

    meta = _meta(state)
    ss = meta.get("self_state") or {}
    metrics = _abMetrics(state)
    test_pass = float(metrics.get("test_pass", 0.0))
    run_valence = max(-1.0, min(1.0, test_pass * 2.0 - 1.0))
    features = {"verified_success": test_pass >= 0.5, "progress": test_pass}
    psyche_runtime.integrate_outcome(ss, run_valence, 0.0, features)
    meta["self_state"] = ss
    store = psyche_store.open_store()
    try:
        psyche_store.save_psyche(
            store,
            _projectKey(),
            {k: ss.get(k) for k in ("mood", "drives", "personality_ref", "affect_manifold", "scars_ref")},
        )
    finally:
        psyche_store.close_store(store)
