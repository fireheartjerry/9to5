"""Society coupling: internal faculty dissonance triggers a heterogeneous debate.

Reads the psyche's momentary opinion/intuition/instinct signals plus the self-model's
calibration from ``state.meta``, scores DISSONANCE via ``human_nature.conflict``, and
routes it. Only on a "debate" route, with rate-limit budget remaining, does it call
``coordinator.resolveContested`` (best-effort, defensive ``getattr`` -- never a hard
import/attribute dependency on ``society.coordinator``) to spawn an OPPOSING critic
lens alongside the incumbent verdict, per
docs/superpowers/specs/2026-07-06-human-nature-psyche-v2-design.md §6.5.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  maybeDebate(state: Any, coordinator: Any=None, dashboard: Any=None) -> 'dict | None'  -- If the psyche's faculties disagree strongly (high dissonance) and debate budget
DEPENDS-ON: config, human_nature.conflict, platform_core.core.best_effort
SIDE-EFFECTS: mutates state.meta["hn_debate"] when enabled; may invoke coordinator.resolveContested
RUN/TEST: python -m pytest tests/orchestration/test_bridge_society.py tests/orchestration/test_society_batch.py tests/orchestration/test_society_blackboard.py tests/orchestration/test_society_config.py tests/orchestration/test_society_contracts.py tests/orchestration/test_society_coordinator.py tests/orchestration/test_society_debate.py tests/orchestration/test_society_off_invariance.py tests/orchestration/test_society_roles.py tests/orchestration/test_society_worker.py
"""
from __future__ import annotations

from typing import Any

import config
from platform_core.core.best_effort import best_effort

from ._common import LOG, _meta

# The spawned opposing lens for a debate: a heterogeneous critic role, never a clone
# of the incumbent (homogeneous debate collapses into conformity -- see spec §6.5/§12).
_OPPOSING_ROLE = "skeptic"
_OPPOSING_LENS = "risk"
_INCUMBENT_ROLE = "incumbent"

_DEFAULT_CALIBRATION = 0.7


def _calibration(meta: dict) -> float:
    """Best-effort self-model calibration in [0,1] from meta['self_state']['competence'].

    A scalar competence is used directly; a per-domain dict is averaged; anything
    missing or malformed falls back to the neutral default."""
    try:
        self_state = meta.get("self_state")
        competence = self_state.get("competence") if isinstance(self_state, dict) else None
        if isinstance(competence, dict) and competence:
            vals = [float(v) for v in competence.values() if isinstance(v, (int, float))]
            return sum(vals) / len(vals) if vals else _DEFAULT_CALIBRATION
        if isinstance(competence, (int, float)):
            return float(competence)
    except Exception:  # noqa: BLE001
        return _DEFAULT_CALIBRATION
    return _DEFAULT_CALIBRATION


def _contestedSubtaskId(state: Any) -> str:
    """Best-effort id of the subtask under dissonance: the current in-flight subtask
    when a real TaskState is available, else a meta-carried hint, else a placeholder."""
    subtasks = getattr(state, "subtasks", None) or []
    for st in subtasks:
        if isinstance(st, dict) and st.get("status") not in ("done", "failed"):
            return st.get("subtask_id", "unknown")
    if subtasks and isinstance(subtasks[-1], dict):
        return subtasks[-1].get("subtask_id", "unknown")
    try:
        return str(_meta(state).get("current_subtask_id", "unknown"))
    except Exception:  # noqa: BLE001
        return "unknown"


def _spawnOpposingMessages(subtask_id: str) -> list:
    """A minimal 2-role, heterogeneous message roster for Coordinator.resolveContested:
    the incumbent verdict plus a spawned opposing critic lens on the same subtask."""
    return [
        {"subtask_id": subtask_id, "role": _INCUMBENT_ROLE, "ok": True},
        {"subtask_id": subtask_id, "role": _OPPOSING_ROLE, "lens": _OPPOSING_LENS, "ok": False},
    ]


def _sameDebateCheck(existing: Any, record: dict) -> bool:
    if not isinstance(existing, dict):
        return False
    try:
        same_signal = float(existing.get("dissonance", -1.0)) == float(record.get("dissonance", -2.0))
        if same_signal and existing.get("fired"):
            return True
        return (
            same_signal and existing.get("route") == record.get("route")
        )
    except Exception:  # noqa: BLE001
        return False


def _debateRecords(meta: dict) -> list:
    """Return the mutable debate-record list, normalizing older/scrambled shapes."""
    existing = meta.get("hn_debate", [])
    if isinstance(existing, list):
        records = [rec for rec in existing if isinstance(rec, dict)]
    elif isinstance(existing, dict):
        records = [existing]
    else:
        records = []
    meta["hn_debate"] = records
    return records


def maybeDebate(state: Any, coordinator: Any = None, dashboard: Any = None) -> "dict | None":
    """If the psyche's faculties disagree strongly (high dissonance) and debate budget
    remains, trigger a heterogeneous society debate via ``coordinator.resolveContested``
    (best-effort), spawning an OPPOSING critic lens. Records
    {"dissonance","route","fired"} to state.meta["hn_debate"] and returns it. Best-effort
    + gated + RATE-LIMITED (config.HN_DEBATE_RATE_LIMIT per run): a complete no-op (None)
    unless BOTH config.HUMAN_NATURE_ENABLED and config.HN_SOCIETY_TRIGGER are True. Never
    raises. Never reads or alters a verifier verdict -- resolveContested is advisory-only
    downstream."""
    if not (config.HUMAN_NATURE_ENABLED and config.HN_SOCIETY_TRIGGER):
        return None
    try:
        meta = _meta(state)
        opinion = float(meta.get("hn_opinion_signal", 0.0))
        intuition = float(meta.get("hn_intuition_signal", 0.0))
        instinct = float(meta.get("hn_instinct_signal", 0.0))
        calibration = _calibration(meta)

        from human_nature import conflict

        dissonance = conflict.dissonance(opinion, intuition, instinct, calibration)
        checks = _debateRecords(meta)
        fired_count = sum(1 for rec in checks if rec.get("fired"))
        budget = max(0, config.HN_DEBATE_RATE_LIMIT - fired_count)
        route = conflict.route(dissonance, {"debate": budget, "allow_replan": False})

        fired = False
        if route == "debate" and coordinator is not None and budget > 0:
            resolve = getattr(coordinator, "resolveContested", None)
            if callable(resolve):
                with best_effort("human_nature.society_debate", log=LOG):
                    sid = _contestedSubtaskId(state)
                    resolve(_spawnOpposingMessages(sid))
                    fired = True
                if fired and dashboard is not None:
                    with best_effort("human_nature.society_debate_surface", log=LOG):
                        dashboard.event(f"society debate — dissonance {dissonance:.2f}")

        record = {"dissonance": dissonance, "route": route, "fired": fired}
        for idx, existing in enumerate(checks):
            if _sameDebateCheck(existing, record):
                if fired and not existing.get("fired"):
                    checks[idx] = record
                else:
                    record = existing
                break
        else:
            checks.append(record)
        LOG.info("human-nature society debate check: %s", record)
        return record
    except Exception:  # noqa: BLE001
        LOG.debug("maybeDebate failed (ignored)", exc_info=True)
        return None
