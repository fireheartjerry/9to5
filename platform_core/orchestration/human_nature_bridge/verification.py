"""Verify-deepen coupling: ADDITIVE-ONLY request surface for extra verification.

Composes the shared 5-cap ``resolveTier`` for an additive-only ``"deepen_verification"``
action. When the psyche's earned authority for that action reaches the "hold" (or
"veto") tier, this appends an advisory deepen REQUEST to
``state.meta["hn_verify_deepen"]`` -- capped at ``config.HN_MAX_VERIFY_DEEPEN`` -- and
surfaces a dashboard receipt. It NEVER reads or mutates a verifier verdict/status; the
verifier alone owns verification status. This coupling only ever *asks* for more.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  requestDeepen(state: Any, reason: str='', conviction: float=0.0, dashboard: Any=None) -> int  -- ADDITIVE-ONLY: if the psyche's earned authority for an additive
DEPENDS-ON: config, platform_core.core.best_effort, platform_core.orchestration.human_nature_bridge._common, platform_core.orchestration.human_nature_bridge.authority_gate
SIDE-EFFECTS: mutates state.meta["hn_verify_deepen"] when enabled and authority clears "hold"
RUN/TEST: python -m pytest tests/review/test_verification.py
"""
from __future__ import annotations

from typing import Any

import config
from platform_core.core.best_effort import best_effort

from ._common import LOG, _meta
from .authority_gate import resolveTier

# Tiers that grant the additive "deepen_verification" request (never higher than
# what verifier_invariance_ceiling permits for an additive action: capped at "hold").
_GRANTING_TIERS = ("hold", "veto")


def _sameRequest(rec: Any, reason: str, conviction: float) -> bool:
    if not isinstance(rec, dict):
        return False
    try:
        return rec.get("reason") == reason and float(rec.get("conviction", 0.0)) == float(conviction)
    except Exception:  # noqa: BLE001
        return False


def requestDeepen(state: Any, reason: str = "", conviction: float = 0.0, dashboard: Any = None) -> int:
    """ADDITIVE-ONLY: if the psyche's earned authority for an additive
    'deepen_verification' action reaches the 'hold' tier, append a deepen request to
    state.meta['hn_verify_deepen'] (capped at config.HN_MAX_VERIFY_DEEPEN). Returns the
    number of deepen requests now recorded. Best-effort + gated: returns 0 (no-op)
    unless config.HUMAN_NATURE_ENABLED and config.HN_VERIFY_DEEPEN. Never raises. NEVER
    reads or mutates any verifier verdict/status -- it only appends an advisory
    REQUEST."""
    if not (config.HUMAN_NATURE_ENABLED and config.HN_VERIFY_DEEPEN):
        return 0
    try:
        meta = _meta(state)
        domain = meta.get("domain", "unknown")
        tier = resolveTier("instinct", domain, conviction, {}, action="deepen_verification")
        deepens = meta.get("hn_verify_deepen", [])
        if tier not in _GRANTING_TIERS:
            return len(deepens)
        if any(_sameRequest(rec, reason, conviction) for rec in deepens):
            return len(deepens)
        max_deepen = int(getattr(config, "HN_MAX_VERIFY_DEEPEN", 2))
        if len(deepens) >= max_deepen:
            return len(deepens)
        deepens = meta.setdefault("hn_verify_deepen", [])
        deepens.append({"reason": reason, "conviction": conviction})
        LOG.info("human-nature verify-deepen requested (%s): %s", tier, reason)
        if dashboard is not None:
            with best_effort("human_nature.verify_deepen_surface", log=LOG):
                dashboard.event(f"verify-deepen -- {reason}" if reason else "verify-deepen requested")
        return len(deepens)
    except Exception:  # noqa: BLE001
        LOG.debug("requestDeepen failed (ignored)", exc_info=True)
        return 0
