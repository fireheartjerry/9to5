"""Inventor engine coupling -- psyche-derived exploration/QD-budget advisory knobs.

Advisory-only bridge between the human-nature psyche (drives + personality) and the
inventor engine's exploration knobs. The inventor package is DARK in most checkouts
(uncommitted / flagged off), so this coupling is a clean, import-safe no-op unless ALL
of HUMAN_NATURE_ENABLED, HN_INVENTOR_COUPLING, and INVENTOR_MODE_ENABLED are True AND
the ``inventor`` package is importable. It never raises ImportError and never mutates
anything beyond recording proposed knob values to ``state.meta["hn_inventor"]``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  inventorCouple(state: Any, dashboard: Any=None) -> 'dict | None'  -- When the inventor engine is active (config.INVENTOR_MODE_ENABLED and
DEPENDS-ON: config, human_nature.drives, human_nature.personality, platform_core.core.best_effort
SIDE-EFFECTS: mutates state.meta["hn_inventor"] when active
RUN/TEST: python -m pytest tests/orchestration/test_bridge_inventor.py tests/orchestration/test_inventor_e2e.py tests/platform/test_inventor_flags_config.py
"""
from __future__ import annotations

from typing import Any

import config
from platform_core.core.best_effort import best_effort

from ._common import LOG, _meta

_BASE_EXPLORATION_BUDGET = 10
_BASE_QD_BREADTH = 4
_DEFAULT_RISK_BAND = 0.5


def _selfState(state: Any) -> dict:
    """Best-effort self_state dict; {} when absent/malformed."""
    try:
        return dict(_meta(state).get("self_state") or {})
    except Exception:  # noqa: BLE001
        return {}


def _curiosityPressure(self_state: dict) -> float:
    """Curiosity drive pressure in [0,1]; 0.0 (no extra exploration push) when unknown."""
    try:
        from human_nature import drives

        drive_state = dict(self_state.get("drives") or {})
        pressures = drives.pressure(drive_state)
        return max(0.0, min(1.0, float(pressures.get("curiosity", 0.0))))
    except Exception:  # noqa: BLE001
        return 0.0


def _boldness(self_state: dict) -> float:
    """Personality risk-tolerance in [0,1]; a neutral default when personality is absent."""
    try:
        personality_ref = self_state.get("personality_ref")
        if not personality_ref:
            return _DEFAULT_RISK_BAND
        from human_nature import personality

        return max(0.0, min(1.0, float(personality.risk_band(personality_ref))))
    except Exception:  # noqa: BLE001
        return _DEFAULT_RISK_BAND


def _isCoupled() -> bool:
    """Both HN and the inventor coupling knob must be on before we even try importing."""
    return bool(
        getattr(config, "HUMAN_NATURE_ENABLED", False)
        and getattr(config, "HN_INVENTOR_COUPLING", False)
        and getattr(config, "INVENTOR_MODE_ENABLED", False)
    )


def inventorCouple(state: Any, dashboard: Any = None) -> "dict | None":
    """When the inventor engine is active (config.INVENTOR_MODE_ENABLED and
    config.HN_INVENTOR_COUPLING and the inventor package is importable), derive
    exploration/QD-budget + risk-band modulation from the psyche's drives
    (curiosity/boredom) and personality (boldness), record the proposed knob
    values to state.meta['hn_inventor'], and return them. Pure ADVISORY: it
    records proposed knob values; it does NOT import-fail or raise when the
    inventor is absent (returns None). Best-effort + gated.
    """
    if not _isCoupled():
        return None
    try:
        import inventor  # noqa: F401  -- presence check only; knobs are advisory, not applied here
    except ImportError:
        return None
    try:
        self_state = _selfState(state)
        curiosity = _curiosityPressure(self_state)
        boldness = _boldness(self_state)
        knobs = {
            "exploration_budget": round(_BASE_EXPLORATION_BUDGET * (1.0 + curiosity)),
            "risk_band": round(boldness, 4),
            "qd_breadth": max(1, round(_BASE_QD_BREADTH * (1.0 + boldness))),
        }
        _meta(state).setdefault("hn_inventor", []).append(knobs)
        LOG.info("human-nature inventor coupling: %s", knobs)
        if dashboard is not None:
            with best_effort("human_nature.inventor_surface", log=LOG):
                dashboard.event(
                    f"inventor -- exploration_budget={knobs['exploration_budget']} "
                    f"qd_breadth={knobs['qd_breadth']}"
                )
        return knobs
    except Exception:  # noqa: BLE001
        LOG.debug("inventorCouple failed (ignored)", exc_info=True)
        return None
