"""Per-attempt couplings: retrieval-grounded signals + intuition effort bias.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  attemptSignals(state: Any, subtask: dict) -> dict  -- Assemble REAL momentary confidence signals for preActRouting
  preActRouting(state: Any, domain: str, signals: 'dict | None'=None) -> str  -- Hook 2: thin wrapper over integration.route_pre_act
  biasEffort(current_effort: str, routing: str) -> str  -- Pure ADVISORY bias: drop effort one tier on "fast"
  biasEffortTiered(current_effort: str, routing: str, tier: str) -> str  -- Soft-tier bidirectional effort bias, gated on HN_EXEC_AUTHORITY
DEPENDS-ON: config, human_nature.integration, memory.retrieval
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/orchestration/test_human_nature_bridge.py
"""
from __future__ import annotations

from typing import Any

import config

from ._common import LOG, _meta

# --- Hook 2: intuition dual-process routing -> advisory effort bias --------------
# Ordered effort ladder (lowest -> highest); mirrors config.MODEL_BY_EFFORT routing.
# "medium" is a display alias of "default" and folds onto it before laddering.
_EFFORT_LADDER: tuple[str, ...] = ("low", "default", "high", "xhigh", "ultracode")
_EFFORT_ALIASES: dict[str, str] = {"medium": "default"}
# Earned-authority tiers that clear the "soft" floor required to move effort UP as well
# as down (see authority_gate.resolveTier / docs/superpowers/specs/2026-07-06-human-
# nature-psyche-v2-design.md §4.1). "cosmetic" (and anything unrecognised) is surface-only.
_AUTHORIZED_TIERS: frozenset[str] = frozenset({"soft", "vote", "hold", "veto"})


def _retrievalSignals(goal: str, title: str) -> dict:
    """Best-effort {similarity, p_true} from the SIE retrieval ledger. ``similarity`` is
    the top cosine score to a past SUCCESSFUL subtask (clamped to [0,1]); ``p_true`` is the
    pass fraction among near neighbours (successes vs. similar failures). Empty when nothing
    is retrieved -- no fabricated confidence. Never raises."""
    from memory import retrieval

    successes = list(retrieval.retrieve(goal, title) or [])
    if not successes:
        return {}
    out: dict = {}
    top = max((float(r.get("score") or 0.0) for r in successes), default=0.0)
    out["similarity"] = max(0.0, min(1.0, top))
    try:
        failures = list(retrieval.retrieve_failures(goal, title) or [])
    except Exception:  # noqa: BLE001 -- the failure lane is optional; successes still count
        failures = []
    n_ok, n_bad = len(successes), len(failures)
    if n_ok + n_bad:
        out["p_true"] = max(0.0, min(1.0, n_ok / (n_ok + n_bad)))
    return out


def attemptSignals(state: Any, subtask: dict) -> dict:
    """Assemble REAL momentary confidence signals for ``preActRouting`` from data that
    genuinely exists: the SIE retrieval ledger (``memory.retrieval``) and any numeric
    ``confidence`` the brain already put on the subtask. Returns numeric keys intuition
    fuses -- ``similarity`` (top retrieval cosine to a past success, clamped [0,1]) and
    ``p_true`` (near-neighbour pass fraction, or the brain's confidence when retrieval is
    cold). NEVER fabricates confidence: with no real source it returns {} so intuition
    honestly stays on the "deliberate" default. Gated (no-op {} when HN off), best-effort
    (any error -> {}), never raises."""
    # Gate on the shortcut too: when it's off, intuition.route can only return "deliberate", so
    # the (local-Ollama) retrieval embeds here would be pure hot-path waste that can't change routing.
    if not (config.HUMAN_NATURE_ENABLED and config.HN_INTUITION_SHORTCUT):
        return {}
    try:
        goal = _meta(state).get("goal_elaborated") or _meta(state).get("goal_raw") or ""
        title = str(subtask.get("title") or "")
        signals = _retrievalSignals(str(goal), title)
        # Brain-authored confidence: only a source when retrieval didn't already give p_true.
        if "p_true" not in signals:
            conf = subtask.get("confidence")
            if isinstance(conf, (int, float)) and not isinstance(conf, bool):
                signals["p_true"] = max(0.0, min(1.0, float(conf)))
        return signals
    except Exception:  # noqa: BLE001 -- signal assembly must never break an attempt
        LOG.debug("attemptSignals failed (ignored)", exc_info=True)
        return {}


def preActRouting(state: Any, domain: str, signals: "dict | None" = None) -> str:
    """Hook 2: best-effort thin wrapper over ``integration.route_pre_act``. Returns
    "fast" or "deliberate". No-op ("deliberate") when HUMAN_NATURE_ENABLED is off
    (route_pre_act itself gates), and "deliberate" on ANY error. Never raises."""
    if not config.HUMAN_NATURE_ENABLED:
        return "deliberate"
    try:
        from human_nature import integration

        return integration.route_pre_act(state, str(domain), dict(signals or {}))
    except Exception:  # noqa: BLE001
        LOG.debug("preActRouting failed (ignored)", exc_info=True)
        return "deliberate"


def biasEffort(current_effort: str, routing: str) -> str:
    """Pure ADVISORY bias: when *routing* == "fast", drop *current_effort* ONE tier on
    the effort ladder (clamped at the lowest tier); otherwise return it unchanged. It
    can ONLY lower effort, never raise it, and an off-ladder effort is passed through
    untouched. No side effects, never raises."""
    if routing != "fast":
        return current_effort
    key = _EFFORT_ALIASES.get(str(current_effort).lower(), str(current_effort).lower())
    try:
        idx = _EFFORT_LADDER.index(key)
    except ValueError:
        return current_effort  # unknown tier: safe passthrough
    return _EFFORT_LADDER[max(0, idx - 1)]


def biasEffortTiered(current_effort: str, routing: str, tier: str) -> str:
    """Soft-tier BIDIRECTIONAL effort bias, gated on ``config.HN_EXEC_AUTHORITY``. When the
    earned authority *tier* is at least "soft" (soft/vote/hold/veto), this may move
    *current_effort* ONE tier on ``_EFFORT_LADDER`` in EITHER direction: ``routing ==
    "fast"`` lowers by one (identical to ``biasEffort``), ``routing == "deliberate"``
    RAISES by one. Clamped at the ladder ends. Below "soft" tier ("cosmetic" or unknown),
    or when ``HN_EXEC_AUTHORITY`` is off, returns *current_effort* UNCHANGED. Off-ladder
    effort passes through untouched. Pure, no side effects, never raises."""
    if not getattr(config, "HN_EXEC_AUTHORITY", False):
        return current_effort
    if str(tier).lower() not in _AUTHORIZED_TIERS:
        return current_effort
    key = _EFFORT_ALIASES.get(str(current_effort).lower(), str(current_effort).lower())
    try:
        idx = _EFFORT_LADDER.index(key)
    except ValueError:
        return current_effort  # unknown tier: safe passthrough
    if routing == "fast":
        return _EFFORT_LADDER[max(0, idx - 1)]
    if routing == "deliberate":
        return _EFFORT_LADDER[min(len(_EFFORT_LADDER) - 1, idx + 1)]
    return current_effort
