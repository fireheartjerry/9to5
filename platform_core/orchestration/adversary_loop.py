"""Adversary remediation loop -- free function extracted from OrchestratorExecuteMixin.

Holds the bounded post-pass remediation loop (feed reviewer concerns back to the executor, re-verify
under a snapshot/restore guard, re-review with the second brain) as a free function taking the
Orchestrator as ``orch``. Extracted so execute_mixin.py stays under the size threshold; the mixin keeps
a thin ``_remediate`` delegate so callers are unchanged.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  runReview(orch, state, subtask: dict, combined: str, final: str, exec_cwd: str, bus, dashboard, heartbeat_ordinal: int, attempt: int, architect_doc: str)  -- Trigger adversary review if warranted; run remediation if challenged
  remediate(orch, state, subtask: dict, architect_doc: str, exec_cwd: str, concerns: list, cancel_check=None) -> dict  -- Bounded remediation LOOP (up to ADVERSARY_REMEDIATION_MAX_ATTEMPTS) on a subtask that
DEPENDS-ON: agents.adversary, agents.second_brain, agents.verifier, config, notifications.cast, notifications.discord_bot, platform_core.runtime
SIDE-EFFECTS: spawns Claude subprocesses; snapshots/restores the git tree; mutates state verify + notifications
RUN/TEST: python -m pytest tests/orchestration/test_adversary.py
"""
from __future__ import annotations

import config
from agents import adversary, second_brain, verifier
from notifications import cast
from notifications import discord_bot as discord

LOG = config.getLogger("orchestrator")


def runReview(orch, state, subtask: dict, combined: str, final: str, exec_cwd: str,
              bus, dashboard, heartbeat_ordinal: int, attempt: int,
              architect_doc: str):
    """Trigger adversary review if warranted; run remediation if challenged. Returns (verdict, stub).

    Free function (takes the Orchestrator as ``orch``) extracted from
    OrchestratorExecuteMixin so execute_mixin.py stays under the size threshold;
    the mixin keeps a thin ``_runAdversaryReview`` delegate so behavior is unchanged."""
    sid = subtask["subtask_id"]
    triggered, reason = adversary.shouldTrigger(combined, heartbeat_ordinal, attempt)
    if not triggered:
        return None, False
    rv = orch._review(subtask["title"], reason, combined,
                      ollama_chat=orch._ollamaChat,
                      goal=state.meta.get("goal_elaborated") or state.meta.get("goal_raw", ""))
    _adv_verdict = rv.get("verdict")
    _adv_stub = rv.get("stub", False)
    discord.sendEmbed(discord.adversaryTriggeredEmbed(subtask["title"], reason, rv.get("verdict")))
    cast.speak("adversary", f"⚔️ Reviewing `{sid}` ({subtask['title']}) → "
               f"**{discord.formatVerdict(rv.get('verdict'))}**.")
    cast.duel(subtask["title"], rv.get("verdict"))   # VS-card on a CHALLENGE (T8)
    # Proactive narration + a rare Moment when the adversary catches something critical.
    orch._narrate(f"⚠️ Adversary flagged something in {sid}. Remediating.")
    if rv.get("verdict") == "rejected":
        orch._emitMoment(sid, f"⚡ MOMENT — The adversary caught a critical issue in "
                         f"`{sid}` the plan never anticipated.")
    with orch._state_lock:
        state.addNotification("adversary_triggered", f"{sid}: {reason} -> {rv['verdict']}")
        orch.obs.writeNote(state.subtaskReviewNoteRel(sid),
                           orch._reviewNote(subtask, reason, rv, combined))
        state.addAdversaryReview(sid, reason, rv["verdict"],
                                 state.subtaskReviewNoteRel(sid), stub=rv.get("stub", False))
    # TEETH: a challenged verdict on a PASSED subtask earns ONE bounded remediation attempt.
    if (config.ADVERSARY_REMEDIATION_ENABLED and final == "done"
            and rv.get("verdict") == "challenged" and rv.get("concerns")):
        if orch._remediationUnsafe(exec_cwd):
            # Skip ONLY a shared tree under parallelism (a revert would clobber peers).
            LOG.warning("%s: skipping adversary remediation -- shared working tree under "
                        "parallelism>1 (a revert would clobber peer subtasks)", sid)
            with orch._state_lock:
                state.addNotification("adversary_remediation",
                                      f"{sid}: remediation skipped (shared tree, parallel run)")
        else:
            dashboard.update(state, "executing", f"{sid} adversary remediation (1 attempt)")
            orch._remediate(state, subtask, architect_doc, exec_cwd, rv["concerns"],
                            cancel_check=lambda: bus.isAbort() or orch._deadlinePassed(state))
    return _adv_verdict, _adv_stub


def remediate(orch, state, subtask: dict, architect_doc: str, exec_cwd: str,
              concerns: list, cancel_check=None) -> dict:
    """Bounded remediation LOOP (up to ADVERSARY_REMEDIATION_MAX_ATTEMPTS) on a subtask that
    ALREADY passed verification: feed the reviewer's concerns back to the executor, re-verify,
    then re-review with the second brain; stop when it approves (or attempts run out). Each
    attempt is snapshot-guarded -- an edit that breaks the artifact is reverted and the prior
    pass kept, so remediation can only keep or improve. Returns the last verify_result."""
    sid = subtask["subtask_id"]
    goal = orch._goalText(state)
    vres: dict = {}
    attempts = max(1, config.ADVERSARY_REMEDIATION_MAX_ATTEMPTS)
    # The REAL git edit tree to snapshot/restore. For a self-referential run exec_cwd is the
    # gitignored .sc-ctx scratch, but the executor edits the project at work_dir via --add-dir --
    # so snapshotting/restoring exec_cwd was a NO-OP and a broken remediation was never reverted.
    # work_dir IS the real tree for both self-ref (== PROJECT_ROOT) and non-self-ref runs.
    from platform_core.runtime import worktree
    # With worktree isolation, exec_cwd IS this subtask's private tree -> snapshot it so a
    # revert is peer-safe. Otherwise fall back to the shared work_dir (today's behavior).
    repo_tree = exec_cwd if worktree.isIsolated(exec_cwd) else (
        getattr(orch, "_work_dir", None) or exec_cwd)
    for i in range(1, attempts + 1):
        feedback = ("The work PASSED its acceptance check, but an adversarial reviewer raised "
                    "concerns. Address these WITHOUT breaking the passing verification:\n- "
                    + "\n- ".join(concerns))
        snap = orch._gitSnapshot(repo_tree)
        spec = orch.authorInvocationSpec(state, subtask, architect_doc, feedback)
        result = orch._run_claude(spec, work_dir=exec_cwd, task_state=state, subtask=subtask,
                                  cancel_check=cancel_check)
        vres = verifier.runVerification(subtask.get("verify"), exec_cwd, result)
        with orch._state_lock:
            if vres.get("passed"):
                state.recordVerify(sid, vres)   # adopt the still-passing post-remediation evidence
            else:
                orch._gitRestore(repo_tree, snap)   # revert broken edits so disk == kept pass
            state.addNotification(
                "adversary_remediation",
                f"{sid}: remediation {i}/{attempts} "
                f"{'verified' if vres.get('passed') else 'did not verify (reverted, prior pass kept)'}")
        LOG.info("Adversary remediation %d/%d for %s -> %s", i, attempts, sid,
                 "verified" if vres.get("passed") else "reverted (kept prior pass)")
        if not vres.get("passed"):
            break   # a broken attempt was reverted; another try would re-break -- stop
        # Re-review the remediated output: if the second brain is now satisfied, we're done.
        combined = ((result or {}).get("stdout", "") + "\n" + (result or {}).get("stderr", "")) \
            if isinstance(result, dict) else ""
        rv = orch._review(subtask["title"], f"remediation re-review {i}/{attempts}", combined,
                          ollama_chat=orch._ollamaChat, goal=goal)
        if not second_brain.is_blocking(rv):
            break
        concerns = (rv.get("must_fix") or rv.get("concerns") or concerns)[:10]
    return vres
