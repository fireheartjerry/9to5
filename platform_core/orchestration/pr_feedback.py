def _buildFeedbackResult(owner: str, repo: str, pr_number: str, pr_url: str, run_id: str,
                         subtask_id: Optional[str], poll_attempts: int,
                         poll_interval: int) -> dict[str, Any]:
    """Poll CI + review state and assemble the feedback result dict (with ``promote_safe``)."""
    sha = _fetchHeadSHA(owner, repo, pr_number)
    ci: dict[str, Any]
    if sha:
        ci = _pollCIStatus(owner, repo, sha, poll_attempts, poll_interval)
    else:
        LOG.warning("pr_feedback: could not fetch head SHA; CI status unknown")
        ci = {"status": "unknown", "summary": "Could not fetch head commit SHA", "runs": []}

    reviews = _fetchReviews(owner, repo, pr_number)

    ci_passed = ci["status"] == "passed"
    review_blocks = reviews["state"] in _BLOCK_REVIEW_STATES
    promote_safe = ci_passed and not review_blocks

    result: dict[str, Any] = {
        "ok": True,
        "pr_url": pr_url,
        "ci_status": ci["status"],
        "ci_summary": ci["summary"],
        "review_state": reviews["state"],
        "review_feedback": reviews["feedback"],
        "promote_safe": promote_safe,
        "provenance": {
            "origin": "pr_feedback",
            "owner": owner,
            "repo": repo,
            "pr_number": pr_number,
            "head_sha": sha,
            "run_id": run_id,
            "subtask_id": subtask_id,
        },
    }

    if not promote_safe:
        LOG.warning(
            "pr_feedback: promote_safe=False for %s (ci=%s, review=%s)",
            pr_url, ci["status"], reviews["state"],
        )
    return result


def capturePRFeedback(
    pr_url: str,
    run_id: str,
    subtask_id: Optional[str] = None,
    *,
    poll_attempts: int = 6,
    poll_interval: int = 30,
) -> dict[str, Any]:
    """Poll GitHub CI + review state for ``pr_url`` and write the result to the experience ledger.

    Args:
        pr_url:        Full GitHub PR URL (``https://github.com/owner/repo/pull/N``).
        run_id:        9TO5 run ID (used as the ledger key).
        subtask_id:    Optional subtask ID; enables ``record_reflection`` write.
        poll_attempts: How many times to re-poll CI before giving up.
        poll_interval: Seconds between CI polls (applied only when runs are still in-progress).

    Returns a dict with keys:
        ``pr_url``, ``ci_status`` (passed/failed/pending/unknown),
        ``ci_summary``, ``review_state``, ``review_feedback`` (list[str]),
        ``promote_safe`` (bool), ``provenance`` (dict), ``ok`` (bool).

    Never raises — errors degrade to ``{"ok": False, "skipped": True, "reason": "..."}``.
    """
    if not pr_url or not run_id:
        return {"ok": False, "skipped": True, "reason": "pr_url and run_id are required"}

    slug = _parsePRSlug(pr_url)
    if slug is None:
        LOG.warning("pr_feedback: cannot parse PR URL: %s", pr_url)
        return {"ok": False, "skipped": True, "reason": f"unrecognised PR URL: {pr_url}"}

    owner, repo, pr_number = slug
    LOG.info("pr_feedback: capturing feedback for %s/%s#%s", owner, repo, pr_number)

    try:
        result = _buildFeedbackResult(owner, repo, pr_number, pr_url, run_id,
                                      subtask_id, poll_attempts, poll_interval)
        ledger_status = _writeLedger(run_id, subtask_id, pr_url, result)
        result["ledger_pr_outcome_ok"] = ledger_status.get("pr_outcome_ok", False)

        # Caller-level retry: if the PR outcome write failed inside _writeLedger, attempt it
        # again here (max 2 retries) before giving up so a transient DB error doesn't
        # silently drop the outcome record.  We retry only record_pr_outcome — not the
        # full _writeLedger — to avoid duplicating feedback/reflection rows.
        if not result["ledger_pr_outcome_ok"]:
            for _attempt in range(2):
                try:
                    from memory.experience_pr import record_pr_outcome
                    ok = record_pr_outcome(run_id, pr_url, result, subtask_id=subtask_id)
                    if ok:
                        result["ledger_pr_outcome_ok"] = True
                        LOG.info("pr_feedback: record_pr_outcome succeeded on retry %d", _attempt + 1)
                        break
                except Exception as retry_exc:  # noqa: BLE001
                    LOG.warning("pr_feedback: record_pr_outcome retry %d failed: %s", _attempt + 1, retry_exc)

        return result

    except Exception as exc:  # noqa: BLE001
        LOG.warning("pr_feedback: unexpected error (%s); skipping ledger write", exc)
        return {"ok": False, "skipped": True, "reason": f"unexpected error: {exc}"[:300]}


