def _selfTest() -> None:  # noqa: N802  (camelCase per project convention)
    """Run lightweight unit tests that require no network or gh CLI."""
    import sys

    failures: list[str] = []

    def _check(name: str, got: Any, expected: Any) -> None:
        if got != expected:
            failures.append(f"{name}: expected {expected!r}, got {got!r}")

    # --- _parsePRSlug ---
    slug = _parsePRSlug("https://github.com/acme/my-repo/pull/42")
    _check("parsePRSlug owner",  slug and slug[0], "acme")
    _check("parsePRSlug repo",   slug and slug[1], "my-repo")
    _check("parsePRSlug number", slug and slug[2], "42")
    _check("parsePRSlug bad url", _parsePRSlug("https://example.com/no-pr"), None)

    # --- capturePRFeedback: missing args ---
    r = capturePRFeedback("", "run-123")
    _check("capture empty pr_url ok",      r.get("ok"),      False)
    _check("capture empty pr_url skipped", r.get("skipped"), True)

    r2 = capturePRFeedback("https://github.com/a/b/pull/1", "")
    _check("capture empty run_id ok",      r2.get("ok"),      False)
    _check("capture empty run_id skipped", r2.get("skipped"), True)

    # --- capturePRFeedback: bad URL ---
    r3 = capturePRFeedback("https://not-github.com/x", "run-999")
    _check("capture bad url ok",      r3.get("ok"),      False)
    _check("capture bad url skipped", r3.get("skipped"), True)

    # --- _writeLedger: smoke (no real DB path; import may fail gracefully) ---
    dummy_result: dict[str, Any] = {
        "ok": True, "pr_url": "https://github.com/a/b/pull/1",
        "ci_status": "passed", "ci_summary": "ok", "review_state": "none",
        "review_feedback": [], "promote_safe": True,
        "provenance": {"origin": "test"},
    }
    ledger_status = _writeLedger("run-0", None, "https://github.com/a/b/pull/1", dummy_result)
    if not isinstance(ledger_status, dict):
        failures.append(f"_writeLedger return type: expected dict, got {type(ledger_status)}")

    if failures:
        for f in failures:
            print(f"FAIL: {f}", file=sys.stderr)
        sys.exit(1)

    print("pr_feedback self-test: all checks passed")


if __name__ == "__main__":
    if "--test" in sys.argv:
        _selfTest()
    else:
        print("Usage: python pr_feedback.py --test", file=sys.stderr)
        sys.exit(1)
