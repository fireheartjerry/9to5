"""Poll GitHub for CI status + review state after PR creation; write results to experience ledger.

Called by the orchestrator finalization phase (after createPullRequest succeeds) so that:
  * failed CI / change-request reviews feed the learning loop (record_reflection + record_feedback)
  * a ``promote_safe`` flag is returned that callers MUST check before auto-promoting changes

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  capturePRFeedback(pr_url: str, run_id: str, subtask_id: Optional[str]=None, *, poll_attempts: int=6, poll_interval: int=30) -> dict[str, Any]  -- Poll GitHub CI + review state for ``pr_url`` and write the result to the experience led…
DEPENDS-ON: config, memory.experience_pr, platform_core.orchestration.pr_feedback_ledger
SIDE-EFFECTS: writes to experience ledger (record_feedback, record_reflection)
RUN/TEST: python -m pytest tests/test_pr_feedback.py
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import time
from pathlib import Path
from typing import Any, Optional

# Ensure project root is importable when this file is run directly.
_PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

import config
# _writeLedger lives in pr_feedback_ledger (size split); re-exported so callers/tests keep
# ``from platform_core.orchestration.pr_feedback import _writeLedger``.
from platform_core.orchestration.pr_feedback_ledger import _writeLedger  # noqa: F401

LOG = config.getLogger("orchestrator.pr_feedback")

# gh CLI timeout — reuses the project-wide git ceiling
_GH_TIMEOUT = getattr(config, "GIT_TIMEOUT_SECONDS", 120)

# CI conclusions that mean "check suite finished and failed"
_CI_FAIL_CONCLUSIONS = {"failure", "cancelled", "timed_out", "action_required", "stale"}

# Review states that block promotion
_BLOCK_REVIEW_STATES = {"changes_requested"}


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _gh(args: list[str]) -> "tuple[int, str]":
    """Run a ``gh`` sub-command; return (returncode, stdout-or-stderr text)."""
    try:
        r = subprocess.run(
            ["gh", *args],
            capture_output=True, text=True,
            stdin=subprocess.DEVNULL,
            timeout=_GH_TIMEOUT,
        )
        return r.returncode, (r.stdout or r.stderr or "").strip()
    except subprocess.TimeoutExpired:
        return -1, f"gh timed out after {_GH_TIMEOUT}s"
    except FileNotFoundError:
        return -1, "gh CLI not found"
    except Exception as exc:  # noqa: BLE001
        return -1, str(exc)


def _parsePRSlug(pr_url: str) -> "tuple[str, str, str] | None":
    """Extract (owner, repo, pr_number) from a GitHub PR URL.  Returns None if unrecognised."""
    m = re.search(r"github\.com/([^/]+)/([^/]+)/pull/(\d+)", pr_url)
    if not m:
        return None
    return m.group(1), m.group(2), m.group(3)


def _fetchHeadSHA(owner: str, repo: str, pr_number: str) -> "str | None":
    """Fetch the head commit SHA for the PR (needed to query check-runs)."""
    code, out = _gh(["pr", "view", pr_number,
                     "--repo", f"{owner}/{repo}",
                     "--json", "headRefOid",
                     "-q", ".headRefOid"])
    if code != 0 or not out:
        LOG.debug("fetchHeadSHA failed (code=%s): %s", code, out[:200])
        return None
    return out.strip()


def _pollCIStatus(owner: str, repo: str, sha: str,
                  poll_attempts: int, poll_interval: int) -> dict[str, Any]:
    """Poll check-runs until all complete or attempts exhausted.

    Returns::
        {
            "status": "passed" | "failed" | "pending" | "unknown",
            "summary": str,           # human-readable, max 400 chars
            "runs": list[dict],       # raw check-run conclusions
        }
    """
    endpoint = f"repos/{owner}/{repo}/commits/{sha}/check-runs"
    for attempt in range(1, poll_attempts + 1):
        code, out = _gh(["api", endpoint, "--jq", ".check_runs[]|{name,status,conclusion}"])
        if code != 0:
            LOG.debug("check-runs poll %d/%d failed: %s", attempt, poll_attempts, out[:200])
            if attempt < poll_attempts:
                time.sleep(poll_interval)
            continue

        runs: list[dict[str, Any]] = []
        for line in out.splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                runs.append(json.loads(line))
            except json.JSONDecodeError:
                pass

        if not runs:
            if attempt < poll_attempts:
                time.sleep(poll_interval)
            continue

        in_progress = [r for r in runs if r.get("status") not in ("completed",)]
        if in_progress and attempt < poll_attempts:
            LOG.debug("CI poll %d/%d: %d run(s) still in_progress", attempt, poll_attempts, len(in_progress))
            time.sleep(poll_interval)
            continue

        failed = [r for r in runs if r.get("conclusion") in _CI_FAIL_CONCLUSIONS]
        if failed:
            names = ", ".join(r.get("name", "?") for r in failed[:5])
            return {
                "status": "failed",
                "summary": f"CI failed: {names}"[:400],
                "runs": runs,
            }
        pending = [r for r in runs if r.get("status") != "completed"]
        if pending:
            return {
                "status": "pending",
                "summary": f"{len(pending)} check(s) still running after {poll_attempts} poll(s)",
                "runs": runs,
            }
        return {
            "status": "passed",
            "summary": f"All {len(runs)} CI check(s) passed",
            "runs": runs,
        }

    return {"status": "unknown", "summary": "No check-run data retrieved", "runs": []}


def _fetchReviews(owner: str, repo: str, pr_number: str) -> dict[str, Any]:
    """Fetch latest review state per reviewer.

    Returns::
        {
            "state": "approved" | "changes_requested" | "pending" | "none",
            "feedback": list[str],   # non-empty comment bodies (max 3, truncated)
        }
    """
    code, out = _gh(["api",
                      f"repos/{owner}/{repo}/pulls/{pr_number}/reviews",
                      "--jq", ".[].{state,body}"])
    if code != 0 or not out:
        LOG.debug("fetch reviews failed (code=%s): %s", code, out[:200])
        return {"state": "none", "feedback": []}

    states: list[str] = []
    feedback: list[str] = []
    for line in out.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            rv = json.loads(line)
        except json.JSONDecodeError:
            continue
        s = (rv.get("state") or "").lower()
        if s:
            states.append(s)
        body = (rv.get("body") or "").strip()
        if body and len(feedback) < 3:
            feedback.append(body[:300])

    if "changes_requested" in states:
        agg_state = "changes_requested"
    elif states and all(s == "approved" for s in states):
        agg_state = "approved"
    elif states:
        agg_state = "pending"
    else:
        agg_state = "none"

    return {"state": agg_state, "feedback": feedback}


