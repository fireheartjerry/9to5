"""Resume-from-last-step reconcile (Epic 1, unit b).

Replaces the blind in_progress->pending reset with a journal-aware reconcile: a crashed
subtask whose plan signature still matches its journal is kept resumable (the executor
continues the SAME Claude session and is TOLD what is done -- it does not re-run completed
edits, which are already on disk); a changed plan signature safely rerolls the subtask to a
clean attempt. The state store still owns every mutation (via updateSubtask); the journal is
a replay artifact only. Fail-open: any error degrades to today's safe reset.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  planSignature(state) -> str
  resumePlan(state, subtask, steps) -> dict
  reconcileResume(state, db_path=None) -> None
DEPENDS-ON: config, memory.experience, state.task
SIDE-EFFECTS: mutates subtask session/status via state.updateSubtask
RUN/TEST: python -m pytest tests/test_step_resume.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any, Optional

import config
from memory import experience

LOG = config.getLogger("orchestrator.step_resume")

_FOOTER = ("Continue from the current step. Do NOT rewrite the plan or redo completed steps.")
_RESUME_BLOCK_MAX = 4000   # token-budget guard (chars)


def planSignature(state) -> str:
    """Stable hash over the task graph: each subtask's id, title, depends_on, verify.cmd.
    Recorded on every journal row at write time; compared on resume (MAF graph-sig gate)."""
    try:
        graph = []
        for s in state.subtasks:
            graph.append([
                s.get("subtask_id"), s.get("title"),
                sorted(s.get("depends_on") or []),
                (s.get("verify") or {}).get("cmd"),
            ])
        blob = json.dumps(graph, sort_keys=True, ensure_ascii=False, default=str)
        return hashlib.sha256(blob.encode("utf-8")).hexdigest()
    except Exception as e:  # noqa: BLE001 -- a bad sig must degrade to a clean rerun, never crash
        LOG.warning("planSignature failed (ignored): %s", e)
        return ""


def resumePlan(state, subtask: dict, steps: list[dict]) -> dict:
    """AGX-style reconstruction: a token-budgeted [x]/[->]/[ ] block + stability footer.
    Returns {resume_block, session_id, current_idx}."""
    done_idx = [int(s.get("step_idx", -1)) for s in steps if s.get("step_idx") is not None]
    current_idx = (max(done_idx) + 1) if done_idx else 0
    lines = ["## Resume context (you crashed mid-subtask; continue -- do NOT redo done steps)"]
    for s in steps:
        lines.append(f"- [x] step {s.get('step_idx')}: {s.get('tool')} -- {s.get('summary')}")
    lines.append(f"- [→] step {current_idx}: (resume here)")
    lines.append(f"- [ ] remaining steps as needed")
    lines.append("")
    lines.append(_FOOTER)
    block = "\n".join(lines)[:_RESUME_BLOCK_MAX]
    session_id = (steps[-1].get("session_id") if steps else None) \
        or (subtask.get("session") or {}).get("resume_session_id")
    return {"resume_block": block, "session_id": session_id, "current_idx": current_idx}


def reconcileResume(state, db_path: Optional[Path] = None) -> None:
    """For each in_progress subtask: keep it resumable on a plan-sig match (stash resume_block +
    session id on subtask['session'], status->pending), else reset clean + supersede the journal."""
    sig = planSignature(state)
    for s in list(state.subtasks):
        if s.get("status") != "in_progress":
            continue
        sid = s.get("subtask_id")
        try:
            steps = experience.loadSteps(state.task_id, sid, 1, db_path=db_path) \
                if db_path is not None else experience.loadSteps(state.task_id, sid, 1)
        except Exception:  # noqa: BLE001
            steps = []
        row_sig = steps[-1].get("plan_sig") if steps else None
        matches = bool(steps) and sig != "" and row_sig == sig
        sess = dict(s.get("session") or {})
        if matches:
            plan = resumePlan(state, s, steps)
            sess.update({"resumable": True, "resume_block": plan["resume_block"],
                         "resume_session_id": plan["session_id"],
                         "resume_from_idx": plan["current_idx"]})
            state.updateSubtask(sid, status="pending", session=sess)
            LOG.info("resume: %s kept resumable from step %d", sid, plan["current_idx"])
        else:
            sess.update({"resumable": False, "resume_block": None, "resume_from_idx": None})
            state.updateSubtask(sid, status="pending", session=sess)
            try:
                if db_path is not None:
                    experience.markAttemptSuperseded(state.task_id, sid, 1, db_path=db_path)
                else:
                    experience.markAttemptSuperseded(state.task_id, sid, 1)
            except Exception:  # noqa: BLE001
                pass
            LOG.info("resume: %s reset clean (sig mismatch / empty journal)", sid)
    return None
