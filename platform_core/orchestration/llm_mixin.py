LOG = config.getLogger("orchestrator")


class OrchestratorLlmMixin:
    """Handles all LLM/brain interaction: Ollama calls, goal evaluation, executor routing."""

    def _fitnessUnderTag(self, tag: str) -> float:
        """Run the golden eval suite with the brain forced to ``tag`` and return fitness.
        Used by automatic adapter promotion to A/B a challenger vs the champion."""
        from learning import eval_harness
        prev = self._brain_tag_override
        self._brain_tag_override = None if tag == config.OLLAMA_MODEL else tag
        try:
            out = eval_harness.run_suite(runner=self._evalGoal, record=False)
            return float(out.get("fitness", 0.0))
        finally:
            self._brain_tag_override = prev

    def _selectExecutor(self, spec: dict):
        """Pick the hands layer for a spec's requested surface. Default: Claude CLI (L3).
        Routes to the browser backend whenever requested.  An unavailable browser
        returns its own typed failed receipt; it must never become a hidden CLI run."""
        if spec.get("surface") == "browser":
            try:
                from agents import browser_executor
                return browser_executor.runBrowser if config.BROWSER_LAYER_ENABLED else browser_executor.unavailableBrowser
            except Exception:  # noqa: BLE001
                LOG.exception("browser surface requested but backend import failed")
                def unavailable(*_args, **_kwargs):
                    return {"ok": False, "returncode": 1, "is_error": True, "surface": "browser",
                            "stderr": "browser backend import failed", "surface_receipt": {"surface": "browser", "requested_mode": "live", "actual_mode": "unavailable", "status": "unavailable", "artifacts": [], "live": False}}
                return unavailable
        return self._run_claude

    def _evalGoal(self, goal: dict) -> dict:
        """Execute ONE golden goal as a bounded single subtask (brain authors under the
        current tag -> Claude runs -> held-out verify scores it). Used by the live eval
        runner and per-adapter fitness."""
        verify = goal.get("verify") or {}
        subtask = {"subtask_id": "eval", "title": goal.get("goal", "")[:80],
                   "description": goal.get("goal", ""), "verify": verify,
                   "effort_level": goal.get("effort_level", "default")}
        try:
            state = TaskState.create(goal.get("goal", ""), 1.0)
            state.meta["goal_elaborated"] = goal.get("goal", "")
            # Pin a baseline universe so the self_modification_guard protects secrets/VCS/venv/state +
            # the core loop files: this eval runs Claude in PROJECT_ROOT, and WITHOUT a pinned task the
            # guard has no boundaries and an eval goal's executor could edit core files unguarded.
            state.setUniverse({
                "description": "eval/fitness run", "allowed_paths": [], "allowed_to_expand_to": [],
                "hard_boundaries": [".env", ".git", "venv", "state/tasks",
                                    *getattr(config, "CORE_PROTECTED_FILES", ())]})
            state.save()
            spec = self.authorInvocationSpec(state, subtask, "")
            # task_state=state so the executor exports the task pin (guard resolves THIS task's
            # boundaries); deadline-only cancel (no run bus here) so an eval's session-token-limit
            # pause still breaks at the 1h horizon instead of wedging the eval/fitness pass for hours.
            result = self._run_claude(spec, work_dir=str(config.PROJECT_ROOT), task_state=state,
                                      subtask=subtask, cancel_check=lambda: self._deadlinePassed(state))
            vres = verifier.runVerification(
                verify, str(config.PROJECT_ROOT), result if isinstance(result, dict) else {})
            return {"passed": bool(vres.get("passed")), "attempts": 1,
                    "challenged": not bool(vres.get("passed"))}
        except Exception:  # noqa: BLE001
            return {"passed": False, "attempts": 1, "challenged": True}

    def _ollamaChat(self, system: str, user: str, *, act: str = "unspecified",
                    want_json: bool = False, retries: int = 3):
        """Resilient Ollama call through the ONE blessed seam (llm_io.chat): retry/backoff and
        empty-completion salvage live there; this layer adds capability injection, compaction,
        adapter-tag routing, the Discord blocked alert, and act telemetry. Returns resp or None.

        ``act`` is the structured brain-act tag (R5): real Ollama never sees it; simulation
        doubles dispatch on it EXACTLY (never on prompt wording), and it is recorded on
        trajectory spans for free telemetry."""
        system = injectCapabilities(system)
        # ONE constant context window for every brain call. Sizing num_ctx per-prompt forces ollama
        # to reload the entire 4.7GB runner on each change (the empty-completion storm: a slow reload
        # under VRAM pressure gets its connection dropped -> "Load failed" -> empty). Instead keep
        # num_ctx fixed and TRIM an over-long user payload so the system prompt -- which carries the
        # JSON-schema instruction format="json" relies on -- is never the thing that gets truncated.
        num_ctx = config.OLLAMA_NUM_CTX
        user = compaction.fitOrCompact(system, user, num_ctx, config.OLLAMA_GEN_HEADROOM,
                                       summarize=self._summarizeForCompaction)
        # SIE Layer 5/G: route to a forced tag (adapter A/B eval), else the champion
        # adapter, else the frozen base. Best-effort -- any error falls back to OLLAMA_MODEL.
        # NO model/effort routing change here (R5 mandate): selection stays exactly as it was.
        try:
            from learning import finetune
            model = getattr(self, "_brain_tag_override", None) or finetune.active_brain_tag()
        except Exception:  # noqa: BLE001
            model = config.OLLAMA_MODEL
        recorder = getattr(self, "_trajectory", None)   # free telemetry: act on a brain span
        span = None
        if recorder is not None:
            span = recorder.openSpan("brain", None, {"want_json": want_json}, act=act)
        try:
            resp = llm_io.chat(system, user, act=act, model=model, want_json=want_json,
                               retries=retries, client=self.ollama)
        finally:
            if recorder is not None and span is not None:
                recorder.closeSpan(span)
        if resp is None and not getattr(self, "_offline_mode", False):
            try:
                discord.sendEmbed(discord.noticeEmbed(
                    f"Brain (Ollama) unavailable after {retries} attempts; falling back (act={act})"))
            except Exception:  # noqa: BLE001
                pass
        return resp

    def _summarizeForCompaction(self, text: str) -> str:
        """Summarize the oldest payload half for compaction. CRITICAL: calls ollama.chat
        DIRECTLY at the SAME fixed num_ctx (never via _ollamaChat -> no recursion into
        fitOrCompact) and never resizes the window. A circuit breaker (COMPACTION_MAX_PASSES
        consecutive failures) stops a doomed summarize-retry loop; on trip it returns "" so
        compactPayload falls back to truncation."""
        if getattr(self, "_compaction_fail_streak", 0) >= config.COMPACTION_MAX_PASSES:
            return ""
        num_ctx = config.OLLAMA_NUM_CTX
        sys_prompt = compaction.MUST_PRESERVE_CONTRACT
        bounded = _fitUserToCtx(sys_prompt, text, num_ctx, config.OLLAMA_GEN_HEADROOM)
        try:
            from learning import finetune
            model = getattr(self, "_brain_tag_override", None) or finetune.active_brain_tag()
        except Exception:  # noqa: BLE001
            model = config.OLLAMA_MODEL
        # act tag for sim dispatch/telemetry -- only forwarded when the client accepts it
        # (real ollama.Client does not; SimBrain/BuilderBrain dispatch on it exactly).
        extra = {"act": "compaction"} if llm_io.chatAcceptsAct(self.ollama.chat) else {}
        try:
            resp = self.ollama.chat(
                model=model,
                messages=[{"role": "system", "content": sys_prompt},
                          {"role": "user", "content": bounded}],
                options={"num_ctx": num_ctx}, keep_alive=config.OLLAMA_KEEP_ALIVE, **extra)
            out = _chatText(resp).strip()
            if not out:
                self._compaction_fail_streak = getattr(self, "_compaction_fail_streak", 0) + 1
                return ""
            self._compaction_fail_streak = 0
            return out
        except Exception as e:  # noqa: BLE001
            LOG.debug("compaction summarize failed (ignored): %s", e)
            self._compaction_fail_streak = getattr(self, "_compaction_fail_streak", 0) + 1
            return ""

    def _resolveClarifications(self, state: TaskState, subtask: dict, claude_output: str,
                               dashboard: "DiscordDashboard | None" = None) -> "str | None":
        """If the executor punted a decision to a human, have the Ollama brain answer it so the
        next attempt proceeds with NO human intervention. Returns the answer text, or None."""
        questions = clarifier.detectClarificationNeeded(claude_output)
        if not questions:
            return None
        answer = clarifier.answerClarifications(
            self._ollamaChat, state.meta.get("goal_elaborated") or state.meta.get("goal_raw", ""),
            subtask, claude_output, questions)
        if answer:
            LOG.info("%s: brain auto-answered %d executor question(s) -- no human needed",
                     subtask.get("subtask_id"), len(questions))
            if dashboard is not None:
                dashboard.update(state, "executing",
                                 f"{subtask.get('subtask_id')} brain answered executor ({len(questions)} q) autonomously")
        return answer
