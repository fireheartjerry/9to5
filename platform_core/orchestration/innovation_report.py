"""Fact-grounded innovation report: compile shipped/proposed inventions with evidence.

Turns a finished run into ``InnovativeChangeReportEntry`` items that derive ONLY from facts:
a shipped innovation needs a verified subtask + extracted evidence (no evidence => dropped,
failed-verify => never 'shipped'); proposed inventions come from the ledger's feature
candidates seeded this run. Shipped, proposed, and rejected are kept distinct. Best-effort:
never raises, returns [] when there is nothing fact-backed to report.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  compileInnovativeChanges(state: Any, *, db_path=None) -> list[InnovativeChangeReportEntry]  -- Fact-backed innovation entries for a finished run (shipped first, then proposed).
  persist(state: Any, entries: list, *, db_path=None) -> int  -- Write entries to the run_innovations ledger (best-effort)
  render_markdown(entries: list) -> str  -- Human-readable 'Innovative Changes' section ('' when there is nothing to report).
  render_discord_fields(entries: list) -> list[tuple[str, str]]  -- (name, value) embed fields for the 'Innovative Changes' Discord post (<=5 items).
DEPENDS-ON: config, memory.experience_evolution, platform_core.orchestration, platform_core.orchestration.invention_types
SIDE-EFFECTS: persist() writes the run_innovations ledger
RUN/TEST: python -m pytest tests/orchestration/test_innovation_report.py
"""
from __future__ import annotations

from typing import Any, Optional

import config
from platform_core.orchestration import evidence_extract as ev
from platform_core.orchestration.invention_types import InnovativeChangeReportEntry

LOG = config.getLogger("orchestrator.innovation_report")


def _get(o: Any, k: str, d: Any = None) -> Any:
    return o.get(k, d) if isinstance(o, dict) else getattr(o, k, d)


def _subtasks(state: Any) -> list:
    return list(_get(state, "subtasks", []) or [])


def _task_id(state: Any) -> str:
    meta = _get(state, "meta", {}) or {}
    return str(meta.get("task_id") or _get(state, "task_id", "") or "")


def _is_invention(st: Any) -> bool:
    """A subtask counts as an invention when it carries invention metadata (else a normal task)."""
    floor = float(getattr(config, "NOVELTY_FINDER_FLOOR", 0.55))
    return bool(_get(st, "candidate_kind") or _get(st, "invention")
                or float(_get(st, "measured_novelty", 0.0) or 0.0) >= floor)


def _subtask_text(st: Any) -> str:
    vres = _get(st, "verify_result", {}) or {}
    res = _get(st, "result", {}) or {}
    return "\n".join(str(x) for x in (vres.get("stdout"), vres.get("stderr"),
                                      vres.get("receipt"), res.get("stdout"),
                                      _get(st, "diff_summary", "")) if x)


def _shipped_entry(st: Any, evidence: dict) -> InnovativeChangeReportEntry:
    title = str(_get(st, "title", "") or "untitled")
    metric = next((r for r in evidence["evidence_refs"] if r.startswith(("test_pass", "verify_ok",
                                                                         "factsgate", "benchmark"))), "")
    return InnovativeChangeReportEntry(
        title=title, claim=f"Shipped and verified: {title}", status="shipped",
        why_innovative={"measured_novelty": round(float(_get(st, "measured_novelty", 0.0) or 0.0), 4),
                        "nearest_prior_similarity": round(float(_get(st, "history_similarity_max", 0.0) or 0.0), 4),
                        "qd_cell": str(_get(st, "qd_cell", "") or ""),
                        "innovation_mechanism": str(_get(st, "innovation_mechanism", "") or "")},
        how_it_improves={"behavior_delta": str(_get(st, "behavior_delta", "") or title),
                         "verified_metric": metric,
                         "before": str(_get(st, "before", "") or ""),
                         "after": str(_get(st, "after", "") or "")},
        risk_and_scope={"risk": str(_get(st, "risk", "medium")),
                        "blast_radius": str(_get(st, "blast_bin", "medium")),
                        "rollback_plan": str(_get(st, "rollback_plan", "revert the subtask diff"))},
        evidence_refs=evidence["evidence_refs"])


def _shipped(state: Any) -> list[InnovativeChangeReportEntry]:
    """Verified invention subtasks with real evidence (factless / failed-verify are excluded)."""
    out: list[InnovativeChangeReportEntry] = []
    for st in _subtasks(state):
        if str(_get(st, "status", "")) != "done" or not _is_invention(st):
            continue
        vres = _get(st, "verify_result", {}) or {}
        if not vres.get("passed", False):
            continue                                   # failed verify is NEVER a shipped innovation
        evidence = ev.extract_evidence(_subtask_text(st),
                                       module_names=_get(st, "affected_files", []) or [])
        if not ev.supports_claim(evidence):
            continue                                   # no evidence => no claim
        out.append(_shipped_entry(st, evidence))
    return out


def _proposed(state: Any, db_path) -> list[InnovativeChangeReportEntry]:
    """Feature candidates seeded THIS run that are proposals, not yet shipped."""
    run_id = _task_id(state)
    if not run_id:
        return []
    try:
        from memory import experience_evolution as ee
        import json
        cands = ee.fetch_candidates(kind="feature", db_path=db_path)
    except Exception as e:  # noqa: BLE001
        LOG.debug("proposed fetch failed (ignored): %s", e)
        return []
    out: list[InnovativeChangeReportEntry] = []
    for c in cands:
        prov = {}
        try:
            prov = json.loads(c.get("provenance_json") or "{}")
        except Exception:  # noqa: BLE001
            prov = {}
        if str(prov.get("run_id")) != run_id or c.get("state") == "champion":
            continue
        out.append(InnovativeChangeReportEntry(
            title=str(prov.get("title") or c.get("target") or "proposed invention"),
            claim="Proposed invention (not yet built)", status="proposed",
            why_innovative={"measured_novelty": round(float(c.get("measured_novelty") or 0.0), 4),
                            "innovation_mechanism": str(prov.get("route", ""))},
            risk_and_scope={"risk": str(c.get("risk") or "medium")},
            evidence_refs=[f"ledger:candidate:{c.get('id')}"]))
    return out


def compileInnovativeChanges(state: Any, *, db_path=None) -> list[InnovativeChangeReportEntry]:
    """Fact-backed innovation entries for a finished run (shipped first, then proposed)."""
    try:
        return _shipped(state) + _proposed(state, db_path)
    except Exception as e:  # noqa: BLE001 -- reporting must never break a run
        LOG.warning("compileInnovativeChanges failed (ignored): %s", e)
        return []


def persist(state: Any, entries: list, *, db_path=None) -> int:
    """Write entries to the run_innovations ledger (best-effort). Returns count written."""
    from memory import experience_evolution as ee
    run_id = _task_id(state)
    n = 0
    for e in entries:
        rid = ee.record_innovation(
            run_id=run_id, title=e.title, claim=e.claim, status=e.status,
            measured_novelty=float(e.why_innovative.get("measured_novelty", 0.0) or 0.0),
            qd_cell=str(e.why_innovative.get("qd_cell", "")),
            innovation_mechanism=str(e.why_innovative.get("innovation_mechanism", "")),
            why=e.why_innovative, how=e.how_it_improves, risk=e.risk_and_scope,
            evidence=e.evidence_refs, db_path=db_path)
        n += 1 if rid is not None else 0
    return n


def render_markdown(entries: list) -> str:
    """Human-readable 'Innovative Changes' section ('' when there is nothing to report)."""
    shipped = [e for e in entries if e.status == "shipped"]
    proposed = [e for e in entries if e.status == "proposed"]
    if not shipped and not proposed:
        return ""
    lines = ["## Innovative Changes"]
    if shipped:
        lines.append("\n### Shipped (verified)")
        for e in shipped:
            nov = e.why_innovative.get("measured_novelty", 0.0)
            lines.append(f"- **{e.title}** — novelty {nov:.2f}; {e.how_it_improves.get('behavior_delta','')}. "
                         f"Evidence: {', '.join(e.evidence_refs[:4]) or 'n/a'}")
    if proposed:
        lines.append("\n### Proposed (not yet built)")
        for e in proposed:
            lines.append(f"- **{e.title}** — novelty "
                         f"{e.why_innovative.get('measured_novelty', 0.0):.2f} ({e.risk_and_scope.get('risk','?')} risk)")
    return "\n".join(lines)


def render_discord_fields(entries: list) -> list[tuple[str, str]]:
    """(name, value) embed fields for the 'Innovative Changes' Discord post (<=5 items)."""
    fields: list[tuple[str, str]] = []
    for e in entries[:5]:
        tag = "✅" if e.status == "shipped" else "💡"
        val = f"novelty {e.why_innovative.get('measured_novelty', 0.0):.2f} · {e.status}"
        refs = ", ".join(e.evidence_refs[:3])
        fields.append((f"{tag} {e.title[:80]}", f"{val}\n{refs}"[:1024]))
    return fields
