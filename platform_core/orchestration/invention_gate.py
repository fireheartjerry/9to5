"""Hybrid-by-confidence autonomy gate: the final decision to auto-run or propose an invention.

An invention only auto-runs (in an isolated worktree, behind the existing safety hooks) when
EVERY guard holds: auto-run explicitly enabled, autonomy mode allows it, high measured novelty,
high confidence, low risk, low blast radius, reversible, non-destructive, no external deploy,
and NOT self-referential (never lets the system rewrite its own core loop unattended).
Everything else becomes a ranked human-gated proposal. Default mode is 'proposal', so nothing
auto-runs unless the operator turns it on. Pure + deterministic + fully auditable (reasons +
lineage on every decision).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  is_self_referential(candidate: Any) -> bool  -- True when the candidate is flagged self-referential OR targets a core-loop file.
  routeInvention(candidate: Any, *, blast_bin: Optional[str]=None) -> dict  -- Decide auto_run vs proposal for one invention
DEPENDS-ON: config, platform_core.orchestration.invention_types
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/orchestration/test_invention_gate.py
"""
from __future__ import annotations

from typing import Any, Optional

import config
from platform_core.orchestration.invention_types import clamp01, norm_blast, norm_risk

LOG = config.getLogger("orchestrator.invention_gate")

_RISK_ORDER = {"low": 0, "medium": 1, "high": 2}
# Touching any of these unattended = self-modification of the core loop -> never auto-run.
_CORE_FILES = (
    "agents/executor.py", "agents/hooks.py", "config.py", "main.py", "orchestrator.py",
    "platform_core/orchestration/execute_mixin.py", "platform_core/orchestration/run_loop",
    "platform_core/runtime/control", "platform_core/app_config/",
)


def _get(c: Any, k: str, d: Any = None) -> Any:
    return c.get(k, d) if isinstance(c, dict) else getattr(c, k, d)


def is_self_referential(candidate: Any) -> bool:
    """True when the candidate is flagged self-referential OR targets a core-loop file."""
    if bool(_get(candidate, "is_self_referential", False)):
        return True
    subs = _get(candidate, "target_subsystems", None) or _get(candidate, "affected_files", None) or []
    for s in subs:
        s = str(s).replace("\\", "/")
        if any(core in s for core in _CORE_FILES):
            return True
    return False


def _auto_run_reasons(candidate: Any, blast: str) -> list[str]:
    """Collect every FAILED auto-run guard (empty list => all guards pass)."""
    mode = str(getattr(config, "INVENTION_AUTONOMY", "proposal"))
    nov_min = float(getattr(config, "INVENTION_AUTO_NOVELTY_MIN", 0.75))
    conf_min = float(getattr(config, "INVENTION_AUTO_CONFIDENCE_MIN", 0.80))
    risk_max = norm_risk(getattr(config, "INVENTION_AUTO_RISK_MAX", "low"))
    reasons: list[str] = []
    if not bool(getattr(config, "INVENTION_AUTO_RUN_ENABLED", False)):
        reasons.append("auto_run_disabled")
    if mode not in ("auto", "hybrid"):
        reasons.append(f"autonomy_mode={mode}")
    if clamp01(_get(candidate, "measured_novelty", 0.0)) < nov_min:
        reasons.append("novelty_below_min")
    if clamp01(_get(candidate, "confidence", 0.0)) < conf_min:
        reasons.append("confidence_below_min")
    if _RISK_ORDER.get(norm_risk(_get(candidate, "risk", "high")), 2) > _RISK_ORDER.get(risk_max, 0):
        reasons.append("risk_above_max")
    if norm_blast(blast) != "small" and blast != "low":
        reasons.append("blast_not_low")
    if not bool(_get(candidate, "reversible", True)):
        reasons.append("not_reversible")
    if bool(_get(candidate, "destructive", False)):
        reasons.append("destructive")
    if bool(_get(candidate, "deploy", False)) or bool(_get(candidate, "external_deploy", False)):
        reasons.append("external_deploy")
    if is_self_referential(candidate):
        reasons.append("self_referential")
    return reasons


def routeInvention(candidate: Any, *, blast_bin: Optional[str] = None) -> dict:
    """Decide auto_run vs proposal for one invention. Never raises; default => proposal."""
    blast = str(blast_bin if blast_bin is not None else _get(candidate, "blast_bin", "medium"))
    try:
        fails = _auto_run_reasons(candidate, blast)
    except Exception as e:  # noqa: BLE001 -- a gate error must fail SAFE (propose, never auto-run)
        LOG.warning("invention gate errored, defaulting to proposal (ignored): %s", e)
        fails = ["gate_error"]
    decision = "auto_run" if not fails else "proposal"
    return {"decision": decision,
            "candidate_id": str(_get(candidate, "id", "") or _get(candidate, "candidate_id", "")),
            "reasons": fails or ["all_guards_passed"],
            "blast_bin": norm_blast(blast) if blast not in ("low", "medium", "high") else blast,
            "lineage": _get(candidate, "lineage", {}) or {}}
