from __future__ import annotations

import config
import llm_io

LOG = config.getLogger("orchestrator.brain_io")

# Chars-per-token budgeting constant, unified with compaction._approxTokens (which estimates
# ~4 chars/token via ``len(text) // 4``). Kept as a module constant here rather than importing
# compaction to avoid a circular import (compaction imports brain_io).
CHARS_PER_TOK = 4
# When the system prompt alone exceeds the window (budget <= 0) we still must NOT hand the model
# the full user payload -- keep at most this many trailing chars so the request stays bounded.
BUDGET_FLOOR_CHARS = 512


def _chatText(resp) -> str:
    """Safely pull resp['message']['content'] as text."""
    return llm_io.responseText(resp)


def _fitUserToCtx(system: str, user: str, num_ctx: int, headroom: int) -> str:
    """Bound the user payload so system+user fits a fixed Ollama context."""
    budget = int((num_ctx - headroom) * CHARS_PER_TOK) - len(system)
    if budget <= 0:
        # The system prompt alone overflows the window. Returning the FULL user payload here (old
        # bug) guaranteed an over-window request; instead keep only a bounded trailing slice so the
        # most-recent context survives, and warn -- the caller/compaction layer should shrink system.
        keep = max(BUDGET_FLOOR_CHARS, 0)
        LOG.warning("brain payload: system prompt (%d chars) exceeds the window budget "
                    "(num_ctx=%d, headroom=%d); trimming user to last %d chars",
                    len(system), num_ctx, headroom, keep)
        return user if len(user) <= keep else user[-keep:]
    if len(user) <= budget:
        return user
    marker = "\n\n...[context trimmed to fit the model window]...\n\n"
    keep = budget - len(marker)
    if keep <= 0:
        return user[-budget:]
    head = keep * 2 // 3
    tail = keep - head
    return user[:head] + marker + (user[-tail:] if tail > 0 else "")


def _resultText(result, key: str = "stdout") -> str:
    """Pull a text field from an executor result, or empty string."""
    v = result.get(key) if isinstance(result, dict) else None
    return v if isinstance(v, str) else ""


def _chatJson(resp):
    """Safely parse the JSON body of a chat response."""
    return parseJsonText(_chatText(resp).strip())


