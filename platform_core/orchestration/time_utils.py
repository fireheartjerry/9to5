from __future__ import annotations

from platform_core.core.clock import elapsedSecondsSince


def _fmtElapsed(seconds: float) -> str:
    """Compact hms display ('1h02m03s') -- the orchestrator-status format, distinct from
    the dashboard/cv2 '1h 2m' style owned by platform_core.core.clock.fmtElapsed."""
    seconds = int(seconds)
    h, rem = divmod(seconds, 3600)
    m, s = divmod(rem, 60)
    return f"{h}h{m:02d}m{s:02d}s"


def _elapsedSince(started_at_iso: str) -> float:
    """Total wall-clock seconds since the task's original start."""
    return elapsedSecondsSince(started_at_iso)
