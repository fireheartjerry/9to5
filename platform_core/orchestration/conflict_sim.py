"""Rollback-DSU conflict simulation: a cheap prefilter before real worktree execution.

Running candidates in parallel is only safe if they touch disjoint files. This models each
candidate as a DSU node and unions any two that share a touched file — so a connected
component is a set of candidates that would collide. A rollback-capable union-find (union by
size, NO path compression, undo stack) lets callers try a bundle, read the components, and
cheaply roll back to test an alternative bundle without rebuilding the structure. Pure +
deterministic.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  RollbackDSU  -- Union-find with rollback: union by size, no path compression, undoable via an op stack.
  would_conflict(a: Any, b: Any) -> bool  -- True iff two candidates touch at least one common file.
  conflict_groups(candidates: list) -> list[list[str]]  -- Group candidate ids into components that would collide (share files transitively).
  bundle_conflict_free(candidates: list) -> bool  -- True iff the whole bundle can run in parallel (every candidate is its own component).
DEPENDS-ON: config
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/orchestration/test_conflict_sim.py
"""
from __future__ import annotations

from typing import Any, Iterable

import config

LOG = config.getLogger("orchestrator.conflict_sim")


class RollbackDSU:
    """Union-find with rollback: union by size, no path compression, undoable via an op stack."""

    def __init__(self, items: Iterable) -> None:
        self.parent: dict = {i: i for i in items}
        self.size: dict = {i: 1 for i in self.parent}
        self.history: list = []

    def find(self, x: Any) -> Any:
        while self.parent[x] != x:                     # no path compression (must stay reversible)
            x = self.parent[x]
        return x

    def union(self, a: Any, b: Any) -> bool:
        ra, rb = self.find(a), self.find(b)
        if ra == rb:
            self.history.append(None)                  # record a no-op so rollback counts align
            return False
        if self.size[ra] < self.size[rb]:
            ra, rb = rb, ra
        self.parent[rb] = ra
        self.size[ra] += self.size[rb]
        self.history.append((rb, ra))
        return True

    def connected(self, a: Any, b: Any) -> bool:
        return self.find(a) == self.find(b)

    def snapshot(self) -> int:
        """Return an opaque marker to rollback_to()."""
        return len(self.history)

    def rollback(self, steps: int = 1) -> None:
        """Undo the last ``steps`` union operations (no-ops included)."""
        for _ in range(steps):
            if not self.history:
                return
            op = self.history.pop()
            if op is None:
                continue
            rb, ra = op
            self.size[ra] -= self.size[rb]
            self.parent[rb] = rb

    def rollback_to(self, marker: int) -> None:
        """Undo back to a snapshot() marker."""
        self.rollback(max(0, len(self.history) - int(marker)))


def _get(o: Any, k: str, d: Any = None) -> Any:
    return o.get(k, d) if isinstance(o, dict) else getattr(o, k, d)


def _cid(c: Any) -> str:
    return str(_get(c, "candidate_id", None) or _get(c, "id", None) or _get(c, "title", None) or id(c))


def _files(c: Any) -> set:
    subs = _get(c, "target_subsystems", None) or _get(c, "affected_files", None) or []
    return {str(s) for s in subs}


def would_conflict(a: Any, b: Any) -> bool:
    """True iff two candidates touch at least one common file."""
    return not _files(a).isdisjoint(_files(b))


def conflict_groups(candidates: list) -> list[list[str]]:
    """Group candidate ids into components that would collide (share files transitively)."""
    ids = [_cid(c) for c in candidates]
    dsu = RollbackDSU(ids)
    owner: dict[str, str] = {}
    for c in candidates:
        cid = _cid(c)
        for f in _files(c):
            if f in owner:
                dsu.union(owner[f], cid)
            else:
                owner[f] = cid
    groups: dict[str, list[str]] = {}
    for cid in ids:
        groups.setdefault(dsu.find(cid), []).append(cid)
    return [sorted(g) for g in groups.values()]


def bundle_conflict_free(candidates: list) -> bool:
    """True iff the whole bundle can run in parallel (every candidate is its own component)."""
    return len(conflict_groups(candidates)) == len(candidates)
