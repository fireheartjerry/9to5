"""Self-referential quality gate -- cheap Windows repo checks after a self-ref subtask passes.

Extracted from ``execute_mixin`` so the execute mixin stays within the modularity ceiling.
Catches stale generated artifacts and nearby test failures while the executor still has retry
attempts left, instead of discovering them only at pre-PR time.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  run_self_ref_quality_gate(work_dir: str) -> 'tuple[bool, str]'  -- Run cheap Windows repo gates after a self-ref subtask passes its own verify.
DEPENDS-ON: config, platform_core.core
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import subprocess   # kept imported: TimeoutExpired + the patch point tests rely on
import sys

import config
from platform_core.core import git_io


def _run(cmd: list, work_dir: str) -> "tuple[int, str, str]":
    """Run a gate command; return (returncode, stdout, combined_tail).
    On timeout/error returns (-1, "", message)."""
    try:
        proc = git_io.runTool(cmd, cwd=work_dir, timeout=config.GIT_TIMEOUT_SECONDS)
    except subprocess.TimeoutExpired:
        return -1, "", f"{' '.join(cmd)} timed out after {config.GIT_TIMEOUT_SECONDS}s"
    except Exception as e:  # noqa: BLE001
        return -1, "", f"{' '.join(cmd)} errored: {e}"
    tail = ((proc.stdout or "") + "\n" + (proc.stderr or "")).strip()
    return proc.returncode, (proc.stdout or ""), tail


def run_self_ref_quality_gate(work_dir: str) -> "tuple[bool, str]":
    """Run cheap Windows repo gates after a self-ref subtask passes its own verify."""
    commands = git_io.gateCommands("repo_checks")   # shared tier table with the pre-PR gate
    tail = ""
    for cmd in commands:
        rc, _out, tail = _run(cmd, work_dir)
        if rc == -1:
            return False, tail
        if rc != 0:
            return False, f"{' '.join(cmd)} failed:\n{tail}"[-1200:]

    mapper_cmd = [sys.executable, "tools\\affected_tests.py"]
    rc, mapper_out, mapper_tail = _run(mapper_cmd, work_dir)
    if rc == -1:
        return False, mapper_tail
    if rc != 0:
        return False, f"{' '.join(mapper_cmd)} failed:\n{mapper_tail}"[-1200:]
    targets = [t for t in mapper_out.split() if t.strip()]
    if not targets:
        return True, (tail or "no affected tests")
    pytest_cmd = [sys.executable, "-m", "pytest", *targets, "-q"]
    rc, _out, test_tail = _run(pytest_cmd, work_dir)
    if rc == -1:
        return False, test_tail
    if rc != 0:
        return False, f"{' '.join(pytest_cmd)} failed:\n{test_tail}"[-1200:]
    return True, test_tail[-1200:] or tail[-1200:]
