from __future__ import annotations

from typing import Optional

from platform_core.orchestration.validation_cache import run_validation_suite


def run_self_ref_quality_gate(work_dir: str, changed_files: Optional[list[str]] = None) -> "tuple[bool, str]":
    """Run cheap Windows repo gates after a self-ref subtask passes its own verify.

    ``changed_files`` scopes the affected-tests resolution to the subtask's OWN changed files so an
    unrelated red test elsewhere in the repo cannot doom this subtask; None keeps the legacy
    cumulative-git-diff fallback."""
    result = run_validation_suite("self_ref_incremental", work_dir, changed_files=changed_files)
    return result.ok, result.detail[-1200:]
