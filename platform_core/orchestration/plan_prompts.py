"""Planner prompt constants for the orchestrator (extracted from plan_mixin for modularity).

Owns every static system prompt the planning mixin sends to the brain: the invocation-spec
constitution, the planner, the plan critique, the shape-fixer, and the horizon-fill template.
plan_mixin re-exports ORCHESTRATOR_CONSTITUTION and _VERIFY_EXAMPLE_PATH so the orchestrator
facade import path is unchanged.

R10 note: the VERIFY RULES here are the fail-closed contract. ``expect`` is REQUIRED (the
sanitizer rejects a verify without one -- the runner never guesses), and a test-runner cmd
must use ``exit_zero`` because expect is evaluated STRICTLY (a green suite with a wrong
stdout needle FAILS; there is no silent test-runner override anymore).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  horizonFillSystem(room: int, remaining_hours: float) -> str  -- The HORIZON-FILL planner system prompt (self-improvement runs with time left).
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_dry_run.py
"""
from __future__ import annotations

import config

