"""Queued plan-op application -- the drain side of the ControlBus single-writer contract.

Every out-of-process surface (gateway bot, launcher, web dashboard) queues intent as
``plan_ops``; the orchestrator run loop drains them here and is the ONLY process that
writes task JSON (docs/STATE.md). Extracted from control_mixin to keep it under the size
threshold; the mixin keeps the thin ``_applyOps`` delegate so callers and tests are
unchanged.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  applyOp(state, op: dict, dashboard) -> None  -- Apply ONE drained plan op to the task state
DEPENDS-ON: config
SIDE-EFFECTS: mutates + saves task JSON; emits dashboard events
RUN/TEST: python -m pytest tests/orchestration/test_control_ops.py
"""
from __future__ import annotations

import config

LOG = config.getLogger("orchestrator")


def _applySkip(state, op: dict, dashboard) -> None:
    sid = op.get("subtask_id")
    st = state.getSubtask(sid)
    if st is None:
        dashboard.event(f"skip ignored: {sid} not found")
    elif st["status"] == "pending":
        state.updateSubtask(sid, status="removed")
        dashboard.event(f"skipped {sid}")
    else:
        # in_progress/done/failed/removed can't be skipped between steps -- say so
        # instead of dropping the request silently (the user is waiting on feedback).
        dashboard.event(f"skip ignored: {sid} is {st['status']} (only pending can be skipped)")


def _applyEdit(state, op: dict, dashboard) -> None:
    # in-Discord plan editor: amend a subtask's title/description (Tier 2).
    sid = op.get("subtask_id")
    st = state.getSubtask(sid)
    if st is None:
        dashboard.event(f"edit ignored: {sid} not found")
    elif st["status"] in ("pending", "in_progress"):
        fields = {k: op[k] for k in ("title", "description") if op.get(k)}
        if fields:
            state.updateSubtask(sid, **fields)
            dashboard.event(f"edited {sid}")
    else:
        dashboard.event(f"edit ignored: {sid} is {st['status']} (only pending/in_progress)")


def applyOp(state, op: dict, dashboard) -> None:
    """Apply ONE drained plan op to the task state. The caller (control_mixin._applyOps)
    holds the orchestrator's state lock around this call."""
    kind = op.get("op")
    if kind == "skip":
        _applySkip(state, op, dashboard)
    elif kind == "add":
        st = state.addSubtask(op.get("title", "untitled"), op.get("description", ""))
        dashboard.event(f"added {st['subtask_id']}")
    elif kind == "retry":
        cur = next((s for s in state.subtasks if s["status"] == "in_progress"), None)
        if cur:
            state.updateSubtask(cur["subtask_id"], status="pending")
            dashboard.event(f"retry {cur['subtask_id']}")
    elif kind == "edit":
        _applyEdit(state, op, dashboard)
    elif kind == "intent":
        state.addIntent(op.get("text", ""))
        dashboard.event(f"intent noted: {op.get('text', '')[:60]}")
    elif kind == "intent_clear":
        state.clearIntents()
        dashboard.event("intents cleared")
    elif kind == "inject_context":
        state.addInjectedContext(op.get("text", ""))
        dashboard.event("context injected for next attempt")
    elif kind == "set_effort":
        sid = op.get("subtask_id")
        if state.getSubtask(sid):
            state.updateSubtask(sid, effort_override=op.get("level"))
            dashboard.event(f"effort override {sid} -> {op.get('level')}")
    elif kind == "set_run_effort":
        state.meta["run_effort_override"] = op.get("level")
        state.save()
        dashboard.event(f"run effort -> {op.get('level')}")
    elif kind == "extend_deadline":
        new_dl = state.extendDeadline(float(op.get("delta_seconds", 0)))
        dashboard.event(f"deadline extended -> {new_dl}")
    elif kind == "set_mode":
        # queued by '!mode' (single-writer rule: the bot never writes task JSON)
        m = op.get("mode")
        if m in ("gated", "watch"):
            state.setControlMode(m)
            dashboard.event(f"control mode -> {m}")
    elif kind == "mark_stale":
        # launcher breadcrumb: it judged this run dead. If we are draining this,
        # we are demonstrably alive -- surface it (the paired abort still applies).
        dashboard.event(f"launcher flagged this run stale: {op.get('reason', '')[:80]}")
