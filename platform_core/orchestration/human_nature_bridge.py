from __future__ import annotations

from typing import Any

import config
from platform_core.core.best_effort import best_effort

LOG = config.getLogger("human_nature_bridge")


def midRunInstinct(state: Any, dashboard: Any = None) -> "str | None":
    """Hook 4: once per run, fire the ledger-grounded instinct ("gut") check and SURFACE the
    advisory flag. Best-effort + gated: no-op when HUMAN_NATURE_ENABLED is off, never raises, and
    never blocks the run -- it only narrates a suspicion drawn from past reflections/failure modes."""
    if not config.HUMAN_NATURE_ENABLED:
        return None
    try:
        from human_nature import integration
        from memory.experience_adapters import fetch_failure_modes
        from memory.experience_solutions import fetch_reflections

        flag = integration.maybe_run_instinct(state, fetch_reflections() or [], fetch_failure_modes() or [])
        if flag:
            LOG.info("human-nature instinct: %s", flag)
            if dashboard is not None:
                with best_effort("human_nature.instinct_surface", log=LOG):
                    dashboard.event(f"instinct — {flag}")
        return flag
    except Exception:  # noqa: BLE001
        LOG.debug("midRunInstinct failed (ignored)", exc_info=True)
        return None


def _subtasks(state: Any) -> list:
    """Read planned subtasks from a TaskState or a plain state dict. Best-effort: []."""
    try:
        if hasattr(state, "subtasks"):
            return list(state.subtasks or [])
        return list(state.get("plan", {}).get("subtasks", []) or [])
    except Exception:  # noqa: BLE001
        return []


def _subtaskDomain(state: Any, subtask: dict) -> str:
    """Derive the opinion domain for a subtask: explicit type, else run domain, else 'unknown'."""
    dom = subtask.get("type") or _meta(state).get("domain") or "unknown"
    return str(dom)


# judgment_type recorded for opinion/flag calibration in the conviction ledger.
_OPINION_JUDGMENT_TYPE = "opinion"


def _convictionFor(state: Any, domain: str) -> float:
    """Best-effort conviction score in [0,1] for *domain*, sourced from the REAL
    conviction ledger's per-domain track record. ``track_record`` returns the HONEST
    hit-rate (fraction of times HN's past opinions in this domain proved correct);
    ``conviction.track_weight`` folds in the ledger's cold-start floor (below
    ``MIN_SAMPLES`` observations it yields 0.0, so a 1/1 record earns no teeth) and
    otherwise returns that hit-rate directly. 0.0 when the ledger is empty, the domain
    is unseen, or the accessor errors -- a 0.0 conviction maps to the "cosmetic" tier,
    i.e. a silent no-op. No fabricated conviction, no LLM calls. Never raises. The
    *state* arg is kept for signature stability (ledger scope is domain-wide, not per-run)."""
    try:
        from human_nature.conviction import track_weight
        from memory.conviction_ledger import track_record

        track = track_record(_OPINION_JUDGMENT_TYPE, str(domain))
        return max(0.0, min(1.0, float(track_weight(track))))
    except Exception:  # noqa: BLE001
        return 0.0


def opinionAdvisory(state: Any, dashboard: Any = None) -> "list[dict]":
    """Advisory-only opinion coupling on the plan gate. For each planned subtask, look
    up the HN conviction for its domain and grade it via ``opinions.tier``; when the
    tier is "hard" (a strong conviction), SURFACE it as an advisory concern -- append
    {"domain","tier","note"} to ``state.meta["hn_opinions"]``, emit a dashboard event,
    and LOG.info. It is a complete no-op unless BOTH HUMAN_NATURE_ENABLED and
    HN_OPINIONS_BEHAVIOR are True, is best-effort (never raises), and is ADVISORY ONLY:
    it never rejects/holds the plan, removes/skips subtasks, or alters control flow.
    Returns the list of surfaced advisories (empty when disabled or nothing surfaced)."""
    if not (config.HUMAN_NATURE_ENABLED and config.HN_OPINIONS_BEHAVIOR):
        return []
    surfaced: list[dict] = []
    try:
        from human_nature import opinions

        for subtask in _subtasks(state):
            domain = _subtaskDomain(state, subtask)
            conviction = _convictionFor(state, domain)
            tier = opinions.tier(conviction, domain)
            if tier != "hard":
                continue
            note = f"strong reservation on {domain} (conviction {conviction:.2f})"
            surfaced.append({"domain": domain, "tier": tier, "note": note})
        if surfaced:
            _meta(state).setdefault("hn_opinions", []).extend(surfaced)
            LOG.info("human-nature opinion advisory: %s", surfaced)
            if dashboard is not None:
                with best_effort("human_nature.opinion_surface", log=LOG):
                    for adv in surfaced:
                        dashboard.event(f"opinion -- strong reservation on {adv['domain']}")
    except Exception:  # noqa: BLE001
        LOG.debug("opinionAdvisory failed (ignored)", exc_info=True)
        return []
    return surfaced


# --- Emotion faculty: affect -> emotion label -> advisory behavior coupling ------
# Behavior intents this repo maps to a SAFE, BOUNDED run effect (a +1 retry-budget
# nudge). Only intents whose "do more" reading is bounded and non-destructive live
# here; every OTHER intent (explore/propose_refactor/None/unknown) is RECORD-ONLY
# (delta 0) -- it is still "used" (surfaced) but applies no run effect.
_SAFE_NUDGE_INTENTS: frozenset[str] = frozenset({"escalate_effort", "raise_verification"})


def _affectToLabel(affect: "dict | None") -> str:
    """Derive an emotion label from the self-model PAD affect (valence/arousal/control).

    SIMPLE, documented rule (never invents affect -- absent/zero affect => "neutral"):
      high valence (>= 0.3)                    -> satisfaction
      low valence (<= -0.3) + high arousal     -> frustration
      low valence (<= -0.3) + not-high arousal -> anxiety
      low arousal (<= -0.3), neutral valence   -> boredom
      else                                     -> neutral
    Best-effort: any malformed affect maps to "neutral"; never raises."""
    try:
        aff = affect or {}
        v = float(aff.get("valence", 0.0) or 0.0)
        a = float(aff.get("arousal", 0.0) or 0.0)
    except Exception:  # noqa: BLE001 -- garbage affect must never raise
        return "neutral"
    if v >= 0.3:
        return "satisfaction"
    if v <= -0.3:
        return "frustration" if a >= 0.3 else "anxiety"
    if a <= -0.3:
        return "boredom"
    return "neutral"


def emotionNudge(behavior_intent: "str | None") -> int:
    """Pure helper: map a coupled behavior intent to a BOUNDED retry-budget delta in
    {0, +1}. Only the clearly-safe subset (escalate_effort, raise_verification) maps
    to +1 -- both read as "carefully try once more", a bounded, non-destructive act.
    Every other intent (explore/propose_refactor/None/unknown) maps to 0 (record-only).
    No side effects, never raises."""
    return 1 if behavior_intent in _SAFE_NUDGE_INTENTS else 0


def emotionAdvisory(state: Any, dashboard: Any = None) -> dict:
    """Wire the Human-Nature emotion faculty as an ADVISORY behavior coupling. Derive an
    emotion label from this run's self-model affect, call ``emotions.couple(label, meta)``,
    RECORD ``{"emotion", "behavior"}`` into ``state.meta["hn_behavior"]``, SURFACE a
    dashboard event, and RETURN the coupling dict. Complete no-op ({}) unless BOTH
    HUMAN_NATURE_ENABLED and HN_EMOTIONS_BEHAVIOR are True. Best-effort (never raises) and
    ADVISORY ONLY: it records + surfaces; it never blocks, aborts, skips/alters verification,
    rejects a plan, or changes control flow. The bounded run effect (a +1 retry nudge for a
    safe intent, via ``emotionNudge``) is applied ONLY at the opt-in call site, clamped there
    to the hard max. Returns the coupling ({"behavior", "comms"}) or {} when disabled/failed."""
    if not (config.HUMAN_NATURE_ENABLED and config.HN_EMOTIONS_BEHAVIOR):
        return {}
    try:
        from human_nature import emotions

        meta = _meta(state)
        self_state = meta.get("self_state") or {}
        label = _affectToLabel(self_state.get("affect"))
        coupling = emotions.couple(label, meta)
        intent = coupling.get("behavior")
        meta.setdefault("hn_behavior", []).append({"emotion": label, "behavior": intent})
        LOG.info("human-nature emotion advisory: %s -> %s", label, intent)
        if dashboard is not None:
            with best_effort("human_nature.emotion_surface", log=LOG):
                dashboard.event(f"emotion — {label} (behavior: {intent})")
        return coupling
    except Exception:  # noqa: BLE001
        LOG.debug("emotionAdvisory failed (ignored)", exc_info=True)
        return {}


# --- Hook 2: intuition dual-process routing -> advisory effort bias --------------
# Ordered effort ladder (lowest -> highest); mirrors config.MODEL_BY_EFFORT routing.
# "medium" is a display alias of "default" and folds onto it before laddering.
_EFFORT_LADDER: tuple[str, ...] = ("low", "default", "high", "xhigh", "ultracode")
_EFFORT_ALIASES: dict[str, str] = {"medium": "default"}


def _retrievalSignals(goal: str, title: str) -> dict:
    """Best-effort {similarity, p_true} from the SIE retrieval ledger. ``similarity`` is
    the top cosine score to a past SUCCESSFUL subtask (clamped to [0,1]); ``p_true`` is the
    pass fraction among near neighbours (successes vs. similar failures). Empty when nothing
    is retrieved -- no fabricated confidence. Never raises."""
    from memory import retrieval

    successes = list(retrieval.retrieve(goal, title) or [])
    if not successes:
        return {}
    out: dict = {}
    top = max((float(r.get("score") or 0.0) for r in successes), default=0.0)
    out["similarity"] = max(0.0, min(1.0, top))
    try:
        failures = list(retrieval.retrieve_failures(goal, title) or [])
    except Exception:  # noqa: BLE001 -- the failure lane is optional; successes still count
        failures = []
    n_ok, n_bad = len(successes), len(failures)
    if n_ok + n_bad:
        out["p_true"] = max(0.0, min(1.0, n_ok / (n_ok + n_bad)))
    return out


def attemptSignals(state: Any, subtask: dict) -> dict:
    """Assemble REAL momentary confidence signals for ``preActRouting`` from data that
    genuinely exists: the SIE retrieval ledger (``memory.retrieval``) and any numeric
    ``confidence`` the brain already put on the subtask. Returns numeric keys intuition
    fuses -- ``similarity`` (top retrieval cosine to a past success, clamped [0,1]) and
    ``p_true`` (near-neighbour pass fraction, or the brain's confidence when retrieval is
    cold). NEVER fabricates confidence: with no real source it returns {} so intuition
    honestly stays on the "deliberate" default. Gated (no-op {} when HN off), best-effort
    (any error -> {}), never raises."""
    # Gate on the shortcut too: when it's off, intuition.route can only return "deliberate", so
    # the (local-Ollama) retrieval embeds here would be pure hot-path waste that can't change routing.
    if not (config.HUMAN_NATURE_ENABLED and config.HN_INTUITION_SHORTCUT):
        return {}
    try:
        goal = _meta(state).get("goal_elaborated") or _meta(state).get("goal_raw") or ""
        title = str(subtask.get("title") or "")
        signals = _retrievalSignals(str(goal), title)
        # Brain-authored confidence: only a source when retrieval didn't already give p_true.
        if "p_true" not in signals:
            conf = subtask.get("confidence")
            if isinstance(conf, (int, float)) and not isinstance(conf, bool):
                signals["p_true"] = max(0.0, min(1.0, float(conf)))
        return signals
    except Exception:  # noqa: BLE001 -- signal assembly must never break an attempt
        LOG.debug("attemptSignals failed (ignored)", exc_info=True)
        return {}


def preActRouting(state: Any, domain: str, signals: "dict | None" = None) -> str:
    """Hook 2: best-effort thin wrapper over ``integration.route_pre_act``. Returns
    "fast" or "deliberate". No-op ("deliberate") when HUMAN_NATURE_ENABLED is off
    (route_pre_act itself gates), and "deliberate" on ANY error. Never raises."""
    if not config.HUMAN_NATURE_ENABLED:
        return "deliberate"
    try:
        from human_nature import integration

        return integration.route_pre_act(state, str(domain), dict(signals or {}))
    except Exception:  # noqa: BLE001
        LOG.debug("preActRouting failed (ignored)", exc_info=True)
        return "deliberate"


def biasEffort(current_effort: str, routing: str) -> str:
    """Pure ADVISORY bias: when *routing* == "fast", drop *current_effort* ONE tier on
    the effort ladder (clamped at the lowest tier); otherwise return it unchanged. It
    can ONLY lower effort, never raise it, and an off-ladder effort is passed through
    untouched. No side effects, never raises."""
    if routing != "fast":
        return current_effort
    key = _EFFORT_ALIASES.get(str(current_effort).lower(), str(current_effort).lower())
    try:
        idx = _EFFORT_LADDER.index(key)
    except ValueError:
        return current_effort  # unknown tier: safe passthrough
    return _EFFORT_LADDER[max(0, idx - 1)]


def runPreambleHooks(state: Any) -> None:
    """Hook 1: lazily initialise self_state at run start. No-op when disabled."""
    if not config.HUMAN_NATURE_ENABLED:
        return
    with best_effort("human_nature.preamble", log=LOG):
        from human_nature import integration

        integration.ensure_self_state(state)


def _meta(state: Any) -> dict:
    return state.data["meta"] if hasattr(state, "data") else state["meta"]


def _scoredJudgments(state: Any) -> list:
    """Build {"domain": str, "correct": bool} from this run's verified subtasks."""
    out = []
    for s in state.subtasks:
        vr = s.get("verify_result") or {}
        if vr:
            out.append({"domain": (s.get("title") or "")[:60], "correct": bool(vr.get("passed"))})
    return out


def _runEvents(state: Any) -> list:
    """Build appraisal events (outcome/agency/novelty) from this run's subtask outcomes."""
    events = []
    for s in state.subtasks:
        if s.get("status") not in ("done", "failed"):
            continue
        # agency is a float in [0,1] (appraisal coerces it via float()); these are the run's
        # OWN subtask outcomes, so self-agency is full (1.0). NOT the string "self" -- that
        # raised ValueError: could not convert string to float: 'self' in the appraisal path.
        events.append(
            {"outcome": "success" if s["status"] == "done" else "failure", "agency": 1.0, "novelty": 0.0}
        )
    return events


def _abMetrics(state: Any) -> dict:
    """test_pass (fraction of verified subtasks that passed) + time_to_green (run elapsed)."""
    from platform_core.orchestration.time_utils import _elapsedSince

    verified = [s.get("verify_result") for s in state.subtasks if s.get("verify_result")]
    test_pass = (sum(1 for v in verified if v.get("passed")) / len(verified)) if verified else 0.0
    meta = _meta(state)
    elapsed = _elapsedSince(meta.get("started_at")) if meta.get("started_at") else 0.0
    return {"test_pass": test_pass, "time_to_green": elapsed}


def runTeardownHooks(orch: Any, state: Any) -> None:
    """Hook 6 (A/B recording) always fires -- both arms need data for comparison.
    Hooks 3/5 (appraisal, consolidation, continuity letter) are gated behind
    HUMAN_NATURE_ENABLED and no-op otherwise. Every step is best-effort: a failure
    here must never fail run teardown."""
    arm = "on" if config.HUMAN_NATURE_ENABLED else "off"
    with best_effort("human_nature.ab_record", log=LOG):
        from human_nature.ab_harness import record_run

        record_run(run_id=state.task_id, arm=arm, metrics=_abMetrics(state))
    if not config.HUMAN_NATURE_ENABLED:
        return
    from human_nature import integration

    with best_effort("human_nature.observe", log=LOG):
        integration.observe_run_events(state, _runEvents(state))
    reflections: list = []
    with best_effort("human_nature.fetch_reflections", log=LOG):
        from memory.experience_solutions import fetch_reflections

        reflections = [
            r.get("text", "") for r in (fetch_reflections(trusted_only=False) or []) if r.get("text")
        ][:10]
    with best_effort("human_nature.consolidation", log=LOG):
        chat = getattr(orch, "_ollamaChat", None)
        integration.at_teardown(state, _scoredJudgments(state), reflections, chat=chat)
    with best_effort("human_nature.continuity", log=LOG):
        from human_nature.continuity import write_letter

        meta = _meta(state)
        self_state = meta.get("self_state") or {}
        write_letter(
            state.task_id,
            body_state={
                "competence": self_state.get("competence"),
                "affect": self_state.get("affect"),
            },
        )
