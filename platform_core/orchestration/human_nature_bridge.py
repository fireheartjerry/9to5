"""Human-Nature layer bridge -- wires human_nature.integration into run-loop boundary hooks.

Confined to run start/end (lowest-risk, zero per-attempt overhead): ensure_self_state at
preamble; appraisal + consolidation + continuity + A/B recording at teardown. This covers
checklist hooks 1, 3, 5, 6 from docs/human-nature/integration-wiring.md. Hook 2 (pre-act
routing in execute_attempt_mixin.py's hot per-attempt path) and hook 4 (mid-run instinct
checkpoint) are deliberately NOT wired here -- both require touching size-constrained,
high-risk hot-path files; see the wiring doc's "Deferred" section for the follow-up plan.

The A/B recording call (hook 6) is the one exception to the enabled-gate: BOTH arms need
rows before ``ab_harness.compare()`` means anything, so it always fires with ``arm`` set
from the live flag. Every other call is a true no-op when ``config.HUMAN_NATURE_ENABLED``
is False (the default) -- byte-identical run behavior.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  midRunInstinct(state: Any, dashboard: Any=None) -> 'str | None'  -- Hook 4: once per run, fire the ledger-grounded instinct ("gut") check and SURFACE the
  runPreambleHooks(state: Any) -> None  -- Hook 1: lazily initialise self_state at run start
  runTeardownHooks(orch: Any, state: Any) -> None  -- Hook 6 (A/B recording) always fires
DEPENDS-ON: config, human_nature.ab_harness, human_nature.continuity, human_nature.integration, memory.experience_adapters, memory.experience_solutions, platform_core.core.best_effort, platform_core.orchestration.time_utils
SIDE-EFFECTS: mutates state.meta when enabled; writes continuity letters + ab_runs.db rows
RUN/TEST: python -m pytest tests/orchestration/test_human_nature_bridge.py
"""
from __future__ import annotations

from typing import Any

import config
from platform_core.core.best_effort import best_effort

LOG = config.getLogger("human_nature_bridge")


def midRunInstinct(state: Any, dashboard: Any = None) -> "str | None":
    """Hook 4: once per run, fire the ledger-grounded instinct ("gut") check and SURFACE the
    advisory flag. Best-effort + gated: no-op when HUMAN_NATURE_ENABLED is off, never raises, and
    never blocks the run -- it only narrates a suspicion drawn from past reflections/failure modes."""
    if not config.HUMAN_NATURE_ENABLED:
        return None
    try:
        from human_nature import integration
        from memory.experience_adapters import fetch_failure_modes
        from memory.experience_solutions import fetch_reflections
        flag = integration.maybe_run_instinct(
            state, fetch_reflections() or [], fetch_failure_modes() or [])
        if flag:
            LOG.info("human-nature instinct: %s", flag)
            if dashboard is not None:
                with best_effort("human_nature.instinct_surface", log=LOG):
                    dashboard.event(f"instinct — {flag}")
        return flag
    except Exception:  # noqa: BLE001
        LOG.debug("midRunInstinct failed (ignored)", exc_info=True)
        return None


def runPreambleHooks(state: Any) -> None:
    """Hook 1: lazily initialise self_state at run start. No-op when disabled."""
    if not config.HUMAN_NATURE_ENABLED:
        return
    with best_effort("human_nature.preamble", log=LOG):
        from human_nature import integration
        integration.ensure_self_state(state)


def _meta(state: Any) -> dict:
    return state.data["meta"] if hasattr(state, "data") else state["meta"]


def _scoredJudgments(state: Any) -> list:
    """Build {"domain": str, "correct": bool} from this run's verified subtasks."""
    out = []
    for s in state.subtasks:
        vr = s.get("verify_result") or {}
        if vr:
            out.append({"domain": (s.get("title") or "")[:60], "correct": bool(vr.get("passed"))})
    return out


def _runEvents(state: Any) -> list:
    """Build appraisal events (outcome/agency/novelty) from this run's subtask outcomes."""
    events = []
    for s in state.subtasks:
        if s.get("status") not in ("done", "failed"):
            continue
        events.append({"outcome": "success" if s["status"] == "done" else "failure",
                       "agency": "self", "novelty": 0.0})
    return events


def _abMetrics(state: Any) -> dict:
    """test_pass (fraction of verified subtasks that passed) + time_to_green (run elapsed)."""
    from platform_core.orchestration.time_utils import _elapsedSince
    verified = [s.get("verify_result") for s in state.subtasks if s.get("verify_result")]
    test_pass = (sum(1 for v in verified if v.get("passed")) / len(verified)) if verified else 0.0
    meta = _meta(state)
    elapsed = _elapsedSince(meta.get("started_at")) if meta.get("started_at") else 0.0
    return {"test_pass": test_pass, "time_to_green": elapsed}


def runTeardownHooks(orch: Any, state: Any) -> None:
    """Hook 6 (A/B recording) always fires -- both arms need data for comparison.
    Hooks 3/5 (appraisal, consolidation, continuity letter) are gated behind
    HUMAN_NATURE_ENABLED and no-op otherwise. Every step is best-effort: a failure
    here must never fail run teardown."""
    arm = "on" if config.HUMAN_NATURE_ENABLED else "off"
    with best_effort("human_nature.ab_record", log=LOG):
        from human_nature.ab_harness import record_run
        record_run(run_id=state.task_id, arm=arm, metrics=_abMetrics(state))
    if not config.HUMAN_NATURE_ENABLED:
        return
    from human_nature import integration
    with best_effort("human_nature.observe", log=LOG):
        integration.observe_run_events(state, _runEvents(state))
    reflections: list = []
    with best_effort("human_nature.fetch_reflections", log=LOG):
        from memory.experience_solutions import fetch_reflections
        reflections = [r.get("text", "") for r in (fetch_reflections(trusted_only=False) or [])
                       if r.get("text")][:10]
    with best_effort("human_nature.consolidation", log=LOG):
        chat = getattr(orch, "_ollamaChat", None)
        integration.at_teardown(state, _scoredJudgments(state), reflections, chat=chat)
    with best_effort("human_nature.continuity", log=LOG):
        from human_nature.continuity import write_letter
        meta = _meta(state)
        self_state = meta.get("self_state") or {}
        write_letter(state.task_id, body_state={
            "competence": self_state.get("competence"),
            "affect": self_state.get("affect"),
        })
