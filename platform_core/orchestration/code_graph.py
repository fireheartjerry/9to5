"""Code-graph blast-radius scoring: SCC condensation + dependency reachability.

Estimates how risky a change is from the import graph, not from diff size. Edge A->B means
"A imports/depends on B", so changing B impacts everything that can REACH B (its dependents).
We collapse import cycles with Tarjan SCC (so circular imports count once), then measure the
touched + downstream-dependent components, weight entrypoints/public-API touches higher, and
bin the result low/medium/high. Everything is pure + deterministic; the repo extractor is
best-effort and FAILS OPEN to a neutral 'medium' when the graph can't be built.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  tarjan_scc(graph) -> list[list[str]]  -- Strongly-connected components (iterative Tarjan).
  component_index(sccs) -> dict[str, int]  -- node -> component id.
  reverse_condensation(graph, comp_of) -> dict[int, set[int]]  -- dependent-direction condensed DAG.
  blast_radius(touched, *, graph, entrypoints, public_api) -> dict  -- Risk verdict for a change set.
  build_import_graph(root) -> dict[str, list[str]]  -- Best-effort import graph via introspect.
  blast_radius_for(touched, *, root) -> dict  -- Build graph + score (fail-open to medium).
DEPENDS-ON: config
SIDE-EFFECTS: build_import_graph reads the project via introspect (best-effort)
RUN/TEST: python -m pytest tests/orchestration/test_code_graph.py
"""
from __future__ import annotations

from typing import Any, Iterable, Optional

import config

LOG = config.getLogger("orchestrator.code_graph")

# blast score -> bin thresholds (score is a weighted component count; see blast_radius).
_LOW_MAX = 2.0
_MEDIUM_MAX = 8.0
_NORM_K = 6.0                       # score/(score+K) -> [0,1)


def _all_nodes(graph: dict[str, Iterable[str]]) -> set[str]:
    nodes = set(graph.keys())
    for dsts in graph.values():
        nodes.update(dsts)
    return nodes


def tarjan_scc(graph: dict[str, Iterable[str]]) -> list[list[str]]:
    """Strongly-connected components via ITERATIVE Tarjan (no recursion depth limit)."""
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    on_stack: set[str] = set()
    stack: list[str] = []
    result: list[list[str]] = []
    counter = 0
    for start in _all_nodes(graph):
        if start in index:
            continue
        index[start] = low[start] = counter
        counter += 1
        stack.append(start)
        on_stack.add(start)
        work: list[tuple[str, Any]] = [(start, iter(graph.get(start, ())))]
        while work:
            node, it = work[-1]
            advanced = False
            for w in it:
                if w not in index:
                    index[w] = low[w] = counter
                    counter += 1
                    stack.append(w)
                    on_stack.add(w)
                    work.append((w, iter(graph.get(w, ()))))
                    advanced = True
                    break
                if w in on_stack:
                    low[node] = min(low[node], index[w])
            if advanced:
                continue
            work.pop()
            if work:
                low[work[-1][0]] = min(low[work[-1][0]], low[node])
            if low[node] == index[node]:
                comp = []
                while True:
                    w = stack.pop()
                    on_stack.discard(w)
                    comp.append(w)
                    if w == node:
                        break
                result.append(comp)
    return result


def component_index(sccs: list[list[str]]) -> dict[str, int]:
    """Map each node to its component id."""
    return {node: cid for cid, comp in enumerate(sccs) for node in comp}


def reverse_condensation(graph: dict[str, Iterable[str]],
                         comp_of: dict[str, int]) -> dict[int, set[int]]:
    """Condensed DAG in the DEPENDENT direction: edge cB->cA when A imports B (so a change
    to B propagates to A). Self-loops (intra-SCC) are dropped."""
    radj: dict[int, set[int]] = {}
    for src, dsts in graph.items():
        cs = comp_of.get(src)
        for dst in dsts:
            cd = comp_of.get(dst)
            if cs is None or cd is None or cs == cd:
                continue
            radj.setdefault(cd, set()).add(cs)     # dependents of cd include cs
    return radj


def _reachable(starts: set[int], radj: dict[int, set[int]]) -> set[int]:
    """All components reachable from ``starts`` over the dependent-direction DAG."""
    seen: set[int] = set(starts)
    stack = list(starts)
    while stack:
        for nxt in radj.get(stack.pop(), ()):
            if nxt not in seen:
                seen.add(nxt)
                stack.append(nxt)
    return seen


def _bin(score: float) -> str:
    return "low" if score <= _LOW_MAX else "medium" if score <= _MEDIUM_MAX else "high"


def blast_radius(touched: Iterable[str], *, graph: dict[str, Iterable[str]],
                 entrypoints: Iterable[str] = (), public_api: Iterable[str] = ()) -> dict:
    """Risk verdict for a change set. Fail-open: empty graph -> degraded 'medium'.

    score = touched_SCCs + downstream_dependent_SCCs + 2*entrypoints_impacted + public_api_touches
    """
    touched = [t for t in touched]
    if not graph:
        return {"bin": "medium", "score": 0.5, "touched_scc": 0, "downstream_scc": 0,
                "entrypoints_impacted": 0, "public_api_touches": 0, "degraded": True}
    sccs = tarjan_scc(graph)
    comp_of = component_index(sccs)
    radj = reverse_condensation(graph, comp_of)
    touched_comps = {comp_of[t] for t in touched if t in comp_of}
    impacted = _reachable(touched_comps, radj)
    downstream = impacted - touched_comps
    impacted_nodes = {n for c in impacted for n in sccs[c]}
    eps = set(entrypoints)
    ep_hit = len(eps & impacted_nodes)
    pub_hit = len(set(public_api) & set(touched))
    raw = len(touched_comps) + len(downstream) + 2 * ep_hit + pub_hit
    return {"bin": _bin(raw), "score": round(raw / (raw + _NORM_K), 4),
            "touched_scc": len(touched_comps), "downstream_scc": len(downstream),
            "entrypoints_impacted": ep_hit, "public_api_touches": pub_hit, "degraded": False}


def build_import_graph(root: Optional[str] = None) -> dict[str, list[str]]:
    """Best-effort import graph (module -> imported modules) via introspect. {} on failure."""
    try:
        from introspect import extractProject
        model = extractProject(root or str(config.PROJECT_ROOT),
                               max_files=getattr(config, "PROJECT_INTROSPECTION_MAX_FILES", 4000))
        graph: dict[str, list[str]] = {}
        for src, dst in getattr(model, "import_edges", ()):
            graph.setdefault(str(src), []).append(str(dst))
        return graph
    except Exception as e:  # noqa: BLE001 -- fail-open: caller degrades to 'medium'
        LOG.debug("import graph build failed (ignored): %s", e)
        return {}


def blast_radius_for(touched: Iterable[str], *, root: Optional[str] = None) -> dict:
    """Convenience: build the repo import graph then score ``touched`` (fail-open to medium)."""
    if not getattr(config, "CODE_GRAPH_ENABLED", True):
        return {"bin": "medium", "score": 0.5, "degraded": True}
    graph = build_import_graph(root)
    ep: tuple = ()
    pub: tuple = ()
    try:
        from introspect import extractProject
        model = extractProject(root or str(config.PROJECT_ROOT),
                               max_files=getattr(config, "PROJECT_INTROSPECTION_MAX_FILES", 4000))
        ep = tuple(getattr(model.boundaries, "entrypoints", ()) or ())
        pub = tuple(getattr(model.boundaries, "facades", ()) or ())
    except Exception as e:  # noqa: BLE001
        LOG.debug("entrypoint/facade extraction failed (ignored): %s", e)
    return blast_radius(touched, graph=graph, entrypoints=ep, public_api=pub)
