"""One on_step callback that fans each executor tool call to BOTH the step journal
(unit a) and the trajectory recorder (unit d). Keeps subprocess_feed ledger-free --
the orchestrator injects this sink. Fail-open: the sink never raises into the feed.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  makeSink(run_id: str, subtask_id: str, attempt: int, plan_sig: str, session_getter: Callable[[], Optional[str]], recorder: Any=None, parent_span_id: Optional[str]=None, profile_meta: Optional[dict]=None) -> Callable[[int, str, str, dict], None]  -- Build the on_step(step_idx, tool, summary, input) callback
  buildAttemptFeed(orch, state, sid: str, attempt: int, resume_session: Optional[str]) -> tuple  -- Wire the live surface feed for ONE Claude-CLI attempt: step-journal sink + trajectory
DEPENDS-ON: config, memory.experience, notifications.runtime.event_bus, notifications.runtime.subprocess_feed, platform_core.orchestration.step_resume
SIDE-EFFECTS: writes journal rows + trajectory spans
RUN/TEST: python -m pytest tests/orchestration/test_step_sink.py
"""
from __future__ import annotations

import time
from typing import Any, Callable, Optional

import config
from memory import experience

LOG = config.getLogger("orchestrator.step_sink")


def makeSink(run_id: str, subtask_id: str, attempt: int, plan_sig: str,
             session_getter: Callable[[], Optional[str]],
             recorder: Any = None, parent_span_id: Optional[str] = None,
             profile_meta: Optional[dict] = None
             ) -> Callable[[int, str, str, dict], None]:
    """Build the on_step(step_idx, tool, summary, input) callback. Every write is best-effort."""

    def _sink(step_idx: int, tool: str, summary: str, tool_input: dict) -> None:
        try:
            session_id = session_getter() if session_getter else None
        except Exception:  # noqa: BLE001
            session_id = None
        try:
            input_obj = tool_input
            if profile_meta:
                input_obj = dict(tool_input or {})
                input_obj.setdefault("_work_profile", profile_meta.get("work_profile"))
                input_obj.setdefault("_run_intent_policy", profile_meta.get("run_intent_policy"))
            experience.appendStep(run_id, subtask_id, attempt, step_idx, "tool", tool,
                                  summary, input_obj, plan_sig, session_id or "")
        except Exception as e:  # noqa: BLE001 -- journaling never crashes a run
            LOG.warning("step_sink journal write failed (ignored): %s", e)
        if recorder is not None:
            try:
                attrs = {"tool": tool}
                if isinstance(tool_input, dict):
                    attrs.update({k: v for k, v in tool_input.items()
                                  if k in ("file_path", "path", "command", "pattern")})
                span_id = recorder.openSpan("tool", parent_span_id, attrs)
                recorder.closeSpan(span_id, usage=None, cost_usd=0.0)
            except Exception as e:  # noqa: BLE001
                LOG.warning("step_sink trajectory write failed (ignored): %s", e)

    return _sink


def buildAttemptFeed(orch, state, sid: str, attempt: int,
                     resume_session: Optional[str]) -> tuple:
    """Wire the live surface feed for ONE Claude-CLI attempt: step-journal sink + trajectory
    executor span (moved from execute_mixin._runOneAttempt for size). Returns
    (feed, recorder, parent_span) -- ALL None on any failure, because the live feed and
    journal are best-effort and must never block an attempt."""
    try:
        from notifications.runtime.event_bus import get_bus
        from notifications.runtime.subprocess_feed import SubprocessFeed
        # Plan signature gates resume; recorded on every journal row (Epic 1b consumer).
        try:
            from platform_core.orchestration.step_resume import planSignature
            plan_sig = planSignature(state)
        except Exception:  # noqa: BLE001 -- step_resume lands in Epic 1b; until then plan_sig=""
            plan_sig = ""
        recorder = orch._trajectoryRecorder(state)
        parent_span = None   # LOCAL (not on self): per-thread so a peer worker can't close it
        if recorder is not None:
            parent_span = recorder.openSpan(
                "executor", None, {"sid": sid, "attempt": attempt,
                                   "work_profile": state.meta.get("work_profile"),
                                   "run_intent_policy": state.meta.get("run_intent_policy")})
        last = {"sid": resume_session}

        def _session_getter():
            s = (state.getSubtask(sid) or {}).get("session") or {}
            return s.get("resume_session_id") or last.get("sid")

        sink = makeSink(state.task_id, sid, attempt, plan_sig, _session_getter,
                        recorder=recorder, parent_span_id=parent_span,
                        profile_meta={
                            "work_profile": state.meta.get("work_profile"),
                            "run_intent_policy": state.meta.get("run_intent_policy"),
                        })
        feed = SubprocessFeed(get_bus(), sid, time.monotonic(), on_step=sink)
        return feed, recorder, parent_span
    except Exception:  # noqa: BLE001 -- live feed + journal are best-effort
        return None, None, None
