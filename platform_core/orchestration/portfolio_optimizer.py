"""Candidate-portfolio selection via maximum-weight closure (s-t min-cut / max-flow).

Picking which inventions to pursue is not a ranked list: candidates have dependencies,
conflicts, cost, and value. We model it as the maximum-weight closure of a directed graph
(positive node weight = expected utility, negative = cost/risk; a dependency edge A->B with
infinite capacity means "choosing A requires B") and solve it exactly with a min-cut over a
Dinic max-flow. The source side of the min cut is the optimal closed set — so a weak
foundation IS chosen when it unlocks a high-value dependent, and standalone negative-value
nodes are rejected. Mutual-exclusion conflicts (which closure can't express) are then repaired
deterministically. Pure + deterministic given the inputs.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  max_closure(weights: dict[Any, float], deps: Iterable[tuple]) -> tuple[set, float]  -- Optimal closed set (source side of min cut) + closure objective
  candidate_weight(c: Any) -> float  -- Node weight = utility - cost/risk
  optimize(candidates: list, *, deps: Iterable[tuple]=(), conflicts: Iterable[tuple]=(), weight_fn: Optional[Callable[[Any], float]]=None, safe_only: bool=False) -> PortfolioSelection  -- Select an optimal candidate bundle under dependencies + conflicts
DEPENDS-ON: config, platform_core.orchestration.invention_types
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/orchestration/test_portfolio_optimizer.py
"""
from __future__ import annotations

from typing import Any, Callable, Iterable, Optional

import config
from platform_core.orchestration.invention_types import PortfolioSelection, clamp01, norm_risk

LOG = config.getLogger("orchestrator.portfolio")

_EPS = 1e-9
_RISK_PEN = {"low": 0.1, "medium": 0.4, "high": 0.9}
_BLAST_PEN = {"low": 0.1, "medium": 0.35, "high": 0.8}


class _Dinic:
    """Minimal float-capacity Dinic max-flow (small graphs: portfolios are < a few hundred)."""

    def __init__(self, n: int) -> None:
        self.n = n
        self.g: list[list[list]] = [[] for _ in range(n)]

    def add(self, u: int, v: int, cap: float) -> None:
        self.g[u].append([v, cap, len(self.g[v])])
        self.g[v].append([u, 0.0, len(self.g[u]) - 1])

    def _bfs(self, s: int, t: int) -> bool:
        self.level = [-1] * self.n
        self.level[s] = 0
        q = [s]
        for u in q:
            for e in self.g[u]:
                if e[1] > _EPS and self.level[e[0]] < 0:
                    self.level[e[0]] = self.level[u] + 1
                    q.append(e[0])
        return self.level[t] >= 0

    def _dfs(self, u: int, t: int, f: float) -> float:
        if u == t:
            return f
        while self.it[u] < len(self.g[u]):
            e = self.g[u][self.it[u]]
            if e[1] > _EPS and self.level[e[0]] == self.level[u] + 1:
                d = self._dfs(e[0], t, min(f, e[1]))
                if d > _EPS:
                    e[1] -= d
                    self.g[e[0]][e[2]][1] += d
                    return d
            self.it[u] += 1
        return 0.0

    def maxflow(self, s: int, t: int) -> float:
        flow = 0.0
        while self._bfs(s, t):
            self.it = [0] * self.n
            while True:
                f = self._dfs(s, t, float("inf"))
                if f <= _EPS:
                    break
                flow += f
        return flow

    def source_side(self, s: int) -> list[bool]:
        seen = [False] * self.n
        seen[s] = True
        stack = [s]
        while stack:
            for e in self.g[stack.pop()]:
                if e[1] > _EPS and not seen[e[0]]:
                    seen[e[0]] = True
                    stack.append(e[0])
        return seen


def max_closure(weights: dict[Any, float], deps: Iterable[tuple]) -> tuple[set, float]:
    """Optimal closed set (source side of min cut) + closure objective. Pure."""
    ids = list(weights.keys())
    if not ids:
        return set(), 0.0
    idx = {cid: i + 2 for i, cid in enumerate(ids)}      # 0 = source, 1 = sink
    inf = sum(abs(w) for w in weights.values()) + 1.0
    d = _Dinic(len(ids) + 2)
    pos_sum = 0.0
    for cid, w in weights.items():
        if w > 0:
            d.add(0, idx[cid], w)
            pos_sum += w
        elif w < 0:
            d.add(idx[cid], 1, -w)
    for a, b in deps:
        if a in idx and b in idx:
            d.add(idx[a], idx[b], inf)                    # pick A => must pick B
    flow = d.maxflow(0, 1)
    reach = d.source_side(0)
    selected = {cid for cid in ids if reach[idx[cid]]}
    return selected, round(pos_sum - flow, 6)


def _get(c: Any, key: str, default: Any = None) -> Any:
    if isinstance(c, dict):
        return c.get(key, default)
    return getattr(c, key, default)


def candidate_weight(c: Any) -> float:
    """Node weight = utility - cost/risk. Positive = worth selecting on its own."""
    impact = clamp01(_get(c, "impact", 0.0))
    novelty = clamp01(_get(c, "measured_novelty", 0.0))
    rarity = clamp01(_get(c, "archive_cell_rarity", 0.0))
    confidence = clamp01(_get(c, "confidence", 0.0))
    feasibility = clamp01(_get(c, "feasibility", confidence))
    risk_pen = _RISK_PEN.get(norm_risk(_get(c, "risk", "medium")), 0.4)
    blast_pen = _BLAST_PEN.get(str(_get(c, "blast_bin", "medium")), 0.35)
    uncertainty = 1.0 - confidence
    cost = 1.0 - feasibility
    return round(1.5 * impact + 1.0 * novelty + 0.5 * rarity + 0.5 * confidence
                 - 0.6 * risk_pen - 0.8 * blast_pen - 0.4 * uncertainty - 0.5 * cost, 6)


def _cid(c: Any) -> str:
    return str(_get(c, "id", None) or _get(c, "title", None) or id(c))


def _is_safe(c: Any) -> bool:
    """Auto-run-safe: low risk AND low blast AND reversible."""
    return (norm_risk(_get(c, "risk", "high")) == "low"
            and str(_get(c, "blast_bin", "high")) == "low"
            and bool(_get(c, "reversible", True)))


def _repair_conflicts(selected: set, weights: dict, conflicts: Iterable[tuple]) -> tuple[set, list]:
    """Drop the lower-utility member of each selected conflicting pair (deterministic)."""
    sel = set(selected)
    repaired: list[list] = []
    for a, b in conflicts:
        if a in sel and b in sel:
            lo = a if weights.get(a, 0.0) < weights.get(b, 0.0) else b
            sel.discard(lo)
            repaired.append([a, b])
    return sel, repaired


def _prune_broken_deps(sel: set, deps: Iterable[tuple]) -> set:
    """After conflict demotion, drop any selected node whose prerequisite is gone."""
    deps = list(deps)
    changed = True
    while changed:
        changed = False
        for a, b in deps:
            if a in sel and b not in sel:
                sel.discard(a)
                changed = True
    return sel


def optimize(candidates: list, *, deps: Iterable[tuple] = (), conflicts: Iterable[tuple] = (),
             weight_fn: Optional[Callable[[Any], float]] = None,
             safe_only: bool = False) -> PortfolioSelection:
    """Select an optimal candidate bundle under dependencies + conflicts. Never raises."""
    wf = weight_fn or candidate_weight
    weights: dict[str, float] = {}
    for c in candidates:
        if safe_only and not _is_safe(c):
            continue                                      # unsafe never enters the auto-run bundle
        weights[_cid(c)] = float(wf(c))
    deps = [(str(a), str(b)) for a, b in deps if str(a) in weights and str(b) in weights]
    conflicts = [(str(a), str(b)) for a, b in conflicts if str(a) in weights and str(b) in weights]
    selected, objective = max_closure(weights, deps)
    selected, repaired = _repair_conflicts(selected, weights, conflicts)
    selected = _prune_broken_deps(selected, deps)
    demoted = [cid for cid in weights if cid not in selected]
    evidence = [f"objective={objective:.3f}", f"selected={len(selected)}/{len(weights)}",
                f"repaired_conflicts={len(repaired)}", f"safe_only={safe_only}"]
    return PortfolioSelection(
        selected_candidate_ids=sorted(selected), demoted_candidate_ids=sorted(demoted),
        dependency_edges=[list(d) for d in deps], conflicts_repaired=repaired,
        objective_value=objective, evidence=evidence)
