"""Deterministic evidence extraction (Aho-Corasick multi-pattern scan).

The innovation report must be grounded in FACTS, not LLM prose. This module scans run text
(verify stdout, receipts, diffs) in a single pass with an Aho-Corasick automaton for evidence
tokens — test-pass markers, factsGate receipts, benchmark phrases, diff summaries, verify
labels, and risk markers (TODO/FIXME/regression). A claim with no supporting evidence is
droppable; TODO/FIXME near a change lowers confidence. Pure + deterministic.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  AhoCorasick  -- Compact multi-pattern string-matching automaton.
  extract_evidence(text, *, module_names) -> dict  -- Structured evidence + refs from run text.
  supports_claim(evidence) -> bool  -- True iff a verify/test/receipt fact is present.
  confidence_adjust(base, evidence) -> float  -- Lower confidence near TODO/FIXME/regression.
DEPENDS-ON: config
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/orchestration/test_evidence_extract.py
"""
from __future__ import annotations

from collections import deque
from typing import Iterable, Optional

import config

LOG = config.getLogger("orchestrator.evidence")

# Evidence categories -> lowercase patterns. Order-independent; scanned in one pass.
_CATEGORIES: dict[str, tuple[str, ...]] = {
    "test_pass": ("passed", "tests passed", "0 failed", "all tests pass", " ok ", "green"),
    "factsgate": ("verified", "factsgate", "facts gate", "receipt", "verify_passed"),
    "verify_ok": ("returncode 0", "return code 0", "exit code 0", "exit 0"),
    "benchmark": ("faster", "latency", "throughput", "reduction", "speedup", "x faster",
                  "coverage", "qd_score", "qd score"),
    "diff": ("diff --git", "files changed", "insertions", "deletions", "+++ b/"),
    "risk": ("todo", "fixme", "xxx", "hack", "regression", "broken", "flaky"),
}
_SUPPORTING = ("test_pass", "factsgate", "verify_ok")


class AhoCorasick:
    """Compact multi-pattern automaton: add() patterns, then find() all matches in one pass."""

    def __init__(self) -> None:
        self.goto: list[dict[str, int]] = [{}]
        self.fail: list[int] = [0]
        self.out: list[list[tuple[str, str]]] = [[]]
        self._built = False

    def add(self, pattern: str, tag: str = "") -> None:
        s = 0
        for ch in pattern:
            nxt = self.goto[s].get(ch)
            if nxt is None:
                nxt = len(self.goto)
                self.goto.append({})
                self.fail.append(0)
                self.out.append([])
                self.goto[s][ch] = nxt
            s = nxt
        self.out[s].append((pattern, tag))

    def build(self) -> None:
        q: deque[int] = deque()
        for s in self.goto[0].values():
            q.append(s)
        while q:
            r = q.popleft()
            for ch, s in self.goto[r].items():
                q.append(s)
                f = self.fail[r]
                while f and ch not in self.goto[f]:
                    f = self.fail[f]
                self.fail[s] = self.goto[f].get(ch, 0) if f or ch in self.goto[0] else 0
                if self.fail[s] == s:
                    self.fail[s] = 0
                self.out[s] = self.out[s] + self.out[self.fail[s]]
        self._built = True

    def find(self, text: str) -> list[tuple[int, str, str]]:
        if not self._built:
            self.build()
        s = 0
        res: list[tuple[int, str, str]] = []
        for i, ch in enumerate(text):
            while s and ch not in self.goto[s]:
                s = self.fail[s]
            s = self.goto[s].get(ch, 0)
            for pat, tag in self.out[s]:
                res.append((i - len(pat) + 1, pat, tag))
        return res


_AUTOMATON: Optional[AhoCorasick] = None


def _automaton() -> AhoCorasick:
    global _AUTOMATON
    if _AUTOMATON is None:
        ac = AhoCorasick()
        for tag, pats in _CATEGORIES.items():
            for p in pats:
                ac.add(p, tag)
        ac.build()
        _AUTOMATON = ac
    return _AUTOMATON


def extract_evidence(text: str, *, module_names: Iterable[str] = ()) -> dict:
    """Scan ``text`` for evidence tokens; return structured facts + citable refs."""
    low = (text or "").lower()
    hits = _automaton().find(low) if low else []
    counts: dict[str, int] = {}
    tags: dict[str, list[str]] = {}
    refs: list[str] = []
    for pos, pat, tag in hits:
        counts[tag] = counts.get(tag, 0) + 1
        tags.setdefault(tag, [])
        if pat not in tags[tag]:
            tags[tag].append(pat)
            refs.append(f"{tag}:{pat}@{pos}")
    modules = [m for m in module_names if m and m.lower() in low]
    refs += [f"module:{m}" for m in modules]
    supported = any(counts.get(t, 0) for t in _SUPPORTING)
    return {"counts": counts, "tags": tags, "modules": modules, "evidence_refs": refs,
            "risk_markers": counts.get("risk", 0), "supported": supported}


def supports_claim(evidence: dict) -> bool:
    """True iff a re-derivable verify/test/receipt fact backs the claim."""
    return bool(evidence.get("supported"))


def confidence_adjust(base: float, evidence: dict) -> float:
    """Lower confidence in the presence of TODO/FIXME/regression markers (capped)."""
    penalty = 0.1 * min(int(evidence.get("risk_markers", 0)), 3)
    return max(0.0, min(1.0, float(base) - penalty))
