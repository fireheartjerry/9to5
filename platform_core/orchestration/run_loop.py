def _execCwd(state, sid: "str | None", work_dir: str) -> str:
    """For self-referential runs, give the executor an isolated cwd so the living CLAUDE.md never
    clobbers the project's own CLAUDE.md.  For non-self-ref runs the cwd IS work_dir.

    Epic 8: when the execution fabric is enabled with a NON-local backend, that backend's
    provision (e.g. a git worktree) supplies the isolated tree, so the .sc-ctx scratch is
    skipped -- it would be redundant. Fabric off, or the local backend, keeps today's scratch."""
    if (config.EXECUTION_FABRIC_ENABLED
            and (config.EXECUTION_BACKEND or "local") != "local"):
        return work_dir
    if (state.meta.get("is_self_referential")
            and os.path.abspath(work_dir) == os.path.abspath(str(config.PROJECT_ROOT))):
        ctx = os.path.join(str(config.PROJECT_ROOT), ".sc-ctx", sid or "architect")
        os.makedirs(ctx, exist_ok=True)
        return ctx
    return work_dir


def _detectSelfReferential(state, work_dir: str) -> bool:
    """Return True only when the selected work_dir is the 9to5 install root.

    A user-provided external work_dir must never be reclassified from goal text; otherwise phrases
    like "make this app improve itself" can create branches and apply core-file locks in the user's
    target repo.
    """
    return os.path.abspath(work_dir).lower() == os.path.abspath(str(config.PROJECT_ROOT)).lower()


def _prepareSelfReferential(state, work_dir: str, bus, dashboard) -> None:
    """Create (or resume) the isolation branch for a self-referential run and notify Discord."""
    from notifications import discord_bot as discord
    branch = f"{config.SELF_REF_BRANCH_PREFIX}{state.task_id[:8]}"
    state.markSelfReferential(branch)
    try:
        t = config.GIT_TIMEOUT_SECONDS
        repo_ok, _reason = git_io.gitPreflight(work_dir, timeout=t)
        if repo_ok:
            exists = git_io.runGit("rev-parse", "--verify", branch,
                                   cwd=work_dir, timeout=t).returncode == 0
            git_io.runGit(*(("checkout", branch) if exists else ("checkout", "-B", branch)),
                          cwd=work_dir, timeout=t)
            LOG.info("Self-referential task -> %s branch %s",
                     "resumed" if exists else "created", branch)
        else:
            LOG.warning("Self-ref task but %s is not a git repo; no isolation branch", work_dir)
    except Exception as e:  # noqa: BLE001
        LOG.warning("self-ref branch creation failed: %s", e)
    discord.sendEmbed(discord.selfRefEmbed(branch, config.CORE_PROTECTED_FILES))
    dashboard.event(f"self-referential · branch {branch}")


