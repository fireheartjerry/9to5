"""Bounded generational loop for solution-space forking (MAP-Elites over generations).

Turns E6's one-shot breadth-N fork into a bounded generational search: each generation runs
a batch, its verified results become QD elites, and the NEXT generation is seeded from DIVERSE
archive elites + recombination of them (open-ended, not greedy-top). The loop stops at the
generation cap, a cost/wall-clock ceiling, or a QD-score plateau. This module is pure — it
takes an injected ``run_gen`` callback so it is fully testable without the real fork machinery,
and it accumulates into a QDArchive so "did later generations get more diverse wins" is
measurable.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  qd_plateaued(history: list[float], patience: int) -> bool  -- True when the last ``patience`` generations produced no qd_score improvement.
  next_generation_seeds(archive: QDArchive, base_angles: list, *, n: int=3) -> list[str]  -- Seed the next generation from diverse elites + a recombination graft (not greedy-top).
  run_generational(*, generations: int, run_gen: Callable[[int, list], list], base_angles: list, cost_ceiling: float=0.0, wallclock_ceiling: float=0.0, patience: Optional[int]=None, now_fn: Optional[Callable[[], float]]=None, cost_fn: Optional[Callable[[], float]]=None, archive: Optional[QDArchive]=None) -> dict  -- Run up to ``generations`` batches, seeding each from the QD archive
DEPENDS-ON: config, platform_core.orchestration.qd_archive, platform_core.orchestration.qd_emitters
SIDE-EFFECTS: none (run_gen callback is caller-supplied)
RUN/TEST: python -m pytest tests/orchestration/test_generational.py
"""
from __future__ import annotations

from typing import Any, Callable, Optional

import config
from platform_core.orchestration import qd_emitters
from platform_core.orchestration.qd_archive import QDArchive

LOG = config.getLogger("orchestrator.generational")


def qd_plateaued(history: list[float], patience: int) -> bool:
    """True when the last ``patience`` generations produced no qd_score improvement."""
    patience = max(1, int(patience))
    if len(history) <= patience:
        return False
    baseline = history[-patience - 1]
    return max(history[-patience:]) <= baseline + 1e-9


def next_generation_seeds(archive: QDArchive, base_angles: list, *, n: int = 3) -> list[str]:
    """Seed the next generation from diverse elites + a recombination graft (not greedy-top)."""
    seeds: list[str] = list(base_angles)
    elites = archive.diverse_elites(n)
    for e in elites:
        seeds.append(f"build on elite {e.candidate_id} in cell {e.cell.subsystem} "
                     f"(novelty bin {e.cell.novelty_bin})")
    parents = [{"id": e.candidate_id, "target_cell": e.cell.key(),
                "target_subsystems": [e.cell.subsystem],
                "measured_novelty": float((e.metrics or {}).get("measured_novelty", 0.0))}
               for e in elites]
    matches = qd_emitters.match_parents(parents)
    if matches:
        a, b, _ = matches[0]
        seeds.append(f"graft {a['id']} + {b['id']} (recombination)")
    out: list[str] = []
    for s in seeds:                                    # de-dupe, preserve order
        if s not in out:
            out.append(s)
    return out[:max(1, n * 2)]


def run_generational(*, generations: int, run_gen: Callable[[int, list], list], base_angles: list,
                     cost_ceiling: float = 0.0, wallclock_ceiling: float = 0.0,
                     patience: Optional[int] = None, now_fn: Optional[Callable[[], float]] = None,
                     cost_fn: Optional[Callable[[], float]] = None,
                     archive: Optional[QDArchive] = None) -> dict:
    """Run up to ``generations`` batches, seeding each from the QD archive. Never raises.

    ``run_gen(gen, seeds) -> list[QDElite]`` runs one batch and returns its verified elites.
    Stops early on cost/wall-clock ceiling (0 = disabled) or a qd_score plateau."""
    archive = archive or QDArchive()
    patience = int(patience if patience is not None else getattr(config, "QD_PLATEAU_PATIENCE", 2))
    now_fn = now_fn or (lambda: 0.0)
    cost_fn = cost_fn or (lambda: 0.0)
    start = now_fn()
    qd_history: list[float] = []
    seeds = list(base_angles)
    gens_run = 0
    stop_reason = "generations_exhausted"
    for gen in range(max(1, int(generations))):
        if gen > 0:
            if cost_ceiling and cost_fn() > cost_ceiling:
                stop_reason = "cost_ceiling"
                break
            if wallclock_ceiling and (now_fn() - start) > wallclock_ceiling:
                stop_reason = "wallclock_ceiling"
                break
            if qd_plateaued(qd_history, patience):
                stop_reason = "qd_plateau"
                break
        try:
            elites = run_gen(gen, seeds) or []
        except Exception as e:  # noqa: BLE001 -- a bad generation must not kill the search
            LOG.warning("generation %d failed (ignored): %s", gen, e)
            elites = []
        for el in elites:
            try:
                archive.add(el)
            except Exception as e:  # noqa: BLE001
                LOG.debug("archive add failed (ignored): %s", e)
        qd_history.append(archive.qd_score())
        gens_run += 1
        seeds = next_generation_seeds(archive, base_angles, n=max(1, len(base_angles) or 3))
    champs = archive.champions()
    return {"best": champs[0] if champs else None, "generations_run": gens_run,
            "qd_history": qd_history, "coverage": archive.coverage(),
            "stop_reason": stop_reason, "archive": archive}
