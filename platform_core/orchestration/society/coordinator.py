"""Coordinator -- deterministic Python workforce orchestration (NOT a new LLM).

Decompose (reuse OrchestratorPlanMixin.authorSubtaskPlan) -> select a file-disjoint
batch (Epic-1 seam) -> spawn one WorkerAgent per claim in a ThreadPoolExecutor
mirroring run_loop_mixin._handleParallelBatch (same crash containment) -> collect
results from the blackboard. A HARD pre-spawn budget gate consults budgetExceeded()
before every spawn; once spend breaches SOCIETY_TOKEN_BUDGET_USD the remaining batch
is skipped and a `budget` entry is posted. Task JSON owns status/claim; the verifier
still gates. Workers never spawn sub-workers.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  busMirror(task_id: str, bus=None) -> Callable[[dict], None]  -- Build a presentation-only on_append hook mirroring blackboard appends to the bus.
  Coordinator  -- Owns workforce orchestration over the blackboard
DEPENDS-ON: config, notifications.event_bus, platform_core.orchestration.society.blackboard, platform_core.orchestration.society.debate, platform_core.orchestration.society.roles, platform_core.orchestration.society.worker, state.task
SIDE-EFFECTS: claims/updates task JSON, runs workers, appends to the blackboard
RUN/TEST: python -m pytest tests/orchestration/test_society_coordinator.py
"""
from __future__ import annotations

from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import Callable, Optional

import config
from notifications.event_bus import Event, get_bus
from platform_core.orchestration.society.blackboard import makeEntry
from platform_core.orchestration.society.roles import classifyRole
from platform_core.orchestration.society.worker import WorkerAgent
from state.task import nowIso

LOG = config.getLogger("society.coordinator")


def busMirror(task_id: str, bus=None) -> Callable[[dict], None]:
    """Build a presentation-only on_append hook mirroring blackboard appends to the bus.

    Passed to ``Blackboard.forTask(..., on_append=busMirror(task_id))`` so the hook
    travels through the constructor instead of anything reaching into ``_on_append``.
    The blackboard stays the source of truth; event_bus stays ephemeral fan-out."""
    def _mirror(rec: dict) -> None:
        try:
            (bus or get_bus()).emit(Event(
                kind="society", sid=str(task_id),
                text=f"{rec.get('author')} -> {rec.get('to')}: {rec.get('kind')}",
                data=rec))
        except Exception:  # noqa: BLE001 -- the mirror must never break coordination
            LOG.warning("society bus mirror failed", exc_info=True)
    return _mirror


class Coordinator:
    """Owns workforce orchestration over the blackboard; never owns run state."""

    def __init__(self, state, blackboard, state_lock, *, work_dir: str) -> None:
        self._state = state
        self._blackboard = blackboard
        self._state_lock = state_lock
        self._work_dir = work_dir
        self.spent_usd = 0.0

    def selectDisjointBatch(self, ready: list, max_workers: int,
                            file_sets_fn: Optional[Callable] = None) -> list:
        """Pick up to max_workers ready subtasks with DISJOINT file-sets (Epic-1 CAS seam).

        SEAM: file_sets_fn(subtask) -> set[str]. When None (no Epic 1), fall back to the
        deps-only batch -- identical to today's _handleParallelBatch scheduling."""
        if file_sets_fn is None:
            return ready[:max_workers]
        chosen, used = [], set()
        for st in ready:
            # The run loop normally supplies only pending work, but a concurrent
            # claim can make that snapshot stale before this batch is selected.
            # Skip it so it cannot block later runnable subtasks.
            if st.get("status") != "pending":
                continue
            files = file_sets_fn(st) or set()
            # Keep the society path consistent with parallel_safety.safeParallelSet:
            # an absent file set means we cannot prove this subtask is independent.
            # Treating it as an empty set used to let the society batch run unknown
            # edit scopes concurrently, which can produce conflicting changes.
            if not files:
                if not chosen:
                    chosen.append(st)
                break
            if files & used:
                continue
            used |= files
            chosen.append(st)
            if len(chosen) >= max_workers:
                break
        return chosen

    def _postBudgetStop(self, skipped: list) -> None:
        """Post one `budget` entry recording the spend breach + the skipped subtask ids."""
        LOG.warning("society budget exceeded (%.4f >= %.4f USD); skipping %d subtask(s)",
                    self.spent_usd, config.SOCIETY_TOKEN_BUDGET_USD, len(skipped))
        self._blackboard.append(makeEntry(
            kind="budget", author="coordinator", to="all",
            value={"spent_usd": self.spent_usd,
                   "budget_usd": float(config.SOCIETY_TOKEN_BUDGET_USD),
                   "skipped": [s.get("subtask_id") for s in skipped]}))

    def _handleSocietyBatch(self, batch: list, parallelism: int,
                            run_fn: Optional[Callable] = None) -> list:
        """Spawn one WorkerAgent per subtask concurrently; collect WorkerMessages.

        HARD pre-spawn budget gate: budgetExceeded() is consulted before every spawn;
        once tripped the remaining batch is skipped and a `budget` entry is posted.

        Mirrors run_loop_mixin._handleParallelBatch crash containment: a crashed worker
        flips its subtask to 'failed' and records a notification; peers are unaffected."""
        messages: list = []
        with ThreadPoolExecutor(max_workers=max(1, parallelism)) as pool:
            futures = {}
            for i, st in enumerate(batch):
                if self.budgetExceeded():
                    self._postBudgetStop(batch[i:])
                    break
                role = classifyRole(st, hint=st.get("assigned_role", ""),
                                    work_profile=(self._state.meta or {}).get("work_profile"))
                worker = WorkerAgent(role, st, self._work_dir, self._blackboard,
                                     self._state, self._state_lock, run_fn=run_fn)
                futures[pool.submit(worker.run)] = st
            for f in as_completed(futures):
                st = futures[f]
                try:
                    msg = f.result()
                    messages.append(msg)
                    cost = (msg.get("value") or {}).get("cost_usd")
                    if isinstance(cost, (int, float)):
                        self.spent_usd += float(cost)
                except Exception as e:  # noqa: BLE001 -- a crashed worker must not strand the subtask
                    LOG.error("society worker %s crashed: %s",
                              st.get("subtask_id"), e, exc_info=True)
                    with self._state_lock:
                        self._state.updateSubtask(st["subtask_id"], status="failed",
                                                  completed_at=nowIso())
                        self._state.addNotification(
                            "subtask_crashed", f"{st.get('subtask_id')}: {e}")
        return messages

    def detectContested(self, messages: list) -> list:
        """Subtask ids with conflicting worker verdicts (any not-ok report) -> need debate."""
        contested = []
        for sid in {m.get("subtask_id") for m in messages}:
            verdicts = [m.get("ok") for m in messages if m.get("subtask_id") == sid]
            if any(v is False for v in verdicts):
                contested.append(sid)
        return sorted(c for c in contested if c)

    def resolveContested(self, messages: list) -> list:
        """Run bounded debate for each contested subtask id; advisory only (never re-gates).

        Roster = distinct roles that posted a message for that subtask id. Fewer than 2
        roles means there is nothing to debate (single-claim CAS means this is a no-op on
        today's one-worker-per-subtask path; it activates once multiple workers can post
        competing results for the same subtask, e.g. Epic-6 solution-space forking).
        Debate failures are logged and swallowed -- the verifier already landed the
        subtask's terminal status; debate can never re-open or override it here."""
        verdicts = []
        for sid in self.detectContested(messages):
            roster = sorted({m.get("role") for m in messages
                             if m.get("subtask_id") == sid and m.get("role")})
            if len(roster) < 2:
                continue
            try:
                from platform_core.orchestration.society.debate import runDebate
                goal = (self._state.meta or {}).get("goal", "")
                v = runDebate(self._blackboard, sid, roster, goal=goal)
            except Exception as e:  # noqa: BLE001 -- debate is advisory; never break the batch
                LOG.warning("debate failed for %s: %s", sid, e, exc_info=True)
                continue
            verdicts.append({"subtask_id": sid, **v})
        return verdicts

    def budgetExceeded(self) -> bool:
        """True once accumulated worker spend breaches SOCIETY_TOKEN_BUDGET_USD."""
        return self.spent_usd >= config.SOCIETY_TOKEN_BUDGET_USD
