"""Emitter budget allocation: UCB value estimate + min-cost/max-cost flow under hard caps.

Heterogeneous emitters (cheap Ollama, deep Claude, recombination, random) compete for a
scarce fork budget. A UCB bandit estimates each emitter's recent value; a min-cost flow
(rewards negated) then allocates the fixed budget across (emitter -> QD cell) edges to
MAXIMIZE total expected quality-diversity gain without ever exceeding a cap. Only beneficial
(positive-reward) allocations are made, and the result is deterministic given seeded inputs.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  UCB  -- Per-emitter upper-confidence-bound value tracker.
  MinCostFlow  -- Successive-shortest-path min-cost flow (negated rewards = max reward).
  allocate(emitters, cells, *, fork_budget, emitter_caps, cell_caps, reward_fn, ucb) -> list  -- Budget plan.
DEPENDS-ON: config, platform_core.orchestration.invention_types
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/orchestration/test_emitter_scheduler.py
"""
from __future__ import annotations

import math
from collections import deque
from typing import Any, Callable, Optional

import config
from platform_core.orchestration.invention_types import EmitterAllocation

LOG = config.getLogger("orchestrator.emitter_scheduler")

_INF = float("inf")
_EPS = 1e-9
# Per-use cost of an emitter (deep models cost more; used by the default reward).
_EMITTER_COST = {"ollama": 0.1, "claude": 1.0, "recombination": 0.3, "random": 0.15}


class UCB:
    """Per-emitter UCB value tracker: unpulled emitters are optimistic; means + exploration bonus."""

    def __init__(self, c: Optional[float] = None) -> None:
        self.c = float(c if c is not None else getattr(config, "EMITTER_UCB_C", 1.4))
        self.pulls: dict[str, int] = {}
        self.reward: dict[str, float] = {}

    def update(self, emitter: str, reward: float) -> None:
        self.pulls[emitter] = self.pulls.get(emitter, 0) + 1
        self.reward[emitter] = self.reward.get(emitter, 0.0) + float(reward)

    def score(self, emitter: str) -> float:
        n = self.pulls.get(emitter, 0)
        if n == 0:
            return 1.0                                      # optimistic: explore untried emitters
        total = sum(self.pulls.values())
        mean = self.reward[emitter] / n
        return mean + self.c * math.sqrt(math.log(max(1, total)) / n)


class MinCostFlow:
    """Successive-shortest-path (SPFA) min-cost flow; augments only while cost < 0 (max reward)."""

    def __init__(self, n: int) -> None:
        self.n = n
        self.g: list[list[list]] = [[] for _ in range(n)]

    def add(self, u: int, v: int, cap: int, cost: float) -> None:
        self.g[u].append([v, cap, cost, len(self.g[v])])
        self.g[v].append([u, 0, -cost, len(self.g[u]) - 1])

    def run(self, s: int, t: int, maxf: int) -> tuple[int, float]:
        flow, cost = 0, 0.0
        while flow < maxf:
            dist = [_INF] * self.n
            inq = [False] * self.n
            pv = [-1] * self.n
            pe = [-1] * self.n
            dist[s] = 0.0
            q = deque([s])
            inq[s] = True
            while q:
                u = q.popleft()
                inq[u] = False
                for i, e in enumerate(self.g[u]):
                    v, cap, c, _ = e
                    if cap > 0 and dist[u] + c < dist[v] - _EPS:
                        dist[v] = dist[u] + c
                        pv[v], pe[v] = u, i
                        if not inq[v]:
                            q.append(v)
                            inq[v] = True
            if dist[t] == _INF or dist[t] >= -_EPS:
                break                                       # no beneficial augmenting path
            d = maxf - flow
            v = t
            while v != s:
                d = min(d, self.g[pv[v]][pe[v]][1])
                v = pv[v]
            v = t
            while v != s:
                e = self.g[pv[v]][pe[v]]
                e[1] -= d
                self.g[v][e[3]][1] += d
                v = pv[v]
            flow += d
            cost += d * dist[t]
        return flow, round(cost, 6)


def _default_reward(ucb: UCB) -> Callable[[str, dict], float]:
    def reward(emitter: str, cell: dict) -> float:
        return round(0.5 * ucb.score(emitter) + float(cell.get("qd_gain", 0.0))
                     + float(cell.get("rarity", 0.0)) - _EMITTER_COST.get(emitter, 0.3), 6)
    return reward


def allocate(emitters: list[str], cells: list[dict], *, fork_budget: int,
             emitter_caps: Optional[dict] = None, cell_caps: Optional[dict] = None,
             reward_fn: Optional[Callable[[str, dict], float]] = None,
             ucb: Optional[UCB] = None) -> list[EmitterAllocation]:
    """Allocate ``fork_budget`` forks across (emitter, cell) pairs to maximize expected QD gain.

    Hard caps are never exceeded; only positive-reward allocations are made; deterministic."""
    if not emitters or not cells or fork_budget <= 0:
        return []
    ucb = ucb or UCB()
    reward_fn = reward_fn or _default_reward(ucb)
    ecaps = emitter_caps or {}
    ccaps = cell_caps or {}
    n = 2 + len(emitters) + len(cells)                      # 0=S, 1=T
    mcf = MinCostFlow(n)
    e_node = {e: 2 + i for i, e in enumerate(emitters)}
    c_node = {c["key"]: 2 + len(emitters) + i for i, c in enumerate(cells)}
    for e in emitters:
        mcf.add(0, e_node[e], int(ecaps.get(e, fork_budget)), 0.0)
    for c in cells:
        cap = int(ccaps.get(c["key"], 1))                   # 1 fork/cell/generation by default
        mcf.add(c_node[c["key"]], 1, cap, 0.0)
        for e in emitters:
            r = reward_fn(e, c)
            if r > 0:                                        # only offer beneficial edges
                mcf.add(e_node[e], c_node[c["key"]], cap, -r)
    mcf.run(0, 1, int(fork_budget))
    return _read_allocations(mcf, emitters, cells, e_node, c_node, reward_fn)


def _read_allocations(mcf: MinCostFlow, emitters, cells, e_node, c_node, reward_fn) -> list:
    """Recover per-(emitter,cell) flow from residual capacities into EmitterAllocations."""
    cell_by_node = {c_node[c["key"]]: c for c in cells}
    out: list[EmitterAllocation] = []
    for e in emitters:
        for edge in mcf.g[e_node[e]]:
            v, cap, cost, rev_idx = edge
            if v in cell_by_node and cost < 0:               # a forward reward edge (cost = -reward)
                flow = mcf.g[v][rev_idx][1]                  # reverse-edge residual == flow pushed
                if flow > 0:
                    cell = cell_by_node[v]
                    out.append(EmitterAllocation(
                        emitter=e, target_cell=cell["key"], budget={"forks": int(flow)},
                        expected_qd_gain=reward_fn(e, cell), reason="mcmf"))
    return out
