from __future__ import annotations

import json

import config
from learning import reflection, solution_cache
from memory import experience
from platform_core.orchestration import clarification_replan, dual_ledger_planner as dlp
from state.task import TaskState

LOG = config.getLogger("orchestrator")


def runSieAndReplan(orch, state: TaskState, subtask: dict, spec: dict, combined: str,
                    passed: bool, final: str, architect_doc: str,
                    dashboard, adv_verdict, adv_stub: bool,
                    result: dict | None = None) -> None:
    """Capture SIE reflection, memoize passing spec, and trigger adaptive replan."""
    sid = subtask["subtask_id"]
    try:
        reflection.capture(run_id=state.task_id, subtask_id=sid, executor_output=combined,
                           verify_passed=passed, adversary_verdict=adv_verdict,
                           adversary_stub=adv_stub)
        if passed and spec.get("prompt"):
            solution_cache_spec = json.dumps({k: spec.get(k) for k in
                ("prompt", "effort_level", "skills_to_invoke", "subagent") if spec.get(k)})
            experience.upsert_solution(solution_cache.signature_of(subtask.get("title", "")),
                                       solution_cache_spec, verify_passed=True,
                                       provenance=json.dumps({
                                           "origin": "executor",
                                           "work_profile": state.meta.get("work_profile"),
                                           "run_intent_policy": state.meta.get("run_intent_policy"),
                                       }))
    except Exception:  # noqa: BLE001 -- learning never affects the run
        pass
    if (config.CLARIFICATION_REPLANNER_ON_BLOCK and isinstance(result, dict)
            and result.get("subtype") == "blocked_clarification"):
        decision = clarification_replan.blockedClarificationDecision(subtask, result)
        dashboard.update(state, "replanning", f"readonly probe after {sid}")
        with orch._state_lock:
            orch._applyReplan(state, decision)
        return
    # Epic 2 (steal #2): when the dual-ledger planner is on, drive replanning from the Progress
    # Ledger + stall counter (root-cause rewrite at STALL_THRESHOLD) instead of the greedy heuristic.
    if config.DUAL_LEDGER_PLANNER_ENABLED:
        orch._progressLedgerReplan(state, subtask, combined, architect_doc, dashboard)
        return
    # Legacy path: replan after a PASSED subtask always; after a FAILED one ONLY on a self-ref run.
    # Churn (fail -> re-add -> fail) is bounded by the no-progress livelock guard and pending cap.
    self_ref = bool(state.meta.get("is_self_referential"))
    replan_ok = final == "done" or (self_ref and final == "failed")
    if replan_ok and not orch._singleDeliverable(state.meta.get("goal_elaborated", "")):
        with orch._state_lock:                       # snapshot for parallel-safety
            subs_snapshot = list(state.subtasks)
        decision = orch._replan(state.meta["goal_elaborated"], subs_snapshot, subtask, combined,
                                self_referential=bool(state.meta.get("is_self_referential")),
                                remaining_hours=orch._remainingHours(state),
                                work_profile=state.meta.get("work_profile"))
        if decision.get("action") == "mutate" and (decision.get("add") or decision.get("remove")):
            dashboard.update(state, "replanning", f"replanning after {sid}")
            with orch._state_lock:
                orch._applyReplan(state, decision)
            from notifications import run_arc as _arc
            orch._arcBeat(state, _arc.beat_replan(f"after {sid}"))
            orch._narrate(f"🔁 Replanning after {sid}. Scope was wider than expected.")


def progressLedgerReplan(orch, state: TaskState, subtask: dict, combined: str,
                         architect_doc: str, dashboard) -> None:
    """Dual-ledger replan driver: one tiny Progress Ledger call updates the stall counter; at
    STALL_THRESHOLD fire exactly one root-cause facts+plan rewrite. Best-effort."""
    sid = subtask["subtask_id"]
    if orch._singleDeliverable(state.meta.get("goal_elaborated", "")):
        return
    goal = state.meta.get("goal_elaborated") or state.meta.get("goal_raw", "")
    progress = dlp.progressLedgerStep(orch._ollamaChat, goal, combined)
    if progress is None:
        return
    with orch._state_lock:
        cur = int(state.meta.get("stall_count", 0))
        new_count = dlp.updateStallCount(progress, cur)
        state.meta["stall_count"] = new_count
        state.save()
    if new_count >= config.STALL_THRESHOLD:
        dashboard.update(state, "replanning", f"root-cause replan after {sid} (stall {new_count})")
        summary = f"stalled after {sid}: {((progress.get('instruction') or {}).get('answer'))}"
        orch._stallReplan(state, architect_doc, summary)
