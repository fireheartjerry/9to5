"""Staging environment validator — runs pre-deployment checks automatically.

Called from CI (via tests.yml) and locally before deploying to verify that
all critical modules import cleanly, the CI workflow is intact, and the repo
is in a consistent state.

Usage:
    python -m platform_core.ops.staging_validator         # runs all gates; exits 0 or 1
    python -m platform_core.ops.staging_validator --quiet # suppress detail lines

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  validate() -> list[dict]  -- Run all staging gates
  main(quiet: bool=False) -> int
DEPENDS-ON: config
SIDE-EFFECTS: stdout
RUN/TEST: python -m pytest tests/platform/test_staging_validator.py
"""
from __future__ import annotations

import importlib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

# Modules that must import cleanly for the system to function at all.
_CRITICAL_MODULES = [
    "config",
    "platform_core.ops.health",
    "platform_core.runtime.control",
    "state.task",
    "agents.verifier",
    "agents.executor",
]

# Steps that must appear in the main CI workflow.
_REQUIRED_CI_STEPS = [
    "validate_workflows.py",
    'pytest -m "not slow"',   # the fast-lane test step (replaced `unittest discover`)
]


def _gateImports() -> list[dict]:
    """Verify every critical module imports without error."""
    results = []
    for mod in _CRITICAL_MODULES:
        try:
            importlib.import_module(mod)
            results.append({"gate": f"import:{mod}", "passed": True, "detail": "ok"})
        except Exception as exc:  # noqa: BLE001
            results.append({"gate": f"import:{mod}", "passed": False,
                            "detail": str(exc)[:200]})
    return results


def _gateCiWorkflow() -> list[dict]:
    """Verify .github/workflows/tests.yml exists and contains required steps."""
    results = []
    ci_path = REPO_ROOT / ".github" / "workflows" / "tests.yml"

    if not ci_path.exists():
        return [{"gate": "ci_workflow:exists", "passed": False,
                 "detail": f"missing: {ci_path}"}]

    results.append({"gate": "ci_workflow:exists", "passed": True, "detail": str(ci_path)})
    text = ci_path.read_text(encoding="utf-8")
    for step in _REQUIRED_CI_STEPS:
        passed = step in text
        results.append({
            "gate": f"ci_workflow:step:{step}",
            "passed": passed,
            "detail": "present" if passed else f"missing step: {step!r}",
        })
    return results


def _gateValidateWorkflowsScript() -> list[dict]:
    """Verify validate_workflows.py exists at repo root."""
    script = REPO_ROOT / "validate_workflows.py"
    passed = script.exists()
    return [{"gate": "validate_workflows_script:exists", "passed": passed,
             "detail": str(script) if passed else f"missing: {script}"}]


def _gateConfigImport() -> list[dict]:
    """Verify config imports and its root paths resolve sanely.

    INSTALL_ROOT may legitimately not exist on CI runners (it defaults to the
    dev-box path C:\\9to5), so gate on it resolving to an absolute path plus
    PROJECT_ROOT actually existing -- machine-independent checks.
    """
    try:
        import config  # noqa: PLC0415
        passed = config.INSTALL_ROOT.is_absolute() and config.PROJECT_ROOT.exists()
        return [{"gate": "config:INSTALL_ROOT_exists", "passed": passed,
                 "detail": f"INSTALL_ROOT={config.INSTALL_ROOT} "
                           f"PROJECT_ROOT={config.PROJECT_ROOT}"}]
    except Exception as exc:  # noqa: BLE001
        return [{"gate": "config:INSTALL_ROOT_exists", "passed": False, "detail": str(exc)[:200]}]


def validate() -> list[dict]:
    """Run all staging gates; return list of {gate, passed, detail}."""
    results: list[dict] = []
    results.extend(_gateImports())
    results.extend(_gateCiWorkflow())
    results.extend(_gateValidateWorkflowsScript())
    results.extend(_gateConfigImport())
    return results


def main(quiet: bool = False) -> int:
    results = validate()
    failed = [r for r in results if not r["passed"]]
    passed = [r for r in results if r["passed"]]

    if not quiet:
        for r in results:
            status = "PASS" if r["passed"] else "FAIL"
            print(f"[{status}] {r['gate']}: {r['detail']}")
        print(f"\n{len(passed)}/{len(results)} gates passed.")

    if failed:
        if not quiet:
            print("STAGING VALIDATION FAILED")
        return 1

    if not quiet:
        print("STAGING VALIDATION OK")
    return 0


if __name__ == "__main__":
    quiet = "--quiet" in sys.argv
    sys.exit(main(quiet=quiet))
