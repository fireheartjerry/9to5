"""9to5 /health -- environment readiness checks.

Each check yields (name, ok, detail, fix). Run via `python main.py --health`
or `python health.py`. Exits 0 only if every check passes.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  collectHealth() -> list[dict]  -- Run independent checks concurrently while preserving the public result order.
  runHealthChecks() -> bool
DEPENDS-ON: agents.executor_env, config, platform_core.core.concurrency, platform_core.core.git_io, platform_core.execution, platform_core.execution.provider_probe
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/notifications/test_health_aura.py tests/platform/test_health_collect.py tests/platform/test_repo_health.py
"""
from __future__ import annotations

import shutil
import time

import requests
import urllib3

import config
from platform_core.core.concurrency import boundedWorkerBudget, runBounded
from platform_core.core.git_io import runGit, runTool
from platform_core.execution.provider_probe import ProviderProbe

urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)

LOG = config.getLogger("ops.health")

GREEN = "\033[92m"
RED = "\033[91m"
YEL = "\033[93m"
RST = "\033[0m"


def _ollama() -> tuple[bool, str, str]:
    try:
        r = requests.get(f"{config.OLLAMA_HOST}/api/tags", timeout=5)
        r.raise_for_status()
        body = r.json()
        if not isinstance(body, dict):
            return False, f"Ollama /api/tags returned unexpected shape ({type(body).__name__})", \
                "check Ollama version / ensure it listens on 11434"
        models = [m.get("name") for m in (body.get("models") or []) if isinstance(m, dict)]
        if config.OLLAMA_MODEL not in models:
            return False, f"server up but {config.OLLAMA_MODEL} not pulled (have {models})", \
                f"run: ollama pull {config.OLLAMA_MODEL}"
        # GPU: check loaded models for VRAM usage
        gpu = "GPU unknown (model not currently loaded)"
        try:
            ps_body = requests.get(f"{config.OLLAMA_HOST}/api/ps", timeout=5).json()
            ps = (ps_body.get("models") if isinstance(ps_body, dict) else None) or []
            for m in ps:
                if m.get("name") == config.OLLAMA_MODEL or m.get("model") == config.OLLAMA_MODEL:
                    vram = m.get("size_vram", 0)
                    gpu = f"on GPU ({vram // (1024*1024)} MB VRAM)" if vram else "loaded on CPU only"
        except Exception:  # noqa: BLE001
            pass
        return True, f"{config.OLLAMA_MODEL} present; {gpu}", ""
    except Exception as e:  # noqa: BLE001
        return False, f"server not reachable at {config.OLLAMA_HOST} ({e})", \
            "start Ollama (ollama serve) and ensure it listens on 11434"


def _claudeCli(*, probe_executable=None) -> tuple[bool, str, str]:
    from platform_core.execution import provider_probe
    try:
        if probe_executable is None:
            result = provider_probe.runProviderProbe(ProviderProbe.CLAUDE_AUTH_STATUS)
        else:
            result = provider_probe.runProviderProbe(
                ProviderProbe.CLAUDE_AUTH_STATUS, executable=probe_executable
            )
        output = (result.stdout or result.stderr or "").strip()
        if result.ok and output:
            return True, f"authenticated; status {output[:80]!r}", ""
        return False, f"diagnostic failed (rc={result.returncode}): {output[:120]}", \
            "run `claude` once interactively to authenticate"
    except Exception as e:  # noqa: BLE001
        return False, str(e), "run `claude` interactively to authenticate"


def _gh() -> tuple[bool, str, str]:
    if not shutil.which("gh"):
        return False, "gh not on PATH", "install GitHub CLI (https://cli.github.com)"
    try:
        proc = runTool(["gh", "auth", "status"], timeout=15)
        ok = proc.returncode == 0
        msg = (proc.stderr or proc.stdout or "").strip().splitlines()
        return ok, (msg[-1] if msg else "ok"), ("" if ok else "run: gh auth login")
    except Exception as e:  # noqa: BLE001
        return False, str(e), "run: gh auth login"


def _obsidian() -> tuple[bool, str, str]:
    try:
        r = requests.get(config.OBSIDIAN_BASE_URL + "/", verify=False, timeout=5)
        return r.status_code == 200, f"reachable ({r.status_code}) at {config.OBSIDIAN_BASE_URL}", \
            ("" if r.status_code == 200 else "open Obsidian + enable Local REST API")
    except Exception as e:  # noqa: BLE001
        return False, f"not reachable ({e})", "start Obsidian with the Local REST API plugin"


def _discord() -> tuple[bool, str, str]:
    if not config.DISCORD_BOT_TOKEN:
        return False, "DISCORD_BOT_TOKEN missing", "set DISCORD_BOT_TOKEN in .env"
    try:
        r = requests.get("https://discord.com/api/v10/users/@me",
                         headers={"Authorization": f"Bot {config.DISCORD_BOT_TOKEN}"}, timeout=10)
        if r.status_code == 200:
            try:
                username = r.json().get("username") or "(unknown)"
            except Exception:  # noqa: BLE001
                username = "(unknown)"
            return True, f"bot online as {username}", ""
        return False, f"token rejected ({r.status_code})", "check DISCORD_BOT_TOKEN in .env"
    except Exception as e:  # noqa: BLE001
        return False, str(e), "check network / DISCORD_BOT_TOKEN"


def _envKeys() -> tuple[bool, str, str]:
    required = ["DISCORD_BOT_TOKEN", "DISCORD_CHANNEL_ID", "DISCORD_HUMAN_USER_ID",
               "OBSIDIAN_API_KEY", "OBSIDIAN_PORT", "OBSIDIAN_VAULT_PATH", "PROJECT_ROOT", "LOG_PATH"]
    import os
    missing = [k for k in required if not os.getenv(k)]
    return (not missing), ("all present" if not missing else f"missing {missing}"), \
        ("" if not missing else f"add {missing} to .env")


def _git() -> tuple[bool, str, str]:
    try:
        # timeout + no terminal prompt: a hung git (network remote, credential prompt, locked index)
        # must never wedge /health and the gateway thread that calls collectHealth. Matches the
        # bounded sibling checks (_claudeCli=40s, _gh=15s). TimeoutExpired is caught below.
        proc = runGit("rev-parse", "--is-inside-work-tree",
                      cwd=config.PROJECT_ROOT, timeout=15)
        ok = proc.returncode == 0 and "true" in (proc.stdout or "").lower()
        return ok, ("initialized" if ok else "not a git repo"), \
            ("" if ok else f"run: git -C {config.PROJECT_ROOT} init")
    except Exception as e:  # noqa: BLE001
        return False, str(e), "install git"


def _hooks() -> tuple[bool, str, str]:
    """HARD check (R7): the guard hooks (block_destructive, self_modification_guard) must be
    registered in settings AND survive per-run settings generation -- 'hooks: {}' is a failure."""
    p = config.CLAUDE_SETTINGS_PATH
    if not p.exists():
        return False, "no .claude/settings.json", "create .claude/settings.json with hooks"
    try:
        import json
        from agents.executor_env import composeRunSettingsDict, settingsHasGuardHooks
        data = json.loads(p.read_text(encoding="utf-8"))
        hooks = data.get("hooks") or {}
        if not settingsHasGuardHooks(data):
            return False, f"guard hooks NOT registered (hooks={sorted(hooks.keys())})", \
                "register HOOKS_SPEC guards in .claude/settings.json (see agents/executor_env.py)"
        if not settingsHasGuardHooks(composeRunSettingsDict(p)):
            return False, "generated per-run settings LOST the guard hooks block", \
                "fix agents/executor_env.buildHooksBlock / composeRunSettingsDict"
        return True, f"guard hooks registered: {sorted(hooks.keys())}", ""
    except Exception as e:  # noqa: BLE001
        return False, str(e), "fix .claude/settings.json JSON"


def _vault() -> tuple[bool, str, str]:
    root = config.VAULT_DISK_ROOT
    ok = root.exists()
    return ok, (f"exists at {root}" if ok else f"missing {root}"), \
        ("" if ok else "run any task once (ensureDirs creates it) or mkdir it")


CHECKS = [
    (f"Ollama + {config.OLLAMA_MODEL} (GPU)", _ollama),
    ("Claude Code CLI auth", _claudeCli),
    ("GitHub CLI auth", _gh),
    ("Obsidian REST", _obsidian),
    ("Discord bot", _discord),
    (".env keys", _envKeys),
    ("git initialized", _git),
    ("hooks configured", _hooks),
    ("vault structure", _vault),
]


def collectHealth() -> list[dict]:
    """Run independent checks concurrently while preserving the public result order."""
    config.ensureDirs()
    started = time.perf_counter()

    def check(item: tuple[str, object]) -> dict:
        name, fn = item
        try:
            ok, detail, fix = fn()  # type: ignore[operator]
        except Exception as e:  # noqa: BLE001
            ok, detail, fix = False, f"check errored: {e}", "see traceback"
        return {"name": name, "ok": bool(ok), "detail": detail, "fix": fix}

    budget = boundedWorkerBudget(
        requested=config.HEALTH_CHECK_MAX_WORKERS,
        configured_cap=config.HEALTH_CHECK_MAX_WORKERS,
        item_count=len(CHECKS),
    )
    outcomes = runBounded(CHECKS, check, budget=budget)
    # ``check`` contains its own exception boundary; retain a defensive result
    # for an unexpected scheduler-level exception without changing payload shape.
    results = [
        outcome.value if outcome.value is not None else {
            "name": CHECKS[index][0], "ok": False,
            "detail": f"check errored: {outcome.error}", "fix": "see traceback",
        }
        for index, outcome in enumerate(outcomes)
    ]
    LOG.info("health checks=%d workers=%d wall_seconds=%.3f", len(CHECKS), budget.effective, time.perf_counter() - started)
    return results


def runHealthChecks() -> bool:
    checks = collectHealth()
    print(f"\n  9to5 /health  —  {len(checks)} checks\n  " + "=" * 52)
    all_ok = True
    for c in checks:
        all_ok = all_ok and c["ok"]
        tag = f"{GREEN}PASS{RST}" if c["ok"] else f"{RED}FAIL{RST}"
        print(f"  [{tag}] {c['name']:30s} {c['detail']}")
        if not c["ok"] and c["fix"]:
            print(f"         {YEL}fix:{RST} {c['fix']}")
    print("  " + "=" * 52)
    print(f"  {'ALL SYSTEMS GO' if all_ok else 'NOT READY — see fixes above'}\n")
    return all_ok


if __name__ == "__main__":
    import sys
    sys.exit(0 if runHealthChecks() else 1)
