"""Managed external project checkout helpers.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  cloneRepo(repo_url: str, ref: str | None=None) -> Path  -- Clone a remote repo into 9to5's managed external workspace.
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_external_project.py
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import uuid
from pathlib import Path

import config

LOG = config.getLogger("external_project")


def _slugFor(repo_url: str) -> str:
    """Return a conservative directory stem derived from a repo URL/path."""
    tail = (repo_url.rstrip("/\\").rsplit("/", 1)[-1].rsplit("\\", 1)[-1] or "repo")
    if tail.endswith(".git"):
        tail = tail[:-4]
    slug = re.sub(r"[^A-Za-z0-9_.-]+", "-", tail).strip(".-")
    return slug[:40] or "repo"


def cloneRepo(repo_url: str, ref: str | None = None) -> Path:
    """Clone a remote repo into 9to5's managed external workspace."""
    url = (repo_url or "").strip()
    if not url:
        raise ValueError("repo_url is required")
    ref = (ref or "").strip() or None
    root = config.PROJECT_ROOT / "state" / "external-projects"
    root.mkdir(parents=True, exist_ok=True)
    target = root / f"{_slugFor(url)}-{uuid.uuid4().hex[:8]}"
    env = {**os.environ, "GIT_TERMINAL_PROMPT": "0"}
    clone_cmd = ["git", "clone", "--origin", "origin"]
    if ref:
        clone_cmd += ["--branch", ref]
    clone_cmd += [url, str(target)]
    proc = subprocess.run(clone_cmd, cwd=str(root),
                          capture_output=True, text=True, stdin=subprocess.DEVNULL,
                          env=env,
                          timeout=config.GIT_TIMEOUT_SECONDS)
    if proc.returncode != 0:
        shutil.rmtree(target, ignore_errors=True)
        detail = ((proc.stderr or "") + (proc.stdout or "")).strip()
        raise RuntimeError(f"git clone failed: {detail[:300]}")
    LOG.info("cloned external repo %s -> %s", url, target)
    return target.resolve()
