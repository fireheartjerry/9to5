"""State retention sweep — best-effort GC of per-run artifacts.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  sweepBlackboard(directory=None, keep_recent=None, max_age_days=None) -> int
  sweepCompaction(directory=None, keep_recent=None, max_age_days=None) -> int
  archiveTerminalTasks(max_age_days=None) -> int  -- Move terminal-status task JSON older than the archive horizon into state/archive/
  sweepHookLogs(path=None, max_bytes=None) -> int  -- Truncate logs/hooks.log to its tail once it exceeds ``max_bytes``
  sweepGuardAlerts(path=None, max_bytes=None) -> int  -- Truncate logs/guard_alerts.jsonl to its tail once it exceeds ``max_bytes``
  sweepAll(*, effect_authority=None, controller_state_authority=None) -> dict  -- Run every sweep, gated by config.RETENTION_ENABLED
DEPENDS-ON: config, platform_core.execution, platform_core.runtime
SIDE-EFFECTS: deletes/moves files under state/ (never .py; guarded, fail-open); truncates logs/hooks.log and logs/guard_alerts.jsonl
RUN/TEST: python -m pytest tests/platform/test_retention.py
"""

from __future__ import annotations

import shutil
import time
from pathlib import Path

import config
from platform_core.execution.pre_execution import (
    globLegacy,
    mutateLegacyPath,
    observeLegacyPath,
    openLegacyFile,
    readLegacyText,
)

LOG = config.getLogger("retention")

_DAY_SECONDS = 86400
_TERMINAL_STATUSES = {"done", "complete", "aborted", "partial", "blocked", "failed"}


def _resolveDir(value) -> Path:
    """Resolve a configured dir that may be a relative string (e.g. COMPACTION_OFFLOAD_DIR)."""
    p = Path(value)
    if not p.is_absolute():
        p = Path(config.PROJECT_ROOT) / p
    return p


def _pruneByPolicy(directory: Path, pattern: str, keep_recent: int, max_age_days: int) -> int:
    """Keep the newest ``keep_recent`` files matching ``pattern`` plus any younger than
    ``max_age_days``; delete the rest. Never touches .py. Fail-open per file. Returns count removed."""
    removed = 0
    try:
        if not observeLegacyPath(directory.is_dir):
            return 0
        files = [f for f in globLegacy(directory, pattern) if observeLegacyPath(f.is_file) and f.suffix != ".py"]
    except Exception as e:  # noqa: BLE001
        LOG.warning("retention: cannot list %s: %s", directory, e)
        return 0
    now = time.time()
    cutoff = now - max_age_days * _DAY_SECONDS
    # Newest first; the first keep_recent are always retained.
    try:
        files.sort(key=lambda f: observeLegacyPath(f.stat).st_mtime, reverse=True)
    except Exception:  # noqa: BLE001 -- a vanished file mid-sort must not abort the sweep
        files = [f for f in files if observeLegacyPath(f.exists)]
        files.sort(key=lambda f: observeLegacyPath(f.stat).st_mtime, reverse=True)
    for idx, f in enumerate(files):
        if idx < max(0, keep_recent):
            continue
        try:
            if observeLegacyPath(f.stat).st_mtime >= cutoff:
                continue  # young enough to keep regardless of position
            mutateLegacyPath(f.unlink)
            removed += 1
        except Exception as e:  # noqa: BLE001
            LOG.debug("retention: could not remove %s: %s", f, e)
    return removed


def sweepBlackboard(directory=None, keep_recent=None, max_age_days=None) -> int:
    directory = _resolveDir(directory if directory is not None else config.BLACKBOARD_DIR)
    kr = config.RETENTION_KEEP_RECENT if keep_recent is None else keep_recent
    ma = config.RETENTION_MAX_AGE_DAYS if max_age_days is None else max_age_days
    return _pruneByPolicy(directory, "*.jsonl", kr, ma)


def sweepCompaction(directory=None, keep_recent=None, max_age_days=None) -> int:
    directory = _resolveDir(directory if directory is not None else config.COMPACTION_OFFLOAD_DIR)
    kr = config.RETENTION_KEEP_RECENT if keep_recent is None else keep_recent
    ma = config.RETENTION_MAX_AGE_DAYS if max_age_days is None else max_age_days
    return _pruneByPolicy(directory, "ctx-*.txt", kr, ma)


def _isTerminalTaskFile(path: Path) -> bool:
    """True iff ``path`` is a task/control JSON whose recorded status is terminal.

    Fails CLOSED (returns False) on any read/parse error so a live or unreadable run
    is never archived out from under the orchestrator."""
    try:
        import json

        data = json.loads(readLegacyText(path, encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return False
    status = (data.get("meta") or {}).get("status") or data.get("status") or ""
    return str(status).lower() in _TERMINAL_STATUSES


def archiveTerminalTasks(max_age_days=None) -> int:
    """Move terminal-status task JSON older than the archive horizon into state/archive/
    (NEVER delete task state — the wipe-safety constraint). Returns count archived."""
    ma = config.RETENTION_ARCHIVE_AGE_DAYS if max_age_days is None else max_age_days
    archived = 0
    try:
        state_dir = Path(config.STATE_DIR)
        archive_dir = Path(config.ARCHIVE_DIR)
        if not observeLegacyPath(state_dir.is_dir):
            return 0
        candidates = [f for f in globLegacy(state_dir, "*.json") if observeLegacyPath(f.is_file)]
    except Exception as e:  # noqa: BLE001
        LOG.warning("retention: cannot list task dir: %s", e)
        return 0
    cutoff = time.time() - ma * _DAY_SECONDS
    for f in candidates:
        try:
            if observeLegacyPath(f.stat).st_mtime >= cutoff or not _isTerminalTaskFile(f):
                continue
            mutateLegacyPath(archive_dir.mkdir,parents=True, exist_ok=True)
            mutateLegacyPath(shutil.move,str(f), str(archive_dir / f.name))
            archived += 1
        except Exception as e:  # noqa: BLE001
            LOG.debug("retention: could not archive %s: %s", f, e)
    return archived


def _truncateToTail(path: Path, max_bytes: int) -> int:
    """Keep only the last ``max_bytes`` of ``path``, dropping everything before it (and
    any partial first line so the kept content starts on a clean record boundary).
    Returns bytes trimmed (0 if under the cap, missing, or on any error). Fail-open:
    a read/write failure here must never abort the sweep."""
    try:
        size = observeLegacyPath(path.stat).st_size
    except FileNotFoundError:
        return 0
    except Exception as e:  # noqa: BLE001
        LOG.debug("retention: cannot stat %s: %s", path, e)
        return 0
    if size <= max_bytes:
        return 0
    try:
        with openLegacyFile(path, "rb") as fh:
            fh.seek(size - max_bytes)
            tail = fh.read()
        nl = tail.find(b"\n")
        if nl != -1:
            tail = tail[nl + 1 :]
        tmp = path.with_name(path.name + ".tmp")
        mutateLegacyPath(tmp.write_bytes,tail)
        mutateLegacyPath(tmp.replace,path)
        return size - observeLegacyPath(path.stat).st_size
    except Exception as e:  # noqa: BLE001
        LOG.debug("retention: could not truncate %s: %s", path, e)
        return 0


def sweepHookLogs(path=None, max_bytes=None) -> int:
    """Truncate logs/hooks.log to its tail once it exceeds ``max_bytes``. hooks.log is
    appended on essentially every tool-use hook fire (the highest-frequency write in the
    system) with no rotation at the write site -- retention trims it out-of-band instead,
    so the hook append itself stays a plain fast write (non-blocking)."""
    p = _resolveDir(path if path is not None else Path(config.LOG_PATH) / "hooks.log")
    mb = config.HOOKS_LOG_MAX_BYTES if max_bytes is None else max_bytes
    return _truncateToTail(p, mb)


def sweepGuardAlerts(path=None, max_bytes=None) -> int:
    """Truncate logs/guard_alerts.jsonl to its tail once it exceeds ``max_bytes``. Same
    rationale as sweepHookLogs: the guard block path is a fire-and-forget append with no
    rotation, so retention trims it out-of-band instead."""
    p = _resolveDir(path if path is not None else Path(config.LOG_PATH) / "guard_alerts.jsonl")
    mb = config.GUARD_ALERTS_MAX_BYTES if max_bytes is None else max_bytes
    return _truncateToTail(p, mb)


def sweepAll(*, effect_authority=None, controller_state_authority=None) -> dict:
    """Run every sweep, gated by config.RETENTION_ENABLED. Fail-open: never raises."""
    del effect_authority, controller_state_authority
    from platform_core.runtime.effect_guard import maintenanceDeferred

    return maintenanceDeferred(
        "retention",
        reason="retention requires the future durable effect-command authority",
    )


def _sweepAllUnsafe() -> dict:
    """Legacy implementation retained only for migration tests; not a public boundary."""

    if not getattr(config, "RETENTION_ENABLED", True):
        return {"enabled": False}
    result = {
        "enabled": True,
        "blackboard": 0,
        "compaction": 0,
        "archived": 0,
        "hooks_log_trimmed": 0,
        "guard_alerts_trimmed": 0,
    }
    try:
        result["blackboard"] = sweepBlackboard()
        result["compaction"] = sweepCompaction()
        result["archived"] = archiveTerminalTasks()
        result["hooks_log_trimmed"] = sweepHookLogs()
        result["guard_alerts_trimmed"] = sweepGuardAlerts()
        LOG.info(
            "retention sweep: blackboard=-%d compaction=-%d archived=%d "
            "hooks_log_trimmed=%d guard_alerts_trimmed=%d",
            result["blackboard"],
            result["compaction"],
            result["archived"],
            result["hooks_log_trimmed"],
            result["guard_alerts_trimmed"],
        )
    except Exception as e:  # noqa: BLE001 -- retention must never break a run
        LOG.warning("retention sweep failed (ignored): %s", e)
    return result
