def _executiveExcerpt(recs_text: str, max_chars: int = 2400) -> str:
    """Pull the 'Executive Recommendations' block (top-N) out of recommendations.md for
    the injection. Falls back to the document head if no executive header is found."""
    if not recs_text:
        return ""
    m = re.search(r"^##\s+Executive Recommendations.*$", recs_text, flags=re.M)
    if m:
        start = m.start()
        nxt = re.search(r"\n##\s+(?!#)", recs_text[m.end():])
        block = recs_text[start: m.end() + nxt.start()] if nxt else recs_text[start:]
    else:
        block = recs_text
    return block.strip()[:max_chars]


def _buildLocalCapabilityParts(local: dict) -> list[str]:
    """Build skills, agents, workflows, hooks, and MCP sections from local inventory."""
    parts: list[str] = []
    skills = local.get("skills", [])
    if skills:
        parts.append("### Installed skills (invoke by name in skills_to_invoke / via /<name>)")
        for s in skills[:40]:
            if s.get("desc_trusted"):
                parts.append(f"- {s['name']}: {s['description'][:160]}")
            else:
                parts.append(f"- {s['name']}")
    parts.append("")
    agents = local.get("agents", [])
    if agents:
        parts.append("### Installed subagents (route isolated analysis here)")
        for a in agents[:30]:
            if a.get("desc_trusted"):
                parts.append(f"- {a['name']} (tools: {a.get('tools') or '*'}): {a['description'][:140]}")
            else:
                parts.append(f"- {a['name']} (tools: {a.get('tools') or '*'})")
    parts.append("")
    if local.get("workflows"):
        parts.append("### Saved workflows")
        parts.append(", ".join(w["name"] for w in local["workflows"][:30]))
        parts.append("")
    if local.get("hooks"):
        parts.append("### Configured hooks (deterministic guardrails already wired)")
        evs: dict = {}
        for h in local["hooks"]:
            evs.setdefault(h["event"], set()).add(h["matcher"] or "*")
        for ev, ms in evs.items():
            parts.append(f"- {ev}: matchers {', '.join(sorted(ms))}")
        parts.append("")
    if local.get("mcp_servers"):
        parts.append("### MCP servers (tools named mcp__<server>__<tool>; load via ToolSearch)")
        parts.append(", ".join(local["mcp_servers"][:40]))
        parts.append("")
    return parts


def compressForInjection(unified_doc: str, local: dict, fetched: dict,
                         max_chars: Optional[int] = None, recs: Optional[dict] = None) -> str:
    """Distill the unified reference into the structured ``CLAUDE CODE CAPABILITIES``
    block. Prioritizes (per spec): installed skills + invocation, installed subagents +
    tool access, workflows, effort levels, hook types, MCP servers, CLAUDE.md best
    practices, non-interactive CLI patterns, advanced chaining/dynamic-workflow guidance,
    plus the expert executive recommendations. Caps length so a 7B context never overflows."""
    max_chars = max_chars or config.CLAUDE_CAPABILITIES_MAX_CHARS
    parts: list[str] = []
    if recs and recs.get("found"):
        recs_raw = recs.get("text", "")
        recs_gated = injectableDoc(recs_raw, name=recs.get("path") or "recommendations.md")
        ex = _executiveExcerpt(recs_gated) if recs_gated else ""
        if ex:
            parts.append("### Expert recommendations (apply to EVERY spec; full set = Part E of claude_code.md)")
            parts.append(ex)
            parts.append("")
    parts.extend(_buildLocalCapabilityParts(local))
    parts.append(_DISTILLED_CHEATSHEET)
    parts.append("")
    idx = [h for h in _topHeadings(unified_doc)
           if "http://" not in h and "https://" not in h]
    if idx:
        parts.append("### Full reference index (see claude_code.md on disk for detail)")
        parts.append("; ".join(h.replace("## ", "") for h in idx[:60]))
    out = "\n".join(parts).strip()
    if len(out) > max_chars:
        out = out[:max_chars].rsplit("\n", 1)[0] + "\n... (truncated; full detail in claude_code.md)"
    return out


# ============================================================================
# 5) Shared injection cache -- so EVERY Ollama caller (orchestrator brain,
#    elaborator, replanner, architect) injects the same CLAUDE CODE CAPABILITIES
#    block. Lives here (config-only deps) to avoid an orchestrator import cycle.
# ============================================================================
_CAPABILITIES: str = ""
_CAP_LOCK = threading.Lock()   # collapses a parallel-subtask thundering-herd rebuild to one

_CAPABILITIES_DIRECTIVE = (
    "Before generating ANY spec/plan/decision, consult CLAUDE CODE CAPABILITIES above and ask: "
    "is there a SKILL for this? a better SUBAGENT? should this be a WORKFLOW (use_workflow)? "
    "what EFFORT level does it deserve? which HOOKS should fire? which MCP tools apply? "
    "Generic flat-prompt generation is FORBIDDEN when a more powerful Claude Code primitive fits."
)


def setCapabilities(summary: str) -> None:
    """Cache the compressed CLAUDE CODE CAPABILITIES summary (called by the full refresh)."""
    global _CAPABILITIES
    _CAPABILITIES = summary or ""


def getCapabilities() -> str:
    return _CAPABILITIES


def ensureCapabilities() -> str:
    """Lazily build the capabilities summary OFFLINE (no web fetch) from the on-disk
    claude_code.md + live local scan, if a full refresh has not populated the cache yet.
    Guarantees no Ollama call is ever sent capability-blind. Never raises."""
    global _CAPABILITIES
    if _CAPABILITIES:
        return _CAPABILITIES
    with _CAP_LOCK:                       # double-checked: one thread builds, the herd waits
        if _CAPABILITIES:
            return _CAPABILITIES
        try:
            prior = ""
            if config.CLAUDE_KNOWLEDGE_PATH.exists():
                raw = _readText(config.CLAUDE_KNOWLEDGE_PATH, limit=2_000_000)
                # Gate: only use the on-disk unified doc as the heading-index source
                # if it carries a valid provenance stamp (written by buildUnifiedDoc).
                prior = injectableDoc(raw, name="claude_code.md")
            local = scanLocalClaude()
            recs = readRecommendations()
            _CAPABILITIES = compressForInjection(prior, local, {"pages": {}, "ok": [], "failed": []}, recs=recs)
        except Exception as e:  # noqa: BLE001
            LOG.warning("ensureCapabilities offline build failed: %s", e)
        return _CAPABILITIES


def injectCapabilities(system_prompt: str) -> str:
    """Prepend the cached CLAUDE CODE CAPABILITIES block to ANY brain system prompt.
    Used by the orchestrator AND elaborator/replanner/architect so every single Ollama
    system prompt carries the live capability set. Lazy-loads offline if needed."""
    caps = _CAPABILITIES or ensureCapabilities()
    if not caps:
        return system_prompt
    return ("## CLAUDE CODE CAPABILITIES\n" + caps + "\n\n" + _CAPABILITIES_DIRECTIVE
            + "\n\n---\n\n" + system_prompt)
