"""Unified knowledge-doc assembly: folds prior analysis, live docs, local surface, and recs.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  buildUnifiedDoc(prior_doc: str, fetched: dict, local: dict, psk: dict, *, refreshed_at: str, sources: list[str], recs: Optional[dict]=None) -> str  -- Fold prior self-analysis + live docs + local capability surface +
  diffHeadings(prior_doc: str, new_doc: str) -> dict  -- Naive 'what changed' delta on top-level headings (for the refresh log).
DEPENDS-ON: platform_core.app_config, platform_core.knowledge_base.scraper
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_builder_sim.py
"""
from __future__ import annotations

import re
from typing import Optional

# Direction rule (R12): platform_core modules read the in-platform registry facade.
from platform_core import app_config as config
from platform_core.knowledge_base.scraper import _SCRAPE_PROVENANCE_HEADER

LOG = config.getLogger("knowledge.builder")

_AUTHORED_HEADER = "# Part A — Maximalist Self-Analysis (authored reference)"


def _topHeadings(markdown: str) -> list[str]:
    return [ln.strip() for ln in (markdown or "").splitlines() if ln.startswith("## ")]


def _extractAuthoredBody(prior_doc: str) -> str:
    """Pull ONLY the stable authored reference out of a prior unified doc so repeated
    refreshes never nest Parts A-D inside each other (the live Parts B/C/D are always
    regenerated). On the first run (raw authored sections, no provenance), returns the
    whole doc minus any leading provenance header."""
    if not prior_doc or not prior_doc.strip():
        return ""
    if _AUTHORED_HEADER in prior_doc:
        start = prior_doc.index(_AUTHORED_HEADER) + len(_AUTHORED_HEADER)
        rest = prior_doc[start:]
        # cut at the next top-level Part divider (B/C/D/E), tolerating a leading --- rule
        m = re.search(r"\n-{3,}\s*\n+# Part [BCDE]\b|\n# Part [BCDE]\b", rest)
        body = rest[:m.start()] if m else rest
        return body.strip()
    # first run: strip a provenance header if present, keep everything else
    return re.sub(r"^# Claude Code — Living Capability Reference.*?(?=\n## |\n# |\Z)",
                  "", prior_doc, flags=re.DOTALL).strip()


def _extractPart(prior_doc: str, letter: str) -> str:
    """Extract a whole '# Part <letter> — ...' block (header + body) from a prior unified doc,
    up to the next '# Part <X>' divider or EOF. Returns '' if absent. Used to carry a prior
    Part D (scraped live docs) forward when the current refresh fetched nothing -- so an offline
    or failed scrape never ERASES previously-captured documentation."""
    if not prior_doc:
        return ""
    m = re.search(rf"^# Part {letter} —", prior_doc, flags=re.M)
    if not m:
        return ""
    rest = prior_doc[m.start():]
    nxt = re.search(r"\n-{3,}\s*\n+# Part [A-Z]\b|\n# Part [A-Z]\b", rest[1:])
    body = rest[: nxt.start() + 1] if nxt else rest
    return body.strip()


def _buildDocHeader(refreshed_at: str, sources: list[str], fetched: dict,
                    local: dict, psk: dict, recs: dict) -> list[str]:
    """Build the provenance header block for the unified doc."""
    lines: list[str] = []
    lines.append("# Claude Code — Living Capability Reference (9to5 knowledge base)")
    lines.append("")
    lines.append(f"> **Last refreshed:** {refreshed_at}")
    lines.append(f"> **Sources used this refresh:** {len(sources)} "
                 f"({len(fetched.get('ok', []))} live doc pages, "
                 f"{local.get('files_scanned', 0)} local .claude files, "
                 f"product-self-knowledge={'yes' if psk.get('found') else 'no'}, "
                 f"recommendations={'yes' if recs.get('found') else 'no'})")
    lines.append("> This file is regenerated by `orchestrator.refreshClaudeKnowledge()`; edit the "
                 "section authoring/compression there, not this file (it is overwritten each refresh).")
    lines.append("")
    lines.append("## Sources")
    for s in sources:
        lines.append(f"- {s}")
    lines.append("")
    return lines


def _buildPartAB(prior_doc: str, local: dict) -> list[str]:
    """Build Part A (authored body) and Part B (installed capability surface)."""
    lines: list[str] = []
    authored = _extractAuthoredBody(prior_doc)
    if authored:
        lines.extend(["---", "", _AUTHORED_HEADER, "", authored, ""])
    lines.extend(["---", "", "# Part B — Installed Capability Surface (this environment, scanned live)", ""])
    lines.append(f"Scanned roots: {', '.join(local.get('roots', [])) or '(none found)'}")
    lines.append("")
    lines.append("## Installed skills")
    for s in local.get("skills", []):
        lines.append(f"- **{s['name']}** — {s['description']}")
    if not local.get("skills"):
        lines.append("- (none found on disk)")
    lines.append("")
    lines.append("## Installed subagents")
    for a in local.get("agents", []):
        lines.append(f"- **{a['name']}** (tools: {a.get('tools') or '*'}; model: {a.get('model') or 'inherit'}) — {a['description']}")
    if not local.get("agents"):
        lines.append("- (none found on disk)")
    lines.append("")
    for label, key, fmt in [
        ("Installed workflows", "workflows", lambda w: f"- {w['name']} — `{w['path']}`"),
        ("Custom slash commands", "commands", lambda c: f"- /{c['name']} — {c['description']}"),
    ]:
        lines.append(f"## {label}")
        for item in local.get(key, []):
            lines.append(fmt(item))
        if not local.get(key):
            lines.append("- (none found on disk)")
        lines.append("")
    lines.append("## Configured hooks")
    for h in local.get("hooks", []):
        lines.append(f"- `{h['event']}` matcher=`{h['matcher']}` -> `{h['command']}`")
    if not local.get("hooks"):
        lines.append("- (none configured)")
    lines.append("")
    lines.append("## MCP servers configured on disk")
    lines.append(", ".join(local.get("mcp_servers", [])) or "(none in scanned settings)")
    lines.append("")
    return lines


def _buildPartCDE(psk: dict, fetched: dict, prior_doc: str, recs: dict) -> list[str]:
    """Build Parts C (product-self-knowledge), D (live docs), E (expert recs)."""
    lines: list[str] = []
    if psk.get("found"):
        lines.extend(["---", "", "# Part C — product-self-knowledge skill (verbatim)",
                      f"Source: `{psk.get('path')}`", "", psk.get("text", "").strip(), ""])
    pages = fetched.get("pages") or {}
    prior_d = _extractPart(prior_doc, "D")
    prior_d_pages = prior_d.count("\n## http") if prior_d else 0
    if pages and (len(pages) >= 5 or len(pages) >= prior_d_pages or not prior_d):
        lines.extend(["---", "", "# Part D — Latest Live Documentation (scraped this refresh)", ""])
        for url, text in pages.items():
            lines.extend([f"## {url}", "", text[:14_000].strip(), ""])
    elif prior_d:
        lines.extend(["---", "", prior_d, ""])
        LOG.info("Part D preserved from prior doc (%d fresh pages vs %d prior)", len(pages), prior_d_pages)
    if recs.get("found") and recs.get("text", "").strip():
        lines.extend(["---", "", "# Part E — Expert Recommendations (how 9to5 should wield Claude Code)",
                      f"Source: `{recs.get('path')}`", "", recs["text"].strip(), ""])
    return lines


def buildUnifiedDoc(prior_doc: str, fetched: dict, local: dict, psk: dict, *,
                    refreshed_at: str, sources: list[str], recs: Optional[dict] = None) -> str:
    """Fold prior self-analysis + live docs + local capability surface +
    product-self-knowledge + expert recommendations into ONE maximalist reference,
    with provenance header."""
    recs = recs or {"found": False, "text": "", "path": None}
    lines = (
        _buildDocHeader(refreshed_at, sources, fetched, local, psk, recs)
        + _buildPartAB(prior_doc, local)
        + _buildPartCDE(psk, fetched, prior_doc, recs)
    )
    return _SCRAPE_PROVENANCE_HEADER + "\n".join(lines).rstrip() + "\n"


def diffHeadings(prior_doc: str, new_doc: str) -> dict:
    """Naive 'what changed' delta on top-level headings (for the refresh log)."""
    old = set(_topHeadings(prior_doc))
    new = set(_topHeadings(new_doc))
    return {"added": sorted(new - old), "removed": sorted(old - new)}
