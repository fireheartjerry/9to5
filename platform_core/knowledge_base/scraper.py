def _parseFrontmatter(text: str) -> dict:
    """Tiny YAML-frontmatter reader (no pyyaml dep). Returns flat str->value."""
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    block = text[3:end]
    out: dict = {}
    key = None
    for line in block.splitlines():
        if not line.strip():
            continue
        m = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if m:
            key, val = m.group(1).strip(), m.group(2).strip()
            out[key] = val.strip('"\'') if val else ""
        elif key and re.match(r"^\s*-\s+", line):  # YAML list item
            out.setdefault(key, [])
            if isinstance(out[key], str):
                out[key] = [out[key]] if out[key] else []
            out[key].append(re.sub(r"^\s*-\s+", "", line).strip().strip('"\''))
    return out


def _readText(p: Path, limit: int = 200_000) -> str:
    try:
        return p.read_text(encoding="utf-8", errors="replace")[:limit]
    except Exception:  # noqa: BLE001
        return ""


# ============================================================================
# Provenance gate for knowledge-doc injection
# ============================================================================
_PROV_HEADER_RE = re.compile(
    r"^<!--\s*provenance:\s*(\{[^}]*\})\s*-->\n?", re.MULTILINE
)

# Header prepended by the writer path so genuinely-built docs pass the gate.
_SCRAPE_PROVENANCE_HEADER = '<!-- provenance: {"origin": "scrape"} -->\n'


def injectableDoc(text: str, *, name: str) -> str:
    """Gate a knowledge-doc for injection into the brain prompt.

    Parses an optional FIRST-LINE HTML provenance comment
    ``<!-- provenance: {"origin": "<value>"} -->`` from *text*.  Coerces it
    through :mod:`provenance` and calls ``assertIngestible`` with
    ``intended_role="believe"`` (docs are trusted evidence but not user directives).

    Returns the doc body (without the header line) when the verdict is
    ``ALLOW`` (i.e. origin is ``human`` or ``scrape``).  Returns ``""`` for
    any other verdict (executor/brain/derived/absent/malformed) so an
    unattested or task-forged-absent doc contributes nothing to the prompt.

    Fails CLOSED: no header → EXECUTOR provenance → quarantined → "".
    """
    if not text:
        return ""
    m = _PROV_HEADER_RE.match(text)
    raw_dict: Optional[dict] = None
    body = text
    if m:
        try:
            raw_dict = _json.loads(m.group(1))
        except Exception:  # noqa: BLE001
            raw_dict = None  # malformed JSON → coerces to EXECUTOR
        body = text[m.end():]  # strip the header from returned content

    prov = _prov.coerce(raw_dict)
    # Knowledge docs are trusted evidence (believe), not user directives (obey).
    # "believe" allows origin=human and origin=scrape; blocks executor/brain/derived.
    decision = _prov.assertIngestible(name, "believe", prov)
    if decision.verdict is _prov.Verdict.ALLOW:
        return body
    LOG.debug("knowledge doc %r quarantined: %s", name, decision.reason)
    return ""


def _isTrustedSource(text: str, name: str) -> bool:
    """Return True iff *text* carries a trusted provenance header (human or scrape origin).

    Reuses the same provenance-parse + coerce + assertIngestible logic as
    :func:`injectableDoc` so the gate is identical.  Fails closed: no header →
    EXECUTOR provenance → untrusted → False.

    Used by :func:`scanLocalClaude` to decide whether a locally-scanned agent/skill
    description is safe to inject into the brain prompt.
    """
    if not text:
        return False
    m = _PROV_HEADER_RE.match(text)
    raw_dict: Optional[dict] = None
    if m:
        try:
            raw_dict = _json.loads(m.group(1))
        except Exception:  # noqa: BLE001
            raw_dict = None  # malformed JSON → coerces to EXECUTOR
    prov = _prov.coerce(raw_dict)
    decision = _prov.assertIngestible(name, "believe", prov)
    return decision.verdict is _prov.Verdict.ALLOW


def _stripProvHeader(text: str) -> str:
    """Strip the first-line provenance comment (if present) so frontmatter parsing
    sees ``---`` as the first meaningful line.  Returns the text unchanged if no header."""
    m = _PROV_HEADER_RE.match(text)
    return text[m.end():] if m else text


def _scanRootSkillsAndAgents(root: Path, inv: dict,
                              seen_skill: set, seen_agent: set) -> None:
    """Scan skills and subagents from one .claude root into inv in-place."""
    for skill_md in root.glob("**/SKILL.md"):
        inv["files_scanned"] += 1
        raw_text = _readText(skill_md)
        desc_trusted = _isTrustedSource(raw_text, str(skill_md))
        fm = _parseFrontmatter(_stripProvHeader(raw_text))
        name = fm.get("name") or skill_md.parent.name
        if name in seen_skill:
            continue
        seen_skill.add(name)
        inv["skills"].append({"name": name, "description": (fm.get("description") or "")[:400],
                              "allowed_tools": fm.get("allowed-tools") or fm.get("allowed_tools"),
                              "path": str(skill_md), "desc_trusted": desc_trusted})
    for agent_md in (root / "agents").glob("*.md") if (root / "agents").exists() else []:
        inv["files_scanned"] += 1
        raw_text = _readText(agent_md)
        desc_trusted = _isTrustedSource(raw_text, str(agent_md))
        fm = _parseFrontmatter(_stripProvHeader(raw_text))
        name = fm.get("name") or agent_md.stem
        if name in seen_agent:
            continue
        seen_agent.add(name)
        inv["agents"].append({"name": name, "description": (fm.get("description") or "")[:400],
                              "tools": fm.get("tools"), "model": fm.get("model"),
                              "path": str(agent_md), "desc_trusted": desc_trusted})


def _scanRootSettings(root: Path, inv: dict) -> None:
    """Scan settings.json / .mcp.json from one .claude root into inv in-place."""
    import json
    for sj in list(root.glob("settings*.json")) + list(root.glob(".mcp.json")) + \
            list((root.parent).glob(".mcp.json")):
        if not sj.exists():
            continue
        inv["files_scanned"] += 1
        inv["settings"].append(str(sj))
        try:
            data = json.loads(_readText(sj))
        except Exception:  # noqa: BLE001
            continue
        for ev, entries in (data.get("hooks") or {}).items():
            for entry in entries or []:
                for h in entry.get("hooks", []) or []:
                    inv["hooks"].append({"event": ev, "matcher": entry.get("matcher", ""),
                                         "command": (h.get("command") or "")[:200]})
        for srv in (data.get("mcpServers") or {}):
            if srv not in inv["mcp_servers"]:
                inv["mcp_servers"].append(srv)


def scanLocalClaude(roots: Optional[tuple] = None) -> dict:
    """Recursively read every installed ``.claude`` surface. Returns a structured
    inventory of skills, subagents, workflows, commands, hooks, settings, MCP
    config -- the *authoritative, environment-specific* capability set. Never raises."""
    roots = roots or config.CLAUDE_SCAN_ROOTS
    inv: dict = {"skills": [], "agents": [], "workflows": [], "commands": [],
                 "settings": [], "hooks": [], "mcp_servers": [], "roots": [], "files_scanned": 0}
    seen_skill: set[str] = set()
    seen_agent: set[str] = set()
    for root in roots:
        root = Path(root)
        if not root.exists():
            continue
        inv["roots"].append(str(root))
        _scanRootSkillsAndAgents(root, inv, seen_skill, seen_agent)
        for wf in (root / "workflows").glob("**/*") if (root / "workflows").exists() else []:
            if wf.is_file() and wf.suffix in (".js", ".ts", ".md"):
                inv["files_scanned"] += 1
                inv["workflows"].append({"name": wf.stem, "path": str(wf)})
        for cmd in (root / "commands").glob("**/*.md") if (root / "commands").exists() else []:
            inv["files_scanned"] += 1
            fm = _parseFrontmatter(_readText(cmd))
            inv["commands"].append({"name": cmd.stem, "description": (fm.get("description") or "")[:200],
                                    "path": str(cmd)})
        _scanRootSettings(root, inv)
    LOG.info("local .claude scan: %d skills, %d agents, %d workflows, %d hooks across %d files",
             len(inv["skills"]), len(inv["agents"]), len(inv["workflows"]), len(inv["hooks"]),
             inv["files_scanned"])
    return inv


def readProductSelfKnowledge(roots: Optional[tuple] = None) -> dict:
    """Locate + read the product-self-knowledge skill (Claude Code's own current
    state). Returns ``{found: bool, path: str|None, text: str}``. Never raises."""
    search_roots = list(roots or config.CLAUDE_SCAN_ROOTS) + [
        Path.home() / ".claude", config.INSTALL_ROOT]
    for root in search_roots:
        root = Path(root)
        if not root.exists():
            continue
        for pattern in _PRODUCT_SELF_KNOWLEDGE_GLOBS:
            for hit in root.glob(pattern):
                if hit.is_file():
                    txt = _readText(hit, limit=60_000)
                    if txt:
                        LOG.info("product-self-knowledge found: %s", hit)
                        return {"found": True, "path": str(hit), "text": txt}
    LOG.info("product-self-knowledge skill not found in any scan root")
    return {"found": False, "path": None, "text": ""}


def readRecommendations(path: Optional[Path] = None) -> dict:
    """Read the expert recommendations doc (how 9to5 should wield Claude Code). Returns
    ``{found, path, text}``. Never raises."""
    path = Path(path or config.CLAUDE_RECOMMENDATIONS_PATH)
    if path.exists():
        txt = _readText(path, limit=300_000)
        if txt.strip():
            LOG.info("recommendations found: %s (%d chars)", path, len(txt))
            return {"found": True, "path": str(path), "text": txt}
    LOG.info("recommendations doc not present at %s", path)
    return {"found": False, "path": str(path), "text": ""}
