    def _winIdentity(handle: int) -> NativeFileIdentity:
        info = _BY_HANDLE_FILE_INFORMATION()
        if not _GetFileInformationByHandle(handle, ctypes.byref(info)):
            raise ctypes.WinError(ctypes.get_last_error())
        basic = _FILE_BASIC_INFO()
        tag = _FILE_ATTRIBUTE_TAG_INFO()
        file_id = _FILE_ID_INFO()
        for value, info_class in (
            (basic, _FILE_BASIC_INFO_CLASS),
            (tag, _FILE_ATTRIBUTE_TAG_INFO_CLASS),
            (file_id, _FILE_ID_INFO_CLASS),
        ):
            if not _GetFileInformationByHandleEx(
                handle,
                info_class,
                ctypes.byref(value),
                ctypes.sizeof(value),
            ):
                raise ctypes.WinError(ctypes.get_last_error())
        attributes = int(info.dwFileAttributes)
        if attributes != int(basic.FileAttributes) or attributes != int(tag.FileAttributes):
            raise OSError("Windows file attributes raced retained identity")
        volume_id = int(file_id.VolumeSerialNumber)
        identity = int.from_bytes(bytes(file_id.FileId.Identifier), "little")
        return NativeFileIdentity(
            volume_id=volume_id,
            file_id=identity,
            link_count=int(info.nNumberOfLinks),
            size=(int(info.nFileSizeHigh) << 32) | int(info.nFileSizeLow),
            attributes=attributes,
            mode=stat.S_IFDIR if attributes & _FILE_ATTRIBUTE_DIRECTORY else stat.S_IFREG,
            write_time=(
                int(info.ftLastWriteTime.dwHighDateTime) << 32
            )
            | int(info.ftLastWriteTime.dwLowDateTime),
            change_time=int(basic.ChangeTime),
            is_directory=bool(attributes & _FILE_ATTRIBUTE_DIRECTORY),
            is_reparse=bool(attributes & _FILE_ATTRIBUTE_REPARSE_POINT),
            mount_id=volume_id,
            reparse_tag=int(tag.ReparseTag),
        )

    def _winOpenRelative(
        parent: int,
        name: str,
        *,
        directory: bool,
        disposition: int = _FILE_OPEN,
        access_extra: int = 0,
    ) -> int:
        if not name or name in {".", ".."} or "\\" in name or "/" in name:
            raise ValueError("relative native child name is invalid")
        buffer = ctypes.create_unicode_buffer(name)
        byte_length = len(name.encode("utf-16-le"))
        unicode_name = _UNICODE_STRING(
            Length=byte_length,
            MaximumLength=byte_length + 2,
            Buffer=ctypes.cast(buffer, wintypes.LPWSTR),
        )
        attributes = _OBJECT_ATTRIBUTES(
            Length=ctypes.sizeof(_OBJECT_ATTRIBUTES),
            RootDirectory=parent,
            ObjectName=ctypes.pointer(unicode_name),
            Attributes=_OBJ_CASE_INSENSITIVE,
            SecurityDescriptor=None,
            SecurityQualityOfService=None,
        )
        result = wintypes.HANDLE()
        status_block = _IO_STATUS_BLOCK()
        desired = _FILE_READ_ATTRIBUTES | _SYNCHRONIZE | access_extra
        options = _FILE_SYNCHRONOUS_IO_NONALERT | _FILE_OPEN_REPARSE_POINT
        if access_extra & (_FILE_WRITE_DATA | _DELETE):
            options |= _FILE_WRITE_THROUGH
        if directory:
            desired |= _FILE_LIST_DIRECTORY
            options |= _FILE_DIRECTORY_FILE
        else:
            desired |= _FILE_READ_DATA
            options |= _FILE_NON_DIRECTORY_FILE
        status = _NtCreateFile(
            ctypes.byref(result),
            desired,
            ctypes.byref(attributes),
            ctypes.byref(status_block),
            None,
            0,
            _FILE_SHARE_ALL,
            disposition,
            options,
            None,
            0,
        )
        if status < 0:
            raise _winErrorFromStatus(status)
        if result.value is None:
            raise OSError("native relative open returned no handle")
        return int(result.value)

    def _winWriteAll(handle: int, payload: bytes, *, flush: bool = True) -> None:
        view = memoryview(payload)
        offset = 0
        while offset < len(view):
            chunk = bytes(view[offset : offset + 65536])
            written = wintypes.DWORD()
            if not _WriteFile(
                handle,
                chunk,
                len(chunk),
                ctypes.byref(written),
                None,
            ):
                raise ctypes.WinError(ctypes.get_last_error())
            if not written.value:
                raise OSError("short retained-handle write")
            offset += int(written.value)
        if flush and not _FlushFileBuffers(handle):
            raise ctypes.WinError(ctypes.get_last_error())

    def _winRenameRelative(
        source: int,
        destination_directory: int,
        destination_name: str,
        *,
        replace: bool,
    ) -> None:
        if (
            not destination_name
            or destination_name in {".", ".."}
            or "\\" in destination_name
            or "/" in destination_name
        ):
            raise ValueError("relative native destination name is invalid")
        name_bytes = destination_name.encode("utf-16-le")
        size = _FILE_RENAME_INFO.FileName.offset + len(name_bytes)
        buffer = ctypes.create_string_buffer(size)
        info = _FILE_RENAME_INFO.from_buffer(buffer)
        info.ReplaceIfExists = bool(replace)
        info.RootDirectory = destination_directory
        info.FileNameLength = len(name_bytes)
        ctypes.memmove(
            ctypes.addressof(buffer) + _FILE_RENAME_INFO.FileName.offset,
            name_bytes,
            len(name_bytes),
        )
        status_block = _IO_STATUS_BLOCK()
        status = _NtSetInformationFile(
            source,
            ctypes.byref(status_block),
            buffer,
            size,
            10,
        )
        if status < 0:
            raise _winErrorFromStatus(status)

