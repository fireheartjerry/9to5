"""Crash-safe file IO kernel: atomic writes, robust JSON load/update, pid file locks.

THE single home for the temp+replace+Windows-backoff ritual that used to be copy-pasted
across the tree (task_io, control, obsidian, ...). Every write uses a UNIQUE
pid-thread-rand temp name so concurrent writers (threads AND processes) never race the
same temp file, and ``os.replace`` is retried with bounded backoff because Windows raises
PermissionError while a reader momentarily holds the destination.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  atomicWriteText(path, text: str, *, retries: int=12, backoff: float=0.02, cap: float=1.0, encoding: str='utf-8') -> None  -- Write ``text`` as a COMPLETE-file swap (unique temp + os.replace).
  atomicWriteJson(path, obj: Any, *, indent: Optional[int]=2, ensure_ascii: bool=False, retries: int=12, backoff: float=0.02, cap: float=1.0) -> None  -- Serialize ``obj`` and atomically swap it into ``path`` (see atomicWriteText).
  loadJson(path, default: Any=None) -> Any  -- Parse JSON from ``path``
  updateJson(path, mutate_fn: Callable[[Any], Any], *, default: Any=None, lock: bool=False, stale_after: float=3600.0, timeout: float=10.0, indent: Optional[int]=2) -> Any  -- Read-mutate-write ``path`` with an atomic swap
  tryAcquireLock(path, *, stale_after: float=3600.0, owner_alive: Optional[Callable[[int], bool]]=None) -> bool  -- One non-blocking acquire attempt (O_CREAT|O_EXCL) writing our pid as the owner.
  releaseLock(path) -> None  -- Best-effort unlink of the lock file
  fileLock(path, *, stale_after: float=3600.0, timeout: float=10.0, poll: float=0.05)  -- Hold the pid lock at ``path`` for the ``with`` body
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: writes/replaces the given paths; creates parent dirs; creates/removes .lock and .bak files
RUN/TEST: python -m pytest tests/execution/test_fsio.py
"""
from __future__ import annotations

import json
import logging
import os
import threading
import time
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Callable, Optional

LOG = logging.getLogger("core.fsio")


def _uniqueTmp(path: Path) -> Path:
    """Unique temp sibling per writer (pid+thread+rand) so concurrent processes each have
    their own source file; avoids the FileNotFoundError when two writers race os.replace
    on a shared fixed temp name."""
    return path.parent / (
        f"{path.name}.{os.getpid()}-{threading.get_ident()}-{os.urandom(4).hex()}.tmp"
    )


def _atomicReplace(tmp: Path, dest: Path, retries: int, backoff: float, cap: float) -> None:
    """os.replace(tmp, dest) with bounded exponential backoff + jitter on transient Windows locks.

    Jitter desynchronizes concurrent writers so a replace storm (N processes hammering one
    destination) doesn't retry in lockstep; the 12-retry/1.0s-cap default budget (~6s worst)
    absorbs heavy contention -- a crash-safe control write must not give up in a second."""
    delay = backoff
    for attempt in range(1, retries + 1):
        try:
            os.replace(tmp, dest)
            return
        except PermissionError:
            if attempt >= retries:
                raise
            jitter = 1.0 + (os.urandom(1)[0] / 255.0)   # 1.0x-2.0x, no shared RNG state
            time.sleep(min(delay * jitter, cap))
            delay *= 2


def atomicWriteText(path, text: str, *, retries: int = 12, backoff: float = 0.02,
                    cap: float = 1.0, encoding: str = "utf-8") -> None:
    """Write ``text`` as a COMPLETE-file swap (unique temp + os.replace).

    A concurrent reader observes either the old file or the new one, never a torn mix.
    Creates parent directories. On failure the temp file is removed and the error re-raised
    (callers own their fail-open policy)."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = _uniqueTmp(p)
    try:
        tmp.write_text(text, encoding=encoding)
        _atomicReplace(tmp, p, retries, backoff, cap)
    except Exception:
        try:
            tmp.unlink(missing_ok=True)
        except OSError:
            pass
        raise


def atomicWriteJson(path, obj: Any, *, indent: Optional[int] = 2, ensure_ascii: bool = False,
                    retries: int = 12, backoff: float = 0.02, cap: float = 1.0) -> None:
    """Serialize ``obj`` and atomically swap it into ``path`` (see atomicWriteText)."""
    atomicWriteText(path, json.dumps(obj, indent=indent, ensure_ascii=ensure_ascii),
                    retries=retries, backoff=backoff, cap=cap)


def loadJson(path, default: Any = None) -> Any:
    """Parse JSON from ``path``. Missing file -> ``default`` silently; corrupt or
    unreadable -> ``default`` with a WARNING (never a silent reset)."""
    p = Path(path)
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return default
    except Exception as e:  # noqa: BLE001 -- corrupt/unreadable degrades loudly
        LOG.warning("loadJson(%s) unreadable (default used): %s", p, e)
        return default


def _readForUpdate(p: Path, default: Any) -> Any:
    """Current JSON content for a read-modify-write; a corrupt file is PRESERVED as
    ``<name>.bak`` (post-mortem evidence) with a WARNING, then ``default`` is used."""
    try:
        raw = p.read_text(encoding="utf-8")
    except FileNotFoundError:
        return default
    except OSError as e:
        LOG.warning("updateJson(%s) unreadable (default used): %s", p, e)
        return default
    try:
        return json.loads(raw)
    except Exception as e:  # noqa: BLE001
        bak = p.with_name(p.name + ".bak")
        try:
            bak.write_text(raw, encoding="utf-8")
            LOG.warning("updateJson(%s): corrupt JSON preserved at %s (%s); starting from default",
                        p, bak, e)
        except OSError as be:
            LOG.warning("updateJson(%s): corrupt JSON, .bak write failed (%s / %s); "
                        "starting from default", p, e, be)
        return default


def updateJson(path, mutate_fn: Callable[[Any], Any], *, default: Any = None,
               lock: bool = False, stale_after: float = 3600.0, timeout: float = 10.0,
               indent: Optional[int] = 2) -> Any:
    """Read-mutate-write ``path`` with an atomic swap; returns the value written.

    ``mutate_fn(data)`` may mutate in place (return None) or return a replacement object.
    ``default`` seeds a missing/corrupt file (corrupt content is kept as ``.bak`` + WARNING,
    never silently reset). ``lock=True`` holds a sibling ``.lock`` file across the
    read-modify-write so concurrent processes serialize."""
    p = Path(path)
    if lock:
        with fileLock(p.with_name(p.name + ".lock"), stale_after=stale_after, timeout=timeout):
            return _updateJsonUnlocked(p, mutate_fn, default, indent)
    return _updateJsonUnlocked(p, mutate_fn, default, indent)


def _updateJsonUnlocked(p: Path, mutate_fn: Callable[[Any], Any], default: Any,
                        indent: Optional[int]) -> Any:
    data = _readForUpdate(p, {} if default is None else default)
    result = mutate_fn(data)
    if result is not None:
        data = result
    atomicWriteJson(p, data, indent=indent)
    return data


# ---- pid file locks ---------------------------------------------------------

def _readOwnerPid(lp: Path) -> Optional[int]:
    try:
        return int((lp.read_text(encoding="utf-8") or "").strip())
    except Exception:  # noqa: BLE001 -- unreadable/garbage owner -> unknown
        return None


def _maybeStealStale(lp: Path, stale_after: float,
                     owner_alive: Optional[Callable[[int], bool]]) -> None:
    """Remove ``lp`` ONLY when provably stale (old mtime, or a dead owner per the injected
    ``owner_alive(pid)`` check) AND a re-stat confirms the very same file is still there.
    The re-stat closes the remove-fresh-lock race: between our staleness check and unlink,
    the stale lock may be released and a NEW holder's lock created -- unlinking that fresh
    lock would let two owners in."""
    try:
        st = lp.stat()
    except OSError:
        return
    stale = (time.time() - st.st_mtime) > stale_after
    if not stale and owner_alive is not None:
        pid = _readOwnerPid(lp)
        if pid is not None and not owner_alive(pid):
            stale = True
    if not stale:
        return
    try:
        st2 = lp.stat()
        if (st2.st_mtime_ns, st2.st_ino, st2.st_size) != (st.st_mtime_ns, st.st_ino, st.st_size):
            return  # the lock changed hands since we judged it stale -> treat as live
        lp.unlink()
        LOG.warning("stole stale lock %s (age %.0fs)", lp, time.time() - st.st_mtime)
    except OSError:
        pass  # someone else removed/replaced it first; O_EXCL below stays authoritative


def tryAcquireLock(path, *, stale_after: float = 3600.0,
                   owner_alive: Optional[Callable[[int], bool]] = None) -> bool:
    """One non-blocking acquire attempt (O_CREAT|O_EXCL) writing our pid as the owner.

    A stale lock (mtime older than ``stale_after``, or ``owner_alive(pid)`` False) is
    reclaimed first -- but only after a re-stat proves the SAME lock file is still present.
    When the owner cannot be determined we assume alive (never steal an unprovable lock)."""
    lp = Path(path)
    try:
        lp.parent.mkdir(parents=True, exist_ok=True)
        _maybeStealStale(lp, stale_after, owner_alive)
        fd = os.open(str(lp), os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        try:
            os.write(fd, str(os.getpid()).encode("ascii"))
        finally:
            os.close(fd)
        return True
    except FileExistsError:
        return False
    except Exception as e:  # noqa: BLE001 -- lock unavailable is a soft failure
        LOG.debug("tryAcquireLock(%s) unavailable (%s)", lp, e)
        return False


def releaseLock(path) -> None:
    """Best-effort unlink of the lock file. Never raises."""
    try:
        Path(path).unlink(missing_ok=True)
    except OSError as e:
        LOG.debug("releaseLock(%s) failed (ignored): %s", path, e)


@contextmanager
def fileLock(path, *, stale_after: float = 3600.0, timeout: float = 10.0, poll: float = 0.05):
    """Hold the pid lock at ``path`` for the ``with`` body; raises TimeoutError if it can
    never be acquired within ``timeout`` seconds."""
    lp = Path(path)
    deadline = time.monotonic() + timeout
    while not tryAcquireLock(lp, stale_after=stale_after):
        if time.monotonic() >= deadline:
            raise TimeoutError(f"could not acquire lock {lp} within {timeout}s")
        time.sleep(poll)
    try:
        yield lp
    finally:
        releaseLock(lp)
