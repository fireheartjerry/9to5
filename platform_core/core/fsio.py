def _fenceNativeDirectoryOperation(
    operation: Callable[_P, _R],
) -> Callable[_P, _R]:
    """Hold the receiver's lifecycle authority for one complete public operation."""

    @functools.wraps(operation)
    def fenced(*args: _P.args, **kwargs: _P.kwargs) -> _R:
        directory = cast("NativeDirectoryHandle", args[0])
        with directory._lifecycleFence():
            return operation(*args, **kwargs)

    return fenced


@contextmanager
def _nativeDirectoryPairLifecycleFence(
    left: "NativeDirectoryHandle",
    right: "NativeDirectoryHandle",
):
    """Fence two live handles in a canonical order, preventing ABBA close races."""

    if left is right:
        with left._lifecycleFence():
            yield
        return
    first, second = sorted((left, right), key=lambda item: item._lifecycle_key)
    with first._lifecycleFence():
        with second._lifecycleFence():
            yield


def _fenceNativeDirectoryPairOperation(
    operation: Callable[_P, _R],
) -> Callable[_P, _R]:
    """Hold both receiver and destination authorities for a public transfer."""

    @functools.wraps(operation)
    def fenced(*args: _P.args, **kwargs: _P.kwargs) -> _R:
        left = cast("NativeDirectoryHandle", args[0])
        destination_value = (
            args[2] if len(args) > 2 else cast(dict[str, object], kwargs)["destination"]
        )
        right = cast("NativeDirectoryHandle", destination_value)
        with _nativeDirectoryPairLifecycleFence(left, right):
            return operation(*args, **kwargs)

    return fenced


def _isReparseStat(info: os.stat_result) -> bool:
    attributes = getattr(info, "st_file_attributes", 0)
    reparse_flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
    return stat.S_ISLNK(info.st_mode) or bool(attributes & reparse_flag)


def assertNoReparsePath(path) -> Path:
    """Return an absolute path after rejecting every existing reparse component."""

    absolute = Path(os.path.abspath(os.fspath(path)))
    current = Path(absolute.anchor)
    for part in absolute.parts[1:]:
        current /= part
        try:
            info = os.lstat(current)
        except FileNotFoundError:
            continue
        if _isReparseStat(info):
            raise OSError(f"path traverses a reparse point: {current}")
    return absolute


def readNoFollowBytes(path, *, max_bytes: int) -> bytes:
    """Read one bounded regular file while retaining its no-follow identity."""

    p = Path(path)
    before = os.lstat(p)
    if _isReparseStat(before) or not stat.S_ISREG(before.st_mode):
        raise OSError(f"path is not a regular no-follow file: {p}")
    if before.st_nlink != 1:
        raise OSError(f"no-follow file has multiple links: {p}")
    if before.st_size > max_bytes:
        raise ValueError(f"file exceeds {max_bytes} bytes")
    flags = os.O_RDONLY
    if hasattr(os, "O_BINARY"):
        flags |= os.O_BINARY
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    fd = os.open(p, flags)
    try:
        opened = os.fstat(fd)
        if (opened.st_dev, opened.st_ino) != (before.st_dev, before.st_ino):
            raise OSError("file identity changed during no-follow open")
        chunks: list[bytes] = []
        total = 0
        while True:
            chunk = os.read(fd, min(65536, max_bytes + 1 - total))
            if not chunk:
                break
            chunks.append(chunk)
            total += len(chunk)
            if total > max_bytes:
                raise ValueError(f"file exceeds {max_bytes} bytes")
        return b"".join(chunks)
    finally:
        os.close(fd)


