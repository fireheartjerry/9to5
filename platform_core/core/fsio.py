def _nativePublicationOwnerAlive(
    pid: int,
    process_start_token: str,
    publication_name: str,
) -> bool:
    if process_start_token == _NATIVE_UNQUALIFIED_PROCESS_START_TOKEN:
        # This closed sentinel means the issuer could not prove a PID-reuse-safe
        # birth identity. Such evidence is permanently non-reclaimable.
        return True
    if pid == os.getpid() and process_start_token == _currentNativeProcessStartToken():
        with _ACTIVE_NATIVE_PUBLICATIONS_LOCK:
            return publication_name in _ACTIVE_NATIVE_PUBLICATIONS
    try:
        observed = _nativeProcessStartToken(pid)
    except (OSError, UnicodeError, ValueError):
        # An unverifiable foreign writer remains conservatively live.
        return True
    if observed is None:
        return False
    return observed == process_start_token


def _nativeDeleteOwnerAlive(
    pid: int,
    process_start_token: str,
    quarantine_name: str,
) -> bool:
    """Qualify one deleter by exact process birth and its active intent key."""

    if process_start_token == _NATIVE_UNQUALIFIED_PROCESS_START_TOKEN:
        return True
    if pid == os.getpid() and process_start_token == _currentNativeProcessStartToken():
        with _ACTIVE_NATIVE_DELETIONS_LOCK:
            return quarantine_name in _ACTIVE_NATIVE_DELETE_ARTIFACTS
    try:
        observed = _nativeProcessStartToken(pid)
    except (OSError, UnicodeError, ValueError):
        return True
    if observed is None:
        return False
    return observed == process_start_token


def _posixRenameNoReplace(
    source_directory: int,
    source_name: str,
    destination_directory: int,
    destination_name: str,
) -> None:
    """Atomically publish one complete file without replacing an existing name."""

    libc = ctypes.CDLL(None, use_errno=True)
    source = os.fsencode(source_name)
    destination = os.fsencode(destination_name)
    result: int
    if sys.platform.startswith("linux"):
        rename = getattr(libc, "renameat2", None)
        if rename is None:
            raise OSError(errno.ENOTSUP, "renameat2 is unavailable")
        rename.argtypes = (
            ctypes.c_int,
            ctypes.c_char_p,
            ctypes.c_int,
            ctypes.c_char_p,
            ctypes.c_uint,
        )
        rename.restype = ctypes.c_int
        result = rename(
            source_directory,
            source,
            destination_directory,
            destination,
            1,  # RENAME_NOREPLACE
        )
    elif sys.platform == "darwin":
        rename = getattr(libc, "renameatx_np", None)
        if rename is None:
            raise OSError(errno.ENOTSUP, "renameatx_np is unavailable")
        rename.argtypes = (
            ctypes.c_int,
            ctypes.c_char_p,
            ctypes.c_int,
            ctypes.c_char_p,
            ctypes.c_uint,
        )
        rename.restype = ctypes.c_int
        result = rename(
            source_directory,
            source,
            destination_directory,
            destination,
            0x00000004,  # RENAME_EXCL
        )
    else:
        raise OSError(errno.ENOTSUP, "atomic no-replace rename is unavailable")
    if result == 0:
        return
    error = ctypes.get_errno()
    if error in {errno.EEXIST, errno.ENOTEMPTY}:
        raise FileExistsError(error, os.strerror(error), destination_name)
    raise OSError(error, os.strerror(error), destination_name)


