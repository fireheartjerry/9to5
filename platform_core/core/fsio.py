def _boundedNativePublicationEntries(
    entries: tuple[NativeDirectoryEntry, ...],
    *,
    destination_key: str | None = None,
    destination_keys: frozenset[str] | None = None,
    reserve_one: bool = False,
) -> tuple[NativeDirectoryEntry, ...]:
    """Validate the complete generic publisher inventory before any cleanup."""

    if destination_keys is None:
        if destination_key is None:
            raise ValueError("native publication destination key is required")
        destination_keys = frozenset({destination_key})
    elif destination_key is not None:
        raise ValueError("native publication destination keys are ambiguous")
    total = 0
    matching: list[NativeDirectoryEntry] = []
    for entry in entries:
        if entry.name.startswith(".galaxy-delete-"):
            total += 1
            if (
                _NATIVE_DELETE_INTENT_RE.fullmatch(entry.name) is None
                and _NATIVE_DELETE_STAGING_RE.fullmatch(entry.name) is None
            ):
                raise OSError("native deletion artifact name is malformed")
            continue
        if not entry.name.startswith(".galaxy-publish-"):
            continue
        total += 1
        if total > _NATIVE_MUTATION_DEBRIS_MAX_TOTAL:
            raise NativeDirectoryQuotaExceeded(
                errno.E2BIG,
                "native publication debris total quota exceeded across mutation artifacts",
            )
        match = _NATIVE_PUBLISH_TEMP_RE.fullmatch(entry.name)
        if match is None:
            raise OSError("create-only publisher artifact is malformed")
        if match.group("destination") not in destination_keys:
            continue
        if len(matching) >= _NATIVE_PUBLICATION_DEBRIS_MAX_SAME_DESTINATION:
            raise NativeDirectoryQuotaExceeded(
                errno.E2BIG,
                "native same-destination publication debris quota exceeded",
            )
        matching.append(entry)
    if total > _NATIVE_MUTATION_DEBRIS_MAX_TOTAL or (
        reserve_one and total >= _NATIVE_MUTATION_DEBRIS_MAX_TOTAL
    ):
        raise NativeDirectoryQuotaExceeded(
            errno.E2BIG,
            "native publication debris total quota has no publication capacity",
        )
    if (
        reserve_one
        and len(matching) >= _NATIVE_PUBLICATION_DEBRIS_MAX_SAME_DESTINATION
    ):
        raise NativeDirectoryQuotaExceeded(
            errno.E2BIG,
            "native same-destination publication debris quota has no publication capacity",
        )
    return tuple(matching)


def _boundedNativeDeleteEntries(
    entries: tuple[NativeDirectoryEntry, ...],
    *,
    destination_key: str,
    reserve_one: bool = False,
) -> tuple[NativeDirectoryEntry, ...]:
    """Validate the combined mutation namespace and one delete destination."""

    total = 0
    matching: list[NativeDirectoryEntry] = []
    for entry in entries:
        if entry.name.startswith(".galaxy-publish-"):
            total += 1
            if _NATIVE_PUBLISH_TEMP_RE.fullmatch(entry.name) is None:
                raise OSError("create-only publisher artifact is malformed")
            continue
        if not entry.name.startswith(".galaxy-delete-"):
            continue
        total += 1
        match = _NATIVE_DELETE_INTENT_RE.fullmatch(entry.name)
        if match is None:
            match = _NATIVE_DELETE_STAGING_RE.fullmatch(entry.name)
        if match is None:
            raise OSError("native deletion artifact name is malformed")
        if match.group("destination") != destination_key:
            continue
        if len(matching) >= _NATIVE_DELETE_DEBRIS_MAX_SAME_DESTINATION:
            raise NativeDirectoryQuotaExceeded(
                errno.E2BIG,
                "native same-destination deletion debris quota exceeded",
            )
        matching.append(entry)
    if total > _NATIVE_MUTATION_DEBRIS_MAX_TOTAL or (
        reserve_one and total >= _NATIVE_MUTATION_DEBRIS_MAX_TOTAL
    ):
        raise NativeDirectoryQuotaExceeded(
            errno.E2BIG,
            "native deletion debris total quota exceeded across mutation artifacts",
        )
    if reserve_one and len(matching) >= _NATIVE_DELETE_DEBRIS_MAX_SAME_DESTINATION:
        raise NativeDirectoryQuotaExceeded(
            errno.E2BIG,
            "native same-destination deletion debris quota has no deletion capacity",
        )
    return tuple(matching)


