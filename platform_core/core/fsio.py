def _nativeDeleteIntentPayload(
    *,
    destination_name: str,
    quarantine_name: str,
    target: NativeFileIdentity,
    guard: NativeFileIdentity,
) -> bytes:
    base = {
        "destination": _nativeDeleteDestinationKey(destination_name),
        "destination_name": destination_name,
        "guard": list(_nativeStableIdentityKey(guard)),
        "owner": [os.getpid(), _currentNativeProcessStartToken()],
        "quarantine": quarantine_name,
        "schema": _NATIVE_DELETE_INTENT_SCHEMA,
        "target": list(_nativeStableIdentityKey(target)),
    }
    canonical = json.dumps(
        base,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("ascii")
    record = {**base, "digest": hashlib.sha256(canonical).hexdigest()}
    payload = json.dumps(
        record,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("ascii")
    if len(payload) > _NATIVE_DELETE_INTENT_MAX_BYTES:
        raise OSError("native deletion intent exceeds its bound")
    return payload


def _nativeDeleteIdentityKey(value: object) -> tuple[int, int, bool, bool, int, int]:
    if not isinstance(value, list) or len(value) != 6:
        raise OSError("native deletion intent identity is malformed")
    volume_id, file_id, is_directory, is_reparse, mount_id, reparse_tag = value
    if (
        type(volume_id) is not int
        or volume_id < 0
        or type(file_id) is not int
        or file_id <= 0
        or type(is_directory) is not bool
        or type(is_reparse) is not bool
        or type(mount_id) is not int
        or mount_id < 0
        or type(reparse_tag) is not int
        or reparse_tag < 0
    ):
        raise OSError("native deletion intent identity is unsafe")
    return (
        volume_id,
        file_id,
        is_directory,
        is_reparse,
        mount_id,
        reparse_tag,
    )


def _parseNativeDeleteIntent(payload: bytes) -> NativeDeleteIntent:
    if len(payload) > _NATIVE_DELETE_INTENT_MAX_BYTES:
        raise OSError("native deletion intent exceeds its bound")
    try:
        record = json.loads(payload.decode("ascii", errors="strict"))
    except (UnicodeError, json.JSONDecodeError) as exc:
        raise OSError("native deletion intent is malformed") from exc
    if not isinstance(record, dict) or set(record) != {
        "destination",
        "destination_name",
        "digest",
        "guard",
        "owner",
        "quarantine",
        "schema",
        "target",
    }:
        raise OSError("native deletion intent schema is malformed")
    if record["schema"] != _NATIVE_DELETE_INTENT_SCHEMA:
        raise OSError("native deletion intent schema is unknown")
    destination = record["destination"]
    destination_name = record["destination_name"]
    quarantine = record["quarantine"]
    digest = record["digest"]
    owner = record["owner"]
    if (
        type(destination) is not str
        or re.fullmatch(r"[0-9a-f]{64}", destination) is None
        or type(destination_name) is not str
        or not destination_name
        or destination_name in {".", ".."}
        or "/" in destination_name
        or "\0" in destination_name
        or len(destination_name.encode("utf-8"))
        > _NATIVE_DELETE_DESTINATION_MAX_BYTES
        or type(quarantine) is not str
        or _NATIVE_DELETE_INTENT_RE.fullmatch(quarantine) is None
        or type(digest) is not str
        or re.fullmatch(r"[0-9a-f]{64}", digest) is None
        or not isinstance(owner, list)
        or len(owner) != 2
        or type(owner[0]) is not int
        or owner[0] <= 0
        or type(owner[1]) is not str
        or re.fullmatch(r"[0-9a-f]{32}", owner[1]) is None
    ):
        raise OSError("native deletion intent binding is malformed")
    match = _NATIVE_DELETE_INTENT_RE.fullmatch(quarantine)
    assert match is not None
    target_key = _nativeDeleteIdentityKey(record["target"])
    guard_key = _nativeDeleteIdentityKey(record["guard"])
    if (
        destination != match.group("destination")
        or _nativeDeleteDestinationKey(destination_name) != destination
        or _nativeDeleteIdentityTokenFromKey(target_key) != match.group("target")
        or _nativeDeleteIdentityTokenFromKey(guard_key) != match.group("guard")
        or owner[0] != int(match.group("pid"))
        or owner[1] != match.group("start")
        or target_key[2]
        or target_key[3]
        or guard_key[2]
        or guard_key[3]
    ):
        raise OSError("native deletion intent filename binding differs")
    base = {key: value for key, value in record.items() if key != "digest"}
    canonical = json.dumps(
        base,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("ascii")
    if hashlib.sha256(canonical).hexdigest() != digest:
        raise OSError("native deletion intent digest differs")
    canonical_record = json.dumps(
        record,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("ascii")
    if canonical_record != payload:
        raise OSError("native deletion intent encoding is non-canonical")
    return NativeDeleteIntent(
        destination_key=destination,
        destination_name=destination_name,
        quarantine_name=quarantine,
        owner_pid=owner[0],
        owner_start=owner[1],
        target_key=target_key,
        guard_key=guard_key,
        digest=digest,
    )


