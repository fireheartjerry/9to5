def _nativeProcessStartToken(pid: int) -> str | None:
    """Return a compact PID-reuse-safe process birth identity where qualified."""

    if type(pid) is not int or pid <= 0:
        raise ValueError("pid must be positive")
    if os.name == "nt":
        from ctypes import wintypes

        kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
        kernel32.OpenProcess.argtypes = (
            wintypes.DWORD,
            wintypes.BOOL,
            wintypes.DWORD,
        )
        kernel32.OpenProcess.restype = wintypes.HANDLE
        kernel32.GetProcessTimes.argtypes = (
            wintypes.HANDLE,
            ctypes.POINTER(wintypes.FILETIME),
            ctypes.POINTER(wintypes.FILETIME),
            ctypes.POINTER(wintypes.FILETIME),
            ctypes.POINTER(wintypes.FILETIME),
        )
        kernel32.GetProcessTimes.restype = wintypes.BOOL
        kernel32.GetExitCodeProcess.argtypes = (
            wintypes.HANDLE,
            ctypes.POINTER(wintypes.DWORD),
        )
        kernel32.GetExitCodeProcess.restype = wintypes.BOOL
        kernel32.CloseHandle.argtypes = (wintypes.HANDLE,)
        kernel32.CloseHandle.restype = wintypes.BOOL
        handle = kernel32.OpenProcess(0x1000, False, pid)
        if not handle:
            if ctypes.get_last_error() == 87:
                return None
            raise OSError("process creation identity is not observable")
        creation = wintypes.FILETIME()
        exit_time = wintypes.FILETIME()
        kernel = wintypes.FILETIME()
        user = wintypes.FILETIME()
        exit_code = wintypes.DWORD()
        try:
            if not kernel32.GetProcessTimes(
                handle,
                ctypes.byref(creation),
                ctypes.byref(exit_time),
                ctypes.byref(kernel),
                ctypes.byref(user),
            ) or not kernel32.GetExitCodeProcess(handle, ctypes.byref(exit_code)):
                raise OSError("process creation identity changed during observation")
            if exit_code.value != 259:
                return None
        finally:
            kernel32.CloseHandle(handle)
        ticks = (creation.dwHighDateTime << 32) | creation.dwLowDateTime
        return hashlib.sha256(
            f"windows\0{pid}\0{ticks}".encode("ascii")
        ).hexdigest()[:32]
    if sys.platform.startswith("linux"):
        try:
            stat_text = Path(f"/proc/{pid}/stat").read_text(
                encoding="ascii",
                errors="strict",
            )
        except FileNotFoundError:
            return None
        closing = stat_text.rfind(")")
        fields = stat_text[closing + 1 :].split() if closing > 0 else []
        if len(fields) <= 19 or not fields[19].isdigit():
            raise OSError("Linux process creation identity is malformed")
        if fields[0] in {"Z", "X", "x"}:
            return None
        boot_id = Path("/proc/sys/kernel/random/boot_id").read_text(
            encoding="ascii",
            errors="strict",
        ).strip()
        if re.fullmatch(r"[0-9a-fA-F-]{36}", boot_id) is None:
            raise OSError("Linux boot identity is malformed")
        return hashlib.sha256(
            f"linux\0{pid}\0{boot_id.lower()}\0{fields[19]}".encode("ascii")
        ).hexdigest()[:32]
    return None


