def _nativeNamesEquivalent(left: str, right: str, *, windows: bool) -> bool:
    """Compare one native component using the host namespace's name rules."""

    if not windows:
        return left == right
    if os.name == "nt":
        # CompareStringOrdinal is the same non-linguistic, case-insensitive
        # comparison used for Win32 component lookup.  In particular it avoids
        # Python ``casefold`` expansions being treated as filesystem aliases.
        return bool(
            _CompareStringOrdinal(  # type: ignore[name-defined]
                left,
                len(left),
                right,
                len(right),
                True,
            )
            == 2
        )
    # ``windows=True`` is useful to deterministic metadata tests on POSIX.  The
    # production Windows path above remains authoritative for lookup equality.
    return left.lower() == right.lower()


