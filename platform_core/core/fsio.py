def _posixMountId(handle: int, device: int) -> int:
    """Return Linux's mount identity; same-device bind mounts remain distinct."""

    if not sys.platform.startswith("linux"):
        return device
    flags = os.O_RDONLY
    if hasattr(os, "O_CLOEXEC"):
        flags |= os.O_CLOEXEC
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    fdinfo = os.open(f"/proc/self/fdinfo/{handle}", flags)
    try:
        chunks: list[bytes] = []
        total = 0
        while True:
            chunk = os.pread(fdinfo, min(4096, 65537 - total), total)
            if not chunk:
                break
            chunks.append(chunk)
            total += len(chunk)
            if total > 65536:
                raise OSError("Linux fdinfo exceeds its identity quota")
    finally:
        os.close(fdinfo)
    try:
        text = b"".join(chunks).decode("ascii", errors="strict")
    except UnicodeError as exc:
        raise OSError("Linux fdinfo is not ASCII") from exc
    prefix = "mnt_id:\t"
    values = [
        line[len(prefix) :]
        for line in text.splitlines()
        if line.startswith(prefix)
    ]
    if len(values) != 1 or not values[0].isdigit() or int(values[0]) <= 0:
        raise OSError("Linux fdinfo has no unique mount identity")
    return int(values[0])


