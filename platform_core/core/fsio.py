class NativeDirectoryQuotaExceeded(OSError):
    """A retained directory inventory exceeded one immutable memory bound."""


_NATIVE_DIRECTORY_MAX_ENTRIES = 65_536
_NATIVE_DIRECTORY_MAX_NAME_BYTES = 1_024
_NATIVE_PUBLICATION_DIRECTORY_MAX_ENTRIES = _NATIVE_DIRECTORY_MAX_ENTRIES


def _validateNativeDirectoryLimits(
    *,
    max_entries: int,
    max_name_bytes: int,
) -> None:
    """Accept only caller tightening of the kernel's closed enumeration bounds."""

    for label, value, hard_limit in (
        ("max_entries", max_entries, _NATIVE_DIRECTORY_MAX_ENTRIES),
        ("max_name_bytes", max_name_bytes, _NATIVE_DIRECTORY_MAX_NAME_BYTES),
    ):
        if type(value) is not int:
            raise TypeError(f"{label} must be an integer")
        if value <= 0:
            raise ValueError(f"{label} must be positive")
        if value > hard_limit:
            raise ValueError(f"{label} may only tighten the native hard limit")


def _nativeDirectoryNameBytes(name: object, *, max_name_bytes: int) -> bytes:
    """Validate one component and return its strict UTF-8 representation."""

    if type(name) is not str:
        raise OSError(errno.EILSEQ, "native directory name is not strict UTF-8")
    try:
        encoded = name.encode("utf-8", errors="strict")
    except UnicodeError as exc:
        raise OSError(
            errno.EILSEQ,
            "native directory name is not strict UTF-8",
        ) from exc
    if len(encoded) > max_name_bytes:
        raise NativeDirectoryQuotaExceeded(
            errno.E2BIG,
            "native directory name byte quota exceeded",
        )
    return encoded


def _validateNativeDirectoryChildName(
    name: object,
    *,
    max_name_bytes: int,
    windows: bool,
) -> str:
    if (
        type(name) is not str
        or not name
        or name in {".", ".."}
        or "/" in name
        or (windows and ("\\" in name or ":" in name))
        or "\0" in name
    ):
        raise ValueError("relative native child name is invalid")
    _nativeDirectoryNameBytes(name, max_name_bytes=max_name_bytes)
    return name


def _posixListDirectoryNames(
    handle: int,
    *,
    max_entries: int,
    max_name_bytes: int,
) -> tuple[str, ...]:
    """Incrementally collect one bounded retained POSIX directory inventory."""

    _validateNativeDirectoryLimits(
        max_entries=max_entries,
        max_name_bytes=max_name_bytes,
    )
    try:
        scanner = os.scandir(handle)
    except (TypeError, NotImplementedError) as exc:
        raise OSError(
            errno.ENOTSUP,
            "retained incremental directory enumeration is unavailable",
        ) from exc
    names: list[str] = []
    with scanner:
        for observed in scanner:
            name = observed.name
            _nativeDirectoryNameBytes(name, max_name_bytes=max_name_bytes)
            if len(names) >= max_entries:
                raise NativeDirectoryQuotaExceeded(
                    errno.E2BIG,
                    "native directory entry quota exceeded",
                )
            names.append(name)
    return tuple(names)


