def _currentNativeProcessStartToken() -> str:
    """Return a PID-bound birth token, refreshing inherited state after a fork."""

    global _NATIVE_PROCESS_IDENTITY_PID, _NATIVE_PROCESS_START_TOKEN
    pid = os.getpid()
    if _NATIVE_PROCESS_IDENTITY_PID == pid:
        return _NATIVE_PROCESS_START_TOKEN
    with _ACTIVE_NATIVE_PUBLICATIONS_LOCK:
        if _NATIVE_PROCESS_IDENTITY_PID != pid:
            try:
                observed = _nativeProcessStartToken(pid)
            except OSError:
                observed = None
            _NATIVE_PROCESS_IDENTITY_PID = pid
            _NATIVE_PROCESS_START_TOKEN = (
                observed
                if observed is not None
                else _NATIVE_UNQUALIFIED_PROCESS_START_TOKEN
            )
        return _NATIVE_PROCESS_START_TOKEN


