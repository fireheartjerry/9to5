@contextmanager
def _activeNativePublication(name: str):
    with _ACTIVE_NATIVE_PUBLICATIONS_LOCK:
        if name in _ACTIVE_NATIVE_PUBLICATIONS:
            raise OSError("native publication identity is already active")
        _ACTIVE_NATIVE_PUBLICATIONS.add(name)
    try:
        yield
    finally:
        with _ACTIVE_NATIVE_PUBLICATIONS_LOCK:
            _ACTIVE_NATIVE_PUBLICATIONS.discard(name)


@contextmanager
def _activeNativeDeletion(parent: NativeFileIdentity, name: str):
    """Fence cooperative same-process mutation of one retained child name."""

    key = (_nativeIdentityToken(parent), name)
    with _ACTIVE_NATIVE_DELETIONS_LOCK:
        if key in _ACTIVE_NATIVE_DELETIONS:
            raise BlockingIOError(errno.EBUSY, "native deletion is already active", name)
        _ACTIVE_NATIVE_DELETIONS.add(key)
    try:
        yield
    finally:
        with _ACTIVE_NATIVE_DELETIONS_LOCK:
            _ACTIVE_NATIVE_DELETIONS.discard(key)


@contextmanager
def _activeNativeDeleteArtifacts(*names: str):
    """Bind same-process deleter liveness to exact private artifact names."""

    if (
        not names
        or any(type(name) is not str or not name for name in names)
        or len(set(names)) != len(names)
    ):
        raise ValueError("native deletion artifact identities are invalid")
    with _ACTIVE_NATIVE_DELETIONS_LOCK:
        if any(name in _ACTIVE_NATIVE_DELETE_ARTIFACTS for name in names):
            raise OSError("native deletion artifact identity is already active")
        _ACTIVE_NATIVE_DELETE_ARTIFACTS.update(names)
    try:
        yield
    finally:
        with _ACTIVE_NATIVE_DELETIONS_LOCK:
            _ACTIVE_NATIVE_DELETE_ARTIFACTS.difference_update(names)


def _lockPosixDeleteGuard(handle: int) -> bool:
    """Take a non-blocking lifetime lock on one retained deletion guard."""

    try:
        import fcntl as fcntl_module
    except ImportError as exc:  # pragma: no cover - POSIX runtimes provide fcntl
        raise OSError(errno.ENOTSUP, "POSIX deletion guard locking is unavailable") from exc
    flock = getattr(fcntl_module, "flock", None)
    lock_ex = getattr(fcntl_module, "LOCK_EX", None)
    lock_nb = getattr(fcntl_module, "LOCK_NB", None)
    if flock is None or type(lock_ex) is not int or type(lock_nb) is not int:
        raise OSError(errno.ENOTSUP, "POSIX deletion guard locking is unavailable")
    try:
        flock(handle, lock_ex | lock_nb)
    except BlockingIOError:
        return False
    except OSError as exc:
        raise OSError(errno.ENOTSUP, "POSIX deletion guard locking failed") from exc
    return True


