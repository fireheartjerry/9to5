_NATIVE_DELETE_INTENT_SCHEMA = "galaxy-native-delete-intent-v1"
_NATIVE_DELETE_INTENT_MAX_BYTES = 4096
_NATIVE_DELETE_DESTINATION_MAX_BYTES = 255


def _nativeDeleteDestinationKey(name: str) -> str:
    if (
        type(name) is not str
        or not name
        or name in {".", ".."}
        or "/" in name
        or "\0" in name
        or len(name.encode("utf-8")) > _NATIVE_DELETE_DESTINATION_MAX_BYTES
    ):
        raise ValueError("native deletion destination name is invalid")
    return hashlib.sha256(name.encode("utf-8")).hexdigest()


def _nativeDeleteIdentityToken(
    identity: NativeFileIdentity,
) -> str:
    return _nativeDeleteIdentityTokenFromKey(_nativeStableIdentityKey(identity))


def _nativeDeleteIdentityTokenFromKey(
    key: tuple[int, int, bool, bool, int, int],
) -> str:
    digest = hashlib.sha256(repr(key).encode("ascii")).digest()
    return base64.urlsafe_b64encode(digest).decode("ascii").rstrip("=")


