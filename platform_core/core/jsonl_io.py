"""Append-only JSONL kernel: one-line append with rotation, torn-line-tolerant reads.

THE single home for the "append a JSON record per line / read them back" ritual that used
to be re-implemented across audit, adversary_trust, tracing-style logs, and trajectory.
Reads are per-line fail-open: ONE torn tail line (a crash mid-append) skips that line
only -- it never erases the rest of the history.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  appendRecord(path, record: Any, *, max_bytes: Optional[int]=None) -> None  -- Append ``record`` as one JSON line
  iterRecords(path) -> 'tuple[list, int]'  -- Parse every line of ``path``
  readTail(path, n: int=20) -> list  -- The last ``n`` records (oldest-first within the window)
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: appends to the given path; rotates to <name>.1; creates parent dirs
RUN/TEST: python -m pytest tests/platform/test_jsonl_io.py
"""
from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Optional

LOG = logging.getLogger("core.jsonl_io")


def appendRecord(path, record: Any, *, max_bytes: Optional[int] = None) -> None:
    """Append ``record`` as one JSON line. When ``max_bytes`` is given and the file is
    already past it, the file is first rotated to ``<name>.1`` (overwriting a prior .1).
    Raises on IO failure -- callers own their fail-open policy."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    if max_bytes is not None and p.exists() and p.stat().st_size > max_bytes:
        p.replace(p.with_name(p.name + ".1"))   # rotate (overwrites the prior .1)
    with p.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(record, ensure_ascii=False) + "\n")


def iterRecords(path) -> "tuple[list, int]":
    """Parse every line of ``path``; returns ``(records, skipped_count)``.

    Per-line try/except: a single torn/corrupt line is counted in ``skipped_count`` and
    skipped -- it never discards the parseable remainder. A missing file is ``([], 0)``;
    an unreadable file logs a WARNING and returns ``([], 0)``."""
    p = Path(path)
    try:
        lines = p.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return [], 0
    except Exception as e:  # noqa: BLE001
        LOG.warning("iterRecords(%s) unreadable: %s", p, e)
        return [], 0
    records: list = []
    skipped = 0
    for ln in lines:
        ln = ln.strip()
        if not ln:
            continue
        try:
            records.append(json.loads(ln))
        except Exception:  # noqa: BLE001 -- torn line: skip, never erase history
            skipped += 1
    return records, skipped


def readTail(path, n: int = 20) -> list:
    """The last ``n`` records (oldest-first within the window). Bad lines are skipped;
    any read error degrades to ``[]``."""
    p = Path(path)
    try:
        lines = p.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        return []
    except Exception as e:  # noqa: BLE001
        LOG.warning("readTail(%s) unreadable: %s", p, e)
        return []
    out: list = []
    for ln in lines[-n:]:
        ln = ln.strip()
        if not ln:
            continue
        try:
            out.append(json.loads(ln))
        except Exception:  # noqa: BLE001
            continue
    return out
