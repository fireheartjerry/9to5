"""Safe subprocess kernel for git/gh/gate commands: no prompts, no stdin, always bounded.

THE single home for the git-subprocess ritual that used to diverge across nine wrappers
(worktree had NO timeout, so a credential prompt could hang a run). Every invocation:
GIT_TERMINAL_PROMPT=0 (git never blocks on credentials), stdin=DEVNULL, capture_output,
text mode, and a hard timeout. Also owns the shared GATE_COMMANDS tier table consumed by
``github._prePrSuiteGate`` and ``self_ref_gate``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  runTool(cmd, *, cwd=None, timeout: Optional[float]=DEFAULT_TIMEOUT_SECONDS, extra_env: Optional[dict]=None, check: bool=False) -> subprocess.CompletedProcess  -- Run ``cmd`` with the safety rails every external tool call needs: stdin=DEVNULL
  runGit(*args: str, cwd, timeout: Optional[float]=DEFAULT_TIMEOUT_SECONDS, check: bool=False) -> subprocess.CompletedProcess  -- ``git <args>`` in ``cwd`` with GIT_TERMINAL_PROMPT=0 so git can NEVER hang a run
  gitPreflight(work_dir, *, require_origin: bool=False, timeout: Optional[float]=DEFAULT_TIMEOUT_SECONDS) -> 'tuple[bool, str]'  -- (ok, reason) preflight: ``work_dir`` is inside a git work tree, and (optionally)
  gateCommands(tier: str) -> 'list[list[str]]'  -- Fresh mutable copies of a GATE_COMMANDS tier so callers can't mutate the table.
DEPENDS-ON: platform_core.execution
SIDE-EFFECTS: spawns subprocesses (git, gh, python gate commands)
RUN/TEST: python -m pytest tests/platform/test_git_io.py
"""

from __future__ import annotations

import os
import subprocess
import sys
from typing import Optional

from platform_core.execution.sandbox_broker import runLegacyProcess

# Callers should pass config.GIT_TIMEOUT_SECONDS; this fallback keeps the kernel a
# stdlib-only leaf (it must not import config).
DEFAULT_TIMEOUT_SECONDS: int = 120


def runTool(
    cmd,
    *,
    cwd=None,
    timeout: Optional[float] = DEFAULT_TIMEOUT_SECONDS,
    extra_env: Optional[dict] = None,
    check: bool = False,
) -> subprocess.CompletedProcess:
    """Run ``cmd`` with the safety rails every external tool call needs: stdin=DEVNULL
    (never blocks on input), capture_output+text, and a hard ``timeout``. Raises
    TimeoutExpired/CalledProcessError per stdlib semantics -- callers own their policy."""
    env = None
    if extra_env:
        env = os.environ.copy()
        env.update(extra_env)
    return runLegacyProcess(
        list(cmd),
        cwd=(str(cwd) if cwd is not None else None),
        check=check,
        capture_output=True,
        text=True,
        # Pin UTF-8 decoding: without it text mode uses the OS default (cp1252 on Windows),
        # and a git/gh diff byte undefined in cp1252 (e.g. 0x8f/0x9d in UTF-8 code) crashes
        # the subprocess reader thread and SILENTLY drops the output (rc=0, stdout=None).
        # errors="replace" keeps the capture intact. Mirrors agents/verification.py.
        encoding="utf-8",
        errors="replace",
        stdin=subprocess.DEVNULL,
        env=env,
        timeout=timeout,
    )


def runGit(
    *args: str, cwd, timeout: Optional[float] = DEFAULT_TIMEOUT_SECONDS, check: bool = False
) -> subprocess.CompletedProcess:
    """``git <args>`` in ``cwd`` with GIT_TERMINAL_PROMPT=0 so git can NEVER hang a run
    waiting on a credential prompt."""
    return runTool(
        ["git", *args], cwd=cwd, timeout=timeout, check=check, extra_env={"GIT_TERMINAL_PROMPT": "0"}
    )


def gitPreflight(
    work_dir, *, require_origin: bool = False, timeout: Optional[float] = DEFAULT_TIMEOUT_SECONDS
) -> "tuple[bool, str]":
    """(ok, reason) preflight: ``work_dir`` is inside a git work tree, and (optionally)
    an ``origin`` remote is configured. Reasons are stable strings callers surface
    verbatim. Propagates subprocess exceptions (e.g. TimeoutExpired) to the caller."""
    chk = runGit("rev-parse", "--is-inside-work-tree", cwd=work_dir, timeout=timeout)
    if chk.returncode != 0 or "true" not in (chk.stdout or "").lower():
        return False, "not a git repository"
    if require_origin:
        remote = runGit("remote", "get-url", "origin", cwd=work_dir, timeout=timeout)
        if remote.returncode != 0 or not (remote.stdout or "").strip():
            return False, "no origin remote configured"
    return True, ""


# ---- shared gate-command tiers ------------------------------------------------
# ONE table for the cheap Windows repo gates so github._prePrSuiteGate and
# self_ref_gate can never drift apart on what "the repo is healthy" means.
_REPO_CHECKS: "tuple[tuple[str, ...], ...]" = (
    (sys.executable, "tools\\repo_map.py"),
    (sys.executable, "tools\\repo_map.py", "--check"),
    (sys.executable, "validate_workflows.py"),
)
_FAST_SUITE: "tuple[str, ...]" = (
    sys.executable,
    "-m",
    "pytest",
    "-m",
    "not slow",
    "-n",
    "auto",
    "--dist",
    "loadscope",
    "-q",
)

GATE_COMMANDS: "dict[str, tuple[tuple[str, ...], ...]]" = {
    "repo_checks": _REPO_CHECKS,  # self_ref post-verify tier (cheap)
    "pre_pr": _REPO_CHECKS + (_FAST_SUITE,),  # pre-PR tier (repo gates + fast suite)
}


def gateCommands(tier: str) -> "list[list[str]]":
    """Fresh mutable copies of a GATE_COMMANDS tier so callers can't mutate the table."""
    return [list(cmd) for cmd in GATE_COMMANDS[tier]]
