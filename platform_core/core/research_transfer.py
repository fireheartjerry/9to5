def _text(value: str, name: str, *, limit: int = 16_384) -> None:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{name} must be non-empty")
    if len(value.encode("utf-8")) > limit:
        raise ValueError(f"{name} is oversized")


def _time(
    value: str,
    name: str,
    *,
    allow_subseconds: bool = False,
) -> datetime:
    _text(value, name, limit=128)
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError(f"{name} is invalid") from exc
    if parsed.tzinfo is None:
        raise ValueError(f"{name} must be timezone-aware")
    utc = parsed.astimezone(timezone.utc)
    timespec = "microseconds" if allow_subseconds and utc.microsecond else "seconds"
    canonical = utc.isoformat(timespec=timespec).replace("+00:00", "Z")
    if value != canonical:
        raise ValueError(f"{name} must use canonical UTC second precision")
    return utc


def _sha256(value: str, name: str) -> None:
    if not isinstance(value, str) or _SHA256.fullmatch(value) is None:
        raise ValueError(f"{name} must be a lowercase SHA-256 digest")


def _closed_sorted(values: tuple[str, ...], name: str) -> None:
    if not values or any(not isinstance(value, str) or not value.strip() for value in values):
        raise ValueError(f"{name} must be non-empty text")
    if values != tuple(sorted(values)) or len(values) != len(set(values)):
        raise ValueError(f"{name} must be unique and sorted")


def _artifact_path(value: str) -> None:
    _text(value, "source_artifact_path", limit=2_048)
    path = PurePosixPath(value)
    if (
        path.is_absolute()
        or value != path.as_posix()
        or "\\" in value
        or any(part in {"", ".", ".."} for part in path.parts)
    ):
        raise ValueError("source_artifact_path must be a canonical repository-relative path")


def _resolve_artifact(root: Path, relative: str) -> Path:
    safe_root = assertNoReparsePath(root.resolve(strict=True))
    candidate = assertNoReparsePath(safe_root / PurePosixPath(relative))
    try:
        candidate.relative_to(safe_root)
    except ValueError as exc:
        raise ResearchTransferLedgerError(
            "source artifact escapes artifact_root"
        ) from exc
    if candidate == safe_root or not candidate.is_file():
        raise ResearchTransferLedgerError(
            "source artifact must resolve to a regular file within artifact_root"
        )
    return candidate


@dataclass(frozen=True, slots=True)
class ResearchClaim:
    """One immutable paraphrased claim bound to its observed location."""

    url: str
    locator: str
    source_class: ResearchSourceClass
    retrieved_at: str
    claim: str
    source_response_sha256: str
    source_artifact_path: str
    source_artifact_sha256: str
    claim_sha256: str

    def __post_init__(self) -> None:
        _text(self.url, "url", limit=2_048)
        parsed = urlsplit(self.url)
        if (
            parsed.scheme != "https"
            or not parsed.hostname
            or parsed.username is not None
            or parsed.password is not None
            or parsed.fragment
        ):
            raise ValueError("research claim URL must be a credentialless HTTPS location")
        _text(self.locator, "locator", limit=1_024)
        if type(self.source_class) is not ResearchSourceClass:
            raise ValueError("source_class must use the closed enum")
        _time(self.retrieved_at, "retrieved_at")
        _text(self.claim, "claim")
        _sha256(self.source_response_sha256, "source_response_sha256")
        _artifact_path(self.source_artifact_path)
        _sha256(self.source_artifact_sha256, "source_artifact_sha256")
        _sha256(self.claim_sha256, "claim_sha256")
        expected = canonical_digest(
            {
                "claim": self.claim,
                "locator": self.locator,
                "retrieved_at": self.retrieved_at,
                "source_response_sha256": self.source_response_sha256,
                "source_artifact_path": self.source_artifact_path,
                "source_artifact_sha256": self.source_artifact_sha256,
                "source_class": self.source_class,
                "url": self.url,
            }
        )
        if self.claim_sha256 != expected:
            raise ValueError("claim_sha256 does not match the claim location and text")


@dataclass(frozen=True, slots=True)
class ResearchTransferRecord:
    """Content-addressed research intake that is never launch authority."""

    candidate_id: str
    registry_id: str | None
    registry_entry_sha256: str | None
    title: str
    source_status: ResearchSourceStatus
    claims: tuple[ResearchClaim, ...]
    local_hypothesis: str
    proposed_consumers: tuple[ResearchConsumer, ...]
    required_controls: tuple[ResearchControl, ...]
    experiment_manifest_id: str | None
    falsifier: str
    status_recheck_at: str
    evidence_state: EvidenceState
    blocked_reasons: tuple[ResearchBlocker, ...]
    trial_requested: bool = False
    runtime_authority: bool = False
    shadow_only: bool = True

    def __post_init__(self) -> None:
        if not isinstance(self.candidate_id, str) or _CANDIDATE_ID.fullmatch(self.candidate_id) is None:
            raise ValueError("candidate_id is invalid")
        if self.registry_id is not None and (
            not isinstance(self.registry_id, str) or _FR_ID.fullmatch(self.registry_id) is None
        ):
            raise ValueError("registry_id must be one of the approved FR01..FR35 range")
        if self.registry_entry_sha256 is not None:
            _sha256(self.registry_entry_sha256, "registry_entry_sha256")
        if (self.registry_id is None) != (self.registry_entry_sha256 is None):
            raise ValueError("registry ID and registry entry digest must be present together")
        _text(self.title, "title")
        if type(self.source_status) is not ResearchSourceStatus:
            raise ValueError("source_status must use the closed enum")
        if not self.claims or any(type(claim) is not ResearchClaim for claim in self.claims):
            raise ValueError("claims must contain typed research claims")
        claim_ids = tuple(claim.claim_sha256 for claim in self.claims)
        if len(claim_ids) != len(set(claim_ids)):
            raise ValueError("claims contain duplicate evidence")
        if claim_ids != tuple(sorted(claim_ids)):
            raise ValueError("claims must be sorted by claim_sha256")
        _text(self.local_hypothesis, "local_hypothesis")
        if not self.proposed_consumers or any(
            type(value) is not ResearchConsumer for value in self.proposed_consumers
        ):
            raise ValueError("proposed_consumers must use the closed enum")
        _closed_sorted(tuple(value.value for value in self.proposed_consumers), "proposed_consumers")
        if not self.required_controls or any(
            type(value) is not ResearchControl for value in self.required_controls
        ):
            raise ValueError("required_controls must use the closed enum")
        _closed_sorted(
            tuple(value.value for value in self.required_controls),
            "required_controls",
        )
        _text(self.falsifier, "falsifier")
        recheck = _time(self.status_recheck_at, "status_recheck_at")
        if recheck <= max(_time(claim.retrieved_at, "retrieved_at") for claim in self.claims):
            raise ValueError("status_recheck_at must follow every captured claim")
        if type(self.evidence_state) is not EvidenceState or self.evidence_state not in _NON_AUTHORITY_STATES:
            raise ValueError("research evidence state cannot imply runtime authority")
        if self.blocked_reasons:
            if any(type(value) is not ResearchBlocker for value in self.blocked_reasons):
                raise ValueError("blocked_reasons must use the closed enum")
            _closed_sorted(tuple(value.value for value in self.blocked_reasons), "blocked_reasons")
        if self.experiment_manifest_id is not None:
            _sha256(self.experiment_manifest_id, "experiment_manifest_id")
        if type(self.trial_requested) is not bool:
            raise ValueError("trial_requested must be boolean")
        if self.runtime_authority is not False:
            raise ValueError("a research transfer is never runtime authority")
        if self.shadow_only is not True:
            raise ValueError("a research transfer must remain shadow_only")
        if (
            self.registry_id is None
            and ResearchBlocker.CANONICAL_REGISTRY_ADMISSION_REQUIRED
            not in self.blocked_reasons
        ):
            raise ValueError("unregistered research must preserve its registry-admission blocker")
        if self.evidence_state is EvidenceState.UNAVAILABLE and not self.blocked_reasons:
            raise ValueError("unavailable research requires explicit blockers")
        if (
            self.source_status
            in {
                ResearchSourceStatus.ANNOUNCED,
                ResearchSourceStatus.HOSTED_SERVICE,
            }
            and self.evidence_state is not EvidenceState.UNAVAILABLE
        ):
            raise ValueError(
                "a non-artifact source or hosted service must remain unavailable"
            )
        if self.trial_requested:
            if self.registry_id is None:
                raise ValueError("trial eligibility requires canonical FR registry admission")
            if self.registry_entry_sha256 is None:
                raise ValueError("trial eligibility requires a registry entry digest")
            if self.source_status is not ResearchSourceStatus.PUBLIC_ARTIFACT:
                raise ValueError("trial eligibility requires a public source artifact")
            if self.experiment_manifest_id is None:
                raise ValueError("trial eligibility requires an experiment manifest")
            if self.evidence_state is not EvidenceState.QUALIFICATION_ONLY:
                raise ValueError("trial-eligible research must remain qualification_only")
            if self.blocked_reasons:
                raise ValueError("trial-eligible research cannot retain blockers")

    @property
    def receipt_id(self) -> str:
        return canonical_digest(self)


@dataclass(frozen=True, slots=True)
class ResearchTrialBinding:
    """Externally issued exact binding for one non-authoritative shadow trial."""

    transfer_record_id: str
    registry_id: str
    registry_entry_sha256: str
    claim_sha256s: tuple[str, ...]
    experiment_manifest_id: str
    required_controls: tuple[ResearchControl, ...]
    falsifier_sha256: str
    issuer: str
    issuer_revision: str
    authority_generation: int
    issued_at: str
    expires_at: str
    runtime_authority: bool = False
    shadow_only: bool = True

    def __post_init__(self) -> None:
        for name in (
            "transfer_record_id",
            "registry_entry_sha256",
            "experiment_manifest_id",
            "falsifier_sha256",
        ):
            _sha256(getattr(self, name), name)
        if _FR_ID.fullmatch(self.registry_id) is None:
            raise ValueError("binding registry_id must be in FR01..FR35")
        if not self.claim_sha256s:
            raise ValueError("binding claim_sha256s must be non-empty")
        for claim_id in self.claim_sha256s:
            _sha256(claim_id, "claim_sha256")
        _closed_sorted(self.claim_sha256s, "claim_sha256s")
        if not self.required_controls or any(
            type(value) is not ResearchControl for value in self.required_controls
        ):
            raise ValueError("binding required_controls must use the closed enum")
        _closed_sorted(
            tuple(value.value for value in self.required_controls),
            "required_controls",
        )
        _text(self.issuer, "issuer", limit=256)
        if not isinstance(self.issuer_revision, str) or _REVISION.fullmatch(
            self.issuer_revision
        ) is None:
            raise ValueError("issuer_revision must be a full lowercase revision")
        if (
            isinstance(self.authority_generation, bool)
            or not isinstance(self.authority_generation, int)
            or self.authority_generation < 1
        ):
            raise ValueError("authority_generation must be a positive integer")
        if _time(self.expires_at, "expires_at") <= _time(self.issued_at, "issued_at"):
            raise ValueError("binding expires_at must follow issued_at")
        if self.runtime_authority is not False or self.shadow_only is not True:
            raise ValueError("research trial bindings are shadow-only and non-authoritative")

    @property
    def receipt_id(self) -> str:
        return canonical_digest(self)


@dataclass(frozen=True, slots=True)
class ResearchQualificationContext:
    """Protected-controller facts used to authenticate and revoke bindings."""

    issuer: str
    issuer_revision: str
    current_generation: int
    minimum_valid_generation: int
    authenticated_binding_ids: tuple[str, ...]
    revoked_binding_ids: tuple[str, ...]
    captured_at: str
    expires_at: str
    runtime_authority: bool = False
    shadow_only: bool = True

    def __post_init__(self) -> None:
        _text(self.issuer, "issuer", limit=256)
        if not isinstance(self.issuer_revision, str) or _REVISION.fullmatch(
            self.issuer_revision
        ) is None:
            raise ValueError("issuer_revision must be a full lowercase revision")
        for name in ("current_generation", "minimum_valid_generation"):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, int) or value < 1:
                raise ValueError(f"{name} must be a positive integer")
        if self.minimum_valid_generation > self.current_generation:
            raise ValueError("minimum_valid_generation exceeds current_generation")
        if not self.authenticated_binding_ids:
            raise ValueError("authenticated_binding_ids must be non-empty")
        for name, receipt_ids in (
            ("authenticated_binding_ids", self.authenticated_binding_ids),
            ("revoked_binding_ids", self.revoked_binding_ids),
        ):
            for receipt_id in receipt_ids:
                _sha256(receipt_id, "binding_id")
            if receipt_ids != tuple(sorted(receipt_ids)) or len(receipt_ids) != len(
                set(receipt_ids)
            ):
                raise ValueError(f"{name} must be unique and sorted")
        captured_at = _time(self.captured_at, "captured_at")
        expires_at = _time(self.expires_at, "expires_at")
        lifetime_seconds = (expires_at - captured_at).total_seconds()
        if lifetime_seconds <= 0:
            raise ValueError("qualification context expires_at must follow captured_at")
        if lifetime_seconds > _MAX_QUALIFICATION_CONTEXT_SECONDS:
            raise ValueError("qualification context lifetime exceeds five minutes")
        if self.runtime_authority is not False or self.shadow_only is not True:
            raise ValueError(
                "research qualification context is shadow-only and non-authoritative"
            )

    @property
    def receipt_id(self) -> str:
        return canonical_digest(self)


@dataclass(frozen=True, slots=True)
class ResearchTrialAdmissionDecision:
    """Non-authoritative exact-match decision for one shadow trial."""

    record_id: str
    registry_id: str | None
    experiment_manifest_id: str | None
    allowed: bool
    reason: str
    evaluated_at: str
    runtime_authority: bool = False
    shadow_only: bool = True

    def __post_init__(self) -> None:
        _sha256(self.record_id, "record_id")
        if self.registry_id is not None and _FR_ID.fullmatch(self.registry_id) is None:
            raise ValueError("decision registry_id is invalid")
        if self.experiment_manifest_id is not None:
            _sha256(self.experiment_manifest_id, "experiment_manifest_id")
        if type(self.allowed) is not bool:
            raise ValueError("allowed must be boolean")
        _text(self.reason, "reason")
        _time(self.evaluated_at, "evaluated_at", allow_subseconds=True)
        if self.runtime_authority is not False or self.shadow_only is not True:
            raise ValueError("research trial admission is shadow-only and non-authoritative")

    @property
    def receipt_id(self) -> str:
        return canonical_digest(self)


def _iso_utc(value: datetime) -> str:
    if value.tzinfo is None:
        raise ValueError("trial admission clock must be timezone-aware")
    utc = value.astimezone(timezone.utc)
    timespec = "microseconds" if utc.microsecond else "seconds"
    return utc.isoformat(timespec=timespec).replace("+00:00", "Z")


def evaluate_research_trial(
    record: ResearchTransferRecord,
    *,
    canonical_registry_entries: Mapping[str, str],
    experiment_manifests: Mapping[str, ExperimentManifest],
    trial_bindings: Mapping[str, ResearchTrialBinding],
    qualification_contexts: Mapping[str, ResearchQualificationContext],
    at_time: datetime,
) -> ResearchTrialAdmissionDecision:
    """Exact-match external binding, registry, and manifest without execution."""

    if type(record) is not ResearchTransferRecord:
        raise ValueError("typed research transfer record is required")
    evaluated_at = _iso_utc(at_time)
    evaluated_dt = at_time.astimezone(timezone.utc)
    reason: str | None = None
    if not record.trial_requested:
        reason = "trial-not-requested"
    elif record.registry_id is None or record.registry_entry_sha256 is None:
        reason = "canonical-registry-admission-required"
    else:
        observed_registry_digest = canonical_registry_entries.get(record.registry_id)
        if observed_registry_digest != record.registry_entry_sha256:
            reason = "registry-entry-mismatch"
    binding: ResearchTrialBinding | None = None
    if reason is None:
        binding = trial_bindings.get(record.receipt_id)
        if type(binding) is not ResearchTrialBinding:
            reason = "trial-binding-unavailable"
        else:
            context = qualification_contexts.get(binding.issuer)
            if type(context) is not ResearchQualificationContext:
                reason = "trial-binding-issuer-untrusted"
            elif (
                context.issuer != binding.issuer
                or context.issuer_revision != binding.issuer_revision
            ):
                reason = "trial-binding-issuer-untrusted"
            elif _time(context.captured_at, "captured_at") > evaluated_dt:
                reason = "qualification-context-not-yet-valid"
            elif _time(context.expires_at, "expires_at") <= evaluated_dt:
                reason = "qualification-context-expired"
            elif binding.receipt_id in context.revoked_binding_ids:
                reason = "trial-binding-revoked"
            elif binding.receipt_id not in context.authenticated_binding_ids:
                reason = "trial-binding-unauthenticated"
            elif (
                binding.authority_generation != context.current_generation
                or binding.authority_generation < context.minimum_valid_generation
            ):
                reason = "trial-binding-generation-stale"
            elif binding.transfer_record_id != record.receipt_id:
                reason = "trial-binding-record-mismatch"
            elif (
                binding.registry_id != record.registry_id
                or binding.registry_entry_sha256 != record.registry_entry_sha256
            ):
                reason = "trial-binding-registry-mismatch"
            elif binding.claim_sha256s != tuple(
                sorted(claim.claim_sha256 for claim in record.claims)
            ):
                reason = "trial-binding-claims-mismatch"
            elif binding.required_controls != record.required_controls:
                reason = "trial-binding-controls-mismatch"
            elif binding.falsifier_sha256 != canonical_digest(record.falsifier):
                reason = "trial-binding-falsifier-mismatch"
            elif binding.experiment_manifest_id != record.experiment_manifest_id:
                reason = "trial-binding-manifest-mismatch"
            elif _time(binding.issued_at, "issued_at") > evaluated_dt:
                reason = "trial-binding-not-yet-valid"
            elif _time(binding.expires_at, "expires_at") <= evaluated_dt:
                reason = "trial-binding-expired"
    manifest: ExperimentManifest | None = None
    if reason is None:
        manifest = experiment_manifests.get(record.experiment_manifest_id or "")
        if type(manifest) is not ExperimentManifest:
            reason = "experiment-manifest-unavailable"
        else:
            typed_manifest = cast(ExperimentManifest, manifest)
            if typed_manifest.receipt_id != record.experiment_manifest_id:
                reason = "experiment-manifest-mismatch"
    if reason is None and _time(record.status_recheck_at, "status_recheck_at") <= evaluated_dt:
        reason = "status-recheck-expired"
    return ResearchTrialAdmissionDecision(
        record_id=record.receipt_id,
        registry_id=record.registry_id,
        experiment_manifest_id=record.experiment_manifest_id,
        allowed=reason is None,
        reason=reason or "preregistered-shadow-trial",
        evaluated_at=evaluated_at,
    )


def _exact_keys(value: Mapping[str, object], expected: frozenset[str], name: str) -> None:
    observed = frozenset(value)
    if observed != expected:
        missing = sorted(expected - observed)
        extra = sorted(observed - expected)
        raise ResearchTransferLedgerError(
            f"{name} keys differ (missing={missing}, extra={extra})"
        )


def load_research_transfer_ledger(
    path: str | Path,
    *,
    artifact_root: str | Path,
) -> tuple[ResearchTransferRecord, ...]:
    """Load a closed research-intake ledger without granting trial authority."""

    try:
        unreparsed_artifact_root = assertNoReparsePath(artifact_root)
        resolved_artifact_root = unreparsed_artifact_root.resolve(strict=True)
    except OSError as exc:
        raise ResearchTransferLedgerError(f"artifact_root is unavailable: {exc}") from exc
    if not resolved_artifact_root.is_dir():
        raise ResearchTransferLedgerError("artifact_root must be a directory")
    try:
        ledger_path = assertNoReparsePath(path)
        ledger_bytes = readNoFollowBytes(
            ledger_path,
            max_bytes=_MAX_LEDGER_BYTES,
        )
        payload = json.loads(ledger_bytes.decode("utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ResearchTransferLedgerError(f"cannot read research-transfer ledger: {exc}") from exc
    except ValueError as exc:
        raise ResearchTransferLedgerError(f"research-transfer ledger is oversized: {exc}") from exc
    if not isinstance(payload, dict):
        raise ResearchTransferLedgerError("research-transfer ledger must be an object")
    _exact_keys(payload, _LEDGER_KEYS, "ledger")
    if payload["schema_version"] != "galaxy.research-transfers/v1":
        raise ResearchTransferLedgerError("unsupported research-transfer schema")
    if payload["external_spend_allowed"] is not False:
        raise ResearchTransferLedgerError("research intake cannot enable external spend")
    try:
        generated_at = _time(payload["generated_at"], "generated_at")
    except (TypeError, ValueError) as exc:
        raise ResearchTransferLedgerError(f"invalid generated_at: {exc}") from exc
    raw_records = payload["records"]
    if not isinstance(raw_records, list) or not raw_records:
        raise ResearchTransferLedgerError("records must be a non-empty list")

    records: list[ResearchTransferRecord] = []
    seen_candidates: set[str] = set()
    verified_artifacts: dict[str, tuple[str, bytes]] = {}
    for raw in raw_records:
        if not isinstance(raw, dict):
            raise ResearchTransferLedgerError("record must be an object")
        _exact_keys(raw, _RECORD_KEYS, "record")
        for field in ("proposed_consumers", "required_controls", "blocked_reasons"):
            if not isinstance(raw[field], list):
                raise ResearchTransferLedgerError(f"{field} must be a list")
        raw_claims = raw["claims"]
        if not isinstance(raw_claims, list) or not raw_claims:
            raise ResearchTransferLedgerError("record claims must be a non-empty list")
        claims: list[ResearchClaim] = []
        for raw_claim in raw_claims:
            if not isinstance(raw_claim, dict):
                raise ResearchTransferLedgerError("claim must be an object")
            _exact_keys(raw_claim, _CLAIM_KEYS, "claim")
            try:
                claim = ResearchClaim(
                    url=raw_claim["url"],
                    locator=raw_claim["locator"],
                    source_class=ResearchSourceClass(raw_claim["source_class"]),
                    retrieved_at=raw_claim["retrieved_at"],
                    claim=raw_claim["claim"],
                    source_response_sha256=raw_claim["source_response_sha256"],
                    source_artifact_path=raw_claim["source_artifact_path"],
                    source_artifact_sha256=raw_claim["source_artifact_sha256"],
                    claim_sha256=raw_claim["claim_sha256"],
                )
            except (TypeError, ValueError) as exc:
                raise ResearchTransferLedgerError(f"invalid research claim: {exc}") from exc
            cached_artifact = verified_artifacts.get(claim.source_artifact_path)
            if cached_artifact is None:
                try:
                    artifact = _resolve_artifact(
                        resolved_artifact_root,
                        claim.source_artifact_path,
                    )
                    artifact_bytes = readNoFollowBytes(
                        artifact,
                        max_bytes=_MAX_SOURCE_ARTIFACT_BYTES,
                    )
                    observed_digest = hashlib.sha256(artifact_bytes).hexdigest()
                except (OSError, RuntimeError, ValueError) as exc:
                    raise ResearchTransferLedgerError(
                        f"cannot verify source artifact: {exc}"
                    ) from exc
                cached_artifact = (observed_digest, artifact_bytes)
                verified_artifacts[claim.source_artifact_path] = cached_artifact
            observed_digest, artifact_bytes = cached_artifact
            if observed_digest != claim.source_artifact_sha256:
                raise ResearchTransferLedgerError(
                    "source artifact digest does not match retained evidence"
                )
            if claim.source_response_sha256.encode("ascii") not in artifact_bytes:
                raise ResearchTransferLedgerError(
                    "source response digest is absent from retained evidence"
                )
            claims.append(claim)
        try:
            record = ResearchTransferRecord(
                candidate_id=raw["candidate_id"],
                registry_id=raw["registry_id"],
                registry_entry_sha256=raw["registry_entry_sha256"],
                title=raw["title"],
                source_status=ResearchSourceStatus(raw["source_status"]),
                claims=tuple(claims),
                local_hypothesis=raw["local_hypothesis"],
                proposed_consumers=tuple(
                    ResearchConsumer(value) for value in raw["proposed_consumers"]
                ),
                required_controls=tuple(
                    ResearchControl(value) for value in raw["required_controls"]
                ),
                experiment_manifest_id=raw["experiment_manifest_id"],
                falsifier=raw["falsifier"],
                status_recheck_at=raw["status_recheck_at"],
                evidence_state=EvidenceState(raw["evidence_state"]),
                blocked_reasons=tuple(
                    ResearchBlocker(value) for value in raw["blocked_reasons"]
                ),
                trial_requested=raw["trial_requested"],
                runtime_authority=raw["runtime_authority"],
                shadow_only=raw["shadow_only"],
            )
        except (TypeError, ValueError) as exc:
            raise ResearchTransferLedgerError(f"invalid research transfer: {exc}") from exc
        if raw["record_id"] != record.receipt_id:
            raise ResearchTransferLedgerError("record_id does not match canonical record bytes")
        if record.candidate_id in seen_candidates:
            raise ResearchTransferLedgerError("duplicate research candidate")
        seen_candidates.add(record.candidate_id)
        records.append(record)
    if generated_at < max(
        _time(claim.retrieved_at, "retrieved_at")
        for record in records
        for claim in record.claims
    ):
        raise ResearchTransferLedgerError(
            "generated_at cannot precede a captured research claim"
        )
    if tuple(record.candidate_id for record in records) != tuple(
        sorted(record.candidate_id for record in records)
    ):
        raise ResearchTransferLedgerError("records must be sorted by candidate_id")
    return tuple(records)


