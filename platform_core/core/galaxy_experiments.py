"""Durable append-only SQLite journal for GALAXY shadow experiment receipts.

The journal is intentionally small: it stores canonical receipt bytes and their
parent IDs, refuses missing parents, and makes update/delete impossible with database
triggers.  It is an evidence store, not an activation surface.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ShadowJournalError
  ParentReceiptMissing
  ReceiptCollision
  ReceiptLineageMismatch
  StoredReceipt
  ShadowEvidenceJournal  -- Create-only receipt journal with restart-safe WAL durability.
DEPENDS-ON: platform_core.core.galaxy_evidence
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import json
import sqlite3
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator, Sequence, TypeAlias

from platform_core.core.galaxy_evidence import (
    AnalysisReceipt,
    AssignmentReceipt,
    ExperimentManifest,
    ObservationReceipt,
    PromotionRecommendation,
    RollbackReceipt,
    canonical_json_bytes,
)


ShadowReceipt: TypeAlias = (
    ExperimentManifest
    | AssignmentReceipt
    | ObservationReceipt
    | AnalysisReceipt
    | PromotionRecommendation
    | RollbackReceipt
)
_RECEIPT_TYPES = (
    ExperimentManifest,
    AssignmentReceipt,
    ObservationReceipt,
    AnalysisReceipt,
    PromotionRecommendation,
    RollbackReceipt,
)
_TYPE_NAMES = tuple(item.__name__ for item in _RECEIPT_TYPES)


class ShadowJournalError(RuntimeError):
    pass


class ParentReceiptMissing(ShadowJournalError):
    pass


class ReceiptCollision(ShadowJournalError):
    pass


class ReceiptLineageMismatch(ShadowJournalError):
    pass


@dataclass(frozen=True)
class StoredReceipt:
    receipt_id: str
    receipt_type: str
    payload: dict
    parent_receipt_ids: tuple[str, ...]


class ShadowEvidenceJournal:
    """Create-only receipt journal with restart-safe WAL durability."""

    def __init__(self, path: str | Path):
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self._connection = sqlite3.connect(
            self.path, timeout=30.0, isolation_level=None
        )
        self._connection.execute("PRAGMA journal_mode=WAL")
        self._connection.execute("PRAGMA synchronous=FULL")
        self._connection.execute("PRAGMA foreign_keys=ON")
        self._initialize()

    def _initialize(self) -> None:
        allowed = ",".join(f"'{name}'" for name in _TYPE_NAMES)
        self._connection.executescript(
            f"""
            CREATE TABLE IF NOT EXISTS shadow_receipts (
                receipt_id TEXT PRIMARY KEY NOT NULL,
                receipt_type TEXT NOT NULL CHECK(receipt_type IN ({allowed})),
                payload BLOB NOT NULL,
                parent_ids BLOB NOT NULL,
                shadow_only INTEGER NOT NULL CHECK(shadow_only = 1)
            ) WITHOUT ROWID;

            CREATE TRIGGER IF NOT EXISTS shadow_receipts_no_update
            BEFORE UPDATE ON shadow_receipts
            BEGIN
                SELECT RAISE(ABORT, 'shadow receipts are append-only');
            END;

            CREATE TRIGGER IF NOT EXISTS shadow_receipts_no_delete
            BEFORE DELETE ON shadow_receipts
            BEGIN
                SELECT RAISE(ABORT, 'shadow receipts are append-only');
            END;
            """
        )

    @property
    def journal_mode(self) -> str:
        return str(self._connection.execute("PRAGMA journal_mode").fetchone()[0]).lower()

    @property
    def synchronous(self) -> str:
        level = int(self._connection.execute("PRAGMA synchronous").fetchone()[0])
        return {0: "off", 1: "normal", 2: "full", 3: "extra"}.get(level, str(level))

    @contextmanager
    def _transaction(self) -> Iterator[None]:
        self._connection.execute("BEGIN IMMEDIATE")
        try:
            yield
        except BaseException:
            self._connection.execute("ROLLBACK")
            raise
        else:
            self._connection.execute("COMMIT")

    @staticmethod
    def _receipt_parts(receipt: ShadowReceipt) -> tuple[str, str, bytes, tuple[str, ...]]:
        if not isinstance(receipt, _RECEIPT_TYPES):
            raise TypeError(f"unsupported shadow receipt: {type(receipt).__name__}")
        if getattr(receipt, "shadow_only", None) is not True:
            raise ShadowJournalError("journal accepts shadow_only receipts")
        receipt_id = receipt.receipt_id
        receipt_type = type(receipt).__name__
        payload = canonical_json_bytes(receipt)
        parent_ids = tuple(getattr(receipt, "parent_receipt_ids", ()))
        if len(parent_ids) != len(set(parent_ids)):
            raise ShadowJournalError("receipt contains duplicate parents")
        if receipt_id in parent_ids:
            raise ShadowJournalError("receipt cannot be its own parent")
        return receipt_id, receipt_type, payload, parent_ids

    def _append(self, receipt: ShadowReceipt) -> bool:
        receipt_id, receipt_type, payload, parent_ids = self._receipt_parts(receipt)
        existing = self._connection.execute(
            "SELECT receipt_type, payload, parent_ids FROM shadow_receipts WHERE receipt_id = ?",
            (receipt_id,),
        ).fetchone()
        encoded_parents = json.dumps(
            parent_ids, separators=(",", ":"), ensure_ascii=True
        ).encode("ascii")
        if existing is not None:
            if (
                existing[0] == receipt_type
                and bytes(existing[1]) == payload
                and bytes(existing[2]) == encoded_parents
            ):
                return False
            raise ReceiptCollision(f"receipt ID collision: {receipt_id}")
        for parent_id in parent_ids:
            found = self._connection.execute(
                "SELECT 1 FROM shadow_receipts WHERE receipt_id = ?", (parent_id,)
            ).fetchone()
            if found is None:
                raise ParentReceiptMissing(f"parent receipt is missing: {parent_id}")
        self._validate_lineage(receipt, json.loads(payload.decode("utf-8")))
        self._connection.execute(
            """
            INSERT INTO shadow_receipts
                (receipt_id, receipt_type, payload, parent_ids, shadow_only)
            VALUES (?, ?, ?, ?, 1)
            """,
            (receipt_id, receipt_type, payload, encoded_parents),
        )
        return True

    def _required(self, receipt_id: str, expected_type: str) -> StoredReceipt:
        stored = self.fetch(receipt_id)
        if stored is None:
            raise ParentReceiptMissing(f"referenced receipt is missing: {receipt_id}")
        if stored.receipt_type != expected_type:
            raise ReceiptLineageMismatch(
                f"expected {expected_type} parent, got {stored.receipt_type}: {receipt_id}"
            )
        return stored

    def _validate_lineage(self, receipt: ShadowReceipt, payload: dict) -> None:
        if isinstance(receipt, ExperimentManifest):
            return
        if isinstance(receipt, AssignmentReceipt):
            manifest = self._required(receipt.manifest_id, "ExperimentManifest").payload
            comparisons = {
                "policy_version": manifest["policy_version"],
                "fixture_digest": manifest["fixture_digest"],
            }
            for field_name, expected in comparisons.items():
                if payload[field_name] != expected:
                    raise ReceiptLineageMismatch(
                        f"assignment {field_name} does not match manifest"
                    )
            if payload["provider"] not in manifest["provider_cohort"]:
                raise ReceiptLineageMismatch("assignment provider is outside manifest cohort")
            if payload["seed"] not in manifest["seeds"]:
                raise ReceiptLineageMismatch("assignment seed is outside manifest seed registry")
            return
        if isinstance(receipt, ObservationReceipt):
            assignment = self._required(receipt.assignment_id, "AssignmentReceipt").payload
            bound_fields = (
                "manifest_id",
                "unit_id",
                "treatment",
                "assignment_probability",
                "seed",
                "policy_version",
                "provider",
                "capability_profile_id",
                "quota_state",
                "source_revision",
                "fixture_digest",
            )
            for field_name in bound_fields:
                if payload[field_name] != assignment[field_name]:
                    raise ReceiptLineageMismatch(
                        f"observation {field_name} does not match assignment"
                    )
            return
        if isinstance(receipt, AnalysisReceipt):
            manifest = self._required(receipt.manifest_id, "ExperimentManifest").payload
            if payload["primary_endpoint"] != manifest["primary_endpoint"]:
                raise ReceiptLineageMismatch("analysis endpoint does not match manifest")
            for observation_id in receipt.observation_ids:
                observation = self._required(observation_id, "ObservationReceipt").payload
                if observation["manifest_id"] != receipt.manifest_id:
                    raise ReceiptLineageMismatch("analysis observation belongs to another manifest")
            return
        if isinstance(receipt, PromotionRecommendation):
            self._required(receipt.analysis_id, "AnalysisReceipt")
            return
        if isinstance(receipt, RollbackReceipt):
            self._required(receipt.recommendation_id, "PromotionRecommendation")
            return
        raise TypeError(f"unsupported shadow receipt: {type(receipt).__name__}")

    def append(self, receipt: ShadowReceipt) -> bool:
        with self._transaction():
            return self._append(receipt)

    def append_chain(self, receipts: Sequence[ShadowReceipt]) -> int:
        """Append an ordered chain atomically; exact replay inserts nothing."""

        inserted = 0
        with self._transaction():
            for receipt in receipts:
                inserted += int(self._append(receipt))
        return inserted

    def fetch(self, receipt_id: str) -> StoredReceipt | None:
        row = self._connection.execute(
            "SELECT receipt_type, payload, parent_ids FROM shadow_receipts WHERE receipt_id = ?",
            (receipt_id,),
        ).fetchone()
        if row is None:
            return None
        return StoredReceipt(
            receipt_id=receipt_id,
            receipt_type=str(row[0]),
            payload=json.loads(bytes(row[1]).decode("utf-8")),
            parent_receipt_ids=tuple(json.loads(bytes(row[2]).decode("ascii"))),
        )

    def verify_chain(self, tail_receipt_id: str) -> tuple[str, ...]:
        """Return a deterministic tail-to-root traversal, rejecting broken/cyclic chains."""

        ordered: list[str] = []
        active: set[str] = set()
        visited: set[str] = set()

        def visit(receipt_id: str) -> None:
            if receipt_id in active:
                raise ShadowJournalError(f"receipt cycle detected at {receipt_id}")
            if receipt_id in visited:
                return
            stored = self.fetch(receipt_id)
            if stored is None:
                raise ParentReceiptMissing(f"receipt is missing: {receipt_id}")
            active.add(receipt_id)
            ordered.append(receipt_id)
            for parent_id in stored.parent_receipt_ids:
                visit(parent_id)
            active.remove(receipt_id)
            visited.add(receipt_id)

        visit(tail_receipt_id)
        return tuple(ordered)

    def count(self) -> int:
        return int(self._connection.execute("SELECT COUNT(*) FROM shadow_receipts").fetchone()[0])

    def integrity_check(self) -> str:
        return str(self._connection.execute("PRAGMA integrity_check").fetchone()[0])

    def close(self) -> None:
        self._connection.close()

    def __enter__(self) -> "ShadowEvidenceJournal":
        return self

    def __exit__(self, _exc_type, _exc, _traceback) -> None:
        self.close()


