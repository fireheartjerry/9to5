"""tracing -- structured per-run JSONL event log.

Emits one machine-readable event per line to ``logs/runs/<run_id>/events.jsonl`` so a future
LLM agent (or scripts/repo_health.py, or a trace analyst) can reconstruct a run WITHOUT replaying
it: what the system tried, who decided it, what verification expected, why it failed, what the
adversary objected to, what the replanner changed, and the final state.

**Best-effort, like memory/obsidian + the experience ledger: a tracing failure NEVER raises into
a run.** This module is intentionally low-level -- it depends only on ``config`` (no orchestrator
back-edge) so any layer may emit without creating an import cycle. Adoption is incremental: call
``tracing.emit(run_id, "<event>", ...)`` at any boundary; nothing breaks if it is never called.

Standard fields on every record: ``ts`` (UTC ISO), ``run_id``, ``subtask_id`` (or None),
``event``. Callers merge in extra fields -- ``cmd``, ``exit_code``, ``decided_by``,
``next_action``, ``expect``, etc. -- so the line is self-describing.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  runDir(run_id: str) -> Path  -- The directory holding one run's artifacts (events.jsonl, stdout.log, ...).
  emit(run_id: str, event: str, *, subtask_id: Optional[str]=None, **fields: Any) -> None  -- Append one structured event to ``logs/runs/<run_id>/events.jsonl``
  readEvents(run_id: str) -> list[dict]  -- Parse a run's events.jsonl into a list of dicts (skips blank/corrupt lines)
  recentRunIds(limit: int=10) -> list[str]  -- The most-recently-modified run ids under RUNS_ROOT (newest first)
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/platform/test_tracing.py
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

import config

LOG = config.getLogger("tracing")

# Per-run artifacts live under here: logs/runs/<run_id>/events.jsonl. Derived from the
# env-overridable logs dir so a relocated checkout / worktree writes to the active tree.
RUNS_ROOT: Path = Path(config.LOG_PATH) / "runs"


def runDir(run_id: str) -> Path:
    """The directory holding one run's artifacts (events.jsonl, stdout.log, ...)."""
    return RUNS_ROOT / str(run_id)


def _nowIso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def emit(run_id: str, event: str, *, subtask_id: Optional[str] = None, **fields: Any) -> None:
    """Append one structured event to ``logs/runs/<run_id>/events.jsonl``. Never raises.

    ``event`` is a short stable verb (e.g. ``"verification_failed"``, ``"adversary_challenged"``,
    ``"replan_split"``, ``"run_completed"``). Extra ``**fields`` are merged into the record."""
    try:
        d = runDir(run_id)
        d.mkdir(parents=True, exist_ok=True)
        record: dict[str, Any] = {
            "ts": _nowIso(),
            "run_id": str(run_id),
            "subtask_id": subtask_id,
            "event": event,
        }
        record.update(fields)
        line = json.dumps(record, ensure_ascii=False, default=str)
        with open(d / "events.jsonl", "a", encoding="utf-8") as fh:
            fh.write(line + "\n")
    except Exception as e:  # noqa: BLE001 -- tracing must never break a run
        LOG.debug("trace emit failed for %s/%s: %s", run_id, event, e)


def readEvents(run_id: str) -> list[dict]:
    """Parse a run's events.jsonl into a list of dicts (skips blank/corrupt lines). [] if absent."""
    out: list[dict] = []
    path = runDir(run_id) / "events.jsonl"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return out
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return out


def recentRunIds(limit: int = 10) -> list[str]:
    """The most-recently-modified run ids under RUNS_ROOT (newest first). Best-effort, [] if none."""
    try:
        dirs = [p for p in RUNS_ROOT.iterdir() if p.is_dir()]
    except OSError:
        return []
    dirs.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    return [p.name for p in dirs[:limit]]
