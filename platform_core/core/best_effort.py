"""best_effort() degradation kernel: swallowed failures counted, logged, surfaced.

Replaces silent ``except Exception: pass`` sites. The exception is STILL swallowed
(the never-raise contract is preserved everywhere), but every swallow is counted in
the module-level ``DEGRADATIONS`` registry, the full traceback lands at DEBUG, and
the FIRST failure per ``(name, exception type)`` in this process emits one WARNING
(later identical failures stay at DEBUG). ``degradationSummary()`` /
``degradationLine()`` feed the run-teardown complete embed, the preflight doctor,
and the webdash ``/api/state`` payload.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  best_effort(name: str, *, log: Optional[logging.Logger]=None, level: int=logging.WARNING) -> Iterator[None]  -- Swallow ``Exception`` from the wrapped block
  recordDegradation(name: str, exc: Exception, *, log: Optional[logging.Logger]=None, level: int=logging.WARNING) -> None  -- Count + log a swallowed exception
  degradationSummary() -> dict[str, dict]  -- Snapshot copy of the registry: {name: {count, last_error, last_at}}.
  degradationLine() -> str  -- One aggregated human line, grouped by surface (the segment before the first
  resetDegradations(*, warnings: bool=False) -> None  -- Clear the registry so the next run's summary is per-run
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: mutates the module-level DEGRADATIONS registry; emits log records
RUN/TEST: python -m pytest tests/test_best_effort.py
"""
from __future__ import annotations

import logging
import threading
from contextlib import contextmanager
from datetime import datetime
from typing import Iterator, Optional

_LOG = logging.getLogger("9to5.best_effort")
_LOCK = threading.Lock()

# name -> {"count": int, "last_error": str, "last_at": str-iso}. Module-level on purpose:
# one process = one degradation picture, readable from any surface without plumbing.
DEGRADATIONS: dict[str, dict] = {}

# (name, exc_type_name) pairs that already emitted their one WARNING this process.
_WARNED: set = set()


@contextmanager
def best_effort(name: str, *, log: Optional[logging.Logger] = None,
                level: int = logging.WARNING) -> Iterator[None]:
    """Swallow ``Exception`` from the wrapped block -- but never silently.

    Contract: NEVER propagates Exception (BaseException -- KeyboardInterrupt,
    SystemExit -- passes through, exactly like a bare ``except Exception``).
    Every swallow increments ``DEGRADATIONS[name]`` and logs the full traceback
    at DEBUG; the first failure per ``(name, exc_type)`` also logs one ``level``
    (default WARNING) record so a dead surface is visible without log spam.
    """
    try:
        yield
    except Exception as exc:  # noqa: BLE001 -- the whole point: never break the run
        recordDegradation(name, exc, log=log, level=level)


def recordDegradation(name: str, exc: Exception, *, log: Optional[logging.Logger] = None,
                      level: int = logging.WARNING) -> None:
    """Count + log a swallowed exception. For sites that keep their own ``except``
    because they need the exception value for fallback logic. Never raises."""
    try:
        logger = log if log is not None else _LOG
        exc_type = type(exc).__name__
        with _LOCK:
            entry = DEGRADATIONS.setdefault(name, {"count": 0, "last_error": "", "last_at": ""})
            entry["count"] += 1
            entry["last_error"] = f"{exc_type}: {exc}"[:300]
            entry["last_at"] = datetime.now().astimezone().isoformat(timespec="seconds")
            first = (name, exc_type) not in _WARNED
            if first:
                _WARNED.add((name, exc_type))
        logger.debug("best_effort[%s] swallowed %s: %s", name, exc_type, exc, exc_info=exc)
        if first:
            logger.log(level, "best_effort[%s]: %s: %s (first occurrence; repeats at DEBUG)",
                       name, exc_type, exc)
    except Exception:  # noqa: BLE001 -- bookkeeping must never break the caller
        return


def degradationSummary() -> dict[str, dict]:
    """Snapshot copy of the registry: {name: {count, last_error, last_at}}."""
    with _LOCK:
        return {name: dict(entry) for name, entry in DEGRADATIONS.items()}


def degradationLine() -> str:
    """One aggregated human line, grouped by surface (the segment before the first
    '.'): ``'degraded surfaces: obsidian x12, tunnel x1'``. Empty string when clean."""
    grouped: dict[str, int] = {}
    for name, entry in degradationSummary().items():
        surface = name.split(".", 1)[0] or name
        grouped[surface] = grouped.get(surface, 0) + int(entry.get("count", 0))
    if not grouped:
        return ""
    parts = [f"{surface} x{count}"
             for surface, count in sorted(grouped.items(), key=lambda kv: (-kv[1], kv[0]))]
    return "degraded surfaces: " + ", ".join(parts)


def resetDegradations(*, warnings: bool = False) -> None:
    """Clear the registry so the next run's summary is per-run. The once-per-process
    WARNING dedup is kept unless ``warnings=True`` (tests)."""
    with _LOCK:
        DEGRADATIONS.clear()
        if warnings:
            _WARNED.clear()
