"""protocols -- the replaceable-intelligence seams of 9to5.

Architectural principle: **strict protocol, replaceable intelligence.** The lifecycle, state
machine, guards and verification rules are deterministic and boring; the *intelligences* that
plug into them (which model executes a step, which reviews it, which decides the next move) are
swappable. This module names those seams as ``typing.Protocol`` interfaces so an LLM agent can
see -- without archaeology -- exactly what a new executor / verifier / reviewer / brain must
provide, and so tests can substitute a fake (see tests/factories.py, future tests/fakes/).

These are **structural** Protocols (duck-typed): existing concrete implementations already
satisfy them by shape and need not inherit. Adoption is therefore zero-risk and incremental --
annotate a parameter as ``Executor`` instead of ``Any`` while touching a module; nothing about
runtime dispatch changes. Payload shapes are the dicts/contracts in contracts.py (kept as
``dict`` here during the transition; tighten to the dataclasses as those land).

Concrete implementers today (informal -> these Protocols):
  * Executor  -> agents/executor.runClaude, agents/browser_executor, agents/native_executor
  * Verifier  -> agents/verifier.runVerification
  * Reviewer  -> agents/adversary.review, agents/second_brain
  * Brain     -> the Ollama chat callable threaded through orchestrator (llm_io / _ollamaChat)

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Executor  -- Runs ONE execution step (a brain-authored invocation spec) and returns a result dict.
  Verifier  -- Decides whether an executed step actually succeeded
  Reviewer  -- Adversarial critique of an executor's output
  Brain  -- The authoring intelligence: given a system+user prompt, return the model's text/JSON.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_protocols.py
"""
from __future__ import annotations

from typing import Any, Optional, Protocol, runtime_checkable


@runtime_checkable
class Executor(Protocol):
    """Runs ONE execution step (a brain-authored invocation spec) and returns a result dict.

    The single seam behind which ClaudeCodeExecutor / BrowserExecutor / NativeExecutor /
    DryRunExecutor / a test FakeExecutor are interchangeable. Input shape: contracts.InvocationSpec
    (or a bare prompt str). Output shape: contracts.ExecutorResult. Must not decide control flow --
    it executes, the orchestrator decides.
    """

    def runClaude(
        self,
        spec_or_prompt: "dict | str",
        *,
        work_dir: Optional[str] = None,
        task_state: Any = None,
        subtask: Optional[dict] = None,
        cancel_check: Any = None,
    ) -> dict:
        ...


@runtime_checkable
class Verifier(Protocol):
    """Decides whether an executed step actually succeeded -- the proof gate, no intelligence.

    Converts a brain-authored verify spec (contracts.Verify) + the work dir into a result dict
    ``{passed: bool, ...}``. Must be deterministic, must not mutate run state, must not replan,
    must not call Discord/dashboard. The strict half of the protocol.
    """

    def runVerification(self, verify: Optional[dict], work_dir: str, **kwargs: Any) -> dict:
        ...


@runtime_checkable
class Reviewer(Protocol):
    """Adversarial critique of an executor's output -- replaceable intelligence (Ollama/GPT/stub).

    Returns a contracts.Verdict dict (``verdict`` in {"approved","challenged"} + concerns).
    Advisory: it informs the orchestrator's gate, it does not itself change state.
    """

    def review(
        self,
        subtask_title: str,
        trigger_reason: str,
        executor_output: str,
        *,
        goal: str = "",
        review_type: str = "subtask",
        **kwargs: Any,
    ) -> dict:
        ...


@runtime_checkable
class Brain(Protocol):
    """The authoring intelligence: given a system+user prompt, return the model's text/JSON.

    This is the orchestrator's local Ollama model (or any swapped-in chat callable). It AUTHORS
    prompts/plans/replans; it is the most-replaceable piece and the one a fake stubs in tests
    (tests/factories.fake_brain). Shape mirrors the ``ollama_chat`` callable threaded through
    orchestrator: ``(system, user, *, want_json=False) -> response``.
    """

    def __call__(self, system: str, user: str, *, want_json: bool = False) -> Any:
        ...
