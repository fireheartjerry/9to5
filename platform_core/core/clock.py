"""Wall-clock kernel: ISO timestamps, elapsed/ETA formatting, and run-deadline math.

THE single home for the timestamp rituals that used to be mirrored across dashboard, cv2,
time_utils, resilience, and run_loop. Canonicalization is alias-first: timestamps are
compared in their OWN frame (an aware timestamp against an aware now, a naive one against
a naive now) so mixing never raises, and the emitted ISO strings are byte-identical to the
historical ``datetime.now().astimezone().isoformat(timespec="seconds")`` format so string
comparisons on stored timestamps keep working.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  nowIsoUtc() -> str  -- UTC ISO-8601 timestamp with seconds precision (ends '+00:00').
  nowIsoLocal() -> str  -- Local-zone AWARE ISO-8601 timestamp with seconds precision.
  parseIso(ts) -> Optional[datetime]  -- ``datetime.fromisoformat`` that returns None for empty/unparseable input.
  elapsedSecondsSince(ts) -> float  -- Wall-clock seconds since ``ts`` (clamped >= 0)
  fmtElapsed(seconds) -> str  -- Human duration: hours+minutes ('2h 15m'), minutes ('5m'), else seconds ('42s').
  elapsedStr(started_at) -> str  -- Human duration since ``started_at`` (e.g
  etaStr(started_at, done: int, total: int) -> str  -- Remaining-time estimate from the current pace
  RunClock  -- Deadline math for one run
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/platform/test_clock.py
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

_DASH = "—"   # em-dash: the shared "unknown" placeholder


def nowIsoUtc() -> str:
    """UTC ISO-8601 timestamp with seconds precision (ends '+00:00')."""
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def nowIsoLocal() -> str:
    """Local-zone AWARE ISO-8601 timestamp with seconds precision."""
    return datetime.now().astimezone().isoformat(timespec="seconds")


def parseIso(ts) -> Optional[datetime]:
    """``datetime.fromisoformat`` that returns None for empty/unparseable input."""
    if not ts:
        return None
    try:
        return datetime.fromisoformat(str(ts))
    except Exception:  # noqa: BLE001
        return None


def _nowFor(dt: datetime) -> datetime:
    """A 'now' in the same frame as ``dt`` (aware vs naive) so subtraction never raises."""
    return datetime.now(dt.tzinfo) if dt.tzinfo else datetime.now()


def elapsedSecondsSince(ts) -> float:
    """Wall-clock seconds since ``ts`` (clamped >= 0). 0.0 for missing/unparseable input."""
    dt = parseIso(ts)
    if dt is None:
        return 0.0
    return max(0.0, (_nowFor(dt) - dt).total_seconds())


def fmtElapsed(seconds) -> str:
    """Human duration: hours+minutes ('2h 15m'), minutes ('5m'), else seconds ('42s')."""
    secs = max(0, int(seconds))
    h, rem = divmod(secs, 3600)
    mins = rem // 60
    if h:
        return f"{h}h {mins}m"
    if mins:
        return f"{mins}m"
    return f"{secs}s"


def elapsedStr(started_at) -> str:
    """Human duration since ``started_at`` (e.g. '1h 23m'); em-dash when unknown."""
    if not started_at:
        return _DASH
    dt = parseIso(started_at)
    if dt is None:
        return _DASH
    return fmtElapsed((_nowFor(dt) - dt).total_seconds())


def etaStr(started_at, done: int, total: int) -> str:
    """Remaining-time estimate from the current pace; em-dash when there is no basis."""
    remaining = total - done
    if remaining <= 0 or done <= 0 or not started_at:
        return _DASH
    dt = parseIso(started_at)
    if dt is None:
        return _DASH
    elapsed = (_nowFor(dt) - dt).total_seconds()
    if elapsed <= 0:
        return _DASH
    eta = int((elapsed / done) * remaining)
    h, rem = divmod(eta, 3600)
    mins = rem // 60
    if h:
        return f"~{h}h {mins}m"
    if mins:
        return f"~{mins}m"
    return f"~{eta}s"


class RunClock:
    """Deadline math for one run -- the single copy of the resilience/run_loop duplicate.

    ``deadline_at`` is an ISO timestamp string (or None/empty for "no deadline"). A run
    with no parseable deadline never passes it (remaining* return None, passed() False)."""

    def __init__(self, deadline_at: Optional[str]) -> None:
        self.deadline_at = deadline_at

    def remainingSeconds(self) -> Optional[float]:
        """Seconds until the deadline (negative once passed); None when unparseable."""
        dt = parseIso(self.deadline_at)
        if dt is None:
            return None
        return (dt - _nowFor(dt)).total_seconds()

    def remainingHours(self) -> Optional[float]:
        """Hours until the deadline (negative once passed); None when unparseable."""
        rem = self.remainingSeconds()
        return None if rem is None else rem / 3600.0

    def passed(self) -> bool:
        """True once the deadline is hit (exactly 0.0 counts as passed); no deadline never passes."""
        rem = self.remainingSeconds()
        return rem is not None and rem <= 0.0
