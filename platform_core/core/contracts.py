@dataclass(frozen=True)
class VerificationResult:
    """``agents/verifier.py`` runVerification() output -- the proof gate's verdict. Exact mirror."""
    passed: bool
    cmd: Optional[str]
    expect: str
    returncode: Optional[int]
    stdout: str = ""
    stderr: str = ""

    @classmethod
    def fromDict(cls, d: dict) -> "VerificationResult":
        return cls(
            passed=bool(d.get("passed")),
            cmd=d.get("cmd"),
            expect=d.get("expect", ""),
            returncode=d.get("returncode"),
            stdout=d.get("stdout", ""),
            stderr=d.get("stderr", ""),
        )


@dataclass(frozen=True)
class ExecutionSurfaceReceipt:
    """Truthful outcome for a terminal, browser, or native executor attempt.

    ``requested_mode`` is intent; ``actual_mode`` is what really ran.  They are
    deliberately separate so an unavailable or simulated surface can never be
    reported as a live success.
    """
    surface: str
    requested_mode: str = "live"
    actual_mode: str = "unavailable"  # live | unavailable | degraded | simulated
    status: str = "error"              # ok | error | unavailable | blocked
    artifacts: tuple[str, ...] = ()
    detail: str = ""

    @property
    def live(self) -> bool:
        return self.actual_mode == "live" and self.status == "ok"

    def toDict(self) -> dict[str, Any]:
        return {
            "surface": self.surface, "requested_mode": self.requested_mode,
            "actual_mode": self.actual_mode, "status": self.status,
            "artifacts": list(self.artifacts), "detail": self.detail,
            "live": self.live,
        }


@dataclass(frozen=True)
class ControlCommand:
    """A parsed human control command (``notifications/commands.py`` Command): name + arg."""
    name: str
    arg: str = ""


@dataclass(frozen=True)
class AgentDecision:
    """Confidence/risk metadata an intelligence may attach so the orchestrator can escalate.

    TARGET shape (not yet emitted) for confidence-based escalation: route to frontier/human
    review when ``confidence`` is below threshold, a universe expansion is requested, or
    verification keeps failing. Kept here so the escalation contract is visible before wiring."""
    confidence: float = 1.0
    risk: str = "low"                  # "low" | "medium" | "high"
    needs_frontier_review: bool = False
    needs_human_review: bool = False
    reason: str = ""


