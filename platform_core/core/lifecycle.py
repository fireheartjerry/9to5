from __future__ import annotations

from enum import Enum


class RunStatus(str, Enum):
    """Every value ``meta["status"]`` may hold over a run's life. Set via TaskState.setStatus.

    Lifecycle order (happy path): CREATED -> ARCHITECTING -> PLANNING -> EXECUTING -> DONE.
    EXECUTING may instead settle to PARTIAL (some subtasks unfinished at the deadline),
    BLOCKED (no actionable subtasks remain), ABORTED (human/control stop), CRASHED (an
    unhandled error; resumable -- NOT a peer terminal state), or FAILED.
    """

    CREATED = "created"            # persisted at TaskState construction (state/task.py:84)
    ARCHITECTING = "architecting"  # Architect (Claude) is writing architect.md
    PLANNING = "planning"          # brain is decomposing the goal into subtasks
    EXECUTING = "executing"        # the per-subtask execution loop is running
    DONE = "done"                  # all countable subtasks completed
    PARTIAL = "partial"            # finished with some subtasks unfinished (deadline/drop)
    BLOCKED = "blocked"            # no actionable subtask remains (e.g. all blocked by a failure)
    FAILED = "failed"             # the run failed outright
    ABORTED = "aborted"           # stopped by a human/control command
    CRASHED = "crashed"           # unhandled error; persisted non-terminal so recovery can resume


class SubtaskStatus(str, Enum):
    """Every value a subtask's ``status`` may hold (state/task.py addSubtask/updateSubtask)."""

    PENDING = "pending"          # not yet started (initial)
    IN_PROGRESS = "in_progress"  # an executor is working it
    DONE = "done"                # completed and verified
    BLOCKED = "blocked"          # cannot proceed (a dependency failed)
    FAILED = "failed"            # exhausted retries / verification never passed
    REMOVED = "removed"          # dropped by a replan (excluded from progress counts)


# Run states after which no further work happens. ``CRASHED`` is deliberately EXCLUDED:
# it is persisted so resilience.run_with_recovery can resume the run. Mirrors -- and is the
# single source for -- the historical ``TaskState._TERMINAL`` tuple, including the legacy
# ``"complete"`` spelling so old on-disk task files still read as terminal.
TERMINAL_RUN_STATUSES: frozenset[str] = frozenset(
    {RunStatus.DONE, RunStatus.ABORTED, RunStatus.PARTIAL, RunStatus.BLOCKED, RunStatus.FAILED, "complete"}
)

# Subtask states that count as "no longer actionable".
TERMINAL_SUBTASK_STATUSES: frozenset[str] = frozenset(
    {SubtaskStatus.DONE, SubtaskStatus.FAILED, SubtaskStatus.REMOVED}
)

# Synonym -> canonical run status. Folds the historical drift (success/ok/passed/finished/
# completed all meant "done") so a normalizer can collapse any surface's string to one term.
_RUN_SYNONYMS: dict[str, RunStatus] = {
    "complete": RunStatus.DONE,
    "completed": RunStatus.DONE,
    "success": RunStatus.DONE,
    "succeeded": RunStatus.DONE,
    "ok": RunStatus.DONE,
    "passed": RunStatus.DONE,
    "finished": RunStatus.DONE,
    "architecture": RunStatus.ARCHITECTING,
    "plan": RunStatus.PLANNING,
    "running": RunStatus.EXECUTING,
    "abort": RunStatus.ABORTED,
    "aborting": RunStatus.ABORTED,
    "crash": RunStatus.CRASHED,
}


def normalizeRunStatus(raw: str) -> str:
    """Fold any surface's status string to its canonical ``RunStatus`` value (returned as a str).

    Unknown values pass through unchanged (so a status this module hasn't catalogued is never
    silently lost). Case/whitespace-insensitive. Use at read boundaries (dashboards, reports,
    logs) so every surface displays one term per real state.
    """
    key = (raw or "").strip().lower()
    if key in _RUN_SYNONYMS:
        return _RUN_SYNONYMS[key].value
    return key or raw


def isTerminalRun(status: str) -> bool:
    """True iff ``status`` (after normalization) is a run state with no further work."""
    return normalizeRunStatus(status) in TERMINAL_RUN_STATUSES


def isTerminalSubtask(status: str) -> bool:
    """True iff a subtask in ``status`` is no longer actionable (done/failed/removed)."""
    return (status or "").strip().lower() in TERMINAL_SUBTASK_STATUSES
