"""Offline Nightclaw replay harness -- a safe substitute for a second live gateway.

Only one ``DISCORD_BOT_TOKEN`` exists, so we cannot spin up a second real bot to
exercise the '!' control surface. This driver feeds SYNTHETIC gateway messages
through the pure command spine (``notifications.commands``) against an in-memory
``ControlBus``, mirroring the two real consumers of a Discord message:

  * the always-running gateway ``on_message`` path (``notifications.bot.core``), and
  * the in-run REST poller (``_translateDiscord`` in the control mixin).

Nothing touches the network: ``DISCORD_BOT_TOKEN`` is blank so the REST chokepoint
(``notifications.discord_client._request``) short-circuits to a no-op. Every side
effect (ops pushed, replies attempted, ignored messages, captured feedback labels)
is recorded on a ``ReplayResult`` so tests can assert on them.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  InMemoryControlBus  -- A ``ControlBus`` whose backing store is a process dict
  ReplayResult  -- Everything a replay produced
  BotReplay  -- Offline driver
  resetTransport() -> None  -- Zero the REST breaker + 401 latch so replays / 429-401 probes are independent.
DEPENDS-ON: config, learning.human_feedback, notifications.commands, notifications.discord_client, notifications.ops, platform_core.runtime.control, state.task
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_bot_replay.py
"""
from __future__ import annotations

import contextlib
import copy
from dataclasses import dataclass, field
from typing import Any, Optional

import config
from platform_core.runtime.control import ControlBus, _PROCESS_LOCK, _blank
from notifications import commands as spine
from notifications import discord_client as _dc

LOG = config.getLogger("bot_replay")

# Mirror notifications.bot.core: replies are clamped before the gateway would send them.
MAX_REPLY_CHARS = config.DISCORD_MAX_CONTENT - 100

# Consumer selectors for BotReplay.run().
GATEWAY = "gateway"
POLLER = "poller"
BOTH = "both"


class InMemoryControlBus(ControlBus):
    """A ``ControlBus`` whose backing store is a process dict -- no disk IO, no lock files --
    yet preserving the REAL ``_blank`` schema, the forward-compatible merge, and the
    ``pushOp`` identity-dedup, so dual-consumer / duplicate behaviour is exercised for real."""

    def __init__(self, task_id: str):
        self.task_id = task_id
        self.path = None  # never touched: all IO is overridden below
        self._store: dict[str, Any] = _blank()

    def load(self) -> dict[str, Any]:
        base = _blank()
        base.update(copy.deepcopy(self._store))
        base["decisions"] = {**_blank()["decisions"], **(self._store.get("decisions") or {})}
        return base

    def _mutate(self, fn) -> dict[str, Any]:
        with _PROCESS_LOCK:
            base = _blank()
            base.update(copy.deepcopy(self._store))
            base["decisions"] = {**_blank()["decisions"], **(self._store.get("decisions") or {})}
            fn(base)
            self._store = copy.deepcopy(base)
        return self._store

    def drainOps(self) -> list[dict[str, Any]]:
        with _PROCESS_LOCK:
            ops = list(self._store.get("plan_ops") or [])
            if ops:
                self._store["plan_ops"] = []
        return ops


@dataclass
class _Msg:
    content: str
    author_id: Optional[object]
    is_bot: bool
    authorized: bool
    msg_id: int
    channel_id: Optional[int]


@dataclass
class ReplayResult:
    """Everything a replay produced. ``errors`` MUST stay empty -- any entry is a bot bug."""
    applied: list[tuple[str, str]] = field(default_factory=list)   # (consumer, command_name)
    replies: list[str] = field(default_factory=list)               # clamped gateway reply texts
    ignored: list[tuple[int, str]] = field(default_factory=list)   # (msg_id, reason)
    errors: list[tuple[int, str]] = field(default_factory=list)    # (msg_id, repr(exc))
    feedback: list[dict[str, Any]] = field(default_factory=list)   # captured human_feedback labels
    sends: list[tuple[str, Any]] = field(default_factory=list)     # (text, rest_result)


def _buildState(n_subtasks: int, status: str):
    """A real in-memory TaskState (never persisted) with N pending subtasks."""
    from state.task import TaskState
    state = TaskState.create("bot replay exercise", 8.0)
    state.meta["status"] = status
    for i in range(1, max(0, n_subtasks) + 1):
        state.subtasks.append({
            "subtask_id": f"st-{i:03d}", "title": f"Replay subtask {i}",
            "description": f"synthetic step {i}", "status": "pending",
            "layer": 3, "effort_level": "default", "verify": None, "depends_on": [],
        })
    if state.subtasks:
        state.subtasks[0]["status"] = "in_progress"
    return state


class BotReplay:
    """Offline driver. Enqueue synthetic '!' messages, then ``run()`` them through the
    command spine against an in-memory bus, capturing every side effect."""

    def __init__(self, *, n_subtasks: int = 3, status: str = "running",
                 pending_gate: Optional[str] = None, channel_id: int = 0):
        self.state = _buildState(n_subtasks, status)
        self.bus = InMemoryControlBus(self.state.task_id)
        if pending_gate:
            self.bus.setPendingGate(pending_gate)
        self.channel_id = channel_id
        self.result = ReplayResult()
        self._log: list[_Msg] = []
        self._next_id = 1
        self._gw_index = 0

    # ---- enqueue -------------------------------------------------------
    def enqueueCommand(self, text: str, author_id: Optional[object] = None,
                       is_bot: bool = False, authorized: bool = True,
                       msg_id: Optional[int] = None,
                       channel_id: Optional[int] = None) -> int:
        """Append one synthetic gateway message. Returns its message id (monotonic by default,
        but an explicit ``msg_id`` lets a test inject a stale/out-of-order cursor case)."""
        mid = msg_id if msg_id is not None else self._next_id
        self._next_id = max(self._next_id, mid) + 1
        self._log.append(_Msg(text, author_id, is_bot, authorized, mid, channel_id))
        return mid

    # ---- run -----------------------------------------------------------
    def run(self, consumer: str = GATEWAY) -> ReplayResult:
        """Process the message log through the chosen consumer path(s). ``both`` delivers each
        message to BOTH the gateway and the poller -- the real dual-consumer situation where
        pushOp dedup must collapse a doubly-parsed op to one."""
        with self._captureFeedback():
            if consumer in (GATEWAY, BOTH):
                self._runGateway()
            if consumer in (POLLER, BOTH):
                self._runPoller()
        return self.result

    def _runGateway(self) -> None:
        while self._gw_index < len(self._log):
            msg = self._log[self._gw_index]
            self._gw_index += 1
            self._dispatchGateway(msg)

    def _runPoller(self) -> None:
        seen = self.bus.getSeen()
        seen_int = int(seen) if str(seen).isdigit() else 0
        fresh = [m for m in self._log if m.msg_id > seen_int]
        if fresh:
            self.bus.setSeen(str(max(m.msg_id for m in fresh)))
        for msg in fresh:
            self._dispatchPoller(msg)

    # ---- dispatch ------------------------------------------------------
    def _resolveCommand(self, msg: _Msg):
        """Faithful gate shared by both consumers: bot authors ignored, unauthorized ignored,
        non-'!'/unknown ignored. Returns ``(Command|None, reason|None)``."""
        if msg.is_bot:
            return None, "bot_author"
        if not msg.authorized:
            return None, "unauthorized"
        cmd = spine.decide(msg.author_id, msg.is_bot, msg.content)
        if cmd is not None:
            return cmd, None
        s = (msg.content or "").strip()
        if not s.startswith("!"):
            return None, "not_command"
        if not spine.isAuthorized(msg.author_id):
            return None, "unauthorized"
        return None, "unknown_command"

    def _dispatchGateway(self, msg: _Msg) -> None:
        chan = msg.channel_id if msg.channel_id is not None else self.channel_id
        if config.DISCORD_CHANNEL_ID and chan != config.DISCORD_CHANNEL_ID:
            self.result.ignored.append((msg.msg_id, "wrong_channel"))
            return
        cmd, reason = self._resolveCommand(msg)
        if cmd is None:
            self.result.ignored.append((msg.msg_id, reason or "ignored"))
            return
        try:
            reply = spine.applyCommand(self.bus, self.state, cmd)
            self.result.applied.append((GATEWAY, cmd.name))
        except Exception as exc:  # noqa: BLE001 -- a raise here is exactly the bug we hunt
            self.result.errors.append((msg.msg_id, repr(exc)))
            return
        if reply:
            self._attemptReply(reply)

    def _dispatchPoller(self, msg: _Msg) -> None:
        cmd, reason = self._resolveCommand(msg)
        if cmd is None:
            self.result.ignored.append((msg.msg_id, reason or "ignored"))
            return
        try:
            spine.applyCommand(self.bus, self.state, cmd)
            self.result.applied.append((POLLER, cmd.name))
        except Exception as exc:  # noqa: BLE001
            self.result.errors.append((msg.msg_id, repr(exc)))

    # ---- side-effect transports (all no-op offline) --------------------
    def _attemptReply(self, reply: str) -> None:
        """Clamp like the gateway then route through the REAL REST chokepoint (a no-op while the
        token is blank), proving the send path is exercised without any network."""
        clamped = reply[:MAX_REPLY_CHARS]
        self.result.replies.append(clamped)
        self.result.sends.append((clamped, self.attemptSend(clamped)))

    def attemptSend(self, text: str):
        """Send through ``discord_client._request`` -- returns None offline (token blank)."""
        return _dc._request(
            "POST", f"/channels/{config.DISCORD_CHANNEL_ID}/messages", json={"content": text})

    def attemptEmbed(self, embed: dict) -> dict:
        """Clamp an embed the way the wire path does; returns the sendable (bounded) embed."""
        return _dc._clampEmbed(embed)

    # ---- watchdog (Tier 5 ops) ----------------------------------------
    def setLastActivity(self, at_iso: str) -> None:
        """Stamp a synthetic notification so the watchdog's staleness logic can be exercised."""
        self.state.data.setdefault("notifications", []).append({"at": at_iso, "kind": "sim"})

    def isStale(self, now_ts: float, threshold_s: Optional[int] = None) -> bool:
        from notifications import ops
        thr = ops.STALE_SECONDS if threshold_s is None else threshold_s
        return ops.runIsStale(self.state, now_ts, thr)

    # ---- inspection ----------------------------------------------------
    def queuedOps(self) -> list[dict[str, Any]]:
        """The ops still queued on the bus (NOT drained) -- for asserting dedup collapsing."""
        return copy.deepcopy(self.bus.load().get("plan_ops") or [])

    def drainOps(self) -> list[dict[str, Any]]:
        return self.bus.drainOps()

    # ---- helpers -------------------------------------------------------
    @contextlib.contextmanager
    def _captureFeedback(self):
        """Redirect ``human_feedback.record`` into ``result.feedback`` for the duration of a run,
        so the harness never writes the real SIE label DB and the label is assertable."""
        from learning import human_feedback
        original = human_feedback.record

        def _capture(kind, *, run_id=None, subtask_id=None, target=None,
                     before=None, after=None, db_path=None):  # noqa: ANN001
            self.result.feedback.append({"kind": kind, "run_id": run_id, "subtask_id": subtask_id})
            return True

        human_feedback.record = _capture
        try:
            yield
        finally:
            human_feedback.record = original


def resetTransport() -> None:
    """Zero the REST breaker + 401 latch so replays / 429-401 probes are independent."""
    _dc._DISABLED = False
    _dc._RATE_LIMITED_UNTIL = 0.0
