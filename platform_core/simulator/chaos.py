"""Chaos-simulation doubles: a --dry-run variant that deliberately injects the SAME
fault shapes the executor/brain fuzz tests exercise, deterministically seeded so a run
is reproducible from a single integer. Wraps the plain simulation doubles
(``simulation.simRunClaude`` / ``SimBrain``) and, on a seeded fraction of calls, returns
malformed executor envelopes (``None``, non-dict, ``{}``, partial, mistyped, ``is_error``
envelope, a simulated-timeout marker) and malformed / empty brain completions.

Purpose: prove the orchestration survives a hostile local stack end-to-end -- every run
must still reach a graceful terminal status and never raise out of ``runFull``. This is the
same invariant the fuzz property tests assert, exposed as a runnable ``--dry-run --chaos``
mode for manual soak.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  chaosRunClaude(seed: int)  -- Return a seeded ``run_claude`` double
  ChaosBrain  -- Seeded wrapper around ``SimBrain``: on a fraction of calls returns malformed JSON,
  chaosBrain(seed: int, n_subtasks: int=3) -> 'ChaosBrain'  -- Seeded ``SimBrain`` wrapper that sometimes emits malformed / empty completions.
  buildChaosOrchestrator(work_dir: str, seed: int=0, n_subtasks: int=3)  -- An Orchestrator wired entirely with chaos doubles (no external services)
DEPENDS-ON: config, orchestrator.Orchestrator, platform_core.simulator
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/slow/test_chaos_sim.py
"""
from __future__ import annotations

import random

import config
from platform_core.simulator import simulation

LOG = config.getLogger("chaos")

# Executor fault shapes -- mirror tests/test_fuzz_executor.py plus the is_error envelope
# and simulated-timeout marker the real executor emits on a killed run.
_RUN_CLAUDE_SHAPES = (
    "valid", "valid", "valid",   # weight VALID so architect/plan phases usually progress
    "none", "str", "int", "list", "empty", "partial", "mistyped",
    "is_error", "timeout",
)

# Brain completion shapes -- mirror the garbage a local 7B realistically emits
# (tests/test_fuzz_brain.py). "valid" delegates to SimBrain so planning sometimes works.
_BRAIN_SHAPES = (
    "valid", "valid",            # weight VALID so subtasks usually get planned + executed
    "empty_content", "not_json", "no_message", "no_content", "message_not_dict",
    "resp_none", "bad_subtasks",
)


def _mixSeed(seed: int, salt: str) -> int:
    """Derive an independent stream seed from the base seed + a channel label."""
    return (int(seed) * 1_000_003) ^ (hash(salt) & 0xFFFF_FFFF)


def chaosRunClaude(seed: int):
    """Return a seeded ``run_claude`` double. Each call deterministically picks a fault
    shape; ``valid`` delegates to ``simRunClaude`` (so the architect phase still returns a
    real design doc), the rest return the malformed envelopes the fuzz tests use."""
    rng = random.Random(_mixSeed(seed, "run_claude"))

    def run_claude(spec, *, work_dir=None, task_state=None, subtask=None,
                   system_prompt=None, extra=None, timeout=None, resume_session=None, **_kw):
        shape = rng.choice(_RUN_CLAUDE_SHAPES)
        sid = (subtask or {}).get("subtask_id", "?")
        if shape == "valid":
            return simulation.simRunClaude(
                spec, work_dir=work_dir, task_state=task_state, subtask=subtask,
                system_prompt=system_prompt, extra=extra, timeout=timeout,
                resume_session=resume_session, **_kw)
        if shape == "none":
            return None
        if shape == "str":
            return f"[chaos] not a dict for {sid}"
        if shape == "int":
            return 42
        if shape == "list":
            return [1, 2, 3]
        if shape == "empty":
            return {}
        if shape == "partial":
            return {"ok": rng.choice([True, False, None, "yes"])}
        if shape == "is_error":
            return {"ok": False, "returncode": 1, "stdout": f"[chaos] error for {sid}",
                    "stderr": "chaos-injected failure", "is_error": True, "session_id": None}
        if shape == "timeout":
            return {"ok": False, "returncode": -1, "stdout": "",
                    "stderr": f"TIMEOUT after {config.CLAUDE_CLI_TIMEOUT_SECONDS}s",
                    "is_error": True, "timed_out": True, "session_id": None}
        return {"ok": "truthy", "returncode": "x", "stdout": 5, "stderr": {"a": 1},
                "is_error": "maybe", "session_id": ["s"]}

    return run_claude


class ChaosBrain:
    """Seeded wrapper around ``SimBrain``: on a fraction of calls returns malformed JSON,
    empty completions, or a broken response envelope instead of the valid plan/spec. The
    valid path delegates to ``SimBrain`` so a run still makes forward progress overall."""

    def __init__(self, seed: int, n_subtasks: int = 3):
        self._sim = simulation.SimBrain(n_subtasks=n_subtasks)
        self._rng = random.Random(_mixSeed(seed, "brain"))

    def chat(self, *, model=None, messages=None, **kwargs):  # noqa: ANN001
        shape = self._rng.choice(_BRAIN_SHAPES)
        if shape == "valid":
            return self._sim.chat(model=model, messages=messages, **kwargs)
        if shape == "empty_content":
            return {"message": {"content": self._rng.choice(["", "   ", None])}}
        if shape == "not_json":
            return {"message": {"content": self._rng.choice(["{", "}{", "not json", "42"])}}
        if shape == "no_message":
            return {}
        if shape == "no_content":
            return {"message": {}}
        if shape == "message_not_dict":
            return {"message": "not-a-dict"}
        if shape == "resp_none":
            return None
        return {"message": {"content": self._rng.choice(
            ['{"subtasks": 5}', '{"subtasks": "nope"}', '{"subtasks": [1, 2, 3]}',
             '{"subtasks": [{"title": 5}]}', '{"subtasks": null}'])}}


def chaosBrain(seed: int, n_subtasks: int = 3) -> "ChaosBrain":
    """Seeded ``SimBrain`` wrapper that sometimes emits malformed / empty completions."""
    return ChaosBrain(seed, n_subtasks=n_subtasks)


def buildChaosOrchestrator(work_dir: str, seed: int = 0, n_subtasks: int = 3):
    """An Orchestrator wired entirely with chaos doubles (no external services). ``work_dir``
    is the tree the run operates on and is passed to ``runFull`` by the caller; it is accepted
    here for API symmetry with ``simulation.buildBuilderOrchestrator``."""
    try:
        from orchestrator import Orchestrator
    except ImportError as exc:
        raise ImportError(
            "chaos.buildChaosOrchestrator requires 'orchestrator' and its dependencies "
            "(e.g. 'ollama'). Install missing packages or run in the full 9to5 environment. "
            f"Underlying error: {exc}"
        ) from exc
    LOG.info("chaos orchestrator built (work_dir=%s seed=%s)", work_dir, seed)
    return Orchestrator(brain=chaosBrain(seed, n_subtasks=n_subtasks), obs=simulation.SimObs(),
                        run_claude=chaosRunClaude(seed), replan=simulation.simReplan,
                        review=simulation.simReview, skip_pre_execution_council=True, offline_mode=True)
