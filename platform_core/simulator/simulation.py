"""Simulation doubles for a --dry-run: exercise the WHOLE 9TO5 pipeline
(architect -> plan -> execute -> verify -> complete) with NO Ollama, Claude CLI,
Discord, or Obsidian. The orchestrator accepts these via its dependency seams
(``Orchestrator(brain=, obs=, run_claude=, replan=, review=)``).

This is what makes the loop runnable locally and in CI -- the only way to gain
real confidence in the orchestration before a live 9-to-5 run.

R5: SimBrain/BuilderBrain dispatch EXACTLY on the structured ``act`` tag threaded
through ``llm_mixin._ollamaChat`` / ``llm_io.chat`` -- NEVER on prompt wording. An
unknown/missing act RAISES (fail loud), so a prompt rewording can never silently
reroute the sim onto the wrong payload shape.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  SimBrain  -- Stand-in for ``ollama.Client``
  simRunClaude(spec, *, work_dir=None, task_state=None, subtask=None, system_prompt=None, extra=None, timeout=None, resume_session=None, **_kw)  -- Fake executor
  simReplan(*args, **kwargs)
  simReview(subtask_title, trigger_reason, executor_output, *, ollama_chat=None, goal='')
  SimObs  -- In-memory Obsidian double: records writes, never touches disk or REST.
  buildOrchestrator(n_subtasks: int=3, *, offline: bool=True)  -- An Orchestrator wired with simulation doubles.
  BuilderBrain  -- Plans N subtasks, each producing a real file under ``work_dir`` with a REAL
  builderRunClaude(spec, *, work_dir=None, task_state=None, subtask=None, system_prompt=None, extra=None, timeout=None, resume_session=None, _project_root=None, **_kw)  -- Fake hands that ACTUALLY write the target file parsed from the subtask's verify cmd,
  buildBuilderOrchestrator(work_dir: str, n_subtasks: int=3)  -- An Orchestrator that produces real artifacts under work_dir and verifies them for real.
DEPENDS-ON: config, orchestrator
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/slow/test_simulation_advanced.py tests/slow/test_simulation_core.py
"""
from __future__ import annotations

import functools as _functools
import json
import os as _os
import re as _re
import subprocess as _subprocess
import sys as _sys
from pathlib import Path as _Path

import config

LOG = config.getLogger("simulation")

# This token deliberately makes the planner-authored command structurally invalid for
# the production verifier.  ``sanitizeVerify`` drops angle-bracket placeholders, so a
# builder fixture can never cross the sealed launch boundary by accident.  The
# credentialless simulation executor extracts and runs the path itself below.
_BUILDER_VERIFY_OWNER = "<SIMULATION_EXECUTOR_OWNS_VERIFY>"

# Every act the sim doubles know how to fake. Dispatch is EXACT: anything else raises,
# so a rerouted/reworded prompt can never silently exercise the wrong payload shape.
KNOWN_SIM_ACTS = ("architect", "plan", "critique", "invocation_spec", "replan",
                  "gatekeeper", "compaction", "horizon_fill", "elaborate", "universe",
                  "adversary_review", "instinct",
                  # Epic 2 dual-ledger planner (flag-gated in production; acts registered so a
                  # flag-on sim/dry-run stays deterministic instead of retry-looping to fallback)
                  "ledger_facts", "ledger_plan", "ledger_progress",
                  "ledger_facts_update", "ledger_plan_update")

_TEXT_RESPONSES = {
    "architect": "Produce a thorough architecture and design document for the specification.",
    "compaction": "[sim] compacted context summary.",
    "elaborate": "# Objective\nSimulated elaborated specification.",
    "instinct": "NONE",   # best-effort instinct scan: nothing flagged in a dry-run
}

_LEDGER_ANSWER = {"answer": False, "reason": "dry-run"}
_JSON_RESPONSES = {
    "replan": {"action": "keep", "add": [], "remove": [], "reason": "dry-run"},
    "ledger_facts": {"given_facts": ["dry-run: the goal is fully specified"],
                     "lookup_facts": [], "derive_facts": [], "guess_facts": []},
    "ledger_facts_update": {"root_cause": "dry-run", "given_facts": [],
                            "lookup_facts": [], "derive_facts": [], "guess_facts": []},
    "ledger_progress": {"is_request_satisfied": dict(_LEDGER_ANSWER),
                        "is_in_loop": dict(_LEDGER_ANSWER),
                        "is_progress_being_made": {"answer": True, "reason": "dry-run"},
                        "instruction": {"answer": "continue", "reason": "dry-run"}},
    "gatekeeper": {"approve": True, "reason": "dry-run auto-approve"},
    "horizon_fill": {"subtasks": []},   # wind down: never invent extra dry-run work
    "universe": {"description": "dry-run universe", "allowed_paths": [],
                 "allowed_to_expand_to": [], "hard_boundaries": []},
    "adversary_review": {"verdict": "approved", "severity": "none", "must_fix": [],
                         "suggested_fix": "", "confidence": 1.0, "concerns": [],
                         "notes": "dry-run auto-approve"},
}


def _simPayload(act, plan: dict, spec: dict):
    """Shared EXACT act dispatch for the sim brains. Returns a chat-response dict;
    RAISES on an unknown/missing act (fail loud -- prompt wording must never route)."""
    if act in ("plan", "critique"):        # critique pass echoes a valid plan
        return {"message": {"content": json.dumps(plan)}}
    if act in ("ledger_plan", "ledger_plan_update"):   # bullet form of the SAME plan, so the
        # dual-ledger DAG derives the identical subtasks the one-shot planner would author
        bullets = [s.get("title", f"step {i + 1}")
                   for i, s in enumerate(plan.get("subtasks") or [])] or ["Simulated subtask 1"]
        return {"message": {"content": json.dumps({"plan": bullets})}}
    if act == "invocation_spec":
        return {"message": {"content": json.dumps(spec)}}
    if act in _TEXT_RESPONSES:
        return {"message": {"content": _TEXT_RESPONSES[act]}}
    if act in _JSON_RESPONSES:
        return {"message": {"content": json.dumps(_JSON_RESPONSES[act])}}
    raise ValueError(
        f"sim brain got unknown act {act!r} -- register it in simulation.KNOWN_SIM_ACTS "
        "and give it a payload (dispatch is act-exact; prompt wording never routes)")


class SimBrain:
    """Stand-in for ``ollama.Client``. Dispatches on the structured ``act`` tag to return
    deterministic, schema-correct JSON for each brain act (plan / critique / invocation
    spec / ...). Subtasks carry NO verify so they pass on the simulated executor's
    exit-zero (no subprocess). Unknown act raises."""

    def __init__(self, n_subtasks: int = 3):
        self.n = max(1, n_subtasks)
        self.calls = 0

    def _plan(self) -> dict:
        return {"subtasks": [
            {"title": f"Simulated subtask {i}", "description": f"Do simulated step {i}.",
             "layer": 3, "effort_level": "default", "verify": None}
            for i in range(1, self.n + 1)
        ]}

    def _spec(self) -> dict:
        return {"prompt": "Simulated implementation work.", "effort_level": "default",
                "skills_to_invoke": [], "subagent": None,
                "pre_tool_hooks": [], "post_tool_hooks": []}

    def chat(self, *, model=None, messages=None, act=None, **kwargs):  # noqa: ANN001
        self.calls += 1
        return _simPayload(act, self._plan(), self._spec())


def simRunClaude(spec, *, work_dir=None, task_state=None, subtask=None,
                 system_prompt=None, extra=None, timeout=None, resume_session=None, **_kw):
    """Fake executor. The architect phase (system_prompt set) returns a design doc long
    enough to pass the architect gate; subtask runs return a clean success envelope."""
    if system_prompt is not None:
        doc = ("# Simulated architecture\n\n" + "This is a dry-run design document. " * 20)
        return {"ok": True, "returncode": 0, "stdout": doc, "is_error": False, "session_id": None}
    sid = (subtask or {}).get("subtask_id", "?")
    return {"ok": True, "returncode": 0, "stdout": f"[sim] completed {sid}", "is_error": False,
            "session_id": None}


def simReplan(*args, **kwargs):
    return {"action": "keep", "add": [], "remove": [], "reason": "dry-run"}


def simReview(subtask_title, trigger_reason, executor_output, *, ollama_chat=None, goal=""):
    return {"verdict": "approved", "trigger_reason": trigger_reason, "concerns": [],
            "notes": "dry-run auto-approve", "stub": True}


class SimObs:
    """In-memory Obsidian double: records writes, never touches disk or REST."""

    def __init__(self):
        self.notes: dict[str, str] = {}

    def writeNote(self, rel_path: str, content: str) -> dict:
        key = str(rel_path)
        self.notes[key] = content
        return {"ok": True, "via": "sim", "rel_path": key}

    def appendNote(self, rel_path: str, content: str) -> dict:
        key = str(rel_path)
        self.notes[key] = self.notes.get(key, "") + content
        return {"ok": True, "via": "sim", "rel_path": key}

    def readNote(self, rel_path: str):
        return self.notes.get(str(rel_path))

    def health(self) -> dict:
        return {"rest_ok": False, "authed": False}


def buildOrchestrator(n_subtasks: int = 3, *, offline: bool = True):
    """An Orchestrator wired with simulation doubles.

    Offline is the safe default for tests and ``--dry-run``. ``--sim-run``
    explicitly opts into live surfaces while retaining simulated work.
    """
    try:
        from orchestrator import Orchestrator
    except ImportError as exc:
        raise ImportError(
            "simulation.buildOrchestrator requires 'orchestrator' and its dependencies "
            "(e.g. 'ollama'). Install missing packages or run in the full 9to5 environment. "
            f"Underlying error: {exc}"
        ) from exc
    return Orchestrator(brain=SimBrain(n_subtasks=n_subtasks), obs=SimObs(),
                        run_claude=simRunClaude, replan=simReplan, review=simReview,
                        skip_pre_execution_council=True, offline_mode=offline)


# ---------------------------------------------------------------------------
# Higher-fidelity "builder" doubles: produce REAL files in a chosen work_dir and
# verify them for real (real subprocess), so a dry-run exercises the work-dir +
# verification paths against an actual project tree -- not just no-ops.
# ---------------------------------------------------------------------------


class BuilderBrain:
    """Plans N subtasks, each producing a real file under ``work_dir`` with a REAL
    behavioral verify (``python <file>`` / exit_zero). Captures work_dir so the verify
    paths are absolute and runnable. Dispatches EXACTLY on ``act`` (unknown raises)."""

    def __init__(self, work_dir: str, n_subtasks: int = 3):
        self.work = str(work_dir)
        self.n = max(1, n_subtasks)

    def _plan(self) -> dict:
        subs = []
        for i in range(1, self.n + 1):
            target = str(_Path(self.work) / f"feature_{i}.py")
            subs.append({"title": f"build feature {i}",
                         "description": f"create deterministic feature artifact {i}",
                         "layer": 3, "effort_level": "default",
                         "verify": {
                             "cmd": f'python "{target}" {_BUILDER_VERIFY_OWNER}',
                             "expect": "exit_zero",
                         },
                         # Each subtask touches only its own file -- mutually disjoint, so Epic 1's
                         # safeParallelSet/Epic 5's selectDisjointBatch can schedule them together
                         # instead of collapsing to one-at-a-time (unknown file-sets conflict).
                         "files_touched": [f"feature_{i}.py"]})
        return {"subtasks": subs}

    def _spec(self) -> dict:
        return {"prompt": "Write the target file so it runs cleanly.", "effort_level": "default"}

    def chat(self, *, model=None, messages=None, act=None, **kwargs):
        return _simPayload(act, self._plan(), self._spec())


def builderRunClaude(spec, *, work_dir=None, task_state=None, subtask=None,
                     system_prompt=None, extra=None, timeout=None, resume_session=None,
                     _project_root=None, **_kw):
    """Fake hands that ACTUALLY write the target file parsed from the subtask's verify cmd,
    so the real verify (`python <file>`) passes. Architect phase returns a design doc.

    ``_project_root`` (bound via functools.partial in buildBuilderOrchestrator) is the
    containment boundary for the path-traversal guard below. It defaults to ``work_dir``
    for backward compatibility, but under worktree isolation ``work_dir`` becomes a
    per-attempt worktree copy while BuilderBrain's verify commands always reference the
    ORIGINAL project root -- so the boundary must stay pinned to that root, not drift with
    the particular worktree where an attempt happens to execute."""
    if system_prompt is not None:
        return {"ok": True, "returncode": 0, "stdout": "# design\n" + "doc " * 60,
                "is_error": False, "session_id": None}
    cmd = ((subtask or {}).get("verify") or {}).get("cmd") or ""
    m = _re.search(r'python\s+"([^"]+)"', cmd)
    sid = (subtask or {}).get("subtask_id", "?")
    boundary = _project_root or work_dir
    target = m.group(1) if m else None
    if target is None and boundary:
        touched = (subtask or {}).get("files_touched") or []
        if touched:
            target = str(_Path(boundary) / str(touched[0]))
    if target:
        try:
            p = _Path(target).resolve()
            root = _Path(boundary).resolve() if boundary else None
            if root is not None:
                try:
                    p.relative_to(root)
                except ValueError:
                    return {"ok": False, "returncode": 1,
                            "stdout": f"path traversal blocked: {p} outside {root}",
                            "stderr": "", "is_error": True, "session_id": None}
            if root is None:
                root = p.parent
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(f'"""Built by 9to5 builder-sim for {sid}."""\nprint("{sid} ok")\n',
                         encoding="utf-8")
            sterile_env = {
                key: value for key, value in _os.environ.items()
                if key.upper() in {"SYSTEMROOT", "WINDIR", "TEMP", "TMP"}
            }
            proc = _subprocess.run(
                [_sys.executable, "-I", "-S", "-B", str(p)],
                cwd=str(root), env=sterile_env, capture_output=True, text=True,
                timeout=30, check=False,
            )
            output = (proc.stdout or "").strip()
            error = (proc.stderr or "").strip()
            if proc.returncode != 0:
                return {"ok": False, "returncode": 1,
                        "stdout": output, "stderr": error,
                        "is_error": True, "session_id": None,
                        "simulation_verification": "failed"}
        except Exception as e:  # noqa: BLE001
            return {"ok": False, "returncode": 1, "stdout": f"write failed: {e}",
                    "stderr": "", "is_error": True, "session_id": None,
                    "simulation_verification": "error"}
        return {"ok": True, "returncode": 0,
                "stdout": f"[builder] wrote and ran artifact for {sid}\n{output}",
                "stderr": error, "is_error": False, "session_id": None,
                "simulation_verification": "passed"}
    return {"ok": True, "returncode": 0, "stdout": f"[builder] no artifact for {sid}",
            "stderr": "", "is_error": False, "session_id": None,
            "simulation_verification": "not_applicable"}


def buildBuilderOrchestrator(work_dir: str, n_subtasks: int = 3):
    """An Orchestrator that produces real artifacts under work_dir and verifies them for real."""
    try:
        from orchestrator import Orchestrator
    except ImportError as exc:
        raise ImportError(
            "simulation.buildBuilderOrchestrator requires 'orchestrator' and its dependencies "
            "(e.g. 'ollama'). Install missing packages or run in the full 9to5 environment. "
            f"Underlying error: {exc}"
        ) from exc
    return Orchestrator(brain=BuilderBrain(work_dir, n_subtasks), obs=SimObs(),
                        run_claude=_functools.partial(builderRunClaude, _project_root=str(work_dir)),
                        replan=simReplan, review=simReview, skip_pre_execution_council=True,
                        offline_mode=True)
