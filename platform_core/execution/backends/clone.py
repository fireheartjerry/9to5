class _SnapshotJournalValidation:
    """One-use proof that this kernel freshly reloaded and probed one closure."""

    __slots__ = ("kernel", "lease", "quiescence", "seal")

    def __init__(
        self,
        *,
        kernel: TransactionalCloneKernel,
        lease: CloneLease,
        quiescence: CloneQuiescenceProof,
        seal: object,
        _factory: object,
    ) -> None:
        if _factory is not _SNAPSHOT_VALIDATION_FACTORY:
            raise StagedRevisionRefused(
                "snapshot journal validation requires its kernel factory"
            )
        self.kernel = kernel
        self.lease = lease
        self.quiescence = quiescence
        self.seal = seal


def _pathsOverlap(left: str | Path, right: str | Path) -> bool:
    left_text = os.path.normcase(os.path.abspath(os.fspath(left)))
    right_text = os.path.normcase(os.path.abspath(os.fspath(right)))
    try:
        common = os.path.commonpath((left_text, right_text))
    except ValueError:
        return False
    return common in {left_text, right_text}


class TransactionalCloneKernel:
    """Concrete ordered adapter from a quiesced clone to one staged revision."""

    def __init__(
        self,
        *,
        parser: _SnapshotParser,
        snapshot_root: str | Path,
        verification_root: str | Path,
        expected_manifest_provider: ExpectedManifestProvider,
        quiescence_provider: QuiescenceProvider,
        commit_metadata_provider: CommitMetadataProvider,
        coordinator_factory: CoordinatorFactory,
        release_callback: ReleaseCallback | None = None,
        artifact_qualification: VerifiedKernelArtifacts | None = None,
        landing_authority_issuer: LandingAuthorityIssuer | None = None,
        run_admission: RunAdmissionAuthority | None = None,
        credential_absence_verifier: CredentialChannelAbsenceVerifier | None = None,
    ) -> None:
        for name, provider in (
            ("expected_manifest_provider", expected_manifest_provider),
            ("quiescence_provider", quiescence_provider),
            ("commit_metadata_provider", commit_metadata_provider),
            ("coordinator_factory", coordinator_factory),
        ):
            if not callable(provider):
                raise TypeError(f"{name} must be callable")
        if not callable(getattr(parser, "parseCandidateSnapshot", None)):
            raise TypeError("parser must expose parseCandidateSnapshot")
        snapshot = Path(snapshot_root)
        verification = Path(verification_root)
        if not snapshot.is_absolute() or not verification.is_absolute():
            raise ValueError("transactional clone artifact roots must be absolute")
        if _pathsOverlap(snapshot, verification):
            raise ValueError("snapshot and verification roots must not overlap")
        if release_callback is not None and not callable(release_callback):
            raise TypeError("release_callback must be callable")
        if (
            credential_absence_verifier is not None
            and type(credential_absence_verifier) is not CredentialChannelAbsenceVerifier
        ):
            raise TypeError(
                "credential_absence_verifier must be the exact sealed verifier"
            )
        if artifact_qualification is not None:
            if not isinstance(artifact_qualification, VerifiedKernelArtifacts):
                raise TypeError("artifact_qualification must be VerifiedKernelArtifacts")
            try:
                artifact_qualification.revalidate()
            except KernelArtifactsUnavailable as exc:
                raise EnvironmentUnavailable(
                    "clone", "installed kernel artifacts are not live", cause=exc
                ) from exc
            if type(credential_absence_verifier) is not CredentialChannelAbsenceVerifier:
                raise EnvironmentUnavailable(
                    "clone",
                    "installed clone kernel requires a sealed broker credential verifier",
                )
            if (
                not isinstance(parser, ObjectParser)
                or not parser.hasInstalledArtifactAuthority()
                or parser.artifactQualification is None
                or parser.artifactQualification.qualification_id
                != artifact_qualification.qualification_id
            ):
                raise EnvironmentUnavailable(
                    "clone", "parser is not bound to installed kernel artifacts"
                )
            issuer = landing_authority_issuer
            admission = run_admission
            if (
                type(issuer) is not LandingAuthorityIssuer
                or type(admission) is not RunAdmissionAuthority
            ):
                raise EnvironmentUnavailable(
                    "clone",
                    "installed clone kernel requires live controller-owned run admission",
                )
            assert isinstance(issuer, LandingAuthorityIssuer)
            assert isinstance(admission, RunAdmissionAuthority)
            typed_issuer = cast(LandingAuthorityIssuer, issuer)
            typed_admission = cast(RunAdmissionAuthority, admission)
            if not typed_issuer.isInstalledAuthority():
                raise EnvironmentUnavailable(
                    "clone",
                    "installed clone kernel requires live controller-owned run admission",
                )
            try:
                typed_issuer._validateAdmission(typed_admission)
            except Exception as exc:
                raise EnvironmentUnavailable(
                    "clone",
                    "installed clone kernel run admission is not live",
                    cause=exc,
                ) from exc
        self.parser = parser
        self.snapshot_root = Path(os.path.abspath(snapshot))
        self.verification_root = Path(os.path.abspath(verification))
        self.expected_manifest_provider = expected_manifest_provider
        self.quiescence_provider = quiescence_provider
        self.commit_metadata_provider = commit_metadata_provider
        self.coordinator_factory = coordinator_factory
        self.release_callback = release_callback
        self._artifact_qualification = artifact_qualification
        self._landing_authority_issuer = landing_authority_issuer
        self._run_admission = run_admission
        self._credential_absence_verifier = credential_absence_verifier
        self._snapshot_process_capability = object()
        self._snapshot_composition_seal = object()
        self._snapshot_validation_seal = object()
        self._snapshot_validations: dict[
            int,
            tuple[
                _SnapshotJournalValidation,
                CloneLease,
                CloneQuiescenceProof,
            ],
        ] = {}
        with _INITIALIZED_SNAPSHOT_KERNELS_LOCK:
            _INITIALIZED_SNAPSHOT_KERNELS[id(self)] = _InitializedSnapshotKernel(
                kernel=self,
                process_capability=self._snapshot_process_capability,
                composition_seal=self._snapshot_composition_seal,
                validation_seal=self._snapshot_validation_seal,
            )
        self._snapshot_admission_issuer = _createCloneSnapshotAdmissionIssuer(
            owner=self,
            process_capability=self._snapshot_process_capability
        )
        self._writer_runtime_source = (
            Path(_git_object_writer_module.__file__).resolve(strict=True)
            if artifact_qualification is not None
            else None
        )
        self._cleanup_capability = object()
        self._contexts: dict[str, _PreparedCloneContext] = {}
        self._lock = threading.RLock()

    def _snapshotAdmissionCompositionLive(
        self,
        process_capability: object,
    ) -> bool:
        with _INITIALIZED_SNAPSHOT_KERNELS_LOCK:
            initialized = _INITIALIZED_SNAPSHOT_KERNELS.get(id(self))
        return bool(
            initialized is not None
            and initialized.kernel is self
            and initialized.process_capability is process_capability
            and initialized.process_capability is self._snapshot_process_capability
            and initialized.composition_seal is self._snapshot_composition_seal
            and initialized.validation_seal is self._snapshot_validation_seal
        )

    def _consumeSnapshotJournalValidation(
        self,
        validation: object,
        lease: CloneLease,
        quiescence: CloneQuiescenceProof,
    ) -> bool:
        if type(validation) is not _SnapshotJournalValidation:
            raise StagedRevisionRefused(
                "snapshot admission requires exact fresh journal validation"
            )
        exact = cast(_SnapshotJournalValidation, validation)
        with self._lock:
            registered = self._snapshot_validations.pop(id(exact), None)
            if (
                registered is None
                or registered[0] is not exact
                or registered[1] is not lease
                or registered[2] is not quiescence
                or exact.kernel is not self
                or exact.lease is not lease
                or exact.quiescence is not quiescence
                or exact.seal is not self._snapshot_validation_seal
            ):
                raise StagedRevisionRefused(
                    "snapshot admission fresh journal validation differs"
                )
        return True

    def productionReady(self) -> bool:
        """Return whether the adapter has live installed staging authority."""

        qualification = self._artifact_qualification
        if qualification is None:
            return False
        try:
            qualification.revalidate()
            self._requireWriterSource(qualification)
            issuer = self._landing_authority_issuer
            admission = self._run_admission
            if (
                type(issuer) is not LandingAuthorityIssuer
                or type(admission) is not RunAdmissionAuthority
                or type(self._credential_absence_verifier)
                is not CredentialChannelAbsenceVerifier
            ):
                return False
            assert isinstance(issuer, LandingAuthorityIssuer)
            assert isinstance(admission, RunAdmissionAuthority)
            typed_issuer = cast(LandingAuthorityIssuer, issuer)
            typed_admission = cast(RunAdmissionAuthority, admission)
            if not typed_issuer.isInstalledAuthority():
                return False
            typed_issuer._validateAdmission(typed_admission)
        except (KernelArtifactsUnavailable, OSError, ValueError):
            return False
        except Exception:
            return False
        return True

    def _requireLiveRunAdmission(self) -> None:
        """Reprove controller-owned run admission at use time, not only at build."""

        issuer = self._landing_authority_issuer
        admission = self._run_admission
        if (
            type(issuer) is not LandingAuthorityIssuer
            or type(admission) is not RunAdmissionAuthority
        ):
            raise EnvironmentUnavailable(
                "clone",
                "installed clone kernel requires live controller-owned run admission",
            )
        assert isinstance(issuer, LandingAuthorityIssuer)
        assert isinstance(admission, RunAdmissionAuthority)
        typed_issuer = cast(LandingAuthorityIssuer, issuer)
        typed_admission = cast(RunAdmissionAuthority, admission)
        if not typed_issuer.isInstalledAuthority():
            raise EnvironmentUnavailable(
                "clone",
                "installed clone kernel requires live controller-owned run admission",
            )
        try:
            typed_issuer._validateAdmission(typed_admission)
        except Exception as exc:
            raise EnvironmentUnavailable(
                "clone",
                "installed clone kernel run admission is not live",
                cause=exc,
            ) from exc

    def _requireWriterSource(
        self,
        qualification: VerifiedKernelArtifacts,
    ) -> None:
        if self._writer_runtime_source is None:
            raise KernelArtifactsUnavailable("object writer source is not bound")
        writer_source = readNoFollowBytes(
            self._writer_runtime_source,
            max_bytes=8 * 1024 * 1024,
        )
        if (
            hashlib.sha256(writer_source).hexdigest()
            != qualification.writer_source_sha256
        ):
            raise KernelArtifactsUnavailable("object writer imported source differs")

    def _revalidateInstalledArtifacts(
        self,
        coordinator: StagingCoordinator | None = None,
    ) -> None:
        qualification = self._artifact_qualification
        if qualification is None:
            return
        try:
            qualification.revalidate()
            self._requireWriterSource(qualification)
            self._requireLiveRunAdmission()
            parser = self.parser
            if (
                not isinstance(parser, ObjectParser)
                or not parser.hasInstalledArtifactAuthority()
                or parser.artifactQualification is None
                or parser.artifactQualification.qualification_id
                != qualification.qualification_id
            ):
                raise KernelArtifactsUnavailable("parser qualification differs")
            if coordinator is not None:
                if (
                    coordinator._landing_authority_issuer
                    is not self._landing_authority_issuer
                    or coordinator._run_admission is not self._run_admission
                ):
                    raise KernelArtifactsUnavailable(
                        "staging coordinator run admission differs"
                    )
                writer = coordinator.writer
                if not isinstance(writer, GitObjectWriter):
                    raise KernelArtifactsUnavailable("object writer is not typed")
                evidence = dict(writer.sha1dcEvidence.toDict())
                if (
                    writer.writer_version_digest
                    != qualification.writer_version_digest
                    or evidence != dict(qualification.host_sha1dc_evidence)
                ):
                    raise KernelArtifactsUnavailable(
                        "object writer runtime identity differs"
                    )
        except (KernelArtifactsUnavailable, OSError, ValueError) as exc:
            raise EnvironmentUnavailable(
                "clone", "installed kernel artifact binding changed", cause=exc
            ) from exc


    def _validateCoordinatorAndRecord(
        self,
        lease: CloneLease,
        expected: ObjectManifest,
        quiescence: CloneQuiescenceProof,
        coordinator: StagingCoordinator,
    ) -> _SnapshotJournalValidation:
        attestation = coordinator.attestation
        if (
            attestation.repository_id != lease.repository_id
            or attestation.head_oid != lease.expected_base_revision
            or expected.expected_revision != lease.expected_base_revision
        ):
            raise EnvironmentUnavailable(
                "clone",
                "coordinator, expected tree, and clone revision differ",
            )
        journal = coordinator.journal
        if type(journal) is not AttemptJournal:
            raise EnvironmentUnavailable(
                "clone",
                "snapshot admission requires the exact attempt journal",
            )
        record = AttemptJournal.load(journal, lease.transaction_id)
        exact_fields = {
            "transaction_id": lease.transaction_id,
            "task_id": lease.task_id,
            "subtask_id": lease.subtask_id,
            "attempt_id": lease.attempt_id,
            "repository_id": lease.repository_id,
            "clone_path": lease.checkout_path,
            "ownership_nonce": lease.ownership_nonce,
            "base_revision": lease.expected_base_revision,
            "candidate_branch": lease.candidate_branch,
        }
        if any(getattr(record, name) != value for name, value in exact_fields.items()):
            raise EnvironmentUnavailable(
                "clone",
                "attempt journal differs from the executable clone lease",
            )
        if record.phase not in {
            AttemptPhase.RUNNING,
            AttemptPhase.CANDIDATE_CHECKPOINTED,
            AttemptPhase.STAGED_PREPARED,
        }:
            raise EnvironmentUnavailable(
                "clone",
                "attempt is not in a snapshot-preparable phase",
            )
        if tuple(record.resource_lease_ids) != quiescence.resource_ids:
            raise EnvironmentUnavailable(
                "clone",
                "quiescence does not cover the journaled runtime resources",
            )
        try:
            resources = AttemptJournal.load_resources(
                journal,
                lease.transaction_id,
            )
        except MissingResourceSet as exc:
            raise EnvironmentUnavailable(
                "clone",
                "runtime resource closure is missing",
                cause=exc,
            ) from exc
        except IncompleteResourceSet as exc:
            raise EnvironmentUnavailable(
                "clone",
                "runtime resource closure is incomplete",
                cause=exc,
            ) from exc
        except JournalCorruption as exc:
            raise EnvironmentUnavailable(
                "clone",
                "runtime resource closure is corrupt",
                cause=exc,
            ) from exc
        except (AttributeError, JournalError, OSError, TypeError, ValueError) as exc:
            raise EnvironmentUnavailable(
                "clone",
                "journaled runtime resources are unavailable",
                cause=exc,
            ) from exc
        if not isinstance(resources, tuple) or not resources:
            raise EnvironmentUnavailable(
                "clone",
                "attempt has no immutable runtime resource set",
            )
        resource_ids = tuple(
            f"{resource.role.value}:{resource.resource_id}"
            for resource in resources
            if isinstance(resource, RuntimeResourceLease)
        )
        if (
            len(resource_ids) != len(resources)
            or resource_ids != tuple(record.resource_lease_ids)
            or resource_ids != quiescence.resource_ids
        ):
            raise EnvironmentUnavailable(
                "clone",
                "runtime resource observations differ from the closed attempt set",
            )
        if runtimeResourceStateDigest(resources) != quiescence.resource_state_digest:
            raise EnvironmentUnavailable(
                "clone",
                "quiescence proof differs from the exact runtime resource states",
            )
        proof_time = datetime.fromisoformat(
            quiescence.observed_at.replace("Z", "+00:00")
        )
        for resource in resources:
            if (
                resource.transaction_id != lease.transaction_id
                or resource.ownership_nonce != lease.ownership_nonce
            ):
                raise EnvironmentUnavailable(
                    "clone",
                    "runtime resource ownership differs from the clone lease",
                )
            resource_time = datetime.fromisoformat(
                resource.updated_at.replace("Z", "+00:00")
            )
            if resource_time > proof_time:
                raise EnvironmentUnavailable(
                    "clone",
                    "quiescence observation predates a runtime resource state",
                )
            try:
                quiesced = runtimeResourceIsQuiescent(
                    resource,
                    container_absence_probe=self._containerResourceAbsent,
                    credential_absence_verifier=self._credential_absence_verifier,
                )
            except RuntimeResourceProbeRefused as exc:
                raise EnvironmentUnavailable(
                    "clone",
                    "runtime resource quiescence is not independently observable",
                    cause=exc,
                ) from exc
            if not quiesced:
                raise EnvironmentUnavailable(
                    "clone",
                    "runtime resource remains capable of writing the candidate",
                )
        policy_digest = canonical_digest(
            {
                "attribute_rules": [
                    rule.toDict() for rule in expected.attribute_rules
                ],
                "policy": expected.policy.toDict(),
            }
        )
        if record.policy_digest != policy_digest:
            raise EnvironmentUnavailable(
                "clone",
                "expected tree policy differs from the journaled attempt",
            )
        validation = _SnapshotJournalValidation(
            kernel=self,
            lease=lease,
            quiescence=quiescence,
            seal=self._snapshot_validation_seal,
            _factory=_SNAPSHOT_VALIDATION_FACTORY,
        )
        with self._lock:
            self._snapshot_validations[id(validation)] = (
                validation,
                lease,
                quiescence,
            )
        return validation

    def _containerResourceAbsent(self, resource: RuntimeResourceLease) -> bool:
        """Prove a container ID is absent through the sealed installed Docker CLI."""

        qualification = self._artifact_qualification
        if qualification is None:
            raise RuntimeResourceProbeRefused(
                "container quiescence has no installed artifact qualification"
            )
        if _CONTAINER_ID_RE.fullmatch(resource.container_id) is None:
            raise RuntimeResourceProbeRefused(
                "container identity is not a full lowercase Docker ID"
            )
        try:
            qualification.revalidate()
        except KernelArtifactsUnavailable as exc:
            raise RuntimeResourceProbeRefused(
                "container probe artifact qualification changed"
            ) from exc
        with tempfile.TemporaryDirectory(prefix="galaxy-docker-probe-") as config_root:
            environment = {
                "DOCKER_CONFIG": config_root,
                "DOCKER_HOST": "npipe:////./pipe/dockerDesktopLinuxEngine",
                "DOCKER_CLI_HINTS": "false",
                "DOCKER_SCAN_SUGGEST": "false",
            }
            system_root = os.environ.get("SystemRoot")
            if system_root:
                environment["SystemRoot"] = system_root
            try:
                completed = subprocess.run(
                    [
                        str(qualification.docker_executable),
                        "--host",
                        "npipe:////./pipe/dockerDesktopLinuxEngine",
                        "container",
                        "ls",
                        "--all",
                        "--no-trunc",
                        "--filter",
                        f"id={resource.container_id}",
                        "--format",
                        "{{.ID}}",
                    ],
                    cwd=qualification.docker_executable.parent,
                    env=environment,
                    stdin=subprocess.DEVNULL,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    timeout=15,
                    check=False,
                    shell=False,
                    creationflags=(
                        getattr(subprocess, "CREATE_NO_WINDOW", 0)
                        if os.name == "nt"
                        else 0
                    ),
                )
            except (OSError, subprocess.SubprocessError) as exc:
                raise RuntimeResourceProbeRefused(
                    "sealed Docker container query failed"
                ) from exc
        if (
            completed.returncode != 0
            or completed.stderr
            or len(completed.stdout) > 1024 * 1024
        ):
            raise RuntimeResourceProbeRefused(
                "sealed Docker container query was not exact"
            )
        try:
            observed = tuple(
                line
                for line in completed.stdout.decode(
                    "ascii",
                    errors="strict",
                ).splitlines()
                if line
            )
        except UnicodeError as exc:
            raise RuntimeResourceProbeRefused(
                "sealed Docker container identity is malformed"
            ) from exc
        if any(_CONTAINER_ID_RE.fullmatch(value) is None for value in observed):
            raise RuntimeResourceProbeRefused(
                "sealed Docker returned a noncanonical container identity"
            )
        try:
            qualification.revalidate()
        except KernelArtifactsUnavailable as exc:
            raise RuntimeResourceProbeRefused(
                "container probe artifact qualification changed"
            ) from exc
        if not observed:
            return True
        if observed == (resource.container_id,):
            return False
        raise RuntimeResourceProbeRefused(
            "sealed Docker container filter returned an ambiguous identity"
        )

    def _artifactBoundaries(
        self,
        lease: CloneLease,
        coordinator: StagingCoordinator,
    ) -> tuple[str | Path, ...]:
        forbidden: tuple[str | Path, ...] = (
            lease.checkout_path,
            coordinator.attestation.canonical_root,
            coordinator.journal.root,
        )
        for artifact_root in (self.snapshot_root, self.verification_root):
            if any(_pathsOverlap(artifact_root, root) for root in forbidden):
                raise EnvironmentUnavailable(
                    "clone",
                    "transaction artifacts overlap executable or canonical state",
                )
        return forbidden

    def prepare(
        self,
        lease: CloneLease,
        *,
        task_state: object,
        subtask: object,
    ) -> ClonePreparationArtifacts:
        self._revalidateInstalledArtifacts()
        validateCloneLease(lease)
        with self._lock:
            prior = self._contexts.get(lease.transaction_id)
            if prior is not None:
                if prior.lease is not lease or not prior.coordinator.stagedRevisionIntact(
                    prior.request,
                    prior.artifacts.staged,
                ):
                    raise EnvironmentUnavailable(
                        "clone",
                        "prepared transaction replay differs or lost integrity",
                    )
                return prior.artifacts
            expected = self.expected_manifest_provider(lease, task_state, subtask)
            quiescence = self.quiescence_provider(lease, task_state, subtask)
            if not isinstance(expected, ObjectManifest) or not isinstance(
                quiescence,
                CloneQuiescenceProof,
            ):
                raise EnvironmentUnavailable(
                    "clone",
                    "manifest or quiescence provider returned an untyped value",
                )
            coordinator = self.coordinator_factory(lease)
            self._revalidateInstalledArtifacts(coordinator)
            forbidden = self._artifactBoundaries(lease, coordinator)
            snapshot_validation = self._validateCoordinatorAndRecord(
                lease,
                expected,
                quiescence,
                coordinator,
            )
            snapshot_admission = self._snapshot_admission_issuer.issue(
                lease,
                quiescence,
                owner=self,
                process_capability=self._snapshot_process_capability,
                journal_validation=snapshot_validation,
            )
            snapshot = snapshotCloneTree(
                lease,
                quiescence=quiescence,
                admission=snapshot_admission,
                policy=expected.policy,
                snapshot_root=self.snapshot_root,
                expected=expected,
            )
            writer_blob_root = getattr(coordinator.writer, "blob_root", None)
            if writer_blob_root is not None and os.path.normcase(
                os.path.abspath(os.fspath(writer_blob_root))
            ) != os.path.normcase(os.path.abspath(os.fspath(snapshot.blob_root))):
                raise EnvironmentUnavailable(
                    "clone",
                    "object writer is not bound to the immutable snapshot blob root",
                )
            parsed = self.parser.parseCandidateSnapshot(
                snapshot=snapshot,
                expected=expected,
            )
            self._revalidateInstalledArtifacts(coordinator)
            metadata = self.commit_metadata_provider(lease, task_state, subtask)
            if not isinstance(metadata, CommitMetadata):
                raise EnvironmentUnavailable(
                    "clone",
                    "commit metadata provider returned an untyped value",
                )
            request = StagingRequest(
                transaction_id=lease.transaction_id,
                task_id=lease.task_id,
                subtask_id=lease.subtask_id,
                attempt_id=lease.attempt_id,
                runner_kind=lease.runner_kind,
                snapshot=snapshot,
                parsed=parsed,
                expected_manifest=expected,
                commit_metadata=metadata,
                cleanup_token=object(),
            )
            staged = coordinator.prepareStagedRevision(request)
            if (
                staged.candidate_snapshot_digest != snapshot.snapshot_digest
                or staged.parser_manifest_digest != parsed.manifest.manifest_digest
                or staged.expected_target_revision != lease.expected_base_revision
            ):
                raise EnvironmentUnavailable(
                    "clone",
                    "staged revision differs from its immutable native inputs",
                )
            object_receipt: ObjectWriteReceipt = coordinator.writer.writeRevision(
                manifest=parsed.manifest,
                metadata=metadata,
            )
            if (
                object_receipt.commit_oid != staged.proposed_revision
                or object_receipt.tree_oid != staged.proposed_tree
                or object_receipt.object_closure_digest != staged.object_closure_digest
            ):
                raise EnvironmentUnavailable(
                    "clone",
                    "verification closure differs from the staged revision",
                )
            verification = coordinator.writer.createVerificationRepository(
                transaction_id=lease.transaction_id,
                checkout_root=self.verification_root / lease.transaction_id,
                manifest=parsed.manifest,
                receipt=object_receipt,
                forbidden_roots=forbidden,
            )
            artifacts = ClonePreparationArtifacts(
                staged=staged,
                verification_dir=verification.checkout_path,
                verification_backend="credentialless-container",
            )
            self._contexts[lease.transaction_id] = _PreparedCloneContext(
                lease=lease,
                coordinator=coordinator,
                request=request,
                verification=verification,
                artifacts=artifacts,
            )
            return artifacts

    def intact(self, staged: StagedRevisionLease) -> bool:
        if not isinstance(staged, StagedRevisionLease):
            return False
        with self._lock:
            context = self._contexts.get(staged.transaction_id)
            return bool(
                context is not None
                and context.artifacts.staged is staged
                and context.coordinator.stagedRevisionIntact(context.request, staged)
            )

    def promote(
        self,
        staged: StagedRevisionLease,
        authorization: object,
        landing_authority: object,
    ) -> PromotionReceipt:
        with self._lock:
            context = self._contexts.get(staged.transaction_id)
            if context is None or context.artifacts.staged is not staged:
                raise EnvironmentUnavailable("clone", "staged transaction is not live")
            return context.coordinator.promoteStagedRevision(
                staged,
                authorization,
                landing_authority,
            )

    def reject(self, staged: StagedRevisionLease) -> CandidateResult:
        with self._lock:
            context = self._contexts.get(staged.transaction_id)
            if context is None or context.artifacts.staged is not staged:
                raise EnvironmentUnavailable("clone", "staged transaction is not live")
            return context.coordinator.rejectStagedRevision(
                staged,
                reason="verification or selection rejected",
            )

    def checkpoint(
        self,
        lease: CloneLease,
        *,
        task_state: object,
        subtask: object,
    ) -> dict[str, Any]:
        artifacts = self.prepare(lease, task_state=task_state, subtask=subtask)
        return {
            "available": True,
            "transaction_id": lease.transaction_id,
            "checkpoint_ref": artifacts.staged.checkpoint_ref,
            "checkpoint_revision": artifacts.staged.checkpoint_revision,
            "candidate_snapshot_digest": artifacts.staged.candidate_snapshot_digest,
            "artifact_preserved": True,
        }

    @staticmethod
    def _artifact(
        *,
        artifact_id: str,
        disposition: CleanupDisposition,
        locator: str,
        runtime_token: object,
    ) -> CleanupArtifact:
        return CleanupArtifact(
            artifact_id=artifact_id,
            disposition=disposition,
            ownership_digest=canonical_digest(
                {
                    "artifact_id": artifact_id,
                    "disposition": disposition.value,
                    "locator": os.path.normcase(os.path.abspath(locator))
                    if os.path.isabs(locator)
                    else locator,
                }
            ),
            runtime_token=runtime_token,
        )

    def _cleanupArtifacts(
        self,
        context: _PreparedCloneContext,
    ) -> tuple[CleanupArtifact, ...]:
        transaction_id = context.lease.transaction_id
        disposable = (
            CleanupDisposition.REMOVE
            if self.release_callback is not None
            else CleanupDisposition.RETAIN
        )
        artifacts = (
            self._artifact(
                artifact_id=f"candidate:{transaction_id}",
                disposition=disposable,
                locator=context.lease.checkout_path,
                runtime_token=context.lease.runtime_token or context.lease,
            ),
            self._artifact(
                artifact_id=f"checkpoint-ref:{transaction_id}",
                disposition=CleanupDisposition.RETAIN,
                locator=context.artifacts.staged.checkpoint_ref,
                runtime_token=context.artifacts.staged.cleanup_token or context.artifacts.staged,
            ),
            self._artifact(
                artifact_id=f"object-closure:{transaction_id}",
                disposition=CleanupDisposition.RETAIN,
                locator=context.artifacts.staged.object_closure_digest,
                runtime_token=context.artifacts.staged.cleanup_token or context.artifacts.staged,
            ),
            self._artifact(
                artifact_id=f"parser-output:{transaction_id}",
                disposition=CleanupDisposition.RETAIN,
                locator=context.artifacts.staged.parser_manifest_digest,
                runtime_token=context.artifacts.staged.cleanup_token or context.artifacts.staged,
            ),
            self._artifact(
                artifact_id=f"snapshot:{transaction_id}",
                disposition=CleanupDisposition.RETAIN,
                locator=context.artifacts.staged.candidate_snapshot_digest,
                runtime_token=context.artifacts.staged.cleanup_token or context.artifacts.staged,
            ),
            self._artifact(
                artifact_id=f"staged-ref:{transaction_id}",
                disposition=CleanupDisposition.REMOVE,
                locator=context.artifacts.staged.staged_ref,
                runtime_token=context.artifacts.staged.cleanup_token or context.artifacts.staged,
            ),
            self._artifact(
                artifact_id=f"verification:{transaction_id}",
                disposition=disposable,
                locator=context.verification.checkout_path,
                runtime_token=context.verification.runtime_token or context.verification,
            ),
        )
        return tuple(sorted(artifacts, key=lambda artifact: artifact.artifact_id))

    def _removeArtifact(
        self,
        context: _PreparedCloneContext,
        artifact: CleanupArtifact,
    ) -> ArtifactCleanupResult:
        staged_id = f"staged-ref:{context.lease.transaction_id}"
        if artifact.artifact_id == staged_id:
            context.coordinator.ref_store.retirePrivateRef(
                context.artifacts.staged.staged_ref,
                context.artifacts.staged.proposed_revision,
            )
            return ArtifactCleanupResult(
                artifact_id=artifact.artifact_id,
                ownership_digest=artifact.ownership_digest,
                removed=True,
            )
        if self.release_callback is None:
            return ArtifactCleanupResult(
                artifact_id=artifact.artifact_id,
                ownership_digest=artifact.ownership_digest,
                removed=False,
                warning="no reviewed cleanup adapter is installed",
            )
        return self.release_callback(artifact)

    def finalize(
        self,
        staged: StagedRevisionLease,
        finalization: FinalizationReceipt,
    ) -> CleanupReceipt:
        """Persist finalization and cleanup without folding cleanup into landing truth."""

        with self._lock:
            context = self._contexts.get(staged.transaction_id)
            if context is None or context.artifacts.staged is not staged:
                raise EnvironmentUnavailable("clone", "finalization context is not live")
            coordinator = CleanupCoordinator(
                receipt_store=context.coordinator.receipt_store,
                journal=context.coordinator.journal,
                process_capability=self._cleanup_capability,
                remove_artifact=lambda artifact: self._removeArtifact(
                    context,
                    artifact,
                ),
            )
            return coordinator.cleanup(
                transaction_id=staged.transaction_id,
                finalization=finalization,
                artifacts=self._cleanupArtifacts(context),
                process_capability=self._cleanup_capability,
            )

    def release(self, lease: CloneLease) -> None:
        # Teardown is deliberately non-destructive.  Artifact retirement happens
        # only through ``finalize`` after its immutable receipt is journal-bound.
        validateCloneLease(lease)


def buildInstalledTransactionalCloneKernel(
    *,
    parser_state_root: str | Path,
    snapshot_root: str | Path,
    verification_root: str | Path,
    expected_manifest_provider: ExpectedManifestProvider,
    quiescence_provider: QuiescenceProvider,
    commit_metadata_provider: CommitMetadataProvider,
    coordinator_factory: CoordinatorFactory,
    landing_authority_issuer: LandingAuthorityIssuer,
    run_admission: RunAdmissionAuthority,
    credential_absence_verifier: CredentialChannelAbsenceVerifier | None = None,
    release_callback: ReleaseCallback | None = None,
) -> TransactionalCloneKernel:
    """Build the production adapter only from installed signed artifacts."""

    qualification = loadInstalledKernelArtifacts()
    parser = ObjectParser(
        controller_root=parser_state_root,
        image=ObjectParserImage(
            repository=qualification.object_parser_repository,
            manifest_digest=qualification.object_parser_manifest_digest,
            role="object_parser",
        ),
        runtime_entrypoint=qualification.object_parser_entrypoint,
        docker_executable=str(qualification.docker_executable),
        docker_context=qualification.docker_context,
        artifact_qualification=qualification,
    )
    return TransactionalCloneKernel(
        parser=parser,
        snapshot_root=snapshot_root,
        verification_root=verification_root,
        expected_manifest_provider=expected_manifest_provider,
        quiescence_provider=quiescence_provider,
        commit_metadata_provider=commit_metadata_provider,
        coordinator_factory=coordinator_factory,
        release_callback=release_callback,
        artifact_qualification=qualification,
        landing_authority_issuer=landing_authority_issuer,
        run_admission=run_admission,
        credential_absence_verifier=credential_absence_verifier,
    )


class CloneEnvironment(ExecutionEnvironment):
    """One model attempt in a private clone with one staged landing authority."""

    NAME = "clone"
    CAPABILITIES = _CLONE_CAPABILITIES

    def __init__(
        self,
        *,
        clone_factory: CloneFactory | None = None,
        kernel: CloneLandingKernel | None = None,
        runner_kind: RunnerKind = RunnerKind.LOCAL,
        process_manager: RegisteredProcessManager | None = None,
    ) -> None:
        if not isinstance(runner_kind, RunnerKind):
            raise TypeError("runner_kind must be RunnerKind")
        self.clone_factory = clone_factory
        self.kernel = kernel
        self.runner_kind = runner_kind
        self.process_manager = process_manager

    def healthCheck(self) -> bool:
        return (
            callable(self.clone_factory)
            and self.kernel is not None
            and not (
                isinstance(self.kernel, TransactionalCloneKernel)
                and (
                    not self.kernel.productionReady()
                    or not isinstance(self.process_manager, RegisteredProcessManager)
                    or not self.process_manager.productionReady()
                )
            )
        )

    def handleFromLease(
        self,
        lease: CloneLease,
        base_dir: str,
        expected_target_revision: str | None = None,
    ) -> EnvHandle:
        if not os.path.isabs(base_dir):
            raise EnvironmentUnavailable(self.NAME, "base directory must be absolute")
        try:
            validateCloneLease(lease)
        except (TypeError, PrivateCloneRefused, OSError, ValueError) as exc:
            raise EnvironmentUnavailable(
                self.NAME,
                "private clone attestation failed",
                cause=exc,
            ) from exc
        if lease.runner_kind is not self.runner_kind:
            raise EnvironmentUnavailable(self.NAME, "clone runner kind differs")
        if (
            expected_target_revision is not None
            and expected_target_revision != lease.expected_base_revision
        ):
            raise EnvironmentUnavailable(self.NAME, "expected target revision differs")
        return EnvHandle(
            work_dir=lease.checkout_path,
            backend=self.NAME,
            meta={
                "transaction_id": lease.transaction_id,
                "task_id": lease.task_id,
                "subtask_id": lease.subtask_id,
                "attempt_id": lease.attempt_id,
                "candidate_branch": lease.candidate_branch,
                "base_dir": os.path.abspath(base_dir),
                "expected_revision": lease.expected_base_revision,
                "runner_kind": lease.runner_kind.value,
                "requested_backend": self.NAME,
                "effective_backend": "private-clone",
                "linked_worktree": False,
                "repository_id": lease.repository_id,
                "closure_manifest_digest": lease.closure_manifest_digest,
            },
            capabilities=self.CAPABILITIES,
            requires_canonical_landing=True,
            runtime_token=lease,
        )

    def provision(self, *, task_state, subtask, base_dir: str, policy) -> EnvHandle:
        if not callable(self.clone_factory) or self.kernel is None:
            raise EnvironmentUnavailable(
                self.NAME,
                "transactional clone factory and landing kernel are not installed",
            )
        if isinstance(self.kernel, TransactionalCloneKernel) and not self.kernel.productionReady():
            raise EnvironmentUnavailable(
                self.NAME,
                "transactional clone kernel has no installed artifact authority",
            )
        try:
            lease = self.clone_factory(
                task_state=task_state,
                subtask=subtask,
                base_dir=base_dir,
                policy=policy,
                runner_kind=self.runner_kind,
            )
        except EnvironmentUnavailable:
            raise
        except Exception as exc:
            raise EnvironmentUnavailable(
                self.NAME,
                "private clone provisioning failed",
                cause=exc,
            ) from exc
        if not isinstance(lease, CloneLease):
            raise EnvironmentUnavailable(
                self.NAME,
                "clone factory did not return a typed lease",
            )
        return self.handleFromLease(
            lease,
            base_dir,
            expected_target_revision=lease.expected_base_revision,
        )

    def _lease(self, handle: EnvHandle) -> CloneLease:
        lease = handle.runtime_token
        if not isinstance(lease, CloneLease):
            raise EnvironmentUnavailable(self.NAME, "handle has no live clone lease")
        validateCloneLease(lease)
        if handle.work_dir != lease.checkout_path:
            raise EnvironmentUnavailable(self.NAME, "handle checkout path differs")
        return lease

    def wrapLauncher(self, run_cmd: list, handle: EnvHandle) -> tuple[list, str]:
        if isinstance(self.kernel, TransactionalCloneKernel) and not self.kernel.productionReady():
            raise EnvironmentUnavailable(
                self.NAME,
                "transactional clone kernel artifact authority is unavailable",
            )
        self._lease(handle)
        return run_cmd, handle.work_dir

    def processLauncher(
        self,
        handle: EnvHandle,
        *,
        argv: list[str],
        cwd: str,
        environment: dict[str, str],
        creationflags: int,
    ) -> RegisteredProcessLauncher:
        """Return the one journal-bound model-driver launcher for this attempt."""

        lease = self._lease(handle)
        manager = self.process_manager
        if not isinstance(manager, RegisteredProcessManager):
            raise EnvironmentUnavailable(
                self.NAME,
                "controller-owned registered process manager is unavailable",
            )
        try:
            return manager.launcherFor(
                lease,
                argv=argv,
                cwd=cwd,
                environment=environment,
                creationflags=creationflags,
                security_profile_digest=manager.security_profile_digest,
            )
        except Exception as exc:
            raise EnvironmentUnavailable(
                self.NAME,
                "model-driver process registration failed",
                cause=exc,
            ) from exc

    def collectChanges(self, handle: EnvHandle, *, task_state, subtask) -> dict:
        del task_state, subtask
        lease = self._lease(handle)
        return {
            "backend": self.NAME,
            "transaction_id": lease.transaction_id,
            "merged": False,
            "staged_preparation_required": True,
            "canonical_mutation": False,
        }

    def prepareChanges(
        self,
        handle: EnvHandle,
        *,
        task_state,
        subtask,
    ) -> PreparedFinalization:
        lease = self._lease(handle)
        if self.kernel is None:
            return PreparedFinalization(
                backend=self.NAME,
                work_dir=handle.work_dir,
                accepted=False,
                error="staged preparation required but clone kernel is unavailable",
                summary={"artifact_preserved": True},
                runtime_token=lease,
            )
        try:
            artifacts = self.kernel.prepare(
                lease,
                task_state=task_state,
                subtask=subtask,
            )
        except Exception as exc:
            return PreparedFinalization(
                backend=self.NAME,
                work_dir=handle.work_dir,
                accepted=False,
                error=f"staged preparation failed: {exc}",
                summary={"artifact_preserved": True},
                runtime_token=lease,
            )
        staged = artifacts.staged
        if (
            staged.transaction_id != lease.transaction_id
            or staged.task_id != lease.task_id
            or staged.subtask_id != lease.subtask_id
            or staged.attempt_id != lease.attempt_id
            or staged.runner_kind is not lease.runner_kind
            or staged.expected_target_revision != lease.expected_base_revision
        ):
            return PreparedFinalization(
                backend=self.NAME,
                work_dir=handle.work_dir,
                accepted=False,
                error="staged preparation identity differs from clone lease",
                summary={"artifact_preserved": True},
                runtime_token=lease,
            )
        return PreparedFinalization(
            backend=self.NAME,
            work_dir=handle.work_dir,
            accepted=True,
            requires_revision_verification=True,
            proposed_revision=staged.proposed_revision,
            verification_dir=artifacts.verification_dir,
            verification_backend=artifacts.verification_backend,
            staged_ref=staged.staged_ref,
            candidate_snapshot_digest=staged.candidate_snapshot_digest,
            canonical_tree_manifest_digest=staged.parser_manifest_digest,
            staging_receipt_id=staged.staging_receipt_id,
            summary={
                "transaction_id": staged.transaction_id,
                "runner_kind": staged.runner_kind.value,
                "expected_revision": staged.expected_target_revision,
                "checkpoint_ref": staged.checkpoint_ref,
                "linked_worktree": False,
            },
            runtime_token=staged,
        )

    def preparedChangesIntact(self, prepared: PreparedFinalization) -> bool:
        staged = prepared.runtime_token
        return bool(
            prepared.accepted
            and isinstance(staged, StagedRevisionLease)
            and self.kernel is not None
            and self.kernel.intact(staged)
        )

    def _recordFinalization(
        self,
        staged: StagedRevisionLease,
        receipt: FinalizationReceipt,
    ) -> FinalizationReceipt:
        finalize = getattr(self.kernel, "finalize", None)
        if callable(finalize):
            try:
                finalize(staged, receipt)
            except Exception:
                # Landing truth is already immutable.  Recovery discovers the
                # missing finalization/cleanup journal axes and retries them.
                pass
        return receipt

    def completeChanges(
        self,
        prepared: PreparedFinalization,
        *,
        promote: bool,
        authorization: object | None = None,
        landing_authority: object | None = None,
    ) -> FinalizationReceipt:
        staged = prepared.runtime_token
        if (
            not prepared.accepted
            or not isinstance(staged, StagedRevisionLease)
            or self.kernel is None
        ):
            return FinalizationReceipt(
                backend=self.NAME,
                accepted=prepared.accepted,
                requires_canonical_landing=True,
                staging_receipt_id=prepared.staging_receipt_id,
                error=prepared.error or "staged completion is unavailable",
                summary={"artifact_preserved": True},
            )
        if not promote:
            result = self.kernel.reject(staged)
            finalization = FinalizationReceipt(
                backend=self.NAME,
                accepted=False,
                requires_canonical_landing=True,
                collected=True,
                merged=False,
                removed=result.removed,
                expected_revision=result.expected_revision,
                observed_revision=result.observed_revision,
                resulting_revision=result.resulting_revision,
                checkpoint_revision=result.checkpoint_revision,
                checkpoint_ref=result.checkpoint_ref,
                staging_receipt_id=staged.staging_receipt_id,
                journal_phase="rejected",
                error=result.error,
                cleanup_error=result.cleanup_error,
                summary={
                    "quarantine_ref": result.quarantine_ref,
                    "canonical_mutation": False,
                },
            )
            return self._recordFinalization(staged, finalization)
        if authorization is None or landing_authority is None:
            return FinalizationReceipt(
                backend=self.NAME,
                accepted=True,
                requires_canonical_landing=True,
                staging_receipt_id=staged.staging_receipt_id,
                error="authorization required for staged promotion",
                summary={"artifact_preserved": True},
            )
        try:
            auth = PromotionAuthorization.from_value(authorization)
            receipt = self.kernel.promote(
                staged,
                auth,
                landing_authority,
            )
        except Exception as exc:
            return FinalizationReceipt(
                backend=self.NAME,
                accepted=True,
                requires_canonical_landing=True,
                staging_receipt_id=staged.staging_receipt_id,
                error=f"staged completion failed: {exc}",
                summary={"artifact_preserved": True},
            )
        finalization = FinalizationReceipt(
            backend=self.NAME,
            accepted=True,
            requires_canonical_landing=True,
            collected=True,
            merged=True,
            removed=False,
            expected_revision=receipt.expected_revision,
            observed_revision=receipt.observed_revision,
            resulting_revision=receipt.resulting_revision,
            checkpoint_revision=staged.checkpoint_revision,
            checkpoint_ref=staged.checkpoint_ref,
            verification_revision=receipt.resulting_revision,
            promotion_transaction_id=receipt.transaction_id,
            staging_receipt_id=receipt.staging_receipt_id,
            verification_receipt_id=receipt.verification_receipt_id,
            review_receipt_id=receipt.review_receipt_id,
            selection_receipt_id=receipt.selection_receipt_id,
            promotion_receipt_id=receipt.receipt_id,
            materialized=True,
            journal_phase="promoted",
            summary={
                "staged_ref": staged.staged_ref,
                "intent_ref": receipt.intent_ref,
                "canonical_mutation": True,
            },
        )
        return self._recordFinalization(staged, finalization)

    def checkpointRecovery(self, handle: EnvHandle, *, task_state, subtask) -> dict:
        lease = self._lease(handle)
        if self.kernel is None:
            return {
                "available": False,
                "error": "recovery unavailable for clone environment",
                "artifact_preserved": True,
            }
        return self.kernel.checkpoint(
            lease,
            task_state=task_state,
            subtask=subtask,
        )

    def teardown(self, handle: EnvHandle) -> None:
        lease = handle.runtime_token
        if isinstance(lease, CloneLease) and self.kernel is not None:
            self.kernel.release(lease)


def buildInstalledCloneEnvironment(
    *,
    clone_factory: CloneFactory,
    attempt_journal: AttemptJournal,
    controller_scope_id: str,
    process_security_profile_digest: str,
    parser_state_root: str | Path,
    snapshot_root: str | Path,
    verification_root: str | Path,
    expected_manifest_provider: ExpectedManifestProvider,
    quiescence_provider: QuiescenceProvider,
    commit_metadata_provider: CommitMetadataProvider,
    coordinator_factory: CoordinatorFactory,
    landing_authority_issuer: LandingAuthorityIssuer,
    run_admission: RunAdmissionAuthority,
    credential_absence_verifier: CredentialChannelAbsenceVerifier | None = None,
    runner_kind: RunnerKind = RunnerKind.LOCAL,
    release_callback: ReleaseCallback | None = None,
) -> CloneEnvironment:
    """Compose one real router backend from the installed artifact authority."""

    if not callable(clone_factory):
        raise TypeError("clone_factory must be callable")
    kernel = buildInstalledTransactionalCloneKernel(
        parser_state_root=parser_state_root,
        snapshot_root=snapshot_root,
        verification_root=verification_root,
        expected_manifest_provider=expected_manifest_provider,
        quiescence_provider=quiescence_provider,
        commit_metadata_provider=commit_metadata_provider,
        coordinator_factory=coordinator_factory,
        landing_authority_issuer=landing_authority_issuer,
        run_admission=run_admission,
        credential_absence_verifier=credential_absence_verifier,
        release_callback=release_callback,
    )
    process_manager = buildInstalledRegisteredProcessManager(
        journal=attempt_journal,
        controller_scope_id=controller_scope_id,
        security_profile_digest=process_security_profile_digest,
        landing_authority_issuer=landing_authority_issuer,
        run_admission=run_admission,
    )
    environment = CloneEnvironment(
        clone_factory=clone_factory,
        kernel=kernel,
        runner_kind=runner_kind,
        process_manager=process_manager,
    )
    if not environment.healthCheck():
        raise EnvironmentUnavailable(
            "clone",
            "installed transactional clone composition is unhealthy",
        )
    return environment


