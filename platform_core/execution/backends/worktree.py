"""WorktreeEnvironment -- rung 1 isolation: a per-subtask git worktree (Epic 1's worktree seam).

BROWNFIELD ADAPTER: Epic 1 already landed ``platform_core/runtime/worktree.py``
(enterWorktree / collectChanges / exitWorktree / removeWorktree / isIsolated). This backend is a
thin adapter that expresses that same worktree through the fabric ABC -- it does NOT duplicate git
logic. provision -> enterWorktree; collectChanges -> exitWorktree(merge=True) (commit + merge back
+ remove on success, leave-intact on conflict); teardown -> removeWorktree (no-op if already gone).
Fail-open: a git error in the underlying module degrades to the shared tree (today's behavior).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  WorktreeEnvironment  -- A disjoint git worktree per subtask
DEPENDS-ON: config, platform_core.execution.environment, platform_core.runtime.worktree
SIDE-EFFECTS: runs git via platform_core.runtime.worktree; creates/removes worktrees under STATE_DIR
RUN/TEST: python -m pytest tests/execution/test_worktree.py
"""
from __future__ import annotations

import os
import shutil

import config
from platform_core.execution.environment import (
    Capability, EnvHandle, ExecutionEnvironment,
)
from platform_core.runtime import worktree as _wt

LOG = config.getLogger("execution.worktree")

_WT_CAPS = (Capability.FILE_RW | Capability.EXEC | Capability.NETWORK
            | Capability.SNAPSHOT | Capability.PERSISTENT)
# When the underlying module fails open to the shared tree there is no snapshot/isolation.
_SHARED_CAPS = (Capability.FILE_RW | Capability.EXEC
                | Capability.NETWORK | Capability.PERSISTENT)


class WorktreeEnvironment(ExecutionEnvironment):
    """A disjoint git worktree per subtask -- the parallel-safe isolation rung (Epic 1 adapter)."""
    NAME = "worktree"
    CAPABILITIES = _WT_CAPS

    def healthCheck(self) -> bool:
        return shutil.which("git") is not None

    def provision(self, *, task_state, subtask, base_dir: str, policy) -> EnvHandle:
        sid = (subtask or {}).get("subtask_id", "wt")
        task8 = str(getattr(task_state, "task_id", "task"))[:8] or "task"
        branch = f"wt/{task8}/{sid}"
        # Delegate to the landed Epic 1 seam (fail-open to the shared tree on any git error).
        work_dir = _wt.enterWorktree(task_state, sid)
        isolated = _wt.isIsolated(work_dir)
        if not isolated:
            LOG.warning("worktree provision for %s fell open to shared tree %s", sid, work_dir)
        return EnvHandle(
            work_dir=work_dir, backend=self.NAME,
            meta={"branch": branch, "base_dir": base_dir, "sid": sid, "isolated": isolated},
            capabilities=self.CAPABILITIES if isolated else _SHARED_CAPS,
            requires_canonical_landing=True,
        )

    def wrapLauncher(self, run_cmd: list, handle: EnvHandle) -> "tuple[list, str]":
        return run_cmd, handle.work_dir     # native process, isolated cwd

    def collectChanges(self, handle: EnvHandle, *, task_state, subtask) -> dict:
        """Commit + merge the worktree branch back via exitWorktree(merge=True), then it removes the
        worktree on success. On a merge conflict the underlying seam leaves the worktree intact;
        we report merged=False so no edits are ever silently lost."""
        branch = handle.meta.get("branch", "")
        if not handle.meta.get("isolated", True):
            return {"backend": self.NAME, "merged": False, "branch": branch,
                    "note": "shared tree (no isolation); nothing to merge"}
        _wt.exitWorktree(handle.work_dir, merge=True)
        merged = not os.path.isdir(handle.work_dir)   # exitWorktree removes only after a clean merge
        if not merged:
            LOG.warning("worktree merge of %s left intact (conflict)", branch)
            return {"backend": self.NAME, "merged": False, "branch": branch, "left_intact": True}
        return {"backend": self.NAME, "merged": True, "branch": branch}

    def teardown(self, handle: EnvHandle) -> None:
        # collectChanges already removed the worktree on success; this is the best-effort sweep
        # for the failure/skip paths. removeWorktree refuses any path outside STATE_DIR/.sc-worktrees.
        if os.path.isdir(handle.work_dir):
            _wt.removeWorktree(handle.work_dir)
