"""Compatibility facade for the retired linked-worktree backend preference.

Requesting ``worktree`` now selects the transactional private-clone implementation.
The facade reports requested-versus-effective truth and never provisions, merges, or
removes a linked Git worktree.  Missing clone-kernel wiring is typed-unavailable.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  WorktreeEnvironment  -- Historical backend name backed exclusively by ``CloneEnvironment``.
DEPENDS-ON: platform_core.execution.backends, platform_core.execution.environment
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_worktree.py
"""
from __future__ import annotations

from dataclasses import replace

from platform_core.execution.backends.clone import CloneEnvironment
from platform_core.execution.environment import (
    EnvHandle,
    ExecutionEnvironment,
    FinalizationReceipt,
    PreparedFinalization,
)


class WorktreeEnvironment(ExecutionEnvironment):
    """Historical backend name backed exclusively by ``CloneEnvironment``."""

    NAME = "worktree"
    CAPABILITIES = CloneEnvironment.CAPABILITIES

    def __init__(self, clone_environment: CloneEnvironment | None = None) -> None:
        self.clone_environment = clone_environment or CloneEnvironment()

    def healthCheck(self) -> bool:
        return self.clone_environment.healthCheck()

    @staticmethod
    def _facadeHandle(handle: EnvHandle) -> EnvHandle:
        meta = dict(handle.meta)
        meta.update(
            requested_backend="worktree",
            effective_backend="private-clone",
            linked_worktree=False,
        )
        return EnvHandle(
            work_dir=handle.work_dir,
            backend="worktree",
            meta=meta,
            capabilities=handle.capabilities,
            requires_canonical_landing=True,
            runtime_token=handle.runtime_token,
        )

    @staticmethod
    def _cloneHandle(handle: EnvHandle) -> EnvHandle:
        return EnvHandle(
            work_dir=handle.work_dir,
            backend="clone",
            meta=dict(handle.meta),
            capabilities=handle.capabilities,
            requires_canonical_landing=True,
            runtime_token=handle.runtime_token,
        )

    def provision(self, *, task_state, subtask, base_dir: str, policy) -> EnvHandle:
        handle = self.clone_environment.provision(
            task_state=task_state,
            subtask=subtask,
            base_dir=base_dir,
            policy=policy,
        )
        return self._facadeHandle(handle)

    def wrapLauncher(self, run_cmd: list, handle: EnvHandle) -> tuple[list, str]:
        return self.clone_environment.wrapLauncher(
            run_cmd,
            self._cloneHandle(handle),
        )

    def collectChanges(self, handle: EnvHandle, *, task_state, subtask) -> dict:
        summary = self.clone_environment.collectChanges(
            self._cloneHandle(handle),
            task_state=task_state,
            subtask=subtask,
        )
        return {
            **summary,
            "backend": self.NAME,
            "requested_backend": self.NAME,
            "effective_backend": "private-clone",
            "linked_worktree": False,
        }

    def prepareChanges(
        self,
        handle: EnvHandle,
        *,
        task_state,
        subtask,
    ) -> PreparedFinalization:
        prepared = self.clone_environment.prepareChanges(
            self._cloneHandle(handle),
            task_state=task_state,
            subtask=subtask,
        )
        return replace(
            prepared,
            backend=self.NAME,
            summary={
                **prepared.summary,
                "requested_backend": self.NAME,
                "effective_backend": "private-clone",
                "linked_worktree": False,
            },
        )

    def preparedChangesIntact(self, prepared: PreparedFinalization) -> bool:
        return self.clone_environment.preparedChangesIntact(
            replace(prepared, backend="clone")
        )

    def completeChanges(
        self,
        prepared: PreparedFinalization,
        *,
        promote: bool,
        authorization: object | None = None,
        landing_authority: object | None = None,
    ) -> FinalizationReceipt:
        receipt = self.clone_environment.completeChanges(
            replace(prepared, backend="clone"),
            promote=promote,
            authorization=authorization,
            landing_authority=landing_authority,
        )
        return replace(
            receipt,
            backend=self.NAME,
            summary={
                **receipt.summary,
                "requested_backend": self.NAME,
                "effective_backend": "private-clone",
                "linked_worktree": False,
            },
        )

    def checkpointRecovery(self, handle: EnvHandle, *, task_state, subtask) -> dict:
        result = self.clone_environment.checkpointRecovery(
            self._cloneHandle(handle),
            task_state=task_state,
            subtask=subtask,
        )
        return {
            **result,
            "requested_backend": self.NAME,
            "effective_backend": "private-clone",
            "linked_worktree": False,
        }

    def teardown(self, handle: EnvHandle) -> None:
        self.clone_environment.teardown(self._cloneHandle(handle))


__all__ = ["WorktreeEnvironment"]
