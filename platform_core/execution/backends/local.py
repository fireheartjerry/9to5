"""LocalEnvironment -- the explicitly trusted, unconfined host backend.

This backend cannot establish its own eligibility.  The external process-local trust
authority and execution router must approve it before provisioning; the handle records
only the honest negative confinement fact ``os_enforced=False``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  LocalEnvironment  -- The host, the real tree
DEPENDS-ON: platform_core.execution.environment
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_execution_local.py
"""
from __future__ import annotations

from platform_core.execution.environment import (
    Capability,
    EnvHandle,
    ExecutionEnvironment,
)

_LOCAL_CAPS = (Capability.FILE_RW | Capability.EXEC
               | Capability.NETWORK | Capability.PERSISTENT)


class LocalEnvironment(ExecutionEnvironment):
    """The host, the real tree -- no OS confinement and no self-issued eligibility."""
    NAME = "local"
    CAPABILITIES = _LOCAL_CAPS
    OS_ENFORCED = False
    REQUIRES_EXTERNAL_TRUST = True

    def provision(self, *, task_state, subtask, base_dir: str, policy) -> EnvHandle:
        return EnvHandle(
            work_dir=base_dir,
            backend=self.NAME,
            meta={
                "os_enforced": self.OS_ENFORCED,
                "trust_authority": "external_required",
            },
            capabilities=self.CAPABILITIES,
        )

    def wrapLauncher(self, run_cmd: list, handle: EnvHandle) -> "tuple[list, str]":
        return run_cmd, handle.work_dir          # identity

    def collectChanges(self, handle: EnvHandle, *, task_state, subtask) -> dict:
        return {"backend": "local", "merged": False, "note": "identity (no isolation)"}

    def teardown(self, handle: EnvHandle) -> None:
        return None

    def healthCheck(self) -> bool:
        return True
