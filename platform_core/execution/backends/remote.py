"""RemoteEnvironment -- rung 3 (future scale): ssh / modal / daytona / E2B sub-strategies.

One module, sub-strategies keyed by config.EXECUTION_REMOTE_KIND. Shipped as ABC-conformant stubs
that DEGRADE CLEANLY: healthCheck returns False when no host/SDK is present so the router falls
back to local (exactly like browser_executor without Playwright). OPT-IN and OFF by default:
default config selects local; remote is only reached when explicitly enabled. NO paid SDK is a hard
dependency -- the SDK-backed kinds (modal/daytona/e2b) import-guard inside `_run_remote` and raise a
clear NotImplementedError until wired, which healthCheck catches -> local fallback. Every transport
call routes through the one mockable `_run_remote` seam so CI never reaches the network.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  RemoteEnvironment  -- A remote box/microVM per subtask
DEPENDS-ON: config, platform_core.execution, platform_core.execution.environment, platform_core.execution.security
SIDE-EFFECTS: runs `ssh` / remote SDKs (behind _run_remote)
RUN/TEST: python -m pytest tests/execution/test_execution_remote.py
"""
from __future__ import annotations

import re
import shlex
import subprocess

import config
from platform_core.execution.environment import (
    Capability,
    EnvHandle,
    ExecutionEnvironment,
)
from platform_core.execution.sandbox_broker import runLegacyProcess
from platform_core.execution.security import MountSecurityError

LOG = config.getLogger("execution.remote")

# Ephemeral remote tree (no PERSISTENT): torn down after the subtask.
_REMOTE_CAPS = Capability.FILE_RW | Capability.EXEC | Capability.NETWORK

# subtask_id is planner-authored (LLM) free text, never validated as a slug anywhere upstream.
# `ssh host <argv...>` flattens argv into ONE string the remote shell re-parses, so an
# unsanitized sid embedded in mkdir/cd/rm-rf commands is a remote command-injection vector.
_SAFE_SID_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


def _safeSid(subtask: "dict | None") -> str:
    sid = str((subtask or {}).get("subtask_id") or "wt")
    if not _SAFE_SID_RE.match(sid):
        raise ValueError(f"unsafe subtask_id for remote provisioning: {sid!r}")
    return sid


def _run_remote(args: list, *, timeout: "int | None" = None) -> subprocess.CompletedProcess:
    """The single mockable remote-transport seam (ssh today; SDK kinds raise until implemented).

    Paid SDKs (modal/daytona/e2b) are intentionally NOT a core dependency; they raise here so
    healthCheck degrades to local with zero surprise cost until an operator wires them in.
    Every argument is shlex-quoted (defense-in-depth alongside _safeSid's allowlist): ssh hands
    the flattened argv to the remote shell for re-parsing, so any element could otherwise be
    reinterpreted as shell syntax rather than a literal argument."""
    kind = config.EXECUTION_REMOTE_KIND
    if kind != "ssh":
        raise NotImplementedError(f"remote kind {kind!r} SDK not wired yet")
    host, *rest = args
    quoted = " ".join(shlex.quote(a) for a in rest)
    return runLegacyProcess(["ssh", host, quoted], capture_output=True, text=True,
                            timeout=timeout or config.EXECUTION_PROVISION_TIMEOUT_SECONDS)


class RemoteEnvironment(ExecutionEnvironment):
    """A remote box/microVM per subtask -- the cloud-scale rung (opt-in, budget-gated)."""
    NAME = "remote"
    CAPABILITIES = _REMOTE_CAPS

    def healthCheck(self) -> bool:
        host = config.EXECUTION_REMOTE_HOST
        if not host:
            return False
        try:
            return _run_remote([host, "true"]).returncode == 0
        except Exception as e:  # noqa: BLE001 -- no host/SDK -> degrade to local
            LOG.warning("remote healthCheck failed (%s) -> local", e)
            return False

    def provision(self, *, task_state, subtask, base_dir: str, policy) -> EnvHandle:
        # Router.provision() catches any exception here and falls back to LocalEnvironment
        # (platform_core/execution/router.py) -- raising on an unsafe sid or a disallowed
        # network policy degrades cleanly rather than silently under-enforcing either.
        if policy is not None and not policy.network:
            raise MountSecurityError(
                "remote backend cannot enforce a network=False capability policy "
                "(no host-side firewalling wired for any EXECUTION_REMOTE_KIND)")
        host = config.EXECUTION_REMOTE_HOST
        sid = _safeSid(subtask)
        remote_work = f"/tmp/9to5-{sid}"
        _run_remote([host, "mkdir", "-p", remote_work])
        # NOTE: secrets never sync here (validateMounts/openclaw threat model); creds stay host-side.
        # work_dir is the LOCAL anchor cwd for the ssh client subprocess (mirrors docker.py/
        # local.py, which both set work_dir=base_dir) -- NOT the remote path, which lives only
        # in meta. Previously this was set to remote_work, a path that doesn't exist on the
        # local filesystem; every attempt's local `subprocess.Popen(..., cwd=work_dir)` then
        # failed immediately, defeating the "fabric never blocks a run" fallback guarantee
        # (the exception surfaces AFTER provision() already returned successfully, so the
        # router's own try/except never catches it).
        return EnvHandle(work_dir=base_dir, backend=self.NAME,
                         meta={"host": host, "kind": config.EXECUTION_REMOTE_KIND,
                               "remote_work": remote_work, "base_dir": base_dir},
                         capabilities=self.CAPABILITIES,
                         requires_canonical_landing=True)

    def wrapLauncher(self, run_cmd: list, handle: EnvHandle) -> "tuple[list, str]":
        host = handle.meta["host"]
        remote_work = handle.meta["remote_work"]
        # ssh flattens all argv elements after the host into ONE string for the remote shell to
        # re-parse -- shlex-quote each piece so an element of run_cmd (e.g. a prompt fragment
        # with spaces/quotes) can't be reinterpreted as additional shell syntax.
        remote_cmd = "cd " + shlex.quote(remote_work) + " && " + \
            " ".join(shlex.quote(a) for a in run_cmd)
        return ["ssh", host, remote_cmd], handle.work_dir

    def collectChanges(self, handle: EnvHandle, *, task_state, subtask) -> dict:
        """Archive the remote tree back (git-bundle/rsync). Stub records intent; never loses work."""
        return {"backend": self.NAME, "merged": False,
                "note": f"remote {handle.meta.get('kind')} collect not wired; tree left on host",
                "host": handle.meta.get("host")}

    def teardown(self, handle: EnvHandle) -> None:
        try:
            _run_remote([handle.meta["host"], "rm", "-rf", handle.meta["remote_work"]])
        except Exception as e:  # noqa: BLE001 -- best-effort
            LOG.warning("remote teardown failed: %s", e)
