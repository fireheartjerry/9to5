"""Orchestration glue that wraps a subtask's attempt loop in an ExecutionEnvironment lifecycle.

Keeps OrchestratorExecuteMixin thin: the fabric provision/finalize/route logic lives in the
execution package (plan's locked file structure). Fabric OFF => LocalEnvironment => identity in
every method => the attempt loop runs byte-for-byte against today's tree and command.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  envHandsKw(hands, run_claude_fn, environment, env_handle) -> dict  -- Executor kwargs that route the run INTO the provisioned environment.
  provisionForSubtask(state, subtask, exec_cwd: str)  -- Select + provision the per-subtask environment (default local)
  finalizeQuietly(env, handle, state, subtask, sid, log) -> None  -- Bring the env's work back to the canonical tree + tear it down
DEPENDS-ON: platform_core.execution, platform_core.orchestration
SIDE-EFFECTS: emits env_* events via router (best-effort)
RUN/TEST: python -m pytest tests/execution/test_resume_wiring.py tests/orchestration/test_dual_ledger_wiring.py tests/orchestration/test_execute_mixin_fork_wiring.py
"""
from __future__ import annotations

from platform_core.execution import router as _env_router


def envHandsKw(hands, run_claude_fn, environment, env_handle) -> dict:
    """Executor kwargs that route the run INTO the provisioned environment.
    Only the Claude-CLI hands path takes an environment -- browser/native surfaces are API/UIA,
    not sandboxable shells -- mirroring how `feed` is attached only on the _run_claude path."""
    if environment is not None and env_handle is not None and hands is run_claude_fn:
        return {"environment": environment, "env_handle": env_handle}
    return {}


def provisionForSubtask(state, subtask, exec_cwd: str):
    """Select + provision the per-subtask environment (default local). Returns
    (env, handle, env_ctx, work_dir); the loop + verify run against work_dir."""
    spec = subtask.get("session", {}) or {}
    try:
        from platform_core.orchestration import work_profile
        pol = work_profile.policy_from_state(state)
        if pol.execution_environment_preference in ("worktree", "isolated"):
            spec = {**spec, "execution_backend": "worktree"}
    except Exception:  # noqa: BLE001
        pass
    env = _env_router.selectEnvironment(spec, subtask, state)
    env, handle = _env_router.provision(
        env, task_state=state, subtask=subtask, base_dir=exec_cwd,
        policy=(getattr(state, "meta", {}) or {}).get("run_intent_policy"))
    return env, handle, (env, handle), handle.work_dir


def finalizeQuietly(env, handle, state, subtask, sid, log) -> None:
    """Bring the env's work back to the canonical tree + tear it down. Best-effort: a finalize
    hiccup never changes the already-committed subtask status."""
    try:
        _env_router.finalize(env, handle, state, subtask)
    except Exception:  # noqa: BLE001 -- finalize is best-effort; committed status stands
        log.warning("execution-env finalize for %s failed", sid, exc_info=True)
