"""ExecutionEnvironment ABC + Capability flags + EnvHandle for the cloud execution fabric.

Modeled on hermes `BaseEnvironment` and 9TO5's pluggable-surface convention
(agents/browser_executor.runBrowser, agents/native_executor.runNative). The unit of work is
ONE whole Claude CLI invocation, so the environment wraps the LAUNCH of run_cmd, not a bash line.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  EnvironmentUnavailable  -- Typed refusal for an unavailable or unauthorized execution backend.
  Capability  -- What a backend's provisioned environment can do (bernstein frozenset[SandboxCapability]…
  EnvHandle  -- Opaque per-subtask provision result reused across a subtask's attempts.
  FinalizationOutcome
  PreparedFinalization
  FinalizationReceipt
  ExecutionContext
  ExecutionEnvironment  -- Where a subtask's Claude CLI process runs and which tree it touches.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_execution_environment.py
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import asdict, dataclass, field
from enum import Enum, Flag, auto
from typing import Any


class EnvironmentUnavailable(RuntimeError):
    """Typed refusal for an unavailable or unauthorized execution backend."""

    def __init__(
        self,
        backend: str,
        reason: str,
        *,
        cause: BaseException | None = None,
    ) -> None:
        self.backend = backend
        self.reason = reason
        self.cause = cause
        message = f"execution backend {backend!r} unavailable: {reason}"
        super().__init__(message)


class Capability(Flag):
    """What a backend's provisioned environment can do (bernstein frozenset[SandboxCapability])."""
    FILE_RW = auto()
    EXEC = auto()
    NETWORK = auto()
    SNAPSHOT = auto()      # can checkpoint/rollback the tree
    PERSISTENT = auto()    # tree survives teardown (local/worktree) vs ephemeral (docker/remote)


@dataclass
class EnvHandle:
    """Opaque per-subtask provision result reused across a subtask's attempts."""
    work_dir: str                 # the exec_cwd the executor runs against
    backend: str                  # "local" | "worktree" | "docker" | "remote"
    meta: dict = field(default_factory=dict)   # container id / branch / ssh host / base_dir
    capabilities: Capability = Capability(0)
    requires_canonical_landing: bool = False
    runtime_token: object | None = field(default=None, repr=False, compare=False)

    def toDict(self) -> dict[str, Any]:
        return {
            "work_dir": self.work_dir,
            "backend": self.backend,
            "meta": _json_safe(self.meta),
            "capabilities": [
                capability.name
                for capability in Capability
                if capability in self.capabilities
            ],
            "requires_canonical_landing": self.requires_canonical_landing,
        }


class FinalizationOutcome(Enum):
    SUCCEEDED = "succeeded"
    REJECTED = "rejected"
    STAGED_PREPARATION_REQUIRED = "staged_preparation_required"
    RECOVERY_UNAVAILABLE = "recovery_unavailable"
    AUTHORIZATION_REQUIRED = "authorization_required"
    PREPARATION_FAILED = "preparation_failed"
    COMPLETION_FAILED = "completion_failed"


def _json_safe(value: Any) -> Any:
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, Capability):
        return [item.name for item in Capability if item in value]
    if isinstance(value, dict):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(item) for item in value]
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    raise TypeError(f"runtime-only value is not JSON-safe: {type(value).__name__}")


@dataclass(frozen=True)
class PreparedFinalization:
    backend: str = ""
    work_dir: str = ""
    accepted: bool = False
    requires_revision_verification: bool = False
    proposed_revision: str = ""
    verification_dir: str = ""
    verification_backend: str = ""
    staged_ref: str = ""
    candidate_snapshot_digest: str = ""
    canonical_tree_manifest_digest: str = ""
    staging_receipt_id: str = ""
    error: str = ""
    summary: dict[str, Any] = field(default_factory=dict)
    runtime_token: object | None = field(
        default=None, repr=False, compare=False
    )

    def toDict(self) -> dict[str, Any]:
        values = asdict(self)
        values.pop("runtime_token", None)
        return _json_safe(values)


@dataclass(frozen=True)
class FinalizationReceipt:
    backend: str = ""
    accepted: bool = False
    requires_canonical_landing: bool = False
    collected: bool = False
    merged: bool = False
    removed: bool = False
    expected_revision: str = ""
    observed_revision: str = ""
    resulting_revision: str = ""
    checkpoint_revision: str = ""
    checkpoint_ref: str = ""
    verification_revision: str = ""
    promotion_transaction_id: str = ""
    execution_receipt_id: str = ""
    staging_receipt_id: str = ""
    verification_receipt_id: str = ""
    review_receipt_id: str = ""
    selection_receipt_id: str = ""
    promotion_receipt_id: str = ""
    materialized: bool = False
    journal_phase: str = ""
    error: str = ""
    cleanup_error: str = ""
    summary: dict[str, Any] = field(default_factory=dict)

    @property
    def succeeded(self) -> bool:
        if not self.accepted or self.error:
            return False
        if not self.requires_canonical_landing:
            return self.collected
        return bool(
            self.collected
            and self.merged
            and self.materialized
            and self.resulting_revision
            and self.verification_revision == self.resulting_revision
            and self.promotion_receipt_id
            and self.journal_phase == "promoted"
        )

    @property
    def outcome(self) -> FinalizationOutcome:
        lowered = self.error.lower()
        if "staged preparation required" in lowered:
            return FinalizationOutcome.STAGED_PREPARATION_REQUIRED
        if "recovery unavailable" in lowered:
            return FinalizationOutcome.RECOVERY_UNAVAILABLE
        if "authorization required" in lowered:
            return FinalizationOutcome.AUTHORIZATION_REQUIRED
        if self.succeeded:
            return FinalizationOutcome.SUCCEEDED
        if not self.accepted:
            return FinalizationOutcome.REJECTED
        return FinalizationOutcome.COMPLETION_FAILED

    def toDict(self) -> dict[str, Any]:
        return _json_safe(asdict(self))


@dataclass(frozen=True)
class ExecutionContext:
    landing_environment: object
    landing_handle: EnvHandle
    execution_environment: object
    execution_handle: EnvHandle
    runtime_resources: tuple[object, ...]
    verification_environment: object | None
    verification_handle: EnvHandle | None
    work_dir: str = field(metadata={"frozen_scope": True})
    read_only: bool = field(metadata={"frozen_scope": True})


class ExecutionEnvironment(ABC):
    """Where a subtask's Claude CLI process runs and which tree it touches."""
    NAME: str = "base"
    CAPABILITIES: Capability = Capability(0)

    @abstractmethod
    def provision(self, *, task_state, subtask, base_dir: str, policy) -> EnvHandle:
        """Stand up the environment for one subtask; return an EnvHandle (reused across attempts)."""

    @abstractmethod
    def wrapLauncher(self, run_cmd: list, handle: EnvHandle) -> "tuple[list, str]":
        """Transform (run_cmd, work_dir) so the Claude CLI runs INSIDE the env.
        local: identity. docker: prefix `docker exec -w <cdir> <cid> ...`. remote: `ssh host ...`."""

    @abstractmethod
    def collectChanges(self, handle: EnvHandle, *, task_state, subtask) -> dict:
        """Bring work back to the canonical tree; return a trajectory summary. NEVER silently lose edits."""

    @abstractmethod
    def teardown(self, handle: EnvHandle) -> None:
        """Best-effort cleanup (worktree remove / docker rm -f / ssh close)."""

    def healthCheck(self) -> bool:
        """Default True; docker/remote probe reachability so the router can degrade to local."""
        return True

    def prepareChanges(
        self, handle: EnvHandle, *, task_state, subtask
    ) -> PreparedFinalization:
        del task_state, subtask
        return PreparedFinalization(
            backend=self.NAME,
            work_dir=handle.work_dir,
            accepted=False,
            error="staged landing preparation is unsupported",
            summary={"artifact_preserved": True},
            runtime_token=handle.runtime_token,
        )

    def preparedChangesIntact(self, prepared: PreparedFinalization) -> bool:
        del prepared
        return False

    def completeChanges(
        self,
        prepared: PreparedFinalization,
        *,
        promote: bool,
        authorization: object | None = None,
        landing_authority: object | None = None,
    ) -> FinalizationReceipt:
        del promote, authorization, landing_authority
        return FinalizationReceipt(
            backend=self.NAME,
            accepted=prepared.accepted,
            requires_canonical_landing=True,
            staging_receipt_id=prepared.staging_receipt_id,
            error="staged completion is unsupported",
            summary={"artifact_preserved": True},
        )

    def checkpointRecovery(self, handle: EnvHandle, *, task_state, subtask) -> dict:
        del handle, task_state, subtask
        return {
            "available": False,
            "error": "recovery unavailable for this environment",
            "artifact_preserved": True,
        }
