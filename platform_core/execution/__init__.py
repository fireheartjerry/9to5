def __getattr__(name: str) -> Any:
    """Resolve compatibility exports without contaminating capsule bootstrap."""

    if name in _ENVIRONMENT_EXPORTS:
        module = importlib.import_module("platform_core.execution.environment")
    elif name in _ROUTER_EXPORTS:
        module = importlib.import_module("platform_core.execution.router")
    else:
        raise AttributeError(
            f"module 'platform_core.execution' has no attribute {name!r}"
        )
    value = getattr(module, name)
    globals()[name] = value
    return value


def __dir__() -> list[str]:
    return sorted(set(globals()) | set(__all__))

