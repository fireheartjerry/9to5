"""Sole neutral subprocess boundary for provider diagnostics.

Only version and authentication-status probes are accepted.  The process gets
no prompt, stdin, repository cwd, project discovery, or ambient secret-bearing
environment.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  InvalidProviderProbe  -- The requested operation is outside the closed diagnostic protocol.
  ProviderProbe
  ProviderProbeResult
  runProviderProbe(probe: ProviderProbe, *, executable: Sequence[str] | None=None, inherited_env: Mapping[str, str] | None=None, runner: Callable[..., object] | None=None) -> ProviderProbeResult  -- Run one bounded diagnostic from an empty directory and closed environment.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_provider_probe.py
"""
from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
from typing import Callable, Mapping, Sequence


_OUTPUT_LIMIT = 16 * 1024
_TIMEOUT_SECONDS = 15


class InvalidProviderProbe(ValueError):
    """The requested operation is outside the closed diagnostic protocol."""


class ProviderProbe(Enum):
    CLAUDE_VERSION = "claude_version"
    CLAUDE_AUTH_STATUS = "claude_auth_status"


@dataclass(frozen=True)
class ProviderProbeResult:
    probe: ProviderProbe
    argv: tuple[str, ...]
    returncode: int
    stdout: str
    stderr: str
    working_directory: str
    prompt_bytes_sent: int = 0

    @property
    def ok(self) -> bool:
        return self.returncode == 0


def _resolved_executable(executable: Sequence[str] | None) -> list[str]:
    if executable is None:
        resolved = shutil.which("claude")
        if not resolved:
            raise FileNotFoundError("Claude diagnostic executable is unavailable")
        command = [str(Path(resolved).resolve(strict=True))]
    else:
        if isinstance(executable, (str, bytes)) or not executable:
            raise InvalidProviderProbe("diagnostic executable must be a non-empty argv prefix")
        command = list(executable)
        if any(not isinstance(item, str) or not item for item in command):
            raise InvalidProviderProbe("diagnostic executable argv contains an invalid item")
        first = Path(command[0])
        if not first.is_absolute() or not first.is_file():
            raise InvalidProviderProbe("diagnostic executable must be an absolute ordinary file")
        command[0] = str(first.resolve(strict=True))
    return command


def _closed_environment(cwd: str) -> dict[str, str]:
    environment = {
        "CLAUDE_CODE_DISABLE_PROJECT_DISCOVERY": "1",
        "CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC": "1",
        "NO_COLOR": "1",
        "TERM": "dumb",
        "TEMP": cwd,
        "TMP": cwd,
    }
    # Only OS-loader and installed-provider identity paths cross this boundary.
    for key in (
        "SystemRoot",
        "WINDIR",
        "COMSPEC",
        "PATHEXT",
        "USERPROFILE",
        "APPDATA",
        "LOCALAPPDATA",
    ):
        value = os.environ.get(key)
        if value:
            environment[key] = value
    return environment


def runProviderProbe(
    probe: ProviderProbe,
    *,
    executable: Sequence[str] | None = None,
    inherited_env: Mapping[str, str] | None = None,
    runner: Callable[..., object] | None = None,
) -> ProviderProbeResult:
    """Run one bounded diagnostic from an empty directory and closed environment."""
    del inherited_env  # Ambient/caller environment is deliberately never inherited.
    if type(probe) is not ProviderProbe:
        raise InvalidProviderProbe("provider diagnostics accept only the closed probe enum")
    prefix = _resolved_executable(executable)
    suffix = (
        ["--version"]
        if probe is ProviderProbe.CLAUDE_VERSION
        else ["auth", "status"]
    )
    argv = [*prefix, *suffix]
    invoke = runner or subprocess.run
    with tempfile.TemporaryDirectory(prefix="galaxy-provider-probe-") as cwd:
        completed = invoke(
            args=argv,
            shell=False,
            cwd=cwd,
            env=_closed_environment(cwd),
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=_TIMEOUT_SECONDS,
            check=False,
        )
        returncode = getattr(completed, "returncode", None)
        if type(returncode) is not int:
            raise InvalidProviderProbe("diagnostic runner returned an invalid result")
        stdout = str(getattr(completed, "stdout", "") or "")[:_OUTPUT_LIMIT]
        stderr = str(getattr(completed, "stderr", "") or "")[:_OUTPUT_LIMIT]
        return ProviderProbeResult(
            probe=probe,
            argv=tuple(argv),
            returncode=returncode,
            stdout=stdout,
            stderr=stderr,
            working_directory=cwd,
            prompt_bytes_sent=0,
        )


