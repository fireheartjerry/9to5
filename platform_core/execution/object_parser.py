@dataclass(frozen=True, kw_only=True)
class ObjectParserImage:
    repository: str
    manifest_digest: str
    role: str

    def __post_init__(self) -> None:
        if (
            not isinstance(self.repository, str)
            or _REPOSITORY_RE.fullmatch(self.repository) is None
            or ".." in self.repository.split("/")
        ):
            raise ValueError("image repository is malformed")
        _requireDigest(self.manifest_digest, "manifest_digest")
        if self.role != "object_parser":
            raise ValueError("image role must be object_parser")

    @property
    def reference(self) -> str:
        return f"{self.repository}@sha256:{self.manifest_digest}"


