@dataclass(frozen=True, kw_only=True)
class LooseObjectProof:
    transaction_id: str
    object_record: ObjectRecord
    raw_sha256: str
    parser_image_digest: str
    parser_version_digest: str
    parser_security_profile_digest: str
    receipt_id: str
    raw_result: bytes
    container_network_allowed: bool

    def __post_init__(self) -> None:
        if not isinstance(self.object_record, ObjectRecord):
            raise TypeError("loose-object proof requires an ObjectRecord")
        for name in (
            "raw_sha256",
            "parser_image_digest",
            "parser_version_digest",
            "parser_security_profile_digest",
            "receipt_id",
        ):
            _requireDigest(getattr(self, name), name)
        if self.container_network_allowed is not False:
            raise ValueError("loose-object proof networking must remain disabled")


def _objectRecordFromDict(value: object) -> ObjectRecord:
    if not isinstance(value, dict) or set(value) != {
        "object_type",
        "oid",
        "payload_sha256",
        "framed_object_sha256",
        "size",
    }:
        raise ObjectParserRefused("source object record fields are not closed")
    try:
        return ObjectRecord(**value)
    except (TypeError, ValueError) as exc:
        raise ObjectParserRefused("source object record violates its contract") from exc


def _rejectDuplicatePairs(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise ObjectParserRefused("parser result contains a duplicate key")
        result[key] = value
    return result


def _strictResult(raw: bytes) -> dict[str, object]:
    if not raw or len(raw) > _MAX_OUTPUT_BYTES or not raw.endswith(b"\n"):
        raise ObjectParserRefused("parser result framing is invalid")
    canonical = raw[:-1]
    if b"\n" in canonical:
        raise ObjectParserRefused("parser emitted more than one result record")
    try:
        value = json.loads(
            canonical.decode("utf-8", errors="strict"),
            object_pairs_hook=_rejectDuplicatePairs,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ObjectParserRefused("parser result is not strict JSON") from exc
    if not isinstance(value, dict) or canonical_json_bytes(value) != canonical:
        raise ObjectParserRefused("parser result is not canonical JSON")
    return value


def _manifestFromDict(value: object) -> ObjectManifest:
    if not isinstance(value, dict) or set(value) != {
        "expected_revision",
        "entries",
        "attribute_rules",
        "policy",
    }:
        raise ObjectParserRefused("proposed manifest fields are not closed")
    policy_value = value["policy"]
    entries_value = value["entries"]
    rules_value = value["attribute_rules"]
    if not isinstance(policy_value, dict) or not isinstance(entries_value, list) or not isinstance(
        rules_value, list
    ):
        raise ObjectParserRefused("proposed manifest collections are malformed")
    try:
        policy = ManifestPolicy(
            reserved_roots=tuple(policy_value["reserved_roots"]),
            max_files=policy_value["max_files"],
            max_total_bytes=policy_value["max_total_bytes"],
            max_file_bytes=policy_value["max_file_bytes"],
            max_depth=policy_value["max_depth"],
            max_path_bytes=policy_value["max_path_bytes"],
        )
        entries = tuple(ManifestEntry(**entry) for entry in entries_value)
        rules = tuple(
            AttributeRule(pattern=rule["pattern"], attributes=tuple(rule["attributes"]))
            for rule in rules_value
        )
        return ObjectManifest(
            expected_revision=value["expected_revision"],
            entries=entries,
            attribute_rules=rules,
            policy=policy,
        )
    except (KeyError, TypeError, ValueError) as exc:
        raise ObjectParserRefused("proposed manifest is not valid") from exc


def _diffDigest(expected: ObjectManifest, proposed: ObjectManifest) -> str:
    before = {entry.path: entry for entry in expected.entries}
    after = {entry.path: entry for entry in proposed.entries}
    changes: list[dict[str, Any]] = []
    for path in sorted(set(before) | set(after), key=lambda value: value.encode("utf-8")):
        old = before.get(path)
        new = after.get(path)
        if old == new:
            continue
        changes.append(
            {
                "path": path,
                "before": None
                if old is None
                else {"mode": old.mode, "blob_sha256": old.blob_sha256},
                "after": None
                if new is None
                else {"mode": new.mode, "blob_sha256": new.blob_sha256},
            }
        )
    return canonical_digest(changes)


class ObjectParser:
    def __init__(
        self,
        *,
        controller_root: str | Path,
        image: ObjectParserImage,
        runtime_entrypoint: str | Path,
        process_runner: Callable[[ObjectParserInvocation], ObjectParserProcessResult] | None = None,
        docker_executable: str = "docker",
        docker_context: str = "desktop-linux",
        timeout_seconds: float = _DEFAULT_TIMEOUT,
        idle_timeout_seconds: float = _DEFAULT_IDLE_TIMEOUT,
        artifact_qualification: VerifiedKernelArtifacts | None = None,
    ) -> None:
        if not isinstance(image, ObjectParserImage):
            raise TypeError("image must be an ObjectParserImage")
        try:
            root = assertNoReparsePath(controller_root)
            entrypoint = assertNoReparsePath(runtime_entrypoint)
            raw = readNoFollowBytes(entrypoint, max_bytes=_MAX_RUNTIME_BYTES)
        except (OSError, ValueError) as exc:
            raise ObjectParserRefused("object-parser runtime cannot be attested") from exc
        if not isinstance(timeout_seconds, (int, float)) or isinstance(timeout_seconds, bool):
            raise TypeError("timeout_seconds must be numeric")
        if timeout_seconds <= 0:
            raise ValueError("timeout_seconds must be positive")
        if not isinstance(idle_timeout_seconds, (int, float)) or isinstance(
            idle_timeout_seconds,
            bool,
        ):
            raise TypeError("idle_timeout_seconds must be numeric")
        if idle_timeout_seconds <= 0:
            raise ValueError("idle_timeout_seconds must be positive")
        if not docker_executable or not docker_context:
            raise ValueError("Docker executable and context must be explicit")
        if artifact_qualification is not None:
            if not isinstance(artifact_qualification, VerifiedKernelArtifacts):
                raise TypeError("artifact_qualification must be VerifiedKernelArtifacts")
            if process_runner is not None:
                raise ObjectParserRefused(
                    "installed parser authority cannot use an injected process runner"
                )
            artifact_qualification.revalidate()
            if (
                image.repository != artifact_qualification.object_parser_repository
                or image.manifest_digest
                != artifact_qualification.object_parser_manifest_digest
                or entrypoint != artifact_qualification.object_parser_entrypoint
                or self._digest(raw)
                != artifact_qualification.object_parser_entrypoint_sha256
                or os.path.normcase(os.path.abspath(docker_executable))
                != os.path.normcase(
                    os.path.abspath(artifact_qualification.docker_executable)
                )
                or docker_context != artifact_qualification.docker_context
            ):
                raise ObjectParserRefused(
                    "object parser differs from installed artifact qualification"
                )
        self.controller_root = root
        self.image = image
        self.runtime_entrypoint = entrypoint
        self._runtime_bytes = raw
        self._runtime_digest = hashlib.sha256(raw).hexdigest()
        self._process_runner = process_runner
        self._docker_executable = docker_executable
        self._docker_context = docker_context
        self._timeout_seconds = float(timeout_seconds)
        self._idle_timeout_seconds = float(idle_timeout_seconds)
        self._artifact_qualification = artifact_qualification

    @staticmethod
    def _digest(raw: bytes) -> str:
        return hashlib.sha256(raw).hexdigest()

    @classmethod
    def fromInstalledArtifacts(
        cls,
        *,
        controller_root: str | Path,
        timeout_seconds: float = _DEFAULT_TIMEOUT,
        idle_timeout_seconds: float = _DEFAULT_IDLE_TIMEOUT,
    ) -> "ObjectParser":
        """Construct only from the protected, signed installed artifact lineage."""

        artifacts = loadInstalledKernelArtifacts()
        return cls(
            controller_root=controller_root,
            image=ObjectParserImage(
                repository=artifacts.object_parser_repository,
                manifest_digest=artifacts.object_parser_manifest_digest,
                role="object_parser",
            ),
            runtime_entrypoint=artifacts.object_parser_entrypoint,
            docker_executable=str(artifacts.docker_executable),
            docker_context=artifacts.docker_context,
            timeout_seconds=timeout_seconds,
            idle_timeout_seconds=idle_timeout_seconds,
            artifact_qualification=artifacts,
        )

    def hasInstalledArtifactAuthority(self) -> bool:
        qualification = self._artifact_qualification
        return bool(
            qualification is not None and qualification.isInstalledAuthority()
        )

    @property
    def artifactQualification(self) -> VerifiedKernelArtifacts | None:
        return self._artifact_qualification

    def _revalidateArtifactQualification(self) -> None:
        qualification = self._artifact_qualification
        if qualification is None:
            return
        qualification.revalidate()
        try:
            current = readNoFollowBytes(
                self.runtime_entrypoint,
                max_bytes=_MAX_RUNTIME_BYTES,
            )
        except (OSError, ValueError) as exc:
            raise ObjectParserRefused(
                "installed object-parser entrypoint cannot be revalidated"
            ) from exc
        if (
            hashlib.sha256(current).hexdigest()
            != qualification.object_parser_entrypoint_sha256
            or self.image.repository != qualification.object_parser_repository
            or self.image.manifest_digest
            != qualification.object_parser_manifest_digest
        ):
            raise ObjectParserRefused(
                "installed object-parser artifact identity changed"
            )

    def _validateSnapshotBytes(
        self,
        snapshot: CandidateSnapshot,
    ) -> tuple[tuple[str, int, str, str, int], ...]:
        """Revalidate only inert bytes and strong digests on the host.

        Git OIDs and repository attribute semantics belong exclusively to the
        contained parser and the independently pinned writer oracle.
        """

        entries: list[tuple[str, int, str, str, int]] = []
        for entry in snapshot.entries:
            location = snapshot.blob_root / entry.blob_sha256[:2] / entry.blob_sha256
            try:
                payload = readNoFollowBytes(location, max_bytes=entry.size)
            except (OSError, ValueError) as exc:
                raise ObjectParserRefused("snapshot blob cannot be revalidated") from exc
            if len(payload) != entry.size or hashlib.sha256(payload).hexdigest() != entry.blob_sha256:
                raise ObjectParserRefused("snapshot blob digest differs from immutable manifest")
            frame = b"blob " + str(entry.size).encode("ascii") + b"\0" + payload
            entries.append(
                (
                    entry.path,
                    entry.mode,
                    entry.blob_sha256,
                    hashlib.sha256(frame).hexdigest(),
                    entry.size,
                )
            )
        return tuple(entries)

    @staticmethod
    def _manifestStrongProjection(
        manifest: ObjectManifest,
    ) -> tuple[tuple[str, int, str, str, int], ...]:
        return tuple(
            (
                entry.path,
                entry.mode,
                entry.blob_sha256,
                entry.framed_object_sha256,
                entry.size,
            )
            for entry in manifest.entries
        )

    def _validateRawSnapshotBytes(self, snapshot: CanonicalObjectSnapshot) -> None:
        _validateStreamedRawProjection(snapshot)

    def _validateCatalogBytes(self, catalog: CanonicalObjectCatalog) -> None:
        if _inventoryDigest(catalog.inventory) != catalog.inventory_digest:
            raise ObjectParserRefused("source catalog inventory binding differs")
        _validateStreamedContentProjection(catalog.catalog_root, catalog.indexes)

    @staticmethod
    def _validateClosedContentRoot(root: Path, expected: set[str]) -> None:
        actual: set[str] = set()
        actual_directories: set[str] = set()
        expected_directories: set[str] = set()
        for relative in expected:
            parts = relative.split("/")
            if any(part in {"", ".", ".."} for part in parts):
                raise ObjectParserRefused(
                    "content-addressed parser expectation is not canonical"
                )
            for index in range(1, len(parts)):
                expected_directories.add("/".join(parts[:index]))

        def walk(
            directory: NativeDirectoryHandle,
            prefix: str,
            *,
            root_identity: NativeFileIdentity,
        ) -> None:
            before = directory.identity
            try:
                children = directory.listEntries()
            except (OSError, UnicodeError) as exc:
                raise ObjectParserRefused(
                    "content-addressed parser root cannot be scanned"
                ) from exc
            for child in children:
                relative = f"{prefix}/{child.name}" if prefix else child.name
                identity = child.identity
                if (
                    identity.is_reparse
                    or identity.volume_id != root_identity.volume_id
                    or identity.mount_id != root_identity.mount_id
                ):
                    raise ObjectParserRefused(
                        "content-addressed parser root contains a reparse or mount escape"
                    )
                if identity.is_directory:
                    if relative not in expected_directories:
                        raise ObjectParserRefused(
                            "content-addressed parser root has an unexpected directory"
                        )
                    actual_directories.add(relative)
                    try:
                        with directory.openDirectory(
                            child.name,
                            expected=identity,
                        ) as nested:
                            walk(
                                nested,
                                relative,
                                root_identity=root_identity,
                            )
                    except ObjectParserRefused:
                        raise
                    except OSError as exc:
                        raise ObjectParserRefused(
                            "content-addressed parser directory identity raced"
                        ) from exc
                elif stat.S_ISREG(identity.mode) and identity.link_count == 1:
                    actual.add(relative)
                else:
                    raise ObjectParserRefused(
                        "content-addressed parser root has unsafe data"
                    )
            try:
                after_children = directory.listEntries()
            except (OSError, UnicodeError) as exc:
                raise ObjectParserRefused(
                    "content-addressed parser root raced final enumeration"
                ) from exc
            if directory.identity != before or after_children != children:
                raise ObjectParserRefused(
                    "content-addressed parser root raced retained enumeration"
                )

        try:
            with openNativeDirectory(root) as native_root:
                root_identity = native_root.identity
                if root_identity.is_reparse or not root_identity.is_directory:
                    raise ObjectParserRefused(
                        "content-addressed parser root is not a native directory"
                    )
                walk(native_root, "", root_identity=root_identity)
                if native_root.identity != root_identity:
                    raise ObjectParserRefused(
                        "content-addressed parser root identity changed"
                    )
        except ObjectParserRefused:
            raise
        except OSError as exc:
            raise ObjectParserRefused(
                "content-addressed parser root cannot be opened safely"
            ) from exc
        if actual != expected or actual_directories != expected_directories:
            raise ObjectParserRefused(
                "content-addressed parser root is not an exact closure"
            )

    @staticmethod
    def _mount(source: Path, target: str, *, readonly: bool = True) -> str:
        source_text = str(source)
        if "," in source_text or not target.startswith("/"):
            raise ObjectParserRefused("Docker bind mount path is not losslessly representable")
        suffix = ",readonly" if readonly else ""
        return f"type=bind,source={source_text},target={target}{suffix}"

    def _finalizeInvocation(
        self,
        *,
        root: Path,
        operation: str,
        argv: tuple[str, ...],
        request_path: Path,
        container_name: str,
        output_root: Path | None = None,
        wall_timeout_seconds: float | None = None,
        idle_timeout_seconds: float | None = None,
    ) -> ObjectParserInvocation:
        wall_timeout = (
            self._timeout_seconds
            if wall_timeout_seconds is None
            else float(wall_timeout_seconds)
        )
        idle_timeout = (
            self._idle_timeout_seconds
            if idle_timeout_seconds is None
            else float(idle_timeout_seconds)
        )
        if wall_timeout <= 0 or idle_timeout <= 0:
            raise ValueError("parser invocation timeouts must be positive")
        try:
            request_raw = readNoFollowBytes(request_path, max_bytes=8 * 1024 * 1024)
        except (OSError, ValueError) as exc:
            raise ObjectParserRefused("parser request cannot be bound durably") from exc
        request_sha256 = hashlib.sha256(request_raw).hexdigest()
        invocation_id = canonical_digest(
            {
                "schema": "galaxy.object-parser-invocation-identity/v1",
                "operation": operation,
                "request_sha256": request_sha256,
                "image_reference": self.image.reference,
                "parser_runtime_sha256": self._runtime_digest,
                "docker_context": self._docker_context,
                "base_argv": list(argv),
            }
        )
        try:
            name_index = argv.index("--name")
        except ValueError as exc:
            raise ObjectParserRefused("parser Docker command has no exact name") from exc
        labels = (
            "--label",
            f"galaxy.invocation_id={invocation_id}",
            "--label",
            f"galaxy.request_sha256={request_sha256}",
            "--label",
            f"galaxy.parser_runtime_sha256={self._runtime_digest}",
            "--label",
            f"galaxy.parser_image_manifest={self.image.manifest_digest}",
            "--label",
            f"galaxy.operation={operation}",
        )
        final_argv = argv[: name_index + 2] + labels + argv[name_index + 2 :]
        evidence_root = root / "evidence"
        try:
            evidence_root.mkdir(parents=True, exist_ok=True)
            assertNoReparsePath(evidence_root)
        except OSError as exc:
            raise ObjectParserRefused("parser evidence root is unsafe") from exc
        record_path = evidence_root / "invocation.json"
        created_path = evidence_root / "container-created.json"
        start_intent_path = evidence_root / "container-start-intent.json"
        result_path = evidence_root / "terminal-result.json"
        cleanup_path = evidence_root / "container-cleaned.json"
        qualification = self._artifact_qualification
        record = {
            "schema": "galaxy.object-parser-invocation/v1",
            "status": "prepared",
            "invocation_id": invocation_id,
            "operation": operation,
            "container_name": container_name,
            "request_path": str(request_path),
            "request_sha256": request_sha256,
            "image_reference": self.image.reference,
            "parser_runtime_sha256": self._runtime_digest,
            "docker_context": self._docker_context,
            "argv_sha256": canonical_digest(list(final_argv)),
            "artifact_qualification_id": (
                qualification.qualification_id if qualification is not None else None
            ),
        }
        try:
            _createExact(record_path, canonical_json_bytes(record))
        except OSError as exc:
            raise ObjectParserRefused("parser invocation could not be registered") from exc
        return ObjectParserInvocation(
            argv=final_argv,
            request_path=request_path,
            container_name=container_name,
            invocation_id=invocation_id,
            operation=operation,
            request_sha256=request_sha256,
            record_path=record_path,
            created_path=created_path,
            start_intent_path=start_intent_path,
            result_path=result_path,
            cleanup_path=cleanup_path,
            wall_timeout_seconds=wall_timeout,
            idle_timeout_seconds=min(idle_timeout, wall_timeout),
            output_root=output_root,
        )

    def _prepareInvocation(
        self,
        *,
        snapshot: CandidateSnapshot,
        expected: ObjectManifest,
    ) -> ObjectParserInvocation:
        namespace = hashlib.sha256(snapshot.transaction_id.encode("utf-8")).hexdigest()
        root = self.controller_root / "object-parser" / namespace
        runtime = root / "runtime"
        control = root / "control"
        request_root = root / "input"
        try:
            for directory in (runtime, control, request_root):
                directory.mkdir(parents=True, exist_ok=True)
                assertNoReparsePath(directory)
            runtime_path = runtime / "object_parser_entrypoint.py"
            _createExact(runtime_path, self._runtime_bytes)
            activation = {
                "schema": "galaxy.activation-runtime/v1",
                "role": "object_parser",
                "entrypoint": "object_parser_entrypoint.py",
                "argv": [],
                "leaves": [
                    {
                        "path": "object_parser_entrypoint.py",
                        "sha256": self._runtime_digest,
                        "size": len(self._runtime_bytes),
                    }
                ],
            }
            activation_raw = canonical_json_bytes(activation)
            activation_digest = hashlib.sha256(activation_raw).hexdigest()
            _createExact(control / "activation.json", activation_raw)
            request = buildObjectParserRequest(snapshot=snapshot, expected=expected)
            request_path = request_root / "request.json"
            _createExact(request_path, canonical_json_bytes(request))
        except OSError as exc:
            raise ObjectParserRefused("could not prepare immutable parser projection") from exc
        container_name = _scopedContainerName(
            self.controller_root,
            prefix="galaxy-object-parser",
            operation="candidate-snapshot",
            logical_identity=snapshot.transaction_id,
        )
        argv = (
            *self._dockerPrefix(),
            "create",
            "--name",
            container_name,
            "--pull=never",
            "--platform=linux/amd64",
            "--network=none",
            "--read-only",
            "--cap-drop=ALL",
            "--security-opt=no-new-privileges:true",
            "--pids-limit=64",
            "--memory=134217728",
            "--cpus=0.5",
            "--restart=no",
            "--user=65532:65532",
            "--workdir=/empty",
            "--mount",
            self._mount(runtime, "/galaxy-runtime"),
            "--mount",
            self._mount(control, "/galaxy-control"),
            "--mount",
            self._mount(request_root, "/galaxy-input"),
            "--mount",
            self._mount(snapshot.blob_root, "/galaxy-blobs"),
            self.image.reference,
            "run-bound",
            "--sealed-role",
            self.image.role,
            "--manifest-sha256",
            activation_digest,
            "candidate-snapshot",
            "--sha1dc-executable",
            "/opt/galaxy/galaxy-sha1dc",
            "--request",
            "/galaxy-input/request.json",
            "--blob-root",
            "/galaxy-blobs",
            "--heartbeat-interval",
            "1.0",
        )
        return self._finalizeInvocation(
            root=root,
            operation="candidate-snapshot",
            argv=argv,
            request_path=request_path,
            container_name=container_name,
        )

