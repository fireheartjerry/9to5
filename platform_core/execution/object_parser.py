    def _persistDockerResult(
        self,
        invocation: ObjectParserInvocation,
        result: ObjectParserProcessResult,
        *,
        disposition: str,
        container_id: str,
    ) -> None:
        if disposition not in {
            "completed",
            "wall_timeout",
            "idle_timeout",
            "output_quota",
            "reader_failure",
        }:
            raise ObjectParserRefused("durable parser disposition is not closed")
        if _CONTAINER_ID_RE.fullmatch(container_id) is None:
            raise ObjectParserRefused("durable parser container id is malformed")
        if (
            not isinstance(result, ObjectParserProcessResult)
            or len(result.stdout) + len(result.stderr) > _MAX_OUTPUT_BYTES
            or type(result.returncode) is not int
        ):
            raise ObjectParserRefused("durable parser result exceeds its contract")
        value = {
            "schema": "galaxy.object-parser-terminal-result/v1",
            "disposition": disposition,
            "invocation_id": invocation.invocation_id,
            "operation": invocation.operation,
            "container_name": invocation.container_name,
            "container_id": container_id,
            "request_sha256": invocation.request_sha256,
            "image_reference": self.image.reference,
            "parser_runtime_sha256": self._runtime_digest,
            "returncode": result.returncode,
            "stdout_base64url": self._encodeDurableBytes(result.stdout),
            "stdout_sha256": hashlib.sha256(result.stdout).hexdigest(),
            "stderr_base64url": self._encodeDurableBytes(result.stderr),
            "stderr_sha256": hashlib.sha256(result.stderr).hexdigest(),
        }
        try:
            _createExact(invocation.result_path, canonical_json_bytes(value))
        except OSError as exc:
            raise ObjectParserRefused("durable parser result could not be persisted") from exc

    def _loadDockerResult(
        self,
        invocation: ObjectParserInvocation,
    ) -> ObjectParserProcessResult | None:
        if not invocation.result_path.exists():
            return None
        try:
            raw = readNoFollowBytes(
                invocation.result_path,
                max_bytes=32 * 1024 * 1024,
            )
            value = json.loads(
                raw.decode("utf-8", errors="strict"),
                object_pairs_hook=_rejectDuplicatePairs,
            )
        except (OSError, ValueError, UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise ObjectParserRefused("durable parser result is unavailable") from exc
        fields = {
            "schema",
            "disposition",
            "invocation_id",
            "operation",
            "container_name",
            "container_id",
            "request_sha256",
            "image_reference",
            "parser_runtime_sha256",
            "returncode",
            "stdout_base64url",
            "stdout_sha256",
            "stderr_base64url",
            "stderr_sha256",
        }
        if (
            not isinstance(value, dict)
            or canonical_json_bytes(value) != raw
            or set(value) != fields
            or value.get("schema") != "galaxy.object-parser-terminal-result/v1"
            or value.get("invocation_id") != invocation.invocation_id
            or value.get("operation") != invocation.operation
            or value.get("container_name") != invocation.container_name
            or value.get("request_sha256") != invocation.request_sha256
            or value.get("image_reference") != self.image.reference
            or value.get("parser_runtime_sha256") != self._runtime_digest
            or not isinstance(value.get("returncode"), int)
            or isinstance(value.get("returncode"), bool)
            or not isinstance(value.get("container_id"), str)
            or _CONTAINER_ID_RE.fullmatch(str(value["container_id"])) is None
        ):
            raise ObjectParserRefused("durable parser result binding differs")
        stdout = self._decodeDurableBytes(value["stdout_base64url"], "stdout")
        stderr = self._decodeDurableBytes(value["stderr_base64url"], "stderr")
        if (
            hashlib.sha256(stdout).hexdigest() != value.get("stdout_sha256")
            or hashlib.sha256(stderr).hexdigest() != value.get("stderr_sha256")
            or len(stdout) + len(stderr) > _MAX_OUTPUT_BYTES
        ):
            raise ObjectParserRefused("durable parser result digest differs")
        disposition = value.get("disposition")
        if disposition == "wall_timeout":
            raise ObjectParserRefused("object-parser container exceeded wall-time quota")
        if disposition == "idle_timeout":
            raise ObjectParserRefused("object-parser container exceeded idle-time quota")
        if disposition == "output_quota":
            raise ObjectParserRefused("object-parser container exceeded output quota")
        if disposition == "reader_failure":
            raise ObjectParserRefused("object-parser output reader failed")
        if disposition != "completed":
            raise ObjectParserRefused("durable parser disposition is unknown")
        return ObjectParserProcessResult(
            returncode=int(value["returncode"]),
            stdout=stdout,
            stderr=stderr,
        )

