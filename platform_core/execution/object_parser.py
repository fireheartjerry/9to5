class ObjectParserRefused(RuntimeError):
    """The parser boundary or its result was not exact and closed."""


def _scopedContainerName(
    controller_root: str | Path,
    *,
    prefix: str,
    operation: str,
    logical_identity: str,
) -> str:
    """Return one stable host-global name bound to its controller scope."""

    namespace = canonical_digest(
        {
            "schema": "galaxy.object-parser-container-namespace/v1",
            "controller_root": os.path.normcase(
                os.path.abspath(os.fspath(controller_root))
            ),
            "operation": operation,
            "logical_identity": logical_identity,
        }
    )
    return f"{prefix}-{namespace[:24]}"


def _requireDigest(value: str, name: str) -> None:
    if not isinstance(value, str) or _DIGEST_RE.fullmatch(value) is None:
        raise ValueError(f"{name} must be a lowercase SHA-256 digest")


def _createExact(path: Path, payload: bytes) -> None:
    try:
        exclusiveCreateBytes(path, payload)
    except FileExistsError:
        try:
            observed = readNoFollowBytes(path, max_bytes=max(1, len(payload)))
        except (OSError, ValueError) as exc:
            raise ObjectParserRefused("parser projection contains unsafe existing evidence") from exc
        if observed != payload:
            raise ObjectParserRefused("parser projection immutable-file collision")


