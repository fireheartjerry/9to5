@dataclass(frozen=True, kw_only=True)
class CandidateSnapshot:
    transaction_id: str
    blob_root: Path
    entries: tuple[SnapshotEntry, ...]
    policy: ManifestPolicy

    def __post_init__(self) -> None:
        if (
            not isinstance(self.transaction_id, str)
            or not self.transaction_id
            or len(self.transaction_id.encode("utf-8")) > 256
            or any(ord(character) < 33 or ord(character) > 126 for character in self.transaction_id)
        ):
            raise ValueError("transaction_id must be bounded visible ASCII")
        if not isinstance(self.entries, tuple) or not isinstance(self.policy, ManifestPolicy):
            raise TypeError("snapshot entries and policy must be immutable typed values")
        try:
            root = assertNoReparsePath(self.blob_root)
        except OSError as exc:
            raise ValueError("snapshot blob root traverses a reparse point") from exc
        if not root.is_dir():
            raise ValueError("snapshot blob root must exist")
        ordered = tuple(sorted(self.entries, key=lambda entry: entry.path.encode("utf-8")))
        ObjectManifest(
            expected_revision="0" * 40,
            entries=tuple(
                ManifestEntry(
                    path=entry.path,
                    mode=entry.mode,
                    blob_oid="0" * 40,
                    blob_sha256=entry.blob_sha256,
                    framed_object_sha256="0" * 64,
                    size=entry.size,
                )
                for entry in ordered
            ),
            attribute_rules=(),
            policy=self.policy,
        )
        object.__setattr__(self, "entries", ordered)
        object.__setattr__(self, "blob_root", root)

    @property
    def snapshot_digest(self) -> str:
        return canonical_digest({"entries": [entry.toDict() for entry in self.entries]})

    @property
    def blob_set_digest(self) -> str:
        records = sorted(
            {
                (entry.blob_sha256, entry.size)
                for entry in self.entries
            }
        )
        return canonical_digest(
            [{"sha256": digest, "size": size} for digest, size in records]
        )

    def toDict(self) -> dict[str, Any]:
        return {
            "entries": [entry.toDict() for entry in self.entries],
            "snapshot_digest": self.snapshot_digest,
            "blob_set_digest": self.blob_set_digest,
        }


@dataclass(frozen=True, kw_only=True)
class RawObjectSnapshotEntry:
    """One opaque canonical object-store byte range copied through no-follow I/O."""

    path: str
    raw_sha256: str
    size: int

    def __post_init__(self) -> None:
        if not isinstance(self.path, str) or _RAW_OBJECT_PATH_RE.fullmatch(self.path) is None:
            raise ValueError("raw object snapshot path is outside the closed grammar")
        _requireDigest(self.raw_sha256, "raw_sha256")
        if type(self.size) is not int or self.size < 1:
            raise ValueError("raw object snapshot size must be positive")

    def toDict(self) -> dict[str, Any]:
        return {"path": self.path, "raw_sha256": self.raw_sha256, "size": self.size}


@dataclass(frozen=True, kw_only=True)
class CanonicalObjectSnapshot:
    """Immutable raw object projection for one exact canonical source revision."""

    transaction_id: str
    repository_id: str
    revision: str
    canonical_attestation_digest: str
    raw_root: Path
    entries: tuple[RawObjectSnapshotEntry, ...]
    policy: ManifestPolicy

    def __post_init__(self) -> None:
        if (
            not isinstance(self.transaction_id, str)
            or _TRANSACTION_RE.fullmatch(self.transaction_id) is None
        ):
            raise ValueError("transaction_id is not filesystem-safe")
        _requireDigest(self.repository_id, "repository_id")
        _requireDigest(self.canonical_attestation_digest, "canonical_attestation_digest")
        if not isinstance(self.revision, str) or _OID_RE.fullmatch(self.revision) is None:
            raise ValueError("revision must be a full SHA-1 object id")
        if not isinstance(self.entries, tuple) or not isinstance(self.policy, ManifestPolicy):
            raise TypeError("source snapshot entries and policy must be immutable typed values")
        ordered = tuple(sorted(self.entries, key=lambda entry: entry.path))
        if not ordered or len({entry.path for entry in ordered}) != len(ordered):
            raise ValueError("source snapshot entries must be nonempty and unique")
        pack_members: dict[str, set[str]] = {}
        for entry in ordered:
            if match := re.fullmatch(r"pack/pack-([0-9a-f]{40})\.idx", entry.path):
                pack_members.setdefault(match.group(1), set()).add("idx")
            elif match := _PACK_HEADER_PATH_RE.fullmatch(entry.path):
                pack_members.setdefault(match.group(1), set()).add("header")
            elif match := _PACK_RANGE_PATH_RE.fullmatch(entry.path):
                pack_members.setdefault(match.group(1), set()).add("range")
        if any(members != {"idx", "header", "range"} for members in pack_members.values()):
            raise ValueError("source snapshot pack evidence is incomplete")
        try:
            raw_root = assertNoReparsePath(self.raw_root)
        except OSError as exc:
            raise ValueError("source snapshot root traverses a reparse point") from exc
        if not raw_root.is_dir():
            raise ValueError("source snapshot root must exist")
        object.__setattr__(self, "entries", ordered)
        object.__setattr__(self, "raw_root", raw_root)

    @property
    def snapshot_digest(self) -> str:
        return canonical_digest(
            {
                "repository_id": self.repository_id,
                "revision": self.revision,
                "canonical_attestation_digest": self.canonical_attestation_digest,
                "entries": [entry.toDict() for entry in self.entries],
                "policy": self.policy.toDict(),
            }
        )

    def toDict(self) -> dict[str, Any]:
        return {
            "repository_id": self.repository_id,
            "revision": self.revision,
            "canonical_attestation_digest": self.canonical_attestation_digest,
            "entries": [entry.toDict() for entry in self.entries],
            "policy": self.policy.toDict(),
            "snapshot_digest": self.snapshot_digest,
        }


@dataclass(frozen=True, kw_only=True)
class CanonicalObjectCatalog:
    """Opaque loose-name and contained pack-index catalog for source selection."""

    transaction_id: str
    repository_id: str
    revision: str
    canonical_attestation_digest: str
    canonical_root: Path
    git_common_dir: Path
    catalog_root: Path
    loose_oids: tuple[str, ...]
    indexes: tuple[RawObjectSnapshotEntry, ...]
    inventory: tuple["_RawInventoryEntry", ...]
    inventory_digest: str
    catalog_bytes: int
    policy: ManifestPolicy

    def __post_init__(self) -> None:
        if _TRANSACTION_RE.fullmatch(self.transaction_id) is None:
            raise ValueError("catalog transaction_id is not filesystem-safe")
        _requireDigest(self.repository_id, "repository_id")
        _requireDigest(self.canonical_attestation_digest, "canonical_attestation_digest")
        _requireDigest(self.inventory_digest, "inventory_digest")
        if _OID_RE.fullmatch(self.revision) is None:
            raise ValueError("catalog revision must be a full SHA-1 object id")
        if (
            self.loose_oids != tuple(sorted(self.loose_oids))
            or len(set(self.loose_oids)) != len(self.loose_oids)
            or any(_OID_RE.fullmatch(oid) is None for oid in self.loose_oids)
            or self.indexes != tuple(sorted(self.indexes, key=lambda entry: entry.path))
            or any(not entry.path.endswith(".idx") for entry in self.indexes)
            or type(self.catalog_bytes) is not int
            or self.catalog_bytes < 0
            or not isinstance(self.policy, ManifestPolicy)
        ):
            raise ValueError("canonical object catalog is not closed and ordered")
        try:
            root = assertNoReparsePath(self.catalog_root)
            canonical_root = assertNoReparsePath(self.canonical_root)
            git_common_dir = assertNoReparsePath(self.git_common_dir)
        except OSError as exc:
            raise ValueError("catalog root traverses a reparse point") from exc
        if not root.is_dir() or not canonical_root.is_dir() or not git_common_dir.is_dir():
            raise ValueError("catalog and canonical roots must exist")
        object.__setattr__(self, "catalog_root", root)
        object.__setattr__(self, "canonical_root", canonical_root)
        object.__setattr__(self, "git_common_dir", git_common_dir)

    def locatorRequest(self, requested_oids: Collection[str]) -> dict[str, Any]:
        requested = sorted(set(requested_oids))
        if not requested or any(_OID_RE.fullmatch(oid) is None for oid in requested):
            raise ValueError("locator request requires full source-object OIDs")
        return {
            "schema": "galaxy.source-object-locator-request/v1",
            "operation": "source-object-locate",
            "transaction_id": self.transaction_id,
            "inventory_digest": self.inventory_digest,
            "loose_oids": list(self.loose_oids),
            "indexes": [entry.toDict() for entry in self.indexes],
            "packs": [
                {"path": record.logical_path, "size": record.identity.size}
                for record in self.inventory
                if record.logical_path.endswith(".pack")
            ],
            "requested_oids": requested,
        }


@dataclass(frozen=True, slots=True)
class _RawInventoryEntry:
    logical_path: str
    parent_name: str
    parent_identity: NativeFileIdentity
    name: str
    identity: NativeFileIdentity


def _selectedSourceRecord(
    catalog: CanonicalObjectCatalog,
    path: str,
) -> tuple[_RawInventoryEntry, int, int]:
    inventory = {record.logical_path: record for record in catalog.inventory}
    direct = inventory.get(path)
    if direct is not None:
        if path.endswith(".pack"):
            raise ObjectParserRefused("whole pack selection is forbidden")
        return direct, 0, direct.identity.size
    header = _PACK_HEADER_PATH_RE.fullmatch(path)
    if header is not None:
        record = inventory.get(f"pack/pack-{header.group(1)}.pack")
        if record is None or record.identity.size < 32:
            raise ObjectParserRefused("selected pack header has no exact source")
        return record, 0, 12
    selected_range = _PACK_RANGE_PATH_RE.fullmatch(path)
    if selected_range is None:
        raise ObjectParserRefused("selected source path is outside the closed grammar")
    record = inventory.get(f"pack/pack-{selected_range.group(1)}.pack")
    source_size = int(selected_range.group(2))
    offset = int(selected_range.group(3))
    length = int(selected_range.group(4))
    if (
        record is None
        or source_size != record.identity.size
        or offset < 12
        or offset > record.identity.size - 20
        or length > record.identity.size - 20 - offset
    ):
        raise ObjectParserRefused("selected pack range escapes its exact source")
    return record, offset, length


def _validateSelectedSourcePaths(
    catalog: CanonicalObjectCatalog,
    selected: Collection[str],
) -> None:
    groups: dict[str, set[str]] = {}
    for path in selected:
        _selectedSourceRecord(catalog, path)
        if match := re.fullmatch(r"pack/pack-([0-9a-f]{40})\.idx", path):
            groups.setdefault(match.group(1), set()).add("idx")
        elif match := _PACK_HEADER_PATH_RE.fullmatch(path):
            groups.setdefault(match.group(1), set()).add("header")
        elif match := _PACK_RANGE_PATH_RE.fullmatch(path):
            groups.setdefault(match.group(1), set()).add("range")
    if any(roles != {"idx", "header", "range"} for roles in groups.values()):
        raise ObjectParserRefused(
            "selected pack evidence requires its index, header, and at least one range"
        )


