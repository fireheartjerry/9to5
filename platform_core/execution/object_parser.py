def _nativeObjectEntries(
    directory: NativeDirectoryHandle,
    *,
    label: str,
) -> tuple[NativeDirectoryEntry, ...]:
    try:
        entries = directory.listEntries()
    except (OSError, UnicodeError) as exc:
        raise ObjectParserRefused(f"{label} cannot be inventoried") from exc
    aliases: dict[str, tuple[str, int]] = {}
    for entry in entries:
        if entry.identity.is_reparse:
            raise ObjectParserRefused(f"{label} contains a reparse entry")
        for alias in (entry.name, entry.short_name):
            if not alias:
                continue
            key = alias.casefold().rstrip(" .")
            identity = (entry.name, entry.identity.file_id)
            prior = aliases.get(key)
            if not key or (prior is not None and prior != identity):
                raise ObjectParserRefused(f"{label} contains an alias collision")
            aliases[key] = identity
    return entries


def _rawInventory(
    objects: NativeDirectoryHandle,
) -> tuple[_RawInventoryEntry, ...]:
    records: list[_RawInventoryEntry] = []
    root_identity = objects.identity
    for entry in _nativeObjectEntries(objects, label="canonical object store"):
        name = entry.name
        if entry.identity.volume_id != root_identity.volume_id:
            raise ObjectParserRefused("canonical object store crosses a mount boundary")
        if re.fullmatch(r"[0-9a-f]{2}", name):
            if not entry.identity.is_directory:
                raise ObjectParserRefused("loose-object fanout is not a directory")
            try:
                fanout = objects.openDirectory(name, expected=entry.identity)
            except OSError as exc:
                raise ObjectParserRefused("loose-object fanout cannot be inventoried") from exc
            with fanout:
                leaves = _nativeObjectEntries(fanout, label="loose-object fanout")
            for leaf_entry in leaves:
                leaf = leaf_entry.name
                if leaf.startswith("tmp_obj_"):
                    continue
                if re.fullmatch(r"[0-9a-f]{38}", leaf) is None:
                    raise ObjectParserRefused("canonical loose-object name is malformed")
                records.append(
                    _RawInventoryEntry(
                        logical_path=f"loose/{name}{leaf}",
                        parent_name=name,
                        parent_identity=entry.identity,
                        name=leaf,
                        identity=leaf_entry.identity,
                    )
                )
        elif name == "pack":
            if not entry.identity.is_directory:
                raise ObjectParserRefused("pack object store is not a directory")
            try:
                pack = objects.openDirectory(name, expected=entry.identity)
            except OSError as exc:
                raise ObjectParserRefused("pack directory cannot be inventoried") from exc
            with pack:
                pack_entries = _nativeObjectEntries(pack, label="pack directory")
            pack_pairs: dict[str, set[str]] = {}
            for pack_entry in pack_entries:
                authority = re.fullmatch(
                    r"pack-([0-9a-f]{40})\.(pack|idx)",
                    pack_entry.name,
                )
                if authority is not None:
                    pack_pairs.setdefault(authority.group(1), set()).add(
                        authority.group(2)
                    )
            if any(members != {"pack", "idx"} for members in pack_pairs.values()):
                raise ObjectParserRefused(
                    "canonical pack and index files must be paired"
                )
            for pack_entry in pack_entries:
                leaf = pack_entry.name
                if re.fullmatch(r"pack-[0-9a-f]{40}\.(?:pack|idx)", leaf):
                    records.append(
                        _RawInventoryEntry(
                            logical_path=f"pack/{leaf}",
                            parent_name=name,
                            parent_identity=entry.identity,
                            name=leaf,
                            identity=pack_entry.identity,
                        )
                    )
                elif leaf == "multi-pack-index":
                    continue
                else:
                    sidecar = re.fullmatch(
                        r"pack-([0-9a-f]{40})\.(?:bitmap|rev|mtimes)",
                        leaf,
                    )
                    if sidecar is not None and sidecar.group(1) in pack_pairs:
                        continue
                    if sidecar is not None:
                        raise ObjectParserRefused(
                            "derived object sidecar lacks its paired pack and index"
                        )
                    raise ObjectParserRefused(
                        "canonical pack directory has unknown authority data"
                    )
        elif name == "info":
            if not entry.identity.is_directory:
                raise ObjectParserRefused("object info store is not a directory")
            continue
        else:
            raise ObjectParserRefused("canonical object store has unknown top-level data")
    return tuple(sorted(records, key=lambda record: record.logical_path))


def _captureRawRecord(
    objects: NativeDirectoryHandle,
    raw_output: NativeDirectoryHandle,
    record: _RawInventoryEntry,
    *,
    max_bytes: int,
    known_digests: set[str],
    source_offset: int = 0,
    source_length: int | None = None,
) -> tuple[str, int]:
    """Stream one opaque Git file or exact byte range into the raw projection."""

    temporary_name = (
        ".galaxy-raw-"
        + hashlib.sha256(record.logical_path.encode("utf-8")).hexdigest()[:16]
        + f"-{os.getpid()}-{threading.get_ident()}-{os.urandom(8).hex()}.tmp"
    )
    copied: NativeFileIdentity | None = None
    try:
        with objects.openDirectory(
            record.parent_name,
            expected=record.parent_identity,
        ) as parent:
            if source_length is None:
                if source_offset != 0:
                    raise ValueError("whole-file capture cannot begin at a nonzero offset")
                copied, digest, size = parent.copyFileTo(
                    record.name,
                    raw_output,
                    temporary_name,
                    max_bytes=max_bytes,
                    expected=record.identity,
                )
            else:
                copied, digest, size = parent.copyFileRangeTo(
                    record.name,
                    raw_output,
                    temporary_name,
                    offset=source_offset,
                    length=source_length,
                    expected=record.identity,
                )
        prefix = digest[:2]
        try:
            fanout = raw_output.createDirectory(prefix)
        except FileExistsError:
            matches = [
                entry
                for entry in raw_output.listEntries()
                if entry.name == prefix
            ]
            if len(matches) != 1 or not matches[0].identity.is_directory:
                raise ObjectParserRefused("raw snapshot fanout is unsafe")
            fanout = raw_output.openDirectory(prefix, expected=matches[0].identity)
        with fanout:
            leaves = [entry for entry in fanout.listEntries() if entry.name == digest]
            if leaves:
                if len(leaves) != 1:
                    raise ObjectParserRefused("raw snapshot payload collision")
                existing_identity, existing_digest, existing_size = fanout.hashFile(
                    digest,
                    max_bytes=size,
                    expected=leaves[0].identity,
                )
                if (
                    existing_identity != leaves[0].identity
                    or existing_digest != digest
                    or existing_size != size
                ):
                    raise ObjectParserRefused("raw snapshot payload collision")
                raw_output.removeFile(temporary_name, expected=copied)
            else:
                published = raw_output.moveChild(
                    temporary_name,
                    fanout,
                    digest,
                    expected=copied,
                )
                if published.size != size:
                    raise ObjectParserRefused("raw snapshot payload size drifted")
        known_digests.add(digest)
        return digest, size
    except (ObjectParserRefused, OSError, ValueError) as exc:
        if copied is not None:
            try:
                raw_output.removeFile(temporary_name, expected=copied)
            except (FileNotFoundError, OSError):
                pass
        if isinstance(exc, ObjectParserRefused):
            raise
        raise ObjectParserRefused("canonical raw-object streaming failed") from exc


def _requireSafeRawRecord(
    record: _RawInventoryEntry,
    *,
    max_raw_file_bytes: int,
) -> None:
    identity = record.identity
    if (
        identity.is_reparse
        or identity.is_directory
        or not stat.S_ISREG(identity.mode)
        or identity.link_count != 1
        or identity.size < 1
        or identity.size > max_raw_file_bytes
    ):
        raise ObjectParserRefused("canonical raw-object leaf is unsafe")


def captureCanonicalObjectCatalog(
    *,
    attestation: CanonicalRepositoryAttestation,
    transaction_id: str,
    snapshot_root: str | Path,
    policy: ManifestPolicy,
    max_raw_files: int = 100_000,
    max_catalog_bytes: int = 128 * 1024 * 1024,
    max_raw_file_bytes: int = 1024 * 1024 * 1024,
    wall_timeout_seconds: float = 120.0,
    idle_timeout_seconds: float = 15.0,
) -> CanonicalObjectCatalog:
    """Capture only pack indexes plus loose OID names for contained selection."""

    if not isinstance(attestation, CanonicalRepositoryAttestation):
        raise TypeError("source catalog requires a canonical repository attestation")
    if not isinstance(policy, ManifestPolicy):
        raise TypeError("source catalog requires a manifest policy")
    for name, value in (
        ("max_raw_files", max_raw_files),
        ("max_catalog_bytes", max_catalog_bytes),
        ("max_raw_file_bytes", max_raw_file_bytes),
    ):
        if type(value) is not int or value < 1:
            raise ValueError(f"{name} must be a positive integer")
    if wall_timeout_seconds <= 0 or idle_timeout_seconds <= 0:
        raise ValueError("source catalog timeouts must be positive")
    if _TRANSACTION_RE.fullmatch(transaction_id) is None:
        raise ValueError("transaction_id is not filesystem-safe")
    try:
        destination_parent = assertNoReparsePath(snapshot_root)
        canonical_root = assertNoReparsePath(attestation.canonical_root)
        common = assertNoReparsePath(attestation.git_common_dir)
    except OSError as exc:
        raise ObjectParserRefused("source catalog root is unsafe") from exc
    destination_parent.mkdir(parents=True, exist_ok=True)
    destination_parent = assertNoReparsePath(destination_parent)
    destination = destination_parent / transaction_id / "catalog"
    raw_root = destination / "raw"
    raw_root.mkdir(parents=True, exist_ok=True)
    raw_root = assertNoReparsePath(raw_root)
    for forbidden in (canonical_root, common):
        try:
            if os.path.commonpath((str(raw_root), str(forbidden))) in {
                str(raw_root),
                str(forbidden),
            }:
                raise ObjectParserRefused("source catalog overlaps canonical storage")
        except ValueError:
            pass
    started = time.monotonic()
    last_progress = started
    total = 0
    indexes: list[RawObjectSnapshotEntry] = []
    inventory: tuple[_RawInventoryEntry, ...]
    try:
        with (
            openNativeDirectory(raw_root) as catalog_output,
            openNativeDirectory(common) as common_handle,
        ):
            common_identity = common_handle.identity
            common_entries = _nativeObjectEntries(
                common_handle,
                label="Git common directory",
            )
            object_entries = [entry for entry in common_entries if entry.name == "objects"]
            if len(object_entries) != 1:
                raise ObjectParserRefused("Git common directory has no exact object store")
            with common_handle.openDirectory(
                "objects",
                expected=object_entries[0].identity,
            ) as objects:
                objects_identity = objects.identity
                inventory = _rawInventory(objects)
                if not inventory or len(inventory) > max_raw_files:
                    raise ObjectParserRefused("canonical raw-object inventory exceeds quota")
                known_digests: set[str] = set()
                for record in inventory:
                    now = time.monotonic()
                    if (
                        now - started > wall_timeout_seconds
                        or now - last_progress > idle_timeout_seconds
                    ):
                        raise ObjectParserRefused("source catalog capture exceeded time quota")
                    _requireSafeRawRecord(
                        record,
                        max_raw_file_bytes=max_raw_file_bytes,
                    )
                    if not record.logical_path.endswith(".idx"):
                        continue
                    if total + record.identity.size > max_catalog_bytes:
                        raise ObjectParserRefused("source catalog exceeds byte quota")
                    digest, size = _captureRawRecord(
                        objects,
                        catalog_output,
                        record,
                        max_bytes=record.identity.size,
                        known_digests=known_digests,
                    )
                    total += size
                    indexes.append(
                        RawObjectSnapshotEntry(
                            path=record.logical_path,
                            raw_sha256=digest,
                            size=size,
                        )
                    )
                    last_progress = time.monotonic()
                if _rawInventory(objects) != inventory or objects.identity != objects_identity:
                    raise ObjectParserRefused(
                        "canonical object store drifted during catalog capture"
                    )
            if (
                common_handle.identity != common_identity
                or _nativeObjectEntries(
                    common_handle,
                    label="Git common directory",
                )
                != common_entries
            ):
                raise ObjectParserRefused("Git common directory drifted during catalog capture")
    except ObjectParserRefused:
        raise
    except OSError as exc:
        raise ObjectParserRefused("canonical catalog drifted during capture") from exc
    try:
        live = attestCanonicalRepository(attestation.canonical_root)
    except CanonicalRepositoryRefused as exc:
        raise ObjectParserRefused("canonical repository drifted during catalog capture") from exc
    if live.attestation_digest != attestation.attestation_digest:
        raise ObjectParserRefused("canonical repository drifted during catalog capture")
    catalog = CanonicalObjectCatalog(
        transaction_id=transaction_id,
        repository_id=attestation.repository_id,
        revision=attestation.head_oid,
        canonical_attestation_digest=attestation.attestation_digest,
        canonical_root=canonical_root,
        git_common_dir=common,
        catalog_root=raw_root,
        loose_oids=tuple(
            record.logical_path.split("/", 1)[1]
            for record in inventory
            if record.logical_path.startswith("loose/")
        ),
        indexes=tuple(indexes),
        inventory=inventory,
        inventory_digest=_inventoryDigest(inventory),
        catalog_bytes=total,
        policy=policy,
    )
    _createExact(
        destination / "catalog.json",
        canonical_json_bytes(
            {
                "schema": "galaxy.canonical-object-catalog/v1",
                "transaction_id": catalog.transaction_id,
                "repository_id": catalog.repository_id,
                "revision": catalog.revision,
                "canonical_attestation_digest": catalog.canonical_attestation_digest,
                "inventory_digest": catalog.inventory_digest,
                "loose_oids": list(catalog.loose_oids),
                "indexes": [entry.toDict() for entry in catalog.indexes],
                "catalog_bytes": catalog.catalog_bytes,
                "policy": catalog.policy.toDict(),
            }
        ),
    )
    return catalog


def _validateStreamedContentProjection(
    root: Path,
    entries: Collection[RawObjectSnapshotEntry],
) -> None:
    sizes: dict[str, int] = {}
    for entry in entries:
        relative = f"{entry.raw_sha256[:2]}/{entry.raw_sha256}"
        previous = sizes.setdefault(relative, entry.size)
        if previous != entry.size:
            raise ObjectParserRefused("raw object snapshot aliases unequal sizes")
    expected = set(sizes)
    try:
        with openNativeDirectory(root) as raw_root:
            roots = {entry.name: entry for entry in raw_root.listEntries()}
            for prefix in sorted({relative.split("/", 1)[0] for relative in expected}):
                prefix_entry = roots.get(prefix)
                if prefix_entry is None or not prefix_entry.identity.is_directory:
                    raise OSError("raw snapshot fanout is unavailable")
                with raw_root.openDirectory(
                    prefix,
                    expected=prefix_entry.identity,
                ) as fanout:
                    leaves = {entry.name: entry for entry in fanout.listEntries()}
                    for relative in sorted(
                        item for item in expected if item.startswith(prefix + "/")
                    ):
                        digest = relative.split("/", 1)[1]
                        leaf = leaves.get(digest)
                        if leaf is None:
                            raise OSError("raw snapshot leaf is unavailable")
                        identity, observed, size = fanout.hashFile(
                            digest,
                            max_bytes=sizes[relative],
                            expected=leaf.identity,
                        )
                        if (
                            identity != leaf.identity
                            or size != sizes[relative]
                            or observed != digest
                        ):
                            raise ObjectParserRefused("raw object snapshot digest differs")
    except ObjectParserRefused:
        raise
    except (OSError, ValueError) as exc:
        raise ObjectParserRefused("raw object snapshot cannot be revalidated") from exc
    ObjectParser._validateClosedContentRoot(root, expected)


def _validateStreamedRawProjection(snapshot: CanonicalObjectSnapshot) -> None:
    _validateStreamedContentProjection(snapshot.raw_root, snapshot.entries)


def _recoverSelectedSnapshot(
    *,
    catalog: CanonicalObjectCatalog,
    snapshot_root: Path,
    max_evidence_bytes: int = 64 * 1024 * 1024,
) -> CanonicalObjectSnapshot | None:
    """Recover the maximal exact snapshot from a monotonic immutable evidence chain."""

    transaction_root = assertNoReparsePath(snapshot_root / catalog.transaction_id)
    destination = transaction_root / "selected"
    try:
        with openNativeDirectory(transaction_root) as transaction:
            transaction_entries = transaction.listEntries()
            selected_entries = [
                entry for entry in transaction_entries if entry.name == "selected"
            ]
            if not selected_entries:
                return None
            if len(selected_entries) != 1 or not selected_entries[0].identity.is_directory:
                raise ObjectParserRefused("selected snapshot root is unsafe")
            selected_expected = selected_entries[0].identity
        raw_root = assertNoReparsePath(destination / "raw")
        with openNativeDirectory(destination) as selected_root:
            if selected_root.identity != selected_expected:
                raise ObjectParserRefused("selected snapshot root identity raced")
            selected_identity = selected_root.identity
            children = selected_root.listEntries()
            snapshot_entries = [entry for entry in children if entry.name == "snapshots"]
            if not snapshot_entries:
                return None
            if len(snapshot_entries) != 1 or not snapshot_entries[0].identity.is_directory:
                raise ObjectParserRefused("selected snapshot evidence directory is unsafe")
            with selected_root.openDirectory(
                "snapshots",
                expected=snapshot_entries[0].identity,
            ) as evidence_root:
                evidence_identity = evidence_root.identity
                evidence_files = evidence_root.listEntries()
                if not evidence_files:
                    raise ObjectParserRefused("selected snapshot evidence chain is empty")
                snapshots: list[CanonicalObjectSnapshot] = []
                total_evidence_bytes = 0
                for entry in evidence_files:
                    match = re.fullmatch(r"([0-9a-f]{64})\.json", entry.name)
                    if (
                        match is None
                        or entry.identity.is_directory
                        or entry.identity.is_reparse
                        or entry.identity.link_count != 1
                    ):
                        raise ObjectParserRefused(
                            "selected snapshot evidence contains an unsafe record"
                        )
                    total_evidence_bytes += entry.identity.size
                    if total_evidence_bytes > max_evidence_bytes:
                        raise ObjectParserRefused(
                            "selected snapshot evidence exceeds its byte quota"
                        )
                    raw = evidence_root.readFile(
                        entry.name,
                        max_bytes=max_evidence_bytes,
                        expected=entry.identity,
                    )
                    try:
                        value = json.loads(raw.decode("utf-8", errors="strict"))
                    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
                        raise ObjectParserRefused(
                            "selected snapshot evidence is not canonical JSON"
                        ) from exc
                    if (
                        not isinstance(value, dict)
                        or set(value)
                        != {
                            "repository_id",
                            "revision",
                            "canonical_attestation_digest",
                            "entries",
                            "policy",
                            "snapshot_digest",
                        }
                        or canonical_json_bytes(value) != raw
                        or not isinstance(value.get("entries"), list)
                    ):
                        raise ObjectParserRefused(
                            "selected snapshot evidence fields are not closed"
                        )
                    try:
                        records = tuple(
                            RawObjectSnapshotEntry(**item)
                            for item in value["entries"]
                            if isinstance(item, dict)
                            and set(item) == {"path", "raw_sha256", "size"}
                        )
                        policy = ManifestPolicy.fromDict(value["policy"])
                        snapshot = CanonicalObjectSnapshot(
                            transaction_id=catalog.transaction_id,
                            repository_id=value["repository_id"],
                            revision=value["revision"],
                            canonical_attestation_digest=value[
                                "canonical_attestation_digest"
                            ],
                            raw_root=raw_root,
                            entries=records,
                            policy=policy,
                        )
                    except (TypeError, ValueError) as exc:
                        raise ObjectParserRefused(
                            "selected snapshot evidence violates its contract"
                        ) from exc
                    if (
                        len(records) != len(value["entries"])
                        or snapshot.repository_id != catalog.repository_id
                        or snapshot.revision != catalog.revision
                        or snapshot.canonical_attestation_digest
                        != catalog.canonical_attestation_digest
                        or snapshot.policy != catalog.policy
                        or snapshot.snapshot_digest != value["snapshot_digest"]
                        or snapshot.snapshot_digest != match.group(1)
                        or snapshot.toDict() != value
                    ):
                        raise ObjectParserRefused(
                            "selected snapshot evidence binding differs"
                        )
                    _validateSelectedSourcePaths(
                        catalog,
                        [record.path for record in records],
                    )
                    snapshots.append(snapshot)
                if (
                    evidence_root.identity != evidence_identity
                    or evidence_root.listEntries() != evidence_files
                ):
                    raise ObjectParserRefused(
                        "selected snapshot evidence raced retained enumeration"
                    )
            if (
                selected_root.identity != selected_identity
                or selected_root.listEntries() != children
            ):
                raise ObjectParserRefused(
                    "selected snapshot root raced retained enumeration"
                )
    except ObjectParserRefused:
        raise
    except (OSError, ValueError) as exc:
        raise ObjectParserRefused("selected snapshot evidence cannot be recovered") from exc

    ordered = sorted(snapshots, key=lambda item: (len(item.entries), item.snapshot_digest))
    prior: dict[str, RawObjectSnapshotEntry] = {}
    for snapshot in ordered:
        current = {entry.path: entry for entry in snapshot.entries}
        if any(current.get(path) != entry for path, entry in prior.items()):
            raise ObjectParserRefused("selected snapshot evidence is not monotonic")
        if len(current) == len(prior) and prior:
            raise ObjectParserRefused("selected snapshot evidence is ambiguous")
        prior = current
    recovered = ordered[-1]
    _validateStreamedRawProjection(recovered)
    return recovered


def captureCanonicalObjectSnapshot(
    *,
    catalog: CanonicalObjectCatalog,
    selected_paths: Collection[str],
    snapshot_root: str | Path,
    previous_snapshot: CanonicalObjectSnapshot | None = None,
    max_selected_bytes: int = 4 * 1024 * 1024 * 1024,
    wall_timeout_seconds: float = 120.0,
    idle_timeout_seconds: float = 15.0,
) -> CanonicalObjectSnapshot:
    """Incrementally copy only contained-locator-selected opaque source files."""

    if not isinstance(catalog, CanonicalObjectCatalog):
        raise TypeError("selected source capture requires a typed catalog")
    if type(max_selected_bytes) is not int or max_selected_bytes < 1:
        raise ValueError("max_selected_bytes must be a positive integer")
    if wall_timeout_seconds <= 0 or idle_timeout_seconds <= 0:
        raise ValueError("selected source capture timeouts must be positive")
    provided_paths = tuple(selected_paths)
    selected = tuple(sorted(set(provided_paths)))
    if (
        not selected
        or len(selected) != len(provided_paths)
    ):
        raise ObjectParserRefused("selected source paths are empty, repeated, or unknown")
    _validateSelectedSourcePaths(catalog, selected)
    selection_by_path = {
        path: _selectedSourceRecord(catalog, path)
        for path in selected
    }
    selected_bytes = sum(length for _record, _offset, length in selection_by_path.values())
    if selected_bytes > max_selected_bytes:
        raise ObjectParserRefused("selected source closure exceeds byte quota")
    try:
        destination_parent = assertNoReparsePath(snapshot_root)
        common = assertNoReparsePath(catalog.git_common_dir)
        canonical_root = assertNoReparsePath(catalog.canonical_root)
    except OSError as exc:
        raise ObjectParserRefused("selected source destination is unsafe") from exc
    destination_parent.mkdir(parents=True, exist_ok=True)
    destination_parent = assertNoReparsePath(destination_parent)
    destination = destination_parent / catalog.transaction_id / "selected"
    raw_root = destination / "raw"
    raw_root.mkdir(parents=True, exist_ok=True)
    raw_root = assertNoReparsePath(raw_root)
    for forbidden in (canonical_root, common):
        try:
            if os.path.commonpath((str(raw_root), str(forbidden))) in {
                str(raw_root),
                str(forbidden),
            }:
                raise ObjectParserRefused("selected source snapshot overlaps canonical storage")
        except ValueError:
            pass
    if previous_snapshot is None:
        prior_entries = {}
    else:
        if (
            previous_snapshot.transaction_id != catalog.transaction_id
            or previous_snapshot.repository_id != catalog.repository_id
            or previous_snapshot.revision != catalog.revision
            or previous_snapshot.canonical_attestation_digest
            != catalog.canonical_attestation_digest
            or previous_snapshot.policy != catalog.policy
            or previous_snapshot.raw_root != raw_root
        ):
            raise ObjectParserRefused("previous selected snapshot binding differs")
        prior_entries = {entry.path: entry for entry in previous_snapshot.entries}
        if not set(prior_entries).issubset(selected):
            raise ObjectParserRefused("selected source frontier cannot move backward")
        _validateStreamedRawProjection(previous_snapshot)
    entries = dict(prior_entries)
    known_digests = {entry.raw_sha256 for entry in prior_entries.values()}
    started = time.monotonic()
    last_progress = started
    try:
        with (
            openNativeDirectory(raw_root) as raw_output,
            openNativeDirectory(common) as common_handle,
        ):
            common_identity = common_handle.identity
            common_entries = _nativeObjectEntries(
                common_handle,
                label="Git common directory",
            )
            object_entries = [entry for entry in common_entries if entry.name == "objects"]
            if len(object_entries) != 1:
                raise ObjectParserRefused("Git common directory has no exact object store")
            with common_handle.openDirectory(
                "objects",
                expected=object_entries[0].identity,
            ) as objects:
                objects_identity = objects.identity
                if (
                    _rawInventory(objects) != catalog.inventory
                    or _inventoryDigest(catalog.inventory) != catalog.inventory_digest
                ):
                    raise ObjectParserRefused("canonical object inventory differs from catalog")
                for path in selected:
                    if path in entries:
                        continue
                    now = time.monotonic()
                    if (
                        now - started > wall_timeout_seconds
                        or now - last_progress > idle_timeout_seconds
                    ):
                        raise ObjectParserRefused("selected source capture exceeded time quota")
                    record, source_offset, source_length = selection_by_path[path]
                    _requireSafeRawRecord(
                        record,
                        max_raw_file_bytes=record.identity.size,
                    )
                    digest, size = _captureRawRecord(
                        objects,
                        raw_output,
                        record,
                        max_bytes=record.identity.size,
                        known_digests=known_digests,
                        source_offset=source_offset,
                        source_length=(
                            None
                            if source_offset == 0 and source_length == record.identity.size
                            else source_length
                        ),
                    )
                    if size != source_length:
                        raise ObjectParserRefused("selected source leaf raced capture")
                    entries[path] = RawObjectSnapshotEntry(
                        path=path,
                        raw_sha256=digest,
                        size=size,
                    )
                    last_progress = time.monotonic()
                if (
                    _rawInventory(objects) != catalog.inventory
                    or objects.identity != objects_identity
                ):
                    raise ObjectParserRefused(
                        "canonical object store drifted during selected capture"
                    )
            if (
                common_handle.identity != common_identity
                or _nativeObjectEntries(
                    common_handle,
                    label="Git common directory",
                )
                != common_entries
            ):
                raise ObjectParserRefused(
                    "Git common directory drifted during selected capture"
                )
    except ObjectParserRefused:
        raise
    except OSError as exc:
        raise ObjectParserRefused("selected canonical source capture failed") from exc
    try:
        live = attestCanonicalRepository(catalog.canonical_root)
    except CanonicalRepositoryRefused as exc:
        raise ObjectParserRefused("canonical repository drifted during selected capture") from exc
    if (
        live.attestation_digest != catalog.canonical_attestation_digest
        or live.repository_id != catalog.repository_id
        or live.head_oid != catalog.revision
    ):
        raise ObjectParserRefused("canonical repository drifted during selected capture")
    snapshot = CanonicalObjectSnapshot(
        transaction_id=catalog.transaction_id,
        repository_id=catalog.repository_id,
        revision=catalog.revision,
        canonical_attestation_digest=catalog.canonical_attestation_digest,
        raw_root=raw_root,
        entries=tuple(entries[path] for path in selected),
        policy=catalog.policy,
    )
    _validateStreamedRawProjection(snapshot)
    snapshots_root = destination / "snapshots"
    snapshots_root.mkdir(parents=True, exist_ok=True)
    snapshots_root = assertNoReparsePath(snapshots_root)
    _createExact(
        snapshots_root / f"{snapshot.snapshot_digest}.json",
        canonical_json_bytes(snapshot.toDict()),
    )
    return snapshot


