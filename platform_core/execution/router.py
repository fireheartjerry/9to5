"""Fail-closed execution-environment selection and finalization.

Local execution is an operator-authorized capability, not a fallback.  Missing,
unknown, unhealthy, or failed backends therefore produce a typed refusal.  A
canonical-landing backend also cannot be finalized through the legacy one-step
surface: it must cross the explicit prepare/complete authority boundary.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  selectEnvironment(spec: dict, subtask: dict, task_state, *, trust_grant: object=None, trust_scope: dict | None=None, trust_authority: object=None) -> ExecutionEnvironment  -- Select exactly one eligible backend
  provision(env: ExecutionEnvironment, *, task_state, subtask, base_dir: str, policy=None) -> 'tuple[ExecutionEnvironment, EnvHandle]'  -- Provision the selected backend without hidden substitution.
  prepare(env: ExecutionEnvironment, handle: EnvHandle, task_state, subtask, *, accepted: bool) -> PreparedFinalization  -- Prepare an immutable candidate or a durable rejection checkpoint.
  complete(env: ExecutionEnvironment, handle: EnvHandle, prepared: PreparedFinalization, *, authorization: object, landing_authority: object) -> FinalizationReceipt  -- Complete a prepared landing only when both evidence authorities exist.
  finalize(env: ExecutionEnvironment, handle: EnvHandle, task_state, subtask, *, accepted: bool=True)  -- Compatibility lifecycle for environments that do not require landing.
DEPENDS-ON: config, notifications.event_bus, platform_core.execution.backends.docker, platform_core.execution.backends.local, platform_core.execution.backends.remote, platform_core.execution.backends.worktree, platform_core.execution.environment, platform_core.execution.trust
SIDE-EFFECTS: emits env_* events on notifications.event_bus (best-effort)
RUN/TEST: python -m pytest tests/execution/test_execution_router.py
"""
from __future__ import annotations

import config
from platform_core.execution.backends.local import LocalEnvironment
from platform_core.execution.environment import (
    EnvHandle,
    EnvironmentUnavailable,
    ExecutionEnvironment,
    FinalizationReceipt,
    PreparedFinalization,
)
from platform_core.execution.trust import tightenWorkloadTrust

LOG = config.getLogger("execution.router")


def _emit(name: str, payload: dict) -> None:
    """Best-effort lifecycle event onto the process bus (Epic 1 trajectory consumes these later)."""
    try:
        from notifications.event_bus import Event, get_bus
        get_bus().emit(Event(kind=name, sid=str(payload.get("sid", "")),
                             text=name, data=payload))
    except Exception:  # noqa: BLE001 -- a bus hiccup must never break a run
        pass


def _backendClass(name: str):
    """Lazy import so a missing optional SDK/module never breaks router import (degrade-clean)."""
    if name == "local":
        return LocalEnvironment
    if name == "worktree":
        from platform_core.execution.backends.worktree import WorktreeEnvironment
        return WorktreeEnvironment
    if name == "docker":
        from platform_core.execution.backends.docker import DockerEnvironment
        return DockerEnvironment
    if name == "remote":
        from platform_core.execution.backends.remote import RemoteEnvironment
        return RemoteEnvironment
    return None


def _policyBackend(spec: dict, subtask: dict) -> "str | None":
    """Epic 4 hook: risk-tier -> backend via config.EXECUTION_BACKEND_BY_RISK. None until Epic 4 lands."""
    risk = (subtask or {}).get("risk_tier") or (spec or {}).get("risk_tier")
    if risk and risk in config.EXECUTION_BACKEND_BY_RISK:
        return config.EXECUTION_BACKEND_BY_RISK[risk]
    return None


_TRUST_SCOPE_FIELDS = frozenset(
    {
        "repository_attestation_digest",
        "expected_base_sha",
        "task_id",
        "acceptance_spec_digest",
        "capability_profile",
    }
)
_ISOLATING_RISK_TIERS = frozenset(
    {"hostile", "untrusted", "unknown", "high", "critical"}
)


def _unavailable(
    backend: str, reason: str, cause: BaseException | None = None
) -> EnvironmentUnavailable:
    return EnvironmentUnavailable(backend, reason, cause=cause)


def _resolveLocalTrust(
    *,
    name: str,
    spec: dict,
    subtask: dict,
    trust_grant: object,
    trust_scope: dict | None,
    trust_authority: object,
):
    if not isinstance(trust_scope, dict) or set(trust_scope) != _TRUST_SCOPE_FIELDS:
        raise _unavailable(name, "exact operator trust scope is missing or malformed")
    resolve = getattr(trust_authority, "resolve", None)
    if not callable(resolve):
        raise _unavailable(name, "live operator trust authority is unavailable")
    try:
        resolved = resolve(grant=trust_grant, **trust_scope)
    except Exception as exc:  # noqa: BLE001 -- authority failure is a refusal
        raise _unavailable(name, f"operator trust validation failed: {exc}", exc) from exc
    resolved = tightenWorkloadTrust(
        resolved,
        model_fields={**(spec or {}), **(subtask or {})},
    )
    if not resolved.local_eligible:
        reason = resolved.refusal_reason or "live exact-scope Local grant was refused"
        raise _unavailable(name, reason)
    return resolved


def selectEnvironment(
    spec: dict,
    subtask: dict,
    task_state,
    *,
    trust_grant: object = None,
    trust_scope: dict | None = None,
    trust_authority: object = None,
) -> ExecutionEnvironment:
    """Select exactly one eligible backend; never silently substitute Local."""
    del task_state
    spec = spec or {}
    subtask = subtask or {}
    explicit = subtask.get("execution_backend") or spec.get("execution_backend")
    fabric_enabled = bool(config.EXECUTION_FABRIC_ENABLED)
    if not fabric_enabled:
        if explicit and str(explicit).strip().lower() != "local":
            requested = str(explicit).strip().lower()
            raise _unavailable(requested, "execution fabric is disabled")
        # A disabled fabric is an explicit Local request.  Repository-local
        # FULL_STACK/config values cannot smuggle in an isolated backend.
        name = "local"
    else:
        name = str(
            explicit
            or _policyBackend(spec, subtask)
            or config.EXECUTION_BACKEND
            or "local"
        ).strip().lower()
    if not name:
        raise _unavailable("<empty>", "backend name is empty")

    risk = str(subtask.get("risk_tier") or spec.get("risk_tier") or "").lower()
    if not explicit and name != "local" and risk in {"trusted", "safe", "low"}:
        # Positive trust labels are untrusted inputs.  Refuse an implicit route
        # whose safety classification depends on one unless an exact Local
        # grant independently establishes the claim.
        _resolveLocalTrust(
            name="local",
            spec=spec,
            subtask=subtask,
            trust_grant=trust_grant,
            trust_scope=trust_scope,
            trust_authority=trust_authority,
        )
    if name == "local":
        try:
            _resolveLocalTrust(
                name=name,
                spec=spec,
                subtask=subtask,
                trust_grant=trust_grant,
                trust_scope=trust_scope,
                trust_authority=trust_authority,
            )
        except EnvironmentUnavailable:
            # A live Local grant may be tightened to an isolated backend, but
            # an explicit Local request is never silently rewritten.
            if explicit or risk not in _ISOLATING_RISK_TIERS:
                raise
            name = str(_policyBackend(spec, subtask) or "docker").lower()

    if name != "local" and not fabric_enabled:
        raise _unavailable(name, "execution fabric is disabled")

    try:
        cls = _backendClass(name)
    except Exception as exc:  # noqa: BLE001 -- preserve optional import cause
        raise _unavailable(name, f"backend loading failed: {exc}", exc) from exc
    if cls is None:
        raise _unavailable(name, "backend is not registered")
    try:
        env = cls()
    except Exception as exc:  # noqa: BLE001 -- constructor failure is typed
        raise _unavailable(name, f"backend construction failed: {exc}", exc) from exc
    try:
        healthy = env.healthCheck()
    except Exception as exc:  # noqa: BLE001 -- health probe failure is typed
        raise _unavailable(name, f"health check failed: {exc}", exc) from exc
    if not healthy:
        raise _unavailable(name, "health check returned false")
    return env


def provision(env: ExecutionEnvironment, *, task_state, subtask, base_dir: str,
              policy=None) -> "tuple[ExecutionEnvironment, EnvHandle]":
    """Provision the selected backend without hidden substitution."""
    try:
        handle = env.provision(task_state=task_state, subtask=subtask,
                               base_dir=base_dir, policy=policy)
        _emit("env_provisioned", {"backend": env.NAME, "work_dir": handle.work_dir,
                                  "meta": handle.meta})
        return env, handle
    except Exception as exc:  # noqa: BLE001 -- translate to a typed refusal
        LOG.warning("%s provision failed (%s)", env.NAME, exc)
        _emit("env_provision_refused", {"backend": env.NAME, "error": str(exc)})
        try:
            if task_state is not None and hasattr(task_state, "addNotification"):
                task_state.addNotification(
                    "execution_fabric", f"{env.NAME} provision failed: {exc}")
        except Exception:  # noqa: BLE001
            pass
        raise _unavailable(
            env.NAME, f"provision failed: {exc}", exc
        ) from exc


def prepare(
    env: ExecutionEnvironment,
    handle: EnvHandle,
    task_state,
    subtask,
    *,
    accepted: bool,
) -> PreparedFinalization:
    """Prepare an immutable candidate or a durable rejection checkpoint."""
    if not handle.requires_canonical_landing:
        return PreparedFinalization(
            backend=env.NAME,
            work_dir=handle.work_dir,
            accepted=accepted,
            runtime_token=handle.runtime_token,
            summary={"canonical_landing_required": False},
        )
    if accepted:
        try:
            prepared = env.prepareChanges(
                handle, task_state=task_state, subtask=subtask
            )
        except Exception as exc:  # noqa: BLE001 -- preserve candidate on failure
            return PreparedFinalization(
                backend=env.NAME,
                work_dir=handle.work_dir,
                accepted=True,
                error=f"staged preparation failed: {exc}",
                summary={"artifact_preserved": True},
                runtime_token=handle.runtime_token,
            )
        if not isinstance(prepared, PreparedFinalization):
            return PreparedFinalization(
                backend=env.NAME,
                work_dir=handle.work_dir,
                accepted=True,
                error="staged preparation returned an invalid contract",
                summary={"artifact_preserved": True},
                runtime_token=handle.runtime_token,
            )
        return prepared

    try:
        recovery = env.checkpointRecovery(
            handle, task_state=task_state, subtask=subtask
        )
    except Exception as exc:  # noqa: BLE001 -- preserve uncheckpointed artifact
        recovery = {
            "available": False,
            "error": f"recovery unavailable: {exc}",
            "artifact_preserved": True,
        }
    if not isinstance(recovery, dict) or recovery.get("available") is not True:
        detail = (
            recovery.get("error", "recovery unavailable")
            if isinstance(recovery, dict)
            else "recovery unavailable: invalid checkpoint response"
        )
        summary = dict(recovery) if isinstance(recovery, dict) else {}
        summary["artifact_preserved"] = True
        return PreparedFinalization(
            backend=env.NAME,
            work_dir=handle.work_dir,
            accepted=False,
            error=str(detail),
            summary=summary,
            runtime_token=handle.runtime_token,
        )
    return PreparedFinalization(
        backend=env.NAME,
        work_dir=handle.work_dir,
        accepted=False,
        summary=dict(recovery),
        runtime_token=handle.runtime_token,
    )


def complete(
    env: ExecutionEnvironment,
    handle: EnvHandle,
    prepared: PreparedFinalization,
    *,
    authorization: object,
    landing_authority: object,
) -> FinalizationReceipt:
    """Complete a prepared landing only when both evidence authorities exist."""
    del handle
    if authorization is None or landing_authority is None:
        return FinalizationReceipt(
            backend=env.NAME,
            accepted=prepared.accepted,
            requires_canonical_landing=True,
            staging_receipt_id=prepared.staging_receipt_id,
            error="authorization required: verification and landing authority are mandatory",
            summary={"artifact_preserved": True},
        )
    try:
        if not env.preparedChangesIntact(prepared):
            return FinalizationReceipt(
                backend=env.NAME,
                accepted=prepared.accepted,
                requires_canonical_landing=True,
                staging_receipt_id=prepared.staging_receipt_id,
                error="prepared candidate is stale or no longer intact",
                summary={"artifact_preserved": True},
            )
        receipt = env.completeChanges(
            prepared,
            promote=prepared.accepted,
            authorization=authorization,
            landing_authority=landing_authority,
        )
    except Exception as exc:  # noqa: BLE001 -- evidence must record refusal
        return FinalizationReceipt(
            backend=env.NAME,
            accepted=prepared.accepted,
            requires_canonical_landing=True,
            staging_receipt_id=prepared.staging_receipt_id,
            error=f"staged completion failed: {exc}",
            summary={"artifact_preserved": True},
        )
    if not isinstance(receipt, FinalizationReceipt):
        return FinalizationReceipt(
            backend=env.NAME,
            accepted=prepared.accepted,
            requires_canonical_landing=True,
            staging_receipt_id=prepared.staging_receipt_id,
            error="staged completion returned an invalid contract",
            summary={"artifact_preserved": True},
        )
    return receipt


def finalize(
    env: ExecutionEnvironment,
    handle: EnvHandle,
    task_state,
    subtask,
    *,
    accepted: bool = True,
):
    """Compatibility lifecycle for environments that do not require landing."""
    if handle.requires_canonical_landing:
        if not accepted:
            return prepare(
                env, handle, task_state, subtask, accepted=False
            )
        return FinalizationReceipt(
            backend=env.NAME,
            accepted=True,
            requires_canonical_landing=True,
            error="staged preparation required before canonical landing",
            summary={"artifact_preserved": True},
        )
    summary: dict = {}
    try:
        summary = env.collectChanges(handle, task_state=task_state, subtask=subtask)
        _emit("env_changes_collected", {"backend": env.NAME, "summary": summary})
    except Exception as exc:  # noqa: BLE001 -- preserve artifact and report failure
        LOG.warning("%s collectChanges failed (%s) -- work left intact", env.NAME, exc)
        try:
            if task_state is not None and hasattr(task_state, "addNotification"):
                task_state.addNotification(
                    "execution_fabric", f"{env.NAME} collectChanges failed; work left intact: {exc}")
        except Exception:  # noqa: BLE001
            pass
        return FinalizationReceipt(
            backend=env.NAME,
            accepted=accepted,
            error=f"collect changes failed: {exc}",
            summary={"artifact_preserved": True},
        )
    try:
        env.teardown(handle)
        _emit("env_teardown", {"backend": env.NAME})
    except Exception as e:  # noqa: BLE001 -- teardown is best-effort (hermes cleanup/__del__)
        LOG.warning("%s teardown failed (%s)", env.NAME, e)
    return summary
