"""Fail-closed workload trust contracts.

Receipts are durable JSON-safe evidence.  Grants deliberately are not: a live
grant contains process-local capability identity and cannot be reconstructed
from receipt bytes.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  WorkloadTrustReceipt  -- Immutable evidence describing one exact-scope grant issuance.
  WorkloadTrustGrant  -- Non-serializable process-local authority paired with a receipt.
  ResolvedWorkloadTrust
  unknownTrust(reason: str) -> ResolvedWorkloadTrust
  resolveWorkloadTrust(*, operator_grant: object, model_fields: Mapping[str, object] | None=None, deterministic_probe: object=None) -> ResolvedWorkloadTrust  -- Resolve untrusted inputs conservatively.
  tightenWorkloadTrust(resolved: ResolvedWorkloadTrust, *, model_fields: Mapping[str, object] | None) -> ResolvedWorkloadTrust  -- Permit untrusted policy fields to reduce, never increase, authority.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/control/test_execution_trust_authority.py tests/evolution/test_reflection_trust.py tests/execution/test_execution_trust.py tests/orchestration/test_adversary_trust.py
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
import hashlib
import json
from typing import Any, Mapping


TRUSTED_LOCAL_PROFILE = "trusted_local"


def _utc(value: datetime) -> datetime:
    if value.tzinfo is None or value.utcoffset() is None:
        raise ValueError("trust timestamps must be timezone-aware")
    return value.astimezone(timezone.utc)


def _timestamp(value: datetime) -> str:
    return _utc(value).isoformat(timespec="microseconds").replace("+00:00", "Z")


def _parse_timestamp(value: object) -> datetime:
    if not isinstance(value, str) or not value:
        raise ValueError("trust timestamp must be non-empty text")
    normalized = value[:-1] + "+00:00" if value.endswith("Z") else value
    return _utc(datetime.fromisoformat(normalized))


def _canonical_json(value: object) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        allow_nan=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")


@dataclass(frozen=True)
class WorkloadTrustReceipt:
    """Immutable evidence describing one exact-scope grant issuance."""

    issuer_id: str
    repository_attestation_digest: str
    expected_base_sha: str
    task_id: str
    acceptance_spec_digest: str
    capability_profile: str
    issued_at: datetime
    expires_at: datetime
    nonce: str
    revocation_generation: int

    def __post_init__(self) -> None:
        text_fields = (
            self.issuer_id,
            self.repository_attestation_digest,
            self.expected_base_sha,
            self.task_id,
            self.acceptance_spec_digest,
            self.capability_profile,
            self.nonce,
        )
        if any(not isinstance(value, str) or not value for value in text_fields):
            raise ValueError("trust receipt text fields must be non-empty")
        issued = _utc(self.issued_at)
        expires = _utc(self.expires_at)
        if expires <= issued:
            raise ValueError("trust receipt expiry must follow issuance")
        if type(self.revocation_generation) is not int or self.revocation_generation < 0:
            raise ValueError("revocation generation must be a non-negative integer")
        object.__setattr__(self, "issued_at", issued)
        object.__setattr__(self, "expires_at", expires)

    @property
    def id(self) -> str:
        return hashlib.sha256(_canonical_json(self.toDict())).hexdigest()

    def toDict(self) -> dict[str, Any]:
        return {
            "issuer_id": self.issuer_id,
            "repository_attestation_digest": self.repository_attestation_digest,
            "expected_base_sha": self.expected_base_sha,
            "task_id": self.task_id,
            "acceptance_spec_digest": self.acceptance_spec_digest,
            "capability_profile": self.capability_profile,
            "issued_at": _timestamp(self.issued_at),
            "expires_at": _timestamp(self.expires_at),
            "nonce": self.nonce,
            "revocation_generation": self.revocation_generation,
        }

    @classmethod
    def fromDict(cls, value: Mapping[str, object]) -> "WorkloadTrustReceipt":
        expected = {
            "issuer_id",
            "repository_attestation_digest",
            "expected_base_sha",
            "task_id",
            "acceptance_spec_digest",
            "capability_profile",
            "issued_at",
            "expires_at",
            "nonce",
            "revocation_generation",
        }
        if not isinstance(value, Mapping) or set(value) != expected:
            raise ValueError("trust receipt has unknown or missing fields")
        generation = value["revocation_generation"]
        if type(generation) is not int:
            raise ValueError("revocation generation must be an integer")
        text = {key: value[key] for key in expected - {"issued_at", "expires_at", "revocation_generation"}}
        if any(not isinstance(item, str) for item in text.values()):
            raise ValueError("trust receipt text field has the wrong type")
        return cls(
            issuer_id=str(value["issuer_id"]),
            repository_attestation_digest=str(value["repository_attestation_digest"]),
            expected_base_sha=str(value["expected_base_sha"]),
            task_id=str(value["task_id"]),
            acceptance_spec_digest=str(value["acceptance_spec_digest"]),
            capability_profile=str(value["capability_profile"]),
            issued_at=_parse_timestamp(value["issued_at"]),
            expires_at=_parse_timestamp(value["expires_at"]),
            nonce=str(value["nonce"]),
            revocation_generation=generation,
        )


@dataclass(frozen=True)
class WorkloadTrustGrant:
    """Non-serializable process-local authority paired with a receipt."""

    receipt: WorkloadTrustReceipt
    capability_profile: str
    _process_capability: object
    _authority_instance_id: str

    @property
    def receipt_id(self) -> str:
        return self.receipt.id


@dataclass(frozen=True)
class ResolvedWorkloadTrust:
    tier: str
    local_eligible: bool
    receipt_id: str | None
    refusal_reason: str | None

    def toDict(self) -> dict[str, object]:
        return {
            "tier": self.tier,
            "local_eligible": self.local_eligible,
            "receipt_id": self.receipt_id,
            "refusal_reason": self.refusal_reason,
        }


def unknownTrust(reason: str) -> ResolvedWorkloadTrust:
    return ResolvedWorkloadTrust(
        tier="unknown",
        local_eligible=False,
        receipt_id=None,
        refusal_reason=reason,
    )


def resolveWorkloadTrust(
    *,
    operator_grant: object,
    model_fields: Mapping[str, object] | None = None,
    deterministic_probe: object = None,
) -> ResolvedWorkloadTrust:
    """Resolve untrusted inputs conservatively.

    A :class:`WorkloadTrustGrant` is intentionally insufficient here because
    only its issuing ``OperatorTrustAuthority`` can validate live identity and
    exact scope.  This helper exists for surfaces that have no authority and
    therefore must remain unknown regardless of labels or probes.
    """

    del operator_grant, model_fields, deterministic_probe
    return unknownTrust("operator trust authority did not validate a live grant")


def tightenWorkloadTrust(
    resolved: ResolvedWorkloadTrust,
    *,
    model_fields: Mapping[str, object] | None,
) -> ResolvedWorkloadTrust:
    """Permit untrusted policy fields to reduce, never increase, authority."""

    if not resolved.local_eligible:
        return resolved
    fields = dict(model_fields or {})
    backend = str(fields.get("execution_backend", "")).strip().lower()
    risk = str(fields.get("risk_tier", "")).strip().lower()
    if backend and backend != "local":
        return ResolvedWorkloadTrust(
            tier="hostile" if backend == "docker" else "unknown",
            local_eligible=False,
            receipt_id=resolved.receipt_id,
            refusal_reason=f"backend {backend!r} tightens trusted Local eligibility",
        )
    if risk in {"hostile", "untrusted", "unknown", "high", "critical"}:
        return ResolvedWorkloadTrust(
            tier="hostile" if risk in {"hostile", "untrusted", "high", "critical"} else "unknown",
            local_eligible=False,
            receipt_id=resolved.receipt_id,
            refusal_reason=f"risk tier {risk!r} tightens trusted Local eligibility",
        )
    return resolved


