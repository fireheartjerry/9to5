"""Capability scoping + sandbox-mount threat model for the execution fabric.

CapabilityPolicy is the per-subtask allow/deny resolved from 9TO5's existing universe
(allowed_paths/hard_boundaries/CORE_PROTECTED_FILES) and -- when present -- the landed Epic 4
semantic action-risk tier (platform_core.runtime.action_risk.RiskTier). validateMounts is a port
of openclaw `validate-sandbox-security.ts`: hard-block bind-mounts whose host path is, or lives
under, a secrets/VCS/cred dir, the docker socket, or a system root; block symlink escapes (realpath
of the nearest existing ancestor); block host/container network modes. Docker/remote backends MUST
call validateMounts in provision().

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  MountSecurityError  -- A requested mount or network mode violates the sandbox threat model.
  CapabilityPolicy  -- Per-subtask resolved capability scope with source provenance (openclaw layered scopes).
  validateMounts(policy: CapabilityPolicy, mounts, *, network_mode: str='bridge') -> None  -- Refuse a backend's requested bind-mounts/network
DEPENDS-ON: config, platform_core.runtime.action_risk
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_execution_security.py
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field

import config

LOG = config.getLogger("execution.security")

# Path COMPONENTS that must NEVER appear in a bind-mount source (openclaw blocked home/VCS set).
# Checked per path segment, so .../user/.aws/credentials is blocked via the ".aws" segment.
_BLOCKED_MOUNT_NAMES = (".env", ".git", ".ssh", ".aws", ".gnupg", ".gpg",
                        ".docker", ".npmrc", ".netrc")
# Substrings that flag a system root or the docker socket directory anywhere in the path.
_BLOCKED_MOUNT_FRAGMENTS = ("docker.sock", "/var/run/docker", "/etc", "/root", "/boot",
                            "/sys", "/proc", "/dev/")
_BLOCKED_NETWORK_MODES = ("host", "container")


class MountSecurityError(RuntimeError):
    """A requested mount or network mode violates the sandbox threat model."""


@dataclass
class CapabilityPolicy:
    """Per-subtask resolved capability scope with source provenance (openclaw layered scopes)."""
    allowed_paths: list = field(default_factory=list)
    hard_boundaries: list = field(default_factory=list)
    network: bool = True
    disallowed_tools: list = field(default_factory=list)
    source: str = "default"

    @classmethod
    def resolve(cls, task_state, subtask) -> "CapabilityPolicy":
        """Derive from the 9TO5 universe + (optional) Epic 4 risk tier. Network on by default."""
        universe = {}
        try:
            if task_state is not None and hasattr(task_state, "universe"):
                universe = task_state.universe() or {}
        except Exception:  # noqa: BLE001
            universe = {}
        allowed = list(universe.get("allowed_paths") or [])
        boundaries = list(universe.get("hard_boundaries")
                          or config.UNIVERSE_DEFAULT_HARD_BOUNDARIES)
        for core in getattr(config, "CORE_PROTECTED_FILES", ()):
            if core not in boundaries:
                boundaries.append(core)
        network = True
        disallowed: list = []
        source = "universe" if universe else "default"
        # Epic 4 seam (optional, guarded): a destructive/unknown risk tier tightens the policy.
        try:
            from platform_core.runtime.action_risk import RiskTier
            risk = (subtask or {}).get("risk_tier")
            risk_value = risk.value if isinstance(risk, RiskTier) else risk
            if risk_value in (RiskTier.DESTRUCTIVE.value, RiskTier.UNKNOWN.value):
                network = False
                source = "risk:" + str(risk_value)
        except Exception:  # noqa: BLE001 -- Epic 4 absent / odd input -> universe-only policy
            pass
        return cls(allowed_paths=allowed, hard_boundaries=boundaries, network=network,
                   disallowed_tools=disallowed, source=source)


def _existingAncestorRealpath(path: str) -> str:
    """Resolve the realpath of the nearest existing ancestor (symlink-escape hardening)."""
    cur = os.path.abspath(path)
    while not os.path.exists(cur):
        parent = os.path.dirname(cur)
        if parent == cur:
            break
        cur = parent
    return os.path.realpath(cur)


def _components(norm_path: str) -> list:
    """Lowercased non-empty path segments of a forward-slash-normalized path."""
    return [seg for seg in norm_path.lower().split("/") if seg]


def _assertSafePath(host_path: str, norm: str) -> None:
    """Raise MountSecurityError if any segment is a blocked name or any fragment is present."""
    if any(seg in _BLOCKED_MOUNT_NAMES for seg in _components(norm)):
        raise MountSecurityError(f"refusing to mount secret/VCS/cred path: {host_path}")
    low = norm.lower()
    if any(frag in low for frag in _BLOCKED_MOUNT_FRAGMENTS):
        raise MountSecurityError(f"refusing to mount system/socket path: {host_path}")


def validateMounts(policy: CapabilityPolicy, mounts, *, network_mode: str = "bridge") -> None:
    """Refuse a backend's requested bind-mounts/network. Raises MountSecurityError on any violation."""
    if network_mode in _BLOCKED_NETWORK_MODES:
        raise MountSecurityError(f"network mode {network_mode!r} is forbidden")
    for raw in (mounts or []):
        host_path = raw if isinstance(raw, str) else (raw[0] if raw else "")
        if not host_path:
            continue
        norm = os.path.normpath(host_path).replace("\\", "/")
        _assertSafePath(host_path, norm)
        # Symlink-escape hardening: re-check through the realpath of the nearest existing ancestor.
        real = _existingAncestorRealpath(host_path).replace("\\", "/")
        _assertSafePath(host_path, real)
