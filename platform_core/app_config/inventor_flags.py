"""Inventor Mega-Build feature flags: the frozen ``InventorFlags`` domain.

Every flag defaults so that the INVENTOR pipeline is either additive-and-cheap (novelty
index, corpus, code-graph, portfolio optimizer -> ON) or fully DARK (QD archive,
generational forks, emitter bandit, auto-run -> OFF). Flag-off must fail open to today's
behavior. Registered as the ``inventor`` domain in ``settings.py`` so every constant is
reachable as ``config.<NAME>`` via the PEP 562 facade.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  InventorFlags  -- Inventor Mega-Build feature flags (Tracks A-D).
DEPENDS-ON: platform_core.app_config._env
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/platform/test_inventor_flags_config.py
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field

from platform_core.app_config._env import _envBool, _envFloat, _envInt

_F = field
_AUTONOMY_MODES = ("proposal", "hybrid", "auto")


def _envChoice(key: str, default: str, choices: tuple[str, ...]) -> str:
    """Env string constrained to ``choices`` (unknown/unset -> default)."""
    raw = (os.getenv(key) or "").strip().lower()
    return raw if raw in choices else default


@dataclass(frozen=True)
class InventorFlags:
    """Inventor Mega-Build feature flags (Tracks A-D)."""

    # --- Track A: finders that invent (novelty index + corpus additive-ON) ---
    NOVELTY_INDEX_ENABLED: bool = _F(default_factory=lambda: _envBool("NOVELTY_INDEX_ENABLED", True))
    NOVELTY_DEDUP_THRESHOLD: float = _F(default_factory=lambda: _envFloat("NOVELTY_DEDUP_THRESHOLD", 0.88))
    NOVELTY_FINDER_FLOOR: float = _F(default_factory=lambda: _envFloat("NOVELTY_FINDER_FLOOR", 0.55))
    INVENTION_CORPUS_ENABLED: bool = _F(default_factory=lambda: _envBool("INVENTION_CORPUS_ENABLED", True))
    INVENTION_CORPUS_TOPK: int = _F(default_factory=lambda: _envInt("INVENTION_CORPUS_TOPK", 3))
    INVENTOR_MODE_ENABLED: bool = _F(default_factory=lambda: _envBool("INVENTOR_MODE_ENABLED", False))
    INVENTOR_EXPLORE_APPROACHES_ENABLED: bool = _F(
        default_factory=lambda: _envBool("INVENTOR_EXPLORE_APPROACHES_ENABLED", True))
    # --- Innovator Excellence: local-only divergent idea generation (ship DARK) ---
    INVENTOR_EXCELLENCE_ENABLED: bool = _F(
        default_factory=lambda: _envBool("INVENTOR_EXCELLENCE_ENABLED", False))
    INVENTOR_MODEL: str = _F(default_factory=lambda: os.getenv("INVENTOR_MODEL", "qwen2.5:7b"))
    INVENTOR_RAW_IDEA_COUNT: int = _F(default_factory=lambda: _envInt("INVENTOR_RAW_IDEA_COUNT", 18))
    INVENTOR_FINAL_IDEA_COUNT: int = _F(default_factory=lambda: _envInt("INVENTOR_FINAL_IDEA_COUNT", 6))
    INVENTOR_TEMPERATURE: float = _F(default_factory=lambda: _envFloat("INVENTOR_TEMPERATURE", 0.9))
    INVENTOR_TOP_P: float = _F(default_factory=lambda: _envFloat("INVENTOR_TOP_P", 0.92))
    INVENTOR_DISCORD_TELEMETRY_ENABLED: bool = _F(
        default_factory=lambda: _envBool("INVENTOR_DISCORD_TELEMETRY_ENABLED", True))
    INVENTOR_DISCORD_FINALISTS_ENABLED: bool = _F(
        default_factory=lambda: _envBool("INVENTOR_DISCORD_FINALISTS_ENABLED", True))
    # --- Track D read-only analysis: additive-ON (never mutate behavior, only score) ---
    CODE_GRAPH_ENABLED: bool = _F(default_factory=lambda: _envBool("CODE_GRAPH_ENABLED", True))
    PORTFOLIO_OPTIMIZER_ENABLED: bool = _F(default_factory=lambda: _envBool("PORTFOLIO_OPTIMIZER_ENABLED", True))
    # --- Track B: QD archive + generational forks + emitter bandit (ship DARK) ---
    QD_ARCHIVE_ENABLED: bool = _F(default_factory=lambda: _envBool("QD_ARCHIVE_ENABLED", False))
    QD_GENERATIONS_ENABLED: bool = _F(default_factory=lambda: _envBool("QD_GENERATIONS_ENABLED", False))
    QD_EMITTER_BANDIT_ENABLED: bool = _F(default_factory=lambda: _envBool("QD_EMITTER_BANDIT_ENABLED", False))
    QD_PARETO_CAP: int = _F(default_factory=lambda: _envInt("QD_PARETO_CAP", 4))
    QD_PLATEAU_PATIENCE: int = _F(default_factory=lambda: _envInt("QD_PLATEAU_PATIENCE", 2))
    EMITTER_UCB_C: float = _F(default_factory=lambda: _envFloat("EMITTER_UCB_C", 1.4))
    SOLUTION_FORK_GENERATIONS: int = _F(default_factory=lambda: _envInt("SOLUTION_FORK_GENERATIONS", 1))
    SOLUTION_FORK_GEN_COST_CEILING_USD: float = _F(
        default_factory=lambda: _envFloat("SOLUTION_FORK_GEN_COST_CEILING_USD", 5.0))
    SOLUTION_FORK_GEN_WALLCLOCK_CEILING_SEC: int = _F(
        default_factory=lambda: _envInt("SOLUTION_FORK_GEN_WALLCLOCK_CEILING_SEC", 3600))
    # --- Track C: hybrid autonomy gate (proposal by default; auto-run DARK) ---
    INVENTION_AUTONOMY: str = _F(default_factory=lambda: _envChoice("INVENTION_AUTONOMY", "proposal", _AUTONOMY_MODES))
    INVENTION_AUTO_RUN_ENABLED: bool = _F(default_factory=lambda: _envBool("INVENTION_AUTO_RUN_ENABLED", False))
    INVENTION_AUTO_NOVELTY_MIN: float = _F(default_factory=lambda: _envFloat("INVENTION_AUTO_NOVELTY_MIN", 0.75))
    INVENTION_AUTO_CONFIDENCE_MIN: float = _F(default_factory=lambda: _envFloat("INVENTION_AUTO_CONFIDENCE_MIN", 0.80))
    INVENTION_AUTO_RISK_MAX: str = _F(default_factory=lambda: _envChoice("INVENTION_AUTO_RISK_MAX", "low",
                                                                         ("low", "medium", "high")))
