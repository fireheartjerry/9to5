"""9TO5 file-system paths: the frozen ``PathsCfg`` domain of the config registry.

Every path derives from the ``_env`` bootstrap: PROJECT_ROOT defaults to the COMPUTED
REPO ROOT (never this package's own directory -- the pre-R12 landmine that made
STATE_DIR/LOG_PATH/EXPERIENCE_DB_PATH resolve inside ``platform_core/app_config/``).
Module-level access (``paths.STATE_DIR``) resolves through the LIVE registry via
PEP 562 ``__getattr__`` so reloads stay visible; ``setattr`` on this module still
wins (test monkeypatching keeps working).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  PathsCfg  -- Every 9TO5 path constant (plus the audit rotation size that rides with them).
  buildPathsCfg() -> PathsCfg  -- Compute every path from env (after loadEnvOnce) + the repo-root bootstrap.
  ensureDirs() -> None  -- Create every directory 9TO5 needs (idempotent)
DEPENDS-ON: platform_core.app_config, platform_core.app_config._env
SIDE-EFFECTS: ensureDirs creates the runtime directory tree
RUN/TEST: python -m pytest tests/orchestration/test_society_coordinator.py tests/orchestration/test_society_off_invariance.py tests/platform/test_config_bootstrap.py tests/slow/test_epic_flags_combined.py
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from platform_core.app_config._env import (
    _envBool,
    _envInt,
    _envPath,
    installRoot,
    loadEnvOnce,
    projectRoot,
)


@dataclass(frozen=True)
class PathsCfg:
    """Every 9TO5 path constant (plus the audit rotation size that rides with them)."""

    # --- core roots ---
    PROJECT_ROOT: Path
    LOG_PATH: Path
    INSTALL_ROOT: Path            # durable home of vault/logs/knowledge, worktree-independent
    # --- living Claude Code knowledge base ---
    KNOWLEDGE_DIR: Path
    CLAUDE_KNOWLEDGE_PATH: Path
    CLAUDE_RECOMMENDATIONS_PATH: Path
    CLAUDE_SCAN_ROOTS: tuple[Path, ...]   # roots scanned recursively for installed .claude surfaces
    # --- Obsidian vault ---
    OBSIDIAN_VAULT_PATH: Path
    VAULT_DISK_ROOT: Path         # physical folder that actually contains ``.obsidian/``
    # --- task state and control ---
    STATE_DIR: Path
    CONTROL_DIR: Path
    HEARTBEAT_DIR: Path           # liveness heartbeats -- one JSON per run + gateway bot (R9)
    LAUNCH_DIR: Path              # launch handshake files (work_launcher <-> main --launch-id) (R9)
    IPC_DIR: Path                 # cross-process IPC (Live Terminal nav/mirror), OUTSIDE state/tasks (R9)
    BLACKBOARD_DIR: Path          # Agent Society / Workforce (Epic 5) blackboard
    # --- SIE / learning ---
    EXPERIENCE_DB_PATH: Path
    # --- Human-Nature layer (mirrors EXPERIENCE_DB_PATH location) ---
    CONVICTION_DB_PATH: Path      # ledger-grounded conviction/calibration history
    AB_HARNESS_DB_PATH: Path      # behaviour-coupling A/B validation runs
    EVAL_SUITE_DIR: Path
    EVOLUTION_SUITE_DIR: Path     # Epic 7 evolution (flags + ints live in llm.py)
    EVOLUTION_SKILL_DIR: Path
    EVOLUTION_CANDIDATE_DIR: Path
    LORA_OUTPUT_DIR: Path
    # --- adversary + meta-optimizer ---
    ADVERSARY_TRUST_LOG: Path
    SIE_OVERRIDES_PATH: Path
    # --- audit log (who issued which control command) ---
    AUDIT_LOG_PATH: Path
    # --- Claude Code primitives ---
    CLAUDE_DIR: Path
    CLAUDE_SETTINGS_PATH: Path
    VENV_PYTHON: Path             # absolute venv python so hooks run with our deps regardless of cwd
    # --- state retention sweep (best-effort GC of per-run artifacts) ---
    ARCHIVE_DIR: Path
    # --- literal defaults ---
    AUDIT_MAX_BYTES: int = 1_000_000   # rotate audit.jsonl past ~1 MB
    TASKS_DIR_REL: str = "tasks"
    SESSIONS_DIR_REL: str = "sessions"
    # The blackboard/compaction dirs accumulate one file per run and were never pruned;
    # terminal task/control JSON is archived (never deleted) past a longer horizon.
    RETENTION_ENABLED: bool = True
    RETENTION_KEEP_RECENT: int = 10
    RETENTION_MAX_AGE_DAYS: int = 14
    RETENTION_ARCHIVE_AGE_DAYS: int = 30

    def requiredDirs(self) -> tuple[Path, ...]:
        """Directories that must exist for a run (see ensureDirs)."""
        return (self.LOG_PATH, self.STATE_DIR, self.CONTROL_DIR, self.HEARTBEAT_DIR,
                self.LAUNCH_DIR, self.IPC_DIR, self.CLAUDE_DIR, self.VAULT_DISK_ROOT,
                self.VAULT_DISK_ROOT / self.TASKS_DIR_REL,
                self.VAULT_DISK_ROOT / self.SESSIONS_DIR_REL)


def buildPathsCfg() -> PathsCfg:
    """Compute every path from env (after loadEnvOnce) + the repo-root bootstrap."""
    loadEnvOnce()
    root = projectRoot()
    install = installRoot()
    knowledge_dir = _envPath("KNOWLEDGE_DIR") or install / "knowledge"
    vault = _envPath("OBSIDIAN_VAULT_PATH") or root / "vault"
    state = root / "state"
    return PathsCfg(
        PROJECT_ROOT=root,
        LOG_PATH=_envPath("LOG_PATH") or root / "logs",
        INSTALL_ROOT=install,
        KNOWLEDGE_DIR=knowledge_dir,
        CLAUDE_KNOWLEDGE_PATH=knowledge_dir / "claude_code.md",
        CLAUDE_RECOMMENDATIONS_PATH=knowledge_dir / "recommendations.md",
        CLAUDE_SCAN_ROOTS=(install / ".claude", root / ".claude"),
        OBSIDIAN_VAULT_PATH=vault,
        VAULT_DISK_ROOT=vault / "9to5",
        STATE_DIR=state / "tasks",
        CONTROL_DIR=state / "control",
        HEARTBEAT_DIR=state / "heartbeats",
        LAUNCH_DIR=state / "launch",
        IPC_DIR=state / "ipc",
        BLACKBOARD_DIR=state / "blackboard",
        EXPERIENCE_DB_PATH=state / "experience.db",
        CONVICTION_DB_PATH=state / "conviction.db",
        AB_HARNESS_DB_PATH=state / "ab_runs.db",
        EVAL_SUITE_DIR=root / "learning" / "eval_suite",
        EVOLUTION_SUITE_DIR=state / "evolution" / "eval_suite",
        EVOLUTION_SKILL_DIR=root / ".claude" / "skills" / "evolved",
        EVOLUTION_CANDIDATE_DIR=state / "evolution" / "candidates",
        LORA_OUTPUT_DIR=_envPath("LORA_OUTPUT_DIR") or state / "adapters",
        ADVERSARY_TRUST_LOG=state / "adversary_trust.jsonl",
        SIE_OVERRIDES_PATH=state / "sie_overrides.json",
        AUDIT_LOG_PATH=state / "audit.jsonl",
        CLAUDE_DIR=root / ".claude",
        CLAUDE_SETTINGS_PATH=root / ".claude" / "settings.json",
        VENV_PYTHON=root / "venv" / "Scripts" / "python.exe",
        # --- state retention sweep (best-effort GC of per-run artifacts) ---
        ARCHIVE_DIR=state / "archive",
        RETENTION_ENABLED=_envBool("RETENTION_ENABLED", True),
        RETENTION_KEEP_RECENT=_envInt("RETENTION_KEEP_RECENT", 10),
        RETENTION_MAX_AGE_DAYS=_envInt("RETENTION_MAX_AGE_DAYS", 14),
        RETENTION_ARCHIVE_AGE_DAYS=_envInt("RETENTION_ARCHIVE_AGE_DAYS", 30),
    )


def ensureDirs() -> None:
    """Create every directory 9TO5 needs (idempotent). Reads the LIVE registry."""
    from platform_core.app_config import settings as _settings
    for d in _settings.settings().paths.requiredDirs():
        Path(d).mkdir(parents=True, exist_ok=True)


def __getattr__(name: str):
    """PEP 562: ``paths.STATE_DIR`` etc. resolve from the live registry. A value
    setattr'd onto this module (test monkeypatching) shadows this and wins."""
    from platform_core.app_config import settings as _settings
    return _settings.lookupDomain(("paths",), name)
