def ensureDirs() -> None:
    """Create every directory 9TO5 needs (idempotent). Reads the LIVE registry."""
    # Refuse a pending/poisoned/installed runtime before resolving even one
    # legacy setting or path.  Keep the absence permit across every mkdir so a
    # controller install cannot race the legacy directory tree into existence.
    with _bootstrap_env._runtimeAbsencePermit():
        if controllerPathsActive():
            raise RuntimeError("installed controller owns runtime directory creation")
        from platform_core.app_config import settings as _settings

        for d in _settings.settings().paths.requiredDirs():
            _legacyConfigPathMutation(Path(d).mkdir, parents=True, exist_ok=True)


def __getattr__(name: str):
    """PEP 562: ``paths.STATE_DIR`` etc. resolve from the live registry. A value
    setattr'd onto this module (test monkeypatching) shadows this and wins."""
    if name.startswith("__"):
        raise AttributeError(name)
    from platform_core.app_config import settings as _settings

    return _settings.lookupDomain(("paths",), name)
