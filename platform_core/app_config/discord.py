"""9TO5 Discord credentials, limits, branding, surface flags: the ``DiscordCfg`` domain.

Frozen registry dataclass + builder. Module-level access resolves through the live
registry via PEP 562 ``__getattr__``; setattr on this module still wins (tests).
NIGHT_MODE / WEB_DASHBOARD / WEB_DASHBOARD_PORT here are the *coded/env defaults*;
the run-scoped live values main.py pokes live in ``settings.runFlags()``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  DiscordCfg
  buildDiscordCfg() -> DiscordCfg  -- Construct from env
DEPENDS-ON: platform_core.app_config, platform_core.app_config._env
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/test_discord_rest.py tests/test_discord_surfaces.py
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field

from platform_core.app_config._env import _envBool, _envInt, loadEnvOnce


def _envSnowflake(key: str) -> int:
    """Discord id from env; non-numeric/absent -> 0 (never crashes import)."""
    raw = os.getenv(key, "0") or "0"
    return int(raw) if raw.isdigit() else 0


@dataclass(frozen=True)
class DiscordCfg:
    # --- credentials + channel ids (builder-computed) ---
    DISCORD_BOT_TOKEN: str = field(default_factory=lambda: os.getenv("DISCORD_BOT_TOKEN", ""))
    DISCORD_CHANNEL_ID: int = field(default_factory=lambda: _envSnowflake("DISCORD_CHANNEL_ID"))
    # Human to @-ping for severe events only (blocked / critical decision / deadlock abort).
    DISCORD_HUMAN_USER_ID: str = field(default_factory=lambda: os.getenv("DISCORD_HUMAN_USER_ID", ""))
    # Guild for instant slash-command registration; 0 => global (~1h to propagate).
    DISCORD_GUILD_ID: int = field(default_factory=lambda: _envSnowflake("DISCORD_GUILD_ID"))

    # --- Discord hard limits (single source of truth for all truncation/clamping) ---
    DISCORD_MAX_CONTENT: int = 2000
    DISCORD_MAX_EMBED_DESC: int = 4096
    DISCORD_MAX_FIELD_NAME: int = 256
    DISCORD_MAX_FIELD_VALUE: int = 1024
    DISCORD_EMBED_TOTAL_MAX: int = 6000
    DISCORD_REST_TIMEOUT: int = 15      # seconds per Discord REST call
    DISCORD_RETRY_MAX: int = 2          # 429 retries for milestone sends (NOT the control poll)

    # --- bot identity / branding ---
    VERSION: str = "1.0.0"
    BRAND_COLOR: int = 0x5865F2                      # 9TO5 brand (Discord blurple)
    BRAND_ICON_URL: str = field(default_factory=lambda: os.getenv("BRAND_ICON_URL", ""))

    # --- bot UX behaviour ---
    COOLDOWN_RATE: int = 3                            # max mutating-command uses ...
    COOLDOWN_PER: float = 10.0                        # ... per this many seconds, per user
    PRESENCE_INTERVAL: int = 30                       # seconds between presence refreshes

    # --- run control + live dashboards ---
    DISCORD_POLL_SECONDS: int = 4         # poll the channel for control commands between steps
    DISCORD_DASHBOARD: bool = True        # one self-updating embed per run
    WEB_DASHBOARD: bool = True            # run-scoped live value: settings.runFlags()
    WEB_DASHBOARD_PORT: int = 8787        # run-scoped live value: settings.runFlags()

    # --- Discord lab (frontier surface; master switch DISCORD_LAB_MODE) ---
    DISCORD_LAB_MODE: bool = field(default_factory=lambda: _envBool("DISCORD_LAB_MODE", False))
    DASHBOARD_CV2: bool = field(default_factory=lambda: _envBool("DASHBOARD_CV2", True))
    CAST_MODE: bool = False               # multi-agent webhook personas ("The Cast"); lab-gated
    ASK_ENABLED: bool = field(default_factory=lambda: _envBool("ASK_ENABLED", True))
    ASK_NL_CONTROL: bool = False          # natural-language control (guarded, audited); lab-gated
    POLL_GATES: bool = False              # native Poll approvals in gated mode; lab-gated
    RUN_THREADS: bool = False             # forum/thread-per-run; lab-gated
    SCHEDULED_EVENTS: bool = False        # Scheduled Event for the 9-5 window; lab-gated
    AUTOMOD_GUARD: bool = False           # AutoMod safety rule on the control channel; lab-gated
    REACTION_APPROVE: bool = field(default_factory=lambda: _envBool("REACTION_APPROVE", True))
    WATCHDOG_ENABLED: bool = field(default_factory=lambda: _envBool("WATCHDOG_ENABLED", True))
    VISUALS_ENABLED: bool = field(default_factory=lambda: _envBool("VISUALS_ENABLED", True))
    COCKPIT_THEME: str = field(default_factory=lambda: os.getenv("COCKPIT_THEME", "dark"))
    # Throttle the cockpit's Pillow hero-image upload (text-CV2 edits still flow freely).
    COCKPIT_IMAGE_MIN_INTERVAL: int = field(
        default_factory=lambda: _envInt("COCKPIT_IMAGE_MIN_INTERVAL", 30))

    # --- Components V2 transport limits (cv2.py + discord_bot._clampComponents) ---
    DISCORD_MSGFLAG_COMPONENTS_V2: int = 1 << 15   # 32768 -- IS_COMPONENTS_V2 message flag
    DISCORD_CV2_MAX_COMPONENTS: int = 40           # total components across the CV2 message tree
    DISCORD_CV2_MAX_CHARS: int = 4000              # total text length across a CV2 message

    # --- night mode (zero human interaction; run-scoped live value: settings.runFlags()) ---
    # Forces watch mode, disables adversary PR hold, auto-resumes pauses, suppresses @-pings.
    NIGHT_MODE: bool = field(default_factory=lambda: _envBool("NIGHT_MODE", False))
    NIGHT_MODE_PAUSE_TIMEOUT: int = field(
        default_factory=lambda: _envInt("NIGHT_MODE_PAUSE_TIMEOUT", 600))  # 10 min

    # --- status palette ("Nightclaw Ops Console", GitHub-dark; embeds + CV2 accent) ---
    STATUS_COLORS: dict[str, int] = field(default_factory=lambda: {
        "created": 0x8B949E, "starting": 0x8B949E,       # muted gray
        "architecting": 0x58A6FF,                        # info blue = architect/plan phase
        "planning": 0x58A6FF,
        "executing": 0x3FB950, "running": 0x3FB950,      # success green = running
        "verifying": 0x3FB950,
        "adversary": 0xDB6D28,                           # orange = adversary reviewing
        "replanning": 0xBC8CFF,                          # purple = replanning
        "paused": 0xD29922,                              # amber = paused/awaiting
        "blocked": 0xF85149,                             # red = blocked
        "failed": 0xF85149,
        "aborted": 0xC93C37,                             # dark red
        "done": 0x3FB950, "complete": 0x3FB950, "partial": 0xD29922,
    })


def buildDiscordCfg() -> DiscordCfg:
    """Construct from env; the lab-gated flags default to DISCORD_LAB_MODE but each can
    still be overridden individually in .env."""
    loadEnvOnce()
    lab = _envBool("DISCORD_LAB_MODE", False)
    return DiscordCfg(
        CAST_MODE=_envBool("CAST_MODE", lab),
        ASK_NL_CONTROL=_envBool("ASK_NL_CONTROL", lab),
        POLL_GATES=_envBool("POLL_GATES", lab),
        RUN_THREADS=_envBool("RUN_THREADS", lab),
        SCHEDULED_EVENTS=_envBool("SCHEDULED_EVENTS", lab),
        AUTOMOD_GUARD=_envBool("AUTOMOD_GUARD", lab),
    )


def __getattr__(name: str):
    """PEP 562: live-registry resolution for module-level constant access."""
    from platform_core.app_config import settings as _settings
    return _settings.lookupDomain(("discord",), name)
