from __future__ import annotations

import importlib
from typing import Any

_SUBMODULES = ("settings", "paths", "discord", "llm", "_env")


def __getattr__(name: str) -> Any:
    # Serve submodules explicitly: `from platform_core.app_config import settings`
    # probes the package attribute (PEP 562) BEFORE importing the submodule -- without
    # this branch that probe would recurse into the registry lookup below.
    if name in _SUBMODULES:
        return importlib.import_module(f"platform_core.app_config.{name}")
    _settings = importlib.import_module("platform_core.app_config.settings")
    if name == "getLogger":
        return _settings.getLogger
    if name == "ensureDirs":
        return importlib.import_module("platform_core.app_config.paths").ensureDirs
    try:
        return _settings.lookup(name)
    except AttributeError:
        raise AttributeError(f"module 'platform_core.app_config' has no attribute {name!r}") from None
