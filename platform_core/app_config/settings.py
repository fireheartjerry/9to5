@dataclass(frozen=True)
class Settings:
    """The whole typed registry: one frozen composite per process (swap-on-override)."""

    paths: PathsCfg
    ollama: OllamaCfg
    claude_cli: ClaudeCliCfg
    discord: DiscordCfg
    sie: SieCfg
    epic: EpicFlags
    inventor: InventorFlags
    prompts: PromptsCfg


_DOMAINS: tuple[str, ...] = ("paths", "ollama", "claude_cli", "discord", "sie", "epic",
                             "inventor", "prompts")

