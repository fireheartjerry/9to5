def _withinBounds(bounds: dict, knob: str, value: Any) -> bool:
    lo, hi = bounds.get(knob, (float("-inf"), float("inf")))
    try:
        return lo <= float(value) <= hi
    except (TypeError, ValueError):
        return False


def _applyOverridesLayer(s: Settings) -> Settings:
    """sie_overrides.json as a first-class build layer (whitelisted + bounds-checked).
    Absent/corrupt file -> stock defaults; out-of-band values are skipped LOUDLY."""
    from platform_core.core import fsio
    try:   # absent or EMPTY file -> stock defaults, silently (matches the old loader)
        if s.paths.SIE_OVERRIDES_PATH.stat().st_size == 0:
            return s
    except OSError:
        return s
    data = fsio.loadJson(s.paths.SIE_OVERRIDES_PATH, None)
    if not isinstance(data, dict):
        return s
    valid: dict[str, Any] = {}
    for knob, value in data.items():
        if knob not in s.sie.SIE_TUNABLE_KNOBS:
            continue
        if not _withinBounds(s.sie.SIE_BOUNDS, knob, value):
            _LOG.warning("sie_overrides: skipping %s=%r — out of bounds %s",
                         knob, value, s.sie.SIE_BOUNDS.get(knob))
            continue
        valid[knob] = value
    return replace(s, sie=replace(s.sie, **valid)) if valid else s


def buildSettings() -> Settings:
    """Fresh registry: coded defaults < .env (loadEnvOnce) < sie_overrides.json."""
    loadEnvOnce()
    s = Settings(paths=buildPathsCfg(), ollama=buildOllamaCfg(),
                 claude_cli=buildClaudeCliCfg(), discord=buildDiscordCfg(),
                 sie=buildSieCfg(), epic=EpicFlags(), inventor=InventorFlags(),
                 prompts=PromptsCfg())
    return _applyOverridesLayer(s)


_LOCK = threading.Lock()
_SETTINGS: Optional[Settings] = None
_NAME_MAP: Optional[dict[str, str]] = None   # ALL_CAPS constant name -> domain attr


def settings() -> Settings:
    """The process-wide registry singleton (lazy, thread-safe)."""
    global _SETTINGS
    if _SETTINGS is None:
        with _LOCK:
            if _SETTINGS is None:
                _SETTINGS = buildSettings()
    return _SETTINGS


def _nameMap() -> dict[str, str]:
    global _NAME_MAP
    if _NAME_MAP is None:
        s = settings()
        m: dict[str, str] = {}
        for dom in _DOMAINS:
            for f in fields(getattr(s, dom)):
                if f.name in m:   # a duplicate name would make lookup ambiguous -- hard error
                    raise RuntimeError(f"config registry: duplicate constant {f.name!r} "
                                       f"in domains {m[f.name]!r} and {dom!r}")
                m[f.name] = dom
        _NAME_MAP = m
    return _NAME_MAP


def allNames() -> list[str]:
    """Every legacy ALL_CAPS constant name the registry serves (for the facade __all__/__dir__)."""
    return sorted(list(_nameMap()) + list(_RUN_FLAG_NAMES))


def lookup(name: str) -> Any:
    """Constant by legacy name; run-scoped flags route to the live RunFlags object."""
    if name in _RUN_FLAG_NAMES:
        return getattr(runFlags(), name)
    dom = _nameMap().get(name)
    if dom is None:
        raise AttributeError(f"unknown config constant {name!r}")
    current = settings()
    value = getattr(getattr(current, dom), name)
    if current.epic.GALAXY_R3_POLICY_ENFORCEMENT_ENABLED and isinstance(value, bool):
        is_human_nature_coupling = name.startswith("HN_")
        is_external_council_seat = name.startswith("PRE_EXECUTION_COUNCIL_LIVE_")
        if name in _GALAXY_BEHAVIOR_FLAGS or is_human_nature_coupling or is_external_council_seat:
            return False
    return value


def lookupDomain(domains: tuple[str, ...], name: str) -> Any:
    """lookup() restricted to the given domains (PEP 562 seam for the domain modules)."""
    if name in _RUN_FLAG_NAMES:
        return getattr(runFlags(), name)
    dom = _nameMap().get(name)
    if dom is None or dom not in domains:
        raise AttributeError(f"no config constant {name!r} in domains {domains}")
    return lookup(name)


# ---------------------------------------------------------------------------
# Run-scoped flags: the ONLY mutable config surface. main.py CLI overrides land
# here (never on config module globals); the facade routes these four names here.
# ---------------------------------------------------------------------------

_RUN_FLAG_NAMES: tuple[str, ...] = ("NIGHT_MODE", "WEB_DASHBOARD", "WEB_DASHBOARD_PORT",
                                    "CLAUDE_DOC_FETCH")


@dataclass
class RunFlags:
    NIGHT_MODE: bool
    WEB_DASHBOARD: bool
    WEB_DASHBOARD_PORT: int
    CLAUDE_DOC_FETCH: bool


_RUN_FLAGS: Optional[RunFlags] = None


def runFlags() -> RunFlags:
    """The run-scoped flag singleton, seeded from the registry's coded/env defaults."""
    global _RUN_FLAGS
    if _RUN_FLAGS is None:
        s = settings()   # build OUTSIDE the lock (settings() takes _LOCK; it is not reentrant)
        with _LOCK:
            if _RUN_FLAGS is None:
                _RUN_FLAGS = RunFlags(NIGHT_MODE=s.discord.NIGHT_MODE,
                                      WEB_DASHBOARD=s.discord.WEB_DASHBOARD,
                                      WEB_DASHBOARD_PORT=s.discord.WEB_DASHBOARD_PORT,
                                      CLAUDE_DOC_FETCH=s.claude_cli.CLAUDE_DOC_FETCH)
    return _RUN_FLAGS


def reload() -> Settings:
    """Rebuild the registry from the current env + overrides file and reseed run flags.
    For tests; production never reloads mid-process."""
    global _SETTINGS, _RUN_FLAGS
    with _LOCK:
        _SETTINGS = buildSettings()
        _RUN_FLAGS = None
    return _SETTINGS


# ---------------------------------------------------------------------------
# Meta-optimizer overrides: live registry swap + atomic persistence.
# ---------------------------------------------------------------------------

def setOverride(knob: str, value: Any) -> tuple[bool, bool]:
    """Live-apply + persist a whitelisted, bounds-checked SIE knob.

    Returns ``(live_applied, persisted)``: unknown/out-of-band knobs -> (False, False);
    a persistence failure still leaves the live registry updated -> (True, False),
    matching the historical config.set_override semantics."""
    global _SETTINGS
    s = settings()
    if knob not in s.sie.SIE_TUNABLE_KNOBS or not _withinBounds(s.sie.SIE_BOUNDS, knob, value):
        return False, False
    with _LOCK:
        cur = _SETTINGS if _SETTINGS is not None else s
        _SETTINGS = replace(cur, sie=replace(cur.sie, **{knob: value}))
    try:
        from platform_core.core import fsio
        # Honor an explicit shadow on the root facade (tests patch config.SIE_OVERRIDES_PATH;
        # a patched attr lives in vars(), unpatched reads route through __getattr__ -> here).
        # Without this the persistence path ignored the patch and wrote the REAL state file.
        _cfg = sys.modules.get("config")
        path = (_cfg and vars(_cfg).get("SIE_OVERRIDES_PATH")) or settings().paths.SIE_OVERRIDES_PATH
        data = fsio.loadJson(path, {})
        if not isinstance(data, dict):
            data = {}
        data[knob] = value
        fsio.atomicWriteJson(path, data)
        return True, True
    except Exception:  # noqa: BLE001 -- caller decides how loud to be
        return True, False


# ---------------------------------------------------------------------------
# Logging (was config._configureLogging; lives here so platform_core modules can
# log without importing the root facade).
# ---------------------------------------------------------------------------

_LOGGER_CONFIGURED = False
_LOGGER_CONFIG_LOCK = threading.Lock()
_LOG_MAX_BYTES = 10 * 1024 * 1024   # 10MB per file, 5 rotated backups
_LOG_BACKUP_COUNT = 5


def _logLevelFromEnv() -> int:
    """NINE_TO_FIVE_LOG_LEVEL env knob (DEBUG/INFO/WARNING/ERROR/CRITICAL or a number);
    unset or unparseable -> INFO. This is what finally makes LOG.debug diagnostics reachable."""
    raw = (os.getenv("NINE_TO_FIVE_LOG_LEVEL") or "").strip().upper()
    if not raw:
        return logging.INFO
    if raw.isdigit():
        return int(raw)
    level = logging.getLevelName(raw)
    return level if isinstance(level, int) else logging.INFO


def _configureLogging() -> None:
    """BUG-016: the check-and-set on _LOGGER_CONFIGURED must be lock-protected -- otherwise
    two threads racing this at import time both pass the flag check and each add a
    FileHandler/StreamHandler, doubling every log line for the rest of the process."""
    global _LOGGER_CONFIGURED
    with _LOGGER_CONFIG_LOCK:
        if _LOGGER_CONFIGURED:
            return
        _configureLoggingLocked()
        _LOGGER_CONFIGURED = True


def _configureLoggingLocked() -> None:
    from logging.handlers import RotatingFileHandler

    class _SharedLogRotatingHandler(RotatingFileHandler):
        """Multi-process safe on Windows: the orchestrator, gateway bot, and web
        dashboard all hold 9to5.log, so rollover's os.rename can hit WinError 32.
        Skip that rotation attempt (the file grows past the cap until the sole
        holder rotates) instead of spraying 'Logging error' tracebacks per emit."""

        def rotate(self, source: str, dest: str) -> None:
            try:
                super().rotate(source, dest)
            except OSError:
                pass

    # NINE_TO_FIVE_LOG_DIR redirects the log FileHandler (read live so conftest's sandbox works; prod uses LOG_PATH).
    _override = os.getenv("NINE_TO_FIVE_LOG_DIR", "").strip()
    log_dir = Path(_override) if _override else settings().paths.LOG_PATH
    log_dir.mkdir(parents=True, exist_ok=True)
    fmt = logging.Formatter("%(asctime)s [%(levelname)s] %(name)s: %(message)s")
    base = logging.getLogger("9to5")
    base.setLevel(_logLevelFromEnv())
    fh = _SharedLogRotatingHandler(log_dir / "9to5.log", maxBytes=_LOG_MAX_BYTES,
                                   backupCount=_LOG_BACKUP_COUNT, encoding="utf-8",
                                   delay=True)
    fh.setFormatter(fmt)
    ch = logging.StreamHandler()
    ch.setFormatter(fmt)
    base.addHandler(fh)
    base.addHandler(ch)
    base.propagate = False


def getLogger(name: str = "9to5") -> logging.Logger:
    """Return a child of the configured ``9to5`` logger."""
    _configureLogging()
    full = name if name.startswith("9to5") else f"9to5.{name}"
    return logging.getLogger(full)
