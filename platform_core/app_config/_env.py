"""Env bootstrap + never-crash env-coercion helpers (single home for BOTH).

THE one place in the tree that touches ``.env`` and computes the repo root:

* ``locateRepoRoot()`` walks UP from this file to the first ``.git``/``pyproject.toml``
  marker, so PROJECT_ROOT never depends on cwd and never collapses to the package dir
  (the old default was ``platform_core/app_config/`` itself -- the R12 landmine).
* ``loadEnvOnce()`` loads ``INSTALL_ROOT/.env`` then ``<repo>/.env`` exactly once per
  process (idempotent, thread-safe). Real process env vars always win (load_dotenv
  never overrides existing keys).
* ``projectRoot()`` honours a PROJECT_ROOT set on the PROCESS environment, but a
  PROJECT_ROOT line inside a ``.env`` file is deliberately inert: the shared install
  ``.env`` (C:\\9to5\\.env sets PROJECT_ROOT=C:\\9to5) must never re-point a checkout
  at a different tree.
* ``_envBool/_envInt/_envFloat/_envPath/_envTuple`` are the never-crash readers used
  by every app_config domain module (single-homed here; do not copy them).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ControllerConfigPosture  -- Typed, fail-closed configuration facts installed by the boot capsule.
  controllerConfigActive() -> bool
  locateRepoRoot() -> Path  -- Repo root = nearest ancestor of THIS FILE containing ``.git`` (dir or worktree
  installRoot() -> Path  -- Install root from the process env (INSTALL_ROOT) or the C:\\9to5 default.
  loadEnvOnce() -> None  -- Load ``.env`` exactly once per process: INSTALL_ROOT/.env first (durable install
  projectRoot() -> Path  -- This checkout's root
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: loadEnvOnce mutates os.environ from .env files (never overriding existing keys)
RUN/TEST: python -m pytest tests/execution/test_completion_envelope.py tests/execution/test_execution_environment.py tests/orchestration/test_execute_mixin_env.py
"""
from __future__ import annotations

import importlib
import os
import sys
import threading
from contextlib import AbstractContextManager, contextmanager
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType
from typing import Callable, Iterator, TypeVar, overload

from dotenv import load_dotenv

# Durable home of vault/logs/knowledge + the production .env, independent of checkout.
DEFAULT_INSTALL_ROOT: Path = Path(r"C:\9to5")

_THIS_FILE = Path(__file__).resolve()
_ENV_LOCK = threading.RLock()
_ENV_LOADED = False
# PROJECT_ROOT as provided by the REAL process environment, captured BEFORE any .env
# load so a .env-file PROJECT_ROOT can never masquerade as a process-level override.
_PROCESS_PROJECT_ROOT: "str | None" = None
_T = TypeVar("_T")


def _controllerStateModule() -> ModuleType:
    controller_state_module = sys.modules.get("platform_core.runtime.controller_state")
    if controller_state_module is None:
        # This dependency is intentionally lazy: ``controller_state`` itself has
        # a stdlib/fsio-only import surface, so loading it here closes the
        # pre-import race without pulling normal app configuration into the
        # trusted module's initialization path.
        controller_state_module = importlib.import_module(
            "platform_core.runtime.controller_state"
        )
    return controller_state_module


def _runtimeAbsencePermit() -> AbstractContextManager[None]:
    """Materialize and retain the controller runtime's exact-absence boundary."""

    controller_state_module = _controllerStateModule()
    permit_factory = getattr(
        controller_state_module,
        "controllerRuntimeStateAbsentPermit",
        None,
    )
    if not callable(permit_factory):
        raise RuntimeError("controller runtime absence boundary is unavailable")
    return permit_factory()


@contextmanager
def _runtimeConfigPermit() -> Iterator[ControllerConfigPosture | None]:
    """Hold runtime state while selecting controller or ambient configuration."""

    controller_state_module = _controllerStateModule()
    fence_factory = getattr(
        controller_state_module,
        "controllerRuntimeStateConfigFence",
        None,
    )
    refusal_type = getattr(
        controller_state_module,
        "ControllerStateRefused",
        RuntimeError,
    )
    if not callable(fence_factory) or not isinstance(refusal_type, type):
        raise RuntimeError("controller runtime configuration boundary is unavailable")
    with fence_factory() as exactly_absent:
        with _ENV_LOCK:
            controller = _CONTROLLER_CONFIG
        if controller is None and not exactly_absent:
            raise refusal_type(
                "ambient configuration requires an exactly absent controller runtime"
            )
        yield controller


@dataclass(frozen=True, slots=True)
class ControllerConfigPosture:
    """Typed, fail-closed configuration facts installed by the boot capsule."""

    source_root: Path
    installed_root: Path
    target_env_allowed: bool = False
    raw_overrides_allowed: bool = False
    external_effects_allowed: bool = False
    external_spend_allowed: bool = False

    def __post_init__(self) -> None:
        if not self.source_root.is_absolute() or not self.installed_root.is_absolute():
            raise RuntimeError("controller configuration roots must be absolute")
        if any(
            (
                self.target_env_allowed,
                self.raw_overrides_allowed,
                self.external_effects_allowed,
                self.external_spend_allowed,
            )
        ):
            raise RuntimeError("bootstrap configuration cannot widen authority")


_CONTROLLER_CONFIG: ControllerConfigPosture | None = None


def _installControllerConfig(
    *,
    source_root: str | Path,
    installed_root: str | Path,
) -> ControllerConfigPosture:
    """One-use internal seam called only after controller authority validation."""

    candidate = ControllerConfigPosture(
        source_root=Path(source_root).resolve(strict=False),
        installed_root=Path(installed_root).resolve(strict=False),
    )
    global _CONTROLLER_CONFIG
    with _ENV_LOCK:
        if _ENV_LOADED and _CONTROLLER_CONFIG is None:
            raise RuntimeError(
                "controller configuration must be installed before environment loading"
            )
        if _CONTROLLER_CONFIG is None:
            _CONTROLLER_CONFIG = candidate
        elif _CONTROLLER_CONFIG != candidate:
            raise RuntimeError(
                "controller configuration is already installed with different facts"
            )
        return _CONTROLLER_CONFIG


def controllerConfigActive() -> bool:
    with _ENV_LOCK:
        return _CONTROLLER_CONFIG is not None


def _controllerConfig() -> ControllerConfigPosture | None:
    with _ENV_LOCK:
        return _CONTROLLER_CONFIG


def _legacyConfigPathObservation(
    operation: Callable[..., _T],
    *args: object,
    **kwargs: object,
) -> _T:
    with _runtimeAbsencePermit():
        with _ENV_LOCK:
            if _CONTROLLER_CONFIG is not None:
                raise RuntimeError("legacy configuration path observation is unavailable")
            return operation(*args, **kwargs)


def _legacyConfigPathMutation(
    operation: Callable[..., _T],
    *args: object,
    **kwargs: object,
) -> _T:
    with _runtimeAbsencePermit():
        with _ENV_LOCK:
            if _CONTROLLER_CONFIG is not None:
                raise RuntimeError("legacy configuration path mutation is unavailable")
            return operation(*args, **kwargs)


def locateRepoRoot() -> Path:
    """Repo root = nearest ancestor of THIS FILE containing ``.git`` (dir or worktree
    file) or ``pyproject.toml``. cwd-independent by construction. A marker-less tree
    (e.g. an exported source archive) falls back to the structural root two package
    levels up (<root>/platform_core/app_config/_env.py)."""
    with _runtimeConfigPermit() as controller:
        if controller is not None:
            return controller.source_root
        for parent in _THIS_FILE.parents:
            if _legacyConfigPathObservation(
                (parent / ".git").exists
            ) or _legacyConfigPathObservation((parent / "pyproject.toml").exists):
                return parent
        return _THIS_FILE.parents[2]


def installRoot() -> Path:
    """Install root from the process env (INSTALL_ROOT) or the C:\\9to5 default."""
    with _runtimeConfigPermit() as controller:
        if controller is not None:
            return controller.installed_root
        raw = (os.environ.get("INSTALL_ROOT") or "").strip()
        return Path(raw) if raw else DEFAULT_INSTALL_ROOT


def loadEnvOnce() -> None:
    """Load ``.env`` exactly once per process: INSTALL_ROOT/.env first (durable install
    secrets/service config), then <repo>/.env (checkout-local additions). Keys already
    present in os.environ are never overridden. Idempotent and thread-safe."""
    global _ENV_LOADED, _PROCESS_PROJECT_ROOT
    if _ENV_LOADED:
        return
    # Preserve runtime -> env ordering even though the nested legacy observation
    # helper re-enters both locks while checking the two candidate files.
    with _runtimeConfigPermit() as controller:
        with _ENV_LOCK:
            if _ENV_LOADED:
                return
            if controller is not None:
                _PROCESS_PROJECT_ROOT = None
                _ENV_LOADED = True
                return
            _PROCESS_PROJECT_ROOT = os.environ.get("PROJECT_ROOT")
            for env_file in (installRoot() / ".env", locateRepoRoot() / ".env"):
                try:
                    if _legacyConfigPathObservation(env_file.is_file):
                        load_dotenv(dotenv_path=env_file)  # the ONLY load_dotenv call in 9to5
                except OSError:  # unreadable .env -> defaults still work
                    pass
            if _PROCESS_PROJECT_ROOT is None:
                # A .env-file PROJECT_ROOT is inert here (projectRoot ignores it) -- ALSO keep
                # it out of os.environ so child processes don't inherit it as a fake
                # process-level override and re-point themselves at a different tree.
                os.environ.pop("PROJECT_ROOT", None)
            _ENV_LOADED = True


def projectRoot() -> Path:
    """This checkout's root. Precedence: PROJECT_ROOT set on the PROCESS environment
    (tests/tools may re-point deliberately) > the computed repo root. A PROJECT_ROOT
    inside a .env FILE is ignored on purpose -- see module docstring. NEVER defaults
    to the package dir."""
    with _runtimeConfigPermit() as controller:
        if controller is not None:
            return controller.source_root
        loadEnvOnce()
        raw = (_PROCESS_PROJECT_ROOT or "").strip()
        return Path(raw) if raw else locateRepoRoot()


# --- never-crash env readers (import-time safe: bad values warn + fall back) ---

def _fullStack() -> bool:
    """Master switch (FULL_STACK env, default ON): the default SOURCE for every 'dark' epic flag +
    Human-Nature. An individual X_ENABLED env var still overrides it. FULL_STACK=0 reverts to the
    conservative ship-dark defaults."""
    return _envBool("FULL_STACK", True)


@overload
def _envString(key: str, default: str) -> str: ...


@overload
def _envString(key: str, default: None = None) -> str | None: ...


def _envString(key: str, default: str | None = None) -> str | None:
    """Ambient string input, disabled completely by the boot capsule."""

    with _runtimeConfigPermit() as controller:
        if controller is not None:
            return default
        return os.getenv(key, default)


def _envBool(key: str, default: bool = False) -> bool:
    with _runtimeConfigPermit() as controller:
        if controller is not None:
            return False
        raw = os.getenv(key)
        if raw is None:
            return default
        return raw.strip().lower() in {"1", "true", "yes", "on"}


def _envInt(key: str, default: int) -> int:
    raw = _envString(key)
    if raw is None or not str(raw).strip():
        return default
    try:
        return int(str(raw).strip())
    except (TypeError, ValueError):
        sys.stderr.write(f"[config] {key}={raw!r} is not an int; using default {default}\n")
        return default


def _envFloat(key: str, default: float) -> float:
    """float(os.getenv(...)) that never crashes config import (see _envInt)."""
    raw = _envString(key)
    if raw is None or not str(raw).strip():
        return default
    try:
        return float(str(raw).strip())
    except (TypeError, ValueError):
        sys.stderr.write(f"[config] {key}={raw!r} is not a float; using default {default}\n")
        return default


def _envPath(key: str) -> "Path | None":
    """Path from env, or None when unset/empty (callers supply the default via ``or``)."""
    raw = _envString(key)
    return Path(raw) if raw and raw.strip() else None


def _envTuple(key: str, default_csv: str) -> tuple[str, ...]:
    """Comma-separated env list -> stripped, empty-free tuple."""
    raw = _envString(key, default_csv) or default_csv
    return tuple(s.strip() for s in raw.split(",") if s.strip())
