"""Env bootstrap + never-crash env-coercion helpers (single home for BOTH).

THE one place in the tree that touches ``.env`` and computes the repo root:

* ``locateRepoRoot()`` walks UP from this file to the first ``.git``/``pyproject.toml``
  marker, so PROJECT_ROOT never depends on cwd and never collapses to the package dir
  (the old default was ``platform_core/app_config/`` itself -- the R12 landmine).
* ``loadEnvOnce()`` loads ``INSTALL_ROOT/.env`` then ``<repo>/.env`` exactly once per
  process (idempotent, thread-safe). Real process env vars always win (load_dotenv
  never overrides existing keys).
* ``projectRoot()`` honours a PROJECT_ROOT set on the PROCESS environment, but a
  PROJECT_ROOT line inside a ``.env`` file is deliberately inert: the shared install
  ``.env`` (C:\\9to5\\.env sets PROJECT_ROOT=C:\\9to5) must never re-point a checkout
  at a different tree.
* ``_envBool/_envInt/_envFloat/_envPath/_envTuple`` are the never-crash readers used
  by every app_config domain module (single-homed here; do not copy them).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  locateRepoRoot() -> Path  -- Repo root = nearest ancestor of THIS FILE containing ``.git`` (dir or worktree
  installRoot() -> Path  -- Install root from the process env (INSTALL_ROOT) or the C:\\9to5 default.
  loadEnvOnce() -> None  -- Load ``.env`` exactly once per process: INSTALL_ROOT/.env first (durable install
  projectRoot() -> Path  -- This checkout's root
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: loadEnvOnce mutates os.environ from .env files (never overriding existing keys)
RUN/TEST: python -m pytest tests/execution/test_completion_envelope.py tests/execution/test_execution_environment.py tests/orchestration/test_execute_mixin_env.py
"""
from __future__ import annotations

import os
import sys
import threading
from pathlib import Path

from dotenv import load_dotenv

# Durable home of vault/logs/knowledge + the production .env, independent of checkout.
DEFAULT_INSTALL_ROOT: Path = Path(r"C:\9to5")

_THIS_FILE = Path(__file__).resolve()
_ENV_LOCK = threading.Lock()
_ENV_LOADED = False
# PROJECT_ROOT as provided by the REAL process environment, captured BEFORE any .env
# load so a .env-file PROJECT_ROOT can never masquerade as a process-level override.
_PROCESS_PROJECT_ROOT: "str | None" = None


def locateRepoRoot() -> Path:
    """Repo root = nearest ancestor of THIS FILE containing ``.git`` (dir or worktree
    file) or ``pyproject.toml``. cwd-independent by construction. A marker-less tree
    (e.g. an exported source archive) falls back to the structural root two package
    levels up (<root>/platform_core/app_config/_env.py)."""
    for parent in _THIS_FILE.parents:
        if (parent / ".git").exists() or (parent / "pyproject.toml").exists():
            return parent
    return _THIS_FILE.parents[2]


def installRoot() -> Path:
    """Install root from the process env (INSTALL_ROOT) or the C:\\9to5 default."""
    raw = (os.environ.get("INSTALL_ROOT") or "").strip()
    return Path(raw) if raw else DEFAULT_INSTALL_ROOT


def loadEnvOnce() -> None:
    """Load ``.env`` exactly once per process: INSTALL_ROOT/.env first (durable install
    secrets/service config), then <repo>/.env (checkout-local additions). Keys already
    present in os.environ are never overridden. Idempotent and thread-safe."""
    global _ENV_LOADED, _PROCESS_PROJECT_ROOT
    if _ENV_LOADED:
        return
    with _ENV_LOCK:
        if _ENV_LOADED:
            return
        _PROCESS_PROJECT_ROOT = os.environ.get("PROJECT_ROOT")
        for env_file in (installRoot() / ".env", locateRepoRoot() / ".env"):
            try:
                if env_file.is_file():
                    load_dotenv(dotenv_path=env_file)  # the ONLY load_dotenv call in 9to5
            except OSError:  # unreadable .env -> defaults still work
                pass
        if _PROCESS_PROJECT_ROOT is None:
            # A .env-file PROJECT_ROOT is inert here (projectRoot ignores it) -- ALSO keep
            # it out of os.environ so child processes don't inherit it as a fake
            # process-level override and re-point themselves at a different tree.
            os.environ.pop("PROJECT_ROOT", None)
        _ENV_LOADED = True


def projectRoot() -> Path:
    """This checkout's root. Precedence: PROJECT_ROOT set on the PROCESS environment
    (tests/tools may re-point deliberately) > the computed repo root. A PROJECT_ROOT
    inside a .env FILE is ignored on purpose -- see module docstring. NEVER defaults
    to the package dir."""
    loadEnvOnce()
    raw = (_PROCESS_PROJECT_ROOT or "").strip()
    return Path(raw) if raw else locateRepoRoot()


# --- never-crash env readers (import-time safe: bad values warn + fall back) ---

def _envBool(key: str, default: bool = False) -> bool:
    raw = os.getenv(key)
    if raw is None:
        return default
    return raw.strip().lower() in {"1", "true", "yes", "on"}


def _envInt(key: str, default: int) -> int:
    raw = os.getenv(key)
    if raw is None or not str(raw).strip():
        return default
    try:
        return int(str(raw).strip())
    except (TypeError, ValueError):
        sys.stderr.write(f"[config] {key}={raw!r} is not an int; using default {default}\n")
        return default


def _envFloat(key: str, default: float) -> float:
    """float(os.getenv(...)) that never crashes config import (see _envInt)."""
    raw = os.getenv(key)
    if raw is None or not str(raw).strip():
        return default
    try:
        return float(str(raw).strip())
    except (TypeError, ValueError):
        sys.stderr.write(f"[config] {key}={raw!r} is not a float; using default {default}\n")
        return default


def _envPath(key: str) -> "Path | None":
    """Path from env, or None when unset/empty (callers supply the default via ``or``)."""
    raw = os.getenv(key)
    return Path(raw) if raw and raw.strip() else None


def _envTuple(key: str, default_csv: str) -> tuple[str, ...]:
    """Comma-separated env list -> stripped, empty-free tuple."""
    return tuple(s.strip() for s in os.getenv(key, default_csv).split(",") if s.strip())
