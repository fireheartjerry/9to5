"""TaskState file I/O: atomic save, load, iteration, and list helpers.

All functions accept or return ``TaskState`` instances from ``state.task_schema``.
Import from ``state.task`` for backward compatibility.

SINGLE-WRITER RULE (docs/STATE.md): only the orchestrator process writes task JSON. Other
processes (gateway bot, launcher, dashboards) act through the ControlBus; the ONLY sanctioned
out-of-process write is ``reapDeadRun``, which refuses unless the run is provably dead.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  validateTaskId(task_id: str) -> str  -- Return task_id if it is UUID-shaped, else raise ValueError
  save(state: 'TaskState') -> Path  -- Atomic JSON save (unique temp + os.replace via the fsio kernel).
  load(task_id: str) -> 'TaskState'  -- Load task JSON from the state store
  loadSafe(task_id: str) -> 'Optional[TaskState]'  -- Like ``load`` but returns None for a missing/corrupt file instead of raising.
  iterStored()  -- Yield ``(path, data)`` for every readable, task-shaped JSON in the store.
  loadLatest() -> 'Optional[TaskState]'  -- Prefer the most-recently-STARTED active (non-terminal) task.
  listRecent(n: int=10) -> list[dict[str, Any]]  -- Lightweight summaries of recent tasks, newest first
  reapDeadRun(task_id: str, *, reason: str='orchestrator process dead (no heartbeat, pid gone)') -> bool  -- Finalize a PROVABLY-DEAD, still-non-terminal run as ``aborted``.
DEPENDS-ON: config, platform_core.core, platform_core.runtime.heartbeat, state.task_schema
SIDE-EFFECTS: writes state/tasks/<id>.json
RUN/TEST: python -m pytest tests/control/test_task.py
"""
from __future__ import annotations

import json
import re
import threading
from pathlib import Path
from typing import TYPE_CHECKING, Any, Optional

import config
from platform_core.core import fsio

if TYPE_CHECKING:
    from state.task_schema import TaskState

LOG = config.getLogger("task_io")

# Task ids are always uuid.uuid4() (state/task_schema.py::create). Reject anything else BEFORE
# it reaches a filesystem path -- a task_id of "../../.env" would otherwise resolve outside
# STATE_DIR (CLI --resume, the Discord /run command, and webdash's task_id query param all flow
# unvalidated task_id values into TaskState.load()).
_TASK_ID_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")


def validateTaskId(task_id: str) -> str:
    """Return task_id if it is UUID-shaped, else raise ValueError. Call before any path join."""
    if not isinstance(task_id, str) or not _TASK_ID_RE.match(task_id):
        raise ValueError(f"invalid task_id: {task_id!r}")
    return task_id

# Serializes concurrent save() calls within this process so the temp-file
# write + os.replace swap never interleave.
_SAVE_LOCK = threading.Lock()


def save(state: "TaskState") -> Path:
    """Atomic JSON save (unique temp + os.replace via the fsio kernel)."""
    p = state.path()
    with _SAVE_LOCK:
        # Serialize INSIDE the lock: another thread mutating state.data while json.dumps
        # walks it raises "changed size during iteration".
        payload = json.dumps(state.data, indent=2, ensure_ascii=False)
        # Kernel swap: unique pid-thread-rand temp + bounded Windows backoff, so
        # concurrent processes never race a shared temp name.
        fsio.atomicWriteText(p, payload)
    return p


def load(task_id: str) -> "TaskState":
    """Load task JSON from the state store; raises on missing or corrupt file."""
    from state.task_schema import TaskState
    p = config.STATE_DIR / f"{validateTaskId(task_id)}.json"
    data = json.loads(p.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"task JSON for {task_id!r} is not a dict: {type(data).__name__}")
    return TaskState(data)


def loadSafe(task_id: str) -> "Optional[TaskState]":
    """Like ``load`` but returns None for a missing/corrupt file instead of raising."""
    try:
        return load(task_id)
    except Exception:  # noqa: BLE001
        return None


def _taskShaped(data) -> bool:
    """A stored file counts as a task only with a task_id and a dict meta -- so a stray
    non-task JSON dropped into the store can never be misparsed as a run."""
    return isinstance(data, dict) and bool(data.get("task_id")) and isinstance(data.get("meta"), dict)


def iterStored():
    """Yield ``(path, data)`` for every readable, task-shaped JSON in the store.

    The single place that scans STATE_DIR. Corrupt/unreadable/foreign-shaped files are
    skipped -- counted and logged once per scan -- so every consumer
    (loadLatest/listRecent/metrics) gets robust behavior with a visible signal.
    """
    skipped = 0
    for f in config.STATE_DIR.glob("*.json"):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except Exception:  # noqa: BLE001
            skipped += 1
            continue
        if not _taskShaped(data):
            skipped += 1
            continue
        yield f, data
    if skipped:
        LOG.warning("iterStored: skipped %d corrupt/non-task file(s) under %s",
                    skipped, config.STATE_DIR)


def loadLatest() -> "Optional[TaskState]":
    """Prefer the most-recently-STARTED active (non-terminal) task.

    An unrelated save() bumping an old task's mtime must not cause the wrong task
    to be resumed/inspected.
    """
    from state.task_schema import TaskState
    best: Optional[dict[str, Any]] = None
    best_key = None
    for _f, data in iterStored():
        meta = data.get("meta", {})
        key = (0 if meta.get("status") in TaskState._TERMINAL else 1, meta.get("started_at", ""))
        if best_key is None or key > best_key:
            best_key, best = key, data
    return TaskState(best) if best is not None else None


def listRecent(n: int = 10) -> list[dict[str, Any]]:
    """Lightweight summaries of recent tasks, newest first. Reads the JSON store directly."""
    out: list[dict[str, Any]] = []
    for f, data in iterStored():
        meta = data.get("meta", {})
        subs = (data.get("plan", {}) or {}).get("subtasks", []) or []
        done = sum(1 for s in subs if s.get("status") == "done")
        total = sum(1 for s in subs if s.get("status") != "removed")
        out.append({
            "task_id": data.get("task_id", f.stem),
            "status": meta.get("status", "unknown"),
            "goal": meta.get("goal_raw", ""),
            "done": done,
            "total": total,
            "started_at": meta.get("started_at", ""),
        })
    out.sort(key=lambda d: d["started_at"], reverse=True)
    return out[:n]


def reapDeadRun(task_id: str, *,
                reason: str = "orchestrator process dead (no heartbeat, pid gone)") -> bool:
    """Finalize a PROVABLY-DEAD, still-non-terminal run as ``aborted``.

    The single-writer escape hatch: the ONLY sanctioned task-JSON write outside the
    orchestrator process (used by the launcher's stale cleanup). Refuses -- returns
    False without writing -- while ``heartbeat.isRunAlive`` says the run may still be
    alive, and when the task is missing or already terminal.
    """
    from platform_core.runtime.heartbeat import isRunAlive
    from state.task_schema import TaskState
    if isRunAlive(task_id):
        LOG.warning("reapDeadRun(%s): refused -- run may still be alive", task_id[:8])
        return False
    st = loadSafe(task_id)
    if st is None or st.meta.get("status") in TaskState._TERMINAL:
        return False
    st.meta["status"] = "aborted"
    st.meta["blocked_reason"] = reason
    save(st)
    LOG.warning("reapDeadRun(%s): finalized dead run as aborted (%s)", task_id[:8], reason)
    return True
