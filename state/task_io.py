# Fork-branch throwaway clones are written as "<task_id>__fork_<branch>.json" by
# platform_core/orchestration/solution_space.py::forkBranchState (its _FORK_STATE_SUFFIX
# constant == "__fork_"). Duplicated here as a literal rather than imported: solution_space
# imports state.task (-> state.task_io), so importing back would be circular. Keep this in
# sync with solution_space._FORK_STATE_SUFFIX.
_FORK_STATE_SUFFIX = "__fork_"


def _startedDt(meta: dict) -> datetime:
    """Parse ``meta['started_at']`` into an aware datetime for chronological comparison.

    Plain string comparison of ISO timestamps breaks across differing UTC offsets (DST
    transitions, tz/machine changes) -- two lexicographically-ordered strings are not
    guaranteed to be chronologically ordered when their offsets differ. Missing/garbage
    values fall back to an aware datetime.min so they always sort as oldest and never raise
    "can't compare offset-naive and offset-aware datetimes" against real parsed values."""
    s = meta.get("started_at", "")
    try:
        return datetime.fromisoformat(s)
    except (ValueError, TypeError):
        return datetime.min.replace(tzinfo=timezone.utc)


# Task ids are always uuid.uuid4() (state/task_schema.py::create). Reject anything else BEFORE
# it reaches a filesystem path -- a task_id of "../../.env" would otherwise resolve outside
# STATE_DIR (CLI --resume, the Discord /run command, and webdash's task_id query param all flow
# unvalidated task_id values into TaskState.load()).
_TASK_ID_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")


def validateTaskId(task_id: str) -> str:
    """Return task_id if it is UUID-shaped, else raise ValueError. Call before any path join."""
    if not isinstance(task_id, str) or not _TASK_ID_RE.match(task_id):
        raise ValueError(f"invalid task_id: {task_id!r}")
    return task_id


# Serializes concurrent save() calls within this process so the temp-file
# write + os.replace swap never interleave.
_SAVE_LOCK = threading.Lock()


class TaskStateStoreUnavailable(RuntimeError):
    """No exact external TaskState store binding is available in capsule mode."""


class TaskStateSnapshotReceiptRefused(RuntimeError):
    """A detached TaskState durability proof is missing, forged, or stale."""


@dataclass(frozen=True, slots=True)
class TaskStateStoreBinding:
    store: ControllerStateStore
    authority: ControllerStateAuthority


@dataclass(frozen=True, slots=True, kw_only=True)
class TaskStateSnapshotReceipt:
    """Opaque process-local proof of exact durable TaskState snapshot bytes."""

    receipt_id: str
    task_id: str
    destination_id: str
    snapshot_sha256: str
    byte_length: int
    storage_binding_id: str
    controller_generation: int
    _issuer: object
    _token: object


@dataclass(frozen=True, slots=True, kw_only=True)
class _IssuedTaskStateSnapshotReceipt:
    receipt: TaskStateSnapshotReceipt
    token: object
    task_id: str
    destination_id: str
    snapshot_sha256: str
    byte_length: int
    storage_binding_id: str
    controller_generation: int
    serialization_kind: str


_INSTALLED_BINDING: TaskStateStoreBinding | None = None
_BINDING_LOCK = threading.RLock()
_SNAPSHOT_RECEIPT_ISSUER = object()
_SNAPSHOT_RECEIPT_LOCK = threading.RLock()
_SNAPSHOT_RECEIPTS: dict[str, _IssuedTaskStateSnapshotReceipt] = {}
_MAX_TASKSTATE_BYTES = 16 * 1024 * 1024


def installTaskStateStore(
    *,
    store: ControllerStateStore,
    authority: ControllerStateAuthority,
) -> TaskStateStoreBinding:
    """Install an inactive-path diagnostic binding; production resolves centrally."""

    if type(store) is not ControllerStateStore or type(authority) is not ControllerStateAuthority:
        raise TaskStateStoreUnavailable(
            "exact open diagnostic controller-state store and authority are required"
        )
    from platform_core.app_config.paths import controllerPathsActivationFence
    from platform_core.runtime.controller_state import (
        controllerRuntimeStateAbsentPermit,
    )

    try:
        store._validateInstallableAuthority(authority)
    except ControllerStateRefused as exc:
        raise TaskStateStoreUnavailable(
            "an open diagnostic controller-state store and authority are required"
        ) from exc
    if not isDiagnosticControllerStateAuthority(authority):
        raise TaskStateStoreUnavailable(
            "diagnostic controller-state authority is required"
        )

    try:
        with controllerRuntimeStateAbsentPermit():
            with controllerPathsActivationFence() as paths_active:
                if paths_active or _controllerPathsActive():
                    raise TaskStateStoreUnavailable(
                        "diagnostic TaskState binding is unavailable after activation"
                    )
                try:
                    store._validateInstallableAuthority(authority)
                except ControllerStateRefused as exc:
                    raise TaskStateStoreUnavailable(
                        "an open diagnostic controller-state store and authority are required"
                    ) from exc
                binding = TaskStateStoreBinding(store=store, authority=authority)
                global _INSTALLED_BINDING
                with _BINDING_LOCK:
                    if _INSTALLED_BINDING is not None:
                        if (
                            _INSTALLED_BINDING.store is store
                            and _INSTALLED_BINDING.authority is authority
                        ):
                            installed = _INSTALLED_BINDING
                        else:
                            raise TaskStateStoreUnavailable(
                                "diagnostic TaskState binding is already installed"
                            )
                    else:
                        _INSTALLED_BINDING = binding
                        installed = binding
    except TaskStateStoreUnavailable:
        raise
    except ControllerStateRefused as exc:
        raise TaskStateStoreUnavailable(
            "controller runtime installation is not exactly absent"
        ) from exc
    return installed


def _controllerPathsActive() -> bool:
    try:
        from platform_core.app_config.paths import controllerPathsActive

        return bool(controllerPathsActive())
    except Exception:
        # An ambiguous boot/configuration state never authorizes a legacy path.
        return True


def _centralBinding() -> TaskStateStoreBinding:
    from platform_core.runtime import controller_state

    try:
        runtime = controller_state.currentControllerRuntimeStateBinding()
        store = runtime.store
        authority = runtime.authority
        if (
            type(store) is not ControllerStateStore
            or type(authority) is not ControllerStateAuthority
        ):
            raise ControllerStateRefused(
                "central controller runtime binding has invalid exact types"
            )
        store._validateInstallableAuthority(authority)
    except (AttributeError, ControllerStateRefused) as exc:
        raise TaskStateStoreUnavailable(
            "external TaskState controller binding is unavailable"
        ) from exc
    return TaskStateStoreBinding(store=store, authority=authority)


@contextmanager
def _bindingOperation():
    try:
        central = _centralBinding()
    except TaskStateStoreUnavailable:
        pass
    else:
        yield central
        return

    from platform_core.app_config.paths import controllerPathsActivationFence
    from platform_core.runtime.controller_state import (
        controllerRuntimeStateAbsentPermit,
    )

    diagnostic: TaskStateStoreBinding | None = None
    active = False
    permit = ExitStack()
    try:
        permit.enter_context(controllerRuntimeStateAbsentPermit())
    except ControllerStateRefused as exc:
        permit.close()
        raise TaskStateStoreUnavailable(
            "controller runtime installation is not exactly absent"
        ) from exc
    with permit:
        with controllerPathsActivationFence() as paths_active:
            active = paths_active or _controllerPathsActive()
            if not active:
                with _BINDING_LOCK:
                    diagnostic = _INSTALLED_BINDING
                yield diagnostic
                return

    if active:
        yield _centralBinding()
        return
    raise TaskStateStoreUnavailable(
        "external TaskState controller binding is unavailable"
    )


def _binding() -> TaskStateStoreBinding | None:
    with _bindingOperation() as binding:
        return binding


def _logicalTask(task_id: str) -> str:
    return f"tasks/{validateTaskId(task_id)}"


def _logicalBackup(task_id: str) -> str:
    return f"task-backups/{validateTaskId(task_id)}"


def _controllerJsonBytes(value: object) -> bytes:
    try:
        return json.dumps(
            value,
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=False,
            allow_nan=False,
        ).encode("utf-8")
    except (TypeError, ValueError, UnicodeEncodeError) as exc:
        raise TaskStateSnapshotReceiptRefused(
            "TaskState snapshot is not canonically serializable"
        ) from exc


def _legacyJsonBytes(value: object) -> bytes:
    try:
        return json.dumps(
            value,
            indent=2,
            ensure_ascii=False,
            allow_nan=False,
        ).encode("utf-8")
    except (TypeError, ValueError, UnicodeEncodeError) as exc:
        raise TaskStateSnapshotReceiptRefused(
            "TaskState snapshot is not durably serializable"
        ) from exc


def _snapshotStorageFacts(
    task_id: str,
    binding: TaskStateStoreBinding | None,
) -> tuple[str, str, str, int]:
    if binding is None:
        destination = Path(config.STATE_DIR) / f"{task_id}.json"
        destination_id = os.path.normcase(os.path.abspath(destination))
        descriptor = {
            "destination_id": destination_id,
            "kind": "legacy-diagnostic",
        }
        generation = 0
        kind = "legacy"
    else:
        authority = binding.authority
        logical_id = _logicalTask(task_id)
        destination_id = f"controller:{authority.root}:{logical_id}"
        descriptor = {
            "authority_identity": id(authority),
            "controller_generation": authority.controller_generation,
            "destination_id": destination_id,
            "repository_id": authority.repository_id,
            "store_identity": id(binding.store),
        }
        generation = authority.controller_generation
        kind = "controller"
    storage_binding_id = hashlib.sha256(
        _controllerJsonBytes(descriptor)
    ).hexdigest()
    return kind, destination_id, storage_binding_id, generation


def _snapshotPayload(value: object, serialization_kind: str) -> bytes:
    if serialization_kind == "controller":
        return _controllerJsonBytes(value)
    if serialization_kind == "legacy":
        return _legacyJsonBytes(value)
    raise TaskStateSnapshotReceiptRefused(
        "TaskState snapshot serialization kind is invalid"
    )


def _observeSnapshotPayload(
    *,
    task_id: str,
    binding: TaskStateStoreBinding | None,
    serialization_kind: str,
    destination_id: str,
) -> bytes:
    if binding is not None:
        observed = binding.store.readJson(
            _logicalTask(task_id),
            authority=binding.authority,
        )
        return _snapshotPayload(observed, serialization_kind)
    path = Path(destination_id)
    return fsio.readNoFollowBytes(path, max_bytes=_MAX_TASKSTATE_BYTES)


def _issueSnapshotReceipt(
    *,
    task_id: str,
    destination_id: str,
    payload: bytes,
    storage_binding_id: str,
    controller_generation: int,
    serialization_kind: str,
) -> TaskStateSnapshotReceipt:
    receipt_id = secrets.token_hex(32)
    token = object()
    snapshot_sha256 = hashlib.sha256(payload).hexdigest()
    receipt = TaskStateSnapshotReceipt(
        receipt_id=receipt_id,
        task_id=task_id,
        destination_id=destination_id,
        snapshot_sha256=snapshot_sha256,
        byte_length=len(payload),
        storage_binding_id=storage_binding_id,
        controller_generation=controller_generation,
        _issuer=_SNAPSHOT_RECEIPT_ISSUER,
        _token=token,
    )
    issued = _IssuedTaskStateSnapshotReceipt(
        receipt=receipt,
        token=token,
        task_id=task_id,
        destination_id=destination_id,
        snapshot_sha256=snapshot_sha256,
        byte_length=len(payload),
        storage_binding_id=storage_binding_id,
        controller_generation=controller_generation,
        serialization_kind=serialization_kind,
    )
    with _SNAPSHOT_RECEIPT_LOCK:
        _SNAPSHOT_RECEIPTS[receipt_id] = issued
    return receipt


def _bakPath(p: Path) -> Path:
    return p.with_name(p.name + ".bak")


def _backupPriorGood(p: Path) -> None:
    """Copy the current on-disk file to ``<name>.bak`` before swapping in a new version.

    Cheap complementary safeguard to the durable write in save(): if the new write is
    somehow lost (or the process dies mid-swap on a filesystem without our fsync
    guarantees), the prior known-good task JSON is recoverable from ``.bak``. Best-effort
    -- a backup failure must never block the real save."""
    try:
        raw = readLegacyText(p, encoding="utf-8")
    except OSError:
        return  # nothing to back up yet (first save, or unreadable) -- fine
    if not raw.strip():
        return  # don't preserve an already-empty file as "the prior good state"
    try:
        fsio.atomicWriteText(_bakPath(p), raw, durable=True)
    except OSError as e:  # noqa: BLE001 -- best-effort safeguard only
        LOG.debug("save(%s): .bak backup failed (ignored): %s", p, e)


def save(state: "TaskState") -> Path:
    """Durable JSON save: prior good state backed up to ``.bak``, then a real-fd fsync +
    os.replace swap via the fsio kernel (unique temp + bounded Windows backoff)."""
    task_id = validateTaskId(state.task_id)
    with _SAVE_LOCK:
        if not _taskShaped(state.data) or state.data.get("task_id") != task_id:
            raise ValueError("TaskState data does not match its validated task ID")
        with _bindingOperation() as binding:
            p = state.path()
            if binding is not None:
                binding.store.replaceJsonWithBackup(
                    _logicalTask(task_id),
                    _logicalBackup(task_id),
                    state.data,
                    authority=binding.authority,
                )
                return p
            # Serialize INSIDE the lock: another thread mutating state.data while
            # json.dumps walks it raises "changed size during iteration".
            payload = json.dumps(state.data, indent=2, ensure_ascii=False)
            _backupPriorGood(p)
            # Kernel swap: unique pid-thread-rand temp + bounded Windows backoff, so
            # concurrent processes never race a shared temp name. durable=True also
            # flushes+fsyncs the temp file (and, on POSIX, the parent directory).
            fsio.atomicWriteText(p, payload, durable=True)
    return p


def saveDataSnapshot(state: "TaskState", snapshot: dict[str, Any]) -> Path:
    """Persist one detached TaskState snapshot without changing ``state.data``."""

    if not isinstance(snapshot, dict):
        raise TypeError("TaskState snapshot must be a dict")
    task_id = validateTaskId(state.task_id)
    with _SAVE_LOCK:
        candidate = copy.deepcopy(snapshot)
        if not _taskShaped(candidate) or candidate.get("task_id") != task_id:
            raise ValueError("TaskState snapshot does not match its validated task ID")
        with _bindingOperation() as binding:
            p = state.path()
            if binding is not None:
                binding.store.replaceJsonWithBackup(
                    _logicalTask(task_id),
                    _logicalBackup(task_id),
                    candidate,
                    authority=binding.authority,
                )
                return p
            payload = json.dumps(candidate, indent=2, ensure_ascii=False)
            _backupPriorGood(p)
            fsio.atomicWriteText(p, payload, durable=True)
    return p


def _loadDataWithBakFallback(p: Path, task_id: str) -> dict:
    """Read+parse ``p``; if missing/empty/corrupt, fall back to ``<p>.bak``.

    Raises the original error only when BOTH the primary and the backup are unusable, so a
    single torn/corrupt write doesn't silently strand a run."""
    try:
        raw = readLegacyText(p, encoding="utf-8")
        if not raw.strip():
            raise ValueError("empty task JSON")
        data = json.loads(raw)
    except (FileNotFoundError, ValueError, OSError) as primary_err:
        bak = _bakPath(p)
        try:
            bak_raw = readLegacyText(bak, encoding="utf-8")
            if not bak_raw.strip():
                raise ValueError("empty .bak")
            data = json.loads(bak_raw)
            LOG.warning("load(%s): primary unusable (%s); recovered from %s", task_id, primary_err, bak)
        except Exception:  # noqa: BLE001 -- no usable backup either; surface the primary error
            raise primary_err from None
    if not isinstance(data, dict):
        raise ValueError(f"task JSON for {task_id!r} is not a dict: {type(data).__name__}")
    if not _taskShaped(data):
        # A dict-but-non-task JSON (no task_id / no dict meta) would build a TaskState whose
        # .task_id/.meta accessors raise a bare KeyError in unguarded consumers (webdash
        # _snapshot). Reject it here -- the single load choke-point -- like a non-dict.
        raise ValueError(f"task JSON for {task_id!r} lacks task_id/meta shape")
    return data


def _loadControllerDataWithBackup(
    binding: TaskStateStoreBinding,
    task_id: str,
) -> dict:
    """Load one authoritative task, recovering only from its durable backup."""

    try:
        data = binding.store.readJson(
            _logicalTask(task_id), authority=binding.authority
        )
    except (FileNotFoundError, ControllerStateRefused) as primary_err:
        try:
            data = binding.store.readJson(
                _logicalBackup(task_id), authority=binding.authority
            )
            LOG.warning(
                "load(%s): controller primary unusable (%s); recovered from backup",
                task_id,
                primary_err,
            )
        except (FileNotFoundError, ControllerStateRefused):
            raise primary_err from None
    if not isinstance(data, dict):
        raise ValueError(
            f"task JSON for {task_id!r} is not a dict: {type(data).__name__}"
        )
    if not _taskShaped(data):
        raise ValueError(f"task JSON for {task_id!r} lacks task_id/meta shape")
    if data.get("task_id") != task_id:
        raise ValueError(f"task JSON for {task_id!r} carries a different task_id")
    return data


def load(task_id: str) -> "TaskState":
    """Load task JSON from the state store; falls back to ``<id>.json.bak`` when the
    primary is missing/empty/corrupt. Raises only if both are unusable."""
    from state.task_schema import TaskState

    task_id = validateTaskId(task_id)
    with _bindingOperation() as binding:
        if binding is not None:
            data = _loadControllerDataWithBackup(binding, task_id)
        else:
            p = config.STATE_DIR / f"{task_id}.json"
            data = _loadDataWithBakFallback(p, task_id)
    return TaskState(data)


def loadSafe(task_id: str) -> "Optional[TaskState]":
    """Like ``load`` but returns None for a missing/corrupt file instead of raising."""
    try:
        return load(task_id)
    except Exception:  # noqa: BLE001
        return None


def _taskShaped(data) -> bool:
    """A stored file counts as a task only with a task_id and a dict meta -- so a stray
    non-task JSON dropped into the store can never be misparsed as a run."""
    return isinstance(data, dict) and bool(data.get("task_id")) and isinstance(data.get("meta"), dict)


def iterStored():
    """Yield ``(path, data)`` for every readable, task-shaped JSON in the store.

    The single place that scans STATE_DIR. Corrupt/unreadable/foreign-shaped files are
    skipped -- counted and logged once per scan -- so every consumer
    (loadLatest/listRecent/metrics) gets robust behavior with a visible signal.
    Fork-branch throwaway clones (see ``_FORK_STATE_SUFFIX`` above) are skipped outright,
    not counted as "skipped" -- they're deep copies of a real run's data and would
    otherwise double-count as a run in learning stats (experience_runs.backfill_from_store).
    """
    skipped = 0
    collected: list[tuple[Path, dict[str, Any]]] = []
    with _bindingOperation() as binding:
        if binding is not None:
            logical_ids = binding.store.listJsonIds(
                "tasks", authority=binding.authority
            )
            records = (
                (
                    config.STATE_DIR / f"{logical_id.rpartition('/')[2]}.json",
                    logical_id,
                )
                for logical_id in logical_ids
            )
            location: object = "external controller store"
        else:
            records = (
                (path, None) for path in globLegacy(config.STATE_DIR, "*.json")
            )
            location = config.STATE_DIR
        for f, logical_id in records:
            if _FORK_STATE_SUFFIX in f.name:
                continue
            try:
                if logical_id is None:
                    data = json.loads(readLegacyText(f, encoding="utf-8"))
                else:
                    assert binding is not None
                    data = binding.store.readJson(
                        logical_id, authority=binding.authority
                    )
            except Exception:  # noqa: BLE001
                skipped += 1
                continue
            if not _taskShaped(data):
                skipped += 1
                continue
            collected.append((f, data))
    if skipped:
        LOG.warning(
            "iterStored: skipped %d corrupt/non-task file(s) under %s",
            skipped,
            location,
        )
    yield from collected


def loadLatest() -> "Optional[TaskState]":
    """Prefer the most-recently-STARTED active (non-terminal) task.

    An unrelated save() bumping an old task's mtime must not cause the wrong task to be
    resumed/inspected. The sort key parses ``started_at`` into an aware datetime
    (offset-safe -- see ``_startedDt``) and appends ``task_id`` as a final deterministic
    tie-breaker, so two runs sharing a key never depend on filesystem glob order.
    """
    from state.task_schema import TaskState

    best: Optional[dict[str, Any]] = None
    best_key = None
    for _f, data in iterStored():
        meta = data.get("meta", {})
        key = (
            0 if meta.get("status") in TaskState._TERMINAL else 1,
            _startedDt(meta),
            data.get("task_id", ""),
        )
        if best_key is None or key > best_key:
            best_key, best = key, data
    return TaskState(best) if best is not None else None


def listRecent(n: int = 10) -> list[dict[str, Any]]:
    """Lightweight summaries of recent tasks, newest first. Reads the JSON store directly."""
    out: list[dict[str, Any]] = []
    for f, data in iterStored():
        meta = data.get("meta", {})
        subs = (data.get("plan", {}) or {}).get("subtasks", []) or []
        done = sum(1 for s in subs if s.get("status") == "done")
        total = sum(1 for s in subs if s.get("status") != "removed")
        out.append(
            {
                "task_id": data.get("task_id", f.stem),
                "status": meta.get("status", "unknown"),
                "goal": meta.get("goal_raw", ""),
                "done": done,
                "total": total,
                "started_at": meta.get("started_at", ""),
            }
        )
    # Offset-aware ordering (see _startedDt): raw string sort is wrong across differing
    # UTC offsets (DST transitions, tz/machine changes).
    out.sort(key=lambda d: _startedDt({"started_at": d["started_at"]}), reverse=True)
    return out[:n]


def reapDeadRun(task_id: str, *, reason: str = "orchestrator process dead (no heartbeat, pid gone)") -> bool:
    """Finalize a PROVABLY-DEAD, still-non-terminal run as ``aborted``.

    The single-writer escape hatch: the ONLY sanctioned task-JSON write outside the
    orchestrator process (used by the launcher's stale cleanup). Refuses -- returns
    False without writing -- while ``heartbeat.isRunAlive`` says the run may still be
    alive, and when the task is missing or already terminal.
    """
    from platform_core.runtime.heartbeat import isRunAlive
    from state.task_schema import TaskState

    if isRunAlive(task_id):
        LOG.warning("reapDeadRun(%s): refused -- run may still be alive", task_id[:8])
        return False
    st = loadSafe(task_id)
    if st is None or st.meta.get("status") in TaskState._TERMINAL:
        return False
    st.meta["status"] = "aborted"
    st.meta["blocked_reason"] = reason
    save(st)
    LOG.warning("reapDeadRun(%s): finalized dead run as aborted (%s)", task_id[:8], reason)
    return True
