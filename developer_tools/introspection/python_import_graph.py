"""AST analysis for Python modules: exports, first-party import edges, side effects.

Generalizes the extraction patterns in tools/repo_map.py (``_exports``,
``_depends_on``, ``parse_module``) for ANY root: exports honor ``__all__``;
imports are resolved dotted -> relpath only when the target file is in the
analyzed set (first-party test); top-level and in-function imports are split
(load-time graph vs lazy); a heuristic tags module-level calls as subprocess /
file-write (``open`` only with a literal write mode) / network / env-read. A
SyntaxError yields a skeleton ModuleInfo, never a crash.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  analyzePython(root: str | Path, relpaths: list[str]) -> dict[str, ModuleInfo]  -- Analyze the given ``.py`` relpaths under ``root`` into full ModuleInfos.
DEPENDS-ON: developer_tools.introspection.project_model
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/introspect/test_python_import_graph.py
"""
from __future__ import annotations

import ast
from pathlib import Path

from developer_tools.introspection.project_model import LANG_PYTHON, ModuleInfo

_NETWORK_ROOTS = ("socket", "urllib", "requests", "httpx")


def analyzePython(root: str | Path, relpaths: list[str]) -> dict[str, ModuleInfo]:
    """Analyze the given ``.py`` relpaths under ``root`` into full ModuleInfos."""
    root_path = Path(root).resolve()
    dotted_to_path = _dottedIndex(relpaths)
    out: dict[str, ModuleInfo] = {}
    for rel in sorted(r for r in relpaths if r.endswith(".py")):
        out[rel] = _analyzeOne(root_path, rel, dotted_to_path)
    return out


def _dottedIndex(relpaths: list[str]) -> dict[str, str]:
    """Map dotted module names to relpaths ('pkg/core.py' -> 'pkg.core', __init__ -> pkg)."""
    index: dict[str, str] = {}
    for rel in relpaths:
        if not rel.endswith(".py"):
            continue
        parts = rel[:-3].split("/")
        if parts[-1] == "__init__":
            parts = parts[:-1]
        if parts:
            index[".".join(parts)] = rel
    return index


def _analyzeOne(root_path: Path, rel: str, dotted_to_path: dict[str, str]) -> ModuleInfo:
    """Full analysis of one file; SyntaxError degrades to a skeleton ModuleInfo."""
    try:
        src = (root_path / rel).read_text(encoding="utf-8", errors="replace")
    except OSError:
        src = ""
    loc = len(src.splitlines())
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return ModuleInfo(path=rel, lang=LANG_PYTHON, loc=loc)
    top_nodes, lazy_nodes = _splitImports(tree)
    top = _resolveNodes(top_nodes, rel, dotted_to_path)
    lazy = _resolveNodes(lazy_nodes, rel, dotted_to_path) - top
    return ModuleInfo(
        path=rel,
        lang=LANG_PYTHON,
        loc=loc,
        exports=_exports(tree),
        imports=tuple(sorted(top)),
        lazy_imports=tuple(sorted(lazy)),
        side_effects=_sideEffects(tree),
    )


def _splitImports(tree: ast.Module) -> tuple[list[ast.stmt], list[ast.stmt]]:
    """Import nodes split into (top-level/load-time, inside-a-function/lazy)."""
    top: list[ast.stmt] = []
    lazy: list[ast.stmt] = []

    def _visit(node: ast.AST, in_func: bool) -> None:
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.Import, ast.ImportFrom)):
                (lazy if in_func else top).append(child)
                continue
            child_in_func = in_func or isinstance(
                child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)
            )
            _visit(child, child_in_func)

    _visit(tree, False)
    return top, lazy


def _resolveNodes(nodes: list[ast.stmt], rel: str, dotted_to_path: dict[str, str]) -> set[str]:
    """First-party relpaths imported by the given import nodes (self excluded)."""
    hits: set[str] = set()
    for node in nodes:
        for dotted in _dottedCandidates(node, rel):
            target = _resolveDotted(dotted, dotted_to_path)
            if target and target != rel:
                hits.add(target)
    return hits


def _dottedCandidates(node: ast.stmt, rel: str):
    """Dotted names an import node may refer to (relative imports resolved to absolute)."""
    if isinstance(node, ast.Import):
        for alias in node.names:
            yield alias.name
        return
    if not isinstance(node, ast.ImportFrom):
        return
    if node.level == 0:
        base = node.module or ""
    else:
        pkg_parts = rel[:-3].split("/")[:-1]           # package dir of this module
        pkg_parts = pkg_parts[: len(pkg_parts) - (node.level - 1)]
        if not pkg_parts and node.level > 1:
            return                                     # relative import escapes the root
        base = ".".join(pkg_parts + ([node.module] if node.module else []))
    for alias in node.names:
        yield f"{base}.{alias.name}" if base else alias.name
    if base:
        yield base


def _resolveDotted(dotted: str, dotted_to_path: dict[str, str]) -> str | None:
    """Longest-prefix resolution of a dotted name against the analyzed set."""
    parts = dotted.split(".")
    while parts:
        hit = dotted_to_path.get(".".join(parts))
        if hit:
            return hit
        parts.pop()
    return None


def _exports(tree: ast.Module) -> tuple[str, ...]:
    """__all__ members when defined, else public top-level def/class names in order."""
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "__all__":
                    try:
                        value = ast.literal_eval(node.value)
                        return tuple(dict.fromkeys(str(v) for v in value))
                    except Exception:  # noqa: BLE001 -- dynamic __all__: fall through
                        break
    return tuple(
        node.name
        for node in tree.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
        and not node.name.startswith("_")
    )


def _sideEffects(tree: ast.Module) -> tuple[str, ...]:
    """Heuristic tags for module-level calls (load-time side effects only)."""
    tags: set[str] = set()
    for stmt in tree.body:
        if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        for node in ast.walk(stmt):
            if isinstance(node, ast.Call):
                tag = _tagCall(node)
                if tag:
                    tags.add(tag)
    return tuple(sorted(tags))


def _tagCall(call: ast.Call) -> str | None:
    """Classify one call node into a side-effect tag, or None."""
    if isinstance(call.func, ast.Attribute) and call.func.attr.startswith("write_"):
        return "file-write"                            # Path(...).write_text / write_bytes
    dotted = _callDottedName(call.func)
    if not dotted:
        return None
    if dotted == "open":
        return "file-write" if _openModeWrites(call) else None
    if dotted.split(".")[0] == "subprocess" or dotted == "os.system":
        return "subprocess"
    if dotted.split(".")[0] in _NETWORK_ROOTS:
        return "network"
    if dotted.startswith("os.environ") or dotted == "os.getenv":
        return "env-read"
    return None


def _openModeWrites(call: ast.Call) -> bool:
    """True only when open()'s mode is a literal string containing w/a/x/+.

    Plain ``open(p)`` and read modes are NOT file writes; a dynamic (non-literal)
    mode is not provable, so it is not tagged either.
    """
    mode: ast.expr | None = call.args[1] if len(call.args) > 1 else None
    if mode is None:
        for kw in call.keywords:
            if kw.arg == "mode":
                mode = kw.value
                break
    if not (isinstance(mode, ast.Constant) and isinstance(mode.value, str)):
        return False
    return any(flag in mode.value for flag in ("w", "a", "x", "+"))


def _callDottedName(node: ast.AST) -> str:
    """'subprocess.run' for Attribute chains, 'open' for Names, '' when dynamic."""
    parts: list[str] = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    if not isinstance(node, ast.Name):
        return ""
    parts.append(node.id)
    return ".".join(reversed(parts))
