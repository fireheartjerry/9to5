"""Detect test/build/lint/typecheck commands from config files -- never guessed.

Every DetectedCommand carries the relpath of the config file that proved it
(pyproject.toml, pytest.ini/tox.ini/setup.cfg, package.json scripts, Makefile
targets, Cargo.toml, go.mod). An empty directory yields an empty list.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  detectCommands(root: str | Path) -> list[DetectedCommand]  -- All commands provable from config files under ``root`` (root level only).
DEPENDS-ON: developer_tools.introspection.project_model
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/introspect/test_project_commands.py
"""
from __future__ import annotations

import configparser
import json
import re
import tomllib
from pathlib import Path

from developer_tools.introspection.project_model import (
    KIND_BUILD,
    KIND_LINT,
    KIND_TEST,
    KIND_TYPECHECK,
    DetectedCommand,
)

_PACKAGE_JSON_KINDS = {
    "test": KIND_TEST,
    "build": KIND_BUILD,
    "lint": KIND_LINT,
    "typecheck": KIND_TYPECHECK,
}

_MAKE_TARGET_RE = re.compile(r"^(test|build|lint|typecheck):")

PYTEST_CMD = "python -m pytest"


def detectCommands(root: str | Path) -> list[DetectedCommand]:
    """All commands provable from config files under ``root`` (root level only)."""
    root_path = Path(root).resolve()
    cmds: list[DetectedCommand] = []
    cmds += _fromPyproject(root_path)
    cmds += _fromPytestStyleIni(root_path)
    cmds += _fromPackageJson(root_path)
    cmds += _fromMakefile(root_path)
    if (root_path / "Cargo.toml").is_file():
        cmds.append(DetectedCommand(KIND_TEST, "cargo test", "Cargo.toml"))
        cmds.append(DetectedCommand(KIND_BUILD, "cargo build", "Cargo.toml"))
    if (root_path / "go.mod").is_file():
        cmds.append(DetectedCommand(KIND_TEST, "go test ./...", "go.mod"))
    return cmds


def _fromPyproject(root_path: Path) -> list[DetectedCommand]:
    """pyproject.toml tool sections -> pytest / ruff / mypy / build commands."""
    path = root_path / "pyproject.toml"
    if not path.is_file():
        return []
    try:
        data = tomllib.loads(path.read_text(encoding="utf-8", errors="replace"))
    except Exception:  # noqa: BLE001 -- malformed toml proves nothing
        return []
    tool = data.get("tool", {})
    out: list[DetectedCommand] = []
    if "pytest" in tool:
        out.append(DetectedCommand(KIND_TEST, PYTEST_CMD, "pyproject.toml"))
    if "ruff" in tool:
        out.append(DetectedCommand(KIND_LINT, "ruff check .", "pyproject.toml"))
    if "mypy" in tool:
        out.append(DetectedCommand(KIND_TYPECHECK, "mypy .", "pyproject.toml"))
    if "build-system" in data:
        out.append(DetectedCommand(KIND_BUILD, "python -m build", "pyproject.toml"))
    return out


def _fromPytestStyleIni(root_path: Path) -> list[DetectedCommand]:
    """pytest.ini presence, or a [pytest]/[tool:pytest] section in tox.ini/setup.cfg."""
    out: list[DetectedCommand] = []
    if (root_path / "pytest.ini").is_file():
        out.append(DetectedCommand(KIND_TEST, PYTEST_CMD, "pytest.ini"))
    for name in ("tox.ini", "setup.cfg"):
        path = root_path / name
        if not path.is_file():
            continue
        parser = configparser.ConfigParser()
        try:
            parser.read_string(path.read_text(encoding="utf-8", errors="replace"))
        except configparser.Error:
            continue
        if parser.has_section("pytest") or parser.has_section("tool:pytest"):
            out.append(DetectedCommand(KIND_TEST, PYTEST_CMD, name))
    return out


def _fromPackageJson(root_path: Path) -> list[DetectedCommand]:
    """package.json scripts with test/build/lint/typecheck keys -> ``npm run <key>``."""
    path = root_path / "package.json"
    if not path.is_file():
        return []
    try:
        scripts = json.loads(path.read_text(encoding="utf-8", errors="replace")).get(
            "scripts", {}
        )
    except (json.JSONDecodeError, AttributeError):
        return []
    if not isinstance(scripts, dict):
        return []
    return [
        DetectedCommand(kind, f"npm run {key}", "package.json")
        for key, kind in _PACKAGE_JSON_KINDS.items()
        if key in scripts
    ]


def _fromMakefile(root_path: Path) -> list[DetectedCommand]:
    """Makefile targets named test/build/lint/typecheck -> ``make <target>``."""
    path = root_path / "Makefile"
    if not path.is_file():
        return []
    out: list[DetectedCommand] = []
    seen: set[str] = set()
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        match = _MAKE_TARGET_RE.match(line)
        if match and match.group(1) not in seen:
            target = match.group(1)
            seen.add(target)
            out.append(
                DetectedCommand(_PACKAGE_JSON_KINDS[target], f"make {target}", "Makefile")
            )
    return out
