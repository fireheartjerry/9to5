"""Deterministic file-tree scan: classify source files into ModuleInfo skeletons.

Walks any root with os.walk, skipping vendored/build/cache dirs, classifying files
by extension into a language, and counting lines. Graph fields (exports/imports)
stay empty here -- the analyzer modules fill them; the extract facade sets
``truncated`` when the ``max_files`` cap was hit.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  gitignoreExcludes(root_path: Path) -> tuple[frozenset[str], frozenset[str]]  -- (dir names, dir relpaths) to prune, parsed from the root ``.gitignore``.
  pruneDirnames(rel_dir: str, dirnames: list[str], ig_names: frozenset[str], ig_rels: frozenset[str]) -> list[str]  -- Sorted dirnames minus EXCLUDE_DIRS and gitignore-derived exclusions.
  scanProject(root: str | Path, *, max_files: int=4000) -> list[ModuleInfo]  -- Scan ``root`` into sorted ModuleInfo skeletons, at most ``max_files`` entries.
DEPENDS-ON: developer_tools.introspection.project_model
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/introspect/test_project_scanner.py
"""
from __future__ import annotations

import os
from pathlib import Path

from developer_tools.introspection.project_model import (
    LANG_JAVASCRIPT,
    LANG_OTHER,
    LANG_PYTHON,
    LANG_TYPESCRIPT,
    ModuleInfo,
)

# Directories never scanned in ANY project: VCS internals, virtualenvs, vendored
# deps, build output, tool caches (superset of refactor's FORBIDDEN_SEGMENTS).
EXCLUDE_DIRS = frozenset({
    ".git",
    ".hg",
    ".svn",
    "venv",
    ".venv",
    "node_modules",
    "__pycache__",
    "build",
    "dist",
    ".tox",
    ".pytest_cache",
    "target",
    ".mypy_cache",
    ".ruff_cache",
    ".eggs",
    ".idea",
    ".vscode",
    "vendor",
    ".next",
    ".nuxt",
    "coverage",
    "site-packages",
    ".cache",
})

# Extensions with a dedicated analyzer tier.
LANG_BY_EXTENSION = {
    ".py": LANG_PYTHON,
    ".js": LANG_JAVASCRIPT,
    ".mjs": LANG_JAVASCRIPT,
    ".cjs": LANG_JAVASCRIPT,
    ".jsx": LANG_JAVASCRIPT,
    ".ts": LANG_TYPESCRIPT,
    ".tsx": LANG_TYPESCRIPT,
}

# Recognized-but-unanalyzed code extensions: included as LANG_OTHER so language
# stats stay honest on polyglot repos; everything else (docs/config/data) skipped.
OTHER_CODE_EXTENSIONS = frozenset({
    ".c", ".cc", ".cpp", ".cs", ".go", ".h", ".hpp", ".java", ".kt",
    ".lua", ".php", ".ps1", ".rb", ".rs", ".sh", ".swift",
})


def gitignoreExcludes(root_path: Path) -> tuple[frozenset[str], frozenset[str]]:
    """(dir names, dir relpaths) to prune, parsed from the root ``.gitignore``.

    Honest subset of gitignore semantics: comments, negations, and wildcard
    patterns are skipped; a bare name prunes at any depth (like EXCLUDE_DIRS),
    a path containing ``/`` prunes that exact relpath. Enough to skip vendored
    corpora and runtime dirs on any project without a git dependency.
    """
    try:
        text = (root_path / ".gitignore").read_text(encoding="utf-8", errors="replace")
    except OSError:
        return frozenset(), frozenset()
    names: set[str] = set()
    rels: set[str] = set()
    for line in text.splitlines():
        pat = line.strip()
        if not pat or pat.startswith(("#", "!")) or any(ch in pat for ch in "*?["):
            continue
        pat = pat.strip("/")
        if pat:
            (rels if "/" in pat else names).add(pat)
    return frozenset(names), frozenset(rels)


def pruneDirnames(rel_dir: str, dirnames: list[str],
                  ig_names: frozenset[str], ig_rels: frozenset[str]) -> list[str]:
    """Sorted dirnames minus EXCLUDE_DIRS and gitignore-derived exclusions."""
    return sorted(
        d for d in dirnames
        if d not in EXCLUDE_DIRS and d not in ig_names
        and (f"{rel_dir}/{d}" if rel_dir else d) not in ig_rels
    )


def scanProject(root: str | Path, *, max_files: int = 4000) -> list[ModuleInfo]:
    """Scan ``root`` into sorted ModuleInfo skeletons, at most ``max_files`` entries.

    Deterministic: full candidate list is sorted by POSIX relpath BEFORE the cap is
    applied, so two scans of the same tree always return the same slice. Dirs listed
    in the project's own .gitignore (simple patterns) are pruned like EXCLUDE_DIRS.
    """
    root_path = Path(root).resolve()
    ig_names, ig_rels = gitignoreExcludes(root_path)
    found: list[tuple[str, str]] = []
    for dirpath, dirnames, filenames in os.walk(root_path):
        rel_dir = Path(dirpath).relative_to(root_path).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        dirnames[:] = pruneDirnames(rel_dir, dirnames, ig_names, ig_rels)
        for name in filenames:
            lang = _classify(name)
            if lang is None:
                continue
            rel = f"{rel_dir}/{name}" if rel_dir else name
            found.append((rel, lang))
    found.sort()
    return [
        ModuleInfo(path=rel, lang=lang, loc=_countLoc(root_path / rel))
        for rel, lang in found[:max_files]
    ]


def _classify(filename: str) -> str | None:
    """Language for a filename, or None when the file is not source code."""
    ext = os.path.splitext(filename)[1].lower()
    lang = LANG_BY_EXTENSION.get(ext)
    if lang is not None:
        return lang
    return LANG_OTHER if ext in OTHER_CODE_EXTENSIONS else None


def _countLoc(path: Path) -> int:
    """Line count, UTF-8 with errors replaced; unreadable file counts as 0."""
    try:
        return len(path.read_text(encoding="utf-8", errors="replace").splitlines())
    except OSError:
        return 0
