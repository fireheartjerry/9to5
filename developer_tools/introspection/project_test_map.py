"""Convention-based file->test mapping for any root (no manual map required).

Python: exact ``test_<stem>.py`` -> progressively shorter ``_``-prefixes (min 4
chars) -> glob ``test_*<stem>*.py`` (generalizes tools/repo_map.py::find_tests).
JS/TS: sibling ``<stem>.test.<ext>`` / ``<stem>.spec.<ext>``. Both branches are
PURE lookups against the caller-supplied ``test_files`` list -- the live
filesystem is never consulted, so results are always a subset of ``test_files``.
A caller-supplied ``overrides`` dict is checked first and replaces
MANUAL_TEST_MAP-style knowledge.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  mapFileToTests(root: str | Path, relpath: str, test_files: list[str], overrides: dict[str, list[str]] | None=None) -> list[str]  -- Tests covering ``relpath``: overrides -> exact -> prefix -> glob -> JS sibling -> [].
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/introspect/test_project_test_map.py
"""
from __future__ import annotations

import fnmatch
import posixpath
from pathlib import Path

MIN_PREFIX_CHARS = 4

_JS_TEST_INFIXES = (".test", ".spec")


def mapFileToTests(
    root: str | Path,
    relpath: str,
    test_files: list[str],
    overrides: dict[str, list[str]] | None = None,
) -> list[str]:
    """Tests covering ``relpath``: overrides -> exact -> prefix -> glob -> JS sibling -> [].

    Pure lookup: every returned path comes from ``overrides`` or ``test_files``;
    the filesystem under ``root`` is never consulted.
    """
    if overrides and relpath in overrides:
        return list(overrides[relpath])
    candidates = list(dict.fromkeys(test_files))
    stem, ext = posixpath.splitext(posixpath.basename(relpath))
    if ext == ".py":
        return _mapPython(stem, candidates)
    return _mapJsSibling(relpath, stem, ext, candidates)


def _mapPython(stem: str, test_files: list[str]) -> list[str]:
    """Exact -> shrinking prefix (min 4 chars) -> glob, first tier that hits wins."""
    exact = _byBasename(test_files, f"test_{stem}.py")
    if exact:
        return exact
    parts = stem.split("_")
    for size in range(len(parts) - 1, 0, -1):
        prefix = "_".join(parts[:size])
        if len(prefix) < MIN_PREFIX_CHARS:
            continue
        hits = _byBasename(test_files, f"test_{prefix}.py")
        if hits:
            return hits
    return sorted(
        t for t in test_files
        if fnmatch.fnmatch(posixpath.basename(t), f"test_*{stem}*.py")
    )


def _byBasename(test_files: list[str], basename: str) -> list[str]:
    """All test relpaths whose basename matches exactly, sorted."""
    return sorted(t for t in test_files if posixpath.basename(t) == basename)


def _mapJsSibling(relpath: str, stem: str, ext: str, test_files: list[str]) -> list[str]:
    """Sibling ``<stem>.test.<ext>`` / ``<stem>.spec.<ext>`` present in ``test_files``."""
    directory = posixpath.dirname(relpath)
    test_set = set(test_files)
    hits: list[str] = []
    for infix in _JS_TEST_INFIXES:
        candidate = posixpath.join(directory, f"{stem}{infix}{ext}") if directory \
            else f"{stem}{infix}{ext}"
        if candidate in test_set:
            hits.append(candidate)
    return hits
