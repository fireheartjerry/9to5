"""Facade: build a full ProjectModel for any root + render an LLM prompt digest.

Orchestrates scanner -> python/generic analyzers -> commands -> boundaries, adds
``git_head`` (``git -C <root> rev-parse HEAD``; failure => "") and the
``truncated`` flag. A JSON disk cache lives under
``config.STATE_DIR.parent / "project_models"`` keyed by sha256(root)[:16] and
validated with ``root|git_head|mtime_hash|max_files``: the mtime hash is ALWAYS
computed (even inside git) so uncommitted working-tree edits invalidate the
cache, and ``max_files`` is part of the key so a truncated model is never served
for a larger request. The 9to5 ``config`` module is imported LAZILY so this
package still works outside 9to5 (cache disabled then).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  extractProject(root: str | Path, *, max_files: int=4000, use_cache: bool=True) -> ProjectModel  -- Extract (or load from cache) the full typed model of ``root``.
  contextForPrompt(model: ProjectModel, *, budget_chars: int=4000) -> str  -- LLM-ready sectioned digest of the model, hard-truncated at ``budget_chars``.
DEPENDS-ON: config, developer_tools.introspection.generic_import_scan, developer_tools.introspection.project_boundaries, developer_tools.introspection.project_commands, developer_tools.introspection.project_model, developer_tools.introspection.project_scanner, developer_tools.introspection.python_import_graph
SIDE-EFFECTS: reads/writes JSON cache files under state/project_models/ (when 9to5
RUN/TEST: python -m pytest tests/introspect/test_project_extract.py
"""
from __future__ import annotations

import contextlib
import hashlib
import json
import os
import posixpath
import subprocess
from collections import Counter
from pathlib import Path

from developer_tools.introspection.generic_import_scan import analyzeGeneric
from developer_tools.introspection.project_boundaries import detectBoundaries
from developer_tools.introspection.project_commands import detectCommands
from developer_tools.introspection.project_model import (
    LANG_JAVASCRIPT,
    LANG_PYTHON,
    LANG_TYPESCRIPT,
    ProjectModel,
)
from developer_tools.introspection.project_scanner import gitignoreExcludes, pruneDirnames, scanProject
from developer_tools.introspection.python_import_graph import analyzePython

TOP_FAN_IN_COUNT = 5


def extractProject(
    root: str | Path, *, max_files: int = 4000, use_cache: bool = True
) -> ProjectModel:
    """Extract (or load from cache) the full typed model of ``root``.

    Cache validation key is ``root|git_head|mtime_hash|max_files``. The mtime
    hash is always computed -- git HEAD alone would go stale on uncommitted
    edits (the common path: extract, edit, re-extract) -- and ``max_files``
    is folded in so a truncated model never satisfies a larger request.
    """
    root_path = Path(root).resolve()
    root_str = root_path.as_posix()
    git_head = _gitHead(root_path)
    cache_path = cache_key = None
    if use_cache:
        cache_dir = _cacheDir()
        if cache_dir is not None:
            cache_key = f"{root_str}|{git_head}|{_mtimeHash(root_path)}|{max_files}"
            digest = hashlib.sha256(root_str.encode("utf-8")).hexdigest()[:16]
            cache_path = cache_dir / f"{digest}.json"
            cached = _readCache(cache_path, cache_key)
            if cached is not None:
                return cached
    model = _buildModel(root_path, root_str, git_head, max_files)
    if cache_path is not None:
        _writeCache(cache_path, cache_key, model)
    return model


def _buildModel(root_path: Path, root_str: str, git_head: str, max_files: int) -> ProjectModel:
    """Scan + analyze + assemble the model (no cache involvement)."""
    scanned = scanProject(root_path, max_files=max_files + 1)
    truncated = len(scanned) > max_files
    scanned = scanned[:max_files]
    py_paths = [m.path for m in scanned if m.lang == LANG_PYTHON]
    js_paths = [m.path for m in scanned if m.lang in (LANG_JAVASCRIPT, LANG_TYPESCRIPT)]
    analyzed = analyzePython(root_path, py_paths)
    analyzed.update(analyzeGeneric(root_path, js_paths))
    modules = tuple(analyzed.get(m.path, m) for m in scanned)
    edges = tuple(sorted({(m.path, t) for m in modules for t in m.imports}))
    counts = Counter(m.lang for m in modules)
    languages = tuple(sorted(counts, key=lambda lang: (-counts[lang], lang)))
    return ProjectModel(
        root=root_str,
        languages=languages,
        modules=modules,
        import_edges=edges,
        commands=tuple(detectCommands(root_path)),
        boundaries=detectBoundaries(root_path, list(modules)),
        truncated=truncated,
        git_head=git_head,
    )


def _gitHead(root_path: Path) -> str:
    """`git -C <root> rev-parse HEAD`; any failure (no git, no repo) => ''."""
    try:
        proc = subprocess.run(
            ["git", "-C", str(root_path), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            timeout=15,
        )
    except Exception:  # noqa: BLE001 -- git missing / timeout: cache falls back to mtimes
        return ""
    return proc.stdout.strip() if proc.returncode == 0 else ""


def _cacheDir() -> Path | None:
    """9to5 cache dir, or None outside 9to5 (config not importable => cache disabled)."""
    try:
        import config  # lazy: keeps this package importable in any checkout

        return Path(config.STATE_DIR).parent / "project_models"
    except Exception:  # noqa: BLE001
        return None


def _mtimeHash(root_path: Path) -> str:
    """Digest of (relpath, mtime_ns, size) of every non-excluded file.

    Always part of the cache key so dirty-worktree edits invalidate cached models.
    Prunes the same dirs the scanner prunes (EXCLUDE_DIRS + .gitignore simple
    patterns) so runtime churn in ignored dirs never invalidates the key, and the
    walk cost matches the scan cost. The cache dir itself is skipped when it lives
    under root: otherwise writing the cache would perturb the very hash that keys it.
    """
    cache_dir = _cacheDir()
    skip_abs = str(cache_dir.resolve()) if cache_dir is not None else None
    ig_names, ig_rels = gitignoreExcludes(root_path)
    entries: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root_path):
        rel_dir = Path(dirpath).relative_to(root_path).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        dirnames[:] = pruneDirnames(rel_dir, dirnames, ig_names, ig_rels)
        if skip_abs is not None and str(Path(dirpath).resolve()) == skip_abs:
            continue
        for name in filenames:
            full = Path(dirpath) / name
            try:
                stat = full.stat()
            except OSError:
                continue
            rel = full.relative_to(root_path).as_posix()
            entries.append(f"{rel}|{stat.st_mtime_ns}|{stat.st_size}")
    entries.sort()
    return hashlib.sha256("\n".join(entries).encode("utf-8")).hexdigest()[:16]


def _readCache(cache_path: Path, cache_key: str) -> ProjectModel | None:
    """Cached model when the file exists AND its validation key matches, else None."""
    try:
        data = json.loads(cache_path.read_text(encoding="utf-8"))
        if data.get("key") != cache_key:
            return None
        return ProjectModel.fromJson(json.dumps(data["model"]))
    except Exception:  # noqa: BLE001 -- missing/corrupt cache is a miss, never an error
        return None


def _writeCache(cache_path: Path, cache_key: str, model: ProjectModel) -> None:
    """Best-effort cache write; failure never breaks extraction."""
    with contextlib.suppress(Exception):
        cache_path.parent.mkdir(parents=True, exist_ok=True)
        payload = {"key": cache_key, "model": json.loads(model.toJson())}
        cache_path.write_text(json.dumps(payload, indent=1), encoding="utf-8")


def contextForPrompt(model: ProjectModel, *, budget_chars: int = 4000) -> str:
    """LLM-ready sectioned digest of the model, hard-truncated at ``budget_chars``."""
    name = posixpath.basename(model.root.rstrip("/")) or model.root
    lines = [f"PROJECT: {name} ({model.root})"]
    if model.git_head:
        lines.append(f"git: {model.git_head[:12]}")
    trunc = " [truncated]" if model.truncated else ""
    lines.append(f"languages: {', '.join(model.languages)}; modules: {len(model.modules)}{trunc}")
    if model.commands:
        lines.append("commands:")
        lines.extend(f"- {c.kind}: {c.cmd}  (from {c.source})" for c in model.commands)
    if model.boundaries.packages:
        lines.append(f"packages: {', '.join(model.boundaries.packages)}")
    if model.boundaries.entrypoints:
        lines.append(f"entrypoints: {', '.join(model.boundaries.entrypoints)}")
    fan_in = Counter(target for _, target in model.import_edges)
    if fan_in:
        top = sorted(fan_in.items(), key=lambda item: (-item[1], item[0]))[:TOP_FAN_IN_COUNT]
        lines.append("top fan-in: " + ", ".join(f"{p} ({n})" for p, n in top))
    lines.append(f"import cycles: {_cycleCount(model)}")
    return "\n".join(lines)[:budget_chars]


def _cycleCount(model: ProjectModel) -> int:
    """Count import cycles (SCCs of size >1, plus self-loops) -- iterative Tarjan."""
    graph: dict[str, list[str]] = {m.path: [] for m in model.modules}
    for src, dst in model.import_edges:
        if src in graph and dst in graph:
            graph[src].append(dst)
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    on_stack: set[str] = set()
    stack: list[str] = []
    next_index = 0
    count = 0
    for start in graph:
        if start in index:
            continue
        work: list[tuple[str, int]] = [(start, 0)]
        while work:
            node, i = work.pop()
            if i == 0:
                index[node] = low[node] = next_index
                next_index += 1
                stack.append(node)
                on_stack.add(node)
            descended = False
            for j in range(i, len(graph[node])):
                nxt = graph[node][j]
                if nxt not in index:
                    work.append((node, j + 1))
                    work.append((nxt, 0))
                    descended = True
                    break
                if nxt in on_stack:
                    low[node] = min(low[node], index[nxt])
            if descended:
                continue
            if low[node] == index[node]:
                scc: list[str] = []
                while True:
                    member = stack.pop()
                    on_stack.discard(member)
                    scc.append(member)
                    if member == node:
                        break
                if len(scc) > 1 or node in graph[node]:
                    count += 1
            if work:
                parent = work[-1][0]
                low[parent] = min(low[parent], low[node])
    return count
