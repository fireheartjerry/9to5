"""Regex import scan for JS/TS files: `import ... from '...'` and `require('...')`.

Honest tiering (design spec 3.1): no parsing, just line-level regex plus
``./``-relative specifier resolution (exact, +.js, +.ts, /index.js). Only targets
inside the analyzed set become edges; bare specifiers (npm packages) are dropped.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  analyzeGeneric(root: str | Path, relpaths: list[str]) -> dict[str, ModuleInfo]  -- Analyze JS/TS relpaths under ``root``
DEPENDS-ON: introspect.project_model
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/introspect/test_generic_import_scan.py
"""
from __future__ import annotations

import posixpath
import re
from pathlib import Path

from introspect.project_model import LANG_JAVASCRIPT, LANG_TYPESCRIPT, ModuleInfo

_JS_EXTENSIONS = {".js": LANG_JAVASCRIPT, ".mjs": LANG_JAVASCRIPT, ".cjs": LANG_JAVASCRIPT,
                  ".jsx": LANG_JAVASCRIPT, ".ts": LANG_TYPESCRIPT, ".tsx": LANG_TYPESCRIPT}

_IMPORT_RE = re.compile(
    r"^\s*import\b.*?\bfrom\s+['\"](.+?)['\"]|require\(\s*['\"](.+?)['\"]"
)

_RESOLUTION_SUFFIXES = ("", ".js", ".ts", "/index.js")


def analyzeGeneric(root: str | Path, relpaths: list[str]) -> dict[str, ModuleInfo]:
    """Analyze JS/TS relpaths under ``root``; unknown extensions are skipped."""
    root_path = Path(root).resolve()
    path_set = set(relpaths)
    out: dict[str, ModuleInfo] = {}
    for rel in sorted(relpaths):
        lang = _JS_EXTENSIONS.get(posixpath.splitext(rel)[1].lower())
        if lang is None:
            continue
        out[rel] = _analyzeOne(root_path, rel, lang, path_set)
    return out


def _analyzeOne(root_path: Path, rel: str, lang: str, path_set: set[str]) -> ModuleInfo:
    """Line-regex scan of one file into a ModuleInfo with resolved in-set imports."""
    try:
        src = (root_path / rel).read_text(encoding="utf-8", errors="replace")
    except OSError:
        src = ""
    imports: set[str] = set()
    for line in src.splitlines():
        match = _IMPORT_RE.search(line)
        if not match:
            continue
        spec = match.group(1) or match.group(2)
        target = _resolveSpec(spec, rel, path_set)
        if target and target != rel:
            imports.add(target)
    return ModuleInfo(
        path=rel, lang=lang, loc=len(src.splitlines()), imports=tuple(sorted(imports))
    )


def _resolveSpec(spec: str, from_rel: str, path_set: set[str]) -> str | None:
    """Resolve a ``./``-relative specifier to an in-set relpath, else None."""
    if not spec.startswith("."):
        return None                                    # bare specifier (npm package)
    joined = posixpath.normpath(posixpath.join(posixpath.dirname(from_rel), spec))
    if joined.startswith(".."):
        return None                                    # escapes the project root
    for suffix in _RESOLUTION_SUFFIXES:
        candidate = joined + suffix
        if candidate in path_set:
            return candidate
    return None
