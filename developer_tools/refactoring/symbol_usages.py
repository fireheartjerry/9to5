"""Cross-root symbol usage scan: every AST Name/Attribute/ImportFrom reference.

Generalizes ``tools/codemod.py::cmd_usages`` to ANY root directory: walks .py
files (skipping the same vendored/build/cache dirs as introspect's scanner) and
records each reference to ``symbol`` with its file, line, and reference kind.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Usage  -- One reference to a symbol: POSIX relpath, 1-based line, reference kind.
  findUsages(root: str | Path, symbol: str) -> list[Usage]  -- Every reference to ``symbol`` in .py files under ``root``, sorted.
  findUsagesMulti(root: str | Path, symbols: set[str]) -> dict[str, list[Usage]]  -- Per-symbol usage lists for a whole symbol SET in one walk.
DEPENDS-ON: introspect.project_scanner
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/refactor/test_symbol_usages.py
"""
from __future__ import annotations

import ast
import os
from dataclasses import dataclass
from pathlib import Path

from introspect.project_scanner import gitignoreExcludes, pruneDirnames


@dataclass(frozen=True)
class Usage:
    """One reference to a symbol: POSIX relpath, 1-based line, reference kind."""

    file: str
    line: int
    kind: str  # "name" | "attr" | "import"


def findUsages(root: str | Path, symbol: str) -> list[Usage]:
    """Every reference to ``symbol`` in .py files under ``root``, sorted.

    ``ast.Name`` => "name", ``ast.Attribute`` (matching ``.attr``) => "attr",
    ``ast.ImportFrom`` imported names => "import". Unreadable or syntactically
    invalid files are skipped, never a crash. Thin wrapper over
    ``findUsagesMulti`` (locked public API, unchanged behavior).
    """
    return findUsagesMulti(root, {symbol})[symbol]


def findUsagesMulti(root: str | Path, symbols: set[str]) -> dict[str, list[Usage]]:
    """Per-symbol usage lists for a whole symbol SET in one walk.

    Each .py file under ``root`` is read and parsed exactly once no matter how
    many symbols are requested (vs one full walk per symbol). Every requested
    symbol is present in the result, mapped to a (file, line, kind)-sorted
    list ([] when unused). Same skip semantics as ``findUsages``.
    """
    root_path = Path(root).resolve()
    results: dict[str, list[Usage]] = {symbol: [] for symbol in symbols}
    if not symbols:
        return results
    for rel in _pyFiles(root_path):
        tree = _parseOrNone(root_path / rel)
        if tree is None:
            continue
        for symbol, usage in _usagesInTree(tree, rel, symbols):
            results[symbol].append(usage)
    for hits in results.values():
        hits.sort(key=lambda u: (u.file, u.line, u.kind))
    return results


def _usagesInTree(tree: ast.Module, rel: str, symbols: set[str]) -> list[tuple[str, Usage]]:
    """(symbol, Usage) pairs for every requested symbol in one parsed module."""
    hits: list[tuple[str, Usage]] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            hits.extend(
                (
                    alias.name,
                    Usage(file=rel, line=getattr(alias, "lineno", node.lineno), kind="import"),
                )
                for alias in node.names
                if alias.name in symbols
            )
        elif isinstance(node, ast.Name) and node.id in symbols:
            hits.append((node.id, Usage(file=rel, line=node.lineno, kind="name")))
        elif isinstance(node, ast.Attribute) and node.attr in symbols:
            hits.append((node.attr, Usage(file=rel, line=node.lineno, kind="attr")))
    return hits


def _pyFiles(root_path: Path) -> list[str]:
    """Sorted POSIX relpaths of every .py file under root, pruned like the scanner
    (EXCLUDE_DIRS + the project's own .gitignore simple patterns)."""
    ig_names, ig_rels = gitignoreExcludes(root_path)
    found: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root_path):
        rel_dir = Path(dirpath).relative_to(root_path).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        dirnames[:] = pruneDirnames(rel_dir, dirnames, ig_names, ig_rels)
        found.extend(
            f"{rel_dir}/{name}" if rel_dir else name
            for name in filenames
            if name.endswith(".py")
        )
    return sorted(found)


def _parseOrNone(path: Path) -> ast.Module | None:
    """Parsed AST for ``path``, or None when unreadable / not valid Python."""
    try:
        src = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    try:
        return ast.parse(src)
    except SyntaxError:
        return None
