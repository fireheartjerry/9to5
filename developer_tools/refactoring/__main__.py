"""CLI: ``python -m refactor check <root>`` -- import-cycle report, exit 1 on cycles.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  main(argv: list[str] | None=None) -> int  -- Report modules + import cycles for a root
DEPENDS-ON: developer_tools.introspection, developer_tools.refactoring.cycle_detect
SIDE-EFFECTS: prints to stdout
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import argparse

from developer_tools.introspection import extractProject

from developer_tools.refactoring.cycle_detect import buildImportGraph, findCycles


def main(argv: list[str] | None = None) -> int:
    """Report modules + import cycles for a root; exit 1 when cycles exist."""
    parser = argparse.ArgumentParser(
        prog="python -m refactor",
        description="Refactoring safety checks for any project root.",
    )
    sub = parser.add_subparsers(dest="command", required=True)
    check = sub.add_parser("check", help="report import cycles under <root>")
    check.add_argument("root", help="project root directory to analyze")
    check.add_argument("--max-files", type=int, default=4000, help="scan cap (default 4000)")
    args = parser.parse_args(argv)
    model = extractProject(args.root, max_files=args.max_files, use_cache=False)
    cycles = findCycles(buildImportGraph(model))
    print(f"modules: {len(model.modules)}")
    print(f"import cycles: {len(cycles)}")
    for cycle in cycles:
        print("  " + " -> ".join(cycle))
    return 1 if cycles else 0


if __name__ == "__main__":
    raise SystemExit(main())
