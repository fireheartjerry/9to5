"""Atomic multi-file refactor transaction: snapshot -> journal -> write -> gate -> rollback.

All-or-nothing versus validation and gate failures: every touched path is
byte-snapshotted (MISSING sentinel for not-yet-existing files) AND spilled to
an on-disk journal (``refactor-tx-*`` temp dir, see refactor_journal) before
any write; any validation or gate failure restores every snapshot
byte-for-byte (MISSING => unlink) and reports an explicit RefactorResult. A
hard process CRASH mid-apply leaves the journal behind -- restore manually
from its manifest.json or call ``recoverJournal(journal_dir)``. Gates:
py_compile on every touched .py (fail-closed even on pre-existing breakage),
only-NEW-import-cycles check (pre-existing cycles never block unrelated
edits), and an optional caller command run WITHOUT a shell (argv list, or a
string split Windows-safely). Unrelated dirty files are never touched.
Restore errors are reported loudly in ``reason``, never swallowed.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  RefactorResult  -- Outcome of one apply(): all-applied or nothing-applied, with the why.
  RefactorTransaction  -- Collect edits against one root, preview their impact, apply atomically.
  recoverJournal(journal_dir: str | Path) -> RefactorResult  -- Restore a crashed apply() from its on-disk journal
DEPENDS-ON: developer_tools.introspection, developer_tools.refactoring.change_impact, developer_tools.refactoring.cycle_detect, developer_tools.refactoring.refactor_edits, developer_tools.refactoring.refactor_journal
SIDE-EFFECTS: writes/renames/deletes files under the transaction root during apply; 
RUN/TEST: python -m pytest tests/refactor/test_refactor_transaction.py
"""
from __future__ import annotations

import os
import py_compile
import shlex
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

from developer_tools.refactoring.change_impact import ImpactReport, predictImpact
from developer_tools.refactoring.cycle_detect import buildImportGraph, findCycles
from developer_tools.refactoring.refactor_edits import (
    DeleteFile,
    Edit,
    RenameFile,
    ReplaceInFile,
    WriteFile,
    editPaths,
    validateEdit,
)
from developer_tools.refactoring.refactor_journal import (
    MISSING,
    deleteJournal,
    loadJournal,
    restoreSnapshots,
    writeJournal,
)


@dataclass(frozen=True)
class RefactorResult:
    """Outcome of one apply(): all-applied or nothing-applied, with the why."""

    applied: bool
    reason: str = ""
    gate_output: str = ""
    files_touched: tuple[str, ...] = ()


class RefactorTransaction:
    """Collect edits against one root, preview their impact, apply atomically."""

    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()
        self.edits: list[Edit] = []

    def add(self, edit) -> None:
        """Queue one edit; raises ValueError when validation rejects it."""
        reason = validateEdit(self.root, edit)
        if reason is not None:
            raise ValueError(reason)
        self.edits.append(edit)

    def preview(self, model=None) -> ImpactReport:
        """Pure impact prediction for the queued edits (no writes)."""
        if model is None:
            from developer_tools.introspection import extractProject

            model = extractProject(self.root, use_cache=False)
        return predictImpact(model, self.edits)

    def apply(
        self,
        *,
        gate_cmd: str | list[str] | None = None,
        check_cycles: bool = True,
        timeout_s: int = 300,
    ) -> RefactorResult:
        """Validate -> journal snapshots -> write all -> gate -> commit or full rollback.

        Guarantee: all-or-nothing versus validation and GATE failures. A hard
        process crash mid-apply leaves the journal at a ``refactor-tx-*`` temp
        dir -- restore manually from its manifest.json or with
        ``recoverJournal``. Note the gate asymmetry: the compile gate is
        fail-closed even on PRE-EXISTING breakage (a touched .py that fails
        py_compile blocks the apply no matter whether it compiled before),
        unlike the cycle gate, which blocks only NEW import cycles.
        """
        reason = self._validateAll()
        if reason is not None:
            return RefactorResult(applied=False, reason=reason)
        pre_cycles = self._cycleSet() if check_cycles else set()
        touched = sorted({self._norm(p) for e in self.edits for p in editPaths(e)})
        snapshots = self._snapshot(touched)
        journal_dir = writeJournal(self.root, snapshots)
        created_dirs: list[Path] = []
        try:
            self._writeAll(created_dirs)
        except Exception as exc:  # noqa: BLE001 -- any write failure => rollback
            return self._rollback(snapshots, journal_dir, created_dirs, f"write failed: {exc}", "")
        failure, gate_output = self._gate(touched, pre_cycles, check_cycles, gate_cmd, timeout_s)
        if failure is not None:
            return self._rollback(snapshots, journal_dir, created_dirs, failure, gate_output)
        deleteJournal(journal_dir)
        return RefactorResult(applied=True, gate_output=gate_output, files_touched=tuple(touched))

    # -- apply phases ----------------------------------------------------------

    def _validateAll(self) -> str | None:
        """Re-validate every edit + must-match-once, simulated sequentially in memory."""
        if not self.edits:
            return "no edits added"
        contents: dict[str, bytes | None] = {}
        for edit in self.edits:
            reason = validateEdit(self.root, edit)
            if reason is None:
                reason = self._simulateEdit(edit, contents)
            if reason is not None:
                return reason
        return None

    def _simulateEdit(self, edit, contents: dict[str, bytes | None]) -> str | None:
        """Apply one edit to the in-memory byte map; reason string on any problem."""
        current = self._currentReader(contents)
        if isinstance(edit, WriteFile):
            contents[self._norm(edit.path)] = edit.content.encode("utf-8")
            return None
        if isinstance(edit, ReplaceInFile):
            rel = self._norm(edit.path)
            data = current(rel)
            if data is None:
                return f"ReplaceInFile target missing: {rel}"
            count = data.count(edit.old.encode("utf-8"))
            if count != 1:
                return f"ReplaceInFile {rel}: old text must match exactly once, found {count}"
            contents[rel] = data.replace(edit.old.encode("utf-8"), edit.new.encode("utf-8"))
            return None
        if isinstance(edit, DeleteFile):
            rel = self._norm(edit.path)
            if current(rel) is None:
                return f"DeleteFile target missing: {rel}"
            contents[rel] = None
            return None
        src, dst = self._norm(edit.path), self._norm(edit.new_path)   # RenameFile
        data = current(src)
        if data is None:
            return f"RenameFile source missing: {src}"
        if current(dst) is not None:
            return f"rename target exists: {dst}"           # fail-closed: never overwrite
        contents[dst] = data
        contents[src] = None
        return None

    def _currentReader(self, contents: dict[str, bytes | None]):
        """Reader over the in-memory map, falling back to on-disk bytes."""

        def current(rel: str) -> bytes | None:
            if rel in contents:
                return contents[rel]
            path = self.root / rel
            return path.read_bytes() if path.is_file() else None

        return current

    def _snapshot(self, touched: list[str]) -> dict[str, object]:
        """Exact current bytes per touched path; MISSING when it does not exist."""
        snapshots: dict[str, object] = {}
        for rel in touched:
            path = self.root / rel
            snapshots[rel] = path.read_bytes() if path.is_file() else MISSING
        return snapshots

    def _writeAll(self, created_dirs: list[Path]) -> None:
        """Perform every edit on disk, in order; new parent dirs are recorded."""
        for edit in self.edits:
            if isinstance(edit, WriteFile):
                target = self.root / self._norm(edit.path)
                self._makeParents(target, created_dirs)
                target.write_bytes(edit.content.encode("utf-8"))
            elif isinstance(edit, ReplaceInFile):
                target = self.root / self._norm(edit.path)
                data = target.read_bytes()
                target.write_bytes(
                    data.replace(edit.old.encode("utf-8"), edit.new.encode("utf-8"))
                )
            elif isinstance(edit, DeleteFile):
                (self.root / self._norm(edit.path)).unlink()
            else:                                            # RenameFile: read+write+delete
                src = self.root / self._norm(edit.path)
                dst = self.root / self._norm(edit.new_path)
                data = src.read_bytes()
                self._makeParents(dst, created_dirs)
                dst.write_bytes(data)
                src.unlink()

    def _makeParents(self, target: Path, created_dirs: list[Path]) -> None:
        """mkdir -p for ``target``'s parent, recording dirs that did not exist."""
        probe = target.parent
        while probe != self.root and probe != probe.parent and not probe.exists():
            created_dirs.append(probe)
            probe = probe.parent
        target.parent.mkdir(parents=True, exist_ok=True)

    def _gate(
        self,
        touched: list[str],
        pre_cycles: set[tuple[str, ...]],
        check_cycles: bool,
        gate_cmd: str | list[str] | None,
        timeout_s: int,
    ) -> tuple[str | None, str]:
        """(failure reason | None, gate command output). Order: compile, cycles, cmd."""
        reason = self._compileGate(touched)
        if reason is not None:
            return reason, ""
        if check_cycles:
            new_cycles = sorted(self._cycleSet() - pre_cycles)
            if new_cycles:
                rendered = "; ".join(" -> ".join(c) for c in new_cycles)
                return f"new import cycle(s) introduced: {rendered}", ""
        if gate_cmd is not None:
            return self._commandGate(gate_cmd, timeout_s)
        return None, ""

    def _compileGate(self, touched: list[str]) -> str | None:
        """py_compile every touched .py that still exists; scratch cfile, no pollution."""
        with tempfile.TemporaryDirectory(prefix="9to5-gate-") as scratch:
            cfile = str(Path(scratch) / "gate.pyc")
            for rel in touched:
                path = self.root / rel
                if not rel.endswith(".py") or not path.is_file():
                    continue
                try:
                    py_compile.compile(str(path), cfile=cfile, doraise=True)
                except py_compile.PyCompileError as exc:
                    return f"py_compile failed: {exc}"
                except Exception as exc:  # noqa: BLE001 -- unreadable file etc.
                    return f"py_compile failed for {rel}: {exc}"
        return None

    def _commandGate(self, gate_cmd: str | list[str], timeout_s: int) -> tuple[str | None, str]:
        """Run the caller's gate command WITHOUT a shell; rc 0 required."""
        try:
            proc = subprocess.run(
                _splitGateCmd(gate_cmd),
                cwd=self.root,
                timeout=timeout_s,
                capture_output=True,
            )
        except subprocess.TimeoutExpired:
            return f"gate command timed out after {timeout_s}s: {gate_cmd}", ""
        except Exception as exc:  # noqa: BLE001 -- e.g. executable not found
            return f"gate command failed to start: {exc}", ""
        output = (proc.stdout + proc.stderr).decode("utf-8", errors="replace")
        if proc.returncode != 0:
            return f"gate command exited {proc.returncode}: {gate_cmd}", output
        return None, output

    def _cycleSet(self) -> set[tuple[str, ...]]:
        """Current import cycles of the root as canonical tuples."""
        from developer_tools.introspection import extractProject

        model = extractProject(self.root, use_cache=False)
        return {tuple(c) for c in findCycles(buildImportGraph(model))}

    def _rollback(
        self,
        snapshots: dict[str, object],
        journal_dir: Path,
        created_dirs: list[Path],
        reason: str,
        gate_output: str,
    ) -> RefactorResult:
        """Restore every snapshot byte-for-byte; restore errors reported loudly.

        The journal is deleted only after a CLEAN restore; on restore errors it
        is kept so the pre-apply bytes remain recoverable. Empty dirs the tx
        itself created are removed best-effort (deepest first).
        """
        errors = restoreSnapshots(self.root, snapshots)
        _removeCreatedDirs(created_dirs)
        if errors:
            reason += " | ROLLBACK ERRORS (tree may be inconsistent): " + "; ".join(errors)
            reason += f" | journal kept at {journal_dir}"
        else:
            deleteJournal(journal_dir)
        return RefactorResult(applied=False, reason=reason, gate_output=gate_output)

    def _norm(self, path: str) -> str:
        """Canonical POSIX relpath key: './a.py', 'a.py', absolute-in-root all agree."""
        candidate = Path(str(path).replace("\\", "/"))
        target = candidate if candidate.is_absolute() else self.root / candidate
        return Path(os.path.relpath(target, self.root)).as_posix()


def recoverJournal(journal_dir: str | Path) -> RefactorResult:
    """Restore a crashed apply() from its on-disk journal; delete it when clean."""
    root, snapshots = loadJournal(journal_dir)
    errors = restoreSnapshots(root, snapshots)
    if errors:
        reason = "journal restore errors (journal kept): " + "; ".join(errors)
        return RefactorResult(applied=False, reason=reason)
    deleteJournal(Path(journal_dir))
    return RefactorResult(
        applied=False,
        reason=f"recovered from journal: {journal_dir}",
        files_touched=tuple(sorted(snapshots)),
    )


def _splitGateCmd(gate_cmd: str | list[str]) -> list[str]:
    """argv for the gate command; list form passes through untouched.

    A string is shlex-split with ``posix=False`` on Windows so backslashed
    paths like ``C:\\tools\\gate.py`` survive; prefer the list form for
    quoting-heavy commands.
    """
    if isinstance(gate_cmd, list):
        return list(gate_cmd)
    return shlex.split(gate_cmd, posix=(os.name != "nt"))


def _removeCreatedDirs(created_dirs: list[Path]) -> None:
    """Best-effort removal of tx-created dirs (deepest first, only when empty)."""
    for directory in sorted(set(created_dirs), key=lambda p: len(p.parts), reverse=True):
        try:
            directory.rmdir()
        except OSError:
            pass
