"""Approach generation: archetype-templated (brainless) or brain-authored candidates.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ApproachCandidate  -- One candidate approach to a goal, comparable and JSON-friendly.
  generateApproaches(goal: str, model: ProjectModel, *, brain=None, n: int=3) -> list[ApproachCandidate]  -- Generate up to ``n`` approach candidates for ``goal`` against ``model``.
  brainText(raw) -> str  -- Accept Brain-protocol return shapes: plain str or ollama chat dict.
DEPENDS-ON: developer_tools.introspection.project_model
SIDE-EFFECTS: none (brain callable is caller-injected; None => deterministic fallback)
RUN/TEST: python -m pytest tests/explore/test_approach_gen.py
"""
from __future__ import annotations

import json
from dataclasses import dataclass

from developer_tools.introspection.project_model import ProjectModel

APPROACH_ARCHETYPES = (
    "minimal-patch",
    "refactor-first",
    "test-first",
    "new-module",
    "bold-redesign",
)

_ARCHETYPE_TITLES = {
    "minimal-patch": "Minimal patch",
    "refactor-first": "Refactor first",
    "test-first": "Test first",
    "new-module": "New module",
    "bold-redesign": "Bold redesign",
}

_ARCHETYPE_FILES = {
    "minimal-patch": 1,
    "refactor-first": 3,
    "test-first": 2,
    "new-module": 2,
    "bold-redesign": 5,
}

_GEN_SYSTEM = (
    "You propose distinct implementation approaches for a coding goal. "
    "Reply ONLY with a JSON list of objects, each with keys: title, summary, "
    "steps (list of strings), files_touched_estimate (int), archetype "
    f"(one of {list(APPROACH_ARCHETYPES)})."
)


@dataclass(frozen=True)
class ApproachCandidate:
    """One candidate approach to a goal, comparable and JSON-friendly."""

    approach_id: str        # "a1", "a2", ...
    title: str
    summary: str            # 1-3 sentences, used as E6 angle_hint
    steps: tuple[str, ...]
    files_touched_estimate: int
    archetype: str


def generateApproaches(
    goal: str, model: ProjectModel, *, brain=None, n: int = 3
) -> list[ApproachCandidate]:
    """Generate up to ``n`` approach candidates for ``goal`` against ``model``.

    Brainless: deterministic specialization of the first ``n`` archetypes.
    With brain: one want_json call; invalid items dropped, unknown archetypes
    clamped to "minimal-patch", shortfall topped up from unused archetypes.
    """
    traits = _projectTraits(model)
    drafts: list[dict] = []
    if brain is not None:
        drafts = _brainDrafts(goal, brain, n)
    used = {d["archetype"] for d in drafts}
    for archetype in APPROACH_ARCHETYPES:
        if len(drafts) >= n:
            break
        if archetype in used:
            continue
        drafts.append(_archetypeDraft(archetype, goal, traits))
        used.add(archetype)
    return [
        ApproachCandidate(approach_id=f"a{i + 1}", **draft)
        for i, draft in enumerate(drafts[:n])
    ]


def _projectTraits(model: ProjectModel) -> dict:
    """Extract the traits the templates specialize on (all deterministic)."""
    test_cmd = next((c.cmd for c in model.commands if c.kind == "test"), "")
    edges = set(model.import_edges)
    # only detects direct A<->B mutual imports, not longer cycles
    has_mutual_import = any((dst, src) in edges for src, dst in edges if src != dst)
    return {
        "test_cmd": test_cmd,
        "facades": tuple(model.boundaries.facades),
        "has_mutual_import": has_mutual_import,
        "entrypoints": tuple(model.boundaries.entrypoints),
    }


def _archetypeDraft(archetype: str, goal: str, traits: dict) -> dict:
    """Deterministic candidate draft (no approach_id yet) for one archetype."""
    steps = list(_ARCHETYPE_STEPS[archetype])
    if archetype == "test-first" and traits["test_cmd"]:
        steps.insert(0, f"Run the detected test command first: {traits['test_cmd']}")
    if traits["test_cmd"]:
        steps.append(f"Verify with `{traits['test_cmd']}` before finishing")
    if traits["facades"]:
        steps.append(
            f"Preserve re-exports in facade module {traits['facades'][0]}"
        )
    if traits["has_mutual_import"]:
        steps.append(
            "Do not deepen the existing mutual import; guard against new cycles"
        )
    summary = (
        f"{_ARCHETYPE_TITLES[archetype]} approach to: {goal}. "
        f"{_ARCHETYPE_SUMMARIES[archetype]}"
    )
    if traits["entrypoints"]:
        summary += f" Entrypoint {traits['entrypoints'][0]} stays runnable."
    return {
        "title": f"{_ARCHETYPE_TITLES[archetype]}: {goal}",
        "summary": summary,
        "steps": tuple(steps),
        "files_touched_estimate": _ARCHETYPE_FILES[archetype],
        "archetype": archetype,
    }


_ARCHETYPE_STEPS = {
    "minimal-patch": (
        "Locate the narrowest module owning the behavior",
        "Apply the smallest edit that satisfies the goal",
    ),
    "refactor-first": (
        "Add guard tests around the seams before moving code",
        "Reshape the touched modules for the change, behavior-preserving",
        "Land the goal change on the cleaned structure",
    ),
    "test-first": (
        "Write failing tests capturing the goal",
        "Implement until the new tests pass",
    ),
    "new-module": (
        "Create a dedicated module for the new behavior",
        "Wire it in behind the existing public surface",
    ),
    "bold-redesign": (
        "Prepare a rollback plan before wide edits",
        "Redesign the affected subsystem around the goal",
        "Migrate callers and delete the superseded paths",
    ),
}

_ARCHETYPE_SUMMARIES = {
    "minimal-patch": "Touch as little as possible; lowest blast radius.",
    "refactor-first": "Clean the structure first so the change lands simply.",
    "test-first": "Lock behavior in tests before changing code.",
    "new-module": "Isolate new behavior in its own module boundary.",
    "bold-redesign": "Accept churn now for a structurally better end state.",
}


def _brainDrafts(goal: str, brain, n: int) -> list[dict]:
    """One brain call -> validated/clamped drafts (may be empty on bad output)."""
    user = f"Goal: {goal}\nPropose {n} distinct approaches as a JSON list."
    try:
        raw = brain(_GEN_SYSTEM, user, want_json=True)
        items = json.loads(brainText(raw))
    except Exception:
        return []
    if not isinstance(items, list):
        return []
    drafts = []
    for item in items[:n]:
        draft = _clampItem(item)
        if draft is not None:
            drafts.append(draft)
    return drafts


def _clampItem(item) -> dict | None:
    """Validate one brain-authored item; None means drop it."""
    if not isinstance(item, dict):
        return None
    if not isinstance(item.get("steps"), (list, tuple)):
        return None  # a bare string would coerce to a tuple of characters
    try:
        title = str(item["title"])
        summary = str(item["summary"])
        steps = tuple(str(s) for s in item["steps"])
        files_estimate = max(1, int(item["files_touched_estimate"]))
    except (KeyError, TypeError, ValueError):
        return None
    if not title or not steps:
        return None
    archetype = str(item.get("archetype", ""))
    if archetype not in APPROACH_ARCHETYPES:
        archetype = "minimal-patch"
    return {
        "title": title,
        "summary": summary,
        "steps": steps,
        "files_touched_estimate": files_estimate,
        "archetype": archetype,
    }


def brainText(raw) -> str:
    """Accept Brain-protocol return shapes: plain str or ollama chat dict."""
    if isinstance(raw, dict):
        return str(raw.get("message", {}).get("content", ""))
    return str(raw)
