"""Winner selection + mechanical synthesis of runner-up mitigations.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  SynthesisResult  -- The selected approach plus lifted mitigations and a scored rationale.
  selectOrSynthesize(candidates: list[ApproachCandidate], scores: list[TradeoffScore], *, brain=None) -> SynthesisResult  -- Pick the winner (total desc, fewer files, lowest id) and lift mitigations.
DEPENDS-ON: developer_tools.exploration.approach_gen, developer_tools.exploration.approach_tradeoffs
SIDE-EFFECTS: none (brain, when given, may only reword the rationale)
RUN/TEST: python -m pytest tests/explore/test_approach_synthesis.py
"""
from __future__ import annotations

from dataclasses import dataclass

from developer_tools.exploration.approach_gen import ApproachCandidate, brainText
from developer_tools.exploration.approach_tradeoffs import TradeoffScore

MITIGATION_MARKERS = ("test", "rollback", "guard", "verify")

MAX_ADOPTED_MITIGATIONS = 2

_REWORD_SYSTEM = (
    "Reword the following approach-selection rationale into one clear sentence. "
    "Do not change any facts or numbers. Reply with the sentence only."
)


@dataclass(frozen=True)
class SynthesisResult:
    """The selected approach plus lifted mitigations and a scored rationale."""

    winner: ApproachCandidate
    scores: tuple[TradeoffScore, ...]
    adopted_mitigations: tuple[str, ...]   # steps lifted from runners-up
    rationale: str


def selectOrSynthesize(
    candidates: list[ApproachCandidate],
    scores: list[TradeoffScore],
    *,
    brain=None,
) -> SynthesisResult:
    """Pick the winner (total desc, fewer files, lowest id) and lift mitigations.

    Deterministic; ``brain`` may only reword the rationale (never the choice).
    """
    if not candidates or not scores:
        raise ValueError("selectOrSynthesize needs at least one scored candidate")
    by_id = {c.approach_id: c for c in candidates}
    ranked = sorted(
        (s for s in scores if s.approach_id in by_id),
        key=lambda s: (
            -s.total,
            by_id[s.approach_id].files_touched_estimate,
            s.approach_id,
        ),
    )
    if not ranked:
        raise ValueError("no score matches any candidate approach_id")
    winner = by_id[ranked[0].approach_id]
    adopted = _adoptMitigations(winner, [by_id[s.approach_id] for s in ranked[1:]])
    rationale = _rationale(winner, ranked[0])
    if brain is not None:
        rationale = _rewordRationale(brain, rationale)
    return SynthesisResult(
        winner=winner,
        scores=tuple(ranked),
        adopted_mitigations=adopted,
        rationale=rationale,
    )


def _adoptMitigations(
    winner: ApproachCandidate, runners_up: list[ApproachCandidate]
) -> tuple[str, ...]:
    """Lift up to MAX_ADOPTED_MITIGATIONS marker-bearing steps absent from winner."""
    winner_steps = set(winner.steps)
    adopted: list[str] = []
    for cand in runners_up:
        for step in cand.steps:
            if len(adopted) >= MAX_ADOPTED_MITIGATIONS:
                return tuple(adopted)
            lowered = step.lower()
            if step in winner_steps or step in adopted:
                continue
            if any(marker in lowered for marker in MITIGATION_MARKERS):
                adopted.append(step)
    return tuple(adopted)


def _rationale(winner: ApproachCandidate, score: TradeoffScore) -> str:
    """One deterministic sentence citing every score component."""
    return (
        f"Selected {winner.approach_id} '{winner.title}' ({winner.archetype}) "
        f"with total {score.total} from risk {score.risk}, effort {score.effort}, "
        f"testability {score.testability}, fit {score.fit}."
    )


def _rewordRationale(brain, rationale: str) -> str:
    """Ask the brain for a reworded rationale; fall back to the original."""
    try:
        text = brainText(brain(_REWORD_SYSTEM, rationale)).strip()
    except Exception:
        return rationale
    return text or rationale
