"""Validate completion of a bug-fixing workflow.

Usage:
    python check_workflow.py --workflow-file <path>

Exits 0 if all acceptance criteria are met, non-zero otherwise.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  parseArgs() -> argparse.Namespace
  checkFile(path: Path, label: str) -> list[str]  -- Return list of failure messages for a required file.
  validateWorkflow(workflow_file: Path) -> tuple[bool, list[str], list[str]]  -- Return (ok, passes, failures).
  main() -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def parseArgs() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Validate bug-fixing workflow completion")
    parser.add_argument("--workflow-file", required=True, help="Path to workflow JSON file")
    return parser.parse_args()


def checkFile(path: Path, label: str) -> list[str]:
    """Return list of failure messages for a required file."""
    failures = []
    if not path.exists():
        failures.append(f"MISSING: {label} ({path})")
    elif path.stat().st_size == 0:
        failures.append(f"EMPTY: {label} ({path})")
    return failures


def validateWorkflow(workflow_file: Path) -> tuple[bool, list[str], list[str]]:
    """Return (ok, passes, failures)."""
    passes: list[str] = []
    failures: list[str] = []

    if not workflow_file.exists():
        failures.append(f"Workflow file not found: {workflow_file}")
        return False, passes, failures

    with workflow_file.open() as f:
        workflow = json.load(f)

    passes.append(f"Workflow file valid JSON: {workflow_file.name}")

    repo_root = workflow_file.parent

    # Check each step's deliverables
    for step in workflow.get("workflow_definition", []):
        step_name = step.get("step_name", "unknown")
        for deliverable in step.get("deliverables", []):
            target = repo_root / deliverable
            if deliverable.endswith("/"):
                # Directory — just check it exists
                if target.exists():
                    passes.append(f"[{step_name}] directory exists: {deliverable}")
                else:
                    failures.append(f"[{step_name}] directory missing: {deliverable}")
            else:
                result = checkFile(target, f"[{step_name}] {deliverable}")
                if result:
                    failures.extend(result)
                else:
                    passes.append(f"[{step_name}] file present and non-empty: {deliverable}")

    # Always-required outputs
    required = [
        (repo_root / "state" / "bug_reports.txt", "bug_reports.txt"),
        (repo_root / "docs" / "bug_fixing_report.md", "bug_fixing_report.md"),
    ]
    for path, label in required:
        result = checkFile(path, label)
        if result:
            failures.extend(result)
        else:
            passes.append(f"Required output present: {label}")

    return len(failures) == 0, passes, failures


def main() -> int:
    args = parseArgs()
    workflow_file = Path(args.workflow_file)

    ok, passes, failures = validateWorkflow(workflow_file)

    for msg in passes:
        print(f"  PASS  {msg}")
    for msg in failures:
        print(f"  FAIL  {msg}", file=sys.stderr)

    if ok:
        print(f"\nAll {len(passes)} checks passed.")
        return 0
    else:
        print(f"\n{len(failures)} check(s) failed.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
