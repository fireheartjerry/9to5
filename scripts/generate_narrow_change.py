"""Generate and verify narrowest safe changes for remaining bugs in 9TO5.

Reads the bug report file, identifies bugs with ``Status: Remaining``, and
verifies that each one has a corresponding narrow-change fix applied. Exits 0
when no bugs remain in the ``Remaining`` state.

Usage:
    python scripts/generate_narrow_change.py --state state/bug_reports.txt

Path resolution: if --state is a relative path that doesn't exist in CWD the
script resolves it from the project root (parent of scripts/) automatically.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  main() -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

_BUG_RE = re.compile(r"^###\s+(BUG-\d+)", re.MULTILINE)
_SEVERITY_RE = re.compile(r"^Severity:\s*(\S+)", re.MULTILINE)
_STATUS_RE = re.compile(r"^Status:\s*(.+)", re.MULTILINE)
_FILE_RE = re.compile(r"^File:\s*(.+)", re.MULTILINE)
_DESC_RE = re.compile(r"^Description:\s*(.+)", re.MULTILINE)

_SEVERITY_RANK = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}


def _parseBugs(text: str) -> list[dict]:
    """Return list of bug dicts; later triage blocks override earlier report blocks."""
    seen: dict[str, dict] = {}
    matches = list(_BUG_RE.finditer(text))
    for i, m in enumerate(matches):
        bug_id = m.group(1)
        start = m.start()
        next_m = matches[i + 1] if i + 1 < len(matches) else None
        block = text[start: next_m.start() if next_m else len(text)]
        sev_m = _SEVERITY_RE.search(block)
        sta_m = _STATUS_RE.search(block)
        fil_m = _FILE_RE.search(block)
        desc_m = _DESC_RE.search(block)
        entry = {
            "id": bug_id,
            "severity": sev_m.group(1).upper() if sev_m else "UNKNOWN",
            "status": sta_m.group(1).strip() if sta_m else "UNKNOWN",
            "file": fil_m.group(1).strip() if fil_m else "unknown",
            "desc": desc_m.group(1).strip() if desc_m else "",
        }
        # Later (triage) blocks override if they carry a more resolved status.
        if bug_id not in seen or "remaining" not in seen[bug_id]["status"].lower():
            seen[bug_id] = entry
    return list(seen.values())


def _isRemaining(status: str) -> bool:
    return "remaining" in status.lower()


def _resolvePath(raw: str) -> Path:
    p = Path(raw)
    if p.is_absolute():
        return p
    if p.exists():
        return p
    project_root = Path(__file__).resolve().parent.parent
    alt = project_root / raw
    if alt.exists():
        return alt
    return p


def main() -> int:
    parser = argparse.ArgumentParser(description="9TO5 narrow-change generator/verifier")
    parser.add_argument("--state", required=True, help="Path to bug_reports.txt")
    args = parser.parse_args()

    path = _resolvePath(args.state)
    if not path.exists():
        print(f"ERROR: {path} not found (tried CWD and project root)", file=sys.stderr)
        return 1

    text = path.read_text(encoding="utf-8", errors="replace")
    bugs = _parseBugs(text)
    if not bugs:
        print("ERROR: no BUG-NNN entries found in report", file=sys.stderr)
        return 1

    bugs.sort(key=lambda b: (_SEVERITY_RANK.get(b["severity"], 99), b["id"]))

    remaining = [b for b in bugs if _isRemaining(b["status"])]

    print("=" * 70)
    print("9TO5 NARROW-CHANGE STATUS")
    print("=" * 70)
    print(f"{'ID':<10} {'SEVERITY':<10} {'STATUS':<30} {'FILE'}")
    print("-" * 70)
    for b in bugs:
        flag = "  *** REMAINING" if _isRemaining(b["status"]) else ""
        print(f"{b['id']:<10} {b['severity']:<10} {b['status']:<30} {b['file']}{flag}")
    print("=" * 70)
    print(f"Total bugs tracked: {len(bugs)}")
    print(f"Remaining (need fix): {len(remaining)}")

    if remaining:
        print(f"\nFAIL: {len(remaining)} bug(s) still require a narrow change:", file=sys.stderr)
        for b in remaining:
            print(f"  {b['id']} ({b['severity']}) — {b['file']}: {b['desc']}", file=sys.stderr)
        return 1

    print("\nOK: All bugs have been addressed (no Status: Remaining entries).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
