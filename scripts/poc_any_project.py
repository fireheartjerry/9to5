"""poc_any_project -- runnable proof of the introspect/refactor/explore packages.

Part A ([A/self]) runs the three packages against this 9to5 checkout: extract a
typed ProjectModel, assert pytest is the detected test command, count import
cycles (expect zero touching first-party, non-references/ code), rank solution
approaches for a real goal, and demo RefactorTransaction rollback + apply on a
SCRATCH COPY of three first-party files -- the real tree is proven untouched
via before/after hashes. Part B ([B/external]) shallow-clones
pallets/itsdangerous (on any clone failure: a clearly-labeled offline-fallback
fixture project is generated instead) and repeats extract / test-command
detection / cycle check / brain-free exploration.

Run from repo root:
    python scripts/poc_any_project.py

Deterministic and non-destructive: the only network access is the one optional
git clone; every write lands in tempfile.mkdtemp() dirs (removed afterwards)
or the designed introspect model cache. Exit 0 = all checks passed, 1 = any
assertion failure.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  PocError  -- One PoC assertion failed
  require(cond: bool, msg: str) -> None  -- Hard-fail the PoC with ``msg`` when ``cond`` is false.
  sha256File(path: Path) -> str  -- Hex sha256 of one file's bytes.
  indent(text: str) -> str  -- Indent every line by four spaces (digest excerpts).
  testCommand(model) -> str  -- The model's detected test command, or '' when none was proven.
  forceRmtree(path: Path) -> None  -- rmtree that survives git's read-only object files on Windows.
  printApproaches(label: str, goal: str, result, titles: dict) -> None  -- Ranked score table + winner/mitigations/rationale for one explore run.
  partASelf() -> None  -- Extract 9to5, assert pytest detection, cycles, explore, refactor demo.
  partACycles(model) -> None  -- findCycles over the self model
  partARefactorDemo() -> None  -- RefactorTransaction rollback + apply on scratch copies
  pickUniqueLine(text: str) -> str  -- First long line occurring exactly once (comment-appendable: no trailing \\).
  runFailingTx(scratch: Path, copies: list[Path], edit) -> None  -- Valid ReplaceInFile + syntax-error WriteFile: compile gate must roll back.
  runSucceedingTx(scratch: Path, target: Path, edit) -> None  -- Same ReplaceInFile + a valid WriteFile: previews clean and applies.
  partBExternal() -> None  -- Clone (or fixture) an external project: extract, cycles, brain-free explore.
  cloneOrFixture(ext_root: Path) -> tuple[Path, bool]  -- (project dir, offline?)
  writeFixture(dest: Path) -> None  -- Minimal python package (pyproject + pytest config + a test) at ``dest``.
  main() -> int  -- Run parts A and B
DEPENDS-ON: config, explore.exploreSolutionSpace, explore.generateApproaches, introspect.contextForPrompt, introspect.extractProject, refactor.RefactorTransaction, refactor.ReplaceInFile, refactor.WriteFile, refactor.buildImportGraph, refactor.findCycles
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import hashlib
import os
import shutil
import stat
import subprocess
import sys
import tempfile
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

import config  # noqa: E402
from explore import exploreSolutionSpace, generateApproaches  # noqa: E402
from introspect import contextForPrompt, extractProject  # noqa: E402
from refactor import (  # noqa: E402
    RefactorTransaction,
    ReplaceInFile,
    WriteFile,
    buildImportGraph,
    findCycles,
)

SELF_MAX_FILES = 20000
EXTERNAL_MAX_FILES = 2000
DIGEST_EXCERPT_CHARS = 1200
CLONE_URL = "https://github.com/pallets/itsdangerous"
CLONE_TIMEOUT_S = 60
SCRATCH_COPY_FILES = (
    "introspect/project_model.py",
    "refactor/refactor_edits.py",
    "explore/__init__.py",
)
BROKEN_PY = "def broken(:\n    pass\n"
EXTRA_PY = '"""PoC scratch module (safe to delete)."""\nVALUE = 1\n'
RULE = "=" * 72


class PocError(AssertionError):
    """One PoC assertion failed; main() turns this into exit code 1."""


def require(cond: bool, msg: str) -> None:
    """Hard-fail the PoC with ``msg`` when ``cond`` is false."""
    if not cond:
        raise PocError(msg)


def sha256File(path: Path) -> str:
    """Hex sha256 of one file's bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def indent(text: str) -> str:
    """Indent every line by four spaces (digest excerpts)."""
    return "\n".join("    " + line for line in text.splitlines())


def testCommand(model) -> str:
    """The model's detected test command, or '' when none was proven."""
    return next((c.cmd for c in model.commands if c.kind == "test"), "")


def forceRmtree(path: Path) -> None:
    """rmtree that survives git's read-only object files on Windows."""
    if not path.exists():
        return
    for dirpath, _dirnames, filenames in os.walk(path):
        for name in filenames:
            try:
                os.chmod(os.path.join(dirpath, name), stat.S_IWRITE)
            except OSError:
                pass
    shutil.rmtree(path, ignore_errors=True)


def printApproaches(label: str, goal: str, result, titles: dict) -> None:
    """Ranked score table + winner/mitigations/rationale for one explore run."""
    print(f"{label} explore goal: {goal!r}")
    header = f"  {'id':<4} {'total':>6} {'risk':>5} {'effort':>6} {'test':>5} {'fit':>4}  title"
    print(header)
    for s in result.scores:
        title = titles.get(s.approach_id, "?")
        print(
            f"  {s.approach_id:<4} {s.total:>6.4f} {s.risk:>5.2f} {s.effort:>6.2f}"
            f" {s.testability:>5.2f} {s.fit:>4.2f}  {title}"
        )
    print(f"{label} winner: {result.winner.title}")
    for mitigation in result.adopted_mitigations:
        print(f"{label} adopted mitigation: {mitigation}")
    print(f"{label} rationale: {result.rationale}")


# -- Part A: 9to5 itself -------------------------------------------------------


def partASelf() -> None:
    """Extract 9to5, assert pytest detection, cycles, explore, refactor demo."""
    print(RULE)
    print(f"[A/self] extracting {config.PROJECT_ROOT} (max_files={SELF_MAX_FILES}) ...")
    started = time.time()
    model = extractProject(config.PROJECT_ROOT, max_files=SELF_MAX_FILES)
    print(
        f"[A/self] extracted in {time.time() - started:.1f}s: "
        f"{len(model.modules)} modules, truncated={model.truncated} "
        "(references/ vendored corpus is huge; cap + honest flag is deliberate)"
    )
    print("[A/self] digest excerpt:")
    print(indent(contextForPrompt(model, budget_chars=DIGEST_EXCERPT_CHARS)))
    test_cmd = testCommand(model)
    print(f"[A/self] detected test command: {test_cmd!r}")
    require("pytest" in test_cmd, "self test command must contain 'pytest'")
    partACycles(model)
    goal = "reduce notification latency"
    result = exploreSolutionSpace(goal, model, n=3)  # pass the model: no re-extract
    titles = {c.approach_id: c.title for c in generateApproaches(goal, model, n=3)}
    printApproaches("[A/self]", goal, result, titles)
    partARefactorDemo()


def partACycles(model) -> None:
    """findCycles over the self model; zero cycles may touch first-party code."""
    cycles = findCycles(buildImportGraph(model))
    first_party = [c for c in cycles if any(not m.startswith("references/") for m in c)]
    print(
        f"[A/self] import cycles: {len(cycles)} total, "
        f"{len(first_party)} touching first-party (non-references/) code"
    )
    for cycle in first_party:
        print("  first-party cycle: " + " -> ".join(cycle))
    require(not first_party, "expected zero cycles touching first-party 9to5 code")


def partARefactorDemo() -> None:
    """RefactorTransaction rollback + apply on scratch copies; real tree untouched."""
    real_paths = [REPO_ROOT / rel for rel in SCRATCH_COPY_FILES]
    before = {str(p): sha256File(p) for p in real_paths}
    scratch = Path(tempfile.mkdtemp(prefix="9to5-poc-refactor-"))
    print(f"[A/self] refactor demo scratch dir: {scratch}")
    try:
        copies = []
        for src in real_paths:
            dst = scratch / src.name
            shutil.copyfile(src, dst)
            copies.append(dst)
        target = copies[0]
        old_line = pickUniqueLine(target.read_text(encoding="utf-8"))
        edit = ReplaceInFile(target.name, old_line, old_line + "  # poc-edit")
        runFailingTx(scratch, copies, edit)
        runSucceedingTx(scratch, target, edit)
    finally:
        forceRmtree(scratch)
    after = {str(p): sha256File(p) for p in real_paths}
    print("[A/self] real-tree hash check (before == after):")
    for path, digest in before.items():
        same = digest == after[path]
        print(f"  {'OK  ' if same else 'DIFF'} {digest[:16]} {path}")
    require(before == after, "real tree was modified by the scratch demo")


def pickUniqueLine(text: str) -> str:
    """First long line occurring exactly once (comment-appendable: no trailing \\)."""
    for line in text.splitlines():
        if len(line.strip()) > 20 and not line.rstrip().endswith("\\") and text.count(line) == 1:
            return line
    raise PocError("no unique line found in scratch target")


def runFailingTx(scratch: Path, copies: list[Path], edit) -> None:
    """Valid ReplaceInFile + syntax-error WriteFile: compile gate must roll back."""
    pre = {p.name: sha256File(p) for p in copies}
    tx = RefactorTransaction(scratch)
    tx.add(edit)
    tx.add(WriteFile("broken.py", BROKEN_PY))
    result = tx.apply()
    print(f"[A/self] failing tx: applied={result.applied} reason={result.reason[:90]!r}")
    require(not result.applied, "failing tx must not apply")
    require("py_compile failed" in result.reason, "failure must come from the compile gate")
    require(not (scratch / "broken.py").exists(), "broken.py must be rolled back")
    post = {p.name: sha256File(p) for p in copies}
    require(pre == post, "rollback must restore every scratch copy byte-for-byte")
    print("[A/self] rollback verified: scratch copies byte-identical, broken.py absent")


def runSucceedingTx(scratch: Path, target: Path, edit) -> None:
    """Same ReplaceInFile + a valid WriteFile: previews clean and applies."""
    tx = RefactorTransaction(scratch)
    tx.add(edit)
    tx.add(WriteFile("poc_extra.py", EXTRA_PY))
    report = tx.preview()
    print(
        f"[A/self] preview: files_touched={len(report.files_touched)} "
        f"new_cycles={len(report.new_cycles)} ok={report.ok}"
    )
    result = tx.apply()
    print(f"[A/self] succeeding tx: applied={result.applied} files={list(result.files_touched)}")
    require(result.applied, f"succeeding tx must apply: {result.reason}")
    require("# poc-edit" in target.read_text(encoding="utf-8"), "ReplaceInFile edit must land")
    require((scratch / "poc_extra.py").is_file(), "WriteFile must land")


# -- Part B: external project --------------------------------------------------


def partBExternal() -> None:
    """Clone (or fixture) an external project: extract, cycles, brain-free explore."""
    print(RULE)
    ext_root = Path(tempfile.mkdtemp(prefix="9to5-poc-external-"))
    try:
        dest, offline = cloneOrFixture(ext_root)
        name = "offline fixture project" if offline else "pallets/itsdangerous"
        model = extractProject(dest, max_files=EXTERNAL_MAX_FILES, use_cache=False)
        print(
            f"[B/external] extracted {name}: "
            f"{len(model.modules)} modules, truncated={model.truncated}"
        )
        print("[B/external] digest:")
        print(indent(contextForPrompt(model, budget_chars=DIGEST_EXCERPT_CHARS)))
        test_cmd = testCommand(model)
        print(f"[B/external] detected test command: {test_cmd!r}")
        require("pytest" in test_cmd, "external test command must contain 'pytest'")
        cycles = findCycles(buildImportGraph(model))
        print(f"[B/external] import cycles: {len(cycles)}")
        goal = "add a new serializer"
        result = exploreSolutionSpace(goal, model, n=3)  # brain=None: brain-free
        titles = {c.approach_id: c.title for c in generateApproaches(goal, model, n=3)}
        printApproaches("[B/external]", goal, result, titles)
        require(len(result.scores) == 3, "expected 3 brain-free approaches")
    finally:
        forceRmtree(ext_root)


def cloneOrFixture(ext_root: Path) -> tuple[Path, bool]:
    """(project dir, offline?) -- shallow clone, or generated fixture on failure."""
    dest = ext_root / "itsdangerous"
    err = ""
    try:
        proc = subprocess.run(
            ["git", "clone", "--depth", "1", CLONE_URL, str(dest)],
            capture_output=True,
            text=True,
            timeout=CLONE_TIMEOUT_S,
        )
        if proc.returncode != 0:
            err = (proc.stderr.strip() or f"git exited {proc.returncode}").splitlines()[-1]
    except Exception as exc:  # noqa: BLE001 -- no git / timeout: fall back offline
        err = str(exc)
    if not err:
        print(f"[B/external] cloned {CLONE_URL} (depth 1) -> {dest}")
        return dest, False
    print(f"[B/external] [offline fallback] clone failed ({err}); generating fixture project")
    forceRmtree(dest)
    writeFixture(dest)
    return dest, True


def writeFixture(dest: Path) -> None:
    """Minimal python package (pyproject + pytest config + a test) at ``dest``."""
    (dest / "fixturepkg").mkdir(parents=True)
    (dest / "tests").mkdir()
    (dest / "pyproject.toml").write_text(
        '[build-system]\nrequires = ["setuptools"]\n\n'
        '[tool.pytest.ini_options]\ntestpaths = ["tests"]\n',
        encoding="utf-8",
    )
    (dest / "fixturepkg" / "__init__.py").write_text(
        '"""Offline fixture package."""\n'
        "from fixturepkg.serializer import dumps, loads\n",
        encoding="utf-8",
    )
    (dest / "fixturepkg" / "serializer.py").write_text(
        '"""Tiny serializer."""\nimport json\n\n\n'
        "def dumps(obj):\n    return json.dumps(obj)\n\n\n"
        "def loads(text):\n    return json.loads(text)\n",
        encoding="utf-8",
    )
    (dest / "tests" / "test_serializer.py").write_text(
        "from fixturepkg import dumps, loads\n\n\n"
        'def test_roundtrip():\n    assert loads(dumps({"a": 1})) == {"a": 1}\n',
        encoding="utf-8",
    )


def main() -> int:
    """Run parts A and B; 0 = every assertion held, 1 = any PoC assertion failed."""
    try:
        partASelf()
        partBExternal()
    except PocError as exc:
        print(RULE)
        print(f"POC FAILED: {exc}")
        return 1
    print(RULE)
    print("POC PASSED: all assertions held (parts A and B)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
