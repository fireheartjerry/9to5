"""repo_health -- a compact, cold-start status line for the 9to5 repo.

Every Claude Code subprocess starts fresh with no memory of the last one. This prints a small
human + machine-readable snapshot so a new session can orient in one command instead of
re-deriving everything: Python version, branch/dirty, test count, configs present, recent run
traces, optional-service availability, and the canonical next commands.

Run from repo root:
    python scripts/repo_health.py            # human-readable
    python scripts/repo_health.py --json     # machine-readable

Everything is best-effort: a probe that fails reports "unknown"/False rather than crashing, so
this is safe to run in any checkout, worktree, or CI shell.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  gather() -> dict  -- Collect the repo-health snapshot as a plain dict
  render(snap: dict) -> str
  main(argv: 'list[str] | None'=None) -> int
DEPENDS-ON: config, tracing
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_repo_health.py
"""
from __future__ import annotations

import json
import platform
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))


def _git(*args: str) -> str:
    try:
        out = subprocess.run(["git", *args], cwd=str(REPO_ROOT),
                             capture_output=True, text=True, timeout=10)
        return (out.stdout or "").strip()
    except Exception:
        return ""


def _testCount() -> int:
    try:
        return len(list((REPO_ROOT / "tests").glob("test_*.py")))
    except Exception:
        return 0


def _recentTraceCount() -> int:
    try:
        import tracing
        return len(tracing.recentRunIds(limit=50))
    except Exception:
        return 0


def _optionalServices() -> dict:
    """Best-effort availability of the optional external services (no network calls that block)."""
    services: dict[str, bool] = {}
    try:
        import config
        # Discord is "configured" when a token + channel are present in the environment/config.
        services["discord_configured"] = bool(getattr(config, "DISCORD_BOT_TOKEN", "")
                                              and getattr(config, "DISCORD_CHANNEL_ID", 0))
        services["obsidian_configured"] = bool(getattr(config, "OBSIDIAN_API_KEY", ""))
        services["ollama_model"] = getattr(config, "OLLAMA_MODEL", "unknown")
    except Exception:
        services["config_import"] = False
    return services


def gather() -> dict:
    """Collect the repo-health snapshot as a plain dict. Pure-ish: only reads git/fs/config."""
    branch = _git("rev-parse", "--abbrev-ref", "HEAD") or "unknown"
    dirty = _git("status", "--porcelain")
    dirty_count = len([ln for ln in dirty.splitlines() if ln.strip()]) if dirty else 0
    return {
        "python": platform.python_version(),
        "branch": branch,
        "dirty_files": dirty_count,
        "test_count": _testCount(),
        "recent_traces": _recentTraceCount(),
        "configs_present": {
            ".env": (REPO_ROOT / ".env").exists(),
            "config.py": (REPO_ROOT / "config.py").exists(),
            "pytest.ini": (REPO_ROOT / "pytest.ini").exists(),
            "ruff.toml": (REPO_ROOT / "ruff.toml").exists(),
        },
        "optional_services": _optionalServices(),
        "suggested_commands": [
            "python tools/dev.py check <file>      # fast lint+type+affected-tests for one file",
            "python -m unittest discover -s tests -v   # full suite (CI-canonical)",
            "python -m pytest -m 'not slow' -q     # fast lane",
            "python tools/repo_map.py --check      # AI-nav drift check",
        ],
    }


def render(snap: dict) -> str:
    cfg = ", ".join(k for k, v in snap["configs_present"].items() if v) or "(none)"
    svc = snap["optional_services"]
    lines = [
        "9to5 repo health",
        f"  python        {snap['python']}",
        f"  branch        {snap['branch']} ({snap['dirty_files']} dirty file(s))",
        f"  tests         {snap['test_count']} test_*.py modules",
        f"  recent traces {snap['recent_traces']} run(s) under logs/runs/",
        f"  configs       {cfg}",
        f"  ollama model  {svc.get('ollama_model', 'unknown')}",
        f"  discord       {'configured' if svc.get('discord_configured') else 'not configured'}"
        f" | obsidian {'configured' if svc.get('obsidian_configured') else 'not configured'}",
        "  next:",
    ]
    lines += [f"    {c}" for c in snap["suggested_commands"]]
    return "\n".join(lines)


def main(argv: "list[str] | None" = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    snap = gather()
    if "--json" in argv:
        print(json.dumps(snap, indent=2))
    else:
        print(render(snap))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
