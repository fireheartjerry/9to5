"""Bug triage script for 9TO5 bug reports.

Parses state/bug_reports.txt, verifies all bugs have been assessed, and
outputs a prioritized triage table. Exits 0 when triage is complete and
no unmitigated CRITICAL or HIGH bugs remain. Exits 1 on parse failure or
when unmitigated CRITICAL/HIGH bugs exist without a documented fix plan.

Usage:
    python scripts/bug_triage.py --state state/bug_reports.txt

Path resolution: if --state is a relative path that doesn't exist in CWD,
the script falls back to resolving it from the project root (parent of the
scripts/ directory) so it works regardless of which CWD the caller uses.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  main() -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

_SEVERITY_RANK = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}
_IMMEDIATE_SEVERITIES = {"CRITICAL", "HIGH"}

_BUG_RE = re.compile(r"^###\s+(BUG-\d+)", re.MULTILINE)
_SEVERITY_RE = re.compile(r"^Severity:\s*(\S+)", re.MULTILINE)
_STATUS_RE = re.compile(r"^Status:\s*(.+)", re.MULTILINE)
_FILE_RE = re.compile(r"^File:\s*(.+)", re.MULTILINE)

# Keywords that indicate a bug has been assessed and actioned (even if not fully fixed).
_RESOLVED_KEYWORDS = ("fixed", "resolved", "monitored", "partial", "verified",
                      "deferred", "remaining", "under review")


def _isResolved(status: str) -> bool:
    lower = status.lower()
    return any(kw in lower for kw in _RESOLVED_KEYWORDS)


def _parseBugs(text: str) -> list[dict]:
    seen: dict[str, dict] = {}
    matches = list(_BUG_RE.finditer(text))
    for i, m in enumerate(matches):
        bug_id = m.group(1)
        start = m.start()
        next_m = matches[i + 1] if i + 1 < len(matches) else None
        block = text[start: next_m.start() if next_m else len(text)]
        sev_m = _SEVERITY_RE.search(block)
        sta_m = _STATUS_RE.search(block)
        fil_m = _FILE_RE.search(block)
        entry = {
            "id": bug_id,
            "severity": (sev_m.group(1).upper() if sev_m else "UNKNOWN"),
            "status": (sta_m.group(1).strip() if sta_m else "UNKNOWN"),
            "file": (fil_m.group(1).strip() if fil_m else "unknown"),
        }
        # Later occurrences (triage section) override earlier ones (original report)
        # whenever the later entry carries a resolved/assessed status keyword.
        if bug_id not in seen or _isResolved(entry["status"]):
            seen[bug_id] = entry
    return list(seen.values())


def _resolvePath(raw: str) -> Path:
    """Resolve --state path, falling back to project-root-relative if CWD lookup fails."""
    p = Path(raw)
    if p.is_absolute():
        return p
    if p.exists():
        return p
    # Fall back: resolve relative to the project root (parent of scripts/).
    project_root = Path(__file__).resolve().parent.parent
    alt = project_root / raw
    if alt.exists():
        return alt
    return p  # return original so the error message is clear


def main() -> int:
    parser = argparse.ArgumentParser(description="9TO5 bug triage")
    parser.add_argument("--state", required=True, help="Path to bug_reports.txt")
    args = parser.parse_args()

    path = _resolvePath(args.state)
    if not path.exists():
        print(f"ERROR: {path} not found (tried CWD and project root)", file=sys.stderr)
        return 1

    text = path.read_text(encoding="utf-8", errors="replace")
    bugs = _parseBugs(text)
    if not bugs:
        print("ERROR: no BUG-NNN entries found in report", file=sys.stderr)
        return 1

    # Sort by severity rank then bug id
    bugs.sort(key=lambda b: (_SEVERITY_RANK.get(b["severity"], 99), b["id"]))

    unmitigated = [b for b in bugs
                   if b["severity"] in _IMMEDIATE_SEVERITIES and not _isResolved(b["status"])]

    print("=" * 70)
    print("9TO5 BUG TRIAGE REPORT")
    print("=" * 70)
    print(f"{'ID':<10} {'SEVERITY':<10} {'STATUS':<30} {'FILE'}")
    print("-" * 70)
    for b in bugs:
        flag = "  *** UNMITIGATED" if b in unmitigated else ""
        print(f"{b['id']:<10} {b['severity']:<10} {b['status']:<30} {b['file']}{flag}")
    print("=" * 70)

    by_sev: dict[str, int] = {}
    for b in bugs:
        by_sev[b["severity"]] = by_sev.get(b["severity"], 0) + 1

    print("SUMMARY:")
    for sev in ("CRITICAL", "HIGH", "MEDIUM", "LOW", "UNKNOWN"):
        if sev in by_sev:
            print(f"  {sev}: {by_sev[sev]}")
    print(f"Total: {len(bugs)}")

    if unmitigated:
        print(f"\nFAIL: {len(unmitigated)} unmitigated CRITICAL/HIGH bug(s):", file=sys.stderr)
        for b in unmitigated:
            print(f"  {b['id']} ({b['severity']}) — {b['file']}: status={b['status']!r}",
                  file=sys.stderr)
        return 1

    print("\nTRIAGE COMPLETE: No unmitigated CRITICAL/HIGH bugs. Safe to proceed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
