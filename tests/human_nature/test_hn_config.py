import config
from platform_core.app_config import settings as app_settings


def test_hn_new_bool_flags_exposed_via_facade():
    for name in ("HN_MANIFOLD", "HN_INSTINCT", "HN_DRIVES", "HN_MOOD_PERSIST",
                 "HN_PERSONALITY", "HN_PLAN_AUTHORITY", "HN_EXEC_AUTHORITY",
                 "HN_VERIFY_DEEPEN", "HN_SOCIETY_TRIGGER", "HN_INVENTOR_COUPLING"):
        assert isinstance(getattr(config, name), bool)


def test_hn_new_float_flags_have_locked_defaults():
    assert config.HN_THETA_VOTE == 0.72
    assert config.HN_THETA_HOLD == 0.85
    assert config.HN_THETA_VETO == 0.95
    assert config.HN_MOOD_DECAY == 0.15
    assert config.HN_SCAR_DECAY == 0.1
    assert config.HN_SCAR_MATCH_THRESHOLD == 0.6


def test_hn_new_int_flags_have_locked_defaults():
    assert config.HN_MAX_HOLDS == 2
    assert config.HN_HOLD_TIMEOUT_S == 120
    assert config.HN_MAX_VERIFY_DEEPEN == 2
    assert config.HN_DEBATE_RATE_LIMIT == 1
    assert config.HN_INSTINCT_HOTPATH_BUDGET_MS == 25


def test_hn_new_string_flags_have_locked_defaults():
    assert config.HN_AUTHORITY_MAX == "hold"
    assert config.HN_OPERATOR_CEILING == "veto"


def test_hn_max_holds_env_override_via_reload(monkeypatch):
    saved = app_settings._SETTINGS
    monkeypatch.setenv("HN_MAX_HOLDS", "5")
    try:
        app_settings.reload()
        assert config.HN_MAX_HOLDS == 5
    finally:
        monkeypatch.delenv("HN_MAX_HOLDS", raising=False)
        app_settings._SETTINGS = saved
        app_settings._RUN_FLAGS = None
