import config

LOG = config.getLogger("llm_io")

JsonContainer: TypeAlias = dict[str, Any] | list[Any]

_CLIENT: Any | None = None
_CLIENT_LOCK = threading.Lock()
_ALLOWED_GENERATION_OPTIONS = frozenset({"temperature", "top_p", "seed"})


class EmptyCompletionError(RuntimeError):
    """A provider call returned no usable completion text."""


def getClient() -> Any:
    """Lazily build (and memoize) THE Ollama client. Host and timeout are constant for the
    process -- per the empty-completion incident, per-call client/num_ctx churn forces model
    reloads and drops connections under VRAM pressure."""
    global _CLIENT
    if _CLIENT is None:
        with _CLIENT_LOCK:
            if _CLIENT is None:
                from platform_core.execution.local_model_broker import (
                    buildDiagnosticOllamaClient,
                )

                _CLIENT = buildDiagnosticOllamaClient(
                    host=config.OLLAMA_HOST,
                    timeout=config.OLLAMA_TIMEOUT_SECONDS,
                )
    return _CLIENT


def resetClient() -> None:
    """Forget the memoized client for explicit recovery, reconfiguration, or tests."""
    global _CLIENT
    with _CLIENT_LOCK:
        _CLIENT = None


def chatAcceptsAct(chat_callable) -> bool:
    """True when ``chat_callable`` can receive the structured ``act`` tag (an explicit ``act``
    parameter or ``**kwargs``). The real ``ollama.Client.chat`` has neither, so the tag is
    never forwarded to it; sim doubles and the orchestrator seam declare it explicitly."""
    try:
        params = inspect.signature(chat_callable).parameters
    except (TypeError, ValueError):
        return False
    if "act" in params:
        return True
    return any(p.kind is inspect.Parameter.VAR_KEYWORD for p in params.values())


def callChat(chat_fn, system: str, user: str, *, act: str, **kw):
    """Invoke an INJECTED chat callable ``(system, user, ...)`` forwarding ``act`` only when the
    callable accepts it -- so legacy test doubles keep working while act-aware seams
    (``_ollamaChat``, sim brains) get exact structured dispatch."""
    if chatAcceptsAct(chat_fn):
        return chat_fn(system, user, act=act, **kw)
    return chat_fn(system, user, **kw)


def _safeGenerationOptions(options: Mapping[str, object] | None) -> dict[str, object]:
    """Return the small validated provider-option allowlist; reject invalid values."""
    safe: dict[str, object] = {}
    for key, value in (options or {}).items():
        if key not in _ALLOWED_GENERATION_OPTIONS:
            continue
        if key in {"temperature", "top_p"}:
            if isinstance(value, bool) or not isinstance(value, Real):
                raise ValueError(f"{key} must be a finite number")
            numeric = float(value)
            upper = 2.0 if key == "temperature" else 1.0
            if not math.isfinite(numeric) or not 0.0 <= numeric <= upper:
                raise ValueError(f"{key} is outside the supported range")
        elif isinstance(value, bool) or not isinstance(value, int):
            raise ValueError("seed must be an integer")
        safe[key] = value
    return safe


def chat(
    system: str,
    user: str,
    *,
    act: str,
    model: str | None = None,
    want_json: bool = False,
    retries: int = 3,
    client: Any | None = None,
    generation_options: Mapping[str, object] | None = None,
    sleep_fn: Callable[[float], None] | None = None,
    jitter_fn: Callable[[float, float], float] | None = None,
) -> Any | None:
    """The single blessed LLM call (R5): retry/backoff + empty-completion salvage.

    Returns the raw response (dict or pydantic; extract via responseText/responseJson),
    or ``None`` after the configured attempts fail. The legacy ``retries`` name counts
    total attempts and is normalized to at least one. ``client`` defaults to the memoized
    real client; the orchestrator passes its injected brain (real or sim) here.
    num_ctx is ALWAYS config.OLLAMA_NUM_CTX and keep_alive is ALWAYS pinned: sizing
    num_ctx per-prompt forces a full model reload per call (the empty-completion storm).
    """
    cli = client if client is not None else getClient()
    chat_fn = cli.chat
    extra = {"act": act} if chatAcceptsAct(chat_fn) else {}
    num_ctx = config.OLLAMA_NUM_CTX
    messages = [{"role": "system", "content": system}, {"role": "user", "content": user}]
    model = model or config.OLLAMA_MODEL
    safe_options = _safeGenerationOptions(generation_options)
    attempts = max(1, retries)
    sleep = sleep_fn if sleep_fn is not None else time.sleep
    jitter = jitter_fn if jitter_fn is not None else random.uniform
    delay = 2.0
    for attempt in range(1, attempts + 1):
        try:
            kwargs = {
                "options": {"num_ctx": num_ctx, **safe_options},
                "keep_alive": config.OLLAMA_KEEP_ALIVE,
            }
            if want_json:
                kwargs["format"] = "json"
            resp = chat_fn(model=model, messages=messages, **kwargs, **extra)
            # An EMPTY completion is a TRANSIENT model failure (qwen2.5 can dead-end to "" under
            # format=json on markdown-heavy prompts). Salvage IN-attempt by dropping format=json
            # (free-form JSON is recovered by parseJsonLoose's fence/object extraction); only if
            # THAT is also empty is the attempt failed and backed off.
            if want_json and not responseText(resp).strip():
                resp = chat_fn(
                    model=model,
                    messages=messages,
                    options={"num_ctx": num_ctx, **safe_options},
                    keep_alive=config.OLLAMA_KEEP_ALIVE,
                    **extra,
                )
            text = responseText(resp)
            if not text.strip():
                raise EmptyCompletionError("empty completion")
            try:
                _tap_brain(user, text)
            except Exception:  # noqa: BLE001 -- telemetry cannot invalidate provider evidence
                LOG.debug("brain telemetry unavailable", exc_info=True)
            return resp
        except (TypeError, AttributeError):
            LOG.exception("Invalid LLM client contract (act=%s)", act)
            raise
        except Exception as exc:  # noqa: BLE001 -- provider SDK taxonomy is not stable
            LOG.warning(
                "LLM call failed/empty (act=%s, attempt %d/%d): %s",
                act,
                attempt,
                attempts,
                exc,
            )
            if attempt == attempts:
                return None
            low, high = delay * 0.8, delay * 1.2
            sleep_for = min(high, max(low, float(jitter(low, high))))
            sleep(sleep_for)
            delay = min(delay * 2, 30.0)
    return None


def _field(obj, key):
    """Pull ``key`` from a dict OR a pydantic/attribute object. None on any miss -- never raises."""
    if obj is None:
        return None
    if isinstance(obj, dict):
        return obj.get(key)
    # pydantic ChatResponse/Message: attribute access, then mapping .get() for back-compat.
    val = getattr(obj, key, None)
    if val is None:
        getter = getattr(obj, "get", None)
        if callable(getter):
            try:
                val = getter(key)
            except Exception:  # noqa: BLE001
                val = None
    return val


def _tap_brain(prompt_summary: str, response_summary: str) -> None:
    """Best-effort: publish one terminal-lane line for a completed brain call."""
    from notifications.lane_feed import laneTap

    laneTap("brain", f"→ {str(prompt_summary)[:90]}")
    laneTap("brain", f"← {str(response_summary)[:90]}")


def responseText(resp) -> str:
    """``resp['message']['content']`` as text. '' for ANY malformed shape (dict or pydantic)."""
    try:
        content = _field(_field(resp, "message"), "content")
        return content if isinstance(content, str) else ""
    except Exception:  # noqa: BLE001 -- malformed boundary objects must remain inert
        return ""


def _balancedContainerAt(text: str, start: int) -> str | None:
    """Return the balanced container beginning exactly at ``start``."""
    if start < 0 or start >= len(text) or text[start] not in "{[":
        return None
    stack: list[str] = []
    in_string = False
    escape_next = False
    pairs = {"{": "}", "[": "]"}
    for index, char in enumerate(text[start:], start):
        if escape_next:
            escape_next = False
            continue
        if char == "\\" and in_string:
            escape_next = True
            continue
        if char == '"':
            in_string = not in_string
            continue
        if in_string:
            continue
        if char in pairs:
            stack.append(char)
        elif char in "}]":
            if not stack or pairs[stack[-1]] != char:
                return None
            stack.pop()
            if not stack:
                return text[start : index + 1]
    return None


def _firstBalancedContainer(text: str, openers: str = "{[") -> str | None:
    """Extract the first balanced JSON container, validating mixed bracket types."""
    starts = [text.find(opener) for opener in openers]
    starts = [index for index in starts if index >= 0]
    return _balancedContainerAt(text, min(starts)) if starts else None


def _firstBalancedObject(text: str) -> str | None:
    """Extract the first balanced {…} from *text*, respecting nesting and string literals.

    The naive ``re.search(r"\\{.*\\}", text, re.DOTALL)`` is maximally greedy: on any
    output that contains two separate JSON objects it spans from the first ``{`` to the
    LAST ``}``, producing a concatenated blob that fails ``json.loads``. This extractor
    walks character-by-character and closes at the correct depth-0 ``}``."""
    return _firstBalancedContainer(text, "{")


def _jsonRepairSalvage(text: str) -> JsonContainer | None:
    """Last-resort salvage of malformed/truncated JSON via the json_repair pip dep.

    Returns a dict/list only -- a repaired scalar/empty (e.g. from pure prose) yields None so the
    schema validator above this layer still rejects genuinely-broken output. No-op if json_repair
    is not installed."""
    try:
        from json_repair import repair_json
    except Exception:  # noqa: BLE001 -- optional dep; degrade to no salvage
        return None
    try:
        repaired = repair_json(text, return_objects=True)
    except Exception:  # noqa: BLE001
        return None
    return repaired if isinstance(repaired, (dict, list)) and repaired else None


_FULL_FENCE = re.compile(
    r"^\s*```(?:json)?[ \t]*\r?\n?(.*?)\r?\n?```\s*$",
    re.IGNORECASE | re.DOTALL,
)
_ANY_FENCE = re.compile(
    r"```(?:json)?[ \t]*\r?\n?(.*?)\r?\n?```",
    re.IGNORECASE | re.DOTALL,
)


def _strictJsonContainer(text: str) -> JsonContainer | None:
    try:
        value = json.loads(text)
    except (json.JSONDecodeError, TypeError):
        return None
    return value if isinstance(value, (dict, list)) else None


def _repairCandidate(text: str) -> str | None:
    """Return the first JSON-shaped suffix suitable for conservative repair."""
    for index, opener in enumerate(text):
        if opener not in "{[":
            continue
        tail = text[index + 1 :].lstrip()
        if opener == "{" and tail and not tail.startswith(('"', "}")):
            continue
        if opener == "[" and tail:
            valid_array_start = tail[0] in '{["-0123456789]' or tail.startswith(
                ("true", "false", "null", "]")
            )
            if not valid_array_start:
                continue
        return _balancedContainerAt(text, index) or text[index:]
    return None


def parseJsonLoose(text: str | None) -> JsonContainer | None:
    """THE tolerant JSON ladder (promoted from brain_io.parseJsonText -- single copy, R5).

    Ladder: (1) strict container parse after fence extraction, (2) first JSON-shaped balanced
    object/array, (3) conservative repair of that candidate only. Scalars and defeat return None."""
    if not text:
        return None
    text = text.strip()
    full_fence = _FULL_FENCE.fullmatch(text)
    candidate = full_fence.group(1).strip() if full_fence else text
    parsed = _strictJsonContainer(candidate)
    if parsed is not None:
        return parsed
    fenced = _ANY_FENCE.search(text) if full_fence is None else None
    if fenced is not None:
        candidate = fenced.group(1).strip()
        parsed = _strictJsonContainer(candidate)
        if parsed is not None:
            return parsed
    repair_target = _repairCandidate(candidate)
    if repair_target is None:
        return None
    parsed = _strictJsonContainer(repair_target)
    if parsed is not None:
        return parsed
    return _jsonRepairSalvage(repair_target)


def responseJson(resp: Any) -> JsonContainer | None:
    """Parse the JSON body of a chat response via the ONE loose ladder. None on any problem."""
    return parseJsonLoose(responseText(resp))
