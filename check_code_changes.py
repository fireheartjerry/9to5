"""Validate that bug-fix code changes have been applied to the 9TO5 codebase.

Usage:
    python check_code_changes.py --source-dir <dir> --output-file <path>

The --source-dir is the repository root to inspect.  If the path does not
exist, the script falls back to the directory containing this script (the
actual 9TO5 install root, C:\\9to5).

Exits 0 when all mandatory fix markers are present in their target files.
Exits 1 otherwise.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  parseArgs() -> argparse.Namespace
  resolveRoot(source_dir_arg: str) -> Path  -- Return the real repo root: the given path if it exists, else the script's parent.
  validateCodeChanges(root: Path) -> 'tuple[bool, list[str], list[str]]'  -- Return (ok, passes, failures).
  writeOutput(path: Path, passes: list[str], failures: list[str]) -> None
  main() -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Each tuple: (relative_file, marker_text, human_label)
# Asserts that each BUG-NNN fix marker is present in the named source file.
CHECKS: list[tuple[str, str, str]] = [
    ("state/task_io.py",                       "BUG-003", "UUID validation in task_io.load() prevents path traversal"),
    ("notifications/webdash.py",               "BUG-005", "CSRF token always checked, empty token rejected"),
    ("agents/verifier_sanitize.py",            "BUG-006", "trailing content after python -c closing quote is rejected"),
    ("platform_core/runtime/control.py",       "BUG-007", "drainOps uses strict read to avoid clobbering abort signal"),
    ("human_nature/continuity.py",             "BUG-008", "UUID validation in continuity letters path prevents traversal"),
    ("agents/executor_env.py",                 "BUG-010", "broadened rm pattern catches rm -rfv and similar variants"),
    ("agents/hooks_selfmod.py",                "BUG-012", "no fallback to loadLatest() in _resolveState"),
    ("platform_core/ops/external_project.py",  "BUG-014", "SSRF guard rejects non-https URIs in cloneRepo"),
    ("platform_core/runtime/action_risk.py",   "BUG-015", "format-drive regex prevents false positives on 'reformat'"),
    ("memory/obsidian.py",                     "BUG-017", "atexit registered only once per pool lifecycle"),
]


def parseArgs() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Validate bug-fix code changes")
    parser.add_argument("--source-dir", required=True,
                        help="Repository root to inspect (falls back to script dir if missing)")
    parser.add_argument("--output-file", required=True, help="Path to write code_changes.txt")
    return parser.parse_args()


def resolveRoot(source_dir_arg: str) -> Path:
    """Return the real repo root: the given path if it exists, else the script's parent."""
    p = Path(source_dir_arg)
    if p.exists():
        return p
    # The orchestrator spec may generate a non-existent sub-path (e.g. .../repo).
    # Fall back to the install root so the check still validates the real codebase.
    fallback = Path(__file__).resolve().parent
    print(f"  NOTE  source-dir {source_dir_arg!r} not found; using {fallback}")
    return fallback


def validateCodeChanges(root: Path) -> "tuple[bool, list[str], list[str]]":
    """Return (ok, passes, failures)."""
    passes: list[str] = []
    failures: list[str] = []

    for rel_path, marker, label in CHECKS:
        target = root / rel_path
        if not target.exists():
            failures.append(f"MISSING FILE {rel_path} ({label})")
            continue
        content = target.read_text(encoding="utf-8", errors="replace")
        if marker in content:
            passes.append(f"{marker}: {label}")
        else:
            failures.append(f"MISSING MARKER '{marker}' in {rel_path} ({label})")

    return len(failures) == 0, passes, failures


def writeOutput(path: Path, passes: list[str], failures: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "9TO5 Code Changes Validation Report",
        "====================================",
        "",
        f"Checks passed : {len(passes)}",
        f"Checks failed : {len(failures)}",
        "",
    ]
    for msg in passes:
        lines.append(f"  PASS  {msg}")
    for msg in failures:
        lines.append(f"  FAIL  {msg}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    args = parseArgs()
    root = resolveRoot(args.source_dir)
    output_path = Path(args.output_file)

    ok, passes, failures = validateCodeChanges(root)
    writeOutput(output_path, passes, failures)

    for msg in passes:
        print(f"  PASS  {msg}")
    for msg in failures:
        print(f"  FAIL  {msg}", file=sys.stderr)

    if ok:
        print(f"\nAll {len(passes)} checks passed. Output written to: {output_path}")
        return 0
    print(f"\n{len(failures)} check(s) failed.", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
