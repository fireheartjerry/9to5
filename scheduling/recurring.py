from __future__ import annotations

import time
import uuid
from dataclasses import dataclass, field
from typing import Dict, List, Optional

from workflows.scheduler import WorkflowJob, WorkflowScheduler

MAX_DELAY_SECONDS: float = 300.0  # 5-minute SLA


@dataclass
class RecurringTask:
    """Definition of a repeating workflow task."""
    task_id: str
    interval_seconds: float
    priority: int
    max_delay_seconds: float
    _last_due_at: float = field(repr=False)  # managed by RecurringScheduler


class RecurringScheduler:
    """Schedules recurring tasks through a priority + deadline-aware queue.

    Each call to tick() enqueues any tasks whose interval has elapsed.  The
    underlying WorkflowScheduler dispatches them highest-priority first, with
    EDF tie-breaking and a slot cap.

    Delay tracking: complete() records (started_at - due_at) for every finished
    job.  average_delay_seconds() returns the mean; a healthy system stays < 300 s.

    Usage::

        sched = RecurringScheduler(max_concurrent=4)
        sched.register("health-check", interval_seconds=60, priority=5)
        jobs = sched.tick()          # enqueues due tasks
        job  = sched.next()          # dispatches highest-priority slot
        sched.complete(job.job_id)   # records delay, frees slot

    All public methods are thread-safe (via WorkflowScheduler's internal lock).
    """

    def __init__(self, max_concurrent: int = 8) -> None:
        self._inner = WorkflowScheduler(max_concurrent=max_concurrent)
        self._tasks: Dict[str, RecurringTask] = {}
        self._job_due_at: Dict[str, float] = {}      # job_id → due timestamp
        self._job_started_at: Dict[str, float] = {}  # job_id → started timestamp
        self._delays: List[float] = []               # recorded start delays (seconds)

    def register(
        self,
        task_id: str,
        interval_seconds: float,
        priority: int = 0,
        max_delay_seconds: float = MAX_DELAY_SECONDS,
        first_due_at: Optional[float] = None,
    ) -> RecurringTask:
        """Register a recurring task.

        The first invocation fires at *first_due_at* (default: now).
        Subsequent fires are spaced *interval_seconds* apart.
        """
        if interval_seconds <= 0:
            raise ValueError("interval_seconds must be positive")
        due = first_due_at if first_due_at is not None else time.time()
        task = RecurringTask(
            task_id=task_id,
            interval_seconds=interval_seconds,
            priority=priority,
            max_delay_seconds=max_delay_seconds,
            _last_due_at=due - interval_seconds,  # ensures first tick fires at first_due_at
        )
        self._tasks[task_id] = task
        return task

    def tick(self, now: Optional[float] = None) -> List[WorkflowJob]:
        """Enqueue all tasks whose interval has elapsed.

        Passing *now* (a Unix timestamp) enables deterministic testing without
        wall-clock sleeps.  Returns the list of newly enqueued WorkflowJobs.
        """
        if now is None:
            now = time.time()
        enqueued: List[WorkflowJob] = []
        for task in self._tasks.values():
            next_due = task._last_due_at + task.interval_seconds
            if now >= next_due:
                deadline = next_due + task.max_delay_seconds
                jid = f"{task.task_id}-{uuid.uuid4().hex[:8]}"
                job = self._inner.enqueue(
                    task.task_id,
                    priority=task.priority,
                    deadline=deadline,
                    job_id=jid,
                )
                self._job_due_at[jid] = next_due
                task._last_due_at = next_due
                enqueued.append(job)
        return enqueued

    def next(self) -> Optional[WorkflowJob]:
        """Dispatch the next eligible job (highest priority, earliest deadline).

        Returns None when slots are full or the queue is empty.
        Records started_at for delay calculation at complete() time.
        """
        job = self._inner.next()
        if job is not None:
            self._job_started_at[job.job_id] = job.started_at or time.time()
        return job

    def complete(self, job_id: str) -> None:
        """Mark a job done, record its start delay, and free its slot."""
        started_at = self._job_started_at.pop(job_id, None)
        due_at = self._job_due_at.pop(job_id, None)
        if started_at is not None and due_at is not None:
            self._delays.append(max(0.0, started_at - due_at))
        self._inner.complete(job_id)

    def cancel(self, job_id: str) -> bool:
        """Cancel a queued (not yet started) job.  Returns True if found."""
        self._job_due_at.pop(job_id, None)
        return self._inner.cancel(job_id)

    def overdue_jobs(self) -> List[WorkflowJob]:
        """Return queued jobs whose deadline has already passed."""
        return self._inner.overdueJobs()

    def average_delay_seconds(self) -> float:
        """Mean start delay across all completed jobs.  Returns 0.0 if none."""
        if not self._delays:
            return 0.0
        return sum(self._delays) / len(self._delays)

    @property
    def queued_count(self) -> int:
        return self._inner.queued_count

    @property
    def running_count(self) -> int:
        return self._inner.running_count

    @property
    def slot_available(self) -> bool:
        return self._inner.slot_available
