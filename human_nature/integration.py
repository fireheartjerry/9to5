from __future__ import annotations

from pathlib import Path
from typing import Any, Callable, Optional

import config
from human_nature.appraisal import appraise
from human_nature.consolidation import run_cycle
from human_nature.instinct import maybe_flag
from human_nature.intuition import route, snap
from human_nature.self_state import new_self_state, set_affect


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _meta(state: Any) -> dict[str, Any]:
    """Return the meta dict from state (plain dict or TaskState-style object)."""
    if hasattr(state, "data"):
        return state.data["meta"]
    return state["meta"]


# ---------------------------------------------------------------------------
# Public API — all guards check is_enabled() first
# ---------------------------------------------------------------------------

def is_enabled() -> bool:
    """Return True iff the human-nature layer is currently enabled."""
    return bool(config.HUMAN_NATURE_ENABLED)


def ensure_self_state(state: Any) -> Optional[dict[str, Any]]:
    """Lazily initialise SelfState inside state.meta.

    OFF → returns None without touching state (byte-identical guarantee).
    ON  → if meta["self_state"] is absent or None, creates a fresh SelfState
           and stores it; returns the stored SelfState dict.

    Args:
        state: Run-state dict or TaskState-style object with a .data["meta"] dict.

    Returns:
        The SelfState dict when enabled, else None.
    """
    if not is_enabled():
        return None
    meta = _meta(state)
    if meta.get("self_state") is None:
        meta["self_state"] = new_self_state()
    if meta.get("autonomy") is None:
        meta["autonomy"] = {}
    return meta["self_state"]


def observe_run_events(
    state: Any,
    events: list[dict[str, Any]],
) -> None:
    """Appraise run events and write the resulting PAD vector to self_state.

    OFF → returns immediately (no state change whatsoever).
    ON  → calls appraise(events), then set_affect on the SelfState.

    Args:
        state:  Run-state dict or TaskState-style object.
        events: List of event dicts (each may contain outcome/agency/novelty).
    """
    if not is_enabled():
        return
    self_state = ensure_self_state(state)
    pad = appraise(events)
    set_affect(self_state, pad["valence"], pad["arousal"], pad["control"])


def route_pre_act(
    state: Any,
    domain: str,
    signals: dict[str, Any],
    *,
    chat: Optional[Callable] = None,
) -> str:
    """Return the dual-process routing decision before an action is taken.

    OFF → always returns "deliberate" without calling snap or route.
    ON  → calls snap(domain, signals, chat=chat), then route(snap_result).

    Args:
        state:   Run-state dict or TaskState-style object (not mutated here).
        domain:  Task domain string.
        signals: Numeric signal dict for snap (p_true, self_consistency, etc.).
        chat:    Optional injectable chat callable (reserved for future snap extension).

    Returns:
        "fast" or "deliberate".
    """
    if not is_enabled():
        return "deliberate"
    snap_result = snap(domain, signals, chat=chat)
    return route(snap_result)


def maybe_run_instinct(
    state: Any,
    reflections: list[dict[str, Any]],
    failure_modes: list[dict[str, Any]],
    *,
    chat: Optional[Callable] = None,
    db_path: Optional[Path] = None,
) -> Optional[str]:
    """Fire the instinct check if enabled; return the flag sentence or None.

    OFF → returns None immediately without calling chat (call-count stays 0).
    ON  → delegates to human_nature.instinct.maybe_flag (at most once per run).

    Args:
        state:         Run-state dict or TaskState-style object.
        reflections:   Recent SIE reflection dicts.
        failure_modes: Recent failure-mode dicts.
        chat:          Injectable chat callable; None → Ollama (blocked in tests).
        db_path:       Override conviction DB path (for test isolation).

    Returns:
        Flag sentence if fired, else None.
    """
    if not is_enabled():
        return None
    return maybe_flag(state, reflections, failure_modes, chat=chat, db_path=db_path)


def at_teardown(
    state: Any,
    scored_judgments: list[dict[str, Any]],
    reflections: list[str],
    *,
    chat: Optional[Callable] = None,
) -> Optional[dict[str, Any]]:
    """Run the consolidation cycle at run teardown; return the cycle report.

    OFF → returns None.
    ON  → ensures self_state is initialised, then runs run_cycle and returns
           its report (competence_updated, counterfactual, proposals, practice).

    Args:
        state:             Run-state dict or TaskState-style object.
        scored_judgments:  List of {"domain": str, "correct": bool} dicts.
        reflections:       Free-text reflection strings.
        chat:              Optional injectable chat callable for counterfactual.

    Returns:
        Consolidation report dict when enabled, else None.
    """
    if not is_enabled():
        return None
    self_state = ensure_self_state(state)
    return run_cycle(self_state, scored_judgments, reflections, chat=chat)
