"""Emotions faculty — affect → behavior/comms coupling (F8 mandate) and regulation.

The appraisal engine (appraisal.py) produces a PAD coordinate; this module
decides what the system *does* about it.  Every affect region is a control signal
(F8: if it drives no behavior and no communication, it is theater and is cut).

Manipulation guard (anti-Ava principle): expressed affect is a true readout of the
system's internal state, NEVER a lever on the user.  couple() therefore accepts
(emotion_label, state) only — it must NOT take the user's emotional state as input.
This is enforced by the absence of any user_affect / user_emotion / user_mood
parameter, asserted in tests via inspect.signature.

Behavior coupling is gated by HN_EMOTIONS_BEHAVIOR (default OFF); all behavior
is disabled until an in-house A/B proves it helps task outcomes (spec gate).
Comms (functional labels) are always emitted regardless of the flag.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  couple(emotion_label: str, state: dict[str, Any], *, behavior_enabled: Optional[bool]=None) -> dict[str, Any]  -- Map an emotion label to a behavior intent and functional comms string.
  bias_appraisal(pad: dict[str, Any], morale: float) -> dict[str, Any]  -- Apply mood-congruent bias to an ambiguous PAD coordinate.
  regulate(pad: dict[str, Any], *, decay: float=0.7) -> dict[str, Any]  -- Homeostatic decay of all PAD dimensions toward the zero setpoint.
DEPENDS-ON: config
SIDE-EFFECTS: none (pure)
RUN/TEST: python -m pytest tests/test_emotions.py
"""
from __future__ import annotations

from typing import Any, Optional

import config

# ---------------------------------------------------------------------------
# Behavior map (F8: every region drives a control signal or comms; else cut)
# ---------------------------------------------------------------------------
# satisfaction → comms-only (complacency guard: no behavior escalation on success)
_BEHAVIOR_MAP: dict[str, Optional[str]] = {
    "frustration": "escalate_effort",
    "curiosity":   "explore",
    "anxiety":     "raise_verification",
    "boredom":     "propose_refactor",
    "satisfaction": None,
}


def couple(
    emotion_label: str,
    state: dict[str, Any],
    *,
    behavior_enabled: Optional[bool] = None,
) -> dict[str, Any]:
    """Map an emotion label to a behavior intent and functional comms string.

    MANIPULATION GUARD: This function takes (emotion_label, state) only.
    It must NOT accept any user-affect/user-emotion/user-mood parameter.
    Expressed affect is a true readout, never a lever on the user (anti-Ava).

    Args:
        emotion_label:    One of satisfaction/frustration/curiosity/anxiety/boredom/neutral
        state:            Current run state dict (read-only here; available for future routing)
        behavior_enabled: Override for HN_EMOTIONS_BEHAVIOR; None → use config default.

    Returns:
        {"behavior": str|None, "comms": str}
        behavior is None when disabled (default) or for comms-only emotions.
        comms always carries the functional label so it is never theater.
    """
    enabled = config.HN_EMOTIONS_BEHAVIOR if behavior_enabled is None else behavior_enabled
    behavior = _BEHAVIOR_MAP.get(emotion_label) if enabled else None
    comms = f"{emotion_label} (functional: introspective state readout, not a directive)"
    return {"behavior": behavior, "comms": comms}


def bias_appraisal(pad: dict[str, Any], morale: float) -> dict[str, Any]:
    """Apply mood-congruent bias to an ambiguous PAD coordinate.

    When morale is negative, low-magnitude (ambiguous) valence is pulled
    negative — consistent with the mood-congruent appraisal literature.
    Strong positive valence is protected from being flipped.

    Args:
        pad:    PAD dict from appraise(); not mutated.
        morale: Slow homeostatic scalar in [-1, 1] from SelfState.

    Returns:
        New PAD dict with adjusted valence; other fields copied unchanged.
    """
    result: dict[str, Any] = dict(pad)
    result["vars"] = dict(pad.get("vars") or {})
    if float(morale) >= 0.0:
        return result
    old_v = float(pad.get("valence", 0.0))
    # Ambiguity = how far from a strong, clear signal (1.0 when v=0, 0.0 when |v|=1)
    ambiguity = 1.0 - abs(old_v)
    shift = float(morale) * ambiguity * 0.5   # morale ∈ [-1,0) → shift ∈ [-0.5, 0)
    new_v = max(-1.0, min(1.0, old_v + shift))
    result["valence"] = new_v
    return result


def regulate(pad: dict[str, Any], *, decay: float = 0.7) -> dict[str, Any]:
    """Homeostatic decay of all PAD dimensions toward the zero setpoint.

    Each step retains (1 - decay) of the current magnitude, pulling all
    dimensions toward neutral.  Default decay=0.7 gives strong single-step
    regulation; repeated calls converge to zero.

    Args:
        pad:   PAD dict; not mutated.
        decay: Fraction to move toward zero per step (0 = no change, 1 = instant reset).

    Returns:
        New PAD dict with decayed dimensions; vars copied unchanged.
    """
    decay = max(0.0, min(1.0, float(decay)))
    retention = 1.0 - decay
    result: dict[str, Any] = dict(pad)
    result["vars"] = dict(pad.get("vars") or {})
    result["valence"] = float(pad.get("valence", 0.0)) * retention
    result["arousal"] = float(pad.get("arousal", 0.0)) * retention
    result["control"] = float(pad.get("control", 0.0)) * retention
    return result
