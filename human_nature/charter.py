"""Living Constitution — versioned, human-gated charter (F1, F6).

The Cast Charter is the supreme authority over all faculties.  Amendments
follow a strict propose → human-ratify workflow.  The system may DRAFT
proposals; it can NEVER self-apply them.  Every ``ratify`` call requires a
truthy ``human_token``; without one a ``PermissionError`` is raised.  This
is a mechanical guarantee, not a social convention.

See: docs/human-nature/cast-charter.md (the authority document itself).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  new_charter() -> dict -- fresh charter {"version": 1, "ratified": []}
  draft_amendment(text, evidence) -> dict -- proposed amendment with uuid4 id
  ratify(charter, amendment, human_token) -> dict -- human-gated ratification
  active_tenets(charter) -> list -- texts of all ratified amendments
DEPENDS-ON: copy, uuid (stdlib only)
SIDE-EFFECTS: none (pure; does not mutate inputs, no I/O)
RUN/TEST: python -m pytest tests/test_charter.py
"""
from __future__ import annotations

import copy
import uuid
from typing import Any


def new_charter() -> dict[str, Any]:
    """Return a fresh charter with no ratified amendments and version 1."""
    return {
        "version": 1,
        "ratified": [],
    }


def draft_amendment(text: str, evidence: str) -> dict[str, Any]:
    """Draft an amendment proposal.

    Returns a proposed amendment dict.  Does NOT change any charter.
    The system calls this; a human must call ``ratify`` to apply it.

    Args:
        text:     The proposed new tenet or amendment text.
        evidence: Supporting evidence or rationale.

    Returns:
        dict with keys ``id`` (uuid4 str), ``text``, ``evidence``,
        ``status`` (always ``"proposed"``).
    """
    return {
        "id": str(uuid.uuid4()),
        "text": text,
        "evidence": evidence,
        "status": "proposed",
    }


def ratify(
    charter: dict[str, Any],
    amendment: dict[str, Any],
    human_token: Any,
) -> dict[str, Any]:
    """Apply an amendment to the charter — requires a truthy human token.

    Self-application is mechanically impossible: if ``human_token`` is falsy,
    a ``PermissionError`` is raised before any state is touched.

    Args:
        charter:     The current charter dict.
        amendment:   A proposal produced by ``draft_amendment``.
        human_token: Any truthy value (a passphrase, session token, etc.)
                     supplied by the human operator.

    Returns:
        A NEW charter dict with the amendment appended to ``ratified`` and
        ``version`` incremented.

    Raises:
        PermissionError: if ``human_token`` is falsy.
    """
    if not human_token:
        raise PermissionError("charter amendments require human ratification")

    new_c = copy.deepcopy(charter)
    new_c["ratified"].append(amendment)
    new_c["version"] = charter["version"] + 1
    return new_c


def active_tenets(charter: dict[str, Any]) -> list[str]:
    """Return the texts of all ratified amendments in ratification order.

    This is the read-authority view of what the constitution currently says.
    """
    return [a["text"] for a in charter.get("ratified", [])]
