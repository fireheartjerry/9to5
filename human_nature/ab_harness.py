"""A/B validation harness — behaviour-coupling gate before any flag goes ON-by-default.

Records per-Run metrics (test_pass, time_to_green, commit_quality) for both the "on"
and "off" arms of an experiment. ``compare`` returns per-arm averages and the on-off
delta. No behaviour-coupling flag flips to ON-by-default until this harness shows
non-inferior task outcomes (spec §5.5 validation gate).

SQLite schema mirrors memory/conviction_ledger.py's ``closing(_connect(...))`` pattern.
DB path defaults to config.AB_HARNESS_DB_PATH; pass ``db_path`` to override (tests).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  record_run(run_id: str, arm: str, metrics: dict[str, Any], *, db_path: Optional[Path]=None) -> None  -- Record a single run's metrics for the given experiment arm.
  compare(*, db_path: Optional[Path]=None) -> dict[str, Any]  -- Aggregate per-arm averages and return the on-minus-off delta.
DEPENDS-ON: config
SIDE-EFFECTS: creates/writes the ab_runs SQLite db at AB_HARNESS_DB_PATH (or db_path)
RUN/TEST: python -m pytest tests/test_ab_harness.py
"""
from __future__ import annotations

import sqlite3
from contextlib import closing
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

import config

_VALID_ARMS = frozenset({"on", "off"})

_SCHEMA = """
CREATE TABLE IF NOT EXISTS ab_runs (
  run_id         TEXT NOT NULL,
  arm            TEXT NOT NULL,
  test_pass      REAL,
  time_to_green  REAL,
  commit_quality REAL,
  created_at     TEXT NOT NULL
);
"""


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _connect(db_path: Optional[Path] = None) -> sqlite3.Connection:
    """Open (or create) the ab_runs SQLite database."""
    path = Path(db_path) if db_path is not None else config.AB_HARNESS_DB_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(path))
    conn.row_factory = sqlite3.Row
    conn.execute(_SCHEMA)
    return conn


def _avg(values: list[Optional[float]]) -> Optional[float]:
    """Mean of non-None values, or None if the list is empty / all None."""
    numeric = [v for v in values if v is not None]
    return sum(numeric) / len(numeric) if numeric else None


def _arm_stats(rows: list[sqlite3.Row]) -> dict[str, Any]:
    """Aggregate metric columns from a list of db rows into per-arm stats."""
    test_pass_vals = [row["test_pass"] for row in rows]
    ttg_vals = [row["time_to_green"] for row in rows]
    cq_vals = [row["commit_quality"] for row in rows]
    return {
        "test_pass": _avg(test_pass_vals),
        "time_to_green": _avg(ttg_vals),
        "commit_quality": _avg(cq_vals),
    }


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def record_run(
    run_id: str,
    arm: str,
    metrics: dict[str, Any],
    *,
    db_path: Optional[Path] = None,
) -> None:
    """Record a single run's metrics for the given experiment arm.

    Args:
        run_id:  Unique identifier for the run.
        arm:     "on" (human-nature enabled) or "off" (control); any other value
                 raises ValueError immediately, before any DB write.
        metrics: Dict with optional float keys: test_pass, time_to_green,
                 commit_quality.  Missing keys default to NULL.
        db_path: Override the database path (for test isolation).

    Raises:
        ValueError: if ``arm`` is not "on" or "off".
    """
    if arm not in _VALID_ARMS:
        raise ValueError(
            f"invalid arm {arm!r}: must be 'on' or 'off'"
        )
    test_pass = metrics.get("test_pass")
    time_to_green = metrics.get("time_to_green")
    commit_quality = metrics.get("commit_quality")
    created_at = datetime.now(timezone.utc).isoformat()

    with closing(_connect(db_path)) as conn:
        conn.execute(
            "INSERT INTO ab_runs"
            " (run_id, arm, test_pass, time_to_green, commit_quality, created_at)"
            " VALUES (?, ?, ?, ?, ?, ?)",
            (run_id, arm, test_pass, time_to_green, commit_quality, created_at),
        )
        conn.commit()


def compare(*, db_path: Optional[Path] = None) -> dict[str, Any]:
    """Aggregate per-arm averages and return the on-minus-off delta.

    Returns a dict:
        {
          "on":    {"test_pass": float|None, "time_to_green": float|None,
                    "commit_quality": float|None},
          "off":   {same},
          "delta": {"test_pass": float|None, ...},   # on - off (None if either is None)
          "n_on":  int,
          "n_off": int,
        }

    Values are None when no rows exist for that arm (or that metric is all NULL).

    Args:
        db_path: Override the database path (for test isolation).
    """
    with closing(_connect(db_path)) as conn:
        on_rows = conn.execute(
            "SELECT test_pass, time_to_green, commit_quality"
            " FROM ab_runs WHERE arm = 'on'"
        ).fetchall()
        off_rows = conn.execute(
            "SELECT test_pass, time_to_green, commit_quality"
            " FROM ab_runs WHERE arm = 'off'"
        ).fetchall()

    on_stats = _arm_stats(on_rows)
    off_stats = _arm_stats(off_rows)

    def _delta(key: str) -> Optional[float]:
        a = on_stats[key]
        b = off_stats[key]
        if a is None or b is None:
            return None
        return round(a - b, 10)

    delta = {k: _delta(k) for k in ("test_pass", "time_to_green", "commit_quality")}

    return {
        "on": on_stats,
        "off": off_stats,
        "delta": delta,
        "n_on": len(on_rows),
        "n_off": len(off_rows),
    }
