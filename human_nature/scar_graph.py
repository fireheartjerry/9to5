"""Scar-Tissue Failure Graph — pure directed weighted graph ops over a dict.

A durable graph of failure motifs, their causes, contexts, and recoveries.
The graph is a plain dict so it round-trips through psyche_store with no new
serialization. Mutating functions mutate the graph in place (repo convention);
query functions are pure. All algorithms are stdlib-only (heapq, iteration).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  new_graph() -> dict
  add_node(g: dict, node_id: str, node_type: str, **attrs: Any) -> None
  link(g: dict, src: str, dst: str, relation: str, weight: float=1.0) -> None
  recovery_path(g: dict, failure_node: str, recovery_relations: tuple[str, ...]=('recovered_by', 'resolved_by')) -> list[str]  -- Dijkstra shortest path (edge cost = 1/weight) from failure_node to the
  toxic_patterns(g: dict, k: int=5) -> list[str]  -- Top-k FailureMotif node ids by PageRank (power iteration).
  loops(g: dict) -> list[list[str]]  -- Strongly-connected components with >1 node (Tarjan SCC).
  decay(g: dict, disconfirmed_ids: Iterable[str], rate: float) -> None  -- Multiply node and incident-edge weights of disconfirmed ids by (1-rate).
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: mutates the passed-in graph dict in place (add_node/link/decay)
RUN/TEST: python -m pytest tests/human_nature/test_scar_graph.py
"""
from __future__ import annotations

import heapq
from typing import Any, Iterable

NODE_TYPES = frozenset({
    "FailureMotif", "SubtaskType", "CodeArea", "AgentAction", "VerifierSignal",
    "OperatorFeedback", "RecoveryStrategy", "ToolFailure", "ConfidencePattern",
    "AffectState", "DriveState", "AuthorityExercise",
})

RELATIONS = frozenset({
    "usually_precedes", "caused_by", "similar_to", "recovered_by", "worsened_by",
    "blocked_by", "requires_verification", "triggered_instinct", "resolved_by",
})


def new_graph() -> dict:
    return {"nodes": {}, "edges": []}


def add_node(g: dict, node_id: str, node_type: str, **attrs: Any) -> None:
    g["nodes"][node_id] = {"type": node_type, "attrs": dict(attrs), "weight": 1.0}


def link(g: dict, src: str, dst: str, relation: str, weight: float = 1.0) -> None:
    if relation not in RELATIONS:
        return  # best-effort: silently ignore unknown relations
    g["edges"].append({
        "src": src, "dst": dst, "relation": relation, "weight": float(weight),
    })


def _adjacency(g: dict) -> dict[str, list[tuple[str, float]]]:
    """node_id -> list of (neighbor, edge_weight); edge cost = 1/weight."""
    adj: dict[str, list[tuple[str, float]]] = {nid: [] for nid in g["nodes"]}
    for e in g["edges"]:
        if e["src"] in adj:
            adj[e["src"]].append((e["dst"], float(e["weight"])))
    return adj


def recovery_path(
    g: dict,
    failure_node: str,
    recovery_relations: tuple[str, ...] = ("recovered_by", "resolved_by"),
) -> list[str]:
    """Dijkstra shortest path (edge cost = 1/weight) from failure_node to the
    nearest RecoveryStrategy node. Returns the node-id path, or [] if none."""
    nodes = g["nodes"]
    if failure_node not in nodes:
        return []
    targets = {
        nid for nid, nd in nodes.items() if nd.get("type") == "RecoveryStrategy"
    }
    adj = _adjacency(g)
    prev = _dijkstra(adj, failure_node, targets)
    if prev is None:
        return []
    goal, back = prev
    path = [goal]
    while path[-1] != failure_node:
        path.append(back[path[-1]])
    path.reverse()
    return path


def _dijkstra(
    adj: dict[str, list[tuple[str, float]]],
    source: str,
    targets: set[str],
) -> tuple[str, dict[str, str]] | None:
    """Return (first_reached_target, back_pointers) or None if unreachable."""
    dist = {source: 0.0}
    back: dict[str, str] = {}
    heap: list[tuple[float, str]] = [(0.0, source)]
    while heap:
        d, u = heapq.heappop(heap)
        if d > dist.get(u, float("inf")):
            continue
        if u in targets:
            return u, back
        for v, w in adj.get(u, ()):
            cost = d + (1.0 / w if w > 0 else float("inf"))
            if cost < dist.get(v, float("inf")):
                dist[v] = cost
                back[v] = u
                heapq.heappush(heap, (cost, v))
    return None


def toxic_patterns(g: dict, k: int = 5) -> list[str]:
    """Top-k FailureMotif node ids by PageRank (power iteration)."""
    ranks = _pagerank(g)
    motifs = [
        nid for nid, nd in g["nodes"].items() if nd.get("type") == "FailureMotif"
    ]
    motifs.sort(key=lambda nid: (-ranks.get(nid, 0.0), nid))
    return motifs[:k]


def _pagerank(g: dict, damping: float = 0.85, iters: int = 50) -> dict[str, float]:
    nodes = list(g["nodes"])
    n = len(nodes)
    if n == 0:
        return {}
    out: dict[str, list[tuple[str, float]]] = {nid: [] for nid in nodes}
    out_sum: dict[str, float] = {nid: 0.0 for nid in nodes}
    for e in g["edges"]:
        s, d, w = e["src"], e["dst"], float(e["weight"])
        if s in out and d in out:
            out[s].append((d, w))
            out_sum[s] += w
    rank = {nid: 1.0 / n for nid in nodes}
    base = (1.0 - damping) / n
    for _ in range(iters):
        nxt = {nid: base for nid in nodes}
        dangling = 0.0
        for nid in nodes:
            if out_sum[nid] == 0.0:
                dangling += rank[nid]
        for nid in nodes:
            for d, w in out[nid]:
                nxt[d] += damping * rank[nid] * (w / out_sum[nid])
        share = damping * dangling / n
        for nid in nodes:
            nxt[nid] += share
        rank = nxt
    return rank


def loops(g: dict) -> list[list[str]]:
    """Strongly-connected components with >1 node (Tarjan SCC)."""
    adj = {nid: [v for v, _ in nbrs] for nid, nbrs in _adjacency(g).items()}
    return _tarjan_scc(adj)


def _tarjan_scc(adj: dict[str, list[str]]) -> list[list[str]]:
    index_of: dict[str, int] = {}
    low: dict[str, str] = {}
    on_stack: set[str] = set()
    stack: list[str] = []
    result: list[list[str]] = []
    counter = [0]

    def strongconnect(v: str) -> None:
        index_of[v] = counter[0]
        low[v] = counter[0]
        counter[0] += 1
        stack.append(v)
        on_stack.add(v)
        for w in adj.get(v, ()):  # iterative-safe for our graph sizes
            if w not in index_of:
                strongconnect(w)
                low[v] = min(low[v], low[w])
            elif w in on_stack:
                low[v] = min(low[v], index_of[w])
        if low[v] == index_of[v]:
            comp: list[str] = []
            while True:
                w = stack.pop()
                on_stack.discard(w)
                comp.append(w)
                if w == v:
                    break
            if len(comp) > 1:
                result.append(comp)

    for v in adj:
        if v not in index_of:
            strongconnect(v)
    return result


def decay(g: dict, disconfirmed_ids: Iterable[str], rate: float) -> None:
    """Multiply node and incident-edge weights of disconfirmed ids by (1-rate)."""
    factor = 1.0 - rate
    ids = set(disconfirmed_ids)
    for nid in ids:
        nd = g["nodes"].get(nid)
        if nd is not None:
            nd["weight"] = float(nd["weight"]) * factor
    for e in g["edges"]:
        if e["src"] in ids or e["dst"] in ids:
            e["weight"] = float(e["weight"]) * factor
