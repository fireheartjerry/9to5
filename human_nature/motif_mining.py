"""Offline miner for recurring failure motifs and anomaly scoring.

Teardown-time (not hot-path) analysis over many historical run event-sequences.
Extracts frequent contiguous subsequences (n-grams) that recur across distinct
runs, and scores how unlike any known-good run a given sequence is.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  mine_frequent(sequences: list[list[str]], min_support: int, min_len: int=2, max_len: int=5) -> list[dict]  -- Mine frequent contiguous subsequences across sequences.
  anomaly_score(seq: list[str], success_seqs: list[list[str]]) -> float  -- Return [0, 1]: 1 - max LCS-ratio of seq against any success sequence.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none (pure functions)
RUN/TEST: python -m pytest tests/human_nature/test_motif_mining.py
"""
from __future__ import annotations


def _ngrams(seq: list[str], min_len: int, max_len: int) -> set[tuple[str, ...]]:
    """All distinct contiguous subsequences of seq with length in [min_len, max_len]."""
    grams: set[tuple[str, ...]] = set()
    n = len(seq)
    hi = min(max_len, n)
    for length in range(min_len, hi + 1):
        for start in range(0, n - length + 1):
            grams.add(tuple(seq[start:start + length]))
    return grams


def mine_frequent(
    sequences: list[list[str]],
    min_support: int,
    min_len: int = 2,
    max_len: int = 5,
) -> list[dict]:
    """Mine frequent contiguous subsequences across sequences.

    Returns one entry per contiguous subsequence of length in [min_len, max_len]
    occurring in >= min_support DISTINCT sequences, sorted by support desc then
    motif length desc.
    """
    counts: dict[tuple[str, ...], int] = {}
    for seq in sequences:
        # count each gram once per sequence (distinct-sequence support)
        for gram in _ngrams(seq, min_len, max_len):
            counts[gram] = counts.get(gram, 0) + 1
    motifs = [
        {"motif": list(gram), "support": support}
        for gram, support in counts.items()
        if support >= min_support
    ]
    motifs.sort(key=lambda m: (m["support"], len(m["motif"])), reverse=True)
    return motifs


def _lcs(a: list[str], b: list[str]) -> int:
    """Length of the longest common subsequence of a and b."""
    if not a or not b:
        return 0
    prev = [0] * (len(b) + 1)
    for x in a:
        cur = [0] * (len(b) + 1)
        for j, y in enumerate(b, start=1):
            cur[j] = prev[j - 1] + 1 if x == y else max(prev[j], cur[j - 1])
        prev = cur
    return prev[-1]


def anomaly_score(seq: list[str], success_seqs: list[list[str]]) -> float:
    """Return [0, 1]: 1 - max LCS-ratio of seq against any success sequence.

    LCS ratio = 2*LCS / (len(seq) + len(other)). High score => unlike any
    known-good run. Empty success_seqs => 1.0. Empty seq => 0.0.
    """
    if not seq:
        return 0.0
    if not success_seqs:
        return 1.0
    best_ratio = 0.0
    for other in success_seqs:
        denom = len(seq) + len(other)
        if denom == 0:
            continue
        ratio = (2.0 * _lcs(seq, other)) / denom
        if ratio > best_ratio:
            best_ratio = ratio
    return 1.0 - best_ratio
