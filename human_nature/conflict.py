"""Conflict — internal DISSONANCE scoring and resolution routing.

Faculties (opinion/intuition/instinct) emit directional confidence signals in
[-1, 1] (positive=proceed, negative=stop). Dissonance rises when those signals
disagree and when the self-model's calibration of its own reliability is low.
`route` maps a dissonance level plus a resolution budget to the cheapest
adequate response.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  dissonance(opinion: float, intuition: float, instinct: float, self_model_calibration: float) -> float
  route(dissonance_level: float, budget: dict) -> str
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none (pure functions)
RUN/TEST: python -m pytest tests/human_nature/test_conflict.py
"""
from __future__ import annotations

_HIGH = 0.7
_MODERATE = 0.4
_REPLAN = 0.85

_DISAGREEMENT_WEIGHT = 0.6
_MISCALIBRATION_WEIGHT = 0.4


def dissonance(
    opinion: float,
    intuition: float,
    instinct: float,
    self_model_calibration: float,
) -> float:
    disagreement = _normalized_spread(opinion, intuition, instinct)
    miscalibration = 1.0 - _clamp01(self_model_calibration)
    raw = _DISAGREEMENT_WEIGHT * disagreement + _MISCALIBRATION_WEIGHT * miscalibration
    return _clamp01(raw)


def route(dissonance_level: float, budget: dict) -> str:
    level = _clamp01(dissonance_level)
    if level >= _HIGH and budget.get("debate", 0) > 0:
        return "debate"
    if level >= _REPLAN and budget.get("allow_replan"):
        return "replan"
    if level >= _MODERATE:
        return "deepen_verify"
    return "none"


def _normalized_spread(opinion: float, intuition: float, instinct: float) -> float:
    signals = (opinion, intuition, instinct)
    mean = sum(signals) / len(signals)
    variance = sum((s - mean) ** 2 for s in signals) / len(signals)
    # signals live in [-1, 1], so max possible variance (fully split at the
    # extremes) is 4/3; normalize into [0, 1].
    max_variance = 4.0 / 3.0
    return _clamp01(variance / max_variance)


def _clamp01(value: float) -> float:
    return max(0.0, min(1.0, value))
