"""Self-model — metacognitive supervisor (F11 / F3 + honest phenomenology).

Implements the access-consciousness self-model layer:
  - Calibrated competence with epistemic uncertainty intervals
  - Johari-window style known/unknown blind-spot detection
  - Two dissonance channels: overconfidence (felt vs demonstrated) and
    drift (self-report vs observed)
  - Honest phenomenology: the access-vs-phenomenal answer, fixed and immutable

All functions are pure projections over SelfState; no I/O, no Ollama.

Verdict thresholds (VERDICT_P / VERDICT_N) decide when low competence should
trigger safeguards (raise verification / ask for help / lower veto appetite).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  competence_report(ss: dict[str, Any], domain: str) -> dict[str, Any]  -- Calibrated competence with epistemic interval and verdict.
  johari(ss: dict[str, Any], ood: bool, surprise: float) -> dict[str, Any]  -- Johari-window blind-spot analysis.
  dissonance(felt: float, demonstrated: float, self_report: float, observed: float) -> dict[str, Any]  -- Two dissonance channels (spec § self-awareness, F3).
  honest_phenomenology() -> str  -- Return the fixed, honest access-vs-phenomenal paragraph.
DEPENDS-ON: human_nature.self_state
SIDE-EFFECTS: none (pure)
RUN/TEST: python -m pytest tests/test_self_model.py
"""
from __future__ import annotations

import math
from typing import Any

from human_nature.self_state import get_competence

# Competence threshold below which the verdict triggers safeguards.
VERDICT_P = 0.5
# Sample-count floor: below this n, competence estimate is too uncertain to trust.
VERDICT_N = 5
# Surprise / prediction-error threshold for unknown-unknown detection.
SURPRISE_THRESHOLD = 0.7
# Competence below this → included in known_unknowns Johari window.
KNOWN_UNKNOWN_P = 0.5


def competence_report(ss: dict[str, Any], domain: str) -> dict[str, Any]:
    """Calibrated competence with epistemic interval and verdict.

    The epistemic interval widens as sample count shrinks:
      interval = 1 / sqrt(n + 1)
    At n=0 (cold start) interval = 1.0 (maximum uncertainty).
    At n=99 interval ≈ 0.1 (narrow, confident estimate).

    Verdict:
      "raise verification / ask for help / lower veto appetite"
        when p < VERDICT_P or n < VERDICT_N
      "proceed"
        when p >= VERDICT_P and n >= VERDICT_N
    """
    c = get_competence(ss, domain)
    p: float = float(c["p"])
    n: int = int(c["n"])
    interval = 1.0 / math.sqrt(n + 1)
    if p < VERDICT_P or n < VERDICT_N:
        verdict = "raise verification / ask for help / lower veto appetite"
    else:
        verdict = "proceed"
    return {"p": p, "n": n, "interval": interval, "verdict": verdict}


def johari(ss: dict[str, Any], ood: bool, surprise: float) -> dict[str, Any]:
    """Johari-window blind-spot analysis.

    known_unknowns: domains tracked in self_state with p < KNOWN_UNKNOWN_P.
    unknown_unknowns: surfaced when ood=True (out-of-distribution) or when
      surprise exceeds SURPRISE_THRESHOLD (prediction-error spike → possible
      unseen domain).

    This implements the "active unknown-unknown hunt" from the spec (F11):
    the system actively seeks its own blind spots rather than assuming coverage.
    """
    known_unknowns = [
        domain
        for domain, val in ss.get("competence", {}).items()
        if float(val.get("p", 0.5)) < KNOWN_UNKNOWN_P
    ]
    unknown_unknowns: list[str] = []
    if ood:
        unknown_unknowns.append(
            "out-of-distribution input detected: competence estimate is unreliable here"
        )
    if float(surprise) > SURPRISE_THRESHOLD:
        unknown_unknowns.append(
            f"prediction-error spike (surprise={surprise:.2f}): "
            "possible unknown-unknown domain — treat competence estimate with caution"
        )
    return {"known_unknowns": known_unknowns, "unknown_unknowns": unknown_unknowns}


def dissonance(
    felt: float,
    demonstrated: float,
    self_report: float,
    observed: float,
) -> dict[str, Any]:
    """Two dissonance channels (spec § self-awareness, F3).

    Channel 1 — overconfidence: felt − demonstrated (signed).
      Positive → felt confidence exceeds demonstrated performance (overconfident).
      Negative → demonstrated exceeds felt (underestimated own competence).

    Channel 2 — drift: |self_report − observed| (unsigned).
      Non-zero means what the system says about itself diverges from what is
      externally measured; self-report alone carries no evidential weight (F3).
    """
    overconfidence = float(felt) - float(demonstrated)
    drift = abs(float(self_report) - float(observed))
    return {"overconfidence": overconfidence, "drift": drift}


