# ---------------------------------------------------------------------------

def cmd_whatyouknow(user_model: dict[str, Any]) -> str:
    """Render the user-model snapshot for the ``!whatyouknow`` command.

    Fully inspectable; service-only (no persuasion path exposed).

    Args:
        user_model: User model dict from ``human_nature.user_model``.

    Returns:
        Formatted string of the model's inspectable fields.
    """
    if not user_model:
        return "**What I know about you**\n  (no data collected yet)"

    snap = snapshot(user_model)
    risk = snap.get("risk_tolerance", 0.5)
    trust = snap.get("trust", 0.5)
    attention = snap.get("attention", "unknown")
    prefs: dict = snap.get("prefs", {})
    obs_count = len(snap.get("observations", []))

    prefs_lines = (
        "\n".join(f"  • {k}: {v}" for k, v in prefs.items())
        if prefs
        else "  (none recorded)"
    )

    return (
        "**What I know about you** (service-only, inspectable)\n"
        f"Risk tolerance: {risk:.2f}\n"
        f"Trust level:    {trust:.2f}\n"
        f"Attention:      {attention}\n"
        f"Preferences:\n{prefs_lines}\n"
        f"Observations recorded: {obs_count}"
    )


