# cmd_why_i_feel
# ---------------------------------------------------------------------------

def cmd_why_i_feel(
    self_state: dict[str, Any],
    appraisal_vars: dict[str, Any],
) -> str:
    """Return a functional-label trace of the current affect.

    Format: "<label> (functional: key=val, ...)"
    Output always carries "functional" so consumers can assert honest labeling.
    Never emits a bare "I feel <emotion>" — affective manipulation is
    charter-forbidden (spec § emotions, honest-label mandate).

    Args:
        self_state:     SelfState dict; PAD affect is read from it.
        appraisal_vars: Free-form appraisal context dict (goal_congruence,
                        self_agency, streak, etc.) echoed in the trace.

    Returns:
        A str containing the functional label and appraisal detail.
    """
    valence, arousal, control = _read_pad(self_state)
    label = _pad_label(valence, arousal, control)

    # Build the functional detail string from appraisal_vars.
    if appraisal_vars:
        detail_parts = [f"{k}={v}" for k, v in appraisal_vars.items()]
        detail = ", ".join(detail_parts)
    else:
        detail = f"v={valence:+.2f}, a={arousal:+.2f}, c={control:+.2f}"

    return f"{label} (functional: {detail})"
