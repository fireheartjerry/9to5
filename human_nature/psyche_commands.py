"""Psyche Discord command routers — pure functions, no discord.py import.

Each function returns the response text / objects a Discord cog will later post.
No network calls; all state is passed in as arguments. Discord cog wiring is
deferred to the A+B merge.

Affect labeling follows the spec mandate: always "frustration (functional: ...)",
never a bare "I feel <emotion>" — honest label, never a lever on the user.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  cmd_psyche(self_state) -> str
  cmd_dial(character_vector, trait, value) -> tuple[dict, str]
  cmd_charter(charter) -> str
  cmd_whatyouknow(user_model) -> str
  cmd_why_i_feel(self_state, appraisal_vars) -> str
DEPENDS-ON: human_nature.self_state, human_nature.character_vector,
            human_nature.charter, human_nature.user_model
SIDE-EFFECTS: none (pure)
RUN/TEST: python -m pytest tests/test_psyche_commands.py
"""
from __future__ import annotations

from typing import Any

from human_nature.charter import active_tenets
from human_nature.character_vector import set_dial
from human_nature.user_model import snapshot


# ---------------------------------------------------------------------------
# PAD → functional label (mirrors psyche_surface logic; kept local to avoid
# cross-module coupling at this layer)
# ---------------------------------------------------------------------------

def _pad_label(valence: float, arousal: float, control: float) -> str:
    """Map a PAD vector to a named functional-affect region."""
    if arousal < 0.2 and abs(valence) <= 0.3:
        return "boredom"
    if valence < -0.2 and arousal > 0.2 and control < 0.0:
        return "frustration"
    if valence < -0.2 and arousal > 0.2:
        return "anxiety"
    if valence > 0.2 and arousal > 0.2:
        return "curiosity"
    if valence > 0.2 and arousal <= 0.2 and control >= 0.0:
        return "satisfaction"
    return "neutral"


def _autonomy_lines(autonomy: dict[str, str] | None) -> str:
    """Render earned-autonomy curve, or placeholder when absent/empty."""
    if not autonomy:
        return "Autonomy: earning trust…"
    lines = "\n".join(f"  {domain}: {tier}" for domain, tier in autonomy.items())
    return f"Autonomy:\n{lines}"


def _read_pad(self_state: dict[str, Any]) -> tuple[float, float, float]:
    affect = self_state.get("affect", {})
    return (
        float(affect.get("valence", 0.0)),
        float(affect.get("arousal", 0.0)),
        float(affect.get("control", 0.0)),
    )


# ---------------------------------------------------------------------------
# cmd_psyche
# ---------------------------------------------------------------------------

def cmd_psyche(
    self_state: dict[str, Any],
    *,
    autonomy: dict[str, str] | None = None,
) -> str:
    """Render a text snapshot of the interior for the ``!psyche`` command.

    Args:
        self_state: The SelfState dict (read defensively; may be empty).
        autonomy:   Optional earned-autonomy dict {domain: ceiling_tier}.
                    When None/empty, an "earning trust…" placeholder is shown.

    Returns:
        A multi-line str suitable for a Discord reply.
    """
    valence, arousal, control = _read_pad(self_state)
    label = _pad_label(valence, arousal, control)
    morale = float(self_state.get("morale", 0.0))

    comp: dict = self_state.get("competence", {})
    comp_lines = []
    for domain, val in comp.items():
        p = float(val.get("p", 0.5))
        n = int(val.get("n", 0))
        comp_lines.append(f"  {domain}: p={p:.2f} (n={n})")
    comp_block = "\n".join(comp_lines) if comp_lines else "  (no domains yet)"

    dissonance = float(self_state.get("dissonance", 0.0))
    open_stances: list = self_state.get("open_stances", [])
    convictions: list = self_state.get("convictions", [])

    return (
        "**Psyche · Interior Snapshot**\n"
        f"Mood-Core: {label} (functional)  "
        f"[v={valence:+.2f} a={arousal:+.2f} c={control:+.2f}]\n"
        f"Morale: {morale:+.2f}\n"
        f"Dissonance: {dissonance:.2f}\n"
        f"Competence:\n{comp_block}\n"
        f"Open stances: {len(open_stances)}  "
        f"Convictions: {len(convictions)}\n"
        f"{_autonomy_lines(autonomy)}"
    )


# ---------------------------------------------------------------------------
# cmd_dial
# ---------------------------------------------------------------------------

def cmd_dial(
    character_vector: dict[str, Any],
    trait: str,
    value: int | float,
) -> tuple[dict[str, Any], str]:
    """Apply ``set_dial`` and return (new_vector, confirmation_text).

    If ``trait`` is unknown, the original vector is returned unchanged and
    ``text`` is an error string.  No exception is raised; the router absorbs
    it so the Discord cog never crashes.

    Args:
        character_vector: Current character vector dict.
        trait:            Trait name to adjust.
        value:            New dial value (clamped to [0, 100] by set_dial).

    Returns:
        (new_vector, text) where text is either a confirmation or an error.
    """
    try:
        new_vec = set_dial(character_vector, trait, value)
    except ValueError as exc:
        error_text = f"Error: {exc}"
        return character_vector, error_text

    clamped = new_vec["traits"][trait]
    text = (
        f"Dial updated: **{trait}** → {clamped}  "
        f"(vector version {new_vec['version']})"
    )
    return new_vec, text


