# cmd_charter
# ---------------------------------------------------------------------------

def cmd_charter(charter: dict[str, Any]) -> str:
    """Render the active tenets and charter version for the ``!charter`` command.

    Args:
        charter: Charter dict produced by ``human_nature.charter.new_charter``.

    Returns:
        Formatted string listing all ratified tenets and the current version.
    """
    version = charter.get("version", 1)
    tenets = active_tenets(charter)
    if not tenets:
        tenet_block = "  (no ratified amendments yet)"
    else:
        tenet_block = "\n".join(f"  {i + 1}. {t}" for i, t in enumerate(tenets))

    return (
        f"**Cast Charter · Version {version}**\n"
        f"Active tenets ({len(tenets)}):\n"
        f"{tenet_block}"
    )


