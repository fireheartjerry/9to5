"""Instinct stream matcher — cheap multi-pattern failure-motif detection.

Hot-path faculty that recognizes known failure "motifs" (sequences of event-type
strings from run_events.EVENT_TYPES) inside a live run's event stream. No LLM: an
Aho-Corasick automaton finds exact contiguous motif occurrences, KMP/Z-style prefix
matching scores partial motifs still unfolding at the stream tail, and an LCS ratio
measures near-duplication between two streams. All pure, stdlib-only.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  build_matcher(motifs: list[tuple[str, list[str]]]) -> dict  -- Build an Aho-Corasick automaton over the event-type alphabet.
  scan(matcher: dict, seq: list[str]) -> list[dict]  -- Run the automaton
  match_prefix(seq: list[str], motif: list[str]) -> float  -- Fraction of `motif` matched as a prefix aligned at seq's tail, in [0, 1].
  scan_prefixes(matcher_motifs: list[tuple[str, list[str]]], seq: list[str], threshold: float) -> list[dict]  -- Report motifs whose tail prefix-score(seq) is in [threshold, 1.0).
  near_duplicate(seq_a: list[str], seq_b: list[str]) -> float  -- LCS ratio similarity in [0, 1]: 2*LCS/(len_a+len_b)
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none (pure functions)
RUN/TEST: python -m pytest tests/human_nature/test_instinct_stream.py
"""
from __future__ import annotations

from collections import deque
from typing import Any


def build_matcher(motifs: list[tuple[str, list[str]]]) -> dict:
    """Build an Aho-Corasick automaton over the event-type alphabet."""
    goto: list[dict[str, int]] = [{}]
    out: list[list[dict[str, Any]]] = [[]]
    for motif_id, pattern in motifs:
        node = 0
        for token in pattern:
            nxt = goto[node].get(token)
            if nxt is None:
                nxt = len(goto)
                goto.append({})
                out.append([])
                goto[node][token] = nxt
            node = nxt
        out[node].append({"motif_id": motif_id, "length": len(pattern)})
    fail = _ac_build_fail(goto, out)
    return {"goto": goto, "fail": fail, "out": out}


def _ac_build_fail(goto: list[dict[str, int]], out: list[list[dict[str, Any]]]) -> list[int]:
    """Breadth-first construction of failure links (and merged outputs)."""
    fail = [0] * len(goto)
    queue: deque[int] = deque()
    for token, child in goto[0].items():
        fail[child] = 0
        queue.append(child)
    while queue:
        node = queue.popleft()
        for token, child in goto[node].items():
            queue.append(child)
            f = fail[node]
            while f and token not in goto[f]:
                f = fail[f]
            target = goto[f].get(token, 0)
            fail[child] = target if target != child else 0
            out[child] = out[child] + out[fail[child]]
    return fail


def scan(matcher: dict, seq: list[str]) -> list[dict]:
    """Run the automaton; report every full motif contiguous in seq."""
    goto = matcher["goto"]
    fail = matcher["fail"]
    out = matcher["out"]
    hits: list[dict] = []
    node = 0
    for index, token in enumerate(seq):
        while node and token not in goto[node]:
            node = fail[node]
        node = goto[node].get(token, 0)
        for entry in out[node]:
            hits.append({
                "motif_id": entry["motif_id"],
                "match_type": "exact",
                "score": 1.0,
                "end_index": index,
            })
    hits.sort(key=lambda h: h["end_index"])
    return hits


def match_prefix(seq: list[str], motif: list[str]) -> float:
    """Fraction of `motif` matched as a prefix aligned at seq's tail, in [0, 1]."""
    if not motif:
        return 0.0
    k = _longest_tail_prefix(seq, motif)
    return k / len(motif)


def _longest_tail_prefix(seq: list[str], motif: list[str]) -> int:
    """Largest k such that seq ends with motif[:k] (Z/KMP-style, capped at len(motif))."""
    max_k = min(len(seq), len(motif))
    for k in range(max_k, 0, -1):
        if seq[len(seq) - k:] == motif[:k]:
            return k
    return 0


def scan_prefixes(
    matcher_motifs: list[tuple[str, list[str]]], seq: list[str], threshold: float
) -> list[dict]:
    """Report motifs whose tail prefix-score(seq) is in [threshold, 1.0)."""
    hits: list[dict] = []
    for motif_id, motif in matcher_motifs:
        score = match_prefix(seq, motif)
        if score >= threshold and score < 1.0:
            hits.append({"motif_id": motif_id, "match_type": "prefix", "score": score})
    return hits


def near_duplicate(seq_a: list[str], seq_b: list[str]) -> float:
    """LCS ratio similarity in [0, 1]: 2*LCS/(len_a+len_b); empty/empty => 1.0."""
    total = len(seq_a) + len(seq_b)
    if total == 0:
        return 1.0
    if not seq_a or not seq_b:
        return 0.0
    return 2.0 * _lcs(seq_a, seq_b) / total


def _lcs(a: list[str], b: list[str]) -> int:
    """Length of the longest common subsequence (rolling-row DP)."""
    prev = [0] * (len(b) + 1)
    for token_a in a:
        cur = [0] * (len(b) + 1)
        for j, token_b in enumerate(b, start=1):
            if token_a == token_b:
                cur[j] = prev[j - 1] + 1
            else:
                cur[j] = max(prev[j], cur[j - 1])
        prev = cur
    return prev[len(b)]
