"""Appraisal engine — Scherer/OCC appraisal variables → PAD affect coordinate.

Implements interoceptive predictive affect (Anil Seth): the system appraises its
own internal state (goal-congruence, agency, novelty, certainty, coping) and maps
those vars to a valence-arousal-control coordinate.  Fully pure; no I/O.

Appraisal variable derivation (from events):
  goal_congruence  — mean of +1 (success) / -1 (failure) / 0 (unknown) per event
  self_agency      — mean agency field (default 0.5 per event)
  novelty          — mean novelty field (default 0.0 per event)
  certainty        — |goal_congruence| (how clearly the outcome direction is known)
  coping           — = self_agency (can we handle what is happening?)

PAD mapping:
  valence  = goal_congruence (success → +, failure → −), clamped [-1, 1]
  arousal  = novelty + |goal_congruence| * (1 − coping), clamped [0, 1]
             (rises with novelty; also rises when outcome is clear but agency is low)
  control  = coping (= self_agency), clamped [-1, 1]

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  appraise(events: list[dict]) -> dict  -- Appraise a list of run events
  emotion_label(pad: dict) -> str  -- Map a PAD coordinate to a discrete emotion label.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none (pure)
RUN/TEST: python -m pytest tests/test_appraisal.py
"""
from __future__ import annotations

# Novelty threshold above which arousal is considered "novelty-driven" in
# emotion_label (used to distinguish curiosity from other high-arousal states).
_NOVELTY_DRIVEN_THRESHOLD = 0.3


def _clamp(value: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, value))


def _appraisal_vars(events: list[dict]) -> dict:
    """Derive Scherer/OCC appraisal variables from raw events."""
    if not events:
        return {
            "goal_congruence": 0.0,
            "self_agency": 0.5,
            "novelty": 0.0,
            "certainty": 0.0,
            "coping": 0.5,
        }
    n = len(events)
    gc_sum = 0.0
    agency_sum = 0.0
    novelty_sum = 0.0
    for e in events:
        outcome = e.get("outcome", "")
        if outcome == "success":
            gc_sum += 1.0
        elif outcome == "failure":
            gc_sum -= 1.0
        agency_sum += float(e.get("agency", 0.5))
        novelty_sum += float(e.get("novelty", 0.0))
    gc = gc_sum / n
    agency = agency_sum / n
    nov = novelty_sum / n
    return {
        "goal_congruence": gc,
        "self_agency": agency,
        "novelty": nov,
        "certainty": abs(gc),
        "coping": agency,
    }


def _pad_from_vars(v: dict) -> tuple[float, float, float]:
    """Map appraisal vars to (valence, arousal, control), all clamped."""
    gc = float(v["goal_congruence"])
    coping = float(v["coping"])
    nov = float(v["novelty"])

    valence = _clamp(gc, -1.0, 1.0)
    arousal = _clamp(nov + abs(gc) * (1.0 - coping), 0.0, 1.0)
    control = _clamp(coping, -1.0, 1.0)
    return valence, arousal, control


def appraise(events: list[dict]) -> dict:
    """Appraise a list of run events; return a PAD dict with embedded vars.

    Each event may contain:
      outcome  -- "success" | "failure" | omitted (treated as neutral)
      novelty  -- float 0..1 (default 0.0)
      agency   -- float 0..1 (default 0.5)

    Returns:
      {"valence": float, "arousal": float, "control": float,
       "vars": {goal_congruence, self_agency, novelty, certainty, coping}}
    """
    if not events:
        # Homeostatic baseline: neutral PAD, mid-range agency
        vars_ = _appraisal_vars([])
        return {"valence": 0.0, "arousal": 0.0, "control": 0.5, "vars": vars_}
    vars_ = _appraisal_vars(events)
    valence, arousal, control = _pad_from_vars(vars_)
    return {"valence": valence, "arousal": arousal, "control": control, "vars": vars_}


def emotion_label(pad: dict) -> str:
    """Map a PAD coordinate to a discrete emotion label.

    Requires:
        pad must contain a ``"vars"`` key — i.e. it must be the output of
        ``appraise()``.  A bare PAD dict without ``vars`` will raise
        ``ValueError`` because the novelty field inside ``vars`` is load-bearing
        for curiosity detection; silently defaulting to 0 would suppress that
        signal and mask real emotions.

    Region definitions:
      satisfaction — valence > 0.3 AND arousal < 0.5
                     (positive outcome, calm — consolidate)
      curiosity    — arousal > 0.5 AND novelty-driven AND valence >= 0
                     (high arousal from novelty, not threat — explore)
      frustration  — valence < -0.3 AND arousal > 0.5 AND control < 0.5
                     (negative, activated, low coping — escalate effort)
      anxiety      — valence < 0 AND arousal > 0.5 AND control >= 0.5
                     (negative, activated, but coping — raise verification)
      neutral      — everything else (homeostatic baseline)

    Checked in this order so high-arousal novel-positive events → curiosity,
    not satisfaction (satisfaction requires arousal < 0.5).
    """
    if "vars" not in pad:
        raise ValueError(
            "emotion_label requires pad['vars'] (use the output of appraise())"
        )
    v = float(pad.get("valence", 0.0))
    a = float(pad.get("arousal", 0.0))
    c = float(pad.get("control", 0.0))
    nov = float(pad["vars"].get("novelty", 0.0))

    if v > 0.3 and a < 0.5:
        return "satisfaction"
    if a > 0.5 and nov > _NOVELTY_DRIVEN_THRESHOLD and v >= 0.0:
        return "curiosity"
    if v < -0.3 and a > 0.5 and c < 0.5:
        return "frustration"
    if v < 0.0 and a > 0.5 and c >= 0.5:
        return "anxiety"
    if a < 0.2 and abs(v) <= 0.3 and nov < 0.2:
        return "boredom"
    return "neutral"
