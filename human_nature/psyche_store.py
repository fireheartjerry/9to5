"""Psyche Store — durable cross-run persistence for mood/drives/personality/scars.

The psyche (mood, drives, personality, scars) is a plain dict, same shape
philosophy as SelfState. This module gives it a home that survives past a
single run: one row per project_key, JSON-encoded, in its own SQLite table.
Mirrors the memory/conviction_ledger.py SQLite pattern (connect-per-call +
contextlib.closing) so no connection is ever held open across calls -- on
Windows that means no stale file lock blocks a second store on the same path.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  open_store(db_path: Optional[str]=None) -> PsycheStore
  load_psyche(store: PsycheStore, project_key: str) -> dict[str, Any]
  save_psyche(store: PsycheStore, project_key: str, state: dict[str, Any]) -> None
  close_store(store: PsycheStore) -> None
DEPENDS-ON: config
SIDE-EFFECTS: creates/writes the psyche SQLite db at STATE_DIR/psyche.db (or db_path)
RUN/TEST: python -m pytest tests/human_nature/test_psyche_store.py
"""
from __future__ import annotations

import json
import sqlite3
from contextlib import closing
from pathlib import Path
from typing import Any, Optional

import config

SCHEMA_VERSION = 1

_SCHEMA = """
CREATE TABLE IF NOT EXISTS psyche (
  project_key    TEXT PRIMARY KEY,
  schema_version INTEGER NOT NULL,
  blob           TEXT NOT NULL
);
"""


class PsycheStore:
    """Handle to the psyche SQLite database; holds only the resolved path.

    No connection is kept open between calls -- each public function opens
    and closes its own connection (see memory/conviction_ledger.py), so
    multiple stores can safely point at the same file without lock contention.
    """

    def __init__(self, path: Path) -> None:
        self.path = path


def _connect(path: Path) -> sqlite3.Connection:
    conn = sqlite3.connect(str(path))
    conn.row_factory = sqlite3.Row
    conn.execute(_SCHEMA)
    return conn


def open_store(db_path: Optional[str] = None) -> PsycheStore:
    path = Path(db_path) if db_path else Path(config.STATE_DIR) / "psyche.db"
    path.parent.mkdir(parents=True, exist_ok=True)
    with closing(_connect(path)) as conn:
        conn.commit()
    return PsycheStore(path)


def load_psyche(store: PsycheStore, project_key: str) -> dict[str, Any]:
    with closing(_connect(store.path)) as conn:
        row = conn.execute(
            "SELECT blob FROM psyche WHERE project_key = ?", (project_key,)
        ).fetchone()
    if row is None:
        return {}
    return json.loads(row["blob"])


def save_psyche(store: PsycheStore, project_key: str, state: dict[str, Any]) -> None:
    blob = json.dumps(state)
    with closing(_connect(store.path)) as conn:
        conn.execute(
            "INSERT INTO psyche (project_key, schema_version, blob) VALUES (?, ?, ?)"
            " ON CONFLICT(project_key) DO UPDATE SET"
            " schema_version = excluded.schema_version, blob = excluded.blob",
            (project_key, SCHEMA_VERSION, blob),
        )
        conn.commit()


def close_store(store: PsycheStore) -> None:
    """No persistent connection is held; present for API symmetry / lifecycle callers."""
    return None
