"""Momentary confidence providers for the human-nature Conviction Engine.

Black-box approximations of pre-verbal confidence (F10: no hidden-state probe).
verbalized_p_true asks HN_FAST_MODEL for P(True) in a calibration-friendly format,
recalibrates via temperature scaling, and returns the result.  All LLM calls accept
an injectable ``chat`` callable so tests never touch the network.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  verbalized_p_true(statement: str, *, chat: Optional[Callable]=None) -> float  -- Ask HN_FAST_MODEL for P(True) of *statement*
  self_consistency(sampler: Callable, n: int=5) -> float  -- Run *sampler* n times
  cross_cast_agreement(votes: list) -> float  -- Fraction of *votes* equal to the modal vote
DEPENDS-ON: config, human_nature.conviction, llm_io
SIDE-EFFECTS: calls Ollama (HN_FAST_MODEL) when chat=None
RUN/TEST: python -m pytest tests/human_nature/test_momentary.py
"""
from __future__ import annotations

import re
from typing import Callable, Optional

import config
import llm_io
from human_nature.conviction import recalibrate

_SYSTEM_PROMPT = (
    "You are a calibration-friendly probability assessor. "
    "Respond only with a probability: TRUE, FALSE, a decimal (e.g. 0.7), "
    "or a percentage (e.g. 70%). Do not add explanation."
)

_OLLAMA = None  # lazy singleton; never imported at module load time


def _getOllama():
    global _OLLAMA
    if _OLLAMA is None:
        import ollama  # deferred: ~0.3 s SDK import paid only on first real call
        _OLLAMA = ollama.Client(host=config.OLLAMA_HOST,
                                timeout=config.OLLAMA_TIMEOUT_SECONDS)
    return _OLLAMA


def _default_chat(system: str, user: str):
    return _getOllama().chat(
        model=config.HN_FAST_MODEL,
        messages=[{"role": "system", "content": system},
                  {"role": "user", "content": user}],
    )


def _parse_prob(text: str) -> float:
    """Parse a probability from a model reply.

    Accepts:
    - "TRUE" / "FALSE" (case-insensitive)
    - decimal like "0.8" or "0.75"
    - percentage like "80%" or "75.5%"
    Falls back to 0.5 on unparseable input.
    """
    t = text.strip().upper()
    if t.startswith("TRUE"):
        return 1.0
    if t.startswith("FALSE"):
        return 0.0
    # Percentage wins over bare decimal to handle "80%" before "80"
    m = re.search(r'(\d+(?:\.\d+)?)\s*%', t)
    if m:
        return min(1.0, max(0.0, float(m.group(1)) / 100.0))
    # Bare decimal / integer
    m = re.search(r'(\d+(?:\.\d+)?)', t)
    if m:
        v = float(m.group(1))
        if v > 1.0:
            v /= 100.0  # treat large numbers as percentages
        return min(1.0, max(0.0, v))
    return 0.5  # fallback: maximum uncertainty


def verbalized_p_true(statement: str, *, chat: Optional[Callable] = None) -> float:
    """Ask HN_FAST_MODEL for P(True) of *statement*; return recalibrated probability.

    Parses TRUE / FALSE / decimal / percentage from the model reply and applies
    temperature recalibration (config.HN_RECAL_TEMPERATURE, default 2.5) to undo
    RLHF overconfidence (F11).
    """
    _chat = chat if chat is not None else _default_chat
    user = (
        f"Statement: {statement}\n\n"
        "Answer only with: TRUE, FALSE, a decimal like 0.7, or a percentage like 70%."
    )
    resp = _chat(_SYSTEM_PROMPT, user)
    raw = _parse_prob(llm_io.responseText(resp))
    return recalibrate(raw, config.HN_RECAL_TEMPERATURE)


def self_consistency(sampler: Callable, n: int = 5) -> float:
    """Run *sampler* n times; return fraction of answers equal to the modal answer.

    Used as a cheap N-sample ensemble: the fraction of trials that agree with the
    most common answer measures how stable the model's response is.
    """
    answers = [sampler() for _ in range(n)]
    if not answers:
        return 0.0
    modal = max(set(answers), key=answers.count)
    return answers.count(modal) / len(answers)


def cross_cast_agreement(votes: list) -> float:
    """Fraction of *votes* equal to the modal vote.  Empty list → 0.0."""
    if not votes:
        return 0.0
    modal = max(set(votes), key=votes.count)
    return votes.count(modal) / len(votes)
