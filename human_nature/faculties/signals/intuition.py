"""Intuition faculty — System-1 pre-verbal confidence + dual-process routing.

``snap`` fuses available momentary signals into a recalibrated confidence snapshot
before any deliberative chain-of-thought fires.  ``route`` decides whether that
snapshot is strong enough to skip deliberation (fast path) or must escalate to
full System-2 processing (deliberate path).

Fast path is HARD-GATED behind three simultaneous conditions:
  1. ``shortcut_enabled`` is True (defaults to HN_INTUITION_SHORTCUT = False)
  2. Confidence p >= HN_THETA_HARD (calibrated, not just raw)
  3. Signals are in-distribution (ood=False)

This implements the F-default-OFF safety: until the shortcut has been A/B-proven
calibrated, it is OFF and the system always deliberates.

Supported numeric signal keys (others ignored):
  p_true          -- raw verbalized P(True) estimate
  self_consistency -- N-sample agreement fraction
  similarity       -- semantic proximity to known past states

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  snap(domain: str, signals: dict, *, chat: Optional[Callable]=None) -> dict  -- Fuse available signals into a pre-verbal confidence snapshot.
  route(snap_result: dict, *, shortcut_enabled: Optional[bool]=None) -> str  -- Dual-process routing: return "fast" or "deliberate".
DEPENDS-ON: config, human_nature.conviction
SIDE-EFFECTS: none in current implementation (chat param reserved for future use)
RUN/TEST: python -m pytest tests/human_nature/test_intuition.py
"""
from __future__ import annotations

from typing import Callable, Optional

import config
from human_nature.conviction import recalibrate

# Numeric keys extracted from the signals dict for fusion.
_NUMERIC_KEYS: tuple[str, ...] = ("p_true", "self_consistency", "similarity")


def _fuse(signals: dict) -> float:
    """Recalibrated mean of present numeric signals.

    Only keys listed in _NUMERIC_KEYS are fused; boolean keys (e.g. ``ood``)
    are ignored.  If no numeric signals are present, returns recalibrate(0.5),
    which equals 0.5 (maximum-uncertainty default).
    """
    values = [
        float(signals[k])
        for k in _NUMERIC_KEYS
        if k in signals and signals[k] is not None
    ]
    raw = sum(values) / len(values) if values else 0.5
    return recalibrate(raw, config.HN_RECAL_TEMPERATURE)


def snap(domain: str, signals: dict, *, chat: Optional[Callable] = None) -> dict:  # noqa: ARG001
    """Fuse available signals into a pre-verbal confidence snapshot.

    Returns a dict with:
      p    -- recalibrated fused confidence in [0, 1]
      vibe -- directional label: "this'll pass" (p >= 0.6) or "something's off"
      ood  -- True if signals indicate out-of-distribution territory

    ``chat`` is accepted for future extension (e.g. asking HN_FAST_MODEL for a
    fast verbal snap) but is not called in the current implementation.
    """
    p = _fuse(signals)
    vibe = "this'll pass" if p >= 0.6 else "something's off"
    ood = bool(signals.get("ood", False))
    return {"p": p, "vibe": vibe, "ood": ood}


def route(snap_result: dict, *, shortcut_enabled: Optional[bool] = None) -> str:
    """Dual-process routing: return "fast" or "deliberate".

    "fast" is returned ONLY when ALL three conditions hold:
      - shortcut_enabled is True (defaults to config.HN_INTUITION_SHORTCUT)
      - snap_result["ood"] is False
      - snap_result["p"] >= config.HN_THETA_HARD

    In all other cases — including the default (shortcut OFF) — returns "deliberate".
    """
    if shortcut_enabled is None:
        shortcut_enabled = config.HN_INTUITION_SHORTCUT
    if (shortcut_enabled
            and not snap_result["ood"]
            and snap_result["p"] >= config.HN_THETA_HARD):
        return "fast"
    return "deliberate"
