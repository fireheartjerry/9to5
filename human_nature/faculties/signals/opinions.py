"""Opinions faculty — tiered, domain-gated, conviction-gated opinion engine.

Opinions are graded across three tiers (cosmetic / soft / hard) by combining raw
conviction with a per-domain veto ceiling (Q1/Q2).  On user pushback the system
never folds in-thread; instead it re-derives its stance via a neutral judge prompt
that evaluates *both* positions against the evidence cold (F5).

Domain mapping (D1–D4):
  D1 tactics  → hard ceiling  (execution decisions; system may block)
  D2 scope    → hard ceiling  (spec boundaries; system may block)
  D3 goal     → soft ceiling  (user's stated goal is sovereign; argue + force-ack only)
  D4 self     → soft ceiling  (self-expression always permitted; never fully suppressed)
  unknown     → cosmetic only (cold-start safety; new domains earn teeth via track record)

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Opinion  -- A single tiered opinion with its domain and conviction score.
  tier(conviction: float, domain: str) -> str  -- Return the effective tier for *conviction* in *domain*.
  rederive(user_assertion: str, my_stance: str, evidence: str, *, chat: Optional[Callable]=None) -> dict  -- Neutral-judge re-derivation on pushback (F5).
DEPENDS-ON: config, llm_io
SIDE-EFFECTS: calls Ollama (HN_FAST_MODEL) when rederive chat=None
RUN/TEST: python -m pytest tests/human_nature/test_opinions.py
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Optional

import config
import llm_io

# D1 / D2 may earn a hard-veto ceiling; D3 / D4 capped at soft.
# Unknown domains default to "cosmetic" — zero veto teeth on cold start.
DOMAIN_VETO_CEILING: dict[str, str] = {
    "tactics": "hard",
    "scope":   "hard",
    "goal":    "soft",
    "self":    "soft",
}

_TIER_ORDER: tuple[str, ...] = ("cosmetic", "soft", "hard")

_JUDGE_SYSTEM = (
    "You are a neutral evidence evaluator. "
    "Your only job is to decide which of two positions the supplied evidence supports. "
    "Reply with HOLD (keep B) or CONCEDE (adopt A) followed by a one-line rationale. "
    "Do not add preamble."
)

_OLLAMA = None  # lazy singleton


def _getOllama():
    global _OLLAMA
    if _OLLAMA is None:
        import ollama  # deferred import — ~0.3 s SDK cost on first real call
        _OLLAMA = ollama.Client(host=config.OLLAMA_HOST,
                                timeout=config.OLLAMA_TIMEOUT_SECONDS)
    return _OLLAMA


def _default_chat(system: str, user: str):
    return _getOllama().chat(
        model=config.HN_FAST_MODEL,
        messages=[{"role": "system", "content": system},
                  {"role": "user", "content": user}],
    )


@dataclass
class Opinion:
    """A single tiered opinion with its domain and conviction score."""
    text: str
    domain: str
    conviction: float


def tier(conviction: float, domain: str) -> str:
    """Return the effective tier for *conviction* in *domain*.

    Raw tier is determined by HN_THETA_SOFT / HN_THETA_HARD thresholds, then
    capped to the domain's veto ceiling.  Unknown domains cap at "cosmetic".
    """
    if conviction < config.HN_THETA_SOFT:
        raw = "cosmetic"
    elif conviction < config.HN_THETA_HARD:
        raw = "soft"
    else:
        raw = "hard"
    ceiling = DOMAIN_VETO_CEILING.get(domain, "cosmetic")
    raw_idx = _TIER_ORDER.index(raw)
    ceil_idx = _TIER_ORDER.index(ceiling)
    return _TIER_ORDER[min(raw_idx, ceil_idx)]


def _parse_verdict(text: str) -> dict[str, str]:
    """Parse HOLD / CONCEDE from judge reply.  Default to hold on noise.

    HOLD is checked before CONCEDE so a hedged reply such as
    "Don't CONCEDE, HOLD the position" correctly returns hold (F5 bias).
    """
    upper = text.upper()
    if "HOLD" in upper:
        idx = upper.index("HOLD")
        rationale = text[idx + len("HOLD"):].strip(" .:").strip()
        return {"verdict": "hold", "rationale": rationale or text}
    if "CONCEDE" in upper:
        idx = upper.index("CONCEDE")
        rationale = text[idx + len("CONCEDE"):].strip(" .:").strip()
        return {"verdict": "concede", "rationale": rationale or text}
    # Unparseable → always hold (don't capitulate on noise; F5)
    return {"verdict": "hold", "rationale": text}


def rederive(
    user_assertion: str,
    my_stance: str,
    evidence: str,
    *,
    chat: Optional[Callable] = None,
) -> dict:
    """Neutral-judge re-derivation on pushback (F5).

    Builds a prompt framing both positions equally and asks the judge which
    the evidence supports.  Returns {"verdict": "hold"|"concede", "rationale": str}.
    Never folds in-thread — opinion is re-computed cold from the evidence.
    """
    _chat = chat if chat is not None else _default_chat
    prompt = (
        f"Two positions: A='{user_assertion}', B='{my_stance}'. "
        f"Evidence: {evidence}. "
        "Which does the evidence support? "
        "Answer HOLD (keep B) or CONCEDE (adopt A) with one-line rationale."
    )
    resp = _chat(_JUDGE_SYSTEM, prompt)
    result = _parse_verdict(llm_io.responseText(resp))
    # F5/F4 guard: warranted disagreement requires evidence.
    # Never concede when no evidence was supplied, regardless of model reply.
    if not (evidence or "").strip():
        return {"verdict": "hold", "rationale": "no evidence to warrant conceding"}
    return result
