"""Psyche surface — legible interior readouts for Discord and web (PRISM-gated).

Both renderers project the SelfState interior into human-readable form.
render_discord returns None on accuracy-critical surfaces (PRISM gate, F2).
render_web returns an HTML fragment; no external dependencies.
All keys are read defensively — missing keys produce sensible placeholders.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  render_discord(self_state: dict[str, Any], *, surface: str='psyche', autonomy: dict[str, str] | None=None) -> dict[str, Any] | None  -- Return an embed-shaped dict of the interior, or None if PRISM-gated.
  render_web(self_state: dict[str, Any], *, autonomy: dict[str, str] | None=None) -> str  -- Return an HTML fragment of the interior (no external dependencies).
DEPENDS-ON: human_nature
SIDE-EFFECTS: none (pure render)
RUN/TEST: python -m pytest tests/human_nature/test_psyche_surface.py
"""
from __future__ import annotations

from typing import Any

from human_nature.gating import is_expression_allowed

# ---------------------------------------------------------------------------
# Internal helpers — read self_state defensively
# ---------------------------------------------------------------------------


def _competence_text(ss: dict[str, Any]) -> str:
    comp: dict = ss.get("competence", {})
    if not comp:
        return "No domains observed yet (cold start)."
    lines = []
    for domain, val in comp.items():
        p = float(val.get("p", 0.5))
        n = int(val.get("n", 0))
        lines.append(f"• {domain}: p={p:.2f} (n={n})")
    return "\n".join(lines) or "No domains observed yet."


def _mood_text(ss: dict[str, Any]) -> str:
    affect: dict = ss.get("affect", {})
    valence = float(affect.get("valence", 0.0))
    arousal = float(affect.get("arousal", 0.0))
    control = float(affect.get("control", 0.0))
    morale = float(ss.get("morale", 0.0))
    label = _affect_label(valence, arousal, control)
    return (
        f"Affect: {label}  "
        f"[v={valence:+.2f} a={arousal:+.2f} c={control:+.2f}]  "
        f"Morale: {morale:+.2f}"
    )


def _affect_label(valence: float, arousal: float, control: float) -> str:
    """Map a PAD vector to a functional region label."""
    if arousal < 0.2 and abs(valence) <= 0.3:
        return "boredom"
    if valence < -0.2 and arousal > 0.2 and control < 0.0:
        return "frustration"
    if valence < -0.2 and arousal > 0.2:
        return "anxiety"
    if valence > 0.2 and arousal > 0.2:
        return "curiosity"
    if valence > 0.2 and arousal <= 0.2 and control >= 0.0:
        return "satisfaction"
    return "neutral"


def _dissonance_text(ss: dict[str, Any]) -> str:
    d = float(ss.get("dissonance", 0.0))
    level = "high" if d > 0.5 else ("moderate" if d > 0.2 else "low")
    return f"{d:.2f} ({level})"


def _attention_text(ss: dict[str, Any]) -> str | None:
    focus = ss.get("attention_focus")
    if focus is None:
        return None
    return str(focus)


def _charter_text(ss: dict[str, Any]) -> str | None:
    version = ss.get("charter_version")
    if version is None:
        return None
    return f"v{version}"


def _autonomy_text(autonomy: dict[str, str] | None) -> str:
    """Render the earned-autonomy curve, or a placeholder when absent."""
    if not autonomy:
        return "earning trust…"
    return "\n".join(f"{domain} → {tier}" for domain, tier in autonomy.items())


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def render_discord(
    self_state: dict[str, Any],
    *,
    surface: str = "psyche",
    autonomy: dict[str, str] | None = None,
) -> dict[str, Any] | None:
    """Return an embed-shaped dict of the interior, or None if PRISM-gated.

    Args:
        self_state: SelfState dict (may be empty; keys read defensively).
        surface:    The surface requesting a render.  If it is accuracy-critical
                    (verifier, verdict, etc.) the function returns None and no
                    interior content leaks into that surface.

    Returns:
        dict with "title" and "fields" keys, or None if expression is blocked.
    """
    if not is_expression_allowed(surface):
        return None

    fields: list[dict[str, str]] = []

    # Competence summary
    fields.append({
        "name": "Competence",
        "value": _competence_text(self_state),
    })

    # Mood-core (PAD affect + morale)
    fields.append({
        "name": "Mood-Core",
        "value": _mood_text(self_state),
    })

    # Dissonance
    fields.append({
        "name": "Dissonance",
        "value": _dissonance_text(self_state),
    })

    # Attention focus (conditional)
    attn = _attention_text(self_state)
    if attn is not None:
        fields.append({"name": "Attention Focus", "value": attn})

    # Charter version (conditional)
    charter = _charter_text(self_state)
    if charter is not None:
        fields.append({"name": "Charter", "value": charter})

    # Earned-autonomy curve
    fields.append({
        "name": "Autonomy",
        "value": _autonomy_text(autonomy),
    })

    return {"title": "Nightclaw Psyche · Interior Snapshot", "fields": fields}


def render_web(self_state: dict[str, Any], *, autonomy: dict[str, str] | None = None) -> str:
    """Return an HTML fragment of the interior (no external dependencies).

    Always renders regardless of surface — callers must ensure the web
    dashboard is not an accuracy-critical path.  The fragment is a
    ``<div class="psyche">`` containing labelled sections.

    Args:
        self_state: SelfState dict (may be empty; keys read defensively).

    Returns:
        HTML string.
    """
    competence = _competence_text(self_state)
    mood = _mood_text(self_state)
    dissonance = _dissonance_text(self_state)

    html = (
        '<div class="psyche">\n'
        '  <section class="competence">\n'
        '    <h3>Competence</h3>\n'
        f"    <pre>{competence}</pre>\n"
        "  </section>\n"
        '  <section class="mood-core">\n'
        '    <h3>Mood-Core (Affect)</h3>\n'
        f"    <p>{mood}</p>\n"
        "  </section>\n"
        '  <section class="dissonance">\n'
        '    <h3>Dissonance</h3>\n'
        f"    <p>{dissonance}</p>\n"
        "  </section>\n"
    )

    attn = _attention_text(self_state)
    if attn is not None:
        html += (
            '  <section class="attention-focus">\n'
            '    <h3>Attention Focus</h3>\n'
            f"    <p>{attn}</p>\n"
            "  </section>\n"
        )

    charter = _charter_text(self_state)
    if charter is not None:
        html += (
            '  <section class="charter">\n'
            '    <h3>Charter</h3>\n'
            f"    <p>Version {charter}</p>\n"
            "  </section>\n"
        )

    # Earned-autonomy curve
    autonomy_content = _autonomy_text(autonomy)
    html += (
        '  <section class="autonomy">\n'
        '    <h3>Autonomy</h3>\n'
        f"    <pre>{autonomy_content}</pre>\n"
        "  </section>\n"
    )

    html += "</div>"
    return html
