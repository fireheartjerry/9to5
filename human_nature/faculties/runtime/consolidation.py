def run_cycle(
    self_state: dict[str, Any],
    scored_judgments: list[dict[str, Any]],
    reflections: list[str],
    *,
    chat: Optional[Callable] = None,
) -> dict[str, Any]:
    """Run the consolidation cycle (the 'sleep' phase).

    Mutates *self_state* (competence update only).  All other outputs are
    proposals or schedule lists — NOTHING is ratified or applied here (F6).

    Args:
        self_state:        The active SelfState dict (mutated in place).
        scored_judgments:  List of ``{"domain": str, "correct": bool}`` dicts.
        reflections:       Free-text strings from post-run reflections.
        chat:              Optional injectable chat callable (system, user) -> resp.
                           When None, no Ollama call is made (counterfactual = "").

    Returns:
        dict with keys:
          "competence_updated" — list of domains whose competence was updated
          "counterfactual"     — text from the sharpness reflection, or ""
          "proposals"          — list of draft_amendment dicts (all status "proposed")
          "practice"           — list of domains to schedule for deliberate practice
    """
    # 1. Competence update
    updated: list[str] = []
    for j in scored_judgments:
        domain = str(j["domain"])
        correct = bool(j["correct"])
        observe_competence(self_state, domain, correct)
        if domain not in updated:
            updated.append(domain)

    # 2. Counterfactual reflection (skips gracefully when chat=None)
    counterfactual = _build_counterfactual(reflections, chat)

    # 3. Amendment drafts from recurring patterns (propose-only)
    proposals = _build_proposals(reflections)

    # 4. Practice schedule from current competence state
    practice = _build_practice_schedule(self_state)

    return {
        "competence_updated": updated,
        "counterfactual": counterfactual,
        "proposals": proposals,
        "practice": practice,
    }


def propose_updates(evidence: dict[str, Any]) -> list[dict[str, Any]]:
    """From run evidence, produce PROPOSED (never applied) psyche updates.

    Pure: never mutates ``evidence`` or any external state, and never applies
    anything (F6 propose-not-apply doctrine). Deterministic — same evidence
    always yields the same list (idempotent).

    Each item is a dict:
        {"kind": "personality"|"drive_setpoint"|"scar_decay",
         "target": str, "value": float, "status": "proposed", "rationale": str}

    Rules:
      - evidence["repeated_overconfidence"] truthy -> propose RAISING the
        "caution" personality trait (never lowering it).
      - evidence["low_curiosity_satisfaction"] truthy -> propose raising the
        "curiosity" drive setpoint.
      - evidence["disconfirmed_scars"] a non-empty list -> one "scar_decay"
        proposal per scar, in order.

    Empty evidence -> [].
    """
    proposals: list[dict[str, Any]] = []

    if evidence.get("repeated_overconfidence"):
        proposals.append({
            "kind": "personality",
            "target": "caution",
            "value": _CAUTION_RAISE_DELTA,
            "status": "proposed",
            "rationale": (
                "repeated overconfidence observed in run evidence; "
                "raise caution to counteract (not lower it)"
            ),
        })

    if evidence.get("low_curiosity_satisfaction"):
        proposals.append({
            "kind": "drive_setpoint",
            "target": "curiosity",
            "value": _CURIOSITY_RAISE_DELTA,
            "status": "proposed",
            "rationale": (
                "curiosity drive under-satisfied across the run; "
                "raise its setpoint"
            ),
        })

    scars = evidence.get("disconfirmed_scars")
    if isinstance(scars, list):
        for scar_id in scars:
            proposals.append({
                "kind": "scar_decay",
                "target": str(scar_id),
                "value": _SCAR_DECAY_AMOUNT,
                "status": "proposed",
                "rationale": f"scar {scar_id!r} was disconfirmed by run evidence; decay it",
            })

    return proposals
