"""Consolidation cycle — the "sleep" phase between runs (propose, never apply).

Replays scored judgments to update the competence model, generates counterfactual
reflections ("what would a sharper me have done?"), drafts charter-amendment proposals
from recurring patterns in reflections, and schedules deliberate practice for
high-uncertainty domains. Growth happens in rest, not mid-run.

F6: this cycle only PROPOSES. It never ratifies amendments or modifies the charter.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  run_cycle(self_state: dict[str, Any], scored_judgments: list[dict[str, Any]], reflections: list[str], *, chat: Optional[Callable]=None) -> dict[str, Any]  -- Run the consolidation cycle (the 'sleep' phase).
  propose_updates(evidence: dict[str, Any]) -> list[dict[str, Any]]  -- From run evidence, produce PROPOSED (never applied) psyche updates.
DEPENDS-ON: config, human_nature, llm_io
SIDE-EFFECTS: mutates self_state in place (competence update); no I/O otherwise
RUN/TEST: python -m pytest tests/human_nature/test_consolidation.py
"""
from __future__ import annotations

import re
from typing import Any, Callable, Optional

import llm_io
from human_nature.charter import draft_amendment
from human_nature.self_state import get_competence, observe_competence

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_SYSTEM = (
    "You are a rigorous AI reflecting on a completed task. "
    "Be concise, honest, and constructive."
)

# Competence thresholds for the practice schedule.
_P_LOW = 0.5   # below this → schedule practice
_N_MIN = 5     # fewer observations than this → high uncertainty → schedule practice

# Minimum number of reflections in which a word must appear to be "recurring".
_RECURRENCE_MIN = 2

# propose_updates: bounded deltas/magnitudes for each proposal kind.
_CAUTION_RAISE_DELTA = 0.15    # personality "caution" — raise, never lower
_CURIOSITY_RAISE_DELTA = 0.15  # drive_setpoint "curiosity" — raise
_SCAR_DECAY_AMOUNT = 0.2       # scar_decay — magnitude of decay per disconfirmed scar

# Words too common to signal a recurring pattern.
_STOP_WORDS = frozenset({
    "a", "an", "the", "and", "or", "but", "in", "on", "of", "to", "for",
    "is", "it", "i", "my", "me", "we", "that", "this", "was", "with",
    "have", "had", "be", "by", "at", "as", "so", "do", "did", "not",
    "up", "if", "all", "use", "used", "more", "over", "than", "then",
    "when", "which", "who", "will", "would", "could", "should", "from",
    "into", "also", "well", "out", "has",
})

# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

_OLLAMA: Any = None


def _getOllama():  # pragma: no cover — real Ollama blocked in tests
    global _OLLAMA
    if _OLLAMA is None:
        import ollama
        import config
        _OLLAMA = ollama.Client(
            host=config.OLLAMA_HOST,
            timeout=config.OLLAMA_TIMEOUT_SECONDS,
        )
    return _OLLAMA


def _default_chat(system: str, user: str):  # pragma: no cover
    import config
    return _getOllama().chat(
        model=config.HN_FAST_MODEL,
        messages=[
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
    )


def _build_counterfactual(
    reflections: list[str],
    chat: Optional[Callable],
) -> str:
    """Generate a counterfactual reflection via chat; '' when chat is None."""
    if not reflections or chat is None:
        return ""
    summary = "\n".join(f"- {r}" for r in reflections)
    user_prompt = (
        f"Here are reflections from a completed task:\n{summary}\n\n"
        "What would a sharper version of you have done differently? "
        "Be specific and concise (2-3 sentences)."
    )
    try:
        resp = chat(_SYSTEM, user_prompt)
        return (llm_io.responseText(resp) or "").strip()
    except Exception:  # noqa: BLE001 — graceful degradation
        return ""


def _find_recurring_words(reflections: list[str]) -> list[str]:
    """Return words that appear (case-insensitively) in >= _RECURRENCE_MIN reflections."""
    word_re = re.compile(r"[a-z]+")
    word_to_reflections: dict[str, set[int]] = {}
    for idx, text in enumerate(reflections):
        for word in word_re.findall(text.lower()):
            if word not in _STOP_WORDS and len(word) > 2:
                word_to_reflections.setdefault(word, set()).add(idx)
    return [
        word for word, idxs in word_to_reflections.items()
        if len(idxs) >= _RECURRENCE_MIN
    ]


def _build_proposals(reflections: list[str]) -> list[dict[str, Any]]:
    """Draft one amendment per top recurring theme found across reflections."""
    if not reflections:
        return []
    recurring = _find_recurring_words(reflections)
    if not recurring:
        return []
    # Group into one amendment per recurring word (capped at 3 to stay focused)
    proposals = []
    for word in recurring[:3]:
        evidence = "; ".join(
            r for r in reflections
            if word in r.lower()
        )
        proposal = draft_amendment(
            text=f"Hold '{word}' as a persistent practice preference",
            evidence=evidence,
        )
        proposals.append(proposal)
    return proposals


def _build_practice_schedule(
    self_state: dict[str, Any],
) -> list[str]:
    """List domains with p < _P_LOW or n < _N_MIN (high self-uncertainty)."""
    all_domains = list(self_state.get("competence", {}).keys())
    schedule = []
    for domain in all_domains:
        c = get_competence(self_state, domain)
        if c["p"] < _P_LOW or c["n"] < _N_MIN:
            schedule.append(domain)
    return schedule


