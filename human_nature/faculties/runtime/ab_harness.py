"""A/B validation harness over the isolated logical state worker.

The harness is evidence-only.  It cannot grant activation and has no direct path or
database engine.  Capsule mode requires the exact generation-scoped worker authority;
pre-activation tests use the closed worker protocol through its diagnostic mount.

RUN/TEST: python -m pytest tests/human_nature/test_ab_harness.py

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  record_run(run_id: str, arm: str, metrics: dict[str, Any], *, db_path: Optional[Path]=None, state_authority: object=None) -> None  -- Record one immutable evidence observation for an experiment arm.
  compare(*, db_path: Optional[Path]=None, state_authority: object=None) -> dict[str, Any]  -- Aggregate per-arm means
DEPENDS-ON: config, platform_core.app_config.paths, platform_core.runtime
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/human_nature/test_ab_harness.py
"""

from __future__ import annotations

import secrets
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

import config
from platform_core.runtime.state_store_worker import (
    executeStateOperation,
    legacyDiagnosticStateWorkerAccess,
)

_VALID_ARMS = frozenset({"on", "off"})
_DATABASE_ID = "ab_harness"
_NAMESPACE = "runs"


def _legacyPath(db_path: Optional[Path], authority: object) -> Path | None:
    if authority is not None:
        return None
    return Path(db_path) if db_path is not None else Path(config.AB_HARNESS_DB_PATH)


def _execute(
    operation: str,
    *,
    db_path: Optional[Path],
    state_authority: object,
    key: str = "",
    value: object = None,
) -> object:
    if state_authority is not None:
        return executeStateOperation(
            database_id=_DATABASE_ID,
            namespace=_NAMESPACE,
            operation=operation,
            key=key,
            value=value,
            authority=state_authority,
        )
    with legacyDiagnosticStateWorkerAccess():
        return executeStateOperation(
            database_id=_DATABASE_ID,
            namespace=_NAMESPACE,
            operation=operation,
            key=key,
            value=value,
            legacy_path=_legacyPath(db_path, state_authority),
        )


def _avg(values: list[Optional[float]]) -> Optional[float]:
    numeric = [value for value in values if value is not None]
    return sum(numeric) / len(numeric) if numeric else None


def _armStats(rows: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "test_pass": _avg([row.get("test_pass") for row in rows]),
        "time_to_green": _avg([row.get("time_to_green") for row in rows]),
        "commit_quality": _avg([row.get("commit_quality") for row in rows]),
    }


def record_run(
    run_id: str,
    arm: str,
    metrics: dict[str, Any],
    *,
    db_path: Optional[Path] = None,
    state_authority: object = None,
) -> None:
    """Record one immutable evidence observation for an experiment arm."""

    if arm not in _VALID_ARMS:
        raise ValueError(f"invalid arm {arm!r}: must be 'on' or 'off'")
    row = {
        "arm": arm,
        "commit_quality": metrics.get("commit_quality"),
        "created_at": datetime.now(timezone.utc).isoformat(),
        "run_id": str(run_id),
        "test_pass": metrics.get("test_pass"),
        "time_to_green": metrics.get("time_to_green"),
    }
    _execute(
        "kv_put",
        db_path=db_path,
        state_authority=state_authority,
        key=f"run_{secrets.token_hex(16)}",
        value=row,
    )


def compare(
    *,
    db_path: Optional[Path] = None,
    state_authority: object = None,
) -> dict[str, Any]:
    """Aggregate per-arm means; never interprets the result as activation authority."""

    values = _execute(
        "kv_list",
        db_path=db_path,
        state_authority=state_authority,
    )
    rows: list[dict[str, Any]] = []
    for item in values if isinstance(values, list) else []:
        row = item.get("value") if isinstance(item, dict) else None
        if isinstance(row, dict):
            rows.append(row)
    on_rows = [row for row in rows if row.get("arm") == "on"]
    off_rows = [row for row in rows if row.get("arm") == "off"]
    on_stats = _armStats(on_rows)
    off_stats = _armStats(off_rows)

    def delta(key: str) -> Optional[float]:
        on = on_stats[key]
        off = off_stats[key]
        return None if on is None or off is None else round(on - off, 10)

    return {
        "on": on_stats,
        "off": off_stats,
        "delta": {
            key: delta(key)
            for key in ("test_pass", "time_to_green", "commit_quality")
        },
        "n_on": len(on_rows),
        "n_off": len(off_rows),
    }


__all__ = ["compare", "record_run"]
