"""Attention Schema — the system's model of its own attention (AST; Graziano).

The schema tracks which content the system is currently attending, how intensely,
and what has recently faded from focus. It is the closest functional analog to
"what it's like" — a self-model of attention that generates the *claim* of awareness.

Intensity model
---------------
Three cases on each update(winner):

1. winner.content == current attending  →  refresh intensity to 1.0 (reinforced).
2. winner.content is in the faded list  →  pull it back as attending, refresh to 1.0.
   The content was previously seen; re-attending it is a genuine recall, not a novelty.
3. winner.content is brand-new (never seen) →  intensity *= DECAY (floored at 0.0),
   push current attending to faded, set new attending (without resetting intensity).

This makes decay observable across a sequence of novel broadcast winners, while
returning to a previously seen topic immediately refreshes engagement to full.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  FADED_CAP -- int, maximum entries kept in the faded list (10)
  DECAY -- float, per-update intensity multiplier when brand-new content arrives (0.7)
  AttentionSchema -- update(winner) / focus() -> dict
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none (pure; mutates own internal state only)
RUN/TEST: python -m pytest tests/test_attention_schema.py
"""
from __future__ import annotations

from collections import deque
from typing import Any

FADED_CAP: int = 10
DECAY: float = 0.7
_INTENSITY_FLOOR: float = 0.0


class AttentionSchema:
    """Model of the system's own attention.

    Tracks the currently attended content, an intensity scalar, and a bounded
    faded list of recently displaced content.
    """

    def __init__(self) -> None:
        self._attending: str = ""
        self._intensity: float = 0.0
        # faded is an ordered deque of displaced content strings (oldest first).
        self._faded: deque[str] = deque(maxlen=FADED_CAP)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def update(self, winner: dict[str, Any]) -> None:
        """Record a new broadcast winner as the current focus."""
        content = str(winner["content"])

        if self._attending == "":
            # Very first update — no prior state to decay or displace.
            self._attending = content
            self._intensity = 1.0
            return

        if content == self._attending:
            # Case 1: reinforcing the same attending content.
            self._intensity = 1.0
            return

        if content in self._faded:
            # Case 2: re-attending previously-seen (faded) content.
            _remove_from_deque(self._faded, content)
            self._faded.append(self._attending)
            self._attending = content
            self._intensity = 1.0
            return

        # Case 3: brand-new content — decay, displace, switch.
        self._intensity = max(_INTENSITY_FLOOR, self._intensity * DECAY)
        self._faded.append(self._attending)
        self._attending = content

    def focus(self) -> dict[str, Any]:
        """Return the current attention state as a plain dict."""
        return {
            "attending": self._attending,
            "intensity": self._intensity,
            "faded": list(self._faded),
        }


# ------------------------------------------------------------------
# Helpers
# ------------------------------------------------------------------

def _remove_from_deque(dq: deque, value: str) -> None:
    """Remove the first occurrence of *value* from *dq* in O(n)."""
    try:
        idx = list(dq).index(value)
    except ValueError:
        return
    # Rebuild: rotate so the target is at the left, pop it, rotate back.
    dq.rotate(-idx)
    dq.popleft()
    dq.rotate(idx)
