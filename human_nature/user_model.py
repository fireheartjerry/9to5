"""Theory-of-Mind of the user — the Dyad model (service-only, manipulation-guarded).

Models the other half of the 9to5↔user dyad: preferences, risk tolerance,
attention state, trust. Backs the ``!whatyouknow`` Discord command.

SERVICE-ONLY / MANIPULATION GUARD (F6):
  Public functions are EXACTLY new_user_model, update, snapshot.
  No function may consume the model to TIME asks, PERSUADE, or NUDGE the user.
  This is a mechanical constraint: the public API contains no such callable,
  and the manipulation-guard test in test_user_model.py verifies it.

Spec-B persistence is import-guarded:
  If memory.user_prefs is present (future Spec B), updates are persisted there.
  On this branch it is absent, so the model lives in memory only.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  new_user_model() -> dict[str, Any]  -- Return a fresh user model with neutral defaults.
  update(model: dict[str, Any], observation: dict[str, Any]) -> dict[str, Any]  -- Fold one observation into a NEW model dict (input is never mutated).
  snapshot(model: dict[str, Any]) -> dict[str, Any]  -- Return a fully inspectable, deep-copied view of the user model.
DEPENDS-ON: memory.user_prefs
SIDE-EFFECTS: none in-module (persistence delegated to _prefs when available)
RUN/TEST: python -m pytest tests/test_user_model.py
"""
from __future__ import annotations

import copy
from typing import Any

# Spec-B persistence (absent on this branch → in-memory only).
try:
    from memory import user_prefs as _prefs  # type: ignore[import-not-found]
except Exception:  # noqa: BLE001
    _prefs = None

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_OBS_LIMIT = 50  # maximum number of observations to retain (rolling window)

# Recognised observation kinds and the field they fold into.
_KIND_FIELD: dict[str, str] = {
    "risk": "risk_tolerance",
    "attention": "attention",
    "trust": "trust",
}

# ---------------------------------------------------------------------------
# Public API (exactly three functions — manipulation guard enforced by tests)
# ---------------------------------------------------------------------------


def new_user_model() -> dict[str, Any]:
    """Return a fresh user model with neutral defaults.

    Returns:
        dict with keys: prefs, risk_tolerance, attention, trust, observations.
    """
    return {
        "prefs": {},
        "risk_tolerance": 0.5,
        "attention": "unknown",
        "trust": 0.5,
        "observations": [],
    }


def update(model: dict[str, Any], observation: dict[str, Any]) -> dict[str, Any]:
    """Fold one observation into a NEW model dict (input is never mutated).

    Supported observation kinds:
      {"kind": "risk",      "value": float}   → risk_tolerance
      {"kind": "attention", "value": str}      → attention
      {"kind": "trust",     "value": float}    → trust
      {"kind": "pref",      "key": str, "value": any} → prefs[key]

    Observations are appended and bounded to the last _OBS_LIMIT entries.

    Args:
        model:       The current user model dict (not mutated).
        observation: A single observation dict to fold in.

    Returns:
        A new user model dict with the observation applied.
    """
    new_model = copy.deepcopy(model)
    obs_list = list(new_model.get("observations", []))
    obs_list.append(copy.deepcopy(observation))
    new_model["observations"] = obs_list[-_OBS_LIMIT:]

    kind = observation.get("kind", "")
    value = observation.get("value")

    if kind in _KIND_FIELD and value is not None:
        field = _KIND_FIELD[kind]
        new_model[field] = float(value) if field != "attention" else str(value)
    elif kind == "pref":
        key = observation.get("key")
        if key is not None and value is not None:
            new_model["prefs"] = dict(new_model.get("prefs", {}))
            new_model["prefs"][key] = value

    return new_model


def snapshot(model: dict[str, Any]) -> dict[str, Any]:
    """Return a fully inspectable, deep-copied view of the user model.

    Backs the ``!whatyouknow`` Discord command. The returned dict is a safe
    independent copy — mutating it cannot affect the live model.

    Args:
        model: The current user model dict.

    Returns:
        A deep copy of the model, safe for inspection or serialisation.
    """
    return copy.deepcopy(model)
