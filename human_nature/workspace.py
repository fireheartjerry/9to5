"""Global Workspace — the GWT competition/broadcast loop (Baars, Dehaene).

Specialist processes compete for the workspace; the winning content is broadcast
to all specialists and becomes the system's momentary "conscious content." Awareness
equals global availability. All specialists are injected callables — no Ollama, no
Discord, no hidden state (closed API, F10).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Workspace  -- Global Workspace: specialists compete, winner is broadcast.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none (pure; broadcast may call specialist.on_broadcast callbacks)
RUN/TEST: python -m pytest tests/human_nature/test_workspace.py
"""
from __future__ import annotations

from typing import Any, Callable, Optional


class Workspace:
    """Global Workspace: specialists compete, winner is broadcast.

    Each specialist is a callable ``(state) -> {"content": str, "salience": float}``.
    Ties in salience are broken by registration order (first-registered wins).
    """

    def __init__(self) -> None:
        # Preserve insertion order for deterministic tie-breaking.
        self._specialists: list[tuple[str, Callable]] = []

    def register(self, name: str, specialist: Callable) -> None:
        """Register a named specialist process."""
        self._specialists.append((name, specialist))

    def tick(self, state: Any) -> Optional[dict]:
        """Run all specialists on *state*; return the broadcast winner or None."""
        if not self._specialists:
            return None

        results = [
            (name, spec(state))
            for name, spec in self._specialists
        ]

        # Pick max salience; ties broken by list order (first wins, via stable max).
        winner_name, winner_out = _select_winner(results)

        losers = [name for name, _ in results if name != winner_name]
        return {
            "winner": winner_name,
            "content": winner_out["content"],
            "salience": winner_out["salience"],
            "losers": losers,
        }

    def broadcast(self, winner: dict) -> None:
        """Notify all specialists that define an ``on_broadcast`` method."""
        for _name, spec in self._specialists:
            callback = getattr(spec, "on_broadcast", None)
            if callable(callback):
                try:
                    callback(winner)
                except Exception:
                    pass  # defensive: never let a broken callback silence the loop


def _select_winner(results: list[tuple[str, dict]]) -> tuple[str, dict]:
    """Return the (name, output) with the highest salience (first-registered on tie)."""
    best_name, best_out = results[0]
    best_sal = float(best_out["salience"])
    for name, out in results[1:]:
        sal = float(out["salience"])
        if sal > best_sal:
            best_sal = sal
            best_name = name
            best_out = out
    return best_name, best_out
