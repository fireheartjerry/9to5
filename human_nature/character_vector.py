"""TARS dials — versioned, inspectable, propose-not-apply character vector (F6).

The character vector is a structured dict of named traits, each clamped to [0,100].
Humans set dials directly (``set_dial``); the system may only PROPOSE changes
(``propose_change``) and must wait for a human to ``ratify`` before any change is
applied.  This is the mechanical enforcement of "propose, never self-apply" (F6).

The vector is immutable at the call site: every mutating function returns a NEW dict
and leaves the original unchanged.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  new_character_vector() -> dict[str, Any]  -- Return a fresh character vector with all traits at the neutral midpoint.
  set_dial(vec: dict[str, Any], trait: str, value: int | float) -> dict[str, Any]  -- Human action — return a NEW vector with ``trait`` set to clamped ``value``.
  propose_change(vec: dict[str, Any], trait: str, value: int | float, rationale: str) -> dict[str, Any]  -- System action — return a proposal dict
  ratify(vec: dict[str, Any], proposal: dict[str, Any]) -> dict[str, Any]  -- Apply a proposal (clamped) + bump version
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none (pure; does not mutate inputs)
RUN/TEST: python -m pytest tests/human_nature/test_character_vector.py
"""
from __future__ import annotations

import copy
from typing import Any

TRAITS: tuple[str, ...] = (
    "honesty",
    "humor",
    "terseness",
    "formality",
    "sass",
    "caution",
    "rigor",
    "risk_appetite",
    "contrarianism",
    "curiosity",
)

_VALID_TRAITS: frozenset[str] = frozenset(TRAITS)

# Dial bounds.
DIAL_MIN: int = 0
DIAL_MAX: int = 100


def new_character_vector() -> dict[str, Any]:
    """Return a fresh character vector with all traits at the neutral midpoint."""
    return {
        "traits": {t: 50 for t in TRAITS},
        "version": 1,
    }


def _clamp(value: int | float) -> int:
    """Clamp a dial value to [DIAL_MIN, DIAL_MAX]."""
    return int(max(DIAL_MIN, min(DIAL_MAX, value)))


def set_dial(vec: dict[str, Any], trait: str, value: int | float) -> dict[str, Any]:
    """Human action — return a NEW vector with ``trait`` set to clamped ``value``.

    Does NOT mutate ``vec``.  Bumps ``version`` by one.

    Raises:
        ValueError: if ``trait`` is not in TRAITS.
    """
    if trait not in _VALID_TRAITS:
        raise ValueError(f"unknown trait {trait!r}; valid traits: {sorted(_VALID_TRAITS)}")
    new_vec = copy.deepcopy(vec)
    new_vec["traits"][trait] = _clamp(value)
    new_vec["version"] = vec["version"] + 1
    return new_vec


def propose_change(
    vec: dict[str, Any],
    trait: str,
    value: int | float,
    rationale: str,
) -> dict[str, Any]:
    """System action — return a proposal dict; MUST NOT mutate ``vec`` or change version.

    The proposal has ``status="proposed"`` and must be ratified by a human before
    any change is applied.  The vector is not touched.

    Returns:
        dict with keys: ``trait``, ``value``, ``rationale``, ``status``.
    """
    if trait not in _VALID_TRAITS:
        raise ValueError(f"unknown trait {trait!r}; valid traits: {sorted(_VALID_TRAITS)}")
    return {
        "trait": trait,
        "value": value,
        "rationale": rationale,
        "status": "proposed",
    }


def ratify(vec: dict[str, Any], proposal: dict[str, Any]) -> dict[str, Any]:
    """Apply a proposal (clamped) + bump version; return a NEW vector.

    Does NOT mutate ``vec``.

    Args:
        vec:      The current character vector.
        proposal: A dict produced by ``propose_change`` (must contain ``trait`` and ``value``).

    Returns:
        New character vector with the proposed change applied.
    """
    trait = proposal["trait"]
    if trait not in _VALID_TRAITS:
        raise ValueError(f"unknown trait {trait!r}; valid traits: {sorted(_VALID_TRAITS)}")
    value = proposal["value"]
    new_vec = copy.deepcopy(vec)
    new_vec["traits"][trait] = _clamp(value)
    new_vec["version"] = vec["version"] + 1
    return new_vec
