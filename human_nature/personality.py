"""PERSONALITY — versioned trait vector wrapping character_vector, and its setpoints.

A simple 6-trait, 0..1 personality vector distinct from the 10-trait TARS
``character_vector`` dials. Runtime steering derives drive/mood/risk setpoints
from this vector; persona-vector steering (the heavier, embedding-space
technique) is monitor-only and offline — it never drives these setpoints
directly. Same propose-not-apply discipline as ``character_vector``: the
system may only ``propose_trait``; a human (or ratifying caller) must
``ratify`` before any change lands.

The vector is immutable at the call site: every function returns a NEW dict
(or plain value) and leaves its inputs unchanged.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  new_personality() -> dict[str, Any]  -- Return a fresh personality vector with all traits at the neutral midpoint.
  drive_setpoints(p: dict[str, Any]) -> dict[str, float]  -- Derive the 8 drive setpoints from ``p``'s traits
  mood_setpoint(p: dict[str, Any]) -> dict[str, float]  -- Derive a baseline {valence, arousal} mood setpoint from ``p``'s traits.
  risk_band(p: dict[str, Any]) -> float  -- Derive a [0,1] risk-tolerance band: rises with (1-caution) and openness,
  propose_trait(p: dict[str, Any], trait: str, value: float) -> dict[str, Any]  -- System action — return a proposal dict
  ratify(p: dict[str, Any], proposal: dict[str, Any]) -> dict[str, Any]  -- Apply a proposal (clamped) + bump version
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none (pure; does not mutate inputs)
RUN/TEST: python -m pytest tests/human_nature/test_personality.py
"""
from __future__ import annotations

import copy
from typing import Any

TRAITS: tuple[str, ...] = (
    "caution",
    "rigor",
    "skepticism",
    "openness",
    "terseness",
    "warmth",
)

_VALID_TRAITS: frozenset[str] = frozenset(TRAITS)

DRIVE_NAMES: tuple[str, ...] = (
    "mastery",
    "curiosity",
    "coherence",
    "economy",
    "agency",
    "commitment",
    "integrity",
    "recovery",
)

TRAIT_MIN: float = 0.0
TRAIT_MAX: float = 1.0


def new_personality() -> dict[str, Any]:
    """Return a fresh personality vector with all traits at the neutral midpoint."""
    return {
        "traits": {t: 0.5 for t in TRAITS},
        "version": 1,
    }


def _clamp01(value: float) -> float:
    """Clamp a value to [TRAIT_MIN, TRAIT_MAX]."""
    return max(TRAIT_MIN, min(TRAIT_MAX, float(value)))


def drive_setpoints(p: dict[str, Any]) -> dict[str, float]:
    """Derive the 8 drive setpoints from ``p``'s traits. Does not mutate ``p``."""
    t = p["traits"]
    caution = t["caution"]
    rigor = t["rigor"]
    skepticism = t["skepticism"]
    openness = t["openness"]
    terseness = t["terseness"]
    warmth = t["warmth"]
    return {
        "mastery": _clamp01(0.5 * rigor + 0.5 * skepticism),
        "curiosity": _clamp01(openness),
        "coherence": _clamp01(rigor),
        "economy": _clamp01(terseness),
        "agency": _clamp01(1.0 - caution),
        "commitment": _clamp01(0.5 * rigor + 0.5 * (1.0 - caution)),
        "integrity": _clamp01(0.75 + 0.25 * (rigor - 0.5)),
        "recovery": _clamp01(0.3 + 0.4 * warmth + 0.3 * caution),
    }


def mood_setpoint(p: dict[str, Any]) -> dict[str, float]:
    """Derive a baseline {valence, arousal} mood setpoint from ``p``'s traits.

    Both values are in [-1, 1]. Does not mutate ``p``.
    """
    t = p["traits"]
    warmth = t["warmth"]
    caution = t["caution"]
    valence = max(-1.0, min(1.0, 2.0 * warmth - 1.0))
    arousal = max(-1.0, min(1.0, 2.0 * (1.0 - caution) - 1.0))
    return {"valence": valence, "arousal": arousal}


def risk_band(p: dict[str, Any]) -> float:
    """Derive a [0,1] risk-tolerance band: rises with (1-caution) and openness,
    falls with rigor. Does not mutate ``p``.
    """
    t = p["traits"]
    caution = t["caution"]
    rigor = t["rigor"]
    openness = t["openness"]
    return _clamp01(0.5 * (1.0 - caution) + 0.3 * openness - 0.2 * rigor + 0.2)


def propose_trait(p: dict[str, Any], trait: str, value: float) -> dict[str, Any]:
    """System action — return a proposal dict; MUST NOT mutate ``p``.

    Returns:
        dict with keys: ``trait``, ``value``, ``status``.
    """
    if trait not in _VALID_TRAITS:
        raise ValueError(f"unknown trait {trait!r}; valid traits: {sorted(_VALID_TRAITS)}")
    return {
        "trait": trait,
        "value": value,
        "status": "proposed",
    }


def ratify(p: dict[str, Any], proposal: dict[str, Any]) -> dict[str, Any]:
    """Apply a proposal (clamped) + bump version; return a NEW personality dict.

    Does NOT mutate ``p``.

    Raises:
        ValueError: if ``proposal["status"] != "proposed"`` or the trait is unknown.
    """
    if proposal.get("status") != "proposed":
        raise ValueError(f"proposal status must be 'proposed', got {proposal.get('status')!r}")
    trait = proposal["trait"]
    if trait not in _VALID_TRAITS:
        raise ValueError(f"unknown trait {trait!r}; valid traits: {sorted(_VALID_TRAITS)}")
    new_p = copy.deepcopy(p)
    new_p["traits"][trait] = _clamp01(proposal["value"])
    new_p["version"] = p["version"] + 1
    return new_p
