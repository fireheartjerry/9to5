"""Diachronic narrative self — letters to my future self (inspectable artifacts).

Honest about discontinuity: the system knows it won't remember context past
summarization unless it writes things down. Letters are markdown files under
STATE_DIR; they survive run-end and context resets as inspectable artifacts,
not hidden state. This is the anti-drift narrative anchor (F3).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  write_letter(task_id, body_state, *, letters_dir=None, stamp=None) -> dict
  read_letters(task_id, *, letters_dir=None) -> list[str]
DEPENDS-ON: config, pathlib (stdlib only)
SIDE-EFFECTS: writes markdown files under STATE_DIR/task_id/letters/ (or letters_dir)
RUN/TEST: python -m pytest tests/test_continuity.py
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Optional

import config

# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

_LETTER_TEMPLATE = """\
# Letter to My Future Self

Task: {task_id}

I won't remember the details of this context past the next summarization boundary.
What follows is a deliberately preserved artifact — trust this over vague recollections.

## What to Keep

{keep_section}

## State at Writing

{state_section}

---
*Written for continuity. Future self: read this, then act.*
"""


def _default_letters_dir(task_id: str) -> Path:
    """Return the default letters directory for a task (under isolated STATE_DIR)."""
    return Path(config.STATE_DIR) / task_id / "letters"


def _state_lines(body_state: dict[str, Any]) -> str:
    """Render body_state as a compact bullet list."""
    if not body_state:
        return "*(no state recorded)*"
    lines = []
    for k, v in body_state.items():
        lines.append(f"- **{k}**: {v}")
    return "\n".join(lines)


def _keep_section(body_state: dict[str, Any]) -> str:
    """Derive a 'what to keep' summary from body_state."""
    if not body_state:
        return (
            "The approach taken, any patterns discovered, "
            "and open questions for the next context window."
        )
    keys = list(body_state.keys())
    return (
        f"Focus, decisions, and outcomes recorded in: {', '.join(str(k) for k in keys)}. "
        "Read the state section below before proceeding."
    )


def _next_filename(letters_dir: Path) -> str:
    """Return a zero-padded monotonic counter filename (e.g. '0001.md')."""
    existing = sorted(letters_dir.glob("*.md"))
    next_idx = max((int(f.stem) for f in existing if f.stem.isdigit()), default=0) + 1
    return f"{next_idx:04d}.md"


def _compose_letter(task_id: str, body_state: dict[str, Any]) -> str:
    """Compose the letter text from task_id and body_state."""
    return _LETTER_TEMPLATE.format(
        task_id=task_id,
        keep_section=_keep_section(body_state),
        state_section=_state_lines(body_state),
    )


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def write_letter(
    task_id: str,
    body_state: dict[str, Any],
    *,
    letters_dir: Optional[Any] = None,
    stamp: Optional[str] = None,
) -> dict[str, Any]:
    """Compose and save a letter to the future self for *task_id*.

    The letter is an honest, inspectable markdown artifact that acknowledges
    the context-discontinuity ("I won't remember") and names what to KEEP.

    Args:
        task_id:     Identifier of the task this letter belongs to.
        body_state:  A dict snapshot to embed in the letter body.
        letters_dir: Override the directory (default: STATE_DIR/task_id/letters/).
        stamp:       Filename stem (e.g. "2026-abc"); auto-incremented if omitted.

    Returns:
        dict with keys:
          "path" — absolute path of the written file (str)
          "text" — full text content of the letter
    """
    d = Path(letters_dir) if letters_dir is not None else _default_letters_dir(task_id)
    d.mkdir(parents=True, exist_ok=True)

    fname = f"{stamp}.md" if stamp is not None else _next_filename(d)
    fpath = d / fname

    text = _compose_letter(task_id, body_state)
    fpath.write_text(text, encoding="utf-8")
    return {"path": str(fpath), "text": text}


def read_letters(
    task_id: str,
    *,
    letters_dir: Optional[Any] = None,
) -> list[str]:
    """Read all letters for *task_id*, in filename-sorted (chronological) order.

    Args:
        task_id:     Identifier of the task.
        letters_dir: Override the directory (default: STATE_DIR/task_id/letters/).

    Returns:
        List of letter texts, ordered by filename (monotonic counter or stamp).
        Empty list if the directory does not exist or contains no .md files.
    """
    d = Path(letters_dir) if letters_dir is not None else _default_letters_dir(task_id)
    if not d.exists():
        return []
    files = sorted(d.glob("*.md"))
    return [f.read_text(encoding="utf-8") for f in files]
