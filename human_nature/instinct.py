"""Instinct faculty — ledger-grounded "something feels off" signal (Phase 3.4).

Distinct from Spec-B's rule-derived Predictive Flags: instinct is the residual
*gut* — pattern-recognition that fires when accumulated reflections and failure
modes suggest something is wrong, even without a matching explicit rule.

Key properties (spec §3.3 / F10):
  - At most once per run (guarded by state.meta["instinct_flags"])
  - Ledger-grounded: flags a "instinct" judgment in the Conviction Ledger so
    track_record can later measure how often the gut was right
  - Sometimes-wrong by design — that is what separates an instinct from a rule
  - Injectable chat callable so tests never touch Ollama

Spec-B integration guard:
  Spec-B's notifications.instinct (NightclawInstinct) may not exist on this
  branch.  We try to import it; if absent, _nc = None and we operate standalone.
  When present, the caller may extend or delegate to it; this module does not
  duplicate its logic.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  maybe_flag(state: dict[str, Any], reflections: list[dict], failure_modes: list[dict], *, chat: Optional[Callable]=None, db_path: Optional[Path]=None) -> Optional[str]  -- Fire the instinct check
DEPENDS-ON: config, llm_io, memory.conviction_ledger, notifications.instinct
SIDE-EFFECTS: mutates state["meta"]["instinct_flags"]; writes conviction ledger
RUN/TEST: python -m pytest tests/test_instinct.py
"""
from __future__ import annotations

from pathlib import Path
from typing import Any, Callable, Optional

import config
import llm_io
from memory.conviction_ledger import record_judgment

# ---------------------------------------------------------------------------
# Spec-B integration guard (import-guarded; absent → standalone)
# ---------------------------------------------------------------------------
try:
    from notifications import instinct as _nc  # type: ignore[attr-defined]
except Exception:  # noqa: BLE001 -- Spec-B not on this branch
    _nc = None  # type: ignore[assignment]

# ---------------------------------------------------------------------------
# System prompt for the instinct inference
# ---------------------------------------------------------------------------
_SYSTEM = (
    "You are a pattern-recognition layer for an autonomous AI system. "
    "Your job is to detect when something feels off — subtle patterns in "
    "the run history, reflections, and failure modes that suggest a problem "
    "the explicit rules haven't caught. "
    "If you detect a genuine concern, output one concise sentence describing it. "
    "If nothing feels wrong, output nothing (empty response). "
    "Never output a rule-derived or obvious observation — only genuine gut signals."
)

_OLLAMA = None  # lazy singleton; never imported at module load time


def _getOllama():  # pragma: no cover -- real Ollama blocked in tests
    global _OLLAMA
    if _OLLAMA is None:
        import ollama  # deferred import — ~0.3s SDK cost on first real call
        _OLLAMA = ollama.Client(host=config.OLLAMA_HOST,
                                timeout=config.OLLAMA_TIMEOUT_SECONDS)
    return _OLLAMA


def _default_chat(system: str, user: str):  # pragma: no cover
    return _getOllama().chat(
        model=config.HN_FAST_MODEL,
        messages=[{"role": "system", "content": system},
                  {"role": "user", "content": user}],
    )


# ---------------------------------------------------------------------------
# State helpers (handle plain dicts and TaskState-style dicts)
# ---------------------------------------------------------------------------

def _get_instinct_flags(state: dict[str, Any]) -> list:
    """Return the instinct_flags list from state, creating the path if absent."""
    if "meta" not in state:
        state["meta"] = {}
    return state["meta"].setdefault("instinct_flags", [])


def _get_domain(state: dict[str, Any]) -> str:
    """Extract a short domain string for the conviction ledger entry."""
    meta = state.get("meta") or {}
    return str(meta.get("domain") or meta.get("goal_raw") or "general")[:64]


# ---------------------------------------------------------------------------
# Prompt builder
# ---------------------------------------------------------------------------

def _build_user_prompt(
    state: dict[str, Any],
    reflections: list[dict],
    failure_modes: list[dict],
) -> str:
    """Compose the user-side context block for the instinct model call."""
    meta = state.get("meta") or {}
    lines: list[str] = [
        f"GOAL: {meta.get('goal_raw', '')}",
        f"STATUS: {meta.get('status', '?')}",
        "RECENT REFLECTIONS:",
    ]
    for r in (reflections or [])[-10:]:
        note = r.get("approach") or r.get("reusable_recipe") or ""
        if note:
            lines.append(f"  - {note}")
    lines.append("RECENT FAILURE MODES:")
    for fm in (failure_modes or [])[:5]:
        tc = fm.get("taxonomy_class", "")
        rc = fm.get("root_cause", "")
        if tc or rc:
            lines.append(f"  - {tc}: {rc}")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def maybe_flag(
    state: dict[str, Any],
    reflections: list[dict],
    failure_modes: list[dict],
    *,
    chat: Optional[Callable] = None,
    db_path: Optional[Path] = None,
) -> Optional[str]:
    """Fire the instinct check; return the flag sentence or None.

    At most once per run: if instinct_flags is already non-empty, returns None
    without calling the model.

    Args:
        state:         Run state dict (plain dict or TaskState-style; mutated in place).
        reflections:   Recent SIE reflections (list of dicts with "approach" field).
        failure_modes: Recent failure modes (list of dicts with taxonomy_class/root_cause).
        chat:          Injectable chat callable (system, user) -> response.  None → Ollama.
        db_path:       Override conviction DB path (for test isolation).

    Returns:
        Flag sentence str if the model returns a non-empty signal this run.
        None if already fired, or if the model returns empty/whitespace.
    """
    flags = _get_instinct_flags(state)
    if flags:
        return None  # once-per-run guard

    _chat = chat if chat is not None else _default_chat
    user_prompt = _build_user_prompt(state, reflections, failure_modes)

    try:
        resp = _chat(_SYSTEM, user_prompt)
        flag_text = (llm_io.responseText(resp) or "").strip()
    except Exception:  # noqa: BLE001 -- instinct is best-effort
        return None

    if not flag_text:
        return None

    # Non-empty: record and surface
    flags.append(flag_text)
    _record_to_ledger(state, db_path)
    return flag_text


def _record_to_ledger(state: dict[str, Any], db_path: Optional[Path]) -> None:
    """Log an instinct judgment to the conviction ledger (best-effort)."""
    try:
        domain = _get_domain(state)
        record_judgment(
            judgment_type="instinct",
            domain=domain,
            conviction=0.5,   # instinct is a mid-confidence signal by design (F10)
            db_path=db_path,
        )
    except Exception:  # noqa: BLE001 -- ledger write is best-effort
        pass
