"""Psyche runtime — the per-tick glue that makes the interior LIVE.

Pure faculties (affect_manifold, drives, mood, prototypes, personality) are
composed here into three lifecycle hooks over a self_state dict:

  * ensure_psyche  — SETUP: populate drives/mood/affect_manifold/personality_ref.
  * tick           — WORKSPACE: one affect step + dominant-label projection.
  * integrate_outcome — TEARDOWN: fold the run outcome into mood + drives.

All functions are best-effort and never raise on empty inputs; a bare `{}`
self_state with a `{}` appraisal still yields a valid "neutral" label. The
self_state dict is mutated in place (matching self_state.py's own updaters) and
also returned for chaining.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ensure_psyche(ss: dict, personality: dict | None = None) -> dict  -- Fill missing psyche state.
  tick(ss: dict, appraisal: dict, scars: dict | None = None, prev_label: str | None = None) -> dict  -- One workspace tick.
  integrate_outcome(ss: dict, run_valence: float, run_arousal: float, outcome_features: dict) -> dict  -- Fold outcome into mood + drives.
DEPENDS-ON: config, human_nature.{affect_manifold, drives, mood, personality, prototypes}
SIDE-EFFECTS: mutates the passed-in self_state dict in place
RUN/TEST: python -m pytest tests/human_nature/test_psyche_runtime.py
"""
from __future__ import annotations

from typing import Any

import config

from human_nature import affect_manifold, drives, mood, personality, prototypes

_MOOD_DECAY = getattr(config, "HN_MOOD_DECAY", 0.15)


def ensure_psyche(ss: dict[str, Any], personality: dict | None = None) -> dict[str, Any]:
    """Populate any missing psyche sub-state on `ss`; return `ss`."""
    if not ss.get("drives"):
        ss["drives"] = drives.new_drives()
    if not ss.get("mood"):
        ss["mood"] = mood.new_mood()
    if not ss.get("affect_manifold"):
        ss["affect_manifold"] = affect_manifold.new_manifold()
    if ss.get("personality_ref") is None and personality is not None:
        ss["personality_ref"] = personality
    return ss


def tick(
    ss: dict[str, Any],
    appraisal: dict[str, Any],
    scars: dict | None = None,
    prev_label: str | None = None,
) -> dict[str, Any]:
    """Advance the interior one workspace tick; return the tick result dict."""
    ensure_psyche(ss)
    drive_pressure = drives.pressure(ss["drives"])
    personality_baseline: dict[str, float] = {}
    ss["affect_manifold"] = affect_manifold.update(
        ss["affect_manifold"],
        appraisal or {},
        ss["mood"],
        drive_pressure,
        scars or {},
        personality_baseline,
    )
    label = prototypes.dominant(ss["affect_manifold"], prev=prev_label)
    return {"self_state": ss, "dominant": label, "manifold": ss["affect_manifold"]}


def integrate_outcome(
    ss: dict[str, Any],
    run_valence: float,
    run_arousal: float,
    outcome_features: dict[str, Any],
) -> dict[str, Any]:
    """Teardown: fold this run's outcome into mood and drives; return `ss`."""
    ensure_psyche(ss)
    ss["mood"] = mood.blend_outcome(ss["mood"], run_valence, run_arousal)
    p = ss.get("personality_ref")
    if p is not None:
        setpoint = personality.mood_setpoint(p)
        ss["mood"] = mood.decay(ss["mood"], setpoint, _MOOD_DECAY)
    ss["drives"] = drives.update(ss["drives"], outcome_features or {})
    return ss
