"""Earned-autonomy dynamic trust contract (F6).

Autonomy is earned from demonstrated calibration (track_record), never fixed.
The veto ceiling rises with proven reliability and auto-revokes on miscalibration.
Three tiers — cosmetic < soft < hard — operationalise the F6 principle that teeth
are a strict function of proven reliability.

The system PROPOSES; autonomy is EARNED; humans can always revoke.  This module
is pure: no I/O, no Ollama, no Discord.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ceiling(track: dict[str, Any]) -> str  -- Derive earned autonomy tier from a ``track_record``-shaped dict.
  revoke_on_miscalibration(current: str, recent_rate: float, threshold: float=0.5) -> str  -- Demote exactly one tier level when recent performance is below ``threshold``.
  cap_to(tier: str, ceil: str) -> str  -- Return ``min(tier, ceil)`` on the cosmetic < soft < hard ordering.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none (pure)
RUN/TEST: python -m pytest tests/test_autonomy.py
"""
from __future__ import annotations

from typing import Any

# Ordered tiers: index 0 = weakest, index 2 = strongest.
TIERS: tuple[str, ...] = ("cosmetic", "soft", "hard")

# Cold-start floor: below this sample count, the track record has no teeth.
COLD_START_MIN: int = 5

# Rate thresholds for tier promotion.
RATE_SOFT: float = 0.65   # rate >= RATE_SOFT → at least soft
RATE_HARD: float = 0.85   # rate >= RATE_HARD (and volume >= HARD_MIN_TOTAL) → hard
HARD_MIN_TOTAL: int = 20  # minimum observations before hard is earnable


def ceiling(track: dict[str, Any]) -> str:
    """Derive earned autonomy tier from a ``track_record``-shaped dict.

    Args:
        track: dict with keys ``rate`` (float in [0,1]) and ``total`` (int).

    Returns:
        ``"cosmetic"`` | ``"soft"`` | ``"hard"``
    """
    total = int(track.get("total", 0))
    rate = float(track.get("rate", 0.0))

    if total < COLD_START_MIN:
        return "cosmetic"
    if rate >= RATE_HARD and total >= HARD_MIN_TOTAL:
        return "hard"
    if rate >= RATE_SOFT:
        return "soft"
    return "cosmetic"


def revoke_on_miscalibration(
    current: str,
    recent_rate: float,
    threshold: float = 0.5,
) -> str:
    """Demote exactly one tier level when recent performance is below ``threshold``.

    Floors at ``"cosmetic"`` — can never demote below the minimum.

    Args:
        current:     The current autonomy tier (``"cosmetic"``, ``"soft"``, ``"hard"``).
        recent_rate: Hit-rate of the most-recent window.
        threshold:   Below this rate, demote one level.

    Returns:
        New tier string (unchanged when ``recent_rate >= threshold``).
    """
    if recent_rate >= threshold:
        return current
    idx = TIERS.index(current) if current in TIERS else 0
    return TIERS[max(0, idx - 1)]


def cap_to(tier: str, ceil: str) -> str:
    """Return ``min(tier, ceil)`` on the cosmetic < soft < hard ordering.

    An opinion tier can never exceed the earned autonomy ceiling.

    Args:
        tier: The requested/opinion tier.
        ceil: The earned autonomy ceiling.

    Returns:
        The lower of the two tiers.
    """
    tier_idx = TIERS.index(tier) if tier in TIERS else 0
    ceil_idx = TIERS.index(ceil) if ceil in TIERS else 0
    return TIERS[min(tier_idx, ceil_idx)]
