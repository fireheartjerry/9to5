class _TextExtractor(HTMLParser):
    """Collect visible text, dropping <script>/<style>/<nav>/<head> content."""

    _SKIP = {"script", "style", "head", "nav", "svg", "noscript", "template"}
    _BLOCK = {"p", "div", "section", "article", "li", "tr", "br", "h1", "h2",
              "h3", "h4", "h5", "h6", "pre", "table", "ul", "ol"}

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self._chunks: list[str] = []
        self._skip_depth = 0

    def handle_starttag(self, tag: str, attrs) -> None:  # noqa: ANN001
        if tag in self._SKIP:
            self._skip_depth += 1
        elif tag in self._BLOCK:
            self._chunks.append("\n")

    def handle_endtag(self, tag: str) -> None:
        if tag in self._SKIP and self._skip_depth > 0:
            self._skip_depth -= 1
        elif tag in self._BLOCK:
            self._chunks.append("\n")

    def handle_data(self, data: str) -> None:
        if self._skip_depth == 0 and data.strip():
            self._chunks.append(data)

    def text(self) -> str:
        raw = "".join(self._chunks)
        raw = re.sub(r"[ \t]+", " ", raw)
        raw = re.sub(r"\n{3,}", "\n\n", raw)
        return raw.strip()


def _htmlToText(html: str) -> str:
    try:
        p = _TextExtractor()
        p.feed(html)
        return p.text()
    except Exception:  # noqa: BLE001
        # crude fallback: strip tags
        return re.sub(r"<[^>]+>", " ", html or "")


# ============================================================================
# 1) Fetch the latest docs (Python has internet; Ollama does not)
# ============================================================================
def _fetchOne(url: str, timeout: int) -> "tuple[str, str | None]":
    """Fetch one URL -> (url, body or None). Never raises."""
    try:
        import requests
        r = requests.get(url, timeout=timeout, headers={"User-Agent": "9to5-knowledge-refresh"})
        if 200 <= r.status_code < 300 and r.text:
            body = r.text if url.endswith(".md") else _htmlToText(r.text)
            if body and len(body) > 200:
                return url, body
    except Exception as e:  # noqa: BLE001
        LOG.debug("doc fetch failed %s (%s)", url, e)
    return url, None


def fetchClaudeDocs(enabled: bool = True, timeout: Optional[int] = None) -> dict:
    """Scrape current Claude Code docs + changelog IN PARALLEL. Returns
    ``{pages: {url: text}, ok: [url...], failed: [url...], fetched_at: iso}``.
    Never raises -- a fully offline run yields empty pages and the disk knowledge
    still drives the injection. Parallel fetch cuts the 27-page scrape from ~10s to ~2s."""
    timeout = timeout or config.CLAUDE_DOC_TIMEOUT_SECONDS
    result = {"pages": {}, "ok": [], "failed": [],
              "fetched_at": datetime.now().astimezone().isoformat(timespec="seconds")}
    if not enabled:
        LOG.info("doc fetch disabled (CLAUDE_DOC_FETCH=false)")
        return result
    try:
        import requests  # noqa: F401 -- presence check; offline installs still load this module
    except Exception as e:  # noqa: BLE001
        LOG.warning("requests unavailable; skipping doc fetch (%s)", e)
        return result

    import time as _time
    from concurrent.futures import ThreadPoolExecutor, as_completed
    from concurrent.futures import TimeoutError as _FuturesTimeout

    workers = max(1, int(getattr(config, "CLAUDE_DOC_FETCH_WORKERS", 10)))
    budget = float(getattr(config, "CLAUDE_DOC_FETCH_BUDGET_SECONDS", 30))
    urls = list(_CHANGELOG_URLS) + [_DOC_BASES[0] + p for p in _DOC_PAGES]
    seen_pages: set[str] = set()
    deadline = _time.monotonic() + budget

    def _drain(futures: dict) -> None:
        """Collect results until each future completes OR the TOTAL budget elapses, then stop waiting.
        A slow-trickle server (whose per-socket read timeout never trips) therefore cannot hang run
        start past `budget` -- we proceed with whatever has arrived (CB-10)."""
        remaining = max(0.1, deadline - _time.monotonic())
        try:
            for fut in as_completed(list(futures), timeout=remaining):
                url, body = fut.result()
                if body:
                    result["pages"][url] = body
                    result["ok"].append(url)
                    seen_pages.add(url.rsplit("/", 1)[-1])
                else:
                    result["failed"].append(url)
        except _FuturesTimeout:
            LOG.warning("doc fetch exceeded %.0fs total budget; proceeding with %d pages",
                        budget, len(result["ok"]))

    # Own the pool explicitly so we can shutdown(cancel_futures) WITHOUT a wait=True that would block
    # on a stuck socket (the `with` form's implicit shutdown(wait=True) is the actual hang risk).
    pool = ThreadPoolExecutor(max_workers=workers)
    try:
        _drain({pool.submit(_fetchOne, u, timeout): u for u in urls})
        if _time.monotonic() < deadline:   # legacy-domain retry within the remaining budget
            retry = [_DOC_BASES[1] + p for p in _DOC_PAGES if p not in seen_pages]
            if retry:
                _drain({pool.submit(_fetchOne, u, timeout): u for u in retry})
    finally:
        pool.shutdown(wait=False, cancel_futures=True)
    LOG.info("doc fetch (%d workers): %d ok, %d failed", workers, len(result["ok"]), len(result["failed"]))
    return result


