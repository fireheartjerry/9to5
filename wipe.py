"""Factory-reset module — granular deletion of 9to5 state, vault, and logs.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  backupState(keys: list[str]) -> Optional[Path]  -- Tarball the paths about to be wiped
  deleteCategory(key: str) -> tuple[bool, str]  -- Delete one category
  executeWipe(keys: list[str], backup: bool=False) -> dict[str, str]  -- Run wipe on selected categories
  restartBot() -> None  -- Spawn a FRESH detached bot process, then exit this one
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tarfile
from datetime import datetime
from pathlib import Path
from typing import Optional

import config

LOG = config.getLogger("wipe")

ROOT = config.INSTALL_ROOT

CATEGORIES: dict[str, dict] = {
    "tasks": {
        "paths": [ROOT / "state" / "tasks"],
        "label": "Task JSON files",
    },
    "control": {
        "paths": [ROOT / "state" / "control"],
        "label": "Control bus files",
    },
    "experience": {
        "paths": [
            ROOT / "state" / "experience.db",
            ROOT / "state" / "experience.db-shm",
            ROOT / "state" / "experience.db-wal",
            ROOT / "state" / "adversary_trust.jsonl",
            ROOT / "state" / "audit.jsonl",
        ],
        "label": "Experience DB + audit log",
    },
    "vault": {
        "paths": [ROOT / "vault"],
        "label": "Obsidian vault",
        "keep_dir": True,
    },
    "logs": {
        "paths": [ROOT / "logs"],
        "label": "Execution logs",
    },
    "learning": {
        "paths": [ROOT / "learning"],
        "label": "Learning directory",
    },
    "knowledge": {
        "paths": [ROOT / "knowledge"],
        "label": "Knowledge base",
    },
    "chatgpt_profile": {
        "paths": [ROOT / "state" / "chatgpt_profile"],
        "label": "ChatGPT browser profile",
    },
}

BACKUP_DIR = ROOT / "state" / "backups"


def backupState(keys: list[str]) -> Optional[Path]:
    """Tarball the paths about to be wiped. Returns path or None on failure."""
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    dest = BACKUP_DIR / f"wipe-backup-{stamp}.tar.gz"
    try:
        with tarfile.open(dest, "w:gz") as tar:
            for key in keys:
                cat = CATEGORIES.get(key, {})
                for p in cat.get("paths", []):
                    if p.exists():
                        tar.add(p, arcname=str(p.relative_to(ROOT)))
        LOG.info("Backup saved → %s", dest)
        return dest
    except Exception:
        LOG.exception("Backup failed")
        return None


def deleteCategory(key: str) -> tuple[bool, str]:
    """Delete one category. Returns (ok, human-readable status line)."""
    cat = CATEGORIES.get(key)
    if cat is None:
        return False, f"Unknown category: {key}"
    errors: list[str] = []
    for p in cat["paths"]:
        if not p.exists():
            continue
        try:
            if p.is_dir() and cat.get("keep_dir"):
                for child in p.iterdir():
                    shutil.rmtree(child) if child.is_dir() else child.unlink()
            elif p.is_dir():
                shutil.rmtree(p)
            else:
                p.unlink()
        except Exception as exc:
            errors.append(f"{p.name}: {exc}")
    if errors:
        return False, f"{cat['label']}: {'; '.join(errors)}"
    return True, cat["label"]


def executeWipe(keys: list[str], backup: bool = False) -> dict[str, str]:
    """Run wipe on selected categories. Returns ordered {key: status_line} dict."""
    results: dict[str, str] = {}
    if backup:
        path = backupState(keys)
        results["_backup"] = f"✓ Backup: {path}" if path else "✗ Backup failed (proceeding anyway)"
    for key in keys:
        ok, msg = deleteCategory(key)
        results[key] = f"✓ {msg}" if ok else f"✗ {msg}"
    LOG.info("Wipe complete: %s", results)
    return results


def restartBot() -> None:
    """Spawn a FRESH detached bot process, then exit this one -- a clean handoff with no leftover
    in-memory state. os.execv is avoided on purpose: this runs inside the gateway's asyncio loop,
    where execv abandons the live Discord websocket uncleanly and is unreliable on Windows (it is
    emulated as spawn+exit and can leave the parent alive). The explicit spawn + os._exit is
    deterministic on both platforms."""
    LOG.info("Restarting bot: spawning fresh instance then exiting current process")
    try:
        creationflags = 0
        if os.name == "nt":
            creationflags = subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP
        subprocess.Popen([sys.executable, "-m", "notifications.command_bot"],
                         cwd=str(config.INSTALL_ROOT), stdin=subprocess.DEVNULL,
                         close_fds=True, creationflags=creationflags)
    except Exception:  # noqa: BLE001
        LOG.exception("failed to spawn fresh bot instance; NOT exiting current bot")
        return
    os._exit(0)   # hard exit: the new process owns the gateway now; no async cleanup to await
