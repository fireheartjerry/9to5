"""Native engagement APIs (Tier 4) -- pure builders + mappers, no network, no discord.py.

  * ``gatePollPayload(gate)`` -- the Discord Poll object for a gated approval
    ("Approve this <gate>?  Yes / Revise / Abort").
  * ``voteToVerdict(answer)`` -- map a poll answer label to a ControlBus verdict
    (approve / reject / abort), so the gateway's on_raw_poll_vote_add can resolve the gate.
    'abort' is distinct from 'reject' (decline-the-gate vs kill-the-run).
  * ``scheduledEventPayload(...)`` -- the body for a guild Scheduled Event covering
    the 9-5 run window.

The transport (``discord_bot.createPoll`` / the gateway poll-vote listener) is thin
over these; the decision logic lives here where it is unit-testable.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  voteToVerdict(answer: str) -> Optional[str]  -- Map a poll answer label (e.g
  gatePollPayload(gate: str, *, duration_hours: int=1) -> dict  -- A Discord Poll object asking the owner to resolve ``gate``
  scheduledEventPayload(name: str, start_iso: str, end_iso: str, description: str='') -> dict  -- Body for POST /guilds/{id}/scheduled-events
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/notifications/test_engagement.py
"""
from __future__ import annotations

from typing import Optional

# Canonical gate-poll answers. Order matters (Discord answer_ids are 1-based by order).
GATE_ANSWERS = ("Yes", "Revise", "Abort")

_APPROVE = {"yes", "approve", "approved", "lgtm", "ship", "ok"}
# 'Reject' DECLINES the gate (revise/no/deny); 'Abort' KILLS the run -- two distinct control
# actions on the ControlBus (decide(gate,'reject') vs requestAbort()). Folding 'abort' into
# _REJECT silently downgraded a kill-the-run vote to a plain gate decline, so they are split.
_REJECT = {"revise", "reject", "rejected", "no", "deny"}
_ABORT = {"abort", "stop", "kill", "cancel"}


def voteToVerdict(answer: str) -> Optional[str]:
    """Map a poll answer label (e.g. 'Yes') to 'approve' | 'reject' | 'abort' | None.

    'abort' is returned distinctly (never collapsed into 'reject') so the caller can route it to
    the real kill-switch (ControlBus.requestAbort) rather than a gate decline -- they are different
    control actions. Callers that only understand approve/reject MUST treat 'abort' as a run abort.
    """
    t = "".join(ch for ch in (answer or "").lower() if ch.isalnum() or ch.isspace()).strip()
    for w in t.split():
        if w in _APPROVE:
            return "approve"
        if w in _ABORT:
            return "abort"
        if w in _REJECT:
            return "reject"
    return None


def gatePollPayload(gate: str, *, duration_hours: int = 1) -> dict:
    """A Discord Poll object asking the owner to resolve ``gate``. multiselect off; short window."""
    return {
        "question": {"text": f"Approve this {gate}?"[:300]},
        "answers": [{"poll_media": {"text": a}} for a in GATE_ANSWERS],
        "duration": max(1, min(int(duration_hours), 768)),   # Discord allows 1h..32d
        "allow_multiselect": False,
    }


def scheduledEventPayload(name: str, start_iso: str, end_iso: str,
                          description: str = "") -> dict:
    """Body for POST /guilds/{id}/scheduled-events -- an EXTERNAL event for the run window."""
    return {
        "name": name[:100],
        "privacy_level": 2,                 # GUILD_ONLY
        "entity_type": 3,                   # EXTERNAL
        "scheduled_start_time": start_iso,
        "scheduled_end_time": end_iso,
        "entity_metadata": {"location": "9to5 orchestrator"},
        "description": (description or "")[:1000],
    }
