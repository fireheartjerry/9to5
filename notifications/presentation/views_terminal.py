"""Persistent Discord view for the Live Terminal surface: ◀ Prev · ⏸ Freeze · Raw ·
Next ▶ · 📷 Snapshot. timeout=None + stable custom_ids so it survives multi-hour runs
and bot restarts. Registered in notifications/bot/core.py.

The buttons live in the bot process while the surface lives in the orchestrator
process, so navigation is driven through the filesystem bridge (notifications.terminal_ipc):
buttons write nav intent + read the mirror; the orchestrator surface repaints within
~0.4s. All bridge I/O is best-effort and never raises.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  TerminalView
DEPENDS-ON: notifications.commands, notifications.discord_bot, notifications.terminal_ipc, platform_core.runtime
SIDE-EFFECTS: writes nav intent via notifications.terminal_ipc; reads the mirror for snapshots
RUN/TEST: python -m pytest tests/control/test_views_terminal.py
"""

from __future__ import annotations

import discord

from notifications import commands, terminal_ipc
from platform_core.runtime.effect_guard import legacyDiagnosticDiscordSend


async def _ack(interaction: "discord.Interaction") -> bool:
    """Ack the button so the orchestrator surface repaints within ~0.4s. If there is no
    live run (mirror reports zero pages), reply ephemerally and return False."""
    if terminal_ipc.read_mirror().get("page_count", 0) == 0:
        await legacyDiagnosticDiscordSend(interaction.response.send_message, "No live run.", ephemeral=True)
        return False
    await interaction.response.defer()
    return True


def _page_count() -> "int | None":
    return terminal_ipc.read_mirror().get("page_count")


class TerminalView(discord.ui.View):
    def __init__(self) -> None:
        super().__init__(timeout=None)

    async def _guard(self, interaction) -> bool:
        if not commands.isAuthorized(interaction.user.id):
            await legacyDiagnosticDiscordSend(
                interaction.response.send_message, "Not authorized.", ephemeral=True
            )
            return False
        return True

    @discord.ui.button(emoji="◀", style=discord.ButtonStyle.secondary, custom_id="term_prev")
    async def prev(self, interaction, _button):  # noqa: ANN001
        if not await self._guard(interaction):
            return
        terminal_ipc.bump_nav(delta_page=-1, page_count=_page_count())
        await _ack(interaction)

    @discord.ui.button(emoji="⏸", style=discord.ButtonStyle.secondary, custom_id="term_freeze")
    async def freeze(self, interaction, _button):  # noqa: ANN001
        if not await self._guard(interaction):
            return
        terminal_ipc.bump_nav(toggle_freeze=True, page_count=_page_count())
        await _ack(interaction)

    @discord.ui.button(label="Raw", style=discord.ButtonStyle.primary, custom_id="term_raw")
    async def raw(self, interaction, _button):  # noqa: ANN001
        if not await self._guard(interaction):
            return
        terminal_ipc.bump_nav(toggle_raw=True, page_count=_page_count())
        await _ack(interaction)

    @discord.ui.button(emoji="▶", style=discord.ButtonStyle.secondary, custom_id="term_next")
    async def next(self, interaction, _button):  # noqa: ANN001
        if not await self._guard(interaction):
            return
        terminal_ipc.bump_nav(delta_page=1, page_count=_page_count())
        await _ack(interaction)

    @discord.ui.button(emoji="📷", style=discord.ButtonStyle.success, custom_id="term_snap")
    async def snap(self, interaction, _button):  # noqa: ANN001
        body = terminal_ipc.read_mirror().get("body") or ""
        if not body:
            await legacyDiagnosticDiscordSend(
                interaction.response.send_message, "No live run.", ephemeral=True
            )
            return
        from notifications import discord_bot as discord_facade

        await legacyDiagnosticDiscordSend(
            interaction.response.send_message,
            embed=discord_facade.noticeEmbed(body, title="🖥 Live Terminal (snapshot)"),
            ephemeral=True,
        )
