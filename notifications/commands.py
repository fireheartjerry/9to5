class Command(NamedTuple):
    name: str
    arg: str


def parseCommand(content: str) -> Optional[Command]:
    """Exact-token parse of a '!' command. None for non-'!' or unknown names."""
    s = (content or "").strip()
    if not s.startswith("!"):
        return None
    parts = s[1:].split(maxsplit=1)
    if not parts:
        return None
    name = parts[0].lower()
    if name not in COMMAND_REGISTRY:
        return None
    arg = parts[1].strip() if len(parts) > 1 else ""
    return Command(name, arg)


def isAuthorized(user_id: Optional[object]) -> bool:
    """True if no owner configured (dev), else only the configured owner. Empty-string safe."""
    raw = (config.DISCORD_HUMAN_USER_ID or "").strip()
    if not raw or not raw.isdigit():
        return True
    try:
        return user_id is not None and int(user_id) == int(raw)
    except (TypeError, ValueError):
        return False


def decide(author_id: Optional[object], is_bot: bool, content: str) -> Optional[Command]:
    """Shared gate for BOTH the gateway and the in-run poller: returns the command to
    apply only if the author is a non-bot AND authorized. Pure -> directly testable."""
    if is_bot:
        return None
    if not isAuthorized(author_id):
        return None
    return parseCommand(content)


# ---- task resolution / active-run policy (one definition reused everywhere) ----
def resolveTargetTask() -> Optional[TaskState]:
    return TaskState.loadLatest()


def isRunActive(state: Optional[TaskState]) -> bool:
    """A run is 'active' iff its status is not terminal. Derived from TaskState._TERMINAL
    so it can never drift from the terminal set."""
    if state is None:
        return False
    return state.meta.get("status") not in TaskState._TERMINAL


def footerHelp() -> str:
    """Short, never-stale command hint derived from the registry (used by the dashboard)."""
    return " ".join(f"!{n}" for n in ("status", "abort", "pause", "help"))


def _fmtDelta(seconds: float) -> str:
    seconds = max(0, int(seconds))
    h, rem = divmod(seconds, 3600)
    m, s = divmod(rem, 60)
    return f"{h}h{m:02d}m{s:02d}s"


def _statusText(bus: ControlBus, state: TaskState) -> str:
    done, total = state.progress()
    try:
        started = datetime.fromisoformat(state.meta["started_at"])
        deadline = datetime.fromisoformat(state.meta["deadline_at"])
        now = datetime.now().astimezone()
        elapsed = _fmtDelta((now - started).total_seconds())
        eta = _fmtDelta((deadline - now).total_seconds())
    except Exception:  # noqa: BLE001
        elapsed = eta = "-"
    cur = next((s for s in state.subtasks if s["status"] == "in_progress"), None) or state.nextActionable()
    cur_txt = f"`{cur['subtask_id']}` {cur['title']}" if cur else "—"
    gate = bus.getPendingGate()
    gate_txt = f"\n awaiting gate **{gate}** — `!approve` / `!reject`" if gate else ""
    return (f"**`{state.meta['status']}`** · {discord.progressBar(done, total)} · "
            f"mode `{state.meta.get('control_mode', 'watch')}`\n"
            f"Current: {cur_txt}\n `{state.meta.get('work_dir') or '—'}`\n"
            f"Elapsed {elapsed} · ETA {eta}{gate_txt}")


def _planText(state: TaskState) -> str:
    lines = [f"{s['subtask_id']} [{s['status']}] {s['title']}" for s in state.subtasks]
    body = ("\n".join(lines) or "(no subtasks)")[:1800]
    return f"{discord.subtaskTracker(state.subtasks)}\n```\n{body}\n```"


def _helpText() -> str:
    rows = [f"`!{n}` — {m['help']}" for n, m in COMMAND_REGISTRY.items()]
    return "**9TO5 commands**\n" + "\n".join(rows)


def _resolveSid(state: TaskState, arg: str) -> Optional[str]:
    """Pick the subtask for a raw-stdout query: explicit arg, else current, else last."""
    if arg and _SKIP_ID_RE.match(arg):
        return arg
    cur = next((s for s in state.subtasks if s["status"] == "in_progress"), None)
    if cur:
        return cur["subtask_id"]
    return state.subtasks[-1]["subtask_id"] if state.subtasks else None


def _logsText(state: TaskState, arg: str, last_n: int) -> str:
    """Last ``last_n`` raw stdout lines of a subprocess as a code block (off the LiveEventBus)."""
    try:
        from notifications.event_bus import get_bus
        sid = _resolveSid(state, arg)
        if not sid:
            return "(no subtask has produced output yet)"
        lines = [r["line"] for r in get_bus().raw_history(sid, last_n=last_n)]
        body = ("\n".join(lines) or "(no output captured)")[-1800:]
        return f"**stdout `{sid}`** (last {last_n})\n```\n{body}\n```"
    except Exception:  # noqa: BLE001
        return "(logs unavailable)"


def _arcText(state: TaskState) -> str:
    try:
        from notifications import run_arc
        return "**Run arc**\n" + run_arc.render_arc(state)
    except Exception:  # noqa: BLE001
        return "(arc unavailable)"


def _historyText(state: TaskState, last_n: int = 50) -> str:
    try:
        from notifications.event_bus import get_bus
        evs = get_bus().history(last_n=last_n)
        lines = [f"{e.get('at', '')} {e.get('kind')}: {e.get('text', '')}" for e in evs]
        body = ("\n".join(lines) or "(no events)")[-1800:]
        return f"**Event history** (last {last_n})\n```\n{body}\n```"
    except Exception:  # noqa: BLE001
        return "(history unavailable)"


def _applyIntent(bus: ControlBus, cmd: Command) -> str:
    arg = cmd.arg.strip()
    if arg.lower() == "clear":
        bus.pushOp({"op": "intent_clear"})
        return "Cleared active intents."
    if arg.lower().startswith("persist "):
        text = arg[len("persist "):].strip()
        from memory import user_prefs
        prefs = user_prefs.load()
        prefs["persistent_intents"] = list(prefs.get("persistent_intents") or []) + [text]
        user_prefs.save(prefs)
        bus.pushOp({"op": "intent", "text": text})
        return f"Persisted intent (every run) + active now: {text}"
    if not arg:
        return "usage: `!intent <text>` | `!intent clear` | `!intent persist <text>`"
    bus.pushOp({"op": "intent", "text": arg})
    return f"Intent noted — the brain will weigh it at the next decision: {arg}"


def _applyIntelCommand(bus: ControlBus, state: TaskState, cmd: Command) -> Optional[str]:
    """Spec B intelligence/control commands. Returns None for an unrecognized name."""
    n = cmd.name
    if n == "intent":
        return _applyIntent(bus, cmd)
    if n == "prefer":
        from memory import user_prefs
        return user_prefs.applyPrefer(cmd.arg)
    if n == "prefs":
        from memory import user_prefs
        if cmd.arg.strip().lower() == "reset":
            user_prefs.reset()
            return "Preferences reset to defaults."
        return user_prefs.formatPrefs(user_prefs.load())
    if n == "effort":
        lvl = cmd.arg.strip().lower()
        if lvl not in config.EFFORT_FLAG_MAP:
            return f"usage: `!effort <{'|'.join(sorted(set(config.EFFORT_FLAG_MAP)))}>`"
        bus.pushOp({"op": "set_run_effort", "level": lvl})
        return f"Run effort -> `{lvl}` for all future subtasks this run."
    if n == "mode":
        m = cmd.arg.strip().lower()
        if m not in ("gated", "watch"):
            return "usage: `!mode gated|watch`"
        # SINGLE-WRITER RULE: this layer also runs in the gateway-bot process, which must
        # never write task JSON. Queue the change; the run loop drains + applies it.
        bus.pushOp({"op": "set_mode", "mode": m})
        return f"Control mode -> `{m}` (applies at the next loop tick)."
    if n == "replan":
        bus.requestForceReplan()
        return "Replanning pass requested — runs at the next loop tick."
    if n == "deadline":
        m = re.match(r"^\+?(\d+(?:\.\d+)?)\s*([hm])$", cmd.arg.strip().lower())
        if not m:
            return "usage: `!deadline +1h` or `!deadline +30m`"
        secs = float(m.group(1)) * (3600 if m.group(2) == "h" else 60)
        bus.pushOp({"op": "extend_deadline", "delta_seconds": secs})
        return f"Deadline extension queued: +{cmd.arg.strip()}"
    if n == "kill":
        bus.requestKillSubprocess()
        return (f"Kill signal sent — the in-flight Claude attempt's process tree will be "
                f"killed within ~{config.CANCEL_POLL_SECONDS:g}s. The run continues; the "
                "killed attempt does not burn a retry slot.")
    if n == "inject":
        if not cmd.arg.strip():
            return "usage: `!inject <text>`"
        bus.pushOp({"op": "inject_context", "text": cmd.arg.strip()})
        return "Context queued for the next attempt (no replan)."
    if n == "set-effort":
        parts = cmd.arg.split()
        if (len(parts) != 2 or not _SKIP_ID_RE.match(parts[0])
                or parts[1].lower() not in config.EFFORT_FLAG_MAP):
            return "usage: `!set-effort st-00N <level>`"
        bus.pushOp({"op": "set_effort", "subtask_id": parts[0], "level": parts[1].lower()})
        return f"Effort override queued for `{parts[0]}` -> `{parts[1].lower()}`."
    return None


def applyCommand(bus: ControlBus, state: TaskState, cmd: Command) -> str:
    """Perform the bus mutation and return human markdown text ('' for silent control ops)."""
    if state is None:
        return NO_TASK
    n = cmd.name
    # SIE subsystem J: capture the human's decision as an implicit-feedback label
    # (best-effort, never affects control flow).
    if n in ("approve", "reject", "skip", "abort", "retry", "add"):
        try:
            from learning import human_feedback
            human_feedback.record(n, run_id=state.task_id,
                                  subtask_id=getattr(cmd, "arg", None) or None)
        except Exception:  # noqa: BLE001
            pass
    if n == "status":
        return _statusText(bus, state)
    if n == "plan":
        return _planText(state)
    if n == "log":
        return (f"Index: `{state.indexNoteRel()}`\n"
                f"Vault: `{state.data['obsidian']['vault_root']}`\n"
                f"Web: http://127.0.0.1:{config.WEB_DASHBOARD_PORT}/")
    if n == "help":
        return _helpText()
    if n == "abort":
        bus.requestAbort()
        return "Abort requested — run stops after the current step."
    if n == "pause":
        bus.requestPause()
        return "Paused."
    if n == "resume":
        bus.clearPause()
        return "▶ Resumed."
    if n in ("approve", "reject"):
        gate = bus.getPendingGate()
        if not gate:
            return "No gate is currently pending."
        verdict = "approve" if n == "approve" else "reject"
        bus.decide(gate, verdict)
        return f"Gate **{gate}** → {'approved' if n == 'approve' else 'rejected'}."
    if n == "skip":
        if not _SKIP_ID_RE.match(cmd.arg):
            return "usage: `!skip st-00N` (e.g. `!skip st-003`)"
        bus.pushOp({"op": "skip", "subtask_id": cmd.arg})
        return f" Queued skip of `{cmd.arg}`."
    if n == "add":
        if not cmd.arg:
            return "usage: `!add <title>`"
        bus.pushOp({"op": "add", "title": cmd.arg, "description": cmd.arg})
        return f" Queued new subtask: {cmd.arg}"
    if n == "retry":
        bus.pushOp({"op": "retry"})
        return "Queued retry of the current subtask."
    if n == "logs":
        return _logsText(state, cmd.arg, 100)
    if n == "stdout":
        return _logsText(state, cmd.arg, 500)
    if n == "arc":
        return _arcText(state)
    if n == "history":
        return _historyText(state)
    intel = _applyIntelCommand(bus, state, cmd)
    if intel is not None:
        return intel
    return _helpText()
