"""Nightclaw instinct -- occasional, unprompted pattern signals not derived from explicit rules.

The first step toward the human-nature layer. A periodic Ollama call reads the current run
state + the last 10 SIE reflections + the last 5 failure modes + the event stream, and -- if the
model emits a non-empty sentence -- surfaces an "something feels off" signal. At most once per run.

Pure, injectable core: ``build_prompt(state, reflections, failure_modes, events)`` and
``maybe_fire(state, *, reflections, failure_modes, chat, already_fired)``. The orchestrator fires
it OFF-THREAD so it never blocks the run loop (see run_phase_mixin._maybeInstinct).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  NightclawInstinct  -- Periodic 'something feels off' pattern layer
DEPENDS-ON: config, llm_io, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/notifications/test_instinct.py
"""
from __future__ import annotations

from typing import Callable, Optional

import config
import llm_io

LOG = config.getLogger("instinct")


def _defaultChat(system: str, user: str) -> str:  # pragma: no cover -- needs live Ollama
    client = llm_io.getClient()
    resp = client.chat(model=config.BRIEF_MODEL,
                       messages=[{"role": "system", "content": system},
                                 {"role": "user", "content": user}],
                       options={"num_ctx": config.OLLAMA_NUM_CTX},
                       keep_alive=config.OLLAMA_KEEP_ALIVE)
    return llm_io.responseText(resp)


class NightclawInstinct:
    """Periodic 'something feels off' pattern layer. At most one signal per run."""

    def build_prompt(self, state, *, reflections: list, failure_modes: list,
                     events: list) -> tuple[str, str]:
        subs = [s for s in state.subtasks if s.get("status") != "removed"]
        done = sum(1 for s in subs if s.get("status") == "done")
        lines = [
            f"GOAL: {state.meta.get('goal_raw','')}",
            f"STATUS: {state.meta.get('status','?')} | PROGRESS: {done}/{max(len(subs),1)}",
            "SUBTASKS:",
        ]
        for s in subs[:20]:
            lines.append(f"  {s['subtask_id']} [{s.get('status')}] {s.get('title','')}")
        lines.append("RECENT REFLECTIONS:")
        for r in (reflections or [])[-10:]:
            lines.append(f"  - {r.get('approach') or r.get('reusable_recipe') or ''}")
        lines.append("RECENT FAILURE MODES:")
        for f in (failure_modes or [])[:5]:
            lines.append(f"  - {f.get('taxonomy_class','')}: {f.get('root_cause','')}")
        evs = events if events else [n.get("kind", "") for n in (state.data.get("notifications") or [])[-8:]]
        lines.append("EVENT STREAM: " + ", ".join(str(e) for e in evs[-12:]))
        return config.INSTINCT_SYSTEM_PROMPT, "\n".join(lines)

    def maybe_fire(self, state, *, reflections: Optional[list] = None,
                   failure_modes: Optional[list] = None,
                   chat: Optional[Callable[[str, str], str]] = None,
                   already_fired: bool = False) -> Optional[str]:
        """Return the instinct sentence, or None (already fired this run / empty / offline)."""
        if already_fired or (state.meta.get("instinct_flags") or []):
            return None
        if reflections is None or failure_modes is None:
            reflections, failure_modes = self._defaultExperience()
        chat = chat or _defaultChat
        try:
            system, user = self.build_prompt(state, reflections=reflections,
                                             failure_modes=failure_modes, events=[])
            out = (chat(system, user) or "").strip()
            return out or None
        except Exception:  # noqa: BLE001 -- instinct is best-effort; silence on any failure
            LOG.debug("instinct maybe_fire failed (ignored)", exc_info=True)
            return None

    @staticmethod
    def _defaultExperience() -> tuple[list, list]:  # pragma: no cover -- reads the ledger
        try:
            from memory import experience
            return experience.fetch_reflections()[-10:], experience.fetch_failure_modes()[:5]
        except Exception:  # noqa: BLE001
            return [], []
