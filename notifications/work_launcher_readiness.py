"""External-project readiness preflight for the /work launcher (split from work_launcher.py).

A cohesive, dependency-light slice: given a WorkRequest targeting an external ``work_dir``,
warn (never block) about setup gaps that would degrade PR output -- missing git, not a repo,
no ``origin`` remote, no ``gh`` on PATH. Kept out of the launcher facade so the latter stays
under the modularity size budget. Sub-module rule: this file does NOT import from its facade
(the ``WorkRequest`` annotation is a string under ``from __future__ import annotations``, so it
is never evaluated at runtime -- no circular import).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  externalReadiness(req) -> list[str]  -- Warn about external-project setup gaps that degrade PR output, without blocking launch.
DEPENDS-ON: config, platform_core (none), stdlib
SIDE-EFFECTS: spawns git subprocesses (read-only) in the target work_dir
RUN/TEST: python -m pytest tests/execution/test_work_launcher.py
"""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import config


def externalReadiness(req) -> list[str]:
    """Warn about external-project setup gaps that degrade PR output, without blocking launch."""
    if not req.work_dir:
        return []
    work = Path(req.work_dir).resolve()
    if work == config.PROJECT_ROOT.resolve():
        return []
    if not shutil.which("git"):
        return ["External project: git is not installed, so PR output will be skipped."]
    warnings: list[str] = []
    env = os.environ.copy()
    env["GIT_TERMINAL_PROMPT"] = "0"

    def git(*args: str) -> subprocess.CompletedProcess:
        return subprocess.run(
            ["git", *args],
            cwd=str(work),
            capture_output=True,
            text=True,
            # Pin UTF-8 so non-ASCII git output never crashes the reader thread (cp1252 on
            # Windows); mirrors platform_core.core.git_io.runTool.
            encoding="utf-8",
            errors="replace",
            stdin=subprocess.DEVNULL,
            env=env,
            timeout=config.GIT_TIMEOUT_SECONDS,
        )

    try:
        inside = git("rev-parse", "--is-inside-work-tree")
        if inside.returncode != 0 or "true" not in (inside.stdout or "").lower():
            return ["External project: not a git repo, so the run can edit files but cannot open a PR."]
        remote = git("remote", "get-url", "origin")
        if remote.returncode != 0 or not (remote.stdout or "").strip():
            warnings.append("External project: no `origin` remote, so PR push/create will be skipped.")
    except subprocess.TimeoutExpired:
        warnings.append("External project: git preflight timed out; PR output may be skipped.")
    except Exception as e:  # noqa: BLE001
        warnings.append(f"External project: git preflight failed ({e}); PR output may be skipped.")
    if not shutil.which("gh"):
        warnings.append("External project: `gh` is not on PATH, so GitHub PR creation will be skipped.")
    return warnings
