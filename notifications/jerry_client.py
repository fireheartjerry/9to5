"""jerry_client -- thin, zero-dependency bridge from 9to5 to the Jerry decision service.

The Jerry manager model (a fine-tuned clone of the operator's gate decisions) runs
as a localhost HTTP service in the WSL GPU venv (manager_data/scripts/jerry_serve.py).
This client is pure stdlib so it imports cleanly inside the 9to5 bot env with no
torch/unsloth. It NEVER raises and NEVER blocks the run: any failure -> returns
None, and the caller falls back to the normal human Discord gate.

Used in SHADOW MODE first (predict + log, human still decides). Autonomy is gated
on the agreement the shadow log measures.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  buildGateContext(gate: str, state) -> dict  -- Summarize TaskState into the compact context the Jerry service expects.
  decide(gate: str, state, *, timeout: float=6.0) -> Optional[dict]  -- Ask the Jerry service for a verb
  advise(gate: str, state, *, timeout: float=6.0) -> Optional[str]  -- Advisor role: a one-line second opinion to inject into the Ollama brain's
  recordOutcome(gate: str, predicted: Optional[dict], human_verb: str) -> None  -- Append a shadow-mode comparison line (model vs human)
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: appends to logs/jerry_shadow.jsonl
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import json
import os
import urllib.request
from datetime import datetime
from pathlib import Path
from typing import Optional

SERVICE_URL = os.getenv("JERRY_URL", "http://127.0.0.1:8008")
SHADOW_LOG = Path(__file__).resolve().parent.parent / "logs" / "jerry_shadow.jsonl"


def buildGateContext(gate: str, state) -> dict:
    """Summarize TaskState into the compact context the Jerry service expects."""
    try:
        m = getattr(state, "meta", {}) or {}
        subs = [s for s in (getattr(state, "subtasks", []) or [])
                if s.get("status") != "removed"]
        done = sum(1 for s in subs if s.get("status") == "done")
        total = max(len(subs), 1)
        cur = next((s for s in subs if s.get("status") == "in_progress"), None) \
            or next((s for s in subs if s.get("status") == "pending"), None)
        data = getattr(state, "data", {}) or {}
        sub_lines, errors = [], []
        for s in subs[:12]:
            vr = s.get("verify_result") or {}
            mark = "PASS" if vr.get("passed") else ("FAIL" if vr else "")
            sub_lines.append(f"{s.get('subtask_id','?')} [{s.get('status','?')}] {mark} "
                             f"{s.get('title','')}".strip())
            if vr and not vr.get("passed"):
                msg = str(vr.get("summary") or vr.get("error") or "verification failed")
                errors.append(f"{s.get('subtask_id','?')}: {msg}"[:200])
        events = []
        for n in (data.get("notifications", []) or [])[-8:]:
            events.append(f"{n.get('kind','event')}: {str(n.get('text',''))[:120]}")
        for a in (data.get("adversary_reviews", []) or [])[-3:]:
            events.append(f"adversary[{a.get('trigger_reason','?')}] -> {a.get('verdict','?')}")
        return {
            "goal": m.get("goal_raw", ""),
            "status": m.get("status", "?"),
            "progress": f"{done}/{total}",
            "current": (f"{cur['subtask_id']} {cur.get('title','')}" if cur else ""),
            "subtasks": sub_lines, "events": events, "errors": errors,
        }
    except Exception:
        return {"goal": "", "status": "?", "progress": "?", "current": "",
                "subtasks": [], "events": [], "errors": []}


def decide(gate: str, state, *, timeout: float = 6.0) -> Optional[dict]:
    """Ask the Jerry service for a verb. Returns {verb,message,confidence} or None.

    None means 'service unavailable / undecided' -> caller uses the human gate.
    """
    try:
        ctx = buildGateContext(gate, state)
        body = json.dumps({"gate": gate, "context": ctx}).encode("utf-8")
        req = urllib.request.Request(f"{SERVICE_URL}/decide", data=body, method="POST",
                                     headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            out = json.loads(resp.read().decode("utf-8"))
        if isinstance(out, dict) and out.get("verb") and out.get("verb") != "none":
            return out
        return None
    except Exception:
        return None


def advise(gate: str, state, *, timeout: float = 6.0) -> Optional[str]:
    """Advisor role: a one-line second opinion to inject into the Ollama brain's
    prompt. Returns None if the service is down/undecided (brain proceeds as normal).
    The brain remains the decider; this is advisory context only."""
    out = decide(gate, state, timeout=timeout)
    if not out:
        return None
    return (f"would lean '{out.get('verb')}' "
            f"(confidence {out.get('confidence')}): {out.get('message', '')[:300]}")


def recordOutcome(gate: str, predicted: Optional[dict], human_verb: str) -> None:
    """Append a shadow-mode comparison line (model vs human). Never raises."""
    try:
        rec = {
            "ts": datetime.now().isoformat(timespec="seconds"),
            "gate": gate,
            "model_verb": (predicted or {}).get("verb"),
            "model_confidence": (predicted or {}).get("confidence"),
            "model_message": (predicted or {}).get("message", "")[:200],
            "human_verb": human_verb,
            "agreed": bool(predicted) and (predicted.get("verb") == human_verb),
        }
        SHADOW_LOG.parent.mkdir(parents=True, exist_ok=True)
        with SHADOW_LOG.open("a", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
    except Exception:
        pass
