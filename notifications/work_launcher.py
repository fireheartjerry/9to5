"""Pure launcher core for the Discord /work command. No discord import -> unit-testable.
Builds an argv for main.py and spawns it as a detached child so the gateway stays
responsive and a bot restart never kills an in-flight run.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  WorkRequest
  parseHours(raw) -> float  -- Tolerant parse ('2', '2h', '1.5')
  validate(req: WorkRequest) -> list[str]
  externalReadiness(req: WorkRequest) -> list[str]  -- Warn about external-project setup gaps that degrade PR output, without blocking launch.
  buildArgv(req: WorkRequest) -> list[str]
  prepareExternalRepo(req: WorkRequest) -> None  -- Clone repo_url into a managed workspace and mutate req.work_dir for this launch.
  activeRun() -> Optional[TaskState]  -- The latest task iff it's still active
  newestTaskSince(ts: float) -> Optional[str]  -- task_id of the newest state file created at/after `ts` (with ~2s mtime fuzz for filesys…
  spawn(req: WorkRequest) -> int
  buildResumeArgv(task_id: str) -> list[str]
  taskExists(task_id: str) -> bool
  spawnResume(task_id: str) -> int
  launchOrError(req: WorkRequest) -> str  -- Validate -> block-if-active -> spawn -> confirm
  resumeOrError(task_id: str) -> str  -- Resume an existing task by id (block if a run is active)
DEPENDS-ON: config, notifications.commands, platform_core.ops.external_project, platform_core.orchestration, platform_core.runtime.control, state.task
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_work_launcher.py
"""
from __future__ import annotations

import math
import os
import shutil
import subprocess
import sys
import time
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Optional

import config
from notifications import commands
from platform_core.orchestration import work_profile
from state.task import TaskState

LOG = config.getLogger("work_launcher")

# Test-mode guard for the ONLY place that launches real detached `main.py` runs.
# Without this, any test that reaches the spawn path (directly, or transitively via the
# SIE self-play step -> work_launcher.spawn) starts a REAL orchestrator process that
# survives the test, edits the repo, and -- because the child runs its own post-run SIE
# maintenance in-window -- recursively spawns MORE runs. The guard makes _spawnArgv a
# no-op returning a sentinel pid whenever a test runner is active or NINE_TO_FIVE_TEST_MODE
# is set. Production never imports unittest/pytest and never sets the var, so real runs are
# unaffected. Set NINE_TO_FIVE_TEST_MODE=0 to force the real path (the spawn argv tests do).
_SPAWN_BLOCKED_PID: int = -1


def _spawnBlocked() -> bool:
    """True when a real detached run must NOT be launched (unit/CI context)."""
    env = os.getenv("NINE_TO_FIVE_TEST_MODE", "").strip().lower()
    if env in {"0", "false", "no", "off"}:
        return False                       # explicit opt-out: tests that assert the real Popen path
    if env in {"1", "true", "yes", "on"}:
        return True
    # env unset -> auto-detect a live test runner so a forgotten guard never spawns a real run.
    # Safe: no production module imports unittest/pytest (only test modules do).
    return "unittest" in sys.modules or "pytest" in sys.modules

HOURS_MIN: float = 0.1
HOURS_MAX: float = 24.0
MAX_PARALLEL: int = 4
MAX_GOAL_CHARS: int = 6000
VALID_MODES = ("watch", "gated")


@dataclass
class WorkRequest:
    goal: str
    hours: float = 1.0
    mode: str = "watch"
    parallel: int = 1
    work_dir: Optional[str] = None
    repo_url: Optional[str] = None
    repo_ref: Optional[str] = None
    no_pr: bool = False
    night_mode: bool = False
    work_profile: Optional[str] = None
    sim: bool = False   # token-light: --sim-run (simulation doubles over live surfaces, zero API)


def parseHours(raw) -> float:
    """Tolerant parse ('2', '2h', '1.5'); empty/invalid -> 1.0; clamp to [HOURS_MIN, HOURS_MAX]."""
    if raw is None:
        return 1.0
    if isinstance(raw, (int, float)):
        val = float(raw)
    else:
        s = str(raw).strip().lower().rstrip("h").strip()
        try:
            val = float(s)
        except ValueError:
            return 1.0
    if not math.isfinite(val):
        return 1.0
    return max(HOURS_MIN, min(HOURS_MAX, val))


def validate(req: WorkRequest) -> list[str]:
    errs: list[str] = []
    if not (req.goal or "").strip():
        errs.append("Goal is required.")
    if len((req.goal or "")) > MAX_GOAL_CHARS:
        errs.append(f"Goal too long (>{MAX_GOAL_CHARS} chars).")
    if not (HOURS_MIN <= req.hours <= HOURS_MAX):
        errs.append(f"Hours must be between {HOURS_MIN} and {HOURS_MAX}.")
    if req.mode not in VALID_MODES:
        errs.append(f"Mode must be one of {VALID_MODES}.")
    if not (1 <= req.parallel <= MAX_PARALLEL):
        errs.append(f"Parallel must be between 1 and {MAX_PARALLEL}.")
    if req.repo_url and req.work_dir:
        errs.append("repo_url and work_dir are mutually exclusive.")
    if req.repo_ref and not req.repo_url:
        errs.append("repo_ref requires repo_url.")
    if req.work_dir and not Path(req.work_dir).is_dir():
        errs.append(f"work_dir does not exist or is not a directory: {req.work_dir}")
    if req.work_profile:
        try:
            work_profile.resolve(req.work_profile)
        except ValueError as e:
            errs.append(str(e))
    return errs


def externalReadiness(req: WorkRequest) -> list[str]:
    """Warn about external-project setup gaps that degrade PR output, without blocking launch."""
    if not req.work_dir:
        return []
    work = Path(req.work_dir).resolve()
    if work == config.PROJECT_ROOT.resolve():
        return []
    if not shutil.which("git"):
        return ["External project: git is not installed, so PR output will be skipped."]
    warnings: list[str] = []
    env = os.environ.copy()
    env["GIT_TERMINAL_PROMPT"] = "0"

    def git(*args: str) -> subprocess.CompletedProcess:
        return subprocess.run(["git", *args], cwd=str(work), capture_output=True, text=True,
                              stdin=subprocess.DEVNULL, env=env, timeout=config.GIT_TIMEOUT_SECONDS)

    try:
        inside = git("rev-parse", "--is-inside-work-tree")
        if inside.returncode != 0 or "true" not in (inside.stdout or "").lower():
            return ["External project: not a git repo, so the run can edit files but cannot open a PR."]
        remote = git("remote", "get-url", "origin")
        if remote.returncode != 0 or not (remote.stdout or "").strip():
            warnings.append("External project: no `origin` remote, so PR push/create will be skipped.")
    except subprocess.TimeoutExpired:
        warnings.append("External project: git preflight timed out; PR output may be skipped.")
    except Exception as e:  # noqa: BLE001
        warnings.append(f"External project: git preflight failed ({e}); PR output may be skipped.")
    if not shutil.which("gh"):
        warnings.append("External project: `gh` is not on PATH, so GitHub PR creation will be skipped.")
    return warnings


def buildArgv(req: WorkRequest) -> list[str]:
    argv = [
        str(config.VENV_PYTHON), str(config.PROJECT_ROOT / "main.py"),
        "--goal", req.goal,
        "--hours", str(req.hours),
        "--auto-approve",
        "--mode", req.mode,
        "--parallel", str(req.parallel),
    ]
    # Nightclaw's unattended/night runs should still create a review surface at the end.
    # Keep the raw no_pr escape hatch for CLI/local callers, but never let night mode hide feedback.
    if req.no_pr and not req.night_mode:
        argv.append("--no-pr")
    if req.night_mode:
        argv.append("--night-mode")
    if req.sim:
        argv.append("--sim-run")
    if req.work_profile:
        argv += ["--work-profile", req.work_profile]
    if req.work_dir:
        argv += ["--work-dir", str(Path(req.work_dir).resolve())]
    if req.repo_url:
        argv += ["--repo-url", req.repo_url]
    if req.repo_ref:
        argv += ["--repo-ref", req.repo_ref]
    return argv


def prepareExternalRepo(req: WorkRequest) -> None:
    """Clone repo_url into a managed workspace and mutate req.work_dir for this launch."""
    if not req.repo_url:
        return
    from platform_core.ops.external_project import cloneRepo
    req.work_dir = str(cloneRepo(req.repo_url, req.repo_ref))
    req.repo_url = None
    req.repo_ref = None


def activeRun() -> Optional[TaskState]:
    """The latest task iff it's still active. Auto-aborts stale tasks whose process died
    without updating state (e.g. killed mid-elaboration, left in 'created'/'planning')."""
    state = commands.resolveTargetTask()
    if not commands.isRunActive(state):
        return None
    if _isStale(state):
        try:
            # The orchestrator process is gone -> also request a real abort on the bus (belt and
            # suspenders) before marking the JSON aborted, then let a fresh run take over.
            from platform_core.runtime.control import ControlBus
            ControlBus(state.task_id).requestAbort()
            state.setStatus("aborted")
            LOG.warning("auto-aborted stale task %s (process dead / no heartbeat)", state.task_id[:8])
        except Exception:  # noqa: BLE001
            pass
        return None
    return state


def _runPidAlive(state: TaskState) -> Optional[bool]:
    """Tri-state liveness of the orchestrator process recorded in the task: True alive, False the
    PID is gone, None when no/garbage PID was recorded (caller falls back to the mtime heuristic).
    main.py stamps meta['run_pid'] before runFull, so a LIVE run -- even one quiet for >30min during
    a long subtask or a Pro token-limit pause -- is never misread as stale and double-spawned over."""
    pid = (getattr(state, "meta", {}) or {}).get("run_pid")
    if not isinstance(pid, int) or pid <= 0:
        return None
    try:
        import psutil
        return psutil.pid_exists(pid)
    except Exception:  # noqa: BLE001 -- psutil missing/errored -> unknown, fall back to mtime
        return None


# A task is stale if its state file hasn't been touched in this many seconds.
# 'created' tasks (died in elaboration) stale out faster; executing tasks use RUN_STALL_SECONDS.
_STALE_CREATED_SECONDS: int = 300    # 5 min — elaboration should never take this long
_STALE_SECONDS: int = int(getattr(config, "RUN_STALL_SECONDS", 1800))


def _isStale(state: Optional[TaskState]) -> bool:
    """True when the orchestrator process is dead. PID liveness is authoritative; the mtime
    heuristic is only a fallback for legacy tasks with no recorded run_pid."""
    if state is None:
        return False
    alive = _runPidAlive(state)
    if alive is True:
        return False            # process is running -> NEVER stale, no matter how quiet
    if alive is False:
        return True             # the recorded orchestrator PID is gone -> the run is dead
    try:                        # no/unknown PID -> fall back to the mtime heuristic
        mtime = (config.STATE_DIR / f"{state.task_id}.json").stat().st_mtime
        age = time.time() - mtime
        cutoff = (_STALE_CREATED_SECONDS if state.meta.get("status") in ("created", "planning")
                  else _STALE_SECONDS)
        return age > cutoff
    except OSError:
        return False


def newestTaskSince(ts: float) -> Optional[str]:
    """task_id of the newest state file created at/after `ts` (with ~2s mtime fuzz for filesystem coarseness) (used to confirm a launch)."""
    best_id, best_m = None, ts - 1
    try:
        for f in config.STATE_DIR.glob("*.json"):
            m = f.stat().st_mtime
            if m >= ts - 2.0 and m > best_m:
                best_m, best_id = m, f.stem
    except OSError:
        return None
    return best_id


def _spawnArgv(argv: list[str], tag: str) -> int:
    """Spawn argv as a DETACHED child (survives a bot restart). Returns the child PID.

    In a test context this is a hard no-op (returns ``_SPAWN_BLOCKED_PID``) so a unit test
    can never start a real ``main.py`` run -- see ``_spawnBlocked``."""
    if _spawnBlocked():
        LOG.warning("spawn '%s' suppressed (test mode) -- not launching a real run: %s",
                    tag, " ".join(argv[:3]))
        return _SPAWN_BLOCKED_PID
    config.LOG_PATH.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().astimezone().strftime("%Y%m%d-%H%M%S")
    logfile = open(config.LOG_PATH / f"{tag}-{stamp}.log", "a", encoding="utf-8", errors="replace")
    creationflags = 0
    if os.name == "nt":
        creationflags = subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP
    proc = subprocess.Popen(
        argv, cwd=str(config.PROJECT_ROOT),
        stdin=subprocess.DEVNULL, stdout=logfile, stderr=subprocess.STDOUT,
        close_fds=True, creationflags=creationflags,
    )
    logfile.close()   # child keeps its own duplicated handle; release the parent's copy
    LOG.info("Spawned %s pid=%s", tag, proc.pid)
    return proc.pid


def spawn(req: WorkRequest) -> int:
    return _spawnArgv(buildArgv(req), "work")


def buildResumeArgv(task_id: str) -> list[str]:
    return [str(config.VENV_PYTHON), str(config.PROJECT_ROOT / "main.py"), "--resume", task_id]


def taskExists(task_id: str) -> bool:
    return (config.STATE_DIR / f"{task_id}.json").exists()


def spawnResume(task_id: str) -> int:
    return _spawnArgv(buildResumeArgv(task_id), "resume")


def launchOrError(req: WorkRequest) -> str:
    """Validate -> block-if-active -> spawn -> confirm. Returns the user-facing message.
    BLOCKING (Popen + up to ~10s poll); async callers must run via asyncio.to_thread."""
    errs = validate(req)
    if errs:
        return "❌ " + "  ".join(errs)
    active = activeRun()
    if active is not None:
        return (f"⛔ A run is already active (`{active.task_id[:8]}` · "
                f"`{active.meta.get('status')}`). Abort it first.")
    try:
        prepareExternalRepo(req)
    except Exception as e:  # noqa: BLE001
        LOG.exception("external repo clone failed")
        return f"❌ Clone failed: {e}"
    t0 = time.time()
    try:
        pid = spawn(req)
    except Exception as e:  # noqa: BLE001
        LOG.exception("spawn failed")
        return f"❌ Launch failed: {e}"
    task_id = None
    for _ in range(20):
        task_id = newestTaskSince(t0)
        if task_id:
            break
        time.sleep(0.5)
    web = f"http://127.0.0.1:{config.WEB_DASHBOARD_PORT}/"
    if task_id:
        msg = (f"✅ Launched run `{task_id[:8]}` (pid {pid}) · mode `{req.mode}` · "
               f"{req.hours}h · parallel {req.parallel}\n{web}")
    else:
        msg = (f"✅ Launch started (pid {pid}) · mode `{req.mode}` · {req.hours}h. "
               f"If no dashboard appears shortly, check `logs\\work-*.log`.\n{web}")
    warnings = externalReadiness(req)
    if warnings:
        msg += "\n\n" + "\n".join(f"⚠️ {w}" for w in warnings)
    if req.work_dir and Path(req.work_dir).resolve() != config.PROJECT_ROOT.resolve():
        msg += f"\n\nWorking dir: `{str(Path(req.work_dir).resolve())[:300]}`"
    try:
        prof = work_profile.resolve(req.work_profile)
        msg += f"\n\nProfile: `{prof.preset}` - {prof.summary()}"
    except Exception:  # noqa: BLE001
        pass
    return msg


def resumeOrError(task_id: str) -> str:
    """Resume an existing task by id (block if a run is active). Returns the user message."""
    if not taskExists(task_id):
        return f"❌ No such task `{task_id}`."
    active = activeRun()
    if active is not None:
        return f"⛔ A run is already active (`{active.task_id[:8]}`). Abort it first."
    try:
        pid = spawnResume(task_id)
    except Exception as e:  # noqa: BLE001
        LOG.exception("resume spawn failed")
        return f"❌ Resume failed: {e}"
    web = f"http://127.0.0.1:{config.WEB_DASHBOARD_PORT}/"
    return f"♻️ Resuming `{task_id[:8]}` (pid {pid})\n{web}"
