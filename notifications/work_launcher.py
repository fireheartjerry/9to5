# Test-mode guard for the ONLY place that launches real detached `main.py` runs.
# Without this, any test that reaches the spawn path (directly, or transitively via the
# SIE self-play step -> work_launcher.spawn) starts a REAL orchestrator process that
# survives the test, edits the repo, and -- because the child runs its own post-run SIE
# maintenance in-window -- recursively spawns MORE runs. The guard makes _spawnArgv a
# no-op returning a sentinel pid whenever a test runner is active or NINE_TO_FIVE_TEST_MODE
# is set. Production never imports pytest and never sets the var, so real runs are
# unaffected. Set NINE_TO_FIVE_TEST_MODE=0 to force the real path (the spawn argv tests do).
_SPAWN_BLOCKED_PID: int = -1


def _spawnBlocked() -> bool:
    """True when a real detached run must NOT be launched (unit/CI context)."""
    env = os.getenv("NINE_TO_FIVE_TEST_MODE", "").strip().lower()
    if env in {"0", "false", "no", "off"}:
        return False  # explicit opt-out: tests that assert the real Popen path
    if env in {"1", "true", "yes", "on"}:
        return True
    # env unset -> block only under a REAL test runner. NOT "unittest" in sys.modules (numpy.testing
    # / torch import it at load, so real runs carry it -- see discord_client). Detect pytest instead.
    return os.getenv("PYTEST_CURRENT_TEST") is not None or "pytest" in sys.modules


HOURS_MIN: float = 0.1
HOURS_MAX: float = 24.0
MAX_PARALLEL: int = 4
MAX_GOAL_CHARS: int = 6000
VALID_MODES = ("watch", "gated")


@dataclass
class WorkRequest:
    goal: str
    hours: float = 1.0
    mode: str = "watch"
    parallel: int = 1
    work_dir: Optional[str] = None
    repo_url: Optional[str] = None
    repo_ref: Optional[str] = None
    no_pr: bool = False
    night_mode: bool = False
    work_profile: Optional[str] = None
    launch_id: Optional[str] = None  # handshake token (set by launchOrError)
    sim: bool = False  # token-light: --sim-run (simulation doubles over live surfaces, zero API)


def parseHours(raw) -> float:
    """Tolerant parse ('2', '2h', '1.5'); empty/invalid -> 1.0; clamp to [HOURS_MIN, HOURS_MAX]."""
    if raw is None:
        return 1.0
    if isinstance(raw, (int, float)):
        val = float(raw)
    else:
        s = str(raw).strip().lower().rstrip("h").strip()
        try:
            val = float(s)
        except ValueError:
            return 1.0
    if not math.isfinite(val):
        return 1.0
    return max(HOURS_MIN, min(HOURS_MAX, val))


def validate(req: WorkRequest) -> list[str]:
    errs: list[str] = []
    if not (req.goal or "").strip():
        errs.append("Goal is required.")
    if len((req.goal or "")) > MAX_GOAL_CHARS:
        errs.append(f"Goal too long (>{MAX_GOAL_CHARS} chars).")
    if not (HOURS_MIN <= req.hours <= HOURS_MAX):
        errs.append(f"Hours must be between {HOURS_MIN} and {HOURS_MAX}.")
    if req.mode not in VALID_MODES:
        errs.append(f"Mode must be one of {VALID_MODES}.")
    if not (1 <= req.parallel <= MAX_PARALLEL):
        errs.append(f"Parallel must be between 1 and {MAX_PARALLEL}.")
    if req.repo_url and req.work_dir:
        errs.append("repo_url and work_dir are mutually exclusive.")
    if req.repo_ref and not req.repo_url:
        errs.append("repo_ref requires repo_url.")
    if req.work_dir and not Path(req.work_dir).is_dir():
        errs.append(f"work_dir does not exist or is not a directory: {req.work_dir}")
    if req.work_profile:
        try:
            work_profile.resolve(req.work_profile)
        except ValueError as e:
            errs.append(str(e))
    return errs


def _pythonExe() -> str:
    """Interpreter to spawn child ``main.py`` runs with: the venv python when it exists
    (absolute, dep-complete), else the currently-running interpreter (``sys.executable``).

    ``config.VENV_PYTHON`` is ``<PROJECT_ROOT>/venv/Scripts/python.exe``; in a git worktree
    or a checkout without a ``venv/`` that path does not exist, and ``subprocess.Popen``
    raised WinError 2 (executable not found). ``sys.executable`` is always present and
    carries this process's deps, so it is the correct fallback. Mirrors the existing
    ``executor_env._hookInterpreter`` pattern."""
    # os.path.exists returns False (never raises) on a broken/malformed path, so no swallow needed.
    venv = str(config.VENV_PYTHON)
    return venv if os.path.exists(venv) else sys.executable


def buildArgv(req: WorkRequest) -> list[str]:
    argv = [
        _pythonExe(),
        str(config.PROJECT_ROOT / "main.py"),
        "--goal",
        req.goal,
        "--hours",
        str(req.hours),
        "--auto-approve",
        "--mode",
        req.mode,
        "--parallel",
        str(req.parallel),
    ]
    # Nightclaw's unattended/night runs should still create a review surface at the end.
    # Keep the raw no_pr escape hatch for CLI/local callers, but never let night mode hide feedback.
    if req.no_pr and not req.night_mode:
        argv.append("--no-pr")
    if req.night_mode:
        argv.append("--night-mode")
    if req.sim:
        argv.append("--sim-run")
    if req.work_profile:
        argv += ["--work-profile", req.work_profile]
    if req.work_dir:
        argv += ["--work-dir", str(Path(req.work_dir).resolve())]
    if req.repo_url:
        argv += ["--repo-url", req.repo_url]
    if req.repo_ref:
        argv += ["--repo-ref", req.repo_ref]
    if req.launch_id:
        argv += ["--launch-id", req.launch_id]
    return argv


def prepareExternalRepo(req: WorkRequest) -> None:
    """Clone repo_url into a managed workspace and mutate req.work_dir for this launch."""
    if not req.repo_url:
        return
    from platform_core.ops.external_project import cloneRepo

    req.work_dir = str(cloneRepo(req.repo_url, req.repo_ref))
    req.repo_url = None
    req.repo_ref = None


def activeRun() -> Optional[TaskState]:
    """The latest task iff it's still active. A stale task (its orchestrator process is
    provably dead) is reaped via the bus + the single-writer escape hatch -- this bot-process
    module NEVER writes task JSON directly."""
    state = commands.resolveTargetTask()
    if not commands.isRunActive(state):
        return None
    if _isStale(state):
        _reapStale(state)
        return None
    return state


def _isStale(state: Optional[TaskState]) -> bool:
    """True when the orchestrator process behind this task is provably dead: no fresh
    heartbeat AND its recorded pid is gone (heartbeat.isRunAlive is the ONE liveness
    primitive -- the old mtime heuristic is deleted). A live run, even one quiet for
    >30 min during a long subtask, is never misread as stale."""
    if state is None:
        return False
    from platform_core.runtime.heartbeat import isRunAlive

    return not isRunAlive(state.task_id)


def _reapStale(state: TaskState) -> None:
    """Dead-run cleanup from the bot process: request abort on the bus (belt + suspenders,
    it persists independently of task JSON), leave a breadcrumb op, then finalize through
    task_io.reapDeadRun -- which re-checks liveness and refuses unless the run is dead."""
    try:
        from platform_core.runtime.control import ControlBus
        from state import task_io

        bus = ControlBus(state.task_id)
        bus.requestAbort()
        bus.pushOp({"op": "mark_stale", "reason": "launcher: no heartbeat and pid dead"})
        reaped = task_io.reapDeadRun(state.task_id)
        LOG.warning("stale task %s: abort requested on bus, reaped=%s", state.task_id[:8], reaped)
    except Exception:  # noqa: BLE001 -- cleanup is best-effort; the next poll retries
        LOG.warning("stale-task reap failed (ignored)", exc_info=True)


def waitForLaunch(launch_id: str, *, timeout_s: float = 10.0, poll_s: float = 0.5) -> Optional[str]:
    """Launch handshake: poll state/launch/<launch_id>.json (written by main.py --launch-id)
    for the spawned run's task_id. Replaces newest-state-file polling, which could confirm
    the WRONG task when two writers raced."""
    p = config.LAUNCH_DIR / f"{launch_id}.json"
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        data = fsio.loadJson(p, default=None)
        if isinstance(data, dict) and data.get("task_id"):
            return str(data["task_id"])
        time.sleep(poll_s)
    return None


def _spawnArgv(argv: list[str], tag: str) -> int:
    """Spawn argv as a DETACHED child (survives a bot restart). Returns the child PID.

    In a test context this is a hard no-op (returns ``_SPAWN_BLOCKED_PID``) so a unit test
    can never start a real ``main.py`` run -- see ``_spawnBlocked``."""
    if _spawnBlocked():
        LOG.warning(
            "spawn '%s' suppressed (test mode) -- not launching a real run: %s", tag, " ".join(argv[:3])
        )
        return _SPAWN_BLOCKED_PID
    config.LOG_PATH.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().astimezone().strftime("%Y%m%d-%H%M%S")
    logfile = open(config.LOG_PATH / f"{tag}-{stamp}.log", "a", encoding="utf-8", errors="replace")
    creationflags = 0
    if os.name == "nt":
        creationflags = subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP
    proc = subprocess.Popen(
        argv,
        cwd=str(config.PROJECT_ROOT),
        stdin=subprocess.DEVNULL,
        stdout=logfile,
        stderr=subprocess.STDOUT,
        close_fds=True,
        creationflags=creationflags,
    )
    logfile.close()  # child keeps its own duplicated handle; release the parent's copy
    LOG.info("Spawned %s pid=%s", tag, proc.pid)
    return proc.pid


def spawn(req: WorkRequest) -> int:
    return _spawnArgv(buildArgv(req), "work")


def buildResumeArgv(task_id: str, retry_failed: bool = False) -> list[str]:
    argv = [_pythonExe(), str(config.PROJECT_ROOT / "main.py"), "--resume", task_id]
    if retry_failed:
        argv.append("--retry-failed")
    return argv


def taskExists(task_id: str) -> bool:
    """False for a non-UUID task_id, not just a missing file -- a raw path.exists() check let
    task_id="../user_prefs" resolve to (and confirm the existence of) an arbitrary file outside
    STATE_DIR (e.g. memory/user_prefs.py's real store), a path-traversal existence oracle
    reachable via the unauthenticated Discord /run and !resume commands."""
    from state.task_io import validateTaskId

    try:
        validateTaskId(task_id)
    except ValueError:
        return False
    return (config.STATE_DIR / f"{task_id}.json").exists()


def spawnResume(task_id: str, retry_failed: bool = False) -> int:
    return _spawnArgv(buildResumeArgv(task_id, retry_failed=retry_failed), "resume")


# Double-launch guard: an in-process lock (bot cogs + views can race) plus a cross-process
# O_EXCL sidecar so the check-active -> spawn -> confirm window is atomic even across a bot
# restart or a second launcher process.
_LAUNCH_LOCK = threading.Lock()


def _launchLockPath() -> Path:
    return config.LAUNCH_DIR / "launching.lock"


def _lockOwnerAlive(pid: int) -> bool:
    try:
        import psutil

        return psutil.pid_exists(pid)
    except Exception:  # noqa: BLE001 -- unknowable -> assume alive (never steal a live lock)
        return True


def _doLaunch(req: WorkRequest) -> "tuple[Optional[int], Optional[str], Optional[str]]":
    """Inside-the-lock launch body: returns (pid, task_id, error_message)."""
    active = activeRun()
    if active is not None:
        return (
            None,
            None,
            (
                f"⛔ A run is already active (`{active.task_id[:8]}` · "
                f"`{active.meta.get('status')}`). Abort it first."
            ),
        )
    try:
        prepareExternalRepo(req)
    except Exception as e:  # noqa: BLE001
        LOG.exception("external repo clone failed")
        return None, None, f"❌ Clone failed: {e}"
    req.launch_id = req.launch_id or uuid.uuid4().hex[:12]
    try:
        pid = spawn(req)
    except Exception as e:  # noqa: BLE001
        LOG.exception("spawn failed")
        return None, None, f"❌ Launch failed: {e}"
    return pid, waitForLaunch(req.launch_id), None


def launchOrError(req: WorkRequest) -> str:
    """Validate -> lock -> block-if-active -> spawn -> handshake-confirm. Returns the
    user-facing message. BLOCKING (Popen + up to ~10s handshake poll); async callers must
    run via asyncio.to_thread."""
    errs = validate(req)
    if errs:
        return "❌ " + "  ".join(errs)
    if not _LAUNCH_LOCK.acquire(blocking=False):
        return "⛔ Another launch is already in progress."
    try:
        if not fsio.tryAcquireLock(_launchLockPath(), stale_after=120.0, owner_alive=_lockOwnerAlive):
            return "⛔ Another launch is already in progress (cross-process lock held)."
        try:
            pid, task_id, err = _doLaunch(req)
        finally:
            fsio.releaseLock(_launchLockPath())
    finally:
        _LAUNCH_LOCK.release()
    if err:
        return err
    web = f"http://127.0.0.1:{config.WEB_DASHBOARD_PORT}/"
    if task_id:
        msg = (
            f"✅ Launched run `{task_id[:8]}` (pid {pid}) · mode `{req.mode}` · "
            f"{req.hours}h · parallel {req.parallel}\n{web}"
        )
    else:
        msg = (
            f"✅ Launch started (pid {pid}) · mode `{req.mode}` · {req.hours}h. "
            f"If no dashboard appears shortly, check `logs\\work-*.log`.\n{web}"
        )
    warnings = externalReadiness(req)
    if warnings:
        msg += "\n\n" + "\n".join(f"⚠️ {w}" for w in warnings)
    if req.work_dir and Path(req.work_dir).resolve() != config.PROJECT_ROOT.resolve():
        msg += f"\n\nWorking dir: `{str(Path(req.work_dir).resolve())[:300]}`"
    try:
        prof = work_profile.resolve(req.work_profile)
        msg += f"\n\nProfile: `{prof.preset}` - {prof.summary()}"
    except Exception:  # noqa: BLE001
        pass
    return msg


def resumeOrError(task_id: str, retry_failed: bool = False) -> str:
    """Resume an existing task by id (block if a run is active). Returns the user message.
    Shares the launch locks so a /work and a /resume can never double-spawn.
    retry_failed: also reset 'failed' subtasks back to 'pending' so they're retried -- opt-in,
    since a subtask that failed for a structural reason will just fail the same way again."""
    if not taskExists(task_id):
        return f"❌ No such task `{task_id}`."
    if not _LAUNCH_LOCK.acquire(blocking=False):
        return "⛔ Another launch is already in progress."
    try:
        if not fsio.tryAcquireLock(_launchLockPath(), stale_after=120.0, owner_alive=_lockOwnerAlive):
            return "⛔ Another launch is already in progress (cross-process lock held)."
        try:
            active = activeRun()
            if active is not None:
                return f"⛔ A run is already active (`{active.task_id[:8]}`). Abort it first."
            try:
                pid = spawnResume(task_id, retry_failed=retry_failed)
            except Exception as e:  # noqa: BLE001
                LOG.exception("resume spawn failed")
                return f"❌ Resume failed: {e}"
        finally:
            fsio.releaseLock(_launchLockPath())
    finally:
        _LAUNCH_LOCK.release()
    web = f"http://127.0.0.1:{config.WEB_DASHBOARD_PORT}/"
    suffix = " (retrying failed subtasks)" if retry_failed else ""
    return f"♻️ Resuming `{task_id[:8]}`{suffix} (pid {pid})\n{web}"
