"""The Cast -- the 9to5 agent roster for webhook identity overrides.

Each role maps to a persona ``{name, icon, color, avatar_url}``. Names are clean text
(no emoji -- webhook usernames can't render custom emoji anyway); the professional app-emoji
icon (the ``icon`` concept) is prefixed onto the message CONTENT by cast.speak. An optional
per-role avatar URL can be supplied via env (NIGHTCLAW_AVATAR_<ROLE>).

Pure data + lookup; no network, no discord.py.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  persona(role: str) -> dict  -- Resolve a role to its persona dict (falls back to Brain), with avatar_url filled in.
  roles() -> tuple
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_personas_archetypes.py
"""
from __future__ import annotations

import os

import config


def _avatar(role: str) -> str:
    return os.getenv(f"NIGHTCLAW_AVATAR_{role.upper()}", config.BRAND_ICON_URL or "")


# Clean text names (no emoji -- webhook usernames can't render custom emoji); the professional
# app-emoji icon is the ``icon`` concept, prefixed onto the message CONTENT by cast.speak.
CAST: dict[str, dict] = {
    "brain":        {"name": "Nightclaw · Brain",     "icon": "brain",     "color": 0x5865F2},
    "orchestrator": {"name": "Nightclaw · Brain",     "icon": "brain",     "color": 0x5865F2},
    "architect":    {"name": "Nightclaw · Architect", "icon": "architect", "color": 0x58A6FF},
    "planner":      {"name": "Nightclaw · Planner",   "icon": "plan",      "color": 0x58A6FF},
    "executor":     {"name": "Nightclaw · Executor",  "icon": "mode",      "color": 0x3FB950},
    "verifier":     {"name": "Nightclaw · Verifier",  "icon": "verify",    "color": 0x1ABC9C},
    "adversary":    {"name": "Nightclaw · Adversary", "icon": "adversary", "color": 0xDB6D28},
    "replanner":    {"name": "Nightclaw · Replanner", "icon": "replan",    "color": 0xBC8CFF},
    # Sci-fi archetype personas (Phase 5 / human-nature layer).
    # The Character Vector tunes expression within one archetype;
    # callers enumerate selectable voices via ARCHETYPES.
    "data":   {"name": "Nightclaw · Data",   "icon": "verify",    "color": 0xE3C15C},
    "tars":   {"name": "Nightclaw · TARS",   "icon": "adversary", "color": 0x8E9BAE},
    "jarvis": {"name": "Nightclaw · Jarvis", "icon": "mode",      "color": 0x43B581},
}

# Selectable sci-fi archetype voices (earnest/Data, dry-wit/TARS, warm/Jarvis).
ARCHETYPES: tuple[str, ...] = ("data", "tars", "jarvis")


def persona(role: str) -> dict:
    """Resolve a role to its persona dict (falls back to Brain), with avatar_url filled in."""
    key = (role or "").lower().strip()
    if key not in CAST:
        key = "brain"
    p = dict(CAST[key])
    p["avatar_url"] = _avatar(key)
    return p


def roles() -> tuple:
    return tuple(k for k in CAST if k != "orchestrator")
