"""SubprocessFeed -- tap a Claude subprocess's stdout stream in real time.

One feed is created per Claude subprocess attempt (in ``execute_mixin._runOneAttempt``).
Every stdout line is stored raw on the bus; lines that parse as Claude's JSONL event
format are turned into structured ``tool_use`` events with a human-readable, emoji-tagged
summary. A background heartbeat thread emits a liveness event every 30s while the process
runs, so a long-silent subprocess still shows a pulse on every surface.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  SubprocessFeed
DEPENDS-ON: notifications.event_bus
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/notifications/test_subprocess_feed.py
"""
from __future__ import annotations

import json
import threading
import time
from typing import Optional

from notifications.event_bus import Event, LiveEventBus

_HEARTBEAT_SECONDS = 30.0


class SubprocessFeed:
    def __init__(self, bus: LiveEventBus, sid: str, started_at: float,
                 *, heartbeat: bool = True, on_step=None) -> None:
        self.bus = bus
        self.sid = sid
        self.started_at = started_at
        self._tool_calls = 0
        self._step_idx = 0
        self._on_step = on_step
        self._stop = threading.Event()
        self._thread: Optional[threading.Thread] = None
        if heartbeat:
            self._thread = threading.Thread(target=self._beat_loop, name=f"feed-{sid}", daemon=True)
            self._thread.start()

    # ---- ingestion ------------------------------------------------------
    def consume(self, line: str) -> None:
        """Store the raw line, then emit a structured tool event if it parses."""
        self.bus.emit_raw(self.sid, line)
        event = self._parse(line)
        if event is not None:
            self._tool_calls += 1
            self.bus.emit(event)
            self._emit_step(event)

    def _emit_step(self, event: Event) -> None:
        """Tee the parsed tool call to the durable sink (journal/trajectory). Best-effort:
        a sink failure must never break the live feed."""
        if self._on_step is None:
            return
        try:
            data = event.data or {}
            self._on_step(self._step_idx, data.get("tool") or "tool",
                          event.text, data.get("input") or {})
            self._step_idx += 1
        except Exception:  # noqa: BLE001 -- the sink is best-effort, never blocks a run
            pass

    def stop(self) -> None:
        """Signal the heartbeat thread to exit (idempotent; safe to call repeatedly)."""
        self._stop.set()
        thread = self._thread
        if thread is not None and thread.is_alive() and thread is not threading.current_thread():
            thread.join(timeout=1.0)

    # ---- parsing --------------------------------------------------------
    def _parse(self, line: str) -> Optional[Event]:
        line = (line or "").strip()
        if not line or line[0] not in "{[":
            return None
        try:
            obj = json.loads(line)
        except Exception:  # noqa: BLE001 -- non-JSON stdout stays raw-only
            return None
        block = _first_tool_use(obj)
        if block is None:
            return None
        return self._tool_event(block.get("name") or "tool", block.get("input") or {})

    def _tool_event(self, name: str, tool_input: dict) -> Event:
        text = _summarize(name, tool_input)
        return Event(kind="tool_use", sid=self.sid, text=text,
                     data={"tool": name, "input": tool_input})

    # ---- heartbeat ------------------------------------------------------
    def _beat_loop(self) -> None:
        while not self._stop.wait(_HEARTBEAT_SECONDS):
            self._beat_once()

    def _beat_once(self) -> None:
        elapsed = int(time.monotonic() - self.started_at)
        self.bus.emit(Event(
            kind="heartbeat", sid=self.sid,
            text=f"⏱ {self.sid} · {elapsed}s · still running · {self._tool_calls} tool calls so far",
            data={"elapsed_s": elapsed, "tool_calls": self._tool_calls}))


def _first_tool_use(obj: object) -> Optional[dict]:
    """Find the first ``tool_use`` block in a Claude JSONL event (nested or flat)."""
    if isinstance(obj, dict):
        if obj.get("type") == "tool_use" and obj.get("name"):
            return obj
        content = (obj.get("message") or {}).get("content") if isinstance(obj.get("message"), dict) else None
        if isinstance(content, list):
            for item in content:
                if isinstance(item, dict) and item.get("type") == "tool_use":
                    return item
    return None


def _summarize(name: str, tool_input: dict) -> str:
    """Map a Claude tool call to a short, emoji-tagged, human-readable line."""
    path = tool_input.get("file_path") or tool_input.get("path") or ""
    if name == "Edit":
        return f"✏️ editing {path}"
    if name == "Write":
        return f"📝 writing {path}"
    if name == "Read":
        return f"👁 reading {path}"
    if name == "Bash":
        return f"⚡ bash: {str(tool_input.get('command') or '')[:70]}"
    if name == "Grep":
        return f"🔍 grep: {tool_input.get('pattern') or ''}"
    if name == "Glob":
        return f"🗂 glob: {tool_input.get('pattern') or ''}"
    if name in ("Agent", "Task"):
        return f"🤖 spawning agent: {str(tool_input.get('description') or '')[:60]}"
    return f"🔧 tool: {name}"
