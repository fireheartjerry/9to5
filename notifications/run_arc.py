"""Run narrative arc -- a living story of the run, not a log.

Beats accumulate in ``state.meta["arc"]`` at key phase transitions and read back as a
short chronicle. Surfaced as a collapsible web panel and posted on demand via ``!arc``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  append_beat(state: Any, text: str) -> None  -- Append a beat (``{text, at}``) to ``state.meta["arc"]`` and persist
  render_arc(state: Any) -> str  -- The arc as a readable story (one beat per line), newest last.
  beat_discovery(n: int, theme: str) -> str
  beat_architect(n: int) -> str
  beat_first_verify() -> str
  beat_replan(reason: str) -> str
  beat_complete(status: str, done: int, total: int, elapsed: str) -> str
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/control/test_run_arc.py
"""
from __future__ import annotations

from datetime import datetime
from typing import Any


def append_beat(state: Any, text: str) -> None:
    """Append a beat (``{text, at}``) to ``state.meta["arc"]`` and persist. Never raises."""
    try:
        meta = getattr(state, "meta", None)
        if not isinstance(meta, dict):
            return
        arc = meta.get("arc")
        if not isinstance(arc, list):
            arc = meta["arc"] = []
        arc.append({"text": str(text), "at": datetime.now().astimezone().strftime("%H:%M:%S")})
        save = getattr(state, "save", None)
        if callable(save):
            save()
    except Exception:  # noqa: BLE001 -- the arc is observability; never break a run
        pass


def render_arc(state: Any) -> str:
    """The arc as a readable story (one beat per line), newest last."""
    try:
        meta = getattr(state, "meta", None) or {}
        arc = meta.get("arc") if isinstance(meta, dict) else None
        if not arc:
            return "(no story yet)"
        return "\n".join(b.get("text", "") for b in arc if isinstance(b, dict))
    except Exception:  # noqa: BLE001
        return "(no story yet)"


def beat_discovery(n: int, theme: str) -> str:
    return f"Chapter 1 — Discovery surfaced {n} findings. Theme: {theme}."


def beat_architect(n: int) -> str:
    return f"Chapter 2 — Architect chose {n} findings, shaped them into one narrative."


def beat_first_verify() -> str:
    return "Chapter 3 — First subtask closed clean."


def beat_replan(reason: str) -> str:
    return f"Chapter 4 — Replanning. {reason}."


def beat_complete(status: str, done: int, total: int, elapsed: str) -> str:
    return f"Final — {status}. {done}/{total} subtasks. {elapsed}."
