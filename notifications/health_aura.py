"""Health Aura -- a single composite 0-100 score for a run, surfaced everywhere.

The aura is the at-a-glance "is this run healthy?" signal shown top-right on the
Bloomberg terminal and as a field in the Discord cockpit. It is a pure function of the
run state (replans, adversary friction, verify failures, retry overhead, pace), so it can
be recomputed cheaply on every dashboard tick without touching the network.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  compute_health(state) -> int  -- Composite 0-100 health score for a TaskState-like object.
  aura_color(score: int) -> str  -- Hex color encoding the score band (green/amber/red).
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_health_aura.py
"""
from __future__ import annotations

from datetime import datetime
from typing import Any

_GREEN = "#00d4aa"
_AMBER = "#ff9f00"
_RED = "#ff4444"


def aura_color(score: int) -> str:
    """Green 80-100, amber 50-79, red 0-49."""
    if score >= 80:
        return _GREEN
    if score >= 50:
        return _AMBER
    return _RED


def _pace_penalty(meta: dict, done: int) -> int:
    """-10 when the run is pacing < 0.7x of where the deadline expects it to be."""
    try:
        started = datetime.fromisoformat(str(meta.get("started_at")))
        deadline = datetime.fromisoformat(str(meta.get("deadline_at")))
        now = datetime.now(started.tzinfo) if started.tzinfo else datetime.now()
        total = (deadline - started).total_seconds()
        elapsed = (now - started).total_seconds()
        if total <= 0 or elapsed <= 0 or done <= 0:
            return 0
        expected_done = max(1e-9, elapsed / total)   # fraction of time spent
        # crude pace: done so far vs the fraction of the window consumed.
        pace = (done / max(1, _expected_total(meta))) / expected_done
        return -10 if pace < 0.7 else 0
    except Exception:  # noqa: BLE001 -- pace is best-effort; never break the score
        return 0


def _expected_total(meta: dict) -> int:
    """Best-effort planned-subtask count for pace; defaults to 1 when unknown."""
    try:
        n = int(meta.get("planned_subtasks") or 0)
        return n if n > 0 else 1
    except Exception:  # noqa: BLE001
        return 1


def compute_health(state: Any) -> int:
    """Composite 0-100 health score. Never raises -- garbage state degrades to a number."""
    try:
        meta = getattr(state, "meta", None) or {}
        subtasks = getattr(state, "subtasks", None)
        subtasks = list(subtasks) if isinstance(subtasks, (list, tuple)) else []
        data = getattr(state, "data", None) or {}
        notifs = data.get("notifications") or []
        replans = sum(1 for n in notifs if isinstance(n, dict) and n.get("kind") == "replan")
        adv_triggers = len(data.get("adversary_reviews") or [])
        failed_verifies = sum(
            1 for s in subtasks if isinstance(s, dict)
            and (s.get("verify_result") or {}).get("passed") is False)
        retry_count = sum(
            max(0, int(s.get("attempts") or 0) - 1) for s in subtasks if isinstance(s, dict))
        done = sum(1 for s in subtasks if isinstance(s, dict) and s.get("status") == "done")
    except Exception:  # noqa: BLE001
        return 100
    score = 100
    score -= min(30, replans * 10)
    score -= min(20, adv_triggers * 5)
    score -= min(20, failed_verifies * 5)
    score -= min(20, retry_count * 3)
    score += _pace_penalty(meta, done)
    return max(0, min(100, score))
