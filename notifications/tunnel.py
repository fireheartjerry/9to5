"""TunnelManager -- hyper-robust supervision of a public tunnel to the local dashboard.

Non-blocking: ``start`` spawns a supervisor thread and returns immediately; the URL
arrives later via ``on_url`` callbacks. The supervisor makes fallback genuinely rare:

  * process watchdog (poll) + end-to-end HTTP health probe
  * restart with exponential backoff (reset after sustained clean uptime)
  * provider demotion after repeated establish failures (re-qualify after a cooldown)
  * a URL is validated (probe) before it is ever announced -- never posts a dead link
  * resume: a still-live saved URL is reused with no new tunnel and no re-announce churn

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  TunnelManager
DEPENDS-ON: config, notifications.tunnel_providers
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_tunnel.py
"""
from __future__ import annotations

import threading
from time import monotonic
from typing import Callable, Optional

import config
from notifications.tunnel_providers import default_providers

LOG = config.getLogger("tunnel")


class TunnelManager:
    # All timings are instance-overridable class attrs so tests can collapse them.
    POLL_INTERVAL = 5.0
    PROBE_INTERVAL = 20.0
    VALIDATE_TIMEOUT = 10.0
    URL_WAIT_TIMEOUT = 20.0
    BACKOFF_BASE = 1.0
    BACKOFF_CAP = 15.0
    UPTIME_RESET = 300.0
    DEMOTE_REQUALIFY = 300.0
    DEMOTE_THRESHOLD = 3

    def __init__(self, providers: Optional[list] = None, *, state=None) -> None:
        self.providers = providers if providers is not None else default_providers()
        self._state = state
        self._provider_idx = 0
        self._port = 0
        self._url: Optional[str] = None
        self._proc = None
        self._callbacks: list[Callable[[str], None]] = []
        self._demoted: dict[int, float] = {}
        self._consec_failures = 0
        self._backoff = self.BACKOFF_BASE
        self._session_start = 0.0
        self._stop = threading.Event()
        self._supervisor: Optional[threading.Thread] = None
        self._lock = threading.Lock()

    # ---- public API -----------------------------------------------------
    def start(self, port: int) -> None:
        self._port = port
        self._stop.clear()
        self._supervisor = threading.Thread(target=self._supervise, name="tunnel-sup", daemon=True)
        self._supervisor.start()

    def stop(self) -> None:
        self._stop.set()
        self._kill(self._proc)
        sup = self._supervisor
        if sup is not None and sup.is_alive() and sup is not threading.current_thread():
            sup.join(timeout=2.0)

    def on_url(self, cb: Callable[[str], None]) -> None:
        self._callbacks.append(cb)

    @property
    def url(self) -> Optional[str]:
        return self._url

    @property
    def provider_name(self) -> str:
        try:
            return self.providers[self._provider_idx].name
        except Exception:  # noqa: BLE001
            return "none"

    @property
    def is_alive(self) -> bool:
        sup = self._supervisor
        return bool(sup and sup.is_alive() and not self._stop.is_set())

    # ---- supervision ----------------------------------------------------
    def _supervise(self) -> None:
        if self._try_resume():
            self._monitor_url()
            if self._stop.is_set():
                return
        while not self._stop.is_set():
            ok = self._run_provider_session()
            if self._stop.is_set():
                break
            self._handle_session_end(ok)

    def _try_resume(self) -> bool:
        if self._state is None:
            return False
        saved = (getattr(self._state, "meta", {}) or {}).get("tunnel_url")
        if not saved:
            return False
        if self._current_provider().probe(saved, timeout=min(5.0, self.VALIDATE_TIMEOUT)):
            LOG.info("tunnel resume: reusing live saved URL %s", saved)
            self._announce(saved)
            return True
        return False

    def _monitor_url(self) -> None:
        """Probe a reused URL periodically; return when it dies or we are stopped."""
        while not self._stop.is_set():
            if self._stop.wait(self.PROBE_INTERVAL):
                return
            if not self._current_provider().probe(self._url or "", timeout=5.0):
                LOG.info("tunnel resume: saved URL went dead; launching fresh")
                return

    def _run_provider_session(self) -> bool:
        """Launch the current provider, validate+announce its URL, then watch it.
        Returns True if a validated URL was established, False on establish failure."""
        provider = self._current_provider()
        if not provider.ensure_available():
            return False
        try:
            proc = provider.start(self._port)
        except Exception as e:  # noqa: BLE001
            LOG.warning("tunnel provider %s failed to start: %s", provider.name, e)
            return False
        self._proc = proc
        self._session_start = monotonic()
        announced = threading.Event()
        reader = threading.Thread(target=self._reader_loop, args=(provider, proc, announced),
                                  name="tunnel-reader", daemon=True)
        reader.start()
        if not announced.wait(self.URL_WAIT_TIMEOUT) or self._stop.is_set():
            self._kill(proc)
            reader.join(timeout=1.0)
            return announced.is_set()   # established-then-stopped counts as success
        self._watch(provider, proc)
        self._kill(proc)
        reader.join(timeout=1.0)
        return True

    def _reader_loop(self, provider, proc, announced: threading.Event) -> None:
        try:
            for line in proc.stdout:   # blocks until the process emits or exits
                if self._stop.is_set():
                    return
                candidate = provider.parse_url(line)
                if candidate and candidate != self._url and self._validate(provider, candidate):
                    self._announce(candidate)
                    announced.set()
        except Exception:  # noqa: BLE001 -- a dead pipe just ends the reader
            pass

    def _validate(self, provider, url: str) -> bool:
        """Probe until the URL answers non-5xx, bounded by VALIDATE_TIMEOUT."""
        deadline = monotonic() + self.VALIDATE_TIMEOUT
        while monotonic() < deadline and not self._stop.is_set():
            if provider.probe(url, timeout=min(5.0, self.VALIDATE_TIMEOUT)):
                return True
            self._stop.wait(0.05)
        return False

    def _watch(self, provider, proc) -> None:
        """Poll the process + re-probe the live URL until death/probe-failure/stop."""
        while not self._stop.is_set():
            if proc.poll() is not None:
                return
            if not provider.probe(self._url or "", timeout=5.0):
                LOG.info("tunnel %s probe failed; restarting", provider.name)
                return
            if monotonic() - self._session_start >= self.UPTIME_RESET:
                self._consec_failures = 0
                self._backoff = self.BACKOFF_BASE
            if self._stop.wait(self.PROBE_INTERVAL):
                return

    def _handle_session_end(self, ok: bool) -> None:
        if ok:
            self._sleep_backoff()
            return
        self._consec_failures += 1
        self._sleep_backoff()
        if self._consec_failures >= self.DEMOTE_THRESHOLD:
            self._demote()
            self._consec_failures = 0
            self._backoff = self.BACKOFF_BASE

    def _sleep_backoff(self) -> None:
        self._stop.wait(self._backoff)
        self._backoff = min(self.BACKOFF_CAP, self._backoff * 2)

    def _demote(self) -> None:
        LOG.info("tunnel demoting provider %s", self.provider_name)
        self._demoted[self._provider_idx] = monotonic()
        self._provider_idx = self._next_provider_idx()

    def _next_provider_idx(self) -> int:
        n = len(self.providers)
        for step in range(1, n + 1):
            idx = (self._provider_idx + step) % n
            at = self._demoted.get(idx)
            if at is None or (monotonic() - at) >= self.DEMOTE_REQUALIFY:
                return idx
        return (self._provider_idx + 1) % n

    def _current_provider(self):
        return self.providers[self._provider_idx]

    # ---- announce + teardown -------------------------------------------
    def _announce(self, url: str) -> None:
        with self._lock:
            changed = url != self._url
            self._url = url
        if not changed:
            return
        if self._state is not None:
            try:
                self._state.meta["tunnel_url"] = url
                self._state.save()
            except Exception:  # noqa: BLE001
                pass
        for cb in list(self._callbacks):
            try:
                cb(url)
            except Exception:  # noqa: BLE001 -- a bad callback must not stop supervision
                LOG.warning("tunnel on_url callback failed", exc_info=True)

    def _kill(self, proc) -> None:
        if proc is None:
            return
        try:
            proc.terminate()
            proc.wait(timeout=3.0)
        except Exception:  # noqa: BLE001
            try:
                proc.kill()
            except Exception:  # noqa: BLE001
                pass
