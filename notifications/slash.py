def _fmtUptime(started_at: float) -> str:
    secs = max(0, int(time.time() - started_at))
    h, rem = divmod(secs, 3600)
    m, s = divmod(rem, 60)
    return f"{h}h{m:02d}m" if h else f"{m}m{s:02d}s"


def _embed(d: dict) -> "discord.Embed":
    return discord.Embed.from_dict(d)


def _ownerOk(interaction) -> bool:  # noqa: ANN001
    return commands.isAuthorized(interaction.user.id)


async def _runControl(interaction, name: str, arg: str = "") -> None:  # noqa: ANN001
    """Defer, resolve the task, audit mutating commands, and post the result publicly."""
    await interaction.response.defer(ephemeral=False)

    def _blocking() -> "str | None":
        # All ControlBus/TaskState/audit file IO runs off the event loop so a file-lock stall
        # can't freeze the gateway heartbeat (mirrors notifications/bot/core.py's '!'-command path).
        state = commands.resolveTargetTask()
        if state is None:
            return None
        if commands.COMMAND_REGISTRY.get(name, {}).get("mutating"):
            audit.record(interaction.user.id, name, state.task_id, "slash")
        return commands.applyCommand(ControlBus(state.task_id), state, commands.Command(name, arg))

    msg = await asyncio.to_thread(_blocking)
    if msg is None:
        return await legacyDiagnosticDiscordSend(interaction.followup.send, commands.NO_TASK, ephemeral=False)
    await legacyDiagnosticDiscordSend(interaction.followup.send, msg[:MAX_REPLY], ephemeral=False)


async def _guard(interaction) -> bool:  # noqa: ANN001
    if not _ownerOk(interaction):
        await legacyDiagnosticDiscordSend(interaction.response.send_message, "Not authorized to control runs.", ephemeral=True)
        return False
    return True


async def _subtaskAutocomplete(interaction, current: str):  # noqa: ANN001
    state = commands.resolveTargetTask()
    if state is None:
        return []
    out = []
    for s in state.subtasks:
        # only PENDING subtasks can be skipped between steps; don't offer the rest
        if s.get("status") == "pending" and current.lower() in s.get("subtask_id", "").lower():
            out.append(app_commands.Choice(name=f"{s.get('subtask_id')} — {s.get('title', '')[:60]}",
                                           value=s.get("subtask_id")))
    return out[:25]


async def _taskAutocomplete(interaction, current: str):  # noqa: ANN001
    out = []
    for s in TaskState.listRecent(25):
        if current.lower() in s["task_id"].lower():
            out.append(app_commands.Choice(
                name=f"{s['task_id'][:8]} — [{s['status']}] {s['goal'][:50]}", value=s["task_id"]))
    return out[:25]
