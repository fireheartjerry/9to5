"""Psyche surface cog (Phase 9): read-only, propose-only interior readout.

Wires the pure ``human_nature.psyche_commands`` routers to a real discord.py cog.
The ``!``-bang surface stays flat (``!psyche``/``!dial``/``!charter``/``!why``/
``!whatyouknow``), while every slash command is namespaced under a single ``/psyche``
group (``/psyche mood|dial|charter|why|know``) so no top-level name collides with
commands other cogs register. Everything is
READ-ONLY (verifier/run control state is never mutated) and PROPOSE-ONLY (``!dial``
never persists a change — it only shows the proposed vector, per the F6 discipline).

The whole surface is gated on ``config.HUMAN_NATURE_ENABLED``: with the flag off every
renderer replies that the psyche layer is off and no live state is touched (never
crashes). Live psyche state is pulled best-effort from the current run's
``state.meta`` (``self_state``/``autonomy``/``character_vector``/``charter``/
``user_model`` + authority-exercise receipts ``hn_votes``/``hn_verify_deepen``/
``hn_instinct``); when absent, fresh defaults render gracefully.

The pure cores (``renderPsyche``/``renderDial``/``renderCharter``/``renderWhy``/
``renderWhatYouKnow``/``dispatchPsyche``) are unit-testable without a gateway.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  renderPsyche(state: Any) -> str  -- Render the interior snapshot (mood/affect/competence/autonomy) via cmd_psyche.
  renderDial(state: Any, arg: str) -> str  -- Show current dials (no arg), or PROPOSE a dial change (never persisted).
  renderCharter(state: Any) -> str  -- Render the active charter tenets via cmd_charter.
  renderWhy(state: Any) -> str  -- Render the functional affect trace plus the last authority-exercise receipts.
  renderWhatYouKnow(state: Any) -> str  -- Render the inspectable user-model snapshot via cmd_whatyouknow.
  dispatchPsyche(content: str, *, state: Any) -> Optional[str]  -- Route a psyche bang command to its render core
  PsycheCog
  setup(bot: dpy_commands.Bot) -> None
DEPENDS-ON: config, human_nature, notifications.commands, notifications.slash
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/notifications/test_psyche_cog.py
"""
from __future__ import annotations

import asyncio
from typing import Any, Optional

from discord import app_commands
from discord.ext import commands as dpy_commands

import config
from human_nature.character_vector import new_character_vector
from human_nature.charter import new_charter
from human_nature.psyche_commands import (
    cmd_charter,
    cmd_dial,
    cmd_psyche,
    cmd_whatyouknow,
    cmd_why_i_feel,
)
from human_nature.self_state import new_self_state
from notifications import commands as spine
from notifications import slash

LOG = config.getLogger("cog.psyche")

_BANG = ("psyche", "dial", "charter", "why", "whatyouknow")
_OFF_TEXT = (
    "Psyche layer is **off** (`HUMAN_NATURE_ENABLED=0`). "
    "The interior readout is unavailable until the human-nature layer is enabled."
)
# state.meta keys that record an exercised authority tier (read-only receipts).
_RECEIPT_KEYS = ("hn_votes", "hn_verify_deepen", "hn_instinct")


# ---------------------------------------------------------------------------
# Gate + best-effort state readers (never raise, never mutate)
# ---------------------------------------------------------------------------

def _enabled() -> bool:
    """True iff the human-nature layer is enabled."""
    return bool(config.HUMAN_NATURE_ENABLED)


def _meta(state: Any) -> dict[str, Any]:
    """Return the run's meta dict from a TaskState/dict/None, best-effort ({} on miss)."""
    if state is None:
        return {}
    meta = getattr(state, "meta", None)
    if meta is None and isinstance(state, dict):
        meta = state.get("meta")
    if isinstance(meta, dict):
        return meta
    return {}


def _self_state(meta: dict[str, Any]) -> dict[str, Any]:
    ss = meta.get("self_state")
    return ss if isinstance(ss, dict) else new_self_state()


def _autonomy(meta: dict[str, Any]) -> dict[str, str]:
    autonomy = meta.get("autonomy")
    return autonomy if isinstance(autonomy, dict) else {}


def _character_vector(meta: dict[str, Any]) -> dict[str, Any]:
    vec = meta.get("character_vector")
    return vec if isinstance(vec, dict) and vec.get("traits") else new_character_vector()


def _charter(meta: dict[str, Any]) -> dict[str, Any]:
    charter = meta.get("charter")
    return charter if isinstance(charter, dict) else new_charter()


def _user_model(meta: dict[str, Any]) -> dict[str, Any]:
    um = meta.get("user_model")
    return um if isinstance(um, dict) else {}


def _authority_receipts(meta: dict[str, Any]) -> list[str]:
    """Flatten the read-only authority-exercise receipts from state.meta into lines."""
    lines: list[str] = []
    for key in _RECEIPT_KEYS:
        entries = meta.get(key)
        if not isinstance(entries, list):
            continue
        for entry in entries:
            if isinstance(entry, dict):
                tier = entry.get("tier", "?")
                domain = entry.get("domain") or entry.get("action") or entry.get("motif_id") or "-"
                lines.append(f"{key}: {domain} @ tier={tier}")
            else:
                lines.append(f"{key}: {entry}")
    return lines


# ---------------------------------------------------------------------------
# Pure render cores (one per command) — all gated + defensive
# ---------------------------------------------------------------------------

def renderPsyche(state: Any) -> str:
    """Render the interior snapshot (mood/affect/competence/autonomy) via cmd_psyche."""
    if not _enabled():
        return _OFF_TEXT
    meta = _meta(state)
    return cmd_psyche(_self_state(meta), autonomy=_autonomy(meta))


def renderDial(state: Any, arg: str) -> str:
    """Show current dials (no arg), or PROPOSE a dial change (never persisted).

    ``!dial`` alone lists the current character-vector traits. ``!dial <trait> <value>``
    routes through ``cmd_dial`` to compute the proposed vector, but the result is
    discarded — this surface is propose-not-apply, so nothing is written back.
    """
    if not _enabled():
        return _OFF_TEXT
    vec = _character_vector(_meta(state))
    arg = (arg or "").strip()
    if not arg:
        traits = vec.get("traits", {})
        body = "\n".join(f"  {t}: {v}" for t, v in traits.items()) or "  (no traits)"
        return (
            f"**Character Dials** (version {vec.get('version', 1)}) — propose-only\n"
            f"{body}\n"
            "Use `!dial <trait> <value>` to PROPOSE a change (never auto-applied)."
        )
    parts = arg.split()
    trait = parts[0]
    try:
        value: float = float(parts[1]) if len(parts) > 1 else 50.0
    except ValueError:
        return f"Invalid value {parts[1]!r}; use a number 0-100."
    _new_vec, text = cmd_dial(vec, trait, value)  # _new_vec intentionally discarded
    return f"**Proposed dial change** (not applied — awaiting human ratify)\n{text}"


def renderCharter(state: Any) -> str:
    """Render the active charter tenets via cmd_charter."""
    if not _enabled():
        return _OFF_TEXT
    return cmd_charter(_charter(_meta(state)))


def renderWhy(state: Any) -> str:
    """Render the functional affect trace plus the last authority-exercise receipts."""
    if not _enabled():
        return _OFF_TEXT
    meta = _meta(state)
    trace = cmd_why_i_feel(_self_state(meta), {})
    receipts = _authority_receipts(meta)
    if receipts:
        body = "\n".join(f"  • {r}" for r in receipts[-5:])
    else:
        body = "  (no authority exercised yet)"
    return (
        "**Why · Affect & Authority Receipts** (read-only)\n"
        f"Affect: {trace}\n"
        f"Last authority exercises:\n{body}"
    )


def renderWhatYouKnow(state: Any) -> str:
    """Render the inspectable user-model snapshot via cmd_whatyouknow."""
    if not _enabled():
        return _OFF_TEXT
    return cmd_whatyouknow(_user_model(_meta(state)))


_DISPATCH = {
    "psyche": lambda state, arg: renderPsyche(state),
    "charter": lambda state, arg: renderCharter(state),
    "why": lambda state, arg: renderWhy(state),
    "whatyouknow": lambda state, arg: renderWhatYouKnow(state),
    "dial": lambda state, arg: renderDial(state, arg),
}


def dispatchPsyche(content: str, *, state: Any) -> Optional[str]:
    """Route a psyche bang command to its render core. None for any non-psyche input."""
    s = (content or "").strip()
    if not s.startswith("!"):
        return None
    parts = s[1:].split(maxsplit=1)
    name = parts[0].lower()
    arg = parts[1].strip() if len(parts) > 1 else ""
    handler = _DISPATCH.get(name)
    if handler is None:
        return None
    return handler(state, arg)


# ---------------------------------------------------------------------------
# Cog (gateway shell) — slash commands + bang listener
# ---------------------------------------------------------------------------

class PsycheCog(dpy_commands.Cog):
    def __init__(self, bot: dpy_commands.Bot) -> None:
        self.bot = bot

    # All psyche slash commands are namespaced under a single ``/psyche`` group so no
    # top-level name (``why``/``dial``/``charter``/``whatyouknow``) can collide with
    # commands other cogs already register on the tree.
    psyche_group = app_commands.Group(
        name="psyche", description="Interior psyche readout (read-only, propose-only)")

    @psyche_group.command(name="mood", description="Interior snapshot: mood, drives, authority (read-only)")
    async def psyche(self, interaction) -> None:  # noqa: ANN001  # pragma: no cover -- gateway
        await self._post(interaction, renderPsyche)

    @psyche_group.command(name="dial", description="Show or PROPOSE a character dial (never auto-applied)")
    @app_commands.describe(trait="Trait to propose", value="Proposed value 0-100")
    async def dial(self, interaction, trait: Optional[str] = None,
                   value: Optional[float] = None) -> None:  # noqa: ANN001  # pragma: no cover
        arg = f"{trait} {value}".strip() if trait else ""
        await self._post(interaction, lambda st: renderDial(st, arg))

    @psyche_group.command(name="charter", description="Show the active Cast Charter tenets (read-only)")
    async def charter(self, interaction) -> None:  # noqa: ANN001  # pragma: no cover -- gateway
        await self._post(interaction, renderCharter)

    @psyche_group.command(name="why", description="Affect trace + last authority-exercise receipts")
    async def why(self, interaction) -> None:  # noqa: ANN001  # pragma: no cover -- gateway
        await self._post(interaction, renderWhy)

    @psyche_group.command(name="know", description="Inspectable user-model snapshot (service-only)")
    async def whatyouknow(self, interaction) -> None:  # noqa: ANN001  # pragma: no cover -- gateway
        await self._post(interaction, renderWhatYouKnow)

    async def _post(self, interaction, render) -> None:  # noqa: ANN001  # pragma: no cover -- gateway
        await interaction.response.defer(thinking=True)
        state = await asyncio.to_thread(spine.resolveTargetTask)
        out = await asyncio.to_thread(render, state)
        await interaction.followup.send((out or _OFF_TEXT)[:slash.MAX_REPLY])

    @dpy_commands.Cog.listener("on_message")
    async def _bang_listener(self, message) -> None:  # noqa: ANN001  # pragma: no cover -- gateway
        # Mirror core.py's on_message gate exactly (bot authors ignored, authorized-only,
        # control-channel scoped). This surface is read-only, so no mutation risk either way.
        if message.author.bot or not str(message.content).strip().startswith("!"):
            return
        if not spine.isAuthorized(message.author.id):
            LOG.info("ignored '!' psyche command from unauthorized user %s", message.author.id)
            return
        if config.DISCORD_CHANNEL_ID and message.channel.id != config.DISCORD_CHANNEL_ID:
            return
        name = str(message.content).strip()[1:].split(maxsplit=1)[0].lower()
        if name not in _BANG:
            return
        state = await asyncio.to_thread(spine.resolveTargetTask)
        out = await asyncio.to_thread(lambda: dispatchPsyche(message.content, state=state))
        if out:
            await message.channel.send(out[:slash.MAX_REPLY])


async def setup(bot: dpy_commands.Bot) -> None:
    await bot.add_cog(PsycheCog(bot))
