"""Intelligence gateway cog (Spec B): the Ollama-backed info surface.

Slash commands ``/brief /why /explain /wisdom /growth /intent /prefer /prefs`` plus a
``Cog.listener`` ``on_message`` for the matching ``!`` bang commands. The Ollama-backed
commands (brief/why/explain/ask/wisdom/growth) are handled ONLY here (the gateway, a separate
always-running process) so a slow brain call never blocks the orchestrator run loop. The fast
control commands (intent/prefer/prefs) route through the shared ``commands`` spine.

The pure routing core is ``dispatchBang`` -- fully unit-testable without a gateway.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  dispatchBang(content: str, *, state, prefs: dict, chat: Optional[Callable[[str, str], str]]=None) -> Optional[str]  -- Route a Spec B Ollama-backed bang command to its pure core
  LogCog
  setup(bot: dpy_commands.Bot) -> None
DEPENDS-ON: config, learning.wisdom, memory.user_prefs, notifications.brain_dialogue, notifications.briefing, notifications.commands, notifications.slash
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_log_cog.py
"""
from __future__ import annotations

import asyncio
from typing import Callable, Optional

from discord import app_commands
from discord.ext import commands as dpy_commands

import config
from notifications import briefing
from notifications import brain_dialogue
from learning import wisdom
from memory import user_prefs
from notifications import commands as spine
from notifications import slash

LOG = config.getLogger("cog.log")
_DEPTHS = ("one-line", "standard", "deep", "raw")
_BANG = ("brief", "why", "explain", "plan-rationale", "ask", "wisdom", "growth")


def dispatchBang(content: str, *, state, prefs: dict,
                 chat: Optional[Callable[[str, str], str]] = None) -> Optional[str]:
    """Route a Spec B Ollama-backed bang command to its pure core. None for anything else."""
    s = (content or "").strip()
    if not s.startswith("!"):
        return None
    parts = s[1:].split(maxsplit=1)
    name = parts[0].lower()
    arg = parts[1].strip() if len(parts) > 1 else ""
    if name == "brief":
        if arg.lower().startswith("set "):
            return user_prefs.applyBriefSet(arg)
        depth = arg.lower() if arg.lower() in _DEPTHS else None
        return briefing.generate_brief(state, prefs, depth, chat=chat)
    if name in ("why", "explain", "plan-rationale", "ask"):
        return brain_dialogue.answer(name, arg, state, chat=chat)
    if name == "wisdom":
        return wisdom.wisdomTrail(state)
    if name == "growth":
        return wisdom.growthSummary(domain=arg or None)
    return None


class LogCog(dpy_commands.Cog):
    def __init__(self, bot: dpy_commands.Bot) -> None:
        self.bot = bot

    # ---- Ollama-backed info slash commands -----------------------------
    @app_commands.command(name="brief", description="On-demand run briefing (preference-tuned)")
    @app_commands.describe(depth="one-line | standard | deep | raw")
    async def brief(self, interaction, depth: Optional[str] = None) -> None:  # noqa: ANN001  # pragma: no cover
        await self._postOllama(interaction, f"!brief {depth or ''}")

    @app_commands.command(name="why", description="Why is the plan/subtask ordered this way?")
    async def why(self, interaction, decision: Optional[str] = None) -> None:  # noqa: ANN001  # pragma: no cover
        await self._postOllama(interaction, f"!why {decision or ''}")

    @app_commands.command(name="explain", description="What is a subtask trying to achieve?")
    async def explain(self, interaction, subtask: str) -> None:  # noqa: ANN001  # pragma: no cover
        await self._postOllama(interaction, f"!explain {subtask}")

    @app_commands.command(name="wisdom", description="Relevant lessons from past runs")
    async def wisdom(self, interaction) -> None:  # noqa: ANN001  # pragma: no cover
        await self._postOllama(interaction, "!wisdom")

    @app_commands.command(name="growth", description="What the last runs taught the system")
    async def growth(self, interaction, domain: Optional[str] = None) -> None:  # noqa: ANN001  # pragma: no cover
        await self._postOllama(interaction, f"!growth {domain or ''}")

    # ---- fast control slash commands (spine) ---------------------------
    @app_commands.command(name="intent", description="Steer the run with high-level intent")
    async def intent(self, interaction, text: str) -> None:  # noqa: ANN001  # pragma: no cover
        if await slash._guard(interaction):
            await slash._runControl(interaction, "intent", text)

    @app_commands.command(name="prefer", description="Set a preference (e.g. 'brief without cost')")
    async def prefer(self, interaction, text: str) -> None:  # noqa: ANN001  # pragma: no cover
        if await slash._guard(interaction):
            await slash._runControl(interaction, "prefer", text)

    @app_commands.command(name="prefs", description="Show or reset your preferences")
    async def prefs(self, interaction, action: Optional[str] = None) -> None:  # noqa: ANN001  # pragma: no cover
        await slash._runControl(interaction, "prefs", action or "")

    async def _postOllama(self, interaction, bang: str) -> None:  # noqa: ANN001  # pragma: no cover
        await interaction.response.defer(thinking=True)
        state = await asyncio.to_thread(spine.resolveTargetTask)
        if state is None:
            return await interaction.followup.send(spine.NO_TASK)
        prefs = await asyncio.to_thread(user_prefs.load)
        out = await asyncio.to_thread(lambda: dispatchBang(bang, state=state, prefs=prefs,
                                                           chat=_gatewayChat))
        await interaction.followup.send((out or spine.NO_TASK)[:slash.MAX_REPLY])

    @dpy_commands.Cog.listener("on_message")
    async def _bang_listener(self, message) -> None:  # noqa: ANN001  # pragma: no cover
        if message.author.bot or not str(message.content).strip().startswith("!"):
            return
        if config.DISCORD_CHANNEL_ID and message.channel.id != config.DISCORD_CHANNEL_ID:
            return
        name = message.content.strip()[1:].split(maxsplit=1)[0].lower()
        if name not in _BANG:
            return  # control bangs are handled by the spine on_message path
        state = await asyncio.to_thread(spine.resolveTargetTask)
        if state is None:
            return
        prefs = await asyncio.to_thread(user_prefs.load)
        out = await asyncio.to_thread(lambda: dispatchBang(message.content, state=state,
                                                          prefs=prefs, chat=_gatewayChat))
        if out:
            await message.channel.send(out[:slash.MAX_REPLY])


def _gatewayChat(system: str, user: str) -> str:  # pragma: no cover -- needs live Ollama
    return briefing._defaultChat(system, user)


async def setup(bot: dpy_commands.Bot) -> None:
    await bot.add_cog(LogCog(bot))
