"""NightclawBot -- the gateway ``commands.Bot`` harness.

Replaces the imperative body of ``notifications.command_bot`` with a
``discord.ext.commands.Bot`` whose ``setup_hook`` does all async startup:
load feature cogs (hot-reloadable), register the slash suite + persistent views,
and sync the command tree. The ``discord`` import is lazy (inside the build/run
functions) so this module stays import-safe and unit-testable without a gateway.

The '!' text-command path is handled by our own ``on_message`` against the pure
``notifications.commands`` spine -- NOT the ext.commands prefix framework -- so the
legacy text control surface behaves exactly as before. ``command_prefix`` is
therefore inert.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  handleCommand(content: str) -> str  -- Parse + apply a '!' command against the latest task
  buildBot()  -- Construct (but do not run) the NightclawBot
  runBot() -> None
DEPENDS-ON: config, control.ControlBus, notifications.bot.ui.dynamic, notifications.commands, notifications.icons, notifications.views
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import asyncio
import time

import config
from control import ControlBus
from notifications import commands as spine

LOG = config.getLogger("bot.core")
MAX_REPLY_CHARS = config.DISCORD_MAX_CONTENT - 100

# Feature cogs loaded at startup (each exposes ``async def setup(bot)``). The legacy
# notifications.slash suite is still registered in setup_hook for parity; these cogs ADD
# new frontier commands alongside it. A bad cog is logged and skipped, never killing the bot.
EXTENSIONS: tuple[str, ...] = (
    "notifications.bot.cogs.observe_cog",  # status/plan/log/help/ping/diagnostics/metrics/audit
    "notifications.bot.cogs.control_cog",  # pause/approve/reject/retry/add/skip/abort
    "notifications.bot.cogs.runs_cog",     # work/wipe/runs/run/resume
    "notifications.bot.cogs.admin",        # /reload (hot-reload), /cockpit, /hud
    "notifications.bot.cogs.ask_cog",      # /ask -- conversational Ollama cockpit (Tier 6)
    "notifications.bot.cogs.plan_cog",     # /plan-edit, /timeline + context menus (Tier 2)
    "notifications.bot.cogs.engagement_cog",  # native Poll gate resolution (Tier 4)
    "notifications.bot.cogs.ops_cog",         # super-reaction approve + silence watchdog (Tier 5)
)


def handleCommand(content: str) -> str:
    """Parse + apply a '!' command against the latest task. '' if not a command."""
    cmd = spine.parseCommand(content)
    if cmd is None:
        return ""
    state = spine.resolveTargetTask()
    if state is None:
        return spine.NO_TASK
    return spine.applyCommand(ControlBus(state.task_id), state, cmd)


def buildBot():  # pragma: no cover -- requires discord + a gateway connection
    """Construct (but do not run) the NightclawBot. Lazy-imports discord."""
    import discord
    from discord import app_commands
    from discord.ext import commands as dpy_commands

    intents = discord.Intents.default()
    intents.message_content = True  # required for the '!' on_message path

    class NightclawBot(dpy_commands.Bot):
        def __init__(self) -> None:
            super().__init__(command_prefix=dpy_commands.when_mentioned,
                             intents=intents, help_command=None)
            self.started_at = time.time()
            self._presence_started = False

        async def setup_hook(self) -> None:
            # 1) feature cogs (hot-reloadable via /reload)
            for ext in EXTENSIONS:
                try:
                    await self.load_extension(ext)
                    LOG.info("loaded extension %s", ext)
                except Exception as e:  # noqa: BLE001 -- one bad cog must not kill the bot
                    LOG.exception("failed to load extension %s: %s", ext, e)
            # 2) provision the professional app-emoji icon set FIRST, so persistent views can put
            #    the icons on their buttons when constructed below (best-effort, off the loop).
            try:
                from notifications import icons
                await asyncio.to_thread(icons.ensureIcons)
            except Exception:  # noqa: BLE001
                pass
            # 3) persistent views + dynamic items (all slash commands now live in cogs above)
            from notifications import views
            from notifications.bot.ui.dynamic import SubtaskButton
            self.add_view(views.ControlPanelView())   # persistent: matches cp_* anywhere
            self.add_view(views.BlockedView())         # persistent: matches sc_*
            self.add_dynamic_items(SubtaskButton)      # stateless per-subtask skip/inspect (Tier 2)
            # 4) sync the command tree (guild-scoped is instant; global ~1h)
            try:
                if config.DISCORD_GUILD_ID:
                    guild = discord.Object(id=config.DISCORD_GUILD_ID)
                    self.tree.copy_global_to(guild=guild)
                    synced = await self.tree.sync(guild=guild)
                else:
                    synced = await self.tree.sync()
                LOG.info("synced %d slash command(s)", len(synced))
            except Exception as e:  # noqa: BLE001
                LOG.warning("slash sync failed: %s", e)

        async def on_ready(self) -> None:
            if not self._presence_started:
                self._presence_started = True
                self.loop.create_task(self._presenceLoop())
            LOG.info("Nightclaw online as %s", self.user)

        async def on_message(self, message: "discord.Message") -> None:
            if message.author == self.user or not message.content.strip().startswith("!"):
                return
            if not spine.isAuthorized(message.author.id):
                LOG.info("ignored '!' command from unauthorized user %s", message.author.id)
                return
            if config.DISCORD_CHANNEL_ID and message.channel.id != config.DISCORD_CHANNEL_ID:
                return
            try:
                # off the event loop: handleCommand does blocking ControlBus file IO (atomic temp +
                # os.replace with backoff sleeps, the _fileLock sidecar). Running it inline froze the
                # gateway's heartbeat/other handlers for the duration under contention.
                reply = await asyncio.to_thread(handleCommand, message.content)
            except Exception:  # noqa: BLE001
                LOG.exception("command error")
                reply = "internal error (see logs)"
            if reply:
                await message.channel.send(reply[:MAX_REPLY_CHARS])

        async def _presenceLoop(self) -> None:
            await self.wait_until_ready()
            while not self.is_closed():
                try:
                    state = spine.resolveTargetTask()
                    if state is not None and spine.isRunActive(state):
                        done, total = state.progress()
                        name = f"{done}/{total} · {state.meta.get('status', 'run')}"
                    else:
                        name = "idle · /help"
                    await self.change_presence(
                        activity=discord.Activity(type=discord.ActivityType.watching, name=name))
                except Exception:  # noqa: BLE001
                    pass
                await asyncio.sleep(config.PRESENCE_INTERVAL)

    bot = NightclawBot()

    @bot.tree.error
    async def _on_app_error(interaction, error):  # noqa: ANN001
        if isinstance(error, app_commands.CommandOnCooldown):
            msg = f" Slow down — try again in {error.retry_after:.0f}s."
        else:
            LOG.exception("slash error: %s", error)
            msg = "internal error (see logs)"
        try:
            if interaction.response.is_done():
                await interaction.followup.send(msg, ephemeral=True)
            else:
                await interaction.response.send_message(msg, ephemeral=True)
        except Exception:  # noqa: BLE001
            pass

    return bot


def runBot() -> None:  # pragma: no cover -- long-lived gateway process
    if not config.DISCORD_BOT_TOKEN:
        LOG.error("DISCORD_BOT_TOKEN missing; cannot start command bot")
        return
    bot = buildBot()
    bot.run(config.DISCORD_BOT_TOKEN)


if __name__ == "__main__":
    runBot()
