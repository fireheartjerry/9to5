"""DynamicItem per-subtask actions (Tier 2). A stateless, regex-custom_id button so any
subtask row can carry its own Skip/Inspect action that survives a gateway restart with NO
per-view state -- registered once via ``bot.add_dynamic_items(SubtaskButton)`` in setup_hook.

The routing (``applySubtaskAction``) is a PURE function over the ``commands`` spine + ControlBus
so it is unit-testable without a gateway; the DynamicItem callback is a thin async wrapper.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  applySubtaskAction(action: str, sid: str, user_id) -> str  -- Pure router: returns the human reply for a per-subtask action
  subtaskButton(action: str, sid: str) -> 'SubtaskButton'
  SubtaskButton
DEPENDS-ON: config, notifications.audit, notifications.commands, platform_core.runtime.control
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/notifications/test_dynamic.py
"""
from __future__ import annotations

import discord

import config
from platform_core.runtime.control import ControlBus
from notifications import audit
from notifications import commands as spine

LOG = config.getLogger("ui.dynamic")

# custom_id grammar: nc:st:<action>:<subtask_id>   e.g. "nc:st:skip:st-003"
TEMPLATE = r"nc:st:(?P<action>skip|inspect):(?P<sid>st-\d+)"
_STYLE = {"skip": discord.ButtonStyle.secondary, "inspect": discord.ButtonStyle.primary}
_EMOJI = {"skip": "⏭️", "inspect": "🔍"}


def applySubtaskAction(action: str, sid: str, user_id) -> str:
    """Pure router: returns the human reply for a per-subtask action. ``skip`` mutates via the
    spine (owner-only, audited); ``inspect`` is read-only."""
    state = spine.resolveTargetTask()
    if state is None:
        return spine.NO_TASK
    if action == "inspect":
        s = next((x for x in state.subtasks if x.get("subtask_id") == sid), None)
        if not s:
            return f"`{sid}` not found."
        vr = s.get("verify_result") or {}
        mark = "✅" if vr.get("passed") else ("❌" if vr else "—")
        return (f"**`{sid}`** [{s.get('status')}] {s.get('title')}\n"
                f"verify: {mark}  ·  attempts: {s.get('attempts', 0)}")
    # mutating (skip)
    if not spine.isAuthorized(user_id):
        return "Not authorized."
    audit.record(user_id, "skip", state.task_id, "subtask-button")
    return spine.applyCommand(ControlBus(state.task_id), state, spine.Command("skip", sid))


def subtaskButton(action: str, sid: str) -> "SubtaskButton":
    return SubtaskButton(action, sid)


class SubtaskButton(discord.ui.DynamicItem[discord.ui.Button], template=TEMPLATE):
    def __init__(self, action: str, sid: str) -> None:
        self.action = action
        self.sid = sid
        super().__init__(discord.ui.Button(
            label=action.title(),
            style=_STYLE.get(action, discord.ButtonStyle.secondary),
            emoji=_EMOJI.get(action),
            custom_id=f"nc:st:{action}:{sid}"))

    @classmethod
    async def from_custom_id(cls, interaction, item, match):  # noqa: ANN001
        return cls(match["action"], match["sid"])

    async def callback(self, interaction: discord.Interaction) -> None:
        msg = applySubtaskAction(self.action, self.sid, interaction.user.id)
        await interaction.response.send_message(msg[:1900], ephemeral=True)
