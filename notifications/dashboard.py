"""DiscordDashboard -- ONE persistent, pinned embed that mirrors the whole run.

Created + pinned at run start, then PATCH-edited in place on every transition
(never spams new messages). Professional layout: status-colored sidebar, text
progress bar, subtask tracker, effort indicator, rich metadata (model / effort /
layer / replans / adversary triggers), and Discord-native relative timestamps.
Degrades to a silent no-op when Discord is unconfigured.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  DiscordDashboard
DEPENDS-ON: config, notifications.branding, notifications.commands, notifications.cv2, notifications.discord_bot, notifications.event_bus, notifications.health_aura, notifications.visuals, state.task
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_dashboard.py
"""
from __future__ import annotations

import threading
import time
from collections import deque
from datetime import datetime, timezone
from typing import Optional

import config
from notifications import branding
from notifications import commands
from notifications import cv2
from notifications import discord_bot as discord
from notifications import visuals
from state.task import TaskState

LOG = config.getLogger("dashboard")

# phase label -> emoji for the title
_PHASE_EMOJI = {
    "starting": "", "resuming": "↻", "architecting": "", "planning": "",
    "executing": "", "verifying": "", "replanning": "", "paused": "",
    "blocked": "", "complete": "", "aborted": "", "failed": "",
}


def _healthField(state) -> str:
    """Composite health aura as a colored-dot + number string for the cockpit embed."""
    try:
        from notifications.health_aura import compute_health
        score = compute_health(state)
    except Exception:  # noqa: BLE001
        return "—"
    dot = "🟢" if score >= 80 else ("🟡" if score >= 50 else "🔴")
    return f"{dot} {score}"


class DiscordDashboard:
    def __init__(self) -> None:
        self.message_id: Optional[str] = None
        self.events: deque[str] = deque(maxlen=10)
        self.effort: str = "default"
        self.model: str = config.PRIMARY_MODEL
        self._lock = threading.Lock()   # guards mutable state under parallel workers
        self._send_lock = threading.Lock()    # serialize network PATCH/POST across workers
        self._state_lock = None                # set by start(); used to snapshot TaskState safely
        self._recreated = False                # at most one 404 recovery (no pin spam)
        self._last_image_ts = 0.0              # monotonic: throttle cockpit hero-image uploads
        self._tunnel_msg_id: Optional[str] = None   # second pinned message: live tunnel URL

    def event(self, text: str) -> None:
        with self._lock:
            self.events.append(f"`{datetime.now().astimezone().strftime('%H:%M')}` {text}")
        # Route every dashboard event through the LiveEventBus so the web/SSE surfaces see it too.
        try:
            from notifications.event_bus import Event, get_bus
            get_bus().emit(Event(kind="narration", sid="system", text=text))
        except Exception:  # noqa: BLE001 -- the bus is best-effort; never break a run
            pass

    def set_tunnel_url(self, url: str) -> None:
        """Post/edit the single pinned tunnel message (``🖥 Live Dashboard → <url>``).
        Edited in place on URL change, never replaced. Gated + best-effort; never raises."""
        if not config.DISCORD_DASHBOARD or not url:
            return
        body = f"🖥 Live Dashboard → {url}"
        try:
            with self._send_lock:
                if self._tunnel_msg_id:
                    if discord.editMessageResult(self._tunnel_msg_id, discord.noticeEmbed(
                            body, title="9TO5 — Live Dashboard")) == "ok":
                        return
                self._tunnel_msg_id = discord.createMessage(
                    discord.noticeEmbed(body, title="9TO5 — Live Dashboard"))
                if self._tunnel_msg_id:
                    discord.pinMessage(self._tunnel_msg_id)
        except Exception:  # noqa: BLE001
            LOG.warning("set_tunnel_url failed", exc_info=True)

    def _eventsSnapshot(self) -> list:
        with self._lock:
            return list(self.events)

    @staticmethod
    def _elapsed(started_at) -> str:
        """Human duration since started_at (e.g. '1h 23m'); '—' if unknown."""
        if not started_at:
            return "—"
        try:
            start = datetime.fromisoformat(str(started_at))
            now = datetime.now(start.tzinfo) if start.tzinfo else datetime.now()
            secs = int((now - start).total_seconds())
        except Exception:  # noqa: BLE001
            return "—"
        if secs < 0:
            secs = 0
        h, rem = divmod(secs, 3600)
        mins = rem // 60
        if h:
            return f"{h}h {mins}m"
        if mins:
            return f"{mins}m"
        return f"{secs}s"

    @staticmethod
    def _eta(started_at, done: int, total: int) -> str:
        """Remaining time estimate based on current pace; '—' if insufficient data."""
        remaining = total - done
        if remaining <= 0 or done <= 0 or not started_at:
            return "—"
        try:
            start = datetime.fromisoformat(str(started_at))
            now = datetime.now(start.tzinfo) if start.tzinfo else datetime.now()
            elapsed_secs = (now - start).total_seconds()
        except Exception:  # noqa: BLE001
            return "—"
        if elapsed_secs <= 0:
            return "—"
        secs_per_task = elapsed_secs / done
        eta_secs = int(secs_per_task * remaining)
        h, rem = divmod(eta_secs, 3600)
        mins = rem // 60
        if h:
            return f"~{h}h {mins}m"
        if mins:
            return f"~{mins}m"
        return f"~{eta_secs}s"

    # ---- embed construction --------------------------------------------
    def _embed(self, state: TaskState, phase: str) -> dict:
        lock = self._state_lock
        if lock:
            lock.acquire()
        try:
            m = dict(state.meta)
            subtasks = [dict(s) for s in state.subtasks]
            notifs = list(state.data.get("notifications", []))
            advs = len(state.data.get("adversary_reviews", []))
        finally:
            if lock:
                lock.release()
        done = sum(1 for s in subtasks if s["status"] == "done")
        total = sum(1 for s in subtasks if s["status"] != "removed") or 1
        replans = sum(1 for n in notifs if n.get("kind") == "replan")

        current = next((s for s in subtasks if s["status"] == "in_progress"), None)
        if current is None:
            current = next((s for s in subtasks if s["status"] == "pending"), None)
        attempt_hint = ""
        if current and current.get("attempts"):
            attempt_hint = f"  (attempt {current['attempts']})"
        cur_txt = (f"`{current['subtask_id']}` {current['title']}{attempt_hint}") if current else "—"

        last_v = None
        for s in subtasks:
            if s.get("verify_result"):
                last_v = (s["subtask_id"], s["verify_result"])
        if last_v:
            sid, vr = last_v
            mark = "✅" if vr.get("passed") else "❌"
            verify_txt = f"{mark} `{sid}` — `{str(vr.get('cmd') or vr.get('expect'))[:70]}`"
        else:
            verify_txt = "—"

        paused = m.get("status") == "paused"
        hint = "!resume" if paused else commands.footerHelp()
        return {
            "title": f"9TO5 · {phase}",
            "color": discord.statusColor(m["status"]),
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "description": (
                f"**{m['goal_raw'][:240]}**\n"
                f"{discord.progressBar(done, total)}\n"
                f"{discord.subtaskTracker(subtasks)}"
            ),
            "fields": [
                {"name": "Model", "value": f"`{self.model}`", "inline": True},
                {"name": "Mode", "value": f"`{m.get('control_mode', 'watch')}`", "inline": True},
                {"name": "Elapsed", "value": self._elapsed(m.get("started_at")), "inline": True},
                {"name": "ETA", "value": self._eta(m.get("started_at"), done, total), "inline": True},
                {"name": "Replans", "value": str(replans), "inline": True},
                {"name": "Adversary", "value": str(advs), "inline": True},
                {"name": "Health", "value": _healthField(state), "inline": True},
                {"name": "Effort", "value": discord.effortBar(self.effort), "inline": True},
                {"name": "Current subtask", "value": cur_txt[:1000], "inline": False},
                {"name": "Working dir", "value": f"`{(m.get('work_dir') or '—')[:200]}`", "inline": False},
                {"name": "Last verify", "value": verify_txt, "inline": False},
                {"name": "Recent events", "value": ("\n".join(self._eventsSnapshot()) or "—")[:1000], "inline": False},
            ],
            "footer": {"text": f"task {state.task_id[:8]} · web :{config.WEB_DASHBOARD_PORT} · {hint}"},
        }

    def _cockpit(self, state: TaskState, phase: str) -> tuple:
        """Build the Components-V2 cockpit tree (when DASHBOARD_CV2). Returns ``(components, files)``
        where ``files`` is an optional multipart attachment list for the Pillow hero image.
        Snapshots the event ring first (self._lock), then renders the image + tree under the run's
        state_lock -- same lock discipline as _embed (the two locks are never held simultaneously)."""
        events = self._eventsSnapshot()
        # Throttle the hero-image upload: render+upload at most once per COCKPIT_IMAGE_MIN_INTERVAL.
        # Text-CV2 edits still flow on every tick; this just caps the multipart uploads so the
        # every-4s pause loop (and rapid subtask churn) can never drive a rate-limit storm.
        now = time.monotonic()
        want_image = config.VISUALS_ENABLED and (now - self._last_image_ts) >= config.COCKPIT_IMAGE_MIN_INTERVAL
        lock = self._state_lock
        if lock:
            lock.acquire()
        try:
            img = visuals.progressCard(state, phase=phase, model=self.model, effort=self.effort) \
                if want_image else None
            image_url = "attachment://cockpit.png" if img else None
            comps, _flags = cv2.buildCockpit(state, phase, events=events, model=self.model,
                                             effort=self.effort, image_url=image_url)
        finally:
            if lock:
                lock.release()
        if img:
            self._last_image_ts = now
        files = [("cockpit.png", img, "image/png")] if img else None
        return comps, files

    # ---- lifecycle ------------------------------------------------------
    def start(self, state: TaskState, phase: str = "starting", state_lock=None) -> None:
        if not config.DISCORD_DASHBOARD:
            return
        self._state_lock = state_lock
        # Restore the event ring from a previous run so Recent Events survives a resilience restart
        with self._lock:
            for e in state.data.get("dashboard_events", []):
                self.events.append(e)
        self.event(f"run started · mode `{state.meta.get('control_mode', 'watch')}`")
        try:
            state.saveDashboardEvents(self._eventsSnapshot())
        except Exception:  # noqa: BLE001 -- never fail a run over event persistence
            pass
        cv2_mode = config.DASHBOARD_CV2
        embed = None if cv2_mode else self._embed(state, phase)
        comps, files = self._cockpit(state, phase) if cv2_mode else (None, None)
        with self._send_lock:
            # Reuse existing dashboard message when resilience restarts the same task — avoids
            # creating a new pinned cockpit (and firing all its button components) on every restart.
            existing_id = state.meta.get("dashboard_message_id")
            if existing_id:
                res = (discord.editComponentsV2Result(existing_id, comps, files=files) if cv2_mode
                       else discord.editMessageResult(existing_id, embed, components=branding.controlPanelRow()))
                if res == "ok":
                    self.message_id = existing_id
                    self._recreated = True  # suppress further recreation attempts
                    LOG.info("Dashboard message %s resumed (resilience restart)", self.message_id)
                    return
                if res == "transient":
                    # Discord momentarily unreachable (429 breaker / timeout); the message almost
                    # certainly still exists -- reuse it instead of spawning a duplicate pinned embed.
                    # Don't burn the one-shot: update() can still recreate if it's truly a 404 later.
                    self.message_id = existing_id
                    LOG.info("Dashboard message %s reused (Discord transient at start)", existing_id)
                    return
                # res == "not_found": the old message is gone -> create a fresh one below
            self.message_id = (discord.createComponentsV2(comps, files=files) if cv2_mode
                               else discord.createMessage(embed, components=branding.controlPanelRow()))
            if self.message_id:
                discord.pinMessage(self.message_id)
                LOG.info("Dashboard message %s created + pinned", self.message_id)
                try:
                    state.setDashboardMessageId(self.message_id)
                except Exception:  # noqa: BLE001 -- never fail a run over dashboard persistence
                    pass

    def update(self, state: TaskState, phase: str, note: Optional[str] = None,
               effort: Optional[str] = None, model: Optional[str] = None) -> None:
        if not config.DISCORD_DASHBOARD:
            return
        with self._lock:
            if effort:
                self.effort = effort
            if model:
                self.model = model
        if note:
            self.event(note)
        try:
            state.saveDashboardEvents(self._eventsSnapshot())
        except Exception:  # noqa: BLE001 -- never fail a run over event persistence
            pass
        cv2_mode = config.DASHBOARD_CV2
        embed = None if cv2_mode else self._embed(state, phase)
        comps, files = self._cockpit(state, phase) if cv2_mode else (None, None)
        with self._send_lock:
            row = branding.controlPanelRow()

            def _edit(mid):
                return (discord.editComponentsV2Result(mid, comps, files=files) if cv2_mode
                        else discord.editMessageResult(mid, embed, components=row))

            def _create():
                return (discord.createComponentsV2(comps, files=files) if cv2_mode
                        else discord.createMessage(embed, components=row))

            if self.message_id:
                res = _edit(self.message_id)
                # ONLY recreate on a genuine 404. A 'transient' failure (429 breaker armed, timeout)
                # must leave message_id + _recreated untouched and just retry the edit next tick --
                # otherwise a Discord blip spawns a duplicate dashboard and burns the one-shot guard.
                if res == "not_found" and not self._recreated:
                    self._recreated = True
                    self.message_id = _create()
                    if self.message_id:
                        discord.pinMessage(self.message_id)
            else:
                self.message_id = _create()
                if self.message_id:
                    discord.pinMessage(self.message_id)

    def unpin(self) -> None:
        """Remove the pinned dashboard when the run ends (idempotent; never raises)."""
        if not config.DISCORD_DASHBOARD or not self.message_id:
            return
        try:
            discord.unpinMessage(self.message_id)
            LOG.info("Dashboard message %s unpinned", self.message_id)
        except Exception:  # noqa: BLE001
            LOG.warning("dashboard unpin failed", exc_info=True)
