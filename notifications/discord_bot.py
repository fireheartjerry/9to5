# Proxy mutable primitive state (_DISABLED, _RATE_LIMITED_UNTIL) to discord_client
# so that mutations inside discord_client (global _DISABLED = True after 401) are
# immediately visible to callers that read them through this facade AND that tests
# which set d._DISABLED = False also reset the canonical state in discord_client.
import sys as _sys
import types as _types

class _BotModule(_types.ModuleType):
    # Primitive booleans/floats owned by discord_client; no local copy (always proxied via __getattr__).
    _PROXY_TO_CLIENT = frozenset(("_DISABLED", "_RATE_LIMITED_UNTIL"))
    # Function objects that tests patch on discord_bot; propagate write to both client and channels.
    _PROXY_TO_CLIENT_AND_CHANNELS = frozenset(("_request",))
    # Functions defined in discord_channels that tests patch on discord_bot.
    _PROXY_TO_CHANNELS = frozenset(("_ensureWebhook",))
    # Read-only proxies (time module imported into discord_client).
    _PROXY_RO = frozenset(("time",))

    def __getattr__(self, name: str):
        if name in self._PROXY_TO_CLIENT or name in self._PROXY_RO:
            return getattr(_dc, name)
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")

    def __setattr__(self, name: str, value) -> None:
        if name in self._PROXY_TO_CLIENT:
            setattr(_dc, name, value)
        elif name in self._PROXY_TO_CLIENT_AND_CHANNELS:
            import notifications.discord_channels as _dch
            setattr(_dc, name, value)
            setattr(_dch, name, value)
            super().__setattr__(name, value)
        elif name in self._PROXY_TO_CHANNELS:
            import notifications.discord_channels as _dch
            setattr(_dch, name, value)
            super().__setattr__(name, value)
        else:
            super().__setattr__(name, value)

    def __delattr__(self, name: str) -> None:
        # mock.patch.object cleanup calls delattr to restore the "no local attribute" state.
        # For names we proxy to sub-modules, silently ignore the delete — the proxy handles reads.
        _ALL_PROXIED = self._PROXY_TO_CLIENT | self._PROXY_TO_CLIENT_AND_CHANNELS | self._PROXY_TO_CHANNELS
        if name in _ALL_PROXIED:
            return
        super().__delattr__(name)

_sys.modules[__name__].__class__ = _BotModule


