"""Filesystem bridge for the Live Terminal paginator across the bot <-> orchestrator
processes. The bot writes nav intent; the orchestrator surface reads it each tick and
writes back a mirror (rendered body + page_count + lane ids) so the bot can serve
snapshots and clamp navigation. All I/O is best-effort and never raises.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  TerminalIpcStoreUnavailable  -- No exact external terminal-IPC binding is available in capsule mode.
  TerminalIpcStoreBinding
  installTerminalIpcStore(*, store: ControllerStateStore, authority: ControllerStateAuthority) -> TerminalIpcStoreBinding  -- Install an inactive-path diagnostic binding
  read_nav() -> dict
  write_nav(page_idx: int, mode: str, frozen: bool) -> None
  bump_nav(*, delta_page: int=0, toggle_raw: bool=False, toggle_freeze: bool=False, page_count: 'int | None'=None) -> dict
  read_mirror() -> dict
  write_mirror(body: str, page_count: int, lanes: list) -> None
  clear() -> None
DEPENDS-ON: config, platform_core.app_config.paths, platform_core.core.fsio, platform_core.execution, platform_core.runtime
SIDE-EFFECTS: writes state/ipc/terminal_nav.json + state/ipc/terminal_mirror.json
RUN/TEST: python -m pytest tests/control/test_terminal_ipc.py
"""
from __future__ import annotations

import threading
from contextlib import ExitStack, contextmanager
from dataclasses import dataclass
from pathlib import Path

import config
from platform_core.core import fsio
from platform_core.execution.pre_execution import mutateLegacyPath
from platform_core.runtime.controller_state import (
    ControllerStateAuthority,
    ControllerStateRefused,
    ControllerStateStore,
    isDiagnosticControllerStateAuthority,
)

# IPC files live under state/ipc/ -- OUTSIDE the task store (state/tasks/), so task-store
# scans (task_io.iterStored) can never misparse them as runs.
NAV_PATH: Path = config.IPC_DIR / "terminal_nav.json"
MIRROR_PATH: Path = config.IPC_DIR / "terminal_mirror.json"

_NAV_DEFAULT = {"page_idx": 0, "mode": "summary", "frozen": False}
_MIRROR_DEFAULT = {"body": "", "page_count": 0, "lanes": []}
_BINDING_LOCK = threading.RLock()


class TerminalIpcStoreUnavailable(RuntimeError):
    """No exact external terminal-IPC binding is available in capsule mode."""


@dataclass(frozen=True, slots=True)
class TerminalIpcStoreBinding:
    store: ControllerStateStore
    authority: ControllerStateAuthority


_INSTALLED_BINDING: TerminalIpcStoreBinding | None = None


def installTerminalIpcStore(
    *,
    store: ControllerStateStore,
    authority: ControllerStateAuthority,
) -> TerminalIpcStoreBinding:
    """Install an inactive-path diagnostic binding; production resolves centrally."""

    if type(store) is not ControllerStateStore or type(authority) is not ControllerStateAuthority:
        raise TerminalIpcStoreUnavailable(
            "exact open diagnostic controller-state store and authority are required"
        )
    from platform_core.app_config.paths import controllerPathsActivationFence
    from platform_core.runtime.controller_state import (
        controllerRuntimeStateAbsentPermit,
    )

    try:
        store._validateInstallableAuthority(authority)
    except ControllerStateRefused as exc:
        raise TerminalIpcStoreUnavailable(
            "an open diagnostic controller-state store and authority are required"
        ) from exc
    if not isDiagnosticControllerStateAuthority(authority):
        raise TerminalIpcStoreUnavailable(
            "diagnostic controller-state authority is required"
        )

    try:
        with controllerRuntimeStateAbsentPermit():
            with controllerPathsActivationFence() as paths_active:
                if paths_active or _controllerPathsActive():
                    raise TerminalIpcStoreUnavailable(
                        "diagnostic terminal-IPC binding is unavailable after activation"
                    )
                try:
                    store._validateInstallableAuthority(authority)
                except ControllerStateRefused as exc:
                    raise TerminalIpcStoreUnavailable(
                        "an open diagnostic controller-state store and authority are required"
                    ) from exc
                binding = TerminalIpcStoreBinding(store=store, authority=authority)
                global _INSTALLED_BINDING
                with _BINDING_LOCK:
                    if _INSTALLED_BINDING is not None:
                        if (
                            _INSTALLED_BINDING.store is store
                            and _INSTALLED_BINDING.authority is authority
                        ):
                            installed = _INSTALLED_BINDING
                        else:
                            raise TerminalIpcStoreUnavailable(
                                "diagnostic terminal-IPC binding is already installed"
                            )
                    else:
                        _INSTALLED_BINDING = binding
                        installed = binding
    except TerminalIpcStoreUnavailable:
        raise
    except ControllerStateRefused as exc:
        raise TerminalIpcStoreUnavailable(
            "controller runtime installation is not exactly absent"
        ) from exc
    return installed


def _controllerPathsActive() -> bool:
    try:
        from platform_core.app_config.paths import controllerPathsActive

        return bool(controllerPathsActive())
    except Exception:
        return True


def _centralBinding() -> TerminalIpcStoreBinding:
    from platform_core.runtime import controller_state

    try:
        runtime = controller_state.currentControllerRuntimeStateBinding()
        store = runtime.store
        authority = runtime.authority
        if (
            type(store) is not ControllerStateStore
            or type(authority) is not ControllerStateAuthority
        ):
            raise ControllerStateRefused(
                "central controller runtime binding has invalid exact types"
            )
        store._validateInstallableAuthority(authority)
    except (AttributeError, ControllerStateRefused) as exc:
        raise TerminalIpcStoreUnavailable(
            "external terminal-IPC controller binding is unavailable"
        ) from exc
    return TerminalIpcStoreBinding(store=store, authority=authority)


@contextmanager
def _bindingOperation():
    try:
        central = _centralBinding()
    except TerminalIpcStoreUnavailable:
        pass
    else:
        yield central
        return

    from platform_core.app_config.paths import controllerPathsActivationFence
    from platform_core.runtime.controller_state import (
        controllerRuntimeStateAbsentPermit,
    )

    diagnostic: TerminalIpcStoreBinding | None = None
    active = False
    permit = ExitStack()
    try:
        permit.enter_context(controllerRuntimeStateAbsentPermit())
    except ControllerStateRefused as exc:
        permit.close()
        raise TerminalIpcStoreUnavailable(
            "controller runtime installation is not exactly absent"
        ) from exc
    with permit:
        with controllerPathsActivationFence() as paths_active:
            active = paths_active or _controllerPathsActive()
            if not active:
                with _BINDING_LOCK:
                    diagnostic = _INSTALLED_BINDING
                yield diagnostic
                return

    if active:
        yield _centralBinding()
        return
    raise TerminalIpcStoreUnavailable(
        "external terminal-IPC controller binding is unavailable"
    )


def _binding() -> TerminalIpcStoreBinding | None:
    with _bindingOperation() as binding:
        return binding


def _read(path: Path, logical_id: str, default: dict) -> dict:
    try:
        with _bindingOperation() as binding:
            if binding is not None:
                data = binding.store.readJson(
                    logical_id, authority=binding.authority
                )
            else:
                data = fsio.loadJson(path, default=None)
        if isinstance(data, dict):
            return {**default, **data}
    except (FileNotFoundError, ControllerStateRefused, TerminalIpcStoreUnavailable):
        pass
    return dict(default)


def _write(path: Path, logical_id: str, payload: dict) -> None:
    try:
        with _bindingOperation() as binding:
            if binding is not None:
                binding.store.writeJson(
                    logical_id, payload, authority=binding.authority
                )
            else:
                fsio.atomicWriteJson(path, payload, indent=None)
    except Exception:  # noqa: BLE001 -- bridge writes never break a caller
        pass


def read_nav() -> dict:
    n = _read(NAV_PATH, "ipc/terminal-nav", _NAV_DEFAULT)
    try:
        n["page_idx"] = int(n.get("page_idx", 0))
    except (TypeError, ValueError):
        n["page_idx"] = 0
    if n.get("mode") not in ("summary", "raw"):
        n["mode"] = "summary"
    n["frozen"] = bool(n.get("frozen", False))
    return {"page_idx": n["page_idx"], "mode": n["mode"], "frozen": n["frozen"]}


def write_nav(page_idx: int, mode: str, frozen: bool) -> None:
    _write(NAV_PATH, "ipc/terminal-nav", {"page_idx": int(page_idx),
                                           "mode": mode if mode in ("summary", "raw") else "summary",
                                           "frozen": bool(frozen)})


def bump_nav(*, delta_page: int = 0, toggle_raw: bool = False,
             toggle_freeze: bool = False, page_count: "int | None" = None) -> dict:
    nav = read_nav()
    idx = nav["page_idx"] + delta_page
    if page_count and page_count > 0:
        idx = max(0, min(idx, page_count - 1))
    else:
        idx = max(0, idx)
    mode = ("raw" if nav["mode"] == "summary" else "summary") if toggle_raw else nav["mode"]
    frozen = (not nav["frozen"]) if toggle_freeze else nav["frozen"]
    write_nav(idx, mode, frozen)
    return {"page_idx": idx, "mode": mode, "frozen": frozen}


def read_mirror() -> dict:
    m = _read(MIRROR_PATH, "ipc/terminal-mirror", _MIRROR_DEFAULT)
    if not isinstance(m.get("lanes"), list):
        m["lanes"] = []
    return m


def write_mirror(body: str, page_count: int, lanes: list) -> None:
    _write(MIRROR_PATH, "ipc/terminal-mirror", {
        "body": str(body),
        "page_count": int(page_count),
        "lanes": list(lanes),
    })


def clear() -> None:
    for path, logical_id in (
        (NAV_PATH, "ipc/terminal-nav"),
        (MIRROR_PATH, "ipc/terminal-mirror"),
    ):
        try:
            with _bindingOperation() as binding:
                if binding is not None:
                    binding.store.deleteJson(
                        logical_id, authority=binding.authority
                    )
                else:
                    mutateLegacyPath(Path(path).unlink)
        except Exception:  # noqa: BLE001
            pass
