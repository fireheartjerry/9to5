class _QuietThreadingHTTPServer(ThreadingHTTPServer):
    """ThreadingHTTPServer that does not dump a traceback for benign client disconnects.

    A client drop during the pre-dispatch ``raw_requestline`` read raises
    ConnectionAbortedError/ConnectionResetError inside ``handle_one_request`` BEFORE any
    do_GET/do_POST runs, so the handler's own guards can't catch it; the default
    ``BaseServer.handle_error`` then prints the full traceback to stderr, polluting run logs.
    Swallow only connection errors; delegate everything else so real handler bugs still surface."""

    def handle_error(self, request, client_address) -> None:  # noqa: ANN001
        if isinstance(sys.exc_info()[1], ConnectionError):
            return  # benign client disconnect -- the request is already dead
        super().handle_error(request, client_address)


_SSE_STOP = threading.Event()
_CONTROL_TOKEN = ""  # per-run control token; printed to local console/log ONLY, never served in HTML
_DERIVED_CACHE: dict[str, tuple[float, dict]] = {}
_DERIVED_LOCK = threading.Lock()


# --------------------------------------------------------------------------- payload builders
def _raw_payload(sid: str) -> str:
    """JSON list of the last 500 raw stdout lines for ``sid`` (for /api/raw)."""
    with best_effort("webdash.raw_payload", log=LOG):
        return json.dumps(get_bus().raw_history(sid, last_n=500))
    return "[]"


def _wisdom_trail(goal: str) -> list:
    """Top-3 past-run lessons relevant to ``goal`` (keyword match over SIE reflections)."""
    with best_effort("webdash.wisdom_trail", log=LOG):
        from memory import experience
        import heapq

        rows = experience.fetch_reflections()
        tokens = {w for w in (goal or "").lower().split() if len(w) > 3}
        heap = []
        seq = 0
        for r in rows:
            text = " ".join(str(r.get(k) or "") for k in ("reusable_recipe", "approach", "verify_critique"))
            summary = (r.get("reusable_recipe") or r.get("approach") or "").strip()
            if not summary:
                continue
            score = sum(1 for t in tokens if t in text.lower())
            item = (score, seq, {"summary": summary[:80], "run": str(r.get("run_id") or "")[:8]})
            seq += 1
            if len(heap) < 3:
                heapq.heappush(heap, item)
            elif item[:2] > heap[0][:2]:
                heapq.heapreplace(heap, item)
        scored = sorted(heap, reverse=True)
        return [s[2] for s in scored if s[0] > 0] or [s[2] for s in scored]
    return []


def _intelligence_curve() -> list:
    """Domain-by-domain confidence (best-effort; [] when the ledger has nothing usable)."""
    with best_effort("webdash.intelligence_curve", log=LOG):
        from memory import experience

        rows = experience.fetch_subtasks(limit=300) if hasattr(experience, "fetch_subtasks") else []
        buckets: dict[str, list] = {}
        for r in rows:
            title = str(r.get("title") or r.get("subtask_id") or "").lower()
            domain = next((w for w in title.split() if len(w) > 4), None)
            if not domain:
                continue
            buckets.setdefault(domain, []).append(1 if r.get("verify_passed") else 0)
        out = [
            {"domain": d[:12], "pct": round(100 * sum(v) / len(v))} for d, v in buckets.items() if len(v) >= 2
        ]
        out.sort(key=lambda x: x["pct"], reverse=True)
        return out[:6]
    return []


def _discovery_block(meta: dict) -> Optional[dict]:
    dr = meta.get("discovery_report") or {}
    if not dr:
        return None
    findings = dr.get("findings")
    return {
        "findings": len(findings) if isinstance(findings, list) else (findings or 0),
        "theme": dr.get("theme_suggestion") or "—",
    }


def _derive_model(state: TaskState) -> str:
    for s in reversed(state.subtasks):
        m = (s.get("session") or {}).get("model")
        if m:
            return m
    return config.PRIMARY_MODEL


def _comparative(task_id: str) -> Optional[dict]:
    with best_effort("webdash.comparative", log=LOG):
        from memory import experience

        c = experience.compare_run(task_id)
        return {k: c.get(k) for k in ("pace", "innovation", "adversary", "replans")}
    return None


def _timing(meta: dict) -> "tuple[float, float]":
    from datetime import datetime

    with best_effort("webdash.timing", log=LOG):
        started = datetime.fromisoformat(meta["started_at"])
        deadline = datetime.fromisoformat(meta["deadline_at"])
        now = datetime.now().astimezone()
        return (now - started).total_seconds(), (deadline - now).total_seconds()
    return 0.0, 0.0


def _derived(task_id: str, goal: str) -> dict:
    ttl = max(1, int(getattr(config, "WEBDASH_DERIVED_TTL_SECONDS", 30) or 30))
    now = time.monotonic()
    key = f"{task_id}:{goal}"
    with _DERIVED_LOCK:
        hit = _DERIVED_CACHE.get(key)
        if hit and now - hit[0] < ttl:
            return dict(hit[1])
    data = {
        "wisdom_trail": _wisdom_trail(goal),
        "intelligence_curve": _intelligence_curve(),
        "comparative": _comparative(task_id),
    }
    with _DERIVED_LOCK:
        _DERIVED_CACHE[key] = (now, dict(data))
        if len(_DERIVED_CACHE) > 32:
            oldest = sorted(_DERIVED_CACHE.items(), key=lambda kv: kv[1][0])[:8]
            for old_key, _ in oldest:
                _DERIVED_CACHE.pop(old_key, None)
    return data


def _snapshot(task_id: str) -> dict:
    t0 = time.perf_counter()
    try:
        state = TaskState.load(task_id)
    except Exception:  # noqa: BLE001
        return {"empty": True}
    bus = ControlBus(task_id).load()
    done, total = state.progress()
    m = dict(state.meta)
    m["task_id"] = state.task_id
    elapsed_s, eta_s = _timing(state.meta)
    score = compute_health(state)
    notifs = state.data.get("notifications", [])
    derived = _derived(task_id, state.meta.get("goal_raw") or "")
    payload = {
        "empty": False,
        "meta": m,
        "model": _derive_model(state),
        "work_dir": state.meta.get("work_dir") or "—",
        "progress": {"done": done, "total": total},
        "elapsed_s": elapsed_s,
        "eta_s": eta_s,
        "replans": sum(1 for n in notifs if isinstance(n, dict) and n.get("kind") == "replan"),
        "adversary": len(state.data.get("adversary_reviews", [])),
        "cost": state.meta.get("cost") or "—",
        "tunnel_url": state.meta.get("tunnel_url"),
        "health": {"score": score, "color": aura_color(score)},
        "arc": state.meta.get("arc") or [],
        "discovery": _discovery_block(state.meta),
        "wisdom_trail": derived["wisdom_trail"],
        "intelligence_curve": derived["intelligence_curve"],
        "comparative": derived["comparative"],
        "council": council_summary(state),
        "degradations": degradationSummary(),
        "degraded_line": degradationLine(),
        "subtasks": [
            {
                "subtask_id": s["subtask_id"],
                "title": s["title"],
                "status": s["status"],
                "verify": (s.get("verify_result") or {}).get("passed") if s.get("verify_result") else None,
            }
            for s in state.subtasks
        ],
        "events": state.data.get("notifications", []),
        "control": {"abort": bus["abort"], "pause": bus["pause"], "pending_gate": bus.get("pending_gate")},
    }
    perf.record("webdash_snapshot", time.perf_counter() - t0, task_id=task_id)
    return payload


def _applyControl(task_id: str, action: str, arg: Optional[str]) -> dict:
    if not task_id:
        return {"ok": False, "error": "no active task"}
    if not isinstance(action, str) or not action:
        return {"ok": False, "error": "action must be a non-empty string"}
    bus = ControlBus(task_id)
    if action == "abort":
        bus.requestAbort()
    elif action == "pause":
        bus.requestPause()
    elif action == "resume":
        bus.clearPause()
    elif action in ("approve", "reject"):
        gate = arg or bus.getPendingGate()
        if gate not in GATES:  # ignore a missing/unknown gate, never write a stray decision key
            return {"ok": False, "error": "no valid pending gate"}
        bus.decide(gate, action)
        return {"ok": True, "gate": gate}
    elif action == "skip" and arg:
        bus.pushOp({"op": "skip", "subtask_id": arg})
    elif action == "add" and arg:
        bus.pushOp({"op": "add", "title": arg, "description": arg})
    else:
        return {"ok": False, "error": f"unknown or incomplete action: {action!r}"}
    return {"ok": True}


class _DashboardHandler(BaseHTTPRequestHandler):
    """Per-run handler; ``task_id``/``token`` are bound as class attrs by ``_makeHandler``.

    ``token`` is the control token (console/log only); it is never embedded in served HTML.
    """

    task_id: str = ""
    token: str = ""

    def log_message(self, *_a):  # silence default stderr noise
        return

    def _send(self, code: int, body: bytes, ctype: str) -> None:
        # A browser tab closing mid-response drops the socket; swallow the disconnect.
        try:
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
        except (BrokenPipeError, ConnectionError, ConnectionResetError, ConnectionAbortedError):
            pass

    def _serve_sse(self) -> None:
        bus = get_bus()
        q = bus.subscribe_sse()
        try:
            self.send_response(200)
            self.send_header("Content-Type", "text/event-stream")
            self.send_header("Cache-Control", "no-cache")
            self.send_header("Connection", "keep-alive")
            self.end_headers()
            for e in bus.history(last_n=200):
                self._sse_write(e)
            while not _SSE_STOP.is_set():
                try:
                    item = q.get(timeout=15)
                except queue.Empty:
                    self.wfile.write(b": ping\n\n")
                    self.wfile.flush()
                    continue
                self._sse_write(item)
        except (BrokenPipeError, ConnectionError, ConnectionResetError, ConnectionAbortedError, OSError):
            pass
        finally:
            bus.unsubscribe_sse(q)

    def _sse_write(self, obj: dict) -> None:
        self.wfile.write(f"data: {json.dumps(obj)}\n\n".encode("utf-8"))
        self.wfile.flush()

    def _req_token(self) -> str:
        """Token supplied by the client: ``?token=`` query param (EventSource can't set headers)
        or the ``X-9to5-Token`` header. Query wins so the page can bootstrap a single token."""
        tok = (parse_qs(urlparse(self.path).query).get("token") or [None])[0]
        if tok is None:
            tok = self.headers.get("X-9to5-Token")
        return tok or ""

    def _authed(self) -> bool:
        """True only when a real per-run token is bound AND the client presents it. An unset
        server token never authorizes (fail closed), mirroring the control-POST gate."""
        return bool(self.token) and self._req_token() == self.token

    def do_GET(self):  # noqa: N802
        # The data routes disclose the goal, absolute work_dir, cost, every subtask and up to
        # 500 raw stdout lines (which can contain secrets). The dashboard is reachable from the
        # public tunnel, so these MUST require the per-run token exactly like /api/control. Only
        # the token-less HTML shell (below) is served openly; it carries no run data itself and
        # bootstraps the token from the URL query string on the operator's own machine.
        if self.path.startswith(("/api/state", "/api/events", "/api/raw", "/api/council")) and not self._authed():
            self._send(403, b'{"ok":false,"error":"forbidden"}', "application/json")
            return
        if self.path.startswith("/api/state"):
            self._send(200, json.dumps(_snapshot(self.task_id)).encode("utf-8"), "application/json")
        elif self.path.startswith("/api/council"):
            try:
                state = TaskState.load(self.task_id)
                payload = read_transcript(state)
            except Exception:  # noqa: BLE001
                payload = {"ok": False, "error": "council transcript unavailable", "content": ""}
            self._send(200, json.dumps(payload).encode("utf-8"), "application/json")
        elif self.path.startswith("/api/events"):
            self._serve_sse()
        elif self.path.startswith("/api/raw"):
            sid = (parse_qs(urlparse(self.path).query).get("sid") or [""])[0]
            self._send(200, _raw_payload(sid).encode("utf-8"), "application/json")
        else:
            # View-only render: the control token is NEVER embedded in the served page
            # (it would leak over the public tunnel). Placeholder is blanked; control
            # POSTs require the token printed to the local console/log at startup.
            self._send(
                200, _PAGE.replace("__WEBDASH_TOKEN__", "").encode("utf-8"), "text/html; charset=utf-8"
            )

    def do_POST(self):  # noqa: N802
        # Drain the request body FIRST, before any response path. Responding (especially with
        # an error) while unread bytes remain in the socket buffer makes Windows close the
        # connection with an RST, which surfaces on the client as an intermittent
        # ConnectionAbortedError [WinError 10053]. Reading it up front means every path below
        # (404/403/200) has consumed it, so the close is always graceful.
        try:
            length = int(self.headers.get("Content-Length") or 0)
        except (TypeError, ValueError):
            length = 0
        length = max(0, min(length, 64_000))  # cap the read; control payloads are tiny
        raw_body = self.rfile.read(length) if length else b""

        if not self.path.startswith("/api/control"):
            self._send(404, b"{}", "application/json")
            return
        # Control gate: require the per-run control token that was printed to the local
        # console/log at startup. It is never served in HTML, so a tunnel/cross-origin
        # visitor cannot obtain it. Reject when the token is unset or mismatched.
        if not self.token or self.headers.get("X-9to5-Token") != self.token:
            self._send(403, b'{"ok":false,"error":"forbidden"}', "application/json")
            return
        try:
            payload = json.loads(raw_body or b"{}")
            if not isinstance(payload, dict):
                payload = {}
        except Exception:  # noqa: BLE001
            payload = {}
        action = payload.get("action") or ""
        if not isinstance(action, str):
            action = ""
        arg = payload.get("arg")
        if arg is not None and not isinstance(arg, str):
            arg = str(arg)
        result = _applyControl(self.task_id, action, arg)
        self._send(200, json.dumps(result).encode("utf-8"), "application/json")


def _makeHandler(task_id: str, token: str = ""):
    """Bind ``task_id``/``token`` onto a fresh handler subclass for this run's server."""
    return type("Handler", (_DashboardHandler,), {"task_id": task_id, "token": token})


_SERVER = None  # the live dashboard server, so it can be shut down between runs in one process


def startWebDashboard(task_id: str, port: Optional[int] = None) -> Optional[str]:
    """Start the dashboard in a daemon thread; return its URL (or None if disabled/failed)."""
    global _SERVER
    if not config.WEB_DASHBOARD:
        return None
    stopWebDashboard()  # never leak a prior run's server/port
    _SSE_STOP.clear()
    port = port or config.WEB_DASHBOARD_PORT
    import secrets

    global _CONTROL_TOKEN
    _CONTROL_TOKEN = secrets.token_urlsafe(16)  # per-run control token; console/log only, never in HTML
    token = _CONTROL_TOKEN
    try:
        server = _QuietThreadingHTTPServer(("127.0.0.1", port), _makeHandler(task_id, token))
    except OSError as e:
        LOG.warning("web dashboard could not bind :%s (%s)", port, e)
        return None
    _SERVER = server
    thread = threading.Thread(target=server.serve_forever, name="webdash", daemon=True)
    thread.start()
    url = f"http://127.0.0.1:{port}/"
    # The token gates BOTH control POSTs and the data GETs (state/events/raw). It is surfaced
    # ONLY here (local console/log) and never embedded in the page, so a tunnel visitor cannot
    # obtain it. Open the tokenized local URL below to view the dashboard; the bare URL renders
    # an empty shell by design.
    local_url = f"{url}?token={token}"
    LOG.info("Web dashboard at %s (open the tokenized URL below to view)", url)
    LOG.info("Web dashboard control token (local only): %s", token)
    print(f"[webdash] open (local only, do not share): {local_url}", flush=True)
    return url


def stopWebDashboard() -> None:
    """Shut down the running dashboard server (frees the port). Safe to call repeatedly."""
    global _SERVER, _CONTROL_TOKEN
    _SSE_STOP.set()  # release any blocked SSE reader threads
    _CONTROL_TOKEN = ""
    if _SERVER is not None:
        with best_effort("webdash.shutdown", log=LOG):
            _SERVER.shutdown()
            _SERVER.server_close()
        _SERVER = None
