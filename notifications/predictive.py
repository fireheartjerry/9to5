"""Predictive flags -- the system warns the operator before things go wrong.

Heuristic-first (cheap, deterministic). Pure engine: ``evaluate(state, history)`` returns the
flags implied by the supplied (injectable) history; ``emit_due(state, ...)`` applies the run
rate-limit (at most one flag per ``config.PREDICTIVE_FLAG_MIN_INTERVAL_SECONDS``, never the same
signal twice per run) and returns the single flag to post (or None). An optional natural-language
explanation is gated by ``config.PREDICTIVE_FLAG_OLLAMA`` (default off -> heuristics only).

All ledger data arrives via ``history`` (so tests never touch the DB); the real path fills it
from the experience ledger in ``_defaultHistory``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Flag  -- namedtuple(signal, severity, text)
  PredictiveFlags  -- heuristic flag engine with per-run rate limiting
DEPENDS-ON: config, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_predictive_flags.py
"""
from __future__ import annotations

import time
from collections import namedtuple
from difflib import SequenceMatcher
from typing import Callable, Optional

import config

LOG = config.getLogger("predictive")

Flag = namedtuple("Flag", "signal severity text")
_SEV_ORDER = {"low": 0, "medium": 1, "high": 2}
_HOTSPOT_MIN = 3            # file modified/buggy in >= N past runs -> hotspot
_VERIFY_SIM_MIN = 0.70     # verify-cmd string overlap with a known failing spec
_RUNTIME_RATIO_MIN = 2.5   # subtask runtime vs historical average


def _nonTerminal(state) -> list[dict]:
    return [s for s in state.subtasks if s.get("status") in ("pending", "in_progress")]


def _fileHotspotFlags(state, hist: dict) -> list[Flag]:
    hotspots = hist.get("file_hotspots") or {}
    out = []
    for s in _nonTerminal(state):
        hay = f"{s.get('title','')} {s.get('description','')}".lower()
        for path, count in hotspots.items():
            if int(count) >= _HOTSPOT_MIN and str(path).lower() in hay:
                out.append(Flag("file_hotspot", "high",
                                f"📁 `{path}` was a change/bug hotspot in {count} recent runs — "
                                f"elevated risk on `{s['subtask_id']}`."))
                break
    return out


def _verifySimilarityFlags(state, hist: dict) -> list[Flag]:
    failing = [str(c) for c in (hist.get("failing_specs") or []) if c]
    out = []
    for s in _nonTerminal(state):
        cmd = (s.get("verify") or {}).get("cmd")
        if not cmd:
            continue
        if any(SequenceMatcher(None, cmd, f).ratio() >= _VERIFY_SIM_MIN for f in failing):
            out.append(Flag("verify_similarity", "high",
                            f"⚠️ `{s['subtask_id']}` verify spec looks similar to one that caused "
                            f"retries in a past run. Pre-flagging."))
    return out


def _runtimeFlags(state, hist: dict) -> list[Flag]:
    ratios = hist.get("runtime_ratios") or {}
    out = []
    for sid, ratio in ratios.items():
        if float(ratio) > _RUNTIME_RATIO_MIN:
            out.append(Flag("runtime", "medium",
                            f"⏱ `{sid}` is {float(ratio):.1f}x slower than comparable subtasks. Watching."))
    return out


def _replanFlags(state, hist: dict) -> list[Flag]:
    avg = hist.get("replan_avg")
    if not avg:
        return []
    current = sum(1 for n in (state.data.get("notifications") or []) if n.get("kind") == "replan")
    if current > 2 * float(avg):
        return [Flag("replan", "medium",
                     f"🔁 {current} replans this run — over 2x the usual for this goal type.")]
    return []


def _paceFlags(state, hist: dict) -> list[Flag]:
    tr = hist.get("time_remaining_frac")
    wr = hist.get("work_remaining_frac")
    if tr is None or wr is None:
        return []
    if 0 < float(tr) < 0.2 and float(wr) > 0.4:
        return [Flag("pace", "high",
                     f"⏳ {int(float(wr)*100)}% of work remains but only {int(float(tr)*100)}% of the "
                     "time horizon is left — pace risk.")]
    return []


def _defaultHistory(state) -> dict:  # pragma: no cover -- reads the live experience ledger
    """Best-effort history pulled from the experience ledger for the real run path."""
    hist: dict = {"file_hotspots": {}, "failing_specs": []}
    try:
        from memory import experience
        for fm in experience.fetch_failure_modes()[:50]:
            tags = (fm.get("signature_tags") or "")
            for tok in tags.split(","):
                tok = tok.strip()
                if tok.endswith((".py", ".js", ".ts")):
                    hist["file_hotspots"][tok] = max(hist["file_hotspots"].get(tok, 0),
                                                     int(fm.get("occurrences", 1)))
        for st in experience.fetch_subtasks(limit=200):
            if not st.get("verify_passed") and st.get("verify_cmd"):
                hist["failing_specs"].append(st["verify_cmd"])
    except Exception as e:  # noqa: BLE001
        LOG.warning("predictive default history failed (ignored): %s", e)
    return hist


class PredictiveFlags:
    """Heuristic flag engine with per-run rate limiting."""

    def __init__(self) -> None:
        self._last_emit_ts: Optional[float] = None
        self._seen: set[str] = set()

    def evaluate(self, state, *, history: Optional[dict] = None) -> list[Flag]:
        hist = history if history is not None else _defaultHistory(state)
        flags: list[Flag] = []
        flags += _fileHotspotFlags(state, hist)
        flags += _verifySimilarityFlags(state, hist)
        flags += _runtimeFlags(state, hist)
        flags += _replanFlags(state, hist)
        flags += _paceFlags(state, hist)
        return flags

    def emit_due(self, state, *, history: Optional[dict] = None, now: Optional[float] = None,
                 chat: Optional[Callable[[str, str], str]] = None) -> Optional[Flag]:
        if not config.PREDICTIVE_FLAGS_ENABLED:
            return None
        now = now if now is not None else time.monotonic()
        candidates = [f for f in self.evaluate(state, history=history) if f.signal not in self._seen]
        if not candidates:
            return None
        if (self._last_emit_ts is not None
                and (now - self._last_emit_ts) < config.PREDICTIVE_FLAG_MIN_INTERVAL_SECONDS):
            return None
        candidates.sort(key=lambda f: _SEV_ORDER.get(f.severity, 0), reverse=True)
        chosen = candidates[0]
        self._seen.add(chosen.signal)
        self._last_emit_ts = now
        if config.PREDICTIVE_FLAG_OLLAMA and chat is not None:
            try:
                enriched = self._ollamaExplain(chosen, chat)
                if enriched:
                    chosen = chosen._replace(text=enriched)
            except Exception:  # noqa: BLE001
                pass
        return chosen

    @staticmethod
    def _ollamaExplain(flag: Flag, chat: Callable[[str, str], str]) -> str:  # pragma: no cover
        system = ("You are 9to5's predictive analyst. Given a fired heuristic flag, write ONE "
                  "natural-language sentence the operator can act on. No preamble.")
        return (chat(system, f"FLAG[{flag.signal}/{flag.severity}]: {flag.text}") or "").strip()
