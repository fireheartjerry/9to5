"""Bloomberg-terminal HTML page for the live web dashboard (data only, no logic).

Kept separate from ``notifications.webdash`` so the handler module stays small.
Assembled from ``webdash_markup`` (HTML skeleton), ``webdash_styles`` (CSS),
and ``webdash_script`` (client JS) — split out because the fully-featured page
exceeds the single-file line budget in ``tools/size_audit.py``.
``__WEBDASH_TOKEN__`` is substituted with the per-run control token before
serving (CSRF guard preserved from the legacy page).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  (no public exports)
DEPENDS-ON: config, notifications.webdash_markup, notifications.webdash_script, notifications.webdash_styles
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/notifications/test_webdash_page_split.py
"""
from __future__ import annotations

import config
from notifications.webdash_markup import MARKUP
from notifications.webdash_script import SCRIPT
from notifications.webdash_styles import STYLES

_SCRIPT = (
    SCRIPT
    .replace("__ACTIVE_POLL__", str(int(getattr(config, "WEBDASH_ACTIVE_POLL_SECONDS", 2)) * 1000))
    .replace("__IDLE_POLL__", str(int(getattr(config, "WEBDASH_IDLE_POLL_SECONDS", 8)) * 1000))
)

PAGE = MARKUP.format(styles=STYLES, script=_SCRIPT)
