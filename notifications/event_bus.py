"""LiveEventBus -- the single nervous system every 9to5 surface listens to.

Every event in the system -- raw subprocess stdout lines, parsed tool calls, phase
transitions, heartbeats, cost updates, moments, narration posts, learning signals --
flows through one process-global bus. Nothing bypasses it. The bus fans out to:
  * web SSE subscribers (one queue per open browser tab) -- zero-poll live feed
  * an optional throttled Discord layer (set via ``set_discord_feed``)

Ring buffers bound memory: 10,000 raw lines, 2,000 structured events, 1,000 raw lines
per subtask. Producers never block: a full SSE queue drops the event for that tab only.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Event  -- A structured, fan-out event (kind/sid/text/data/ts).
  RawLine  -- One raw stdout line tagged with its subtask id.
  LiveEventBus  -- Ring-buffered pub/sub bus for all surfaces.
  get_bus() -> LiveEventBus  -- Process-global singleton accessor.
  reset_bus() -> None  -- Drop the singleton (test hook).
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_event_bus.py
"""
from __future__ import annotations

import queue
import threading
import time
from collections import deque
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Optional

_RAW_MAX = 10_000
_STRUCTURED_MAX = 2_000
_PER_SID_MAX = 1_000
_SSE_QUEUE_MAX = 1_000


@dataclass
class Event:
    """A structured, fan-out event. ``ts`` is a monotonic timestamp for ordering."""
    kind: str
    sid: str
    text: str
    data: dict = field(default_factory=dict)
    ts: float = field(default_factory=time.monotonic)

    def to_dict(self) -> dict[str, Any]:
        return {
            "kind": self.kind,
            "sid": self.sid,
            "text": self.text,
            "data": self.data,
            "ts": self.ts,
            "at": datetime.now().astimezone().strftime("%H:%M:%S"),
        }


@dataclass
class RawLine:
    """One raw stdout line tagged with its subtask id."""
    sid: str
    line: str
    ts: float = field(default_factory=time.monotonic)

    def to_dict(self) -> dict[str, Any]:
        return {"sid": self.sid, "line": self.line, "ts": self.ts}


class LiveEventBus:
    """Ring-buffered pub/sub bus. Thread-safe; producers never block on slow consumers."""

    def __init__(self) -> None:
        self._raw: deque[RawLine] = deque(maxlen=_RAW_MAX)
        self._structured: deque[Event] = deque(maxlen=_STRUCTURED_MAX)
        self._per_sid: dict[str, deque[RawLine]] = {}
        self._sse_queues: list[queue.Queue] = []
        self._discord_feed: Any = None
        self._lock = threading.Lock()

    # ---- producers ------------------------------------------------------
    def emit_raw(self, sid: str, line: str) -> None:
        """Store a raw stdout line in the global + per-subtask rings (not fanned to SSE)."""
        rl = RawLine(sid=sid, line=line)
        with self._lock:
            self._raw.append(rl)
            ring = self._per_sid.get(sid)
            if ring is None:
                ring = self._per_sid[sid] = deque(maxlen=_PER_SID_MAX)
            ring.append(rl)

    def emit(self, event: Event) -> None:
        """Append a structured event and fan it out to all SSE subscribers + Discord."""
        payload = event.to_dict()
        with self._lock:
            self._structured.append(event)
            subscribers = list(self._sse_queues)
            feed = self._discord_feed
        for q in subscribers:
            try:
                q.put_nowait(payload)
            except queue.Full:  # a slow tab must never stall a producer
                pass
        if feed is not None:
            try:
                feed.consume_event(event)
            except Exception:  # noqa: BLE001 -- the Discord layer is best-effort
                pass

    # ---- SSE subscribers ------------------------------------------------
    def subscribe_sse(self) -> queue.Queue:
        q: queue.Queue = queue.Queue(maxsize=_SSE_QUEUE_MAX)
        with self._lock:
            self._sse_queues.append(q)
        return q

    def unsubscribe_sse(self, q: queue.Queue) -> None:
        with self._lock:
            try:
                self._sse_queues.remove(q)
            except ValueError:
                pass

    def sse_subscriber_count(self) -> int:
        with self._lock:
            return len(self._sse_queues)

    def set_discord_feed(self, feed: Any) -> None:
        with self._lock:
            self._discord_feed = feed

    # ---- history --------------------------------------------------------
    def history(self, sid: Optional[str] = None, last_n: int = 200) -> list[dict[str, Any]]:
        with self._lock:
            events = list(self._structured)
        if sid is not None:
            events = [e for e in events if e.sid == sid]
        return [e.to_dict() for e in events[-last_n:]]

    def raw_history(self, sid: str, last_n: int = 500) -> list[dict[str, Any]]:
        with self._lock:
            ring = self._per_sid.get(sid)
            lines = list(ring) if ring is not None else []
        return [r.to_dict() for r in lines[-last_n:]]


_BUS: Optional[LiveEventBus] = None
_BUS_LOCK = threading.Lock()


def get_bus() -> LiveEventBus:
    """Process-global singleton -- the one bus every surface shares."""
    global _BUS
    if _BUS is None:
        with _BUS_LOCK:
            if _BUS is None:
                _BUS = LiveEventBus()
    return _BUS


def reset_bus() -> None:
    """Drop the singleton so the next ``get_bus`` builds a fresh one (test hook)."""
    global _BUS
    with _BUS_LOCK:
        _BUS = None
