"""Discord REST plumbing: single HTTP chokepoint, rate-limit circuit breaker, session state.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  truncate(text, n: int) -> str  -- Clamp to n chars, marking a clip with a trailing ellipsis.
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/notifications/test_bot_replay.py tests/notifications/test_discord_rest.py
"""
from __future__ import annotations

import json as _jsonlib   # aliased: the _request kwarg is named `json` (Discord body)
import os
import sys
import time
from typing import Optional

import requests

import config

LOG = config.getLogger("discord")

_SESSION = requests.Session()   # persistent connection pool; reused across all REST calls


def _realDiscordBlocked() -> bool:
    """True when a REAL Discord REST call must be REFUSED (unit/CI context).

    Mirrors ``work_launcher._spawnBlocked`` / ``gemini_driver._realApiBlocked``: this chokepoint
    normally only avoids the live channel because conftest.py blanks DISCORD_BOT_TOKEN/
    DISCORD_CHANNEL_ID for pytest -- a test file invoked directly (bare ``python test_x.py`` /
    ``python -m unittest``) never loads conftest.py and so isn't sandboxed at all, letting a
    stray test post to the real channel. This is a second, independent guard so that escape
    hatch can't reach the network regardless of how the test got invoked."""
    allow = os.getenv("NINE_TO_FIVE_TEST_MODE", "").strip().lower()
    if allow in {"0", "false", "no", "off"}:
        return False                       # explicit opt-out: tests that assert the real path
    if allow in {"1", "true", "yes", "on"}:
        return True
    # env unset -> auto-detect a live test runner so a forgotten/bypassed sandbox never posts live.
    return "unittest" in sys.modules or "pytest" in sys.modules

_API = "https://discord.com/api/v10"

# =====================================================================
# Rate-limit state and auth
# =====================================================================
_DISABLED = False   # latched ON only by a hard 401 (bad token); never by 403/404
# Global 429 circuit breaker: a monotonic deadline. While now < this, EVERY REST call short-circuits
# locally (returns None without touching the network). Discord rate-limits are global to the bot, so
# without this any caller -- the 4s control poll, the dashboard PATCH, parallel workers -- keeps
# hitting a rate-limited API and deepens the ban (the same-millisecond 429 storms seen in logs). The
# chokepoint itself now enforces the backoff so no caller can hammer regardless of its loop cadence.
_RATE_LIMITED_UNTIL = 0.0
_RL_COOLDOWN_MAX = 60.0   # sanity cap so a malformed huge retry_after can't wedge Discord off for long


def _authHeaders() -> dict:
    return {"Authorization": f"Bot {config.DISCORD_BOT_TOKEN}", "Content-Type": "application/json"}


def _authHeadersMultipart() -> dict:
    """Auth without Content-Type: requests sets the multipart boundary itself for file uploads."""
    return {"Authorization": f"Bot {config.DISCORD_BOT_TOKEN}"}


def _requestHeaders(noauth: bool, files: Optional[dict]) -> dict:
    """Webhook-execute (noauth) is authorized by the token IN the URL, so it carries no Bot
    header; a multipart upload drops Content-Type so requests can set its own boundary."""
    if noauth:
        return {}
    if files is not None:
        return _authHeadersMultipart()
    return _authHeaders()


def _ownerMentions() -> dict:
    """allowed_mentions that can never expand past the configured owner."""
    oid = (config.DISCORD_HUMAN_USER_ID or "").strip()
    # Discord snowflakes must be JSON strings, not ints (a bare int can exceed JS safe-int range
    # and Discord rejects/mangles it); keep the numeric string as-is.
    return {"parse": [], "users": [oid] if oid.isdigit() else []}


def _request(method: str, path: str, *, json: Optional[dict] = None,
             params: Optional[dict] = None, data: Optional[dict] = None,
             files: Optional[dict] = None, noauth: bool = False,
             retries: int = config.DISCORD_RETRY_MAX):
    """Single REST chokepoint. 429 -> sleep(retry_after) up to `retries` (milestone sends);
    pass retries=0 on the control-poll path so it never blocks the run loop. A hard 401 latches
    the whole surface off; 403/404 are logged but NEVER disable (a deleted message is normal).

    Multipart: pass ``files`` (+ ``data`` carrying ``payload_json``) to upload attachments
    (Pillow cockpit images, GIF replays, persona cards). When ``files`` is set the JSON
    Content-Type is dropped so requests can set the multipart boundary itself. Everything else
    -- the 429 breaker, the 401 latch, the timeout -- is identical so no upload can bypass them."""
    global _DISABLED, _RATE_LIMITED_UNTIL
    if _DISABLED or not config.DISCORD_BOT_TOKEN or not config.DISCORD_CHANNEL_ID:
        return None
    if _realDiscordBlocked():
        return None
    # Global 429 circuit breaker: while inside the rate-limit window, do not touch the network at all.
    if time.monotonic() < _RATE_LIMITED_UNTIL:
        return None
    url = f"{_API}{path}"
    attempt = 0
    while True:
        headers = _requestHeaders(noauth, files)
        try:
            if files is not None:
                r = _SESSION.request(method, url, headers=headers, data=data,
                                     files=files, params=params, timeout=config.DISCORD_REST_TIMEOUT)
            else:
                r = _SESSION.request(method, url, headers=headers, json=json, params=params,
                                     timeout=config.DISCORD_REST_TIMEOUT)
        except Exception as e:  # noqa: BLE001
            LOG.warning("Discord %s %s failed: %s", method, path, e)
            return None
        if r.status_code == 429:
            try:
                retry_after = float((r.json() or {}).get("retry_after",
                                    r.headers.get("Retry-After", 1)))
            except Exception:  # noqa: BLE001
                retry_after = 1.0
            retry_after = min(max(retry_after, 0.0), _RL_COOLDOWN_MAX)
            # Arm the global breaker so the NEXT call (any path, any thread) short-circuits instead of
            # re-hitting the rate-limited API -- this is what stops the 429 storm even on retries=0.
            _RATE_LIMITED_UNTIL = time.monotonic() + retry_after
            if attempt < retries:
                time.sleep(retry_after)
                attempt += 1
                continue
            # poll path (retries=0): return now without blocking the run loop; the breaker above
            # throttles every subsequent call until the window passes. Log once (not per-spin).
            LOG.warning("Discord %s %s -> 429; global backoff %.1fs", method, path, retry_after)
            return r
        if r.status_code == 401:
            # Only the bot-token auth path may latch the whole surface off. A noauth webhook
            # request (The Cast) is authed by the token IN its URL; a bad/rotated Cast token
            # must fail just that one send, never disable the live dashboard / milestone /
            # BLOCKED-decision pings that ride the bot token. The Cast "must never break a run".
            if noauth:
                LOG.warning("Discord webhook auth failed (401) -> Cast send dropped, surface left alive")
                return r
            _DISABLED = True
            LOG.error("Discord auth failed (401) -> disabling Discord for this process")
        elif not (200 <= r.status_code < 300) and r.status_code != 404:
            LOG.warning("Discord %s %s -> %s: %s", method, path, r.status_code, (r.text or "")[:200])
        return r


# =====================================================================
# Shared payload utilities (used by channel senders)
# =====================================================================
def truncate(text, n: int) -> str:
    """Clamp to n chars, marking a clip with a trailing ellipsis."""
    text = str(text if text is not None else "")
    if n <= 1:
        return text[:max(n, 0)]
    return text if len(text) <= n else text[:n - 1].rstrip() + "…"


def _embedLen(embed: dict) -> int:
    total = len(str(embed.get("title", ""))) + len(str(embed.get("description", "")))
    total += len(str((embed.get("footer") or {}).get("text", "")))
    for f in embed.get("fields", []) or []:
        total += len(str(f.get("name", ""))) + len(str(f.get("value", "")))
    return total


def _clampEmbed(embed: dict) -> dict:
    """Guarantee a sendable embed: title + per-field clamp (no oversize part can 400 the whole
    message), <=25 fields, and a hard 6000-total budget. The budget is enforced by shrinking the
    largest field VALUE first (dashboard tail rows survive longest), then the largest field NAME,
    then dropping trailing fields — so a many-long-names embed can never exceed the total limit."""
    if not isinstance(embed, dict):
        return embed
    e = dict(embed)
    if isinstance(e.get("title"), str):
        e["title"] = truncate(e["title"], config.DISCORD_MAX_EMBED_TITLE)
    if isinstance(e.get("description"), str):
        e["description"] = truncate(e["description"], config.DISCORD_MAX_EMBED_DESC)
    fields = e.get("fields")
    if isinstance(fields, list):
        clamped = []
        for f in fields[:25]:
            if not isinstance(f, dict):
                continue
            nf = dict(f)
            nf["name"] = truncate(nf.get("name", ""), config.DISCORD_MAX_FIELD_NAME)
            nf["value"] = truncate(nf.get("value", ""), config.DISCORD_MAX_FIELD_VALUE) or "—"
            clamped.append(nf)
        e["fields"] = clamped
        _shrinkEmbedToBudget(e)
    return e


def _shrinkEmbedToBudget(e: dict) -> None:
    """Mutate ``e`` in place until _embedLen(e) <= the total budget: shrink largest value, then
    largest name, then drop the last field as a final fallback (guaranteed to terminate)."""
    guard = 0
    while _embedLen(e) > config.DISCORD_EMBED_TOTAL_MAX and guard < 200:
        guard += 1
        over = _embedLen(e) - config.DISCORD_EMBED_TOTAL_MAX
        fields = e["fields"]
        val = max(fields, key=lambda f: len(str(f.get("value", ""))), default=None)
        if val is not None and len(str(val.get("value", ""))) > 8:
            cur = len(str(val["value"]))
            val["value"] = truncate(val["value"], max(8, cur - over - 1))
            continue
        nm = max(fields, key=lambda f: len(str(f.get("name", ""))), default=None)
        if nm is not None and len(str(nm.get("name", ""))) > 1:
            cur = len(str(nm.get("name", "")))
            nm["name"] = truncate(nm["name"], max(1, cur - over - 1))
            continue
        if fields:                       # values + names at floor: drop a trailing field
            fields.pop()
            continue
        break                            # no fields left; title/description already clamped


def _cv2TextLen(components) -> int:
    """Total text length across a CV2 tree (TextDisplay content + button labels)."""
    total = 0

    def walk(node):
        nonlocal total
        if isinstance(node, dict):
            if node.get("type") == 10:        # TextDisplay
                total += len(str(node.get("content", "")))
            elif node.get("type") == 2:       # Button
                total += len(str(node.get("label", "")))
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for it in node:
                walk(it)

    walk(components)
    return total


def _cv2Count(components) -> int:
    """Total component nodes (anything carrying a numeric 'type') -- Discord caps a CV2 tree at 40."""
    n = 0

    def walk(node):
        nonlocal n
        if isinstance(node, dict):
            if isinstance(node.get("type"), int):
                n += 1
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for it in node:
                walk(it)

    walk(components)
    return n


def _clampComponents(components: list) -> list:
    """Best-effort guard so a runaway cockpit can never 400 the whole message: trim top-level
    components from the END (controls/events tail) until the tree is within Discord's
    40-component / 4000-char CV2 budget, so the header + progress zones always survive."""
    comps = list(components or [])
    limit = len(comps) + 1   # at most one pop per top-level component -> always converges to budget
    guard = 0
    while comps and guard < limit and (
            _cv2Count(comps) > config.DISCORD_CV2_MAX_COMPONENTS
            or _cv2TextLen(comps) > config.DISCORD_CV2_MAX_CHARS):
        guard += 1
        comps.pop()
    # A CV2 message with zero components is rejected by Discord (HTTP 400), so the whole update
    # would fail instead of degrading. If clamping emptied the tree (or it was empty to begin with),
    # fall back to a minimal valid container so the message still sends.
    if not comps:
        comps = [{"type": 17, "components": [{"type": 10, "content": "…"}]}]
    return comps


def _multipartParts(payload: dict, files: list) -> tuple[dict, dict]:
    """Wire Discord's multipart convention: payload_json + attachments[]. ``files`` is a list of
    (filename, raw_bytes, content_type); returns (data, files) ready for requests."""
    attachments = []
    fdict: dict = {}
    for i, (fname, fbytes, ctype) in enumerate(files):
        attachments.append({"id": i, "filename": fname})
        fdict[f"files[{i}]"] = (fname, fbytes, ctype or "application/octet-stream")
    body = dict(payload)
    body["attachments"] = attachments
    return {"payload_json": _jsonlib.dumps(body)}, fdict
