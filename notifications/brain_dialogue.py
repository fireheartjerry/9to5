"""Brain dialogue -- a direct window into the Ollama brain's reasoning, mid-run.

Pure, testable core (mirrors ``notifications.ask``): ``build_context(state, kind, arg)``
assembles the plan + recent events + the operator's question; ``answer(kind, arg, state,
*, chat=None)`` queries the brain in the voice of a thoughtful engineer (system prompt from
``config.BRAIN_DIALOGUE_SYSTEM_PROMPT``) and degrades gracefully when Ollama is offline.

Commands: ``!why`` / ``!why <decision>`` / ``!explain st-003`` / ``!plan-rationale`` / ``!ask``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  build_context(state, kind: str, arg: str) -> str
  answer(kind: str, arg: str, state, *, chat: Optional[Callable[[str, str], str]]=None) -> str  -- Answer a brain-dialogue command
DEPENDS-ON: config, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_brain_dialogue.py
"""
from __future__ import annotations

from typing import Callable, Optional

import config
import llm_io

LOG = config.getLogger("brain_dialogue")

_SID_RE_HINT = "st-"


def _planLines(state) -> list[str]:
    out = ["PLAN:"]
    for s in state.subtasks:
        if s.get("status") == "removed":
            continue
        deps = s.get("depends_on") or []
        dep_txt = f" depends_on={deps}" if deps else ""
        vr = s.get("verify_result") or {}
        mark = " PASS" if vr.get("passed") else (" FAIL" if vr else "")
        out.append(f"  {s['subtask_id']} [{s.get('status')}]{mark} {s.get('title','')}{dep_txt}")
    return out


def _recentEvents(state, n: int = 3) -> list[str]:
    notifs = (state.data.get("notifications") or [])[-n:]
    return ["RECENT EVENTS:"] + [f"  {x.get('kind','?')}: {x.get('detail','')}" for x in notifs]


def build_context(state, kind: str, arg: str) -> str:
    m = state.meta
    head = [f"GOAL: {m.get('goal_elaborated') or m.get('goal_raw','')}",
            f"STATUS: {m.get('status','?')}"]
    body = _planLines(state)
    if kind == "explain":
        target = next((s for s in state.subtasks if s["subtask_id"] == arg.strip()), None)
        if target is not None:
            body += ["", f"FOCUS SUBTASK {target['subtask_id']}: {target.get('title','')}",
                     f"  description: {target.get('description','')}",
                     f"  verify: {(target.get('verify') or {}).get('cmd')}"]
        question = f"What is {arg.strip()} trying to achieve, and how does it fit the plan?"
    elif kind in ("why", ""):
        question = arg.strip() or "Why is the current subtask ordered the way it is?"
    elif kind == "plan-rationale":
        question = "Why is the plan structured this way overall? Explain the ordering and dependencies."
    else:  # ask
        question = arg.strip() or "Give me your read on the current run."
    return "\n".join(head + body + _recentEvents(state) + ["", f"QUESTION: {question}"])


def _defaultChat(system: str, user: str) -> str:  # pragma: no cover -- needs live Ollama
    import ollama
    client = ollama.Client(host=config.OLLAMA_HOST, timeout=config.OLLAMA_TIMEOUT_SECONDS)
    resp = client.chat(model=config.BRIEF_MODEL,
                       messages=[{"role": "system", "content": system},
                                 {"role": "user", "content": user}],
                       options={"num_ctx": config.OLLAMA_NUM_CTX},
                       keep_alive=config.OLLAMA_KEEP_ALIVE)
    return llm_io.responseText(resp)


def answer(kind: str, arg: str, state, *,
           chat: Optional[Callable[[str, str], str]] = None) -> str:
    """Answer a brain-dialogue command. Never raises; degrades to a friendly offline message."""
    if kind == "explain":
        sid = arg.strip()
        if sid and not any(s["subtask_id"] == sid for s in state.subtasks):
            return f"`{sid}` isn't in the current plan — try `!plan` for the live subtask list."
    chat = chat or _defaultChat
    ctx = build_context(state, kind, arg)
    try:
        out = (chat(config.BRAIN_DIALOGUE_SYSTEM_PROMPT, ctx) or "").strip()
        return out or "The brain returned an empty answer — try rephrasing."
    except Exception:  # noqa: BLE001
        LOG.warning("brain_dialogue.answer failed", exc_info=True)
        return "Brain offline (Ollama unavailable). Use `/status` for the raw run state."
