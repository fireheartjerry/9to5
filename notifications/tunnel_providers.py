"""Tunnel providers -- pluggable public-URL backends for the local web dashboard.

Each provider knows how to (a) decide if it is usable, (b) ensure its binary exists
(auto-downloading when possible), (c) launch a tunnel to a local port, (d) parse its
public URL out of the process's stdout, and (e) probe that URL for end-to-end reach.

Priority order (``default_providers``): cloudflared (no account, auto-downloaded, most
reliable) -> ngrok (only with NGROK_AUTH_TOKEN) -> bore (open-source) -> localtunnel
(npx). ``TunnelManager`` supervises and fails over between them.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  TunnelProvider  -- Base interface
  CloudflaredProvider
  NgrokProvider
  BoreProvider
  LocaltunnelProvider
  default_providers() -> list  -- Providers in priority order (cloudflared first, localtunnel last).
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import os
import platform
import re
import shutil
import stat
import subprocess
import urllib.error
import urllib.request
from pathlib import Path
from typing import Optional

import config

LOG = config.getLogger("tunnel.providers")

_CF_RE = re.compile(r"https://[a-z0-9-]+\.trycloudflare\.com")
_NGROK_RE = re.compile(r"https://[-a-z0-9]+\.ngrok(?:[-a-z0-9.]*)?\.(?:app|io)")
_BORE_RE = re.compile(r"bore\.pub:(\d+)")
_LT_RE = re.compile(r"https://[a-z0-9-]+\.loca\.lt")


class TunnelProvider:
    """Base interface. Subclasses override the verbs; defaults are safe no-ops."""

    name: str = "base"

    def available(self) -> bool:
        return False

    def ensure_available(self) -> bool:
        return False

    def start(self, port: int) -> "subprocess.Popen":
        raise NotImplementedError

    def parse_url(self, line: str) -> Optional[str]:
        return None

    def probe(self, url: str, timeout: float = 5.0) -> bool:
        """True when an HTTP GET returns a non-5xx status (end-to-end reachability)."""
        try:
            req = urllib.request.Request(url, method="GET", headers={"User-Agent": "9to5-probe"})
            with urllib.request.urlopen(req, timeout=timeout) as resp:   # noqa: S310 -- known https
                return int(getattr(resp, "status", 200)) < 500
        except urllib.error.HTTPError as e:   # an HTTP error code is still "reachable" if <500
            return int(getattr(e, "code", 500)) < 500
        except Exception:  # noqa: BLE001 -- connection refused / timeout / DNS -> unreachable
            return False

    # ---- shared download helper ----------------------------------------
    @staticmethod
    def _download_binary(url: str, dest: Path) -> bool:
        """Download a binary to ``dest`` and mark it executable. Best-effort."""
        try:
            dest.parent.mkdir(parents=True, exist_ok=True)
            urllib.request.urlretrieve(url, dest)   # noqa: S310 -- pinned vendor URL
            dest.chmod(dest.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
            return dest.exists()
        except Exception as e:  # noqa: BLE001
            LOG.warning("binary download failed (%s): %s", url, e)
            return False


def _plat() -> "tuple[str, str, str]":
    """Return (os_token, arch_token, exe_suffix) for asset-name construction."""
    sysname = platform.system().lower()
    os_token = {"windows": "windows", "darwin": "darwin"}.get(sysname, "linux")
    machine = platform.machine().lower()
    arch = "arm64" if machine in ("arm64", "aarch64") else "amd64"
    return os_token, arch, (".exe" if os_token == "windows" else "")


class CloudflaredProvider(TunnelProvider):
    name = "cloudflared"

    def __init__(self) -> None:
        self._bin: Optional[str] = None

    def available(self) -> bool:
        return True   # binary is auto-downloadable with no account

    def _cached_path(self) -> Path:
        _os, _arch, suffix = _plat()
        return Path.home() / ".cloudflared" / f"cloudflared{suffix}"

    def ensure_available(self) -> bool:
        found = shutil.which("cloudflared")
        if found:
            self._bin = found
            return True
        cached = self._cached_path()
        if cached.exists():
            self._bin = str(cached)
            return True
        os_token, arch, suffix = _plat()
        url = ("https://github.com/cloudflare/cloudflared/releases/latest/download/"
               f"cloudflared-{os_token}-{arch}{suffix}")
        if self._download_binary(url, cached):
            self._bin = str(cached)
            return True
        return False

    def start(self, port: int) -> "subprocess.Popen":
        binary = self._bin or "cloudflared"
        cmd = [binary, "tunnel", "--no-autoupdate", "--url", f"http://127.0.0.1:{port}"]
        return _spawn(cmd)

    def parse_url(self, line: str) -> Optional[str]:
        m = _CF_RE.search(line or "")
        return m.group(0) if m else None


class NgrokProvider(TunnelProvider):
    name = "ngrok"

    def __init__(self) -> None:
        self._bin: Optional[str] = None

    def available(self) -> bool:
        return bool(os.getenv("NGROK_AUTH_TOKEN"))

    def ensure_available(self) -> bool:
        if not self.available():
            return False
        found = shutil.which("ngrok")
        if found:
            self._bin = found
            return True
        return False   # ngrok install needs an account flow; do not auto-fetch

    def start(self, port: int) -> "subprocess.Popen":
        binary = self._bin or "ngrok"
        return _spawn([binary, "http", str(port), "--log", "stdout"])

    def parse_url(self, line: str) -> Optional[str]:
        m = _NGROK_RE.search(line or "")
        return m.group(0) if m else None


class BoreProvider(TunnelProvider):
    name = "bore"

    def __init__(self) -> None:
        self._bin: Optional[str] = None

    def available(self) -> bool:
        return True

    def ensure_available(self) -> bool:
        found = shutil.which("bore")
        if found:
            self._bin = found
            return True
        return False   # bore release assets are versioned tarballs; require a pre-installed binary

    def start(self, port: int) -> "subprocess.Popen":
        binary = self._bin or "bore"
        return _spawn([binary, "local", str(port), "--to", "bore.pub"])

    def parse_url(self, line: str) -> Optional[str]:
        m = _BORE_RE.search(line or "")
        return f"http://bore.pub:{m.group(1)}" if m else None


class LocaltunnelProvider(TunnelProvider):
    name = "localtunnel"

    def available(self) -> bool:
        return shutil.which("npx") is not None

    def ensure_available(self) -> bool:
        return self.available()

    def start(self, port: int) -> "subprocess.Popen":
        return _spawn(["npx", "localtunnel", "--port", str(port)])

    def parse_url(self, line: str) -> Optional[str]:
        m = _LT_RE.search(line or "")
        return m.group(0) if m else None


def _spawn(cmd: list) -> "subprocess.Popen":
    """Launch a tunnel process with a line-buffered text stdout pipe."""
    creationflags = subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0
    return subprocess.Popen(
        cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
        text=True, encoding="utf-8", errors="replace", bufsize=1,
        creationflags=creationflags, start_new_session=(os.name != "nt"))


def default_providers() -> list:
    """Providers in priority order (cloudflared first, localtunnel last)."""
    return [CloudflaredProvider(), NgrokProvider(), BoreProvider(), LocaltunnelProvider()]
