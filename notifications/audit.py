"""File-backed audit log: who issued which control command. JSON-lines at
config.AUDIT_LOG_PATH, size-rotated. Best-effort -- never raises into a command.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  record(user_id, action: str, task_id: Optional[str]=None, detail: str='') -> None  -- Append one audit entry
  recent(n: int=20) -> list[dict]  -- The last n audit entries (oldest-first within the window)
DEPENDS-ON: config, platform_core.core
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/notifications/test_audit.py
"""
from __future__ import annotations

from typing import Optional

import config
from platform_core.core import clock, jsonl_io

LOG = config.getLogger("audit")


def record(user_id, action: str, task_id: Optional[str] = None, detail: str = "") -> None:
    """Append one audit entry. Swallows all errors (audit must never break a command)."""
    try:
        entry = {
            "at": clock.nowIsoLocal(),
            "user_id": str(user_id) if user_id is not None else None,
            "action": action,
            "task_id": task_id,
            "detail": detail,
        }
        jsonl_io.appendRecord(config.AUDIT_LOG_PATH, entry,
                              max_bytes=config.AUDIT_MAX_BYTES)   # size-rotates to .1
    except Exception as e:  # noqa: BLE001
        LOG.warning("audit record failed: %s", e)


def recent(n: int = 20) -> list[dict]:
    """The last n audit entries (oldest-first within the window). [] on any error."""
    try:
        return jsonl_io.readTail(config.AUDIT_LOG_PATH, n)
    except Exception as e:  # noqa: BLE001
        LOG.warning("audit recent failed: %s", e)
        return []
