"""webdash -- a zero-dependency local web dashboard for a running task.

Stdlib ``http.server`` only. Serves a Bloomberg-terminal view of the latest/!named task
plus control buttons (abort / pause / resume / approve / reject / skip) that write straight
to the ControlBus. The live feed is pushed over Server-Sent Events from the LiveEventBus
(zero polling lag); metadata/subtasks poll ``/api/state``; per-subtask raw stdout is fetched
from ``/api/raw``. Runs in a daemon thread started by the orchestrator; dies with the process.

Routes:
  GET  /              -> Bloomberg HTML page (SSE + poll)
  GET  /api/state     -> JSON snapshot {meta, subtasks, health, arc, wisdom_trail, ...}
  GET  /api/events    -> Server-Sent Events stream of bus events
  GET  /api/raw?sid=  -> JSON list of the last 500 raw stdout lines for a subtask
  POST /api/control   -> {action, arg} -> ControlBus mutation

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  startWebDashboard(task_id: str, port: Optional[int]=None) -> Optional[str]  -- Start the dashboard in a daemon thread
  stopWebDashboard() -> None  -- Shut down the running dashboard server (frees the port)
DEPENDS-ON: config, notifications.event_bus, notifications.health_aura, notifications.webdash_page, platform_core.runtime.control, state.task
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_webdash_control.py tests/test_bloomberg_webdash.py
"""
from __future__ import annotations

import json
import queue
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from typing import Optional
from urllib.parse import parse_qs, urlparse

import config
from notifications.event_bus import get_bus
from notifications.health_aura import aura_color, compute_health
from notifications.webdash_page import PAGE as _PAGE
from platform_core.runtime.control import GATES, ControlBus
from state.task import TaskState

LOG = config.getLogger("webdash")

_SSE_STOP = threading.Event()


# --------------------------------------------------------------------------- payload builders
def _raw_payload(sid: str) -> str:
    """JSON list of the last 500 raw stdout lines for ``sid`` (for /api/raw)."""
    try:
        return json.dumps(get_bus().raw_history(sid, last_n=500))
    except Exception:  # noqa: BLE001
        return "[]"


def _wisdom_trail(goal: str) -> list:
    """Top-3 past-run lessons relevant to ``goal`` (keyword match over SIE reflections)."""
    try:
        from memory import experience
        rows = experience.fetch_reflections()
        tokens = {w for w in (goal or "").lower().split() if len(w) > 3}
        scored = []
        for r in rows:
            text = " ".join(str(r.get(k) or "") for k in ("reusable_recipe", "approach", "verify_critique"))
            summary = (r.get("reusable_recipe") or r.get("approach") or "").strip()
            if not summary:
                continue
            score = sum(1 for t in tokens if t in text.lower())
            scored.append((score, {"summary": summary[:80], "run": str(r.get("run_id") or "")[:8]}))
        scored.sort(key=lambda x: x[0], reverse=True)
        return [s[1] for s in scored[:3] if s[0] > 0] or [s[1] for s in scored[:3]]
    except Exception:  # noqa: BLE001
        return []


def _intelligence_curve() -> list:
    """Domain-by-domain confidence (best-effort; [] when the ledger has nothing usable)."""
    try:
        from memory import experience
        rows = experience.fetch_subtasks() if hasattr(experience, "fetch_subtasks") else []
        buckets: dict[str, list] = {}
        for r in rows[-300:]:
            title = str(r.get("title") or r.get("subtask_id") or "").lower()
            domain = next((w for w in title.split() if len(w) > 4), None)
            if not domain:
                continue
            buckets.setdefault(domain, []).append(1 if r.get("verify_passed") else 0)
        out = [{"domain": d[:12], "pct": round(100 * sum(v) / len(v))}
               for d, v in buckets.items() if len(v) >= 2]
        out.sort(key=lambda x: x["pct"], reverse=True)
        return out[:6]
    except Exception:  # noqa: BLE001
        return []


def _discovery_block(meta: dict) -> Optional[dict]:
    dr = meta.get("discovery_report") or {}
    if not dr:
        return None
    findings = dr.get("findings")
    return {"findings": len(findings) if isinstance(findings, list) else (findings or 0),
            "theme": dr.get("theme_suggestion") or "—"}


def _derive_model(state: TaskState) -> str:
    for s in reversed(state.subtasks):
        m = (s.get("session") or {}).get("model")
        if m:
            return m
    return config.PRIMARY_MODEL


def _comparative(task_id: str) -> Optional[dict]:
    try:
        from memory import experience
        c = experience.compare_run(task_id)
        return {k: c.get(k) for k in ("pace", "innovation", "adversary", "replans")}
    except Exception:  # noqa: BLE001
        return None


def _timing(meta: dict) -> "tuple[float, float]":
    from datetime import datetime
    try:
        started = datetime.fromisoformat(meta["started_at"])
        deadline = datetime.fromisoformat(meta["deadline_at"])
        now = datetime.now().astimezone()
        return (now - started).total_seconds(), (deadline - now).total_seconds()
    except Exception:  # noqa: BLE001
        return 0.0, 0.0


def _snapshot(task_id: str) -> dict:
    try:
        state = TaskState.load(task_id)
    except Exception:  # noqa: BLE001
        return {"empty": True}
    bus = ControlBus(task_id).load()
    done, total = state.progress()
    m = dict(state.meta)
    m["task_id"] = state.task_id
    elapsed_s, eta_s = _timing(state.meta)
    score = compute_health(state)
    notifs = state.data.get("notifications", [])
    return {
        "empty": False,
        "meta": m,
        "model": _derive_model(state),
        "work_dir": state.meta.get("work_dir") or "—",
        "progress": {"done": done, "total": total},
        "elapsed_s": elapsed_s,
        "eta_s": eta_s,
        "replans": sum(1 for n in notifs if isinstance(n, dict) and n.get("kind") == "replan"),
        "adversary": len(state.data.get("adversary_reviews", [])),
        "cost": state.meta.get("cost") or "—",
        "tunnel_url": state.meta.get("tunnel_url"),
        "health": {"score": score, "color": aura_color(score)},
        "arc": state.meta.get("arc") or [],
        "discovery": _discovery_block(state.meta),
        "wisdom_trail": _wisdom_trail(state.meta.get("goal_raw") or ""),
        "intelligence_curve": _intelligence_curve(),
        "comparative": _comparative(task_id),
        "subtasks": [
            {
                "subtask_id": s["subtask_id"],
                "title": s["title"],
                "status": s["status"],
                "verify": (s.get("verify_result") or {}).get("passed") if s.get("verify_result") else None,
            }
            for s in state.subtasks
        ],
        "events": state.data.get("notifications", []),
        "control": {"abort": bus["abort"], "pause": bus["pause"], "pending_gate": bus.get("pending_gate")},
    }


def _applyControl(task_id: str, action: str, arg: Optional[str]) -> dict:
    if not task_id:
        return {"ok": False, "error": "no active task"}
    if not isinstance(action, str) or not action:
        return {"ok": False, "error": "action must be a non-empty string"}
    bus = ControlBus(task_id)
    if action == "abort":
        bus.requestAbort()
    elif action == "pause":
        bus.requestPause()
    elif action == "resume":
        bus.clearPause()
    elif action in ("approve", "reject"):
        gate = arg or bus.getPendingGate()
        if gate not in GATES:   # ignore a missing/unknown gate, never write a stray decision key
            return {"ok": False, "error": "no valid pending gate"}
        bus.decide(gate, action)
        return {"ok": True, "gate": gate}
    elif action == "skip" and arg:
        bus.pushOp({"op": "skip", "subtask_id": arg})
    elif action == "add" and arg:
        bus.pushOp({"op": "add", "title": arg, "description": arg})
    else:
        return {"ok": False, "error": f"unknown or incomplete action: {action!r}"}
    return {"ok": True}


def _makeHandler(task_id: str, token: str = ""):
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *_a):  # silence default stderr noise
            return

        def _send(self, code: int, body: bytes, ctype: str) -> None:
            # A browser tab closing mid-response drops the socket; swallow the disconnect.
            try:
                self.send_response(code)
                self.send_header("Content-Type", ctype)
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
            except (BrokenPipeError, ConnectionError, ConnectionResetError, ConnectionAbortedError):
                pass

        def _serve_sse(self) -> None:
            bus = get_bus()
            q = bus.subscribe_sse()
            try:
                self.send_response(200)
                self.send_header("Content-Type", "text/event-stream")
                self.send_header("Cache-Control", "no-cache")
                self.send_header("Connection", "keep-alive")
                self.end_headers()
                for e in bus.history(last_n=200):
                    self._sse_write(e)
                while not _SSE_STOP.is_set():
                    try:
                        item = q.get(timeout=15)
                    except queue.Empty:
                        self.wfile.write(b": ping\n\n")
                        self.wfile.flush()
                        continue
                    self._sse_write(item)
            except (BrokenPipeError, ConnectionError, ConnectionResetError,
                    ConnectionAbortedError, OSError):
                pass
            finally:
                bus.unsubscribe_sse(q)

        def _sse_write(self, obj: dict) -> None:
            self.wfile.write(f"data: {json.dumps(obj)}\n\n".encode("utf-8"))
            self.wfile.flush()

        def do_GET(self):  # noqa: N802
            if self.path.startswith("/api/state"):
                self._send(200, json.dumps(_snapshot(task_id)).encode("utf-8"), "application/json")
            elif self.path.startswith("/api/events"):
                self._serve_sse()
            elif self.path.startswith("/api/raw"):
                sid = (parse_qs(urlparse(self.path).query).get("sid") or [""])[0]
                self._send(200, _raw_payload(sid).encode("utf-8"), "application/json")
            else:
                self._send(200, _PAGE.replace("__WEBDASH_TOKEN__", token).encode("utf-8"),
                           "text/html; charset=utf-8")

        def do_POST(self):  # noqa: N802
            if not self.path.startswith("/api/control"):
                self._send(404, b"{}", "application/json")
                return
            # CSRF / local-process guard: require the per-run token embedded in the served page.
            if token and self.headers.get("X-9to5-Token") != token:
                self._send(403, b'{"ok":false,"error":"forbidden"}', "application/json")
                return
            try:
                length = int(self.headers.get("Content-Length") or 0)
            except (TypeError, ValueError):
                length = 0
            length = max(0, min(length, 64_000))   # cap the read; control payloads are tiny
            try:
                payload = json.loads(self.rfile.read(length) or b"{}")
                if not isinstance(payload, dict):
                    payload = {}
            except Exception:  # noqa: BLE001
                payload = {}
            action = payload.get("action") or ""
            if not isinstance(action, str):
                action = ""
            arg = payload.get("arg")
            if arg is not None and not isinstance(arg, str):
                arg = str(arg)
            result = _applyControl(task_id, action, arg)
            self._send(200, json.dumps(result).encode("utf-8"), "application/json")

    return Handler


_SERVER = None  # the live dashboard server, so it can be shut down between runs in one process


def startWebDashboard(task_id: str, port: Optional[int] = None) -> Optional[str]:
    """Start the dashboard in a daemon thread; return its URL (or None if disabled/failed)."""
    global _SERVER
    if not config.WEB_DASHBOARD:
        return None
    stopWebDashboard()  # never leak a prior run's server/port
    _SSE_STOP.clear()
    port = port or config.WEB_DASHBOARD_PORT
    import secrets
    token = secrets.token_urlsafe(16)   # per-run control token, embedded only in the served page
    try:
        server = ThreadingHTTPServer(("127.0.0.1", port), _makeHandler(task_id, token))
    except OSError as e:
        LOG.warning("web dashboard could not bind :%s (%s)", port, e)
        return None
    _SERVER = server
    thread = threading.Thread(target=server.serve_forever, name="webdash", daemon=True)
    thread.start()
    url = f"http://127.0.0.1:{port}/"
    LOG.info("Web dashboard at %s", url)
    return url


def stopWebDashboard() -> None:
    """Shut down the running dashboard server (frees the port). Safe to call repeatedly."""
    global _SERVER
    _SSE_STOP.set()   # release any blocked SSE reader threads
    if _SERVER is not None:
        try:
            _SERVER.shutdown()
            _SERVER.server_close()
        except Exception:  # noqa: BLE001
            pass
        _SERVER = None
