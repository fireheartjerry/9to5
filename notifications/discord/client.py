def truncate(text, n: int) -> str:
    """Clamp to n chars, marking a clip with a trailing ellipsis."""
    text = str(text if text is not None else "")
    if n <= 1:
        return text[:max(n, 0)]
    return text if len(text) <= n else text[:n - 1].rstrip() + "…"


def _embedLen(embed: dict) -> int:
    total = len(str(embed.get("title", ""))) + len(str(embed.get("description", "")))
    total += len(str((embed.get("footer") or {}).get("text", "")))
    for f in embed.get("fields", []) or []:
        total += len(str(f.get("name", ""))) + len(str(f.get("value", "")))
    return total


def _clampEmbed(embed: dict) -> dict:
    """Guarantee a sendable embed: title + per-field clamp (no oversize part can 400 the whole
    message), <=25 fields, and a hard 6000-total budget. The budget is enforced by shrinking the
    largest field VALUE first (dashboard tail rows survive longest), then the largest field NAME,
    then dropping trailing fields — so a many-long-names embed can never exceed the total limit."""
    if not isinstance(embed, dict):
        return embed
    e = dict(embed)
    if isinstance(e.get("title"), str):
        e["title"] = truncate(e["title"], config.DISCORD_MAX_EMBED_TITLE)
    if isinstance(e.get("description"), str):
        e["description"] = truncate(e["description"], config.DISCORD_MAX_EMBED_DESC)
    footer = e.get("footer")               # Discord caps footer.text at 2048, author.name at 256;
    if isinstance(footer, dict) and isinstance(footer.get("text"), str):   # unclamped they 400 the embed
        e["footer"] = {**footer, "text": truncate(footer["text"], 2048)}
    author = e.get("author")
    if isinstance(author, dict) and isinstance(author.get("name"), str):
        e["author"] = {**author, "name": truncate(author["name"], 256)}
    fields = e.get("fields")
    if isinstance(fields, list):
        clamped = []
        for f in fields[:25]:
            if not isinstance(f, dict):
                continue
            nf = dict(f)
            nf["name"] = truncate(nf.get("name", ""), config.DISCORD_MAX_FIELD_NAME)
            nf["value"] = truncate(nf.get("value", ""), config.DISCORD_MAX_FIELD_VALUE) or "—"
            clamped.append(nf)
        e["fields"] = clamped
    _shrinkEmbedToBudget(e)                 # always enforce the 6000 total, even with zero fields
    return e


def _shrinkEmbedToBudget(e: dict) -> None:
    """Mutate ``e`` in place until _embedLen(e) <= the total budget: shrink largest value, then
    largest name, then drop the last field as a final fallback (guaranteed to terminate)."""
    guard = 0
    while _embedLen(e) > config.DISCORD_EMBED_TOTAL_MAX and guard < 200:
        guard += 1
        over = _embedLen(e) - config.DISCORD_EMBED_TOTAL_MAX
        fields = e.get("fields") or []
        val = max(fields, key=lambda f: len(str(f.get("value", ""))), default=None)
        if val is not None and len(str(val.get("value", ""))) > 8:
            cur = len(str(val["value"]))
            val["value"] = truncate(val["value"], max(8, cur - over - 1))
            continue
        nm = max(fields, key=lambda f: len(str(f.get("name", ""))), default=None)
        if nm is not None and len(str(nm.get("name", ""))) > 1:
            cur = len(str(nm.get("name", "")))
            nm["name"] = truncate(nm["name"], max(1, cur - over - 1))
            continue
        if fields:                       # values + names at floor: drop a trailing field
            fields.pop()
            continue
        # no fields left: shrink description, then footer, then title so title+desc+footer ALONE
        # can never exceed the total (the old code broke here and shipped an over-budget embed -> 400).
        if isinstance(e.get("description"), str) and len(e["description"]) > 1:
            e["description"] = truncate(e["description"], max(1, len(e["description"]) - over - 1))
            continue
        foot = e.get("footer") or {}
        if isinstance(foot.get("text"), str) and len(foot["text"]) > 1:
            e["footer"] = {**foot, "text": truncate(foot["text"], max(1, len(foot["text"]) - over - 1))}
            continue
        if isinstance(e.get("title"), str) and len(e["title"]) > 1:
            e["title"] = truncate(e["title"], max(1, len(e["title"]) - over - 1))
            continue
        break


def _cv2TextLen(components) -> int:
    """Total text length across a CV2 tree (TextDisplay content + button labels)."""
    total = 0

    def walk(node):
        nonlocal total
        if isinstance(node, dict):
            if node.get("type") == 10:        # TextDisplay
                total += len(str(node.get("content", "")))
            elif node.get("type") == 2:       # Button
                total += len(str(node.get("label", "")))
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for it in node:
                walk(it)

    walk(components)
    return total


def _cv2Count(components) -> int:
    """Total component nodes (anything carrying a numeric 'type') -- Discord caps a CV2 tree at 40."""
    n = 0

    def walk(node):
        nonlocal n
        if isinstance(node, dict):
            if isinstance(node.get("type"), int):
                n += 1
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for it in node:
                walk(it)

    walk(components)
    return n


def _largestCv2Text(comps: list):
    """The TextDisplay (type 10) node with the longest content in a CV2 tree, or None."""
    biggest = None

    def walk(node):
        nonlocal biggest
        if isinstance(node, dict):
            if node.get("type") == 10 and isinstance(node.get("content"), str):
                if biggest is None or len(node["content"]) > len(str(biggest.get("content", ""))):
                    biggest = node
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for it in node:
                walk(it)

    walk(comps)
    return biggest


def _shrinkCv2Text(comps: list) -> None:
    """Truncate the largest TextDisplay content until the char budget is met -- popping tail
    components can't rescue a tree whose one header TextDisplay alone exceeds the limit (which
    otherwise collapsed the whole cockpit to a '…' placeholder)."""
    guard = 0
    while _cv2TextLen(comps) > config.DISCORD_CV2_MAX_CHARS and guard < 200:
        guard += 1
        biggest = _largestCv2Text(comps)
        cur = len(str(biggest.get("content", ""))) if biggest else 0
        if cur <= 8:
            break
        over = _cv2TextLen(comps) - config.DISCORD_CV2_MAX_CHARS
        biggest["content"] = truncate(biggest["content"], max(8, cur - over - 1))


def _clampComponents(components: list) -> list:
    """Best-effort guard so a runaway cockpit can never 400 the whole message: trim top-level
    components from the END (controls/events tail) until the tree is within Discord's
    40-component / 4000-char CV2 budget, so the header + progress zones always survive."""
    comps = list(components or [])
    limit = len(comps) + 1   # at most one pop per top-level component -> always converges to budget
    guard = 0
    while comps and guard < limit and (
            _cv2Count(comps) > config.DISCORD_CV2_MAX_COMPONENTS
            or _cv2TextLen(comps) > config.DISCORD_CV2_MAX_CHARS):
        guard += 1
        comps.pop()
    _shrinkCv2Text(comps)   # a single oversized TextDisplay survives popping -> shrink it in place
    # A CV2 message with zero components is rejected by Discord (HTTP 400), so the whole update
    # would fail instead of degrading. If clamping emptied the tree (or it was empty to begin with),
    # fall back to a minimal valid container so the message still sends.
    if not comps:
        comps = [{"type": 17, "components": [{"type": 10, "content": "…"}]}]
    return comps


def _multipartParts(payload: dict, files: list) -> tuple[dict, dict]:
    """Wire Discord's multipart convention: payload_json + attachments[]. ``files`` is a list of
    (filename, raw_bytes, content_type); returns (data, files) ready for requests."""
    attachments = []
    fdict: dict = {}
    for i, (fname, fbytes, ctype) in enumerate(files):
        attachments.append({"id": i, "filename": fname})
        fdict[f"files[{i}]"] = (fname, fbytes, ctype or "application/octet-stream")
    body = dict(payload)
    body["attachments"] = attachments
    return {"payload_json": _jsonlib.dumps(body)}, fdict
