"""Proactive narration, Moments, and attention-mode detection.

Three surface behaviours live here:
  * ``Narrator`` -- posts a one-sentence, in-voice channel message on meaningful
    transitions, rate-limited to one per 60s so an event burst never spams.
  * ``MomentDetector`` / ``emit_moment`` -- elevates rare, special events with ceremony:
    a ``kind="moment"`` bus event plus a non-ephemeral Cast line. Rarity is the point.
  * ``detect_mode`` -- Present (a browser SSE tab is open) vs Away (phone/Discord).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Narrator  -- Rate-limited proactive narrator (posts in The Cast's voice).
  MomentDetector  -- Detects rare, ceremony-worthy moments.
  emit_moment(bus, sid: str, text: str, *, sink=None) -> None  -- Emit a moment to the bus + channel.
  detect_mode(bus) -> str  -- "present" when a web SSE tab is open, else "away".
DEPENDS-ON: config, notifications.cast, notifications.event_bus
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_narration.py
"""
from __future__ import annotations

import time
from typing import Callable, Optional

import config
from notifications.event_bus import Event

LOG = config.getLogger("narration")


def _default_sink(text: str, role: str) -> bool:
    """Post a one-line narration in The Cast's voice. No-op when CAST_MODE is off."""
    try:
        from notifications import cast
        return cast.speak(role, text)
    except Exception:  # noqa: BLE001 -- narration is best-effort
        return False


class Narrator:
    """Posts proactive narration, rate-limited to one message per ``min_interval`` seconds."""

    def __init__(self, *, min_interval: float = 60.0,
                 clock: Callable[[], float] = time.monotonic) -> None:
        self.min_interval = min_interval
        self._clock = clock
        self._last = -1e18
        self._sink: Callable[[str, str], bool] = _default_sink

    def narrate(self, text: str, *, role: str = "brain", force: bool = False) -> bool:
        """Post ``text`` unless inside the rate-limit window (``force`` overrides). Never raises."""
        now = self._clock()
        if not force and (now - self._last) < self.min_interval:
            return False
        try:
            ok = bool(self._sink(text, role))
        except Exception:  # noqa: BLE001 -- a posting hiccup must never break a run
            LOG.warning("narration sink failed", exc_info=True)
            return False
        if ok:
            self._last = now
        return ok


class MomentDetector:
    """Pure detectors returning a one-sentence moment (in voice) or None."""

    def adversary_offplan(self, verdict: Optional[str], in_original_plan: bool) -> Optional[str]:
        if (verdict or "").lower() == "challenged" and not in_original_plan:
            return "⚡ MOMENT — The adversary caught something the plan never anticipated. Watch this."
        return None

    def scope_expanded(self, files_touched: int, files_expected: int) -> Optional[str]:
        if files_touched > files_expected:
            return "⚡ MOMENT — Claude found something the subtask didn't ask for. Expanding. Watch this."
        return None

    def redemption(self, attempts: int, passed: bool) -> Optional[str]:
        if passed and attempts >= 3:
            return "⚡ MOMENT — Redemption. It clawed back from two dead ends and closed clean."
        return None

    def perfect_run(self, replans: int, adversary_triggers: int) -> Optional[str]:
        if replans == 0 and adversary_triggers == 0:
            return "⚡ MOMENT — A perfect run. Zero replans, zero adversary triggers. Flawless."
        return None


def emit_moment(bus, sid: str, text: str, *, sink: Optional[Callable[[str, str], bool]] = None) -> None:
    """Emit a ``kind='moment'`` bus event and post it (non-ephemeral) to the channel."""
    try:
        bus.emit(Event(kind="moment", sid=sid, text=text))
    except Exception:  # noqa: BLE001
        pass
    poster = sink or _default_sink
    try:
        poster(text, "brain")
    except Exception:  # noqa: BLE001
        pass


def detect_mode(bus) -> str:
    """Heuristic attention mode: Present if a web SSE tab is subscribed, else Away."""
    try:
        return "present" if bus.sse_subscriber_count() > 0 else "away"
    except Exception:  # noqa: BLE001
        return "away"
