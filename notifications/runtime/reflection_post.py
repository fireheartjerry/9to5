"""Self-reflection -- the run, in its own voice, at the end.

At run end one short first-person paragraph is written by a fast Ollama call with the run
summary as input, then saved to ``state/tasks/<task_id>/reflection.md``, mirrored to
Obsidian, and posted to Discord (with the comparative-intelligence footer). Accumulated
reflections feed the institutional-memory lens of the discovery engine.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  write_reflection(state: Any, *, chat: Callable[..., Any], comparative: Optional[dict]=None, obs: Any=None, innovative_changes: Optional[list]=None) -> Optional[str]  -- Generate the reflection paragraph, persist it to disk + Obsidian, and return it.
  post_reflection(state: Any, text: str, comparative: Optional[dict]=None) -> None  -- Post the reflection to Discord as ``CODENAME — text`` with a comparative footer
  post_innovations(state: Any, entries: list) -> None  -- Post a dedicated 'Innovative Changes' Discord embed (fact-backed entries)
DEPENDS-ON: config, notifications.discord_bot, platform_core.orchestration
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/notifications/test_reflection_post.py
"""
from __future__ import annotations

import hashlib
from typing import Any, Callable, Optional

import config

LOG = config.getLogger("reflection")

_SYSTEM = (
    "You are 9to5, an autonomous AI system. Write one short paragraph in first person about "
    "what you just did. Be specific about what surprised you, what you struggled with, and what "
    "you learned. Write as if in a personal journal, not a report. Max 100 words."
)


def _extract(resp: Any) -> str:
    """Pull plain text from a chat callable's return (str or an Ollama response dict)."""
    if isinstance(resp, str):
        return resp.strip()
    if isinstance(resp, dict):
        msg = resp.get("message")
        if isinstance(msg, dict) and isinstance(msg.get("content"), str):
            return msg["content"].strip()
        if isinstance(resp.get("content"), str):
            return resp["content"].strip()
    return ""


def _seed_user(state: Any, innovative_changes: Optional[list] = None) -> str:
    meta = getattr(state, "meta", {}) or {}
    codename = meta.get("codename") or "this run"
    goal = meta.get("goal_raw") or meta.get("goal_elaborated") or ""
    seed = f"Run {codename}. Goal: {goal}"
    shipped = [e for e in (innovative_changes or []) if getattr(e, "status", "") == "shipped"]
    if shipped:
        titles = "; ".join(getattr(e, "title", "") for e in shipped[:5])
        seed += (f"\nInnovative changes you shipped (verified): {titles}. "
                 "Mention what made them genuinely new.")
    return seed + "\nWrite your one-paragraph journal entry now."


def write_reflection(state: Any, *, chat: Callable[..., Any],
                     comparative: Optional[dict] = None, obs: Any = None,
                     innovative_changes: Optional[list] = None) -> Optional[str]:
    """Generate the reflection paragraph, persist it to disk + Obsidian, and return it.
    Returns None when generation yields nothing. Never raises."""
    try:
        resp = chat(_SYSTEM, _seed_user(state, innovative_changes))
        text = _extract(resp)
    except Exception as e:  # noqa: BLE001 -- a model hiccup must never break teardown
        LOG.warning("reflection generation failed: %s", e)
        return None
    if not text:
        return None
    _save_to_disk(state, text)
    _save_to_obsidian(state, text, obs)
    return text


def _save_to_disk(state: Any, text: str) -> None:
    try:
        task_id = getattr(state, "task_id", None) or (getattr(state, "meta", {}) or {}).get("task_id")
        if not task_id:
            return
        dest = config.STATE_DIR / str(task_id) / "reflection.md"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text + "\n", encoding="utf-8")
    except Exception as e:  # noqa: BLE001
        LOG.warning("reflection disk save failed: %s", e)


def _save_to_obsidian(state: Any, text: str, obs: Any) -> None:
    if obs is None:
        return
    try:
        rel = f"{state.vaultTaskDir()}/reflection.md" if hasattr(state, "vaultTaskDir") \
            else f"tasks/{getattr(state, 'task_id', 'run')}/reflection.md"
        obs.writeNote(rel, f"# Reflection\n\n{text}\n")
    except Exception as e:  # noqa: BLE001
        LOG.warning("reflection obsidian save failed: %s", e)


def post_reflection(state: Any, text: str, comparative: Optional[dict] = None) -> None:
    """Post the reflection to Discord as ``CODENAME — text`` with a comparative footer. Never raises."""
    try:
        from notifications import discord_bot as discord
        codename = (getattr(state, "meta", {}) or {}).get("codename") or "RUN"
        body = f"**{codename}** — {text}"
        footer = _comparative_footer(comparative)
        if footer:
            body += "\n\n" + footer
        if _already_posted(state, "reflection", body):
            return
        discord.sendEmbed(discord.noticeEmbed(body, title="Self-reflection"))
        _mark_posted(state, "reflection", body)
    except Exception as e:  # noqa: BLE001 -- posting is best-effort
        LOG.warning("reflection post failed: %s", e)


def post_innovations(state: Any, entries: list) -> None:
    """Post a dedicated 'Innovative Changes' Discord embed (fact-backed entries). Never raises."""
    if not entries:
        return
    try:
        from notifications import discord_bot as discord
        from platform_core.orchestration import innovation_report
        fields = innovation_report.render_discord_fields(entries)
        if not fields:
            return
        codename = (getattr(state, "meta", {}) or {}).get("codename") or "RUN"
        embed = discord.noticeEmbed(f"**{codename}** — fact-backed inventions this run",
                                    title="💡 Innovative Changes")
        for name, value in fields:
            try:
                embed.add_field(name=name, value=value, inline=False)
            except Exception:  # noqa: BLE001 -- embed shape varies; body already carries the gist
                break
        marker = repr([(name, value) for name, value in fields])
        if _already_posted(state, "innovations", marker):
            return
        discord.sendEmbed(embed)
        _mark_posted(state, "innovations", marker)
    except Exception as e:  # noqa: BLE001 -- posting is best-effort
        LOG.warning("innovations post failed: %s", e)


def _comparative_footer(comparative: Optional[dict]) -> str:
    if not isinstance(comparative, dict) or not comparative:
        return ""
    parts = [f"{k}: {comparative[k]}" for k in ("pace", "innovation", "adversary", "replans")
             if isinstance(comparative.get(k), str)]
    return ("THIS RUN vs AVG\n" + "\n".join(parts)) if parts else ""


def _post_key(kind: str, body: str) -> str:
    return f"{kind}:{hashlib.sha1(body.encode('utf-8', errors='replace')).hexdigest()[:16]}"


def _already_posted(state: Any, kind: str, body: str) -> bool:
    meta = getattr(state, "meta", None)
    if not isinstance(meta, dict):
        return False
    return _post_key(kind, body) in set(meta.get("posted_surfaces") or [])


def _mark_posted(state: Any, kind: str, body: str) -> None:
    meta = getattr(state, "meta", None)
    if not isinstance(meta, dict):
        return
    posted = meta.setdefault("posted_surfaces", [])
    key = _post_key(kind, body)
    if key not in posted:
        posted.append(key)
        save = getattr(state, "save", None)
        if callable(save):
            save()
