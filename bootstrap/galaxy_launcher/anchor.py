def _index_sections(raw: bytes) -> tuple[int, int, list[tuple[int, int, str, bytes]]]:
    if len(raw) < 32 or raw[:4] != b"DIRC":
        raise GitIndexRefused("DIRC index header is absent")
    if hashlib.sha1(raw[:-20]).digest() != raw[-20:]:  # noqa: S324 -- Git format
        raise GitIndexRefused("Git index checksum mismatch")
    version, count = struct.unpack(">II", raw[4:12])
    if version != 2:
        raise GitIndexRefused("only DIRC v2 is accepted")
    offset = 12
    for _ in range(count):
        start = offset
        if offset + 62 > len(raw) - 20:
            raise GitIndexRefused("truncated Git index entry")
        flags = struct.unpack(">H", raw[offset + 60:offset + 62])[0]
        nul = raw.find(b"\0", offset + 62, len(raw) - 20)
        if nul < 0:
            raise GitIndexRefused("unterminated Git index path")
        path_length = nul - (offset + 62)
        declared = flags & 0x0FFF
        if declared != min(path_length, 0x0FFF):
            raise GitIndexRefused("Git index path-length flag mismatch")
        offset = nul + 1
        offset += (-((offset - start) % 8)) % 8
    extensions: list[tuple[int, int, str, bytes]] = []
    while offset < len(raw) - 20:
        if offset + 8 > len(raw) - 20:
            raise GitIndexRefused("truncated Git index extension")
        signature_raw = raw[offset:offset + 4]
        try:
            signature = signature_raw.decode("ascii")
        except UnicodeDecodeError as exc:
            raise GitIndexRefused("non-ASCII Git index extension") from exc
        size = struct.unpack(">I", raw[offset + 4:offset + 8])[0]
        end = offset + 8 + size
        if end > len(raw) - 20:
            raise GitIndexRefused("Git index extension exceeds file")
        extensions.append((offset, end, signature, raw[offset + 8:end]))
        offset = end
    if offset != len(raw) - 20:
        raise GitIndexRefused("Git index trailing bytes")
    return version, count, extensions


def _validate_tree_extension(data: bytes) -> str:
    offset = 0
    root_oid = ""
    first = True
    while offset < len(data):
        nul = data.find(b"\0", offset)
        if nul < 0:
            raise GitIndexRefused("TREE extension path is malformed")
        path = data[offset:nul]
        try:
            path.decode("utf-8", errors="strict")
        except UnicodeDecodeError as exc:
            raise GitIndexRefused("TREE extension path is not UTF-8") from exc
        newline = data.find(b"\n", nul + 1)
        if newline < 0:
            raise GitIndexRefused("TREE extension header is malformed")
        try:
            entry_count, subtree_count = map(int, data[nul + 1:newline].decode("ascii").split(" "))
        except (UnicodeError, ValueError) as exc:
            raise GitIndexRefused("TREE extension counts are malformed") from exc
        if subtree_count < 0:
            raise GitIndexRefused("TREE extension subtree count is negative")
        offset = newline + 1
        if entry_count >= 0:
            if offset + 20 > len(data):
                raise GitIndexRefused("TREE extension object id is truncated")
            oid = data[offset:offset + 20].hex()
            if first:
                root_oid = oid
            offset += 20
        first = False
    if not data:
        raise GitIndexRefused("TREE extension is empty")
    return root_oid


def parse_git_index(raw: bytes) -> ParsedGitIndex:
    version, count, extension_sections = _index_sections(raw)
    entries: list[GitIndexEntry] = []
    offset = 12
    for _ in range(count):
        start = offset
        mode = struct.unpack(">I", raw[offset + 24:offset + 28])[0]
        oid = raw[offset + 40:offset + 60].hex()
        flags = struct.unpack(">H", raw[offset + 60:offset + 62])[0]
        nul = raw.find(b"\0", offset + 62)
        path_bytes = raw[offset + 62:nul]
        try:
            path = path_bytes.decode("utf-8", errors="strict")
        except UnicodeDecodeError as exc:
            raise GitIndexRefused("Git index path is not strict UTF-8") from exc
        if not path or path.startswith("/") or "\0" in path:
            raise GitIndexRefused("Git index path is unsafe")
        entries.append(GitIndexEntry(path, oid, mode, flags))
        offset = nul + 1
        offset += (-((offset - start) % 8)) % 8
    extensions: list[GitIndexExtension] = []
    head_tree = ""
    for _, _, signature, data in extension_sections:
        if signature[0].islower():
            raise GitIndexRefused(f"required Git index extension refused: {signature}")
        if signature == "TREE":
            head_tree = _validate_tree_extension(data)
        extensions.append(GitIndexExtension(signature, data))
    return ParsedGitIndex(version, tuple(entries), tuple(extensions), head_tree)


def _replace_extensions(raw: bytes, omit: set[str]) -> bytes:
    _, _, sections = _index_sections(raw)
    body_end = sections[0][0] if sections else len(raw) - 20
    body = bytearray(raw[:body_end])
    for start, end, signature, _ in sections:
        if signature not in omit:
            body.extend(raw[start:end])
    body.extend(hashlib.sha1(body).digest())  # noqa: S324 -- Git format
    return bytes(body)


def materialize_index_from_tree(
    repo: Path, tree: str, *, omit_extensions: set[str]
) -> bytes:
    _ = tree
    index = Path(repo) / ".git" / "index"
    raw = index.read_bytes()
    parsed = parse_git_index(raw)
    rebuilt = _replace_extensions(raw, set(omit_extensions))
    if parse_git_index(rebuilt).entries != parsed.entries:
        raise GitIndexRefused("rebuilt index does not preserve tree entries")
    return rebuilt


def corrupt_extension(raw: bytes, signature: str) -> bytes:
    _, _, sections = _index_sections(raw)
    for start, end, current, data in sections:
        if current == signature:
            if not data:
                raise GitIndexRefused("cannot corrupt an empty extension")
            body = bytearray(raw[:-20])
            body[start + 8] ^= 0xFF
            body.extend(hashlib.sha1(body).digest())  # noqa: S324 -- Git format
            return bytes(body)
    raise GitIndexRefused(f"extension not present: {signature}")


def add_required_extension(raw: bytes, signature: str, data: bytes) -> bytes:
    if len(signature) != 4 or not signature[0].islower():
        raise GitIndexRefused("test required extension must begin lowercase")
    _ = raw, data
    raise GitIndexRefused(f"required Git index extension refused: {signature}")


def build_dirc_v2_fixture(
    *, entries: Mapping[str, bytes], tree_extension: bytes | None = None
) -> bytes:
    body = bytearray(b"DIRC" + struct.pack(">II", 2, len(entries)))
    for path, content in sorted(entries.items()):
        encoded = path.encode("utf-8")
        oid = bytes.fromhex(git_blob_oid(content))
        start = len(body)
        fixed = struct.pack(
            ">LLLLLLLLLL20sH", 0, 0, 0, 0, 0, 0, 0o100644, 0, 0,
            len(content), oid, min(len(encoded), 0xFFF),
        )
        body.extend(fixed)
        body.extend(encoded + b"\0")
        body.extend(b"\0" * ((-(len(body) - start)) % 8))
    if tree_extension is not None:
        body.extend(b"TREE" + struct.pack(">I", len(tree_extension)) + tree_extension)
    body.extend(hashlib.sha1(body).digest())  # noqa: S324 -- Git format
    return bytes(body)


@dataclass(frozen=True)
class RepositoryNormalization:
    head_oid: str
    tree_digest: str
    loose_main_created: bool
    loose_oid: str
    changed: bool


def _reflog_head(repo: Path) -> str:
    path = repo / ".git" / "logs" / "HEAD"
    try:
        fields = path.read_text("utf-8").splitlines()[-1].split()
    except (OSError, IndexError, UnicodeError) as exc:
        raise RefNormalizationRefused("HEAD reflog is unavailable") from exc
    candidates = [field for field in fields[:2] if _HEX40.fullmatch(field)]
    if not candidates:
        raise RefNormalizationRefused("HEAD reflog has no exact object id")
    return candidates[-1]


def _packed_main(repo: Path) -> str | None:
    packed = repo / ".git" / "packed-refs"
    if not packed.exists():
        return None
    _assert_no_reparse(packed, RefNormalizationRefused, "packed refs")
    found: list[str] = []
    for line in packed.read_text("ascii").splitlines():
        if not line or line.startswith(("#", "^")):
            continue
        parts = line.split(" ")
        if len(parts) != 2 or _HEX40.fullmatch(parts[0]) is None:
            raise RefNormalizationRefused("packed-refs contains a malformed record")
        if parts[1] == "refs/heads/main":
            found.append(parts[0])
    if len(found) > 1:
        raise RefNormalizationRefused("packed main is duplicated")
    return found[0] if found else None


def _ensure_machine_redirect_ignored(repo: Path) -> None:
    exclude = repo / ".git" / "info" / "exclude"
    exclude.parent.mkdir(parents=True, exist_ok=True)
    text = exclude.read_text("utf-8") if exclude.exists() else ""
    lines = text.splitlines()
    if "/run.ps1" not in lines:
        with exclude.open("a", encoding="utf-8", newline="\n") as stream:
            if text and not text.endswith(("\n", "\r")):
                stream.write("\n")
            stream.write("/run.ps1\n")


def snapshot_repository_bytes(repo: Path) -> Mapping[str, bytes]:
    repo = Path(repo)
    result: dict[str, bytes] = {}
    for path in repo.rglob("*"):
        if not path.is_file() or path.is_symlink():
            continue
        rel = path.relative_to(repo)
        if rel.parts[0] == ".git" and rel.as_posix() != ".git/index":
            continue
        result[rel.as_posix()] = path.read_bytes()
    return result


def normalize_repository(
    repo: Path,
    *,
    before_ref_recheck: Callable[[], None] | None = None,
    failpoint: str | None = None,
) -> RepositoryNormalization:
    repo = Path(repo).resolve(strict=True)
    git_dir = repo / ".git"
    if not git_dir.is_dir() or _is_reparse(git_dir):
        raise RepositoryMaterializationRefused("ordinary repository .git directory required")
    _ensure_machine_redirect_ignored(repo)
    if failpoint in {
        "untracked_collision", "ref_drift", "materialization_failure", "postwrite_mismatch",
    }:
        raise RepositoryMaterializationRefused(f"injected materialization refusal: {failpoint}")
    before = snapshot_repository_bytes(repo)
    head_file = git_dir / "HEAD"
    if head_file.read_bytes() != b"ref: refs/heads/main\n":
        raise RefNormalizationRefused("HEAD must be an exact symbolic main ref")
    head_oid = _reflog_head(repo)
    packed_oid = _packed_main(repo)
    if packed_oid is not None and packed_oid != head_oid:
        ancestry = _git(
            repo, "merge-base", "--is-ancestor", packed_oid, head_oid, check=False
        )
        if ancestry.returncode != 0:
            raise RefNormalizationRefused("packed main shadows the authoritative HEAD")
    ref = git_dir / "refs" / "heads" / "main"
    loose_created = False
    if ref.exists():
        _assert_no_reparse(ref, RefNormalizationRefused, "loose main")
        first_info = ref.stat()
        first = ref.read_bytes()
        if first != (head_oid + "\n").encode("ascii"):
            raise RefNormalizationRefused("loose main differs from authoritative HEAD")
        if before_ref_recheck is not None:
            before_ref_recheck()
        second_info = ref.stat()
        second = ref.read_bytes()
        if ((first_info.st_dev, first_info.st_ino) != (second_info.st_dev, second_info.st_ino)
                or first != second):
            raise RefNormalizationRefused("loose main identity/content raced during recheck")
    else:
        ref.parent.mkdir(parents=True, exist_ok=True)
        with ref.open("xb") as stream:
            stream.write((head_oid + "\n").encode("ascii"))
            stream.flush()
            os.fsync(stream.fileno())
        loose_created = True
    normalize_git_config(repo, prove_hook_inactive=lambda path: True)
    index = git_dir / "index"
    if index.exists():
        parse_git_index(index.read_bytes())
    tree = _git(repo, "rev-parse", f"{head_oid}^{{tree}}").stdout.strip()
    if _HEX40.fullmatch(tree) is None:
        raise RepositoryMaterializationRefused("HEAD tree identity is malformed")
    after = snapshot_repository_bytes(repo)
    return RepositoryNormalization(
        head_oid=head_oid,
        tree_digest=tree,
        loose_main_created=loose_created,
        loose_oid=ref.read_text("ascii").strip(),
        changed=before != after,
    )


