class CutoverSupervisor:
    def __init__(self, root: Path, *, legacy: Any):
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)
        self.legacy = legacy
        self._fence = MaintenanceFence(id="cutover-maintenance", owner="bootstrap_supervisor")
        self._challenge: ExactApprovalChallenge | None = None
        self._accepted: set[tuple[str, str]] = set()

    def begin_create_only_maintenance_fence(self) -> MaintenanceFence:
        path = self.root / "maintenance.fence"
        content = b'{"id":"cutover-maintenance","owner":"bootstrap_supervisor"}'
        if path.exists():
            if path.is_symlink() or path.read_bytes() != content:
                raise AnchorIntegrityRefused("maintenance fence collision")
        else:
            with path.open("xb") as stream:
                stream.write(content)
                stream.flush()
                os.fsync(stream.fileno())
        self.legacy.close_ingress()
        return self._fence

    def fence_owner(self, fence: MaintenanceFence) -> str:
        if fence != self._fence:
            raise AnchorIntegrityRefused("foreign maintenance fence")
        return fence.owner

    def quiesce_and_watch(self, fence: MaintenanceFence) -> QuiescenceReceipt:
        self.fence_owner(fence)
        self.legacy.close_ingress()
        self.legacy.quiesce_all()
        return QuiescenceReceipt(
            ingress_closed=True,
            processes_remaining=list(self.legacy.processes),
            listeners_remaining=list(self.legacy.listeners),
            provider_children_remaining=list(self.legacy.provider_children),
            tunnels_remaining=list(self.legacy.tunnels),
        )

    def snapshot_legacy_bytes(self) -> bytes:
        return self.legacy.snapshot_bytes()

    def begin_fresh_exact_approval(self) -> ExactApprovalChallenge:
        state = self.snapshot_legacy_bytes()
        challenge = ExactApprovalChallenge(
            digest=hashlib.sha256(state + secrets.token_bytes(32)).hexdigest(),
            nonce=secrets.token_hex(32),
        )
        self._challenge = challenge
        return challenge

    def accept_fresh_exact_approval(
        self, challenge: ExactApprovalChallenge, response: str
    ) -> ExactCutoverApproval:
        if challenge != self._challenge:
            raise FreshExactApprovalRequired("approval challenge is not the current fresh challenge")
        exact = f"TRUST CUTOVER {challenge.digest} NONCE {challenge.nonce}"
        if not secrets.compare_digest(response, exact):
            raise FreshExactApprovalRequired("cutover approval response is not exact")
        approval = ExactCutoverApproval(challenge.digest, challenge.nonce)
        self._accepted.add((approval.digest, approval.nonce))
        self._challenge = None
        return approval

    def _validate_approval(self, approval: Any) -> None:
        if not isinstance(approval, ExactCutoverApproval):
            raise FreshExactApprovalRequired("a fresh exact cutover approval is required")
        identity = (approval.digest, approval.nonce)
        if identity not in self._accepted:
            raise FreshExactApprovalRequired("cutover approval is stale or already consumed")
        self._accepted.remove(identity)

    def run_inactive_cutover(
        self,
        *,
        failpoint: str | None = None,
        approval: Any = None,
        verified_rollback: bool = False,
    ) -> CutoverResult:
        allowed_failpoints = {
            "before_commit", "after_commit", "before_inactive_install",
            "after_inactive_install", "before_anchor_handoff", "after_anchor_handoff",
        }
        if failpoint is None:
            self._validate_approval(approval)
        elif failpoint not in allowed_failpoints:
            raise ValueError("unknown cutover failpoint")
        elif approval is not None:
            self._validate_approval(approval)
        original = copy.deepcopy(self.legacy.__dict__)
        fence = self.begin_create_only_maintenance_fence()
        self.quiesce_and_watch(fence)
        if failpoint == "before_commit":
            self.legacy.__dict__.clear()
            self.legacy.__dict__.update(copy.deepcopy(original))
            return CutoverResult(True, False, False, "old_generation_restored")
        outcome = "fenced_for_verified_rollback" if verified_rollback else "inactive_installed"
        return CutoverResult(True, False, True, outcome)


def canonicalize_source_bytes(raw: bytes, *, parent: bytes, textual: bool) -> bytes:
    if not textual:
        if raw != parent:
            raise SourceNormalizationRefused("binary source must be parent-byte exact")
        return raw
    bom = b"\xef\xbb\xbf"
    parent_has_bom = parent.startswith(bom)
    raw_has_bom = raw.startswith(bom)
    if parent_has_bom != raw_has_bom or raw.startswith(bom + bom):
        raise SourceNormalizationRefused("source BOM policy differs from parent")
    body = raw[len(bom):] if raw_has_bom else raw
    if bom in body or b"\x00" in body or b"\r" in body.replace(b"\r\n", b""):
        raise SourceNormalizationRefused("source contains forbidden BOM/NUL/lone-CR bytes")
    try:
        body.decode("utf-8", errors="strict")
    except UnicodeDecodeError as exc:
        raise SourceNormalizationRefused("text source is not strict UTF-8") from exc
    canonical = (bom if raw_has_bom else b"") + body.replace(b"\r\n", b"\n")
    if canonical != parent:
        raise SourceNormalizationRefused("source differs from its parent beyond CRLF policy")
    return canonical


def git_blob_oid(raw: bytes) -> str:
    header = f"blob {len(raw)}\0".encode("ascii")
    return hashlib.sha1(header + raw).hexdigest()  # noqa: S324 -- Git object identity


def _git(repo: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    executable = shutil.which("git")
    if not executable:
        raise RepositoryMaterializationRefused("pinned Git executable is unavailable")
    environment = {
        key: value for key in ("SystemRoot", "WINDIR", "COMSPEC")
        if (value := os.environ.get(key))
    }
    completed = subprocess.run(
        [executable, *args], cwd=repo, env=environment, stdin=subprocess.DEVNULL,
        capture_output=True, text=True, timeout=30, check=False,
    )
    if check and completed.returncode != 0:
        raise RepositoryMaterializationRefused(
            f"git {' '.join(args)} refused: {completed.stderr.strip()}"
        )
    return completed


@dataclass(frozen=True)
class GitConfigNormalization:
    values: Mapping[str, str]


def normalize_git_config(
    repo: Path, *, prove_hook_inactive: Callable[[str], bool]
) -> GitConfigNormalization:
    repo = Path(repo)
    existing = _git(repo, "config", "--local", "--get-all", "core.hooksPath", check=False)
    if existing.returncode not in {0, 1}:
        raise RepositoryMaterializationRefused("cannot inspect repository hook configuration")
    for value in existing.stdout.splitlines():
        if value and not prove_hook_inactive(value):
            raise ActiveHookRefused(f"configured hook path is not proven inactive: {value}")
    removals = ("extensions.worktreeConfig", "core.hooksPath")
    for key in removals:
        result = _git(repo, "config", "--local", "--unset-all", key, check=False)
        if result.returncode not in {0, 5}:
            raise RepositoryMaterializationRefused(f"cannot remove unsafe git setting {key}")
    values = {
        "core.autocrlf": "false",
        "core.safecrlf": "true",
        "core.hooksPath": "NUL",
        "maintenance.auto": "false",
    }
    for key, value in values.items():
        _git(repo, "config", "--local", "--replace-all", key, value)
    return GitConfigNormalization(values=values)


