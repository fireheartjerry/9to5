def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _is_reparse(path: Path) -> bool:
    if path.is_symlink():
        return True
    if os.name != "nt":
        return False
    attributes = ctypes.windll.kernel32.GetFileAttributesW(str(path))
    return attributes != 0xFFFFFFFF and bool(attributes & 0x400)


def _assert_no_reparse(path: Path, error: type[RuntimeError], label: str) -> None:
    absolute = Path(os.path.abspath(path))
    current = Path(absolute.parts[0])
    for part in absolute.parts[1:]:
        current /= part
        if current.exists() and _is_reparse(current):
            raise error(f"{label} traverses a reparse point: {current}")


def _strict_file(path: Path, root: Path, label: str) -> Path:
    _assert_no_reparse(path, AnchorIntegrityRefused, label)
    try:
        resolved = path.resolve(strict=True)
        resolved.relative_to(root)
    except (OSError, ValueError) as exc:
        raise AnchorIntegrityRefused(f"{label} is unavailable or outside the anchor root") from exc
    info = resolved.stat()
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise AnchorIntegrityRefused(f"{label} must be a single-link regular file")
    return resolved


@dataclass(frozen=True)
class ProtectedAnchorRecord:
    record_path: Path
    capsule_path: Path
    capsule_sha256: str
    runtime_manifest_path: Path
    runtime_manifest_sha256: str
    generation_path: Path
    generation: int
    activation_state: str
    identities: Mapping[str, tuple[int, int, int]]

    @classmethod
    def load(cls, record_path: Path, *, no_follow: bool) -> "ProtectedAnchorRecord":
        if not no_follow:
            raise AnchorIntegrityRefused("protected records require no-follow loading")
        raw_path = Path(record_path)
        _assert_no_reparse(raw_path, AnchorIntegrityRefused, "anchor record")
        try:
            resolved_record = raw_path.resolve(strict=True)
            raw = resolved_record.read_bytes()
            text = raw.decode("utf-8")
            mapping = json.loads(text)
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise AnchorIntegrityRefused("anchor record is unavailable or malformed") from exc
        if raw.startswith((b"\xef\xbb\xbf", b"\xff\xfe", b"\xfe\xff")):
            raise AnchorIntegrityRefused("anchor record BOM is forbidden")
        if not isinstance(mapping, dict):
            raise AnchorIntegrityRefused("anchor record must be an object")
        expected = {
            "schema", "capsule_path", "capsule_sha256", "runtime_manifest_path",
            "runtime_manifest_sha256", "generation_path", "generation", "activation_state",
        }
        if set(mapping) != expected or mapping.get("schema") != 1:
            raise AnchorIntegrityRefused("anchor record schema mismatch")
        if json.dumps(mapping, sort_keys=True, separators=(",", ":")) != text:
            raise AnchorIntegrityRefused("anchor record is not canonical JSON")
        if (not isinstance(mapping["generation"], int) or mapping["generation"] < 1
                or mapping["activation_state"] not in {"inactive", "active"}
                or _HEX64.fullmatch(mapping["capsule_sha256"]) is None
                or _HEX64.fullmatch(mapping["runtime_manifest_sha256"]) is None):
            raise AnchorIntegrityRefused("anchor record fields are invalid")
        root = resolved_record.parent.resolve(strict=True)
        capsule = _strict_file(Path(mapping["capsule_path"]), root, "capsule")
        manifest = _strict_file(Path(mapping["runtime_manifest_path"]), root, "runtime manifest")
        generation_path = _strict_file(Path(mapping["generation_path"]), root, "generation")
        paths = {
            "record": resolved_record,
            "capsule": capsule,
            "manifest": manifest,
            "generation": generation_path,
        }
        identities = {
            name: (value.stat().st_dev, value.stat().st_ino, value.stat().st_size)
            for name, value in paths.items()
        }
        return cls(
            record_path=resolved_record,
            capsule_path=capsule,
            capsule_sha256=mapping["capsule_sha256"],
            runtime_manifest_path=manifest,
            runtime_manifest_sha256=mapping["runtime_manifest_sha256"],
            generation_path=generation_path,
            generation=mapping["generation"],
            activation_state=mapping["activation_state"],
            identities=identities,
        )

    @classmethod
    def discover_for_checkout(
        cls, checkout: Path, *, no_follow: bool
    ) -> "ProtectedAnchorRecord":
        """Discover only an installed external record bound to a checkout identity."""
        checkout_path = Path(checkout).resolve(strict=True)
        identity = hashlib.sha256(os.path.normcase(str(checkout_path)).encode("utf-8")).hexdigest()
        local = os.environ.get("LOCALAPPDATA")
        if not local:
            raise AnchorIntegrityRefused("installed anchor root is unavailable")
        base = Path(local) / "9to5" / "singularity"
        candidates = (
            base / "repositories" / identity / "anchor-record.json",
            base / "anchor-record.json",
        )
        for candidate in candidates:
            if candidate.is_file():
                record = cls.load(candidate, no_follow=no_follow)
                binding = candidate.parent / "checkout-binding.txt"
                if binding.exists():
                    _assert_no_reparse(binding, AnchorIntegrityRefused, "checkout binding")
                    if os.path.normcase(binding.read_text("utf-8").strip()) != os.path.normcase(
                        str(checkout_path)
                    ):
                        raise AnchorIntegrityRefused("installed record checkout binding mismatch")
                return record
        raise AnchorIntegrityRefused("no installed protected anchor record exists for checkout")

    def verify_current(self) -> None:
        root = self.record_path.parent.resolve(strict=True)
        current = {
            "record": _strict_file(self.record_path, root, "anchor record"),
            "capsule": _strict_file(self.capsule_path, root, "capsule"),
            "manifest": _strict_file(self.runtime_manifest_path, root, "runtime manifest"),
            "generation": _strict_file(self.generation_path, root, "generation"),
        }
        for name, path in current.items():
            identity = (path.stat().st_dev, path.stat().st_ino, path.stat().st_size)
            if identity != self.identities[name]:
                raise AnchorIntegrityRefused(f"{name} identity changed after protected load")
        if _sha256(self.capsule_path) != self.capsule_sha256:
            raise AnchorIntegrityRefused("capsule digest mismatch")
        if _sha256(self.runtime_manifest_path) != self.runtime_manifest_sha256:
            raise AnchorIntegrityRefused("runtime manifest digest mismatch")
        try:
            generation = int(self.generation_path.read_text("ascii"))
        except (OSError, UnicodeError, ValueError) as exc:
            raise AnchorIntegrityRefused("generation file malformed") from exc
        if generation != self.generation:
            raise AnchorIntegrityRefused("generation is not monotonic/exact")


