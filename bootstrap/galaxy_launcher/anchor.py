class SingularityAnchor:
    def __init__(self, record: ProtectedAnchorRecord):
        self.record = record

    def resolve_service_launch(self, operation: str) -> ServiceLaunchPlan:
        if operation not in {"fresh", "resume", "diagnostic"}:
            raise AnchorIntegrityRefused("unknown service launch operation")
        self.record.verify_current()
        cwd = self.record.record_path.parent / "empty-cwd"
        _assert_no_reparse(cwd, AnchorIntegrityRefused, "empty launch directory")
        cwd.mkdir(exist_ok=True)
        if any(cwd.iterdir()):
            raise AnchorIntegrityRefused("launch working directory is not empty")
        return ServiceLaunchPlan(
            argv=(str(self.record.capsule_path), operation),
            cwd=cwd,
            env={},
            flags=("-I", "-S"),
        )

    def launch(
        self,
        operation: str,
        *,
        starter: Callable[..., Any],
        inherited_env: Mapping[str, str] | None = None,
        inherited_cwd: Path | None = None,
    ) -> Any:
        _ = inherited_env, inherited_cwd
        self.record.verify_current()
        if self.record.activation_state != "active":
            raise TransactionalKernelInactive("installed controller generation is inactive")
        plan = self.resolve_service_launch(operation)
        return starter(
            argv=list(plan.argv), cwd=plan.cwd, env=dict(plan.env), flags=list(plan.flags),
            stdin=plan.stdin, stdout=plan.stdout, stderr=plan.stderr,
        )

    def accept_readiness(self, readiness: PreAnchorLegacyReadiness) -> None:
        _ = readiness
        raise PreAnchorGenerationRefused("pre-anchor readiness can never activate a generation")


