@dataclass(frozen=True)
class Task5Invocation:
    id: str
    input_digest: str
    status: str
    purpose_id: str | None = None


@dataclass(frozen=True)
class Task5RecoveryResult:
    invocation_id: str | None
    input_digest: str | None
    status: str
    purpose_id: str | None = None
    achieved_purpose_id: str | None = None


@dataclass(frozen=True)
class Task5Reservation:
    id: str
    input_digest: str
    path: Path


@dataclass(frozen=True)
class Task5Cancellation:
    reservation_id: str
    cancelled: bool


@dataclass(frozen=True)
class CanonicalBatchRecord:
    path: str
    bytes: bytes
    sha256: str


@dataclass(frozen=True)
class Task5NormalizationReceipt:
    raw_snapshot_digest: str
    policy_digest: str
    canonical_records: Mapping[str, CanonicalBatchRecord]


def digest_raw_snapshot(raw_snapshot: Mapping[str, bytes]) -> str:
    records: list[dict[str, Any]] = []
    for path, raw in sorted(raw_snapshot.items()):
        if not isinstance(path, str) or not isinstance(raw, bytes):
            raise Task5InputDrift("raw snapshot is not a path/bytes mapping")
        records.append({"path": path, "size": len(raw),
                        "sha256": hashlib.sha256(raw).hexdigest()})
    return hashlib.sha256(_canonical_json({"schema": 1, "records": records})).hexdigest()


def _task5_dirs(coordinator: DurableTransitionCoordinator) -> tuple[Path, Path]:
    base = coordinator.root / "task5"
    invocations = base / "invocations"
    reservations = base / "reservations"
    invocations.mkdir(parents=True, exist_ok=True)
    reservations.mkdir(parents=True, exist_ok=True)
    return invocations, reservations


def _invocation_from(mapping: Mapping[str, Any]) -> Task5Invocation:
    return Task5Invocation(str(mapping["id"]), str(mapping["input_digest"]),
                           str(mapping["status"]), mapping.get("purpose_id"))


def _task5_invocations(coordinator: DurableTransitionCoordinator) -> list[dict[str, Any]]:
    invocations, _ = _task5_dirs(coordinator)
    return [_read_json(path, label="Task5 invocation")
            for path in sorted(invocations.glob("invocation-*.json"))]


def _task5_invoke(
    self: DurableTransitionCoordinator,
    *,
    input_digest: str,
    failpoint: str | None = None,
    stop_after: str | None = None,
    disposition: str | None = None,
) -> Task5Invocation:
    existing = [mapping for mapping in _task5_invocations(self)
                if mapping.get("input_digest") == input_digest]
    if len(existing) > 1:
        raise AmbiguousTask5Recovery("Task5 input maps to multiple invocations")
    if existing:
        return _invocation_from(existing[0])
    invocations, _ = _task5_dirs(self)
    invocation_id = "invocation-" + hashlib.sha256(
        f"{input_digest}:{secrets.token_hex(16)}".encode("utf-8")
    ).hexdigest()
    path = invocations / f"{invocation_id}.json"
    mapping: dict[str, Any] = {
        "schema": 1, "id": invocation_id, "input_digest": input_digest,
        "status": "invocation_persisted", "purpose_id": None, "intent_id": None,
    }
    _atomic_json(path, mapping)
    self._bump()
    if failpoint == "after_invocation_persisted_before_purpose":
        raise InjectedTransitionCrash("Task5 invocation response lost before purpose")
    if stop_after == "invocation":
        return _invocation_from(mapping)
    mapping["purpose_id"] = "purpose-" + hashlib.sha256(
        f"task5:{invocation_id}:{input_digest}".encode("utf-8")
    ).hexdigest()
    mapping["status"] = "clear_retryable"
    _atomic_json(path, mapping)
    self._bump()
    if failpoint == "after_purpose_before_intent":
        raise InjectedTransitionCrash("Task5 purpose response lost before intent")
    if disposition == "clear_retryable":
        return _invocation_from(mapping)
    mapping["intent_id"] = "intent-" + hashlib.sha256(
        f"task5:{mapping['purpose_id']}".encode("utf-8")
    ).hexdigest()
    mapping["status"] = "intent_persisted"
    _atomic_json(path, mapping)
    self._bump()
    if failpoint == "after_intent_before_begin":
        raise InjectedTransitionCrash("Task5 intent response lost before begin")
    mapping["status"] = "begun"
    _atomic_json(path, mapping)
    self._bump()
    return _invocation_from(mapping)


def _task5_fresh_shell(
    self: DurableTransitionCoordinator,
    *,
    input_digest: str | None = None,
    observe_slots: Callable[[], Any] | None = None,
    inspect_dirty: Callable[[], Any] | None = None,
    inspect_report: Callable[[], Any] | None = None,
    inspect_sole_untracked_report: Callable[[], Any] | None = None,
) -> Task5RecoveryResult:
    orphan_root = self.root / "task5" / "orphan-results"
    if orphan_root.exists():
        orphans = []
        for path in sorted(orphan_root.glob("*.json")):
            try:
                value = json.loads(path.read_text("utf-8"))
            except (OSError, json.JSONDecodeError) as exc:
                raise AmbiguousTask5Recovery("Task5 orphan record is malformed") from exc
            if isinstance(value, dict) and value.get("invocation_id") is None:
                orphans.append(value)
        if len(orphans) > 1:
            raise AmbiguousTask5Recovery("multiple unbound Task5 orphan results exist")
    if observe_slots is not None:
        observe_slots()
    terminals = [state for state in self.lookup_all_generations()
                 if state.status == "archived_achieved"
                 and state.operation in {"task5", "final_evidence"}]
    if terminals:
        terminal = terminals[-1]
        return Task5RecoveryResult(
            None, terminal.input_digest, "archived_achieved",
            terminal.purpose_id, terminal.purpose_id,
        )
    invocations = _task5_invocations(self)
    matches = [mapping for mapping in invocations
               if input_digest is not None and mapping.get("input_digest") == input_digest]
    if len(matches) > 1:
        raise AmbiguousTask5Recovery("Task5 input maps to multiple invocations")
    if matches:
        mapping = matches[0]
        if mapping.get("status") == "invocation_persisted":
            mapping["purpose_id"] = "purpose-" + hashlib.sha256(
                f"task5:{mapping['id']}:{mapping['input_digest']}".encode("utf-8")
            ).hexdigest()
            mapping["status"] = "clear_retryable"
            invocations_dir, _ = _task5_dirs(self)
            _atomic_json(invocations_dir / f"{mapping['id']}.json", mapping)
            self._bump()
        invocation = _invocation_from(mapping)
        return Task5RecoveryResult(invocation.id, invocation.input_digest,
                                   invocation.status, invocation.purpose_id)
    if input_digest is not None:
        invocation = _task5_invoke(self, input_digest=input_digest)
        return Task5RecoveryResult(invocation.id, invocation.input_digest,
                                   invocation.status, invocation.purpose_id)
    if inspect_dirty is not None:
        inspect_dirty()
    if inspect_report is not None:
        inspect_report()
    if inspect_sole_untracked_report is not None:
        inspect_sole_untracked_report()
    return Task5RecoveryResult(None, None, "settled")


def _task5_resolve_batch(
    self: DurableTransitionCoordinator, input_digest: str
) -> TransitionPurpose:
    matches = [state for state in self.lookup_all_generations(operation="task5")
               if state.input_digest == input_digest and state.purpose_id]
    if len(matches) > 1:
        raise AmbiguousTask5Recovery("Task5 batch maps to multiple purposes")
    if matches:
        return self.lookup_purpose(str(matches[0].purpose_id))
    return self.issue_or_return_purpose(operation="task5", input_digest=input_digest)


def _task5_reserve(self: DurableTransitionCoordinator, input_digest: str) -> Task5Reservation:
    _, reservations = _task5_dirs(self)
    reservation_id = "reservation-" + secrets.token_hex(16)
    path = reservations / f"{reservation_id}.json"
    _atomic_json(path, {"schema": 1, "id": reservation_id,
                        "input_digest": input_digest, "begun": False,
                        "cancelled": False})
    self._bump()
    return Task5Reservation(reservation_id, input_digest, path)


def _task5_begin(
    self: DurableTransitionCoordinator, reservation: Task5Reservation
) -> Task5Reservation:
    try:
        mapping = _read_json(reservation.path, label="Task5 reservation")
    except AnchorIntegrityRefused as exc:
        raise Task5InputDrift("Task5 reservation was edited after issue") from exc
    if (mapping.get("id") != reservation.id
            or mapping.get("input_digest") != reservation.input_digest):
        raise Task5InputDrift("Task5 reservation input binding drifted")
    if mapping.get("cancelled"):
        raise Task5InputDrift("cancelled Task5 reservation cannot begin")
    mapping["begun"] = True
    _atomic_json(reservation.path, mapping)
    self._bump()
    return reservation


def _task5_cancel(
    self: DurableTransitionCoordinator,
    reservation: Task5Reservation,
    *,
    authoritative_no_begin: bool,
) -> Task5Cancellation:
    if authoritative_no_begin is not True:
        raise BegunReservationCannotCancel("authoritative no-begin observation is required")
    mapping = _read_json(reservation.path, label="Task5 reservation")
    if mapping.get("begun"):
        raise BegunReservationCannotCancel("a begun Task5 reservation cannot be cancelled")
    if (mapping.get("id") != reservation.id
            or mapping.get("input_digest") != reservation.input_digest):
        raise Task5InputDrift("Task5 cancellation binding drifted")
    mapping["cancelled"] = True
    _atomic_json(reservation.path, mapping)
    self._bump()
    return Task5Cancellation(reservation.id, True)


def _normalize_task5_batch(
    self: DurableTransitionCoordinator,
    *,
    raw_snapshot: Mapping[str, bytes],
    policy_digest: str,
) -> Task5NormalizationReceipt:
    _ = self
    if policy_digest != "strict-utf8-parent-bom-crlf-to-lf-v1":
        raise Task5InputDrift("unknown Task5 normalization policy")
    canonical: dict[str, CanonicalBatchRecord] = {}
    for path, raw in sorted(raw_snapshot.items()):
        normalized = raw
        if b"\0" not in raw:
            try:
                raw.decode("utf-8", errors="strict")
            except UnicodeDecodeError:
                pass
            else:
                if b"\r" in raw.replace(b"\r\n", b""):
                    raise Task5InputDrift("Task5 text contains lone CR")
                normalized = raw.replace(b"\r\n", b"\n")
        canonical[path] = CanonicalBatchRecord(
            path, normalized, hashlib.sha256(normalized).hexdigest()
        )
    return Task5NormalizationReceipt(
        digest_raw_snapshot(raw_snapshot), policy_digest, canonical
    )


