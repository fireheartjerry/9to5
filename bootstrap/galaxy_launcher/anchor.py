@dataclass(frozen=True)
class TofuProposal:
    source_root: str
    artifact_root: str
    merkle_root: str
    nonce: str
    policy: str
    source_leaves: Mapping[str, bytes]
    artifact_leaves: Mapping[str, bytes]


@dataclass(frozen=True)
class TofuInstallReceipt:
    source_root: str
    artifact_root: str
    merkle_root: str
    nonce: str
    external_root: Path
    activation_state: str = "inactive"


_CONSUMED_TOFU_NONCES: set[str] = set()


def _leaf_manifest(leaves: Mapping[str, bytes], domain: str) -> tuple[str, list[dict[str, Any]]]:
    if not leaves:
        raise TofuApprovalRefused(f"{domain} closure is empty")
    records: list[dict[str, Any]] = []
    for name, raw in sorted(leaves.items()):
        if (not isinstance(name, str) or not name or "\\" in name
                or name.startswith("/") or any(part in {"", ".", ".."}
                                               for part in name.split("/"))
                or not isinstance(raw, bytes)):
            raise TofuApprovalRefused(f"{domain} leaf is malformed")
        records.append({"path": name, "size": len(raw),
                        "sha256": hashlib.sha256(raw).hexdigest()})
    root = hashlib.sha256(_canonical_json({"domain": domain, "leaves": records})).hexdigest()
    return root, records


def build_tofu_proposal(
    *, source_leaves: Mapping[str, bytes], artifact_leaves: Mapping[str, bytes], policy: str
) -> TofuProposal:
    if policy != "strict-utf8-parent-bom-crlf-to-lf-v1":
        raise TofuApprovalRefused("unknown source canonicalization policy")
    source_root, _ = _leaf_manifest(source_leaves, "source")
    artifact_root, _ = _leaf_manifest(artifact_leaves, "artifact")
    nonce = secrets.token_hex(32)
    merkle = hashlib.sha256(_canonical_json({
        "schema": 1, "source_root": source_root, "artifact_root": artifact_root,
        "policy": policy, "nonce": nonce,
    })).hexdigest()
    return TofuProposal(source_root, artifact_root, merkle, nonce, policy,
                        dict(source_leaves), dict(artifact_leaves))


def _write_closure(root: Path, leaves: Mapping[str, bytes]) -> None:
    for name, raw in sorted(leaves.items()):
        target = root.joinpath(*name.split("/"))
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            raise TofuApprovalRefused(f"TOFU target collision: {name}")
        with target.open("xb") as stream:
            stream.write(raw)
            stream.flush()
            os.fsync(stream.fileno())


def install_tofu(
    proposal: TofuProposal, *, response: str, external_root: Path
) -> TofuInstallReceipt:
    source_root, _ = _leaf_manifest(proposal.source_leaves, "source")
    artifact_root, _ = _leaf_manifest(proposal.artifact_leaves, "artifact")
    expected_merkle = hashlib.sha256(_canonical_json({
        "schema": 1, "source_root": source_root, "artifact_root": artifact_root,
        "policy": proposal.policy, "nonce": proposal.nonce,
    })).hexdigest()
    exact = f"TRUST SINGULARITY BOOTSTRAP {proposal.merkle_root} NONCE {proposal.nonce}"
    if (source_root != proposal.source_root or artifact_root != proposal.artifact_root
            or expected_merkle != proposal.merkle_root
            or not secrets.compare_digest(response, exact)
            or proposal.nonce in _CONSUMED_TOFU_NONCES):
        raise TofuApprovalRefused("TOFU approval is stale, replayed, or bound to another closure")
    root = Path(external_root).resolve(strict=False)
    _assert_no_reparse(root.parent, TofuApprovalRefused, "TOFU external root")
    root.mkdir(parents=True, exist_ok=True)
    receipt_path = root / "tofu-install-receipt.json"
    if receipt_path.exists():
        raise TofuApprovalRefused("TOFU installation root is already initialized")
    source_dir = root / "source"
    artifact_dir = root / "artifacts"
    source_dir.mkdir(exist_ok=False)
    artifact_dir.mkdir(exist_ok=False)
    try:
        _write_closure(source_dir, proposal.source_leaves)
        _write_closure(artifact_dir, proposal.artifact_leaves)
        _atomic_json(receipt_path, {
            "schema": 1, "source_root": source_root, "artifact_root": artifact_root,
            "merkle_root": proposal.merkle_root, "nonce": proposal.nonce,
            "activation_state": "inactive",
        })
    except Exception:
        # A partial create-only root remains quarantined evidence.  Never delete
        # it and risk adopting a raced foreign path on retry.
        raise
    _CONSUMED_TOFU_NONCES.add(proposal.nonce)
    return TofuInstallReceipt(source_root, artifact_root, proposal.merkle_root,
                              proposal.nonce, root)


