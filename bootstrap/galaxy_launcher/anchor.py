    def cancel(
        self: DurableTransitionCoordinator,
        reservation: Task5Reservation,
        *,
        authoritative_no_begin: bool,
    ) -> Task5Cancellation:
        _ = name
        return _task5_cancel(
            self, reservation, authoritative_no_begin=authoritative_no_begin
        )
    setattr(DurableTransitionCoordinator, name, cancel)


