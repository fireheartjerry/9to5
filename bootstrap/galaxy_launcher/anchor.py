def _canonical_json(value: Mapping[str, Any]) -> bytes:
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False
    ).encode("utf-8")


def _sealed_mapping(mapping: Mapping[str, Any]) -> dict[str, Any]:
    result = dict(mapping)
    result.pop("record_sha256", None)
    result["record_sha256"] = hashlib.sha256(_canonical_json(result)).hexdigest()
    return result


def _verify_mapping(mapping: Any, *, label: str) -> dict[str, Any]:
    if not isinstance(mapping, dict):
        raise AnchorIntegrityRefused(f"{label} record must be an object")
    digest = mapping.get("record_sha256")
    unsigned = dict(mapping)
    unsigned.pop("record_sha256", None)
    if not isinstance(digest, str) or not secrets.compare_digest(
        digest, hashlib.sha256(_canonical_json(unsigned)).hexdigest()
    ):
        raise AnchorIntegrityRefused(f"{label} record digest mismatch")
    return mapping


def _atomic_json(path: Path, mapping: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    sealed = _sealed_mapping(mapping)
    raw = _canonical_json(sealed)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.{secrets.token_hex(8)}.tmp")
    try:
        with temporary.open("xb") as stream:
            stream.write(raw)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def _read_json(path: Path, *, label: str) -> dict[str, Any]:
    _assert_no_reparse(path, AnchorIntegrityRefused, label)
    try:
        raw = path.read_bytes()
        if raw.startswith((b"\xef\xbb\xbf", b"\xff\xfe", b"\xfe\xff")):
            raise AnchorIntegrityRefused(f"{label} BOM is forbidden")
        mapping = json.loads(raw.decode("utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise AnchorIntegrityRefused(f"{label} record is unreadable") from exc
    if _canonical_json(mapping) != raw:
        raise AnchorIntegrityRefused(f"{label} record is not canonical JSON")
    return _verify_mapping(mapping, label=label)


class DurableTransitionCoordinator:
    """Create-or-return transition state with one host-global logical owner."""

    def __init__(self, root: Path, *, epoch: str, owner_id: str):
        if not epoch or not owner_id:
            raise ValueError("epoch and owner identity are required")
        self.root = Path(root).resolve(strict=False)
        self.root.mkdir(parents=True, exist_ok=True)
        _assert_no_reparse(self.root, AnchorIntegrityRefused, "transition root")
        self.epoch = epoch
        self.owner_id = owner_id
        self.transitions = self.root / "transitions"
        self.transitions.mkdir(exist_ok=True)
        self.meta_path = self.root / "transition-meta.json"
        if not self.meta_path.exists():
            _atomic_json(self.meta_path, {"schema": 1, "revision": 0})

    def _meta(self) -> dict[str, Any]:
        return _read_json(self.meta_path, label="transition meta")

    def _revision(self) -> int:
        value = self._meta().get("revision")
        if not isinstance(value, int) or value < 0:
            raise AnchorIntegrityRefused("transition revision is malformed")
        return value

    def _bump(self) -> int:
        revision = self._revision() + 1
        _atomic_json(self.meta_path, {"schema": 1, "revision": revision})
        return revision

    def _path(self, slot_id: str) -> Path:
        if not re.fullmatch(r"slot-[0-9a-f]{32}", slot_id):
            raise AnchorIntegrityRefused("transition slot identity is malformed")
        return self.transitions / f"{slot_id}.json"

    def _read(self, slot_id: str) -> dict[str, Any]:
        mapping = _read_json(self._path(slot_id), label="transition")
        if mapping.get("schema") != 1 or mapping.get("slot_id") != slot_id:
            raise AnchorIntegrityRefused("transition slot binding mismatch")
        return mapping

    def _write(self, mapping: Mapping[str, Any]) -> None:
        _atomic_json(self._path(str(mapping["slot_id"])), mapping)
        self._bump()

    @staticmethod
    def _state(mapping: Mapping[str, Any]) -> TransitionState:
        return TransitionState(
            slot_id=str(mapping["slot_id"]),
            operation=str(mapping["operation"]),
            input_digest=str(mapping["input_digest"]),
            epoch=str(mapping["epoch"]),
            phase=str(mapping["phase"]),
            purpose_id=mapping.get("purpose_id"),
            intent_id=mapping.get("intent_id"),
            owner_id=str(mapping["owner_id"]),
            owner_generation=int(mapping["owner_generation"]),
            owner_token_value=str(mapping["owner_token"]),
            status=str(mapping["status"]),
            acknowledged=bool(mapping["acknowledged"]),
            production_active=bool(mapping["production_active"]),
            discord_enabled=bool(mapping["discord_enabled"]),
            predecessor_id=mapping.get("predecessor_id"),
        )

    @staticmethod
    def _purpose(mapping: Mapping[str, Any]) -> TransitionPurpose:
        purpose_id = mapping.get("purpose_id")
        if not isinstance(purpose_id, str):
            raise PurposeMismatch("transition purpose is absent")
        return TransitionPurpose(
            id=purpose_id,
            operation=str(mapping["operation"]),
            input_digest=str(mapping["input_digest"]),
            plan_node=str(mapping.get("plan_node", "recovered")),
            expected_old=str(mapping.get("expected_old", "old")),
            epoch=str(mapping["purpose_epoch"]),
            predecessor_id=mapping.get("predecessor_id"),
        )

    def _all_mappings(self) -> list[dict[str, Any]]:
        result: list[dict[str, Any]] = []
        for path in sorted(self.transitions.glob("slot-*.json")):
            result.append(_read_json(path, label="transition"))
        return result

    def _active(self) -> list[dict[str, Any]]:
        return [mapping for mapping in self._all_mappings()
                if mapping.get("status") not in {"archived_achieved", "cancelled"}]

    def _require_owner(
        self, mapping: Mapping[str, Any], token: TransitionOwnerToken | None = None
    ) -> None:
        if mapping.get("owner_id") != self.owner_id:
            raise StaleTransitionOwner("coordinator no longer owns this transition")
        if token is not None and (
            token.owner_id != mapping.get("owner_id")
            or token.owner_generation != mapping.get("owner_generation")
            or not secrets.compare_digest(token.token, str(mapping.get("owner_token")))
        ):
            raise StaleTransitionOwner("transition owner token is stale")

    def reserve(self, *, operation: str, input_digest: str) -> str:
        if not operation or not input_digest:
            raise ValueError("operation and input digest are required")
        if self._active():
            raise GlobalTransitionMutexHeld("another all-generation transition owns the mutex")
        slot = f"slot-{secrets.token_hex(16)}"
        mapping = {
            "schema": 1,
            "slot_id": slot,
            "operation": operation,
            "input_digest": input_digest,
            "epoch": self.epoch,
            "phase": "reserved",
            "purpose_id": None,
            "purpose_epoch": self.epoch,
            "intent_id": None,
            "owner_id": self.owner_id,
            "owner_generation": 1,
            "owner_token": secrets.token_hex(32),
            "status": "reserved",
            "acknowledged": False,
            "production_active": False,
            "discord_enabled": False,
            "predecessor_id": None,
        }
        self._write(mapping)
        return slot

    def issue_purpose(
        self,
        slot_id: str,
        *,
        plan_node: str,
        expected_old: str,
        lose_response_after_persist: bool = False,
        after_persist_hook: Callable[[], Any] | None = None,
    ) -> TransitionPurpose | None:
        mapping = self._read(slot_id)
        self._require_owner(mapping)
        if mapping.get("purpose_id") is None:
            identity = hashlib.sha256(
                _canonical_json({
                    "slot": slot_id, "operation": mapping["operation"],
                    "input": mapping["input_digest"], "epoch": mapping["epoch"],
                    "nonce": secrets.token_hex(16),
                })
            ).hexdigest()
            mapping.update({
                "purpose_id": f"purpose-{identity}",
                "purpose_epoch": mapping["epoch"],
                "plan_node": plan_node,
                "expected_old": expected_old,
                "phase": "purpose",
                "status": "purpose_persisted",
            })
            self._write(mapping)
        elif (mapping.get("plan_node") != plan_node
              or mapping.get("expected_old") != expected_old):
            raise PurposeMismatch("purpose replay changed its plan binding")
        purpose = self._purpose(mapping)
        if after_persist_hook is not None:
            after_persist_hook()
        if lose_response_after_persist:
            return None
        return purpose

    def resolve_purpose(self, slot_id: str) -> TransitionPurpose:
        return self._purpose(self._read(slot_id))

    def persist_intent(self, slot_id: str, *, purpose_id: str) -> TransitionIntent:
        mapping = self._read(slot_id)
        self._require_owner(mapping)
        if mapping.get("purpose_id") != purpose_id:
            raise PurposeMismatch("intent purpose binding mismatch")
        if mapping.get("intent_id") is None:
            mapping["intent_id"] = "intent-" + hashlib.sha256(
                f"{slot_id}:{purpose_id}".encode("utf-8")
            ).hexdigest()
            mapping["phase"] = "intent"
            mapping["status"] = "intent_persisted"
            self._write(mapping)
        return TransitionIntent(str(mapping["intent_id"]), purpose_id)

    def begin(self, slot_id: str, *, purpose_id: str, intent_id: str) -> TransitionBegin:
        mapping = self._read(slot_id)
        self._require_owner(mapping)
        if mapping.get("purpose_id") != purpose_id or mapping.get("intent_id") != intent_id:
            raise PurposeMismatch("begin intent/purpose binding mismatch")
        mapping["phase"] = "begin"
        mapping["status"] = "begun"
        self._write(mapping)
        return TransitionBegin(intent_id, purpose_id, self.owner_token(slot_id))

    def owner_token(self, slot_id: str) -> TransitionOwnerToken:
        mapping = self._read(slot_id)
        return TransitionOwnerToken(
            str(mapping["owner_token"]), str(mapping["owner_id"]),
            int(mapping["owner_generation"]),
        )

    def record_cas(
        self, slot_id: str, *, owner_token: TransitionOwnerToken, old: str = "old",
        new: str = "new",
    ) -> TransitionState:
        mapping = self._read(slot_id)
        self._require_owner(mapping, owner_token)
        if mapping.get("expected_old", old) != old:
            raise PurposeMismatch("CAS old-value binding mismatch")
        mapping.update({"phase": "cas", "status": "cas_persisted", "cas_old": old,
                        "cas_new": new})
        self._write(mapping)
        return self._state(mapping)

    def finish(
        self, slot_id: str, *, owner_token: TransitionOwnerToken
    ) -> TransitionState:
        mapping = self._read(slot_id)
        self._require_owner(mapping, owner_token)
        mapping.update({"phase": "finish", "status": "finished"})
        self._write(mapping)
        return self._state(mapping)

    def observe(
        self, slot_id: str, *, terminal_token: str | None = None
    ) -> TransitionObservation:
        mapping = self._read(slot_id)
        if terminal_token is not None and terminal_token != mapping.get("purpose_id"):
            raise PurposeMismatch("terminal observation purpose mismatch")
        if mapping.get("status") != "archived_achieved":
            self._require_owner(mapping)
            mapping.update({"phase": "observe", "status": "observed"})
            self._write(mapping)
        revision = self._revision()
        token = hashlib.sha256(
            f"{slot_id}:{mapping.get('purpose_id')}:{revision}".encode("utf-8")
        ).hexdigest()
        return TransitionObservation(token, slot_id, revision)

    def acknowledge(
        self,
        slot_id: str,
        *,
        observation_token: str | None = None,
        owner_token: TransitionOwnerToken | None = None,
        lose_response_after_persist: bool = False,
    ) -> TransitionState | None:
        mapping = self._read(slot_id)
        self._require_owner(mapping, owner_token)
        if owner_token is not None and observation_token is None:
            observation_token = "owner-bound-stale-check"
        revision = self._revision()
        expected = hashlib.sha256(
            f"{slot_id}:{mapping.get('purpose_id')}:{revision}".encode("utf-8")
        ).hexdigest()
        if observation_token != expected:
            raise StaleObservation("observation token does not name current global truth")
        mapping.update({"phase": "acknowledge", "status": "acknowledged",
                        "acknowledged": True})
        self._write(mapping)
        if lose_response_after_persist:
            return None
        return self._state(mapping)

    def archive(self, slot_id: str) -> TransitionState:
        mapping = self._read(slot_id)
        self._require_owner(mapping)
        if not mapping.get("acknowledged"):
            raise StaleObservation("unacknowledged transition cannot be archived")
        mapping.update({"phase": "archive", "status": "archived_achieved",
                        "production_active": False, "discord_enabled": False})
        self._write(mapping)
        return self._state(mapping)

    def takeover(
        self,
        slot_id: str,
        *,
        owner_dead: bool | None,
        resources_quiescent: bool | None,
        expected_owner_generation: int | None = None,
    ) -> TransitionState:
        if owner_dead is None or resources_quiescent is None:
            raise LivenessUnknown("transition owner liveness/quiescence is unknown")
        if not owner_dead or not resources_quiescent:
            raise LiveOwnerConflict("a live or nonquiescent owner cannot be fenced")
        mapping = self._read(slot_id)
        if (expected_owner_generation is not None
                and mapping.get("owner_generation") != expected_owner_generation):
            raise StaleTransitionOwner("takeover generation precondition is stale")
        mapping["owner_generation"] = int(mapping["owner_generation"]) + 1
        mapping["owner_id"] = self.owner_id
        mapping["owner_token"] = secrets.token_hex(32)
        self._write(mapping)
        return self._state(mapping)

    def mutate(
        self, slot_id: str, *, mutation: str, owner_token: TransitionOwnerToken
    ) -> TransitionState:
        mapping = self._read(slot_id)
        self._require_owner(mapping, owner_token)
        mapping["last_mutation"] = mutation
        self._write(mapping)
        return self._state(mapping)

    def advance(self, slot_id: str, phase: str, *, failpoint: str | None = None) -> TransitionState:
        if phase not in RECOVERABLE_PHASES - {"reserved"}:
            raise ValueError(f"unknown transition phase: {phase}")
        if failpoint == f"before_persist:{phase}":
            raise InjectedTransitionCrash(f"injected before {phase} persistence")
        mapping = self._read(slot_id)
        self._require_owner(mapping)
        if mapping.get("purpose_id") is None:
            identity = hashlib.sha256(
                f"recovery:{slot_id}:{mapping['input_digest']}".encode("utf-8")
            ).hexdigest()
            mapping.update({
                "purpose_id": f"purpose-{identity}", "purpose_epoch": mapping["epoch"],
                "plan_node": "recovery-campaign", "expected_old": "old",
            })
        if phase in {"intent", "begin", "cas", "finish", "observe", "acknowledge", "archive"}:
            mapping.setdefault(
                "intent_id",
                "intent-" + hashlib.sha256(
                    f"{slot_id}:{mapping['purpose_id']}".encode("utf-8")
                ).hexdigest(),
            )
        mapping["phase"] = phase
        mapping["status"] = "archived_achieved" if phase == "archive" else f"{phase}_persisted"
        if phase in {"acknowledge", "archive"}:
            mapping["acknowledged"] = True
        self._write(mapping)
        state = self._state(mapping)
        if failpoint == f"after_persist:{phase}":
            raise InjectedTransitionCrash(f"injected after {phase} persistence")
        return state

    def recover_all_generations(self) -> list[TransitionState]:
        recovered: list[TransitionState] = []
        for mapping in self._all_mappings():
            if mapping.get("phase") not in RECOVERABLE_PHASES:
                raise AnchorIntegrityRefused("transition phase is outside the recoverable enum")
            if mapping.get("status") not in {"archived_achieved", "cancelled"}:
                if mapping.get("owner_id") != self.owner_id:
                    mapping["owner_generation"] = int(mapping["owner_generation"]) + 1
                    mapping["owner_id"] = self.owner_id
                    mapping["owner_token"] = secrets.token_hex(32)
                if mapping.get("purpose_id") is None:
                    identity = hashlib.sha256(
                        f"resume:{mapping['slot_id']}:{mapping['input_digest']}".encode("utf-8")
                    ).hexdigest()
                    mapping.update({
                        "purpose_id": f"purpose-{identity}",
                        "purpose_epoch": mapping["epoch"], "plan_node": "recovered",
                        "expected_old": "old", "phase": "purpose",
                        "status": "purpose_persisted",
                    })
                self._write(mapping)
            recovered.append(self._state(mapping))
        return recovered

    def resume(self, slot_id: str) -> TransitionState:
        mapping = self._read(slot_id)
        if mapping.get("epoch") != self.epoch:
            raise EpochMismatch("transition epoch differs from the requested recovery epoch")
        if mapping.get("status") not in {"archived_achieved", "cancelled"}:
            self._require_owner(mapping)
        if mapping.get("purpose_id") is None:
            identity = hashlib.sha256(
                f"resume:{slot_id}:{mapping['input_digest']}".encode("utf-8")
            ).hexdigest()
            mapping.update({
                "purpose_id": f"purpose-{identity}", "purpose_epoch": mapping["epoch"],
                "plan_node": "recovered", "expected_old": "old", "phase": "purpose",
                "status": "purpose_persisted",
            })
            self._write(mapping)
        return self._state(mapping)

    def lookup_all_generations(self, operation: str | None = None) -> list[TransitionState]:
        states = [self._state(mapping) for mapping in self._all_mappings()
                  if operation is None or mapping.get("operation") == operation]
        return sorted(states, key=lambda state: state.slot_id)

    def _purpose_candidates(self, purpose_id: str) -> list[dict[str, Any]]:
        candidates: list[dict[str, Any]] = []
        for path in sorted(self.root.rglob("*.json")):
            try:
                raw = path.read_bytes()
            except OSError:
                continue
            if purpose_id.encode("utf-8") not in raw:
                continue
            try:
                mapping = _read_json(path, label="purpose lookup")
            except AnchorIntegrityRefused:
                continue
            if mapping.get("purpose_id") == purpose_id or mapping.get("id") == purpose_id:
                candidates.append(mapping)
        return candidates

    def lookup_purpose(self, purpose_id: str) -> TransitionPurpose:
        candidates = self._purpose_candidates(purpose_id)
        predecessor_refs = 0
        for path in sorted(self.root.rglob("*.json")):
            try:
                mapping = _read_json(path, label="purpose predecessor lookup")
            except (OSError, AnchorIntegrityRefused):
                continue
            if mapping.get("predecessor_id") == purpose_id:
                predecessor_refs += 1
        if predecessor_refs > 1:
            raise AmbiguousArchivedPurpose("purpose predecessor appears in duplicate records")
        if len(candidates) != 1:
            if len(candidates) > 1:
                raise AmbiguousArchivedPurpose("purpose appears in multiple durable records")
            raise PurposeMismatch("purpose does not exist")
        mapping = candidates[0]
        if mapping.get("purpose_id") == purpose_id:
            return self._purpose(mapping)
        return TransitionPurpose(
            id=purpose_id,
            operation=str(mapping["operation"]),
            input_digest=str(mapping["input_digest"]),
            plan_node=str(mapping["plan_node"]),
            expected_old=str(mapping["expected_old"]),
            epoch=str(mapping["epoch"]),
            predecessor_id=mapping.get("predecessor_id"),
        )

    def issue_or_return_purpose(
        self,
        *,
        operation: str,
        input_digest: str,
        predecessor_purpose: str | None = None,
    ) -> TransitionPurpose:
        matches = [mapping for mapping in self._all_mappings()
                   if mapping.get("operation") == operation
                   and mapping.get("input_digest") == input_digest
                   and mapping.get("purpose_id")]
        if len(matches) > 1:
            raise AmbiguousArchivedPurpose("operation/input maps to multiple purposes")
        if matches:
            purpose = self._purpose(matches[0])
            if predecessor_purpose != purpose.predecessor_id:
                if predecessor_purpose is not None:
                    raise PurposeMismatch("purpose predecessor replay differs")
            return purpose
        slot = self.reserve(operation=operation, input_digest=input_digest)
        mapping = self._read(slot)
        mapping["predecessor_id"] = predecessor_purpose
        self._write(mapping)
        issued = self.issue_purpose(slot, plan_node="purpose-handoff", expected_old="old")
        assert issued is not None
        return issued

    def reviewed_wave_restart(self, purpose_id: str, *, new_epoch: str) -> TransitionPurpose:
        original = self.lookup_purpose(purpose_id)
        restarted = TransitionPurpose(
            id="purpose-" + hashlib.sha256(
                f"restart:{purpose_id}:{new_epoch}:{secrets.token_hex(16)}".encode("utf-8")
            ).hexdigest(),
            operation=original.operation,
            input_digest=original.input_digest,
            plan_node="reviewed-wave-restart",
            expected_old=original.expected_old,
            epoch=new_epoch,
            predecessor_id=purpose_id,
        )
        path = self.root / "reviewed-restarts" / f"{restarted.id}.json"
        _atomic_json(path, {
            "schema": 1, "id": restarted.id, "operation": restarted.operation,
            "input_digest": restarted.input_digest, "plan_node": restarted.plan_node,
            "expected_old": restarted.expected_old, "epoch": restarted.epoch,
            "predecessor_id": restarted.predecessor_id,
        })
        self._bump()
        return restarted


