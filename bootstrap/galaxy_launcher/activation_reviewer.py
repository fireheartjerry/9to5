"""Independent, authority-free audit of the native Singularity anchor.

The reviewer consumes only canonical, digest-bound files.  Its result is an
advisory observation: the installed anchor must independently verify it and
mint any durable review receipt.  This module cannot install, sign, activate,
or mutate a controller generation.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ActivationReviewRefused  -- The reviewer input was ambiguous, unbound, or contaminated.
  review_anchor(*, source_path: Path, launch_record_path: Path, request_path: Path) -> dict[str, object]  -- Audit exact anchor bytes and a closed launch record without granting authority.
  review_source_proposal(*, proposal_path: Path, object_root: Path, request_path: Path, hash_object: Callable[[str, bytes], str]) -> dict[str, object]  -- Independently rebuild a proposal from inert bytes with no write authority.
  main(argv: Sequence[str] | None=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import stat
import subprocess
import sys
from pathlib import Path, PureWindowsPath
from typing import Any, Callable, Mapping, Sequence

_SHA256 = re.compile(r"^[0-9a-f]{64}$")
_TOKEN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")
_DRIVE_PATH = re.compile(r"^[A-Za-z]:\\(?!\\)")
_MAX_JSON_BYTES = 64 * 1024
_MAX_SOURCE_BYTES = 512 * 1024
_MAX_PROPOSAL_BYTES = 64 * 1024 * 1024
_MAX_OBJECT_FRAME_BYTES = 128 * 1024 * 1024 + 64
_CONTAMINATION_CONTROLS = [
    "fresh-session",
    "no-writer-rationale",
    "no-writer-transcript",
    "read-only-inputs",
]
_HOST_SUFFIX = r"\System32\WindowsPowerShell\v1.0\powershell.exe"
_HOST_ARGUMENTS = ["-NoLogo", "-NoProfile", "-NonInteractive"]


class ActivationReviewRefused(RuntimeError):
    """The reviewer input was ambiguous, unbound, or contaminated."""


def _canonical_json(value: object) -> bytes:
    return json.dumps(
        value, ensure_ascii=False, separators=(",", ":"), sort_keys=True
    ).encode("utf-8")


def _reject_duplicate_pairs(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise ActivationReviewRefused("JSON contains a duplicate key")
        result[key] = value
    return result


def _reject_non_integral(value: str) -> object:
    raise ActivationReviewRefused(f"non-integral JSON value is forbidden: {value}")


def _load_canonical(
    path: Path, *, label: str, maximum: int = _MAX_JSON_BYTES
) -> dict[str, Any]:
    try:
        metadata = path.lstat()
        if (
            stat.S_ISLNK(metadata.st_mode)
            or not stat.S_ISREG(metadata.st_mode)
            or metadata.st_nlink != 1
        ):
            raise ActivationReviewRefused(f"{label} must be an ordinary file")
        raw = path.read_bytes()
    except OSError as exc:
        raise ActivationReviewRefused(f"{label} is unavailable") from exc
    if not raw or len(raw) > maximum or raw.startswith(b"\xef\xbb\xbf"):
        raise ActivationReviewRefused(f"{label} size or encoding is refused")
    try:
        value = json.loads(
            raw.decode("utf-8", errors="strict"),
            object_pairs_hook=_reject_duplicate_pairs,
            parse_float=_reject_non_integral,
            parse_constant=_reject_non_integral,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ActivationReviewRefused(f"{label} is not strict UTF-8 JSON") from exc
    if not isinstance(value, dict) or _canonical_json(value) != raw:
        raise ActivationReviewRefused(f"{label} is not canonical JSON")
    return value


def _read_source(path: Path) -> tuple[bytes, str]:
    try:
        metadata = path.lstat()
        if stat.S_ISLNK(metadata.st_mode) or not stat.S_ISREG(metadata.st_mode):
            raise ActivationReviewRefused("anchor source must be an ordinary file")
        raw = path.read_bytes()
    except OSError as exc:
        raise ActivationReviewRefused("anchor source is unavailable") from exc
    if not raw or len(raw) > _MAX_SOURCE_BYTES or raw.startswith(b"\xef\xbb\xbf"):
        raise ActivationReviewRefused("anchor source size or encoding is refused")
    try:
        text = raw.decode("utf-8", errors="strict")
    except UnicodeDecodeError as exc:
        raise ActivationReviewRefused("anchor source is not strict UTF-8") from exc
    if "\r" in text or "\x00" in text:
        raise ActivationReviewRefused("anchor source is not canonical LF text")
    return raw, text


def _require_digest(value: object, label: str) -> str:
    if not isinstance(value, str) or _SHA256.fullmatch(value) is None:
        raise ActivationReviewRefused(f"{label} must be a full lowercase SHA-256")
    return value


def _require_token(value: object, label: str) -> str:
    if not isinstance(value, str) or _TOKEN.fullmatch(value) is None:
        raise ActivationReviewRefused(f"{label} is malformed")
    return value


def _validate_request(value: dict[str, Any]) -> None:
    expected = {
        "contamination_controls",
        "independence_context_sha256",
        "installed_anchor_path",
        "launch_record_sha256",
        "prior_reviewer_ids",
        "review_id",
        "review_slot",
        "reviewer_id",
        "schema",
        "source_sha256",
    }
    if set(value) != expected or value["schema"] != "galaxy.activation-review-request/v1":
        raise ActivationReviewRefused("review request fields or schema are not closed")
    _require_digest(value["source_sha256"], "source_sha256")
    _require_digest(value["launch_record_sha256"], "launch_record_sha256")
    _require_digest(value["independence_context_sha256"], "independence context")
    installed_anchor_path = value["installed_anchor_path"]
    if (
        not isinstance(installed_anchor_path, str)
        or _DRIVE_PATH.match(installed_anchor_path) is None
        or ".." in PureWindowsPath(installed_anchor_path).parts
        or not installed_anchor_path.casefold().endswith(
            r"\bootstrap\singularity_anchor.ps1".casefold()
        )
    ):
        raise ActivationReviewRefused("installed anchor path is not exact and absolute")
    _require_token(value["review_id"], "review_id")
    reviewer_id = _require_token(value["reviewer_id"], "reviewer_id")
    if value["review_slot"] not in (1, 2):
        raise ActivationReviewRefused("review_slot must be exactly 1 or 2")
    if value["contamination_controls"] != _CONTAMINATION_CONTROLS:
        raise ActivationReviewRefused("contamination controls are incomplete or reordered")
    prior = value["prior_reviewer_ids"]
    if not isinstance(prior, list) or len(prior) > 1:
        raise ActivationReviewRefused("prior reviewer set is malformed")
    for item in prior:
        _require_token(item, "prior reviewer id")
    if reviewer_id in prior:
        raise ActivationReviewRefused("reviewer is not independent from a prior pass")
    if value["review_slot"] == 1 and prior:
        raise ActivationReviewRefused("first review pass cannot name a prior reviewer")
    if value["review_slot"] == 2 and len(prior) != 1:
        raise ActivationReviewRefused("second review pass requires one distinct prior reviewer")


def _validate_launch_record(
    value: dict[str, Any], *, installed_anchor_path: str, source_sha256: str
) -> None:
    expected = {
        "activation_state",
        "anchor_path",
        "anchor_sha256",
        "arguments",
        "control_pipe",
        "environment",
        "host_path",
        "host_sha256",
        "host_signature",
        "host_signature_sha256",
        "schema",
        "service_name",
        "stdio",
        "working_directory",
    }
    if set(value) != expected or value["schema"] != "galaxy.singularity-anchor-launch/v1":
        raise ActivationReviewRefused("launch record fields or schema are not closed")
    if value["activation_state"] != "inactive":
        raise ActivationReviewRefused("reviewed bootstrap launch must remain inactive")
    if (
        value["anchor_path"] != installed_anchor_path
        or value["anchor_sha256"] != source_sha256
    ):
        raise ActivationReviewRefused("launch record does not bind the reviewed anchor bytes")
    host = value["host_path"]
    workdir = value["working_directory"]
    if (
        not isinstance(host, str)
        or _DRIVE_PATH.match(host) is None
        or not host.casefold().endswith(_HOST_SUFFIX.casefold())
        or not isinstance(workdir, str)
        or _DRIVE_PATH.match(workdir) is None
    ):
        raise ActivationReviewRefused("host or working directory is not a strict local path")
    _require_digest(value["host_sha256"], "host_sha256")
    arguments = value["arguments"]
    if not isinstance(arguments, list) or len(arguments) != 23 or arguments[:3] != _HOST_ARGUMENTS:
        raise ActivationReviewRefused("PowerShell launch arguments are not exact")
    expected_names = {
        3: "-File",
        5: "-ProtectedRecordPath",
        7: "-Operation",
        9: "-ExpectedRecordSha256",
        11: "-ExpectedHostPath",
        13: "-ExpectedHostSha256",
        15: "-ExpectedHostSignatureSha256",
        17: "-ExpectedAnchorSha256",
        19: "-JsonAssemblyPath",
        21: "-ExpectedJsonAssemblySha256",
    }
    if any(arguments[index] != expected for index, expected in expected_names.items()):
        raise ActivationReviewRefused("anchor argument names or order drifted")
    if arguments[4] != installed_anchor_path or arguments[8] != "diagnostic":
        raise ActivationReviewRefused("anchor source or inactive operation binding drifted")
    if arguments[12] != host or arguments[14] != value["host_sha256"]:
        raise ActivationReviewRefused("anchor host argument binding drifted")
    if arguments[18] != source_sha256:
        raise ActivationReviewRefused("anchor digest argument binding drifted")
    _require_digest(arguments[10], "protected record sha256")
    host_signature_sha256 = _require_digest(
        value["host_signature_sha256"], "host signature sha256"
    )
    if arguments[16] != host_signature_sha256:
        raise ActivationReviewRefused("anchor host signature argument binding drifted")
    host_signature = value["host_signature"]
    if (
        not isinstance(host_signature, dict)
        or set(host_signature)
        != {
            "is_os_binary",
            "signature_type",
            "signer_subject",
            "signer_thumbprint",
            "status",
        }
        or hashlib.sha256(_canonical_json(host_signature)).hexdigest()
        != host_signature_sha256
        or host_signature["is_os_binary"] is not True
        or host_signature["status"] != "Valid"
        or host_signature["signature_type"] not in {"Catalog", "Authenticode"}
        or not isinstance(host_signature["signer_subject"], str)
        or not host_signature["signer_subject"].startswith("CN=Microsoft Windows,")
        or not isinstance(host_signature["signer_thumbprint"], str)
        or re.fullmatch(r"[0-9a-f]{40}", host_signature["signer_thumbprint"])
        is None
    ):
        raise ActivationReviewRefused("host signature record is not exact and OS-owned")
    _require_digest(arguments[22], "JSON parser sha256")
    if (
        not isinstance(arguments[6], str)
        or _DRIVE_PATH.match(arguments[6]) is None
        or not isinstance(arguments[20], str)
        or _DRIVE_PATH.match(arguments[20]) is None
    ):
        raise ActivationReviewRefused("record or JSON parser argument is not a strict path")
    if value["service_name"] != "9to5Singularity":
        raise ActivationReviewRefused("service name differs from the protected name")
    if value["control_pipe"] != r"\\.\pipe\9to5-singularity-v1":
        raise ActivationReviewRefused("control pipe differs from the protected endpoint")
    if value["stdio"] != {"stderr": "null", "stdin": "null", "stdout": "null"}:
        raise ActivationReviewRefused("standard handles are not closed")
    environment = value["environment"]
    if not isinstance(environment, dict) or set(environment) != {
        "PATH",
        "PSModulePath",
        "SystemRoot",
        "WINDIR",
    }:
        raise ActivationReviewRefused("launch environment is not closed")
    if environment["PATH"] != "" or environment["PSModulePath"] != "":
        raise ActivationReviewRefused("command and module search must be empty")
    if environment["SystemRoot"] != environment["WINDIR"]:
        raise ActivationReviewRefused("Windows root bindings disagree")


def _audit_source(text: str) -> list[dict[str, object]]:
    rules = (
        ("P0", "dynamic-evaluation", re.compile(r"(?im)^\s*(?:Invoke-Expression|iex)\b")),
        ("P0", "module-import", re.compile(r"(?im)^\s*Import-Module\b")),
        ("P0", "dot-source", re.compile(r"(?m)^\s*\.\s+[^.]")),
        ("P1", "command-resolution", re.compile(r"(?im)^\s*Get-Command\b")),
        ("P1", "profile-access", re.compile(r"(?i)\$(?:PROFILE|profile)\b")),
    )
    findings: list[dict[str, object]] = []
    for severity, code, pattern in rules:
        match = pattern.search(text)
        if match is None:
            continue
        findings.append(
            {
                "code": code,
                "line": text.count("\n", 0, match.start()) + 1,
                "message": "forbidden ambient PowerShell mechanism",
                "severity": severity,
            }
        )
    return sorted(findings, key=lambda item: (str(item["severity"]), str(item["code"])))


def review_anchor(
    *, source_path: Path, launch_record_path: Path, request_path: Path
) -> dict[str, object]:
    """Audit exact anchor bytes and a closed launch record without granting authority."""
    request = _load_canonical(request_path, label="review request")
    _validate_request(request)
    source_raw, source_text = _read_source(source_path)
    source_sha256 = hashlib.sha256(source_raw).hexdigest()
    if source_sha256 != request["source_sha256"]:
        raise ActivationReviewRefused("reviewed source digest drift")
    launch_raw = launch_record_path.read_bytes()
    launch_sha256 = hashlib.sha256(launch_raw).hexdigest()
    if launch_sha256 != request["launch_record_sha256"]:
        raise ActivationReviewRefused("launch record digest drift")
    launch = _load_canonical(launch_record_path, label="launch record")
    _validate_launch_record(
        launch,
        installed_anchor_path=request["installed_anchor_path"],
        source_sha256=source_sha256,
    )
    findings = _audit_source(source_text)
    counts = {severity: 0 for severity in ("P0", "P1", "P2", "P3")}
    for finding in findings:
        counts[str(finding["severity"])] += 1
    return {
        "authority": False,
        "bindings": {
            "independence_context_sha256": request["independence_context_sha256"],
            "installed_anchor_path": request["installed_anchor_path"],
            "launch_record_sha256": launch_sha256,
            "source_sha256": source_sha256,
        },
        "decision": "advisory_refuse" if counts["P0"] or counts["P1"] else "advisory_pass",
        "finding_counts": counts,
        "findings": findings,
        "review_id": request["review_id"],
        "review_slot": request["review_slot"],
        "reviewer_id": request["reviewer_id"],
        "schema": "galaxy.activation-review-observation/v1",
        "signature": None,
    }


def _source_review_request(path: Path) -> dict[str, Any]:
    request = _load_canonical(path, label="source review request")
    expected = {
        "contamination_controls",
        "pass_index",
        "proposal_id",
        "proposal_record_sha256",
        "reviewer_image_digest",
        "reviewer_qualification_receipt_id",
        "reviewer_runtime_sha256",
        "reviewer_session_id",
        "schema",
    }
    if (
        set(request) != expected
        or request.get("schema") != "galaxy.source-proposal-review-request/v1"
        or request.get("contamination_controls") != _CONTAMINATION_CONTROLS
        or type(request.get("pass_index")) is not int
        or request["pass_index"] not in {1, 2}
        or re.fullmatch(r"proposal_[0-9a-f]{64}", str(request.get("proposal_id")))
        is None
        or _SHA256.fullmatch(str(request.get("proposal_record_sha256"))) is None
        or _SHA256.fullmatch(str(request.get("reviewer_runtime_sha256"))) is None
        or re.fullmatch(
            r"sha256:[0-9a-f]{64}", str(request.get("reviewer_image_digest"))
        )
        is None
        or re.fullmatch(
            r"reviewerqualification_[0-9a-f]{64}",
            str(request.get("reviewer_qualification_receipt_id")),
        )
        is None
        or re.fullmatch(
            r"reviewsession_[0-9a-f]{64}",
            str(request.get("reviewer_session_id")),
        )
        is None
    ):
        raise ActivationReviewRefused("source review request binding differs")
    return request


def _source_proposal(path: Path, request: Mapping[str, Any]) -> dict[str, Any]:
    proposal = _load_canonical(
        path, label="source proposal", maximum=_MAX_PROPOSAL_BYTES
    )
    expected = {
        "allowed_paths",
        "canonical_ref_written",
        "changes",
        "commit_oid",
        "commit_payload_hex",
        "contained_parser_receipt_id",
        "current_entries",
        "diff_sha256",
        "discord_enabled",
        "fresh_exact_approval_present",
        "message",
        "normalization_receipt_id",
        "normalized_state_sha256",
        "object_closure_sha256",
        "objects",
        "owner_fence_id",
        "parent_entries",
        "parent_manifest_sha256",
        "parent_oid",
        "path_manifest_receipt_id",
        "production_active",
        "proposal_id",
        "purpose_id",
        "record_sha256",
        "required_paths",
        "schema",
        "transaction_id",
        "tree_manifest_sha256",
        "tree_oid",
    }
    unsigned = dict(proposal)
    record_digest = unsigned.pop("record_sha256", None)
    proposal_body = dict(unsigned)
    proposal_id = proposal_body.pop("proposal_id", None)
    expected_proposal_id = "proposal_" + hashlib.sha256(
        _canonical_json(proposal_body)
    ).hexdigest()
    if (
        set(proposal) != expected
        or proposal.get("schema") != "galaxy.source-commit-proposal/v1"
        or proposal_id != expected_proposal_id
        or proposal_id != request.get("proposal_id")
        or record_digest != request.get("proposal_record_sha256")
        or record_digest != hashlib.sha256(_canonical_json(unsigned)).hexdigest()
        or proposal.get("canonical_ref_written") is not False
        or proposal.get("fresh_exact_approval_present") is not False
        or proposal.get("production_active") is not False
        or proposal.get("discord_enabled") is not False
        or re.fullmatch(r"source_[0-9a-f]{64}", str(proposal.get("transaction_id")))
        is None
        or re.fullmatch(r"purpose_[0-9a-f]{64}", str(proposal.get("purpose_id")))
        is None
        or re.fullmatch(
            r"ownerfence_[0-9a-f]{64}", str(proposal.get("owner_fence_id"))
        )
        is None
        or re.fullmatch(
            r"pathmanifest_[0-9a-f]{64}",
            str(proposal.get("path_manifest_receipt_id")),
        )
        is None
        or re.fullmatch(
            r"normalization_[0-9a-f]{64}",
            str(proposal.get("normalization_receipt_id")),
        )
        is None
        or re.fullmatch(
            r"parserreceipt_[0-9a-f]{64}",
            str(proposal.get("contained_parser_receipt_id")),
        )
        is None
        or any(
            _SHA256.fullmatch(str(proposal.get(field))) is None
            for field in (
                "normalized_state_sha256",
                "object_closure_sha256",
                "parent_manifest_sha256",
                "tree_manifest_sha256",
                "diff_sha256",
            )
        )
        or any(
            re.fullmatch(r"[0-9a-f]{40}", str(proposal.get(field))) is None
            for field in ("parent_oid", "tree_oid", "commit_oid")
        )
    ):
        raise ActivationReviewRefused("source proposal authority or identity differs")
    return proposal


def _source_path(value: object) -> str:
    if not isinstance(value, str) or not value or "\\" in value:
        raise ActivationReviewRefused("source proposal path is malformed")
    path = PureWindowsPath(value.replace("/", "\\"))
    parts = value.split("/")
    if (
        path.is_absolute()
        or any(part in {"", ".", ".."} for part in parts)
        or any(part.casefold() == ".git" for part in parts)
        or any(ord(character) < 32 or ord(character) == 127 for character in value)
        or value != value.encode("utf-8", errors="strict").decode("utf-8")
    ):
        raise ActivationReviewRefused("source proposal path is unsafe")
    return value


def _source_entries(value: object, *, label: str) -> list[dict[str, Any]]:
    if not isinstance(value, list) or len(value) > 200_000:
        raise ActivationReviewRefused(f"{label} entries exceed their bound")
    result: list[dict[str, Any]] = []
    seen: set[str] = set()
    for raw in value:
        if not isinstance(raw, dict) or set(raw) != {
            "blob_oid",
            "blob_sha256",
            "mode",
            "path",
            "size",
        }:
            raise ActivationReviewRefused(f"{label} entry fields differ")
        relative = _source_path(raw.get("path"))
        folded = relative.casefold()
        if (
            folded in seen
            or re.fullmatch(r"[0-9a-f]{40}", str(raw.get("blob_oid"))) is None
            or _SHA256.fullmatch(str(raw.get("blob_sha256"))) is None
            or type(raw.get("mode")) is not int
            or raw["mode"] not in {0o100644, 0o100755}
            or type(raw.get("size")) is not int
            or not 0 <= raw["size"] <= 128 * 1024 * 1024
        ):
            raise ActivationReviewRefused(f"{label} entry is malformed")
        seen.add(folded)
        result.append(dict(raw))
    if result != sorted(result, key=lambda entry: str(entry["path"])):
        raise ActivationReviewRefused(f"{label} entries are not ordered")
    return result


def _source_path_set(value: object, *, label: str) -> list[str]:
    if not isinstance(value, list):
        raise ActivationReviewRefused(f"{label} path set is malformed")
    paths = [_source_path(item) for item in value]
    if paths != sorted(paths) or len({item.casefold() for item in paths}) != len(paths):
        raise ActivationReviewRefused(f"{label} path set is not canonical")
    return paths


def _read_proposal_objects(
    value: object,
    *,
    object_root: Path,
    hash_object: Callable[[str, bytes], str],
) -> tuple[list[dict[str, Any]], dict[str, tuple[str, bytes]]]:
    if not isinstance(value, list) or not value or len(value) > 400_002:
        raise ActivationReviewRefused("source proposal object list exceeds its bound")
    try:
        root = object_root.resolve(strict=True)
        root_meta = root.lstat()
    except OSError as exc:
        raise ActivationReviewRefused("source proposal object root is unavailable") from exc
    if not stat.S_ISDIR(root_meta.st_mode) or stat.S_ISLNK(root_meta.st_mode):
        raise ActivationReviewRefused("source proposal object root is unsafe")
    public: list[dict[str, Any]] = []
    objects: dict[str, tuple[str, bytes]] = {}
    previous = ""
    for raw in value:
        if not isinstance(raw, dict) or set(raw) != {
            "frame_sha256",
            "object_type",
            "oid",
            "payload_size",
        }:
            raise ActivationReviewRefused("source proposal object fields differ")
        oid = raw.get("oid")
        object_type = raw.get("object_type")
        size = raw.get("payload_size")
        if (
            not isinstance(oid, str)
            or re.fullmatch(r"[0-9a-f]{40}", oid) is None
            or oid <= previous
            or object_type not in {"blob", "tree", "commit"}
            or type(size) is not int
            or not 0 <= size <= 128 * 1024 * 1024
            or _SHA256.fullmatch(str(raw.get("frame_sha256"))) is None
        ):
            raise ActivationReviewRefused("source proposal object is malformed")
        previous = oid
        path = root / oid[:2] / f"{oid[2:]}.frame"
        try:
            path.relative_to(root)
            metadata = path.lstat()
            if (
                not stat.S_ISREG(metadata.st_mode)
                or stat.S_ISLNK(metadata.st_mode)
                or metadata.st_nlink != 1
                or not 1 <= metadata.st_size <= _MAX_OBJECT_FRAME_BYTES
            ):
                raise OSError("unsafe object frame")
            frame = path.read_bytes()
            after = path.lstat()
        except (OSError, ValueError) as exc:
            raise ActivationReviewRefused(
                "source proposal object frame is unavailable"
            ) from exc
        if (
            (metadata.st_dev, metadata.st_ino, metadata.st_size)
            != (after.st_dev, after.st_ino, after.st_size)
            or len(frame) != metadata.st_size
        ):
            raise ActivationReviewRefused("source proposal object frame raced")
        prefix = f"{object_type} {size}".encode("ascii") + b"\0"
        payload = frame[len(prefix) :]
        try:
            first_oid = hash_object(str(object_type), payload)
            second_oid = hash_object(str(object_type), payload)
        except Exception as exc:
            raise ActivationReviewRefused(
                "source proposal collision-detecting hash oracle refused"
            ) from exc
        if (
            not frame.startswith(prefix)
            or len(payload) != size
            or hashlib.sha256(frame).hexdigest() != raw["frame_sha256"]
            or first_oid != oid
            or second_oid != oid
        ):
            raise ActivationReviewRefused("source proposal object frame differs")
        public.append(dict(raw))
        objects[oid] = (str(object_type), payload)
    return public, objects


def _flatten_source_tree(
    tree_oid: str, objects: Mapping[str, tuple[str, bytes]]
) -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []
    visiting: set[str] = set()

    def walk(oid: str, prefix: tuple[str, ...]) -> None:
        record = objects.get(oid)
        if record is None or record[0] != "tree" or oid in visiting or len(prefix) > 64:
            raise ActivationReviewRefused("source proposal tree closure is malformed")
        visiting.add(oid)
        payload = record[1]
        offset = 0
        previous_name = b""
        local_names: set[str] = set()
        while offset < len(payload):
            space = payload.find(b" ", offset)
            nul = payload.find(b"\0", space + 1)
            if space <= offset or nul <= space or nul + 21 > len(payload):
                raise ActivationReviewRefused("source proposal tree entry is truncated")
            mode_raw = payload[offset:space]
            name_raw = payload[space + 1 : nul]
            child_oid = payload[nul + 1 : nul + 21].hex()
            offset = nul + 21
            if name_raw <= previous_name:
                raise ActivationReviewRefused("source proposal tree is not byte ordered")
            previous_name = name_raw
            try:
                name = name_raw.decode("utf-8", errors="strict")
            except UnicodeDecodeError as exc:
                raise ActivationReviewRefused(
                    "source proposal tree name is not UTF-8"
                ) from exc
            relative = _source_path("/".join((*prefix, name)))
            if name.casefold() in local_names:
                raise ActivationReviewRefused("source proposal tree aliases a name")
            local_names.add(name.casefold())
            if mode_raw == b"40000":
                walk(child_oid, (*prefix, name))
                continue
            if mode_raw not in {b"100644", b"100755"}:
                raise ActivationReviewRefused("source proposal tree mode is unsupported")
            blob = objects.get(child_oid)
            if blob is None or blob[0] != "blob":
                raise ActivationReviewRefused("source proposal tree blob is unavailable")
            entries.append(
                {
                    "blob_oid": child_oid,
                    "blob_sha256": hashlib.sha256(blob[1]).hexdigest(),
                    "mode": int(mode_raw, 8),
                    "path": relative,
                    "size": len(blob[1]),
                }
            )
        visiting.remove(oid)

    walk(tree_oid, ())
    return sorted(entries, key=lambda entry: str(entry["path"]))


def _source_changes(
    parent: Sequence[Mapping[str, Any]], current: Sequence[Mapping[str, Any]]
) -> list[dict[str, Any]]:
    before_by_path = {str(entry["path"]): entry for entry in parent}
    after_by_path = {str(entry["path"]): entry for entry in current}
    changes: list[dict[str, Any]] = []
    for relative in sorted(set(before_by_path) | set(after_by_path)):
        before = before_by_path.get(relative)
        after = after_by_path.get(relative)
        if before is None:
            kind = "added"
        elif after is None:
            kind = "deleted"
        elif (
            before["blob_sha256"] != after["blob_sha256"]
            or before["size"] != after["size"]
            or before["mode"] != after["mode"]
        ):
            kind = "modified"
        else:
            continue
        changes.append(
            {
                "after_mode": None if after is None else after["mode"],
                "after_sha256": None if after is None else after["blob_sha256"],
                "before_mode": None if before is None else before["mode"],
                "before_sha256": None if before is None else before["blob_sha256"],
                "change": kind,
                "path": relative,
            }
        )
    return changes


def review_source_proposal(
    *,
    proposal_path: Path,
    object_root: Path,
    request_path: Path,
    hash_object: Callable[[str, bytes], str],
) -> dict[str, object]:
    """Independently rebuild a proposal from inert bytes with no write authority."""

    request = _source_review_request(request_path)
    proposal = _source_proposal(proposal_path, request)
    public_objects, objects = _read_proposal_objects(
        proposal.get("objects"), object_root=object_root, hash_object=hash_object
    )
    if hashlib.sha256(_canonical_json(public_objects)).hexdigest() != proposal.get(
        "object_closure_sha256"
    ):
        raise ActivationReviewRefused("source proposal object closure digest differs")
    parent = _source_entries(proposal.get("parent_entries"), label="parent")
    current = _source_entries(proposal.get("current_entries"), label="current")
    allowed = _source_path_set(proposal.get("allowed_paths"), label="allowed")
    required = _source_path_set(proposal.get("required_paths"), label="required")
    if not set(required).issubset(allowed):
        raise ActivationReviewRefused("source proposal required paths exceed allowlist")
    flattened = _flatten_source_tree(str(proposal["tree_oid"]), objects)
    if flattened != current:
        raise ActivationReviewRefused("source proposal tree differs from current entries")
    parent_manifest = {
        "contained_parser_receipt_id": proposal["contained_parser_receipt_id"],
        "entries": parent,
        "parent_oid": proposal["parent_oid"],
        "schema": "galaxy.admin-parent-manifest/v1",
    }
    changes = _source_changes(parent, current)
    changed_paths = {str(item["path"]) for item in changes}
    if (
        proposal.get("changes") != changes
        or changed_paths - set(allowed)
        or not set(required).issubset(changed_paths)
        or hashlib.sha256(_canonical_json(parent_manifest)).hexdigest()
        != proposal.get("parent_manifest_sha256")
        or hashlib.sha256(_canonical_json(current)).hexdigest()
        != proposal.get("tree_manifest_sha256")
        or hashlib.sha256(_canonical_json(changes)).hexdigest()
        != proposal.get("diff_sha256")
    ):
        raise ActivationReviewRefused("source proposal manifest or diff differs")
    message = proposal.get("message")
    if (
        not isinstance(message, str)
        or not message
        or message != message.strip()
        or "\0" in message
        or "\r" in message
        or len(message.encode("utf-8", errors="strict")) > 16 * 1024
    ):
        raise ActivationReviewRefused("source proposal message is not canonical")
    expected_commit = (
        f"tree {proposal['tree_oid']}\n"
        f"parent {proposal['parent_oid']}\n"
        "author GALAXY Singularity <singularity@localhost> 0 +0000\n"
        "committer GALAXY Singularity <singularity@localhost> 0 +0000\n"
        f"\n{message}\n"
    ).encode("utf-8", errors="strict")
    try:
        recorded_commit = bytes.fromhex(str(proposal.get("commit_payload_hex")))
    except ValueError as exc:
        raise ActivationReviewRefused("source proposal commit payload is malformed") from exc
    commit_object = objects.get(str(proposal["commit_oid"]))
    if (
        commit_object is None
        or commit_object != ("commit", expected_commit)
        or recorded_commit != expected_commit
    ):
        raise ActivationReviewRefused("source proposal fixed commit differs")
    return {
        "canonical_write_observed": False,
        "decision": "accept",
        "findings": [],
        "independent": True,
        "network_enabled": False,
        "pass_index": request["pass_index"],
        "proposal_id": request["proposal_id"],
        "proposal_record_sha256": request["proposal_record_sha256"],
        "reviewer_image_digest": request["reviewer_image_digest"],
        "reviewer_qualification_receipt_id": request[
            "reviewer_qualification_receipt_id"
        ],
        "reviewer_runtime_sha256": request["reviewer_runtime_sha256"],
        "reviewer_session_id": request["reviewer_session_id"],
        "schema": "galaxy.independent-source-review/v1",
        "source_execution_observed": False,
    }


class _ReviewSha1dcOracle:
    """Repo-less standalone SHA1DC adapter for the contained review process."""

    _VERSION = (
        b"GALAXY_SHA1DC_OBJECT_ORACLE/v1 "
        b"upstream=855827c583bc30645ba427885caa40c5b81764d2\n"
    )
    _SELF_TEST = (
        b"GALAXY_SHA1DC_SELF_TEST/v1 collision-detected normal-sha1-exact\n"
    )

    def __init__(self, executable: Path, *, sterile_root: Path) -> None:
        if not executable.is_absolute() or not sterile_root.is_absolute():
            raise ActivationReviewRefused("review SHA1DC paths must be absolute")
        try:
            metadata = executable.lstat()
            raw = executable.read_bytes()
            after = executable.lstat()
        except OSError as exc:
            raise ActivationReviewRefused("review SHA1DC executable is unavailable") from exc
        self._identity = (
            metadata.st_dev,
            metadata.st_ino,
            metadata.st_size,
            metadata.st_mtime_ns,
        )
        if (
            not stat.S_ISREG(metadata.st_mode)
            or stat.S_ISLNK(metadata.st_mode)
            or metadata.st_nlink != 1
            or not 1 <= len(raw) <= 128 * 1024 * 1024
            or self._identity
            != (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns)
        ):
            raise ActivationReviewRefused("review SHA1DC executable is unsafe")
        self._executable = executable
        self._sterile_root = sterile_root
        self._digest = hashlib.sha256(raw).hexdigest()
        self._attest()

    def _run(
        self, arguments: Sequence[str], *, payload: bytes | None
    ) -> subprocess.CompletedProcess[bytes]:
        return subprocess.run(
            [str(self._executable), *arguments],
            cwd=self._sterile_root,
            env={},
            input=payload,
            stdin=subprocess.DEVNULL if payload is None else None,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=30,
            check=False,
            shell=False,
        )

    def _revalidate(self) -> None:
        try:
            metadata = self._executable.lstat()
            raw = self._executable.read_bytes()
            after = self._executable.lstat()
        except OSError as exc:
            raise ActivationReviewRefused("review SHA1DC cannot be revalidated") from exc
        identity = (
            metadata.st_dev,
            metadata.st_ino,
            metadata.st_size,
            metadata.st_mtime_ns,
        )
        if (
            identity != self._identity
            or identity
            != (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns)
            or hashlib.sha256(raw).hexdigest() != self._digest
        ):
            raise ActivationReviewRefused("review SHA1DC identity changed")

    def _attest(self) -> None:
        self._revalidate()
        for arguments, expected in (
            (("--version",), self._VERSION),
            (("--self-test",), self._SELF_TEST),
        ):
            result = self._run(arguments, payload=None)
            if result.returncode != 0 or result.stderr or result.stdout != expected:
                raise ActivationReviewRefused("review SHA1DC attestation failed")

    def hash_object(self, object_type: str, payload: bytes) -> str:
        if object_type not in {"blob", "tree", "commit"}:
            raise ActivationReviewRefused("review SHA1DC object type is unsupported")
        self._attest()
        result = self._run(
            ("hash-object", object_type, str(len(payload))), payload=payload
        )
        try:
            oid = result.stdout.decode("ascii", errors="strict").strip()
        except UnicodeDecodeError as exc:
            raise ActivationReviewRefused("review SHA1DC output is not ASCII") from exc
        if (
            result.returncode != 0
            or result.stderr
            or re.fullmatch(r"[0-9a-f]{40}", oid) is None
            or result.stdout != (oid + "\n").encode("ascii")
        ):
            raise ActivationReviewRefused("review SHA1DC object hash refused")
        return oid


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="galaxy-activation-reviewer")
    parser.add_argument("--source", type=Path)
    parser.add_argument("--launch-record", type=Path)
    parser.add_argument("--source-proposal", type=Path)
    parser.add_argument("--object-root", type=Path)
    parser.add_argument("--sha1dc-executable", type=Path)
    parser.add_argument("--request", type=Path, required=True)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        source_mode = args.source is not None or args.launch_record is not None
        proposal_mode = any(
            value is not None
            for value in (
                args.source_proposal,
                args.object_root,
                args.sha1dc_executable,
            )
        )
        if source_mode == proposal_mode:
            raise ActivationReviewRefused(
                "exactly one anchor or source-proposal review mode is required"
            )
        if source_mode:
            if args.source is None or args.launch_record is None:
                raise ActivationReviewRefused("anchor review inputs are incomplete")
            report = review_anchor(
                source_path=args.source,
                launch_record_path=args.launch_record,
                request_path=args.request,
            )
        else:
            if (
                args.source_proposal is None
                or args.object_root is None
                or args.sha1dc_executable is None
            ):
                raise ActivationReviewRefused(
                    "source-proposal review inputs are incomplete"
                )
            oracle = _ReviewSha1dcOracle(
                args.sha1dc_executable,
                sterile_root=args.request.resolve(strict=True).parent,
            )
            report = review_source_proposal(
                proposal_path=args.source_proposal,
                object_root=args.object_root,
                request_path=args.request,
                hash_object=oracle.hash_object,
            )
    except ActivationReviewRefused as exc:
        sys.stderr.write(f"activation-review-refused: {exc}\n")
        return 78
    sys.stdout.buffer.write(_canonical_json(report) + b"\n")
    return 0 if report["decision"] in {"advisory_pass", "accept"} else 1


if __name__ == "__main__":
    raise SystemExit(main())
