from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import time
from typing import Any, Mapping, Sequence


class ProbeRefused(RuntimeError):
    """A sealed probe request or broker response was not exact."""


def _canonical_json(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")


def _duplicate_free(pairs: list[tuple[str, object]]) -> dict[str, object]:
    value: dict[str, object] = {}
    for key, item in pairs:
        if key in value:
            raise ProbeRefused("duplicate JSON key")
        value[key] = item
    return value


def _reject_number(value: str) -> object:
    raise ProbeRefused(f"non-integral JSON value: {value}")


def _bounded_integer(value: str) -> int:
    parsed = int(value)
    if not -(2**63) <= parsed < 2**63:
        raise ProbeRefused("JSON integer exceeds signed 64-bit range")
    return parsed


def _load_canonical(path: Path) -> dict[str, Any]:
    try:
        raw = path.read_bytes()
        value = json.loads(
            raw.decode("utf-8", errors="strict"),
            object_pairs_hook=_duplicate_free,
            parse_float=_reject_number,
            parse_int=_bounded_integer,
            parse_constant=_reject_number,
        )
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ProbeRefused("probe specification is unavailable or invalid") from exc
    if not isinstance(value, dict) or raw != _canonical_json(value):
        raise ProbeRefused("probe specification is not canonical JSON")
    return value


def _sha(value: object) -> str:
    return hashlib.sha256(_canonical_json(value)).hexdigest()


def _wait_for(path: Path, deadline: float) -> bytes:
    while time.monotonic() < deadline:
        try:
            return path.read_bytes()
        except FileNotFoundError:
            time.sleep(0.005)
    raise ProbeRefused(f"timed out waiting for {path.name}")


def _broker_exchange(
    request: Mapping[str, object],
    *,
    request_root: Path,
    response_root: Path,
    request_name: str,
    deadline: float,
) -> dict[str, Any]:
    raw = _canonical_json(dict(request))
    temporary = request_root / f".{request_name}.{os.getpid()}.tmp"
    destination = request_root / f"{request_name}.request.json"
    if destination.exists() or temporary.exists():
        raise ProbeRefused("broker request name collision")
    temporary.write_bytes(raw)
    os.replace(temporary, destination)
    response_path = response_root / f"{request_name}.response.json"
    response_raw = _wait_for(response_path, deadline)
    try:
        response = json.loads(
            response_raw.decode("utf-8", errors="strict"),
            object_pairs_hook=_duplicate_free,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ProbeRefused("broker response is invalid") from exc
    if not isinstance(response, dict) or response_raw != _canonical_json(response):
        raise ProbeRefused("broker response is not canonical")
    return response


def run_probe(specification: Path) -> dict[str, object]:
    spec = _load_canonical(specification)
    required = {
        "schema",
        "common",
        "calls",
        "observed_outcome",
        "request_root",
        "response_root",
        "release_root",
        "marker_root",
        "probe_id",
        "probe_digest",
    }
    if set(spec) != required or spec["schema"] != 1:
        raise ProbeRefused("probe specification fields are not closed")
    common = spec["common"]
    calls = spec["calls"]
    if not isinstance(common, dict) or not isinstance(calls, list) or not calls:
        raise ProbeRefused("probe common fields or calls are malformed")
    common_fields = {
        "schema",
        "run_nonce",
        "challenge_digest",
        "observation_id",
        "observation_kind",
        "invariant_id",
        "observation_digest",
        "case_digest",
        "operation_api",
        "operation_digest",
        "preconditions_digest",
        "fault_digest",
        "runtime_role",
        "runtime_profile_id",
        "runtime_profile_digest",
        "runtime_identity",
    }
    if set(common) != common_fields or common.get("schema") != 2:
        raise ProbeRefused("probe broker binding fields are not closed")
    probe_id = spec["probe_id"]
    probe_digest = spec["probe_digest"]
    if (
        not isinstance(probe_id, str)
        or not isinstance(probe_digest, str)
        or re.fullmatch(r"[0-9a-f]{64}", probe_digest) is None
    ):
        raise ProbeRefused("probe identity is malformed")
    roots = []
    for field in ("request_root", "response_root", "release_root", "marker_root"):
        raw_root = spec[field]
        if not isinstance(raw_root, str) or not raw_root:
            raise ProbeRefused(f"{field} is malformed")
        root = Path(raw_root)
        try:
            resolved = root.resolve(strict=True)
        except OSError as exc:
            raise ProbeRefused(f"{field} is unavailable") from exc
        if not root.is_absolute() or not resolved.is_dir() or root.is_symlink():
            raise ProbeRefused(f"{field} is not an ordinary absolute directory")
        roots.append(resolved)
    request_root, response_root, release_root, marker_root = roots
    if (marker_root / "result.json").exists() or (marker_root / "completed.marker").exists():
        raise ProbeRefused("probe marker output already exists")
    deadline = time.monotonic() + 300
    token_raw = _wait_for(release_root / "release.token", deadline)
    try:
        release_token = token_raw.decode("ascii", errors="strict")
    except UnicodeDecodeError as exc:
        raise ProbeRefused("release token is not ASCII") from exc
    if re.fullmatch(r"[0-9a-f]{64}", release_token) is None:
        raise ProbeRefused("release token is malformed")

    bound_common = dict(common)
    bound_common["release_token"] = release_token
    attempts = []
    run_nonce = str(common.get("run_nonce"))
    for sequence, call in enumerate(calls):
        if not isinstance(call, dict) or set(call) != {"operation", "args", "call_digest"}:
            raise ProbeRefused("probe broker call is malformed")
        idempotency_key = _sha(
            {
                "call_digest": call["call_digest"],
                "observation_id": common["observation_id"],
                "run_nonce": run_nonce,
                "sequence": sequence,
            }
        )
        request = {
            **bound_common,
            "message_type": "call",
            "sequence": sequence,
            "idempotency_key": idempotency_key,
            "operation": call["operation"],
            "args": call["args"],
            "call_digest": call["call_digest"],
        }
        request_name = hashlib.sha256(f"{run_nonce}:{probe_id}:{sequence}".encode("utf-8")).hexdigest()
        response = _broker_exchange(
            request,
            request_root=request_root,
            response_root=response_root,
            request_name=request_name,
            deadline=deadline,
        )
        if response.get("status") != "committed" or response.get("result_digest") != _sha(
            response.get("result")
        ):
            raise ProbeRefused("broker did not commit the exact probe result")
        attempts.append(
            {
                "operation": call["operation"],
                "call_digest": call["call_digest"],
                "args_digest": _sha(call["args"]),
                "result_digest": response["result_digest"],
                "broker_event_id": response["event_id"],
                "broker_event_hmac": response["event_hmac"],
                "disposition": "reference_result_committed",
                "run_nonce": run_nonce,
                "challenge_digest": common["challenge_digest"],
            }
        )
    outcome = spec["observed_outcome"]
    completion = {
        **bound_common,
        "message_type": "complete",
        "completed_call_count": len(calls),
        "observed_outcome": outcome,
        "result_digest": _sha(outcome),
    }
    completion_name = hashlib.sha256(f"{run_nonce}:{probe_id}:complete".encode("utf-8")).hexdigest()
    completion_response = _broker_exchange(
        completion,
        request_root=request_root,
        response_root=response_root,
        request_name=completion_name,
        deadline=deadline,
    )
    if completion_response.get("status") != "accepted":
        raise ProbeRefused("broker refused probe completion")
    result = {
        "broker_evidence": attempts,
        "completion_event_id": completion_response["event_id"],
        "completion_event_hmac": completion_response["event_hmac"],
        "observed_outcome": outcome,
    }
    result_path = marker_root / "result.json"
    result_path.write_bytes(_canonical_json(result))
    marker = hashlib.sha256(f"{release_token}:{probe_id}:{probe_digest}".encode("ascii")).hexdigest()
    (marker_root / "completed.marker").write_text(marker, encoding="ascii")
    return result


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="galaxy-activation-probe")
    parser.add_argument("--probe-worker", action="store_true")
    parser.add_argument("probe_id")
    parser.add_argument("probe_digest")
    parser.add_argument("--spec", default="/galaxy/release/probe.json")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if not args.probe_worker:
            raise ProbeRefused("only sealed probe-worker mode is available")
        specification = Path(args.spec)
        parsed = _load_canonical(specification)
        if args.probe_id != parsed.get("probe_id"):
            raise ProbeRefused("probe argument binding mismatch")
        if args.probe_digest != parsed.get("probe_digest"):
            raise ProbeRefused("probe digest argument mismatch")
        result = run_probe(specification)
        sys.stdout.buffer.write(_canonical_json(result) + b"\n")
        return 0
    except ProbeRefused as exc:
        sys.stderr.write(f"ProbeRefused: {exc}\n")
        return 78


if __name__ == "__main__":
    raise SystemExit(main())
