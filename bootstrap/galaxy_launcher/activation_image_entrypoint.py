"""Generic fail-closed entrypoint sealed into every GALAXY activation image.

The image itself grants no authority.  It can emit an inactive boot canary or
execute one fully enumerated read-only runtime whose canonical manifest digest
is supplied by the external controller.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ActivationImageRefused  -- The sealed image refused an ambiguous or unbound request.
  BoundRuntime
  verify_bound_runtime(*, manifest_path: Path, runtime_root: Path, expected_manifest_sha256: str, sealed_role: str) -> BoundRuntime  -- Verify a canonical, role-bound, fully enumerated runtime projection.
  build_image_canary(*, sealed_role: str, requested_role: str, cwd: Path, environment: Mapping[str, str], uid: int, gid: int) -> dict[str, object]  -- Return an authority-free receipt proving the sealed boot boundary.
  main(argv: Sequence[str] | None=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_activation_image_entrypoint.py
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys
from typing import Mapping, Sequence


ACTIVATION_IMAGE_ROLES = frozenset(
    {
        "credentialed_driver",
        "command_sandbox",
        "source_fetcher",
        "source_parser",
        "candidate_parser",
        "object_parser",
        "verifier",
        "reviewer",
        "state_store",
    }
)
_SHA256 = re.compile(r"^[0-9a-f]{64}$")
_MAX_MANIFEST_BYTES = 1024 * 1024
_MAX_RUNTIME_LEAVES = 4096
_MAX_ARG_COUNT = 256
_MAX_ARG_BYTES = 32 * 1024
_EXPECTED_UID = 65532
_EXPECTED_GID = 65532


class ActivationImageRefused(RuntimeError):
    """The sealed image refused an ambiguous or unbound request."""


@dataclass(frozen=True)
class BoundRuntime:
    entrypoint: Path
    argv: tuple[str, ...]
    manifest_sha256: str
    verified_leaves: tuple[Path, ...]


def _canonical_json(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")


def _reject_duplicate_pairs(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise ActivationImageRefused("manifest contains a duplicate key")
        result[key] = value
    return result


def _load_canonical_manifest(path: Path, expected_sha256: str) -> dict[str, object]:
    if _SHA256.fullmatch(expected_sha256) is None:
        raise ActivationImageRefused("manifest sha256 is malformed")
    try:
        if path.is_symlink():
            raise ActivationImageRefused("manifest link is forbidden")
        raw = path.read_bytes()
    except OSError as exc:
        raise ActivationImageRefused("manifest is unavailable") from exc
    if not raw or len(raw) > _MAX_MANIFEST_BYTES or raw.startswith(b"\xef\xbb\xbf"):
        raise ActivationImageRefused("manifest size or encoding is refused")
    if hashlib.sha256(raw).hexdigest() != expected_sha256:
        raise ActivationImageRefused("manifest digest mismatch")
    try:
        value = json.loads(
            raw.decode("utf-8", errors="strict"),
            object_pairs_hook=_reject_duplicate_pairs,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ActivationImageRefused("manifest is not strict UTF-8 JSON") from exc
    if not isinstance(value, dict) or _canonical_json(value) != raw:
        raise ActivationImageRefused("manifest is not canonical JSON")
    return value


def _safe_relative_path(value: object, label: str) -> tuple[str, ...]:
    if not isinstance(value, str) or not value or "\\" in value or "\x00" in value:
        raise ActivationImageRefused(f"{label} path is malformed")
    if value.startswith("/") or re.match(r"^[A-Za-z]:", value):
        raise ActivationImageRefused(f"{label} path must be relative")
    parts = tuple(value.split("/"))
    if any(part in ("", ".", "..") for part in parts):
        raise ActivationImageRefused(f"{label} path is not canonical")
    return parts


def _assert_no_links(root: Path, parts: Sequence[str], label: str) -> Path:
    current = root
    for part in parts:
        current /= part
        try:
            metadata = current.lstat()
        except OSError as exc:
            raise ActivationImageRefused(f"{label} leaf is unavailable") from exc
        if stat.S_ISLNK(metadata.st_mode):
            raise ActivationImageRefused(f"{label} link is forbidden")
    return current


def _file_digest(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def verify_bound_runtime(
    *,
    manifest_path: Path,
    runtime_root: Path,
    expected_manifest_sha256: str,
    sealed_role: str,
) -> BoundRuntime:
    """Verify a canonical, role-bound, fully enumerated runtime projection."""
    if sealed_role not in ACTIVATION_IMAGE_ROLES:
        raise ActivationImageRefused("sealed role is unknown")
    try:
        if runtime_root.is_symlink():
            raise ActivationImageRefused("runtime root link is forbidden")
        root = runtime_root.resolve(strict=True)
    except OSError as exc:
        raise ActivationImageRefused("runtime root is unavailable") from exc
    if not root.is_dir():
        raise ActivationImageRefused("runtime root must be a directory")

    manifest = _load_canonical_manifest(manifest_path, expected_manifest_sha256)
    if set(manifest) != {"schema", "role", "entrypoint", "argv", "leaves"}:
        raise ActivationImageRefused("manifest fields are not closed")
    if manifest["schema"] != "galaxy.activation-runtime/v1":
        raise ActivationImageRefused("manifest schema is unsupported")
    if manifest["role"] != sealed_role:
        raise ActivationImageRefused("manifest role differs from sealed role")

    leaves = manifest["leaves"]
    if not isinstance(leaves, list) or not leaves or len(leaves) > _MAX_RUNTIME_LEAVES:
        raise ActivationImageRefused("manifest leaf closure is empty or too large")
    verified: list[Path] = []
    declared_paths: set[str] = set()
    for leaf in leaves:
        if not isinstance(leaf, dict) or set(leaf) != {"path", "sha256", "size"}:
            raise ActivationImageRefused("manifest leaf fields are malformed")
        relative = leaf["path"]
        parts = _safe_relative_path(relative, "runtime")
        assert isinstance(relative, str)
        collision_key = relative.casefold()
        if collision_key in declared_paths:
            raise ActivationImageRefused("runtime leaf path is duplicated")
        declared_paths.add(collision_key)
        expected_digest = leaf["sha256"]
        expected_size = leaf["size"]
        if not isinstance(expected_digest, str) or _SHA256.fullmatch(expected_digest) is None:
            raise ActivationImageRefused("runtime leaf digest is malformed")
        if not isinstance(expected_size, int) or isinstance(expected_size, bool) or expected_size < 0:
            raise ActivationImageRefused("runtime leaf size is malformed")
        path = _assert_no_links(root, parts, "runtime")
        metadata = path.stat()
        if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
            raise ActivationImageRefused("runtime leaf must be a single-link regular file")
        if metadata.st_size != expected_size or _file_digest(path) != expected_digest:
            raise ActivationImageRefused("runtime leaf digest or size mismatch")
        verified.append(path.resolve(strict=True))

    actual_files: set[str] = set()
    for path in root.rglob("*"):
        relative = path.relative_to(root).as_posix()
        metadata = path.lstat()
        if stat.S_ISLNK(metadata.st_mode):
            raise ActivationImageRefused("runtime link is forbidden")
        if stat.S_ISREG(metadata.st_mode):
            actual_files.add(relative.casefold())
        elif not stat.S_ISDIR(metadata.st_mode):
            raise ActivationImageRefused("runtime special file is forbidden")
    if actual_files != declared_paths:
        raise ActivationImageRefused("runtime contains an unlisted or missing leaf")

    entrypoint_value = manifest["entrypoint"]
    entrypoint_parts = _safe_relative_path(entrypoint_value, "entrypoint")
    assert isinstance(entrypoint_value, str)
    if entrypoint_value.casefold() not in declared_paths:
        raise ActivationImageRefused("entrypoint is not a declared runtime leaf")
    entrypoint = _assert_no_links(root, entrypoint_parts, "entrypoint").resolve(strict=True)

    argv_value = manifest["argv"]
    if not isinstance(argv_value, list) or len(argv_value) > _MAX_ARG_COUNT:
        raise ActivationImageRefused("runtime argv is malformed")
    if any(not isinstance(value, str) or "\x00" in value for value in argv_value):
        raise ActivationImageRefused("runtime argv contains an invalid value")
    if sum(len(value.encode("utf-8")) for value in argv_value) > _MAX_ARG_BYTES:
        raise ActivationImageRefused("runtime argv exceeds the closed limit")
    return BoundRuntime(
        entrypoint=entrypoint,
        argv=tuple(argv_value),
        manifest_sha256=expected_manifest_sha256,
        verified_leaves=tuple(verified),
    )


def _validate_boot_boundary(*, cwd: Path, environment: Mapping[str, str], uid: int, gid: int) -> None:
    if uid != _EXPECTED_UID or gid != _EXPECTED_GID:
        raise ActivationImageRefused("exact nonroot uid/gid is required")
    try:
        if not cwd.is_dir() or any(cwd.iterdir()):
            raise ActivationImageRefused("working directory must be empty")
    except OSError as exc:
        raise ActivationImageRefused("working directory is unavailable") from exc
    # CPython on Debian may synthesize LC_CTYPE while coercing the C locale.
    # It is interpreter-generated, not inherited, and is the sole exception.
    accepted: tuple[dict[str, str], ...] = ({"LC_CTYPE": "C.UTF-8"}, {})
    if dict(environment) not in accepted:
        raise ActivationImageRefused("ambient environment is forbidden")


def build_image_canary(
    *,
    sealed_role: str,
    requested_role: str,
    cwd: Path,
    environment: Mapping[str, str],
    uid: int,
    gid: int,
) -> dict[str, object]:
    """Return an authority-free receipt proving the sealed boot boundary."""
    if sealed_role not in ACTIVATION_IMAGE_ROLES or requested_role != sealed_role:
        raise ActivationImageRefused("requested role differs from sealed role")
    _validate_boot_boundary(cwd=cwd, environment=environment, uid=uid, gid=gid)
    return {
        "schema": "galaxy.activation-image-canary/v1",
        "status": "ready_inactive",
        "role": sealed_role,
        "uid": uid,
        "gid": gid,
        "cwd_empty": True,
        "ambient_environment": [],
        "manifest_binding_required": True,
    }


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="galaxy-activation-image")
    subcommands = parser.add_subparsers(dest="command", required=True)
    canary = subcommands.add_parser("image-canary")
    canary.add_argument("--sealed-role", required=True, choices=sorted(ACTIVATION_IMAGE_ROLES))
    canary.add_argument("--requested-role", required=True, choices=sorted(ACTIVATION_IMAGE_ROLES))
    run = subcommands.add_parser("run-bound")
    run.add_argument("--sealed-role", required=True, choices=sorted(ACTIVATION_IMAGE_ROLES))
    run.add_argument("--manifest-sha256", required=True)
    run.add_argument("runtime_argv", nargs=argparse.REMAINDER)
    return parser


def _unix_identity() -> tuple[int, int]:
    getuid = getattr(os, "getuid", None)
    getgid = getattr(os, "getgid", None)
    if not callable(getuid) or not callable(getgid):
        raise ActivationImageRefused("Unix identity APIs are unavailable")
    return int(getuid()), int(getgid())


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    cwd = Path.cwd()
    environment = dict(os.environ)
    try:
        uid, gid = _unix_identity()
        _validate_boot_boundary(cwd=cwd, environment=environment, uid=uid, gid=gid)
        if args.command == "image-canary":
            receipt = build_image_canary(
                sealed_role=args.sealed_role,
                requested_role=args.requested_role,
                cwd=cwd,
                environment=environment,
                uid=uid,
                gid=gid,
            )
            sys.stdout.buffer.write(_canonical_json(receipt) + b"\n")
            return 0
        bound = verify_bound_runtime(
            manifest_path=Path("/galaxy-control/activation.json"),
            runtime_root=Path("/galaxy-runtime"),
            expected_manifest_sha256=args.manifest_sha256,
            sealed_role=args.sealed_role,
        )
        runtime_argv = tuple(args.runtime_argv)
        if len(runtime_argv) > _MAX_ARG_COUNT or any(
            not isinstance(value, str) or "\x00" in value for value in runtime_argv
        ):
            raise ActivationImageRefused("runtime command arguments are malformed")
        if sum(len(value.encode("utf-8")) for value in runtime_argv) > _MAX_ARG_BYTES:
            raise ActivationImageRefused("runtime command arguments exceed the closed limit")
        os.execve(
            "/usr/local/bin/python3",
            [
                "/usr/local/bin/python3",
                "-I",
                "-S",
                str(bound.entrypoint),
                *bound.argv,
                *runtime_argv,
            ],
            {},
        )
    except ActivationImageRefused as exc:
        sys.stderr.write(f"activation-image-refused: {exc}\n")
        return 78
    return 70


if __name__ == "__main__":
    raise SystemExit(main())
