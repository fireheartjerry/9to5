"""Create canonical records for an already copied, inactive TOFU closure.

This helper has no ACL, service-registration, copy, activation, or network
authority.  The elevated OS-native bootstrap invokes it only after it has
independently verified and copied every proposal leaf and applied the protected
root ACL.  A canonical receipt is written last, so every crash prefix remains
uninstalled/inactive rather than looking successful.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  TofuFinalizationRefused  -- The installed bytes or exact operator response did not match the proposal.
  finalize_inactive_install(*, proposal_path: Path, response_path: Path, dacl_sddl: str) -> dict[str, Any]  -- Verify installed leaves and create the first inactive protected records.
  main(argv: Sequence[str] | None=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""

from __future__ import annotations

import argparse
import ctypes
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import stat
import sys
from typing import Any, Iterable, Mapping, Sequence


_HEX64 = re.compile(r"[0-9a-f]{64}")
_SID = re.compile(r"S-1(?:-[0-9]+)+")
_PROPOSAL_KEYS = {
    "schema",
    "status",
    "generation",
    "staging_root",
    "payload_root",
    "external_root",
    "runtime_lock_staging_path",
    "runtime_lock_installed_path",
    "tofu_receipt_path",
    "source_leaves",
    "artifact_leaves",
    "source_root",
    "artifact_root",
    "merkle_root",
    "nonce",
    "challenge",
    "runtime_digest",
    "image_digests",
    "activation_acceptance_sha256",
    "activation_runtime_profiles_sha256",
    "activation_adapter_sha256",
    "activation_receipt_public_key",
    "activation_receipt_public_key_digest",
    "operator_sid",
    "service_sid",
    "service_name",
    "checkout_path",
    "repository_identity",
    "service_host_path",
    "interpreter_path",
    "interpreter_staging_path",
    "proposal_verifier_staging_path",
    "powershell_wrapper_build",
}


class TofuFinalizationRefused(RuntimeError):
    """The installed bytes or exact operator response did not match the proposal."""


def _canonical(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode(
        "utf-8"
    )


def _duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise TofuFinalizationRefused(f"duplicate JSON member: {key}")
        result[key] = value
    return result


def _constant(value: str) -> Any:
    raise TofuFinalizationRefused(f"non-finite JSON number: {value}")


def _strict_json(raw: bytes, label: str) -> dict[str, Any]:
    try:
        text = raw.decode("utf-8", errors="strict")
        if text.startswith("\ufeff"):
            raise TofuFinalizationRefused(f"{label} has a BOM")
        value = json.loads(text, object_pairs_hook=_duplicates, parse_constant=_constant)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise TofuFinalizationRefused(f"{label} is not strict JSON") from exc
    if not isinstance(value, dict) or _canonical(value) != raw:
        raise TofuFinalizationRefused(f"{label} is not canonical JSON")
    return value


def _sha_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _is_reparse(path: Path) -> bool:
    if path.is_symlink():
        return True
    if os.name != "nt":
        return False
    attributes = ctypes.windll.kernel32.GetFileAttributesW(str(path))
    return attributes != 0xFFFFFFFF and bool(attributes & 0x400)


def _no_reparse(path: Path, label: str) -> None:
    absolute = Path(os.path.abspath(path))
    current = Path(absolute.parts[0])
    for component in absolute.parts[1:]:
        current /= component
        if current.exists() and _is_reparse(current):
            raise TofuFinalizationRefused(f"{label} traverses a reparse point")


def _ordinary_file(path: Path, label: str, *, require_single_link: bool = True) -> Path:
    _no_reparse(path, label)
    try:
        resolved = path.resolve(strict=True)
        metadata = resolved.stat()
    except OSError as exc:
        raise TofuFinalizationRefused(f"{label} is unavailable") from exc
    if (
        path.is_symlink()
        or not stat.S_ISREG(metadata.st_mode)
        or (require_single_link and metadata.st_nlink != 1)
    ):
        raise TofuFinalizationRefused(f"{label} is not an ordinary single-link file")
    return resolved


def _hex(value: object, label: str) -> str:
    if not isinstance(value, str) or _HEX64.fullmatch(value) is None:
        raise TofuFinalizationRefused(f"{label} is not a SHA-256 digest")
    return value


def _leaf_root(domain: str, leaves: Iterable[Mapping[str, Any]]) -> str:
    hashes: list[bytes] = []
    for leaf in leaves:
        record = {
            "logical_path": leaf["logical_path"],
            "sha256": leaf["sha256"],
            "size": leaf["size"],
        }
        hashes.append(hashlib.sha256(_canonical(record)).digest())
    return hashlib.sha256(domain.encode("ascii") + b"\0" + b"".join(sorted(hashes))).hexdigest()


def _validate_leaf_set(value: object, label: str) -> list[dict[str, Any]]:
    if not isinstance(value, list) or not value:
        raise TofuFinalizationRefused(f"{label} closure is empty")
    result: list[dict[str, Any]] = []
    logical_paths: set[str] = set()
    installed_paths: set[Path] = set()
    for index, item in enumerate(value):
        if not isinstance(item, dict) or set(item) != {
            "logical_path",
            "staging_path",
            "installed_path",
            "size",
            "sha256",
        }:
            raise TofuFinalizationRefused(f"{label}[{index}] schema drift")
        logical = item["logical_path"]
        size = item["size"]
        if (
            not isinstance(logical, str)
            or not logical
            or "\\" in logical
            or logical.startswith("/")
            or any(part in {"", ".", ".."} for part in logical.split("/"))
            or type(size) is not int
            or size < 0
        ):
            raise TofuFinalizationRefused(f"{label}[{index}] is malformed")
        digest = _hex(item["sha256"], f"{label}[{index}].sha256")
        installed_value = item["installed_path"]
        if not isinstance(installed_value, str) or not os.path.isabs(installed_value):
            raise TofuFinalizationRefused(f"{label}[{index}] installed path is not absolute")
        installed = _ordinary_file(
            Path(installed_value),
            f"{label}[{index}]",
            require_single_link=item["staging_path"] is not None,
        )
        if logical in logical_paths or installed in installed_paths:
            raise TofuFinalizationRefused(f"{label} contains a duplicate leaf")
        logical_paths.add(logical)
        installed_paths.add(installed)
        if installed.stat().st_size != size or _sha_file(installed) != digest:
            raise TofuFinalizationRefused(f"{label}[{index}] installed bytes drifted")
        result.append(dict(item))
    return result


def _exclusive_bytes(path: Path, raw: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("xb") as stream:
        stream.write(raw)
        stream.flush()
        os.fsync(stream.fileno())


def _exclusive_json(path: Path, value: object) -> None:
    _exclusive_bytes(path, _canonical(value))


def _receipt_leaves(leaves: Iterable[Mapping[str, Any]]) -> list[dict[str, Any]]:
    return [
        {
            "logical_path": leaf["logical_path"],
            "installed_path": leaf["installed_path"],
            "size": leaf["size"],
            "sha256": leaf["sha256"],
        }
        for leaf in leaves
    ]


def _find_leaf(leaves: Iterable[Mapping[str, Any]], logical_path: str) -> Path:
    matches = [Path(str(leaf["installed_path"])) for leaf in leaves if leaf["logical_path"] == logical_path]
    if len(matches) != 1:
        raise TofuFinalizationRefused(f"required closure leaf missing: {logical_path}")
    return _ordinary_file(matches[0], logical_path)


def finalize_inactive_install(
    *,
    proposal_path: Path,
    response_path: Path,
    dacl_sddl: str,
) -> dict[str, Any]:
    """Verify installed leaves and create the first inactive protected records."""
    proposal_raw = _ordinary_file(proposal_path, "proposal").read_bytes()
    # Compare the response before any output write.  This deliberately rejects
    # BOMs, CR/LF, whitespace, generic approval, and stale copied responses.
    try:
        preliminary = json.loads(proposal_raw.decode("utf-8", errors="strict"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise TofuFinalizationRefused("proposal is unreadable") from exc
    challenge = preliminary.get("challenge") if isinstance(preliminary, dict) else None
    if not isinstance(challenge, str):
        raise TofuFinalizationRefused("proposal challenge is unavailable")
    response = _ordinary_file(response_path, "approval response").read_bytes()
    try:
        expected_response = challenge.encode("ascii", errors="strict")
    except UnicodeEncodeError as exc:
        raise TofuFinalizationRefused("proposal challenge is not ASCII") from exc
    if response != expected_response:
        raise TofuFinalizationRefused("approval response is not the exact challenge")

    proposal = _strict_json(proposal_raw, "proposal")
    if set(proposal) != _PROPOSAL_KEYS:
        raise TofuFinalizationRefused("proposal schema fields drifted")
    generation = proposal["generation"]
    if (
        proposal["schema"] != "galaxy.trust-on-first-install-proposal/v1"
        or proposal["status"] != "ready_for_exact_approval"
        or type(generation) is not int
        or generation < 1
        or proposal["service_name"] != "9to5Singularity"
        or not isinstance(dacl_sddl, str)
        or not dacl_sddl.startswith("O:")
        or len(dacl_sddl) > 4096
        or any(ord(character) < 32 for character in dacl_sddl)
    ):
        raise TofuFinalizationRefused("proposal or protected ACL record is malformed")
    for name in ("operator_sid", "service_sid"):
        if not isinstance(proposal[name], str) or _SID.fullmatch(proposal[name]) is None:
            raise TofuFinalizationRefused(f"{name} is malformed")
    nonce = _hex(proposal["nonce"], "nonce")
    source_leaves = _validate_leaf_set(proposal["source_leaves"], "source_leaves")
    artifact_leaves = _validate_leaf_set(proposal["artifact_leaves"], "artifact_leaves")
    source_root = _leaf_root("source", source_leaves)
    artifact_root = _leaf_root("artifact", artifact_leaves)
    merkle_root = hashlib.sha256(
        b"galaxy-tofu-v1\0" + bytes.fromhex(source_root) + bytes.fromhex(artifact_root)
    ).hexdigest()
    expected_challenge = f"TRUST SINGULARITY BOOTSTRAP {merkle_root} NONCE {nonce}"
    if (
        source_root != _hex(proposal["source_root"], "source_root")
        or artifact_root != _hex(proposal["artifact_root"], "artifact_root")
        or merkle_root != _hex(proposal["merkle_root"], "merkle_root")
        or challenge != expected_challenge
    ):
        raise TofuFinalizationRefused("proposal Merkle/challenge binding drifted")

    root = Path(str(proposal["external_root"]))
    _no_reparse(root, "external root")
    try:
        resolved_root = root.resolve(strict=True)
    except OSError as exc:
        raise TofuFinalizationRefused("external root is unavailable") from exc
    if not resolved_root.is_dir() or root.is_symlink():
        raise TofuFinalizationRefused("external root is not an ordinary directory")
    lock_path = _ordinary_file(Path(str(proposal["runtime_lock_installed_path"])), "runtime lock")
    receipt_path = Path(str(proposal["tofu_receipt_path"]))
    for path, label in ((lock_path, "runtime lock"), (receipt_path, "TOFU receipt")):
        try:
            Path(path).absolute().relative_to(resolved_root)
        except ValueError as exc:
            raise TofuFinalizationRefused(f"{label} escaped the external root") from exc
    lock = _strict_json(lock_path.read_bytes(), "runtime lock")
    if (
        lock.get("schema") != "galaxy.activation.sealed-runtime/v1"
        or lock.get("status") != "installed_inactive"
        or lock.get("generation") != generation
        or lock.get("external_root") != str(root)
        or lock.get("runtime_digest") != proposal["runtime_digest"]
        or lock.get("image_digests") != proposal["image_digests"]
        or lock.get("tofu_receipt_path") != str(receipt_path)
    ):
        raise TofuFinalizationRefused("runtime lock/proposal binding mismatch")
    runtime_lock_leaf = _find_leaf(artifact_leaves, "runtime/runtime.lock.json")
    if runtime_lock_leaf != lock_path:
        raise TofuFinalizationRefused("runtime lock is not the declared closure leaf")
    files = lock.get("files")
    digests = lock.get("file_digests")
    if not isinstance(files, dict) or not isinstance(digests, dict):
        raise TofuFinalizationRefused("runtime file closure is malformed")
    public_key_path = _ordinary_file(Path(str(files.get("receipt_public_key"))), "receipt public key")
    adapter_path = _ordinary_file(Path(str(files.get("adapter"))), "activation adapter")
    public_key = public_key_path.read_bytes()
    if (
        len(public_key) != 32
        or _sha_file(public_key_path) != digests.get("receipt_public_key")
        or _sha_file(adapter_path) != digests.get("adapter")
        or public_key.hex() != proposal["activation_receipt_public_key"]
        or hashlib.sha256(public_key).hexdigest()
        != proposal["activation_receipt_public_key_digest"]
        or _sha_file(adapter_path) != proposal["activation_adapter_sha256"]
    ):
        raise TofuFinalizationRefused("receipt-key or adapter binding mismatch")

    checkout = Path(str(proposal["checkout_path"])).resolve(strict=True)
    repository_identity = hashlib.sha256(
        os.path.normcase(str(checkout)).encode("utf-8")
    ).hexdigest()
    if repository_identity != proposal["repository_identity"]:
        raise TofuFinalizationRefused("repository identity binding mismatch")
    record_dir = resolved_root / "repositories" / repository_identity
    if record_dir.exists():
        raise TofuFinalizationRefused("repository anchor already exists")
    record_dir.mkdir(parents=True, exist_ok=False)
    source_capsule = _find_leaf(source_leaves, "bootstrap/capsule.py")
    capsule_path = record_dir / "capsule.py"
    with source_capsule.open("rb") as source, capsule_path.open("xb") as destination:
        shutil.copyfileobj(source, destination)
        destination.flush()
        os.fsync(destination.fileno())
    runtime_manifest_path = record_dir / "runtime-manifest.json"
    runtime_manifest = {
        "schema": 1,
        "closed": True,
        "activation_state": "inactive",
        "generation": generation,
        "runtime_digest": proposal["runtime_digest"],
        "runtime_lock_path": str(lock_path),
        "runtime_lock_sha256": _sha_file(lock_path),
    }
    _exclusive_json(runtime_manifest_path, runtime_manifest)
    generation_path = record_dir / "generation.txt"
    _exclusive_bytes(generation_path, str(generation).encode("ascii"))
    _exclusive_bytes(record_dir / "checkout-binding.txt", str(checkout).encode("utf-8"))
    anchor_path = record_dir / "anchor-record.json"
    anchor_record = {
        "schema": 1,
        "capsule_path": str(capsule_path),
        "capsule_sha256": _sha_file(capsule_path),
        "runtime_manifest_path": str(runtime_manifest_path),
        "runtime_manifest_sha256": _sha_file(runtime_manifest_path),
        "generation_path": str(generation_path),
        "generation": generation,
        "activation_state": "inactive",
    }
    _exclusive_json(anchor_path, anchor_record)

    pointer_path = resolved_root / "activation-runtime.json"
    pointer = {
        "schema": "galaxy.activation.runtime-pointer/v1",
        "runtime_lock_path": str(lock_path),
        "runtime_lock_sha256": _sha_file(lock_path),
        "generation": generation,
        "status": "installed_inactive",
    }
    _exclusive_json(pointer_path, pointer)
    receipt = {
        "schema": "galaxy.trust-on-first-install/v1",
        "status": "installed_inactive",
        "source_leaves": _receipt_leaves(source_leaves),
        "artifact_leaves": _receipt_leaves(artifact_leaves),
        "source_root": source_root,
        "artifact_root": artifact_root,
        "merkle_root": merkle_root,
        "nonce": nonce,
        "challenge": challenge,
        "approval_response_sha256": hashlib.sha256(response).hexdigest(),
        "runtime_digest": proposal["runtime_digest"],
        "image_digests": proposal["image_digests"],
        "activation_acceptance_sha256": proposal["activation_acceptance_sha256"],
        "activation_runtime_profiles_sha256": proposal[
            "activation_runtime_profiles_sha256"
        ],
        "activation_adapter_sha256": proposal["activation_adapter_sha256"],
        "activation_receipt_public_key": proposal["activation_receipt_public_key"],
        "activation_receipt_public_key_digest": proposal[
            "activation_receipt_public_key_digest"
        ],
        "monotone_generation": generation,
        "dacl_sddl": dacl_sddl,
        "operator_sid": proposal["operator_sid"],
        "service_sid": proposal["service_sid"],
        "service_name": proposal["service_name"],
        "repository_identity": repository_identity,
        "anchor_record_path": str(anchor_path),
        "activation_state": "inactive",
    }
    _exclusive_json(receipt_path, receipt)
    return {
        "schema": "galaxy.tofu-finalization-result/v1",
        "status": "installed_inactive",
        "receipt_path": str(receipt_path),
        "anchor_record_path": str(anchor_path),
        "runtime_pointer_path": str(pointer_path),
        "merkle_root": merkle_root,
        "generation": generation,
        "activation_authority": False,
    }


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="galaxy-tofu-finalize")
    parser.add_argument("--proposal", required=True)
    parser.add_argument("--response", required=True)
    parser.add_argument("--dacl-sddl", required=True)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        result = finalize_inactive_install(
            proposal_path=Path(args.proposal),
            response_path=Path(args.response),
            dacl_sddl=args.dacl_sddl,
        )
        sys.stdout.buffer.write(_canonical(result) + b"\n")
        return 0
    except (OSError, ValueError, KeyError, TofuFinalizationRefused) as exc:
        sys.stderr.write(f"GALAXY TOFU finalization refused: {exc}\n")
        return 78


if __name__ == "__main__":
    raise SystemExit(main())
