"""Small standard-library-only Ed25519 receipt primitive.

This is intentionally narrow: deterministic RFC 8032 Ed25519 signatures over
already-canonical receipt bytes.  It avoids ambient OpenSSL/provider loading in
the sealed ``-I -S`` controller runtime.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  public_key_from_seed(seed: bytes) -> bytes  -- Return the RFC 8032 public key for a 32-byte private seed.
  sign(seed: bytes, message: bytes) -> bytes  -- Return a deterministic 64-byte Ed25519 signature.
  verify(public_key: bytes, message: bytes, signature: bytes) -> bool  -- Verify a canonical, prime-subgroup Ed25519 signature.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_activation_crypto.py
"""

from __future__ import annotations

import hashlib


_Q = 2**255 - 19
_L = 2**252 + 27742317777372353535851937790883648493


def _inverse(value: int) -> int:
    return pow(value, _Q - 2, _Q)


_D = (-121665 * _inverse(121666)) % _Q
_I = pow(2, (_Q - 1) // 4, _Q)


def _recover_x(y: int) -> int:
    xx = (y * y - 1) * _inverse(_D * y * y + 1)
    x = pow(xx, (_Q + 3) // 8, _Q)
    if (x * x - xx) % _Q:
        x = x * _I % _Q
    if x & 1:
        x = _Q - x
    return x


_BY = 4 * _inverse(5) % _Q
_BX = _recover_x(_BY)
_IDENTITY = (0, 1, 1, 0)
_BASE = (_BX, _BY, 1, _BX * _BY % _Q)
_Point = tuple[int, int, int, int]


def _add(first: _Point, second: _Point) -> _Point:
    x1, y1, z1, t1 = first
    x2, y2, z2, t2 = second
    a = (y1 - x1) * (y2 - x2) % _Q
    b = (y1 + x1) * (y2 + x2) % _Q
    c = 2 * _D * t1 * t2 % _Q
    d = 2 * z1 * z2 % _Q
    e = b - a
    f = d - c
    g = d + c
    h = b + a
    return (e * f % _Q, g * h % _Q, f * g % _Q, e * h % _Q)


def _double(point: _Point) -> _Point:
    x, y, z, _ = point
    a = x * x % _Q
    b = y * y % _Q
    c = 2 * z * z % _Q
    d = -a
    e = (x + y) * (x + y) - a - b
    g = d + b
    f = g - c
    h = d - b
    return (e * f % _Q, g * h % _Q, f * g % _Q, e * h % _Q)


def _scalar_mult(point: _Point, scalar: int) -> _Point:
    result = _IDENTITY
    current = point
    while scalar:
        if scalar & 1:
            result = _add(result, current)
        current = _double(current)
        scalar >>= 1
    return result


def _base_table() -> tuple[_Point, ...]:
    result = [_BASE]
    for _ in range(255):
        result.append(_double(result[-1]))
    return tuple(result)


_BASE_POWERS = _base_table()


def _scalar_mult_base(scalar: int) -> _Point:
    result = _IDENTITY
    bit = 0
    while scalar:
        if scalar & 1:
            result = _add(result, _BASE_POWERS[bit])
        scalar >>= 1
        bit += 1
    return result


def _encode(point: _Point) -> bytes:
    x, y, z, _ = point
    inverse_z = _inverse(z)
    affine_x = x * inverse_z % _Q
    affine_y = y * inverse_z % _Q
    encoded = affine_y | ((affine_x & 1) << 255)
    return encoded.to_bytes(32, "little")


def _decode(encoded: bytes) -> _Point:
    if len(encoded) != 32:
        raise ValueError("Ed25519 point must be 32 bytes")
    value = int.from_bytes(encoded, "little")
    sign = value >> 255
    y = value & ((1 << 255) - 1)
    if y >= _Q:
        raise ValueError("non-canonical Ed25519 point")
    x = _recover_x(y)
    if (x & 1) != sign:
        x = _Q - x
    if (-x * x + y * y - 1 - _D * x * x * y * y) % _Q:
        raise ValueError("point is not on Ed25519 curve")
    point = (x, y, 1, x * y % _Q)
    if _encode(point) != encoded:
        raise ValueError("non-canonical Ed25519 encoding")
    return point


def _secret_scalar(seed: bytes) -> tuple[int, bytes]:
    if len(seed) != 32:
        raise ValueError("Ed25519 seed must be 32 bytes")
    expanded = bytearray(hashlib.sha512(seed).digest())
    expanded[0] &= 248
    expanded[31] &= 63
    expanded[31] |= 64
    return int.from_bytes(expanded[:32], "little"), bytes(expanded[32:])


def public_key_from_seed(seed: bytes) -> bytes:
    """Return the RFC 8032 public key for a 32-byte private seed."""
    scalar, _ = _secret_scalar(seed)
    return _encode(_scalar_mult_base(scalar))


def sign(seed: bytes, message: bytes) -> bytes:
    """Return a deterministic 64-byte Ed25519 signature."""
    scalar, prefix = _secret_scalar(seed)
    public_key = _encode(_scalar_mult_base(scalar))
    nonce = int.from_bytes(hashlib.sha512(prefix + message).digest(), "little") % _L
    encoded_r = _encode(_scalar_mult_base(nonce))
    challenge = int.from_bytes(hashlib.sha512(encoded_r + public_key + message).digest(), "little") % _L
    encoded_s = ((nonce + challenge * scalar) % _L).to_bytes(32, "little")
    return encoded_r + encoded_s


def verify(public_key: bytes, message: bytes, signature: bytes) -> bool:
    """Verify a canonical, prime-subgroup Ed25519 signature."""
    try:
        if len(public_key) != 32 or len(signature) != 64:
            return False
        public_point = _decode(public_key)
        r_point = _decode(signature[:32])
        scalar = int.from_bytes(signature[32:], "little")
        if scalar >= _L:
            return False
        if _encode(_scalar_mult(public_point, _L)) != _encode(_IDENTITY):
            return False
        if _encode(_scalar_mult(r_point, _L)) != _encode(_IDENTITY):
            return False
        challenge = (
            int.from_bytes(hashlib.sha512(signature[:32] + public_key + message).digest(), "little") % _L
        )
        left = _scalar_mult_base(scalar)
        right = _add(r_point, _scalar_mult(public_point, challenge))
        return _encode(left) == _encode(right)
    except (ValueError, OverflowError):
        return False
