_status_handle: int | None = None
_stop_event: int | None = None
_status = _ServiceStatus()


def _publish(state: int, accepted: int, *, checkpoint: int = 0, wait_hint: int = 0) -> None:
    if _status_handle is None:
        return
    _status.service_type = _SERVICE_WIN32_OWN_PROCESS
    _status.current_state = state
    _status.controls_accepted = accepted
    _status.win32_exit_code = _NO_ERROR
    _status.service_specific_exit_code = 0
    _status.checkpoint = checkpoint
    _status.wait_hint = wait_hint
    if not _advapi32.SetServiceStatus(_status_handle, ctypes.byref(_status)):
        raise ctypes.WinError(ctypes.get_last_error())


def _control_handler_impl(control: int, event_type: int, event_data: int, context: int) -> int:
    del event_type, event_data, context
    if control in {_SERVICE_CONTROL_STOP, _SERVICE_CONTROL_SHUTDOWN}:
        _publish(_SERVICE_STOP_PENDING, 0, checkpoint=1, wait_hint=5000)
        if _stop_event is not None:
            _kernel32.SetEvent(_stop_event)
    elif control == _SERVICE_CONTROL_INTERROGATE:
        _publish(_status.current_state, _status.controls_accepted)
    return _NO_ERROR


_control_handler = _Handler(_control_handler_impl)


def _service_main_impl(argument_count: int, arguments: Any) -> None:
    del argument_count, arguments
    global _status_handle, _stop_event
    _status_handle = int(_advapi32.RegisterServiceCtrlHandlerExW(SERVICE_NAME, _control_handler, None))
    if not _status_handle:
        return
    _publish(_SERVICE_START_PENDING, 0, checkpoint=1, wait_hint=5000)
    _stop_event = int(_kernel32.CreateEventW(None, True, False, None))
    if not _stop_event:
        _publish(_SERVICE_STOPPED, 0)
        return
    worker: threading.Thread | None = None
    try:
        source = Path(__file__).resolve(strict=True)
        pointer = source.parents[3] / "activation-runtime.json"
        if pointer.exists():
            if _path_has_reparse(pointer):
                _publish(_SERVICE_STOPPED, 0)
                return
            try:
                boundary = resolve_anchor_launch_boundary(service_path=source)
            except (OSError, RuntimeError, ValueError):
                _publish(_SERVICE_STOPPED, 0)
                return
            worker = threading.Thread(
                target=_maintenance_pipe_worker,
                args=(boundary,),
                name="singularity-maintenance-pipe",
                daemon=True,
            )
            worker.start()
        _publish(
            _SERVICE_RUNNING,
            _SERVICE_ACCEPT_STOP | _SERVICE_ACCEPT_SHUTDOWN,
        )
        _kernel32.WaitForSingleObject(_stop_event, 0xFFFFFFFF)
        _publish(_SERVICE_STOPPED, 0)
    finally:
        _kernel32.CloseHandle(_stop_event)
        _stop_event = None


