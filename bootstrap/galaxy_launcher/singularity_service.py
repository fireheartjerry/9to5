def _read_pipe_exact(handle: int, count: int) -> bytes:
    if count < 0 or count > _MAX_RESPONSE_BYTES:
        raise ValueError("pipe read length is outside its bound")
    result = bytearray()
    while len(result) < count:
        remaining = count - len(result)
        buffer = ctypes.create_string_buffer(remaining)
        observed = wintypes.DWORD()
        if not _kernel32.ReadFile(
            handle, buffer, remaining, ctypes.byref(observed), None
        ):
            raise ctypes.WinError(ctypes.get_last_error())
        if observed.value < 1 or observed.value > remaining:
            raise OSError("named-pipe frame ended early")
        result.extend(buffer.raw[: observed.value])
    return bytes(result)


def _write_pipe_exact(handle: int, raw: bytes) -> None:
    offset = 0
    while offset < len(raw):
        chunk = raw[offset : offset + 65536]
        buffer = ctypes.create_string_buffer(chunk, len(chunk))
        written = wintypes.DWORD()
        if not _kernel32.WriteFile(
            handle, buffer, len(chunk), ctypes.byref(written), None
        ):
            raise ctypes.WinError(ctypes.get_last_error())
        if written.value < 1 or written.value > len(chunk):
            raise OSError("named-pipe frame write made no progress")
        offset += written.value


def _path_has_reparse(path: Path) -> bool:
    absolute = Path(os.path.abspath(path))
    current = Path(absolute.parts[0])
    for component in absolute.parts[1:]:
        current /= component
        attributes = _kernel32.GetFileAttributesW(str(current))
        if attributes != 0xFFFFFFFF and bool(attributes & 0x400):
            return True
    return False


def _ordinary_digest(path: Path, expected: str, *, label: str) -> Path:
    if re.fullmatch(r"[0-9a-f]{64}", expected) is None:
        raise ValueError(f"{label} expected digest is malformed")
    if _path_has_reparse(path):
        raise OSError(f"{label} traverses a reparse point")
    resolved = path.resolve(strict=True)
    info = resolved.stat()
    if not stat.S_ISREG(info.st_mode):
        raise OSError(f"{label} is not an ordinary file")
    digest = hashlib.sha256()
    with resolved.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    after = resolved.stat()
    if (
        (info.st_dev, info.st_ino, info.st_size)
        != (after.st_dev, after.st_ino, after.st_size)
        or digest.hexdigest() != expected
    ):
        raise OSError(f"{label} identity or digest differs")
    return resolved


def validate_pipe_client(
    pipe_handle: int, expected: ExpectedPipeClient
) -> dict[str, object]:
    """Bind the local pipe peer to the pinned host and installed client bytes."""

    process_id = wintypes.ULONG()
    if not _kernel32.GetNamedPipeClientProcessId(
        pipe_handle, ctypes.byref(process_id)
    ) or process_id.value < 1:
        raise ctypes.WinError(ctypes.get_last_error())
    process = _kernel32.OpenProcess(
        _PROCESS_QUERY_LIMITED_INFORMATION, False, process_id.value
    )
    if not process:
        raise ctypes.WinError(ctypes.get_last_error())
    try:
        capacity = wintypes.DWORD(32768)
        buffer = ctypes.create_unicode_buffer(capacity.value)
        if not _kernel32.QueryFullProcessImageNameW(
            process, 0, buffer, ctypes.byref(capacity)
        ):
            raise ctypes.WinError(ctypes.get_last_error())
        image = Path(buffer.value[: capacity.value])
    finally:
        _kernel32.CloseHandle(process)
    expected_image = _ordinary_digest(
        Path(expected.process_image_path),
        expected.process_image_sha256,
        label="pipe client process image",
    )
    observed_image = _ordinary_digest(
        image, expected.process_image_sha256, label="observed pipe client process image"
    )
    if os.path.normcase(str(observed_image)) != os.path.normcase(str(expected_image)):
        raise OSError("pipe client process image path differs")
    request_client = _ordinary_digest(
        Path(expected.request_client_path),
        expected.request_client_sha256,
        label="installed request client",
    )
    return {
        "schema": "galaxy.pipe-client-identity/v1",
        "process_id": int(process_id.value),
        "process_image_path": str(observed_image),
        "process_image_sha256": expected.process_image_sha256,
        "request_client_path": str(request_client),
        "request_client_sha256": expected.request_client_sha256,
    }


def build_pipe_sddl(operator_sid: str, service_sid: str) -> str:
    """Build the closed local-only DACL committed by the TOFU receipt."""

    if _SID.fullmatch(operator_sid) is None or _SID.fullmatch(service_sid) is None:
        raise ValueError("pipe principal SID is malformed")
    return (
        "D:P(A;;GA;;;SY)"
        f"(A;;GRGW;;;{operator_sid})"
        f"(A;;GA;;;{service_sid})"
    )


def _duplicate_json_member(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON member: {key}")
        result[key] = value
    return result


def _refuse_json_constant(value: str) -> Any:
    raise ValueError(f"non-finite JSON number is forbidden: {value}")


def _canonical_json(value: Any) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        allow_nan=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8", errors="strict")


def _strict_canonical_json(raw: bytes, *, label: str, maximum: int) -> dict[str, Any]:
    if not isinstance(raw, bytes) or not raw or len(raw) > maximum:
        raise ValueError(f"{label} byte length is outside its bound")
    if raw.startswith((b"\xef\xbb\xbf", b"\xff\xfe", b"\xfe\xff")):
        raise ValueError(f"{label} BOM is forbidden")
    try:
        value = json.loads(
            raw.decode("utf-8", errors="strict"),
            object_pairs_hook=_duplicate_json_member,
            parse_constant=_refuse_json_constant,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"{label} is not strict UTF-8 JSON") from exc
    if not isinstance(value, dict) or _canonical_json(value) != raw:
        raise ValueError(f"{label} is not a canonical JSON object")
    return value


def _read_bound_json(
    path: Path,
    *,
    root: Path | None,
    label: str,
    maximum: int,
    expected_sha256: str | None = None,
) -> tuple[Path, dict[str, Any], str]:
    if _path_has_reparse(path):
        raise OSError(f"{label} traverses a reparse point")
    resolved = path.resolve(strict=True)
    if root is not None:
        resolved.relative_to(root)
    before = resolved.stat()
    if (
        not stat.S_ISREG(before.st_mode)
        or before.st_size < 1
        or before.st_size > maximum
    ):
        raise OSError(f"{label} is not a bounded ordinary file")
    raw = resolved.read_bytes()
    after = resolved.stat()
    if (
        len(raw) != before.st_size
        or (before.st_dev, before.st_ino, before.st_size)
        != (after.st_dev, after.st_ino, after.st_size)
    ):
        raise OSError(f"{label} identity changed while reading")
    digest = hashlib.sha256(raw).hexdigest()
    if expected_sha256 is not None and digest != expected_sha256:
        raise OSError(f"{label} digest differs")
    return resolved, _strict_canonical_json(raw, label=label, maximum=maximum), digest


def _closure_leaf(
    leaves: Any,
    logical_path: str,
    *,
    root: Path | None,
    label: str,
) -> tuple[Path, str]:
    if not isinstance(leaves, list):
        raise ValueError(f"{label} leaf collection is malformed")
    matches = [
        leaf
        for leaf in leaves
        if isinstance(leaf, dict) and leaf.get("logical_path") == logical_path
    ]
    if len(matches) != 1:
        raise ValueError(f"{label} leaf is not unique")
    leaf = matches[0]
    if set(leaf) != {"installed_path", "logical_path", "sha256", "size"}:
        raise ValueError(f"{label} leaf fields are not closed")
    digest = leaf.get("sha256")
    size = leaf.get("size")
    path_value = leaf.get("installed_path")
    if (
        not isinstance(digest, str)
        or re.fullmatch(r"[0-9a-f]{64}", digest) is None
        or type(size) is not int
        or size < 1
        or not isinstance(path_value, str)
    ):
        raise ValueError(f"{label} leaf identity is malformed")
    path = _ordinary_digest(Path(path_value), digest, label=label)
    if root is not None:
        path.relative_to(root)
    if path.stat().st_size != size:
        raise OSError(f"{label} leaf size differs")
    return path, digest


def resolve_anchor_launch_boundary(
    *,
    service_path: Path | None = None,
    process_image_path: Path | None = None,
) -> AnchorLaunchBoundary:
    """Resolve one launch boundary solely from the installed sealed closure."""

    source_candidate = Path(__file__ if service_path is None else service_path)
    source = source_candidate.resolve(strict=True)
    if _path_has_reparse(source) or source.name != "singularity_service.py":
        raise OSError("installed service source identity is malformed")
    try:
        external_root = source.parents[3].resolve(strict=True)
    except (IndexError, OSError) as exc:
        raise OSError("installed service path has no external generation root") from exc
    if source.parents[2].name != "generations" or source.parent.name != "controller":
        raise OSError("installed service path is outside the generation controller")
    lock_path, lock, _ = _read_bound_json(
        source.parent / "runtime.lock.json",
        root=external_root,
        label="runtime lock",
        maximum=4 * 1024 * 1024,
    )
    if (
        set(lock) != _RUNTIME_LOCK_KEYS
        or lock.get("schema") != "galaxy.activation.sealed-runtime/v1"
        or lock.get("status") != "installed_inactive"
        or type(lock.get("generation")) is not int
        or lock["generation"] < 1
        or lock.get("external_root") != str(external_root)
    ):
        raise ValueError("runtime lock identity or fields differ")
    files = lock.get("files")
    digests = lock.get("file_digests")
    if not isinstance(files, dict) or not isinstance(digests, dict):
        raise ValueError("runtime file inventory is malformed")
    for key in ("interpreter", "service_host"):
        if not isinstance(files.get(key), str) or not isinstance(digests.get(key), str):
            raise ValueError(f"runtime {key} binding is absent")
    bound_service = _ordinary_digest(
        Path(files["service_host"]), digests["service_host"], label="service host"
    )
    if bound_service != source:
        raise OSError("running service source differs from the runtime lock")
    process_candidate = Path(sys.executable if process_image_path is None else process_image_path)
    interpreter = _ordinary_digest(
        Path(files["interpreter"]), digests["interpreter"], label="service interpreter"
    )
    if os.path.normcase(str(process_candidate.resolve(strict=True))) != os.path.normcase(
        str(interpreter)
    ):
        raise OSError("running service interpreter differs from the runtime lock")
    receipt_value = lock.get("tofu_receipt_path")
    if not isinstance(receipt_value, str):
        raise ValueError("runtime TOFU receipt path is malformed")
    _, receipt, _ = _read_bound_json(
        Path(receipt_value),
        root=external_root,
        label="TOFU receipt",
        maximum=32 * 1024 * 1024,
    )
    if (
        set(receipt) != _TOFU_RECEIPT_KEYS
        or receipt.get("schema") != "galaxy.trust-on-first-install/v1"
        or receipt.get("status") != "installed_inactive"
        or receipt.get("activation_state") != "inactive"
        or receipt.get("service_name") != SERVICE_NAME
        or receipt.get("runtime_digest") != lock.get("runtime_digest")
        or receipt.get("monotone_generation") != lock.get("generation")
    ):
        raise ValueError("TOFU receipt identity or inactive binding differs")
    operator_sid = receipt.get("operator_sid")
    service_sid = receipt.get("service_sid")
    if not isinstance(operator_sid, str) or not isinstance(service_sid, str):
        raise ValueError("TOFU receipt pipe principals are malformed")
    build_pipe_sddl(operator_sid, service_sid)
    request_client, request_client_digest = _closure_leaf(
        receipt.get("source_leaves"),
        "bootstrap/singularity_admin_client.ps1",
        root=external_root,
        label="request client",
    )
    anchor, anchor_digest = _closure_leaf(
        receipt.get("source_leaves"),
        "bootstrap/singularity_anchor.ps1",
        root=external_root,
        label="native anchor",
    )
    powershell, powershell_digest = _closure_leaf(
        receipt.get("artifact_leaves"),
        "system/powershell.exe",
        root=None,
        label="PowerShell host",
    )
    # OS-owned host binaries are deliberately outside the external root; the
    # receipt leaf still binds their exact path, size, and digest.
    launch_value = receipt.get("anchor_launch_record_path")
    launch_digest = receipt.get("anchor_launch_record_sha256")
    if not isinstance(launch_value, str) or not isinstance(launch_digest, str):
        raise ValueError("anchor launch record binding is malformed")
    _, launch, _ = _read_bound_json(
        Path(launch_value),
        root=external_root,
        label="anchor launch record",
        maximum=1024 * 1024,
        expected_sha256=launch_digest,
    )
    if (
        set(launch) != _LAUNCH_RECORD_KEYS
        or launch.get("schema") != "galaxy.singularity-anchor-launch/v1"
        or launch.get("activation_state") != "inactive"
        or launch.get("service_name") != SERVICE_NAME
        or launch.get("control_pipe") != rf"\\.\pipe\{PIPE_NAME}"
        or launch.get("anchor_path") != str(anchor)
        or launch.get("anchor_sha256") != anchor_digest
        or launch.get("host_path") != str(powershell)
        or launch.get("host_sha256") != powershell_digest
        or launch.get("host_signature_sha256")
        != receipt.get("host_signature_sha256")
        or launch.get("stdio")
        != {"stderr": "null", "stdin": "null", "stdout": "null"}
    ):
        raise ValueError("anchor launch record differs from the installed closure")
    arguments = launch.get("arguments")
    environment = launch.get("environment")
    working_value = launch.get("working_directory")
    if (
        not isinstance(arguments, list)
        or not arguments
        or any(not isinstance(value, str) for value in arguments)
        or not isinstance(environment, dict)
        or set(environment) != {"PATH", "PSModulePath", "SystemRoot", "WINDIR"}
        or environment.get("PATH") != ""
        or environment.get("PSModulePath") != ""
        or any(not isinstance(value, str) for value in environment.values())
        or not isinstance(working_value, str)
    ):
        raise ValueError("anchor launch arguments, environment, or cwd are malformed")
    working = Path(working_value)
    working.relative_to(external_root)
    working = working.resolve(strict=True)
    if _path_has_reparse(working) or not working.is_dir() or any(working.iterdir()):
        raise OSError("anchor launch working directory is not empty and ordinary")
    expected_client = ExpectedPipeClient(
        process_image_path=powershell,
        process_image_sha256=powershell_digest,
        request_client_path=request_client,
        request_client_sha256=request_client_digest,
    )
    return AnchorLaunchBoundary(
        expected_client=expected_client,
        anchor_path=anchor,
        anchor_sha256=anchor_digest,
        host_path=powershell,
        host_sha256=powershell_digest,
        launch_arguments=tuple(arguments),
        working_directory=working,
        environment=dict(environment),
        operator_sid=operator_sid,
        service_sid=service_sid,
    )


def invoke_native_anchor(
    boundary: AnchorLaunchBoundary,
    request: bytes,
    *,
    runner: Callable[..., Any] = subprocess.run,
) -> bytes:
    """Transport one request into a freshly re-attested native anchor host."""

    request_value = _strict_canonical_json(
        request, label="anchor request", maximum=_MAX_REQUEST_BYTES
    )
    if set(request_value) != {
        "arguments",
        "operation",
        "payload_base64url",
        "request_id",
    }:
        raise ValueError("anchor request fields are not closed")
    host = _ordinary_digest(
        boundary.host_path, boundary.host_sha256, label="anchor host"
    )
    anchor = _ordinary_digest(
        boundary.anchor_path, boundary.anchor_sha256, label="native anchor"
    )
    arguments = list(boundary.launch_arguments)
    operation_positions = [
        index for index, value in enumerate(arguments) if value == "-Operation"
    ]
    file_positions = [index for index, value in enumerate(arguments) if value == "-File"]
    if (
        len(operation_positions) != 1
        or operation_positions[0] + 1 >= len(arguments)
        or arguments[operation_positions[0] + 1] != "diagnostic"
        or len(file_positions) != 1
        or file_positions[0] + 1 >= len(arguments)
        or os.path.normcase(arguments[file_positions[0] + 1])
        != os.path.normcase(str(anchor))
        or "-MaintenanceRequestBase64Url" in arguments
    ):
        raise ValueError("anchor launch arguments are not the exact inactive template")
    arguments[operation_positions[0] + 1] = "maintenance"
    encoded = base64.urlsafe_b64encode(request).decode("ascii").rstrip("=")
    if len(encoded) > 10923:
        raise ValueError("anchor request base64url wrapper exceeds its bound")
    arguments.extend(["-MaintenanceRequestBase64Url", encoded])
    working = Path(boundary.working_directory)
    if _path_has_reparse(working):
        raise OSError("anchor working directory traverses a reparse point")
    working = working.resolve(strict=True)
    if not working.is_dir() or working.is_symlink() or any(working.iterdir()):
        raise OSError("anchor working directory is not empty and ordinary")
    completed = runner(
        [str(host), *arguments],
        cwd=working,
        env=dict(boundary.environment),
        input=b"",
        capture_output=True,
        timeout=120,
        check=False,
    )
    stdout = completed.stdout
    stderr = completed.stderr
    if not isinstance(stdout, bytes) or not isinstance(stderr, bytes):
        raise RuntimeError("native anchor returned non-byte output")
    if len(stdout) > _MAX_RESPONSE_BYTES + 1 or len(stderr) > _MAX_RESPONSE_BYTES:
        raise RuntimeError("native anchor output exceeds its bound")
    if completed.returncode != 0:
        raise RuntimeError(
            f"native anchor refused maintenance with exit {completed.returncode}"
        )
    if stderr or not stdout.endswith(b"\n") or stdout.endswith(b"\n\n"):
        raise RuntimeError("native anchor success output is not one clean response")
    response = stdout[:-1]
    response_value = _strict_canonical_json(
        response, label="anchor response", maximum=_MAX_RESPONSE_BYTES
    )
    if (
        set(response_value)
        != {
            "accepted",
            "authority_ceiling",
            "operation",
            "production_active",
            "request_id",
            "result",
            "schema",
        }
        or response_value.get("schema")
        != "galaxy.singularity-admin-response/v1"
        or response_value.get("accepted") is not True
        or response_value.get("authority_ceiling") != "maintenance_only"
        or response_value.get("production_active") is not False
        or response_value.get("operation") != request_value.get("operation")
        or response_value.get("request_id") != request_value.get("request_id")
    ):
        raise RuntimeError("native anchor response authority or request binding differs")
    return response


def serve_pipe_once(
    handler: Callable[[bytes], bytes],
    *,
    pipe_name: str = PIPE_NAME,
    ready_event: Any | None = None,
    identity_validator: Callable[[int], Any] | None = None,
    security_sddl: str | None = None,
) -> None:
    """Serve one bounded local request frame through a create-first pipe."""

    if re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9.-]{0,63}", pipe_name) is None:
        raise ValueError("pipe name is outside the closed local grammar")
    path = rf"\\.\pipe\{pipe_name}"
    descriptor = ctypes.c_void_p()
    attributes: _SecurityAttributes | None = None
    if security_sddl is not None:
        if len(security_sddl) > 4096 or not security_sddl.startswith("D:P"):
            raise ValueError("pipe security descriptor is malformed")
        descriptor_size = wintypes.DWORD()
        if not _advapi32.ConvertStringSecurityDescriptorToSecurityDescriptorW(
            security_sddl,
            1,
            ctypes.byref(descriptor),
            ctypes.byref(descriptor_size),
        ):
            raise ctypes.WinError(ctypes.get_last_error())
        attributes = _SecurityAttributes(
            ctypes.sizeof(_SecurityAttributes), descriptor, False
        )
    try:
        raw_handle = _kernel32.CreateNamedPipeW(
                path,
                _PIPE_ACCESS_DUPLEX
                | _FILE_FLAG_FIRST_PIPE_INSTANCE
                | _FILE_FLAG_WRITE_THROUGH,
                _PIPE_TYPE_BYTE
                | _PIPE_READMODE_BYTE
                | _PIPE_WAIT
                | _PIPE_REJECT_REMOTE_CLIENTS,
                1,
                65536,
                65536,
                0,
                ctypes.byref(attributes) if attributes is not None else None,
            )
    finally:
        if descriptor.value:
            _kernel32.LocalFree(descriptor)
    handle = int(raw_handle)
    invalid_handle = ctypes.c_void_p(-1).value
    if not handle or handle == invalid_handle:
        raise ctypes.WinError(ctypes.get_last_error())
    connected = False
    try:
        if ready_event is not None:
            ready_event.set()
        if not _kernel32.ConnectNamedPipe(handle, None):
            error = ctypes.get_last_error()
            if error != _ERROR_PIPE_CONNECTED:
                raise ctypes.WinError(error)
        connected = True
        if identity_validator is not None:
            identity_validator(handle)
        header = _read_pipe_exact(handle, 4)
        request_length = struct.unpack(">I", header)[0]
        if request_length < 1 or request_length > _MAX_REQUEST_BYTES:
            raise ValueError("named-pipe request length is outside 1..8192")
        request = _read_pipe_exact(handle, request_length)
        response = handler(request)
        if (
            not isinstance(response, bytes)
            or len(response) < 1
            or len(response) > _MAX_RESPONSE_BYTES
        ):
            raise ValueError("named-pipe handler response is outside its bound")
        _write_pipe_exact(handle, struct.pack(">I", len(response)) + response)
        if not _kernel32.FlushFileBuffers(handle):
            raise ctypes.WinError(ctypes.get_last_error())
    finally:
        if connected:
            _kernel32.DisconnectNamedPipe(handle)
        _kernel32.CloseHandle(handle)


def _maintenance_pipe_worker(boundary: AnchorLaunchBoundary) -> None:
    security_sddl = build_pipe_sddl(boundary.operator_sid, boundary.service_sid)
    while _stop_event is not None and _kernel32.WaitForSingleObject(_stop_event, 0) == 0x102:
        try:
            serve_pipe_once(
                lambda raw: invoke_native_anchor(boundary, raw),
                identity_validator=lambda handle: validate_pipe_client(
                    handle, boundary.expected_client
                ),
                security_sddl=security_sddl,
            )
        except (OSError, RuntimeError, ValueError):
            # A refused or disconnected client cannot change service state.
            continue


def run_service_dispatcher() -> int:
    """Enter the SCM dispatcher and remain authority-free until stopped."""
    table = (_ServiceTableEntry * 2)()
    table[0].name = SERVICE_NAME
    table[0].service_main = _service_main
    table[1].name = None
    if not _advapi32.StartServiceCtrlDispatcherW(table):
        error = ctypes.get_last_error()
        sys.stderr.write(f"StartServiceCtrlDispatcherW failed ({error})\n")
        return 78
    return 0


def self_test() -> dict[str, object]:
    return {
        "activation_authority": False,
        "accepted_commands": ["interrogate", "shutdown", "stop"],
        "schema": "galaxy.singularity-service-self-test/v1",
        "service_state": "stopped",
    }


def main(argv: Sequence[str] | None = None) -> int:
    arguments = list(sys.argv[1:] if argv is None else argv)
    if arguments == ["--self-test"]:
        sys.stdout.write(json.dumps(self_test(), sort_keys=True, separators=(",", ":")) + "\n")
        return 0
    if arguments == ["--service"]:
        return run_service_dispatcher()
    sys.stderr.write("only --service and --self-test are available\n")
    return 78


if __name__ == "__main__":
    raise SystemExit(main())
