"""Inactive Windows service host for the installed Singularity anchor.

The service deliberately exposes no activation or repository operation.  Its
first installed generation exists only to establish the restricted service SID
and a correct SCM lifecycle boundary for later, separately warranted code.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  run_service_dispatcher() -> int  -- Enter the SCM dispatcher and remain authority-free until stopped.
  self_test() -> dict[str, object]
  main(argv: Sequence[str] | None=None) -> int
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_singularity_service.py
"""

from __future__ import annotations

import ctypes
from ctypes import wintypes
import json
import sys
from typing import Any, Sequence


SERVICE_NAME = "9to5Singularity"
_SERVICE_WIN32_OWN_PROCESS = 0x10
_SERVICE_STOPPED = 0x1
_SERVICE_START_PENDING = 0x2
_SERVICE_STOP_PENDING = 0x3
_SERVICE_RUNNING = 0x4
_SERVICE_ACCEPT_STOP = 0x1
_SERVICE_ACCEPT_SHUTDOWN = 0x4
_SERVICE_CONTROL_STOP = 0x1
_SERVICE_CONTROL_INTERROGATE = 0x4
_SERVICE_CONTROL_SHUTDOWN = 0x5
_NO_ERROR = 0


class _ServiceStatus(ctypes.Structure):
    _fields_ = (
        ("service_type", wintypes.DWORD),
        ("current_state", wintypes.DWORD),
        ("controls_accepted", wintypes.DWORD),
        ("win32_exit_code", wintypes.DWORD),
        ("service_specific_exit_code", wintypes.DWORD),
        ("checkpoint", wintypes.DWORD),
        ("wait_hint", wintypes.DWORD),
    )


_Handler = ctypes.WINFUNCTYPE(
    wintypes.DWORD,
    wintypes.DWORD,
    wintypes.DWORD,
    ctypes.c_void_p,
    ctypes.c_void_p,
)
_ServiceMain = ctypes.WINFUNCTYPE(None, wintypes.DWORD, ctypes.POINTER(wintypes.LPWSTR))


class _ServiceTableEntry(ctypes.Structure):
    _fields_ = (("name", wintypes.LPWSTR), ("service_main", _ServiceMain))


_advapi32 = ctypes.WinDLL("advapi32", use_last_error=True)
_kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
_advapi32.RegisterServiceCtrlHandlerExW.argtypes = (
    wintypes.LPCWSTR,
    _Handler,
    ctypes.c_void_p,
)
_advapi32.RegisterServiceCtrlHandlerExW.restype = wintypes.HANDLE
_advapi32.SetServiceStatus.argtypes = (
    wintypes.HANDLE,
    ctypes.POINTER(_ServiceStatus),
)
_advapi32.SetServiceStatus.restype = wintypes.BOOL
_advapi32.StartServiceCtrlDispatcherW.argtypes = (ctypes.POINTER(_ServiceTableEntry),)
_advapi32.StartServiceCtrlDispatcherW.restype = wintypes.BOOL
_kernel32.CreateEventW.argtypes = (
    ctypes.c_void_p,
    wintypes.BOOL,
    wintypes.BOOL,
    wintypes.LPCWSTR,
)
_kernel32.CreateEventW.restype = wintypes.HANDLE
_kernel32.SetEvent.argtypes = (wintypes.HANDLE,)
_kernel32.SetEvent.restype = wintypes.BOOL
_kernel32.WaitForSingleObject.argtypes = (wintypes.HANDLE, wintypes.DWORD)
_kernel32.WaitForSingleObject.restype = wintypes.DWORD
_kernel32.CloseHandle.argtypes = (wintypes.HANDLE,)
_kernel32.CloseHandle.restype = wintypes.BOOL


_status_handle: int | None = None
_stop_event: int | None = None
_status = _ServiceStatus()


def _publish(state: int, accepted: int, *, checkpoint: int = 0, wait_hint: int = 0) -> None:
    if _status_handle is None:
        return
    _status.service_type = _SERVICE_WIN32_OWN_PROCESS
    _status.current_state = state
    _status.controls_accepted = accepted
    _status.win32_exit_code = _NO_ERROR
    _status.service_specific_exit_code = 0
    _status.checkpoint = checkpoint
    _status.wait_hint = wait_hint
    if not _advapi32.SetServiceStatus(_status_handle, ctypes.byref(_status)):
        raise ctypes.WinError(ctypes.get_last_error())


def _control_handler_impl(control: int, event_type: int, event_data: int, context: int) -> int:
    del event_type, event_data, context
    if control in {_SERVICE_CONTROL_STOP, _SERVICE_CONTROL_SHUTDOWN}:
        _publish(_SERVICE_STOP_PENDING, 0, checkpoint=1, wait_hint=5000)
        if _stop_event is not None:
            _kernel32.SetEvent(_stop_event)
    elif control == _SERVICE_CONTROL_INTERROGATE:
        _publish(_status.current_state, _status.controls_accepted)
    return _NO_ERROR


_control_handler = _Handler(_control_handler_impl)


def _service_main_impl(argument_count: int, arguments: Any) -> None:
    del argument_count, arguments
    global _status_handle, _stop_event
    _status_handle = int(_advapi32.RegisterServiceCtrlHandlerExW(SERVICE_NAME, _control_handler, None))
    if not _status_handle:
        return
    _publish(_SERVICE_START_PENDING, 0, checkpoint=1, wait_hint=5000)
    _stop_event = int(_kernel32.CreateEventW(None, True, False, None))
    if not _stop_event:
        _publish(_SERVICE_STOPPED, 0)
        return
    try:
        _publish(
            _SERVICE_RUNNING,
            _SERVICE_ACCEPT_STOP | _SERVICE_ACCEPT_SHUTDOWN,
        )
        _kernel32.WaitForSingleObject(_stop_event, 0xFFFFFFFF)
        _publish(_SERVICE_STOPPED, 0)
    finally:
        _kernel32.CloseHandle(_stop_event)
        _stop_event = None


_service_main = _ServiceMain(_service_main_impl)


def run_service_dispatcher() -> int:
    """Enter the SCM dispatcher and remain authority-free until stopped."""
    table = (_ServiceTableEntry * 2)()
    table[0].name = SERVICE_NAME
    table[0].service_main = _service_main
    table[1].name = None
    if not _advapi32.StartServiceCtrlDispatcherW(table):
        error = ctypes.get_last_error()
        sys.stderr.write(f"StartServiceCtrlDispatcherW failed ({error})\n")
        return 78
    return 0


def self_test() -> dict[str, object]:
    return {
        "activation_authority": False,
        "accepted_commands": ["interrogate", "shutdown", "stop"],
        "schema": "galaxy.singularity-service-self-test/v1",
        "service_state": "stopped",
    }


def main(argv: Sequence[str] | None = None) -> int:
    arguments = list(sys.argv[1:] if argv is None else argv)
    if arguments == ["--self-test"]:
        sys.stdout.write(json.dumps(self_test(), sort_keys=True, separators=(",", ":")) + "\n")
        return 0
    if arguments == ["--service"]:
        return run_service_dispatcher()
    sys.stderr.write("only --service and --self-test are available\n")
    return 78


if __name__ == "__main__":
    raise SystemExit(main())
