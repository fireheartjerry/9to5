def _environment_block(environment: Mapping[str, str]) -> ctypes.Array[ctypes.c_wchar]:
    entries: list[str] = []
    for key, value in sorted(environment.items(), key=lambda item: item[0].upper()):
        if not key or "=" in key or "\0" in key or "\0" in value:
            raise RestrictedProcessError("environment contains an invalid entry")
        entries.append(f"{key}={value}")
    raw = "\0".join(entries) + "\0\0"
    return ctypes.create_unicode_buffer(raw, len(raw))


@dataclasses.dataclass
class RestrictedProcess:
    process_id: int
    _process_handle: int
    _thread_handle: int
    _suspended: bool
    _closed: bool = False

    def resume(self) -> None:
        if self._closed or not self._suspended:
            raise RestrictedProcessError("process is not suspended")
        previous = _kernel32.ResumeThread(self._thread_handle)
        if previous != 1:
            raise ctypes.WinError(ctypes.get_last_error())
        self._suspended = False

    def wait(self, timeout_seconds: float) -> int:
        milliseconds = max(0, min(0xFFFFFFFE, int(timeout_seconds * 1000)))
        result = _kernel32.WaitForSingleObject(self._process_handle, milliseconds)
        if result == _WAIT_TIMEOUT:
            raise TimeoutError(f"restricted process {self.process_id} did not exit")
        if result != 0:
            raise ctypes.WinError(ctypes.get_last_error())
        exit_code = wintypes.DWORD()
        if not _kernel32.GetExitCodeProcess(self._process_handle, ctypes.byref(exit_code)):
            raise ctypes.WinError(ctypes.get_last_error())
        return int(exit_code.value)

    def terminate(self, exit_code: int = 1) -> None:
        if self._closed:
            return
        _kernel32.TerminateProcess(self._process_handle, exit_code)
        _kernel32.WaitForSingleObject(self._process_handle, 5000)

    def close(self) -> None:
        if self._closed:
            return
        _kernel32.CloseHandle(self._thread_handle)
        _kernel32.CloseHandle(self._process_handle)
        self._closed = True


