def create_restricted_process(
    command: Sequence[str],
    *,
    cwd: Path,
    environment: Mapping[str, str],
    suspended: bool,
) -> RestrictedProcess:
    """Create a non-elevated restricted descendant with no inherited handles."""
    if not command or not Path(command[0]).is_absolute():
        raise RestrictedProcessError("restricted command needs an absolute executable")
    resolved_cwd = Path(cwd).resolve(strict=True)
    if not resolved_cwd.is_dir():
        raise RestrictedProcessError("restricted process cwd must be a directory")
    current_token = wintypes.HANDLE()
    restricted_token = wintypes.HANDLE()
    access = _TOKEN_ASSIGN_PRIMARY | _TOKEN_DUPLICATE | _TOKEN_QUERY
    if not _advapi32.OpenProcessToken(_kernel32.GetCurrentProcess(), access, ctypes.byref(current_token)):
        raise ctypes.WinError(ctypes.get_last_error())
    try:
        required = wintypes.DWORD()
        _advapi32.GetTokenInformation(
            current_token,
            1,
            None,
            0,
            ctypes.byref(required),  # TokenUser
        )
        if not required.value:
            raise ctypes.WinError(ctypes.get_last_error())
        token_user_buffer = ctypes.create_string_buffer(required.value)
        if not _advapi32.GetTokenInformation(
            current_token,
            1,
            token_user_buffer,
            required.value,
            ctypes.byref(required),
        ):
            raise ctypes.WinError(ctypes.get_last_error())
        token_user = ctypes.cast(token_user_buffer, ctypes.POINTER(_TokenUser)).contents
        restricting_sid = _SidAndAttributes(token_user.user.sid, 0)
        if not _advapi32.CreateRestrictedToken(
            current_token,
            _DISABLE_MAX_PRIVILEGE,
            0,
            None,
            0,
            None,
            1,
            ctypes.byref(restricting_sid),
            ctypes.byref(restricted_token),
        ):
            raise ctypes.WinError(ctypes.get_last_error())
        command_line = ctypes.create_unicode_buffer(subprocess.list2cmdline(list(command)))
        environment_block = _environment_block(environment)
        startup = _StartupInfo()
        startup.cb = ctypes.sizeof(startup)
        information = _ProcessInformation()
        flags = _CREATE_UNICODE_ENVIRONMENT | _CREATE_NO_WINDOW
        if suspended:
            flags |= _CREATE_SUSPENDED
        if not _advapi32.CreateProcessAsUserW(
            restricted_token,
            str(Path(command[0]).resolve(strict=True)),
            command_line,
            None,
            None,
            False,
            flags,
            ctypes.cast(environment_block, ctypes.c_void_p),
            str(resolved_cwd),
            ctypes.byref(startup),
            ctypes.byref(information),
        ):
            error = ctypes.get_last_error()
            raise RestrictedProcessError(error, f"CreateProcessAsUserW refused restricted child ({error})")
        return RestrictedProcess(
            int(information.process_id),
            int(information.process),
            int(information.thread),
            suspended,
        )
    finally:
        if restricted_token:
            _kernel32.CloseHandle(restricted_token)
        if current_token:
            _kernel32.CloseHandle(current_token)
