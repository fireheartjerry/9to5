def _digest(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def _is_reparse(path: Path) -> bool:
    if path.is_symlink():
        return True
    if os.name != "nt":
        return False
    # pathlib did not expose junction detection until newer Python releases.
    import ctypes

    attributes = ctypes.windll.kernel32.GetFileAttributesW(str(path))
    if attributes == 0xFFFFFFFF:
        return False
    return bool(attributes & 0x400)  # FILE_ATTRIBUTE_REPARSE_POINT


def _assert_no_reparse(path: Path, label: str) -> None:
    absolute = Path(os.path.abspath(path))
    parts = absolute.parts
    current = Path(parts[0])
    for component in parts[1:]:
        current /= component
        if current.exists() and _is_reparse(current):
            raise RuntimeClosureUnavailable(f"{label}: reparse point refused: {current}")


def _assert_beneath(path: Path, root: Path, label: str, error_type=RuntimeClosureUnavailable) -> None:
    try:
        path.relative_to(root)
    except ValueError as exc:
        raise error_type(f"{label}: path escapes sealed root") from exc


def _resolved_regular_file(path: Path, root: Path, label: str) -> Path:
    _assert_no_reparse(path, label)
    candidate = Path(path).resolve(strict=True)
    _assert_beneath(candidate, root, label)
    try:
        mode = candidate.stat().st_mode
    except OSError as exc:
        raise RuntimeClosureUnavailable(f"{label}: file unavailable") from exc
    if not stat.S_ISREG(mode):
        raise RuntimeClosureUnavailable(f"{label}: regular file required")
    return candidate


def _resolved_directory(path: Path, root: Path, label: str) -> Path:
    _assert_no_reparse(path, label)
    try:
        candidate = Path(path).resolve(strict=True)
    except OSError as exc:
        raise RuntimeClosureUnavailable(f"{label}: directory unavailable") from exc
    _assert_beneath(candidate, root, label)
    if not candidate.is_dir():
        raise RuntimeClosureUnavailable(f"{label}: directory required")
    return candidate


def _valid_digest(value: str, label: str, error_type=RuntimeClosureUnavailable) -> str:
    if not isinstance(value, str) or _SHA256.fullmatch(value) is None:
        raise error_type(f"{label}: invalid sha256 digest")
    return value


def select_verified_runtime(
    manifest: ControllerRuntimeManifest, *, no_follow: bool = True
) -> VerifiedControllerRuntime:
    """Verify and select a fully declared, isolated controller runtime."""
    if manifest.schema_version != 1:
        raise RuntimeClosureUnavailable("unsupported runtime manifest schema")
    if not no_follow:
        raise RuntimeClosureUnavailable("no-follow verification is mandatory")
    if manifest.network_allowed or manifest.ambient_site_packages_allowed:
        raise RuntimeClosureUnavailable("runtime isolation policy is not closed")
    if tuple(manifest.isolated_flags) != ("-I", "-S"):
        raise RuntimeClosureUnavailable("exact isolated interpreter flags are required")
    if not manifest.leaves:
        raise RuntimeClosureUnavailable("runtime closure is empty")

    interpreter_parent = Path(os.path.abspath(manifest.interpreter)).parent
    _assert_no_reparse(interpreter_parent, "sealed root")
    try:
        sealed_root = interpreter_parent.resolve(strict=True)
    except OSError as exc:
        raise RuntimeClosureUnavailable("sealed root unavailable") from exc

    verified: dict[Path, str] = {}
    ordered: list[Path] = []
    for category, leaves in manifest.leaves.items():
        if not isinstance(category, str) or not category or not leaves:
            raise RuntimeClosureUnavailable("runtime category is malformed or empty")
        for leaf in leaves:
            expected = _valid_digest(leaf.sha256, category)
            try:
                resolved = _resolved_regular_file(leaf.path, sealed_root, category)
            except (OSError, RuntimeError) as exc:
                if isinstance(exc, RuntimeClosureUnavailable):
                    raise
                raise RuntimeClosureUnavailable(f"{category}: file unavailable") from exc
            observed = _digest(resolved)
            if observed != expected:
                raise RuntimeClosureUnavailable(f"{category}: sha256 mismatch")
            prior = verified.get(resolved)
            if prior is not None and prior != expected:
                raise RuntimeClosureUnavailable(f"{category}: conflicting duplicate leaf")
            if prior is None:
                ordered.append(resolved)
                verified[resolved] = expected

    interpreter = _resolved_regular_file(manifest.interpreter, sealed_root, "interpreter")
    if interpreter not in verified:
        raise RuntimeClosureUnavailable("interpreter is outside the declared closure")
    return VerifiedControllerRuntime(
        interpreter=interpreter,
        isolated_flags=tuple(manifest.isolated_flags),
        sealed_root=sealed_root,
        resolved_paths=tuple(ordered),
        verified_hashes=verified,
    )


def require_offline_activation_artifacts(
    records: Sequence[ActivationImageRecord],
    *,
    builder: Callable[[], object] | None = None,
    puller: Callable[[], object] | None = None,
) -> Sequence[ActivationImageRecord]:
    """Require artifacts without ever invoking a build or network fallback."""
    _ = builder, puller
    if not records:
        raise OfflineActivationArtifactsUnavailable("offline activation closure is absent")
    return records


def _activation_file(path: Path, label: str) -> Path:
    try:
        _assert_no_reparse(path, label)
        resolved = Path(path).resolve(strict=True)
        if not resolved.is_file():
            raise OSError("not a regular file")
        return resolved
    except (OSError, RuntimeClosureUnavailable) as exc:
        raise OfflineActivationArtifactsUnavailable(f"{label}: archive unavailable") from exc


def verify_activation_images(
    records: Sequence[ActivationImageRecord],
    *,
    network_allowed: bool = False,
    allow_engine_build: bool = False,
    allow_pull: bool = False,
    builder: Callable[[], object] | None = None,
    puller: Callable[[], object] | None = None,
) -> ActivationImageVerificationReport:
    """Verify preseeded image archives; engine and network fallbacks are forbidden."""
    _ = builder, puller
    if network_allowed or allow_engine_build or allow_pull:
        raise OfflineActivationArtifactsUnavailable("activation must use offline preseeded images")
    require_offline_activation_artifacts(records)
    declared_roles = [record.role for record in records]
    if len(declared_roles) != len(set(declared_roles)):
        raise OfflineActivationArtifactsUnavailable("duplicate activation role")
    if set(declared_roles) != ACTIVATION_IMAGE_ROLES:
        raise OfflineActivationArtifactsUnavailable("exact nine-role activation image closure is required")
    roles: set[str] = set()
    for record in records:
        if not record.role:
            raise OfflineActivationArtifactsUnavailable("empty activation role")
        roles.add(record.role)
        archive = _activation_file(record.archive, record.role)
        expected_archive = _valid_digest(
            record.archive_sha256, "archive", OfflineActivationArtifactsUnavailable
        )
        if _digest(archive) != expected_archive:
            raise OfflineActivationArtifactsUnavailable(f"{record.role}: archive sha256 mismatch")
        declared: Iterable[tuple[str, str]] = (
            ("manifest", record.manifest_digest),
            ("config", record.config_digest),
            *(("layer", value) for value in record.layer_digests),
            ("base", record.base_digest),
            ("toolchain", record.toolchain_digest),
            ("package_manifest", record.package_manifest_digest),
            ("sbom", record.sbom_digest),
            ("runtime", record.runtime_digest),
            ("security_profile", record.security_profile_digest),
            ("base_image", record.base_image_digest),
            ("dockerfile", record.dockerfile_sha256),
        )
        if not record.layer_digests:
            raise OfflineActivationArtifactsUnavailable(f"{record.role}: layer closure is empty")
        for label, digest in declared:
            _valid_digest(digest, label, OfflineActivationArtifactsUnavailable)
        observed = _inspect_oci_archive(archive)
        comparisons: tuple[tuple[str, object, object], ...] = (
            ("manifest", observed.manifest_digest, record.manifest_digest),
            ("config", observed.config_digest, record.config_digest),
            ("layer", observed.layer_digests, tuple(record.layer_digests)),
            ("base", observed.closure_digests["base"], record.base_digest),
            ("toolchain", observed.closure_digests["toolchain"], record.toolchain_digest),
            (
                "package_manifest",
                observed.closure_digests["package_manifest"],
                record.package_manifest_digest,
            ),
            ("sbom", observed.closure_digests["sbom"], record.sbom_digest),
            ("runtime", observed.closure_digests["runtime"], record.runtime_digest),
            (
                "security_profile",
                observed.closure_digests["security_profile"],
                record.security_profile_digest,
            ),
        )
        for label, observed_value, expected_value in comparisons:
            if observed_value != expected_value:
                raise OfflineActivationArtifactsUnavailable(
                    f"{record.role}: {label} digest differs from activation lock"
                )
        runtime_document = observed.closure_documents["runtime"]
        base_document = observed.closure_documents["base"]
        toolchain_document = observed.closure_documents["toolchain"]
        security_document = observed.closure_documents["security_profile"]
        supported_roles = runtime_document.get("supported_roles")
        if (
            not record.physical_image
            or runtime_document.get("physical_image") != record.physical_image
            or security_document.get("physical_image") != record.physical_image
            or not isinstance(supported_roles, list)
            or record.role not in supported_roles
            or base_document.get("manifest_digest") != record.base_image_digest
            or toolchain_document.get("dockerfile_sha256") != record.dockerfile_sha256
        ):
            raise OfflineActivationArtifactsUnavailable(
                f"{record.role}: semantic image/role/source binding mismatch"
            )
    return ActivationImageVerificationReport(roles=roles, every_byte_verified=True)


def _safe_archive_parts(name: str) -> tuple[str, ...]:
    if not name or "\x00" in name or "\\" in name:
        raise OfflineActivationArtifactsUnavailable("archive: unsafe member name")
    if name.startswith("/") or re.match(r"^[A-Za-z]:", name):
        raise OfflineActivationArtifactsUnavailable("archive: unsafe member name")
    canonical = name[:-1] if name.endswith("/") else name
    parts = tuple(canonical.split("/"))
    if not parts or any(part in ("", ".", "..") for part in parts):
        raise OfflineActivationArtifactsUnavailable("archive: unsafe member name")
    return parts


def _inspect_oci_archive(archive: Path) -> OciLayoutInspection:
    """Extract an uncompressed OCI archive without following archive-controlled links."""
    with tempfile.TemporaryDirectory(prefix="galaxy-oci-inspect-") as temporary:
        root = Path(temporary)
        try:
            bundle = tarfile.open(archive, mode="r:")
        except (OSError, tarfile.TarError) as exc:
            raise OfflineActivationArtifactsUnavailable("archive: uncompressed OCI tar required") from exc
        with bundle:
            members = bundle.getmembers()
            if not members or len(members) > _MAX_OCI_ARCHIVE_MEMBERS:
                raise OfflineActivationArtifactsUnavailable("archive: unsafe member count")
            total_size = sum(member.size for member in members)
            if total_size < 0 or total_size > _MAX_OCI_ARCHIVE_BYTES:
                raise OfflineActivationArtifactsUnavailable("archive: declared size exceeds limit")
            seen: set[str] = set()
            for member in members:
                parts = _safe_archive_parts(member.name)
                collision_key = "/".join(parts).casefold()
                if collision_key in seen:
                    raise OfflineActivationArtifactsUnavailable("archive: duplicate or case-colliding member")
                seen.add(collision_key)
                destination = root.joinpath(*parts)
                if member.isdir():
                    destination.mkdir(parents=True, exist_ok=True)
                    continue
                if not member.isfile():
                    raise OfflineActivationArtifactsUnavailable(
                        "archive: links and special members are forbidden"
                    )
                destination.parent.mkdir(parents=True, exist_ok=True)
                source = bundle.extractfile(member)
                if source is None:
                    raise OfflineActivationArtifactsUnavailable("archive: regular member is unreadable")
                copied = 0
                try:
                    with destination.open("xb") as output:
                        while True:
                            block = source.read(1024 * 1024)
                            if not block:
                                break
                            copied += len(block)
                            if copied > member.size:
                                raise OfflineActivationArtifactsUnavailable(
                                    "archive: member exceeds declared size"
                                )
                            output.write(block)
                finally:
                    source.close()
                if copied != member.size:
                    raise OfflineActivationArtifactsUnavailable(
                        "archive: member is shorter than declared size"
                    )
        return inspect_oci_layout(root)


def inspect_oci_archive(archive: Path) -> OciLayoutInspection:
    """Inspect one bounded, link-free, uncompressed OCI archive."""

    try:
        _assert_no_reparse(archive, "archive")
        candidate = Path(archive).resolve(strict=True)
        metadata = candidate.stat()
    except (OSError, RuntimeClosureUnavailable) as exc:
        raise OfflineActivationArtifactsUnavailable("archive: unavailable") from exc
    if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
        raise OfflineActivationArtifactsUnavailable(
            "archive: single-link regular file required"
        )
    return _inspect_oci_archive(candidate)


def _descriptor_digest(value: object, label: str) -> str:
    if not isinstance(value, str) or not value.startswith("sha256:"):
        raise OfflineActivationArtifactsUnavailable(f"{label}: sha256 descriptor required")
    return _valid_digest(value[7:], label, OfflineActivationArtifactsUnavailable)


def _read_blob(layout: Path, digest: str, label: str, size: object | None = None) -> bytes:
    path = layout / "blobs" / "sha256" / digest
    try:
        _assert_no_reparse(path, label)
        raw = path.read_bytes()
    except (OSError, RuntimeClosureUnavailable) as exc:
        raise OfflineActivationArtifactsUnavailable(f"{label}: blob unavailable") from exc
    if hashlib.sha256(raw).hexdigest() != digest:
        raise OfflineActivationArtifactsUnavailable(f"{label}: blob digest mismatch")
    if size is not None and (not isinstance(size, int) or size < 0 or len(raw) != size):
        raise OfflineActivationArtifactsUnavailable(f"{label}: blob size mismatch")
    return raw


def _reject_json_duplicates(
    pairs: list[tuple[str, object]],
) -> dict[str, object]:
    value: dict[str, object] = {}
    for key, item in pairs:
        if key in value:
            raise OfflineActivationArtifactsUnavailable("JSON document contains a duplicate key")
        value[key] = item
    return value


def _json_object(raw: bytes, label: str) -> dict[str, object]:
    try:
        value = json.loads(
            raw.decode("utf-8", errors="strict"),
            object_pairs_hook=_reject_json_duplicates,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise OfflineActivationArtifactsUnavailable(f"{label}: invalid JSON") from exc
    if not isinstance(value, dict):
        raise OfflineActivationArtifactsUnavailable(f"{label}: JSON object required")
    return value


def _canonical_json(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")


def _semantic_digest(value: object, label: str) -> str:
    if not isinstance(value, str):
        raise OfflineActivationArtifactsUnavailable(f"{label}: digest is malformed")
    if value.startswith("sha256:"):
        value = value[7:]
    return _valid_digest(value, label, OfflineActivationArtifactsUnavailable)


def _semantic_list(value: object, label: str) -> list[object]:
    if not isinstance(value, list) or not value:
        raise OfflineActivationArtifactsUnavailable(f"{label}: nonempty list required")
    return value


def _validate_sha1dc_binding(
    *,
    physical_image: str,
    base_manifest: str,
    toolchain: Mapping[str, object],
    runtime: Mapping[str, object],
) -> None:
    toolchain_has_oracle = "sha1dc_oracle" in toolchain
    runtime_has_oracle = "sha1dc_oracle" in runtime
    if physical_image not in _SHA1DC_PHYSICAL_IMAGES:
        if toolchain_has_oracle or runtime_has_oracle:
            raise OfflineActivationArtifactsUnavailable(
                "SHA1DC: oracle binding is forbidden outside object-parser or reviewer"
            )
        return
    toolchain_binding = toolchain.get("sha1dc_oracle")
    runtime_binding = runtime.get("sha1dc_oracle")
    exact_fields = {
        "schema",
        "executable_path",
        "executable_sha256",
        "executable_size",
        "source_lock_sha256",
        "source_archive_sha256",
        "source_passport_sha256",
        "wrapper_sha256",
        "builder_base_digest",
        "runtime_base_digest",
        "reproducibility_runs",
        "self_test",
        "normal_object_corpus_count",
        "network_allowed",
    }
    if (
        not toolchain_has_oracle
        or not runtime_has_oracle
        or not isinstance(toolchain_binding, dict)
        or not isinstance(runtime_binding, dict)
        or toolchain_binding != runtime_binding
        or set(toolchain_binding) != exact_fields
    ):
        raise OfflineActivationArtifactsUnavailable(
            "SHA1DC: exact cross-resolved oracle binding is required"
        )
    for field in (
        "executable_sha256",
        "source_lock_sha256",
        "source_archive_sha256",
        "source_passport_sha256",
        "wrapper_sha256",
        "builder_base_digest",
        "runtime_base_digest",
    ):
        _semantic_digest(toolchain_binding.get(field), f"SHA1DC {field}")
    executable_size = toolchain_binding.get("executable_size")
    if (
        toolchain_binding.get("schema") != "galaxy.sha1dc-runtime-binding/v1"
        or toolchain_binding.get("executable_path") != "/opt/galaxy/galaxy-sha1dc"
        or not isinstance(executable_size, int)
        or isinstance(executable_size, bool)
        or not 1024 <= executable_size <= 16 * 1024 * 1024
        or toolchain_binding.get("builder_base_digest") != _SHA1DC_BUILDER_BASE
        or toolchain_binding.get("runtime_base_digest") != _SHA1DC_RUNTIME_BASE
        or base_manifest != _SHA1DC_RUNTIME_BASE
        or toolchain_binding.get("reproducibility_runs") != 2
        or toolchain_binding.get("self_test") != "collision-detected"
        or toolchain_binding.get("normal_object_corpus_count") != 4
        or toolchain_binding.get("network_allowed") is not False
    ):
        raise OfflineActivationArtifactsUnavailable("SHA1DC: offline oracle evidence differs")


def _validate_closure_semantics(
    *,
    config: Mapping[str, object],
    config_digest: str,
    layer_digests: Sequence[str],
    documents: Mapping[str, Mapping[str, object]],
) -> None:
    """Cross-resolve the six closure documents against the actual OCI image."""
    base = documents["base"]
    toolchain = documents["toolchain"]
    packages = documents["package_manifest"]
    sbom = documents["sbom"]
    runtime = documents["runtime"]
    security = documents["security_profile"]

    if (
        base.get("schema") != "galaxy.activation-base/v1"
        or base.get("kind") != "base"
        or base.get("architecture") != "amd64"
        or base.get("os") != "linux"
    ):
        raise OfflineActivationArtifactsUnavailable("base: semantic schema mismatch")
    base_manifest = _semantic_digest(base.get("manifest_digest"), "base")
    if base.get("reference") != f"python@sha256:{base_manifest}":
        raise OfflineActivationArtifactsUnavailable("base: reference is not digest-pinned")
    if base.get("image_id") != f"sha256:{base_manifest}":
        raise OfflineActivationArtifactsUnavailable("base: image ID differs from manifest")
    base_diff_ids = _semantic_list(base.get("rootfs_diff_ids"), "base")
    for value in base_diff_ids:
        _semantic_digest(value, "base rootfs")

    runtime_config = config.get("config")
    rootfs = config.get("rootfs")
    if (
        config.get("architecture") != "amd64"
        or config.get("os") != "linux"
        or not isinstance(runtime_config, dict)
        or not isinstance(rootfs, dict)
    ):
        raise OfflineActivationArtifactsUnavailable("config: platform closure is malformed")
    diff_ids = rootfs.get("diff_ids")
    if (
        rootfs.get("type") != "layers"
        or not isinstance(diff_ids, list)
        or len(diff_ids) <= len(base_diff_ids)
        or diff_ids[: len(base_diff_ids)] != base_diff_ids
    ):
        raise OfflineActivationArtifactsUnavailable("base: rootfs prefix mismatch")
    for value in diff_ids:
        _semantic_digest(value, "config rootfs")

    entrypoint = [
        "/usr/bin/env",
        "-i",
        "/usr/local/bin/python3",
        "-I",
        "-S",
        "/opt/galaxy/activation_image_entrypoint.py",
    ]
    labels = runtime_config.get("Labels")
    if (
        runtime_config.get("User") != "65532:65532"
        or runtime_config.get("WorkingDir") != "/empty"
        or runtime_config.get("Entrypoint") != entrypoint
        or runtime_config.get("Cmd") != ["image-canary"]
        or not isinstance(labels, dict)
        or labels.get("org.galaxy.image.authority") != "inactive"
    ):
        raise OfflineActivationArtifactsUnavailable("config: hardened runtime mismatch")

    exact_build_flags = {
        "--network=none",
        "--pull=false",
        "--provenance=false",
        "--sbom=false",
        "--platform=linux/amd64",
        "SOURCE_DATE_EPOCH=0",
    }
    boundary = toolchain.get("offline_builder")
    build_flags = toolchain.get("build_flags")
    if (
        toolchain.get("schema") != "galaxy.activation-toolchain/v1"
        or toolchain.get("kind") != "toolchain"
        or toolchain.get("base_manifest_digest") != base_manifest
        or not isinstance(boundary, dict)
        or set(boundary)
        != {
            "schema",
            "context",
            "daemon_endpoint",
            "docker_cli",
            "buildx_plugin",
            "wsl_host",
            "docker_server",
            "buildx",
            "ambient_environment",
            "routes",
            "default_route_absent",
        }
        or boundary.get("schema") != "galaxy.offline-docker-boundary/v1"
        or boundary.get("context") != "default"
        or boundary.get("daemon_endpoint") != "npipe:////./pipe/dockerDesktopLinuxEngine"
        or not _exact_host_tool(
            boundary.get("docker_cli"),
            path=r"C:\Program Files\Docker\Docker\resources\bin\docker.exe",
            sha256=_PINNED_DOCKER_CLI_SHA256,
            size=43267504,
        )
        or not _exact_host_tool(
            boundary.get("buildx_plugin"),
            path=r"C:\Program Files\Docker\Docker\resources\cli-plugins\docker-buildx.exe",
            sha256=_PINNED_BUILDX_SHA256,
            size=67032496,
        )
        or not _exact_host_tool(
            boundary.get("wsl_host"),
            path=r"C:\Windows\System32\wsl.exe",
            sha256=_PINNED_WSL_SHA256,
            size=278528,
        )
        or not isinstance(boundary.get("docker_server"), dict)
        or not boundary["docker_server"]
        or not isinstance(boundary.get("buildx"), str)
        or not boundary["buildx"].startswith("github.com/docker/buildx v0.34.0-desktop.1 ")
        or boundary.get("ambient_environment") != []
        or boundary.get("default_route_absent") is not True
        or not isinstance(boundary.get("routes"), list)
        or any(str(route).strip().startswith("default ") for route in boundary["routes"])
        or not isinstance(build_flags, list)
        or set(build_flags) != exact_build_flags
    ):
        raise OfflineActivationArtifactsUnavailable("toolchain: offline closure mismatch")
    dockerfile_digest = _semantic_digest(toolchain.get("dockerfile_sha256"), "toolchain dockerfile")
    if not isinstance(toolchain.get("runtime_tools"), dict) or not isinstance(
        toolchain.get("python_runtime"), dict
    ):
        raise OfflineActivationArtifactsUnavailable("toolchain: inventory is absent")

    package_values = packages.get("packages")
    if (
        packages.get("schema") != "galaxy.activation-package-manifest/v1"
        or packages.get("kind") != "package_manifest"
        or packages.get("base_manifest_digest") != base_manifest
        or packages.get("all_license_evidence_present") is not True
        or not isinstance(package_values, list)
        or not package_values
        or packages.get("package_count") != len(package_values)
    ):
        raise OfflineActivationArtifactsUnavailable("package_manifest: closure mismatch")
    for package in package_values:
        if not isinstance(package, dict) or not all(
            isinstance(package.get(field), str) for field in ("name", "version", "architecture")
        ):
            raise OfflineActivationArtifactsUnavailable("package_manifest: package malformed")
        license_evidence = package.get("license_evidence")
        if (
            not isinstance(license_evidence, dict)
            or not isinstance(license_evidence.get("path"), str)
            or not isinstance(license_evidence.get("size"), int)
            or isinstance(license_evidence.get("size"), bool)
            or license_evidence["size"] < 0
        ):
            raise OfflineActivationArtifactsUnavailable("package_manifest: license evidence is absent")
        _semantic_digest(license_evidence.get("sha256"), "package license")

    components = sbom.get("components")
    metadata = sbom.get("metadata")
    if (
        sbom.get("bomFormat") != "CycloneDX"
        or sbom.get("specVersion") != "1.5"
        or sbom.get("kind") != "sbom"
        or sbom.get("version") != 1
        or not isinstance(sbom.get("serialNumber"), str)
        or not isinstance(components, list)
        or len(components) != len(package_values)
        or not isinstance(metadata, dict)
        or not isinstance(metadata.get("component"), dict)
    ):
        raise OfflineActivationArtifactsUnavailable("sbom: package closure mismatch")

    physical_image = runtime.get("physical_image")
    supported_roles = runtime.get("supported_roles")
    if (
        runtime.get("schema") != "galaxy.activation-image-runtime/v1"
        or runtime.get("kind") != "runtime"
        or not isinstance(physical_image, str)
        or not physical_image
        or not isinstance(supported_roles, list)
        or not supported_roles
        or not all(isinstance(role, str) for role in supported_roles)
        or len(supported_roles) != len(set(supported_roles))
        or not set(supported_roles) <= ACTIVATION_IMAGE_ROLES
        or runtime.get("config_digest") != config_digest
        or runtime.get("layer_digests") != list(layer_digests)
        or runtime.get("entrypoint_path") != "/opt/galaxy/activation_image_entrypoint.py"
        or runtime.get("interpreter") != "/usr/local/bin/python3"
        or runtime.get("interpreter_flags") != ["-I", "-S"]
        or not isinstance(runtime.get("base_runtime"), dict)
    ):
        raise OfflineActivationArtifactsUnavailable("runtime: image binding mismatch")
    _semantic_digest(runtime.get("entrypoint_sha256"), "runtime entrypoint")
    if labels.get("org.galaxy.image.roles") != ",".join(supported_roles):
        raise OfflineActivationArtifactsUnavailable("runtime: role label mismatch")
    _validate_sha1dc_binding(
        physical_image=physical_image,
        base_manifest=base_manifest,
        toolchain=toolchain,
        runtime=runtime,
    )

    identity = security.get("identity")
    process = security.get("process")
    filesystem = security.get("filesystem")
    resources = security.get("resources")
    environment = security.get("environment")
    network_by_role = security.get("maximum_runtime_network_by_role")
    if (
        security.get("schema") != "galaxy.activation-security-profile/v1"
        or security.get("kind") != "security_profile"
        or security.get("physical_image") != physical_image
        or security.get("supported_roles") != supported_roles
        or security.get("config_digest") != config_digest
        or security.get("authority") != "inactive"
        or security.get("build_network") != "none"
        or security.get("canary_network") != "none"
        or not isinstance(network_by_role, dict)
        or set(network_by_role) != set(supported_roles)
        or identity != {"uid": 65532, "gid": 65532, "root_forbidden": True}
        or not isinstance(process, dict)
        or process.get("cap_drop") != ["ALL"]
        or process.get("no_new_privileges") is not True
        or process.get("restart") != "no"
        or process.get("pids_limit") != 64
        or not isinstance(filesystem, dict)
        or filesystem.get("rootfs") != "read_only"
        or filesystem.get("cwd") != "/empty"
        or filesystem.get("cwd_must_be_empty") is not True
        or not isinstance(resources, dict)
        or resources.get("memory_bytes") != 134217728
        or resources.get("nano_cpus") != 500000000
        or environment != {"entrypoint_clears_ambient": True, "inherited_keys": []}
        or security.get("manifest_binding") != "exact_sha256_required"
    ):
        raise OfflineActivationArtifactsUnavailable("security_profile: hardened boundary mismatch")
    sbom_component = metadata["component"]
    if sbom_component.get("name") != physical_image:
        raise OfflineActivationArtifactsUnavailable("sbom: physical image mismatch")

    # Keep these cross-resolved values live so a future schema edit cannot
    # accidentally reduce them to syntax-only validation.
    _ = dockerfile_digest


def inspect_oci_layout(layout: Path) -> OciLayoutInspection:
    """Open every descriptor reachable from one minimal OCI image layout."""
    try:
        _assert_no_reparse(layout, "layout")
        root = Path(layout).resolve(strict=True)
    except (OSError, RuntimeClosureUnavailable) as exc:
        raise OfflineActivationArtifactsUnavailable("layout: unavailable") from exc
    if not root.is_dir():
        raise OfflineActivationArtifactsUnavailable("layout: directory required")
    try:
        _assert_no_reparse(root / "oci-layout", "oci-layout")
        _assert_no_reparse(root / "index.json", "index")
        layout_marker = _json_object((root / "oci-layout").read_bytes(), "oci-layout")
        index = _json_object((root / "index.json").read_bytes(), "index")
    except (OSError, RuntimeClosureUnavailable) as exc:
        raise OfflineActivationArtifactsUnavailable("layout metadata unavailable") from exc
    if layout_marker.get("imageLayoutVersion") != "1.0.0":
        raise OfflineActivationArtifactsUnavailable("oci-layout: unsupported version")
    manifests = index.get("manifests")
    if index.get("schemaVersion") != 2 or not isinstance(manifests, list) or len(manifests) != 1:
        raise OfflineActivationArtifactsUnavailable("index: exactly one OCI manifest required")
    descriptor = manifests[0]
    if not isinstance(descriptor, dict):
        raise OfflineActivationArtifactsUnavailable("manifest: descriptor malformed")
    manifest_digest = _descriptor_digest(descriptor.get("digest"), "manifest")
    manifest = _json_object(_read_blob(root, manifest_digest, "manifest", descriptor.get("size")), "manifest")
    if manifest.get("schemaVersion") != 2:
        raise OfflineActivationArtifactsUnavailable("manifest: unsupported schema")

    config_descriptor = manifest.get("config")
    layers = manifest.get("layers")
    annotations = manifest.get("annotations")
    if not isinstance(config_descriptor, dict):
        raise OfflineActivationArtifactsUnavailable("config: descriptor malformed")
    if not isinstance(layers, list) or not layers:
        raise OfflineActivationArtifactsUnavailable("layer: closure empty")
    if not isinstance(annotations, dict):
        raise OfflineActivationArtifactsUnavailable("manifest: closure annotations absent")

    config_digest = _descriptor_digest(config_descriptor.get("digest"), "config")
    config_document = _json_object(
        _read_blob(root, config_digest, "config", config_descriptor.get("size")),
        "config",
    )
    layer_digests: list[str] = []
    for descriptor_value in layers:
        if not isinstance(descriptor_value, dict):
            raise OfflineActivationArtifactsUnavailable("layer: descriptor malformed")
        layer_digest = _descriptor_digest(descriptor_value.get("digest"), "layer")
        _read_blob(root, layer_digest, "layer", descriptor_value.get("size"))
        layer_digests.append(layer_digest)

    closure: dict[str, str] = {}
    closure_documents: dict[str, Mapping[str, object]] = {}
    for label in _CLOSURE_LEAVES:
        digest = _descriptor_digest(annotations.get(f"org.galaxy.{label}.digest"), label)
        raw = _read_blob(root, digest, label)
        document = _json_object(raw, label)
        if _canonical_json(document) != raw or document.get("kind") != label:
            raise OfflineActivationArtifactsUnavailable(f"{label}: canonical semantic document required")
        closure[label] = digest
        closure_documents[label] = document
    if len(set(closure.values())) != len(_CLOSURE_LEAVES):
        raise OfflineActivationArtifactsUnavailable("manifest: closure blobs are not distinct")
    _validate_closure_semantics(
        config=config_document,
        config_digest=config_digest,
        layer_digests=tuple(layer_digests),
        documents=closure_documents,
    )
    expected_files = {
        "oci-layout",
        "index.json",
        f"blobs/sha256/{manifest_digest}",
        f"blobs/sha256/{config_digest}",
        *(f"blobs/sha256/{digest}" for digest in layer_digests),
        *(f"blobs/sha256/{digest}" for digest in closure.values()),
    }
    actual_files: set[str] = set()
    for path in root.rglob("*"):
        relative = path.relative_to(root).as_posix()
        try:
            metadata = path.lstat()
        except OSError as exc:
            raise OfflineActivationArtifactsUnavailable("layout: member became unavailable") from exc
        if stat.S_ISLNK(metadata.st_mode):
            raise OfflineActivationArtifactsUnavailable("layout: link is forbidden")
        if stat.S_ISREG(metadata.st_mode):
            actual_files.add(relative)
        elif not stat.S_ISDIR(metadata.st_mode):
            raise OfflineActivationArtifactsUnavailable("layout: special member is forbidden")
    if actual_files != expected_files:
        raise OfflineActivationArtifactsUnavailable("layout: unreferenced or missing file in closure")
    return OciLayoutInspection(
        manifest_digest=manifest_digest,
        config_digest=config_digest,
        layer_digests=tuple(layer_digests),
        closure_digests=closure,
        config_document=config_document,
        closure_documents=closure_documents,
    )
