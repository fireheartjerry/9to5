@dataclass(frozen=True)
class VerifiedControllerRuntime:
    interpreter: Path
    isolated_flags: tuple[str, ...]
    sealed_root: Path
    resolved_paths: tuple[Path, ...]
    verified_hashes: Mapping[Path, str]

    def run_python_file(
        self,
        file: Path,
        *,
        cwd: Path,
        env: Mapping[str, str] | None,
        timeout: float,
    ) -> subprocess.CompletedProcess[str]:
        script = _resolved_regular_file(file, self.sealed_root, "entrypoint")
        if script not in self.verified_hashes:
            raise RuntimeClosureUnavailable("entrypoint is not in the verified closure")
        workdir = _resolved_directory(cwd, self.sealed_root, "working directory")
        # An input environment is deliberately not inherited.  The accepted
        # mapping exists only so callers can prove that ambient poison is inert.
        _ = env
        runtime_archives = [path for path in self.resolved_paths if path.suffix.lower() == ".zip"]
        if not runtime_archives:
            raise RuntimeClosureUnavailable("verified standard-library archive is absent")
        # ``sys.executable`` can itself be a CPython venv redirector on Windows.
        # __PYVENV_LAUNCHER__ binds that redirector to the verified copied path;
        # the in-memory bootstrap then replaces every import location before
        # target code runs.  A native copied interpreter follows the same path.
        child_env = {"__PYVENV_LAUNCHER__": str(self.interpreter)}
        import_paths = [str(path) for path in runtime_archives] + [str(self.sealed_root)]
        bootstrap = (
            "import sys;"
            f"sys.executable={str(self.interpreter)!r};"
            f"sys.prefix=sys.exec_prefix=sys.base_prefix=sys.base_exec_prefix={str(self.sealed_root)!r};"
            f"sys.path={import_paths!r};"
            f"p={str(script)!r};"
            "g={'__name__':'__main__','__file__':p,'__package__':None,'__cached__':None};"
            "exec(compile(open(p,'rb').read(),p,'exec'),g,g)"
        )
        return subprocess.run(
            [str(self.interpreter), *self.isolated_flags, "-c", bootstrap],
            cwd=workdir,
            env=child_env,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )


