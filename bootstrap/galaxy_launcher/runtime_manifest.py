def _exact_host_tool(
    value: object,
    *,
    path: str,
    sha256: str,
    size: int,
) -> bool:
    return (
        isinstance(value, dict)
        and set(value) == {"path", "sha256", "size"}
        and value.get("path") == path
        and value.get("sha256") == sha256
        and value.get("size") == size
    )


