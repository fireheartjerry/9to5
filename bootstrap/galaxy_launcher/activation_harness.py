def _execute_broker_observation(
    *,
    common: Mapping[str, Any],
    calls: tuple[BrokerCallSpec, ...],
    outcome: Mapping[str, Any],
    request_root: Path,
    response_root: Path,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any], dict[str, Any]]:
    deadline = time.monotonic() + 300
    reduced: list[dict[str, Any]] = []
    events: list[dict[str, Any]] = []
    for sequence, call in enumerate(calls):
        idempotency_key = _digest(
            {
                "call_digest": call.digest,
                "observation_id": common["observation_id"],
                "run_nonce": common["run_nonce"],
                "sequence": sequence,
            }
        )
        request = {
            **common,
            "message_type": "call",
            "sequence": sequence,
            "idempotency_key": idempotency_key,
            "operation": call.operation,
            "args": call.args,
            "call_digest": call.digest,
        }
        request_name = _digest(
            {
                "kind": "call",
                "observation_id": common["observation_id"],
                "run_nonce": common["run_nonce"],
                "sequence": sequence,
            }
        )
        response = _broker_exchange(
            request,
            request_root=request_root,
            response_root=response_root,
            request_name=request_name,
            deadline=deadline,
        )
        expected_response = {
            "status": "committed",
            "result": call.expected_result,
            "result_digest": _digest(call.expected_result),
            "replayed": False,
        }
        if set(response) != {
            "status",
            "result",
            "result_digest",
            "event_id",
            "event_hmac",
            "replayed",
        } or any(
            _canonical_json(response[key]) != _canonical_json(value)
            for key, value in expected_response.items()
        ):
            raise ActivationInvariantFailed("capability broker call was not exact")
        event_id = _hex_digest(response["event_id"], "broker.event_id")
        event_hmac = _hex_digest(response["event_hmac"], "broker.event_hmac")
        event = {
            "schema": 2,
            "run_nonce": common["run_nonce"],
            "challenge_digest": common["challenge_digest"],
            "observation_id": common["observation_id"],
            "observation_kind": common["observation_kind"],
            "invariant_id": common["invariant_id"],
            "observation_digest": common["observation_digest"],
            "case_digest": common["case_digest"],
            "sequence": sequence,
            "idempotency_key": idempotency_key,
            "operation": call.operation,
            "args_digest": _digest(call.args),
            "call_digest": call.digest,
            "result_digest": response["result_digest"],
            "runtime_profile_digest": common["runtime_profile_digest"],
            "runtime_identity": common["runtime_identity"],
            "disposition": "reference_result_committed",
            "event_id": event_id,
            "event_hmac": event_hmac,
        }
        event_without_auth = {
            key: value for key, value in event.items() if key not in {"event_id", "event_hmac"}
        }
        if _digest(event_without_auth) != event_id:
            raise ActivationInvariantFailed("broker event identity mismatch")
        events.append(event)
        reduced.append(
            {
                "operation": call.operation,
                "call_digest": call.digest,
                "args_digest": _digest(call.args),
                "result_digest": response["result_digest"],
                "broker_event_id": event_id,
                "broker_event_hmac": event_hmac,
                "disposition": "reference_result_committed",
                "run_nonce": common["run_nonce"],
                "challenge_digest": common["challenge_digest"],
            }
        )
    completion_request = {
        **common,
        "message_type": "complete",
        "completed_call_count": len(calls),
        "observed_outcome": dict(outcome),
        "result_digest": _digest(outcome),
    }
    completion_response = _broker_exchange(
        completion_request,
        request_root=request_root,
        response_root=response_root,
        request_name=_digest(
            {
                "kind": "complete",
                "observation_id": common["observation_id"],
                "run_nonce": common["run_nonce"],
            }
        ),
        deadline=deadline,
    )
    if (
        set(completion_response) != {"status", "event_id", "event_hmac", "replayed"}
        or completion_response["status"] != "accepted"
        or completion_response["replayed"] is not False
    ):
        raise ActivationInvariantFailed("capability broker completion was not exact")
    completion_id = _hex_digest(completion_response["event_id"], "broker.completion.event_id")
    completion_hmac = _hex_digest(completion_response["event_hmac"], "broker.completion.event_hmac")
    completion_event = {
        "schema": 2,
        "run_nonce": common["run_nonce"],
        "challenge_digest": common["challenge_digest"],
        "observation_id": common["observation_id"],
        "observation_kind": common["observation_kind"],
        "invariant_id": common["invariant_id"],
        "observation_digest": common["observation_digest"],
        "case_digest": common["case_digest"],
        "call_count": len(calls),
        "result_digest": _digest(outcome),
        "runtime_profile_digest": common["runtime_profile_digest"],
        "runtime_identity": common["runtime_identity"],
        "disposition": "exact_outcome_observed",
        "event_id": completion_id,
        "event_hmac": completion_hmac,
    }
    completion_without_auth = {
        key: value for key, value in completion_event.items() if key not in {"event_id", "event_hmac"}
    }
    if _digest(completion_without_auth) != completion_id:
        raise ActivationInvariantFailed("completion event identity mismatch")
    return reduced, events, completion_event, completion_response


def _dpapi_module(runtime: SealedHarnessRuntime) -> Any:
    return _load_adjacent_module("galaxy_sealed_activation_dpapi", runtime.dpapi_path)


def _receipt_seed(runtime: SealedHarnessRuntime) -> bytes:
    protected = runtime.receipt_private_key_path.read_bytes()
    public_key = runtime.receipt_public_key_path.read_bytes()
    entropy = _canonical_json(
        {
            "generation": runtime.generation,
            "acceptance_ledger_digest": PINNED_ACCEPTANCE_LEDGER_DIGEST,
            "receipt_public_key_digest": hashlib.sha256(public_key).hexdigest(),
        }
    )
    seed = _dpapi_module(runtime).unprotect_for_current_user(protected, entropy=entropy)
    if not isinstance(seed, bytes) or len(seed) != 32:
        raise ActivationInvariantFailed("receipt signing seed is malformed")
    if _crypto_module().public_key_from_seed(seed) != public_key:
        raise ActivationInvariantFailed("receipt signing key/public key mismatch")
    return seed


def _required_bindings(required: tuple[ReceiptSpec, ...], observation_id: str) -> list[dict[str, Any]]:
    bindings = []
    for contract in required:
        fields = {
            field: {
                "observation_id": observation_id,
                "requirement_digest": _digest(
                    {
                        "field": field,
                        "observation_id": observation_id,
                        "receipt_type": contract.type,
                    }
                ),
            }
            for field in contract.required_fields
        }
        content_digest = _digest({"type": contract.type, "observation_id": observation_id, "fields": fields})
        bindings.append(
            {
                "type": contract.type,
                "receipt_id": _digest({"content_digest": content_digest, "type": contract.type}),
                "fields": fields,
                "content_digest": content_digest,
            }
        )
    return bindings


def _signed_receipt(
    *,
    seed: bytes,
    acceptance: ClosedAcceptance,
    run_nonce: str,
    challenge_digest: str,
    reference_state_root: str,
    observation_id: str,
    result_digest: str,
    broker_evidence: list[dict[str, Any]],
    completion_event_id: str,
    required: tuple[ReceiptSpec, ...],
) -> dict[str, Any]:
    payload = {
        "schema": "galaxy.activation.observation-receipt/v2",
        "run_nonce": run_nonce,
        "challenge_digest": challenge_digest,
        "acceptance_ledger_digest": acceptance.ledger_digest,
        "runtime_profile_ledger_digest": acceptance.runtime_profile_ledger_digest,
        "runtime_digest": acceptance.runtime_digest,
        "reference_state_root": reference_state_root,
        "observation_id": observation_id,
        "result_digest": result_digest,
        "broker_evidence_root": _digest(broker_evidence),
        "completion_event_id": completion_event_id,
        "required_receipts": _required_bindings(required, observation_id),
    }
    signature = _crypto_module().sign(seed, _canonical_json(payload))
    encoded = base64.urlsafe_b64encode(signature).decode("ascii").rstrip("=")
    return {"signed_payload": payload, "signature_base64url": encoded}


