def _load_adjacent_module(name: str, path: Path) -> Any:
    existing = sys.modules.get(name)
    if existing is not None:
        return existing
    specification = importlib.util.spec_from_file_location(name, path)
    if specification is None or specification.loader is None:
        raise ActivationInvariantFailed(f"sealed module {name} is unavailable")
    module = importlib.util.module_from_spec(specification)
    sys.modules[name] = module
    specification.loader.exec_module(module)
    return module


def _crypto_module() -> Any:
    try:
        from . import activation_crypto

        return activation_crypto
    except ImportError:
        return _load_adjacent_module(
            "galaxy_sealed_activation_crypto",
            Path(__file__).resolve().with_name("activation_crypto.py"),
        )


def _expected_outcome(kind: str, observation: SubcaseSpec | ProbeSpec) -> dict[str, Any]:
    if kind == "subcase":
        if not isinstance(observation, SubcaseSpec):
            raise ActivationInvariantFailed("subcase type binding failed")
        return {
            "status": observation.expected.status,
            "state": observation.expected.state,
            "forbidden_effects_observed": [],
        }
    if not isinstance(observation, ProbeSpec):
        raise ActivationInvariantFailed("probe type binding failed")
    return {
        "expected_enforcement": observation.expected_enforcement,
        "enforced": True,
        "forbidden_effects_observed": [],
    }


def _observation_calls(
    observation: SubcaseSpec | ProbeSpec,
) -> tuple[BrokerCallSpec, ...]:
    if isinstance(observation, SubcaseSpec):
        return observation.broker_calls
    return observation.broker_operations


def _observation_index(
    acceptance: ClosedAcceptance,
) -> dict[str, tuple[str, ScenarioSpec, SubcaseSpec | ProbeSpec]]:
    result: dict[str, tuple[str, ScenarioSpec, SubcaseSpec | ProbeSpec]] = {}
    for case in acceptance.cases:
        for subcase in case.subcases:
            result[subcase.observation_id] = ("subcase", case, subcase)
        for probe in case.probes:
            result[probe.probe_id] = ("security_probe", case, probe)
    if len(result) != acceptance.observation_count:
        raise ActivationInvariantFailed("observation identity collision")
    return result


def _reference_state_root(
    acceptance: ClosedAcceptance,
    profiles: RuntimeProfileLedger,
) -> str:
    records = []
    for observation_id, (kind, case, observation) in sorted(_observation_index(acceptance).items()):
        if isinstance(observation, ProbeSpec):
            runtime_role = observation.runtime_role
            profile = profiles.profiles[profiles.role_assignments[runtime_role]]
            fault = None
        else:
            runtime_role = "activation_case_adapter"
            profile = profiles.profiles["controller_restricted_win32"]
            fault = dataclasses.asdict(observation.fault)
        records.append(
            {
                "observation_id": observation_id,
                "observation_kind": kind,
                "invariant_id": case.invariant_id,
                "observation_digest": observation.executable_digest,
                "preconditions": [dataclasses.asdict(item) for item in case.preconditions],
                "operation": dataclasses.asdict(case.operation),
                "fault": fault,
                "runtime_role": runtime_role,
                "runtime_profile_id": profile.profile_id,
                "runtime_profile_digest": profile.profile_digest,
                "calls": [dataclasses.asdict(call) for call in _observation_calls(observation)],
                "expected_outcome": _expected_outcome(
                    "subcase" if kind == "subcase" else "security_probe",
                    observation,
                ),
            }
        )
    return _digest(records)


def _parse_broker_evidence(
    value: object,
    *,
    calls: tuple[BrokerCallSpec, ...],
    run_nonce: str,
    challenge_digest: str,
    at: str,
) -> tuple[BrokerEvidence, ...]:
    values = _sequence(value, at)
    if len(values) != len(calls):
        raise ActivationInvariantFailed(f"{at}: broker call count mismatch")
    fields = {
        "operation",
        "call_digest",
        "args_digest",
        "result_digest",
        "broker_event_id",
        "broker_event_hmac",
        "disposition",
        "run_nonce",
        "challenge_digest",
    }
    result = []
    for index, (item, call) in enumerate(zip(values, calls, strict=True)):
        where = f"{at}[{index}]"
        record = _exact_keys(item, fields, where)
        expected = {
            "operation": call.operation,
            "call_digest": call.digest,
            "args_digest": _digest(call.args),
            "result_digest": _digest(call.expected_result),
            "disposition": "reference_result_committed",
            "run_nonce": run_nonce,
            "challenge_digest": challenge_digest,
        }
        if any(record[key] != expected[key] for key in expected):
            raise ActivationInvariantFailed(f"{where}: broker evidence binding mismatch")
        event_id = _hex_digest(record["broker_event_id"], f"{where}.broker_event_id")
        event_hmac = _hex_digest(record["broker_event_hmac"], f"{where}.broker_event_hmac")
        result.append(
            BrokerEvidence(
                operation=call.operation,
                call_digest=call.digest,
                args_digest=expected["args_digest"],
                result_digest=expected["result_digest"],
                broker_event_id=event_id,
                broker_event_hmac=event_hmac,
                disposition="reference_result_committed",
                run_nonce=run_nonce,
                challenge_digest=challenge_digest,
            )
        )
    return tuple(result)


def _decode_signature(value: object) -> bytes:
    text = _text(value, "receipt.signature_base64url")
    if "=" in text:
        raise ActivationInvariantFailed("receipt signature padding is forbidden")
    try:
        return base64.b64decode(
            text + "=" * (-len(text) % 4),
            altchars=b"-_",
            validate=True,
        )
    except (ValueError, TypeError) as exc:
        raise ActivationInvariantFailed("receipt signature is malformed") from exc


def _parse_receipt(
    value: object,
    *,
    acceptance: ClosedAcceptance,
    observation_id: str,
    result_digest: str,
    evidence: tuple[BrokerEvidence, ...],
    completion_event_id: str,
    run_nonce: str,
    challenge_digest: str,
    reference_state_root: str,
    required: tuple[ReceiptSpec, ...],
) -> VerifiedObservationReceipt:
    record = _exact_keys(value, {"signed_payload", "signature_base64url"}, "receipt")
    payload_fields = {
        "schema",
        "run_nonce",
        "challenge_digest",
        "acceptance_ledger_digest",
        "runtime_profile_ledger_digest",
        "runtime_digest",
        "reference_state_root",
        "observation_id",
        "result_digest",
        "broker_evidence_root",
        "completion_event_id",
        "required_receipts",
    }
    payload = _exact_keys(record["signed_payload"], payload_fields, "receipt.payload")
    evidence_root = _digest([dataclasses.asdict(item) for item in evidence])
    expected = {
        "schema": "galaxy.activation.observation-receipt/v2",
        "run_nonce": run_nonce,
        "challenge_digest": challenge_digest,
        "acceptance_ledger_digest": acceptance.ledger_digest,
        "runtime_profile_ledger_digest": acceptance.runtime_profile_ledger_digest,
        "runtime_digest": acceptance.runtime_digest,
        "reference_state_root": reference_state_root,
        "observation_id": observation_id,
        "result_digest": result_digest,
        "broker_evidence_root": evidence_root,
        "completion_event_id": completion_event_id,
    }
    if any(payload[key] != expected[key] for key in expected):
        raise ActivationInvariantFailed("receipt signed binding mismatch")
    raw_bindings = _sequence(payload["required_receipts"], "receipt.required_receipts", nonempty=False)
    if len(raw_bindings) != len(required):
        raise ActivationInvariantFailed("required receipt count mismatch")
    bindings: list[RequiredReceiptBinding] = []
    for index, (item, contract) in enumerate(zip(raw_bindings, required, strict=True)):
        at = f"receipt.required_receipts[{index}]"
        binding = _exact_keys(item, {"type", "receipt_id", "fields", "content_digest"}, at)
        fields = binding["fields"]
        if (
            binding["type"] != contract.type
            or not isinstance(fields, dict)
            or set(fields) != set(contract.required_fields)
            or any(value is None for value in fields.values())
        ):
            raise ActivationInvariantFailed(f"{at}: required field binding mismatch")
        content = {
            "type": contract.type,
            "observation_id": observation_id,
            "fields": fields,
        }
        content_digest = _digest(content)
        if binding["content_digest"] != content_digest or binding["receipt_id"] != _digest(
            {"content_digest": content_digest, "type": contract.type}
        ):
            raise ActivationInvariantFailed(f"{at}: receipt content digest mismatch")
        bindings.append(
            RequiredReceiptBinding(
                contract.type,
                binding["receipt_id"],
                dict(fields),
                content_digest,
            )
        )
    signature = _decode_signature(record["signature_base64url"])
    if not _crypto_module().verify(
        bytes.fromhex(acceptance.receipt_public_key),
        _canonical_json(payload),
        signature,
    ):
        raise ActivationInvariantFailed("receipt signature did not verify")
    return VerifiedObservationReceipt(
        authentication_verified=True,
        runtime_digest=acceptance.runtime_digest,
        acceptance_ledger_digest=acceptance.ledger_digest,
        runtime_profile_ledger_digest=acceptance.runtime_profile_ledger_digest,
        run_nonce=run_nonce,
        challenge_digest=challenge_digest,
        reference_state_root=reference_state_root,
        observation_id=observation_id,
        result_digest=result_digest,
        broker_evidence_root=evidence_root,
        completion_event_id=completion_event_id,
        required_receipts=tuple(bindings),
    )


class EvidenceReplayGuard:
    """One-use evidence admission, optionally durable across validator processes."""

    def __init__(self, database_path: Path | None = None):
        self._seen: set[str] = set()
        self._database_path = Path(database_path) if database_path else None

    def claim(self, identity: str) -> None:
        if self._database_path is None:
            if identity in self._seen:
                raise ActivationInvariantFailed("EvidenceReplay: report was already admitted")
            self._seen.add(identity)
            return
        self._database_path.parent.mkdir(parents=True, exist_ok=True)
        database = sqlite3.connect(self._database_path)
        try:
            database.execute("PRAGMA journal_mode=WAL")
            database.execute("PRAGMA synchronous=FULL")
            database.execute(
                "CREATE TABLE IF NOT EXISTS admitted_evidence ("
                "identity TEXT PRIMARY KEY, admitted_at TEXT NOT NULL) WITHOUT ROWID"
            )
            try:
                database.execute(
                    "INSERT INTO admitted_evidence VALUES (?, datetime('now'))",
                    (identity,),
                )
                database.commit()
            except sqlite3.IntegrityError as exc:
                raise ActivationInvariantFailed("EvidenceReplay: report was already admitted") from exc
        finally:
            database.close()


def validate_external_report(
    raw_report: Mapping[str, Any],
    *,
    acceptance: ClosedAcceptance,
    independent_observation: Mapping[str, Any],
    replay_guard: EvidenceReplayGuard | None = None,
) -> ValidatedExternalReport:
    """Validate every signed result against independent parent observation."""
    observation_fields = {
        "schema",
        "run_nonce",
        "challenge_digest",
        "acceptance_ledger_digest",
        "runtime_profile_ledger_digest",
        "reference_state_root",
        "network_connections",
        "changed_canaries",
        "created_forbidden_paths",
        "sibling_store_unchanged",
        "sibling_wal_present",
        "canary_digests",
        "broker_event_count",
        "broker_evidence_root",
        "completion_count",
        "completion_evidence_root",
        "incomplete_observations",
        "broker_violations",
        "observation_digest",
    }
    observed = _exact_keys(dict(independent_observation), observation_fields, "independent_observation")
    observed_digest = _digest({key: value for key, value in observed.items() if key != "observation_digest"})
    if observed["observation_digest"] != observed_digest:
        raise ActivationInvariantFailed("independent observation digest mismatch")
    if (
        observed["schema"] != 2
        or observed["acceptance_ledger_digest"] != acceptance.ledger_digest
        or observed["runtime_profile_ledger_digest"] != acceptance.runtime_profile_ledger_digest
        or observed["network_connections"] != 0
        or observed["changed_canaries"] != []
        or observed["created_forbidden_paths"] != []
        or observed["sibling_store_unchanged"] is not True
        or observed["sibling_wal_present"] is not True
        or observed["broker_event_count"] != acceptance.broker_call_count
        or observed["completion_count"] != acceptance.observation_count
        or observed["incomplete_observations"] != []
        or tuple(observed["broker_violations"]) != ()
    ):
        raise ActivationInvariantFailed("independent safety observation failed")

    report_fields = {
        "schema",
        "status",
        "run_nonce",
        "challenge_digest",
        "acceptance_ledger_digest",
        "runtime_profile_ledger_digest",
        "runtime_digest",
        "reference_state_root",
        "broker_evidence_root",
        "completion_evidence_root",
        "subcase_results",
        "probe_results",
        "report_digest",
    }
    report = _exact_keys(dict(raw_report), report_fields, "report")
    calculated_report_digest = _digest(
        {key: value for key, value in report.items() if key != "report_digest"}
    )
    if report["report_digest"] != calculated_report_digest:
        raise ActivationInvariantFailed("report digest mismatch")
    common = {
        "schema": "galaxy.activation.external-report/v2",
        "status": "passed_inactive",
        "run_nonce": observed["run_nonce"],
        "challenge_digest": observed["challenge_digest"],
        "acceptance_ledger_digest": acceptance.ledger_digest,
        "runtime_profile_ledger_digest": acceptance.runtime_profile_ledger_digest,
        "runtime_digest": acceptance.runtime_digest,
        "reference_state_root": observed["reference_state_root"],
        "broker_evidence_root": observed["broker_evidence_root"],
        "completion_evidence_root": observed["completion_evidence_root"],
    }
    for key, expected in common.items():
        if report[key] != expected:
            label = (
                "ChallengeBindingMismatch"
                if key in {"run_nonce", "challenge_digest"}
                else f"report {key} mismatch"
            )
            raise ActivationInvariantFailed(label)
    if not isinstance(report["subcase_results"], list) or not isinstance(report["probe_results"], list):
        raise ActivationInvariantFailed("report results must be arrays")
    index = _observation_index(acceptance)
    profiles = parse_runtime_profile_ledger(
        Path(_load_runtime()[0].runtime_profile_ledger_path).read_bytes(),
        expected_ledger_digest=acceptance.runtime_profile_ledger_digest,
        acceptance_ledger_digest=acceptance.ledger_digest,
    )
    if observed["reference_state_root"] != _reference_state_root(acceptance, profiles):
        raise ActivationInvariantFailed("reference state root mismatch")

    subcase_results: dict[str, SubcaseResult] = {}
    probe_results: dict[str, ProbeResult] = {}
    subcase_fields = {
        "observation_id",
        "invariant_id",
        "subcase_id",
        "case_digest",
        "subcase_digest",
        "operation_api",
        "operation_digest",
        "fault_digest",
        "status",
        "state",
        "forbidden_effects_observed",
        "broker_evidence",
        "completion_event_id",
        "completion_event_hmac",
        "result_digest",
        "receipt",
    }
    probe_fields = {
        "observation_id",
        "invariant_id",
        "operation_api",
        "probe_digest",
        "runtime_role",
        "runtime_profile_id",
        "runtime_profile_digest",
        "image_digest",
        "expected_enforcement",
        "enforced",
        "forbidden_effects_observed",
        "broker_evidence",
        "completion_event_id",
        "completion_event_hmac",
        "result_digest",
        "receipt",
    }

    for item_index, item in enumerate(report["subcase_results"]):
        at = f"subcase_results[{item_index}]"
        record = _exact_keys(item, subcase_fields, at)
        observation_id = _text(record["observation_id"], f"{at}.observation_id")
        entry = index.get(observation_id)
        if entry is None or entry[0] != "subcase" or observation_id in subcase_results:
            raise ActivationInvariantFailed(f"{at}: unknown or duplicate subcase")
        _, case, observation = entry
        if not isinstance(observation, SubcaseSpec):
            raise ActivationInvariantFailed(f"{at}: subcase type mismatch")
        outcome = _expected_outcome("subcase", observation)
        result_digest = _digest(outcome)
        expected_fields = {
            "invariant_id": case.invariant_id,
            "subcase_id": observation.subcase_id,
            "case_digest": case.executable_digest,
            "subcase_digest": observation.executable_digest,
            "operation_api": case.operation.api,
            "operation_digest": case.operation.digest,
            "fault_digest": observation.fault.digest,
            "status": outcome["status"],
            "state": outcome["state"],
            "forbidden_effects_observed": [],
            "result_digest": result_digest,
        }
        if any(
            _canonical_json(record[key]) != _canonical_json(value) for key, value in expected_fields.items()
        ):
            raise ActivationInvariantFailed(f"{at}: exact outcome binding mismatch")
        completion_id = _hex_digest(record["completion_event_id"], f"{at}.completion_event_id")
        completion_hmac = _hex_digest(record["completion_event_hmac"], f"{at}.completion_event_hmac")
        evidence = _parse_broker_evidence(
            record["broker_evidence"],
            calls=observation.broker_calls,
            run_nonce=report["run_nonce"],
            challenge_digest=report["challenge_digest"],
            at=f"{at}.broker_evidence",
        )
        receipt = _parse_receipt(
            record["receipt"],
            acceptance=acceptance,
            observation_id=observation_id,
            result_digest=result_digest,
            evidence=evidence,
            completion_event_id=completion_id,
            run_nonce=report["run_nonce"],
            challenge_digest=report["challenge_digest"],
            reference_state_root=report["reference_state_root"],
            required=case.required_receipts,
        )
        subcase_results[observation_id] = SubcaseResult(
            observation_id,
            case.invariant_id,
            observation.subcase_id,
            case.executable_digest,
            observation.executable_digest,
            case.operation.api,
            case.operation.digest,
            observation.fault.digest,
            observation.expected.status,
            observation.expected.state,
            (),
            evidence,
            completion_id,
            completion_hmac,
            result_digest,
            receipt,
        )

    for item_index, item in enumerate(report["probe_results"]):
        at = f"probe_results[{item_index}]"
        record = _exact_keys(item, probe_fields, at)
        observation_id = _text(record["observation_id"], f"{at}.observation_id")
        entry = index.get(observation_id)
        if entry is None or entry[0] != "security_probe" or observation_id in probe_results:
            raise ActivationInvariantFailed(f"{at}: unknown or duplicate probe")
        _, case, observation = entry
        if not isinstance(observation, ProbeSpec):
            raise ActivationInvariantFailed(f"{at}: probe type mismatch")
        profile = profiles.profiles[profiles.role_assignments[observation.runtime_role]]
        outcome = _expected_outcome("security_probe", observation)
        result_digest = _digest(outcome)
        image_digest = (
            acceptance.image_digests[profile.image_role]
            if profile.execution_kind == "hardened_container" and profile.image_role
            else None
        )
        expected_fields = {
            "invariant_id": case.invariant_id,
            "operation_api": case.operation.api,
            "probe_digest": observation.executable_digest,
            "runtime_role": observation.runtime_role,
            "runtime_profile_id": profile.profile_id,
            "runtime_profile_digest": profile.profile_digest,
            "image_digest": image_digest,
            "expected_enforcement": observation.expected_enforcement,
            "enforced": True,
            "forbidden_effects_observed": [],
            "result_digest": result_digest,
        }
        if any(
            _canonical_json(record[key]) != _canonical_json(value) for key, value in expected_fields.items()
        ):
            raise ActivationInvariantFailed(f"{at}: exact probe binding mismatch")
        completion_id = _hex_digest(record["completion_event_id"], f"{at}.completion_event_id")
        completion_hmac = _hex_digest(record["completion_event_hmac"], f"{at}.completion_event_hmac")
        evidence = _parse_broker_evidence(
            record["broker_evidence"],
            calls=observation.broker_operations,
            run_nonce=report["run_nonce"],
            challenge_digest=report["challenge_digest"],
            at=f"{at}.broker_evidence",
        )
        receipt = _parse_receipt(
            record["receipt"],
            acceptance=acceptance,
            observation_id=observation_id,
            result_digest=result_digest,
            evidence=evidence,
            completion_event_id=completion_id,
            run_nonce=report["run_nonce"],
            challenge_digest=report["challenge_digest"],
            reference_state_root=report["reference_state_root"],
            required=(),
        )
        probe_results[observation_id] = ProbeResult(
            observation_id,
            case.invariant_id,
            case.operation.api,
            observation.executable_digest,
            observation.runtime_role,
            profile.profile_id,
            profile.profile_digest,
            image_digest,
            observation.expected_enforcement,
            True,
            (),
            evidence,
            completion_id,
            completion_hmac,
            result_digest,
            receipt,
        )

    expected_subcases = {item.observation_id for case in acceptance.cases for item in case.subcases}
    expected_probes = {item.probe_id for case in acceptance.cases for item in case.probes}
    if set(subcase_results) != expected_subcases or set(probe_results) != expected_probes:
        raise ActivationInvariantFailed("report observation closure is incomplete")
    identity = _digest(
        {
            "run_nonce": report["run_nonce"],
            "challenge_digest": report["challenge_digest"],
            "report_digest": calculated_report_digest,
            "observation_digest": observed_digest,
        }
    )
    if replay_guard is not None:
        replay_guard.claim(identity)
    return ValidatedExternalReport(
        subcase_results=subcase_results,
        probe_results=probe_results,
        executed_subcase_keys=frozenset(
            (case.task, case.invariant_id, item.subcase_id)
            for case in acceptance.cases
            for item in case.subcases
        ),
        executed_probe_ids=tuple(sorted(probe_results)),
        report_digest=calculated_report_digest,
    )


