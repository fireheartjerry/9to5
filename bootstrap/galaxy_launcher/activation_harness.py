def _accept_probe_worker_result(
    *,
    raw: object,
    runtime: SealedHarnessRuntime,
    acceptance: ClosedAcceptance,
    challenge: Mapping[str, Any],
    case: ScenarioSpec,
    probe: ProbeSpec,
    profile: RuntimeProfileSpec,
    common: Mapping[str, Any],
    seed: bytes,
    reference_state_root: str,
) -> _ExecutionEvidence:
    result = _exact_keys(
        raw,
        {
            "broker_evidence",
            "completion_event_id",
            "completion_event_hmac",
            "observed_outcome",
        },
        f"probe_result.{probe.probe_id}",
    )
    outcome = _expected_outcome("security_probe", probe)
    if _canonical_json(result["observed_outcome"]) != _canonical_json(outcome):
        raise ActivationInvariantFailed("probe worker outcome mismatch")
    reduced_values = _sequence(result["broker_evidence"], f"probe_result.{probe.probe_id}.broker_evidence")
    if len(reduced_values) != len(probe.broker_operations):
        raise ActivationInvariantFailed("probe broker evidence count mismatch")
    reduced: list[dict[str, Any]] = []
    events: list[dict[str, Any]] = []
    reduced_fields = {
        "operation",
        "call_digest",
        "args_digest",
        "result_digest",
        "broker_event_id",
        "broker_event_hmac",
        "disposition",
        "run_nonce",
        "challenge_digest",
    }
    for sequence, (item, call) in enumerate(zip(reduced_values, probe.broker_operations, strict=True)):
        at = f"probe_result.{probe.probe_id}.broker_evidence[{sequence}]"
        record = _exact_keys(item, reduced_fields, at)
        expected = {
            "operation": call.operation,
            "call_digest": call.digest,
            "args_digest": _digest(call.args),
            "result_digest": _digest(call.expected_result),
            "disposition": "reference_result_committed",
            "run_nonce": challenge["run_nonce"],
            "challenge_digest": challenge["challenge_digest"],
        }
        if any(record[key] != value for key, value in expected.items()):
            raise ActivationInvariantFailed(f"{at}: broker binding mismatch")
        event_id = _hex_digest(record["broker_event_id"], f"{at}.event_id")
        event_hmac = _hex_digest(record["broker_event_hmac"], f"{at}.event_hmac")
        idempotency_key = _digest(
            {
                "call_digest": call.digest,
                "observation_id": probe.probe_id,
                "run_nonce": challenge["run_nonce"],
                "sequence": sequence,
            }
        )
        event = {
            "schema": 2,
            "run_nonce": challenge["run_nonce"],
            "challenge_digest": challenge["challenge_digest"],
            "observation_id": probe.probe_id,
            "observation_kind": "security_probe",
            "invariant_id": case.invariant_id,
            "observation_digest": probe.executable_digest,
            "case_digest": case.executable_digest,
            "sequence": sequence,
            "idempotency_key": idempotency_key,
            "operation": call.operation,
            "args_digest": _digest(call.args),
            "call_digest": call.digest,
            "result_digest": _digest(call.expected_result),
            "runtime_profile_digest": profile.profile_digest,
            "runtime_identity": common["runtime_identity"],
            "disposition": "reference_result_committed",
            "event_id": event_id,
            "event_hmac": event_hmac,
        }
        if (
            _digest({key: value for key, value in event.items() if key not in {"event_id", "event_hmac"}})
            != event_id
        ):
            raise ActivationInvariantFailed("probe broker event identity mismatch")
        reduced.append(dict(record))
        events.append(event)
    completion_id = _hex_digest(result["completion_event_id"], "probe completion event ID")
    completion_hmac = _hex_digest(result["completion_event_hmac"], "probe completion event HMAC")
    result_digest = _digest(outcome)
    completion_event = {
        "schema": 2,
        "run_nonce": challenge["run_nonce"],
        "challenge_digest": challenge["challenge_digest"],
        "observation_id": probe.probe_id,
        "observation_kind": "security_probe",
        "invariant_id": case.invariant_id,
        "observation_digest": probe.executable_digest,
        "case_digest": case.executable_digest,
        "call_count": len(probe.broker_operations),
        "result_digest": result_digest,
        "runtime_profile_digest": profile.profile_digest,
        "runtime_identity": common["runtime_identity"],
        "disposition": "exact_outcome_observed",
        "event_id": completion_id,
        "event_hmac": completion_hmac,
    }
    if (
        _digest(
            {key: value for key, value in completion_event.items() if key not in {"event_id", "event_hmac"}}
        )
        != completion_id
    ):
        raise ActivationInvariantFailed("probe completion identity mismatch")
    image_digest = (
        acceptance.image_digests[profile.image_role]
        if profile.execution_kind == "hardened_container" and profile.image_role
        else None
    )
    raw_result = {
        "observation_id": probe.probe_id,
        "invariant_id": case.invariant_id,
        "operation_api": case.operation.api,
        "probe_digest": probe.executable_digest,
        "runtime_role": probe.runtime_role,
        "runtime_profile_id": profile.profile_id,
        "runtime_profile_digest": profile.profile_digest,
        "image_digest": image_digest,
        "expected_enforcement": probe.expected_enforcement,
        "enforced": True,
        "forbidden_effects_observed": [],
        "broker_evidence": reduced,
        "completion_event_id": completion_id,
        "completion_event_hmac": completion_hmac,
        "result_digest": result_digest,
        "receipt": _signed_receipt(
            seed=seed,
            acceptance=acceptance,
            run_nonce=challenge["run_nonce"],
            challenge_digest=challenge["challenge_digest"],
            reference_state_root=reference_state_root,
            observation_id=probe.probe_id,
            result_digest=result_digest,
            broker_evidence=reduced,
            completion_event_id=completion_id,
            required=(),
        ),
    }
    return _ExecutionEvidence(raw_result, tuple(events), completion_event)


def _run_restricted_probe(
    *,
    runtime: SealedHarnessRuntime,
    acceptance: ClosedAcceptance,
    profiles: RuntimeProfileLedger,
    challenge: Mapping[str, Any],
    case: ScenarioSpec,
    probe: ProbeSpec,
    profile: RuntimeProfileSpec,
    seed: bytes,
    reference_state_root: str,
) -> _ExecutionEvidence:
    windows = _load_adjacent_module("galaxy_sealed_activation_windows", runtime.windows_launcher_path)
    releases = challenge["release_roots"]
    markers = challenge["marker_roots"]
    channels = challenge["capability_broker_channels"]
    release_root = Path(releases[probe.probe_id])
    marker_root = Path(markers[probe.probe_id])
    specification_path = release_root / "probe.json"
    command = [
        str(runtime.interpreter),
        "-I",
        "-S",
        str(runtime.probe_entrypoint),
        "--probe-worker",
        probe.probe_id,
        probe.executable_digest,
        "--spec",
        str(specification_path),
    ]
    child = windows.create_restricted_process(command, cwd=Path.cwd(), environment={}, suspended=True)
    finished = False
    try:
        runtime_identity = f"win32-pid:{child.process_id}"
        common = _common_binding(
            challenge=challenge,
            case=case,
            observation=probe,
            profile=profile,
            runtime_role=probe.runtime_role,
            runtime_identity=runtime_identity,
            release_token="",
        )
        _atomic_json(
            specification_path,
            _probe_specification(
                common=common,
                probe=probe,
                request_root=str(channels["request_root"]),
                response_root=str(channels["response_root"]),
                release_root=str(release_root),
                marker_root=str(marker_root),
            ),
        )
        child.resume()
        _atomic_json(
            Path(challenge["ready_root"]) / f"{probe.probe_id}.json",
            _ready_event(
                challenge=challenge,
                case=case,
                probe=probe,
                profile=profile,
                runtime_identity=runtime_identity,
                image_digest=None,
                process_id=child.process_id,
            ),
        )
        exit_code = child.wait(300)
        finished = True
        if exit_code != 0:
            raise ActivationInvariantFailed(f"restricted probe {probe.probe_id} exited {exit_code}")
        raw = _strict_json((marker_root / "result.json").read_bytes())
        return _accept_probe_worker_result(
            raw=raw,
            runtime=runtime,
            acceptance=acceptance,
            challenge=challenge,
            case=case,
            probe=probe,
            profile=profile,
            common=common,
            seed=seed,
            reference_state_root=reference_state_root,
        )
    finally:
        if not finished:
            child.terminate()
        child.close()


_DOCKER_ENVIRONMENT = {"DOCKER_HOST": "npipe:////./pipe/dockerDesktopLinuxEngine"}


def _docker_command(
    runtime: SealedHarnessRuntime,
    arguments: Sequence[str],
    *,
    timeout: float,
) -> subprocess.CompletedProcess[str]:
    completed = subprocess.run(
        [str(runtime.docker_path), *arguments],
        cwd=runtime.external_root,
        env=dict(_DOCKER_ENVIRONMENT),
        stdin=subprocess.DEVNULL,
        text=True,
        capture_output=True,
        timeout=timeout,
        check=False,
    )
    if completed.returncode != 0:
        raise ActivationInvariantFailed(
            f"Docker command failed ({completed.returncode}): {completed.stderr.strip()}"
        )
    return completed


def _ensure_images_loaded(runtime: SealedHarnessRuntime) -> None:
    loaded_archives: set[Path] = set()
    for role, archive in sorted(runtime.image_archive_paths.items()):
        if archive not in loaded_archives:
            _docker_command(runtime, ["load", "--input", str(archive)], timeout=180)
            loaded_archives.add(archive)
        inspected = _docker_command(
            runtime,
            ["image", "inspect", f"sha256:{runtime.image_digests[role]}"],
            timeout=30,
        )
        records = json.loads(inspected.stdout)
        if (
            not isinstance(records, list)
            or len(records) != 1
            or records[0].get("Id") != f"sha256:{runtime.image_digests[role]}"
        ):
            raise ActivationInvariantFailed(f"loaded image identity mismatch for {role}")


def _run_container_probe(
    *,
    runtime: SealedHarnessRuntime,
    acceptance: ClosedAcceptance,
    profiles: RuntimeProfileLedger,
    challenge: Mapping[str, Any],
    case: ScenarioSpec,
    probe: ProbeSpec,
    profile: RuntimeProfileSpec,
    seed: bytes,
    reference_state_root: str,
) -> _ExecutionEvidence:
    del profiles
    if profile.image_role is None:
        raise ActivationInvariantFailed("container profile has no image role")
    security = runtime.security_profiles[profile.profile_id]
    releases = challenge["release_roots"]
    markers = challenge["marker_roots"]
    channels = challenge["capability_broker_channels"]
    release_root = Path(releases[probe.probe_id])
    marker_root = Path(markers[probe.probe_id])
    dynamic_sources = {
        "broker_request": Path(channels["request_root"]),
        "broker_response": Path(channels["response_root"]),
        "release": release_root,
        "marker": marker_root,
    }
    arguments = [
        "create",
        "--name",
        f"galaxy-probe-{_digest({'run': challenge['run_nonce'], 'probe': probe.probe_id})[:24]}",
        "--label",
        f"galaxy.probe_id={probe.probe_id}",
        "--label",
        f"galaxy.scenario_digest={case.executable_digest}",
        "--label",
        f"galaxy.run_nonce={challenge['run_nonce']}",
        "--label",
        f"galaxy.challenge_digest={challenge['challenge_digest']}",
        "--label",
        f"galaxy.security_profile_digest={security.profile_digest}",
        "--user",
        security.user,
        "--network",
        security.docker_network_mode,
        "--read-only",
        "--cap-drop",
        "ALL",
        "--security-opt",
        "no-new-privileges",
        "--pids-limit",
        str(security.pids_limit),
        "--memory",
        str(security.memory_bytes),
        "--restart",
        "no",
    ]
    for mount in security.mounts:
        source = (
            Path(mount.sealed_source)
            if mount.source_class == "sealed_runtime" and mount.sealed_source
            else dynamic_sources.get(mount.source_class)
        )
        if source is None:
            raise ActivationInvariantFailed("security profile mount source is unknown")
        option = f"type={mount.kind},source={source},target={mount.target}"
        if not mount.read_write:
            option += ",readonly"
        arguments.extend(["--mount", option])
    arguments.extend(
        [
            f"sha256:{runtime.image_digests[profile.image_role]}",
            *security.command_prefix,
            probe.probe_id,
            probe.executable_digest,
        ]
    )
    created = _docker_command(runtime, arguments, timeout=60)
    container_id = created.stdout.strip()
    if re.fullmatch(r"[0-9a-f]{64}", container_id) is None:
        raise ActivationInvariantFailed("Docker returned a malformed container ID")
    removed = False
    try:
        runtime_identity = f"container:{container_id}"
        common = _common_binding(
            challenge=challenge,
            case=case,
            observation=probe,
            profile=profile,
            runtime_role=probe.runtime_role,
            runtime_identity=runtime_identity,
            release_token="",
        )
        _atomic_json(
            release_root / "probe.json",
            _probe_specification(
                common=common,
                probe=probe,
                request_root="/galaxy/broker-request",
                response_root="/galaxy/broker-response",
                release_root="/galaxy/release",
                marker_root="/galaxy/marker",
            ),
        )
        _docker_command(runtime, ["start", container_id], timeout=30)
        _atomic_json(
            Path(challenge["ready_root"]) / f"{probe.probe_id}.json",
            _ready_event(
                challenge=challenge,
                case=case,
                probe=probe,
                profile=profile,
                runtime_identity=runtime_identity,
                image_digest=runtime.image_digests[profile.image_role],
                container_id=container_id,
            ),
        )
        waited = _docker_command(runtime, ["wait", container_id], timeout=300)
        if waited.stdout.strip() != "0":
            logs = _docker_command(runtime, ["logs", container_id], timeout=30)
            raise ActivationInvariantFailed(
                f"container probe {probe.probe_id} failed: {logs.stdout} {logs.stderr}"
            )
        raw = _strict_json((marker_root / "result.json").read_bytes())
        result = _accept_probe_worker_result(
            raw=raw,
            runtime=runtime,
            acceptance=acceptance,
            challenge=challenge,
            case=case,
            probe=probe,
            profile=profile,
            common=common,
            seed=seed,
            reference_state_root=reference_state_root,
        )
        _docker_command(runtime, ["rm", "-f", container_id], timeout=30)
        removed = True
        return result
    finally:
        if not removed:
            try:
                _docker_command(runtime, ["rm", "-f", container_id], timeout=30)
            except ActivationInvariantFailed:
                pass


def _execute_probe(
    *,
    runtime: SealedHarnessRuntime,
    acceptance: ClosedAcceptance,
    profiles: RuntimeProfileLedger,
    challenge: Mapping[str, Any],
    case: ScenarioSpec,
    probe: ProbeSpec,
    seed: bytes,
    reference_state_root: str,
) -> _ExecutionEvidence:
    profile = profiles.profiles[profiles.role_assignments[probe.runtime_role]]
    if profile.execution_kind == "restricted_os_process":
        return _run_restricted_probe(
            runtime=runtime,
            acceptance=acceptance,
            profiles=profiles,
            challenge=challenge,
            case=case,
            probe=probe,
            profile=profile,
            seed=seed,
            reference_state_root=reference_state_root,
        )
    if profile.execution_kind == "hardened_container":
        return _run_container_probe(
            runtime=runtime,
            acceptance=acceptance,
            profiles=profiles,
            challenge=challenge,
            case=case,
            probe=probe,
            profile=profile,
            seed=seed,
            reference_state_root=reference_state_root,
        )
    raise ActivationInvariantFailed("probe execution kind is not closed")


def _run_closed_campaign(
    *,
    acceptance_path: Path,
    runtime_profiles_path: Path,
    challenge_path: Path,
    report_path: Path,
) -> None:
    acceptance = load_sealed_acceptance()
    runtime = resolve_sealed_harness_runtime(acceptance)
    if (
        acceptance_path.resolve(strict=True) != runtime.acceptance_path
        or runtime_profiles_path.resolve(strict=True) != runtime.runtime_profile_ledger_path
    ):
        raise ActivationAcceptanceRefused("CLI ledger paths differ from sealed runtime")
    profiles = parse_runtime_profile_ledger(
        runtime.runtime_profile_ledger_path.read_bytes(),
        expected_ledger_digest=acceptance.runtime_profile_ledger_digest,
        acceptance_ledger_digest=acceptance.ledger_digest,
    )
    challenge = _load_challenge(challenge_path, acceptance=acceptance, profiles=profiles)
    if any(Path.cwd().iterdir()):
        raise ActivationInvariantFailed("activation harness cwd is not empty")
    seed = _receipt_seed(runtime)
    reference_state_root = _reference_state_root(acceptance, profiles)
    executions: list[_ExecutionEvidence] = []
    for case in acceptance.cases:
        for subcase in case.subcases:
            executions.append(
                _execute_subcase(
                    runtime=runtime,
                    acceptance=acceptance,
                    profiles=profiles,
                    challenge=challenge,
                    case=case,
                    subcase=subcase,
                    seed=seed,
                    reference_state_root=reference_state_root,
                )
            )

    _ensure_images_loaded(runtime)
    probe_work = [(case, probe) for case in acceptance.cases for probe in case.probes]
    with concurrent.futures.ThreadPoolExecutor(
        max_workers=acceptance.max_probe_concurrency,
        thread_name_prefix="galaxy-activation-probe",
    ) as pool:
        futures = {
            pool.submit(
                _execute_probe,
                runtime=runtime,
                acceptance=acceptance,
                profiles=profiles,
                challenge=challenge,
                case=case,
                probe=probe,
                seed=seed,
                reference_state_root=reference_state_root,
            ): probe.probe_id
            for case, probe in probe_work
        }
        for future in concurrent.futures.as_completed(futures):
            try:
                executions.append(future.result())
            except BaseException as exc:
                for other in futures:
                    other.cancel()
                raise ActivationInvariantFailed(f"live probe {futures[future]} failed") from exc

    subcase_ids = {item.observation_id for case in acceptance.cases for item in case.subcases}
    subcase_results = sorted(
        (
            execution.raw_result
            for execution in executions
            if execution.raw_result["observation_id"] in subcase_ids
        ),
        key=lambda item: item["observation_id"],
    )
    probe_results = sorted(
        (
            execution.raw_result
            for execution in executions
            if execution.raw_result["observation_id"] not in subcase_ids
        ),
        key=lambda item: item["observation_id"],
    )
    if len(subcase_results) != acceptance.subcase_count or len(probe_results) != acceptance.probe_count:
        raise ActivationInvariantFailed("campaign result closure is incomplete")
    call_events = sorted(
        (event for execution in executions for event in execution.call_events),
        key=lambda item: (item["observation_id"], item["sequence"]),
    )
    completion_events = sorted(
        (execution.completion_event for execution in executions),
        key=lambda item: item["observation_id"],
    )
    report = {
        "schema": "galaxy.activation.external-report/v2",
        "status": "passed_inactive",
        "run_nonce": challenge["run_nonce"],
        "challenge_digest": challenge["challenge_digest"],
        "acceptance_ledger_digest": acceptance.ledger_digest,
        "runtime_profile_ledger_digest": acceptance.runtime_profile_ledger_digest,
        "runtime_digest": acceptance.runtime_digest,
        "reference_state_root": reference_state_root,
        "broker_evidence_root": _digest(call_events),
        "completion_evidence_root": _digest(completion_events),
        "subcase_results": subcase_results,
        "probe_results": probe_results,
    }
    report["report_digest"] = _digest(report)
    _atomic_json(report_path, report)


def _command_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="galaxy-sealed-activation-harness")
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--run-closed-acceptance", action="store_true")
    modes.add_argument("--validate-closed-report", action="store_true")
    parser.add_argument("--acceptance", required=True)
    parser.add_argument("--runtime-profiles", required=True)
    parser.add_argument("--challenge")
    parser.add_argument("--report", required=True)
    parser.add_argument("--observation")
    parser.add_argument("--replay-store")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _command_parser().parse_args(argv)
    try:
        if args.run_closed_acceptance:
            if args.challenge is None or args.observation is not None or args.replay_store is not None:
                raise ActivationAcceptanceRefused("run-mode arguments are not closed")
            _run_closed_campaign(
                acceptance_path=Path(args.acceptance),
                runtime_profiles_path=Path(args.runtime_profiles),
                challenge_path=Path(args.challenge),
                report_path=Path(args.report),
            )
            return 0
        if args.observation is None or args.replay_store is None or args.challenge is not None:
            raise ActivationAcceptanceRefused("validation-mode arguments are not closed")
        acceptance = load_sealed_acceptance()
        runtime = resolve_sealed_harness_runtime(acceptance)
        if (
            Path(args.acceptance).resolve(strict=True) != runtime.acceptance_path
            or Path(args.runtime_profiles).resolve(strict=True) != runtime.runtime_profile_ledger_path
        ):
            raise ActivationAcceptanceRefused("validator ledger paths are not sealed")
        raw_report = _strict_json(Path(args.report).read_bytes())
        observation = _strict_json(Path(args.observation).read_bytes())
        if not isinstance(raw_report, dict) or not isinstance(observation, dict):
            raise ActivationInvariantFailed("validator inputs are not objects")
        validate_external_report(
            raw_report,
            acceptance=acceptance,
            independent_observation=observation,
            replay_guard=EvidenceReplayGuard(Path(args.replay_store)),
        )
        return 0
    except (ActivationInvariantFailed, OSError, ValueError) as exc:
        sys.stderr.write(f"{type(exc).__name__}: {exc}\n")
        return 78


if __name__ == "__main__":
    raise SystemExit(main())
