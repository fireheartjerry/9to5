class ActivationInvariantFailed(RuntimeError):
    """Externally observed evidence did not prove the closed invariant."""


class ActivationAcceptanceRefused(ActivationInvariantFailed):
    """The closed acceptance input was not byte- and schema-exact."""


def _canonical_json(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")


def _reject_duplicate_keys(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise ActivationAcceptanceRefused(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def _reject_non_integral(value: str) -> object:
    raise ActivationAcceptanceRefused(f"non-integral JSON value: {value}")


def _bounded_integer(value: str) -> int:
    parsed = int(value)
    if not -(2**63) <= parsed < 2**63:
        raise ActivationAcceptanceRefused("JSON integer exceeds signed 64-bit range")
    return parsed


def _strict_json(raw: bytes) -> object:
    try:
        value = json.loads(
            raw.decode("utf-8", errors="strict"),
            object_pairs_hook=_reject_duplicate_keys,
            parse_float=_reject_non_integral,
            parse_int=_bounded_integer,
            parse_constant=_reject_non_integral,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ActivationAcceptanceRefused("input is not strict UTF-8 JSON") from exc
    if raw != _canonical_json(value):
        raise ActivationAcceptanceRefused("input is not canonical JSON")
    return value


def _exact_keys(value: object, keys: set[str], at: str) -> dict[str, Any]:
    if not isinstance(value, dict) or set(value) != keys:
        raise ActivationAcceptanceRefused(f"{at}: expected exact fields {sorted(keys)}")
    return value


def _text(value: object, at: str) -> str:
    if not isinstance(value, str) or not value or "\0" in value:
        raise ActivationAcceptanceRefused(f"{at}: expected non-empty NUL-free text")
    return value


def _object(value: object, at: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ActivationAcceptanceRefused(f"{at}: expected object")
    return value


def _sequence(value: object, at: str, *, nonempty: bool = True) -> list[Any]:
    if not isinstance(value, list) or (nonempty and not value):
        raise ActivationAcceptanceRefused(f"{at}: expected non-empty array")
    return value


def _digest(value: object) -> str:
    return hashlib.sha256(_canonical_json(value)).hexdigest()


