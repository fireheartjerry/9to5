def _load_challenge(
    path: Path,
    *,
    acceptance: ClosedAcceptance,
    profiles: RuntimeProfileLedger,
) -> dict[str, Any]:
    raw = _ordinary_file(path, root=None, label="parent challenge").read_bytes()
    value = _strict_json(raw)
    fields = {
        "schema",
        "run_nonce",
        "acceptance_ledger_digest",
        "runtime_profile_ledger_digest",
        "ready_root",
        "release_roots",
        "marker_roots",
        "poison_cwd",
        "goldstone_path",
        "credential_path",
        "parser_bomb_path",
        "git_authority_path",
        "sibling_store_path",
        "forbidden_write_path",
        "descendant_marker_path",
        "outside_state_path",
        "observer_host",
        "observer_port",
        "capability_broker_channels",
        "expected_probe_ids",
        "expected_observation_ids",
        "runtime_profile_digests",
        "challenge_digest",
    }
    challenge = _exact_keys(value, fields, "challenge")
    unsigned = {key: item for key, item in challenge.items() if key != "challenge_digest"}
    expected_probe_ids = sorted(probe.probe_id for case in acceptance.cases for probe in case.probes)
    expected_observation_ids = sorted(_observation_index(acceptance))
    semantic_digests = {
        profile_id: profile.profile_digest for profile_id, profile in sorted(profiles.profiles.items())
    }
    checks = (
        challenge["schema"] == 2,
        challenge["acceptance_ledger_digest"] == acceptance.ledger_digest,
        challenge["runtime_profile_ledger_digest"] == acceptance.runtime_profile_ledger_digest,
        challenge["expected_probe_ids"] == expected_probe_ids,
        challenge["expected_observation_ids"] == expected_observation_ids,
        challenge["runtime_profile_digests"] == semantic_digests,
        challenge["observer_host"] == "127.0.0.1",
        type(challenge["observer_port"]) is int,
        challenge["challenge_digest"] == _digest(unsigned),
        re.fullmatch(r"[0-9a-f]{64}", str(challenge["run_nonce"])) is not None,
    )
    if not all(checks):
        raise ActivationAcceptanceRefused("parent challenge binding mismatch")
    releases = challenge["release_roots"]
    markers = challenge["marker_roots"]
    channels = challenge["capability_broker_channels"]
    if (
        not isinstance(releases, dict)
        or not isinstance(markers, dict)
        or set(releases) != set(expected_probe_ids)
        or set(markers) != set(expected_probe_ids)
        or not isinstance(channels, dict)
        or set(channels) != {"request_root", "response_root"}
    ):
        raise ActivationAcceptanceRefused("challenge capability closure drift")
    # Only broker/probe coordination paths are opened.  Canary, poison, socket,
    # repository, credential, and sibling-store paths remain opaque strings.
    coordination_paths = [
        challenge["ready_root"],
        channels["request_root"],
        channels["response_root"],
        *releases.values(),
        *markers.values(),
    ]
    for item in coordination_paths:
        candidate = Path(_text(item, "challenge.coordination_path"))
        try:
            resolved = candidate.resolve(strict=True)
        except OSError as exc:
            raise ActivationAcceptanceRefused("challenge path is unavailable") from exc
        if not candidate.is_absolute() or candidate.is_symlink() or not resolved.is_dir():
            raise ActivationAcceptanceRefused("challenge path is not an ordinary directory")
    return challenge


def _wait_for_file(path: Path, *, deadline: float) -> bytes:
    while time.monotonic() < deadline:
        try:
            return path.read_bytes()
        except FileNotFoundError:
            time.sleep(0.005)
    raise ActivationInvariantFailed(f"timed out waiting for {path.name}")


def _atomic_json(path: Path, value: object) -> None:
    raw = _canonical_json(value)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.{time.time_ns()}.tmp")
    temporary.write_bytes(raw)
    os.replace(temporary, path)


def _broker_exchange(
    request: Mapping[str, Any],
    *,
    request_root: Path,
    response_root: Path,
    request_name: str,
    deadline: float,
) -> dict[str, Any]:
    destination = request_root / f"{request_name}.request.json"
    if destination.exists():
        raise ActivationInvariantFailed("broker request identity collision")
    _atomic_json(destination, dict(request))
    raw = _wait_for_file(response_root / f"{request_name}.response.json", deadline=deadline)
    response_path = response_root / f"{request_name}.response.json"
    try:
        destination.unlink()
        response_path.unlink()
    except OSError as exc:
        raise ActivationInvariantFailed("broker channel cleanup failed") from exc
    response = _strict_json(raw)
    if not isinstance(response, dict):
        raise ActivationInvariantFailed("broker response is not an object")
    return response


