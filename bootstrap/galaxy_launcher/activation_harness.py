def _path_has_reparse_component(path: Path) -> bool:
    if path.is_symlink():
        return True
    if os.name != "nt":
        return False
    absolute = Path(os.path.abspath(path))
    current = Path(absolute.parts[0])
    for component in absolute.parts[1:]:
        current /= component
        attributes = ctypes.windll.kernel32.GetFileAttributesW(str(current))
        if attributes != 0xFFFFFFFF and bool(attributes & 0x400):
            return True
    return False


def _ordinary_file(path: Path, *, root: Path | None, label: str) -> Path:
    try:
        resolved = path.resolve(strict=True)
        if root is not None:
            resolved.relative_to(root)
        info = resolved.stat()
    except (OSError, ValueError) as exc:
        raise ActivationAcceptanceRefused(f"{label} is unavailable") from exc
    if (
        _path_has_reparse_component(path)
        or not resolved.is_file()
        or info.st_nlink != 1
    ):
        raise ActivationAcceptanceRefused(f"{label} is not an ordinary single-link file")
    return resolved


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _verify_tofu_receipt_leaves(
    value: object,
    *,
    domain: str,
    root: Path,
    seen_installed: set[Path],
) -> tuple[str, set[Path]]:
    leaves = _sequence(value, f"tofu_receipt.{domain}_leaves")
    logical_order: list[str] = []
    for item in leaves:
        if not isinstance(item, dict) or not isinstance(item.get("logical_path"), str):
            raise ActivationAcceptanceRefused(f"TOFU {domain} leaf schema drift")
        logical_order.append(item["logical_path"])
    if logical_order != sorted(logical_order):
        raise ActivationAcceptanceRefused(f"TOFU {domain} leaves are not ordered")
    leaf_hashes: list[bytes] = []
    paths: set[Path] = set()
    logical_paths: set[str] = set()
    for index, item in enumerate(leaves):
        record = _exact_keys(
            item,
            {"logical_path", "installed_path", "size", "sha256"},
            f"tofu_receipt.{domain}_leaves[{index}]",
        )
        logical = _text(record["logical_path"], f"tofu_receipt.{domain}_leaves[{index}].logical_path")
        if (
            logical in logical_paths
            or "\\" in logical
            or logical.startswith("/")
            or any(part in {"", ".", ".."} for part in logical.split("/"))
            or type(record["size"]) is not int
            or record["size"] < 0
        ):
            raise ActivationAcceptanceRefused(f"TOFU {domain} leaf is malformed")
        logical_paths.add(logical)
        expected = _hex_digest(
            record["sha256"], f"tofu_receipt.{domain}_leaves[{index}].sha256"
        )
        candidate = Path(
            _text(
                record["installed_path"],
                f"tofu_receipt.{domain}_leaves[{index}].installed_path",
            )
        )
        if not candidate.is_absolute() or _path_has_reparse_component(candidate):
            raise ActivationAcceptanceRefused(f"TOFU {domain} leaf path is unsafe")
        try:
            installed = candidate.resolve(strict=True)
            metadata = installed.stat()
        except OSError as exc:
            raise ActivationAcceptanceRefused(f"TOFU {domain} leaf is unavailable") from exc
        if (
            not installed.is_file()
            or installed in seen_installed
            or metadata.st_size != record["size"]
            or _sha256_file(installed) != expected
        ):
            raise ActivationAcceptanceRefused(f"TOFU {domain} leaf bytes drifted")
        if installed.is_relative_to(root) and metadata.st_nlink != 1:
            raise ActivationAcceptanceRefused(f"TOFU {domain} installed leaf is multi-link")
        seen_installed.add(installed)
        paths.add(installed)
        leaf_hashes.append(
            hashlib.sha256(
                _canonical_json(
                    {"logical_path": logical, "sha256": expected, "size": record["size"]}
                )
            ).digest()
        )
    leaf_root = hashlib.sha256(
        domain.encode("ascii") + b"\0" + b"".join(sorted(leaf_hashes))
    ).hexdigest()
    return leaf_root, paths


def _verify_tofu_receipt(
    value: object,
    *,
    root: Path,
    generation: int,
    runtime_digest: str,
    image_digests: Mapping[str, str],
    adapter_digest: str,
    public_key: bytes,
    required_paths: set[Path],
) -> str:
    receipt = _exact_keys(value, _TOFU_RECEIPT_KEYS, "tofu_receipt")
    if (
        receipt["schema"] != "galaxy.trust-on-first-install/v1"
        or receipt["status"] != "installed_inactive"
        or receipt["activation_state"] != "inactive"
        or receipt["monotone_generation"] != generation
        or receipt["runtime_digest"] != runtime_digest
        or receipt["image_digests"] != dict(image_digests)
        or receipt["activation_acceptance_sha256"] != PINNED_ACCEPTANCE_LEDGER_DIGEST
        or receipt["activation_runtime_profiles_sha256"]
        != PINNED_RUNTIME_PROFILE_LEDGER_DIGEST
        or receipt["activation_adapter_sha256"] != adapter_digest
        or receipt["service_name"] != "9to5Singularity"
    ):
        raise ActivationAcceptanceRefused("TOFU receipt runtime binding mismatch")
    source_root, source_paths = _verify_tofu_receipt_leaves(
        receipt["source_leaves"], domain="source", root=root, seen_installed=set()
    )
    seen = set(source_paths)
    artifact_root, artifact_paths = _verify_tofu_receipt_leaves(
        receipt["artifact_leaves"], domain="artifact", root=root, seen_installed=seen
    )
    merkle = hashlib.sha256(
        b"galaxy-tofu-v1\0" + bytes.fromhex(source_root) + bytes.fromhex(artifact_root)
    ).hexdigest()
    nonce = _hex_digest(receipt["nonce"], "tofu_receipt.nonce")
    challenge = f"TRUST SINGULARITY BOOTSTRAP {merkle} NONCE {nonce}"
    if (
        source_root != _hex_digest(receipt["source_root"], "tofu_receipt.source_root")
        or artifact_root != _hex_digest(receipt["artifact_root"], "tofu_receipt.artifact_root")
        or merkle != _hex_digest(receipt["merkle_root"], "tofu_receipt.merkle_root")
        or receipt["challenge"] != challenge
        or receipt["approval_response_sha256"] != hashlib.sha256(challenge.encode("ascii")).hexdigest()
        or not required_paths <= source_paths | artifact_paths
    ):
        raise ActivationAcceptanceRefused("TOFU receipt closure/challenge binding mismatch")
    public_digest = hashlib.sha256(public_key).hexdigest()
    repository_identity = _text(receipt["repository_identity"], "repository identity")
    if (
        receipt["activation_receipt_public_key"] != public_key.hex()
        or receipt["activation_receipt_public_key_digest"] != public_digest
        or re.fullmatch(r"S-1(?:-[0-9]+)+", _text(receipt["operator_sid"], "operator SID"))
        is None
        or re.fullmatch(r"S-1(?:-[0-9]+)+", _text(receipt["service_sid"], "service SID"))
        is None
        or re.fullmatch(r"[0-9a-f]{64}", repository_identity) is None
        or not _text(receipt["dacl_sddl"], "TOFU DACL").startswith("O:")
    ):
        raise ActivationAcceptanceRefused("TOFU receipt authority identity binding mismatch")
    anchor_record = _ordinary_file(
        Path(_text(receipt["anchor_record_path"], "anchor record path")),
        root=root,
        label="anchor record",
    )
    if anchor_record.parent != root / "repositories" / repository_identity:
        raise ActivationAcceptanceRefused("TOFU receipt repository anchor path mismatch")
    return merkle


def _hex_digest(value: object, at: str) -> str:
    parsed = _text(value, at)
    if re.fullmatch(r"[0-9a-f]{64}", parsed) is None:
        raise ActivationAcceptanceRefused(f"{at}: malformed SHA-256")
    return parsed


def _runtime_pointer_path() -> Path:
    adjacent = Path(__file__).resolve().with_name("runtime.lock.json")
    if adjacent.is_file():
        return adjacent
    local = os.environ.get("LOCALAPPDATA")
    if not local:
        raise ActivationAcceptanceRefused("installed controller root is unavailable")
    root = Path(local) / "9to5" / "singularity"
    pointer_path = root / "activation-runtime.json"
    pointer = _exact_keys(
        _strict_json(_ordinary_file(pointer_path, root=root, label="runtime pointer").read_bytes()),
        {"schema", "runtime_lock_path", "runtime_lock_sha256", "generation", "status"},
        "runtime_pointer",
    )
    if (
        pointer["schema"] != "galaxy.activation.runtime-pointer/v1"
        or pointer["status"] != "installed_inactive"
        or type(pointer["generation"]) is not int
        or pointer["generation"] < 1
    ):
        raise ActivationAcceptanceRefused("runtime pointer is not an inactive generation")
    lock_path = _ordinary_file(
        Path(_text(pointer["runtime_lock_path"], "runtime_pointer.runtime_lock_path")),
        root=root.resolve(strict=True),
        label="runtime lock",
    )
    if hashlib.sha256(lock_path.read_bytes()).hexdigest() != _hex_digest(
        pointer["runtime_lock_sha256"], "runtime_pointer.runtime_lock_sha256"
    ):
        raise ActivationAcceptanceRefused("runtime pointer lock digest mismatch")
    return lock_path


def _parse_mount(value: object, at: str) -> MountSpec:
    record = _exact_keys(
        value,
        {
            "kind",
            "target",
            "read_write",
            "source_class",
            "sealed_source",
            "source_digest",
        },
        at,
    )
    if type(record["read_write"]) is not bool:
        raise ActivationAcceptanceRefused(f"{at}: mount mode must be Boolean")
    sealed_source = record["sealed_source"]
    source_digest = record["source_digest"]
    source_class = _text(record["source_class"], f"{at}.source_class")
    if source_class == "sealed_runtime":
        sealed_source = _text(sealed_source, f"{at}.sealed_source")
        source_digest = _hex_digest(source_digest, f"{at}.source_digest")
    elif sealed_source is not None or source_digest is not None:
        raise ActivationAcceptanceRefused(f"{at}: dynamic mount pins a source")
    return MountSpec(
        kind=_text(record["kind"], f"{at}.kind"),
        target=_text(record["target"], f"{at}.target"),
        read_write=record["read_write"],
        source_class=source_class,
        sealed_source=sealed_source,
        source_digest=source_digest,
    )


def _parse_security_profiles(
    value: object,
    profiles: Mapping[str, RuntimeProfileSpec],
) -> dict[str, ContainerSecurityProfile]:
    if not isinstance(value, dict):
        raise ActivationAcceptanceRefused("security profiles must be an object")
    expected_ids = {
        key for key, profile in profiles.items() if profile.execution_kind == "hardened_container"
    }
    if set(value) != expected_ids:
        raise ActivationAcceptanceRefused("container security profile set drift")
    fields = {
        "profile_id",
        "semantic_profile_digest",
        "image_role",
        "user",
        "entrypoint",
        "command_prefix",
        "allowed_environment",
        "docker_network_mode",
        "pids_limit",
        "memory_bytes",
        "mounts",
    }
    result: dict[str, ContainerSecurityProfile] = {}
    for profile_id, item in value.items():
        at = f"security_profiles.{profile_id}"
        record = _exact_keys(item, fields, at)
        semantic = profiles[profile_id]
        if (
            record["profile_id"] != profile_id
            or record["semantic_profile_digest"] != semantic.profile_digest
            or record["image_role"] != semantic.image_role
            or type(record["pids_limit"]) is not int
            or type(record["memory_bytes"]) is not int
            or record["pids_limit"] < 1
            or record["memory_bytes"] < 16 * 1024 * 1024
        ):
            raise ActivationAcceptanceRefused(f"{at}: semantic binding mismatch")
        sequence_fields = ("entrypoint", "command_prefix", "allowed_environment")
        sequences = {
            key: tuple(_text(entry, f"{at}.{key}") for entry in _sequence(record[key], f"{at}.{key}"))
            for key in sequence_fields
        }
        mounts = tuple(
            _parse_mount(entry, f"{at}.mounts[{index}]")
            for index, entry in enumerate(_sequence(record["mounts"], f"{at}.mounts"))
        )
        if len({mount.target for mount in mounts}) != len(mounts):
            raise ActivationAcceptanceRefused(f"{at}: duplicate mount target")
        result[profile_id] = ContainerSecurityProfile(
            profile_id=profile_id,
            semantic_profile_digest=semantic.profile_digest,
            image_role=_text(record["image_role"], f"{at}.image_role"),
            user=_text(record["user"], f"{at}.user"),
            entrypoint=sequences["entrypoint"],
            command_prefix=sequences["command_prefix"],
            allowed_environment=sequences["allowed_environment"],
            docker_network_mode=_text(record["docker_network_mode"], f"{at}.docker_network_mode"),
            pids_limit=record["pids_limit"],
            memory_bytes=record["memory_bytes"],
            mounts=mounts,
        )
    return result


def _load_runtime() -> tuple[SealedHarnessRuntime, ClosedAcceptance]:
    lock_path = _runtime_pointer_path()
    lock_raw = lock_path.read_bytes()
    lock = _exact_keys(
        _strict_json(lock_raw),
        {
            "schema",
            "status",
            "generation",
            "external_root",
            "files",
            "file_digests",
            "runtime_digest",
            "image_digests",
            "image_archive_paths",
            "tofu_receipt_path",
            "security_profiles",
            "max_probe_concurrency",
        },
        "runtime_lock",
    )
    if (
        lock["schema"] != "galaxy.activation.sealed-runtime/v1"
        or lock["status"] != "installed_inactive"
        or type(lock["generation"]) is not int
        or lock["generation"] < 1
        or type(lock["max_probe_concurrency"]) is not int
        or not 1 <= lock["max_probe_concurrency"] <= 8
    ):
        raise ActivationAcceptanceRefused("runtime lock does not describe an inactive generation")
    root = Path(_text(lock["external_root"], "runtime_lock.external_root")).resolve(strict=True)
    if not root.is_dir() or root.is_symlink() or not lock_path.resolve().is_relative_to(root):
        raise ActivationAcceptanceRefused("runtime lock escaped installed root")
    files = lock["files"]
    file_digests = lock["file_digests"]
    if (
        not isinstance(files, dict)
        or not isinstance(file_digests, dict)
        or set(files) != _RUNTIME_FILE_KEYS
        or set(file_digests) != _RUNTIME_FILE_KEYS
    ):
        raise ActivationAcceptanceRefused("runtime file closure drift")
    resolved_files: dict[str, Path] = {}
    digests: dict[str, str] = {}
    for name in sorted(_RUNTIME_FILE_KEYS):
        candidate = Path(_text(files[name], f"runtime_lock.files.{name}"))
        allowed_root = None if name in {"powershell", "docker"} else root
        resolved = _ordinary_file(candidate, root=allowed_root, label=f"runtime {name}")
        expected = _hex_digest(file_digests[name], f"runtime_lock.file_digests.{name}")
        if hashlib.sha256(resolved.read_bytes()).hexdigest() != expected:
            raise ActivationAcceptanceRefused(f"runtime {name} digest mismatch")
        resolved_files[name] = resolved
        digests[name] = expected

    acceptance = parse_closed_acceptance(
        resolved_files["acceptance"].read_bytes(),
        expected_ledger_digest=PINNED_ACCEPTANCE_LEDGER_DIGEST,
        requirements_digest=PINNED_REQUIREMENTS_DIGEST,
    )
    profile_ledger = parse_runtime_profile_ledger(
        resolved_files["runtime_profiles"].read_bytes(),
        expected_ledger_digest=PINNED_RUNTIME_PROFILE_LEDGER_DIGEST,
        acceptance_ledger_digest=PINNED_ACCEPTANCE_LEDGER_DIGEST,
    )
    expected_roles = {probe.runtime_role for case in acceptance.cases for probe in case.probes}
    if set(profile_ledger.role_assignments) != expected_roles:
        raise ActivationAcceptanceRefused("runtime role assignment closure drift")
    security_profiles = _parse_security_profiles(lock["security_profiles"], profile_ledger.profiles)
    image_digests = lock["image_digests"]
    image_paths = lock["image_archive_paths"]
    if not isinstance(image_digests, dict) or not isinstance(image_paths, dict):
        raise ActivationAcceptanceRefused("image closure must be an object")
    expected_image_roles = {
        profile.image_role for profile in profile_ledger.profiles.values() if profile.image_role is not None
    }
    if set(image_digests) != expected_image_roles or set(image_paths) != expected_image_roles:
        raise ActivationAcceptanceRefused("runtime image role set drift")
    resolved_images: dict[str, Path] = {}
    parsed_image_digests: dict[str, str] = {}
    for role in sorted(expected_image_roles):
        parsed_image_digests[role] = _hex_digest(image_digests[role], f"runtime_lock.image_digests.{role}")
        resolved_images[role] = _ordinary_file(
            Path(_text(image_paths[role], f"runtime_lock.image_archive_paths.{role}")),
            root=root,
            label=f"runtime image archive {role}",
        )
    public_key = resolved_files["receipt_public_key"].read_bytes()
    if len(public_key) != 32:
        raise ActivationAcceptanceRefused("activation receipt public key is malformed")
    runtime_digest = _hex_digest(lock["runtime_digest"], "runtime_lock.runtime_digest")
    tofu_receipt_path = _ordinary_file(
        Path(_text(lock["tofu_receipt_path"], "runtime_lock.tofu_receipt_path")),
        root=root,
        label="TOFU receipt",
    )
    tofu_receipt_value = _strict_json(tofu_receipt_path.read_bytes())
    tofu_merkle_root = _verify_tofu_receipt(
        tofu_receipt_value,
        root=root,
        generation=lock["generation"],
        runtime_digest=runtime_digest,
        image_digests=parsed_image_digests,
        adapter_digest=digests["adapter"],
        public_key=public_key,
        required_paths={
            lock_path.resolve(strict=True),
            *resolved_files.values(),
            *resolved_images.values(),
        },
    )
    runtime = SealedHarnessRuntime(
        external_root=root,
        generation=lock["generation"],
        runtime_lock_path=lock_path.resolve(strict=True),
        tofu_receipt_path=tofu_receipt_path,
        tofu_merkle_root=tofu_merkle_root,
        interpreter=resolved_files["interpreter"],
        interpreter_digest=digests["interpreter"],
        powershell_path=resolved_files["powershell"],
        powershell_digest=digests["powershell"],
        docker_path=resolved_files["docker"],
        docker_digest=digests["docker"],
        harness_entrypoint=resolved_files["harness"],
        harness_digest=digests["harness"],
        probe_entrypoint=resolved_files["probe"],
        probe_digest=digests["probe"],
        adapter_entrypoint=resolved_files["adapter"],
        adapter_digest=digests["adapter"],
        acceptance_path=resolved_files["acceptance"],
        runtime_profile_ledger_path=resolved_files["runtime_profiles"],
        receipt_public_key_path=resolved_files["receipt_public_key"],
        receipt_private_key_path=resolved_files["receipt_private_key"],
        windows_launcher_path=resolved_files["windows_launcher"],
        crypto_path=resolved_files["crypto"],
        dpapi_path=resolved_files["dpapi"],
        runtime_digest=runtime_digest,
        image_digests=parsed_image_digests,
        image_archive_paths=resolved_images,
        security_profiles=security_profiles,
        max_probe_concurrency=lock["max_probe_concurrency"],
    )
    return runtime, dataclasses.replace(
        acceptance,
        runtime_profile_ledger_digest=profile_ledger.ledger_digest,
        role_profile_assignments=dict(profile_ledger.role_assignments),
        semantic_profile_digests={
            key: profile.profile_digest for key, profile in profile_ledger.profiles.items()
        },
        runtime_digest=runtime_digest,
        image_digests=parsed_image_digests,
        receipt_public_key=public_key.hex(),
        adapter_digest=digests["adapter"],
        security_profiles=security_profiles,
        max_probe_concurrency=runtime.max_probe_concurrency,
    )


def load_sealed_acceptance() -> ClosedAcceptance:
    """Load acceptance only through the installed inactive runtime lock."""
    return _load_runtime()[1]


def resolve_sealed_harness_runtime(
    acceptance: ClosedAcceptance,
) -> SealedHarnessRuntime:
    """Resolve and revalidate the exact external runtime bound to acceptance."""
    runtime, current = _load_runtime()
    bindings = (
        acceptance.ledger_digest == current.ledger_digest,
        acceptance.runtime_profile_ledger_digest == current.runtime_profile_ledger_digest,
        acceptance.runtime_digest == current.runtime_digest,
        dict(acceptance.image_digests) == dict(current.image_digests),
        acceptance.adapter_digest == current.adapter_digest,
        acceptance.receipt_public_key == current.receipt_public_key,
    )
    if not all(bindings):
        raise ActivationAcceptanceRefused("acceptance/runtime binding mismatch")
    return runtime


