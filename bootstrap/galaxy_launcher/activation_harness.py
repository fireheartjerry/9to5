@dataclasses.dataclass(frozen=True)
class ClosedAcceptance:
    cases: tuple[ScenarioSpec, ...]
    requirements_digest: str
    ledger_digest: str
    runtime_profile_ledger_digest: str = ""
    role_profile_assignments: Mapping[str, str] = dataclasses.field(default_factory=dict)
    semantic_profile_digests: Mapping[str, str] = dataclasses.field(default_factory=dict)
    runtime_digest: str = ""
    image_digests: Mapping[str, str] = dataclasses.field(default_factory=dict)
    receipt_public_key: str = ""
    adapter_digest: str = ""
    security_profiles: Mapping[str, Any] = dataclasses.field(default_factory=dict)
    max_probe_concurrency: int = 1

    @property
    def task_contracts(self) -> tuple[int, ...]:
        return tuple(sorted({case.task for case in self.cases}))

    @property
    def case_count(self) -> int:
        return len(self.cases)

    @property
    def subcase_count(self) -> int:
        return sum(len(case.subcases) for case in self.cases)

    @property
    def probe_count(self) -> int:
        return sum(len(case.probes) for case in self.cases)

    @property
    def observation_count(self) -> int:
        return self.subcase_count + self.probe_count

    @property
    def broker_call_count(self) -> int:
        return sum(
            sum(len(item.broker_calls) for item in case.subcases)
            + sum(len(item.broker_operations) for item in case.probes)
            for case in self.cases
        )

    @property
    def case_ids(self) -> tuple[str, ...]:
        return tuple(case.invariant_id for case in self.cases)

    @property
    def subcase_ids(self) -> tuple[str, ...]:
        return tuple(item.subcase_id for case in self.cases for item in case.subcases)

    @property
    def probe_ids(self) -> tuple[str, ...]:
        return tuple(item.probe_id for case in self.cases for item in case.probes)


def _broker_call(value: object, at: str) -> BrokerCallSpec:
    record = _exact_keys(value, {"operation", "args", "expected_result"}, at)
    return BrokerCallSpec(
        operation=_text(record["operation"], f"{at}.operation"),
        args=_object(record["args"], f"{at}.args"),
        expected_result=record["expected_result"],
    )


def parse_closed_acceptance(
    raw: bytes,
    *,
    expected_ledger_digest: str,
    requirements_digest: str,
) -> ClosedAcceptance:
    """Parse only the immutable 192-invariant canonical acceptance ledger."""
    if requirements_digest != PINNED_REQUIREMENTS_DIGEST:
        raise ActivationAcceptanceRefused("requirements digest is not approved")
    actual_digest = hashlib.sha256(raw).hexdigest()
    if expected_ledger_digest != PINNED_ACCEPTANCE_LEDGER_DIGEST or actual_digest != expected_ledger_digest:
        raise ActivationAcceptanceRefused("acceptance ledger digest mismatch")
    records = _strict_json(raw)
    if not isinstance(records, list) or len(records) != 192:
        raise ActivationAcceptanceRefused("acceptance ledger must contain 192 cases")

    cases: list[ScenarioSpec] = []
    invariant_ids: set[str] = set()
    subcase_ids: set[str] = set()
    probe_ids: set[str] = set()
    top_keys = {
        "invariant_id",
        "requirement_sha256",
        "preconditions",
        "operation",
        "subcases",
        "required_receipts",
        "security_probes",
    }
    for record_index, item in enumerate(records):
        at = f"records[{record_index}]"
        record = _exact_keys(item, top_keys, at)
        invariant_id = _text(record["invariant_id"], f"{at}.invariant_id")
        match = re.fullmatch(r"T([1-4])(?:[AB])?-(\d{2})", invariant_id)
        if match is None or invariant_id in invariant_ids:
            raise ActivationAcceptanceRefused(f"{at}: invalid or duplicate invariant")
        invariant_ids.add(invariant_id)
        family = invariant_id.split("-", 1)[0]
        task = int(family[1])
        requirement_digest = _text(record["requirement_sha256"], f"{at}.requirement_sha256")
        if re.fullmatch(r"[0-9a-f]{64}", requirement_digest) is None:
            raise ActivationAcceptanceRefused(f"{at}: malformed requirement digest")

        preconditions: list[StepSpec] = []
        for index, value in enumerate(_sequence(record["preconditions"], f"{at}.preconditions")):
            where = f"{at}.preconditions[{index}]"
            parsed = _exact_keys(value, {"step", "args"}, where)
            preconditions.append(
                StepSpec(
                    _text(parsed["step"], f"{where}.step"),
                    _object(parsed["args"], f"{where}.args"),
                )
            )

        operation_value = _exact_keys(record["operation"], {"api", "args"}, f"{at}.operation")
        operation = OperationSpec(
            _text(operation_value["api"], f"{at}.operation.api"),
            _object(operation_value["args"], f"{at}.operation.args"),
        )

        subcases: list[SubcaseSpec] = []
        for index, value in enumerate(_sequence(record["subcases"], f"{at}.subcases")):
            where = f"{at}.subcases[{index}]"
            parsed = _exact_keys(value, {"id", "fault", "broker_calls", "expected"}, where)
            subcase_id = _text(parsed["id"], f"{where}.id")
            if (
                re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,191}", subcase_id) is None
                or subcase_id in subcase_ids
            ):
                raise ActivationAcceptanceRefused(f"{where}: invalid duplicate ID")
            subcase_ids.add(subcase_id)
            fault_value = _exact_keys(parsed["fault"], {"edge", "kind", "args"}, f"{where}.fault")
            fault = FaultSpec(
                _text(fault_value["edge"], f"{where}.fault.edge"),
                _text(fault_value["kind"], f"{where}.fault.kind"),
                _object(fault_value["args"], f"{where}.fault.args"),
            )
            calls = tuple(
                _broker_call(call, f"{where}.broker_calls[{call_index}]")
                for call_index, call in enumerate(_sequence(parsed["broker_calls"], f"{where}.broker_calls"))
            )
            expected_value = _exact_keys(
                parsed["expected"],
                {"status", "state", "forbidden_effects"},
                f"{where}.expected",
            )
            if expected_value["state"] is None:
                raise ActivationAcceptanceRefused(f"{where}: state cannot be null")
            forbidden = tuple(
                _text(entry, f"{where}.expected.forbidden_effects")
                for entry in _sequence(
                    expected_value["forbidden_effects"],
                    f"{where}.expected.forbidden_effects",
                    nonempty=False,
                )
            )
            if len(forbidden) != len(set(forbidden)):
                raise ActivationAcceptanceRefused(f"{where}: duplicate forbidden effect")
            expected = ExpectedOutcomeSpec(
                _text(expected_value["status"], f"{where}.expected.status"),
                expected_value["state"],
                forbidden,
            )
            subcases.append(
                SubcaseSpec(
                    invariant_id,
                    subcase_id,
                    fault,
                    calls,
                    expected,
                    _digest(parsed),
                )
            )

        receipts: list[ReceiptSpec] = []
        receipt_types: set[str] = set()
        for index, value in enumerate(_sequence(record["required_receipts"], f"{at}.required_receipts")):
            where = f"{at}.required_receipts[{index}]"
            parsed = _exact_keys(value, {"type", "required_fields"}, where)
            receipt_type = _text(parsed["type"], f"{where}.type")
            fields = tuple(
                _text(field, f"{where}.required_fields")
                for field in _sequence(parsed["required_fields"], f"{where}.required_fields")
            )
            if receipt_type in receipt_types or len(fields) != len(set(fields)):
                raise ActivationAcceptanceRefused(f"{where}: duplicate receipt contract")
            receipt_types.add(receipt_type)
            receipts.append(ReceiptSpec(receipt_type, fields))

        probes: list[ProbeSpec] = []
        for index, value in enumerate(_sequence(record["security_probes"], f"{at}.security_probes")):
            where = f"{at}.security_probes[{index}]"
            parsed = _exact_keys(
                value,
                {"runtime_role", "broker_operations", "expected_enforcement"},
                where,
            )
            source_digest = _digest(parsed)
            probe_id = f"{invariant_id}.probe.{index + 1:02d}.{source_digest[:16]}"
            if probe_id in probe_ids:
                raise ActivationAcceptanceRefused(f"{where}: duplicate probe ID")
            probe_ids.add(probe_id)
            probes.append(
                ProbeSpec(
                    invariant_id,
                    probe_id,
                    _text(parsed["runtime_role"], f"{where}.runtime_role"),
                    tuple(
                        _broker_call(call, f"{where}.broker_operations[{call_index}]")
                        for call_index, call in enumerate(
                            _sequence(
                                parsed["broker_operations"],
                                f"{where}.broker_operations",
                            )
                        )
                    ),
                    _text(
                        parsed["expected_enforcement"],
                        f"{where}.expected_enforcement",
                    ),
                    source_digest,
                )
            )

        cases.append(
            ScenarioSpec(
                task,
                family,
                invariant_id,
                requirement_digest,
                tuple(preconditions),
                operation,
                tuple(subcases),
                tuple(probes),
                tuple(receipts),
                _digest(record),
            )
        )

    result = ClosedAcceptance(
        cases=tuple(cases),
        requirements_digest=requirements_digest,
        ledger_digest=actual_digest,
    )
    if (
        result.task_contracts != (1, 2, 3, 4)
        or result.case_count != 192
        or result.subcase_count != 5230
        or result.probe_count != 552
        or result.observation_count != 5782
        or result.broker_call_count != 16294
    ):
        raise ActivationAcceptanceRefused("closed acceptance cardinality drift")
    return result


def parse_runtime_profile_ledger(
    raw: bytes,
    *,
    expected_ledger_digest: str,
    acceptance_ledger_digest: str,
) -> RuntimeProfileLedger:
    """Parse the exact role-to-runtime-profile assignment ledger."""
    actual_digest = hashlib.sha256(raw).hexdigest()
    if (
        expected_ledger_digest != PINNED_RUNTIME_PROFILE_LEDGER_DIGEST
        or actual_digest != expected_ledger_digest
        or acceptance_ledger_digest != PINNED_ACCEPTANCE_LEDGER_DIGEST
    ):
        raise ActivationAcceptanceRefused("runtime profile ledger digest mismatch")
    value = _exact_keys(
        _strict_json(raw),
        {"schema", "acceptance_sha256", "profiles", "role_assignments"},
        "runtime_profile_ledger",
    )
    if (
        value["schema"] != "galaxy.activation.runtime-profile-ledger/v1"
        or value["acceptance_sha256"] != acceptance_ledger_digest
    ):
        raise ActivationAcceptanceRefused("runtime profile ledger binding mismatch")
    profile_fields = {
        "profile_id",
        "execution_kind",
        "image_role",
        "identity_class",
        "network_mode",
        "credential_mode",
        "filesystem_mode",
        "process_mode",
        "state_store_mode",
        "required_attestations",
    }
    profiles: dict[str, RuntimeProfileSpec] = {}
    for index, item in enumerate(_sequence(value["profiles"], "profiles")):
        at = f"profiles[{index}]"
        record = _exact_keys(item, profile_fields, at)
        profile_id = _text(record["profile_id"], f"{at}.profile_id")
        execution_kind = _text(record["execution_kind"], f"{at}.execution_kind")
        if execution_kind not in {"restricted_os_process", "hardened_container"}:
            raise ActivationAcceptanceRefused(f"{at}: unsupported execution kind")
        image_role = record["image_role"]
        if execution_kind == "hardened_container":
            image_role = _text(image_role, f"{at}.image_role")
        elif image_role is not None:
            raise ActivationAcceptanceRefused(f"{at}: OS profile has image role")
        attestations = tuple(
            _text(entry, f"{at}.required_attestations")
            for entry in _sequence(record["required_attestations"], f"{at}.required_attestations")
        )
        if profile_id in profiles or len(attestations) != len(set(attestations)):
            raise ActivationAcceptanceRefused(f"{at}: duplicate profile data")
        profiles[profile_id] = RuntimeProfileSpec(
            profile_id,
            execution_kind,
            image_role,
            _text(record["identity_class"], f"{at}.identity_class"),
            _text(record["network_mode"], f"{at}.network_mode"),
            _text(record["credential_mode"], f"{at}.credential_mode"),
            _text(record["filesystem_mode"], f"{at}.filesystem_mode"),
            _text(record["process_mode"], f"{at}.process_mode"),
            _text(record["state_store_mode"], f"{at}.state_store_mode"),
            attestations,
        )
    assignments_value = value["role_assignments"]
    if not isinstance(assignments_value, dict):
        raise ActivationAcceptanceRefused("role assignments must be an object")
    assignments: dict[str, str] = {}
    for role, profile_id in assignments_value.items():
        parsed_role = _text(role, "role_assignments.role")
        parsed_profile = _text(profile_id, f"role_assignments.{role}")
        if parsed_profile not in profiles:
            raise ActivationAcceptanceRefused("role references unknown profile")
        assignments[parsed_role] = parsed_profile
    if len(profiles) != 11 or len(assignments) != 498:
        raise ActivationAcceptanceRefused("runtime profile cardinality drift")
    return RuntimeProfileLedger(
        profiles=profiles,
        role_assignments=assignments,
        ledger_digest=actual_digest,
        acceptance_ledger_digest=acceptance_ledger_digest,
    )


def verify_acceptance_candidate(
    candidate: Path,
    *,
    requirements_digest: str,
    acceptance_ledger_digest: str,
    runtime_profile_ledger_digest: str,
) -> ClosedAcceptance:
    """Verify a proposed ledger without granting installation or activation."""
    if runtime_profile_ledger_digest != PINNED_RUNTIME_PROFILE_LEDGER_DIGEST:
        raise ActivationAcceptanceRefused("runtime profile ledger is not approved")
    try:
        raw = candidate.read_bytes()
    except OSError as exc:
        raise ActivationAcceptanceRefused("acceptance candidate is unavailable") from exc
    return parse_closed_acceptance(
        raw,
        expected_ledger_digest=acceptance_ledger_digest,
        requirements_digest=requirements_digest,
    )


