"""workflows.scheduler -- priority queue with deadline-aware slot allocation.

Schedules workflow runs such that:
  - higher-priority items run first
  - when priority is equal, earlier deadlines (EDF) break ties
  - a configurable slot cap limits concurrent executions
  - jobs with unmet dependencies are deferred until their deps complete

Usage::

    scheduler = WorkflowScheduler(max_concurrent=4)
    a = scheduler.enqueue("setup", priority=5)
    scheduler.enqueue("build", priority=2, depends_on=[a.job_id])
    job = scheduler.next()      # pops highest-priority / earliest-deadline item
    scheduler.complete(job.job_id)

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  WorkflowJob  -- One queued workflow execution.
  WorkflowScheduler  -- Deadline-aware priority queue for workflow slot allocation.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_priority_scheduler.py tests/test_scheduler_priority.py
"""
from __future__ import annotations

import heapq
import threading
import time
from dataclasses import dataclass, field
from typing import List, Optional

_DEFAULT_MAX_CONCURRENT: int = 8
_NO_DEADLINE: float = float("inf")


@dataclass
class WorkflowJob:
    """One queued workflow execution."""
    job_id: str
    workflow_name: str
    priority: int          # higher number = higher priority
    deadline: float        # Unix timestamp; float('inf') means no deadline
    enqueued_at: float = field(default_factory=time.time)
    started_at: Optional[float] = None
    depends_on: List[str] = field(default_factory=list)  # job_ids that must complete first

    def isOverdue(self) -> bool:
        return self.deadline < time.time()


class WorkflowScheduler:
    """Deadline-aware priority queue for workflow slot allocation.

    Slot cap: at most *max_concurrent* jobs run simultaneously.  ``next()``
    returns None when all slots are occupied even if items are queued.

    Priority ordering (highest first):
      1. Larger ``priority`` value
      2. Earlier ``deadline`` (EDF) to break ties
      3. Earlier ``enqueued_at`` for identical priority+deadline

    All public methods are thread-safe.
    """

    def __init__(self, max_concurrent: int = _DEFAULT_MAX_CONCURRENT) -> None:
        if max_concurrent < 1:
            raise ValueError("max_concurrent must be >= 1")
        self._max_concurrent = max_concurrent
        self._lock = threading.Lock()
        # Min-heap: (neg_priority, deadline, enqueued_at, job_id) → WorkflowJob
        self._heap: list[tuple] = []
        self._jobs: dict[str, WorkflowJob] = {}
        self._running: set[str] = set()
        self._completed: set[str] = set()  # job_ids that have finished
        self._counter = 0  # monotonic tiebreaker

    # ------------------------------------------------------------------
    # Public interface
    # ------------------------------------------------------------------

    def enqueue(
        self,
        workflow_name: str,
        priority: int = 0,
        deadline: float = _NO_DEADLINE,
        job_id: Optional[str] = None,
        depends_on: Optional[List[str]] = None,
    ) -> WorkflowJob:
        """Add a workflow run to the queue.  Returns the new WorkflowJob.

        ``depends_on`` is a list of job_ids that must be completed before this
        job is eligible to run.  Jobs with unmet dependencies are deferred and
        re-evaluated each time ``next()`` is called.
        """
        with self._lock:
            self._counter += 1
            jid = job_id or f"{workflow_name}-{self._counter}"
            job = WorkflowJob(
                job_id=jid,
                workflow_name=workflow_name,
                priority=priority,
                deadline=deadline,
                depends_on=depends_on or [],
            )
            # Negate priority so Python's min-heap yields highest priority first.
            heapq.heappush(self._heap, (-priority, deadline, job.enqueued_at, jid))
            self._jobs[jid] = job
            return job

    def next(self) -> Optional[WorkflowJob]:
        """Pop and return the next job to execute, or None when no slot is free
        or the queue is empty.  Marks the job as running (occupies a slot).

        Jobs with unmet dependencies are skipped and re-queued for later.
        """
        with self._lock:
            if len(self._running) >= self._max_concurrent:
                return None
            deferred: list[tuple] = []
            result: Optional[WorkflowJob] = None
            while self._heap:
                heap_entry = heapq.heappop(self._heap)
                _, _, _, jid = heap_entry
                job = self._jobs.get(jid)
                if job is None:
                    continue  # cancelled
                if not all(dep in self._completed for dep in job.depends_on):
                    deferred.append(heap_entry)
                    continue
                job.started_at = time.time()
                self._running.add(jid)
                result = job
                break
            for entry in deferred:
                heapq.heappush(self._heap, entry)
            return result

    def complete(self, job_id: str) -> None:
        """Mark a known (running or queued) job as finished, freeing its slot.

        Unknown ids -- never enqueued, or already completed/cancelled -- are
        ignored so ``_completed`` cannot grow without bound from bogus calls.
        """
        with self._lock:
            if job_id not in self._running and job_id not in self._jobs:
                return  # unknown id; nothing to record
            self._running.discard(job_id)
            self._jobs.pop(job_id, None)
            self._completed.add(job_id)

    def cancel(self, job_id: str) -> bool:
        """Remove a queued (not yet started) job.  Returns True if found.

        Cancelling a job that other queued jobs depend on would otherwise leave
        those dependents waiting forever on a dependency that can never complete.
        So dependents are released transitively (dropped from the queue) too.
        """
        with self._lock:
            if job_id in self._running:
                return False  # already running; use complete() when done
            if job_id not in self._jobs:
                return False
            self._releaseDependents(job_id)
            # Heap entries orphaned; cleaned up lazily in next()
            return True

    def _releaseDependents(self, job_id: str) -> None:
        """Drop *job_id* and every queued job transitively depending on it.

        Caller must hold ``self._lock``.  Running dependents are left untouched.
        """
        pending = [job_id]
        while pending:
            jid = pending.pop()
            if jid in self._running or jid not in self._jobs:
                continue
            del self._jobs[jid]
            for other_id, other in self._jobs.items():
                if other_id not in self._running and jid in other.depends_on:
                    pending.append(other_id)

    def overdueJobs(self) -> list[WorkflowJob]:
        """Return queued (not yet started) jobs whose deadline has passed."""
        with self._lock:
            now = time.time()
            return [
                j for j in self._jobs.values()
                if j.job_id not in self._running and j.deadline < now
            ]

    # ------------------------------------------------------------------
    # Introspection
    # ------------------------------------------------------------------

    @property
    def queued_count(self) -> int:
        with self._lock:
            return len(self._jobs) - len(self._running)

    @property
    def running_count(self) -> int:
        with self._lock:
            return len(self._running)

    @property
    def slot_available(self) -> bool:
        with self._lock:
            return len(self._running) < self._max_concurrent
