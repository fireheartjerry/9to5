"""Ownership/interface map: packages, re-export facades, entrypoints, config surface.

Packages = top-level dirs with an ``__init__.py`` or >=3 same-language files.
Facade = a ``.py`` module whose AST holds ONLY imports, an ``__all__`` assignment,
and a docstring (pure re-export). Entrypoints = ``__main__.py`` anywhere, root
``main.py``, and package.json ``main``/``bin``. Config surface = well-known
config file names present at the root.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  detectBoundaries(root, modules) -> BoundaryMap
DEPENDS-ON: introspect.project_model
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/introspect/test_project_boundaries.py
"""
from __future__ import annotations

import ast
import json
import posixpath
from collections import Counter
from pathlib import Path

from introspect.project_model import LANG_PYTHON, BoundaryMap, ModuleInfo

KNOWN_CONFIG_FILES = (
    "pyproject.toml",
    "setup.py",
    "setup.cfg",
    "pytest.ini",
    "tox.ini",
    "requirements.txt",
    "package.json",
    "tsconfig.json",
    "Makefile",
    "Cargo.toml",
    "go.mod",
    "Dockerfile",
)

MIN_PACKAGE_FILES = 3


def detectBoundaries(root: str | Path, modules: list[ModuleInfo]) -> BoundaryMap:
    """Boundary map for ``root`` given its scanned/analyzed modules."""
    root_path = Path(root).resolve()
    return BoundaryMap(
        packages=_packages(root_path, modules),
        facades=_facades(root_path, modules),
        entrypoints=_entrypoints(root_path, modules),
        config_files=tuple(n for n in KNOWN_CONFIG_FILES if (root_path / n).is_file()),
    )


def _packages(root_path: Path, modules: list[ModuleInfo]) -> tuple[str, ...]:
    """Top-level dirs with an __init__.py, or holding >=3 files of one language."""
    lang_counts: dict[str, Counter] = {}
    for mod in modules:
        if "/" not in mod.path:
            continue
        top = mod.path.split("/", 1)[0]
        lang_counts.setdefault(top, Counter())[mod.lang] += 1
    out = []
    for top, counts in sorted(lang_counts.items()):
        if (root_path / top / "__init__.py").is_file() or max(counts.values()) >= MIN_PACKAGE_FILES:
            out.append(top)
    return tuple(out)


def _facades(root_path: Path, modules: list[ModuleInfo]) -> tuple[str, ...]:
    """Python modules whose AST contains only imports / __all__ / docstring."""
    out = []
    for mod in modules:
        if mod.lang == LANG_PYTHON and _isFacade(root_path / mod.path):
            out.append(mod.path)
    return tuple(sorted(out))


def _isFacade(path: Path) -> bool:
    """True when the module is a pure re-export surface (>=1 import, nothing else).

    ``from __future__ import ...`` is allowed but does NOT qualify as the
    re-export import: a docstring + future-import-only file is not a facade.
    """
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except (OSError, SyntaxError):
        return False
    has_import = False
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.module == "__future__":
            continue                                   # tolerated, never qualifying
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            has_import = True
        elif isinstance(node, ast.Assign):
            targets_ok = all(
                isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets
            )
            if not targets_ok:
                return False
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) \
                and isinstance(node.value.value, str):
            continue                                   # docstring
        else:
            return False
    return has_import


def _entrypoints(root_path: Path, modules: list[ModuleInfo]) -> tuple[str, ...]:
    """__main__.py anywhere, root main.py, package.json main/bin scripts."""
    out: set[str] = set()
    for mod in modules:
        if posixpath.basename(mod.path) == "__main__.py" or mod.path == "main.py":
            out.add(mod.path)
    pkg_json = root_path / "package.json"
    if pkg_json.is_file():
        try:
            data = json.loads(pkg_json.read_text(encoding="utf-8", errors="replace"))
            main = data.get("main")
            if isinstance(main, str):
                out.add(main.removeprefix("./"))
            bins = data.get("bin")
            if isinstance(bins, str):
                out.add(bins.removeprefix("./"))
            elif isinstance(bins, dict):
                out.update(str(v).removeprefix("./") for v in bins.values())
        except json.JSONDecodeError:
            pass
    return tuple(sorted(out))
