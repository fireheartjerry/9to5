"""Typed, JSON-round-trippable project model shared by every introspect analyzer.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ModuleInfo(path, lang, loc, exports, imports, lazy_imports, side_effects) -- one source file
  DetectedCommand(kind, cmd, source) -- a command proven by a config file (never guessed)
  BoundaryMap(packages, facades, entrypoints, config_files) -- ownership/interface map
  ProjectModel(root, languages, modules, import_edges, commands, boundaries, truncated, git_head)
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/introspect/test_project_model.py
"""
from __future__ import annotations

import dataclasses
import json
from dataclasses import dataclass

LANG_PYTHON = "python"
LANG_JAVASCRIPT = "javascript"
LANG_TYPESCRIPT = "typescript"
LANG_OTHER = "other"

KIND_TEST = "test"
KIND_BUILD = "build"
KIND_LINT = "lint"
KIND_TYPECHECK = "typecheck"


@dataclass(frozen=True)
class ModuleInfo:
    """One source file: POSIX relpath id + language + analysis results."""

    path: str                            # POSIX relpath from root -- the universal module id
    lang: str
    loc: int
    exports: tuple[str, ...] = ()
    imports: tuple[str, ...] = ()        # first-party imports as relpath module ids
    lazy_imports: tuple[str, ...] = ()   # python in-function imports (not load-time)
    side_effects: tuple[str, ...] = ()   # subset of {"subprocess","file-write","network","env-read"}


@dataclass(frozen=True)
class DetectedCommand:
    """A test/build/lint/typecheck command with the config file that proved it."""

    kind: str        # one of the KIND_* constants
    cmd: str         # e.g. "python -m pytest"
    source: str      # relpath of the config file that proved it (never guessed)


@dataclass(frozen=True)
class BoundaryMap:
    """Ownership/interface map: packages, re-export facades, entrypoints, config surface."""

    packages: tuple[str, ...] = ()       # top-level package dirs
    facades: tuple[str, ...] = ()        # modules that only re-export
    entrypoints: tuple[str, ...] = ()    # __main__.py / main.py / package.json "main" / bin
    config_files: tuple[str, ...] = ()


@dataclass(frozen=True)
class ProjectModel:
    """Full typed model of one project root; JSON round-trip via toJson/fromJson."""

    root: str                            # absolute path, POSIX separators
    languages: tuple[str, ...]           # descending by file count
    modules: tuple[ModuleInfo, ...]
    import_edges: tuple[tuple[str, str], ...]   # (from relpath, to relpath), load-time only
    commands: tuple[DetectedCommand, ...]
    boundaries: BoundaryMap
    truncated: bool = False              # True when max_files cap hit
    git_head: str = ""                   # "" when not a git repo

    def toJson(self) -> str:
        """Serialize to a JSON string (tuples become lists; fromJson restores them)."""
        return json.dumps(dataclasses.asdict(self), indent=1)

    @staticmethod
    def fromJson(text: str) -> "ProjectModel":
        """Rebuild a ProjectModel (with nested frozen dataclasses/tuples) from toJson output."""
        data = json.loads(text)
        return ProjectModel(
            root=data["root"],
            languages=_strTuple(data.get("languages", ())),
            modules=tuple(_moduleFromDict(m) for m in data.get("modules", ())),
            import_edges=tuple(
                (str(e[0]), str(e[1])) for e in data.get("import_edges", ())
            ),
            commands=tuple(_commandFromDict(c) for c in data.get("commands", ())),
            boundaries=_boundariesFromDict(data.get("boundaries", {})),
            truncated=bool(data.get("truncated", False)),
            git_head=str(data.get("git_head", "")),
        )


def _strTuple(items) -> tuple[str, ...]:
    """JSON list -> tuple of strings."""
    return tuple(str(x) for x in items)


def _moduleFromDict(data: dict) -> ModuleInfo:
    """JSON dict -> ModuleInfo with tuple fields restored."""
    return ModuleInfo(
        path=str(data["path"]),
        lang=str(data["lang"]),
        loc=int(data["loc"]),
        exports=_strTuple(data.get("exports", ())),
        imports=_strTuple(data.get("imports", ())),
        lazy_imports=_strTuple(data.get("lazy_imports", ())),
        side_effects=_strTuple(data.get("side_effects", ())),
    )


def _commandFromDict(data: dict) -> DetectedCommand:
    """JSON dict -> DetectedCommand."""
    return DetectedCommand(
        kind=str(data["kind"]), cmd=str(data["cmd"]), source=str(data["source"])
    )


def _boundariesFromDict(data: dict) -> BoundaryMap:
    """JSON dict -> BoundaryMap with tuple fields restored."""
    return BoundaryMap(
        packages=_strTuple(data.get("packages", ())),
        facades=_strTuple(data.get("facades", ())),
        entrypoints=_strTuple(data.get("entrypoints", ())),
        config_files=_strTuple(data.get("config_files", ())),
    )
