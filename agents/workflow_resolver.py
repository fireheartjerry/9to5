"""agents/workflow_resolver.py -- Bridge invocation specs to the centralized WorkflowRegistry.

Provides resolveWorkflowDefinition(spec) which is the single point where the executor
looks up or registers a workflow definition through the registry instead of using raw
inline dicts directly.

Resolution order:
  1. spec["workflow_name"] -> REGISTRY.getWorkflow(name)
  2. spec["workflow_definition"] (inline dict) -> REGISTRY.addWorkflow then REGISTRY.getWorkflow
  3. None if neither present or valid.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  resolveWorkflowDefinition(spec: dict) -> Optional[dict]  -- Return the WorkflowDefinition dict for this spec via the centralized registry.
DEPENDS-ON: src.workflow_registry
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import logging
import sys
from pathlib import Path
from typing import Optional

_REPO_ROOT = Path(__file__).resolve().parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from src.workflow_registry import (  # noqa: E402
    REGISTRY,
    WorkflowNotFoundError,
    WorkflowValidationError,
)

LOG = logging.getLogger("workflow_resolver")


def resolveWorkflowDefinition(spec: dict) -> Optional[dict]:
    """Return the WorkflowDefinition dict for this spec via the centralized registry.

    1. If spec has ``workflow_name``, attempt registry lookup by name.
    2. If spec has inline ``workflow_definition``, register it in REGISTRY (idempotent
       overwrite) and return the stored copy.
    3. Returns None if no valid workflow can be resolved.
    """
    if not isinstance(spec, dict):
        return None

    # Named reference: look up from registry.
    workflow_name: Optional[str] = spec.get("workflow_name")
    if workflow_name:
        try:
            return REGISTRY.getWorkflow(workflow_name)
        except WorkflowNotFoundError:
            LOG.debug("workflow_name '%s' not found in registry; trying inline", workflow_name)

    # Inline definition: register it then return from registry so the registry is always
    # the canonical source during execution.
    wf_def = spec.get("workflow_definition")
    if not isinstance(wf_def, dict) or not wf_def.get("phases"):
        return None

    name: str = wf_def.get("name") or "adhoc"
    try:
        REGISTRY.addWorkflow(name, wf_def)
        return REGISTRY.getWorkflow(name)
    except (WorkflowValidationError, WorkflowNotFoundError):
        LOG.warning("inline workflow_definition validation failed; returning raw dict")
        return wf_def
