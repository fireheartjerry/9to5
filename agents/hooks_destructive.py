"""PreToolUse hook: block destructive Bash commands before they execute.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  blockDestructive(data)  -- PreToolUse: block destructive Bash commands by exiting 2.
DEPENDS-ON: notifications.discord_bot
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import sys
from pathlib import Path as _Path

sys.path.insert(0, str(_Path(__file__).resolve().parent.parent))

# DESTRUCTIVE_PATTERNS now live in the pure classifier so the hook block decision and the
# orchestrator escalation decision derive from ONE taxonomy. Re-exported so existing callers
# (`from agents.hooks import DESTRUCTIVE_PATTERNS`) keep working unchanged.
from platform_core.runtime.action_risk import (  # noqa: E402
    DESTRUCTIVE_PATTERNS, ActionDescriptor, RiskTier, classifyActionRisk,
)


def blockDestructive(data):
    """PreToolUse: block destructive Bash commands by exiting 2.

    Exits 0 when the command is safe (or not a Bash command). Exits 2 when a
    destructive pattern is detected, after best-effort Discord alerting.
    """
    try:
        tool_name = data.get("tool_name", "")
        tool_input = data.get("tool_input", {}) or {}
        command = ""
        if tool_name == "Bash":
            command = tool_input.get("command", "") or ""
    except Exception:
        sys.exit(0)

    if not command:
        sys.exit(0)

    # Shared-taxonomy block decision: classify via the pure classifier; keep the matched-pattern
    # string for the human-readable reason (parity with the legacy message).
    tier = classifyActionRisk(ActionDescriptor(tool_name="Bash", command=command))
    if tier is not RiskTier.DESTRUCTIVE:
        sys.exit(0)
    lowered = command.lower()
    matched = next((pat for pat in DESTRUCTIVE_PATTERNS if pat.lower() in lowered), "destructive")

    reason = f"Blocked destructive command (matched {matched!r}): {command}"

    # (a) best-effort Discord alert -- AUTO-REFUSED safety event, not a human decision.
    try:
        import notifications.discord_bot as discord
        discord.sendEmbed(discord.noticeEmbed(reason, title="🛡️ 9TO5 — auto-refused (safety)"))
    except Exception:
        pass

    # (b) human-readable reason to STDERR.
    try:
        sys.stderr.write(reason + "\n")
    except Exception:
        pass

    # (c) exit code 2 blocks the tool in Claude Code.
    sys.exit(2)
