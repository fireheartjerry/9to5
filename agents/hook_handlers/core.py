"""9TO5 deterministic hook dispatcher.

Claude Code invokes this as:  python agents\\hooks.py <hook_name>
with a JSON event object piped on STDIN.

Failure policy is PER-HOOK, not global:
  * GUARD hooks (block_destructive, self_modification_guard) FAIL CLOSED -- any crash,
    including malformed event JSON, exits 2 and blocks the tool call.
  * All other hooks (telemetry, notify, obsidian) stay FAIL-OPEN (exit 0 on any error)
    so observability can never block work (.claude/rules/orchestration.md).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  discordNotify(data)  -- Notification: forward the message to Discord as a compact embed.
  logAll(data)  -- PostToolUse / any: append one JSON line {time, tool_name} to the log.
  logTelemetry(data)  -- Any Claude hook: append compact non-blocking iteration telemetry.
  main()  -- Dispatch to the requested handler based on argv[1].
DEPENDS-ON: agents.hooks_destructive, agents.hooks_obsidian, agents.hooks_selfmod, config, notifications.discord_bot
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_orch_core_bugs.py tests/slow/test_simulation_core.py
"""

import sys
import json
import logging

LOG = logging.getLogger("hooks")

# Make "import config" (and other project modules) work regardless of cwd.
# Derive the repo root from THIS file's location so hooks always adds ITS OWN tree,
# not a hardcoded install path -- this is correct under any checkout or git worktree.
from pathlib import Path as _Path
sys.path.insert(0, str(_Path(__file__).resolve().parents[2]))

# config is safe to import at module load; project sub-modules are imported
# lazily inside handlers so a broken import can never crash the dispatcher.
try:
    import config  # noqa: F401
except Exception:
    config = None

# ---------------------------------------------------------------------------
# Sub-module imports -- heavy logic lives in focused modules; this file is the
# thin dispatcher layer that wires hook names to handlers.
#
# These top-level imports are ONLY a compatibility facade (callers/tests do
# `from agents.hooks import selfModificationGuard`). They are wrapped so a broken
# guard sub-module can never crash the dispatcher at import time. The DISPATCH path
# re-imports each guard lazily inside main() and, for a BLOCKING guard, fails CLOSED
# (exit 2) on any import/exec error -- so a defeated guard can never silently allow.
# ---------------------------------------------------------------------------
try:
    from agents.hooks_destructive import (  # noqa: E402,F401
        blockDestructive, DESTRUCTIVE_PATTERNS, readHookCtx,
    )
except Exception:  # noqa: BLE001
    blockDestructive = None  # type: ignore[assignment]
    DESTRUCTIVE_PATTERNS = ()  # type: ignore[assignment]
    readHookCtx = lambda: {}  # noqa: E731  -- keeps _hooksLogPath working if the sub-module is broken
try:
    from agents.hooks_obsidian import writeObsidian  # noqa: E402,F401
except Exception:  # noqa: BLE001
    writeObsidian = None  # type: ignore[assignment]
try:
    from agents.hooks_selfmod import (  # noqa: E402,F401
        selfModificationGuard,
        _classifyPath,
        _scanDiff,
        _shouldBlock,
        _resolveState,
        _boundarySetFor,
        _coreLockFor,
        _envTaskRequested,
        _bashHitsBoundary,
    )
except Exception:  # noqa: BLE001
    selfModificationGuard = None  # type: ignore[assignment]
    _classifyPath = _scanDiff = _shouldBlock = _resolveState = None  # type: ignore[assignment]
    _boundarySetFor = _coreLockFor = _envTaskRequested = _bashHitsBoundary = None  # type: ignore[assignment]

# Guard hooks fail CLOSED (exit 2 on any internal error); everything else fails open.
# agents/executor_env.py HOOKS_SPEC registers exactly this set -- test_hooks.py pins parity.
GUARD_HOOKS = frozenset({"block_destructive", "self_modification_guard"})
# Alias kept for callers/tests that refer to the "blocking" framing rather than "guard".
_BLOCKING_HOOKS = GUARD_HOOKS


def _importBlockingGuard(hook_name):
    """Import a BLOCKING guard handler lazily. Raises if the sub-module import fails."""
    if hook_name == "block_destructive":
        from agents.hooks_destructive import blockDestructive as _fn  # noqa: F811
    else:
        from agents.hooks_selfmod import selfModificationGuard as _fn  # noqa: F811
    return _fn


def _runBlockingGuard(hook_name, data):
    """Run a BLOCKING guard, failing CLOSED (exit 2) on any import or exec error.

    A broken guard import previously left the dispatcher failing OPEN (the tool ran).
    For a boundary/destructive guard that is unsafe: exit 2 so the tool call is blocked."""
    try:
        guard = _importBlockingGuard(hook_name)
        guard(data)  # the guard itself exits 0 (allow) or 2 (block)
    except SystemExit:
        raise
    except Exception as e:  # noqa: BLE001
        try:
            sys.stderr.write(f"{hook_name}: guard failed to load/execute, failing closed: {e}\n")
        except Exception:  # noqa: BLE001
            pass
        sys.exit(2)


def _hooksLogPath():
    """hooks.log target: NINE_TO_FIVE_HOOK_CTX override -> config.LOG_PATH -> own-tree logs/.
    No hardcoded install path -- correct under any checkout or git worktree."""
    ctx_path = readHookCtx().get("log_path")
    if ctx_path:
        return _Path(ctx_path)
    if config is not None and getattr(config, "LOG_PATH", None):
        return _Path(config.LOG_PATH) / "hooks.log"
    return _Path(__file__).resolve().parents[2] / "logs" / "hooks.log"


def _readEvent():
    """Read and parse the JSON event piped on STDIN. Never raises (fail-open hooks)."""
    try:
        return _readEventStrict()
    except Exception:
        return {}


def _readEventStrict():
    """Read/parse the STDIN event, RAISING on malformed JSON -- guard hooks must treat an
    undecodable event as un-classifiable and fail CLOSED, never silently allow."""
    raw = sys.stdin.read()
    return json.loads(raw) if raw.strip() else {}


def discordNotify(data):
    """Notification: forward the message to Discord as a compact embed."""
    try:
        message = data.get("message", "") or ""
        import notifications.discord_bot as discord
        discord.sendEmbed(
            {
                "title": "Claude Code notification",
                "color": 3447003,
                "description": message[:1500],
            }
        )
    except Exception as exc:  # noqa: BLE001 -- notification hooks must remain fail-open
        LOG.debug("Discord hook notification skipped: %s", exc)
    sys.exit(0)


def logAll(data):
    """PostToolUse / any: append one JSON line {time, tool_name} to the log."""
    try:
        from datetime import datetime
        from pathlib import Path

        log_path = Path(_hooksLogPath())
        log_path.parent.mkdir(parents=True, exist_ok=True)

        entry = {
            "time": datetime.now().isoformat(timespec="seconds"),
            "tool_name": data.get("tool_name", ""),
        }
        with log_path.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry) + "\n")
    except Exception as exc:  # noqa: BLE001 -- telemetry must never block tool use
        LOG.debug("Hook event log skipped: %s", exc)
    sys.exit(0)


def logTelemetry(data):
    """Any Claude hook: append compact non-blocking iteration telemetry."""
    try:
        sys.path.insert(0, str(_Path(__file__).resolve().parents[2] / "tools"))
        import claude_metrics

        hook_name = sys.argv[1] if len(sys.argv) > 1 else "log_telemetry"
        claude_metrics.record_hook_event(hook_name, data if isinstance(data, dict) else {})
    except Exception as exc:  # noqa: BLE001 -- telemetry must never block tool use
        LOG.debug("Hook metrics skipped: %s", exc)
    sys.exit(0)


def main():
    """Dispatch to the requested handler based on argv[1]."""
    hook_name = sys.argv[1] if len(sys.argv) > 1 else ""
    if hook_name in GUARD_HOOKS:
        # Strict parse: a guard that cannot read its event cannot classify it -- fail CLOSED.
        try:
            data = _readEventStrict()
        except Exception as e:  # noqa: BLE001
            sys.stderr.write(f"{hook_name}: malformed hook event -- failing CLOSED ({e})\n")
            sys.exit(2)
    else:
        data = _readEvent()

    if hook_name in _BLOCKING_HOOKS:
        _runBlockingGuard(hook_name, data)
    elif hook_name == "write_obsidian":
        writeObsidian(data)
    elif hook_name == "discord_notify":
        discordNotify(data)
    elif hook_name == "log_all":
        logAll(data)
    elif hook_name in ("log_telemetry", "user_prompt_telemetry", "stop_telemetry"):
        logTelemetry(data)
    else:
        sys.exit(0)


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception:
        # Absolute last-resort handler. Non-guard hooks NEVER block Claude Code (exit 0);
        # GUARD hooks fail CLOSED (exit 2) -- a crashed guard must block, not allow.
        _hook = sys.argv[1] if len(sys.argv) > 1 else ""
        sys.exit(2 if _hook in GUARD_HOOKS else 0)
