"""PreToolUse hook: block destructive Bash commands before they execute.

FAIL-CLOSED GUARD: if parse or classification crashes, this hook exits 2 (block), never
0 (allow). It imports stdlib + the pure classifier ONLY, so a broken config / notifications
import can never fail the guard open. The safety alert is a fire-and-forget append to
logs/guard_alerts.jsonl (the gateway bot tails and posts) -- NO network I/O in the block path.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  readHookCtx() -> dict  -- Parse the NINE_TO_FIVE_HOOK_CTX env var (JSON: boundaries, log/alert paths).
  writeGuardAlert(hook: str, reason: str) -> None  -- Fire-and-forget guard alert: append one JSON line to guard_alerts.jsonl.
  blockDestructive(data)  -- PreToolUse: block destructive Bash commands by exiting 2.
DEPENDS-ON: platform_core.runtime.action_risk
SIDE-EFFECTS: appends logs/guard_alerts.jsonl when a guard blocks
RUN/TEST: python -m pytest tests/control/test_hooks.py
"""
from __future__ import annotations

import json
import os
import sys
from datetime import datetime
from pathlib import Path as _Path

sys.path.insert(0, str(_Path(__file__).resolve().parents[2]))

# The pattern SOURCE is the one shared taxonomy: the hook block decision, the orchestrator
# escalation decision, and executor_env's headless pre-scan all derive from it.
# DESTRUCTIVE_PATTERNS is re-exported so `from agents.hooks import DESTRUCTIVE_PATTERNS`
# keeps working unchanged.
from platform_core.runtime.action_risk import (  # noqa: E402,F401
    DESTRUCTIVE_PATTERNS, ActionDescriptor, RiskTier, classifyActionRisk, scanDestructive,
)

_REPO_ROOT = _Path(__file__).resolve().parents[2]


def readHookCtx() -> dict:
    """Parse the NINE_TO_FIVE_HOOK_CTX env var (JSON: boundaries, log/alert paths).

    ONE channel for hook context so guard entrypoints never need a config import.
    Never raises; malformed ctx degrades to {} (the guards fall back to own-tree paths)."""
    try:
        raw = os.environ.get("NINE_TO_FIVE_HOOK_CTX", "")
        ctx = json.loads(raw) if raw.strip() else {}
        return ctx if isinstance(ctx, dict) else {}
    except Exception:  # noqa: BLE001
        return {}


def writeGuardAlert(hook: str, reason: str) -> None:
    """Fire-and-forget guard alert: append one JSON line to guard_alerts.jsonl.

    The gateway bot tails this file and posts to Discord OUT of process -- the block path
    itself does no network I/O. Best-effort: a failed append never changes the exit code."""
    try:
        target = readHookCtx().get("guard_alerts") or str(_REPO_ROOT / "logs" / "guard_alerts.jsonl")
        path = _Path(target)
        path.parent.mkdir(parents=True, exist_ok=True)
        entry = {"time": datetime.now().isoformat(timespec="seconds"),
                 "hook": hook, "reason": reason}
        with path.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry) + "\n")
    except Exception:  # noqa: BLE001
        pass


def _emitBlock(reason: str) -> None:
    """Alert (local JSONL, after the block decision) + stderr reason + exit 2."""
    writeGuardAlert("block_destructive", reason)
    try:
        sys.stderr.write(reason + "\n")
    except Exception:  # noqa: BLE001
        pass
    sys.exit(2)


def blockDestructive(data):
    """PreToolUse: block destructive Bash commands by exiting 2.

    Exits 0 only when the call is PROVABLY safe (non-Bash / empty command / non-destructive
    tier). FAIL-CLOSED: any crash in parse or classify exits 2 -- a guard that cannot decide
    must block, not allow.
    """
    command = ""
    try:
        tool_name = (data or {}).get("tool_name", "")
        tool_input = (data or {}).get("tool_input", {}) or {}
        if tool_name == "Bash":
            command = tool_input.get("command", "") or ""
        if not command:
            sys.exit(0)          # not a Bash command / nothing to classify -- provably safe
        tier = classifyActionRisk(ActionDescriptor(tool_name="Bash", command=command))
    except SystemExit:
        raise
    except Exception as e:  # noqa: BLE001
        # FAIL CLOSED: we could not prove the call safe (parser or classifier crashed).
        _emitBlock(f"block_destructive: classification crashed -- failing CLOSED "
                   f"({e.__class__.__name__}: {e}); command={command!r}")

    if tier is not RiskTier.DESTRUCTIVE:
        sys.exit(0)

    hits = scanDestructive(command)
    matched = hits[0] if hits else "destructive"
    _emitBlock(f"Blocked destructive command (matched {matched!r}): {command}")
