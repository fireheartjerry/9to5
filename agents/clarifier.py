"""Clarifier -- the Orchestrator brain answers the Executor's questions, no human.

Headless Claude (``--print --dangerously-skip-permissions``) never pauses for a
permission prompt, but it CAN punt in its *text*: "I'm not sure whether...",
"which approach do you want?", "please clarify...". Left unanswered, the subtask
verify fails and the run burns retries re-sending the same prompt. Instead we
detect that the executor is asking, hand its words to the local Ollama brain, and
fold a decisive answer into the next attempt -- so 9to5 unblocks itself.

Design: pure functions. ``detectClarificationNeeded`` is a cheap regex pass;
``answerClarifications`` takes the orchestrator's own ``_ollamaChat`` callable so
this module never imports the ollama client or config-coupled state.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  detectClarificationNeeded(text: str) -> list[str]  -- Return the snippets where the executor appears to be asking a human to decide.
  answerClarifications(chat: Callable, goal: str, subtask: dict, claude_output: str, questions: list[str]) -> Optional[str]  -- Ask the Ollama brain (via the orchestrator's ``_ollamaChat`` callable) to answer the
DEPENDS-ON: config, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_clarifier.py
"""
from __future__ import annotations

import re
from typing import Callable, Optional

import config
import llm_io

LOG = config.getLogger("clarifier")

# Strong signals that the executor is deferring a DECISION to a human rather than acting.
# Conservative on purpose: a false positive only costs one extra (cheap, local) Ollama call
# plus an injected answer; a false negative stalls the whole subtask.
_SIGNALS = (
    r"i'?m not sure\b",
    r"i am not sure\b",
    r"\bunclear\b",
    r"\bambiguous\b",
    r"could you (?:please )?clarify",
    r"please clarify",
    r"need(?:s|ed)? (?:more )?clarif",
    r"need(?:s|ed)? (?:more|further|additional) (?:information|context|detail)",
    r"without (?:more|further|additional) (?:information|context|clarif|detail)",
    r"which (?:approach|option|one|way) (?:do you|would you|should)",
    r"do you want me to",
    r"would you like me to",
    r"should i\b.*\?",
    r"let me know (?:if|whether|which|what|how)",
    r"could go either way",
    r"multiple (?:approaches|options|ways)\b",
    r"please (?:confirm|advise|specify|decide)",
)
_SIGNAL_RE = re.compile("|".join(_SIGNALS), re.IGNORECASE)

# A line that is a direct question aimed at a human ('...you...?' / 'which...?' / 'should...?').
_QUESTION_LINE_RE = re.compile(
    r"^.{0,200}\b(?:you|which|should|shall|do|would|could|prefer)\b.{0,200}\?\s*$",
    re.IGNORECASE,
)

CLARIFIER_SYSTEM = (
    "You are the 9to5 Orchestrator brain. The Executor (Claude Code) did not finish the "
    "subtask -- instead it asked questions or expressed uncertainty. Your job: answer DECISIVELY "
    "so it can proceed with ZERO human input.\n"
    "Rules:\n"
    "- Make concrete choices. Never punt back to a human. Never ask a question.\n"
    "- Pick the most sensible default consistent with the goal, the subtask, and the project "
    "conventions (ALL_CAPS constants, snake_case variables, camelCase functions, pathlib.Path).\n"
    "- Prefer the simplest approach that satisfies the subtask's acceptance/verify check.\n"
    "- Stay strictly inside the subtask's scope; do not invent new requirements.\n"
    "- Output ONLY the answer as direct, imperative instructions to the Executor (a few sentences "
    "or short bullets). No preamble, no questions, no markdown headers."
)


def detectClarificationNeeded(text: str) -> list[str]:
    """Return the snippets where the executor appears to be asking a human to decide.
    Empty list => the executor was acting, not asking (the common case)."""
    if not text:
        return []
    hits: list[str] = []
    if _SIGNAL_RE.search(text):
        for m in _SIGNAL_RE.finditer(text):
            seg = text[max(0, m.start() - 40): m.end() + 80].strip().replace("\n", " ")
            if seg and seg not in hits:
                hits.append(seg)
            if len(hits) >= 5:
                break
    # also catch bare question lines directed at a human
    if not hits:
        for line in text.splitlines():
            line = line.strip()
            if 8 <= len(line) <= 400 and _QUESTION_LINE_RE.match(line):
                hits.append(line)
                if len(hits) >= 5:
                    break
    return hits


def answerClarifications(chat: Callable, goal: str, subtask: dict, claude_output: str,
                         questions: list[str]) -> Optional[str]:
    """Ask the Ollama brain (via the orchestrator's ``_ollamaChat`` callable) to answer the
    executor's questions. Returns a decisive instruction string, or None on failure/empty."""
    if not questions:
        return None
    verify = (subtask.get("verify") or {})
    user = (
        f"GOAL:\n{(goal or '').strip()[:1500]}\n\n"
        f"SUBTASK: {subtask.get('subtask_id')} -- {subtask.get('title')}\n"
        f"{(subtask.get('description') or '').strip()[:1200]}\n\n"
        f"ACCEPTANCE CHECK (the subtask is DONE only when this passes): "
        f"{verify.get('cmd') or '(none)'} (expect: {verify.get('expect') or 'exit_zero'})\n\n"
        f"THE EXECUTOR ASKED / WAS UNSURE ABOUT:\n- " + "\n- ".join(questions[:5]) + "\n\n"
        f"EXECUTOR OUTPUT (tail):\n{(claude_output or '')[-1500:]}\n\n"
        "Answer every question decisively so it can finish autonomously."
    )
    try:
        resp = chat(CLARIFIER_SYSTEM, user)
    except Exception as e:  # noqa: BLE001
        LOG.warning("clarifier ollama call raised: %s", e)
        return None
    if not resp:
        return None
    # Safe extraction (CB-2): a present-but-None content (empty/tool-call Message) must not make
    # `.strip()` raise AttributeError out of _executeSubtask, forfeiting a subtask's retries.
    # llm_io.responseText handles dict AND pydantic ChatResponse AND every malformed shape.
    answer = llm_io.responseText(resp).strip()
    return answer or None
