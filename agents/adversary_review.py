"""Shared adversary internals: constants, helpers, and the Ollama text-review path.

Import via ``agents.adversary``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  systemFor(review_type: str='subtask') -> str  -- The system prompt for a given touchpoint: the one schema + a type-specific lead-in.
  isCdpTransient(exc: BaseException) -> bool  -- True when ``exc`` looks like a transient CDP/network hiccup worth retrying.
  shouldTrigger(executor_output: str, subtask_position: int, attempt_count: int=1, pre_pr: bool=False) -> tuple[bool, str]  -- Return ``(triggered, reason)``.
  review(subtask_title: str, trigger_reason: str, executor_output: str, *, ollama_chat: Optional[Callable]=None, goal: str='', review_type: str='subtask') -> dict  -- Critique the executor output and return a verdict dict.
DEPENDS-ON: config, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import json
import re
import time
from typing import Callable, Optional

import config
import llm_io

LOG = config.getLogger("adversary")

# Vocabulary aligned with notifications.discord_bot._APPROVED / _CHALLENGED.
_APPROVED = "approved"
_CHALLENGED = "challenged"
_CHALLENGE_WORDS = {"challenged", "rejected", "reject", "blocked", "fail", "concern"}

# Cap how much executor output we hand the brain; the rest is noise for review.
ADVERSARY_MAX_OUTPUT_CHARS = 6000

# Retry knobs: up to CDP_MAX_RETRIES extra attempts on transient transport errors.
CDP_MAX_RETRIES: int = 2
CDP_RETRY_BACKOFF_BASE: float = 1.0

# Error substrings that identify transient network/API failures worth retrying.
_CDP_TRANSIENT_SIGNALS: tuple[str, ...] = (
    "timeout", "timed out", "net::", "connection", "socket", "reset", "disconnect",
    "econnrefused", "unreachable", "unavailable", "503", "502", "500", "deadline",
)

_SYSTEM = (
    "You are the 9TO5 Adversary: a strict, independent reviewer of work just produced by an "
    "executor agent. You did NOT do the work and have no stake in approving it. Judge ONLY what "
    "the output evidences: did it actually accomplish the task, or did it cut corners, leave "
    "TODOs, fake/skip verification, mis-handle errors, or drift off-scope? Be skeptical but fair "
    "-- do not invent problems. Respond with JSON ONLY, no prose, exactly this shape:\n"
    '{"verdict": "approved" | "challenged", '
    '"severity": "none" | "low" | "medium" | "high", '
    '"must_fix": ["specific, actionable fix the executor must make", ...], '
    '"suggested_fix": "one concrete suggestion (may be empty)", '
    '"confidence": 0.0-1.0, '
    '"concerns": ["short, specific concern", ...], '
    '"notes": "one or two sentences of rationale"}\n'
    'Use "challenged" when there is real evidence of incomplete, incorrect, unsafe, or off-scope '
    'work; otherwise "approved" with empty concerns/must_fix and severity "none". Set "severity" '
    'to "high" only for work that is broken, unsafe, or clearly fails the task -- this is the bar '
    'that holds a PR. "must_fix" items feed directly into the executor\'s next attempt, so make '
    'each one precise and verifiable.'
)

# Per-review-type guidance appended to _SYSTEM. Verdict schema lives ONLY in _SYSTEM.
REVIEW_GUIDANCE: dict[str, str] = {
    "subtask": "You are reviewing one subtask's executor output.",
    "plan": ("You are reviewing a PROPOSED PLAN (an ordered subtask list) BEFORE any execution. "
             "Judge completeness, ordering, missing steps, and scope. 'must_fix' = plan changes."),
    "architecture": ("You are reviewing an ARCHITECTURE/DESIGN document before planning. Judge "
                     "soundness, risk, and feasibility. 'must_fix' = design changes."),
    "pre_pr_diff": ("You are reviewing the FINAL git diff of the whole change before a PR is "
                    "opened. Judge correctness, safety, scope, and leftover debt. A 'high' "
                    "severity holds the PR."),
}

_APPROVE_WORDS = {"approved", "approve", "pass", "passed", "ok", "okay", "accept", "accepted",
                  "lgtm"}


def systemFor(review_type: str = "subtask") -> str:
    """The system prompt for a given touchpoint: the one schema + a type-specific lead-in."""
    guidance = REVIEW_GUIDANCE.get(review_type, REVIEW_GUIDANCE["subtask"])
    return f"{_SYSTEM}\n\n{guidance}"


def isCdpTransient(exc: BaseException) -> bool:
    """True when ``exc`` looks like a transient CDP/network hiccup worth retrying."""
    msg = str(exc).lower()
    return any(s in msg for s in _CDP_TRANSIENT_SIGNALS)


def shouldTrigger(executor_output: str, subtask_position: int,
                  attempt_count: int = 1, pre_pr: bool = False) -> tuple[bool, str]:
    """Return ``(triggered, reason)``."""
    text = (executor_output or "").lower()
    for phrase in config.ADVERSARY_TRIGGER_PHRASES:
        if phrase in text:
            return True, f"uncertainty phrase detected: '{phrase}'"
    if attempt_count >= config.MAX_SUBTASK_ATTEMPTS:
        return True, f"{attempt_count} attempts on the same subtask"
    if pre_pr:
        return True, "pre-PR safety review"
    if subtask_position > 0 and subtask_position % config.ADVERSARY_HEARTBEAT_EVERY == 0:
        return True, f"heartbeat: every {config.ADVERSARY_HEARTBEAT_EVERY}rd subtask"
    return False, ""


def _loadJsonLoose(content: object):
    """Parse a brain JSON reply tolerating a ```json fence or prose around the object.

    Critical for the Adversary (FX-5): a real 'challenged' verdict wrapped in a
    fence/prose must NOT silently fail json.loads and degrade to a conservative
    'approved', which would neuter the PR-hold and remediation.
    Returns a dict or None.
    """
    if isinstance(content, dict):
        return content
    if not isinstance(content, str):
        return None
    text = content.strip()
    if not text:
        return None
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text, flags=re.IGNORECASE).strip()
    try:
        return json.loads(text)
    except Exception:  # noqa: BLE001
        pass
    # Salvage the FIRST balanced object. The naive greedy r"\{.*\}" spans first '{' to LAST '}'
    # so multi-object output concatenates into an unparseable blob; the balanced walker closes
    # at the correct depth-0 '}'.
    chunk = llm_io._firstBalancedObject(text)
    if chunk:
        try:
            return json.loads(chunk)
        except Exception:  # noqa: BLE001
            return None
    return None


def _normalizeVerdict(raw: object) -> Optional[str]:
    """Collapse model phrasing into the two-valued contract, or None when absent/unrecognizable.

    A None MUST fail closed at the caller (conservative stub) -- never treated as 'approved',
    otherwise a real 'challenged' expressed off-contract would silently neuter the PR-hold (FX-5).
    """
    if raw is None:
        return None
    v = str(raw).strip().lower()
    if not v:
        return None
    if any(w in v for w in _CHALLENGE_WORDS):
        return _CHALLENGED
    if v in _APPROVE_WORDS or v.startswith(("approve", "pass", "accept")):
        return _APPROVED
    return None


def _stubReview(trigger_reason: str, *, note: Optional[str] = None) -> dict:
    """Conservative fallback: approve, but mark it as un-reviewed so it is never
    mistaken for a real pass. Used when no brain is wired or the brain errors."""
    return {
        "verdict": _APPROVED,
        "trigger_reason": trigger_reason,
        "concerns": [],
        "notes": note or ("Adversary brain unavailable; auto-approved without a real critique. "
                          "Phase 2 -> Gemini via the google-genai SDK."),
        "stub": True,
        "severity": "none",
        "must_fix": [],
        "suggested_fix": "",
        "confidence": None,
    }


def _buildReviewUser(subtask_title: str, trigger_reason: str, executor_output: str,
                     goal: str) -> str:
    """The user-turn prompt handed to whichever brain reviews -- single source so paths can't drift."""
    return (
        f"Subtask under review: {subtask_title}\n"
        f"Why this review fired: {trigger_reason}\n"
        f"Overall goal: {goal[:1000]}\n\n"
        f"Executor output to judge:\n{(executor_output or '')[:ADVERSARY_MAX_OUTPUT_CHARS]}\n\n"
        "Return the review JSON."
    )


def _richFields(data: dict, verdict: str) -> dict:
    """Extract the rich-verdict fields with back-compatible defaults (missing => old behavior)."""
    sev = str(data.get("severity") or "").strip().lower()
    if sev not in ("none", "low", "medium", "high"):
        sev = "none" if verdict == _APPROVED else "medium"
    must_fix = [str(m) for m in (data.get("must_fix") or []) if str(m).strip()][:10]
    try:
        conf = float(data["confidence"]) if data.get("confidence") is not None else None
    except (TypeError, ValueError):
        conf = None
    return {
        "severity": sev,
        "must_fix": must_fix,
        "suggested_fix": str(data.get("suggested_fix") or "").strip(),
        "confidence": conf,
    }


def _parseVerdict(raw_content: object, trigger_reason: str, *, surface: str,
                  review_type: str = "subtask") -> dict:
    """Turn a brain's raw JSON reply into the verdict contract. Raises on junk so the
    caller can degrade to a conservative stub."""
    data = _loadJsonLoose(raw_content)
    if not isinstance(data, dict):
        raise ValueError("non-object review payload")
    verdict = _normalizeVerdict(data.get("verdict"))
    if verdict is None:
        raise ValueError(f"missing or unrecognized verdict: {data.get('verdict')!r}")
    concerns = [str(c) for c in (data.get("concerns") or []) if str(c).strip()][:10]
    notes = str(data.get("notes") or "").strip()
    return {
        "verdict": verdict,
        "trigger_reason": trigger_reason,
        "concerns": concerns,
        "notes": notes,
        "stub": False,
        "surface": surface,
        "review_type": review_type,
        **_richFields(data, verdict),
    }


def review(subtask_title: str, trigger_reason: str, executor_output: str, *,
           ollama_chat: Optional[Callable] = None, goal: str = "",
           review_type: str = "subtask") -> dict:
    """Critique the executor output and return a verdict dict.

    ``ollama_chat`` is the orchestrator's resilient Ollama caller
    ``(system, user, *, want_json=False) -> resp | None``. When it is None
    the reviewer degrades to a conservative auto-approve so the run is never
    blocked by the reviewer itself.
    """
    if ollama_chat is None:
        LOG.info("Adversary (no brain) for '%s' (%s) -> approved [stub]",
                 subtask_title, trigger_reason)
        return _stubReview(trigger_reason)

    user = _buildReviewUser(subtask_title, trigger_reason, executor_output, goal)
    try:
        resp = ollama_chat(systemFor(review_type), user, want_json=True)
        content = llm_io.responseText(resp) or None
        data = _loadJsonLoose(content)
        if not isinstance(data, dict):
            raise ValueError("non-object review payload")
        verdict = _normalizeVerdict(data.get("verdict"))
        if verdict is None:
            raise ValueError(f"missing or unrecognized verdict: {data.get('verdict')!r}")
        concerns = [str(c) for c in (data.get("concerns") or []) if str(c).strip()][:10]
        notes = str(data.get("notes") or "").strip()
        LOG.info("Adversary verdict for '%s' (%s) -> %s (%d concern(s))",
                 subtask_title, trigger_reason, verdict, len(concerns))
        return {
            "verdict": verdict,
            "trigger_reason": trigger_reason,
            "concerns": concerns,
            "notes": notes,
            "stub": False,
            "surface": "ollama",
            "review_type": review_type,
            **_richFields(data, verdict),
        }
    except Exception as e:  # noqa: BLE001
        LOG.warning("Adversary brain critique failed (%s); conservative auto-approve", e,
                    exc_info=True)
        return _stubReview(trigger_reason,
                           note=f"Adversary critique errored ({e}); auto-approved conservatively.")
