def _prepareEnv(spec: dict, work_dir, task_state, subtask, system_prompt, extra,
                resume_session) -> dict:
    """Set up work dir, playbook, CLAUDE.md, and compose prompts. Returns a context dict."""
    work = str(work_dir) if work_dir else str(config.PROJECT_ROOT)
    Path(work).mkdir(parents=True, exist_ok=True)
    effort = (spec.get("effort_level") or "default").lower()
    flag = effortFlag(effort)

    # Role-scoped executor playbook -- DETERMINISTIC, no-forget expertise for the hands.
    # Only for real subtask execution (skip internal calls that pass their own system_prompt,
    # e.g. the architect phase). Injected via BOTH the living CLAUDE.md and --append-system-prompt.
    profile, playbook_md, charter = None, "", ""
    if config.EXECUTOR_PLAYBOOK_ENABLED and subtask is not None and system_prompt is None:
        try:
            profile = playbook.classifyProfile(spec, subtask, task_state)
            playbook_md = playbook.buildPlaybook(profile)
            if config.EXECUTOR_APPEND_SYSTEM_PROMPT:
                charter = playbook.buildCharter(profile)
        except Exception as e:  # noqa: BLE001 -- briefing must never break a run
            LOG.warning("executor playbook build failed: %s", e)

    # Living CLAUDE.md (only when we have task context)
    claude_md_path = None
    if task_state is not None:
        try:
            claude_md_path = str(writeClaudioMd(
                task_state, subtask, spec.get("claude_md_inject", ""),
                work, executor_playbook=playbook_md))
        except Exception as e:  # noqa: BLE001
            LOG.warning("writeClaudioMd failed: %s", e)

    full_prompt = _composePrompt(spec, system_prompt, extra)

    # Resume context: on --resume Claude continues the session and does NOT re-read CLAUDE.md,
    # so fold the (re-authored) claude_md_inject into the prompt and DROP the charter flag.
    is_resume = bool(resume_session and config.EXECUTOR_RESUME_RETRIES)
    inject = (spec.get("claude_md_inject") or "").strip()
    resume_prompt = full_prompt
    if is_resume and inject:
        resume_prompt = ("## Updated context for this retry (CLAUDE.md is not re-read on resume)\n"
                         + inject + "\n\n---\n\n" + full_prompt)
    return {
        "work": work, "effort": effort, "flag": flag, "profile": profile,
        "playbook_md": playbook_md, "charter": charter, "claude_md_path": claude_md_path,
        "full_prompt": full_prompt, "resume_prompt": resume_prompt, "is_resume": is_resume,
    }


def _buildRunConfig(spec: dict, task_state, subtask, resume_session: Optional[str], *,
                    work: str, effort: str, flag, charter: str,
                    claude_md_path,
                    parent_trajectory_step_id: Optional[str] = None
                    ) -> "tuple[list, list | None, dict, int, str]":
    """Build CLI command lists, OS env, and process flags. Raises FileNotFoundError on missing CLI.

    Returns (fresh_cmd, resume_cmd, env, creationflags, model)."""
    launcher = _resolveClaudeLauncher()   # raises FileNotFoundError if claude not on PATH
    base_cmd = launcher + ["--print", "--dangerously-skip-permissions"]
    if config.EXECUTOR_OUTPUT_JSON:
        base_cmd += ["--output-format", "json"]
    # Guard hooks must be registered for EVERY executor run: compose the per-run settings file
    # (base settings + generated guard-hook block; survives a missing/corrupt base) instead of
    # trusting the repo settings.json to still carry the hooks.
    try:
        base_cmd += ["--settings", str(composeRunSettings())]
    except Exception as e:  # noqa: BLE001 -- fall back to the raw settings file, never skip guards silently
        LOG.warning("composeRunSettings failed (%s); falling back to raw settings path", e)
        if config.CLAUDE_SETTINGS_PATH.exists():
            base_cmd += ["--settings", str(config.CLAUDE_SETTINGS_PATH)]
    # Smart model routing: pick the cheapest model that can handle this effort level.
    # low→haiku, default/high→sonnet, xhigh/ultracode→opus. Overridable via MODEL_* env vars.
    model = config.MODEL_BY_EFFORT.get(effort, config.MODEL_BY_EFFORT.get("default", config.PRIMARY_MODEL))
    base_cmd += ["--model", model, "--fallback-model", config.FALLBACK_MODEL]
    if not getattr(config, "GALAXY_R3_POLICY_ENFORCEMENT_ENABLED", False):
        max_budget = spec.get("max_budget_usd") if isinstance(spec, dict) else None
        max_budget = max_budget if max_budget is not None else getattr(config, "CLAUDE_MAX_BUDGET_USD", 0.0)
        try:
            budget = float(max_budget or 0.0)
            if budget > 0:
                base_cmd += ["--max-budget-usd", str(budget)]
        except (TypeError, ValueError):
            LOG.warning("ignoring invalid Claude max budget: %r", max_budget)
    if flag:
        base_cmd += ["--effort", flag]
    base_cmd += ["--add-dir", str(config.PROJECT_ROOT)]   # make .claude discoverable from a sub-cwd
    # Epic 2: a read-only spec (the independent verifier) is denied Edit/Write at the hands layer, so
    # read-only is enforced by the tools layer -- not just the prompt -- same mechanism as the
    # CORE_PROTECTED_FILES self-ref disallow below. Clarification probes are stricter: they gather
    # evidence for high-risk unknowns, so deny Bash too instead of trusting shell-command policing.
    if isinstance(spec, dict) and spec.get("read_only"):
        base_cmd += ["--disallowedTools", "Edit", "Write"]
        if spec.get("clarification_probe"):
            base_cmd += ["--disallowedTools", "Bash"]
    if (task_state is not None and getattr(task_state, "meta", {}).get("is_self_referential")
            and not getattr(config, "SELFMOD_ALLOW_CORE", False)):
        for core in config.CORE_PROTECTED_FILES:
            core_abs = str(config.PROJECT_ROOT / core)
            base_cmd += ["--disallowedTools", f"Edit({core_abs})", f"Write({core_abs})"]
    fresh_cmd = base_cmd + (["--append-system-prompt", charter] if charter else [])
    is_resume = bool(resume_session and config.EXECUTOR_RESUME_RETRIES)
    resume_cmd = (base_cmd + ["--resume", resume_session]) if is_resume else None
    # New process group so the timeout path can kill the WHOLE tree (launcher + node grandchildren).
    creationflags = subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0
    # Identify the active task to the hooks via env -- so PreToolUse guards resolve THIS task's
    # hard_boundaries deterministically instead of TaskState.loadLatest() guessing. The absolute
    # state-FILE path is exported too, so the hook (whose hardcoded config.STATE_DIR may point at a
    # different root in a worktree run) loads the right task without a STATE_DIR mismatch.
    env = os.environ.copy()
    if getattr(config, "GALAXY_R3_POLICY_ENFORCEMENT_ENABLED", False):
        for name in CLAUDE_BILLING_OVERRIDE_ENV:
            env.pop(name, None)
    # ONE channel for guard-hook context: boundaries + log/alert paths (see executor_env.buildHookCtxEnv).
    try:
        universe = (getattr(task_state, "meta", None) or {}).get("universe") or {}
        env["NINE_TO_FIVE_HOOK_CTX"] = buildHookCtxEnv(universe.get("hard_boundaries") or [])
    except Exception:  # noqa: BLE001 -- guards fall back to their own config resolution
        pass
    if task_state is not None and getattr(task_state, "task_id", None):
        env["NINE_TO_FIVE_TASK_ID"] = str(task_state.task_id)
        env["NINE_TO_FIVE_PROJECT_ROOT"] = str(config.PROJECT_ROOT)
        try:
            env["NINE_TO_FIVE_TASK_FILE"] = str(task_state.path())
        except Exception:  # noqa: BLE001
            pass
    if subtask is not None and subtask.get("subtask_id"):
        env["NINE_TO_FIVE_SUBTASK_ID"] = str(subtask.get("subtask_id"))
    # eliza spawn-link: only the CHILD's env carries the parent trajectory step id, so concurrent
    # workers never race a process-global var. Absent id -> ensure no stale value is inherited.
    if parent_trajectory_step_id:
        env["NINE_TO_FIVE_PARENT_TRAJECTORY_STEP_ID"] = str(parent_trajectory_step_id)
    else:
        env.pop("NINE_TO_FIVE_PARENT_TRAJECTORY_STEP_ID", None)
    return fresh_cmd, resume_cmd, env, creationflags, model


def _applyEnvironment(fresh_cmd: list, resume_cmd: "list | None", work: str,
                      environment, env_handle) -> "tuple[list, list | None, str]":
    """Route the built run_cmd(s) INTO a provisioned environment via its wrapLauncher.
    Default (environment/env_handle None) is a pure identity -> zero behavior change (fabric off)."""
    if environment is None or env_handle is None:
        return fresh_cmd, resume_cmd, work
    wrapped_fresh, new_work = environment.wrapLauncher(fresh_cmd, env_handle)
    wrapped_resume = None
    if resume_cmd is not None:
        wrapped_resume, _ = environment.wrapLauncher(resume_cmd, env_handle)
    return wrapped_fresh, wrapped_resume, new_work


