class ChatGptBrowserError(RuntimeError):
    """Controlled failure for the experimental browser driver."""


def _http_json(url: str, timeout: float) -> dict[str, Any] | None:
    try:
        with legacyDiagnosticUrlopen(url, timeout=timeout) as resp:
            return json.loads(resp.read().decode("utf-8", errors="replace"))
    except (urllib.error.URLError, TimeoutError, json.JSONDecodeError, OSError):
        return None


def _port_listening(port: int, timeout: float = 0.5) -> bool:
    with legacyDiagnosticSocket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(timeout)
        return sock.connect_ex(("127.0.0.1", port)) == 0


def _run(cmd: list[str], *, cwd: Path | None = None, timeout: float = 15.0) -> subprocess.CompletedProcess[str]:
    return runLegacyProcess(
        cmd,
        cwd=str(cwd) if cwd else None,
        capture_output=True,
        text=True,
        timeout=timeout,
        check=False,
    )


def _git_repo_root() -> Path:
    here = Path(__file__).resolve().parent.parent.parent
    res = _run(["git", "rev-parse", "--show-toplevel"], cwd=here)
    if res.returncode != 0:
        raise ChatGptBrowserError("Not inside a git repo; cannot verify the profile ignore rule safely.")
    return Path(res.stdout.strip())


def _verify_profile_is_gitignored(profile: Path) -> str:
    repo_root = _git_repo_root()
    try:
        rel = profile.resolve().relative_to(repo_root.resolve())
    except ValueError as exc:
        raise ChatGptBrowserError("Profile path must live inside the repo so gitignore can protect it.") from exc
    rel_text = str(rel).replace("\\", "/").rstrip("/") + "/"
    res = _run(["git", "check-ignore", "-v", "--", rel_text], cwd=repo_root)
    if res.returncode != 0:
        raise ChatGptBrowserError(f"Refusing to use profile path until gitignored: {profile}")
    return (res.stdout.strip().splitlines() or [""])[0]


def _verify_profile_dir(profile: Path) -> None:
    if not observeLegacyPath(profile.exists):
        raise ChatGptBrowserError(f"Profile path missing: {profile}")
    if not observeLegacyPath(profile.is_dir):
        raise ChatGptBrowserError(f"Profile path is not a directory: {profile}")


def _chrome_process_rows() -> list[str]:
    script = (
        "Get-CimInstance Win32_Process -Filter \"Name = 'chrome.exe'\" | "
        "ForEach-Object { \"$($_.ProcessId)`t$($_.CommandLine)\" }"
    )
    res = _run(["powershell", "-NoProfile", "-Command", script], timeout=20.0)
    if res.returncode != 0:
        return []
    return [line.strip() for line in res.stdout.splitlines() if line.strip()]


def _existing_dedicated_chrome(port: int, profile: Path) -> bool:
    debug_flag = f"--remote-debugging-port={port}"
    profile_flag = f"--user-data-dir={profile}"
    for row in _chrome_process_rows():
        if debug_flag in row and profile_flag in row:
            return True
    return False


def _debug_endpoint_ok(port: int) -> dict[str, Any] | None:
    info = _http_json(f"http://127.0.0.1:{port}/json/version", timeout=2.0)
    if not info:
        return None
    browser_name = str(info.get("Browser", ""))
    ws_url = str(info.get("webSocketDebuggerUrl", ""))
    if "Chrome/" not in browser_name:
        return None
    if not ws_url.startswith(f"ws://127.0.0.1:{port}/"):
        return None
    return info


def _launch_chrome(
    *,
    chrome: Path,
    profile: Path,
    project_url: str,
    debug_port: int,
) -> None:
    if not observeLegacyPath(chrome.exists):
        raise ChatGptBrowserError(f"Chrome executable missing: {chrome}")
    launch_args = [
        f"--user-data-dir={profile}",
        f"--remote-debugging-port={debug_port}",
        "--no-first-run",
        "--no-default-browser-check",
        "--new-window",
        project_url,
    ]
    popenLegacyProcess(
        [str(chrome), *launch_args],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )


def _ensure_debuggable_chrome(
    *,
    chrome: Path,
    profile: Path,
    project_url: str,
    debug_port: int,
    timeout_s: float,
) -> str:
    info = _debug_endpoint_ok(debug_port)
    if info and _existing_dedicated_chrome(debug_port, profile):
        return "reused"
    if info and not _existing_dedicated_chrome(debug_port, profile):
        raise ChatGptBrowserError(
            f"Debug port {debug_port} is already occupied by a browser that is not provably "
            "the dedicated recon profile. Stop it or choose another port."
        )
    if _port_listening(debug_port):
        raise ChatGptBrowserError(
            f"Debug port {debug_port} is occupied by a non-Chrome service. Choose another port."
        )
    _launch_chrome(chrome=chrome, profile=profile, project_url=project_url, debug_port=debug_port)
    deadline = time.time() + min(timeout_s, 20.0)
    while time.time() < deadline:
        if _debug_endpoint_ok(debug_port) and _existing_dedicated_chrome(debug_port, profile):
            return "launched"
        time.sleep(0.5)
    raise ChatGptBrowserError("Chrome launched but the local debug endpoint never became ready.")


def _safe_title(page: Any) -> str:
    try:
        return str(page.title())
    except Exception:
        return ""


def _page_text_contains(page: Any, needles: tuple[str, ...]) -> bool:
    try:
        text = str(page.locator("body").inner_text(timeout=2000)).lower()
    except Exception:
        return False
    return any(needle in text for needle in needles)


def _visible_count(locator: Any) -> int:
    try:
        return locator.count()
    except Exception:
        return 0


def _is_login_blocked(page: Any) -> bool:
    title = _safe_title(page).lower()
    url = str(page.url).lower()
    if "login" in url or "auth" in url:
        return True
    if "log in" in title or "sign in" in title:
        return True
    return _page_text_contains(page, LOGIN_TEXT_MARKERS)


def _visible_composer(page: Any) -> Any | None:
    for selector in (PROJECT_COMPOSER_SELECTOR, GLOBAL_COMPOSER_SELECTOR):
        locator = page.locator(selector)
        try:
            if locator.first.is_visible(timeout=250):
                return locator.first
        except Exception as exc:  # noqa: BLE001 -- selectors are intentionally best-effort
            LOG.debug("composer selector unavailable: %s", exc)
            continue
    return None


def _fast_any_visible(page: Any, selectors: tuple[str, ...]) -> bool:
    for selector in selectors:
        try:
            if page.locator(selector).first.is_visible(timeout=100):
                return True
        except Exception as exc:  # noqa: BLE001 -- selectors are intentionally best-effort
            LOG.debug("visibility selector unavailable: %s", exc)
            continue
    return False


def _blocking_modal_present(page: Any) -> str | None:
    try:
        body = str(page.locator("body").inner_text(timeout=1500)).lower()
    except Exception:
        return None
    for needle in BLOCKING_MODAL_TEXT:
        if needle in body:
            return needle
    return None


def _wait_for_initial_page_state(page: Any, timeout_s: float) -> None:
    deadline = time.time() + max(timeout_s, 1.0)
    while time.time() < deadline:
        if _fast_any_visible(page, (PROJECT_COMPOSER_SELECTOR, GLOBAL_COMPOSER_SELECTOR)):
            return
        if _is_login_blocked(page):
            return
        if _blocking_modal_present(page):
            return
        time.sleep(0.25)


def _new_spike_page(context: Any, project_url: str, timeout_s: float) -> Any:
    page = context.new_page()
    page.set_default_timeout(int(timeout_s * 1000))
    page.goto(project_url, wait_until="domcontentloaded")
    _wait_for_initial_page_state(page, min(timeout_s, 10.0))
    return page


def _reuse_project_page(context: Any, project_url: str, timeout_s: float) -> Any:
    """Prefer an already-open project chat; never create a tab if one exists.

    A project conversation URL is retained as-is, which keeps both the existing
    chat context and the tab alive. If no project page exists, navigate the first
    existing tab to the project home. Creating a page is a last-resort bootstrap
    for an otherwise empty CDP context.
    """
    raw_pages = getattr(context, "pages", ())
    pages = list(raw_pages) if isinstance(raw_pages, (list, tuple)) else []
    prefix = _project_prefix(project_url)
    for page in pages:
        if str(getattr(page, "url", "")).startswith(prefix):
            page.set_default_timeout(int(timeout_s * 1000))
            _wait_for_initial_page_state(page, min(timeout_s, 10.0))
            return page
    page = pages[0] if pages else context.new_page()
    page.set_default_timeout(int(timeout_s * 1000))
    page.goto(project_url, wait_until="domcontentloaded")
    _wait_for_initial_page_state(page, min(timeout_s, 10.0))
    return page


def _assert_project_context(page: Any, project_url: str) -> None:
    title = _safe_title(page)
    url = str(page.url)
    heading_text = ""
    try:
        heading = page.locator("h1").first
        if heading.is_visible(timeout=1500):
            heading_text = heading.inner_text(timeout=1500).strip()
    except Exception:
        heading_text = ""
    composer_ok = False
    try:
        composer_ok = page.locator(PROJECT_COMPOSER_SELECTOR).first.is_visible(timeout=1500)
    except Exception:
        composer_ok = False
    if not url.startswith(project_url):
        raise ChatGptBrowserError(f"Wrong project context: expected URL prefix {project_url}, got {url}")
    if title and "9to5" not in title:
        raise ChatGptBrowserError(f"Wrong project title: {title}")
    if heading_text and heading_text != "9to5":
        raise ChatGptBrowserError(f"Wrong project heading: {heading_text}")
    if not composer_ok:
        raise ChatGptBrowserError("Project composer missing; expected 'New chat in 9to5'.")


def _open_intelligence_menu_if_possible(page: Any) -> bool:
    try:
        button = page.locator(f"xpath={INTELLIGENCE_BUTTON_XPATH}").first
        button.click(timeout=2000)
        page.get_by_text("Intelligence", exact=True).wait_for(timeout=3000)
        return True
    except Exception:
        return False


def _verify_or_select_model_reasoning(page: Any, model: str, reasoning: str) -> list[str]:
    warnings: list[str] = []
    if not _open_intelligence_menu_if_possible(page):
        return ["Could not open Intelligence menu safely; skipped model/reasoning verification."]
    model_seen = False
    reasoning_seen = False
    try:
        if page.get_by_text(model, exact=True).count():
            model_seen = True
            page.get_by_text(model, exact=True).first.click(timeout=2000)
            time.sleep(0.3)
        if page.get_by_text(reasoning, exact=True).count():
            reasoning_seen = True
            page.get_by_text(reasoning, exact=True).first.click(timeout=2000)
    except Exception:
        warnings.append("Intelligence menu interaction was brittle; model/reasoning may be unchanged.")
    try:
        page.keyboard.press("Escape")
    except Exception as exc:  # noqa: BLE001 -- closing a transient menu is best-effort
        LOG.debug("could not close Intelligence menu: %s", exc)
    if not model_seen:
        warnings.append(f"Model option missing: {model}")
    if not reasoning_seen:
        warnings.append(f"Reasoning option missing: {reasoning}")
    return warnings


def _send_prompt(page: Any, prompt: str) -> None:
    composer = _visible_composer(page)
    if composer is None:
        raise ChatGptBrowserError("Composer missing; login may be required or the page is not ready.")
    composer.click(timeout=2000)
    try:
        composer.fill(prompt, timeout=4000)
    except Exception:
        page.keyboard.press("Control+A")
        page.keyboard.type(prompt)
    send = page.locator(SEND_BUTTON_SELECTOR).first
    try:
        send.wait_for(state="visible", timeout=5000)
    except Exception as exc:
        raise ChatGptBrowserError("Send button missing.") from exc
    try:
        if not send.is_enabled():
            raise ChatGptBrowserError("Send button not enabled.")
    except Exception as exc:
        raise ChatGptBrowserError("Could not verify send button state.") from exc
    send.click(timeout=3000)


def _assistant_texts(page: Any) -> list[str]:
    locator = page.locator(ASSISTANT_MESSAGE_SELECTOR)
    texts: list[str] = []
    count = _visible_count(locator)
    for idx in range(count):
        item = locator.nth(idx)
        try:
            if item.is_visible(timeout=500):
                text = item.inner_text(timeout=1500).strip()
                if text:
                    texts.append(text)
        except Exception as exc:  # noqa: BLE001 -- a stale message must not abort extraction
            LOG.debug("assistant message extraction skipped: %s", exc)
            continue
    return texts


def _wait_for_response(page: Any, timeout_s: float) -> str:
    start = time.time()
    initial_count = _visible_count(page.locator(ASSISTANT_MESSAGE_SELECTOR))
    response_started = False
    stable_text = ""
    stable_since = 0.0

    while time.time() - start < timeout_s:
        texts = _assistant_texts(page)
        latest = texts[-1] if texts else ""
        stop_visible = False
        copy_visible = False
        try:
            stop_visible = page.locator(STOP_ANSWERING_SELECTOR).first.is_visible(timeout=250)
        except Exception:
            stop_visible = False
        try:
            copy_visible = page.locator(COPY_RESPONSE_SELECTOR).first.is_visible(timeout=250)
        except Exception:
            copy_visible = False

        if len(texts) > initial_count or stop_visible:
            response_started = True
        if response_started and latest:
            if latest != stable_text:
                stable_text = latest
                stable_since = time.time()
            elif stable_since and (time.time() - stable_since) >= 2.0 and not stop_visible:
                if copy_visible or latest:
                    return latest
        time.sleep(0.5)

    if not response_started:
        raise ChatGptBrowserError("Assistant response never started.")
    raise ChatGptBrowserError("Assistant response timed out before completion.")


def _project_prefix(project_url: str) -> str:
    """Normalize project home URL to the shared `/g/...-9to5/` prefix used by chats."""
    url = project_url.rstrip("/")
    if url.endswith("/project"):
        url = url[: -len("/project")]
    return url.rstrip("/") + "/"


def _assert_still_in_project(page: Any, project_url: str) -> None:
    """Mid-chat check: URL must stay under the project prefix (home or /c/<id>)."""
    url = str(page.url)
    prefix = _project_prefix(project_url)
    if not url.startswith(prefix):
        raise ChatGptBrowserError(f"Left project chat context: expected prefix {prefix}, got {url}")
    if _visible_composer(page) is None:
        raise ChatGptBrowserError("Composer missing mid-chat; cannot continue this thread.")


class ChatGptBrowserSession:
    """A reused ChatGPT project chat thread that never opens duplicate tabs."""

    def __init__(
        self,
        *,
        project_url: str,
        model: str = DEFAULT_MODEL,
        reasoning: str = DEFAULT_REASONING,
        profile: Path | None = None,
        chrome: Path | None = None,
        debug_port: int = DEFAULT_PORT,
        timeout_s: float = DEFAULT_TIMEOUT_S,
    ) -> None:
        self.project_url = project_url
        self.model = model or DEFAULT_MODEL
        self.reasoning = reasoning or DEFAULT_REASONING
        self.profile = Path(profile) if profile else DEFAULT_PROFILE
        self.chrome = Path(chrome) if chrome else DEFAULT_CHROME
        self.debug_port = int(debug_port)
        self.timeout_s = float(timeout_s)
        self.session_id = uuid.uuid4().hex[:12]
        self.turn_count = 0
        self._playwright: Any | None = None
        self._browser: Any | None = None
        self._page: Any | None = None
        self._closed = False

    def open(self) -> None:
        if self._closed:
            raise ChatGptBrowserError("ChatGptBrowserSession already closed.")
        if self._page is not None:
            return
        _verify_profile_dir(self.profile)
        _verify_profile_is_gitignored(self.profile)
        _ensure_debuggable_chrome(
            chrome=self.chrome,
            profile=self.profile,
            project_url=self.project_url,
            debug_port=self.debug_port,
            timeout_s=self.timeout_s,
        )
        try:
            from playwright.sync_api import sync_playwright
        except Exception as exc:
            raise ChatGptBrowserError(
                "Playwright is not available. Install dependencies before running this driver."
            ) from exc
        self._playwright = legacyDiagnosticAutomationLease(sync_playwright).start()
        try:
            self._browser = self._playwright.chromium.connect_over_cdp(
                f"http://127.0.0.1:{self.debug_port}"
            )
            context = self._browser.contexts[0] if self._browser.contexts else self._browser.new_context()
            page = _reuse_project_page(context, self.project_url, self.timeout_s)
            if _is_login_blocked(page):
                raise ChatGptBrowserError(
                    "ChatGPT login is required. Log in inside the dedicated Chrome window only, "
                    "then rerun the driver."
                )
            modal = _blocking_modal_present(page)
            if modal:
                raise ChatGptBrowserError(f"Blocking modal/dialog detected: {modal}")
            if _visible_composer(page) is None:
                raise ChatGptBrowserError("Composer missing after navigation.")
            _assert_project_context(page, self.project_url)
            _verify_or_select_model_reasoning(page, self.model, self.reasoning)
            self._page = page
        except Exception:
            self.close()
            raise

    def ask(self, prompt: str) -> str:
        """Send one prompt on the shared chat thread and return the latest assistant text."""
        self.open()
        assert self._page is not None
        if self.turn_count > 0:
            _assert_still_in_project(self._page, self.project_url)
        _send_prompt(self._page, prompt)
        response_text = _wait_for_response(self._page, self.timeout_s)
        if not response_text.strip():
            raise ChatGptBrowserError("Assistant response was empty.")
        self.turn_count += 1
        return response_text

    def close(self) -> None:
        """Detach from the reused page; leave both its tab and Chrome running."""
        self._closed = True
        self._page = None
        # The page belongs to the user/browser session. Keep the existing tab and
        # conversation available for the next project request.
        self._browser = None
        playwright = self._playwright
        self._playwright = None
        if playwright is not None:
            try:
                playwright.stop()
            except Exception as exc:  # noqa: BLE001 -- Playwright may already be stopped
                LOG.debug("Playwright stop skipped: %s", exc)

    def __enter__(self) -> "ChatGptBrowserSession":
        self.open()
        return self

    def __exit__(self, exc_type, exc, tb) -> bool:
        self.close()
        return False


def send_prompt_to_project(
    project_url: str,
    model: str,
    reasoning: str,
    prompt: str,
) -> str:
    """Send a prompt through the reusable project chat, never a fresh tab/chat."""
    key = (project_url, model, reasoning)
    session = _SHARED_PROJECT_SESSIONS.get(key)
    if session is None or session._closed:
        session = ChatGptBrowserSession(project_url=project_url, model=model, reasoning=reasoning)
        _SHARED_PROJECT_SESSIONS[key] = session
    return session.ask(prompt)


def close_project_session(project_url: str, model: str, reasoning: str) -> None:
    """Explicit cleanup only; normally callers should retain the project chat."""
    session = _SHARED_PROJECT_SESSIONS.pop((project_url, model, reasoning), None)
    if session is not None:
        session.close()
