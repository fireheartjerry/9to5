def normalizeSpec(spec_or_prompt: Union[dict, str, None]) -> dict:
    """Accept a full invocation spec dict OR a bare prompt string; return a full spec."""
    base: dict = {
        "prompt": "",
        "claude_md_inject": "",
        "skills_to_invoke": [],
        "effort_level": "default",
        "subagent": None,
        "pre_tool_hooks": [],
        "post_tool_hooks": [],
        "use_workflow": False,
        "workflow_definition": None,
        # Surface routing (rich cross-surface automation): which "hands" execute this spec.
        "surface": "terminal",  # terminal (Claude CLI, L3) | browser (CDP, L1)
        "browser_actions": [],  # structured CDP steps when surface == browser
    }
    if isinstance(spec_or_prompt, str):
        base["prompt"] = spec_or_prompt
        return base
    if isinstance(spec_or_prompt, dict):
        for k, v in spec_or_prompt.items():
            base[k] = v
    return base


def _composeWorkflowPrompt(definition: dict, base_prompt: str) -> str:
    """Render a brain-authored workflow_definition into an explicit, headless-executable
    multi-phase orchestration instruction.

    Headless ``claude --print`` cannot open the interactive ``/workflows`` UI, so the
    faithful realization is to instruct Claude to EXECUTE the workflow: dispatch one
    subagent (Task tool) per agent, run a phase's agents in PARALLEL when marked, carry
    each phase's outputs into the next, and finally synthesize. A Claude build that
    exposes the Workflow tool may run it natively; either way the structured plan drives
    the same fan-out / verify / synthesize shape the brain intended."""
    # EPIC 5: when config.SOCIETY_ENABLED, the coordinator REALIZES a parallel-phase workflow
    # itself as visible 9to5 WorkerAgents (society/coordinator.py) instead of this opaque
    # Claude-internal Task-tool fan-out. With society OFF this path runs exactly as before.
    if not isinstance(definition, dict):
        return base_prompt
    name = definition.get("name") or "dynamic-workflow"
    desc = definition.get("description") or ""
    phases = definition.get("phases") or []
    lines: list[str] = [
        f'EXECUTE THIS DYNAMIC WORKFLOW — "{name}".',
        "This subtask is structured as a multi-phase workflow. Run it as one: for each phase, dispatch the "
        "listed agents (use the Task tool, one subagent per agent; if a Workflow/`/workflows` primitive is "
        "available to you, you may run it natively instead). Run a phase's agents CONCURRENTLY when it is "
        "marked parallel; otherwise run them in order. Feed each phase's results into the next. End with the "
        "synthesis step, which produces the final deliverable for this subtask.",
        "",
    ]
    if desc:
        lines += [f"Goal of the workflow: {desc}", ""]
    for i, ph in enumerate(phases, 1):
        if not isinstance(ph, dict):
            continue
        title = ph.get("title") or f"Phase {i}"
        par = "PARALLEL" if ph.get("parallel") else "sequential"
        lines.append(f"## Phase {i}: {title}  [{par}]")
        for j, ag in enumerate(ph.get("agents") or [], 1):
            if isinstance(ag, dict):
                label = ag.get("label") or f"agent-{j}"
                aprompt = ag.get("prompt") or ""
                eff = ag.get("effort")
                lines.append(f"- Agent `{label}`" + (f" (effort {eff})" if eff else "") + f": {aprompt}")
            elif isinstance(ag, str):
                lines.append(f"- Agent {j}: {ag}")
        lines.append("")
    synth = definition.get("synthesis") or definition.get("synthesize")
    if synth:
        lines += ["## Synthesis", str(synth), ""]
    if base_prompt:
        lines += ["## Underlying subtask (the workflow must accomplish this)", base_prompt, ""]
    return "\n".join(lines).strip()


def _composePrompt(spec: dict, system_prompt: Optional[str], extra: Optional[str]) -> str:
    parts: list[str] = []
    if system_prompt:
        parts.append(system_prompt + "\n\n---\n")
    skills = [s for s in (spec.get("skills_to_invoke") or []) if s]
    if skills:
        parts.append("Invoke these skills as appropriate: " + " ".join(skills))
    subagent = spec.get("subagent")
    if subagent:
        parts.append(f"Use the '{subagent}' subagent for the analysis portion of this task.")
    # Dynamic workflow: resolve from centralized registry, then compose prompt.
    # resolveWorkflowDefinition is the single authoritative path — it already falls back
    # to the raw inline dict when validation fails, so bypassing it here would let
    # registry-rejected definitions render outside registry control.
    if spec.get("use_workflow"):
        from agents.workflow_resolver import resolveWorkflowDefinition

        wf_def = resolveWorkflowDefinition(spec)
        if wf_def is not None:
            parts.append(_composeWorkflowPrompt(wf_def, spec.get("prompt") or ""))
        else:
            parts.append(spec.get("prompt") or "")
    else:
        parts.append(spec.get("prompt") or "")
    if extra:
        parts.append("\n" + extra)
    return "\n\n".join(p for p in parts if p).strip()


def effortFlag(effort_level: str) -> Optional[str]:
    return config.EFFORT_FLAG_MAP.get((effort_level or "default").lower())


# Headless `claude --print --dangerously-skip-permissions` may NOT run .claude hooks or
# permissions, so 9TO5 KEEPS this pre-scan enforcement layer in plumbing we control
# (deterministic, always-on in autonomous mode) -- defense in depth ALONGSIDE the registered
# PreToolUse hooks, never instead of them. The pattern SOURCE is the one shared taxonomy in
# platform_core.runtime.action_risk (anchored command-position regex with sudo/doas and
# chained-command handling), so the two enforcement layers can never drift apart.
from platform_core.runtime.action_risk import scanDestructive  # noqa: E402,F401

# ---------------------------------------------------------------------------
# Guard-hook registration -- single source: HOOKS_SPEC.
# The repo .claude/settings.json (interactive sessions) and the per-run --settings file
# (executor runs) both derive from THIS constant, and platform_core/ops/health.py hard-fails
# when either is missing the block -- registration cannot silently drift back to hooks={}.
# ---------------------------------------------------------------------------
HOOKS_SPEC: tuple[tuple[str, str, str], ...] = (
    # (claude_settings_event, tool_matcher, agents/hooks.py hook name)
    ("PreToolUse", "Bash", "block_destructive"),
    ("PreToolUse", "Bash|Edit|Write|MultiEdit", "self_modification_guard"),
)

# Own-tree root (NOT config.PROJECT_ROOT): hooks must target THIS checkout's agents/hooks.py
# under any worktree, mirroring hooks.py's own sys.path rule (see tests/test_hooks_self_path.py).
_OWN_ROOT = Path(__file__).resolve().parent.parent


def _hookInterpreter() -> str:
    """Prefer the venv python (absolute, dep-complete) when it exists; else PATH python.
    Guard hooks are stdlib+action_risk only by design, so bare `python` still guards."""
    try:
        venv_py = getattr(config, "VENV_PYTHON", None)
        if venv_py and Path(venv_py).exists():
            return '"' + str(venv_py).replace("\\", "/") + '"'
    except Exception:  # noqa: BLE001
        pass
    return "python"


def buildHooksBlock(project_root=None) -> dict:
    """Generate the Claude-settings ``hooks`` block from HOOKS_SPEC (absolute hook path)."""
    root = Path(project_root) if project_root else _OWN_ROOT
    hooks_py = str(root / "agents" / "hooks.py").replace("\\", "/")
    py = _hookInterpreter()
    events: dict = {}
    for event, matcher, hook_name in HOOKS_SPEC:
        events.setdefault(event, []).append(
            {
                "matcher": matcher,
                "hooks": [{"type": "command", "command": f'{py} "{hooks_py}" {hook_name}'}],
            }
        )
    return events


def settingsHasGuardHooks(settings: dict) -> bool:
    """True when every HOOKS_SPEC guard is registered in the settings' hooks block."""
    hooks = (settings or {}).get("hooks") or {}
    if not isinstance(hooks, dict):
        return False
    for event, _matcher, hook_name in HOOKS_SPEC:
        blob = json.dumps(hooks.get(event) or [])
        if "hooks.py" not in blob or hook_name not in blob:
            return False
    return True


def composeRunSettingsDict(base_settings_path=None) -> dict:
    """Per-run settings dict: base settings merged with the generated hooks block.

    The guard-hook block is ALWAYS injected -- even when the base file is missing, unreadable,
    or lost its hooks -- so an executor run can never launch without the guards registered.
    Model/effort keys and permissions pass through untouched."""
    path = Path(base_settings_path) if base_settings_path else Path(config.CLAUDE_SETTINGS_PATH)
    base: dict = {}
    try:
        if path.exists():
            # Windows editors may emit a UTF-8 BOM. It is still a valid settings
            # file and must not trigger a fallback regeneration during a run.
            loaded = json.loads(path.read_text(encoding="utf-8-sig"))
            if isinstance(loaded, dict):
                base = loaded
    except Exception as e:  # noqa: BLE001
        LOG.warning("composeRunSettings: unreadable base settings %s (%s); regenerating", path, e)
    merged = dict(base.get("hooks") or {}) if isinstance(base.get("hooks"), dict) else {}
    for event, entries in buildHooksBlock().items():
        existing = list(merged.get(event) or [])
        for entry in entries:
            hook_name = entry["hooks"][0]["command"].rsplit(" ", 1)[-1]

            def _is_same_guard(e, _name=hook_name) -> bool:
                blob = json.dumps(e)
                return "hooks.py" in blob and _name in blob

            # REPLACE any prior registration of this guard, don't just skip: a base
            # settings.json committed from another checkout carries that checkout's
            # absolute hooks.py path -- keeping it would run the WRONG tree's guards.
            existing = [e for e in existing if not _is_same_guard(e)]
            existing.append(entry)
        merged[event] = existing
    base["hooks"] = merged
    return base


def composeRunSettings(base_settings_path=None, out_path=None) -> Path:
    """Write the per-run --settings file (see composeRunSettingsDict) and return its path."""
    out = Path(out_path) if out_path else (Path(config.LOG_PATH) / "claude_run_settings.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(composeRunSettingsDict(base_settings_path), indent=2), encoding="utf-8")
    return out


def buildHookCtxEnv(boundaries=None) -> str:
    """JSON for the NINE_TO_FIVE_HOOK_CTX env var: ONE channel for hook context (boundaries +
    log/alert paths from config) so guard entrypoints need no config import of their own."""
    return json.dumps(
        {
            "log_path": str(Path(config.LOG_PATH) / "hooks.log"),
            "guard_alerts": str(Path(config.LOG_PATH) / "guard_alerts.jsonl"),
            "boundaries": [str(b) for b in (boundaries or [])],
        }
    )


def _alertBlocked(reason: str) -> None:
    # An AUTO-REFUSED safety event (a destructive command was blocked): inform, don't summon. No
    # "human decision required" framing and no @-ping -- 9to5 already handled it autonomously.
    try:
        from notifications import discord_bot as discord

        discord.sendEmbed(discord.noticeEmbed(reason, title="🛡️ 9TO5 — auto-refused (safety)"))
    except Exception as e:  # noqa: BLE001
        LOG.warning("blocked-alert failed: %s", e)
