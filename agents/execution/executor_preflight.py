"""Zero-cost launch preflight for the incumbent Claude subscription driver.

No secret value is retained or returned.  API-key/cloud billing indicators are a hard
deny in both shadow and enforcement modes.  Unknown quota or capacity is recorded in
shadow mode and fails closed once the GALAXY evidence policy is enforced.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  ClaudeLaunchPreflight
  preflightClaudeLaunch(environ: Mapping[str, str], *, policy_enforced: bool) -> ClaudeLaunchPreflight  -- Evaluate billing, quota, and capacity before any target/workdir operation.
DEPENDS-ON: platform_core.core.galaxy_evidence
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_executor.py
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
from decimal import Decimal
from typing import Mapping

from platform_core.core.galaxy_evidence import (
    CapacityTruth,
    ProviderBillingMode,
    ZeroCostRunPolicy,
)


_API_KEY_INDICATORS = (
    "ANTHROPIC_API_KEY",
    "ANTHROPIC_BASE_URL",
    "AWS_ACCESS_KEY_ID",
    "AWS_SECRET_ACCESS_KEY",
    "GOOGLE_APPLICATION_CREDENTIALS",
)
_CLOUD_MODE_INDICATORS = (
    "CLAUDE_CODE_USE_BEDROCK",
    "CLAUDE_CODE_USE_VERTEX",
    "CLAUDE_CODE_USE_FOUNDRY",
)
CLAUDE_BILLING_OVERRIDE_ENV = (
    *_API_KEY_INDICATORS,
    *_CLOUD_MODE_INDICATORS,
    "CLAUDE_MAX_BUDGET_USD",
)


@dataclass(frozen=True)
class ClaudeLaunchPreflight:
    allowed: bool
    reason: str
    observed_reason: str
    billing_mode: str
    quota_state: str
    capacity_state: str
    external_spend_allowed: bool = False
    shadow_only: bool = True

    def to_dict(self) -> dict:
        return asdict(self)


def _truth(value: str | None) -> CapacityTruth:
    normalized = str(value or "").strip().lower()
    try:
        return CapacityTruth(normalized)
    except ValueError:
        return CapacityTruth.UNKNOWN


def _enabled(value: str | None) -> bool:
    return str(value or "").strip().lower() in {"1", "true", "yes", "on"}


def _billing_mode(environ: Mapping[str, str]) -> ProviderBillingMode:
    if any(str(environ.get(name) or "").strip() for name in _API_KEY_INDICATORS):
        return ProviderBillingMode.API_KEY
    if any(_enabled(environ.get(name)) for name in _CLOUD_MODE_INDICATORS):
        return ProviderBillingMode.API_KEY
    return ProviderBillingMode.SUBSCRIPTION


def preflightClaudeLaunch(
    environ: Mapping[str, str], *, policy_enforced: bool
) -> ClaudeLaunchPreflight:
    """Evaluate billing, quota, and capacity before any target/workdir operation."""

    billing_mode = _billing_mode(environ)
    quota = _truth(environ.get("NINE_TO_FIVE_CLAUDE_QUOTA_STATE"))
    capacity = _truth(environ.get("NINE_TO_FIVE_CLAUDE_CAPACITY_STATE"))
    observed = ZeroCostRunPolicy().preflight(
        billing_mode=billing_mode,
        price_usd=Decimal("0"),
        quota_state=quota,
        capacity_state=capacity,
    )
    hard_billing_deny = billing_mode is ProviderBillingMode.API_KEY
    allowed = observed.allowed if policy_enforced or hard_billing_deny else True
    reason = observed.reason if policy_enforced or hard_billing_deny else "incumbent-baseline"
    return ClaudeLaunchPreflight(
        allowed=allowed,
        reason=reason,
        observed_reason=observed.reason,
        billing_mode=billing_mode.value,
        quota_state=quota.value,
        capacity_state=capacity.value,
        external_spend_allowed=False,
        shadow_only=not policy_enforced,
    )


__all__ = [
    "CLAUDE_BILLING_OVERRIDE_ENV",
    "ClaudeLaunchPreflight",
    "preflightClaudeLaunch",
]
