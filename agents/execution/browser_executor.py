from __future__ import annotations

import re
import time
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any, Optional

import config
from agents import executor

LOG = config.getLogger("browser_executor")

_URL_RE = re.compile(r"https?://[^\s\"'<>)]+")


class BrowserUnavailable(RuntimeError):
    """Raised when no browser backend (Playwright/Chromium) is installed."""


@dataclass(frozen=True)
class BrowserAction:
    """Validated, provider-neutral browser action request."""
    action: str
    selector: str = ""
    url: str = ""


@dataclass(frozen=True)
class BrowserEvidence:
    """Observed proof for one completed browser action."""
    index: int
    action: str
    url: str
    selector: str = ""
    duration_ms: int = 0
    artifact_ref: str = ""


@dataclass(frozen=True)
class BrowserPolicy:
    """Bounded browser protocol. Empty origins preserves legacy local experiments."""
    allowed_origins: tuple[str, ...] = ()
    max_actions: int = 40
    max_retries: int = 1
    max_duration_ms: int = 120_000
    require_confirmation_for_irreversible: bool = True

    @classmethod
    def from_spec(cls, spec: dict) -> "BrowserPolicy":
        raw = spec.get("browser_policy") or {}
        return cls(tuple(raw.get("allowed_origins") or ()), max(1, int(raw.get("max_actions", 40))),
                   max(0, int(raw.get("max_retries", 1))), max(1_000, int(raw.get("max_duration_ms", 120_000))),
                   bool(raw.get("require_confirmation_for_irreversible", True)))


def _result(spec: dict, *, ok: bool, is_error: bool, stdout: str = "", stderr: str = "",
            actual_mode: str = "live", artifacts: tuple[str, ...] = ()) -> dict:
    """A runClaude-shaped result so the orchestrator treats browser output identically."""
    from platform_core.core.contracts import ExecutionSurfaceReceipt
    receipt = ExecutionSurfaceReceipt("browser", actual_mode=actual_mode,
                                      status="ok" if ok else ("unavailable" if actual_mode == "unavailable" else "error"),
                                      artifacts=artifacts, detail=stderr or stdout[:500])
    return {
        "ok": ok, "returncode": 0 if ok else 1, "stdout": stdout, "stderr": stderr,
        "is_error": is_error, "effort": spec.get("effort_level", "default"),
        "effort_flag": None, "spec": spec, "claude_md_path": None,
        "profile": "browser_navigator", "blocked": False, "surface": "browser",
        "surface_receipt": receipt.toDict(),
    }


def _actions_from_prompt(prompt: str) -> list[dict[str, Any]]:
    """Auto-derive simple actions from a URL-bearing prompt: visit each URL + extract text."""
    actions: list[dict[str, Any]] = []
    for url in _URL_RE.findall(prompt or ""):
        actions.append({"action": "goto", "url": url})
        actions.append({"action": "extract"})
    return actions


def _origin_allowed(url: str, policy: BrowserPolicy) -> bool:
    return not policy.allowed_origins or any(url.startswith(origin.rstrip("/") + "/") or url == origin.rstrip("/")
                                             for origin in policy.allowed_origins)


def _validate_actions(actions: list[dict[str, Any]], policy: BrowserPolicy) -> None:
    supported = {"goto", "click", "type", "press", "select", "scroll", "wait", "extract", "screenshot", "assert", "upload", "download"}
    if len(actions) > policy.max_actions:
        raise ValueError(f"browser action budget exceeded ({len(actions)} > {policy.max_actions})")
    for action in actions:
        kind = str(action.get("action") or "").lower()
        if kind not in supported:
            raise ValueError(f"unsupported browser action {kind!r}")
        if kind == "goto":
            url = str(action.get("url") or "")
            if not _origin_allowed(url, policy):
                raise ValueError("browser origin is not allowlisted")
        if kind in {"download", "screenshot"} and action.get("path") and Path(str(action["path"])).name != str(action["path"]):
            raise ValueError("browser artifact path must be a basename")
        if policy.require_confirmation_for_irreversible and action.get("irreversible") and not action.get("confirmed"):
            raise ValueError("irreversible browser action requires explicit confirmation")


def _run_actions(actions: list[dict[str, Any]], *, timeout_ms: int = 30000,
                 screenshot_dir: Optional[str] = None, policy: BrowserPolicy | None = None,
                 evidence: list[BrowserEvidence] | None = None) -> str:
    """Execute structured CDP actions via Playwright; return a transcript. Raises
    BrowserUnavailable if Playwright/Chromium is not installed (caller degrades).

    Supported actions: goto, click, type, press, select, scroll, wait, extract, assert,
    upload, download, screenshot. Each line of the transcript records the action + its observable result so
    the verifier can check the outcome."""
    try:
        from playwright.sync_api import sync_playwright  # type: ignore
    except Exception as e:  # noqa: BLE001 -- not installed -> caller degrades cleanly
        raise BrowserUnavailable(
            "browser layer unavailable: `pip install playwright && playwright install chromium`") from e

    lines: list[str] = []
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        try:
            page = browser.new_page()
            page.set_default_timeout(timeout_ms)
            for i, act in enumerate(actions):
                action_started = time.monotonic()
                kind = (act.get("action") or "").lower()
                from notifications.lane_feed import laneTap
                laneTap("browser", f"{kind}: {str(act.get('url') or act.get('selector') or act)[:80]}")
                if kind == "goto":
                    page.goto(act["url"])
                    lines.append(f"goto {act['url']} -> {page.title()!r}")
                elif kind == "click":
                    page.click(act["selector"])
                    lines.append(f"click {act['selector']}")
                elif kind == "type":
                    page.fill(act["selector"], act.get("text", ""))
                    lines.append(f"type into {act['selector']}")
                elif kind == "press":
                    page.press(act["selector"], act.get("key", "Enter"))
                    lines.append(f"press {act.get('key', 'Enter')} on {act['selector']}")
                elif kind == "select":
                    page.select_option(act["selector"], act.get("value"))
                    lines.append(f"select {act.get('value')} in {act['selector']}")
                elif kind == "scroll":
                    page.mouse.wheel(0, int(act.get("dy", 800)))
                    lines.append(f"scroll dy={act.get('dy', 800)}")
                elif kind == "wait":
                    if act.get("selector"):
                        page.wait_for_selector(act["selector"])
                        lines.append(f"wait {act['selector']}")
                    else:
                        page.wait_for_timeout(int(act.get("ms", 1000)))
                        lines.append(f"wait {act.get('ms', 1000)}ms")
                elif kind == "extract":
                    sel = act.get("selector")
                    text = (page.inner_text(sel) if sel else page.inner_text("body"))[:2000]
                    lines.append(f"extract {sel or 'body'}:\n{text}")
                elif kind == "assert":
                    selector = act.get("selector")
                    expected = str(act.get("contains", ""))
                    actual = page.inner_text(selector) if selector else page.inner_text("body")
                    if expected and expected not in actual:
                        raise AssertionError(f"browser assertion missing {expected!r}")
                    lines.append(f"assert {selector or 'body'} contains {expected!r}")
                elif kind == "upload":
                    page.set_input_files(act["selector"], act["path"])
                    lines.append(f"upload {Path(act['path']).name} -> {act['selector']}")
                elif kind == "download":
                    target = Path(screenshot_dir or ".") / Path(act.get("path") or f"download-{i}").name
                    target.parent.mkdir(parents=True, exist_ok=True)
                    with page.expect_download() as download_info:
                        page.click(act["selector"])
                    download_info.value.save_as(str(target))
                    lines.append(f"download -> {target}")
                elif kind == "screenshot":
                    raw_name = act.get("path") or f"screenshot-{i}.png"
                    name = Path(raw_name).name or f"screenshot-{i}.png"
                    path = str(Path(screenshot_dir) / name) if screenshot_dir else name
                    page.screenshot(path=path)
                    lines.append(f"screenshot -> {path}")
                else:
                    lines.append(f"(skipped unknown action {kind!r})")
                if policy and page.url.startswith(("http://", "https://")) and not _origin_allowed(page.url, policy):
                    raise ValueError(f"browser navigated to non-allowlisted origin: {page.url}")
                if evidence is not None:
                    artifact = ""
                    if kind in {"screenshot", "download"} and screenshot_dir:
                        artifact = str(Path(screenshot_dir) / Path(act.get("path") or (f"screenshot-{i}.png" if kind == "screenshot" else f"download-{i}")).name)
                    evidence.append(BrowserEvidence(i, kind, page.url, str(act.get("selector") or ""),
                                                    int((time.monotonic() - action_started) * 1000), artifact))
        finally:
            browser.close()
    return "\n".join(lines)


def runBrowser(spec_or_prompt, *, work_dir: Optional[str] = None, task_state=None,
               subtask: Optional[dict] = None, resume_session: Optional[str] = None,
               **_kw) -> dict:
    """Execute a browser subtask. Matches executor.runClaude's signature + result shape."""
    spec = executor.normalizeSpec(spec_or_prompt)
    actions = spec.get("browser_actions") or _actions_from_prompt(spec.get("prompt", ""))
    if not actions:
        return _result(spec, ok=False, is_error=True,
                       stderr="browser surface needs 'browser_actions' or a URL in the prompt")
    policy = BrowserPolicy.from_spec(spec)
    artifacts = tuple(str(Path(work_dir) / Path(a.get("path") or (f"screenshot-{i}.png" if a.get("action") == "screenshot" else f"download-{i}")).name)
                      for i, a in enumerate(actions) if a.get("action") in {"screenshot", "download"} and work_dir)
    evidence: list[BrowserEvidence] = []
    try:
        _validate_actions(actions, policy)
        started = time.monotonic()
        transcript = ""
        for attempt in range(policy.max_retries + 1):
            try:
                transcript = _run_actions(actions, timeout_ms=min(30_000, policy.max_duration_ms), screenshot_dir=work_dir,
                                          policy=policy, evidence=evidence)
                if (time.monotonic() - started) * 1000 > policy.max_duration_ms:
                    raise TimeoutError(f"browser total duration exceeded {policy.max_duration_ms}ms")
                break
            except BrowserUnavailable:
                raise
            except Exception as exc:  # noqa: BLE001 -- bounded retry for transient CDP/selector failures
                if attempt >= policy.max_retries:
                    raise
                LOG.warning("browser attempt %d/%d failed: %s", attempt + 1, policy.max_retries + 1, exc)
        LOG.info("browser run: %d actions ok", len(actions))
        result = _result(spec, ok=True, is_error=False,
                         stdout=f"{transcript}\nattempts={attempt + 1}\nduration_s={time.monotonic() - started:.3f}", artifacts=artifacts)
        result["browser_evidence"] = [asdict(item) for item in evidence]
        return result
    except BrowserUnavailable as e:
        LOG.warning("%s", e)
        result = _result(spec, ok=False, is_error=True, stderr=str(e), actual_mode="unavailable", artifacts=artifacts)
        result["browser_evidence"] = [asdict(item) for item in evidence]
        return result
    except Exception as e:  # noqa: BLE001 -- a browser failure is a failed subtask, not a crash
        LOG.warning("browser run failed (ignored): %s", e)
        result = _result(spec, ok=False, is_error=True, stderr=f"browser run failed: {e}", artifacts=artifacts)
        result["browser_evidence"] = [asdict(item) for item in evidence]
        return result


def run_browser(*args, **kwargs) -> dict:
    """PEP-8 public alias for the production browser executor."""
    return runBrowser(*args, **kwargs)


def unavailableBrowser(spec_or_prompt, **_kwargs) -> dict:
    """Strict dispatcher target when the browser surface is disabled."""
    spec = executor.normalizeSpec(spec_or_prompt)
    return _result(spec, ok=False, is_error=True,
                   stderr="browser surface requested but BROWSER_LAYER_ENABLED is false",
                   actual_mode="unavailable")


# --- Gemini second brain (Phase 2 production path) --------------------------------------
# A single long-lived GeminiSession per process: one conversation per run so the model
# accumulates run context across subtask reviews. The orchestrator owns its lifecycle (probe
# at run start, close at run end). Unlike the old sync-Playwright ChatGPT session, the Gemini
# transport is stateless thread-safe HTTPS -- no dedicated worker thread, no profile, no DOM.
_SESSION = None


def get_session():
    """Lazily build the process-wide GeminiSession (does NOT open a client yet)."""
    global _SESSION
    if _SESSION is None:
        from agents.gemini_driver import GeminiSession
        _SESSION = GeminiSession()
    return _SESSION


def probe() -> bool:
    """Health-probe the Gemini session. Never raises; False on any failure."""
    return bool(get_session().health_probe())


def startConversation(goal: str, task_id: str) -> None:
    """Start the single run conversation."""
    get_session().start_run_conversation(goal, task_id)


def closeSession() -> None:
    """Close + tear down the Gemini session."""
    if _SESSION is not None:
        _SESSION.close()


def preflightLogin(timeout_s: int = 300, poll_s: int = 3) -> bool:
    """Verify Gemini is reachable before a run relies on it. Unlike the old chatgpt.com path
    there is NO interactive login -- an API key either works or it doesn't -- so this is just a
    health probe. The ``timeout_s`` / ``poll_s`` params are kept for call-site compatibility.
    Returns True if Gemini answered."""
    return probe()


def sessionAsk(message: str, *, expect_json: bool = False) -> Optional[str]:
    """Ask Gemini one message through the run session. Re-raises typed GeminiError subclasses
    (auth/blocked/rate-limit) so the Adversary can route the fallback chain; returns None on a
    benign empty reply."""
    return get_session().ask(message, expect_json=expect_json)


def askGemini(message: str, *, runner=None, expect_json: bool = False) -> Optional[str]:
    """Send one ``message`` to Gemini and return the reply text.

    Production path (no ``runner``): the long-lived :class:`~agents.gemini_driver.GeminiSession`.
    Test path (``runner`` injected): a ``(message) -> reply`` callable is called directly, so
    tests can drive the Adversary without touching the live API. Returns ``None`` when the layer
    is unavailable or the reply is empty, so callers can degrade conservatively instead of
    crashing."""
    if runner is not None:
        return runner(message)
    return sessionAsk(message, expect_json=expect_json)
