"""PostToolUse hook: log edited file paths to the active Obsidian subtask note.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  writeObsidian(data)  -- PostToolUse: log the edited file path to the in-progress subtask note.
DEPENDS-ON: agents.hooks_selfmod, memory.obsidian, platform_core.core.best_effort
SIDE-EFFECTS: appends a line to the active subtask's Obsidian note (best-effort, never blocks)
RUN/TEST: python -m pytest tests/control/test_hooks_obsidian.py
"""
from __future__ import annotations

import os
import sys
from pathlib import Path as _Path

sys.path.insert(0, str(_Path(__file__).resolve().parent.parent))

from agents.hooks_selfmod import _resolveState  # noqa: E402
from platform_core.core.best_effort import best_effort  # noqa: E402


def writeObsidian(data):
    """PostToolUse: log the edited file path to the in-progress subtask note.
    Telemetry-only hook (NOT a guard hook): failures are swallowed but counted --
    sys.exit(0) raises SystemExit, which best_effort passes through untouched."""
    with best_effort("obsidian.hook_note"):
        tool_name = data.get("tool_name", "")
        if tool_name not in ("Edit", "Write", "MultiEdit"):
            sys.exit(0)

        tool_input = data.get("tool_input", {}) or {}
        file_path = tool_input.get("file_path", "")

        from datetime import datetime
        from memory.obsidian import ObsidianClient

        state, _explicit = _resolveState()
        if state is None:
            sys.exit(0)

        try:
            subtasks = state.subtasks or []
        except Exception:
            subtasks = []

        # Prefer the executor-exported subtask -- but only if it actually belongs to the resolved
        # state (under a fallback resolution it may name a subtask of a different task). Else scan.
        sid = os.environ.get("NINE_TO_FIVE_SUBTASK_ID") or None
        if sid:
            try:
                if state.getSubtask(sid) is None:
                    sid = None
            except Exception:
                sid = None
        if not sid:
            for st in subtasks:
                try:
                    if st.get("status") == "in_progress":
                        sid = st.get("subtask_id")
                        break
                except Exception:
                    continue

        if not sid:
            sys.exit(0)

        ts = datetime.now().isoformat(timespec="seconds")
        line = f"- {ts} | {tool_name} | {file_path}\n"
        ObsidianClient().appendNote(state.subtaskNoteRel(sid), line)
    sys.exit(0)
