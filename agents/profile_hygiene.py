"""Chromium profile hygiene for the 9to5 ChatGPT second-brain profile.

A hard-killed Chromium (the common case when a run crashes or is force-stopped) leaves two
kinds of mess behind, and BOTH break the next launch:

  1. Orphaned chrome.exe processes that still hold the single-instance ``user_data_dir`` -- the
     next ``launch_persistent_context`` then fails with "Opening in existing browser session.
     This usually means that the profile is already in use by another instance of Chromium".
  2. An ``exit_type: "Crashed"`` flag in ``Default/Preferences`` -- Chromium pops the
     "Chrome didn't shut down correctly / Restore pages?" bubble on the next open.

This module reaps the zombies and erases the crash flag so the profile ALWAYS opens clean.
``sanitize()`` is the single entry point called before every launch (and the kill is exposed
on its own for the wipe / health surfaces). Pure pathlib + psutil; never raises.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  killZombies(profile_dir: Optional[Path]=None) -> int  -- Kill every chrome/chromium process whose command line binds this profile
  clearStaleLocks(profile_dir: Optional[Path]=None) -> None  -- Remove leftover single-instance lock artifacts
  markCleanExit(profile_dir: Optional[Path]=None) -> None  -- Erase the crash-restore flag so Chromium never shows the 'didn't shut down correctly /
  sanitize(profile_dir: Optional[Path]=None, *, kill: bool=True) -> int  -- Full pre-launch hygiene: reap zombies, clear stale locks, erase the crash-restore flag.
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

import config

LOG = config.getLogger("profile_hygiene")

# Single-instance lock artifacts Chromium drops next to the profile. Stale ones (after a hard
# kill) can make a launch believe another instance is live. Default/LOCK (leveldb) is left ALONE
# -- Chromium recreates it and deleting a live one corrupts the store; the running PROCESS, not
# this file, is what actually blocks a launch, and killZombies removes that.
_LOCK_NAMES = ("SingletonLock", "SingletonCookie", "SingletonSocket", "lockfile")


def _profileDir(profile_dir: Optional[Path] = None) -> Path:
    return Path(profile_dir or config.CHATGPT_USER_DATA_DIR)


def killZombies(profile_dir: Optional[Path] = None) -> int:
    """Kill every chrome/chromium process whose command line binds this profile. Returns the count
    reaped. Best-effort: per-process races (NoSuchProcess/AccessDenied) are swallowed.

    NOTE: assumes the profile is used by at most ONE session at a time (the 9to5 design -- a single
    second-brain conversation per run). Do not call while a session you want to keep is open."""
    try:
        import psutil
    except Exception:  # noqa: BLE001
        LOG.warning("psutil unavailable; cannot reap profile zombies")
        return 0
    needle = str(_profileDir(profile_dir)).lower()
    killed = 0
    for proc in psutil.process_iter(["name", "cmdline"]):
        try:
            name = (proc.info.get("name") or "").lower()
            if "chrome" not in name and "chromium" not in name:
                continue
            cmd = " ".join(proc.info.get("cmdline") or []).lower()
            if needle in cmd:
                proc.kill()
                killed += 1
        except Exception:  # noqa: BLE001 -- psutil raises several proc-gone/perm types; skip all
            continue
    if killed:
        LOG.info("reaped %d zombie chromium process(es) on %s", killed, needle)
    return killed


def clearStaleLocks(profile_dir: Optional[Path] = None) -> None:
    """Remove leftover single-instance lock artifacts. Call ONLY after killZombies, so a live
    holder is never robbed of its lock. Mostly a no-op on Windows (these are POSIX), kept for
    cross-platform completeness."""
    profile = _profileDir(profile_dir)
    for name in _LOCK_NAMES:
        target = profile / name
        try:
            if target.exists() or target.is_symlink():
                target.unlink()
        except OSError:
            pass


def markCleanExit(profile_dir: Optional[Path] = None) -> None:
    """Erase the crash-restore flag so Chromium never shows the 'didn't shut down correctly /
    restore pages?' bubble. Sets ``profile.exit_type = "Normal"`` + ``exited_cleanly = true`` in
    Default/Preferences (an UNprotected field, safe to edit without the Secure Preferences MAC)."""
    pref = _profileDir(profile_dir) / "Default" / "Preferences"
    try:
        if not pref.exists():
            return
        data = json.loads(pref.read_text(encoding="utf-8"))
        prof = data.setdefault("profile", {})
        if prof.get("exit_type") == "Normal" and prof.get("exited_cleanly") is True:
            return
        prof["exit_type"] = "Normal"
        prof["exited_cleanly"] = True
        pref.write_text(json.dumps(data, separators=(",", ":")), encoding="utf-8")
        LOG.info("reset crash-restore flag on %s", pref)
    except Exception as e:  # noqa: BLE001
        LOG.warning("could not reset crash-restore flag: %s", e)


def sanitize(profile_dir: Optional[Path] = None, *, kill: bool = True) -> int:
    """Full pre-launch hygiene: reap zombies, clear stale locks, erase the crash-restore flag.
    Returns the number of zombies killed. Never raises."""
    profile = _profileDir(profile_dir)
    n = killZombies(profile) if kill else 0
    clearStaleLocks(profile)
    markCleanExit(profile)
    return n
