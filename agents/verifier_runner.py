"""Verification runner: execute brain-authored verify commands and evaluate results.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  runVerification(verify: Optional[dict], work_dir: str, executor_result: dict) -> dict  -- Return a verify_result dict: {passed, cmd, expect, returncode, stdout, stderr}.
DEPENDS-ON: agents.executor, config
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path
from typing import Optional

import config
from agents.executor import _killProcessTree

LOG = config.getLogger("verifier")

_MAX_CAP = 2000  # truncate captured output


def _cap(text: Optional[str]) -> str:
    text = text or ""
    return text if len(text) <= _MAX_CAP else text[:_MAX_CAP] + "\n...[truncated]"


# ==== SHELL RUNNER ====

def _verifyTimeoutSeconds(cmd: str) -> int:
    """A pytest/unittest suite run legitimately needs more wall-clock than a narrow python -c
    check; sharing one tight cap made a broad test-runner verify fail on TimeoutExpired even
    while the suite was still making real progress (never an actual regression signal)."""
    return config.VERIFY_SUITE_TIMEOUT_SECONDS if _isTestRunner(cmd) else config.VERIFY_TIMEOUT_SECONDS


def _runShell(cmd: str, work_dir: str, timeout: int) -> subprocess.CompletedProcess:
    """Run a verify command string via the native shell (cmd.exe on Windows).

    Verifies are constrained to ``python <path>`` shapes, so the native shell is
    correct: cmd.exe handles Windows backslash paths AND nested quotes the way a
    human would type them. (bash would treat the backslashes in C:\\... as escapes
    and mangle the path.)

    Uses Popen + CREATE_NEW_PROCESS_GROUP + tree-kill on timeout -- the SAME Windows
    orphan bug the executor already fixes (f57855b): subprocess.run's timeout kills only
    the cmd.exe launcher, leaking the python.exe grandchild, which keeps a file lock on the
    very artifact the next retry must rewrite -> a phantom verify failure on attempt 2/3.
    """
    Path(work_dir).mkdir(parents=True, exist_ok=True)
    creationflags = subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0
    proc = subprocess.Popen(cmd, shell=True, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, text=True, encoding="utf-8", errors="replace",
                            cwd=work_dir, creationflags=creationflags,
                            start_new_session=(os.name != "nt"))
    try:
        out, err = proc.communicate(timeout=timeout)
        return subprocess.CompletedProcess(cmd, proc.returncode, out or "", err or "")
    except subprocess.TimeoutExpired:
        _killProcessTree(proc.pid)
        try:
            proc.communicate(timeout=10)
        except Exception:  # noqa: BLE001
            pass
        raise


# ==== RESULT EVALUATION ====

_COMPOUND_PREFIXES = ("stdout_contains_all:", "stdout_regex_all:")


def _evaluate(expect: str, returncode: int, stdout: str) -> bool:
    # coerce a non-string/empty expect (brain may emit an int/None) to the safe default
    expect = (expect if isinstance(expect, str) else "").strip() or config.VERIFY_DEFAULT_EXPECT
    if expect == "exit_zero":
        return returncode == 0
    if expect.startswith("stdout_contains:"):
        needle = expect[len("stdout_contains:"):]
        # FX-2: an EMPTY needle makes `"" in stdout` always True -> false-PASS on crash.
        if not needle:
            return returncode == 0
        # Gate on a clean exit too: a crashing program must not pass via a lucky needle in stdout.
        return returncode == 0 and needle in stdout
    if expect.startswith("stdout_regex:"):
        pattern = expect[len("stdout_regex:"):]
        if not pattern:
            return returncode == 0
        try:
            return returncode == 0 and re.search(pattern, stdout) is not None
        except re.error:
            return False
    # Compound expectations -- pass ONLY if EVERY '||'-separated needle/pattern is present.
    if expect.startswith("stdout_contains_all:"):
        needles = [n for n in expect[len("stdout_contains_all:"):].split("||") if n]
        return returncode == 0 and bool(needles) and all(n in stdout for n in needles)
    if expect.startswith("stdout_regex_all:"):
        pats = [p for p in expect[len("stdout_regex_all:"):].split("||") if p]
        if not pats:
            return False
        try:
            return returncode == 0 and all(re.search(p, stdout) is not None for p in pats)
        except re.error:
            return False
    return returncode == 0


# ==== PATH / WORKDIR HELPERS ====

def _extractVerifyPath(cmd: str) -> Optional[str]:
    """Best-effort: return the first path-like argument in a verify command.

    Handles ``python x.py``, ``python -m pytest a/b/*_test.py`` and ``pytest a/b``.
    Runner tokens and flags are skipped; the first arg that looks like a path
    (ends in .py or contains a separator) is returned.
    """
    toks = cmd.strip().split()
    skip = {"py", "python", "python3", "pytest", "unittest", "coverage", "run"}
    for tok in toks[1:]:
        if tok.startswith("-"):
            continue
        if tok.lower() in skip:
            continue
        if tok.endswith(".py") or "/" in tok or "\\" in tok:
            return tok
    return None


def _normalizeWorkDir(cmd: str, work_dir: str) -> str:
    """Return the dir a verify command should run in.

    Verify commands are authored relative to the repo root, but a self-referential
    run sets a subtask's work_dir to a ``.sc-ctx/<sid>`` scratch dir -- so a verify
    like ``python tests/foo.py`` or ``pytest tests/x/*_test.py`` cannot find its
    target from the scratch cwd. Re-root to INSTALL_ROOT when the referenced path
    lives under the repo root but not under work_dir. Absolute repo-root paths are
    normalised too (prevents Windows path mangling).
    """
    candidate = _extractVerifyPath(cmd)
    if not candidate:
        return work_dir
    script = Path(candidate)
    if script.is_absolute():
        for root in (config.PROJECT_ROOT, config.INSTALL_ROOT):
            try:
                script.relative_to(root)
                return str(root)
            except ValueError:
                continue
        return work_dir
    probe = re.split(r"[*?\[]", candidate, maxsplit=1)[0]
    if probe.endswith(("/", "\\")) or probe == candidate:
        check = Path(probe)
    else:
        check = Path(probe).parent
    try:
        in_workdir = (Path(work_dir) / check).exists()
        in_root = (Path(config.INSTALL_ROOT) / check).exists()
    except OSError:
        return work_dir
    if in_root and not in_workdir:
        return str(config.INSTALL_ROOT)
    return work_dir


def _verifyScriptMissing(cmd: str, work_dir: str) -> bool:
    """True when cmd's first path-like argument is a literal .py script that doesn't exist in
    work_dir, PROJECT_ROOT, or INSTALL_ROOT. Catches a brain-authored verify that references a
    helper script (e.g. ``python check_unit_tests.py``) which was never actually created: running
    it would fail with FileNotFoundError on every attempt, burning all MAX_SUBTASK_ATTEMPTS
    retries on a structural authoring defect rather than a real regression."""
    candidate = _extractVerifyPath(cmd)
    if not candidate or not candidate.endswith(".py"):
        return False
    if any(ch in candidate for ch in "*?[]"):   # glob pattern -- existence isn't a literal check
        return False
    path = Path(candidate)
    if path.is_absolute():
        return not path.exists()
    return not any((Path(root) / path).exists()
                   for root in (work_dir, config.PROJECT_ROOT, config.INSTALL_ROOT))


def _isTestRunner(cmd: str) -> bool:
    """True when the command's own exit code is authoritative verification:
    pytest/unittest, or a ``test_*.py`` / ``*_test.py`` script. Inline ``python -c``
    snippets are never runners (they may embed a filename literal)."""
    c = cmd.strip()
    if re.search(r"(?:^|\s)-c(?:\s|$)", c):
        return False
    if re.search(r"\b-m\s+(?:pytest|unittest)\b", c):
        return True
    if re.search(r"(?:^|[\\/\s])pytest(?:\s|$)", c):
        return True
    if re.search(r"(?:test_[\w.\-]+\.py|[\w.\-]+_test\.py)(?=$|[\s\"'])", c):
        return True
    return False


# ==== PUBLIC API ====

def runVerification(verify: Optional[dict], work_dir: str, executor_result: dict) -> dict:
    """Return a verify_result dict: {passed, cmd, expect, returncode, stdout, stderr}."""
    executor_result = executor_result if isinstance(executor_result, dict) else {}
    cmd = (verify or {}).get("cmd") if isinstance(verify, dict) else None
    expect = (verify or {}).get("expect") or config.VERIFY_DEFAULT_EXPECT

    if not cmd:
        passed = bool(executor_result.get("ok"))
        return {
            "passed": passed,
            "cmd": None,
            "expect": "executor_exit_zero",
            "returncode": executor_result.get("returncode"),
            "stdout": "",
            "stderr": "" if passed else _cap(executor_result.get("stderr")),
        }

    work_dir = _normalizeWorkDir(cmd, work_dir)
    if _verifyScriptMissing(cmd, work_dir):
        passed = bool(executor_result.get("ok"))
        LOG.warning("Verify script missing on disk (%s) -- falling back to executor exit status: %s",
                    cmd, "PASS" if passed else "FAIL")
        return {
            "passed": passed,
            "cmd": cmd,
            "expect": "executor_exit_zero (verify script missing)",
            "returncode": executor_result.get("returncode"),
            "stdout": "",
            "stderr": "" if passed else _cap(executor_result.get("stderr")),
        }
    timeout = _verifyTimeoutSeconds(cmd)
    LOG.info("Verifying: %s  (expect: %s, timeout: %ss)", cmd, expect, timeout)
    try:
        proc = _runShell(cmd, work_dir, timeout)
        # Fold stderr into haystack ONLY when the program exited cleanly (rc==0).
        haystack = (proc.stdout or "") + (("\n" + (proc.stderr or "")) if proc.returncode == 0 else "")
        passed = _evaluate(expect, proc.returncode, haystack)
        # A green self-asserting test suite IS the verification; don't false-FAIL on needle mismatch.
        if not passed and proc.returncode == 0 and _isTestRunner(cmd):
            passed = True
        result = {
            "passed": passed,
            "cmd": cmd,
            "expect": expect,
            "returncode": proc.returncode,
            "stdout": _cap(proc.stdout),
            "stderr": _cap(proc.stderr),
        }
    except subprocess.TimeoutExpired:
        result = {"passed": False, "cmd": cmd, "expect": expect, "returncode": -1,
                  "stdout": "", "stderr": f"verify TIMEOUT after {timeout}s"}
    except Exception as e:  # noqa: BLE001
        result = {"passed": False, "cmd": cmd, "expect": expect, "returncode": -1,
                  "stdout": "", "stderr": f"verify error: {e}"}
    LOG.info("Verify %s -> %s (rc=%s)", "PASS" if result["passed"] else "FAIL", cmd, result["returncode"])
    return result
