"""Finder-to-ledger bridge: turn DiscoveryReport findings into executable invention seeds.

Findings today only feed architect prose. This bridge converts qualifying findings into
``FindingCandidate``s, routes each by measured novelty / risk / confidence, and registers
genuine inventions into the evolution ledger (kind='feature') so they become seeds for the
QD archive + generational forking. Audit-shaped findings never enter the invention path;
low-novelty ones are demoted to plain improvements. Accepted candidates are also recorded
into the novelty history so future runs measure novelty against them. Best-effort throughout.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  finding_to_candidate(f: Any, run_id: str='') -> FindingCandidate  -- Adapt a discovery Finding (or dict) into a normalized FindingCandidate.
  route_candidate(fc: FindingCandidate, *, novelty_floor: float, novelty_hi: float, conf_hi: float) -> str  -- Pure routing decision (no I/O)
  bridge_report(report: Any, *, run_id: str='', db_path=None, embed_fn=None, store=None, record: bool=True) -> dict  -- Route + register every finding in a DiscoveryReport
DEPENDS-ON: config, memory.experience_evolution, memory.novelty_index, platform_core.orchestration, platform_core.orchestration.invention_types
SIDE-EFFECTS: registers candidates in the evolution ledger + records findings to novelty history
RUN/TEST: python -m pytest tests/orchestration/test_ledger_bridge.py
"""
from __future__ import annotations

from typing import Any, Optional

import config
from platform_core.orchestration.invention_types import FindingCandidate

LOG = config.getLogger("discovery.bridge")

# Route labels. skipped/improvement never enter the invention path.
ROUTES = ("skipped", "improvement", "qd_seed", "auto_run_eligible", "proposal")
_AUDIT_TYPES = {"health", "memory", "ux"}


def finding_to_candidate(f: Any, run_id: str = "") -> FindingCandidate:
    """Adapt a discovery Finding (or dict) into a normalized FindingCandidate."""
    g = f.get if isinstance(f, dict) else (lambda k, d=None: getattr(f, k, d))
    kind = "feature" if (g("candidate_kind") or g("type") == "new_capability") else "improvement"
    subs = list(g("target_subsystems") or []) or list(g("affected_files") or [])
    return FindingCandidate(
        id="", kind=kind, title=str(g("title") or ""), summary=str(g("rationale") or ""),
        design_sketch=str(g("design_sketch") or ""), target_subsystems=[str(s) for s in subs],
        measured_novelty=float(g("measured_novelty") or 0.0),
        specificity=float(g("specificity") or 0) / 5.0, impact=float(g("impact") or 0) / 5.0,
        confidence=float(g("confidence") if g("confidence") is not None else 0.6),
        risk=str(g("risk") or "medium"),
        provenance={"lens": str(g("source_lens") or ""), "run_id": run_id,
                    "candidate_kind": str(g("candidate_kind") or ""),
                    "verification_plan": str(g("verification_plan") or "")})


def route_candidate(fc: FindingCandidate, *, novelty_floor: float,
                    novelty_hi: float, conf_hi: float) -> str:
    """Pure routing decision (no I/O). See ROUTES. Deterministic + fully unit-testable."""
    if not fc.has_sketch():                       # no sketch/subsystem => audit-shaped
        return "skipped"
    if fc.measured_novelty < novelty_floor:       # real but not novel enough => improvement
        return "improvement"
    if fc.confidence < 0.5:                        # too uncertain to build autonomously
        return "proposal"
    if fc.measured_novelty >= novelty_hi and fc.risk == "low" and fc.confidence >= conf_hi:
        return "auto_run_eligible"                # the gate makes the final call
    if fc.measured_novelty >= novelty_hi and fc.risk != "low":
        return "proposal"                          # novel but risky => human-gated
    if fc.impact >= 0.8:                           # impact >= 4/5 with decent confidence
        return "qd_seed"
    return "proposal"


def _thresholds() -> tuple[float, float, float]:
    return (float(getattr(config, "NOVELTY_FINDER_FLOOR", 0.55)),
            float(getattr(config, "INVENTION_AUTO_NOVELTY_MIN", 0.75)),
            float(getattr(config, "INVENTION_AUTO_CONFIDENCE_MIN", 0.80)))


def _register(fc: FindingCandidate, route: str, db_path) -> Optional[int]:
    """Persist a routed candidate: improvements as plain candidates, inventions as features."""
    from memory import experience_evolution as ee
    target = (fc.target_subsystems or ["unknown"])[0]
    body = fc.design_sketch or fc.summary or fc.title
    prov = {**fc.provenance, "route": route, "title": fc.title}
    if route == "improvement":
        return ee.register_candidate(kind="improvement", target=target, body=body,
                                     provenance=prov, db_path=db_path)
    return ee.register_invention(
        target=target, body=body, measured_novelty=fc.measured_novelty, risk=fc.risk,
        confidence=fc.confidence, subsystem=target, design_sketch=fc.design_sketch,
        verify_plan=str(fc.provenance.get("verification_plan", "")), provenance=prov,
        db_path=db_path)


def bridge_report(report: Any, *, run_id: str = "", db_path=None,
                  embed_fn=None, store=None, record: bool = True) -> dict:
    """Route + register every finding in a DiscoveryReport. Never raises.

    Returns {"routes": {title: route}, "registered": {title: candidate_id}, "counts": {...}}."""
    floor, nov_hi, conf_hi = _thresholds()
    findings = list(getattr(report, "findings", None) or [])
    routes: dict[str, str] = {}
    prepared: list[tuple[FindingCandidate, str, Any]] = []
    registered: dict[str, int] = {}
    for f in findings:
        fc = finding_to_candidate(f, run_id)
        route = route_candidate(fc, novelty_floor=floor, novelty_hi=nov_hi, conf_hi=conf_hi)
        routes[fc.title] = route
        prepared.append((fc, route, f))

    # The bridge is the live seeding seam: rank, deconflict, and allocate invention
    # candidates before persisting them.  The coordinator is pure except for best-effort
    # import-graph reads, and a failure preserves the historical direct-registration path.
    seed_plan = {}
    try:
        from platform_core.orchestration import invention_seeding
        seed_plan = invention_seeding.plan_seeds([p[0] for p in prepared], [p[1] for p in prepared])
        selected = set(seed_plan.get("selected_ids", []))
    except Exception as e:  # noqa: BLE001 -- never lose a discovery seed to optional analysis
        LOG.warning("invention seeding failed; using unfiltered bridge (ignored): %s", e)
        selected = {f"seed-{i}" for i, p in enumerate(prepared) if p[1] != "skipped"}

    for index, (fc, route, f) in enumerate(prepared):
        if route == "skipped":
            continue
        if record:
            _record_history(f, run_id, embed_fn, store)
        # Improvements preserve the legacy direct route.  Invention routes are only
        # persisted when the max-closure portfolio admitted their seed.
        if route != "improvement" and f"seed-{index}" not in selected:
            continue
        cid = _register(fc, route, db_path)
        if cid is not None:
            registered[fc.title] = cid
    counts = {r: sum(1 for v in routes.values() if v == r) for r in ROUTES}
    return {"routes": routes, "registered": registered, "counts": counts,
            "seeding": seed_plan}


def _record_history(finding: Any, run_id: str, embed_fn, store) -> None:
    """Add an accepted finding to the novelty history (so future runs measure against it)."""
    try:
        from memory import novelty_index
        novelty_index.record_finding(finding, run_id=run_id, embed_fn=embed_fn, store=store)
    except Exception as e:  # noqa: BLE001
        LOG.debug("novelty history record skipped (ignored): %s", e)
