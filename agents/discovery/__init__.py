"""Proactive Discovery Engine — public facade.

Compile a codebase digest, run parallel innovation lenses, synthesize an
impact-ranked report for the architect to consume.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  shouldRunFullDiscovery(goal_raw: str) -> bool  -- True when goal is absent or matches a vague pattern.
  run_discovery(work_dir: str, goal_raw: str, work_profile=None) -> Optional[DiscoveryReport]  -- Run the full discovery pipeline
DEPENDS-ON: agents.discovery, agents.discovery.models, config, platform_core.orchestration
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

from typing import Optional

import config
from agents.discovery.models import Finding, DiscoveryReport  # noqa: F401

__all__ = ["Finding", "DiscoveryReport", "shouldRunFullDiscovery", "run_discovery"]

LOG = config.getLogger("discovery")

_VAGUE_PATTERNS = (
    "improve", "fix everything", "do your best", "make it better",
    "optimize", "clean up", "work on the codebase", "improve everything",
    "do something good", "surprise me", "make things better", "enhance",
    "self-improve", "improve self",
)


def shouldRunFullDiscovery(goal_raw: str) -> bool:
    """True when goal is absent or matches a vague pattern."""
    if not goal_raw or not goal_raw.strip():
        return True
    low = goal_raw.lower().strip()
    return any(p in low for p in _VAGUE_PATTERNS)


def run_discovery(work_dir: str, goal_raw: str, work_profile=None) -> Optional[DiscoveryReport]:
    """Run the full discovery pipeline. Returns None on specific goals or any failure.

    Digest is always compiled (injected as context even for specific goals).
    Lens panel + synthesis only run when goal is vague/absent.
    """
    compiled = None
    try:
        from agents.discovery import digest as digest_mod
        LOG.info("Discovery: compiling digest for %s", work_dir)
        compiled = digest_mod.compile_digest(work_dir)
    except Exception as e:  # noqa: BLE001
        LOG.warning("Discovery digest failed (%s); skipping discovery", e)
        return None

    force_lenses = False
    transformative = False
    try:
        from platform_core.orchestration import work_profile as _wp
        pol = _wp.policy(_wp.resolve(work_profile))
        force_lenses = pol.discovery_depth in ("lenses", "transformative")
        transformative = pol.discovery_depth == "transformative"
    except Exception:  # noqa: BLE001
        pass

    if not force_lenses and not shouldRunFullDiscovery(goal_raw):
        LOG.info("Discovery: specific goal detected — skipping lens panel")
        return None

    try:
        from agents.discovery import lenses as lenses_mod
        from agents.discovery import synthesis as synthesis_mod
        LOG.info("Discovery: running lens panel (transformative=%s)", transformative)
        findings = lenses_mod.run_lens_panel(compiled, transformative=transformative)
        LOG.info("Discovery: synthesizing %d findings", len(findings))
        report = synthesis_mod.synthesize(findings)
        if transformative:
            # innovation_ratio is a derived read-only property; the real transformative effect
            # is in generation (corpus + moonshot lens). Just tag the theme for the architect.
            report.theme_suggestion = f"transformative: {report.theme_suggestion}"
        LOG.info("Discovery: complete — %d findings, theme=%r",
                 len(report.findings), report.theme_suggestion)
        return report
    except Exception as e:  # noqa: BLE001
        LOG.warning("Discovery lens/synthesis failed (%s); run proceeds without report", e)
        return None
