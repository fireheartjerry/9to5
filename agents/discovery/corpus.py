"""Invention corpus: retrievable SOTA pattern cards injected into feature-seeking lenses.

Cards live as markdown in ``invention_corpus/`` (MAP-Elites, AlphaEvolve, DGM, ADAS, etc.).
Each is prior art the finders adapt -- NOT authority to copy. ``retrieve`` ranks cards
against a digest/goal (keyword-overlap by default for determinism + zero latency; semantic
cosine when an ``embed_fn`` is injected) and ``corpus_block`` renders the top-k for prompt
injection. Everything is best-effort: a missing/empty corpus dir yields an empty block and
never raises.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  CorpusCard  -- One parsed pattern card (name + full text + section map).
  load_cards() -> list[CorpusCard]  -- Parse + cache every card in invention_corpus/.
  retrieve(query, k, *, embed_fn) -> list[CorpusCard]  -- Top-k cards relevant to the query.
  corpus_block(query, k, *, embed_fn) -> str  -- Prompt-injectable block of the top-k cards.
  reset_cache() -> None  -- Drop the parsed-card cache (tests).
DEPENDS-ON: config
SIDE-EFFECTS: reads agents/discovery/invention_corpus/*.md
RUN/TEST: python -m pytest tests/orchestration/test_invention_corpus.py
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Optional

import config

LOG = config.getLogger("discovery.corpus")

_CARD_DIR = Path(__file__).parent / "invention_corpus"
_STOP = frozenset((
    "the", "a", "an", "to", "of", "and", "or", "for", "in", "on", "is", "it", "this",
    "that", "with", "as", "be", "by", "how", "what", "when", "not", "use", "used", "into",
    "from", "at", "its", "your", "you", "we", "are", "can", "should", "would",
))


@dataclass
class CorpusCard:
    """One parsed pattern card (name + full text + section map)."""

    name: str
    path: str
    text: str
    sections: dict[str, str] = field(default_factory=dict)

    def tokens(self) -> set[str]:
        return _tokenize(self.text)


def _tokenize(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9]+", (text or "").lower())
            if len(w) > 2 and w not in _STOP}


def _parse_card(text: str, name: str, path: str) -> CorpusCard:
    """Split a card's markdown into a {section-title: body} map (H1 name + H2 sections)."""
    sections: dict[str, str] = {}
    cur = "_title"
    buf: list[str] = []
    for line in text.splitlines():
        m = re.match(r"^#{1,3}\s+(.*)$", line)
        if m:
            sections[cur] = "\n".join(buf).strip()
            cur = m.group(1).strip().lower()
            buf = []
        else:
            buf.append(line)
    sections[cur] = "\n".join(buf).strip()
    return CorpusCard(name=name, path=path, text=text, sections=sections)


_CARDS: Optional[list[CorpusCard]] = None


def load_cards() -> list[CorpusCard]:
    """Parse + cache every ``*.md`` card in invention_corpus/ (empty list on any failure)."""
    global _CARDS
    if _CARDS is not None:
        return _CARDS
    cards: list[CorpusCard] = []
    try:
        for p in sorted(_CARD_DIR.glob("*.md")):
            try:
                cards.append(_parse_card(p.read_text(encoding="utf-8"), p.stem, str(p)))
            except OSError as e:
                LOG.debug("corpus card unreadable %s (ignored): %s", p, e)
    except Exception as e:  # noqa: BLE001
        LOG.debug("corpus load failed (ignored): %s", e)
    _CARDS = cards
    return cards


def _keyword_rank(query: str, cards: list[CorpusCard]) -> list[tuple[float, CorpusCard]]:
    """Jaccard-ish token-overlap score per card (deterministic, no embeddings)."""
    q = _tokenize(query)
    if not q:
        return [(0.0, c) for c in cards]
    scored = []
    for c in cards:
        ct = c.tokens()
        overlap = len(q & ct)
        score = overlap / (len(q) ** 0.5) if overlap else 0.0
        scored.append((score, c))
    return scored


def _semantic_rank(query: str, cards: list[CorpusCard],
                   embed_fn: Callable) -> Optional[list[tuple[float, CorpusCard]]]:
    """Cosine rank via an injected embedder; None if the query can't be embedded."""
    try:
        from memory import retrieval
        qv = embed_fn(query)
        if not qv:
            return None
        out = []
        for c in cards:
            cv = embed_fn(c.text[:2000])
            out.append((retrieval.cosine(qv, cv) if cv else 0.0, c))
        return out
    except Exception as e:  # noqa: BLE001
        LOG.debug("corpus semantic rank failed (ignored): %s", e)
        return None


def retrieve(query: str, k: Optional[int] = None, *,
             embed_fn: Optional[Callable] = None) -> list[CorpusCard]:
    """Top-k cards most relevant to ``query`` (semantic when embed_fn given, else keyword)."""
    if not getattr(config, "INVENTION_CORPUS_ENABLED", True):
        return []
    cards = load_cards()
    if not cards:
        return []
    kk = int(k if k is not None else getattr(config, "INVENTION_CORPUS_TOPK", 3))
    scored = (embed_fn and _semantic_rank(query, cards, embed_fn)) or _keyword_rank(query, cards)
    scored = sorted(scored, key=lambda t: t[0], reverse=True)
    hits = [c for s, c in scored if s > 0][:kk]
    return hits or [c for _, c in scored[:kk]]   # never return empty when cards exist


def corpus_block(query: str, k: Optional[int] = None, *,
                 embed_fn: Optional[Callable] = None) -> str:
    """Render the top-k cards as a prompt-injectable 'prior art' block ('' when none)."""
    cards = retrieve(query, k, embed_fn=embed_fn)
    if not cards:
        return ""
    parts = ["PRIOR ART (adapt, don't copy — explain your LOCAL adaptation to THIS repo):"]
    for c in cards:
        mech = c.sections.get("core mechanism", "")[:400]
        recipe = c.sections.get("transfer recipe", "")[:400]
        parts.append(f"\n[{c.name}] {mech}\n  Transfer: {recipe}")
    return "\n".join(parts).strip()


def reset_cache() -> None:
    """Drop the parsed-card cache (tests)."""
    global _CARDS
    _CARDS = None
