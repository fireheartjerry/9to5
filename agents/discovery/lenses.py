"""Phase 1: parallel lens panel — 5 agents run concurrently on the digest.

Each lens produces 0-3 Finding dicts via Ollama. Lenses run in a thread pool;
individual failures are caught so a dead lens never blocks the others.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  run_lens_panel(digest: dict) -> list[Finding]  -- Run all lenses in parallel and return combined findings.
DEPENDS-ON: agents.discovery.models, config, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_discovery_lenses.py
"""
from __future__ import annotations

import json
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import List

import config
import llm_io
from agents.discovery.models import Finding

LOG = config.getLogger("discovery.lenses")

_OLLAMA = None
_VALID_TYPES = {"new_capability", "reimagining", "health", "memory", "ux"}
_MAX_FINDINGS_PER_LENS = 3


def _getOllama():
    global _OLLAMA
    if _OLLAMA is None:
        import ollama
        _OLLAMA = ollama.Client(host=config.OLLAMA_HOST, timeout=config.OLLAMA_TIMEOUT_SECONDS)
    return _OLLAMA


def _brain_call(system: str, user: str, retries: int = 2) -> list:
    """Call Ollama and parse the findings JSON list. Returns [] on any failure."""
    delay = 2.0
    for attempt in range(1, retries + 1):
        try:
            resp = _getOllama().chat(
                model=config.OLLAMA_MODEL,
                messages=[{"role": "system", "content": system},
                          {"role": "user", "content": user}],
                format="json",
                options={"num_ctx": config.OLLAMA_NUM_CTX},
                keep_alive=config.OLLAMA_KEEP_ALIVE,
            )
            text = llm_io.responseText(resp).strip()
            parsed = json.loads(text)
            if isinstance(parsed, dict):
                return parsed.get("findings", [])
            return []
        except json.JSONDecodeError:
            LOG.debug("lens brain returned non-JSON (attempt %d)", attempt)
            return []
        except Exception as e:  # noqa: BLE001
            LOG.warning("lens brain call failed (%d/%d): %s", attempt, retries, e)
            if attempt < retries:
                time.sleep(delay)
                delay *= 2
    return []


def _to_finding(raw: dict, source_lens: str):
    """Validate and coerce a raw dict into a Finding. Returns None if unfit."""
    try:
        title = str(raw.get("title") or "").strip()
        if not title:
            return None
        ftype = str(raw.get("type") or "health")
        if ftype not in _VALID_TYPES:
            ftype = "health"
        impact = max(1, min(5, int(raw.get("impact") or 3)))
        specificity = max(1, min(5, int(raw.get("specificity") or 3)))
        innovation = max(1, min(5, int(raw.get("innovation") or 1)))
        if specificity < 2:  # too vague to act on
            return None
        return Finding(
            title=title, type=ftype, impact=impact,
            specificity=specificity, innovation=innovation,
            rationale=str(raw.get("rationale") or "")[:500],
            affected_files=[str(f) for f in (raw.get("affected_files") or [])],
            source_lens=source_lens,
        )
    except Exception:  # noqa: BLE001
        return None


_OUTPUT_FORMAT = (
    'Respond with JSON only: {"findings": [<0-3 items>]}. '
    'Each item: {"title":"...","type":"new_capability|reimagining|health|memory|ux",'
    '"impact":1-5,"specificity":1-5,"innovation":1-5,'
    '"rationale":"...","affected_files":["..."]}. '
    "NEVER return more than 3 findings. Return [] if nothing strong found."
)


def _digest_summary(digest: dict) -> str:
    """Compact JSON summary of the digest for injection into lens prompts."""
    summary = {
        "architecture": str(digest.get("architecture") or "")[:1500],
        "module_signatures": str(digest.get("module_signatures") or "")[:800],
        "dependency_graph": str(digest.get("dependency_graph") or "")[:500],
        "static_signals": digest.get("static_signals") or {},
        "git_signals": {k: str(v)[:200] for k, v in (digest.get("git_signals") or {}).items()},
        "github": {k: str(v)[:300] for k, v in (digest.get("github") or {}).items()},
        "institutional_memory": digest.get("institutional_memory") or {},
        "innovation_seeds": digest.get("innovation_seeds") or {},
        "leverage_signals": digest.get("leverage_signals") or {},
    }
    return json.dumps(summary, ensure_ascii=False)[:6000]


# ── Individual lenses ─────────────────────────────────────────────────────────

def _lens_1_code_health(digest: dict) -> List[Finding]:
    system = (
        "You are a senior engineer performing a code health audit. "
        "Find the most impactful fixable problems: size violations, test gaps, "
        "security issues, flaky tests. Be SPECIFIC — name exact files and functions. "
        "Never suggest 'add more tests generally'. " + _OUTPUT_FORMAT
    )
    user = f"Codebase digest:\n{_digest_summary(digest)}"
    raw = _brain_call(system, user)
    results = []
    for r in raw[:_MAX_FINDINGS_PER_LENS]:
        f = _to_finding(r, "lens_1")
        if f is not None:
            results.append(f)
    return results


