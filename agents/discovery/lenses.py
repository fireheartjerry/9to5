# Audit lenses take (digest, chat); feature lenses also take a corpus prior-art block.
_AUDIT_LENSES = [
    _lens_1_code_health,
    _lens_2_institutional_memory,
    _lens_5a_confused_newcomer,
    _lens_5b_blocked_power_user,
]
_FEATURE_LENSES = [
    _lens_3_architectural_reimagining,
    _lens_4_missing_capabilities,
]


def _build_tasks(digest: dict, chat, corpus: str, transformative: bool) -> list:
    """(callable, name) tasks: audit lenses always; feature lenses get corpus; moonshot only
    under transformative depth (this is what actually WIDENS the pool + shifts content)."""
    tasks = [(lambda l=l: l(digest, chat), l.__name__) for l in _AUDIT_LENSES]
    feature = list(_FEATURE_LENSES) + ([_lens_6_moonshot] if transformative else [])
    tasks += [(lambda l=l: l(digest, chat, corpus), l.__name__) for l in feature]
    return tasks


def run_lens_panel(digest: dict, chat=None, *, transformative: bool = False) -> List[Finding]:
    """Run all lenses in parallel. Returns combined Finding list. Never raises.

    ``transformative`` (inventor profile) retrieves invention-corpus prior art for the
    feature lenses AND adds the moonshot lens — a real change in generation, not a cosmetic
    ratio bump."""
    corpus = _corpus_for(digest) if transformative else ""
    tasks = _build_tasks(digest, chat, corpus, transformative)
    LOG.info("Running %d discovery lenses (transformative=%s)", len(tasks), transformative)
    all_findings: List[Finding] = []
    with ThreadPoolExecutor(max_workers=len(tasks)) as pool:
        futures = {pool.submit(fn): name for fn, name in tasks}
        for future in as_completed(futures):
            name = futures[future]
            try:
                findings = future.result(timeout=120)
                LOG.info("Lens %s returned %d findings", name, len(findings))
                all_findings.extend(findings)
            except Exception as e:  # noqa: BLE001
                LOG.warning("Lens %s failed: %s", name, e)
    return all_findings
