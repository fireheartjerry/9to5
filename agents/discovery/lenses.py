"""Phase 1: parallel lens panel — 5 agents run concurrently on the digest.

Each lens produces 0-3 Finding dicts via the ONE llm_io seam (R5: the client,
retry/backoff, and empty-completion salvage live there). Lenses run in a thread
pool; individual failures are caught so a dead lens never blocks the others.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  run_lens_panel(digest: dict, chat=None, *, transformative: bool=False) -> List[Finding]  -- Run all lenses in parallel
DEPENDS-ON: agents.discovery.corpus, agents.discovery.models, config, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_discovery_feature_lenses.py tests/orchestration/test_discovery_lenses.py
"""
from __future__ import annotations

import json
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import List

import config
import llm_io
from agents.discovery.models import Finding

LOG = config.getLogger("discovery.lenses")

_VALID_TYPES = {"new_capability", "reimagining", "health", "memory", "ux"}
_VALID_KINDS = {
    "new_capability", "architecture_unlock", "workflow_acceleration", "agent_capability_upgrade",
    "observability_or_explainability", "reliability_or_recovery", "developer_experience",
    "interface_or_reporting",
}
_VALID_RISK = {"low", "medium", "high"}
_MAX_FINDINGS_PER_LENS = 3
_MAX_FINDINGS_PER_LENS_TRANSFORMATIVE = 5


def _brain_call(system: str, user: str, retries: int = 2, chat=None) -> list:
    """One lens call through the seam; parse the findings JSON list. [] on any failure."""
    try:
        if chat is not None:
            resp = llm_io.callChat(chat, system, user, act="discovery_lens", want_json=True)
        else:
            resp = llm_io.chat(system, user, act="discovery_lens", want_json=True,
                               retries=retries)
        parsed = llm_io.responseJson(resp)
        if isinstance(parsed, dict):
            findings = parsed.get("findings", [])
            return findings if isinstance(findings, list) else []
        return []
    except Exception as e:  # noqa: BLE001
        LOG.warning("lens brain call failed: %s", e)
        return []


def _to_finding(raw: dict, source_lens: str):
    """Validate and coerce a raw dict into a Finding. Returns None if unfit."""
    try:
        title = str(raw.get("title") or "").strip()
        if not title:
            return None
        ftype = str(raw.get("type") or "health")
        if ftype not in _VALID_TYPES:
            ftype = "health"
        impact = max(1, min(5, int(raw.get("impact") or 3)))
        specificity = max(1, min(5, int(raw.get("specificity") or 3)))
        innovation = max(1, min(5, int(raw.get("innovation") or 1)))
        if specificity < 2:  # too vague to act on
            return None
        return Finding(
            title=title, type=ftype, impact=impact,
            specificity=specificity, innovation=innovation,
            rationale=str(raw.get("rationale") or "")[:500],
            affected_files=[str(f) for f in (raw.get("affected_files") or [])],
            source_lens=source_lens,
            **_invention_fields(raw),
        )
    except Exception:  # noqa: BLE001
        return None


def _invention_fields(raw: dict) -> dict:
    """Parse the optional feature-invention fields (empty defaults on legacy findings)."""
    kind = str(raw.get("candidate_kind") or "").strip()
    risk = str(raw.get("risk") or "medium").strip().lower()
    try:
        conf = float(raw.get("confidence", 0.6))
    except (TypeError, ValueError):
        conf = 0.6
    subs = raw.get("target_subsystems") or []
    return {
        "candidate_kind": kind if kind in _VALID_KINDS else "",
        "design_sketch": str(raw.get("design_sketch") or "")[:800],
        "verification_plan": str(raw.get("verification_plan") or "")[:400],
        "target_subsystems": [str(s) for s in subs][:6] if isinstance(subs, (list, tuple)) else [],
        "risk": risk if risk in _VALID_RISK else "medium",
        "confidence": max(0.0, min(1.0, conf)),
    }


_OUTPUT_FORMAT = (
    'Respond with JSON only: {"findings": [<0-3 items>]}. '
    'Each item: {"title":"...","type":"new_capability|reimagining|health|memory|ux",'
    '"impact":1-5,"specificity":1-5,"innovation":1-5,'
    '"rationale":"...","affected_files":["..."]}. '
    "NEVER return more than 3 findings. Return [] if nothing strong found."
)

# Feature-invention output contract for the reimagining/missing-capability/moonshot lenses:
# every item must be a CONCRETE, BUILDABLE new capability with a sketch + verification plan.
_FEATURE_OUTPUT_FORMAT = (
    'Respond with JSON only: {"findings": [<0-3 items>]}. Each item is a CONCRETE NEW FEATURE: '
    '{"title":"...","type":"new_capability|reimagining",'
    '"candidate_kind":"new_capability|architecture_unlock|workflow_acceleration|agent_capability_upgrade'
    '|observability_or_explainability|reliability_or_recovery|developer_experience|interface_or_reporting",'
    '"impact":1-5,"specificity":1-5,"innovation":1-5,"confidence":0.0-1.0,"risk":"low|medium|high",'
    '"target_subsystems":["exact/dir/or/module.py"],'
    '"design_sketch":"how to build it concretely — files, seam, mechanism",'
    '"verification_plan":"how to PROVE it works — command/test/metric",'
    '"rationale":"why it is high-upside","affected_files":["..."]}. '
    "REJECT audit-style findings (bug fixes, add-tests-generally, cleanups, renames) — those are NOT "
    "features. Every item MUST include design_sketch AND verification_plan AND target_subsystems. "
    "NEVER return more than 3 findings. Return [] if nothing strong found."
)


def _digest_summary(digest: dict) -> str:
    """Compact JSON summary of the digest for injection into lens prompts."""
    summary = {
        "architecture": str(digest.get("architecture") or "")[:1500],
        "module_signatures": str(digest.get("module_signatures") or "")[:800],
        "dependency_graph": str(digest.get("dependency_graph") or "")[:500],
        "static_signals": digest.get("static_signals") or {},
        "git_signals": {k: str(v)[:200] for k, v in (digest.get("git_signals") or {}).items()},
        "github": {k: str(v)[:300] for k, v in (digest.get("github") or {}).items()},
        "institutional_memory": digest.get("institutional_memory") or {},
        "innovation_seeds": digest.get("innovation_seeds") or {},
        "leverage_signals": digest.get("leverage_signals") or {},
    }
    return json.dumps(summary, ensure_ascii=False)[:6000]


def _corpus_for(digest: dict) -> str:
    """Retrieve invention-corpus prior art relevant to this digest (fail-open to '')."""
    if not getattr(config, "INVENTION_CORPUS_ENABLED", True):
        return ""
    try:
        from agents.discovery import corpus
        arch = str(digest.get("architecture") or "")[:600]
        seeds = json.dumps(digest.get("innovation_seeds") or {})[:300]
        return corpus.corpus_block(f"{arch} new capability feature invention {seeds}")
    except Exception as e:  # noqa: BLE001
        LOG.debug("corpus block skipped (ignored): %s", e)
        return ""


def _feature_findings(system: str, digest: dict, corpus: str, chat, source_lens: str) -> List[Finding]:
    """Shared body for the feature-seeking lenses: inject corpus prior art + parse features."""
    user = f"Codebase digest:\n{_digest_summary(digest)}"
    if corpus:
        user += f"\n\n{corpus}\nAdapt the prior art to THIS repo; state your local adaptation."
    raw = _brain_call(system, user, chat=chat)
    out: List[Finding] = []
    for r in raw[:_MAX_FINDINGS_PER_LENS]:
        f = _to_finding(r, source_lens)
        if f is not None:
            out.append(f)
    return out


