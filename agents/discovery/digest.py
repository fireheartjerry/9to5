"""Phase 0: compile the shared codebase digest for all lens agents.

Pure tool calls — subprocess, file reads, grep. No LLM. Compiled once,
shared by all 5 lens agents. Errors in any sub-collector are caught and
return empty values so a partial environment never crashes a run.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  compile_digest(work_dir: str) -> dict  -- Compile and return the full codebase digest.
DEPENDS-ON: config, memory.experience
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_discovery_digest.py
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

import config

LOG = config.getLogger("discovery.digest")

_TIMEOUT = 15  # seconds per subprocess call


def _run(cmd: list, cwd: str = None) -> str:
    """Run a subprocess and return stdout. Returns '' on any error."""
    try:
        r = subprocess.run(cmd, capture_output=True, text=True,
                           timeout=_TIMEOUT, cwd=cwd)
        return (r.stdout or "").strip()
    except Exception as e:  # noqa: BLE001
        LOG.debug("digest subprocess failed %s: %s", cmd[0], e)
        return ""


def _grep(pattern: str, path: str, extra_args: list = None) -> str:
    args = ["grep", "-r", "-n", "--include=*.py", pattern, path]
    if extra_args:
        args += extra_args
    return _run(args)


def _read_file(path: str) -> str:
    try:
        return Path(path).read_text(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        return ""


# ── Repo structure ────────────────────────────────────────────────────────────

def _read_repo_map(work_dir: str) -> dict:
    raw = _read_file(str(Path(work_dir) / ".repo-map.json"))
    try:
        return json.loads(raw) if raw else {}
    except Exception:  # noqa: BLE001
        return {}


def _read_architecture(work_dir: str) -> str:
    return _read_file(str(Path(work_dir) / "docs" / "ARCHITECTURE.md"))[:8000]


def _extract_module_signatures(work_dir: str) -> str:
    """Top-level EXPORTS sections from all @AI-MAP headers."""
    return _grep("EXPORTS:", work_dir)[:3000]


def _build_dependency_graph(work_dir: str) -> str:
    """DEPENDS-ON lines from all @AI-MAP headers."""
    return _grep("DEPENDS-ON:", work_dir)[:3000]


def _find_dead_code(work_dir: str) -> str:
    """Public function signatures for cross-ref by lenses."""
    return _grep(r"^def [a-z]", work_dir)[:2000]


# ── Static signals ────────────────────────────────────────────────────────────

def _collect_static_signals(work_dir: str) -> dict:
    size_out = _run(["python", "tools/size_audit.py"], cwd=work_dir)
    todos_raw = _grep(r"TODO\|FIXME\|HACK\|XXX\|DEPRECATED", work_dir)
    todos_trimmed = "\n".join(todos_raw.splitlines()[:30])

    docs_drift = _grep(r"@AI-MAP", work_dir)[:1000]
    test_gaps_raw = _grep(r"^def [a-z]", str(Path(work_dir) / "tests"))[:2000]

    isolation = _grep(
        r"import discord\|import ollama\|import requests",
        str(Path(work_dir) / "tests"),
    )[:1000]

    deep_nesting = _run(
        ["python", "-m", "radon", "cc", "-n", "C", "-a", work_dir],
        cwd=work_dir,
    )[:1000]

    long_fns = _grep(r"^def ", work_dir)[:1000]

    security = _grep(
        r"eval(\|exec(\|os\.system(\|password\s*=\s*[\"']", work_dir
    )[:500]

    return {
        "size_violations": size_out[:2000],
        "todos": todos_trimmed,
        "docs_drift": docs_drift,
        "test_gaps": test_gaps_raw,
        "test_isolation_violations": isolation,
        "deep_nesting": deep_nesting,
        "long_functions": long_fns,
        "security_signals": security,
    }


def _collect_quality_signals(work_dir: str) -> dict:
    coverage = _read_file(str(Path(work_dir) / "logs" / "coverage.txt"))[:1000]
    slow_tests = _read_file(str(Path(work_dir) / "logs" / "slow-test-report.md"))[:1000]
    workflow_out = _run(["python", "validate_workflows.py"], cwd=work_dir)[:1000]
    return {
        "coverage": coverage,
        "slow_tests": slow_tests,
        "workflow_registry": workflow_out,
        "flaky_history": "",
    }


# ── Git + GitHub signals ──────────────────────────────────────────────────────

def _collect_git_signals(work_dir: str) -> dict:
    churn = _run(
        ["git", "log", "--name-only", "--format=", "--diff-filter=M", "-n", "30"],
        cwd=work_dir,
    )[:2000]
    bug_hotspots = _run(
        ["git", "log", "--name-only", "--format=", "--grep=fix", "-n", "30"],
        cwd=work_dir,
    )[:1000]
    recent = _run(
        ["git", "log", "--name-only", "--format=", "-n", "10"],
        cwd=work_dir,
    )[:1000]
    stale = _run(
        ["git", "branch", "-a", "--sort=-committerdate",
         "--format=%(refname:short) %(committerdate:relative)"],
        cwd=work_dir,
    )[:500]
    return {
        "churn": churn,
        "bug_fix_hotspots": bug_hotspots,
        "recent_touches": recent,
        "stale_branches": stale,
    }


def _collect_github_signals(work_dir: str) -> dict:
    issues = _run(["gh", "issue", "list", "--limit", "20",
                   "--json", "title,labels,createdAt"], cwd=work_dir)[:2000]
    prs = _run(["gh", "pr", "list", "--limit", "10",
                "--json", "title,createdAt,url"], cwd=work_dir)[:1000]
    ci = _run(["gh", "run", "list", "--limit", "20",
               "--json", "name,conclusion,createdAt"], cwd=work_dir)[:1500]
    return {
        "open_issues": issues,
        "stale_prs": prs,
        "ci_failure_patterns": ci,
        "recent_pr_review_comments": "",
    }


# ── Institutional memory ──────────────────────────────────────────────────────

def _collect_institutional_memory() -> dict:
    try:
        from memory import experience
        lessons = experience.recent_reflections(limit=15)
    except Exception:  # noqa: BLE001
        lessons = []
    try:
        from memory import experience
        failures = experience.recent_failures(limit=10)
    except Exception:  # noqa: BLE001
        failures = []
    try:
        from learning import postmortem
        open_pm = postmortem.open_guidance()
    except Exception:  # noqa: BLE001
        open_pm = []
    return {
        "recent_lessons": lessons,
        "recent_failures": failures,
        "open_postmortems": open_pm,
        "policy_hints": "",
        "knowledge_graph": "",
        "discord_feedback": "",
    }


# ── Innovation seeds ──────────────────────────────────────────────────────────

def _collect_innovation_seeds(work_dir: str) -> dict:
    parked = _grep("PARKED", str(Path(work_dir) / "docs" / "plans"))[:1000]
    arch = _read_architecture(work_dir)
    underused = _grep(r"skills_to_invoke", work_dir)[:500]
    prompts = _grep(r"_SYSTEM\s*=", work_dir)[:1000]
    return {
        "vision_vs_reality": arch[:3000],
        "rejected_ideas": "",
        "parked_plans": parked,
        "underutilized_capabilities": underused,
        "prompt_quality_signals": prompts,
    }


def _collect_leverage_signals(work_dir: str) -> dict:
    slow_log = _read_file(str(Path(work_dir) / "logs" / "slow-test-report.md"))[:500]
    repeats = _grep(r"def _", work_dir)[:1000]
    return {
        "slowest_phases": slow_log,
        "highest_token_cost": "",
        "most_retried": "",
        "abstraction_gaps": repeats,
    }


def _collect_skills_hooks(work_dir: str) -> str:
    hooks = _read_file(str(Path(work_dir) / ".claude" / "settings.json"))[:500]
    skills_dir = Path(work_dir) / ".claude" / "skills"
    skills = str(list(skills_dir.iterdir())) if skills_dir.exists() else ""
    return (hooks + "\n" + skills)[:800]


def _collect_config_signals(work_dir: str) -> str:
    return _grep(r"^[A-Z_]+ =", str(Path(work_dir) / "config.py"))[:1000]


# ── Public facade ─────────────────────────────────────────────────────────────

def compile_digest(work_dir: str) -> dict:
    """Compile and return the full codebase digest. Never raises."""
    LOG.info("Compiling discovery digest for %s", work_dir)
    try:
        return {
            "repo_map": _read_repo_map(work_dir),
            "architecture": _read_architecture(work_dir),
            "module_signatures": _extract_module_signatures(work_dir),
            "dependency_graph": _build_dependency_graph(work_dir),
            "dead_code_signals": _find_dead_code(work_dir),
            "static_signals": _collect_static_signals(work_dir),
            "quality": _collect_quality_signals(work_dir),
            "git_signals": _collect_git_signals(work_dir),
            "github": _collect_github_signals(work_dir),
            "institutional_memory": _collect_institutional_memory(),
            "innovation_seeds": _collect_innovation_seeds(work_dir),
            "leverage_signals": _collect_leverage_signals(work_dir),
            "skills_hooks": _collect_skills_hooks(work_dir),
            "config_signals": _collect_config_signals(work_dir),
        }
    except Exception as e:  # noqa: BLE001
        LOG.warning("compile_digest failed (%s); returning empty digest", e)
        return {k: {} for k in (
            "repo_map", "architecture", "module_signatures", "dependency_graph",
            "dead_code_signals", "static_signals", "quality", "git_signals",
            "github", "institutional_memory", "innovation_seeds",
            "leverage_signals", "skills_hooks", "config_signals",
        )}
