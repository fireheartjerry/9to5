from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class Finding:
    title: str
    type: str          # new_capability | reimagining | health | memory | ux
    impact: int        # 1-5
    specificity: int   # 1-5
    innovation: int    # 1-5
    rationale: str
    affected_files: List[str]
    source_lens: str
    rank: Optional[int] = None
    composes_with: List[int] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "rank": self.rank,
            "title": self.title,
            "type": self.type,
            "impact": self.impact,
            "specificity": self.specificity,
            "innovation": self.innovation,
            "rationale": self.rationale,
            "affected_files": self.affected_files,
            "source_lens": self.source_lens,
            "composes_with": self.composes_with,
        }


@dataclass
class DiscoveryReport:
    theme_suggestion: str
    findings: List[Finding]

    @property
    def innovation_ratio(self) -> float:
        if not self.findings:
            return 0.0
        innovative = sum(1 for f in self.findings if f.innovation >= 3)
        return innovative / len(self.findings)

    def to_dict(self) -> dict:
        return {
            "theme_suggestion": self.theme_suggestion,
            "innovation_ratio": round(self.innovation_ratio, 2),
            "findings": [f.to_dict() for f in self.findings],
        }
