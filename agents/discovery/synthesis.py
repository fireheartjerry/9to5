"""Phase 2: synthesize lens findings into a ranked DiscoveryReport.

Deduplicates, scores (impact × specificity × innovation), enforces the
40% innovation floor, and makes one brain call (via the llm_io seam, R5)
for a theme suggestion.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  synthesize(findings: List[Finding], chat=None) -> DiscoveryReport  -- Rank and filter findings into a DiscoveryReport
DEPENDS-ON: agents.discovery.models, config, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_discovery_synthesis.py
"""
from __future__ import annotations

from typing import List

import config
import llm_io
from agents.discovery.models import Finding, DiscoveryReport

LOG = config.getLogger("discovery.synthesis")

_MAX_FINDINGS = 10
_INNOVATION_FLOOR = 0.40


def _score(f: Finding) -> float:
    return f.impact * f.specificity * f.innovation


def _are_near_duplicates(a: Finding, b: Finding) -> bool:
    """Same first 4 words = duplicate."""
    words_a = a.title.lower().split()[:4]
    words_b = b.title.lower().split()[:4]
    return words_a == words_b


def _dedup(findings: List[Finding]) -> List[Finding]:
    unique: List[Finding] = []
    for f in findings:
        if not any(_are_near_duplicates(f, u) for u in unique):
            unique.append(f)
    return unique


def _enforce_innovation_floor(findings: List[Finding]) -> List[Finding]:
    """Ensure at least 40% of findings score >= 3 on innovation.

    If the ratio is already met, return unchanged.  Otherwise cap the number
    of incremental findings so that innovative / total >= floor, keeping the
    top-scored incrementals and sorting innovatives by score.
    """
    if not findings:
        return findings
    innovative = [f for f in findings if f.innovation >= 3]
    incremental = [f for f in findings if f.innovation < 3]
    if not innovative:
        return findings  # nothing innovative to promote; can't enforce
    if len(innovative) / len(findings) >= _INNOVATION_FLOOR:
        return findings
    # Determine max incremental count so floor is satisfied:
    # innovative / (innovative + max_incr) >= floor
    # => max_incr <= innovative * (1 - floor) / floor
    import math
    max_incr = math.floor(len(innovative) * (1 - _INNOVATION_FLOOR) / _INNOVATION_FLOOR)
    trimmed_incr = sorted(incremental, key=_score, reverse=True)[:max_incr]
    return sorted(innovative, key=_score, reverse=True) + trimmed_incr


def _get_theme(findings: List[Finding], chat=None) -> str:
    """Ask the brain (via the llm_io seam) for a theme. Deterministic fallback on failure."""
    if not findings:
        return "improve codebase quality"
    titles = [f.title for f in findings[:8]]
    system = (
        "Given these discovered improvement opportunities, suggest ONE short theme "
        "phrase (5-8 words) that captures the most impactful narrative direction. "
        "Output JSON only: {\"theme_suggestion\": \"...\"}"
    )
    user = "Findings:\n" + "\n".join(f"- {t}" for t in titles)
    try:
        if chat is not None:
            resp = llm_io.callChat(chat, system, user, act="discovery_synthesis", want_json=True)
        else:
            resp = llm_io.chat(system, user, act="discovery_synthesis", want_json=True, retries=2)
        parsed = llm_io.responseJson(resp)
        theme = str((parsed or {}).get("theme_suggestion") or "").strip() \
            if isinstance(parsed, dict) else ""
        if theme:
            return theme
    except Exception as e:  # noqa: BLE001
        LOG.warning("theme synthesis failed: %s", e)
    top_type = findings[0].type if findings else "health"
    return f"transform the {top_type.replace('_', ' ')} layer"


def synthesize(findings: List[Finding], chat=None) -> DiscoveryReport:
    """Rank and filter findings into a DiscoveryReport. Never raises."""
    LOG.info("Synthesizing %d raw findings", len(findings))
    if not findings:
        return DiscoveryReport(theme_suggestion="improve codebase quality", findings=[])
    # 1. Drop too-vague
    filtered = [f for f in findings if f.specificity >= 2]
    # 2. Deduplicate near-identical titles
    deduped = _dedup(filtered)
    # 3. Score and sort
    scored = sorted(deduped, key=_score, reverse=True)
    # 4. Enforce innovation floor
    balanced = _enforce_innovation_floor(scored)
    # 5. Cap at max findings
    top = balanced[:_MAX_FINDINGS]
    # 6. Assign ranks
    for i, f in enumerate(top):
        f.rank = i + 1
    # 7. Get theme
    theme = _get_theme(top, chat=chat)
    report = DiscoveryReport(theme_suggestion=theme, findings=top)
    LOG.info("Synthesis: %d findings, innovation_ratio=%.2f, theme=%r",
             len(top), report.innovation_ratio, theme)
    return report
