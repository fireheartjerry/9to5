"""agents/timing_harness.py -- Wall-clock timing harness for parallel workflow phases.

Measures actual wall-clock speedup: concurrent (parallel-phase) vs sequential (all-serial)
execution, using synthetic per-agent sleep workloads in real threads.

Public API:
  measureWorkflow(definition, agent_duration) -> TimingResult
  updateSpeedupRatio(workflow_path, result)

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  TimingResult
  measureWorkflow(definition: dict, agent_duration: float=AGENT_DURATION_SECS) -> TimingResult  -- Measure wall-clock time for sequential vs concurrent execution of *definition*.
  updateSpeedupRatio(workflow_path: Path, result: TimingResult) -> None  -- Update speedup_model.estimated_wall_clock_ratio in *workflow_path* with measured ratio.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_timing_harness.py
"""
from __future__ import annotations

import json
import time
from concurrent.futures import ThreadPoolExecutor, wait
from pathlib import Path
from typing import NamedTuple

AGENT_DURATION_SECS: float = 0.05   # synthetic per-agent work duration
SPEEDUP_THRESHOLD: float = 0.80     # concurrent/sequential ratio must be ≤ this (≥20% speedup)


class TimingResult(NamedTuple):
    sequential_secs: float
    concurrent_secs: float
    ratio: float
    meets_threshold: bool
    phase_count: int
    agent_count: int


def _runAgent(duration: float) -> None:
    """Synthetic agent workload."""
    time.sleep(duration)


def measureWorkflow(
    definition: dict,
    agent_duration: float = AGENT_DURATION_SECS,
) -> TimingResult:
    """Measure wall-clock time for sequential vs concurrent execution of *definition*.

    Sequential: all agents across all phases run one-by-one.
    Concurrent: within each phase, agents run in parallel (max-of-phase); phases are sequential.
    """
    phases = definition.get("phases", [])
    agents_per_phase = [phase.get("agents", []) for phase in phases]
    total_agents = sum(len(a) for a in agents_per_phase)

    # Sequential: one agent at a time across all phases
    seq_start = time.perf_counter()
    for phase_agents in agents_per_phase:
        for _ in phase_agents:
            _runAgent(agent_duration)
    sequential_secs = time.perf_counter() - seq_start

    # Concurrent: within each phase, all agents run in parallel; phases are sequential
    con_start = time.perf_counter()
    for phase_agents in agents_per_phase:
        n = len(phase_agents)
        if n <= 1:
            for _ in phase_agents:
                _runAgent(agent_duration)
        else:
            with ThreadPoolExecutor(max_workers=n) as pool:
                futures = [pool.submit(_runAgent, agent_duration) for _ in phase_agents]
                wait(futures)
    concurrent_secs = time.perf_counter() - con_start

    ratio = concurrent_secs / sequential_secs if sequential_secs > 0 else 1.0
    meets_threshold = ratio <= SPEEDUP_THRESHOLD

    return TimingResult(
        sequential_secs=sequential_secs,
        concurrent_secs=concurrent_secs,
        ratio=ratio,
        meets_threshold=meets_threshold,
        phase_count=len(phases),
        agent_count=total_agents,
    )


def updateSpeedupRatio(workflow_path: Path, result: TimingResult) -> None:
    """Update speedup_model.estimated_wall_clock_ratio in *workflow_path* with measured ratio."""
    data = json.loads(workflow_path.read_text(encoding="utf-8"))
    if "speedup_model" not in data:
        data["speedup_model"] = {}
    data["speedup_model"]["estimated_wall_clock_ratio"] = round(result.ratio, 4)
    workflow_path.write_text(json.dumps(data, indent=2), encoding="utf-8")
