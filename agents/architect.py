"""Architect (Step 1).

Two pieces:
  * ARCHITECT_SYSTEM_PROMPT -- a *locked* system prompt prepended to the Claude
    Code CLI call so the Executor behaves as a software architect.
  * authorArchitectPrompt   -- an Orchestrator-brain step: Ollama writes the
    architecture-framed prompt that is then fired at Claude Code CLI.

The Claude invocation itself is performed by agents.executor.runClaude with
``system_prompt=ARCHITECT_SYSTEM_PROMPT``; its stdout becomes architect.md.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  authorArchitectPrompt(goal_elaborated: str, chat=None, discovery_report=None) -> str  -- Ollama authors the prompt that will be sent to Claude Code CLI.
DEPENDS-ON: config, knowledge, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_phase_3_architecture.py
"""
from __future__ import annotations

import config
import knowledge
import llm_io

LOG = config.getLogger("architect")
_OLLAMA: "ollama.Client | None" = None  # noqa: F821  (string annotation; ollama imported lazily)


def _getOllama() -> "ollama.Client":  # noqa: F821
    global _OLLAMA
    if _OLLAMA is None:
        import ollama  # deferred: ~0.3s SDK import paid only when a real brain call happens
        _OLLAMA = ollama.Client(host=config.OLLAMA_HOST, timeout=config.OLLAMA_TIMEOUT_SECONDS)
    return _OLLAMA

ARCHITECT_SYSTEM_PROMPT = (
    "You are the Architect. You produce a single, thorough architecture and design "
    "document for the specification you are given. Cover: high-level approach; component "
    "/ module breakdown; key files and their responsibilities; data flow; external "
    "dependencies; risks and mitigations; and an ordered implementation outline. "
    "Do NOT write application code or create files -- output ONLY the markdown design "
    "document. Begin directly with a top-level heading."
)


_ARCHITECT_PROMPT_SYSTEM = (
    "You author a single prompt instructing a coding agent to design the "
    "architecture for the given specification. The prompt must ask only for a "
    "design document, not code. Output ONLY the prompt text."
)


def authorArchitectPrompt(goal_elaborated: str, chat=None, discovery_report=None) -> str:
    """Ollama authors the prompt that will be sent to Claude Code CLI.

    ``chat`` is an optional ``(system, user, *, want_json=False) -> resp`` callable
    (the orchestrator's seamed ``_ollamaChat``); when given it is used instead of this
    module's own client, so a dry-run / test can drive the architect phase offline.
    ``discovery_report`` is an optional DiscoveryReport injected when discovery ran.
    """
    LOG.info("Authoring architecture prompt via %s", config.OLLAMA_MODEL)

    discovery_block = ""
    if discovery_report is not None:
        import json as _json
        try:
            report_dict = discovery_report.to_dict()
            n = len(report_dict.get("findings") or [])
            ratio = report_dict.get("innovation_ratio", 0)
            theme = report_dict.get("theme_suggestion", "")
            discovery_block = (
                f"\n\nDISCOVERY REPORT (auto-generated, {n} findings, "
                f"innovation ratio: {ratio*100:.0f}%):\n"
                + _json.dumps(report_dict, indent=2, ensure_ascii=False)[:4000]
                + f"\n\nSuggested theme: \"{theme}\"\n\n"
                "Your job:\n"
                "1. Select a coherent set of the highest-impact findings\n"
                "2. Synthesize them into ONE architectural narrative — a single story this PR will tell\n"
                "3. Prioritize transformative findings over incremental ones\n"
                "4. The result should feel like something an ambitious engineer chose, not a chore list\n\n"
                "Avoid picking unrelated items. One bold PR beats five safe ones."
            )
        except Exception:  # noqa: BLE001
            discovery_block = ""

    user = (
        f"Specification:\n{goal_elaborated}"
        + discovery_block
        + "\n\nWrite the architecture-design prompt."
    )
    if chat is not None:
        resp = chat(_ARCHITECT_PROMPT_SYSTEM, user)   # _ollamaChat injects capabilities itself
    else:
        resp = _getOllama().chat(
            model=config.OLLAMA_MODEL,
            messages=[{"role": "system", "content": knowledge.injectCapabilities(_ARCHITECT_PROMPT_SYSTEM)},
                      {"role": "user", "content": user}],
            options={"num_ctx": config.OLLAMA_NUM_CTX},
            keep_alive=config.OLLAMA_KEEP_ALIVE,
        )
    # Safe extraction: handles dict AND the ollama-python PYDANTIC ChatResponse AND malformed
    # shapes (None / non-dict message / non-string content). The old isinstance(dict) gate made
    # every real (pydantic) reply look empty -> this always fell to the deterministic fallback.
    prompt = llm_io.responseText(resp).strip()
    # FX-12: the local 7B brain frequently returns EMPTY here. Returning "" would send the architect
    # Claude a prompt with NO specification (it would design for nothing, and the orchestrator's retry
    # would re-fire the same empty prompt). Fall back to a deterministic GOAL-BEARING prompt so the
    # goal always reaches the architect even with a dead brain.
    if not prompt:
        LOG.warning("architect-prompt brain output empty -> deterministic goal-bearing fallback")
        prompt = (
            "Produce a thorough architecture and design document for the following specification. "
            "Cover the approach, the modules/files to add or change, data flow, key dependencies, "
            "risks, and an ORDERED implementation outline.\n\nSpecification:\n"
            + (goal_elaborated or "").strip()
            + discovery_block
        )
    elif discovery_block:
        # Always append the discovery context so it reaches the architect Claude even when the
        # Ollama brain authored a brief prompt that did not repeat the findings verbatim.
        prompt = prompt + discovery_block
    return prompt
