"""9TO5 deterministic hook dispatcher.

Claude Code invokes this as:  python agents\hooks.py <hook_name>
with a JSON event object piped on STDIN.

This file MUST be robust: it NEVER crashes Claude Code. Every handler is wrapped
in try/except and exits 0 -- EXCEPT block_destructive, which intentionally exits
2 to block a dangerous tool call.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  blockDestructive(data)  -- PreToolUse: block destructive Bash commands by exiting 2.
  writeObsidian(data)  -- PostToolUse: log the edited file path to the in-progress subtask note.
  discordNotify(data)  -- Notification: forward the message to Discord as a compact embed.
  logAll(data)  -- PostToolUse / any: append one JSON line {time, tool_name} to the log.
  selfModificationGuard(data)  -- PreToolUse: during a SELF-REFERENTIAL task, block edits to the core files
  main()  -- Dispatch to the requested handler based on argv[1].
DEPENDS-ON: config, memory.obsidian, notifications.discord_bot, state.task
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_hooks_self_path.py
"""

import sys
import json
import os
import re

# Make "import config" (and other project modules) work regardless of cwd.
# Derive the repo root from THIS file's location so hooks always adds ITS OWN tree,
# not a hardcoded install path -- this is correct under any checkout or git worktree.
from pathlib import Path as _Path
sys.path.insert(0, str(_Path(__file__).resolve().parent.parent))

# config is safe to import at module load; project sub-modules are imported
# lazily inside handlers so a broken import can never crash the dispatcher.
try:
    import config  # noqa: F401
except Exception:
    config = None


# Patterns that we refuse to let a Bash tool run. Matched case-insensitively
# against the raw command string.
DESTRUCTIVE_PATTERNS = (
    "rm -rf",
    "rm -fr",
    "rmdir /s",
    "del /f",
    "del /s",
    "format ",
    "DROP TABLE",
    "git push --force",
    "git push -f",
    "mkfs",
    ":(){",
    ">/dev/sda",
)

LOG_PATH = r"C:\9to5\logs\hooks.log"


def _readEvent():
    """Read and parse the JSON event piped on STDIN. Never raises."""
    try:
        raw = sys.stdin.read()
    except Exception:
        return {}
    try:
        return json.loads(raw) if raw.strip() else {}
    except Exception:
        return {}


def _envTaskRequested():
    """True when the executor pinned a task for this hook (so a run is active)."""
    return bool(os.environ.get("NINE_TO_FIVE_TASK_FILE") or os.environ.get("NINE_TO_FIVE_TASK_ID"))


def _bashHitsBoundary(cmd_low, bbase):
    """True when a writing Bash command's text contains the boundary basename as a real PATH TOKEN
    (bounded by start/end or a shell/path separator) -- not a bare substring. So `rm -rf state/tasks`
    or `> config.py` hit, but `echo x > tasks.json` / `printf ... > my_config.py` do not."""
    if not (cmd_low and bbase):
        return False
    return bool(re.search(r"(^|[\s\"'=:;,()&|<>/\\])" + re.escape(bbase) + r"($|[\s\"'=:;,()&|<>])", cmd_low))


def _resolveState():
    """Resolve ``(state, explicit)`` for this hook.

    ``explicit`` is True ONLY when an executor-pinned task resolved -- the guard fails CLOSED on
    core files when a run is active but its task could not be trusted. Resolution order:
      1. NINE_TO_FIVE_TASK_FILE -- the ABSOLUTE state-file path the executor exported. This is
         worktree/install-root safe: the hook's hardcoded ``config.STATE_DIR`` may point at a
         DIFFERENT root than the orchestrator's, so loading by path avoids that divergence.
      2. NINE_TO_FIVE_TASK_ID via the configured STATE_DIR.
      3. loadLatest() -- manual/standalone fallback (not explicit).
    Never raises; logs to stderr on a degrade so a silent fail-open is visible."""
    try:
        from state.task import TaskState
    except Exception:
        return None, False
    tfile = os.environ.get("NINE_TO_FIVE_TASK_FILE")
    if tfile:
        try:
            with open(tfile, encoding="utf-8") as fh:
                return TaskState(json.load(fh)), True
        except Exception as e:
            sys.stderr.write(f"hooks._resolveState: TASK_FILE load failed ({e}); falling back\n")
    tid = os.environ.get("NINE_TO_FIVE_TASK_ID")
    if tid:
        try:
            return TaskState.load(tid), True
        except Exception as e:
            sys.stderr.write(f"hooks._resolveState: load({tid}) failed ({e}); falling back to loadLatest\n")
    try:
        return TaskState.loadLatest(), False
    except Exception:
        return None, False


def blockDestructive(data):
    """PreToolUse: block destructive Bash commands by exiting 2.

    Exits 0 when the command is safe (or not a Bash command). Exits 2 when a
    destructive pattern is detected, after best-effort Discord alerting.
    """
    try:
        tool_name = data.get("tool_name", "")
        tool_input = data.get("tool_input", {}) or {}
        command = ""
        if tool_name == "Bash":
            command = tool_input.get("command", "") or ""
    except Exception:
        sys.exit(0)

    if not command:
        sys.exit(0)

    lowered = command.lower()
    matched = None
    for pat in DESTRUCTIVE_PATTERNS:
        if pat.lower() in lowered:
            matched = pat
            break

    if matched is None:
        sys.exit(0)

    reason = (
        f"Blocked destructive command (matched {matched!r}): {command}"
    )

    # (a) best-effort Discord alert: an AUTO-REFUSED safety event, not a human decision -- inform
    # without "human decision required" or an @-ping (9to5 runs hands-off).
    try:
        import notifications.discord_bot as discord
        discord.sendEmbed(discord.noticeEmbed(reason, title="🛡️ 9TO5 — auto-refused (safety)"))
    except Exception:
        pass

    # (b) human-readable reason to STDERR.
    try:
        sys.stderr.write(reason + "\n")
    except Exception:
        pass

    # (c) exit code 2 blocks the tool in Claude Code.
    sys.exit(2)


def writeObsidian(data):
    """PostToolUse: log the edited file path to the in-progress subtask note."""
    try:
        tool_name = data.get("tool_name", "")
        if tool_name not in ("Edit", "Write", "MultiEdit"):
            sys.exit(0)

        tool_input = data.get("tool_input", {}) or {}
        file_path = tool_input.get("file_path", "")

        from datetime import datetime
        from memory.obsidian import ObsidianClient

        state, _explicit = _resolveState()
        if state is None:
            sys.exit(0)

        try:
            subtasks = state.subtasks or []
        except Exception:
            subtasks = []

        # Prefer the executor-exported subtask -- but only if it actually belongs to the resolved
        # state (under a fallback resolution it may name a subtask of a different task). Else scan.
        sid = os.environ.get("NINE_TO_FIVE_SUBTASK_ID") or None
        if sid:
            try:
                if state.getSubtask(sid) is None:
                    sid = None
            except Exception:
                sid = None
        if not sid:
            for st in subtasks:
                try:
                    if st.get("status") == "in_progress":
                        sid = st.get("subtask_id")
                        break
                except Exception:
                    continue

        if not sid:
            sys.exit(0)

        ts = datetime.now().isoformat(timespec="seconds")
        line = f"- {ts} | {tool_name} | {file_path}\n"
        ObsidianClient().appendNote(state.subtaskNoteRel(sid), line)
    except Exception:
        pass
    sys.exit(0)


def discordNotify(data):
    """Notification: forward the message to Discord as a compact embed."""
    try:
        message = data.get("message", "") or ""
        import notifications.discord_bot as discord
        discord.sendEmbed(
            {
                "title": "Claude Code notification",
                "color": 3447003,
                "description": message[:1500],
            }
        )
    except Exception:
        pass
    sys.exit(0)


def logAll(data):
    """PostToolUse / any: append one JSON line {time, tool_name} to the log."""
    try:
        from datetime import datetime
        from pathlib import Path

        log_path = Path(LOG_PATH)
        log_path.parent.mkdir(parents=True, exist_ok=True)

        entry = {
            "time": datetime.now().isoformat(timespec="seconds"),
            "tool_name": data.get("tool_name", ""),
        }
        with log_path.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry) + "\n")
    except Exception:
        pass
    sys.exit(0)


def _boundarySetFor(state) -> set:
    """The universe/baseline boundary set the guard enforces.

    Prefers the PINNED epoch stored in task meta over a live config re-import so
    a mid-run edit to config/sie_overrides cannot change what this run enforces
    (fix #1, keystone).  Falls back to the live baseline when no epoch is present
    (legacy tasks -- fail-closed: baseline is always included).

    NOTE: core-file protection (CORE_PROTECTED_FILES) is NOT included here --
    that depends on is_self_referential / explicit resolution state which only
    selfModificationGuard knows.  This helper covers the universe + baseline
    layer only.
    """
    meta = getattr(state, "meta", {}) or {}
    ep = meta.get("epoch") or {}
    pinned = (ep.get("universe") or {}).get("hard_boundaries") or []
    base: list = [str(b) for b in pinned if b]
    # ALWAYS include the baseline secret/VCS/state boundaries (fail-closed).
    for b in (list(getattr(config, "UNIVERSE_DEFAULT_HARD_BOUNDARIES", ()) or ()) if config
              else [".env", ".git", "venv", "state/tasks"]):
        if b not in base:
            base.append(b)
    # Anchor the 9to5-internal task store to the install root. A bare ``state/tasks`` boundary
    # matches ANY path ending in state/tasks (substring match in the guard), so an external target
    # repo that happens to have its OWN state/tasks/ dir was falsely blocked. Replacing it with the
    # absolute install path means it only protects 9to5's own run state, never the target's (#39).
    # ``.env``/``.git``/``venv`` stay relative on purpose -- those are worth blocking in any repo.
    try:
        anchored = str((config.PROJECT_ROOT / "state" / "tasks")) if config else None
    except Exception:  # noqa: BLE001 -- no config / odd PROJECT_ROOT -> leave boundary relative
        anchored = None
    if anchored:
        out: set = set()
        for b in base:
            norm = str(b).replace("/", "\\").lower().strip("\\")
            out.add(anchored if norm in ("state\\tasks", "state/tasks") else b)
        return out
    return set(base)


def _coreLockFor(state):
    """The (allow_core, core_files) the guard uses. Prefer the PINNED epoch so a mid-run
    edit to SELFMOD_ALLOW_CORE / CORE_PROTECTED_FILES cannot change what THIS run enforces
    (#1 keystone, full fix). Falls back to live config for legacy tasks with no epoch."""
    meta = getattr(state, "meta", {}) or {}
    ep = meta.get("epoch")
    if ep:
        allow_core = bool((ep.get("config_knobs") or {}).get("SELFMOD_ALLOW_CORE", False))
        core_files = tuple(ep.get("core_protected_files") or ())
        if core_files:
            return allow_core, core_files
        # epoch present but no core list pinned -> still use pinned allow_core, live core list
        return allow_core, tuple(getattr(config, "CORE_PROTECTED_FILES", ()) or ())
    return (bool(getattr(config, "SELFMOD_ALLOW_CORE", False)),
            tuple(getattr(config, "CORE_PROTECTED_FILES", ()) or ()))


def selfModificationGuard(data):
    """PreToolUse: during a SELF-REFERENTIAL task, block edits to the core files
    that run the orchestrator loop (orchestrator.py, main.py, agents/hooks.py, config.py).
    Exits 2 to block; exits 0 otherwise."""
    bash_cmd = ""      # defined BEFORE the try so the fail-closed handler can read them even if the
    file_path = ""     # body raises early (else they'd NameError and we'd lose the block decision)
    try:
        tool_name = data.get("tool_name", "")
        tool_input = data.get("tool_input", {}) or {}
        if tool_name in ("Edit", "Write", "MultiEdit"):
            file_path = tool_input.get("file_path", "") or ""
        elif tool_name == "Bash":
            # close the Bash write-hole: only inspect commands that WRITE (redirect/sed/mv/cp/tee/git).
            # The write COMMANDS (mv/cp/rm/tee/del/ren/move/copy) must be matched at COMMAND POSITION
            # -- start of line or right after a shell separator -- not as a space-padded substring: the
            # old " mv "/" cp " tokens MISSED a command that STARTS with mv/cp (e.g. `mv .env x`), so a
            # move/copy onto a hard-boundary file slipped past the guard entirely (fail-open).
            bash_cmd = tool_input.get("command", "") or ""
            low = bash_cmd.lower()
            redirect_or_git = (">" in bash_cmd or "sed -i" in low or "git checkout" in low
                               or "git reset" in low or "git restore" in low
                               or "git rm" in low or "git mv" in low)
            # Write/destructive verbs as standalone TOKENS anywhere (word boundary), NOT only at
            # command position: the old `(?:^|[\n;&|])` anchor missed a verb preceded by a wrapper
            # word -- `git rm .env`, `sudo rm`, `xargs rm`, `(rm .env)`, `find . -delete` -- so a
            # write onto a hard boundary slipped past the guard (fail-OPEN). Broad detection is safe
            # because the boundary loop below only BLOCKS when the command actually targets a
            # boundary path token, so a write that touches nothing protected still exits 0.
            write_cmd = re.search(
                r"\b(mv|cp|rm|tee|dd|truncate|del|erase|unlink|shred|ren|rename|move|copy)\b", low)
            # Interpreters that can write a file inline (python -c / perl -e / node -e), plus append.
            interp_write = re.search(r"\b(python3?|py|perl|node|ruby|pwsh|powershell)\b\s*-[ce]\b", low) \
                or ">>" in bash_cmd or "-delete" in low
            if not (redirect_or_git or write_cmd or interp_write):
                sys.exit(0)
        else:
            sys.exit(0)
        state, explicit = _resolveState()
        env_requested = _envTaskRequested()
        # No run context at all -> nothing to guard. But if a run IS active (env-pinned) we proceed
        # even with state=None, enforcing the baseline + core-file boundaries (fail CLOSED).
        if state is None and not env_requested:
            sys.exit(0)
        # Build the boundary list: universe + baseline from the PINNED epoch (or live fallback
        # for legacy tasks).  Core-file protection is appended below when conditions require it.
        boundaries = list(_boundarySetFor(state))
        # When no epoch is present (legacy task), also pull in the live universe.hard_boundaries
        # so existing behavior is fully preserved for tasks that pre-date epoch pinning.
        meta = getattr(state, "meta", {}) or {}
        if not (meta.get("epoch") or {}):
            universe = (state.meta.get("universe") if state else None) or {}
            for b in (universe.get("hard_boundaries") or []):
                b = str(b)
                if b and b not in boundaries:
                    boundaries.append(b)
        # Protect the core loop files when this is a self-ref run OR when a run is active but its
        # task could NOT be trusted (env pinned a task, yet resolution fell back) -- fail CLOSED
        # rather than leave orchestrator.py/main.py/hooks.py/config.py editable on an unknown task.
        # SELFMOD_ALLOW_CORE lets 9to5 improve its OWN core loop: edits are permitted on the
        # isolated branch (the running process keeps its old bytecode, so it's unaffected), and a
        # post-run test-suite safety gate reverts any core change that breaks the build before a PR.
        allow_core, _core_files = _coreLockFor(state) if state else (
            bool(getattr(config, "SELFMOD_ALLOW_CORE", False)) if config else False,
            tuple(getattr(config, "CORE_PROTECTED_FILES", ()) or ()) if config
            else ("orchestrator.py", "main.py", "agents/hooks.py", "config.py"))
        if not allow_core and (
                (state and state.meta.get("is_self_referential")) or (env_requested and not explicit)):
            for c in (list(_core_files) if _core_files
                      else ["orchestrator.py", "main.py", "agents/hooks.py", "config.py"]):
                if c not in boundaries:
                    boundaries.append(c)
        norm = file_path.replace("/", "\\").lower()
        base = norm.rsplit("\\", 1)[-1]
        cmd_low = bash_cmd.lower()
        for b in boundaries:
            bn = b.replace("/", "\\").lower().strip("\\")
            if not bn:
                continue
            bbase = bn.rsplit("\\", 1)[-1]
            # exact file, a file under a boundary dir, or a path ending in the boundary
            hit = norm == bn or norm.endswith("\\" + bn) or ("\\" + bn + "\\") in norm
            # absolute boundary (e.g. the install-anchored task store): match files UNDER it. The
            # endswith/substring clauses above assume a RELATIVE bn (leading-backslash sentinel), so
            # an absolute bn like c:\9to5\state\tasks only matched the dir itself, not files in it.
            if not hit and ":" in bn and norm.startswith(bn + "\\"):
                hit = True
            # secret-family: a ".env" boundary also blocks .env.local / .env.production (NOT .envrc)
            if not hit and bbase.startswith(".") and (base == bbase or base.startswith(bbase + ".")):
                hit = True
            # writing Bash command whose target IS a boundary file (real path-token match, not a
            # bare substring -- so `echo x > tasks.json` / `> my_config.py` are not false-blocked).
            if not hit and bash_cmd and _bashHitsBoundary(cmd_low, bbase):
                hit = True
            if hit:
                reason = (f"self_modification_guard: BLOCKED edit to {file_path} -- it is a HARD BOUNDARY "
                          f"of this task's universe. Stay inside the allowed scope.")
                try:
                    import notifications.discord_bot as discord
                    discord.sendEmbed(discord.noticeEmbed(reason, title="🛡️ 9TO5 — auto-refused (safety)"))
                except Exception:
                    pass
                sys.stderr.write(reason + "\n")
                sys.exit(2)
        sys.exit(0)
    except SystemExit:
        raise
    except Exception as e:  # noqa: BLE001
        # FAIL CLOSED: the guard protects hard boundaries (.env / .git / state/tasks / core loop
        # files). If it crashes WHILE guarding an identified write target (e.g. a malformed task
        # meta), allowing the edit would silently defeat the boundary. Block instead, and log the
        # swallow so a guard failure is never mistaken for "this edit is safe". With no write target
        # identified there is nothing to guard, so allow (exit 0) as before.
        try:
            sys.stderr.write(f"self_modification_guard: internal error, failing closed: {e}\n")
        except Exception:  # noqa: BLE001
            pass
        sys.exit(2 if (file_path or bash_cmd) else 0)


def main():
    """Dispatch to the requested handler based on argv[1]."""
    hook_name = sys.argv[1] if len(sys.argv) > 1 else ""
    data = _readEvent()

    if hook_name == "block_destructive":
        blockDestructive(data)
    elif hook_name == "write_obsidian":
        writeObsidian(data)
    elif hook_name == "discord_notify":
        discordNotify(data)
    elif hook_name == "log_all":
        logAll(data)
    elif hook_name == "self_modification_guard":
        selfModificationGuard(data)
    else:
        sys.exit(0)


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception:
        # Absolute last-resort guard: never crash Claude Code.
        sys.exit(0)
