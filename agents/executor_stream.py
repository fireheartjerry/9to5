"""Subprocess management, stream parsing, and telemetry for the Claude executor.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  runSubprocess(run_cmd: list, run_prompt: str, *, work: str, timeout: int, env: dict, creationflags: int, spec: dict, effort: str, flag, profile, playbook_md: str, claude_md_path, model: str, feed=None, cancel_check=None) -> dict  -- Execute one Claude subprocess and return a normalised result dict.
DEPENDS-ON: agents.executor_env, config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_executor_stream.py
"""
from __future__ import annotations

import os
import shutil
import subprocess
import threading
import time
from pathlib import Path

import config
from agents.executor_env import scanDestructive, _alertBlocked

LOG = config.getLogger("executor.stream")
TOOLS_DIR = Path(__file__).resolve().parent.parent / "tools"


def _killProcessTree(pid: int) -> None:
    """Kill a process AND all its descendants.

    The real Windows defect: ``subprocess`` timeout kills only the direct child (the
    ``cmd.exe`` / ``claude.cmd`` launcher). The ``node.exe`` grandchildren that do the
    actual agent work survive as orphans -- they leak, keep running (which is why the
    artifact still lands "after" a timeout), and hold the inherited stdout pipe open so
    the parent's drain blocks ~200s. ``taskkill /T`` walks the whole tree."""
    try:
        if os.name == "nt":
            subprocess.run(["taskkill", "/T", "/F", "/PID", str(pid)],
                           capture_output=True, timeout=20)
        else:  # posix: kill the process group
            import signal
            os.killpg(os.getpgid(pid), signal.SIGKILL)
    except Exception as e:  # noqa: BLE001
        LOG.warning("process-tree kill of pid %s failed: %s", pid, e)


def _startCancelWatcher(proc, cancel_check) -> dict:
    """R6 operator-kill: start ONE daemon watcher thread that polls ``cancel_check`` every
    ``config.CANCEL_POLL_SECONDS`` while the subprocess runs. On a True signal it kills the
    WHOLE process tree, so a ``!kill``/``!abort``/deadline lands within ~one poll interval
    instead of the full CLI timeout. Returns a shared ``{"v": bool}`` flag the caller checks
    to report subtype='operator_killed' (distinct from 'timeout').

    Lifecycle: started right after Popen; exits when the process ends or the kill fires;
    daemon=True so a lingering poll sleep can never pin the interpreter."""
    cancelled = {"v": False}
    if cancel_check is None:
        return cancelled

    def _watch():
        while proc.poll() is None:
            try:
                hit = bool(cancel_check())
            except Exception:  # noqa: BLE001 -- a broken check must never kill a healthy run
                hit = False
            if hit:
                cancelled["v"] = True
                _killProcessTree(proc.pid)
                break
            time.sleep(config.CANCEL_POLL_SECONDS)

    threading.Thread(target=_watch, name="claude-cancel-watch", daemon=True).start()
    return cancelled


def _resolveClaudeLauncher() -> list[str]:
    exe = shutil.which("claude")
    if not exe:
        raise FileNotFoundError("claude CLI not found on PATH")
    if os.name == "nt" and exe.lower().endswith((".cmd", ".bat")):
        return ["cmd", "/c", exe]
    return [exe]


def _parseEnvelope(out: str) -> "tuple[str, dict]":
    """Parse the `claude --print --output-format json` result envelope.

    Returns ``(assistant_text, fields)`` where fields carries is_error / session_id / cost /
    usage / num_turns. Robust to a leading preamble line (e.g. a fallback-model notice) by
    scanning for the JSON object too, not only requiring the WHOLE stdout to be one object.
    Returns ``(out, {})`` only when no result envelope is found (caller logs the degrade). For an
    error/empty envelope whose ``result`` is missing/non-string, the TEXT channel gets a short
    clean marker -- NEVER the raw JSON blob (which would garble adversary/clarifier/notes)."""
    import json
    s = (out or "").strip()
    if not s:
        return "", {}
    candidates: list[str] = []
    if s.startswith("{") and s.endswith("}"):
        candidates.append(s)
    for line in reversed(s.splitlines()):   # tolerate a preamble: last JSON-object line
        ls = line.strip()
        if ls.startswith("{") and ls.endswith("}") and ls not in candidates:
            candidates.append(ls)
            break
    for cand in candidates:
        try:
            obj = json.loads(cand)
        except Exception:  # noqa: BLE001
            continue
        if not isinstance(obj, dict) or ("result" not in obj and obj.get("type") != "result"):
            continue
        text = obj.get("result")
        if not isinstance(text, str):
            text = f"[claude {obj.get('subtype') or ('error' if obj.get('is_error') else 'no-output')}]"
        return text, {
            "is_error": bool(obj.get("is_error")),
            "subtype": obj.get("subtype"),
            "session_id": obj.get("session_id"),
            "cost_usd": obj.get("total_cost_usd") if obj.get("total_cost_usd") is not None else obj.get("cost_usd"),
            "usage": obj.get("usage"),
            "num_turns": obj.get("num_turns"),
        }
    return out, {}


def _recordIterationMetric(entry: dict) -> None:
    try:
        if getattr(subprocess.Popen, "__module__", "subprocess") != "subprocess":
            return
        import sys
        sys.path.insert(0, str(TOOLS_DIR))
        import claude_metrics

        claude_metrics.record_executor_event(entry)
    except Exception as e:  # noqa: BLE001
        LOG.debug("iteration metric write failed: %s", e)


def _makeMetric(event: str, run_cmd: list, *, work, model, effort, flag, run_started,
                prompt_chars, inject_chars, playbook_chars, context_chars=None,
                returncode, ok, **extra) -> dict:
    """Build a telemetry metric dict for _recordIterationMetric."""
    m: dict = {
        "event": event, "cwd": work, "model": model, "effort": effort,
        "effort_flag": flag, "resume": "--resume" in run_cmd,
        "prompt_chars": prompt_chars, "inject_chars": inject_chars,
        "playbook_chars": playbook_chars,
        "duration_seconds": round(time.perf_counter() - run_started, 3),
        "returncode": returncode, "ok": ok,
    }
    if context_chars is not None:
        m["context_chars"] = context_chars
    m.update(extra)
    return m


def _makeRunResult(returncode: int, text: str, err: str, fields: dict, *,
                   effort, flag, spec, claude_md_path, profile) -> dict:
    """Build the success-path result dict from a completed subprocess."""
    ok = (not fields["is_error"]) if "is_error" in fields else (returncode == 0)
    return {
        "ok": ok, "returncode": returncode, "stdout": text, "stderr": err or "",
        "profile": profile, "session_id": fields.get("session_id"),
        "is_error": fields.get("is_error"), "subtype": fields.get("subtype"),
        "cost_usd": fields.get("cost_usd"), "usage": fields.get("usage"),
        "num_turns": fields.get("num_turns"),
        "effort": effort, "effort_flag": flag, "spec": spec, "claude_md_path": claude_md_path,
    }


def _makeErrResult(returncode: int, stdout: str, stderr: str, *,
                   effort, flag, spec, claude_md_path) -> dict:
    """Build an error result dict for launch/timeout/exception paths."""
    return {
        "ok": False, "returncode": returncode, "stdout": stdout, "stderr": stderr,
        "effort": effort, "effort_flag": flag, "spec": spec, "claude_md_path": claude_md_path,
    }


def _operatorKilledResult(out: str, err: str, run_cmd: list, base_m: dict, *,
                          effort, flag, spec, claude_md_path) -> dict:
    """Telemetry + result dict for an attempt killed by the cancel watcher.

    subtype='operator_killed' is DISTINCT from 'timeout': the orchestrator treats it as
    control flow (no attempt slot burned, no failure feedback), not a failed attempt."""
    LOG.warning("Claude attempt operator-killed via cancel signal (captured %d stdout chars)",
                len(out or ""))
    _recordIterationMetric(_makeMetric("operator_killed", run_cmd, returncode=-1, ok=False,
                                       **base_m))
    res = _makeErrResult(-1, out or "", (err or "") + "\nOPERATOR KILLED (abort/kill signal)",
                         effort=effort, flag=flag, spec=spec, claude_md_path=claude_md_path)
    res["subtype"] = "operator_killed"
    return res


def _logRunStart(run_cmd: list, run_prompt: str, *, wf: bool, spec: dict, work: str,
                 flag, profile, playbook_md: str) -> "tuple[int, int, int]":
    """Log Claude run parameters and return (inject_chars, playbook_chars, context_chars)."""
    inject_chars = len(spec.get("claude_md_inject") or "")
    playbook_chars = len(playbook_md or "")
    context_chars = len(run_prompt or "") + inject_chars + playbook_chars
    if context_chars > 60000:
        LOG.warning("Claude context payload is large: %d chars (prompt=%d inject=%d playbook=%d)",
                    context_chars, len(run_prompt or ""), inject_chars, playbook_chars)
    LOG.info("Claude run (cwd=%s effort=%s role=%s resume=%s skills=%s subagent=%s hooks=%s/%s workflow=%s prompt=%dch)",
             work, flag or "default", profile or "-", "--resume" in run_cmd,
             spec.get("skills_to_invoke"), spec.get("subagent"),
             spec.get("pre_tool_hooks"), spec.get("post_tool_hooks"),
             (spec["workflow_definition"].get("name") if wf else False), len(run_prompt))
    return inject_chars, playbook_chars, context_chars


def _scanOutput(text: str, spec: dict) -> None:
    """Scan output text for destructive commands if the block_destructive hook is active."""
    if "block_destructive" in (spec.get("pre_tool_hooks") or []):
        out_hits = scanDestructive(text)
        if out_hits:
            _alertBlocked(f"block_destructive: executor output shows destructive command(s) {out_hits}")


def _drainStreaming(proc, run_prompt: str, feed, timeout: int) -> "tuple[str, str]":
    """Stream stdout line-by-line through ``feed`` while the prompt is written on a writer
    thread (avoids stdin/stdout pipe deadlock). On timeout, kills the tree and raises
    ``TimeoutExpired`` so the caller's existing timeout path runs unchanged."""
    timed_out = {"v": False}

    def _on_timeout():
        timed_out["v"] = True
        _killProcessTree(proc.pid)

    timer = threading.Timer(timeout, _on_timeout)
    timer.start()

    def _writer():
        try:
            if proc.stdin:
                proc.stdin.write(run_prompt)
                proc.stdin.close()
        except Exception:  # noqa: BLE001 -- child may exit before we finish writing
            pass

    wt = threading.Thread(target=_writer, name="claude-stdin", daemon=True)
    wt.start()

    # Drain stderr CONCURRENTLY with the stdout loop. Sequential read-after-stdout deadlocked:
    # a stderr-chatty child fills the OS pipe buffer, blocks writing, stdout never EOFs, and
    # the attempt silently burns the whole timeout before the tree-kill fires.
    err_parts: list[str] = []

    def _errReader():
        try:
            err_parts.append(proc.stderr.read() or "")
        except Exception:  # noqa: BLE001 -- stderr loss must never break the drain
            pass

    et = threading.Thread(target=_errReader, name="claude-stderr", daemon=True)
    et.start()
    out_lines: list[str] = []
    try:
        for line in proc.stdout:   # blocks until EOF (process exit or tree-kill closes the pipe)
            out_lines.append(line)
            try:
                feed.consume(line.rstrip("\n"))
            except Exception:  # noqa: BLE001 -- a feed hiccup must never break the drain
                pass
    finally:
        timer.cancel()
    # Join BOTH helper threads before proc.wait(); bounded joins so a wedged pipe can't hang us.
    et.join(timeout=15.0)
    wt.join(timeout=1.0)
    err = "".join(err_parts)
    proc.wait()
    out = "".join(out_lines)
    if timed_out["v"]:
        raise subprocess.TimeoutExpired(str(getattr(proc, "args", "claude")), timeout, output=out)
    return out, err


def _completeResult(proc, out: str, err, wf, run_cmd: list, base_m: dict, *,
                    effort, flag, spec, claude_md_path, profile) -> dict:
    """Parse the envelope, build the result dict, and record the completion metric."""
    if config.EXECUTOR_OUTPUT_JSON:
        text, fields = _parseEnvelope(out)
        if not fields:   # the contract degraded silently otherwise
            LOG.warning("EXECUTOR_OUTPUT_JSON on but no result envelope parsed (rc=%s, %dch)",
                        proc.returncode, len(out))
    else:
        text, fields = out, {}
    _scanOutput(text, spec)
    # is_error from the envelope is the authoritative success signal -- exit code is unreliable.
    result = _makeRunResult(proc.returncode, text, err, fields, effort=effort, flag=flag,
                            spec=spec, claude_md_path=claude_md_path, profile=profile)
    _recordIterationMetric(_makeMetric(
        "completed", run_cmd, returncode=proc.returncode, ok=result["ok"],
        skills=spec.get("skills_to_invoke"), subagent=spec.get("subagent"),
        workflow=(spec["workflow_definition"].get("name") if wf else False),
        session_id=fields.get("session_id"), cost_usd=fields.get("cost_usd"),
        usage=fields.get("usage"), num_turns=fields.get("num_turns"), **base_m))
    return result


def runSubprocess(run_cmd: list, run_prompt: str, *, work: str, timeout: int, env: dict,
                  creationflags: int, spec: dict, effort: str, flag, profile,
                  playbook_md: str, claude_md_path, model: str, feed=None,
                  cancel_check=None) -> dict:
    """Execute one Claude subprocess and return a normalised result dict.
    Handles launch errors, JSON envelope parsing, timeout (full tree kill), and telemetry.
    When ``feed`` is set, stdout is streamed line-by-line through it in real time; when
    ``feed`` is None the unchanged ``communicate()`` path runs (zero regression).
    ``cancel_check`` (optional ``() -> bool``): polled by a daemon watcher every
    ``CANCEL_POLL_SECONDS`` while the child runs; True tree-kills the attempt and the
    result carries subtype='operator_killed' (distinct from 'timeout')."""
    wf = spec.get("use_workflow") and isinstance(spec.get("workflow_definition"), dict)
    run_started = time.perf_counter()
    inject_chars, playbook_chars, context_chars = _logRunStart(
        run_cmd, run_prompt, wf=wf, spec=spec, work=work, flag=flag,
        profile=profile, playbook_md=playbook_md)
    base_m = dict(work=work, model=model, effort=effort, flag=flag, run_started=run_started,
                  prompt_chars=len(run_prompt or ""), inject_chars=inject_chars,
                  playbook_chars=playbook_chars, context_chars=context_chars)
    try:
        proc = subprocess.Popen(run_cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE, text=True, encoding="utf-8",
                                errors="replace", cwd=work, creationflags=creationflags, env=env,
                                # POSIX: separate session so killpg targets only the child's group.
                                # Windows: CREATE_NEW_PROCESS_GROUP + taskkill /T do tree-kill.
                                start_new_session=(os.name != "nt"))
    except Exception as e:  # noqa: BLE001
        LOG.error("Claude launch failed: %s", e)
        _recordIterationMetric(_makeMetric("launch_failed", run_cmd, returncode=-1, ok=False,
                                           work=work, model=model, effort=effort, flag=flag,
                                           run_started=run_started, prompt_chars=len(run_prompt or ""),
                                           inject_chars=inject_chars, playbook_chars=playbook_chars))
        return _makeErrResult(-1, "", str(e), effort=effort, flag=flag, spec=spec,
                              claude_md_path=claude_md_path)
    cancelled = _startCancelWatcher(proc, cancel_check)
    try:
        if feed is not None:
            out, err = _drainStreaming(proc, run_prompt, feed, timeout)
        else:
            out, err = proc.communicate(input=run_prompt, timeout=timeout)
        if cancelled["v"]:
            return _operatorKilledResult(out, err, run_cmd, base_m, effort=effort, flag=flag,
                                         spec=spec, claude_md_path=claude_md_path)
        return _completeResult(proc, out or "", err, wf, run_cmd, base_m,
                               effort=effort, flag=flag, spec=spec,
                               claude_md_path=claude_md_path, profile=profile)
    except subprocess.TimeoutExpired:
        _killProcessTree(proc.pid)   # stop the work, no orphan leak, drain returns immediately
        try:
            out, err = proc.communicate(timeout=15)
        except Exception:  # noqa: BLE001
            out, err = "", ""
        if cancelled["v"]:   # watcher fired while the timeout raced -- the kill wins the label
            return _operatorKilledResult(out, err, run_cmd, base_m, effort=effort, flag=flag,
                                         spec=spec, claude_md_path=claude_md_path)
        LOG.error("Claude timed out after %ss -- process tree killed (captured %d stdout chars)",
                  timeout, len(out or ""))
        _recordIterationMetric(_makeMetric("timeout", run_cmd, returncode=-1, ok=False, **base_m))
        return _makeErrResult(-1, out or "", (err or "") + f"\nTIMEOUT after {timeout}s",
                              effort=effort, flag=flag, spec=spec, claude_md_path=claude_md_path)
    except Exception as e:  # noqa: BLE001
        try:
            _killProcessTree(proc.pid)
        except Exception:  # noqa: BLE001
            pass
        LOG.error("Claude failed: %s", e)
        _recordIterationMetric(_makeMetric("failed", run_cmd, returncode=-1, ok=False, **base_m))
        return _makeErrResult(-1, "", str(e), effort=effort, flag=flag, spec=spec,
                              claude_md_path=claude_md_path)
