def _killProcessTree(pid: int) -> None:
    """Kill a process AND all its descendants.

    The real Windows defect: ``subprocess`` timeout kills only the direct child (the
    ``cmd.exe`` / ``claude.cmd`` launcher). The ``node.exe`` grandchildren that do the
    actual agent work survive as orphans -- they leak, keep running (which is why the
    artifact still lands "after" a timeout), and hold the inherited stdout pipe open so
    the parent's drain blocks ~200s. ``taskkill /T`` walks the whole tree."""
    try:
        if os.name == "nt":
            subprocess.run(["taskkill", "/T", "/F", "/PID", str(pid)], capture_output=True, timeout=20)
        else:  # posix: kill the process group
            import signal

            os.killpg(os.getpgid(pid), signal.SIGKILL)
    except Exception as e:  # noqa: BLE001
        LOG.warning("process-tree kill of pid %s failed: %s", pid, e)


def _startCancelWatcher(proc, cancel_check) -> dict:
    """R6 operator-kill: start ONE daemon watcher thread that polls ``cancel_check`` every
    ``config.CANCEL_POLL_SECONDS`` while the subprocess runs. On a True signal it kills the
    WHOLE process tree, so a ``!kill``/``!abort``/deadline lands within ~one poll interval
    instead of the full CLI timeout. Returns a shared ``{"v": bool}`` flag the caller checks
    to report subtype='operator_killed' (distinct from 'timeout').

    Lifecycle: started right after Popen; exits when the process ends or the kill fires;
    daemon=True so a lingering poll sleep can never pin the interpreter."""
    cancelled = {"v": False}
    if cancel_check is None:
        return cancelled

    def _watch():
        while proc.poll() is None:
            try:
                hit = bool(cancel_check())
            except Exception:  # noqa: BLE001 -- a broken check must never kill a healthy run
                hit = False
            if hit:
                cancelled["v"] = True
                _killProcessTree(proc.pid)
                break
            time.sleep(config.CANCEL_POLL_SECONDS)

    threading.Thread(target=_watch, name="claude-cancel-watch", daemon=True).start()
    return cancelled


def _resolveClaudeLauncher() -> list[str]:
    exe = shutil.which("claude")
    if not exe:
        raise FileNotFoundError("claude CLI not found on PATH")
    if os.name == "nt" and exe.lower().endswith((".cmd", ".bat")):
        return ["cmd", "/c", exe]
    return [exe]


def _logRunStart(
    run_cmd: list, run_prompt: str, *, wf: bool, spec: dict, work: str, flag, profile, playbook_md: str
) -> "tuple[int, int, int]":
    """Log Claude run parameters and return (inject_chars, playbook_chars, context_chars)."""
    inject_chars = len(spec.get("claude_md_inject") or "")
    playbook_chars = len(playbook_md or "")
    context_chars = len(run_prompt or "") + inject_chars + playbook_chars
    if context_chars > 60000:
        LOG.warning(
            "Claude context payload is large: %d chars (prompt=%d inject=%d playbook=%d)",
            context_chars,
            len(run_prompt or ""),
            inject_chars,
            playbook_chars,
        )
    LOG.info(
        "Claude run (cwd=%s effort=%s role=%s resume=%s skills=%s subagent=%s hooks=%s/%s workflow=%s prompt=%dch)",
        work,
        flag or "default",
        profile or "-",
        "--resume" in run_cmd,
        spec.get("skills_to_invoke"),
        spec.get("subagent"),
        spec.get("pre_tool_hooks"),
        spec.get("post_tool_hooks"),
        (spec["workflow_definition"].get("name") if wf else False),
        len(run_prompt),
    )
    return inject_chars, playbook_chars, context_chars


def _drainStreaming(proc, run_prompt: str, feed, timeout: int) -> "tuple[str, str]":
    """Stream stdout line-by-line through ``feed`` while the prompt is written on a writer
    thread (avoids stdin/stdout pipe deadlock). On timeout, kills the tree and raises
    ``TimeoutExpired`` so the caller's existing timeout path runs unchanged."""
    timed_out = {"v": False}

    def _on_timeout():
        timed_out["v"] = True
        _killProcessTree(proc.pid)

    timer = threading.Timer(timeout, _on_timeout)
    timer.start()

    def _writer():
        try:
            if proc.stdin:
                proc.stdin.write(run_prompt)
                proc.stdin.close()
        except Exception:  # noqa: BLE001 -- child may exit before we finish writing
            pass

    wt = threading.Thread(target=_writer, name="claude-stdin", daemon=True)
    wt.start()

    # Drain stderr CONCURRENTLY with the stdout loop. Sequential read-after-stdout deadlocked:
    # a stderr-chatty child fills the OS pipe buffer, blocks writing, stdout never EOFs, and
    # the attempt silently burns the whole timeout before the tree-kill fires.
    err_parts: list[str] = []

    def _errReader():
        try:
            if proc.stderr:
                err_parts.append(proc.stderr.read() or "")
        except Exception:  # noqa: BLE001 -- stderr loss must never break the drain
            pass

    et = threading.Thread(target=_errReader, name="claude-stderr", daemon=True)
    et.start()

    out_lines: list[str] = []
    try:
        for line in proc.stdout:  # blocks until EOF (process exit or tree-kill closes the pipe)
            out_lines.append(line)
            try:
                feed.consume(line.rstrip("\n"))
            except Exception:  # noqa: BLE001 -- a feed hiccup must never break the drain
                pass
    finally:
        timer.cancel()
    # Join BOTH helper threads before proc.wait(); bounded joins so a wedged pipe can't hang us.
    et.join(timeout=15.0)
    wt.join(timeout=1.0)
    err = "".join(err_parts)
    # Bounded wait: stdout hit EOF, but a partial/failed tree-kill (_killProcessTree swallows
    # all exceptions, including its own taskkill timeout) can otherwise leave proc.wait() blocking
    # forever, wedging this worker thread (and its ThreadPoolExecutor slot under the batch executor).
    try:
        proc.wait(timeout=15)
    except subprocess.TimeoutExpired:
        _killProcessTree(proc.pid)
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            LOG.warning("child survived tree-kill; abandoning wait for pid %s", proc.pid)
    out = "".join(out_lines)
    if timed_out["v"]:
        raise subprocess.TimeoutExpired(str(getattr(proc, "args", "claude")), timeout, output=out)
    return out, err


def _prepareRunContext(run_cmd, run_prompt, *, work, model, effort, flag, profile, playbook_md, spec):
    """Log the run start and build (wf, run_started, base_m) shared by every result branch."""
    wf = spec.get("use_workflow") and isinstance(spec.get("workflow_definition"), dict)
    run_started = time.perf_counter()
    inject_chars, playbook_chars, context_chars = _logRunStart(
        run_cmd, run_prompt, wf=wf, spec=spec, work=work, flag=flag, profile=profile, playbook_md=playbook_md
    )
    base_m = dict(
        work=work,
        model=model,
        effort=effort,
        flag=flag,
        run_started=run_started,
        prompt_chars=len(run_prompt or ""),
        inject_chars=inject_chars,
        playbook_chars=playbook_chars,
        context_chars=context_chars,
    )
    return wf, run_started, inject_chars, playbook_chars, base_m


def _launchClaude(run_cmd: list, work: str, env: dict, creationflags: int) -> subprocess.Popen:
    return subprocess.Popen(
        run_cmd,
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=work,
        creationflags=creationflags,
        env=env,
        # POSIX: separate session so killpg targets only the child's group.
        # Windows: CREATE_NEW_PROCESS_GROUP + taskkill /T do tree-kill.
        start_new_session=(os.name != "nt"),
    )


def _launchFailureResult(
    e: Exception,
    run_cmd: list,
    run_prompt: str,
    *,
    work,
    model,
    effort,
    flag,
    run_started,
    inject_chars,
    playbook_chars,
    spec,
    claude_md_path,
) -> dict:
    LOG.error("Claude launch failed: %s", e)
    _recordIterationMetric(
        _makeMetric(
            "launch_failed",
            run_cmd,
            returncode=-1,
            ok=False,
            work=work,
            model=model,
            effort=effort,
            flag=flag,
            run_started=run_started,
            prompt_chars=len(run_prompt or ""),
            inject_chars=inject_chars,
            playbook_chars=playbook_chars,
        )
    )
    return _makeErrResult(-1, "", str(e), effort=effort, flag=flag, spec=spec, claude_md_path=claude_md_path)


def _waitOnTimeout(proc, run_cmd, timeout, cancelled, base_m, *, effort, flag, spec, claude_md_path) -> dict:
    _killProcessTree(proc.pid)  # stop the work, no orphan leak, drain returns immediately
    try:
        out, err = proc.communicate(timeout=15)
    except Exception:  # noqa: BLE001
        out, err = "", ""
    if cancelled["v"]:  # watcher fired while the timeout raced -- the kill wins the label
        return _operatorKilledResult(
            out, err, run_cmd, base_m, effort=effort, flag=flag, spec=spec, claude_md_path=claude_md_path
        )
    LOG.error(
        "Claude timed out after %ss -- process tree killed (captured %d stdout chars)",
        timeout,
        len(out or ""),
    )
    _recordIterationMetric(_makeMetric("timeout", run_cmd, returncode=-1, ok=False, **base_m))
    return _makeErrResult(
        -1,
        out or "",
        (err or "") + f"\nTIMEOUT after {timeout}s",
        effort=effort,
        flag=flag,
        spec=spec,
        claude_md_path=claude_md_path,
    )


def _waitOnUnexpectedError(e, proc, run_cmd, base_m, *, effort, flag, spec, claude_md_path) -> dict:
    try:
        _killProcessTree(proc.pid)
    except Exception:  # noqa: BLE001
        pass
    LOG.error("Claude failed: %s", e)
    _recordIterationMetric(_makeMetric("failed", run_cmd, returncode=-1, ok=False, **base_m))
    return _makeErrResult(-1, "", str(e), effort=effort, flag=flag, spec=spec, claude_md_path=claude_md_path)


def _waitForClaude(
    proc,
    run_prompt,
    feed,
    timeout,
    cancelled,
    wf,
    run_cmd,
    base_m,
    *,
    effort,
    flag,
    spec,
    claude_md_path,
    profile,
) -> dict:
    """Drain/communicate with the launched process and classify the outcome (complete,
    operator-killed, timeout, or unexpected error)."""
    try:
        if feed is not None:
            out, err = _drainStreaming(proc, run_prompt, feed, timeout)
        else:
            out, err = proc.communicate(input=run_prompt, timeout=timeout)
        if cancelled["v"]:
            return _operatorKilledResult(
                out, err, run_cmd, base_m, effort=effort, flag=flag, spec=spec, claude_md_path=claude_md_path
            )
        return _completeResult(
            proc,
            out or "",
            err,
            wf,
            run_cmd,
            base_m,
            effort=effort,
            flag=flag,
            spec=spec,
            claude_md_path=claude_md_path,
            profile=profile,
        )
    except subprocess.TimeoutExpired:
        return _waitOnTimeout(
            proc,
            run_cmd,
            timeout,
            cancelled,
            base_m,
            effort=effort,
            flag=flag,
            spec=spec,
            claude_md_path=claude_md_path,
        )
    except Exception as e:  # noqa: BLE001
        return _waitOnUnexpectedError(
            e, proc, run_cmd, base_m, effort=effort, flag=flag, spec=spec, claude_md_path=claude_md_path
        )


def runSubprocess(
    run_cmd: list,
    run_prompt: str,
    *,
    work: str,
    timeout: int,
    env: dict,
    creationflags: int,
    spec: dict,
    effort: str,
    flag,
    profile,
    playbook_md: str,
    claude_md_path,
    model: str,
    feed=None,
    cancel_check=None,
) -> dict:
    """Execute one Claude subprocess and return a normalised result dict.
    Handles launch errors, JSON envelope parsing, timeout (full tree kill), and telemetry.
    When ``feed`` is set, stdout is streamed line-by-line through it in real time; when
    ``feed`` is None the unchanged ``communicate()`` path runs (zero regression).
    ``cancel_check`` (optional ``() -> bool``): polled by a daemon watcher every
    ``CANCEL_POLL_SECONDS`` while the child runs; True tree-kills the attempt and the
    result carries subtype='operator_killed' (distinct from 'timeout')."""
    wf, run_started, inject_chars, playbook_chars, base_m = _prepareRunContext(
        run_cmd,
        run_prompt,
        work=work,
        model=model,
        effort=effort,
        flag=flag,
        profile=profile,
        playbook_md=playbook_md,
        spec=spec,
    )
    try:
        proc = _launchClaude(run_cmd, work, env, creationflags)
    except Exception as e:  # noqa: BLE001
        return _launchFailureResult(
            e,
            run_cmd,
            run_prompt,
            work=work,
            model=model,
            effort=effort,
            flag=flag,
            run_started=run_started,
            inject_chars=inject_chars,
            playbook_chars=playbook_chars,
            spec=spec,
            claude_md_path=claude_md_path,
        )
    cancelled = _startCancelWatcher(proc, cancel_check)
    return _waitForClaude(
        proc,
        run_prompt,
        feed,
        timeout,
        cancelled,
        wf,
        run_cmd,
        base_m,
        effort=effort,
        flag=flag,
        spec=spec,
        claude_md_path=claude_md_path,
        profile=profile,
    )
