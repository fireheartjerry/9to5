"""Browser execution backend -- Layer 1 (CDP) "hands" for 9TO5, plus the Gemini second-brain shim.

Two responsibilities live here:

1. The GENERIC browser surface (``runBrowser`` / ``_run_actions``): a peer to the Claude-CLI
   executor (agents/executor.py) -- same call signature, same result-dict contract -- so the
   orchestrator's dispatcher can route a subtask to the browser when the brain authors
   ``surface="browser"``. It drives Chromium via Playwright (real CDP) to run a list of
   structured actions (goto/click/type/extract/screenshot/wait). When Playwright is not
   installed the call degrades cleanly (ok=False, is_error=True) so the run continues -- exactly
   like a failed terminal subtask -- rather than crashing. This is GATED by BROWSER_LAYER_ENABLED.

2. The second-brain SHIM (``probe`` / ``startConversation`` / ``sessionAsk`` / ``askGemini`` /
   ``closeSession`` / ``preflightLogin``): the function names the orchestrator + Adversary call
   to consult the stronger critic. The transport used to be GPT-5.5 driven over chatgpt.com via
   CDP; it is now Google Gemini through the ``google-genai`` SDK (agents/gemini_driver.py) -- no
   Playwright, no threads, no DOM. The names are unchanged so every call site keeps working; only
   the transport swapped. This is GATED by GEMINI_ENABLED.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  BrowserUnavailable  -- Raised when no browser backend (Playwright/Chromium) is installed.
  runBrowser(spec_or_prompt, *, work_dir: Optional[str]=None, task_state=None, subtask: Optional[dict]=None, resume_session: Optional[str]=None, **_kw) -> dict  -- Execute a browser subtask
  get_session()  -- Lazily build the process-wide GeminiSession (does NOT open a client yet).
  probe() -> bool  -- Health-probe the Gemini session
  startConversation(goal: str, task_id: str) -> None  -- Start the single run conversation.
  closeSession() -> None  -- Close + tear down the Gemini session.
  preflightLogin(timeout_s: int=300, poll_s: int=3) -> bool  -- Verify Gemini is reachable before a run relies on it
  sessionAsk(message: str, *, expect_json: bool=False) -> Optional[str]  -- Ask Gemini one message through the run session
  askGemini(message: str, *, runner=None, expect_json: bool=False) -> Optional[str]  -- Send one ``message`` to Gemini and return the reply text.
DEPENDS-ON: agents.executor, agents.gemini_driver, config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_browser_executor.py tests/test_phase2_cdp_adversary.py
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Optional

import config
from agents import executor

LOG = config.getLogger("browser_executor")

_URL_RE = re.compile(r"https?://[^\s\"'<>)]+")


class BrowserUnavailable(RuntimeError):
    """Raised when no browser backend (Playwright/Chromium) is installed."""


def _result(spec: dict, *, ok: bool, is_error: bool, stdout: str = "", stderr: str = "") -> dict:
    """A runClaude-shaped result so the orchestrator treats browser output identically."""
    return {
        "ok": ok, "returncode": 0 if ok else 1, "stdout": stdout, "stderr": stderr,
        "is_error": is_error, "effort": spec.get("effort_level", "default"),
        "effort_flag": None, "spec": spec, "claude_md_path": None,
        "profile": "browser_navigator", "blocked": False, "surface": "browser",
    }


def _actions_from_prompt(prompt: str) -> list[dict[str, Any]]:
    """Auto-derive simple actions from a URL-bearing prompt: visit each URL + extract text."""
    actions: list[dict[str, Any]] = []
    for url in _URL_RE.findall(prompt or ""):
        actions.append({"action": "goto", "url": url})
        actions.append({"action": "extract"})
    return actions


def _run_actions(actions: list[dict[str, Any]], *, timeout_ms: int = 30000,
                 screenshot_dir: Optional[str] = None) -> str:
    """Execute structured CDP actions via Playwright; return a transcript. Raises
    BrowserUnavailable if Playwright/Chromium is not installed (caller degrades).

    Supported actions: goto, click, type, press, select, scroll, wait, extract, eval,
    screenshot. Each line of the transcript records the action + its observable result so
    the verifier can check the outcome."""
    try:
        from playwright.sync_api import sync_playwright  # type: ignore
    except Exception as e:  # noqa: BLE001 -- not installed -> caller degrades cleanly
        raise BrowserUnavailable(
            "browser layer unavailable: `pip install playwright && playwright install chromium`") from e

    lines: list[str] = []
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        try:
            page = browser.new_page()
            page.set_default_timeout(timeout_ms)
            for i, act in enumerate(actions):
                kind = (act.get("action") or "").lower()
                from notifications.lane_feed import laneTap
                laneTap("browser", f"{kind}: {str(act.get('url') or act.get('selector') or act)[:80]}")
                if kind == "goto":
                    page.goto(act["url"])
                    lines.append(f"goto {act['url']} -> {page.title()!r}")
                elif kind == "click":
                    page.click(act["selector"])
                    lines.append(f"click {act['selector']}")
                elif kind == "type":
                    page.fill(act["selector"], act.get("text", ""))
                    lines.append(f"type into {act['selector']}")
                elif kind == "press":
                    page.press(act["selector"], act.get("key", "Enter"))
                    lines.append(f"press {act.get('key', 'Enter')} on {act['selector']}")
                elif kind == "select":
                    page.select_option(act["selector"], act.get("value"))
                    lines.append(f"select {act.get('value')} in {act['selector']}")
                elif kind == "scroll":
                    page.mouse.wheel(0, int(act.get("dy", 800)))
                    lines.append(f"scroll dy={act.get('dy', 800)}")
                elif kind == "wait":
                    if act.get("selector"):
                        page.wait_for_selector(act["selector"])
                        lines.append(f"wait {act['selector']}")
                    else:
                        page.wait_for_timeout(int(act.get("ms", 1000)))
                        lines.append(f"wait {act.get('ms', 1000)}ms")
                elif kind == "extract":
                    sel = act.get("selector")
                    text = (page.inner_text(sel) if sel else page.inner_text("body"))[:2000]
                    lines.append(f"extract {sel or 'body'}:\n{text}")
                elif kind == "eval":
                    val = page.evaluate(act["script"])
                    lines.append(f"eval -> {str(val)[:500]}")
                elif kind == "screenshot":
                    raw_name = act.get("path") or f"screenshot-{i}.png"
                    name = Path(raw_name).name or f"screenshot-{i}.png"
                    path = str(Path(screenshot_dir) / name) if screenshot_dir else name
                    page.screenshot(path=path)
                    lines.append(f"screenshot -> {path}")
                else:
                    lines.append(f"(skipped unknown action {kind!r})")
        finally:
            browser.close()
    return "\n".join(lines)


def runBrowser(spec_or_prompt, *, work_dir: Optional[str] = None, task_state=None,
               subtask: Optional[dict] = None, resume_session: Optional[str] = None,
               **_kw) -> dict:
    """Execute a browser subtask. Matches executor.runClaude's signature + result shape."""
    spec = executor.normalizeSpec(spec_or_prompt)
    actions = spec.get("browser_actions") or _actions_from_prompt(spec.get("prompt", ""))
    if not actions:
        return _result(spec, ok=False, is_error=True,
                       stderr="browser surface needs 'browser_actions' or a URL in the prompt")
    try:
        transcript = _run_actions(actions, screenshot_dir=work_dir)
        LOG.info("browser run: %d actions ok", len(actions))
        return _result(spec, ok=True, is_error=False, stdout=transcript)
    except BrowserUnavailable as e:
        LOG.warning("%s", e)
        return _result(spec, ok=False, is_error=True, stderr=str(e))
    except Exception as e:  # noqa: BLE001 -- a browser failure is a failed subtask, not a crash
        LOG.warning("browser run failed (ignored): %s", e)
        return _result(spec, ok=False, is_error=True, stderr=f"browser run failed: {e}")


# --- Gemini second brain (Phase 2 production path) --------------------------------------
# A single long-lived GeminiSession per process: one conversation per run so the model
# accumulates run context across subtask reviews. The orchestrator owns its lifecycle (probe
# at run start, close at run end). Unlike the old sync-Playwright ChatGPT session, the Gemini
# transport is stateless thread-safe HTTPS -- no dedicated worker thread, no profile, no DOM.
_SESSION = None


def get_session():
    """Lazily build the process-wide GeminiSession (does NOT open a client yet)."""
    global _SESSION
    if _SESSION is None:
        from agents.gemini_driver import GeminiSession
        _SESSION = GeminiSession()
    return _SESSION


def probe() -> bool:
    """Health-probe the Gemini session. Never raises; False on any failure."""
    return bool(get_session().health_probe())


def startConversation(goal: str, task_id: str) -> None:
    """Start the single run conversation."""
    get_session().start_run_conversation(goal, task_id)


def closeSession() -> None:
    """Close + tear down the Gemini session."""
    if _SESSION is not None:
        _SESSION.close()


def preflightLogin(timeout_s: int = 300, poll_s: int = 3) -> bool:
    """Verify Gemini is reachable before a run relies on it. Unlike the old chatgpt.com path
    there is NO interactive login -- an API key either works or it doesn't -- so this is just a
    health probe. The ``timeout_s`` / ``poll_s`` params are kept for call-site compatibility.
    Returns True if Gemini answered."""
    return probe()


def sessionAsk(message: str, *, expect_json: bool = False) -> Optional[str]:
    """Ask Gemini one message through the run session. Re-raises typed GeminiError subclasses
    (auth/blocked/rate-limit) so the Adversary can route the fallback chain; returns None on a
    benign empty reply."""
    return get_session().ask(message, expect_json=expect_json)


def askGemini(message: str, *, runner=None, expect_json: bool = False) -> Optional[str]:
    """Send one ``message`` to Gemini and return the reply text.

    Production path (no ``runner``): the long-lived :class:`~agents.gemini_driver.GeminiSession`.
    Test path (``runner`` injected): a ``(message) -> reply`` callable is called directly, so
    tests can drive the Adversary without touching the live API. Returns ``None`` when the layer
    is unavailable or the reply is empty, so callers can degrade conservatively instead of
    crashing."""
    if runner is not None:
        return runner(message)
    return sessionAsk(message, expect_json=expect_json)
