"""debugging_workflow -- integrated skill-gap + trace-replay diagnostic.

Combines skill-gap-analysis and trace-replay to surface actionable debugging
recommendations by correlating execution divergences with coverage gaps.

Workflow steps:
  1. Run skill gap analysis to score domain coverage.
  2. Run trace replay against the most recent (or specified) run.
  3. Correlate trace divergences with high-gap domains.
  4. Return a unified report dict.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  loadSkillInventory()
  loadTaskHistory()
  buildDemandCounter(tasks)
  scoreDomains(demand, inventory)
  buildReport(gap_rows: list, trace_result: dict, inventory: dict) -> dict  -- Correlate gap_rows with trace_result and return a unified report dict.
  run(run_id: Optional[str]=None, limit: int=5, calibrate_limit: int=20) -> dict  -- Execute the integrated debugging workflow.
DEPENDS-ON: agents.trace_replay
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_debugging_workflow.py
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from typing import Optional

_ROOT = Path(__file__).resolve().parent.parent
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

# --- skill-gap-analysis loader (hyphen in filename requires importlib) --------
# Loaded lazily on first use so importing this module never executes the skill
# script; tests patch the module-level wrappers below.
_SGA_SCRIPT = _ROOT / ".claude" / "skills" / "skill-gap-analysis.py"
_sga_module = None


def _sga():
    """Load and cache the skill-gap-analysis script on first use."""
    global _sga_module
    if _sga_module is None:
        spec = importlib.util.spec_from_file_location("skill_gap_analysis", _SGA_SCRIPT)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        _sga_module = mod
    return _sga_module


def loadSkillInventory():
    return _sga().loadSkillInventory()


def loadTaskHistory():
    return _sga().loadTaskHistory()


def buildDemandCounter(tasks):
    return _sga().buildDemandCounter(tasks)


def scoreDomains(demand, inventory):
    return _sga().scoreDomains(demand, inventory)

# --- trace-replay workflow (importable module) --------------------------------
from agents.trace_replay import runWorkflow as _runTraceReplay  # noqa: E402

# Domains that map to debugging-related trace divergences.
_DEBUG_DOMAINS: frozenset[str] = frozenset({"debugging", "testing", "monitoring", "workflow"})


def buildReport(
    gap_rows: list,
    trace_result: dict,
    inventory: dict,
) -> dict:
    """Correlate gap_rows with trace_result and return a unified report dict.

    Returns:
        ok              -- bool: True when both inputs are usable.
        gap_rows        -- list[dict]: domain gap scores from skill-gap-analysis.
        trace_result    -- dict: raw result from runWorkflow().
        high_gap_domains -- list[str]: domains with gap_score > 0, sorted desc.
        correlated       -- list[dict]: gaps whose domain overlaps debug domains
                            AND trace has at least one divergence.
        recommendations  -- list[str]: human-readable action strings.
        inventory_count  -- int
        task_count       -- int (0 when unavailable)
    """
    high_gap = sorted(
        [r for r in gap_rows if r["gap_score"] > 0],
        key=lambda r: r["gap_score"],
        reverse=True,
    )
    high_gap_domains = [r["domain"] for r in high_gap]

    divergences = trace_result.get("divergences", [])
    has_divergences = len(divergences) > 0

    correlated: list[dict] = []
    if has_divergences:
        for row in high_gap:
            if row["domain"] in _DEBUG_DOMAINS:
                correlated.append({
                    "domain": row["domain"],
                    "gap_score": row["gap_score"],
                    "covered_by": row["covered_by"],
                    "divergence_count": trace_result.get("divergence_count", 0),
                })

    recommendations: list[str] = []
    for entry in correlated:
        if entry["covered_by"]:
            recommendations.append(
                f"Strengthen '{entry['domain']}' skill coverage "
                f"(gap={entry['gap_score']:.1f}, divergences={entry['divergence_count']})."
            )
        else:
            recommendations.append(
                f"Create new skill for '{entry['domain']}' "
                f"(gap={entry['gap_score']:.1f}, divergences={entry['divergence_count']}, zero coverage)."
            )

    # Always surface top non-debug gap even without divergences.
    non_debug_gaps = [r for r in high_gap if r["domain"] not in _DEBUG_DOMAINS]
    if non_debug_gaps:
        top = non_debug_gaps[0]
        recommendations.append(
            f"Address '{top['domain']}' gap (gap={top['gap_score']:.1f}) proactively."
        )

    return {
        "ok": True,
        "gap_rows": gap_rows,
        "trace_result": trace_result,
        "high_gap_domains": high_gap_domains,
        "correlated": correlated,
        "recommendations": recommendations,
        "inventory_count": len(inventory),
        "task_count": 0,
    }


def run(
    run_id: Optional[str] = None,
    limit: int = 5,
    calibrate_limit: int = 20,
) -> dict:
    """Execute the integrated debugging workflow.

    Runs skill-gap-analysis and trace-replay, then correlates results.

    Args:
        run_id: specific trace run to replay; None = most recent.
        limit: max trace events to surface.
        calibrate_limit: calibration window for trace-replay.

    Returns buildReport() dict plus 'error' key (None on success).
    """
    inventory = loadSkillInventory()
    tasks = loadTaskHistory()
    demand = buildDemandCounter(tasks)
    gap_rows = scoreDomains(demand, inventory)

    trace_result = _runTraceReplay(
        run_id=run_id,
        limit=limit,
        calibrate_limit=calibrate_limit,
    )

    report = buildReport(gap_rows, trace_result, inventory)
    report["task_count"] = len(tasks)
    report["error"] = trace_result.get("error")
    return report
