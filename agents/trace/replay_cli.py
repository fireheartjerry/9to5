# ── Core replay orchestrator ──────────────────────────────────────────────────

def _replayEvents(
    events: list[dict],
    threshold: int,
    run_id: str = "?",
    show_chart: bool = False,
    output_format: str = "text",
) -> int:
    """Replay a pre-loaded event list. Returns count of divergence events."""
    base_ts = _parseTs(events[0].get("ts")) or 0.0 if events else 0.0
    if output_format == "json":
        return _replayEventsJson(events, base_ts, threshold, run_id)
    _printTraceHeader(run_id, len(events), threshold)
    divergences, subtask_event_count = _printEventRows(events, base_ts)
    _printTextSummary(divergences, subtask_event_count, threshold, show_chart, base_ts, events)
    return len(divergences)


def replayTrace(run_id: str, threshold: int) -> int:
    """Load and replay one run's event trace. Returns count of divergence events."""
    events = tracing.readEvents(run_id)
    if not events:
        print(f"[trace-replay] No events found for run {run_id}.")
        return 0
    return _replayEvents(events, threshold, run_id=run_id)


