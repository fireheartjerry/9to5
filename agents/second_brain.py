"""second_brain -- the dual-brain consult router.

9to5's local Ollama is the fast generator/planner; GPT-5.5 (via chatgpt.com) is the stronger
critic/arbiter. Every second-opinion touchpoint -- plan, architecture, per-subtask output,
pre-PR diff, low-confidence consult -- routes through :func:`consult`, which implements ONE
fallback chain so behavior can't drift between touchpoints:

    GPT-5.5 (browser)  ->  Ollama adversary  ->  conservative stub

GPT is tried first when the browser layer is enabled, the run-start health probe passed
(``session_ok``), and the cost guard says this review is ``worth`` it. A real GPT verdict wins.
If GPT fails for ANY reason (login wall, Cloudflare, rate limit, bad JSON, timeout) it degrades
to the Ollama brain -- a genuine middle tier, never a jump straight to auto-approve. The verdict
contract is the rich one from :mod:`agents.adversary`, plus two routing hints:

    ``tier``         -> "gpt" | "ollama" | "stub"  (who actually produced the verdict)
    ``session_dead`` -> True when GPT failed with a FATAL session error (login/Cloudflare/rate
                        limit), so the orchestrator can stop trying GPT for the rest of the run.

The reviewer never blocks a run: any unexpected error still yields a conservative verdict.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  consult(review_type: str, *, title: str, trigger_reason: str, content: str, goal: str='', ollama_chat: Optional[Callable]=None, browser_ask: Optional[Callable]=None, session_ok: bool=False, worth: bool=True) -> dict  -- Run one second-opinion review through the GPT -> Ollama -> stub chain
  is_blocking(verdict: dict) -> bool  -- True when a verdict should hold a PR / drive remediation.
DEPENDS-ON: agents.adversary, agents.chatgpt_driver, config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_phase2_second_brain.py
"""
from __future__ import annotations

from typing import Any, Callable, Optional

import config
from agents import adversary

LOG = config.getLogger("second_brain")

REVIEW_TYPES = ("subtask", "plan", "architecture", "pre_pr_diff")


class _FatalProbe:
    """Wraps ``browser_ask`` to remember a FATAL session error even though reviewViaBrowser
    swallows it into a stub. Lets the orchestrator disable GPT for the rest of the run."""

    def __init__(self, fn: Callable[[str], Optional[str]]) -> None:
        self._fn = fn
        self.fatal: Optional[Exception] = None

    def __call__(self, message: str) -> Optional[str]:
        try:
            return self._fn(message)
        except Exception as e:  # noqa: BLE001
            if _is_fatal_session_error(e):
                self.fatal = e
            raise


def _is_fatal_session_error(exc: BaseException) -> bool:
    """True for errors that mean GPT is unreachable for the WHOLE run (not a one-off hiccup)."""
    try:
        from agents.chatgpt_driver import (ChatGPTBlocked, ChatGPTLoginRequired,
                                           ChatGPTRateLimited)
    except Exception:  # noqa: BLE001
        return False
    return isinstance(exc, (ChatGPTLoginRequired, ChatGPTBlocked, ChatGPTRateLimited))


def consult(review_type: str, *, title: str, trigger_reason: str, content: str,
            goal: str = "", ollama_chat: Optional[Callable] = None,
            browser_ask: Optional[Callable] = None, session_ok: bool = False,
            worth: bool = True) -> dict:
    """Run one second-opinion review through the GPT -> Ollama -> stub chain. Returns the rich
    verdict dict tagged with ``tier`` and ``session_dead``."""
    use_gpt = bool(config.BROWSER_LAYER_ENABLED and session_ok and browser_ask and worth)
    session_dead = False

    if use_gpt:
        probe = _FatalProbe(browser_ask)
        rv = adversary.reviewViaBrowser(title, trigger_reason, content,
                                        browser_ask=probe, goal=goal, review_type=review_type)
        if not rv.get("stub"):
            rv["tier"] = "gpt"
            rv["session_dead"] = False
            LOG.info("consult[%s] '%s' -> GPT %s (sev=%s)",
                     review_type, title, rv["verdict"], rv.get("severity"))
            return rv
        session_dead = probe.fatal is not None
        LOG.info("consult[%s] '%s' -> GPT unavailable (%s); falling back to Ollama",
                 review_type, title, "fatal" if session_dead else "soft")

    rv = adversary.review(title, trigger_reason, content,
                          ollama_chat=ollama_chat, goal=goal, review_type=review_type)
    rv["tier"] = "ollama" if not rv.get("stub") else "stub"
    rv["session_dead"] = session_dead
    return rv


def is_blocking(verdict: dict) -> bool:
    """True when a verdict should hold a PR / drive remediation.

    GPT verdicts are gated by severity (GPT grades it reliably): challenged AND severity at or
    above ``ADVERSARY_BLOCKING_SEVERITY``. Ollama / stub verdicts keep the pre-Phase-2
    conservative rule -- ANY challenge blocks -- because the local model rarely grades severity,
    and we must not weaken the existing teeth on the fallback path."""
    if verdict.get("verdict") != "challenged":
        return False
    if verdict.get("tier", "ollama") != "gpt":
        return True   # conservative: any non-GPT challenge holds, as before Phase 2
    order = {"none": 0, "low": 1, "medium": 2, "high": 3}
    bar = order.get(config.ADVERSARY_BLOCKING_SEVERITY, 3)
    sev = order.get(verdict.get("severity") or "medium", 2)
    return sev >= bar
