def buildSpec(
    run_id: Optional[str] = None,
    limit: int = 5,
    calibrate_limit: int = 20,
) -> dict:
    """Return an invocation spec dict tuned for this run.

    Args:
        run_id:          Target run ID. When None the most recent run is used.
        limit:           How many recent runs to surface as alternatives.
        calibrate_limit: Max runs used to calibrate the high-activity threshold.
                         Lower values trade accuracy for speed (20 is sufficient).
    """
    run_clause = f"--run-id {run_id}" if run_id else f"--limit {limit}"
    prompt = (
        f"python agents/trace_replay_cli.py {run_clause} "
        f"--format json --no-color"
    )
    return {
        "claude_md_inject": DEFAULT_INVOCATION_SPEC["claude_md_inject"],
        "skills_to_invoke": [],
        "effort_level": "default",
        "subagent": None,
        "prompt": prompt,
        "pre_tool_hooks": [],
        "post_tool_hooks": ["write_obsidian"],
        "_meta": {
            "run_id": run_id,
            "limit": limit,
            "calibrate_limit": calibrate_limit,
            "output_format": "json",
            "color": False,
        },
    }


def _emptyResult(run_id: Optional[str]) -> dict:
    """Return the zeroed result template shared by all runWorkflow() paths."""
    return {
        "ok": True,
        "run_id": run_id,
        "divergence_count": 0,
        "high_activity_count": 0,
        "parallel_moments": 0,
        "total_events": 0,
        "divergences": [],
        "raw": "",
        "error": None,
    }


def _replayInProcess(target: str, calibrate_limit: int, _empty: dict) -> dict:
    """Replay one run's events in-process and return the parsed result dict."""
    try:
        events = tracing.readEvents(target)
        if not events:
            LOG.info("trace_replay_workflow: no events for run %s.", target)
            return {**_empty, "run_id": target, "error": "no_events"}
        threshold = _calibrateThreshold(tracing.recentRunIds(limit=calibrate_limit))
        base_ts = _parseTs(events[0].get("ts")) or 0.0
        report = _buildJsonReport(events, base_ts, threshold, target)
    except Exception as exc:  # noqa: BLE001
        return {**_empty, "ok": False, "error": str(exc), "run_id": target}
    return {
        "ok": True,
        "run_id": report.get("run_id", target),
        "divergence_count": report.get("divergence_count", 0),
        "high_activity_count": report.get("high_activity_count", 0),
        "parallel_moments": report.get("parallel_moments", 0),
        "total_events": report.get("total_events", 0),
        "divergences": report.get("divergences", []),
        "raw": json.dumps(report),
        "error": None,
    }


def runWorkflow(
    run_id: Optional[str] = None,
    limit: int = 5,
    calibrate_limit: int = 20,
) -> dict:
    """Replay the trace in-process and return parsed results.

    Optimizations applied:
    - Existence pre-check via tracing.recentRunIds(); skips replay when empty.
    - In-process report building (no subprocess, no stdout scraping).
    - Calibration limited to calibrate_limit runs instead of 100.

    Returns a dict with keys:
        ok          -- bool: True when the replay completed.
        run_id      -- str | None: resolved run ID that was replayed.
        divergence_count  -- int
        high_activity_count -- int
        parallel_moments    -- int
        total_events        -- int
        divergences         -- list[dict]
        raw                 -- str: JSON-serialized report
        error               -- str | None: error message on failure.
    """
    _empty = _emptyResult(run_id)
    recent = tracing.recentRunIds(limit=1)
    if not recent and run_id is None:
        LOG.info("trace_replay_workflow: no archived runs; skipping replay.")
        return {**_empty, "error": "no_traces"}
    target = run_id or recent[0]
    return _replayInProcess(target, calibrate_limit, _empty)


def buildStepSpec(
    run_id: Optional[str] = None,
    limit: int = 5,
    calibrate_limit: int = 20,
) -> dict:
    """Return an invocation spec for step-by-step decision-point replay.

    Identical structure to buildSpec() but the claude_md_inject and _meta
    mark this as 'step' mode so downstream tooling can surface per-decision
    context_before / context_after windows.
    """
    run_clause = f"--run-id {run_id}" if run_id else f"--limit {limit}"
    prompt = (
        f"python agents/trace_replay_cli.py {run_clause} "
        f"--format json --no-color"
    )
    return {
        "claude_md_inject": (
            "You are running the trace-replay subagent in step-by-step decision-point mode.\n"
            "Invoke: python agents/trace_replay_cli.py --format json --no-color\n"
            "Parse the JSON output; for each entry in decision_points surface the\n"
            "kind, event, subtask, offset, context_before, and context_after."
        ),
        "skills_to_invoke": [],
        "effort_level": "default",
        "subagent": None,
        "prompt": prompt,
        "pre_tool_hooks": [],
        "post_tool_hooks": ["write_obsidian"],
        "_meta": {
            "run_id": run_id,
            "limit": limit,
            "calibrate_limit": calibrate_limit,
            "mode": "step",
            "output_format": "json",
            "color": False,
        },
    }


def getDecisionPoints(
    run_id: Optional[str] = None,
    limit: int = 5,
    calibrate_limit: int = 20,
) -> dict:
    """Run trace-replay and return structured decision points with surrounding context.

    Delegates replay to runWorkflow(), then re-packages the divergences list
    as decision_points for step-by-step debugging use.

    Returns a dict with keys:
        ok, run_id, decision_points, total_events, error
    """
    result = runWorkflow(run_id=run_id, limit=limit, calibrate_limit=calibrate_limit)
    return {
        "ok": result["ok"],
        "run_id": result.get("run_id", run_id),
        "decision_points": result.get("divergences", []),
        "total_events": result.get("total_events", 0),
        "error": result.get("error"),
    }
