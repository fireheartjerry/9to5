"""trace_replay -- optimized workflow for invoking the trace-replay subagent.

Provides buildSpec() and runWorkflow() for efficiently dispatching the
trace-replay diagnostic script inside the 9to5 orchestration pipeline.

Key optimizations vs bare CLI invocation:
  - JSON output mode: skips ANSI rendering; structured result is O(1) to parse.
  - Calibration capped at recent N runs (calibrate_limit=20) not 100.
  - Existence pre-check: no subprocess spawned when no traces exist.
  - --no-color always set: removes branch overhead inside the script.

Invocation spec format follows executor.py conventions so the orchestrator
can dispatch this workflow via the standard Claude Code invocation path.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  buildSpec(run_id: Optional[str]=None, limit: int=5, calibrate_limit: int=20) -> dict  -- Return an invocation spec dict tuned for this run.
  runWorkflow(run_id: Optional[str]=None, limit: int=5, calibrate_limit: int=20) -> dict  -- Execute the trace-replay script and return parsed results.
  buildStepSpec(run_id: Optional[str]=None, limit: int=5, calibrate_limit: int=20) -> dict  -- Return an invocation spec for step-by-step decision-point replay.
  getDecisionPoints(run_id: Optional[str]=None, limit: int=5, calibrate_limit: int=20) -> dict  -- Run trace-replay and return structured decision points with surrounding context.
DEPENDS-ON: config, platform_core.core.tracing
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_trace_replay.py
"""
