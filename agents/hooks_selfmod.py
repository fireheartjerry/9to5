def _envTaskRequested() -> bool:
    """True when the executor pinned a task for this hook (so a run is active)."""
    return bool(os.environ.get("NINE_TO_FIVE_TASK_FILE") or os.environ.get("NINE_TO_FIVE_TASK_ID"))


def _classifyPath(path_str: str) -> str:
    """Classify a path as 'source' | 'config' | 'test' | 'other'."""
    norm = path_str.replace("/", "\\").lower()
    base = norm.rsplit("\\", 1)[-1]
    if re.search(r"(?:^|\\)tests?(?:\\|$)|_test\.py$|^test_.*\.py$", norm):
        return "test"
    if base in ("config.py",) or (base.startswith(".env") and not base.startswith(".envrc")):
        return "config"
    if norm.endswith((".py", ".js", ".ts")):
        return "source"
    return "other"


def _scanDiff(diff_text: str) -> list:
    """Extract touched file paths from unified diff text (--- / +++ lines)."""
    paths: list = []
    for line in (diff_text or "").splitlines():
        m = re.match(r"^(?:\+\+\+|---)\s+(?:[ab]/)?(.+)", line)
        if m:
            p = m.group(1).strip()
            if p not in ("/dev/null", "nul") and p not in paths:
                paths.append(p)
    return paths


def _bashHitsBoundary(cmd_low: str, bbase: str) -> bool:
    """True when a writing Bash command's text contains the boundary basename as a real PATH TOKEN
    (bounded by start/end or a shell/path separator) -- not a bare substring."""
    if not (cmd_low and bbase):
        return False
    return bool(re.search(r"(^|[\s\"'=:;,()&|<>/\\])" + re.escape(bbase) + r"($|[\s\"'=:;,()&|<>])", cmd_low))


def _bashReadsSecret(cmd_low: str) -> bool:
    """True when a Bash command READS a secret-family file (.env / .env.*, not .envrc) to stdout.
    Thin wrapper over the shared taxonomy (kept for compat; lowering is idempotent)."""
    return bashReadsSecret(cmd_low)


def _resolveState():
    """Resolve (state, explicit) for this hook.

    explicit is True ONLY when an executor-pinned task resolved. Resolution order:
      1. NINE_TO_FIVE_TASK_FILE -- absolute state-file path the executor exported.
      2. NINE_TO_FIVE_TASK_ID via the configured STATE_DIR.
      3. loadLatest() -- ONLY when an env var WAS set but failed to resolve (degraded, not a
         guess). When NEITHER env var is set at all, there is no run to guess at: in a
         concurrent/resumed session "the latest" task may not be the one this hook's tool call
         actually belongs to, which would enforce the WRONG task's hard_boundaries (BUG-012).
    Never raises; logs to stderr on a degrade so a silent fail-open is visible.
    """
    try:
        from state.task import TaskState
    except Exception:
        return None, False
    tfile = os.environ.get("NINE_TO_FIVE_TASK_FILE")
    if tfile:
        try:
            with open(tfile, encoding="utf-8") as fh:
                return TaskState(json.load(fh)), True
        except Exception as e:
            sys.stderr.write(f"hooks._resolveState: TASK_FILE load failed ({e}); falling back\n")
    tid = os.environ.get("NINE_TO_FIVE_TASK_ID")
    if tid:
        try:
            return TaskState.load(tid), True
        except Exception as e:
            sys.stderr.write(f"hooks._resolveState: load({tid}) failed ({e}); falling back to loadLatest\n")
    if not _envTaskRequested():
        return None, False
    try:
        return TaskState.loadLatest(), False
    except Exception:
        return None, False


def _boundarySetFor(state) -> set:
    """Universe/baseline boundary set from the pinned epoch or live config fallback.

    Prefers the PINNED epoch stored in task meta so a mid-run edit to config/sie_overrides
    cannot change what this run enforces. Falls back to live baseline for legacy tasks.
    Core-file protection is NOT included here -- that is handled by _buildBoundaries.
    """
    meta = getattr(state, "meta", {}) or {}
    ep = meta.get("epoch") or {}
    pinned = (ep.get("universe") or {}).get("hard_boundaries") or []
    base: list = [str(b) for b in pinned if b]
    for b in (list(getattr(config, "UNIVERSE_DEFAULT_HARD_BOUNDARIES", ()) or ()) if config
              else [".env", ".git", "venv", "state/tasks"]):
        if b not in base:
            base.append(b)
    # Anchor the task store to the install root so a target repo's own state/tasks/
    # dir is never falsely blocked (only 9to5's own run state is protected).
    try:
        anchored = str((config.PROJECT_ROOT / "state" / "tasks")) if config else None
    except Exception:
        anchored = None
    if anchored:
        out: set = set()
        for b in base:
            norm = str(b).replace("/", "\\").lower().strip("\\")
            out.add(anchored if norm in ("state\\tasks", "state/tasks") else b)
        return out
    return set(base)


def _coreLockFor(state):
    """Return (allow_core, core_files) preferring the pinned epoch over live config."""
    meta = getattr(state, "meta", {}) or {}
    ep = meta.get("epoch")
    if ep:
        allow_core = bool((ep.get("config_knobs") or {}).get("SELFMOD_ALLOW_CORE", False))
        core_files = tuple(ep.get("core_protected_files") or ())
        if core_files:
            return allow_core, core_files
        return allow_core, tuple(getattr(config, "CORE_PROTECTED_FILES", ()) or ())
    return (bool(getattr(config, "SELFMOD_ALLOW_CORE", False)),
            tuple(getattr(config, "CORE_PROTECTED_FILES", ()) or ()))


def _buildBoundaries(state, env_requested: bool, explicit: bool) -> set:
    """Assemble the full boundary set: universe + baseline + optional core files."""
    boundaries = list(_boundarySetFor(state))
    # For legacy tasks with no pinned epoch, also pull in live universe.hard_boundaries.
    meta = getattr(state, "meta", {}) or {}
    if not (meta.get("epoch") or {}):
        universe = (state.meta.get("universe") if state else None) or {}
        for b in (universe.get("hard_boundaries") or []):
            b = str(b)
            if b and b not in boundaries:
                boundaries.append(b)
    # Add core loop files when self-referential OR when a run is active but its task
    # could not be trusted (env pinned a task but resolution fell back) -- fail CLOSED.
    allow_core, _core_files = _coreLockFor(state) if state else (
        bool(getattr(config, "SELFMOD_ALLOW_CORE", False)) if config else False,
        tuple(getattr(config, "CORE_PROTECTED_FILES", ()) or ()) if config
        else ("orchestrator.py", "main.py", "agents/hooks.py", "config.py"))
    if not allow_core and (
            (state and state.meta.get("is_self_referential")) or (env_requested and not explicit)):
        for c in (list(_core_files) if _core_files
                  else ["orchestrator.py", "main.py", "agents/hooks.py", "config.py"]):
            if c not in boundaries:
                boundaries.append(c)
    # Executor-injected context (NINE_TO_FIVE_HOOK_CTX): additive-only extra boundaries,
    # so the guard enforces the run's boundary set even when state resolution degrades.
    try:
        for b in (readHookCtx().get("boundaries") or []):
            b = str(b)
            if b and b not in boundaries:
                boundaries.append(b)
    except Exception:  # noqa: BLE001
        pass
    return set(boundaries)


def _parseBashGuardInput(tool_input: dict) -> tuple:
    """Parse Bash tool_input for the guard (patterns sourced from the shared taxonomy).

    Returns (bash_cmd, is_secret_block, should_exit0):
      is_secret_block=True: reads a secret file -- must block regardless of state.
      should_exit0=True: read-only non-secret command -- safe, caller should exit(0).
    """
    bash_cmd = tool_input.get("command", "") or ""
    if _bashReadsSecret(bash_cmd.lower()):
        return bash_cmd, True, False
    low = bash_cmd.lower()
    # PowerShell write cmdlets that create/overwrite/delete files -- not covered by the
    # shared isWritingBash() taxonomy (platform_core.runtime.action_risk targets POSIX-ish
    # write verbs/redirects/git; PowerShell cmdlets need their own token match) (B11).
    ps_write = re.search(
        r"\b(set-content|out-file|add-content|new-item|remove-item|clear-content)\b", low)
    # Downloaders that write a fetched file to disk (curl -o/-O, iwr -OutFile, wget) -- same
    # gap: these are network reads to the shared taxonomy but are file WRITES here (B11).
    downloader = (re.search(r"\bcurl\b[^\n]*\s-o\b", low)
                  or re.search(r"\biwr\b[^\n]*-outfile", low)
                  or re.search(r"\bwget\b", low))
    if not (isWritingBash(bash_cmd) or ps_write or downloader):
        return bash_cmd, False, True  # read-only -- safe
    return bash_cmd, False, False


def _blockAndExit(reason: str) -> None:
    """Alert (fire-and-forget local JSONL -- no network in the block path), write the reason
    to stderr, and exit(2) to block the tool call. The gateway bot tails guard_alerts.jsonl."""
    writeGuardAlert("self_modification_guard", reason)
    sys.stderr.write(reason + "\n")
    sys.exit(2)


def _shouldBlock(touched_paths: list, boundaries: set, bash_cmd: str = "") -> tuple:
    """True + matching boundary if any path (or bash_cmd target token) hits a boundary.

    Pass touched_paths=[""] with bash_cmd set to enable bash-token boundary hits when
    no explicit file_path is present (Bash tool case).
    """
    cmd_low = bash_cmd.lower() if bash_cmd else ""
    for path in (touched_paths or []):
        norm = str(path).replace("/", "\\").lower() if path else ""
        base = norm.rsplit("\\", 1)[-1] if norm else ""
        for b in boundaries:
            bn = str(b).replace("/", "\\").lower().strip("\\")
            if not bn:
                continue
            bbase = bn.rsplit("\\", 1)[-1]
            # Exact file, a file under a boundary dir, or a path ending in the boundary.
            hit = bool(norm and (norm == bn or norm.endswith("\\" + bn) or ("\\" + bn + "\\") in norm))
            # Absolute boundary (e.g. install-anchored task store): match files UNDER it.
            if not hit and norm and ":" in bn and norm.startswith(bn + "\\"):
                hit = True
            # Secret-family: a ".env" boundary also blocks .env.local / .env.production.
            if not hit and norm and bbase.startswith(".") and (
                    base == bbase or base.startswith(bbase + ".")):
                hit = True
            # Writing Bash command whose target IS a boundary file (real path-token match).
            if not hit and bash_cmd and _bashHitsBoundary(cmd_low, bbase):
                hit = True
            if hit:
                return True, str(b)
    return False, ""


def selfModificationGuard(data):
    """PreToolUse: block edits to hard boundaries and core loop files. Exits 2 to block; 0 otherwise."""
    bash_cmd = file_path = ""
    try:
        tool_name = data.get("tool_name", "")
        tool_input = data.get("tool_input", {}) or {}
        if tool_name in ("Edit", "Write", "MultiEdit"):
            file_path = tool_input.get("file_path", "") or ""
        elif tool_name == "Bash":
            bash_cmd, is_secret, safe = _parseBashGuardInput(tool_input)
            if is_secret:
                _blockAndExit("self_modification_guard: BLOCKED read of a secret file (.env family) "
                              "via Bash -- secrets are a hard boundary; read values through config.* "
                              "at runtime instead.")
            if safe:
                sys.exit(0)
        else:
            sys.exit(0)
        state, explicit = _resolveState()
        if state is None and not _envTaskRequested():
            sys.exit(0)
        boundaries = _buildBoundaries(state, _envTaskRequested(), explicit)
        # For Edit/Write/MultiEdit: check the explicit file path.
        # For Bash: pass [""] so _shouldBlock still runs the bash-token boundary check.
        touched = [file_path] if file_path else ([""] if bash_cmd else [])
        should_block, _ = _shouldBlock(touched, boundaries, bash_cmd)
        if should_block:
            _blockAndExit(f"self_modification_guard: BLOCKED edit to {file_path or bash_cmd} -- "
                          "it is a HARD BOUNDARY of this task's universe. Stay inside the allowed scope.")
        sys.exit(0)
    except SystemExit:
        raise
    except Exception as e:  # noqa: BLE001
        # FAIL CLOSED: guard protects hard boundaries. If it crashes while guarding an identified
        # write target, allowing the edit would silently defeat the boundary. Block instead.
        try:
            sys.stderr.write(f"self_modification_guard: internal error, failing closed: {e}\n")
        except Exception:  # noqa: BLE001
            pass
        sys.exit(2 if (file_path or bash_cmd) else 0)
