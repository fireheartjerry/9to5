"""Redacted logging and replay files for pre-execution council runs.

RUN/TEST: python -m pytest tests/planning/test_pre_execution_council.py

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  redact_council_text(text: Any) -> str
  slugify(text: str, limit: int=42) -> str
  CouncilRunLogger
DEPENDS-ON: config, platform_core.execution
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import json
import re
from dataclasses import asdict, is_dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

import config
from platform_core.execution.pre_execution import (
    mutateLegacyPath,
    openLegacyFile,
)

SECRET_PATTERNS = (
    re.compile(r"(?i)(api[_-]?key|token|secret|password)\s*[:=]\s*['\"]?[^'\"\s]+"),
    re.compile(r"(?i)\.env\s*[:=]\s*['\"]?[^'\"\s]+"),
    re.compile(r"(?i)AIza[0-9A-Za-z_\-]{20,}"),
    re.compile(r"(?i)sk-[0-9A-Za-z_\-]{20,}"),
)

SENSITIVE_RUNTIME_PATTERNS = (
    re.compile(r"(?i)--user-data-dir[=\s]+[^\s]+"),
    re.compile(r"(?i)--remote-debugging-port[=\s]+\d+"),
    re.compile(r"(?i)C:\\[^\n\r]*chatgpt_profile[^\s\n\r]*"),
    re.compile(r"(?i)C:\\Program Files\\Google\\Chrome\\Application\\chrome\.exe"),
    re.compile(r"(?i)(debug port|user data dir|profile path|chrome path|timeout override)[^.\n\r]*"),
)


def redact_council_text(text: Any) -> str:
    out = str(text or "")
    for pattern in SECRET_PATTERNS:
        out = pattern.sub("[REDACTED_SECRET]", out)
    for pattern in SENSITIVE_RUNTIME_PATTERNS:
        out = pattern.sub("[REDACTED_RUNTIME]", out)
    return out


def _safe_json(value: Any) -> Any:
    if is_dataclass(value):
        value = asdict(value)
    if isinstance(value, dict):
        return {str(k): _safe_json(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_safe_json(v) for v in value]
    if isinstance(value, tuple):
        return [_safe_json(v) for v in value]
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, str):
        return redact_council_text(value)
    return value


def slugify(text: str, limit: int = 42) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", text.lower()).strip("-")
    return (slug or "council")[:limit].strip("-") or "council"


class CouncilRunLogger:
    def __init__(self, *, run_id: str, task: str, output_dir: str | Path | None = None) -> None:
        base = Path(output_dir or config.PRE_EXECUTION_COUNCIL_OUTPUT_DIR)
        if not base.is_absolute():
            base = Path(config.PROJECT_ROOT) / base
        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        self.run_dir = base / f"{stamp}_{slugify(task)}_{run_id[:8]}"
        mutateLegacyPath(self.run_dir.mkdir,parents=True, exist_ok=True)
        self.transcript_jsonl_path = self.run_dir / "transcript.jsonl"
        self.transcript_md_path = self.run_dir / "transcript.md"
        self.brief_json_path = self.run_dir / "brief.json"
        self.brief_md_path = self.run_dir / "brief.md"
        self.metadata_path = self.run_dir / "metadata.json"

    def write_context(self, context_pack: Any) -> None:
        mutateLegacyPath((self.run_dir / "context_pack.json").write_text,
            json.dumps(_safe_json(context_pack), indent=2, ensure_ascii=False),
            encoding="utf-8",
        )

    def write_config(self, council_config: Any) -> None:
        mutateLegacyPath((self.run_dir / "config.json").write_text,
            json.dumps(_safe_json(council_config), indent=2, ensure_ascii=False),
            encoding="utf-8",
        )

    def write_metadata(self, metadata: dict[str, Any]) -> None:
        mutateLegacyPath(self.metadata_path.write_text,
            json.dumps(_safe_json(metadata), indent=2, ensure_ascii=False),
            encoding="utf-8",
        )

    def write_message(self, message: Any) -> None:
        with openLegacyFile(self.transcript_jsonl_path, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(_safe_json(message), ensure_ascii=False) + "\n")
        md = self._message_markdown(message)
        with openLegacyFile(self.transcript_md_path, "a", encoding="utf-8") as fh:
            fh.write(md + "\n\n")

    def write_brief(self, brief: Any, markdown: str) -> None:
        mutateLegacyPath(self.brief_json_path.write_text,
            json.dumps(_safe_json(brief), indent=2, ensure_ascii=False),
            encoding="utf-8",
        )
        mutateLegacyPath(self.brief_md_path.write_text,redact_council_text(markdown), encoding="utf-8")

    def _message_markdown(self, message: Any) -> str:
        data = _safe_json(message)
        warnings = data.get("warnings") or []
        warning_text = "\n".join(f"- WARNING {w.get('kind', 'warning')}: {w.get('detail', '')}" for w in warnings)
        return (
            f"## Turn {data.get('turn_index')} - {data.get('speaker')}\n\n"
            f"Permanent seat: {data.get('permanent_seat')}\n\n"
            f"Temporary hats: {', '.join(data.get('temporary_hats') or []) or '(none)'}\n\n"
            f"{redact_council_text(data.get('content', ''))}\n\n"
            f"{warning_text}".rstrip()
        )
