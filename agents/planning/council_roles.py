@dataclass(frozen=True)
class CouncilSeatSpec:
    name: str
    provider: str
    permanent_role: str
    strengths: tuple[str, ...]
    default_enabled: bool = True


@dataclass(frozen=True)
class TemporaryHat:
    name: str
    instruction: str
    keywords: tuple[str, ...] = field(default_factory=tuple)


