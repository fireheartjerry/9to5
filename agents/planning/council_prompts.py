def compact_protocol_block(enabled: bool = True) -> str:
    if not enabled:
        return ""
    return "Compact protocol tags, encouraged but not mandatory:\n" + " ".join(COMPACT_PROTOCOL_TAGS)


def make_continuity_token(
    *,
    run_id: str,
    seat: str,
    turn: int,
    prompt_version: str = PROMPT_VERSION,
) -> dict[str, Any]:
    """Build a small structured continuity marker for one live-seat turn."""
    return {
        "run": str(run_id or "")[:8],
        "seat": str(seat or ""),
        "turn": int(turn),
        "pv": str(prompt_version or PROMPT_VERSION),
    }


def format_continuity_line(token: dict[str, Any]) -> str:
    """Serialize a continuity token as a single required reply line."""
    return f"{CONTINUITY_TAG} {json.dumps(token, separators=(',', ':'), sort_keys=True)}"


def continuity_instruction(token: dict[str, Any]) -> str:
    """Prompt block: require structured continuity echo, not a free-text canary word."""
    line = format_continuity_line(token)
    return (
        "Required structured continuity line — put this exact line first in your reply, "
        "then your council message:\n"
        f"{line}\n"
        "Missing or mismatched [CONTINUITY] means context continuity is degraded, not proof of hallucination."
    )


def parse_continuity_token(text: str) -> dict[str, Any] | None:
    """Extract the first [CONTINUITY] JSON object from a reply, if present."""
    match = _CONTINUITY_RE.search(text or "")
    if not match:
        return None
    try:
        raw = json.loads(match.group(1))
    except json.JSONDecodeError:
        return None
    return raw if isinstance(raw, dict) else None


def check_continuity(text: str, expected: dict[str, Any]) -> tuple[bool, str]:
    """Return (ok, detail). Missing/mismatched token => continuity degraded."""
    found = parse_continuity_token(text)
    if found is None:
        return False, "missing [CONTINUITY] structured marker"
    for key in ("run", "seat", "turn", "pv"):
        if str(found.get(key, "")) != str(expected.get(key, "")):
            return False, f"mismatched [CONTINUITY].{key}: got {found.get(key)!r} expected {expected.get(key)!r}"
    return True, "ok"


def build_turn_prompt(
    *,
    task: str,
    context_pack_summary: str,
    seat_name: str,
    temporary_roles: Iterable[str],
    recent_transcript: str,
    compact_state: str,
    unresolved_disagreements: str,
    working_brief: str,
    compact_protocol: bool = True,
    anti_filler: bool = True,
) -> str:
    rules = [
        "Do not repeat prior material unless compressing, correcting, or synthesizing it.",
        "Do not merely agree.",
        "Add concrete value.",
        "Prefer claims, risks, questions, data targets, constraints, action items, corrections, or synthesis.",
        "Stay pre-execution. Do not implement.",
    ]
    if anti_filler:
        rules.insert(1, "Do not be polite. Do not write filler.")
    return f"""Task:
{task}

Context pack summary:
{context_pack_summary}

Your permanent seat:
{seat_name}

Your temporary role for this run:
{", ".join(temporary_roles) or "(none)"}

Recent transcript:
{recent_transcript or "(none yet)"}

Current compact council state:
{compact_state or "(empty)"}

Unresolved disagreements:
{unresolved_disagreements or "(none yet)"}

Current working brief:
{working_brief or "(empty)"}

{compact_protocol_block(compact_protocol)}

Produce the most valuable next council message.

Rules:
- """ + "\n- ".join(rules)
