"""Stage D (§7 D): record elaboration fitness so SIE promotion can later learn which stance
wins for which goal-family.

HONEST SEAM: there is no existing 'elaboration outcome' ledger channel. This records via an
injected store_fn (default: a thin wrapper over memory.retrievals.core.embed_and_store). The
orchestrator-loop call-site (post-run, when clean_run is known) is a documented follow-up.
Degrades to a no-op when SIE is halted or the store is unavailable. Never raises.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  recordElaborationOutcome(goal: str, stance: str, *, clean_run: bool, run_id: str='', spec: str='', metadata: dict | None=None, store_fn=None) -> bool  -- Persist the approved spec, selection evidence, and eventual run outcome.
DEPENDS-ON: config, memory.experience_content, memory.ledger, memory.retrievals
SIDE-EFFECTS: writes to experience ledger (best-effort) via store_fn
RUN/TEST: python -m pytest tests/evolution/test_evolution_evolver.py tests/evolution/test_evolver_prompts.py tests/orchestration/test_elaborator_evolve.py
"""
from __future__ import annotations

import config

LOG = config.getLogger("elaborator.evolve")


def _default_store(goal: str, stance: str, clean_run: bool, *, run_id: str = "",
                   spec: str = "", metadata: dict | None = None) -> bool:
    """Store a retrievable synthetic subtask containing the approved spec and outcome."""
    from memory import experience_content
    from memory.ledger import subtasks
    from memory.retrievals import core

    run_id = run_id or "elaboration"
    st_id = "__elaboration__"
    title = f"elaboration[{stance}] {'clean' if clean_run else 'replanned'}: {goal[:180]}"
    st = {"subtask_id": st_id, "title": title, "status": "done" if clean_run else "partial",
          "verify_result": {"passed": clean_run}, "session": {"summary": spec}}
    if not subtasks.record_subtask(run_id, st):
        return False
    outcome = {"stance": stance, "clean_run": clean_run, **(metadata or {})}
    experience_content.recordSolutionContent(
        run_id, st_id, solution_content=spec or goal, post_mortem=str(outcome), importance=1.0,
        model_id=None,
    )
    return bool(core.embed_and_store(run_id, st_id, goal, title=title, verify_passed=clean_run))


def recordElaborationOutcome(goal: str, stance: str, *, clean_run: bool, run_id: str = "",
                             spec: str = "", metadata: dict | None = None, store_fn=None) -> bool:
    """Persist the approved spec, selection evidence, and eventual run outcome."""
    if getattr(config, "SIE_KILL_SWITCH", False):
        return False
    store_fn = store_fn or _default_store
    try:
        try:
            return bool(store_fn(goal, stance, clean_run, run_id=run_id, spec=spec,
                                 metadata=metadata or {}))
        except TypeError:  # compatibility with existing injected three-argument seams
            return bool(store_fn(goal, stance, clean_run))
    except Exception:  # noqa: BLE001  -- best-effort; never block
        LOG.info("elaboration-outcome record failed; skipping")
        return False
