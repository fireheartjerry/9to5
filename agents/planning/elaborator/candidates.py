"""Elaboration candidate pipeline (§7 A'/A/B): adaptive best-of-N + portfolio selection.

Pure orchestration over injected seams (a generator fn and a weight fn) so it is fully
offline-testable. The portfolio optimizer is used only as an optional selection backend and
falls back to a plain max()-by-weight sort.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  budgetFor(goal: str, *, is_vague: bool, precedent_hits: int, max_n: int) -> int  -- §7 A': precise goal -> 1
  generate(goal: str, work_dir, *, n: int, gen_fn) -> list[dict]  -- Call gen_fn(goal, work_dir, stance) for the first n stances.
  meritWeight(candidate: dict, *, groundedness: float=0.0, precedent: float=0.0, predicted: float=0.0, elevated: int=0) -> float  -- §7 B weight: predicted_success + groundedness + precedent - 0.5*elevated.
  selectBest(candidates: list[dict], *, weight_fn, use_optimizer: bool=False) -> 'dict | None'  -- §7 B: return the winning candidate by weight_fn
DEPENDS-ON: config, platform_core.orchestration
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_elaborator_candidates.py
"""
from __future__ import annotations

import config

LOG = config.getLogger("elaborator.candidates")

STANCES = ("minimal-scope", "thorough", "risk-averse", "conservative", "exhaustive")


def budgetFor(goal: str, *, is_vague: bool, precedent_hits: int, max_n: int) -> int:
    """§7 A': precise goal -> 1; vague + thin precedent -> more candidates."""
    if not is_vague:
        return 1
    n = 2 + (2 if precedent_hits == 0 else 0) + 1
    return max(1, min(max_n, n))


def generate(goal: str, work_dir, *, n: int, gen_fn) -> list[dict]:
    """Call gen_fn(goal, work_dir, stance) for the first n stances."""
    out: list[dict] = []
    for stance in STANCES[:max(1, n)]:
        out.append({"id": stance, "stance": stance, "spec": gen_fn(goal, work_dir, stance)})
    return out


def meritWeight(candidate: dict, *, groundedness: float = 0.0, precedent: float = 0.0,
                predicted: float = 0.0, elevated: int = 0) -> float:
    """§7 B weight: predicted_success + groundedness + precedent - 0.5*elevated."""
    return float(predicted) + float(groundedness) + float(precedent) - 0.5 * int(elevated)


def selectBest(candidates: list[dict], *, weight_fn, use_optimizer: bool = False) -> "dict | None":
    """§7 B: return the winning candidate by weight_fn. Optional portfolio-optimizer backend;
    falls back to max()-by-weight on any error or when disabled."""
    if not candidates:
        return None
    if use_optimizer:
        try:
            from platform_core.orchestration import portfolio_optimizer
            sel = portfolio_optimizer.optimize(candidates, weight_fn=weight_fn)
            ids = list(getattr(sel, "selected_candidate_ids", []) or [])
            if ids:
                by_id = {c["id"]: c for c in candidates}
                chosen = [by_id[i] for i in ids if i in by_id]
                if chosen:
                    return max(chosen, key=weight_fn)
        except Exception:  # noqa: BLE001  -- optimizer optional; fall back
            LOG.info("portfolio optimize unavailable; using max-weight sort")
    return max(candidates, key=weight_fn)
