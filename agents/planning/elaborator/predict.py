"""World-model lookahead (§7 B'): predict the executor's immediate consequence of a spec.

One shallow (1-step) brain call, grounded on the real repo snapshot. Advisory only -- the
predicted_success is a term in the candidate weight, never a hard gate. Never raises; returns
a neutral 0.5 on any failure so a bad prediction can at worst mis-rank, not block. Scoped tight
(1 step, re-synced to real state) to bound world-model drift.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  predictOutcome(spec_body, work_dir, *, chat=None) -> dict  -- {likely_files, likely_failure, predicted_success}
DEPENDS-ON: config, knowledge, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_elaborator_predict.py
"""
from __future__ import annotations

import config
import knowledge
import llm_io

LOG = config.getLogger("elaborator.predict")

_NEUTRAL = 0.5

PREDICT_SYSTEM = (
    "You predict the IMMEDIATE consequence of an engineer executing the FIRST step of an "
    "elaborated spec. Do NOT plan the whole task -- only the first action. Output JSON ONLY: "
    '{"likely_files": ["<real files that would change first>"], "likely_failure": '
    '"<the single most likely failure mode, or none>", "predicted_success": <0.0-1.0 '
    "probability the first step goes cleanly>}."
)


def _clamp(v) -> float:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return _NEUTRAL
    return max(0.0, min(1.0, f))


def predictOutcome(spec_body: str, work_dir, *, chat=None) -> dict:
    """One-step lookahead. Never raises; neutral 0.5 on any failure."""
    user = f"Elaborated spec:\n{spec_body[:4000]}\n\nPredict the first-step outcome as JSON."
    try:
        if chat is not None:
            resp = llm_io.callChat(chat, PREDICT_SYSTEM, user, act="predict", want_json=True)
        else:
            resp = llm_io.chat(knowledge.injectCapabilities(PREDICT_SYSTEM), user,
                               act="predict", want_json=True)
        data = llm_io.responseJson(resp)
    except Exception:  # noqa: BLE001  -- advisory; never block
        data = None
    if not isinstance(data, dict):
        return {"likely_files": [], "likely_failure": "unknown", "predicted_success": _NEUTRAL}
    return {
        "likely_files": [str(x) for x in (data.get("likely_files") or []) if x],
        "likely_failure": str(data.get("likely_failure") or "unknown"),
        "predicted_success": _clamp(data.get("predicted_success", _NEUTRAL)),
    }
