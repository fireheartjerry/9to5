"""Case-based-reasoning grounding (§3d): inject similar past (goal->outcome) exemplars.

Reuses the existing embedding index seam (memory.retrievals.core). Best-effort: returns ""
on cold start / any error so grounding degrades cleanly.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  precedentBlock(goal, *, k=3, retrieve_fn=None, fail_fn=None) -> str  -- precedent prompt block or ""
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_elaborator_precedent.py
"""
from __future__ import annotations

import config

LOG = config.getLogger("elaborator.precedent")


def _default_retrieve(goal, k=3):
    from memory.retrievals import core
    return core.retrieve(goal, k=k)


def _default_fail(goal, k=2):
    from memory.retrievals import core
    return core.retrieve_failures(goal, k=k)


def precedentBlock(goal: str, *, k: int = 3, retrieve_fn=None, fail_fn=None) -> str:
    """Top-k similar past successes + failures as a compact prompt block, or "" when nothing
    is retrievable. Seams injectable for offline tests."""
    retrieve_fn = retrieve_fn or _default_retrieve
    fail_fn = fail_fn or _default_fail
    lines: list[str] = []
    try:
        for h in (retrieve_fn(goal, k=k) or []):
            t = str(h.get("title") or "").strip()
            if t:
                lines.append(f"- past success: {t} (score {float(h.get('score') or 0.0):.2f})")
    except Exception:  # noqa: BLE001  -- best-effort
        pass
    try:
        for h in (fail_fn(goal, k=2) or []):
            t = str(h.get("title") or "").strip()
            if t:
                lines.append(f"- avoid (past failure): {t}")
    except Exception:  # noqa: BLE001
        pass
    if not lines:
        return ""
    return "PRECEDENT (how similar goals resolved before):\n" + "\n".join(lines)
