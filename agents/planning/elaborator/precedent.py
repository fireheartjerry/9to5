"""Case-based-reasoning grounding (§3d): inject similar past (goal->outcome) exemplars.

Reuses the existing embedding index seam (memory.retrievals.core). Best-effort: returns ""
on cold start / any error so grounding degrades cleanly.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  precedentEvidence(goal: str, *, k: int=3, retrieve_fn=None, fail_fn=None) -> dict  -- Return a compact evidence block plus factual hit counts for downstream scoring.
  precedentBlock(goal: str, *, k: int=3, retrieve_fn=None, fail_fn=None) -> str  -- Compatibility wrapper returning only the prompt block.
DEPENDS-ON: config, memory.retrievals.core, platform_core.core.best_effort
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_elaborator_precedent.py
"""
from __future__ import annotations

import config
from platform_core.core.best_effort import best_effort

LOG = config.getLogger("elaborator.precedent")


def _default_retrieve(goal, k=3):
    from memory.retrievals import core
    return core.retrieve_content(goal, k=k)


def _default_fail(goal, k=2):
    from memory.retrievals import core
    return core.retrieve_failures(goal, k=k)


def _excerpt(hit: dict, limit: int = 420) -> str:
    """Return compact outcome evidence, never an unbounded prior answer dump."""
    text = str(hit.get("solution_content") or hit.get("post_mortem") or "").strip()
    return " ".join(text.split())[:limit]


def precedentEvidence(goal: str, *, k: int = 3, retrieve_fn=None, fail_fn=None) -> dict:
    """Return a compact evidence block plus factual hit counts for downstream scoring."""
    retrieve_fn = retrieve_fn or _default_retrieve
    fail_fn = fail_fn or _default_fail
    lines: list[str] = []
    success_hits = failure_hits = 0
    with best_effort("elaborator.precedent.retrieve", log=LOG):
        for h in (retrieve_fn(goal, k=k) or []):
            t = str(h.get("title") or "").strip()
            if t:
                success_hits += 1
                detail = _excerpt(h)
                suffix = f" Outcome: {detail}" if detail else ""
                lines.append(f"- past success: {t} (score {float(h.get('score') or 0.0):.2f}).{suffix}")
    with best_effort("elaborator.precedent.failures", log=LOG):
        for h in (fail_fn(goal, k=2) or []):
            t = str(h.get("title") or "").strip()
            if t:
                failure_hits += 1
                detail = _excerpt(h)
                suffix = f" Failure evidence: {detail}" if detail else ""
                lines.append(f"- avoid (past failure): {t}.{suffix}")
    return {"block": ("PRECEDENT (how similar goals resolved before):\n" + "\n".join(lines)) if lines else "",
            "success_hits": success_hits, "failure_hits": failure_hits}


def precedentBlock(goal: str, *, k: int = 3, retrieve_fn=None, fail_fn=None) -> str:
    """Compatibility wrapper returning only the prompt block."""
    return precedentEvidence(goal, k=k, retrieve_fn=retrieve_fn, fail_fn=fail_fn)["block"]
