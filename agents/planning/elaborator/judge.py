"""Layer-2 semantic judge (§4): advisory quality review of an elaborated spec.

Reuses the adversary review seam with review_type='elaboration'. Advisory only -- it can
annotate a spec but never blocks. Never raises.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  judgeElaboration(spec_body, goal, *, chat=None) -> dict  -- adversary review dict (verdict/concerns/...)
DEPENDS-ON: config, agents.review.adversary_review
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_elaborator_judge.py
"""
from __future__ import annotations

import config
from agents.review import adversary_review

LOG = config.getLogger("elaborator.judge")


def judgeElaboration(spec_body: str, goal: str, *, chat=None) -> dict:
    """Advisory semantic judge of an elaborated spec. Returns the review dict; on any failure
    returns {'verdict': 'unreviewed'}."""
    try:
        return adversary_review.review(
            "elaboration", "elaboration-quality", spec_body,
            ollama_chat=chat, goal=goal, review_type="elaboration",
        )
    except Exception:  # noqa: BLE001  -- advisory; never block elaboration
        LOG.info("elaboration judge unavailable; skipping", exc_info=False)
        return {"verdict": "unreviewed"}
