"""Calibrated, distribution-free uncertainty for elaboration (§3b/§7.5).

Deliberately NOT the model's self-reported confidence (RLHF miscalibrates that). Risk comes
from objective proxies: did path-verify confirm the paths, does precedent corroborate, how
tight is the candidate score spread.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  riskBand(*, path_verified, precedent_support) -> str  -- 'low' | 'elevated'
  runUncertainty(*, elevated_count, objective_spread, precedent_hits, threshold=2) -> dict
DEPENDS-ON: (none)
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/orchestration/test_elaborator_uncertainty.py
"""
from __future__ import annotations


def riskBand(*, path_verified: bool, precedent_support: bool) -> str:
    """'low' only when paths verified AND precedent corroborates; else 'elevated'."""
    return "low" if (path_verified and precedent_support) else "elevated"


def runUncertainty(*, elevated_count: int, objective_spread: float, precedent_hits: int,
                   threshold: int = 2) -> dict:
    """Aggregate run-level uncertainty -> {'defer': bool, 'score': int, 'reasons': [str]}."""
    reasons: list[str] = []
    if elevated_count >= threshold:
        reasons.append(f"{elevated_count} elevated-risk assumptions")
    if objective_spread < 0.05 and precedent_hits == 0:
        reasons.append("no good candidate separation and no precedent")
    return {"defer": bool(reasons), "score": elevated_count, "reasons": reasons}
