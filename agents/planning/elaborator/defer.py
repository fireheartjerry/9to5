"""Uncertainty-aware deferral (§7.5): escalate a too-uncertain elaboration to a larger model.

HONEST SEAM: there is no reusable Claude transport in llm_io (the executor shells out via
runClaude). So this module owns the DECISION and calls an injected escalate_fn; the default
returns None -> keep the local spec. This matches the spec's 'degrades to keep best local
candidate' contract. Never raises.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  maybeDefer(local_spec: str, goal: str, uncertainty: dict, *, escalate_fn=None) -> str  -- When deferral is enabled AND uncertainty says defer, try escalate_fn(goal)
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_elaborator_defer.py
"""
from __future__ import annotations

import config

LOG = config.getLogger("elaborator.defer")


def _default_escalate(goal: str):
    """No reusable Claude transport exists; default keeps local. A follow-up can wire a real
    higher-capability call here (e.g. the executor's Claude path)."""
    return None


def maybeDefer(local_spec: str, goal: str, uncertainty: dict, *, escalate_fn=None) -> str:
    """When deferral is enabled AND uncertainty says defer, try escalate_fn(goal); use its
    result only if non-empty, else keep local_spec. Never raises."""
    if not getattr(config, "ELABORATOR_DEFER_ENABLED", False):
        return local_spec
    if not (uncertainty or {}).get("defer"):
        return local_spec
    escalate_fn = escalate_fn or _default_escalate
    try:
        big = escalate_fn(goal)
    except Exception:  # noqa: BLE001  -- degrade to local on any escalation failure
        LOG.info("elaboration deferral failed; keeping local spec")
        return local_spec
    return big if (big and str(big).strip()) else local_spec
