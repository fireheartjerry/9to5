"""Elaborator (Step 0.5) -- Ollama expands the raw goal into a buildable spec.

This is an Orchestrator-brain step: it runs entirely on the local model and
produces the text a human approves before the autonomous run begins.

R5: this module is a pure prompt builder. The Ollama client, retry/backoff, and
extraction live in ``llm_io`` (the ONE seam); ``chat`` is injectable so tests and
dry-runs drive elaboration offline. The old raw ``resp.get('message')`` extraction
(the pydantic-vs-dict incident class) is gone -- extraction goes through
``llm_io.responseText`` / ``llm_io.responseJson``.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  elaborate(goal_raw: str, work_dir: str | None=None, chat=None) -> str  -- Return the elaborated specification for ``goal_raw`` (never raises
  extractUniverse(goal_raw: str, goal_elaborated: str, work_dir: str, chat=None) -> dict  -- Extract the operating universe (scope boundary) from the goal (with safe defaults).
DEPENDS-ON: config, knowledge, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_orch_core_bugs.py tests/slow/test_simulation_core.py
"""
from __future__ import annotations

import re

import config
import knowledge
import llm_io

from . import candidates, defer, escalate, judge, path_verify, precedent, predict, schema, self_review, uncertainty
from .grounding import isVagueGoal, repoContext, vagueGoalBundle

LOG = config.getLogger("elaborator")


def _chat(system: str, user: str, *, act: str, want_json: bool = False, chat=None):
    """One brain call through the seam. ``chat`` is an optional injected callable
    ``(system, user, *, act=..., want_json=...) -> resp`` (e.g. the orchestrator's
    ``_ollamaChat`` or a test double); default is the blessed ``llm_io.chat``.
    Returns the raw response or None -- the caller degrades instead of crashing the
    run before it even starts (this is the very first brain touch)."""
    if chat is not None:
        return llm_io.callChat(chat, system, user, act=act, want_json=want_json)
    return llm_io.chat(knowledge.injectCapabilities(system), user, act=act, want_json=want_json)


def _fallbackSpec(goal_raw: str) -> str:
    """A minimal but valid spec so the run proceeds even if elaboration is unavailable."""
    return (f"# Objective\n{goal_raw}\n\n"
            "# Deliverables\n- Implement the goal exactly as stated.\n\n"
            "# Acceptance Criteria\n- The goal is satisfied and verified.\n\n"
            "# Constraints\n- Keep changes surgical and on-scope.\n\n"
            "# Assumptions\n- (elaboration brain was unavailable; using the raw goal)\n")


_PATH_RE = re.compile(r"[A-Za-z0-9_./-]+\.(?:py|js|ts|md|json|txt|ya?ml)")


def _groundedness(spec: str, work_dir) -> float:
    """Fraction of file-path-like tokens in the spec that actually exist under work_dir.
    Deterministic, no LLM. 0.0 when no paths mentioned or no work_dir."""
    if not work_dir or not spec:
        return 0.0
    paths = _PATH_RE.findall(spec)
    if not paths:
        return 0.0
    split = path_verify.splitVerified(paths, work_dir)
    return len(split["allowed_paths"]) / len(paths)


ELABORATOR_SYSTEM = (
    "You are the Elaborator for 9TO5, an autonomous engineering orchestrator. "
    "Expand the user's raw goal into a precise, buildable specification a coding agent "
    "can execute without further questions. Use markdown. Include these sections: "
    "Objective; Deliverables (with exact file paths); Acceptance Criteria; "
    "Constraints; Assumptions. Be concrete and concise. Output ONLY the specification, "
    "no preamble, no questions. "
    "CRITICAL GROUNDING RULE: an ACTUAL REPOSITORY SNAPSHOT (package/directory map + recent "
    "git history) is provided in the user message. Every file path you name MUST be a real "
    "path from that snapshot, or a plausible sibling of one. This is the real project -- do "
    "NOT invent placeholder or template paths (e.g. /path/to/app, src/features/, "
    "src/components/, com/example/*.java, build.gradle, Makefile) and do NOT assume a "
    "language, framework, or layout the snapshot does not actually show."
)

ELABORATOR_SYSTEM_5W3H = (
    ELABORATOR_SYSTEM
    + " STRUCTURED ELABORATION: before writing the sections, reason briefly through these "
    "dimensions to turn even a terse goal into a complete spec -- Why (the motivation / "
    "problem being solved), Who (which code areas and owners this touches), Where (the real "
    "repo areas and modules from the snapshot), How (the intended approach), What (the "
    "concrete deliverables). Use these dimensions to fill gaps the raw goal left implicit, "
    "then produce the five sections as specified above. Keep the final output to those five "
    "sections; the dimensional reasoning informs them but need not appear as separate headers."
)


def _bestOfN(goal_raw: str, work_dir, user: str, system: str, chat) -> str:
    """§7 A'/A/B: generate N stance-varied candidates, select the most grounded."""
    n = candidates.budgetFor(goal_raw, is_vague=isVagueGoal(goal_raw),
                             precedent_hits=0, max_n=int(config.ELABORATOR_CANDIDATES_MAX))
    if n <= 1:
        resp = _chat(system, user, act="elaborate", chat=chat)
        return llm_io.responseText(resp).strip()

    def gen_fn(goal, wd, stance):
        stance_system = f"{system} Adopt a {stance} stance toward scope and risk."
        r = _chat(stance_system, user, act="elaborate", chat=chat)
        return llm_io.responseText(r).strip()

    cands = [c for c in candidates.generate(goal_raw, work_dir, n=n, gen_fn=gen_fn) if c["spec"]]
    if not cands:
        return ""
    predicted: dict = {}
    if config.ELABORATOR_LOOKAHEAD_ENABLED:
        for c in cands:
            predicted[c["id"]] = predict.predictOutcome(c["spec"], work_dir, chat=chat)["predicted_success"]

    def _weight(c):
        return candidates.meritWeight(
            c,
            groundedness=_groundedness(c["spec"], work_dir),
            predicted=predicted.get(c["id"], 0.0),
        )

    best = candidates.selectBest(cands, weight_fn=_weight,
                                 use_optimizer=bool(config.PORTFOLIO_OPTIMIZER_ENABLED))
    return best["spec"] if best else cands[0]["spec"]


def elaborate(goal_raw: str, work_dir: str | None = None, chat=None) -> str:
    """Return the elaborated specification for ``goal_raw`` (never raises -- degrades to a
    minimal spec built from the raw goal if the brain is unavailable). ``work_dir`` grounds
    the spec in the REAL repository structure so file paths are not hallucinated. ``chat`` is
    an optional injected ``(system, user, *, act=..., want_json=...) -> resp`` callable (e.g.
    the orchestrator's ``_ollamaChat`` or a test double) used instead of the blessed
    ``llm_io.chat``, so a dry-run / test can drive elaboration offline."""
    LOG.info("Elaborating raw goal via %s", config.OLLAMA_MODEL)
    user = f"Raw goal:\n{goal_raw}\n\nProduce the elaborated specification."
    ctx = repoContext(work_dir)
    if ctx:
        user = ("ACTUAL REPOSITORY SNAPSHOT (ground EVERY file path in this real structure):\n"
                f"{ctx}\n\n---\n\n" + user)
    if config.ELABORATOR_EXCELLENCE_ENABLED and isVagueGoal(goal_raw):
        bundle = vagueGoalBundle(work_dir)
        if bundle:
            user += ("\n\nSTATE OF THE REPO (name real files from here for a broad goal):\n"
                     f"{bundle}\n")
    if config.ELABORATOR_EXCELLENCE_ENABLED and config.ELABORATOR_PRECEDENT_ENABLED:
        pb = precedent.precedentBlock(goal_raw)
        if pb:
            user += "\n\n" + pb + "\n"
    system = ELABORATOR_SYSTEM_5W3H if config.ELABORATOR_EXCELLENCE_ENABLED else ELABORATOR_SYSTEM
    if config.ELABORATOR_EXCELLENCE_ENABLED and config.ELABORATOR_BESTOFN_ENABLED:
        out = _bestOfN(goal_raw, work_dir, user, system, chat)
    else:
        resp = _chat(system, user, act="elaborate", chat=chat)
        out = llm_io.responseText(resp).strip()
    if not out:
        LOG.warning("elaboration unavailable after retries; using raw goal as spec")
        return _fallbackSpec(goal_raw)
    if config.ELABORATOR_EXCELLENCE_ENABLED:
        inferred = self_review.reviewAssumptions(out, goal_raw, chat=chat)
        if inferred:
            out = f"{out}\n\n# Inferred Assumptions\n{inferred}\n"
    if config.ELABORATOR_EXCELLENCE_ENABLED and config.SOCIETY_ENABLED:
        verdict = judge.judgeElaboration(out, goal_raw, chat=chat)
        if verdict.get("verdict") == "challenged" and verdict.get("concerns"):
            note = "; ".join(str(c) for c in verdict["concerns"])
            out = f"{out}\n\n# Review Note\n{note}\n"
    if config.ELABORATOR_EXCELLENCE_ENABLED and config.ELABORATOR_DEFER_ENABLED:
        elevated = out.count("Inferred:")
        unc = uncertainty.runUncertainty(elevated_count=elevated, objective_spread=1.0,
                                         precedent_hits=0)
        out = defer.maybeDefer(out, goal_raw, unc,
                               escalate_fn=lambda g: escalate.escalateToModel(g, chat=chat))
    return out


UNIVERSE_SYSTEM = (
    "You define the operating UNIVERSE for an autonomous engineering run. The universe is about "
    "PRECISION, not permission: the agent may freely create or modify whatever files the goal needs "
    "-- the universe just keeps its edits surgical and on-scope so they don't sprawl into unrelated "
    "code. "
    'Respond with JSON ONLY: {"description": "<one line>", "allowed_paths": ["<files/folders the work '
    'is EXPECTED to focus on>"], "allowed_to_expand_to": ["<related code/deps it may also touch if '
    'needed>"], "hard_boundaries": ["<files/dirs that must NEVER be touched>"]}. '
    "allowed_paths = the expected focus area (a precision hint, NOT a hard allowlist -- creating or "
    "editing other in-scope files to achieve the goal is fine). hard_boundaries = the ONLY hard stop: "
    "secrets, VCS internals, virtualenvs, task state (e.g. .env, .git, venv, state/tasks). "
    "An ACTUAL REPOSITORY SNAPSHOT (package/directory map + recent git history) is provided in "
    "the user message: base allowed_paths on REAL directories/files from it (e.g. the real "
    "top-level packages), NEVER on invented placeholder paths like /path/to/app or src/features. "
    "Output ONLY the JSON."
)


def extractUniverse(goal_raw: str, goal_elaborated: str, work_dir: str, chat=None) -> dict:
    """Extract the operating universe (scope boundary) from the goal (with safe defaults)."""
    user = (f"Goal:\n{goal_raw}\n\nElaborated spec:\n{goal_elaborated[:2000]}\n\n"
            f"Working directory: {work_dir}\n")
    ctx = repoContext(work_dir)
    if ctx:
        user += ("\nACTUAL REPOSITORY SNAPSHOT (base allowed_paths on these REAL paths):\n"
                 f"{ctx}\n")
    user += "\nReturn the universe JSON."
    resp = _chat(UNIVERSE_SYSTEM, user, act="universe", want_json=True, chat=chat)
    u = llm_io.responseJson(resp)
    if not isinstance(u, dict):
        if resp is not None:
            LOG.warning("extractUniverse parse failed; using defaults")
        u = {}
    u["description"] = str(u.get("description") or goal_raw[:200])
    u["allowed_paths"] = [str(x) for x in (u.get("allowed_paths") or []) if x] or [work_dir]
    u["allowed_to_expand_to"] = [str(x) for x in (u.get("allowed_to_expand_to") or []) if x]
    hb = [str(x) for x in (u.get("hard_boundaries") or []) if x]
    for d in config.UNIVERSE_DEFAULT_HARD_BOUNDARIES:   # always enforce the baseline boundaries
        if d not in hb:
            hb.append(d)
    u["hard_boundaries"] = hb
    if config.ELABORATOR_EXCELLENCE_ENABLED:
        ok, errs = schema.validateUniverse(u)
        if not ok:
            LOG.info("universe schema_validity=fail: %s", "; ".join(errs))
        split = path_verify.splitVerified(u["allowed_paths"], work_dir)
        u["allowed_paths"] = split["allowed_paths"] or [work_dir]
        u["unverified_paths"] = split["unverified_paths"]
    return u
