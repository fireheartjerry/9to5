"""§7.5 escalation transport: re-elaborate a goal with a MORE CAPABLE model.

ReDAct-style deferral is 'ask a larger model', not specifically Claude. This reuses the
existing llm_io seam with a configured escalation model (config.ELABORATOR_DEFER_MODEL).
Empty model => "" (keep local). Never raises.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  escalateToModel(goal, *, chat=None) -> str  -- higher-capability elaboration, or "" when inert/unavailable
DEPENDS-ON: config, knowledge, llm_io, agents.planning.elaborator.core
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_elaborator_escalate.py
"""
from __future__ import annotations

import config
import knowledge
import llm_io

LOG = config.getLogger("elaborator.escalate")


def escalateToModel(goal: str, *, chat=None) -> str:
    """Re-elaborate `goal` with the configured escalation model. Returns "" when no model is
    configured (inert) or on any failure. `chat` injectable for offline tests."""
    model = str(getattr(config, "ELABORATOR_DEFER_MODEL", "") or "").strip()
    if not model and chat is None:
        return ""
    from .core import ELABORATOR_SYSTEM_5W3H
    user = f"Raw goal:\n{goal}\n\nProduce the elaborated specification."
    try:
        if chat is not None:
            resp = llm_io.callChat(chat, ELABORATOR_SYSTEM_5W3H, user, act="elaborate_defer")
        else:
            resp = llm_io.chat(knowledge.injectCapabilities(ELABORATOR_SYSTEM_5W3H), user,
                               act="elaborate_defer", model=model)
        return llm_io.responseText(resp).strip()
    except Exception:  # noqa: BLE001  -- degrade to local
        LOG.info("escalation model unavailable; keeping local spec")
        return ""
