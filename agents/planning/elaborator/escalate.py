"""§7.5 escalation transport: re-elaborate a goal with a MORE CAPABLE model.

ReDAct-style deferral is 'ask a larger model', not specifically Claude. This reuses the
existing llm_io seam with a configured escalation model (config.ELABORATOR_DEFER_MODEL).
Empty model => "" (keep local). Never raises.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  escalateToModel(goal: str, *, local_spec: str='', repo_context: str='', uncertainty: dict | None=None, chat=None) -> str  -- Re-elaborate with the same evidence, not a context-free second guess.
DEPENDS-ON: config, knowledge, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_elaborator_escalate.py
"""
from __future__ import annotations

import config
import knowledge
import llm_io

LOG = config.getLogger("elaborator.escalate")


def escalateToModel(goal: str, *, local_spec: str = "", repo_context: str = "",
                    uncertainty: dict | None = None, chat=None) -> str:
    """Re-elaborate with the same evidence, not a context-free second guess.

    An escalated model receives the grounded repository snapshot, the candidate that
    triggered deferral, and objective uncertainty reasons. Empty configuration remains
    a safe no-op rather than silently selecting a paid/cloud model.
    """
    model = str(getattr(config, "ELABORATOR_DEFER_MODEL", "") or "").strip()
    if not model and chat is None:
        return ""
    from .core import ELABORATOR_STRUCTURED_SYSTEM
    user = f"Raw goal:\n{goal}\n\nBest local elaboration to improve:\n{local_spec[:5000]}\n"
    if repo_context:
        user += f"\nACTUAL REPOSITORY SNAPSHOT:\n{repo_context[:7000]}\n"
    if uncertainty:
        user += f"\nDeferral evidence: {uncertainty.get('reasons') or []}\n"
    user += "\nReturn a corrected, more reliable structured elaboration."
    try:
        if chat is not None:
            resp = llm_io.callChat(chat, ELABORATOR_STRUCTURED_SYSTEM, user, act="elaborate_defer",
                                   want_json=True)
        else:
            resp = llm_io.chat(knowledge.injectCapabilities(ELABORATOR_STRUCTURED_SYSTEM), user,
                               act="elaborate_defer", model=model)
        return llm_io.responseText(resp).strip()
    except Exception:  # noqa: BLE001  -- degrade to local
        LOG.info("escalation model unavailable; keeping local spec")
        return ""
