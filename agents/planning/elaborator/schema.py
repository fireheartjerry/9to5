"""Elaborator output schema + Layer-1 deterministic validation and rendering.

Uses dataclasses + a manual validate() (repo convention), NOT pydantic, to avoid an
undeclared dependency. Layer 1 is cheap structural validation run before any LLM judgment.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  validateSpec(data: dict) -> tuple[bool, list[str]]  -- Return (ok, errors)
  normalizeSpec(data: dict) -> dict  -- Return a whitespace-normalized copy of a validated structured spec.
  renderSpec(data: dict) -> str  -- Render a normalized structured spec as reviewable Markdown.
  validateUniverse(data: dict) -> tuple[bool, list[str]]  -- Return (ok, errors)
DEPENDS-ON: config
SIDE-EFFECTS: none
RUN/TEST: python -m pytest tests/evolution/test_experience_schema.py tests/evolution/test_run_innovations_schema.py tests/human_nature/test_attention_schema.py tests/notifications/test_notification_schema.py tests/orchestration/test_elaborator_schema.py
"""
from __future__ import annotations

import config

_SPEC_STR_FIELDS = ("objective", "why", "who", "where", "how")
_SPEC_LIST_FIELDS = ("deliverables", "acceptance_criteria", "constraints")
# assumptions may legitimately be empty (a fully-grounded goal has no guesses)


def validateSpec(data: dict) -> tuple[bool, list[str]]:
    """Return (ok, errors). Non-empty required str fields; non-empty list fields of str."""
    errors: list[str] = []
    if not isinstance(data, dict):
        return False, ["spec is not a dict"]
    for f in _SPEC_STR_FIELDS:
        v = data.get(f)
        if not isinstance(v, str) or not v.strip():
            errors.append(f"missing/empty required field: {f}")
    for f in _SPEC_LIST_FIELDS:
        v = data.get(f)
        if not isinstance(v, list) or not v or not all(isinstance(x, str) for x in v):
            errors.append(f"missing/empty/mistyped list field: {f}")
    if not isinstance(data.get("assumptions", []), list):
        errors.append("assumptions must be a list")
    return (not errors), errors


def normalizeSpec(data: dict) -> dict:
    """Return a whitespace-normalized copy of a validated structured spec.

    The elaborator's public API deliberately remains Markdown, but its excellence path
    now uses this JSON-shaped contract internally. Keeping normalization here makes
    validation, rendering, repair, and telemetry agree on one representation.
    """
    out: dict = {}
    for field in _SPEC_STR_FIELDS:
        out[field] = " ".join(str(data.get(field) or "").split())
    for field in (*_SPEC_LIST_FIELDS, "assumptions"):
        out[field] = [" ".join(str(item).split()) for item in (data.get(field) or [])
                      if str(item).strip()]
    return out


def renderSpec(data: dict) -> str:
    """Render a normalized structured spec as reviewable Markdown.

    ``elaborate()`` has historically returned Markdown and humans edit that text in
    the launch flow. Rendering at the edge retains that stable public contract while
    preventing downstream stages from consuming an unvalidated model blob.
    """
    spec = normalizeSpec(data)

    def bullets(items: list[str]) -> str:
        return "\n".join(f"- {item}" for item in items) or "- None."

    context = "\n".join(
        f"- **{label}:** {spec[key]}"
        for key, label in (("why", "Why"), ("who", "Who"), ("where", "Where"), ("how", "How"))
    )
    return (
        f"# Objective\n{spec['objective']}\n\n"
        f"# Context\n{context}\n\n"
        f"# Deliverables\n{bullets(spec['deliverables'])}\n\n"
        f"# Acceptance Criteria\n{bullets(spec['acceptance_criteria'])}\n\n"
        f"# Constraints\n{bullets(spec['constraints'])}\n\n"
        f"# Assumptions\n{bullets(spec['assumptions'])}\n"
    )


def validateUniverse(data: dict) -> tuple[bool, list[str]]:
    """Return (ok, errors). Required keys present; baseline hard boundaries all included."""
    errors: list[str] = []
    if not isinstance(data, dict):
        return False, ["universe is not a dict"]
    if not isinstance(data.get("allowed_paths"), list) or not data.get("allowed_paths"):
        errors.append("missing/empty allowed_paths")
    hb = data.get("hard_boundaries")
    if not isinstance(hb, list):
        errors.append("hard_boundaries must be a list")
        hb = []
    for d in config.UNIVERSE_DEFAULT_HARD_BOUNDARIES:
        if d not in hb:
            errors.append(f"hard_boundaries missing baseline: {d}")
    return (not errors), errors
