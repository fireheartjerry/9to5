    def _known_limitations(self, seat_states: dict[str, dict[str, Any]]) -> list[str]:
        limitations = []
        for state in seat_states.values():
            if state["last_provider_state"] == "partially_live_then_fallback":
                limitations.append(
                    f"{state['seat_name']} was live for {state['actual_live_turn_count']} turn(s) but later fell back."
                )
            elif state["last_provider_state"] == "requested_live_all_fallback":
                limitations.append(f"{state['seat_name']} was requested live but every turn fell back.")
        if not limitations:
            limitations.append("No provider fallback limitation was observed in this council run.")
        return limitations

    def _brief_items(self, items: list[str], *, limit: int, max_chars: int = 220) -> list[str]:
        cleaned = []
        seen = set()
        for item in items:
            text = re.sub(r"\s+", " ", redact_council_text(item)).strip()
            if not text:
                continue
            key = _content_signature(text)
            if key in seen:
                continue
            seen.add(key)
            if len(text) > max_chars:
                text = text[: max_chars - 3].rsplit(" ", 1)[0].rstrip(" .,;:") + "..."
            cleaned.append(text)
            if len(cleaned) >= limit:
                break
        return cleaned

