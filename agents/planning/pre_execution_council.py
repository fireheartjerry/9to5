    def _state_is_unavailable(self, state: dict[str, Any]) -> bool:
        if state["requested_live"] and not state["turn_count"]:
            return False
        if state["last_provider_state"] == "requested_live_no_live_result":
            return True
        if not state["fallback_reasons"]:
            return False
        if state["rate_limit_seen"] or state["quota_limit_seen"]:
            return False
        reason = " ".join(str(r).lower() for r in state["fallback_reasons"])
        unavailable_markers = (
            "missing config",
            "missing",
            "unavailable",
            "transport",
            "returned no text",
            "empty response",
            "malformed response",
            "failed",
        )
        return any(marker in reason for marker in unavailable_markers)

    def _seat_run_summaries(self, messages: list[CouncilMessage]) -> dict[str, dict[str, Any]]:
        seat_names = [spec.name for spec in DEFAULT_SEAT_SPECS]
        summary = {
            name: {
                "seat_name": name,
                "requested_live": False,
                "actual_live_any": False,
                "actual_live_all": False,
                "actual_live_turn_count": 0,
                "fallback_turn_count": 0,
                "mock_turn_count": 0,
                "providers_used": [],
                "models_used": [],
                "fallback_reasons": [],
                "rate_limit_seen": False,
                "quota_limit_seen": False,
                "continuity_status": "",
                "latency_ms": 0,
                "response_digest": "",
                "last_provider_state": "never_requested_live",
                "provider_timeline": [],
                "_turn_count": 0,
            }
            for name in seat_names
        }
        for msg in messages:
            meta = dict(msg.provider_metadata or {})
            state = summary.setdefault(
                msg.speaker,
                {
                    "seat_name": msg.speaker,
                    "requested_live": False,
                    "actual_live_any": False,
                    "actual_live_all": False,
                    "actual_live_turn_count": 0,
                    "fallback_turn_count": 0,
                    "mock_turn_count": 0,
                    "providers_used": [],
                    "models_used": [],
                    "fallback_reasons": [],
                    "rate_limit_seen": False,
                    "quota_limit_seen": False,
                    "continuity_status": "",
                    "last_provider_state": "never_requested_live",
                    "provider_timeline": [],
                    "_turn_count": 0,
                },
            )
            requested = bool(meta.get("requested_live"))
            actual = bool(meta.get("actual_live"))
            fallback = bool(meta.get("fallback"))
            provider = str(meta.get("provider", "mock") or "mock")
            model = redact_council_text(meta.get("model", "") or "")
            fallback_reason = self._compact_provider_reason(redact_council_text(meta.get("fallback_reason", "") or ""))
            state["_turn_count"] += 1
            state["requested_live"] = bool(state["requested_live"] or requested)
            if actual:
                state["actual_live_turn_count"] += 1
                state["actual_live_any"] = True
            if fallback:
                state["fallback_turn_count"] += 1
            if provider == "mock":
                state["mock_turn_count"] += 1
            if provider and provider not in state["providers_used"]:
                state["providers_used"].append(provider)
            if model and model not in state["models_used"]:
                state["models_used"].append(model)
            if fallback_reason and fallback_reason not in state["fallback_reasons"]:
                state["fallback_reasons"].append(fallback_reason)
            reason_l = fallback_reason.lower()
            if "429" in reason_l or "rate limit" in reason_l or "rate_limit" in reason_l:
                state["rate_limit_seen"] = True
            if "quota" in reason_l or "resource_exhausted" in reason_l:
                state["quota_limit_seen"] = True
            continuity = dict(meta.get("continuity") or {})
            if continuity:
                state["continuity_status"] = str(continuity.get("status") or ("ok" if continuity.get("ok") else "degraded"))
            state["latency_ms"] = int(round(float(meta.get("elapsed_s", 0.0) or 0.0) * 1000))
            state["response_digest"] = hashlib.sha256(str(msg.content).encode("utf-8")).hexdigest()[:16]
            state["provider_timeline"].append(
                self._provider_timeline_entry(
                    turn_index=msg.turn_index,
                    provider=provider,
                    requested_live=requested,
                    actual_live=actual,
                    fallback=fallback,
                    model=model,
                    fallback_reason=fallback_reason,
                    continuity_status=state["continuity_status"],
                )
            )
        for state in summary.values():
            turn_count = int(state.pop("_turn_count", 0))
            state["turn_count"] = turn_count
            actual_count = int(state["actual_live_turn_count"])
            state["actual_live_all"] = bool(turn_count and state["requested_live"] and actual_count == turn_count)
            if not turn_count:
                state["last_provider_state"] = "never_requested_live"
            elif not state["requested_live"]:
                state["last_provider_state"] = "mock_only"
            elif state["actual_live_all"]:
                state["last_provider_state"] = "fully_live"
            elif state["actual_live_any"]:
                state["last_provider_state"] = "partially_live_then_fallback"
            elif state["fallback_turn_count"]:
                state["last_provider_state"] = "requested_live_all_fallback"
            else:
                state["last_provider_state"] = "requested_live_no_live_result"
        return summary

    def _visible_seat_states(self, seat_states: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
        core = {"GPT", "Gemini", "Claude", "Local LLM"}
        visible = []
        for state in seat_states.values():
            if state["seat_name"] in core or state["requested_live"] or state.get("turn_count", 0):
                visible.append(state)
        return visible

    def _provider_run_summaries(self, seat_states: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
        return [dict(state) for state in self._visible_seat_states(seat_states)]

    def _live_summary_text(self, seat_states: dict[str, dict[str, Any]]) -> str:
        parts = []
        for state in self._visible_seat_states(seat_states):
            seat_name = state["seat_name"]
            live_providers = [p for p in state.get("providers_used", []) if p != "mock"]
            live_provider = live_providers[-1] if live_providers else "live provider"
            if state["last_provider_state"] == "fully_live":
                status = f"live via {live_provider}"
            elif state["last_provider_state"] == "partially_live_then_fallback":
                status = (
                    f"partially live via {live_provider} ({state['actual_live_turn_count']} live, "
                    f"{state['fallback_turn_count']} fallback)"
                )
            elif state["last_provider_state"] == "requested_live_all_fallback":
                status = f"requested live but all fallback ({state['fallback_turn_count']} turn(s))"
            elif state["last_provider_state"] == "mock_only":
                status = "mock-only"
            else:
                status = "never requested live"
            if state.get("continuity_status"):
                status += f"; continuity={state['continuity_status']}"
            if state["last_provider_state"] == "fully_live":
                status += f"; fully live ({state['actual_live_turn_count']} turn(s))"
            parts.append(f"{seat_name}: {status}")
        return "; ".join(parts)

    def _provider_timeline_entry(
        self,
        *,
        turn_index: int,
        provider: str,
        requested_live: bool,
        actual_live: bool,
        fallback: bool,
        model: str,
        fallback_reason: str,
        continuity_status: str,
    ) -> str:
        if actual_live:
            state = f"T{turn_index}:live:{provider}"
        elif fallback:
            state = f"T{turn_index}:fallback:{provider}"
        elif requested_live:
            state = f"T{turn_index}:requested-live-no-result:{provider}"
        else:
            state = f"T{turn_index}:mock:{provider}"
        details = []
        if model:
            details.append(f"model={model}")
        if fallback_reason:
            details.append(f"reason={fallback_reason}")
        if continuity_status:
            details.append(f"continuity={continuity_status}")
        return f"{state} ({'; '.join(details)})" if details else state

    def _compact_provider_reason(self, reason: str, max_chars: int = 140) -> str:
        text = re.sub(r"\s+", " ", redact_council_text(reason)).strip()
        if not text:
            return ""
        lower = text.lower()
        prefix = ""
        if "gemini" in lower:
            prefix = "Gemini"
        elif "groq" in lower:
            prefix = "Groq"
        elif "cloudflare" in lower or "workers ai" in lower:
            prefix = "Cloudflare"
        elif "cerebras" in lower:
            prefix = "Cerebras"
        elif "gpt" in lower or "browser" in lower:
            prefix = "GPT browser"
        elif "local" in lower or "ollama" in lower:
            prefix = "Local"
        signals = []
        if "429" in lower:
            signals.append("429")
        if "resource_exhausted" in lower:
            signals.append("RESOURCE_EXHAUSTED")
        if "quota" in lower:
            signals.append("quota limit")
        if "rate_limit" in lower or "rate limit" in lower or "ratelimit" in lower:
            signals.append("rate limit")
        if "missing" in lower:
            signals.append("missing config")
        if "returned no text" in lower:
            signals.append("empty response")
        if "malformed" in lower:
            signals.append("malformed response")
        if signals:
            unique = []
            for item in signals:
                if item not in unique:
                    unique.append(item)
            label = " / ".join(unique)
            return f"{prefix + ' ' if prefix else ''}{label}".strip()
        if len(text) > max_chars:
            return text[: max_chars - 3].rsplit(" ", 1)[0].rstrip(" .,;:") + "..."
        return text

    def _provider_participation_lines(self, seat_states: dict[str, dict[str, Any]]) -> list[str]:
        lines = []
        labels = {
            "never_requested_live": "never requested live",
            "mock_only": "mock-only",
            "requested_live_all_fallback": "requested live but all fallback",
            "partially_live_then_fallback": "partially live then fallback",
            "fully_live": "fully live",
            "requested_live_no_live_result": "requested live without a live result",
        }
        for state in self._visible_seat_states(seat_states):
            seat_name = state["seat_name"]
            live_providers = [p for p in state.get("providers_used", []) if p != "mock"]
            live_provider = live_providers[-1] if live_providers else ""
            state_label = labels.get(str(state["last_provider_state"]), str(state["last_provider_state"]))
            if state["last_provider_state"] == "partially_live_then_fallback" and live_provider:
                state_label = f"partially live via {live_provider} then fallback"
            elif state["last_provider_state"] == "fully_live" and live_provider:
                state_label = f"fully live via {live_provider}"
            pieces = [
                f"{seat_name}: {state_label}",
                f"requested_live={state['requested_live']}",
                f"live_turns={state['actual_live_turn_count']}",
                f"fallback_turns={state['fallback_turn_count']}",
                f"mock_turns={state['mock_turn_count']}",
            ]
            if state["models_used"]:
                pieces.append(f"models={', '.join(state['models_used'])}")
            if state["fallback_reasons"]:
                pieces.append(f"fallback={'; '.join(state['fallback_reasons'])}")
            if state["continuity_status"]:
                pieces.append(f"continuity={state['continuity_status']}")
            lines.append("; ".join(pieces))
        return lines

    def _provider_timeline_lines(self, seat_states: dict[str, dict[str, Any]]) -> list[str]:
        lines = []
        for state in self._visible_seat_states(seat_states):
            timeline = state["provider_timeline"]
            if timeline:
                lines.append(f"{state['seat_name']}: {' -> '.join(timeline)}")
        return lines or ["No provider turns were recorded."]

