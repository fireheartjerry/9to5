    def effective_total_messages(self, seat_count: int) -> int:
        if self.conversation_policy == "selector":
            debate_rounds = max(1, int(self.selector_debate_rounds))
            return max(0, seat_count) + (2 * debate_rounds) + 2
        by_seat = max(0, self.messages_per_seat) * max(0, seat_count)
        if self.total_target_messages <= 0:
            return by_seat
        return max(self.total_target_messages, by_seat) if by_seat else 0


