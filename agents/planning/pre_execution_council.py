class MockCouncilSeat:
    def __init__(self, spec: CouncilSeatSpec) -> None:
        self.spec = spec
        self.name = spec.name
        self._turns = 0

    def ask(self, prompt: str, context: dict[str, Any]) -> str:
        self._turns += 1
        task = str(context.get("task", "the task")).strip()
        hats = context.get("temporary_hats") or []
        hat = str(hats[0]).split(":", 1)[0] if hats else "Generalist"
        templates = MOCK_TURN_LIBRARY[self.name]
        base = templates[(self._turns - 1) % len(templates)]
        return (
            f"{base} [UPDATE] {self.name} turn {self._turns} wearing {hat} applies this to task: "
            f"{task[:180]}"
        )

    def provider_metadata(self) -> dict[str, Any]:
        return _seat_metadata(provider="mock", requested_live=False, actual_live=False)


