class LiveGPTBrowserCouncilSeat:
    """Live GPT seat: one browser chat thread per council run + structured continuity checks."""

    def __init__(
        self,
        spec: CouncilSeatSpec,
        *,
        send_fn=None,
        project_url: str = "",
        model: str = "",
        reasoning: str = "",
    ) -> None:
        self.spec = spec
        self.name = spec.name
        self._mock = MockCouncilSeat(spec)
        self._send_fn = send_fn
        self._project_url = project_url
        self._model = model
        self._reasoning = reasoning
        self._fallback_reason = ""
        self._live_turns = 0
        self._session: Any = None
        self._last_continuity: dict[str, Any] = {}

    def ask(self, prompt: str, context: dict[str, Any]) -> str:
        if self._fallback_reason:
            return self._fallback(prompt, context)
        if not self._project_url.strip():
            self._fallback_reason = "GPT project URL missing"
            return self._fallback(prompt, context)
        next_turn = self._live_turns + 1
        token = make_continuity_token(
            run_id=str(context.get("run_id", "")),
            seat=self.name,
            turn=next_turn,
            prompt_version=str(context.get("prompt_version", PROMPT_VERSION)),
        )
        full_prompt = f"{prompt}\n\n{continuity_instruction(token)}"
        try:
            reply = self._session_ask(full_prompt)
            if not reply:
                self._fallback_reason = "GPT browser returned no text"
                return self._fallback(prompt, context)
            ok, detail = check_continuity(str(reply), token)
            self._last_continuity = {
                "ok": ok,
                "detail": detail,
                "expected": token,
                "status": "ok" if ok else "degraded",
            }
            self._live_turns += 1
            return redact_council_text(str(reply))
        except Exception as exc:  # noqa: BLE001 -- browser seat is optional and must degrade cleanly
            self._fallback_reason = f"{type(exc).__name__}: {exc}"
            return self._fallback(prompt, context)

    def _ensure_session(self) -> Any:
        if self._session is not None:
            return self._session
        if self._send_fn is not None:
            self._session = _InjectedGptSession(
                self._send_fn,
                project_url=self._project_url,
                model=self._model,
                reasoning=self._reasoning,
            )
            return self._session
        from agents.execution.chatgpt_browser_driver import (
            DEFAULT_MODEL,
            DEFAULT_PROJECT_URL,
            DEFAULT_REASONING,
            ChatGptBrowserSession,
        )

        self._session = ChatGptBrowserSession(
            project_url=self._project_url or DEFAULT_PROJECT_URL,
            model=self._model or DEFAULT_MODEL,
            reasoning=self._reasoning or DEFAULT_REASONING,
        )
        return self._session

    def _session_ask(self, prompt: str) -> str:
        session = self._ensure_session()
        return str(session.ask(prompt))

    def close(self) -> None:
        session = self._session
        self._session = None
        if session is not None and hasattr(session, "close"):
            try:
                session.close()
            except Exception:  # noqa: BLE001 -- seat teardown must not break the runner
                pass

    def _fallback(self, prompt: str, context: dict[str, Any]) -> str:
        mock_reply = self._mock.ask(prompt, context)
        return f"[RISK] GPT browser seat unavailable; falling back to mock GPT. [DATA] fallback_reason={redact_council_text(self._fallback_reason)}. {mock_reply}"

    def provider_metadata(self) -> dict[str, Any]:
        session_id = ""
        if self._session is not None:
            session_id = str(getattr(self._session, "session_id", "") or "")
        if self._fallback_reason:
            meta = _seat_metadata(
                provider="mock",
                requested_live=True,
                actual_live=False,
                fallback_from="gpt-browser",
                fallback_reason=self._fallback_reason,
                model=self._model,
                reasoning=self._reasoning,
                project_url=redact_council_text(self._project_url),
                live_provider_invoked=self._live_turns > 0,
            )
        else:
            meta = _seat_metadata(
                provider="gpt-browser",
                requested_live=True,
                actual_live=True,
                model=self._model,
                reasoning=self._reasoning,
                project_url=redact_council_text(self._project_url),
                live_provider_invoked=True,
            )
        if session_id:
            meta["chat_session_id"] = session_id
        meta["session_turns"] = self._live_turns
        if self._last_continuity:
            meta["continuity"] = dict(self._last_continuity)
        return meta


def _seat_metadata(
    *,
    provider: str,
    requested_live: bool,
    actual_live: bool,
    live_provider_invoked: bool = False,
    fallback_from: str = "",
    fallback_reason: str = "",
    model: str = "",
    reasoning: str = "",
    project_url: str = "",
    runtime: str = "",
    attempted_models: str = "",
) -> dict[str, Any]:
    data = {
        "provider": provider,
        "requested_live": requested_live,
        "actual_live": actual_live,
        "live_provider_invoked": live_provider_invoked,
        "fallback": bool(requested_live and not actual_live),
    }
    if fallback_from:
        data["fallback_from"] = fallback_from
    if fallback_reason:
        data["fallback_reason"] = redact_council_text(fallback_reason)
    if model:
        data["model"] = model
    if reasoning:
        data["reasoning"] = reasoning
    if project_url:
        data["project_url"] = redact_council_text(project_url)
    if runtime:
        data["runtime"] = runtime
    if attempted_models:
        data["attempted_models"] = attempted_models
    return data


def is_enabled(config_obj: CouncilConfig | None = None) -> bool:
    cfg = config_obj or CouncilConfig.from_config()
    return bool(cfg.enabled)


class CouncilRunner:
    def __init__(
        self,
        council_config: CouncilConfig | None = None,
        seats: list[CouncilSeat] | None = None,
        gemini_session_factory=None,
        local_transport=None,
        local_model: str | None = None,
        gpt_send_fn=None,
    ) -> None:
        self.config = council_config or CouncilConfig.from_config()
        self.seats = seats
        self.gemini_session_factory = gemini_session_factory
        self.local_transport = local_transport
        self.local_model = local_model
        self.gpt_send_fn = gpt_send_fn

    def run(self, context_pack: CouncilContextPack) -> CouncilRunResult:
        run_id = uuid.uuid4().hex
        if not self.config.enabled:
            return CouncilRunResult(
                run_id=run_id,
                config=self.config,
                messages=[],
                compact_state={},
                brief=None,
                warnings=[],
                skipped_reason="pre-execution council disabled",
            )
        seats = self._build_seats()
        hats_by_seat = assign_temporary_hats(context_pack)
        logger = (
            CouncilRunLogger(run_id=run_id, task=context_pack.original_task, output_dir=self.config.output_dir)
            if self.config.logging_enabled
            else None
        )
        if logger:
            logger.write_context(context_pack.to_safe_dict())
            logger.write_config(asdict(self.config))
        messages: list[CouncilMessage] = []
        compact_state: dict[str, list[str]] = {
            "claims": [],
            "risks": [],
            "questions": [],
            "data": [],
            "constraints": [],
            "plans": [],
            "disagreements": [],
            "actions": [],
            "synthesis": [],
        }
        warnings: list[CouncilQualityWarning] = []
        try:
            if self.config.conversation_policy == "selector":
                self._run_selector_policy(
                    run_id=run_id,
                    context_pack=context_pack,
                    seats=seats,
                    hats_by_seat=hats_by_seat,
                    messages=messages,
                    compact_state=compact_state,
                    warnings=warnings,
                    logger=logger,
                )
            else:
                self._run_round_robin_policy(
                    run_id=run_id,
                    context_pack=context_pack,
                    seats=seats,
                    hats_by_seat=hats_by_seat,
                    messages=messages,
                    compact_state=compact_state,
                    warnings=warnings,
                    logger=logger,
                )
            brief = self._synthesize_brief(run_id, context_pack, compact_state, messages, seats, logger)
            brief.validate_required_fields()
            if logger:
                composition = self._run_composition_summary(seats, messages)
                logger.write_brief(brief, brief.to_markdown())
                logger.write_metadata(
                    {
                        "run_id": run_id,
                        "prompt_version": self.config.prompt_version,
                        "created_at": datetime.now().astimezone().isoformat(timespec="seconds"),
                        "message_count": len(messages),
                        "seat_count": len(seats),
                        "conversation_policy": self.config.conversation_policy,
                        "selector_debate_rounds": self.config.selector_debate_rounds,
                        "selector_phases": (
                            ["independent_memo", "compression", "selected_debate", "critique_pair", "final_brief"]
                            if self.config.conversation_policy == "selector"
                            else []
                        ),
                        "provider_budget_state": (
                            self._provider_budget_state(messages)
                            if self.config.conversation_policy == "selector"
                            else {}
                        ),
                        "run_composition_summary": asdict(composition),
                        "mock_only": composition.all_mock_only,
                        "live_provider_flags": {
                            "gpt": self.config.live_gpt_enabled,
                            "gemini": self.config.live_gemini_enabled,
                            "claude": self.config.live_claude_enabled,
                            "local": self.config.live_local_enabled,
                            "groq": self.config.live_groq_enabled,
                            "cloudflare": self.config.live_cloudflare_enabled,
                        },
                        "warnings": [asdict(w) for w in warnings],
                    }
                )
            return CouncilRunResult(
                run_id=run_id,
                config=self.config,
                messages=messages,
                compact_state=compact_state,
                brief=brief,
                warnings=warnings,
                transcript_path=str(logger.transcript_md_path) if logger else "",
                brief_path=str(logger.brief_md_path) if logger else "",
                log_dir=str(logger.run_dir) if logger else "",
            )
        finally:
            for seat in seats:
                closer = getattr(seat, "close", None)
                if callable(closer):
                    try:
                        closer()
                    except Exception:  # noqa: BLE001 -- seat close is best-effort
                        pass

    def _run_round_robin_policy(
        self,
        *,
        run_id: str,
        context_pack: CouncilContextPack,
        seats: list[CouncilSeat],
        hats_by_seat: dict[str, list[str]],
        messages: list[CouncilMessage],
        compact_state: dict[str, list[str]],
        warnings: list[CouncilQualityWarning],
        logger: CouncilRunLogger | None,
    ) -> None:
        total = self.config.effective_total_messages(len(seats))
        for turn_index in range(1, total + 1):
            seat = seats[(turn_index - 1) % len(seats)]
            prompt = self._build_prompt(
                context_pack=context_pack,
                enabled_seats=seats,
                seat=seat,
                temporary_hats=hats_by_seat.get(seat.name, []),
                messages=messages,
                compact_state=compact_state,
            )
            self._ask_and_record(
                run_id=run_id,
                context_pack=context_pack,
                seat=seat,
                prompt=prompt,
                turn_index=turn_index,
                hats=hats_by_seat.get(seat.name, []),
                messages=messages,
                compact_state=compact_state,
                warnings=warnings,
                logger=logger,
                phase="round_robin",
                targeted_challenge="round-robin council turn",
            )

    def _run_selector_policy(
        self,
        *,
        run_id: str,
        context_pack: CouncilContextPack,
        seats: list[CouncilSeat],
        hats_by_seat: dict[str, list[str]],
        messages: list[CouncilMessage],
        compact_state: dict[str, list[str]],
        warnings: list[CouncilQualityWarning],
        logger: CouncilRunLogger | None,
    ) -> None:
        turn_index = 1
        if self.config.parallel_memos_enabled and len(seats) > 1:
            turn_index = self._run_parallel_memos(run_id, context_pack, seats, hats_by_seat, messages,
                                                  compact_state, warnings, logger, turn_index)
        else:
            for seat in seats:
                prompt = self._build_selector_prompt(
                    context_pack=context_pack, enabled_seats=seats, seat=seat,
                    temporary_hats=hats_by_seat.get(seat.name, []), messages=messages,
                    compact_state=compact_state, phase="independent_memo",
                    targeted_challenge="Write an independent memo: strongest claims, risks, missing data, and first-slice constraints. Do not respond to other seats yet.")
                self._ask_and_record(run_id=run_id, context_pack=context_pack, seat=seat, prompt=prompt,
                    turn_index=turn_index, hats=hats_by_seat.get(seat.name, []), messages=messages,
                    compact_state=compact_state, warnings=warnings, logger=logger, phase="independent_memo",
                    targeted_challenge="independent memo")
                turn_index += 1
        # Debate begins only after every independent memo has been recorded.

        debate_seats = self._select_debate_speakers(seats, compact_state, messages)
        for debate_round in range(1, max(1, self.config.selector_debate_rounds) + 1):
            for seat in debate_seats:
                challenge = self._targeted_debate_challenge(seat, compact_state, debate_round)
                prompt = self._build_selector_prompt(
                    context_pack=context_pack,
                    enabled_seats=seats,
                    seat=seat,
                    temporary_hats=hats_by_seat.get(seat.name, []),
                    messages=messages,
                    compact_state=compact_state,
                    phase="selected_debate",
                    targeted_challenge=challenge,
                )
                self._ask_and_record(
                    run_id=run_id,
                    context_pack=context_pack,
                    seat=seat,
                    prompt=prompt,
                    turn_index=turn_index,
                    hats=hats_by_seat.get(seat.name, []),
                    messages=messages,
                    compact_state=compact_state,
                    warnings=warnings,
                    logger=logger,
                    phase="selected_debate",
                    targeted_challenge=challenge,
                )
                turn_index += 1

        for seat, challenge in self._critique_pair(seats, messages):
            prompt = self._build_selector_prompt(
                context_pack=context_pack,
                enabled_seats=seats,
                seat=seat,
                temporary_hats=hats_by_seat.get(seat.name, []),
                messages=messages,
                compact_state=compact_state,
                phase="critique_pair",
                targeted_challenge=challenge,
            )
            self._ask_and_record(
                run_id=run_id,
                context_pack=context_pack,
                seat=seat,
                prompt=prompt,
                turn_index=turn_index,
                hats=hats_by_seat.get(seat.name, []),
                messages=messages,
                compact_state=compact_state,
                warnings=warnings,
                logger=logger,
                phase="critique_pair",
                targeted_challenge=challenge,
            )
            turn_index += 1

    def _ask_and_record(
        self,
        *,
        run_id: str,
        context_pack: CouncilContextPack,
        seat: CouncilSeat,
        prompt: str,
        turn_index: int,
        hats: list[str],
        messages: list[CouncilMessage],
        compact_state: dict[str, list[str]],
        warnings: list[CouncilQualityWarning],
        logger: CouncilRunLogger | None,
        phase: str,
        targeted_challenge: str,
    ) -> None:
        started = time.perf_counter()
        content = seat.ask(
            prompt,
            {
                "task": context_pack.original_task,
                "context_pack": context_pack.to_safe_dict(),
                "temporary_hats": hats,
                "prompt_version": self.config.prompt_version,
                "run_id": run_id,
                "turn_index": turn_index,
                "selector_phase": phase,
                "targeted_challenge": targeted_challenge,
            },
        )
        self._record_content(run_id, seat, turn_index, content, hats, prompt, messages,
                             compact_state, warnings, logger, phase, targeted_challenge,
                             time.perf_counter() - started)

    def _record_content(self, run_id, seat, turn_index, content, hats, prompt, messages,
                        compact_state, warnings, logger, phase, targeted_challenge, elapsed_s: float) -> None:
        msg = self._message(
            run_id=run_id,
            seat=seat,
            turn_index=turn_index,
            content=content,
            hats=hats,
            prompt=prompt,
        )
        msg.provider_metadata["conversation_policy"] = self.config.conversation_policy
        msg.provider_metadata["selector_phase"] = phase
        msg.provider_metadata["targeted_challenge"] = redact_council_text(targeted_challenge)
        msg.provider_metadata["elapsed_s"] = round(float(elapsed_s), 6)
        msg.warnings.extend(self._repetition_warnings(msg, messages))
        self._update_compact_state(compact_state, msg)
        warnings.extend(msg.warnings)
        messages.append(msg)
        if logger:
            logger.write_message(msg)

    def _run_parallel_memos(self, run_id, context_pack, seats, hats_by_seat, messages,
                            compact_state, warnings, logger, turn_index: int) -> int:
        """LPT-scheduled independent asks; record results in deterministic seat order."""
        jobs = []
        for offset, seat in enumerate(seats):
            hats = hats_by_seat.get(seat.name, [])
            prompt = self._build_selector_prompt(context_pack=context_pack, enabled_seats=seats, seat=seat,
                temporary_hats=hats, messages=[], compact_state=compact_state, phase="independent_memo",
                targeted_challenge="Write an independent memo: strongest claims, risks, missing data, and first-slice constraints. Do not respond to other seats yet.")
            jobs.append((seat, prompt, hats, turn_index + offset))
        # Previous observed elapsed time is the LPT key; cold starts use stable seat ordering.
        jobs.sort(key=lambda j: (-float(getattr(self, "_seat_latency", {}).get(j[0].name, 1.0)), j[0].name))
        results = {}
        def ask(job):
            seat, prompt, hats, index = job
            started = time.perf_counter()
            content = seat.ask(prompt, {"task": context_pack.original_task, "context_pack": context_pack.to_safe_dict(),
                "temporary_hats": hats, "prompt_version": self.config.prompt_version, "run_id": run_id,
                "turn_index": index, "selector_phase": "independent_memo", "targeted_challenge": "independent memo"})
            return content, time.perf_counter() - started
        with ThreadPoolExecutor(max_workers=min(self.config.max_parallel_seats, len(jobs))) as pool:
            futures = {pool.submit(ask, job): job for job in jobs}
            for future, job in [(f, futures[f]) for f in futures]:
                results[job[3]] = future.result()
        self._seat_latency = getattr(self, "_seat_latency", {})
        for seat, prompt, hats, index in sorted(jobs, key=lambda j: j[3]):
            content, elapsed = results[index]
            self._seat_latency[seat.name] = elapsed
            self._record_content(run_id, seat, index, content, hats, prompt, messages, compact_state,
                                 warnings, logger, "independent_memo", "independent memo", elapsed)
        return turn_index + len(jobs)

    def _build_seats(self) -> list[CouncilSeat]:
        if self.seats is not None:
            return self.seats
        seats: list[CouncilSeat] = []
        for spec in DEFAULT_SEAT_SPECS:
            if spec.name == "Groq" and not self.config.live_groq_enabled:
                continue
            if spec.name == "Cloudflare" and not self.config.live_cloudflare_enabled:
                continue
            if spec.name == "Cerebras" and not self.config.live_cerebras_enabled:
                continue
            if spec.name == "GPT" and self.config.live_gpt_enabled:
                seats.append(
                    LiveGPTBrowserCouncilSeat(
                        spec,
                        send_fn=self.gpt_send_fn,
                        project_url=self.config.gpt_project_url,
                        model=self.config.gpt_model,
                        reasoning=self.config.gpt_reasoning,
                    )
                )
            elif spec.name == "Gemini" and self.config.live_gemini_enabled:
                seats.append(LiveGeminiCouncilSeat(spec, session_factory=self.gemini_session_factory))
            elif spec.name == "Local LLM" and self.config.live_local_enabled:
                seats.append(
                    LiveLocalCouncilSeat(
                        spec,
                        transport=self.local_transport,
                        model=self.local_model or self.config.local_model,
                    )
                )
            elif spec.name == "Groq" and self.config.live_groq_enabled:
                seats.append(
                    LiveGroqCouncilSeat(
                        spec,
                        model=self.config.groq_model,
                        fallback_models=self.config.groq_fallback_models,
                    )
                )
            elif spec.name == "Cloudflare" and self.config.live_cloudflare_enabled:
                seats.append(LiveCloudflareCouncilSeat(spec, model=self.config.cloudflare_model))
            elif spec.name == "Cerebras" and self.config.live_cerebras_enabled:
                seats.append(LiveCerebrasCouncilSeat(spec, model=self.config.cerebras_model))
            elif self.config.mock_seats_enabled:
                seats.append(MockCouncilSeat(spec))
        if not seats:
            raise RuntimeError("Pre-execution council needs at least one enabled live or mock seat.")
        return seats

    def _build_prompt(
        self,
        *,
        context_pack: CouncilContextPack,
        enabled_seats: list[CouncilSeat],
        seat: CouncilSeat,
        temporary_hats: list[str],
        messages: list[CouncilMessage],
        compact_state: dict[str, list[str]],
    ) -> str:
        recent = "\n".join(f"{m.speaker}: {m.content[:500]}" for m in messages[-8:])
        state_text = "\n".join(f"{k}: {' | '.join(v[-6:])}" for k, v in compact_state.items() if v)
        disagreements = "\n".join(compact_state.get("disagreements", [])[-6:])
        working = "\n".join((compact_state.get("plans", []) + compact_state.get("actions", []))[-8:])
        seat_prompt = SEAT_SYSTEM_PROMPTS.get(seat.name, "")
        turn = build_turn_prompt(
            task=context_pack.original_task,
            context_pack_summary=self._context_summary_for_prompt(context_pack, max_chars=6000),
            run_composition=self._run_composition_summary(enabled_seats, messages).to_prompt_block(),
            seat_name=seat.name,
            temporary_roles=temporary_hats,
            recent_transcript=recent,
            compact_state=state_text,
            unresolved_disagreements=disagreements,
            working_brief=working,
            compact_protocol=self.config.compact_protocol,
            anti_filler=self.config.anti_filler,
        )
        return (
            f"Prompt version: {self.config.prompt_version}\n\n"
            f"{GLOBAL_COUNCIL_SYSTEM_PROMPT}\n\n"
            f"{seat_prompt}\n\n"
            f"{turn}"
        )

    def _build_selector_prompt(
        self,
        *,
        context_pack: CouncilContextPack,
        enabled_seats: list[CouncilSeat],
        seat: CouncilSeat,
        temporary_hats: list[str],
        messages: list[CouncilMessage],
        compact_state: dict[str, list[str]],
        phase: str,
        targeted_challenge: str,
    ) -> str:
        excerpts = self._relevant_excerpts(messages, seat.name)
        state_text = "\n".join(f"{k}: {' | '.join(v[-3:])}" for k, v in compact_state.items() if v)
        disagreements = "\n".join(compact_state.get("disagreements", [])[-3:])
        working = "\n".join((compact_state.get("plans", []) + compact_state.get("actions", []))[-4:])
        seat_prompt = SEAT_SYSTEM_PROMPTS.get(seat.name, "")
        turn = build_turn_prompt(
            task=context_pack.original_task,
            context_pack_summary=self._context_summary_for_prompt(context_pack, max_chars=3000),
            run_composition=self._run_composition_summary(enabled_seats, messages).to_prompt_block(),
            seat_name=seat.name,
            temporary_roles=temporary_hats,
            recent_transcript=excerpts,
            compact_state=state_text,
            unresolved_disagreements=disagreements,
            working_brief=working,
            compact_protocol=self.config.compact_protocol,
            anti_filler=self.config.anti_filler,
        )
        return (
            f"Prompt version: {self.config.prompt_version}\n\n"
            f"{GLOBAL_COUNCIL_SYSTEM_PROMPT}\n\n"
            f"{seat_prompt}\n\n"
            "Conversation policy: selector_v1\n"
            f"Selector phase: {phase}\n"
            f"Targeted challenge: {targeted_challenge}\n\n"
            "Use only the compact state and relevant excerpts below. Do not assume you have the full raw transcript.\n\n"
            f"{turn}"
        )

    def _context_summary_for_prompt(self, context_pack: CouncilContextPack, *, max_chars: int) -> str:
        allowed_live_actions = self._requested_live_forbidden_actions()
        if not allowed_live_actions:
            return context_pack.summarize_for_prompt(max_chars=max_chars)
        filtered = [
            action
            for action in context_pack.forbidden_actions
            if action not in allowed_live_actions
        ]
        available = list(context_pack.available_tools_providers)
        requested = ", ".join(sorted(self._requested_live_seat_names()))
        if requested:
            available.append(f"explicitly requested live council seats: {requested}")
        prompt_pack = replace(
            context_pack,
            forbidden_actions=filtered,
            available_tools_providers=available,
        )
        return prompt_pack.summarize_for_prompt(max_chars=max_chars)

    def _requested_live_forbidden_actions(self) -> set[str]:
        by_seat = {
            "GPT": "Do not call ChatGPT browser driver.",
            "Gemini": "Do not call Gemini.",
            "Claude": "Do not call Claude Code.",
            "Local LLM": "Do not call local LLM/Ollama.",
            "Groq": "Do not call Groq.",
            "Cloudflare": "Do not call Cloudflare Workers AI.",
            "Cerebras": "Do not call Cerebras.",
        }
        return {
            action
            for seat, action in by_seat.items()
            if seat in self._requested_live_seat_names()
        }

    def _relevant_excerpts(self, messages: list[CouncilMessage], seat_name: str) -> str:
        if not messages:
            return "(none yet; independent memo phase)"
        relevant = []
        for msg in reversed(messages):
            if msg.speaker == seat_name or any(tag in msg.compact_tags for tag in ("[RISK]", "[DISAGREE]", "[QUESTION]", "[PLAN]")):
                relevant.append(f"{msg.speaker} T{msg.turn_index}: {msg.content[:240]}")
            if len(relevant) >= 3:
                break
        return "\n".join(reversed(relevant)) if relevant else "(no targeted excerpts)"

    def _select_debate_speakers(
        self,
        seats: list[CouncilSeat],
        compact_state: dict[str, list[str]],
        messages: list[CouncilMessage] | None = None,
    ) -> list[CouncilSeat]:
        by_name = {seat.name: seat for seat in seats}
        budget = self._provider_budget_state(messages or [])
        preferred = (
            ["Local LLM", "Claude"]
            if compact_state.get("risks")
            else ["Gemini", "GPT"]
        )
        if compact_state.get("disagreements"):
            preferred = ["Local LLM", "Gemini"]
        if "Groq" in by_name and compact_state.get("risks") and budget["groq"]["preferred_for_next_turn"]:
            preferred = ["Groq", preferred[0]]
        selected = [by_name[name] for name in preferred if name in by_name]
        if len(selected) < 2:
            selected.extend([seat for seat in seats if seat not in selected][: 2 - len(selected)])
        return selected[: max(1, min(2, len(seats)))]

    def _targeted_debate_challenge(
        self,
        seat: CouncilSeat,
        compact_state: dict[str, list[str]],
        debate_round: int,
    ) -> str:
        risk = (compact_state.get("risks") or ["No concrete risk has been isolated yet."])[-1]
        disagreement = (compact_state.get("disagreements") or ["No explicit disagreement has been preserved yet."])[-1]
        return (
            f"Selected debate round {debate_round}: {seat.name} must resolve or sharpen this risk/disagreement. "
            f"Risk: {risk[:240]} Disagreement: {disagreement[:240]}"
        )

    def _critique_pair(self, seats: list[CouncilSeat], messages: list[CouncilMessage] | None = None) -> list[tuple[CouncilSeat, str]]:
        by_name = {seat.name: seat for seat in seats}
        budget = self._provider_budget_state(messages or [])
        advocate = by_name.get("Claude") or by_name.get("GPT") or seats[0]
        critic = None
        for name in ("Groq", "Local LLM", "Gemini", "GPT"):
            if name == "Groq" and not budget["groq"]["preferred_for_next_turn"]:
                continue
            if by_name.get(name) is not None:
                critic = by_name[name]
                break
        critic = critic or seats[-1]
        if critic is advocate and len(seats) > 1:
            critic = seats[-1] if seats[-1] is not advocate else seats[0]
        return [
            (
                advocate,
                "Critique-pair advocate: state the strongest candidate execution plan and why it should be first.",
            ),
            (
                critic,
                "Critique-pair critic: attack the advocate plan, preserve blocking disagreement, and propose a tighter first slice.",
            ),
        ]

    def _provider_budget_state(self, messages: list[CouncilMessage]) -> dict[str, dict[str, Any]]:
        state = {
            "groq": {
                "recent_429": False,
                "cooldown_until": "",
                "preferred_for_next_turn": True,
            }
        }
        for msg in reversed(messages[-6:]):
            meta = msg.provider_metadata or {}
            if str(meta.get("fallback_from", "")).lower() != "groq":
                continue
            reason = str(meta.get("fallback_reason", "") or "").lower()
            if "429" in reason or "rate limit" in reason:
                state["groq"]["recent_429"] = True
                state["groq"]["preferred_for_next_turn"] = False
                state["groq"]["cooldown_until"] = "next selector turn"
                break
        return state

    def _message(
        self,
        *,
        run_id: str,
        seat: CouncilSeat,
        turn_index: int,
        content: str,
        hats: list[str],
        prompt: str,
    ) -> CouncilMessage:
        tags = [f"[{m.group(1)}]" for m in TAG_RE.finditer(content)]
        msg = CouncilMessage(
            run_id=run_id,
            speaker=seat.name,
            model_name=f"mock-{seat.name.lower().replace(' ', '-')}",
            permanent_seat=seat.name,
            temporary_hats=hats,
            turn_index=turn_index,
            content=redact_council_text(content),
            compact_tags=tags,
            timestamp=datetime.now().astimezone().isoformat(timespec="seconds"),
            provider_metadata=self._provider_metadata(seat),
            prompt_excerpt=redact_council_text(prompt[:12000]),
        )
        msg.warnings = evaluate_message_quality(msg)
        return msg

    def _provider_metadata(self, seat: CouncilSeat) -> dict[str, Any]:
        meta = getattr(seat, "provider_metadata", None)
        if callable(meta):
            return dict(meta())
        return {"provider": "mock", "live_provider_invoked": False}

    def _repetition_warnings(self, msg: CouncilMessage, prior: list[CouncilMessage]) -> list[CouncilQualityWarning]:
        core = _content_signature(msg.content)
        if not core:
            return []
        for old in reversed(prior):
            if old.speaker != msg.speaker:
                continue
            if _content_signature(old.content) == core:
                return [
                    CouncilQualityWarning(
                        "repetition",
                        msg.speaker,
                        msg.turn_index,
                        f"Repeats turn {old.turn_index} without adding a new core claim.",
                    )
                ]
        return []

    def _update_compact_state(self, compact_state: dict[str, list[str]], msg: CouncilMessage) -> None:
        mapping = {
            "[CLAIM]": "claims",
            "[RISK]": "risks",
            "[QUESTION]": "questions",
            "[DATA]": "data",
            "[CONSTRAINT]": "constraints",
            "[PLAN]": "plans",
            "[DISAGREE]": "disagreements",
            "[ACTION]": "actions",
            "[SYNTHESIS]": "synthesis",
            "[UPDATE]": "plans",
            "[COMPRESS]": "synthesis",
        }
        for tag in msg.compact_tags:
            bucket = mapping.get(tag)
            if bucket:
                compact_state.setdefault(bucket, []).append(f"{msg.speaker} T{msg.turn_index}: {msg.content[:260]}")
        for key in list(compact_state):
            compact_state[key] = compact_state[key][-20:]

