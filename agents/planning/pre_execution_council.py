def evaluate_message_quality(message: CouncilMessage) -> list[CouncilQualityWarning]:
    warnings: list[CouncilQualityWarning] = []
    stripped = message.content.strip()
    if len(stripped) < 80:
        warnings.append(CouncilQualityWarning("too_short", message.speaker, message.turn_index, "Message is too short."))
    if FILLER_RE.search(stripped) and not any(t in message.compact_tags for t in ("[COMPRESS]", "[SYNTHESIS]")):
        warnings.append(CouncilQualityWarning("filler", message.speaker, message.turn_index, "Filler-like response."))
    if not message.compact_tags:
        warnings.append(CouncilQualityWarning("missing_tags", message.speaker, message.turn_index, "No compact tags found."))
    if UNSAFE_RE.search(stripped):
        warnings.append(
            CouncilQualityWarning("unsafe_runtime_detail", message.speaker, message.turn_index, "Sensitive runtime detail mentioned.")
        )
    continuity = (message.provider_metadata or {}).get("continuity") or {}
    if continuity and continuity.get("ok") is False:
        warnings.append(
            CouncilQualityWarning(
                "continuity_degraded",
                message.speaker,
                message.turn_index,
                str(continuity.get("detail") or "context continuity degraded"),
            )
        )
    return warnings


def _content_signature(content: str) -> str:
    text = TAG_RE.sub("", content)
    text = re.sub(r"\[UPDATE\].*$", "", text).strip().lower()
    text = re.sub(r"\s+", " ", text)
    return text[:220]


def run_pre_execution_council(task: str, *, work_dir: str | Path | None = None, council_config: CouncilConfig | None = None) -> CouncilRunResult:
    context = CouncilContextPack.for_task(
        task,
        work_dir=work_dir,
        forbidden_actions=[
            "Do not call ChatGPT browser driver.",
            "Do not call Gemini.",
            "Do not call Claude Code.",
            "Do not call local LLM/Ollama.",
            "Do not call Groq.",
            "Do not call Cloudflare Workers AI.",
            "Do not call Cerebras.",
            "Do not wire into orchestration.",
        ],
        safety_boundaries=[
            "Do not inspect Chrome profile contents.",
            "Do not expose profile paths, Chrome paths, debug ports, user data dirs, or timeout overrides.",
        ],
    )
    return CouncilRunner(council_config).run(context)


