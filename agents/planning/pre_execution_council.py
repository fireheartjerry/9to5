def _split_csv_models(value: str | None) -> list[str]:
    return [part.strip() for part in str(value or "").split(",") if part.strip()]


def _groq_error_category(exc: BaseException) -> str:
    text = str(exc).lower()
    if isinstance(exc, urllib.error.HTTPError):
        code = getattr(exc, "code", None)
        if code == 401:
            return "auth"
        if code == 403:
            return "permission"
        if code == 404:
            return "model_access"
        if code == 429:
            return "rate_limit"
        if code and 500 <= int(code) <= 599:
            return "server"
        return "http"
    if "429" in text or "rate limit" in text:
        return "rate_limit"
    if "403" in text or "permission" in text or "forbidden" in text:
        return "permission"
    if "404" in text or "model" in text and "access" in text:
        return "model_access"
    if "malformed" in text:
        return "malformed_response"
    if "no text" in text or "empty" in text:
        return "empty_response"
    return "transport"


def _groq_error_message(exc: BaseException) -> str:
    if isinstance(exc, urllib.error.HTTPError):
        code = getattr(exc, "code", "unknown")
        if code == 429:
            return "Groq rate limited (429)"
        return f"Groq HTTP error {code}"
    if isinstance(exc, (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError)):
        return f"Groq transport unavailable: {exc}"
    return str(exc)


class LiveGroqCouncilSeat:
    def __init__(
        self,
        spec: CouncilSeatSpec,
        model: str | None = None,
        fallback_models: list[str] | tuple[str, ...] | str | None = None,
    ) -> None:
        self.spec = spec
        self.name = spec.name
        self._mock = MockCouncilSeat(spec)
        self._model = model or getattr(config, "PRE_EXECUTION_COUNCIL_GROQ_MODEL", "") or "qwen/qwen3-32b"
        configured_fallbacks = (
            _split_csv_models(fallback_models)
            if isinstance(fallback_models, str)
            else list(fallback_models or [])
        )
        if not configured_fallbacks:
            configured_fallbacks = _split_csv_models(getattr(config, "PRE_EXECUTION_COUNCIL_GROQ_FALLBACK_MODELS", ""))
        self._fallback_models = tuple(configured_fallbacks or GROQ_DEFAULT_FALLBACK_MODELS)
        self._attempted_models: list[str] = []
        self._successful_model = ""
        self._fallback_reason = ""
        self._live_turns = 0

    def ask(self, prompt: str, context: dict[str, Any]) -> str:
        if self._fallback_reason:
            return self._fallback(prompt, context)
        if not os.getenv("GROQ_API_KEY", ""):
            self._fallback_reason = "GROQ_API_KEY missing"
            return self._fallback(prompt, context)
        errors = []
        for model in self._models_to_try():
            self._attempted_models.append(model)
            try:
                reply = self._chat(prompt, model=model)
                if not reply:
                    raise RuntimeError("Groq returned no text")
                self._live_turns += 1
                self._successful_model = model
                return redact_council_text(str(reply))
            except Exception as exc:  # noqa: BLE001 -- optional API seat must degrade cleanly
                category = _groq_error_category(exc)
                errors.append(f"{model}:{category}:{redact_council_text(_groq_error_message(exc))}")
                if category == "rate_limit":
                    break
                if category not in {"permission", "model_access", "http"}:
                    break
        if errors:
            self._fallback_reason = "; ".join(errors)
        else:
            self._fallback_reason = "Groq live request failed"
        return self._fallback(prompt, context)

    def _models_to_try(self) -> list[str]:
        models = [self._model, *self._fallback_models]
        seen = set()
        unique = []
        for model in models:
            if model and model not in seen:
                seen.add(model)
                unique.append(model)
        return unique

    def _chat(self, prompt: str, *, model: str | None = None) -> str:
        use_model = model or self._model
        try:
            return _groq_chat_completion(
                model=use_model,
                messages=[
                    {
                        "role": "system",
                        "content": (
                            "You are the Groq council seat: fast open-model dissent, alternative critique, "
                            "failure spotting, and concise counter-planning. Do not imitate the GPT, Gemini, "
                            "or Claude seats."
                        ),
                    },
                    {"role": "user", "content": prompt},
                ],
                temperature=0.4,
                timeout=60.0,
            )
        except Exception as exc:  # noqa: BLE001 -- normalize Groq transport details before metadata/logging
            message = _groq_error_message(exc)
            raise RuntimeError(message) from exc

    def _fallback(self, prompt: str, context: dict[str, Any]) -> str:
        mock_reply = self._mock.ask(prompt, context)
        return f"[RISK] Groq live seat unavailable; falling back to mock Groq. [DATA] fallback_reason={redact_council_text(self._fallback_reason)}. {mock_reply}"

    def provider_metadata(self) -> dict[str, Any]:
        if self._fallback_reason:
            return _seat_metadata(
                provider="mock",
                requested_live=True,
                actual_live=False,
                fallback_from="groq",
                fallback_reason=self._fallback_reason,
                model=self._successful_model or self._model,
                runtime="groq-openai-compatible-chat",
                live_provider_invoked=self._live_turns > 0,
                attempted_models=",".join(self._attempted_models),
            )
        return _seat_metadata(
            provider="groq",
            requested_live=True,
            actual_live=True,
            model=self._successful_model or self._model,
            runtime="groq-openai-compatible-chat",
            live_provider_invoked=True,
            attempted_models=",".join(self._attempted_models),
        )


def _groq_chat_completion(
    *,
    model: str,
    messages: list[dict[str, str]],
    temperature: float = 0.0,
    timeout: float = 30.0,
) -> str:
    api_key = os.getenv("GROQ_API_KEY", "")
    if not api_key:
        raise RuntimeError("GROQ_API_KEY missing")
    payload = json.dumps(
        {
            "model": model,
            "messages": messages,
            "temperature": temperature,
        }
    ).encode("utf-8")
    req = urllib.request.Request(
        "https://api.groq.com/openai/v1/chat/completions",
        data=payload,
        headers={
            **GROQ_HTTP_HEADERS,
            "Authorization": f"Bearer {api_key}",
        },
        method="POST",
    )
    try:
        with legacyDiagnosticUrlopen(req, timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8", errors="replace"))
    except urllib.error.HTTPError:
        raise
    except (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"Groq transport unavailable: {exc}") from exc
    try:
        text = data["choices"][0]["message"]["content"]
    except Exception as exc:  # noqa: BLE001 -- malformed provider response
        raise RuntimeError(f"Groq malformed response: {exc}") from exc
    return str(text).strip()


