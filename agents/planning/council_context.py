"""Curated context pack for the mock-only pre-execution council.

RUN/TEST: python -m pytest tests/planning/test_pre_execution_council.py

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  safe_git_status_summary(work_dir: str | Path | None=None) -> str  -- Return branch + short dirty summary without file contents or env details.
  CouncilContextPack
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
from __future__ import annotations

import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import config


SENSITIVE_CONTEXT_MARKERS = (
    "--user-data-dir",
    "--remote-debugging-port",
    "debug port",
    "chrome.exe",
    "chatgpt_profile",
    "chatgpt_profile_recon",
    "api_key",
    "api key",
    "token",
    "secret",
)


def _safe_text(value: Any, max_chars: int = 4000) -> str:
    text = str(value or "")
    for marker in SENSITIVE_CONTEXT_MARKERS:
        text = text.replace(marker, "[REDACTED]")
    return text[:max_chars]


def _run_git(args: list[str], cwd: Path) -> str:
    try:
        res = subprocess.run(
            ["git", *args],
            cwd=str(cwd),
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
    except Exception:  # noqa: BLE001 -- context collection is best-effort
        return ""
    if res.returncode != 0:
        return ""
    return (res.stdout or "").strip()


def safe_git_status_summary(work_dir: str | Path | None = None) -> str:
    """Return branch + short dirty summary without file contents or env details."""
    cwd = Path(work_dir or config.PROJECT_ROOT)
    branch = _run_git(["branch", "--show-current"], cwd) or "(unknown)"
    status = _run_git(["status", "--short"], cwd)
    lines = [line for line in status.splitlines() if line.strip()]
    shown = lines[:20]
    suffix = f"\n... {len(lines) - len(shown)} more changed paths" if len(lines) > len(shown) else ""
    body = "\n".join(shown) if shown else "(clean)"
    return _safe_text(f"branch: {branch}\nstatus:\n{body}{suffix}", 3000)


@dataclass(frozen=True)
class CouncilContextPack:
    original_task: str
    user_facing_objective: str = ""
    system_facing_objective: str = ""
    current_project_goal: str = ""
    active_constraints: list[str] = field(default_factory=list)
    forbidden_actions: list[str] = field(default_factory=list)
    safety_boundaries: list[str] = field(default_factory=list)
    available_tools_providers: list[str] = field(default_factory=list)
    git_status_summary: str = ""
    relevant_file_summaries: list[str] = field(default_factory=list)
    recent_test_results: list[str] = field(default_factory=list)
    known_browser_ui_state: str = ""
    execution_mode: str = "planning"
    prior_decisions: list[str] = field(default_factory=list)

    @classmethod
    def for_task(
        cls,
        task: str,
        *,
        work_dir: str | Path | None = None,
        constraints: list[str] | None = None,
        forbidden_actions: list[str] | None = None,
        safety_boundaries: list[str] | None = None,
    ) -> "CouncilContextPack":
        return cls(
            original_task=_safe_text(task, 8000),
            user_facing_objective=_safe_text(task, 2000),
            system_facing_objective="Produce a stronger pre-execution brief without executing the task.",
            current_project_goal="9to5 pre-execution planning and orchestration safety.",
            active_constraints=list(constraints or []),
            forbidden_actions=list(forbidden_actions or []),
            safety_boundaries=list(safety_boundaries or []),
            available_tools_providers=[
                "mock GPT seat",
                "mock Gemini seat",
                "mock Claude seat",
                "mock Local LLM seat",
                "live providers disabled in v0",
            ],
            git_status_summary=safe_git_status_summary(work_dir),
            execution_mode="mock-only pre-execution planning",
        )

    def to_safe_dict(self) -> dict[str, Any]:
        return {
            "original_task": _safe_text(self.original_task, 8000),
            "user_facing_objective": _safe_text(self.user_facing_objective, 2000),
            "system_facing_objective": _safe_text(self.system_facing_objective, 2000),
            "current_project_goal": _safe_text(self.current_project_goal, 2000),
            "active_constraints": [_safe_text(x, 1000) for x in self.active_constraints],
            "forbidden_actions": [_safe_text(x, 1000) for x in self.forbidden_actions],
            "safety_boundaries": [_safe_text(x, 1000) for x in self.safety_boundaries],
            "available_tools_providers": [_safe_text(x, 1000) for x in self.available_tools_providers],
            "git_status_summary": _safe_text(self.git_status_summary, 3000),
            "relevant_file_summaries": [_safe_text(x, 1500) for x in self.relevant_file_summaries],
            "recent_test_results": [_safe_text(x, 1500) for x in self.recent_test_results],
            "known_browser_ui_state": _safe_text(self.known_browser_ui_state, 1000),
            "execution_mode": _safe_text(self.execution_mode, 500),
            "prior_decisions": [_safe_text(x, 1000) for x in self.prior_decisions],
        }

    def summarize_for_prompt(self, max_chars: int = 6000) -> str:
        data = self.to_safe_dict()
        lines = [
            f"Original task: {data['original_task']}",
            f"User objective: {data['user_facing_objective']}",
            f"System objective: {data['system_facing_objective']}",
            f"Execution mode: {data['execution_mode']}",
            "Constraints: " + ("; ".join(data["active_constraints"]) or "(none provided)"),
            "Forbidden actions: " + ("; ".join(data["forbidden_actions"]) or "(none provided)"),
            "Safety boundaries: " + ("; ".join(data["safety_boundaries"]) or "(none provided)"),
            "Available providers/tools: " + "; ".join(data["available_tools_providers"]),
            f"Git summary:\n{data['git_status_summary']}",
        ]
        if data["relevant_file_summaries"]:
            lines.append("Relevant files: " + " | ".join(data["relevant_file_summaries"]))
        if data["recent_test_results"]:
            lines.append("Recent tests/logs: " + " | ".join(data["recent_test_results"]))
        if data["prior_decisions"]:
            lines.append("Prior decisions: " + " | ".join(data["prior_decisions"]))
        return _safe_text("\n".join(lines), max_chars)
