"""Adversary -- independent reviewer of executor output.

Phase 1 runs a REAL critique through the local Ollama brain (zero marginal API
cost). Phase 2 routes to Gemini via the google-genai SDK. The trigger and verdict
contract stay identical so the call site never changes.

Shared constants, helpers, and the Ollama ``review`` path live in
``agents.adversary_review``.  The Gemini-specific preamble lives in
``agents.adversary_browser``.

Trigger signals (per the 9TO5 spec):
  * uncertainty phrases in the executor output,
  * >= MAX_SUBTASK_ATTEMPTS attempts on the same subtask,
  * every Nth subtask as a heartbeat floor,
  * a pre-PR safety review.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  reviewViaBrowser(subtask_title: str, trigger_reason: str, executor_output: str, *, browser_ask: Optional[Callable]=None, goal: str='', review_type: str='subtask') -> dict  -- Phase-2 critique: route the review to Gemini via the google-genai SDK.
DEPENDS-ON: agents.adversary_browser, agents.adversary_review, agents.browser_executor, llm_io
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/orchestration/test_adversary.py
"""

from __future__ import annotations

import time
from typing import Callable, Optional

import llm_io  # noqa: F401 -- re-exported for test mocking (tests patch adv.llm_io)

from agents.adversary_review import (  # noqa: F401
    LOG,
    _APPROVED,
    _CHALLENGED,
    _CHALLENGE_WORDS,
    ADVERSARY_MAX_OUTPUT_CHARS,
    CDP_MAX_RETRIES,
    CDP_RETRY_BACKOFF_BASE,
    _CDP_TRANSIENT_SIGNALS,
    _SYSTEM,
    REVIEW_GUIDANCE,
    _APPROVE_WORDS,
    systemFor,
    isCdpTransient,
    shouldTrigger,
    _loadJsonLoose,
    _normalizeVerdict,
    _stubReview,
    _garbledChallenge,
    _buildReviewUser,
    _richFields,
    _parseVerdict,
    review,
)
from agents.adversary_browser import _GEMINI_PREAMBLE  # noqa: F401


def reviewViaBrowser(
    subtask_title: str,
    trigger_reason: str,
    executor_output: str,
    *,
    browser_ask: Optional[Callable] = None,
    goal: str = "",
    review_type: str = "subtask",
) -> dict:
    """Phase-2 critique: route the review to Gemini via the google-genai SDK.

    ``browser_ask`` is a ``(message) -> reply_text | None`` callable; it defaults to
    :func:`agents.browser_executor.askGemini`, which sends the review to Gemini through the
    second-brain session. The verdict contract is identical to :func:`review`, so the call site
    never changes between phases. (The name ``browser_ask`` / ``reviewViaBrowser`` is retained
    for call-site stability across the transport swap.)

    Transient network/API errors (timeout, dropped connection, 5xx) are retried up to
    ``CDP_MAX_RETRIES`` times with exponential backoff before falling back to a conservative
    auto-approve. Non-transient errors (bad JSON, empty reply, auth/rate-limit) skip retries and
    degrade immediately. The reviewer never blocks a run by itself.
    """
    if browser_ask is None:
        from agents import browser_executor

        browser_ask = browser_executor.askGemini

    user = _buildReviewUser(subtask_title, trigger_reason, executor_output, goal)
    message = f"{_GEMINI_PREAMBLE}\n\n{systemFor(review_type)}\n\n{user}"
    last_exc: Optional[Exception] = None

    for attempt in range(CDP_MAX_RETRIES + 1):
        try:
            reply = browser_ask(message)
            if not reply:
                raise ValueError("empty reply from Gemini")
            try:
                rv = _parseVerdict(reply, trigger_reason, surface="gemini", review_type=review_type)
            except Exception as pe:  # noqa: BLE001 -- responded but GARBLED -> fail closed (R10)
                LOG.warning("Adversary (Gemini) verdict garbled (%s); failing closed as CHALLENGED", pe)
                return _garbledChallenge(trigger_reason, pe, surface="gemini", review_type=review_type)
            LOG.info(
                "Adversary (Gemini) verdict for '%s' (%s) -> %s (%d concern(s))",
                subtask_title,
                trigger_reason,
                rv["verdict"],
                len(rv["concerns"]),
            )
            return rv
        except Exception as e:  # noqa: BLE001
            last_exc = e
            if attempt < CDP_MAX_RETRIES and isCdpTransient(e):
                wait = CDP_RETRY_BACKOFF_BASE * (2**attempt)
                LOG.warning(
                    "Adversary CDP transient error (attempt %d/%d, retry in %.1fs): %s",
                    attempt + 1,
                    CDP_MAX_RETRIES + 1,
                    wait,
                    e,
                )
                time.sleep(wait)
                continue
            # Non-transient or retries exhausted -- log and fall through.
            LOG.warning(
                "Adversary Gemini critique failed after %d attempt(s) (%s); "
                "recording UNREVIEWED (not approved)",
                attempt + 1,
                e,
            )
            break

    return _stubReview(
        trigger_reason,
        note=f"Adversary Gemini critique errored ({last_exc}); recorded UNREVIEWED (no critique ran).",
    )


