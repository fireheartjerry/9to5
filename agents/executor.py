def runClaude(spec_or_prompt: Union[dict, str], *, work_dir: Optional[str] = None,
              task_state=None, subtask: Optional[dict] = None,
              system_prompt: Optional[str] = None, extra: Optional[str] = None,
              timeout: Optional[int] = None, resume_session: Optional[str] = None,
              cancel_check=None, feed=None,
              parent_trajectory_step_id: Optional[str] = None) -> dict:
    """Prepare the environment from the invocation spec, then fire one Claude run.
    Returns result dict with ok/returncode/stdout/stderr/profile/effort/cost_usd/session_id etc.
    ``feed`` (optional SubprocessFeed) taps stdout line-by-line for the live surfaces."""
    spec = normalizeSpec(spec_or_prompt)
    timeout = timeout or config.CLAUDE_CLI_TIMEOUT_SECONDS
    ctx = _prepareEnv(spec, work_dir, task_state, subtask, system_prompt, extra, resume_session)
    work, effort, flag = ctx["work"], ctx["effort"], ctx["flag"]
    profile, playbook_md, claude_md_path = ctx["profile"], ctx["playbook_md"], ctx["claude_md_path"]
    full_prompt, resume_prompt, is_resume = ctx["full_prompt"], ctx["resume_prompt"], ctx["is_resume"]
    # block_destructive guardrail: headless mode bypasses Claude hooks so we enforce it here.
    # Scan the ACTUAL prompt sent (includes folded claude_md_inject on resume retries).
    prompt_to_send = resume_prompt if is_resume else full_prompt
    if "block_destructive" in (spec.get("pre_tool_hooks") or []):
        hits = scanDestructive(prompt_to_send)
        if hits:
            reason = f"block_destructive refused subtask -- prompt contains {hits}"
            LOG.warning(reason)
            _alertBlocked(reason)
            return {"ok": False, "returncode": -1, "stdout": "", "stderr": reason, "blocked": True,
                    "effort": effort, "effort_flag": flag, "spec": spec, "claude_md_path": claude_md_path}
    try:
        fresh_cmd, resume_cmd, env, creationflags, model = _buildRunConfig(
            spec, task_state, subtask, resume_session,
            work=work, effort=effort, flag=flag, charter=ctx["charter"],
            claude_md_path=claude_md_path,
            parent_trajectory_step_id=parent_trajectory_step_id)
    except FileNotFoundError as e:
        LOG.error("%s", e)
        return {"ok": False, "returncode": -1, "stdout": "", "stderr": str(e),
                "effort": effort, "effort_flag": flag, "spec": spec, "claude_md_path": claude_md_path}
    run_kw = dict(work=work, timeout=timeout, env=env, creationflags=creationflags,
                  spec=spec, effort=effort, flag=flag, profile=profile,
                  playbook_md=playbook_md, claude_md_path=claude_md_path, model=model, feed=feed)
    if not is_resume:
        result = runSubprocess(fresh_cmd, full_prompt, **run_kw)
    else:
        result = runSubprocess(resume_cmd, resume_prompt, **run_kw)
        # Stale / unresumable session (nonzero rc, no envelope) -> retry once on a fresh session.
        rc = result.get("returncode")
        if config.EXECUTOR_OUTPUT_JSON and result.get("is_error") is None and isinstance(rc, int) and rc > 0:
            LOG.warning("resume launch yielded no envelope (rc=%s) -- retrying once on a fresh session", rc)
            result = runSubprocess(fresh_cmd, full_prompt, **run_kw)
    # Session token limit: wait out the window then retry on a fresh session.
    # BOUNDED + abort/deadline-aware (CB-4/9); re-arm each round to guarantee a real wait.
    tries = 0
    while _isRateLimitError(result) and tries < config.SESSION_LIMIT_MAX_RETRIES:
        if cancel_check is not None:
            try:
                if cancel_check():
                    LOG.warning("rate-limit retry abandoned (abort/deadline) after %d tries", tries)
                    break
            except Exception:  # noqa: BLE001
                pass
        _SESSION_LIMIT_STATE["first_hit_at"] = time.time()   # re-arm: guarantee a real wait
        if not _waitForSessionReset(cancel_check):
            break   # cancelled mid-wait -> return still-error result to caller
        tries += 1
        LOG.info("Retrying subtask on fresh session after session reset (try %d/%d)",
                 tries, config.SESSION_LIMIT_MAX_RETRIES)
        result = runSubprocess(fresh_cmd, full_prompt, **run_kw)
    return result
