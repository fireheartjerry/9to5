"""gemini_driver -- the second-brain transport: Google Gemini via the google-genai SDK.

This replaces the Phase-2 chatgpt.com / CDP browser driver. GPT-5.5-over-a-browser was slow,
bot-detectable, and DOM-fragile (it needed Playwright, a logged-in Chrome profile, self-healing
selectors, and a dedicated thread for sync-Playwright affinity). Gemini through the official
``google-genai`` SDK is a stateless HTTPS call: no Playwright, no threads, no DOM, no profile --
just ``client.chats.create(...).send_message(...)``.

The session contract the rest of 9to5 relies on is UNCHANGED -- ``health_probe`` /
``start_run_conversation`` / ``ask`` / ``close`` -- so ``agents/browser_executor.py`` and
``agents/second_brain.py`` keep routing through it identically; only the transport swapped.

Design rules (mirrors the old driver so the safety properties hold):
  * ``from google import genai`` is imported LAZILY inside the session, so this module imports
    cleanly with the SDK absent and the caller degrades to the Ollama brain.
  * Every failure surfaces as a typed ``GeminiError`` subclass; ``second_brain`` maps the FATAL
    ones (auth / blocked / rate-limit) to "disable GPT for the rest of the run". The session
    NEVER blocks a run.
  * Under a test runner, a real API call is REFUSED (mirrors the old ``_realBrowserBlocked``) so a
    forgotten mock can never burn live quota or leak the key.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  GeminiError  -- Base for any Gemini transport failure.
  GeminiAuthError  -- Missing / invalid API key (fatal: GPT unreachable for the whole run).
  GeminiBlocked  -- A safety / permission block (fatal).
  GeminiRateLimited  -- Gemini reported a quota / rate limit (fatal).
  GeminiUnavailable  -- SDK not installed or a transient transport error (non-fatal).
  GeminiSession  -- A long-lived Gemini chat session; one conversation per run.
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_gemini_driver.py
"""
from __future__ import annotations

import os
import re
import sys
from typing import Any, Optional

import config

LOG = config.getLogger("gemini_driver")


def _realApiBlocked() -> bool:
    """True when a REAL Gemini API call must be REFUSED (unit/CI context).

    A live call costs quota and uses the real API key; a test that reaches this path would do
    so slowly and non-deterministically. Mirrors the old driver's ``_realBrowserBlocked`` and
    ``notifications.work_launcher._spawnBlocked``: production never imports pytest/unittest and
    never sets the env var, so real runs are unaffected. A deliberate live script opts in with
    ``NINE_TO_FIVE_ALLOW_REAL_API=1``."""
    allow = os.getenv("NINE_TO_FIVE_ALLOW_REAL_API", "").strip().lower()
    if allow in {"1", "true", "yes", "on"}:
        return False                       # explicit opt-in: a real, intentional live call
    env = os.getenv("NINE_TO_FIVE_TEST_MODE", "").strip().lower()
    if env in {"0", "false", "no", "off"}:
        return False
    if env in {"1", "true", "yes", "on"}:
        return True
    # env unset -> auto-detect a live test runner so a forgotten mock never hits the API.
    return "pytest" in sys.modules or "unittest" in sys.modules


# --- typed failures -------------------------------------------------------------------------
class GeminiError(RuntimeError):
    """Base for any Gemini transport failure."""


class GeminiAuthError(GeminiError):
    """Missing / invalid API key (analogue of the old login wall)."""


class GeminiBlocked(GeminiError):
    """A safety / permission block stopped the response (analogue of a Cloudflare wall)."""


class GeminiRateLimited(GeminiError):
    """Gemini reported a usage / rate / quota limit."""


class GeminiUnavailable(GeminiError):
    """The SDK is not installed, blocked under a test runner, or a transient transport error.

    Non-fatal: the caller retries (transient) or degrades to the Ollama brain."""


def _raiseTyped(exc: Exception) -> None:
    """Re-raise an SDK exception as the right typed ``GeminiError`` so second_brain can decide
    whether GPT is dead for the whole run (auth/blocked/rate-limit) or just had a hiccup."""
    code = getattr(exc, "code", None) or getattr(exc, "status_code", None)
    msg = str(exc).lower()
    if code == 429 or any(s in msg for s in ("rate limit", "quota", "resource_exhausted", "429")):
        raise GeminiRateLimited(str(exc)) from exc
    if code in (401, 403) or any(
        s in msg for s in ("api key", "api_key", "unauthenticated", "permission_denied",
                            "permission denied", "invalid authentication")):
        raise GeminiAuthError(str(exc)) from exc
    raise GeminiUnavailable(str(exc)) from exc


def _looks_like_json(text: Optional[str]) -> bool:
    t = (text or "").strip()
    if t.startswith("```"):
        t = re.sub(r"^```(?:json)?\s*|\s*```$", "", t, flags=re.IGNORECASE).strip()
    return t.startswith("{") and t.endswith("}")


def _response_text(resp: Any) -> str:
    """Pull the reply text out of a GenerateContentResponse, tolerating SDK shape changes and a
    blocked/empty response (``resp.text`` can raise or be None when the candidate has no parts)."""
    try:
        t = resp.text
    except Exception:  # noqa: BLE001 -- blocked/empty response: .text accessor can raise
        t = None
    if t:
        return t.strip()
    try:
        for cand in (getattr(resp, "candidates", None) or []):
            parts = getattr(getattr(cand, "content", None), "parts", None) or []
            joined = "".join(getattr(p, "text", "") or "" for p in parts)
            if joined.strip():
                return joined.strip()
    except Exception:  # noqa: BLE001
        pass
    return ""


def _finish_reason(resp: Any) -> str:
    try:
        return str(resp.candidates[0].finish_reason or "")
    except Exception:  # noqa: BLE001
        return ""


class GeminiSession:
    """A long-lived Gemini chat session. Open once per run; reuse for every review so the model
    accumulates run context across subtask critiques (cheaper, more grounded). Stateless HTTPS
    under the hood -- thread-safe, so no dedicated worker thread is needed (unlike sync Playwright)."""

    def __init__(self) -> None:
        self._client = None
        self._types = None
        self._chat = None
        self._turns = 0
        self.opened = False

    # -- lifecycle ---------------------------------------------------------------------------
    def _build_client(self):
        """Lazily construct the genai client. Raises a typed GeminiError so the caller degrades:
        GeminiUnavailable if blocked under a test runner or the SDK is missing, GeminiAuthError
        if no key is configured."""
        if _realApiBlocked():
            raise GeminiUnavailable(
                "real Gemini API call blocked under a test runner (mock the session, or set "
                "NINE_TO_FIVE_ALLOW_REAL_API=1 for a deliberate live run). This guard keeps tests "
                "off the live API/quota.")
        if not config.GEMINI_API_KEY:
            raise GeminiAuthError("GEMINI_API_KEY is not set; cannot reach Gemini.")
        try:
            from google import genai  # type: ignore
            from google.genai import types  # type: ignore
        except Exception as e:  # noqa: BLE001
            raise GeminiUnavailable(
                "google-genai not installed: `pip install google-genai`") from e
        return genai.Client(api_key=config.GEMINI_API_KEY), types

    def open(self) -> None:
        if self.opened:
            return
        self._client, self._types = self._build_client()
        self.opened = True

    def close(self) -> None:
        self._client = self._types = self._chat = None
        self.opened = False

    def _gen_config(self, *, system_instruction: Optional[str] = None, json: bool = False):
        """Build a GenerateContentConfig: optional system instruction, JSON-only mime when the
        caller wants structured output, and the per-request timeout."""
        kwargs: dict[str, Any] = {
            "http_options": self._types.HttpOptions(timeout=config.GEMINI_TIMEOUT_MS),
        }
        if system_instruction:
            kwargs["system_instruction"] = system_instruction
        if json:
            kwargs["response_mime_type"] = "application/json"
        return self._types.GenerateContentConfig(**kwargs)

    # -- run conversation --------------------------------------------------------------------
    def start_run_conversation(self, goal: str, task_id: str) -> None:
        """Open a fresh chat for this run with the second-brain system instruction (and the run
        goal). Every ``ask`` then accumulates context inside this one conversation."""
        self.open()
        sys_inst = config.GEMINI_SYSTEM_PREAMBLE
        if goal:
            sys_inst = f"{sys_inst}\n\nThis run's overall goal: {goal[:1000]}"
        try:
            self._chat = self._client.chats.create(
                model=config.GEMINI_MODEL,
                config=self._gen_config(system_instruction=sys_inst, json=True),
            )
        except Exception as e:  # noqa: BLE001
            _raiseTyped(e)
        self._turns = 0
        LOG.info("started Gemini run conversation for task %s (model=%s)",
                 task_id, config.GEMINI_MODEL)

    # -- run-start health probe --------------------------------------------------------------
    def health_probe(self) -> bool:
        """Confirm Gemini is reachable + the key is valid before a run relies on it. Returns False
        (never raises) on any problem so the orchestrator can fall back to Ollama for the run."""
        try:
            self.open()
            resp = self._client.models.generate_content(
                model=config.GEMINI_MODEL, contents="ping",
                config=self._gen_config())
            ok = bool(_response_text(resp))
            if ok:
                LOG.info("Gemini health probe passed (model=%s reachable)", config.GEMINI_MODEL)
            else:
                LOG.warning("Gemini health probe got an empty reply")
            return ok
        except Exception as e:  # noqa: BLE001
            LOG.warning("Gemini health probe failed: %s", e)
            self.close()
            return False

    # -- the one verb everything routes through ----------------------------------------------
    def ask(self, message: str, *, expect_json: bool = False) -> Optional[str]:
        """Send one message in the run conversation and return Gemini's completed reply text.

        Raises a typed ``GeminiError`` on auth/blocked/rate-limit so the Adversary can fall back
        to the Ollama brain. When ``expect_json`` and the reply isn't a JSON object, sends up to
        ``GEMINI_JSON_REPAIR_RETRIES`` 'reply JSON only' nudges before returning what it has."""
        self.open()
        if self._chat is None:
            self.start_run_conversation(goal="", task_id="adhoc")
        if self._turns >= config.GEMINI_MAX_TURNS:
            LOG.info("conversation hit %d turns; rolling over to a fresh chat", self._turns)
            self.start_run_conversation(goal="", task_id="rollover")

        reply = self._send(message)
        self._turns += 1

        if expect_json and not _looks_like_json(reply):
            for _ in range(max(0, config.GEMINI_JSON_REPAIR_RETRIES)):
                LOG.info("reply not JSON; sending repair nudge")
                reply = self._send(
                    "Your previous reply was not valid JSON. Reply with ONLY the JSON object, "
                    "no prose, no code fence.")
                self._turns += 1
                if _looks_like_json(reply):
                    break
            if not _looks_like_json(reply):
                # Still prose after every repair nudge. Return None -- NOT the prose -- so the
                # caller treats it as 'no usable reply' (Ollama fallback) instead of mis-parsing
                # prose as a verdict.
                LOG.warning("Gemini reply still not JSON after %d repair attempt(s); no reply",
                            max(0, config.GEMINI_JSON_REPAIR_RETRIES))
                return None
        return reply or None

    def _send(self, message: str) -> str:
        try:
            resp = self._chat.send_message(message)
        except Exception as e:  # noqa: BLE001
            _raiseTyped(e)
        text = _response_text(resp)
        if not text:
            fr = _finish_reason(resp)
            if fr and any(s in fr.lower() for s in ("safety", "blocklist", "prohibited", "recitation")):
                raise GeminiBlocked(f"Gemini blocked the response (finish_reason={fr})")
        return text
