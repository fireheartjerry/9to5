"""Verification runner facade -- thin delegate to the ONE typed Receipt pipeline.

R10: the pipeline (sanitize -> arg-vector execution -> STRICT expect -> diff-grounded
targets) lives in ``agents.verification``. This module keeps the legacy entry point and
private helper names alive for one release:

  * ``runVerification`` returns the legacy vresult dict shape (a ``VResult`` -- a dict
    subclass carrying the typed ``.receipt``).
  * The silent test-runner override (rc==0 flipping FAIL->PASS when the expect needle
    missed) is DELETED: expect is evaluated strictly; the brain authors ``exit_zero``
    for test runners (plan_prompts VERIFY RULES ship in the same patch).

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  runVerification(verify: Optional[dict], work_dir: str, executor_result: dict, *, declared_targets=None, cancel_check=None, authority=None) -> dict  -- Run the ONE Receipt pipeline and return the legacy vresult dict shape.
DEPENDS-ON: agents.verification, config
SIDE-EFFECTS: runs the acceptance subprocess; reads git status
RUN/TEST: python -m pytest tests/execution/test_verifier_runner.py
"""
from __future__ import annotations

from typing import Optional

import config
from agents import verification
from agents.verification import (  # noqa: F401 -- legacy import paths kept one release
    _COMPOUND_PREFIXES,
    Receipt,
    Verdict,
    VResult,
    _cap,
)

LOG = config.getLogger("verifier")


def _evaluate(expect: str, returncode: int, stdout: str) -> bool:
    """Legacy boolean view of the PURE verdict function (kept for existing callers)."""
    verdict, _matched, _missing = verification.verdictFor(returncode, stdout, expect)
    return verdict is verification.Verdict.PASS


def _verifyTimeoutSeconds(cmd: str) -> int:
    """A broad pytest/unittest suite run needs more wall-clock than a narrow one-shot
    check -- purely a scheduling knob, no verdict-logic special case (R10 stays intact)."""
    head = " ".join(cmd.strip().split()[:3]).lower()
    if "pytest" in head or "unittest" in head:
        return config.VERIFY_SUITE_TIMEOUT_SECONDS
    return config.VERIFY_TIMEOUT_SECONDS


def runVerification(verify: Optional[dict], work_dir: str, executor_result: dict, *,
                    declared_targets=None, cancel_check=None, authority=None) -> dict:
    """Run the ONE Receipt pipeline and return the legacy vresult dict shape.

    {passed, cmd, expect, returncode, stdout, stderr} -- a ``VResult`` dict subclass;
    the typed ``Receipt`` rides on ``.receipt`` for annotation-aware consumers."""
    cmd = (verify or {}).get("cmd") if isinstance(verify, dict) else None
    timeout_seconds = _verifyTimeoutSeconds(cmd) if cmd else None
    receipt = verification.runReceipt(verify, work_dir, executor_result,
                                      declared_targets=declared_targets,
                                      cancel_check=cancel_check, timeout_seconds=timeout_seconds,
                                      authority=authority)
    return verification.receiptToVResult(receipt)
