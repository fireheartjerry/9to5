"""Sanitization guard for brain-authored verify specs.

Drops structurally-unreliable verify commands before they reach the shell so
a confused brain can never author a destructive or un-runnable check.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  sanitizeVerify(verify: Optional[dict]) -> Optional[dict]  -- Drop a structurally-unreliable brain-authored verify so the subtask falls back to
DEPENDS-ON: config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_verifier.py
"""

from __future__ import annotations

import os
import re
import shlex
from typing import Optional

import config

LOG = config.getLogger("verifier")

# ==== ALLOWLISTS / DENYLISTS ====

_VERIFY_STDLIB_OK = {
    "os",
    "sys",
    "json",
    "re",
    "pathlib",
    "math",
    "io",
    "time",
    "datetime",
    "collections",
    "itertools",
    "functools",
    "typing",
    "string",
    "random",
    "statistics",
    "textwrap",
    "glob",
    "argparse",
    "csv",
    "hashlib",
    "base64",
    "unittest",
    "decimal",
    "fractions",
    "ast",
}
# subprocess/shutil deliberately NOT allowed: a verify must only OBSERVE, never mutate.
_VERIFY_DESTRUCTIVE_CALLS = {
    "system",
    "popen",
    "remove",
    "unlink",
    "rmdir",
    "removedirs",
    "rename",
    "replace",
    "truncate",
    "rmtree",
    "move",
    "chmod",
    "chown",
    "kill",
    "killpg",
    "execv",
    "execve",
}
_VERIFY_DESTRUCTIVE_NAMES = {"eval", "exec", "compile", "__import__"}
_PROVIDER_EXECUTABLE_NAMES = frozenset(
    f"{provider}{suffix}"
    for provider in ("claude", "codex", "ollama")
    for suffix in ("", ".exe", ".com", ".cmd", ".bat", ".ps1")
)


# ==== SUB-CHECKS ====


def _checkAngleBrackets(cmd: str) -> bool:
    """Return True if cmd should be dropped: unresolved placeholder / redirection / Windows .sh."""
    if "<" in cmd or ">" in cmd or "absolute path" in cmd.lower():
        LOG.info("sanitizeVerify: dropping verify with unresolved placeholder / redirection: %s", cmd)
        return True
    if os.name == "nt" and (re.search(r"\.sh\b", cmd.lower()) or re.match(r"(?:bash|sh)\s", cmd.lower())):
        LOG.info("sanitizeVerify: dropping non-Windows shell verify: %s", cmd)
        return True
    return False


def _hasProviderExecutable(cmd: str) -> bool:
    """Recognize obvious provider executables as lexical defense-in-depth.

    The transactional launch guard remains the authority boundary and rejects every
    verification subprocess during Tasks 1/2.  This narrower check prevents the plain
    provider names from becoming acceptance commands after that embargo is replaced,
    without treating filenames such as ``test_claude_sdk_bridge.py`` as executables.
    """
    try:
        lex = shlex.shlex(cmd, posix=False)
        lex.whitespace_split = True
        lex.commenters = ""
        tokens = list(lex)
    except ValueError:
        return True
    for token in tokens:
        # Wrapper commands can place their payload in one quoted token, e.g.
        # ``powershell -Command "codex --version"``. Split that payload once,
        # then compare only exact executable basenames rather than raw prose.
        for part in token.strip("'\"").split():
            leaf = part.strip("'\"").replace("\\", "/").rsplit("/", 1)[-1]
            if leaf.casefold() in _PROVIDER_EXECUTABLE_NAMES:
                return True
    return False


def _validatePythonOneliner(code: str, cmd: str) -> bool:
    """Return True if the python -c body is safe to run; False means drop the whole verify."""
    import ast as _ast

    try:
        tree = _ast.parse(code, "<verify>", "exec")
    except SyntaxError:
        LOG.info("sanitizeVerify: dropping malformed python -c verify: %s", cmd)
        return False
    for node in _ast.walk(tree):
        mods: list[str] = []
        if isinstance(node, _ast.Import):
            mods = [a.name.split(".")[0] for a in node.names]
        elif isinstance(node, _ast.ImportFrom) and node.module:
            mods = [node.module.split(".")[0]]
        for mod in mods:
            if mod not in _VERIFY_STDLIB_OK:
                LOG.info("sanitizeVerify: dropping verify importing non-stdlib '%s': %s", mod, cmd)
                return False
        if isinstance(node, _ast.Call):
            fn = node.func
            if isinstance(fn, _ast.Attribute) and fn.attr in _VERIFY_DESTRUCTIVE_CALLS:
                LOG.info("sanitizeVerify: dropping verify with destructive call '.%s': %s", fn.attr, cmd)
                return False
            if isinstance(fn, _ast.Name) and fn.id in _VERIFY_DESTRUCTIVE_NAMES:
                LOG.info("sanitizeVerify: dropping verify with destructive call '%s': %s", fn.id, cmd)
                return False
    return True


def _isUnquotedPythonDashC(cmd: str) -> bool:
    """True if ``cmd`` is a ``python -c`` invocation whose body is NOT cleanly extractable
    via the quote-wrapped regex in ``sanitizeVerify`` -- e.g. an unquoted single-token body
    with no shell metacharacters, which would otherwise skip AST validation entirely. Uses
    the same Windows-aware, non-posix arg-vector split as the real run path
    (``agents.verification._splitCmd``) so detection matches actual execution semantics.
    A parse failure (unbalanced quotes) also returns True (fail closed)."""
    try:
        lex = shlex.shlex(cmd, posix=False)
        lex.whitespace_split = True
        toks = list(lex)
    except ValueError:
        return True  # unbalanced quotes etc. -- can't reliably extract the body, fail closed
    if len(toks) < 2:
        return False
    interpreter = toks[0].strip("'\"").lower()
    return interpreter in ("py", "python", "python3") and toks[1] == "-c"


# ==== PUBLIC API ====


def _targetsOnly(verify: dict) -> Optional[dict]:
    """A cmd-less verify may still declare target files (R10 diff grounding): keep JUST the
    targets so the receipt pipeline can fail an unchanged declared target. None otherwise."""
    targets = [str(t) for t in (verify.get("targets") or []) if t]
    return {"targets": targets} if targets else None


def sanitizeVerify(verify: Optional[dict]) -> Optional[dict]:
    """Drop a structurally-unreliable brain-authored verify so the subtask falls back to
    'executor exited 0' instead of failing forever on a bad check.

    Catches: a malformed ``python -c`` one-liner (SyntaxError), a ``python -c`` that
    imports a non-stdlib / project module (the 'guessed internal symbol' pattern), AND
    (R10) a verify with NO expect -- the plan sanitizer rejects it here so the runner
    never guesses one (expect is evaluated strictly downstream).
    """
    if not isinstance(verify, dict):
        return None
    cmd_raw = verify.get("cmd")
    cmd = cmd_raw.strip() if isinstance(cmd_raw, str) else ""
    if not cmd:
        return _targetsOnly(verify)
    if _checkAngleBrackets(cmd):
        return _targetsOnly(verify)
    if _hasProviderExecutable(cmd):
        LOG.info("sanitizeVerify: dropping provider-shaped verify command: %s", cmd)
        return _targetsOnly(verify)
    expect = verify.get("expect")
    if not (isinstance(expect, str) and expect.strip()):
        LOG.info(
            "sanitizeVerify: dropping verify with missing expect (the runner never guesses one): %s", cmd
        )
        return _targetsOnly(verify)
    m = re.match(r"""(?:py|python|python3)\s+-c\s+(['"])(.*)\1\s*$""", cmd, re.DOTALL)
    if m and not _validatePythonOneliner(m.group(2), cmd):
        return _targetsOnly(verify)
    # A python -c body that isn't cleanly quote-extractable (e.g. an unquoted single-token
    # body) would otherwise skip AST validation entirely -- fail closed instead.
    if m is None and _isUnquotedPythonDashC(cmd):
        LOG.info("sanitizeVerify: dropping unquoted/unvalidatable python -c verify: %s", cmd)
        return _targetsOnly(verify)
    # Defense-in-depth: non-python-c commands with shell-chaining metacharacters get dropped.
    # A MATCHED python -c is exempt: its body is ast-validated and the closing quote ends it.
    if m is None and re.search(r"[;&|`\n]|\$\(", cmd):
        LOG.info("sanitizeVerify: dropping verify with shell-chaining metacharacters: %s", cmd)
        return _targetsOnly(verify)
    return verify
