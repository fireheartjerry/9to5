"""Verification with ONE owner (R10): the typed Receipt pipeline.

Every acceptance check flows through ``runReceipt`` in this module, strictly ordered:
  (a) sanitize MANDATORY (``verifier_sanitize``) -- call sites never pre-sanitize;
  (b) execute the acceptance command as an ARG-VECTOR (no shell) through the tree-kill
      runner, honoring ``cancel_check``;
  (c) evaluate ``expect`` STRICTLY -- ``verdictFor`` is a PURE function of
      (rc, output, expect); there is NO test-runner special case that flips FAIL->PASS,
      and the runner NEVER guesses a missing expect (the sanitizer rejects it);
  (d) diff-ground declared target files: if the subtask declares targets and git shows
      none of them changed, the receipt FAILS with actionable feedback (this replaces
      the deleted token-scan synthesizer -- a goal word in a comment proves nothing).

Envelope self-reports, the independent verifier, and the adversary verdict are
ANNOTATIONS on the one Receipt -- never verdict overrides.

Compat: ``VResult`` (a dict subclass carrying ``.receipt``/``.passed``) preserves the
legacy vresult dict shape for one release; ``verifier_runner.runVerification`` returns it.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  Verdict
  Receipt  -- The single typed verification result
  annotate(receipt: Receipt, key: str, value) -> None  -- Attach a non-binding annotation (envelope / independent verify / adversary).
  VResult  -- One-release compat shim: the legacy vresult dict shape, carrying the typed Receipt.
  verdictFor(rc, output: str, expect) -> 'tuple[Verdict, tuple, tuple]'  -- PURE function of (rc, output, expect) -> (verdict, matched, missing).
  VerifyCancelled  -- cancel_check fired while the acceptance command was running.
  runReceipt(verify: Optional[dict], work_dir: str, executor_result: dict, *, declared_targets=None, cancel_check=None, timeout_seconds: Optional[int]=None) -> Receipt  -- THE verification pipeline (single owner)
  receiptToVResult(receipt: Receipt) -> VResult  -- The legacy vresult dict shape from a Receipt (compat shim, one release).
DEPENDS-ON: agents.executor, agents.verification_diff, agents.verifier_sanitize, config
SIDE-EFFECTS: runs the acceptance subprocess; reads git status
RUN/TEST: python -m pytest tests/execution/test_verification_diff.py tests/orchestration/test_bridge_verification.py
"""
