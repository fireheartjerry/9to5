def _cap(text: Optional[str]) -> str:
    text = text or ""
    return text if len(text) <= _MAX_CAP else text[:_MAX_CAP] + "\n...[truncated]"


def _skippedReceipt(executor_result: dict, declared: "tuple[str, ...]",
                    work_dir: str) -> Receipt:
    """No behavioral check ran: the executor's own exit is the only signal. Declared
    targets are STILL diff-grounded -- an unchanged declared target FAILS (R10c)."""
    ok = bool(executor_result.get("ok"))
    try:
        changed = changedFiles(work_dir) if declared else None
    except (ValueError, TypeError, KeyError, OSError) as e:
        LOG.warning("changedFiles error: %s", e)
        changed = None
    grounded_ok, ground_fb = _checkDeclaredTargets(work_dir, declared, None, changed)
    if ok and not grounded_ok:
        return Receipt(verdict=Verdict.FAIL, cmd=(), rc=executor_result.get("returncode"),
                       expect_mode="executor_exit_zero", matched=(), missing=tuple(declared),
                       diff_files=tuple(sorted(changed or ())), duration_s=0.0,
                       failure_feedback=ground_fb,
                       annotations={"stdout": "", "stderr": "", "diff_grounded": "failed"})
    verdict = Verdict.SKIPPED
    stderr = "" if ok else _cap(executor_result.get("stderr"))
    return Receipt(verdict=verdict, cmd=(), rc=executor_result.get("returncode"),
                   expect_mode="executor_exit_zero", matched=(), missing=(),
                   diff_files=tuple(sorted(changed or ())), duration_s=0.0,
                   failure_feedback="" if ok else (stderr or "executor exited non-zero"),
                   annotations={"stdout": "", "stderr": stderr, "executor_ok": ok})


def _errorReceipt(argv, cmd: str, expect: str, feedback: str, duration: float) -> Receipt:
    return Receipt(verdict=Verdict.ERROR, cmd=tuple(argv or ()), rc=-1,
                   expect_mode=_expectMode(expect), matched=(), missing=(),
                   diff_files=(), duration_s=duration, failure_feedback=feedback,
                   annotations={"stdout": "", "stderr": feedback,
                                "cmd_str": cmd, "expect_str": expect})


def runReceipt(verify: Optional[dict], work_dir: str, executor_result: dict, *,
               declared_targets=None, cancel_check=None, timeout_seconds: Optional[int] = None,
               authority: object = None) -> Receipt:
    """THE verification pipeline (single owner). See module docstring for the order."""
    executor_result = executor_result if isinstance(executor_result, dict) else {}
    raw_targets = tuple(str(t) for t in (
        declared_targets
        or ((verify or {}).get("targets") if isinstance(verify, dict) else None)
        or ()) if t)
    verify = sanitizeVerify(verify)                    # (a) MANDATORY, inside the owner
    cmd = (verify or {}).get("cmd") if isinstance(verify, dict) else None
    if not cmd:
        return _skippedReceipt(executor_result, raw_targets, work_dir)

    expect = str(verify.get("expect"))                 # sanitizer guarantees a non-empty str
    try:
        argv = _splitCmd(cmd)
    except (ValueError, TypeError) as e:
        return _errorReceipt([], cmd, expect, f"cmd parse error: {e}", 0.0)
    LOG.info("Verifying (vector): %s  (expect: %s)", argv, expect)
    t0 = time.monotonic()
    try:
        proc = _runVector(
            authority,
            argv,
            work_dir,
            cancel_check=cancel_check,
            timeout_seconds=timeout_seconds,
        )
    except subprocess.TimeoutExpired:
        limit = timeout_seconds if timeout_seconds is not None else config.VERIFY_TIMEOUT_SECONDS
        return _errorReceipt(argv, cmd, expect, f"verify TIMEOUT after {limit}s",
                             time.monotonic() - t0)
    except VerifyCancelled:
        return _errorReceipt(argv, cmd, expect, "verification cancelled (operator kill / deadline)",
                             time.monotonic() - t0)
    except Exception as e:  # noqa: BLE001
        return _errorReceipt(argv, cmd, expect, f"verify error: {e}", time.monotonic() - t0)
    duration = time.monotonic() - t0
    # Fold stderr into the haystack ONLY when the program exited cleanly (rc==0).
    haystack = (proc.stdout or "") + (("\n" + (proc.stderr or "")) if proc.returncode == 0 else "")
    verdict, matched, missing = verdictFor(proc.returncode, haystack, expect)   # (c) STRICT

    try:
        changed = changedFiles(work_dir)
    except (ValueError, TypeError, KeyError, OSError) as e:
        LOG.warning("changedFiles error: %s", e)
        changed = None
    grounded_ok, ground_fb = True, ""
    if verdict is Verdict.PASS and raw_targets:
        try:
            grounded_ok, ground_fb = _checkDeclaredTargets(work_dir, raw_targets, cmd, changed)  # (d)
        except (ValueError, TypeError, KeyError) as e:
            LOG.warning("diff-grounding error: %s", e)
            grounded_ok, ground_fb = True, ""
        if not grounded_ok:
            verdict = Verdict.FAIL

    feedback = ""
    if verdict is not Verdict.PASS:
        if not grounded_ok:
            feedback = ground_fb
        elif verdict is Verdict.ERROR:
            feedback = (f"expect {expect!r} could not be evaluated strictly -- author one of the "
                        "documented shapes (exit_zero / stdout_contains:<s> / stdout_regex:<p> / "
                        "compound *_all forms)")
        elif missing:
            feedback = (f"expect {expect!r} not satisfied: missing {list(missing)!r} "
                        f"(rc={proc.returncode})")
        else:
            feedback = f"command exited rc={proc.returncode} (expect {expect!r})"
    annotations = {"stdout": _cap(proc.stdout), "stderr": _cap(proc.stderr),
                   "cmd_str": cmd, "expect_str": expect}
    if not grounded_ok:
        annotations["diff_grounded"] = "failed"
    receipt = Receipt(verdict=verdict, cmd=tuple(argv), rc=proc.returncode,
                      expect_mode=_expectMode(expect), matched=matched, missing=missing,
                      diff_files=tuple(sorted(changed or ())), duration_s=round(duration, 3),
                      failure_feedback=feedback, annotations=annotations)
    LOG.info("Verify %s -> %s (rc=%s)", receipt.verdict.value.upper(), cmd, proc.returncode)
    return receipt


def receiptToVResult(receipt: Receipt) -> VResult:
    """The legacy vresult dict shape from a Receipt (compat shim, one release)."""
    if receipt.expect_mode == "executor_exit_zero":     # no-cmd path keeps legacy fallback pass
        passed = bool(receipt.annotations.get("executor_ok")) \
            if receipt.verdict is Verdict.SKIPPED else receipt.passed
        stderr = receipt.annotations.get("stderr", "") or receipt.failure_feedback
        return VResult(receipt, {
            "passed": passed, "cmd": None, "expect": "executor_exit_zero",
            "returncode": receipt.rc, "stdout": "",
            "stderr": "" if passed else stderr,
        })
    stderr = receipt.annotations.get("stderr", "")
    if receipt.failure_feedback and receipt.annotations.get("diff_grounded") == "failed":
        stderr = (stderr + "\n" + receipt.failure_feedback).strip()
    return VResult(receipt, {
        "passed": receipt.passed,
        "cmd": receipt.annotations.get("cmd_str"),
        "expect": receipt.annotations.get("expect_str"),
        "returncode": receipt.rc,
        "stdout": receipt.annotations.get("stdout", ""),
        "stderr": stderr,
    })
