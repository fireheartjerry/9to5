LOG = config.getLogger("verifier")

_MAX_CAP = 2000  # truncate captured output

# THE single copy (R10 dedup): verifier.py imports this; the old verifier_runner copy is gone.
_COMPOUND_PREFIXES = ("stdout_contains_all:", "stdout_regex_all:")


class Verdict(str, Enum):
    PASS = "pass"
    FAIL = "fail"
    ERROR = "error"      # the check could not be evaluated (timeout/spawn/cancel/bad expect)
    SKIPPED = "skipped"  # no behavioral check ran (no cmd authored / sanitizer dropped it)


@dataclass(frozen=True)
class Receipt:
    """The single typed verification result. ``verdict`` derives ONLY from the strict
    pipeline; ``annotations`` carry non-binding extras (stdout/stderr, envelope
    self-report, independent-verifier verdict, adversary verdict) and NEVER override it."""
    verdict: Verdict
    cmd: "tuple[str, ...]"            # the arg vector actually executed (empty when none ran)
    rc: Optional[int]
    expect_mode: str
    matched: "tuple[str, ...]"
    missing: "tuple[str, ...]"
    diff_files: "tuple[str, ...]"
    duration_s: float
    failure_feedback: str
    annotations: dict = field(default_factory=dict)

    @property
    def passed(self) -> bool:
        return self.verdict is Verdict.PASS


def annotate(receipt: Receipt, key: str, value) -> None:
    """Attach a non-binding annotation (envelope / independent verify / adversary)."""
    receipt.annotations[key] = value


class VResult(dict):
    """One-release compat shim: the legacy vresult dict shape, carrying the typed Receipt.

    Dict access keeps every existing consumer (state.recordVerify, dashboards, feedback
    builders) working unchanged; ``.receipt`` exposes the typed pipeline result and
    ``.passed`` mirrors ``self["passed"]`` for attribute-style consumers."""

    def __init__(self, receipt: Receipt, mapping: dict):
        super().__init__(mapping)
        self.receipt = receipt

    @property
    def passed(self) -> bool:
        return bool(self.get("passed"))


# ==== PURE VERDICT EVALUATION ====

def _expectMode(expect: str) -> str:
    for pfx in ("stdout_contains_all:", "stdout_regex_all:", "stdout_contains:", "stdout_regex:"):
        if expect.startswith(pfx):
            return pfx.rstrip(":")
    return expect


def verdictFor(rc, output: str, expect) -> "tuple[Verdict, tuple, tuple]":
    """PURE function of (rc, output, expect) -> (verdict, matched, missing).

    NO cmd-shape special cases: the silent test-runner FAIL->PASS override is DEAD --
    a green suite with a wrong stdout needle FAILS (the brain authors exit_zero for test
    runners; see plan_prompts VERIFY RULES). An unevaluable expect (non-string/empty/
    unknown shape/bad regex) is ERROR, never a guessed exit_zero."""
    if not isinstance(expect, str) or not expect.strip():
        return Verdict.ERROR, (), ()          # the runner NEVER guesses a missing expect
    expect = expect.strip()
    if rc is None:
        return Verdict.ERROR, (), ()
    output = output or ""
    if expect == "exit_zero":
        return (Verdict.PASS if rc == 0 else Verdict.FAIL), (), ()
    if expect.startswith("stdout_contains_all:"):
        needles = tuple(n for n in expect[len("stdout_contains_all:"):].split("||") if n)
        if not needles:
            return Verdict.ERROR, (), ()
        matched = tuple(n for n in needles if n in output)
        missing = tuple(n for n in needles if n not in output)
        return (Verdict.PASS if rc == 0 and not missing else Verdict.FAIL), matched, missing
    if expect.startswith("stdout_regex_all:"):
        pats = tuple(p for p in expect[len("stdout_regex_all:"):].split("||") if p)
        if not pats:
            return Verdict.ERROR, (), ()
        try:
            matched = tuple(p for p in pats if re.search(p, output) is not None)
        except re.error:
            return Verdict.ERROR, (), ()
        missing = tuple(p for p in pats if p not in matched)
        return (Verdict.PASS if rc == 0 and not missing else Verdict.FAIL), matched, missing
    if expect.startswith("stdout_contains:"):
        needle = expect[len("stdout_contains:"):]
        if not needle:
            # FX-2: an EMPTY needle makes `"" in stdout` always True; degrade to exit gate.
            return (Verdict.PASS if rc == 0 else Verdict.FAIL), (), ()
        hit = rc == 0 and needle in output
        return ((Verdict.PASS, (needle,), ()) if hit else (Verdict.FAIL, (), (needle,)))
    if expect.startswith("stdout_regex:"):
        pattern = expect[len("stdout_regex:"):]
        if not pattern:
            return (Verdict.PASS if rc == 0 else Verdict.FAIL), (), ()
        try:
            hit = rc == 0 and re.search(pattern, output) is not None
        except re.error:
            return Verdict.ERROR, (), ()
        return ((Verdict.PASS, (pattern,), ()) if hit else (Verdict.FAIL, (), (pattern,)))
    return Verdict.ERROR, (), ()              # unknown expect shape: fail closed, don't guess


# ==== ARG-VECTOR RUNNER (no shell; tree-kill; cancel-aware) ====

class VerifyCancelled(Exception):
    """cancel_check fired while the acceptance command was running."""


def _splitCmd(cmd: str) -> "list[str]":
    """Windows-aware arg-vector split. shlex in NON-posix mode preserves backslashes in
    C:\\ paths and groups quoted spans; surrounding quotes are then stripped per token
    (subprocess re-quotes correctly via list2cmdline on Windows)."""
    lex = shlex.shlex(cmd, posix=False)
    lex.whitespace_split = True
    toks = list(lex)
    out = []
    for t in toks:
        if len(t) >= 2 and t[0] == t[-1] and t[0] in "\"'":
            t = t[1:-1]
        out.append(t)
    return out


def _runVector(argv: "list[str]", work_dir: str, cancel_check=None,
               timeout_seconds: Optional[int] = None) -> subprocess.CompletedProcess:
    """Run the acceptance ARG-VECTOR (shell=False) with the tree-kill discipline.

    Popen + CREATE_NEW_PROCESS_GROUP + tree-kill on timeout/cancel -- the SAME Windows
    orphan fix the executor uses (f57855b): a plain kill leaves a python.exe grandchild
    holding a file lock on the artifact the next retry must rewrite. ``cancel_check`` is
    polled every 0.5s so an operator kill / deadline breaks a long verify promptly."""
    # A bare ``python``/``python3`` resolves from PATH, which on CI can be a DIFFERENT
    # interpreter than the one running this suite (uv install) -- module mismatches.
    # Pin it to sys.executable; copy first so the caller's argv stays authored-as-is.
    argv = list(argv)
    if argv and argv[0].lower() in ("python", "python3"):
        argv[0] = sys.executable
    Path(work_dir).mkdir(parents=True, exist_ok=True)
    creationflags = subprocess.CREATE_NEW_PROCESS_GROUP if os.name == "nt" else 0
    proc = subprocess.Popen(argv, shell=False, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, text=True, encoding="utf-8", errors="replace",
                            cwd=work_dir, creationflags=creationflags,
                            start_new_session=(os.name != "nt"))
    limit = timeout_seconds if timeout_seconds is not None else config.VERIFY_TIMEOUT_SECONDS
    deadline = time.monotonic() + limit
    while True:
        try:
            out, err = proc.communicate(timeout=0.5)
            return subprocess.CompletedProcess(argv, proc.returncode, out or "", err or "")
        except subprocess.TimeoutExpired:
            if cancel_check is not None and cancel_check():
                _killProcessTree(proc.pid)
                _drainQuietly(proc)
                raise VerifyCancelled("verification cancelled by cancel_check") from None
            if time.monotonic() >= deadline:
                _killProcessTree(proc.pid)
                _drainQuietly(proc)
                raise subprocess.TimeoutExpired(argv, limit) from None


def _drainQuietly(proc) -> None:
    try:
        proc.communicate(timeout=10)
    except Exception:  # noqa: BLE001
        pass


# ==== PATH / WORKDIR HELPERS ====

def _extractVerifyPath(cmd: str) -> Optional[str]:
    """Best-effort: return the first path-like argument in a verify command."""
    toks = cmd.strip().split()
    skip = {"py", "python", "python3", "pytest", "unittest", "coverage", "run"}
    for tok in toks[1:]:
        if tok.startswith("-"):
            continue
        if tok.lower() in skip:
            continue
        if tok.endswith(".py") or "/" in tok or "\\" in tok:
            return tok
    return None


def _normalizeWorkDir(cmd: str, work_dir: str) -> str:
    """Return the dir a verify command should run in.

    Verify commands are authored relative to the repo root, but a self-referential
    run sets a subtask's work_dir to a ``.sc-ctx/<sid>`` scratch dir -- so a verify
    like ``python tests/foo.py`` cannot find its target from the scratch cwd.
    Re-root to PROJECT_ROOT (this checkout) when the referenced path lives under it
    but not under work_dir; fall back to INSTALL_ROOT only when the PROJECT_ROOT
    probe misses and INSTALL_ROOT exists (dev-box convenience -- INSTALL_ROOT is
    absent on CI). Absolute repo-root paths are normalised too."""
    candidate = _extractVerifyPath(cmd)
    if not candidate:
        return work_dir
    script = Path(candidate.strip("\"'"))
    if script.is_absolute():
        for root in (config.PROJECT_ROOT, config.INSTALL_ROOT):
            try:
                script.relative_to(root)
                return str(root)
            except ValueError:
                continue
        return work_dir
    probe = re.split(r"[*?\[]", str(script), maxsplit=1)[0]
    if probe.endswith(("/", "\\")) or probe == str(script):
        check = Path(probe)
    else:
        check = Path(probe).parent
    try:
        in_workdir = (Path(work_dir) / check).exists()
        in_project = (Path(config.PROJECT_ROOT) / check).exists()
        # INSTALL_ROOT is the OTHER checkout on the dev box; it does not exist on CI.
        in_install = (not in_project and Path(config.INSTALL_ROOT).exists()
                      and (Path(config.INSTALL_ROOT) / check).exists())
    except OSError:
        return work_dir
    if in_project and not in_workdir:
        return str(config.PROJECT_ROOT)
    if in_install and not in_workdir:
        return str(config.INSTALL_ROOT)
    return work_dir


