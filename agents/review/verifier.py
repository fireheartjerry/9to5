"""Verifier facade -- the ONE owner surface for verification (R10).

Each subtask carries a ``verify`` block authored by the Orchestrator brain:

    {"cmd": "python -m taskcli --help", "expect": "exit_zero"}

``expect`` is one of (evaluated STRICTLY -- no test-runner special case, no guessed
default; a verify without an expect is rejected by the sanitizer):
  * ``exit_zero``                       -- the command returned exit code 0
  * ``stdout_contains:<text>``          -- <text> appears in stdout AND rc==0
  * ``stdout_regex:<pattern>``          -- <pattern> matches stdout AND rc==0
  * ``stdout_contains_all:<a>||<b>``    -- EVERY ``||``-separated needle appears (compound)
  * ``stdout_regex_all:<p1>||<p2>``     -- EVERY ``||``-separated pattern matches (compound)

A verify may also declare ``targets`` (file paths): the receipt pipeline diff-grounds
them -- git must show a declared target actually changed, or the subtask FAILS with
actionable feedback. This replaces the deleted token-scan synthesizer
(buildContentScanVerify and friends): goal words in a comment prove nothing.

Pipeline + typed Receipt: agents/verification.py
Sanitization:            agents/verifier_sanitize.py (applied INSIDE the pipeline)
Runner facade:           agents/verifier_runner.py

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  extractRequirements(goal: str) -> list[str]  -- Pull the EXPLICITLY enumerated deliverables out of a goal.
  primaryTargetFile(goal: str) -> Optional[str]  -- The single distinct file path a goal targets, else None (zero or several files named).
  isStrictVerify(verify: Optional[dict]) -> bool  -- True for a deliberate multi-requirement verify (compound expect or ``strict`` flag)
DEPENDS-ON: agents.verification, agents.verifier_runner, agents.verifier_sanitize, config
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/execution/test_verifier.py
"""
