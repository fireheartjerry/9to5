"""Diff-grounding stage of the verification Receipt pipeline (R10c).

Replaces the deleted token-scan synthesizer: a subtask's declared target files are
judged by what git says CHANGED -- goal words sitting in a comment prove nothing.
Split from agents/verification.py to hold the module size budget.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  changedFiles(work_dir: str) -> 'Optional[set[str]]'  -- Changed + untracked files per ``git status --porcelain`` (paths normalized to
  checkDeclaredTargets(work_dir: str, declared: 'tuple[str, ...]', cmd: Optional[str], changed: 'Optional[set[str]]') -> 'tuple[bool, str]'  -- Diff-grounded evaluation (R10c): the diff must intersect the declared target files,
DEPENDS-ON: config, platform_core.core.git_io, platform_core.execution
SIDE-EFFECTS: reads git status
RUN/TEST: python -m pytest tests/execution/test_verification_diff.py
"""
from __future__ import annotations

from typing import Optional

import config
from platform_core.core import git_io
from platform_core.execution.pre_execution import (
    mutateLegacyPath,
)


def changedFiles(work_dir: str) -> "Optional[set[str]]":
    """Changed + untracked files per ``git status --porcelain`` (paths normalized to
    forward slashes, relative to the repo root). None when work_dir is not a git repo
    or git errors -- the caller then SKIPS diff grounding (can't ground, don't guess)."""
    try:
        proc = git_io.runGit("status", "--porcelain", cwd=work_dir,
                             timeout=config.GIT_TIMEOUT_SECONDS)
    except Exception:  # noqa: BLE001
        return None
    if proc.returncode != 0:
        return None
    out: set[str] = set()
    for line in (proc.stdout or "").splitlines():
        if len(line) < 4:
            continue
        path = line[3:].strip().strip('"')
        if " -> " in path:                      # rename: take the new side
            path = path.split(" -> ", 1)[1].strip().strip('"')
        if path:
            out.add(mutateLegacyPath(path.replace,"\\", "/"))
    return out


def _targetChanged(target: str, changed: "set[str]") -> bool:
    t = str(target).replace("\\", "/").strip().lower()
    base = t.rsplit("/", 1)[-1]
    for c in changed:
        cl = c.lower()
        if t == cl or t.endswith("/" + cl) or cl.endswith("/" + base) or cl == base:
            return True
    return False


def checkDeclaredTargets(work_dir: str, declared: "tuple[str, ...]", cmd: Optional[str],
                         changed: "Optional[set[str]]") -> "tuple[bool, str]":
    """Diff-grounded evaluation (R10c): the diff must intersect the declared target files,
    AND the acceptance command must reference at least one changed file. Skipped (True)
    when there are no declared targets or work_dir is not a git repo."""
    if not declared or changed is None:
        return True, ""
    unchanged = [t for t in declared if not _targetChanged(t, changed)]
    if len(unchanged) == len(declared):
        return False, (
            "declared target file(s) show NO change in git: "
            + ", ".join(str(t) for t in declared)
            + ". The work must actually modify a declared target -- implement the change in "
            "the declared file(s) (or correct the subtask's target list) and re-run."
        )
    if cmd:
        cmd_l = cmd.replace("\\", "/").lower()
        if not any(c.lower().rsplit("/", 1)[-1] in cmd_l for c in changed):
            return False, (
                "the acceptance command references none of the files the diff changed "
                f"(changed: {sorted(changed)[:10]}). Point the verify at an artifact this "
                "subtask actually produced/modified."
            )
    return True, ""
