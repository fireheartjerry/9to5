"""Error handling utilities -- retry-before-alert and diagnostic logging.

Provides ``retryTask``: wraps any callable with up to MAX_RETRIES retry attempts,
exponential backoff between attempts (never after the final attempt to avoid
unnecessary wall-clock latency), structured diagnostic logging on every failure,
and a final alert (LOG.critical) when all attempts are exhausted.

Implementation lives here; ``enhanced_error_handling`` re-exports this module
so callers can import from either name.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  MAX_RETRIES (int) -- default retry ceiling (3)
  RETRY_DELAY_SECONDS (float) -- initial sleep between attempts (1.0 s)
  RetryExhausted -- raised when on_alert=None and all retries fail
  retryTask(fn, *, args=(), kwargs=None, max_retries=MAX_RETRIES,
            delay=RETRY_DELAY_SECONDS, on_alert=None) -> dict
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: python -m pytest tests/test_error_handling.py
"""
from __future__ import annotations

import logging
import time
from typing import Any, Callable, Optional

LOG = logging.getLogger("9to5.error_handling")

MAX_RETRIES: int = 3
RETRY_DELAY_SECONDS: float = 1.0


class RetryExhausted(RuntimeError):
    """Raised by retryTask when all attempts fail and no on_alert is provided."""


def retryTask(
    fn: Callable,
    *,
    args: tuple = (),
    kwargs: Optional[dict] = None,
    max_retries: int = MAX_RETRIES,
    delay: float = RETRY_DELAY_SECONDS,
    on_alert: Optional[Callable[[str, int], None]] = None,
) -> dict[str, Any]:
    """Call fn(*args, **kwargs), retrying up to max_retries times on any Exception.

    Sleep fires only BETWEEN attempts (max_retries - 1 total), never after the
    final attempt, avoiding unnecessary wall-clock latency before the alert fires.

    Returns
    -------
    {"ok": True,  "result": <return value>, "attempts": n}  on success
    {"ok": False, "error": "<last error>",  "attempts": n}  when on_alert is set
                                                             and all retries fail

    Raises RetryExhausted when on_alert is None and all attempts are exhausted.

    Logging
    -------
    Every failure emits LOG.warning with attempt index and exception detail.
    Recovery on a later attempt emits LOG.info.
    Final exhaustion emits LOG.critical with a full diagnostic summary.
    """
    kw = kwargs or {}
    last_exc: Optional[Exception] = None

    for attempt in range(1, max_retries + 1):
        try:
            result = fn(*args, **kw)
            if attempt > 1:
                LOG.info(
                    "retryTask: succeeded on attempt %d/%d for %s",
                    attempt, max_retries, getattr(fn, "__name__", repr(fn)),
                )
            return {"ok": True, "result": result, "attempts": attempt}
        except Exception as exc:  # noqa: BLE001
            last_exc = exc
            LOG.warning(
                "retryTask: attempt %d/%d failed for %s — %s: %s",
                attempt, max_retries,
                getattr(fn, "__name__", repr(fn)),
                type(exc).__name__, exc,
            )
            # Sleep only between attempts; skip after the final attempt
            # so no unnecessary latency is introduced before the alert fires.
            if attempt < max_retries:
                time.sleep(delay)

    error_msg = f"{type(last_exc).__name__}: {last_exc}"
    LOG.critical(
        "retryTask: all %d attempts exhausted for %s — last error: %s",
        max_retries, getattr(fn, "__name__", repr(fn)), error_msg,
    )
    if on_alert is not None:
        on_alert(error_msg, max_retries)
        return {"ok": False, "error": error_msg, "attempts": max_retries}
    raise RetryExhausted(error_msg)
