"""Root conftest.py — minimal bootstrap.

Contains hooks that expand shell-unresolved glob patterns so that invocations like
    python -m pytest tests/some_dir/*_test.py
work identically from PowerShell/cmd.exe (which do not expand * for external executables)
and from bash. All test-isolation fixtures live in tests/conftest.py.

@AI-MAP v1  (generated by tools/repo_map.py -- edit SIDE-EFFECTS only, then regenerate)
EXPORTS:
  pytest_configure(config)  -- Expand shell-unresolved glob patterns in pytest's path arguments.
DEPENDS-ON: (stdlib only)
SIDE-EFFECTS: unannotated
RUN/TEST: (no mapped test)
"""
import glob as _glob
import os as _os
import pathlib as _pathlib

# HERMETIC INSTALL ROOT (must run before ANY `import config`): loadEnvOnce() loads
# INSTALL_ROOT/.env FIRST, and INSTALL_ROOT defaults to the shared install C:\9to5 -- so on a
# dev machine every test process silently absorbed the LIVE production .env (Discord creds,
# GEMINI_API_KEY, feature flags), while CI (no C:\9to5) ran with stock defaults. Pinning
# INSTALL_ROOT to THIS checkout makes local and CI test runs see the same world: the checkout's
# own .env if present (none is committed), otherwise pure defaults. A caller that exported
# INSTALL_ROOT deliberately still wins (setdefault).
_os.environ.setdefault("INSTALL_ROOT", str(_pathlib.Path(__file__).resolve().parent))


def _expand_globs(args):
    """Expand any glob-containing args in-place; return True if anything changed."""
    expanded = []
    changed = False
    for arg in list(args):
        if ("*" in arg or "?" in arg) and not arg.startswith("-"):
            matches = sorted(_glob.glob(arg))
            if matches:
                expanded.extend(matches)
                changed = True
                continue
        expanded.append(arg)
    if changed:
        args[:] = expanded
    return changed


def pytest_configure(config):
    """Expand shell-unresolved glob patterns in pytest's path arguments.

    ``config.args`` holds the positional path arguments after parsing. PowerShell and
    cmd.exe do not expand * for external executables, so this hook does it instead.
    """
    if hasattr(config, "args") and isinstance(config.args, list):
        _expand_globs(config.args)
