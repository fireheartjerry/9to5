    source = commands.add_parser("source-object-closure")
    source.add_argument("--sha1dc-executable", required=True)
    source.add_argument("--request", required=True)
    source.add_argument("--raw-root", required=True)
    source.add_argument("--output-root", required=True)
    source.add_argument("--heartbeat-interval", type=float)
