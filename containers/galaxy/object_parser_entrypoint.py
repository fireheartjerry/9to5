class ObjectParserRefused(RuntimeError):
    pass


class _MissingSourceObjects(ObjectParserRefused):
    def __init__(self, oids: set[str]) -> None:
        if not oids or any(_OID_RE.fullmatch(oid) is None for oid in oids):
            raise ValueError("missing source-object frontier must contain full OIDs")
        self.oids = frozenset(oids)
        super().__init__("source object frontier is incomplete")


class _Sha1dcOracle:
    """Exact repo-less Git SHA1DC oracle contained by the parser sandbox."""

    def __init__(self, executable: Path, *, sterile_root: Path) -> None:
        if not executable.is_absolute():
            raise ObjectParserRefused("SHA1DC executable path must be absolute")
        try:
            if executable.parent.name.casefold() == "cmd":
                runtime = executable.parent.parent / "mingw64" / "bin" / "git.exe"
                if runtime.is_file():
                    executable = runtime
            before = executable.lstat()
            if not stat.S_ISREG(before.st_mode) or stat.S_ISLNK(before.st_mode):
                raise OSError("SHA1DC executable is not a regular no-link file")
            raw = executable.read_bytes()
            after = executable.lstat()
        except OSError as exc:
            raise ObjectParserRefused("SHA1DC executable is unavailable or unsafe") from exc
        identity = (
            before.st_dev,
            before.st_ino,
            before.st_size,
            before.st_mtime_ns,
        )
        if (
            identity
            != (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns)
            or len(raw) != before.st_size
            or len(raw) > _MAX_SHA1DC_EXECUTABLE_BYTES
        ):
            raise ObjectParserRefused("SHA1DC executable raced or exceeds quota")
        if not sterile_root.is_absolute():
            raise ObjectParserRefused("SHA1DC sterile root must be absolute")
        try:
            root_meta = sterile_root.lstat()
        except OSError as exc:
            raise ObjectParserRefused("SHA1DC sterile root is unavailable") from exc
        if not stat.S_ISDIR(root_meta.st_mode) or stat.S_ISLNK(root_meta.st_mode):
            raise ObjectParserRefused("SHA1DC sterile root is unsafe")
        self._executable = executable
        self._sterile_root = sterile_root
        self._identity = identity
        self._digest = hashlib.sha256(raw).hexdigest()
        standalone = self._run(["--version"], input_bytes=None, timeout=10)
        expected_version = (
            b"GALAXY_SHA1DC_OBJECT_ORACLE/v1 "
            b"upstream=855827c583bc30645ba427885caa40c5b81764d2\n"
        )
        if standalone.returncode == 0 and not standalone.stderr and standalone.stdout == expected_version:
            self._mode = "standalone"
            self._attestation = standalone.stdout
            self_test = self._run(["--self-test"], input_bytes=None, timeout=10)
            if (
                self_test.returncode != 0
                or self_test.stderr
                or self_test.stdout
                != b"GALAXY_SHA1DC_SELF_TEST/v1 collision-detected normal-sha1-exact\n"
            ):
                raise ObjectParserRefused("standalone SHA1DC self-test failed")
            return
        build = self._run(["version", "--build-options"], input_bytes=None, timeout=10)
        if (
            build.returncode != 0
            or build.stderr
            or len(build.stdout) > 65536
            or b"SHA-1: SHA1_DC" not in build.stdout
        ):
            raise ObjectParserRefused("runtime does not attest collision-detecting SHA1DC")
        self._mode = "git"
        self._attestation = build.stdout

    def _environment(self) -> dict[str, str]:
        environment = {
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_CONFIG_SYSTEM": os.devnull,
            "GIT_TERMINAL_PROMPT": "0",
            "GIT_PROTOCOL_FROM_USER": "0",
            "GIT_ALLOW_PROTOCOL": "",
            "GIT_DISCOVERY_ACROSS_FILESYSTEM": "0",
            "GIT_CEILING_DIRECTORIES": str(self._sterile_root.parent),
            "GIT_NO_LAZY_FETCH": "1",
            "GCM_INTERACTIVE": "Never",
            "HOME": str(self._sterile_root),
            "USERPROFILE": str(self._sterile_root),
            "PATH": str(self._executable.parent),
            "LC_ALL": "C",
            "LANG": "C",
        }
        system_root = os.environ.get("SystemRoot")
        if system_root:
            environment["SystemRoot"] = system_root
        return environment

    def _run(
        self,
        arguments: list[str],
        *,
        input_bytes: bytes | None,
        timeout: float,
    ) -> subprocess.CompletedProcess[bytes]:
        return subprocess.run(
            [str(self._executable), *arguments],
            cwd=self._sterile_root,
            env=self._environment(),
            input=input_bytes,
            stdin=subprocess.DEVNULL if input_bytes is None else None,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=timeout,
            check=False,
            shell=False,
            creationflags=(
                getattr(subprocess, "CREATE_NO_WINDOW", 0) if os.name == "nt" else 0
            ),
        )

    def _revalidate(self) -> None:
        try:
            before = self._executable.lstat()
            raw = self._executable.read_bytes()
            after = self._executable.lstat()
        except OSError as exc:
            raise ObjectParserRefused("SHA1DC executable cannot be revalidated") from exc
        observed = (
            before.st_dev,
            before.st_ino,
            before.st_size,
            before.st_mtime_ns,
        )
        if (
            observed != self._identity
            or observed
            != (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns)
            or len(raw) != before.st_size
            or hashlib.sha256(raw).hexdigest() != self._digest
        ):
            raise ObjectParserRefused("SHA1DC executable identity changed")
        arguments = ["--version"] if self._mode == "standalone" else ["version", "--build-options"]
        build = self._run(arguments, input_bytes=None, timeout=10)
        if build.returncode != 0 or build.stderr or build.stdout != self._attestation:
            raise ObjectParserRefused("SHA1DC build attestation changed")

    def hashObject(self, object_type: str, payload: bytes) -> str:
        if object_type not in {"blob", "tree", "commit", "tag"}:
            raise ObjectParserRefused("SHA1DC object type is outside the closed set")
        if not isinstance(payload, bytes) or len(payload) > _MAX_SOURCE_OBJECT_BYTES:
            raise ObjectParserRefused("SHA1DC object payload exceeds quota")
        self._revalidate()
        arguments = (
            ["hash-object", object_type, str(len(payload))]
            if self._mode == "standalone"
            else ["hash-object", "--stdin", "--no-filters", "-t", object_type]
        )
        result = self._run(
            arguments,
            input_bytes=payload,
            timeout=30,
        )
        if result.returncode != 0 or result.stderr:
            raise ObjectParserRefused("SHA1DC refused the Git object bytes")
        try:
            oid = result.stdout.decode("ascii").strip()
        except UnicodeDecodeError as exc:
            raise ObjectParserRefused("SHA1DC returned non-ASCII output") from exc
        if _OID_RE.fullmatch(oid) is None or result.stdout != (oid + "\n").encode("ascii"):
            raise ObjectParserRefused("SHA1DC returned a noncanonical object id")
        return oid


class _InflationBudget:
    """Bound aggregate decompression work and retained source-object bytes."""

    def __init__(self, *, max_objects: int, max_inflated_bytes: int) -> None:
        if max_objects < 1 or max_inflated_bytes < 1:
            raise ValueError("inflation limits must be positive")
        self.max_objects = max_objects
        self.max_inflated_bytes = max_inflated_bytes
        self._object_ids: set[str] = set()
        self._input_objects = 0
        self._inflated_bytes = 0

    @property
    def remainingInputObjects(self) -> int:
        return self.max_objects - self._input_objects

    def reserveLooseObjects(self, count: int) -> None:
        if count < 0 or self._input_objects + count > self.max_objects:
            raise ObjectParserRefused("source exceeds object-count quota")
        self._input_objects += count

    def assertPackCount(self, count: int) -> None:
        if count < 0 or self._input_objects + count > self.max_objects:
            raise ObjectParserRefused("source pack exceeds object-count quota")
        self._input_objects += count

    def observeInflated(self, size: int) -> None:
        if size < 0 or self._inflated_bytes + size > self.max_inflated_bytes:
            raise ObjectParserRefused("source exceeds aggregate inflated-byte quota")
        self._inflated_bytes += size

    def observeObject(self, oid: str, size: int) -> None:
        if oid in self._object_ids:
            return
        if len(self._object_ids) >= self.max_objects:
            raise ObjectParserRefused("source exceeds object-count quota")
        self.observeInflated(size)
        self._object_ids.add(oid)


class _Policy(TypedDict):
    reserved_roots: list[str]
    max_files: int
    max_total_bytes: int
    max_file_bytes: int
    max_depth: int
    max_path_bytes: int


def _canonicalJson(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode(
        "utf-8"
    )


def _canonicalDigest(value: object) -> str:
    return hashlib.sha256(_canonicalJson(value)).hexdigest()


def _rejectDuplicates(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise ObjectParserRefused("JSON contains a duplicate key")
        result[key] = value
    return result


def _loadCanonical(path: Path) -> dict[str, object]:
    try:
        metadata = path.lstat()
        if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
            raise OSError("not a single-link regular file")
        if metadata.st_size < 1 or metadata.st_size > _MAX_REQUEST_BYTES:
            raise OSError("request size is outside quota")
        raw = path.read_bytes()
    except OSError as exc:
        raise ObjectParserRefused("request is unavailable or unsafe") from exc
    try:
        value = json.loads(
            raw.decode("utf-8", errors="strict"),
            object_pairs_hook=_rejectDuplicates,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ObjectParserRefused("request is not strict JSON") from exc
    if not isinstance(value, dict) or _canonicalJson(value) != raw:
        raise ObjectParserRefused("request is not canonical JSON")
    return value


def _digest(value: object, label: str) -> str:
    if not isinstance(value, str) or _DIGEST_RE.fullmatch(value) is None:
        raise ObjectParserRefused(f"{label} digest is malformed")
    return value


def _oid(value: object, label: str) -> str:
    if not isinstance(value, str) or _OID_RE.fullmatch(value) is None:
        raise ObjectParserRefused(f"{label} object id is malformed")
    return value


def _safePath(value: object) -> tuple[str, ...]:
    if not isinstance(value, str) or not value or "\\" in value:
        raise ObjectParserRefused("snapshot path is malformed")
    path = PurePosixPath(value)
    if path.is_absolute() or path.as_posix() != value:
        raise ObjectParserRefused("snapshot path is not canonical relative POSIX")
    parts = path.parts
    if not parts or any(part in {"", ".", ".."} for part in parts):
        raise ObjectParserRefused("snapshot path contains a dot component")
    for part in parts:
        if any(ord(character) < 32 or ord(character) == 127 for character in part):
            raise ObjectParserRefused("snapshot path contains a control character")
        if (
            ":" in part
            or any(character in _WINDOWS_INVALID_CHARACTERS for character in part)
            or part.endswith((".", " "))
            or part.casefold() == ".git"
        ):
            raise ObjectParserRefused("snapshot path has an unsafe filesystem alias")
        if unicodedata.normalize("NFC", part) != part:
            raise ObjectParserRefused("snapshot path is not canonically normalized")
        try:
            utf16_units = len(part.encode("utf-16-le", errors="strict")) // 2
        except UnicodeEncodeError as exc:
            raise ObjectParserRefused(
                "snapshot path has unrepresentable Unicode"
            ) from exc
        if utf16_units > _WINDOWS_COMPONENT_UTF16_UNITS:
            raise ObjectParserRefused("snapshot path component exceeds native limits")
        base = part.rstrip(" .").split(".", 1)[0].rstrip(" ").upper()
        if base in _RESERVED_DEVICES:
            raise ObjectParserRefused("snapshot path contains a reserved device")
        if _SHORT_ALIAS_RE.fullmatch(part):
            raise ObjectParserRefused("snapshot path contains a short-name alias")
    return parts


def _filesystemKey(path: str) -> tuple[str, ...]:
    return tuple(
        unicodedata.normalize("NFC", component).casefold()
        for component in PurePosixPath(path).parts
    )


def _positiveInteger(value: object, label: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value < 1:
        raise ObjectParserRefused(f"{label} must be a positive integer")
    return value


def _validatePolicy(value: object) -> _Policy:
    fields = {
        "reserved_roots",
        "max_files",
        "max_total_bytes",
        "max_file_bytes",
        "max_depth",
        "max_path_bytes",
    }
    if not isinstance(value, dict) or set(value) != fields:
        raise ObjectParserRefused("manifest policy fields are not closed")
    roots = value["reserved_roots"]
    if not isinstance(roots, list) or any(not isinstance(root, str) for root in roots):
        raise ObjectParserRefused("reserved roots are malformed")
    for root in roots:
        _safePath(root)
    result: _Policy = {
        "reserved_roots": sorted(roots),
        "max_files": _positiveInteger(value["max_files"], "max_files"),
        "max_total_bytes": _positiveInteger(
            value["max_total_bytes"], "max_total_bytes"
        ),
        "max_file_bytes": _positiveInteger(value["max_file_bytes"], "max_file_bytes"),
        "max_depth": _positiveInteger(value["max_depth"], "max_depth"),
        "max_path_bytes": _positiveInteger(value["max_path_bytes"], "max_path_bytes"),
    }
    if result["max_file_bytes"] > result["max_total_bytes"]:
        raise ObjectParserRefused("per-file quota exceeds aggregate quota")
    if result["max_path_bytes"] > _PORTABLE_PATH_BYTES:
        raise ObjectParserRefused("path quota exceeds the portable ceiling")
    return result


def _validateAttributes(value: object) -> list[dict[str, object]]:
    if not isinstance(value, list):
        raise ObjectParserRefused("attribute rules must be a list")
    result: list[dict[str, object]] = []
    seen: set[str] = set()
    for rule in value:
        if not isinstance(rule, dict) or set(rule) != {"pattern", "attributes"}:
            raise ObjectParserRefused("attribute rule fields are malformed")
        pattern = rule["pattern"]
        attributes = rule["attributes"]
        if (
            not isinstance(pattern, str)
            or not pattern
            or any(ord(character) < 32 for character in pattern)
            or pattern.startswith(("!", "[attr]"))
            or "\\" in pattern
            or any(character in pattern for character in "?[]")
            or pattern.startswith("/")
            or pattern.endswith("/")
            or ".." in PurePosixPath(pattern).parts
            or attributes != ["text", "eol=lf"]
            or pattern in seen
        ):
            raise ObjectParserRefused("attribute rule is outside the safe subset")
        seen.add(pattern)
        result.append({"pattern": pattern, "attributes": attributes})
    return sorted(result, key=lambda rule: str(rule["pattern"]))


def _attributePatternMatches(pattern: str, path: str) -> bool:
    candidate = PurePosixPath(path)
    return fnmatchcase(candidate.name, pattern) if "/" not in pattern else fnmatchcase(
        path,
        pattern,
    )


def _expectedEntries(value: object) -> dict[str, dict[str, object]]:
    if not isinstance(value, list):
        raise ObjectParserRefused("expected entries must be a list")
    result: dict[str, dict[str, object]] = {}
    fields = {
        "path",
        "mode",
        "blob_oid",
        "blob_sha256",
        "framed_object_sha256",
        "size",
    }
    for item in value:
        if not isinstance(item, dict) or set(item) != fields:
            raise ObjectParserRefused("expected entry fields are not closed")
        path = item["path"]
        _safePath(path)
        assert isinstance(path, str)
        if path in result:
            raise ObjectParserRefused("expected entry is duplicated")
        if item["mode"] not in _REGULAR_MODES:
            raise ObjectParserRefused("expected mode is unsupported")
        _oid(item["blob_oid"], "expected blob")
        _digest(item["blob_sha256"], "expected blob")
        _digest(item["framed_object_sha256"], "expected frame")
        size = item["size"]
        if not isinstance(size, int) or isinstance(size, bool) or size < 0:
            raise ObjectParserRefused("expected size is malformed")
        result[path] = item
    if list(result) != sorted(result, key=lambda path: path.encode("utf-8")):
        raise ObjectParserRefused("expected entries are not ordered")
    return result


def _readBlob(blob_root: Path, digest: str, size: int) -> bytes:
    path = blob_root / digest[:2] / digest
    current = blob_root
    try:
        root_meta = current.lstat()
        if not stat.S_ISDIR(root_meta.st_mode):
            raise OSError("blob root is not a directory")
        for component in (digest[:2], digest):
            current /= component
            metadata = current.lstat()
            if stat.S_ISLNK(metadata.st_mode):
                raise OSError("blob path contains a link")
        metadata = path.lstat()
        if (
            not stat.S_ISREG(metadata.st_mode)
            or metadata.st_nlink != 1
            or metadata.st_size != size
        ):
            raise OSError("blob leaf metadata differs")
        payload = path.read_bytes()
    except OSError as exc:
        raise ObjectParserRefused("snapshot blob is unavailable or unsafe") from exc
    if len(payload) != size or hashlib.sha256(payload).hexdigest() != digest:
        raise ObjectParserRefused("snapshot blob digest differs")
    return payload


def _statIdentity(
    metadata: os.stat_result,
) -> tuple[int, int, int, int, int, int, int, int]:
    # Python 3.12 exposes a different Windows ``st_ctime_ns`` value for path
    # stat and handle fstat.  Bind stable file-object identity plus mutable size,
    # mtime, mode, and reparse metadata; validate the strong digest separately.
    return (
        metadata.st_dev,
        metadata.st_ino,
        metadata.st_size,
        metadata.st_mtime_ns,
        metadata.st_nlink,
        metadata.st_mode,
        int(getattr(metadata, "st_file_attributes", 0)),
        int(getattr(metadata, "st_reparse_tag", 0)),
    )


class _VerifiedBlob:
    """Content-addressed input whose reads remain bounded and identity-pinned."""

    def __init__(self, path: Path, *, digest: str, size: int, identity: tuple[int, ...]) -> None:
        self.path = path
        self.digest = digest
        self.size = size
        self.identity = identity

    def open(self) -> BinaryIO:
        flags = os.O_RDONLY
        if hasattr(os, "O_CLOEXEC"):
            flags |= os.O_CLOEXEC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        descriptor: int | None = None
        try:
            descriptor = os.open(self.path, flags)
            observed = _statIdentity(os.fstat(descriptor))
            if observed != self.identity:
                raise OSError("blob identity raced retained open")
            return os.fdopen(descriptor, "rb", closefd=True)
        except BaseException:
            if descriptor is not None:
                try:
                    os.close(descriptor)
                except OSError:
                    pass
            raise

    def validateStream(self, stream: BinaryIO) -> None:
        if _statIdentity(os.fstat(stream.fileno())) != self.identity:
            raise ObjectParserRefused("snapshot blob identity raced retained read")

    def readAll(self, *, max_bytes: int) -> bytes:
        if self.size > max_bytes:
            raise ObjectParserRefused("snapshot blob exceeds read quota")
        try:
            with self.open() as stream:
                payload = stream.read(max_bytes + 1)
                self.validateStream(stream)
        except OSError as exc:
            raise ObjectParserRefused("snapshot blob cannot be retained") from exc
        if len(payload) != self.size or len(payload) > max_bytes:
            raise ObjectParserRefused("snapshot blob size raced retained read")
        return payload

    def readRange(self, offset: int, size: int) -> bytes:
        if offset < 0 or size < 0 or offset + size > self.size:
            raise ObjectParserRefused("snapshot blob range is outside its bounds")
        try:
            with self.open() as stream:
                stream.seek(offset)
                payload = stream.read(size)
                self.validateStream(stream)
        except OSError as exc:
            raise ObjectParserRefused("snapshot blob range cannot be retained") from exc
        if len(payload) != size:
            raise ObjectParserRefused("snapshot blob range is truncated")
        return payload


def _verifiedBlob(blob_root: Path, digest: str, size: int) -> _VerifiedBlob:
    path = blob_root / digest[:2] / digest
    current = blob_root
    try:
        root_meta = current.lstat()
        if not stat.S_ISDIR(root_meta.st_mode) or stat.S_ISLNK(root_meta.st_mode):
            raise OSError("blob root is not a native directory")
        for component in (digest[:2], digest):
            current /= component
            metadata = current.lstat()
            if stat.S_ISLNK(metadata.st_mode):
                raise OSError("blob path contains a link")
        before = path.lstat()
        identity = _statIdentity(before)
        if (
            not stat.S_ISREG(before.st_mode)
            or before.st_nlink != 1
            or before.st_size != size
        ):
            raise OSError("blob leaf metadata differs")
        blob = _VerifiedBlob(path, digest=digest, size=size, identity=identity)
        observed = hashlib.sha256()
        total = 0
        with blob.open() as stream:
            while True:
                chunk = stream.read(65536)
                if not chunk:
                    break
                total += len(chunk)
                if total > size:
                    raise OSError("blob grew during digest validation")
                observed.update(chunk)
            blob.validateStream(stream)
        after = path.lstat()
    except OSError as exc:
        raise ObjectParserRefused("snapshot blob is unavailable or unsafe") from exc
    if (
        _statIdentity(after) != identity
        or total != size
        or observed.hexdigest() != digest
    ):
        raise ObjectParserRefused("snapshot blob digest or identity differs")
    return blob


def _snapshotEntries(
    value: object,
    *,
    policy: _Policy,
    blob_root: Path,
    sha1dc: _Sha1dcOracle,
) -> list[dict[str, object]]:
    if not isinstance(value, list):
        raise ObjectParserRefused("snapshot entries must be a list")
    if len(value) > policy["max_files"]:
        raise ObjectParserRefused("snapshot exceeds file-count quota")
    result: list[dict[str, object]] = []
    aliases: set[tuple[str, ...]] = set()
    exact: set[str] = set()
    total = 0
    fields = {"path", "mode", "blob_sha256", "size"}
    reserved = tuple(_filesystemKey(root) for root in policy["reserved_roots"])
    for item in value:
        if not isinstance(item, dict) or set(item) != fields:
            raise ObjectParserRefused("snapshot entry fields are not closed")
        path = item["path"]
        parts = _safePath(path)
        assert isinstance(path, str)
        mode = item["mode"]
        digest = _digest(item["blob_sha256"], "snapshot blob")
        size = item["size"]
        if mode not in _REGULAR_MODES:
            raise ObjectParserRefused("snapshot mode is unsupported")
        if not isinstance(size, int) or isinstance(size, bool) or size < 0:
            raise ObjectParserRefused("snapshot size is malformed")
        if (
            size > policy["max_file_bytes"]
            or len(parts) > policy["max_depth"]
            or len(path.encode("utf-8")) > policy["max_path_bytes"]
        ):
            raise ObjectParserRefused("snapshot entry exceeds quota")
        key = _filesystemKey(path)
        if path in exact or key in aliases:
            raise ObjectParserRefused("snapshot path is duplicated or aliased")
        if any(key[: len(root)] == root for root in reserved):
            raise ObjectParserRefused("snapshot enters a reserved runtime root")
        exact.add(path)
        aliases.add(key)
        total += size
        payload = _readBlob(blob_root, digest, size)
        frame = _frameObject("blob", payload)
        result.append(
            {
                "path": path,
                "mode": mode,
                "blob_oid": sha1dc.hashObject("blob", payload),
                "blob_sha256": digest,
                "framed_object_sha256": hashlib.sha256(frame).hexdigest(),
                "size": size,
            }
        )
    if total > policy["max_total_bytes"]:
        raise ObjectParserRefused("snapshot exceeds aggregate byte quota")
    ordered = sorted(result, key=lambda item: str(item["path"]).encode("utf-8"))
    paths = {str(item["path"]) for item in ordered}
    for path in paths:
        parts = PurePosixPath(path).parts
        for index in range(1, len(parts)):
            if "/".join(parts[:index]) in paths:
                raise ObjectParserRefused("snapshot file is another path's ancestor")
    return ordered


def _entrySize(entry: dict[str, object]) -> int:
    size = entry.get("size")
    if type(size) is not int or size < 0:
        raise ObjectParserRefused("manifest entry size is invalid")
    return size


def _safeSnapshotAttributeRules(
    entries: list[dict[str, object]],
    blob_root: Path,
) -> list[dict[str, object]]:
    files = [entry for entry in entries if entry["path"] == ".gitattributes"]
    if any(
        PurePosixPath(str(entry["path"])).name == ".gitattributes"
        and entry["path"] != ".gitattributes"
        for entry in entries
    ):
        raise ObjectParserRefused("nested attribute files are unsupported")
    if not files:
        return []
    if len(files) != 1:
        raise ObjectParserRefused("attribute file is duplicated")
    entry = files[0]
    payload = _readBlob(
        blob_root,
        str(entry["blob_sha256"]),
        _entrySize(entry),
    )
    if b"\r" in payload:
        raise ObjectParserRefused("attribute file is not canonical LF text")
    try:
        text = payload.decode("utf-8", errors="strict")
    except UnicodeDecodeError as exc:
        raise ObjectParserRefused("attribute file is not strict UTF-8") from exc
    result: list[dict[str, object]] = []
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split()
        if (
            len(fields) != 3
            or fields[1:] != ["text", "eol=lf"]
            or fields[0].startswith(("!", "[attr]"))
            or "\\" in fields[0]
        ):
            raise ObjectParserRefused("attribute rule requires an external driver")
        result.append({"pattern": fields[0], "attributes": fields[1:]})
    rules = _validateAttributes(result)
    for rule in rules:
        pattern = str(rule["pattern"])
        for entry in entries:
            path = str(entry["path"])
            if not _attributePatternMatches(pattern, path):
                continue
            payload = _readBlob(
                blob_root,
                str(entry["blob_sha256"]),
                _entrySize(entry),
            )
            if b"\r" in payload:
                raise ObjectParserRefused(
                    "text attribute target is not canonical LF bytes"
                )
    return rules


def _diffDigest(
    expected: dict[str, dict[str, object]],
    proposed: list[dict[str, object]],
) -> str:
    proposed_by_path = {str(item["path"]): item for item in proposed}
    changes: list[dict[str, object]] = []
    for path in sorted(set(expected) | set(proposed_by_path), key=lambda item: item.encode("utf-8")):
        before = expected.get(path)
        after = proposed_by_path.get(path)
        if before == after:
            continue
        changes.append(
            {
                "path": path,
                "before": None
                if before is None
                else {"mode": before["mode"], "blob_sha256": before["blob_sha256"]},
                "after": None
                if after is None
                else {"mode": after["mode"], "blob_sha256": after["blob_sha256"]},
            }
        )
    return _canonicalDigest(changes)


def parseCandidateSnapshot(
    request: dict[str, object],
    blob_root: Path,
    *,
    sha1dc: _Sha1dcOracle,
) -> dict[str, object]:
    request_fields = {
        "schema",
        "operation",
        "transaction_id",
        "snapshot",
        "expected_manifest",
        "expected_manifest_digest",
    }
    if set(request) != request_fields:
        raise ObjectParserRefused("request fields are not closed")
    if (
        request["schema"] != "galaxy.object-parser-request/v1"
        or request["operation"] != "candidate-snapshot"
    ):
        raise ObjectParserRefused("request schema or operation is unsupported")
    transaction_id = request["transaction_id"]
    if (
        not isinstance(transaction_id, str)
        or not transaction_id
        or len(transaction_id.encode("utf-8")) > 256
        or any(ord(character) < 33 or ord(character) > 126 for character in transaction_id)
    ):
        raise ObjectParserRefused("transaction id is malformed")
    expected_manifest = request["expected_manifest"]
    if not isinstance(expected_manifest, dict):
        raise ObjectParserRefused("expected manifest is malformed")
    if _canonicalDigest(expected_manifest) != _digest(
        request["expected_manifest_digest"], "expected manifest"
    ):
        raise ObjectParserRefused("expected manifest digest differs")
    if set(expected_manifest) != {
        "expected_revision",
        "entries",
        "attribute_rules",
        "policy",
    }:
        raise ObjectParserRefused("expected manifest fields are not closed")
    revision = _oid(expected_manifest["expected_revision"], "expected revision")
    policy = _validatePolicy(expected_manifest["policy"])
    _validateAttributes(expected_manifest["attribute_rules"])
    expected = _expectedEntries(expected_manifest["entries"])
    snapshot = request["snapshot"]
    if not isinstance(snapshot, dict) or set(snapshot) != {
        "entries",
        "snapshot_digest",
        "blob_set_digest",
    }:
        raise ObjectParserRefused("snapshot fields are not closed")
    raw_entries = snapshot["entries"]
    if _canonicalDigest({"entries": raw_entries}) != _digest(
        snapshot["snapshot_digest"], "snapshot"
    ):
        raise ObjectParserRefused("snapshot digest differs")
    if not isinstance(raw_entries, list):
        raise ObjectParserRefused("snapshot entries are malformed")
    unique_blobs = sorted(
        {
            (str(item.get("blob_sha256")), item.get("size"))
            for item in raw_entries
            if isinstance(item, dict)
        }
    )
    blob_records = [{"sha256": digest, "size": size} for digest, size in unique_blobs]
    if _canonicalDigest(blob_records) != _digest(snapshot["blob_set_digest"], "blob set"):
        raise ObjectParserRefused("blob-set digest differs")
    proposed_entries = _snapshotEntries(
        raw_entries,
        policy=policy,
        blob_root=blob_root,
        sha1dc=sha1dc,
    )
    attributes = _safeSnapshotAttributeRules(proposed_entries, blob_root)
    proposed_manifest = {
        "expected_revision": revision,
        "entries": proposed_entries,
        "attribute_rules": attributes,
        "policy": policy,
    }
    parser_digest = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    return {
        "schema": "galaxy.object-parser-result/v1",
        "transaction_id": transaction_id,
        "snapshot_digest": snapshot["snapshot_digest"],
        "blob_set_digest": snapshot["blob_set_digest"],
        "expected_manifest_digest": request["expected_manifest_digest"],
        "proposed_manifest": proposed_manifest,
        "proposed_manifest_digest": _canonicalDigest(proposed_manifest),
        "diff_digest": _diffDigest(expected, proposed_entries),
        "parser_version_digest": parser_digest,
        "network_allowed": False,
    }


class _GitObject(TypedDict):
    object_type: str
    payload: bytes
    frame: bytes


def _frameObject(object_type: str, payload: bytes) -> bytes:
    return (
        object_type.encode("ascii")
        + b" "
        + str(len(payload)).encode("ascii")
        + b"\0"
        + payload
    )


def _addGitObject(
    objects: dict[str, _GitObject] | _ObjectStore,
    *,
    object_type: str,
    payload: bytes,
    expected_oid: str | None = None,
    budget: _InflationBudget,
    sha1dc: _Sha1dcOracle,
) -> str:
    if object_type not in {"blob", "tree", "commit", "tag"}:
        raise ObjectParserRefused("source object type is unsupported")
    if len(payload) > _MAX_SOURCE_OBJECT_BYTES:
        raise ObjectParserRefused("source object exceeds inflated-byte quota")
    frame = _frameObject(object_type, payload)
    oid = sha1dc.hashObject(object_type, payload)
    if expected_oid is not None and oid != expected_oid:
        raise ObjectParserRefused("source object id differs from its exact bytes")
    target = objects._objects if isinstance(objects, _ObjectStore) else objects
    previous = target.get(oid)
    candidate: _GitObject = {
        "object_type": object_type,
        "payload": payload,
        "frame": frame,
    }
    if previous is not None and previous != candidate:
        raise ObjectParserRefused("one Git object id maps to different strong bytes")
    budget.observeObject(oid, len(payload))
    target[oid] = candidate
    return oid


class _ObjectStore:
    """Lazy exact-object view over loose objects and bounded parsed packs."""

    def __init__(self, budget: _InflationBudget, sha1dc: _Sha1dcOracle) -> None:
        self._budget = budget
        self.sha1dc = sha1dc
        self._objects: dict[str, _GitObject] = {}
        self._loose: dict[str, _VerifiedBlob] = {}
        self._packs: list[_PackResolver] = []
        self._catalog_oids: set[str] = set()

    def registerLoose(self, oid: str, raw: _VerifiedBlob) -> None:
        if oid in self._catalog_oids:
            raise ObjectParserRefused("source object id has multiple raw authorities")
        self._catalog_oids.add(oid)
        self._loose[oid] = raw

    def registerPack(self, pack: _PackResolver) -> None:
        overlap = self._catalog_oids.intersection(pack.oid_to_offset)
        if overlap:
            raise ObjectParserRefused("source object id has multiple raw authorities")
        self._catalog_oids.update(pack.oid_to_offset)
        self._packs.append(pack)

    def get(self, oid: str) -> _GitObject | None:
        existing = self._objects.get(oid)
        if existing is not None:
            return existing
        loose = self._loose.get(oid)
        if loose is not None:
            raw = loose.readAll(max_bytes=_MAX_SOURCE_OBJECT_BYTES + (1024 * 1024))
            object_type, payload = _parseLooseObject(
                raw,
                oid,
                sha1dc=self.sha1dc,
            )
            _addGitObject(
                self,
                object_type=object_type,
                payload=payload,
                expected_oid=oid,
                budget=self._budget,
                sha1dc=self.sha1dc,
            )
            return self._objects.get(oid)
        for pack in self._packs:
            if pack.contains(oid):
                pack.resolveOid(oid)
                return self._objects.get(oid)
        return None

    def __getitem__(self, oid: str) -> _GitObject:
        value = self.get(oid)
        if value is None:
            raise KeyError(oid)
        return value

    def __len__(self) -> int:
        return len(self._objects)

    def assertSelectedAuthoritiesUsed(self) -> None:
        if set(self._loose).difference(self._objects):
            raise ObjectParserRefused("source snapshot contains an unused loose authority")
        if any(set(pack.ranges).difference(pack.records) for pack in self._packs):
            raise ObjectParserRefused("source snapshot contains an unused pack range")


def _inflateExact(raw: bytes, *, max_output: int) -> bytes:
    decoder = zlib.decompressobj()
    try:
        output = decoder.decompress(raw, max_output + 1)
        output += decoder.flush()
    except zlib.error as exc:
        raise ObjectParserRefused("source object compression is malformed") from exc
    if (
        len(output) > max_output
        or not decoder.eof
        or decoder.unused_data
        or decoder.unconsumed_tail
    ):
        raise ObjectParserRefused("source object compression exceeds its closed frame")
    return output


def _parseLooseObject(
    raw: bytes,
    expected_oid: str,
    *,
    sha1dc: _Sha1dcOracle,
) -> tuple[str, bytes]:
    frame = _inflateExact(raw, max_output=_MAX_SOURCE_OBJECT_BYTES + 64)
    nul = frame.find(b"\0")
    if nul < 0:
        raise ObjectParserRefused("loose object header is truncated")
    try:
        object_type_raw, size_raw = frame[:nul].split(b" ", 1)
        object_type = object_type_raw.decode("ascii")
        size_text = size_raw.decode("ascii")
        size = int(size_text)
    except (ValueError, UnicodeDecodeError) as exc:
        raise ObjectParserRefused("loose object header is malformed") from exc
    payload = frame[nul + 1 :]
    if (
        object_type not in {"blob", "tree", "commit", "tag"}
        or str(size) != size_text
        or size != len(payload)
        or sha1dc.hashObject(object_type, payload) != expected_oid
    ):
        raise ObjectParserRefused("loose object frame is noncanonical")
    return object_type, payload


def _parsePackIndex(
    raw: bytes,
    *,
    max_objects: int,
) -> tuple[dict[int, tuple[str, int]], bytes]:
    if len(raw) < 8 + 1024 + 40 or raw[:4] != b"\xfftOc":
        raise ObjectParserRefused("pack index header is unsupported")
    if struct.unpack(">I", raw[4:8])[0] != 2:
        raise ObjectParserRefused("only pack index v2 is supported")
    fanout = struct.unpack(">256I", raw[8 : 8 + 1024])
    if any(fanout[index] > fanout[index + 1] for index in range(255)):
        raise ObjectParserRefused("pack index fanout is nonmonotonic")
    count = fanout[-1]
    if count > max_objects:
        raise ObjectParserRefused("source pack exceeds object-count quota")
    cursor = 8 + 1024
    minimum = cursor + count * 20 + count * 4 + count * 4 + 40
    if minimum > len(raw):
        raise ObjectParserRefused("pack index is truncated")
    oids = [raw[cursor + index * 20 : cursor + (index + 1) * 20].hex() for index in range(count)]
    cursor += count * 20
    if oids != sorted(oids) or len(set(oids)) != len(oids):
        raise ObjectParserRefused("pack index object ids are not sorted and unique")
    crcs = struct.unpack(f">{count}I", raw[cursor : cursor + count * 4]) if count else ()
    cursor += count * 4
    words = struct.unpack(f">{count}I", raw[cursor : cursor + count * 4]) if count else ()
    cursor += count * 4
    large_count = sum(1 for word in words if word & 0x80000000)
    if cursor + large_count * 8 + 40 != len(raw):
        raise ObjectParserRefused("pack index size does not match its tables")
    large = (
        struct.unpack(f">{large_count}Q", raw[cursor : cursor + large_count * 8])
        if large_count
        else ()
    )
    cursor += large_count * 8
    pack_checksum = raw[cursor : cursor + 20]
    index_checksum = raw[cursor + 20 : cursor + 40]
    if hashlib.sha1(raw[:-20], usedforsecurity=False).digest() != index_checksum:
        raise ObjectParserRefused("pack index checksum differs")
    result: dict[int, tuple[str, int]] = {}
    for index, word in enumerate(words):
        if word & 0x80000000:
            large_index = word & 0x7FFFFFFF
            if large_index >= len(large):
                raise ObjectParserRefused("pack index large offset is invalid")
            offset = large[large_index]
        else:
            offset = word
        if offset in result or offset < 12:
            raise ObjectParserRefused("pack index offset is duplicated or invalid")
        result[offset] = (oids[index], crcs[index])
    return result, pack_checksum


def _deltaInteger(delta: bytes, cursor: int) -> tuple[int, int]:
    value = 0
    shift = 0
    while True:
        if cursor >= len(delta) or shift > 63:
            raise ObjectParserRefused("pack delta integer is malformed")
        byte = delta[cursor]
        cursor += 1
        value |= (byte & 0x7F) << shift
        if not byte & 0x80:
            return value, cursor
        shift += 7


def _applyDelta(base: bytes, delta: bytes) -> bytes:
    base_size, cursor = _deltaInteger(delta, 0)
    result_size, cursor = _deltaInteger(delta, cursor)
    if base_size != len(base):
        raise ObjectParserRefused("pack delta declares inconsistent sizes")
    if result_size > _MAX_SOURCE_OBJECT_BYTES:
        raise ObjectParserRefused("pack delta result exceeds inflated-byte quota")
    output = bytearray()
    while cursor < len(delta):
        command = delta[cursor]
        cursor += 1
        if command & 0x80:
            offset = 0
            size = 0
            for bit, shift in ((0, 0), (1, 8), (2, 16), (3, 24)):
                if command & (1 << bit):
                    if cursor >= len(delta):
                        raise ObjectParserRefused("pack delta copy offset is truncated")
                    offset |= delta[cursor] << shift
                    cursor += 1
            for bit, shift in ((4, 0), (5, 8), (6, 16)):
                if command & (1 << bit):
                    if cursor >= len(delta):
                        raise ObjectParserRefused("pack delta copy size is truncated")
                    size |= delta[cursor] << shift
                    cursor += 1
            if size == 0:
                size = 0x10000
            if offset + size > len(base):
                raise ObjectParserRefused("pack delta copy escapes its base")
            output.extend(base[offset : offset + size])
        elif command:
            if cursor + command > len(delta):
                raise ObjectParserRefused("pack delta insert is truncated")
            output.extend(delta[cursor : cursor + command])
            cursor += command
        else:
            raise ObjectParserRefused("pack delta contains opcode zero")
        if len(output) > result_size:
            raise ObjectParserRefused("pack delta exceeds its result quota")
    if len(output) != result_size:
        raise ObjectParserRefused("pack delta result size differs")
    return bytes(output)


class _PackResolver:
    def __init__(
        self,
        *,
        store: _ObjectStore,
        oid_to_offset: dict[str, int],
        crc_by_offset: dict[int, int],
        ranges: dict[int, _VerifiedBlob],
        budget: _InflationBudget,
    ) -> None:
        self.store = store
        self.oid_to_offset = oid_to_offset
        self.offset_to_oid = {offset: oid for oid, offset in oid_to_offset.items()}
        self.crc_by_offset = crc_by_offset
        self.ranges = ranges
        self.budget = budget
        self.resolving: set[int] = set()
        self.records: dict[int, dict[str, object]] = {}

    def contains(self, oid: str) -> bool:
        return oid in self.oid_to_offset

    def resolveOid(self, oid: str) -> tuple[str, bytes]:
        offset = self.oid_to_offset.get(oid)
        if offset is None:
            raise ObjectParserRefused("packed source object is unavailable")
        return self._resolve(offset)

    def _readRecord(self, offset: int) -> dict[str, object]:
        cached = self.records.get(offset)
        if cached is not None:
            return cached
        expected_oid = self.offset_to_oid.get(offset)
        raw = self.ranges.get(offset)
        if expected_oid is None:
            raise ObjectParserRefused("pack object offset is outside the indexed stream")
        if raw is None:
            raise _MissingSourceObjects({expected_oid})
        limit = offset + raw.size
        try:
            with raw.open() as stream:
                position = offset
                crc = 0

                def take(size: int) -> bytes:
                    nonlocal position, crc
                    raw = stream.read(size)
                    if len(raw) != size:
                        raise ObjectParserRefused("pack object header is truncated")
                    position += size
                    crc = binascii.crc32(raw, crc) & 0xFFFFFFFF
                    return raw

                byte = take(1)[0]
                type_code = (byte >> 4) & 7
                declared_size = byte & 15
                shift = 4
                while byte & 0x80:
                    if position >= limit or shift > 63:
                        raise ObjectParserRefused("pack object size is malformed")
                    byte = take(1)[0]
                    declared_size |= (byte & 0x7F) << shift
                    shift += 7
                if declared_size > _MAX_SOURCE_OBJECT_BYTES:
                    raise ObjectParserRefused("pack object exceeds inflated-byte quota")
                base_offset: int | None = None
                base_oid: str | None = None
                if type_code == 6:
                    if position >= limit:
                        raise ObjectParserRefused("offset delta base is truncated")
                    byte = take(1)[0]
                    distance = byte & 0x7F
                    while byte & 0x80:
                        if position >= limit:
                            raise ObjectParserRefused("offset delta distance is truncated")
                        byte = take(1)[0]
                        distance = ((distance + 1) << 7) | (byte & 0x7F)
                    base_offset = offset - distance
                    if base_offset not in self.crc_by_offset:
                        raise ObjectParserRefused("offset delta base escapes the indexed pack")
                elif type_code == 7:
                    if position + 20 > limit:
                        raise ObjectParserRefused("reference delta base is truncated")
                    base_oid = take(20).hex()
                elif type_code not in {1, 2, 3, 4}:
                    raise ObjectParserRefused("pack object type is unsupported")

                decoder = zlib.decompressobj()
                inflated = bytearray()
                while position < limit and not decoder.eof:
                    chunk = stream.read(min(65536, limit - position))
                    if not chunk:
                        break
                    piece = decoder.decompress(
                        chunk,
                        (_MAX_SOURCE_OBJECT_BYTES + 1) - len(inflated),
                    )
                    inflated.extend(piece)
                    if len(inflated) > _MAX_SOURCE_OBJECT_BYTES or decoder.unconsumed_tail:
                        raise ObjectParserRefused(
                            "pack object compression exceeds inflated-byte quota"
                        )
                    consumed = len(chunk) - len(decoder.unused_data)
                    if consumed < 1:
                        raise ObjectParserRefused("pack object compression made no progress")
                    crc = binascii.crc32(chunk[:consumed], crc) & 0xFFFFFFFF
                    position += consumed
                if not decoder.eof:
                    raise ObjectParserRefused("pack object compression is truncated")
                tail = decoder.flush()
                inflated.extend(tail)
                if len(inflated) > _MAX_SOURCE_OBJECT_BYTES or position != limit:
                    raise ObjectParserRefused(
                        "pack object compression has ambiguous framing"
                    )
                raw.validateStream(stream)
        except ObjectParserRefused:
            raise
        except (OSError, zlib.error) as exc:
            raise ObjectParserRefused("pack object cannot be read safely") from exc
        if crc != self.crc_by_offset[offset]:
            raise ObjectParserRefused("pack object CRC differs from its index")
        record: dict[str, object] = {
            "type_code": type_code,
            "size": declared_size,
            "inflated": bytes(inflated),
            "base_offset": base_offset,
            "base_oid": base_oid,
            "oid": expected_oid,
        }
        if type_code in {6, 7}:
            self.budget.observeInflated(len(inflated))
        self.records[offset] = record
        return record

    def _resolve(self, offset: int, depth: int = 0) -> tuple[str, bytes]:
        if depth > 64:
            raise ObjectParserRefused("pack delta depth exceeds quota")
        record = self._readRecord(offset)
        cached_type = record.get("resolved_type")
        cached_payload = record.get("resolved_payload")
        if isinstance(cached_type, str) and isinstance(cached_payload, bytes):
            return cached_type, cached_payload
        if offset in self.resolving:
            raise ObjectParserRefused("pack delta graph contains a cycle")
        self.resolving.add(offset)
        try:
            type_code_value = record["type_code"]
            size_value = record["size"]
            if not isinstance(type_code_value, int) or not isinstance(size_value, int):
                raise ObjectParserRefused("pack object metadata is malformed")
            type_code = type_code_value
            inflated = record["inflated"]
            assert isinstance(inflated, bytes)
            if type_code in {1, 2, 3, 4}:
                object_type = {1: "commit", 2: "tree", 3: "blob", 4: "tag"}[
                    type_code
                ]
                payload = inflated
                if len(payload) != size_value:
                    raise ObjectParserRefused(
                        "packed object size differs from its header"
                    )
            else:
                if len(inflated) != size_value:
                    raise ObjectParserRefused(
                        "packed delta instruction size differs from its header"
                    )
                base_offset = record["base_offset"]
                if isinstance(base_offset, int):
                    base_type, base_payload = self._resolve(base_offset, depth + 1)
                else:
                    base_oid = record["base_oid"]
                    assert isinstance(base_oid, str)
                    local_offset = self.oid_to_offset.get(base_oid)
                    if local_offset is not None:
                        base_type, base_payload = self._resolve(
                            local_offset,
                            depth + 1,
                        )
                    else:
                        base = self.store.get(base_oid)
                        if base is None:
                            raise _MissingSourceObjects({base_oid})
                        base_type, base_payload = base["object_type"], base["payload"]
                object_type = base_type
                payload = _applyDelta(base_payload, inflated)
            expected_oid = record["oid"]
            assert isinstance(expected_oid, str)
            _addGitObject(
                self.store,
                object_type=object_type,
                payload=payload,
                expected_oid=expected_oid,
                budget=self.budget,
                sha1dc=self.store.sha1dc,
            )
            record["resolved_type"] = object_type
            record["resolved_payload"] = payload
            return object_type, payload
        finally:
            self.resolving.remove(offset)


def _parsePack(
    header: _VerifiedBlob,
    index_raw: bytes,
    ranges: dict[int, tuple[_VerifiedBlob, int]],
    source_size: int,
    expected_pack_checksum: str,
    store: _ObjectStore,
    budget: _InflationBudget,
) -> _PackResolver:
    index, indexed_pack_checksum = _parsePackIndex(
        index_raw,
        max_objects=budget.remainingInputObjects,
    )
    if header.size != 12 or not 32 <= source_size <= _MAX_SOURCE_PACK_BYTES:
        raise ObjectParserRefused("pack header projection is malformed")
    header_raw = header.readAll(max_bytes=12)
    if header_raw[:4] != b"PACK":
        raise ObjectParserRefused("pack header is malformed")
    version, count = struct.unpack(">II", header_raw[4:12])
    if version not in {2, 3} or count != len(index):
        raise ObjectParserRefused("pack header differs from its index")
    budget.assertPackCount(count)
    if indexed_pack_checksum.hex() != expected_pack_checksum:
        raise ObjectParserRefused("pack index checksum differs from its authority name")
    if index and min(index) != 12:
        raise ObjectParserRefused("pack object stream does not begin after its header")
    offsets = sorted(index)
    if any(offset >= source_size - 20 for offset in offsets):
        raise ObjectParserRefused("pack index offset escapes the declared pack payload")
    expected_lengths = {
        offset: (
            offsets[position + 1] - offset
            if position + 1 < len(offsets)
            else source_size - 20 - offset
        )
        for position, offset in enumerate(offsets)
    }
    for offset, (raw, declared_crc) in ranges.items():
        indexed = index.get(offset)
        if indexed is None or declared_crc != indexed[1]:
            raise ObjectParserRefused("selected pack range differs from its index")
        expected_length = expected_lengths[offset]
        if raw.size != expected_length:
            raise ObjectParserRefused("selected pack range boundary differs from its index")
    oid_to_offset = {oid: offset for offset, (oid, _) in index.items()}
    return _PackResolver(
        store=store,
        oid_to_offset=oid_to_offset,
        crc_by_offset={offset: crc for offset, (_, crc) in index.items()},
        ranges={offset: raw for offset, (raw, _crc) in ranges.items()},
        budget=budget,
    )


def _sourceObjects(
    entries: list[dict[str, object]],
    raw_root: Path,
    *,
    revision: str,
    sha1dc: _Sha1dcOracle,
) -> _ObjectStore:
    budget = _InflationBudget(
        max_objects=_MAX_SOURCE_OBJECT_COUNT,
        max_inflated_bytes=_MAX_SOURCE_INFLATED_BYTES,
    )
    objects = _ObjectStore(budget, sha1dc)
    pack_indexes: dict[str, _VerifiedBlob] = {}
    pack_headers: dict[str, _VerifiedBlob] = {}
    pack_sizes: dict[str, int] = {}
    pack_ranges: dict[str, dict[int, tuple[_VerifiedBlob, int]]] = {}
    seen_paths: set[str] = set()
    budget.reserveLooseObjects(
        sum(
            1
            for entry in entries
            if isinstance(entry, dict)
            and isinstance(entry.get("path"), str)
            and re.fullmatch(r"loose/[0-9a-f]{40}", str(entry["path"]))
        )
    )
    for entry in entries:
        if not isinstance(entry, dict) or set(entry) != {"path", "raw_sha256", "size"}:
            raise ObjectParserRefused("raw snapshot entry fields are not closed")
        path = entry["path"]
        digest = _digest(entry["raw_sha256"], "raw snapshot")
        size = entry["size"]
        if (
            not isinstance(path, str)
            or not isinstance(size, int)
            or isinstance(size, bool)
            or size < 1
            or path in seen_paths
        ):
            raise ObjectParserRefused("raw snapshot entry is malformed or duplicated")
        seen_paths.add(path)
        raw = _verifiedBlob(raw_root, digest, size)
        if re.fullmatch(r"loose/[0-9a-f]{40}", path):
            expected_oid = path.split("/", 1)[1]
            objects.registerLoose(expected_oid, raw)
            continue
        if match := re.fullmatch(r"pack/(pack-[0-9a-f]{40})\.idx", path):
            name = match.group(1)
            if name in pack_indexes:
                raise ObjectParserRefused("raw pack index authority is duplicated")
            pack_indexes[name] = raw
            continue
        if match := re.fullmatch(r"pack-header/(pack-[0-9a-f]{40})", path):
            name = match.group(1)
            if name in pack_headers:
                raise ObjectParserRefused("raw pack header authority is duplicated")
            pack_headers[name] = raw
            continue
        match = re.fullmatch(
            r"pack-range/(pack-[0-9a-f]{40})/"
            r"([1-9][0-9]*)-(0|[1-9][0-9]*)-([1-9][0-9]*)-([0-9a-f]{8})",
            path,
        )
        if match is None:
            raise ObjectParserRefused("raw snapshot path is outside the closed grammar")
        name = match.group(1)
        source_size = int(match.group(2))
        offset = int(match.group(3))
        length = int(match.group(4))
        declared_crc = int(match.group(5), 16)
        if raw.size != length or offset < 12 or offset + length > source_size - 20:
            raise ObjectParserRefused("raw pack range metadata is inconsistent")
        prior_size = pack_sizes.setdefault(name, source_size)
        if prior_size != source_size:
            raise ObjectParserRefused("raw pack ranges disagree about source size")
        ranges = pack_ranges.setdefault(name, {})
        if offset in ranges:
            raise ObjectParserRefused("raw pack range offset is duplicated")
        ranges[offset] = (raw, declared_crc)
    names = set(pack_indexes) | set(pack_headers) | set(pack_ranges)
    for name in sorted(names):
        if name not in pack_indexes or name not in pack_headers or name not in pack_ranges:
            raise ObjectParserRefused("raw pack range snapshot is not structurally complete")
        expected_checksum = name.removeprefix("pack-")
        objects.registerPack(
            _parsePack(
                pack_headers[name],
                pack_indexes[name].readAll(max_bytes=_MAX_SOURCE_OBJECT_BYTES),
                pack_ranges[name],
                pack_sizes[name],
                expected_checksum,
                objects,
                budget,
            )
        )
    if objects.get(revision) is None:
        raise _MissingSourceObjects({revision})
    return objects


def _commitTree(payload: bytes) -> str:
    header, separator, _ = payload.partition(b"\n\n")
    if not separator:
        raise ObjectParserRefused("source commit lacks a message separator")
    trees: list[str] = []
    for line in header.splitlines():
        if line.startswith(b"tree "):
            try:
                trees.append(line[5:].decode("ascii"))
            except UnicodeDecodeError as exc:
                raise ObjectParserRefused("source commit tree id is malformed") from exc
    if len(trees) != 1 or _OID_RE.fullmatch(trees[0]) is None:
        raise ObjectParserRefused("source commit must name one exact tree")
    return trees[0]


def _treeEntries(
    payload: bytes,
    *,
    max_entries: int = _MAX_SOURCE_OBJECT_COUNT,
) -> list[tuple[int, bytes, str]]:
    if type(max_entries) is not int or max_entries < 1:
        raise ValueError("max_entries must be a positive integer")
    cursor = 0
    result: list[tuple[int, bytes, str]] = []
    prior_key: bytes | None = None
    names: set[bytes] = set()
    canonical_modes = {
        b"40000": 0o40000,
        b"100644": 0o100644,
        b"100755": 0o100755,
        b"120000": 0o120000,
        b"160000": 0o160000,
    }
    while cursor < len(payload):
        space = payload.find(b" ", cursor)
        nul = payload.find(b"\0", space + 1)
        if space < 0 or nul < 0 or nul + 21 > len(payload):
            raise ObjectParserRefused("source tree entry is truncated")
        mode_raw = payload[cursor:space]
        name = payload[space + 1 : nul]
        try:
            mode = canonical_modes[mode_raw]
        except KeyError as exc:
            raise ObjectParserRefused("source tree mode is noncanonical") from exc
        if not name or b"/" in name or b"\0" in name:
            raise ObjectParserRefused("source tree name is malformed")
        if name in names:
            raise ObjectParserRefused("source tree entry name is duplicated")
        names.add(name)
        # Git compares a tree entry as ``name + b'/'`` and a non-tree entry as
        # ``name + b'\0'``.  Raw-name ordering rejects valid prefix cases such as
        # the file ``foo.bar`` preceding the directory ``foo``.
        sort_key = name + (b"/" if mode == 0o40000 else b"\0")
        if prior_key is not None and sort_key <= prior_key:
            raise ObjectParserRefused("source tree entries are not Git-byte-ordered")
        prior_key = sort_key
        if len(result) >= max_entries:
            raise ObjectParserRefused("source tree exceeds entry-count quota")
        result.append((mode, name, payload[nul + 1 : nul + 21].hex()))
        cursor = nul + 21
    return result


def _safeAttributeRules(
    entries: list[dict[str, object]],
    objects: _ObjectStore,
) -> list[dict[str, object]]:
    result: list[dict[str, object]] = []
    for entry in entries:
        path = str(entry["path"])
        if PurePosixPath(path).name != ".gitattributes":
            continue
        if path != ".gitattributes":
            raise ObjectParserRefused("nested attribute files are unsupported")
        record = objects[str(entry["blob_oid"])]
        if b"\r" in record["payload"]:
            raise ObjectParserRefused("attribute file is not canonical LF text")
        try:
            text = record["payload"].decode("utf-8", errors="strict")
        except UnicodeDecodeError as exc:
            raise ObjectParserRefused("attribute file is not strict UTF-8") from exc
        for raw_line in text.splitlines():
            line = raw_line.strip()
            if not line or line.startswith("#"):
                continue
            fields = line.split()
            if (
                len(fields) != 3
                or fields[1:] != ["text", "eol=lf"]
                or fields[0].startswith(("!", "[attr]"))
                or "\\" in fields[0]
            ):
                raise ObjectParserRefused("attribute rule requires an external driver")
            result.append({"pattern": fields[0], "attributes": ["text", "eol=lf"]})
    rules = _validateAttributes(result)
    for rule in rules:
        pattern = str(rule["pattern"])
        for entry in entries:
            path = str(entry["path"])
            if not _attributePatternMatches(pattern, path):
                continue
            record = objects[str(entry["blob_oid"])]
            if b"\r" in record["payload"]:
                raise ObjectParserRefused(
                    "text attribute target is not canonical LF bytes"
                )
    return rules


def _sourceManifest(
    *,
    revision: str,
    tree_oid: str,
    objects: _ObjectStore,
    policy: _Policy,
) -> tuple[dict[str, object], set[str]]:
    entries: list[dict[str, object]] = []
    closure: set[str] = {revision}
    visiting: set[str] = set()
    missing: set[str] = set()
    total_bytes = 0

    def resolve(oid: str) -> _GitObject | None:
        try:
            record = objects.get(oid)
        except _MissingSourceObjects as exc:
            missing.update(exc.oids)
            return None
        if record is None:
            missing.add(oid)
        return record

    def walk(oid: str, prefix: tuple[str, ...]) -> None:
        nonlocal total_bytes
        if oid in visiting:
            raise ObjectParserRefused("source tree graph contains a cycle")
        record = resolve(oid)
        if record is None:
            return
        if record["object_type"] != "tree":
            raise ObjectParserRefused("source tree object is unavailable")
        visiting.add(oid)
        closure.add(oid)
        for mode, name_raw, child_oid in _treeEntries(record["payload"]):
            try:
                name = name_raw.decode("utf-8", errors="strict")
            except UnicodeDecodeError as exc:
                raise ObjectParserRefused("source tree path is not strict UTF-8") from exc
            path_parts = (*prefix, name)
            path = "/".join(path_parts)
            _safePath(path)
            if len(path_parts) > policy["max_depth"]:
                raise ObjectParserRefused("source tree exceeds depth quota")
            if len(path.encode("utf-8")) > policy["max_path_bytes"]:
                raise ObjectParserRefused("source tree exceeds path-byte quota")
            if mode == 0o40000:
                walk(child_oid, path_parts)
                continue
            if mode not in _REGULAR_MODES:
                raise ObjectParserRefused("source tree contains symlink, submodule, or unsupported mode")
            if path == ".gitmodules":
                raise ObjectParserRefused("source tree contains unsupported submodule metadata")
            child = resolve(child_oid)
            if child is None:
                continue
            if child["object_type"] != "blob":
                raise ObjectParserRefused("source tree blob is unavailable")
            payload = child["payload"]
            frame = child["frame"]
            if len(entries) >= policy["max_files"]:
                raise ObjectParserRefused("source tree exceeds file-count quota")
            if len(payload) > policy["max_file_bytes"]:
                raise ObjectParserRefused("source tree exceeds per-file byte quota")
            total_bytes += len(payload)
            if total_bytes > policy["max_total_bytes"]:
                raise ObjectParserRefused("source tree exceeds aggregate byte quota")
            closure.add(child_oid)
            entries.append(
                {
                    "path": path,
                    "mode": mode,
                    "blob_oid": child_oid,
                    "blob_sha256": hashlib.sha256(payload).hexdigest(),
                    "framed_object_sha256": hashlib.sha256(frame).hexdigest(),
                    "size": len(payload),
                }
            )
        visiting.remove(oid)

    walk(tree_oid, ())
    if missing:
        raise _MissingSourceObjects(missing)
    ordered = sorted(entries, key=lambda entry: str(entry["path"]).encode("utf-8"))
    attributes = _safeAttributeRules(ordered, objects)
    return (
        {
            "expected_revision": revision,
            "entries": ordered,
            "attribute_rules": attributes,
            "policy": policy,
        },
        closure,
    )


def _validateSourceEntries(entries: list[dict[str, object]], policy: _Policy) -> None:
    if len(entries) > policy["max_files"]:
        raise ObjectParserRefused("source tree exceeds file-count quota")
    aliases: set[tuple[str, ...]] = set()
    paths: set[str] = set()
    total = 0
    reserved = tuple(_filesystemKey(root) for root in policy["reserved_roots"])
    for entry in entries:
        path = str(entry["path"])
        parts = _safePath(path)
        key = _filesystemKey(path)
        size_value = entry["size"]
        if not isinstance(size_value, int) or isinstance(size_value, bool):
            raise ObjectParserRefused("source entry size is malformed")
        size = size_value
        if (
            path in paths
            or key in aliases
            or len(parts) > policy["max_depth"]
            or len(path.encode("utf-8")) > policy["max_path_bytes"]
            or size > policy["max_file_bytes"]
            or any(key[: len(root)] == root for root in reserved)
        ):
            raise ObjectParserRefused("source tree path violates policy")
        paths.add(path)
        aliases.add(key)
        total += size
    if total > policy["max_total_bytes"]:
        raise ObjectParserRefused("source tree exceeds aggregate byte quota")
    for path in paths:
        parts = PurePosixPath(path).parts
        if any("/".join(parts[:index]) in paths for index in range(1, len(parts))):
            raise ObjectParserRefused("source tree file is another path's ancestor")


def _writePayload(output_root: Path, digest: str, payload: bytes) -> None:
    try:
        root_meta = output_root.lstat()
        if not stat.S_ISDIR(root_meta.st_mode) or stat.S_ISLNK(root_meta.st_mode):
            raise OSError("output root is unsafe")
        parent = output_root / digest[:2]
        parent.mkdir(exist_ok=True)
        parent_meta = parent.lstat()
        if not stat.S_ISDIR(parent_meta.st_mode) or stat.S_ISLNK(parent_meta.st_mode):
            raise OSError("output fanout is unsafe")
        target = parent / digest
        try:
            with target.open("xb") as stream:
                stream.write(payload)
        except FileExistsError:
            existing = target.read_bytes()
            if existing != payload:
                raise OSError("payload collision")
        metadata = target.lstat()
        if not stat.S_ISREG(metadata.st_mode) or metadata.st_nlink != 1:
            raise OSError("payload leaf is unsafe")
    except OSError as exc:
        raise ObjectParserRefused("source payload output cannot be created exactly") from exc


def locateSourceObjects(
    request: dict[str, object],
    catalog_root: Path,
) -> dict[str, object]:
    """Resolve requested OIDs to loose leaves or the one containing pack index."""

    fields = {
        "schema",
        "operation",
        "transaction_id",
        "inventory_digest",
        "loose_oids",
        "indexes",
        "packs",
        "requested_oids",
    }
    if set(request) != fields or (
        request.get("schema") != "galaxy.source-object-locator-request/v1"
        or request.get("operation") != "source-object-locate"
    ):
        raise ObjectParserRefused("source locator request fields are not closed")
    transaction_id = request.get("transaction_id")
    if (
        not isinstance(transaction_id, str)
        or not transaction_id
        or len(transaction_id.encode("utf-8")) > 128
        or any(ord(character) < 33 or ord(character) > 126 for character in transaction_id)
    ):
        raise ObjectParserRefused("source locator transaction is malformed")
    inventory_digest = _digest(request.get("inventory_digest"), "source inventory")
    loose_oids = request.get("loose_oids")
    requested_oids = request.get("requested_oids")
    indexes = request.get("indexes")
    packs = request.get("packs")
    if (
        not isinstance(loose_oids, list)
        or loose_oids != sorted(loose_oids)
        or len(set(loose_oids)) != len(loose_oids)
        or len(loose_oids) > _MAX_SOURCE_OBJECT_COUNT
        or any(not isinstance(oid, str) or _OID_RE.fullmatch(oid) is None for oid in loose_oids)
        or not isinstance(requested_oids, list)
        or not requested_oids
        or requested_oids != sorted(requested_oids)
        or len(set(requested_oids)) != len(requested_oids)
        or len(requested_oids) > _MAX_SOURCE_OBJECT_COUNT
        or any(
            not isinstance(oid, str) or _OID_RE.fullmatch(oid) is None
            for oid in requested_oids
        )
        or not isinstance(indexes, list)
        or not isinstance(packs, list)
    ):
        raise ObjectParserRefused("source locator catalog is malformed")
    pack_sizes: dict[str, int] = {}
    prior_pack_path = ""
    for entry in packs:
        if not isinstance(entry, dict) or set(entry) != {"path", "size"}:
            raise ObjectParserRefused("source locator pack fields are not closed")
        path = entry.get("path")
        size = entry.get("size")
        if (
            not isinstance(path, str)
            or re.fullmatch(r"pack/pack-[0-9a-f]{40}\.pack", path) is None
            or path <= prior_pack_path
            or type(size) is not int
            or not 32 <= size <= _MAX_SOURCE_PACK_BYTES
        ):
            raise ObjectParserRefused("source locator pack catalog is malformed")
        prior_pack_path = path
        pack_sizes[path] = size
    authorities: dict[str, tuple[str, ...]] = {
        str(oid): (f"loose/{oid}",) for oid in loose_oids
    }
    indexed_count = len(authorities)
    prior_path = ""
    for entry in indexes:
        if not isinstance(entry, dict) or set(entry) != {"path", "raw_sha256", "size"}:
            raise ObjectParserRefused("source locator index fields are not closed")
        path = entry.get("path")
        digest = _digest(entry.get("raw_sha256"), "source index")
        size = entry.get("size")
        if not isinstance(path, str):
            raise ObjectParserRefused("source locator index path is malformed")
        match = re.fullmatch(r"pack/(pack-([0-9a-f]{40}))\.idx", path)
        if (
            match is None
            or path <= prior_path
            or type(size) is not int
            or not 1 <= size <= _MAX_SOURCE_OBJECT_BYTES
        ):
            raise ObjectParserRefused("source locator index is malformed or unordered")
        prior_path = path
        index_raw = _verifiedBlob(catalog_root, digest, size).readAll(
            max_bytes=_MAX_SOURCE_OBJECT_BYTES
        )
        remaining = _MAX_SOURCE_OBJECT_COUNT - indexed_count
        parsed, pack_checksum = _parsePackIndex(index_raw, max_objects=remaining)
        if pack_checksum.hex() != match.group(2):
            raise ObjectParserRefused("source index differs from its paired pack name")
        index_path = f"pack/{match.group(1)}.idx"
        pack_path = f"pack/{match.group(1)}.pack"
        pack_size = pack_sizes.get(pack_path)
        if pack_size is None:
            raise ObjectParserRefused("source locator index has no paired pack metadata")
        offsets = sorted(parsed)
        limits = {
            offset: (
                offsets[position + 1]
                if position + 1 < len(offsets)
                else pack_size - 20
            )
            for position, offset in enumerate(offsets)
        }
        if any(not 12 <= offset < limits[offset] <= pack_size - 20 for offset in offsets):
            raise ObjectParserRefused("source locator pack ranges are outside the indexed stream")
        for offset, (oid, crc) in parsed.items():
            if oid in authorities:
                raise ObjectParserRefused("source object has multiple catalog authorities")
            length = limits[offset] - offset
            authorities[oid] = (
                index_path,
                f"pack-header/{match.group(1)}",
                f"pack-range/{match.group(1)}/{pack_size}-{offset}-{length}-{crc:08x}",
            )
        indexed_count += len(parsed)
    if {
        path.removesuffix(".idx") + ".pack"
        for path in (
            str(entry.get("path"))
            for entry in indexes
            if isinstance(entry, dict)
        )
    } != set(pack_sizes):
        raise ObjectParserRefused("source locator pack metadata is not exactly paired")
    requested = [str(oid) for oid in requested_oids]
    if any(oid not in authorities for oid in requested):
        raise ObjectParserRefused("requested source object is absent from the catalog")
    return {
        "schema": "galaxy.source-object-locator-result/v1",
        "transaction_id": transaction_id,
        "inventory_digest": inventory_digest,
        "requested_oids": requested,
        "sources": [
            {"oid": oid, "paths": list(authorities[oid])}
            for oid in requested
        ],
        "parser_version_digest": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "network_allowed": False,
    }


def parseSourceObjectFrontier(
    request: dict[str, object],
    raw_root: Path,
    output_root: Path,
    *,
    sha1dc: _Sha1dcOracle,
) -> dict[str, object]:
    """Return a complete closure or the exact next missing object frontier."""

    try:
        return parseSourceObjectClosure(
            request,
            raw_root,
            output_root,
            sha1dc=sha1dc,
        )
    except _MissingSourceObjects as exc:
        snapshot = request.get("snapshot")
        if not isinstance(snapshot, dict):
            raise ObjectParserRefused("source frontier snapshot is malformed") from exc
        transaction_id = request.get("transaction_id")
        snapshot_digest = _digest(snapshot.get("snapshot_digest"), "source snapshot")
        return {
            "schema": "galaxy.source-object-frontier-result/v1",
            "transaction_id": transaction_id,
            "snapshot_digest": snapshot_digest,
            "missing_oids": sorted(exc.oids),
            "parser_version_digest": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "network_allowed": False,
        }


def parseSourceObjectClosure(
    request: dict[str, object],
    raw_root: Path,
    output_root: Path,
    *,
    sha1dc: _Sha1dcOracle,
) -> dict[str, object]:
    if set(request) != {"schema", "operation", "transaction_id", "snapshot"}:
        raise ObjectParserRefused("source request fields are not closed")
    if (
        request["schema"] != "galaxy.source-object-parser-request/v1"
        or request["operation"] != "source-object-closure"
    ):
        raise ObjectParserRefused("source request schema or operation is unsupported")
    transaction_id = request["transaction_id"]
    if (
        not isinstance(transaction_id, str)
        or not transaction_id
        or len(transaction_id.encode("utf-8")) > 128
        or any(ord(character) < 33 or ord(character) > 126 for character in transaction_id)
    ):
        raise ObjectParserRefused("source transaction id is malformed")
    snapshot = request["snapshot"]
    fields = {
        "repository_id",
        "revision",
        "canonical_attestation_digest",
        "entries",
        "policy",
        "snapshot_digest",
    }
    if not isinstance(snapshot, dict) or set(snapshot) != fields:
        raise ObjectParserRefused("source snapshot fields are not closed")
    repository_id = _digest(snapshot["repository_id"], "repository")
    _digest(snapshot["canonical_attestation_digest"], "canonical attestation")
    revision = _oid(snapshot["revision"], "source revision")
    policy = _validatePolicy(snapshot["policy"])
    raw_entries = snapshot["entries"]
    if not isinstance(raw_entries, list) or raw_entries != sorted(
        raw_entries, key=lambda item: str(item.get("path")) if isinstance(item, dict) else ""
    ):
        raise ObjectParserRefused("source snapshot entries are not canonical")
    digest_input = dict(snapshot)
    digest_input.pop("snapshot_digest")
    snapshot_digest = _digest(snapshot["snapshot_digest"], "source snapshot")
    if _canonicalDigest(digest_input) != snapshot_digest:
        raise ObjectParserRefused("source snapshot digest differs")
    objects = _sourceObjects(
        raw_entries,
        raw_root,
        revision=revision,
        sha1dc=sha1dc,
    )
    commit = objects.get(revision)
    if commit is None or commit["object_type"] != "commit":
        raise ObjectParserRefused("exact source commit is unavailable")
    tree_oid = _commitTree(commit["payload"])
    manifest, closure_oids = _sourceManifest(
        revision=revision,
        tree_oid=tree_oid,
        objects=objects,
        policy=policy,
    )
    objects.assertSelectedAuthoritiesUsed()
    manifest_entries = manifest["entries"]
    if not isinstance(manifest_entries, list) or any(
        not isinstance(entry, dict) for entry in manifest_entries
    ):
        raise ObjectParserRefused("source manifest entries are malformed")
    source_entries: list[dict[str, object]] = [
        entry for entry in manifest_entries if isinstance(entry, dict)
    ]
    _validateSourceEntries(source_entries, policy)
    records: list[dict[str, object]] = []
    payload_records: set[tuple[str, int]] = set()
    for oid in sorted(closure_oids):
        record = objects[oid]
        if record["object_type"] not in {"blob", "tree", "commit"}:
            raise ObjectParserRefused("exact source closure contains unsupported object type")
        payload = record["payload"]
        frame = record["frame"]
        payload_digest = hashlib.sha256(payload).hexdigest()
        _writePayload(output_root, payload_digest, payload)
        records.append(
            {
                "object_type": record["object_type"],
                "oid": oid,
                "payload_sha256": payload_digest,
                "framed_object_sha256": hashlib.sha256(frame).hexdigest(),
                "size": len(payload),
            }
        )
        payload_records.add((payload_digest, len(payload)))
    parser_digest = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    return {
        "schema": "galaxy.source-object-parser-result/v1",
        "transaction_id": transaction_id,
        "repository_id": repository_id,
        "revision": revision,
        "tree_oid": tree_oid,
        "snapshot_digest": snapshot_digest,
        "manifest": manifest,
        "manifest_digest": _canonicalDigest(manifest),
        "objects": records,
        "object_closure_digest": _canonicalDigest(records),
        "payload_set_digest": _canonicalDigest(
            [
                {"sha256": digest, "size": size}
                for digest, size in sorted(payload_records)
            ]
        ),
        "parser_version_digest": parser_digest,
        "network_allowed": False,
    }


def proveLooseObject(
    request: dict[str, object],
    raw_path: Path,
    *,
    sha1dc: _Sha1dcOracle,
) -> dict[str, object]:
    if set(request) != {
        "schema",
        "transaction_id",
        "raw_sha256",
        "expected",
    } or request.get("schema") != "galaxy.loose-object-proof-request/v1":
        raise ObjectParserRefused("loose-object proof request fields are malformed")
    transaction_id = request.get("transaction_id")
    if (
        not isinstance(transaction_id, str)
        or not transaction_id
        or len(transaction_id.encode("utf-8")) > 128
        or any(ord(character) < 33 or ord(character) > 126 for character in transaction_id)
    ):
        raise ObjectParserRefused("loose-object proof transaction is malformed")
    raw_digest = _digest(request.get("raw_sha256"), "raw object")
    expected = request.get("expected")
    if not isinstance(expected, dict) or set(expected) != {
        "object_type",
        "oid",
        "payload_sha256",
        "framed_object_sha256",
        "size",
    }:
        raise ObjectParserRefused("loose-object proof expectation is malformed")
    object_type = expected.get("object_type")
    oid = expected.get("oid")
    size = expected.get("size")
    payload_digest = _digest(expected.get("payload_sha256"), "object payload")
    frame_digest = _digest(expected.get("framed_object_sha256"), "object frame")
    if object_type not in {"blob", "tree", "commit"}:
        raise ObjectParserRefused("loose-object proof type is unsupported")
    if not isinstance(oid, str) or _OID_RE.fullmatch(oid) is None:
        raise ObjectParserRefused("loose-object proof OID is malformed")
    if type(size) is not int or not 0 <= size <= _MAX_SOURCE_OBJECT_BYTES:
        raise ObjectParserRefused("loose-object proof size is outside quota")
    try:
        before = raw_path.lstat()
        if (
            not stat.S_ISREG(before.st_mode)
            or before.st_nlink != 1
            or before.st_size < 1
            or before.st_size > _MAX_SOURCE_OBJECT_BYTES
        ):
            raise OSError("raw object is outside the closed file profile")
        raw = raw_path.read_bytes()
        after = raw_path.lstat()
    except OSError as exc:
        raise ObjectParserRefused("raw loose object is unavailable or unsafe") from exc
    if (
        (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns)
        != (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns)
        or len(raw) != before.st_size
        or hashlib.sha256(raw).hexdigest() != raw_digest
    ):
        raise ObjectParserRefused("raw loose object raced or differs from its binding")
    observed_type, payload = _parseLooseObject(raw, oid, sha1dc=sha1dc)
    frame = (
        observed_type.encode("ascii")
        + b" "
        + str(len(payload)).encode("ascii")
        + b"\0"
        + payload
    )
    if (
        observed_type != object_type
        or len(payload) != size
        or hashlib.sha256(payload).hexdigest() != payload_digest
        or hashlib.sha256(frame).hexdigest() != frame_digest
    ):
        raise ObjectParserRefused("loose object differs from its strong expectation")
    return {
        "schema": "galaxy.loose-object-proof-result/v1",
        "transaction_id": transaction_id,
        "object_type": observed_type,
        "oid": oid,
        "payload_sha256": payload_digest,
        "framed_object_sha256": frame_digest,
        "raw_sha256": raw_digest,
        "size": len(payload),
        "parser_version_digest": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "network_allowed": False,
    }


def hashObjectBatch(
    request: dict[str, object],
    payload_root: Path,
    *,
    request_sha256: str,
    sha1dc: _Sha1dcOracle,
) -> dict[str, object]:
    """Hash one bounded, content-addressed batch with the sealed SHA1DC oracle."""

    if set(request) != {"schema", "operation", "batch_id", "records"}:
        raise ObjectParserRefused("object hash batch request fields are not closed")
    if (
        request.get("schema") != "galaxy.object-hash-batch-request/v1"
        or request.get("operation") != "hash-object-batch"
        or not isinstance(request.get("batch_id"), str)
        or re.fullmatch(r"hashbatch_[0-9a-f]{64}", str(request["batch_id"]))
        is None
        or _DIGEST_RE.fullmatch(request_sha256) is None
    ):
        raise ObjectParserRefused("object hash batch request binding is malformed")
    records = request.get("records")
    if (
        not isinstance(records, list)
        or not records
        or len(records) > _MAX_HASH_BATCH_RECORDS
    ):
        raise ObjectParserRefused("object hash batch count is outside quota")
    try:
        root_before = payload_root.lstat()
    except OSError as exc:
        raise ObjectParserRefused("object hash payload root is unavailable") from exc
    if not stat.S_ISDIR(root_before.st_mode) or stat.S_ISLNK(root_before.st_mode):
        raise ObjectParserRefused("object hash payload root is unsafe")

    result: list[dict[str, object]] = []
    seen: set[tuple[str, str, int]] = set()
    total = 0
    for sequence, raw_record in enumerate(records):
        if not isinstance(raw_record, dict) or set(raw_record) != {
            "sequence",
            "object_type",
            "payload_sha256",
            "size",
        }:
            raise ObjectParserRefused("object hash batch record fields differ")
        object_type = raw_record.get("object_type")
        digest = raw_record.get("payload_sha256")
        size = raw_record.get("size")
        if (
            raw_record.get("sequence") != sequence
            or type(raw_record.get("sequence")) is not int
            or object_type not in {"blob", "tree", "commit"}
            or not isinstance(digest, str)
            or _DIGEST_RE.fullmatch(digest) is None
            or type(size) is not int
            or not 0 <= size <= _MAX_HASH_BATCH_FILE_BYTES
            or (str(object_type), digest, size) in seen
        ):
            raise ObjectParserRefused("object hash batch record is malformed or repeated")
        seen.add((str(object_type), digest, size))
        total += size
        if total > _MAX_HASH_BATCH_PAYLOAD_BYTES:
            raise ObjectParserRefused("object hash batch aggregate exceeds quota")
        fanout = payload_root / digest[:2]
        path = fanout / digest
        try:
            fanout_meta = fanout.lstat()
            before = path.lstat()
            if (
                not stat.S_ISDIR(fanout_meta.st_mode)
                or stat.S_ISLNK(fanout_meta.st_mode)
                or not stat.S_ISREG(before.st_mode)
                or stat.S_ISLNK(before.st_mode)
                or before.st_nlink != 1
                or before.st_size != size
            ):
                raise OSError("payload identity differs")
            payload = path.read_bytes()
            after = path.lstat()
        except OSError as exc:
            raise ObjectParserRefused("object hash payload is unavailable or unsafe") from exc
        identity = (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns)
        if (
            len(payload) != size
            or identity
            != (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns)
            or hashlib.sha256(payload).hexdigest() != digest
        ):
            raise ObjectParserRefused("object hash payload raced or differs")
        frame = (
            str(object_type).encode("ascii")
            + b" "
            + str(size).encode("ascii")
            + b"\0"
            + payload
        )
        result.append(
            {
                "sequence": sequence,
                "object_type": object_type,
                "payload_sha256": digest,
                "size": size,
                "oid": sha1dc.hashObject(str(object_type), payload),
                "frame_sha256": hashlib.sha256(frame).hexdigest(),
            }
        )
    root_after = payload_root.lstat()
    if (
        root_before.st_dev,
        root_before.st_ino,
        root_before.st_mtime_ns,
    ) != (
        root_after.st_dev,
        root_after.st_ino,
        root_after.st_mtime_ns,
    ):
        raise ObjectParserRefused("object hash payload root changed")
    return {
        "schema": "galaxy.object-hash-batch-result/v1",
        "batch_id": request["batch_id"],
        "request_sha256": request_sha256,
        "records": result,
        "parser_version_digest": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "network_allowed": False,
    }


